"""
🔴 НАБОР СЛОВ ДЛЯ РЕЖИМА «НАЙДИ ВСЕ СЛОВА» — ПОРТУГАЛЬСКИЙ.

Собирает раскладки: база из 7–8 букв и слова, которые из неё складываются
(каждая плитка берётся не больше раза). Два источника, лицензия каждого
прочитана ФАЙЛОМ, а не бейджем:

  · Викиданные, пространство лексем — CC0 (общественное достояние). Проверено
    исходником страницы Wikidata:Licensing: «All structured data in the main,
    property and lexeme namespaces is made available under the Creative Commons
    CC0 License». Происхождение названо: это сами Викиданные, куда правка
    попадает только под CC0 по условиям использования сайта.
    84 582 португальских лексемы: лемма + часть речи;
  · hermitdave/FrequencyWords — MIT (прочитан LICENSE, © 2016 Hermit Dave),
    происхождение названо в README: корпус OpenSubtitles 2018 через OPUS.

⚠️ ПОЧЕМУ НЕ ОРФОГРАФИЧЕСКИЙ СЛОВАРЬ. Оба живых hunspell-словаря лицензированы
так, что на список слов лицензию не натянуть:
  · LibreOffice/dictionaries/pt_BR (проект VERO, Raimundo Moura) — README_en.txt:
    «GNU Lesser General Public License version 3 (LGPLv3) ... and Mozilla Public
    License». Союз «и», а не «или», и версия MPL не названа НИГДЕ — ни в
    английском README, ни в португальском. Лицензия без номера версии
    непригодна: неизвестно, что именно разрешено;
  · LibreOffice/dictionaries/pt_PT (Natura, Univ. do Minho) — README_pt_PT.txt
    честно перечисляет «GPL Version 2 / LGPL Version 2.1 / MPL Version 1.1».
    MPL 1.1 — не MPL-2.0 из белого списка проекта, поэтому источник оставлен
    в отчёте как запасной, а не взят.

⚠️ ДИАКРИТИКА НЕ СНИМАЕТСЯ — ã õ ç á é í ó ú â ê ô остаются отдельными
плитками. Для португальского это не вкусовое решение, а замер.
06.09.2026 по 6980 целям: диакритика есть у 1362 слов — 19,5%, каждое пятое.
  A оставить как есть  — 1176 раскладок, медиана 14, написание верное;
  B снять диакритику   — 1289 раскладок (+113), ценой 1324 порождённых опечаток
                         («coração»→«coracao», «você»→«voce», «irmão»→«irmao»)
                         и 37 склеек, где ç и ã съедают различие смысла:
                         bisavó/bisavô→bisavo, bebé/bebê→bebe, álibi/alibi;
  C выбросить слова с диакритикой — 5618 целей вместо 6980 и 975 раскладок
                         (−201): из игры уходит пятая часть языка.
Плюс 113 раскладок не стоят 1324 неверных написаний, а минус 201 раскладка
и пятая часть словаря — цена ещё хуже. Берём A.
Одиннадцать букв взяты ровно те, что названы в задании: замер показал, что
добавление à и ü даёт РОВНО ОДНО новое слово — немецкое «führer», которому в
португальском наборе делать нечего.

⚠️ ИМЯ СОБСТВЕННОЕ ЛОВИТСЯ ЗАГЛАВНОЙ, А НЕ ТЕГОМ. У итальянского 1445 лексем
помечены категорией Q147276, у португальского таких всего 16 (China, Brasil,
Japão) — тега мало. Заглавных лемм при этом 294 (Portugal, Estado, Primavera,
Idade Média), и ловит их проверка регистра. Работают оба заслона сразу.

⚠️ БАЗЫ БЕРУТСЯ ПО ЧАСТОТЕ, А НЕ ПО АЛФАВИТУ — как и в итальянском скрипте.
Английский набор так и обрывался: цикл шёл по алфавиту, упирался в потолок 2000,
и баз на t–z не было вовсе. Починено 06.09.2026 этим же приёмом.

Замер 06.09.2026: целей 6980 · раскладок 2000 · подслов на раскладку медиана 14.

Запуск (окружение общее с ru/en, дополнительных пакетов не нужно):
    ./.venv/bin/python3 build_pt_targets.py
"""
import csv
import json
import os
import re
import sys
import urllib.parse
import urllib.request

# Сервис ярлыков (SERVICE wikibase:label) сюда СОЗНАТЕЛЬНО не добавлен: с ним
# этот самый запрос молча вернул 24 485 строк вместо 84 582 — валидный CSV, без
# ошибки и без обрыва соединения. Часть речи сверяем по Q-идентификатору.
ЛЕКСЕМЫ = ("https://query.wikidata.org/sparql?query=" + urllib.parse.quote(
    "SELECT ?lemma ?cat WHERE { ?l dct:language wd:Q5146 ; "
    "wikibase:lemma ?lemma ; wikibase:lexicalCategory ?cat }"))
ЧАСТОТЫ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/pt/pt_50k.txt"

# Существительное, прилагательное, глагол, наречие. Имя собственное Q147276
# в список не входит намеренно.
ЧАСТИ_РЕЧИ = {"Q1084", "Q34698", "Q24905", "Q380057"}
АЛФАВИТ = "a-zãõçáéíóúâêô"
ПОТОЛОК_РАНГА = 30_000        # цели: тот же порог, что у английского набора
ПОТОЛОК_БАЗЫ = 30_000         # база не может быть реже цели
# 🔴 ТРИ ТЫСЯЧИ, А НЕ ДВЕ — РЕШЕНИЕ ДЕНИСА 06.09.2026, И ЦЕНА ЗАМЕРЕНА.
# Замер на английском: 2000 → 3000 раскладок это 272 → 407 КБ, то есть +0,9 МБ на
# семь языков. К вечеру языков стало десять, и цена выросла до ~1,6 МБ. Возражение
# высказано дважды, решение подтверждено — поднимаю.
# ⚠️ Поднятие ПОТОЛОК_БАЗЫ при этом НЕ помогает и не нужно: базы отсортированы по
# частоте, первые N годных берутся из верхушки в любом случае (замер: потолок ×2
# давал совпадение до байта).
МАКС_РАСКЛАДОК = 3_000
МИН_ДЛИНА = 4                 # трёхбуквенные слова — наполнитель: они дают
                              # +179 целей, но в раскладке всё равно вытесняются
                              # сортировкой по длине
МИН_ПОДСЛОВ = 8               # как у английского: слабая база тянет мусор
# 🔴 ЧИСЛО СЛОВ — ОСЬ СЛОЖНОСТИ, А НЕ ОДИН ПОТОЛОК НА ВЕСЬ НАБОР.
# Плоские 14 обрезали лестницу: после сортировки по числу слов верхняя четверть
# набора упиралась ровно в 14,0, то есть все поздние уровни были одинаковы.
# Края померены НА ЭТОМ языке, а не скопированы у соседа (у французского,
# например, запаса нет вовсе): сняв потолок, доступно медиана 17, среднее 21.0,
# максимум 102, больше четырнадцати подслов у 62% баз.
МАКС_ПОДСЛОВ_НАЧАЛО = 8
МАКС_ПОДСЛОВ_КОНЕЦ = 22             # больше на экран не помещается


def скачать(url: str, имя: str) -> str:
    if not os.path.exists(имя):
        # Викиданные отвечают 403 на пустой User-Agent, поэтому он задан явно.
        запрос = urllib.request.Request(url, headers={
            "User-Agent": "psygames-wordlist/1.0 (https://github.com/donosov999-ai)",
            "Accept": "text/csv",
        })
        with urllib.request.urlopen(запрос) as ответ, open(имя, "wb") as f:
            f.write(ответ.read())
    return имя


def леммы(путь: str) -> set:
    """Леммы нужных частей речи. Имя собственное отсекается дважды."""
    with open(путь, encoding="utf-8", newline="") as f:
        строки = list(csv.reader(f))
    # 🔴 Страховка от молчаливого обрыва выгрузки: усечённый ответ Викиданных
    # приходит как валидный CSV, отличить его можно только по числу строк.
    if len(строки) < 50_000:
        raise SystemExit(f"выгрузка лексем оборвана: {len(строки)} строк, ждали ~84 583. "
                         f"Удали {путь} и повтори")
    слова = set()
    for строка in строки[1:]:
        if len(строка) < 2:
            continue
        лемма, категория = строка[0], строка[1].rsplit("/", 1)[-1]
        if категория not in ЧАСТИ_РЕЧИ:
            continue
        if лемма[:1].isupper():        # главный заслон имён: тега Q147276 мало
            continue
        if re.fullmatch(rf"[{АЛФАВИТ}]+", лемма):   # отсекает словосочетания
            слова.add(лемма)
    return слова


def влезает(слово: str, банк: str) -> bool:
    остаток = list(банк)
    for c in слово:
        if c not in остаток:
            return False
        остаток.remove(c)
    return True


def main() -> int:
    словарь = леммы(скачать(ЛЕКСЕМЫ, "pt_lexemes.csv"))
    ранг = {}
    with open(скачать(ЧАСТОТЫ, "pt_50k.txt"), encoding="utf-8") as f:
        for i, стр in enumerate(f):
            части = стр.split()
            if части:
                ранг.setdefault(части[0], i)

    цели = sorted({w for w, r in ранг.items()
                   if r < ПОТОЛОК_РАНГА and w in словарь
                   and re.fullmatch(rf"[{АЛФАВИТ}]{{{МИН_ДЛИНА},8}}", w)})

    базы = sorted((w for w in цели if len(w) in (7, 8) and ранг[w] < ПОТОЛОК_БАЗЫ),
                  key=lambda w: ранг[w])          # самые узнаваемые вперёд

    раскладки = []
    for база in базы:
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        под.sort(key=lambda x: (-len(x), x))      # длинные интереснее коротких
        доля = len(раскладки) / max(1, МАКС_РАСКЛАДОК - 1)
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * min(1.0, доля))
        раскладки.append({"base": база, "words": sorted(под[:лимит])})
        if len(раскладки) >= МАКС_РАСКЛАДОК:
            break

    # 🔴 Проверка того, ради чего всё и делалось: каждое слово раскладки обязано
    # собираться из букв базы. Дешевле упасть здесь, чем в игре.
    for р in раскладки:
        плохие = [w for w in р["words"] if not влезает(w, р["base"])]
        if плохие:
            raise SystemExit(f"не собирается из «{р['base']}»: {плохие}")

    путь = "../frontend/src/constants/allWordsPt.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    print(f"целей {len(цели)} · базы-кандидаты {len(базы)} · раскладок {len(раскладки)} · "
          f"подслов медиана {длины[len(длины) // 2] if длины else 0} · "
          f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
