#!/usr/bin/env python3
"""
🔴 НАБОР СЛОВ «НАЙДИ ВСЕ СЛОВА» — ЯПОНСКИЙ НА КАТАКАНЕ.

📍 Разбор `../WORDLIST_NONLATIN.md` говорил: японский переносится только на кане.
Замер 06.09.2026 уточнил, на КАКОЙ именно — и ответ оказался не тот, что ждали.

⚠️ ХИРАГАНА НЕ ТЯНЕТ, И ЭТО ЧИСЛО, А НЕ ВПЕЧАТЛЕНИЕ. В корпусе 34 504 слова;
чистой хираганой пишутся 876 из них — 2,5%, и это в основном служебные слова.
Баз длиной 6–7 знаков среди них ВСЕГО 42. Режим вышел бы на три десятка уровней
против двух тысяч у соседей.

✅ КАТАКАНА ТЯНЕТ: 4179 слов, из них 983 базы длиной 6–7 знаков. Это пласт
заимствований и звукоподражаний (テーブル, コーヒー, パソコン) — не весь японский,
но живой, узнаваемый и, главное, записываемый ОДНИМИ ЗНАКАМИ, по одному в клетку.

⚠️ СМЕШИВАТЬ КАНЫ НЕЛЬЗЯ. Хирагана и катакана — разные знаки: テ и て это не одна
плитка, и банк из обеих превратился бы в кашу, где половина плиток не подходит ни
к одному слову. Набор строится строго на катакане.

⚠️ ЗНАК ДОЛГОТЫ ー ВХОДИТ В АЛФАВИТ. Он не буква и не знак чтения, а полноценная
часть записи: без него テブル вместо テーブル — другое слово, которого нет.
Поэтому он такая же плитка, как остальные.

🔴 ЧЕГО ЭТОТ НАБОР НЕ ДЕЛАЕТ: он не учит японскому письму вообще. Кандзи здесь
нет и быть не может — 28 611 слов корпуса содержат иероглифы, и «слово из одной
клетки» на них не раскладывается. Это упражнение на катакану, и называть его
«японским» без оговорки нечестно.

Источник: hermitdave/FrequencyWords (MIT), `ja_full.txt` — файла `ja_50k.txt` у
японского в репозитории НЕТ, проверено запросом к API: там лежат только
`ja_full.txt` и `ja_ignored.txt`.

Запуск:
    ./.venv/bin/python3 build_ja_targets.py
"""
import json
import os
import re
import sys
import urllib.request

ЧАСТОТЫ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/ja/ja_full.txt"
ПОТОЛОК_РАНГА = 40_000
ПОТОЛОК_БАЗЫ = 40_000     # корпус мал, отсекать по частоте почти нечего
МАКС_РАСКЛАДОК = 2_000
МИН_ДЛИНА = 2
МАКС_ДЛИНА = 5
ДЛИНА_БАЗЫ = (6, 7)
МИН_ПОДСЛОВ = 6           # ниже, чем у латиницы: корпус вчетверо меньше
МАКС_ПОДСЛОВ_НАЧАЛО = 6
МАКС_ПОДСЛОВ_КОНЕЦ = 16

КАТАКАНА = re.compile(r"^[ァ-ヶー]+$")


def скачать(url: str, имя: str) -> str:
    if not os.path.exists(имя):
        urllib.request.urlretrieve(url, имя)
    return имя


def влезает(слово: str, банк: str) -> bool:
    остаток = list(банк)
    for c in слово:
        if c not in остаток:
            return False
        остаток.remove(c)
    return True


def main() -> int:
    ранг = {}
    with open(скачать(ЧАСТОТЫ, "ja_full.txt"), encoding="utf-8") as f:
        for i, стр in enumerate(f):
            части = стр.split()
            if части:
                ранг.setdefault(части[0], i)

    цели = sorted({w for w, r in ранг.items()
                   if r < ПОТОЛОК_РАНГА and КАТАКАНА.fullmatch(w)
                   and МИН_ДЛИНА <= len(w) <= МАКС_ДЛИНА})
    базы = sorted((w for w, r in ранг.items()
                   if r < ПОТОЛОК_БАЗЫ and КАТАКАНА.fullmatch(w) and len(w) in ДЛИНА_БАЗЫ),
                  key=lambda w: ранг[w])

    раскладки = []
    for база in базы:
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        под.sort(key=lambda x: (-len(x), x))
        доля = len(раскладки) / max(1, МАКС_РАСКЛАДОК - 1)
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * min(1.0, доля))
        раскладки.append({"base": база, "words": sorted(под[:лимит])})
        if len(раскладки) >= МАКС_РАСКЛАДОК:
            break

    for р in раскладки:
        плохие = [w for w in р["words"] if not влезает(w, р["base"])]
        if плохие:
            raise SystemExit(f"не собирается из «{р['base']}»: {плохие}")

    путь = "../frontend/src/constants/allWordsJa.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    плитки = {c for р in раскладки for c in р["base"]}
    print(f"целей {len(цели)} · базы-кандидаты {len(базы)} · раскладок {len(раскладки)} · "
          f"подслов медиана {длины[len(длины) // 2] if длины else 0} "
          f"(мин {длины[0] if длины else 0}, макс {длины[-1] if длины else 0}) · "
          f"разных плиток {len(плитки)} · {os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
