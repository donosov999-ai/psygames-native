"""
🔴 НАБОР СЛОВ ДЛЯ РЕЖИМА «НАЙДИ ВСЕ СЛОВА» — ИТАЛЬЯНСКИЙ.

Собирает раскладки: база из 7–8 букв и слова, которые из неё складываются
(каждая плитка берётся не больше раза). Два источника, лицензия каждого
прочитана ФАЙЛОМ, а не бейджем:

  · Викиданные, пространство лексем — CC0 (общественное достояние). Проверено
    исходником страницы Wikidata:Licensing: «All structured data in the main,
    property and lexeme namespaces is made available under the Creative Commons
    CC0 License». Происхождение названо: это сами Викиданные, куда правка
    попадает только под CC0 по условиям использования сайта.
    64 938 итальянских лексем: лемма + часть речи + пометка имени собственного;
  · hermitdave/FrequencyWords — MIT (прочитан LICENSE, © 2016 Hermit Dave),
    происхождение названо в README: корпус OpenSubtitles 2018 через OPUS.

⚠️ ПОЧЕМУ НЕ ОРФОГРАФИЧЕСКИЙ СЛОВАРЬ, КАК У РУССКОГО. Для итальянского все
проверяльщики орфографии оказались под GPL, то есть вирусными на производный
набор:
  · LibreOffice/dictionaries/it_IT — README_it_IT.txt, строка 6: «License: GNU
    GPL 3» (пакет LibreItalia, форк linguistico.sourceforge.net);
  · Debian witalian — debian/copyright: «License: GPL-3+».

🔴 И ПОЧЕМУ НЕ napolux/paroleitaliane. У репозитория бейдж MIT и 900 000 слов —
выглядит находкой. Но README первым же абзацем говорит про сами списки:
«alcuni di provenienza ignota, recuperati da un vecchio hard disk» — часть
неизвестного происхождения, снята со старого жёсткого диска. Это ровно тот
случай, по которому в проекте отклонён danakt/russian-words: MIT-обёртка
лицензирует работу автора, а не данные, которых он не создавал. Не берём.

⚠️ ДИАКРИТИКА НЕ СНИМАЕТСЯ — à è é ì ò ù остаются отдельными плитками.
Замер 06.09.2026 по 6026 целям: диакритика есть у 99 слов (1,6%). Три способа:
  A оставить как есть  — 1224 раскладки, медиана 14, написание верное;
  B снять диакритику   — 1240 раскладок (+16), но 93 порождённые опечатки
                         («città»→«citta», «perché»→«perche») и 6 склеек, где
                         разные слова сливаются в одно: papa/papà, meta/metà,
                         pure/purè, menu/menù, casino/casinò;
  C выбросить слова с диакритикой — 1215 раскладок (−9), и из игры уходят
                         «perché», «città», «più».
Способ A не проигрывает по числу раскладок ничего заметного и единственный не
показывает игроку неверное написание. Шесть букв взяты ровно те, что названы в
задании: замер показал, что добавление í î ó ú не даёт НИ ОДНОГО нового слова.

⚠️ БАЗЫ БЕРУТСЯ ПО ЧАСТОТЕ, А НЕ ПО АЛФАВИТУ. Лимит на отсортированном обходе —
это выборка по ключу сортировки, а не «первые N штук»: английский скрипт шёл по
алфавиту и упирался в потолок 2000, из-за чего в наборе было 19 первых букв из
26, последняя база «swinging», а слов на t–z не было вовсе (починено 06.09.2026
тем же приёмом — стало 25 букв из 26; двадцать шестая `x` недостижима, английских
слов на x длиной 7–8 в первых 10 000 по частоте нет вообще).
Здесь базы сортируются по частотному рангу: в набор попадают 2000 самых
узнаваемых слов, и алфавит покрыт целиком.

Замер 06.09.2026: целей 6026 · раскладок 2000 · подслов на раскладку медиана 14.

Запуск (окружение общее с ru/en, дополнительных пакетов не нужно):
    ./.venv/bin/python3 build_it_targets.py
"""
import csv
import json
import os
import re
import sys
import urllib.parse
import urllib.request

# Лексемы Викиданных: лемма + часть речи. Сервис ярлыков (SERVICE wikibase:label)
# сюда СОЗНАТЕЛЬНО не добавлен — с ним запрос по португальскому молча вернул
# 24 485 строк вместо 84 582, без ошибки и без обрыва соединения. Часть речи
# сверяем по Q-идентификатору, он и так однозначен.
ЛЕКСЕМЫ = ("https://query.wikidata.org/sparql?query=" + urllib.parse.quote(
    "SELECT ?lemma ?cat WHERE { ?l dct:language wd:Q652 ; "
    "wikibase:lemma ?lemma ; wikibase:lexicalCategory ?cat }"))
ЧАСТОТЫ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/it/it_50k.txt"

# Существительное, прилагательное, глагол, наречие. Имя собственное — Q147276,
# его в списке нет намеренно: 1445 итальянских лексем помечены им (Roma, Italia,
# Giovanni). Служебные части речи (предлог, артикль, союз) в игре бесполезны.
ЧАСТИ_РЕЧИ = {"Q1084", "Q34698", "Q24905", "Q380057"}
АЛФАВИТ = "a-zàèéìòù"
ПОТОЛОК_РАНГА = 30_000        # цели: тот же порог, что у английского набора
ПОТОЛОК_БАЗЫ = 30_000         # база не может быть реже цели
МАКС_РАСКЛАДОК = 2_000
МИН_ДЛИНА = 4                 # трёхбуквенные слова — наполнитель: они дают
                              # +107 целей, но в раскладке всё равно вытесняются
                              # сортировкой по длине
МИН_ПОДСЛОВ = 8               # как у английского: слабая база тянет мусор
МАКС_ПОДСЛОВ = 14             # больше на экран не помещается


def скачать(url: str, имя: str) -> str:
    if not os.path.exists(имя):
        # Викиданные отвечают 403 на пустой User-Agent, поэтому он задан явно.
        запрос = urllib.request.Request(url, headers={
            "User-Agent": "psygames-wordlist/1.0 (https://github.com/donosov999-ai)",
            "Accept": "text/csv",
        })
        with urllib.request.urlopen(запрос) as ответ, open(имя, "wb") as f:
            f.write(ответ.read())
    return имя


def леммы(путь: str) -> set:
    """Леммы нужных частей речи. Имя собственное отсекается дважды."""
    with open(путь, encoding="utf-8", newline="") as f:
        строки = list(csv.reader(f))
    # 🔴 Страховка от молчаливого обрыва выгрузки: усечённый ответ Викиданных
    # приходит как валидный CSV, отличить его можно только по числу строк.
    if len(строки) < 40_000:
        raise SystemExit(f"выгрузка лексем оборвана: {len(строки)} строк, ждали ~64 939. "
                         f"Удали {путь} и повтори")
    слова = set()
    for строка in строки[1:]:
        if len(строка) < 2:
            continue
        лемма, категория = строка[0], строка[1].rsplit("/", 1)[-1]
        if категория not in ЧАСТИ_РЕЧИ:
            continue
        if лемма[:1].isupper():        # второй заслон: Roma, Pasqua, Svizzera
            continue
        if re.fullmatch(rf"[{АЛФАВИТ}]+", лемма):   # отсекает словосочетания
            слова.add(лемма)
    return слова


def влезает(слово: str, банк: str) -> bool:
    остаток = list(банк)
    for c in слово:
        if c not in остаток:
            return False
        остаток.remove(c)
    return True


def main() -> int:
    словарь = леммы(скачать(ЛЕКСЕМЫ, "it_lexemes.csv"))
    ранг = {}
    with open(скачать(ЧАСТОТЫ, "it_50k.txt"), encoding="utf-8") as f:
        for i, стр in enumerate(f):
            части = стр.split()
            if части:
                ранг.setdefault(части[0], i)

    цели = sorted({w for w, r in ранг.items()
                   if r < ПОТОЛОК_РАНГА and w in словарь
                   and re.fullmatch(rf"[{АЛФАВИТ}]{{{МИН_ДЛИНА},8}}", w)})

    базы = sorted((w for w in цели if len(w) in (7, 8) and ранг[w] < ПОТОЛОК_БАЗЫ),
                  key=lambda w: ранг[w])          # самые узнаваемые вперёд

    раскладки = []
    for база in базы:
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        под.sort(key=lambda x: (-len(x), x))      # длинные интереснее коротких
        раскладки.append({"base": база, "words": sorted(под[:МАКС_ПОДСЛОВ])})
        if len(раскладки) >= МАКС_РАСКЛАДОК:
            break

    # 🔴 Проверка того, ради чего всё и делалось: каждое слово раскладки обязано
    # собираться из букв базы. Дешевле упасть здесь, чем в игре.
    for р in раскладки:
        плохие = [w for w in р["words"] if not влезает(w, р["base"])]
        if плохие:
            raise SystemExit(f"не собирается из «{р['base']}»: {плохие}")

    путь = "../frontend/src/constants/allWordsIt.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    print(f"целей {len(цели)} · базы-кандидаты {len(базы)} · раскладок {len(раскладки)} · "
          f"подслов медиана {длины[len(длины) // 2] if длины else 0} · "
          f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
