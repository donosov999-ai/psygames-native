#!/usr/bin/env python3
"""
🔴 НАБОР СЛОВ «НАЙДИ ВСЕ СЛОВА» — АРАБСКИЙ.

📍 Разбор `../WORDLIST_NONLATIN.md` назвал арабский вторым по чистоте после
корейского: письмо буквенное, плитка равна букве, и словник собирается тем же
конвейером, что латинские. Работа не в данных, а в экране — см. ниже.

⚠️ ПЛИТОК ТРИДЦАТЬ ШЕСТЬ, А НЕ ДВАДЦАТЬ ВОСЕМЬ, и это не ошибка отбора. Замер по
корпусу: живьём встречаются 36 знаков — 28 базовых букв плюс варианты, которые в
письме РАЗНЫЕ и на клавиатуре набираются отдельно: أ إ آ (алиф с хамзой сверху,
снизу, с маддой), ة (та марбута), ى (алиф максура), ؤ ئ (хамза на носителе), ء
(одиночная хамза). Сводить их к базовой букве нельзя: `كتاب` и `كتأب` — разные
строки, и человек, собравший одно, не должен получать другое.

⚠️ ОГЛАСОВКИ ОТСЕИВАЮТСЯ ЦЕЛИКОМ. В корпусе 5234 слова несут значки харакат
(ً ٌ ٍ َ ُ ِ ّ ْ). Это НЕ буквы, а надстрочные пометки чтения: разложив их по
клеткам, мы показали бы человеку висящие в воздухе значки — та же беда, из-за
которой отвергнут хинди. Слово со значками не берётся вовсе, а не чистится: в
письме их обычно не пишут, и «очищенное» слово выглядело бы искажённым.

🔴 ЧТО ПРИДЁТСЯ СДЕЛАТЬ НА ЭКРАНЕ, а не здесь: арабское письмо идёт СПРАВА
НАЛЕВО, и буква меняет начертание по позиции в слове (изолированная, начальная,
срединная, конечная). В клетках стоят плитки — то есть изолированные формы, и
это правильно: игрок нажимает именно их. А целое слово читается связно, поэтому
показывается подписью, ровно как слоговые блоки у корейского.

Источник: hermitdave/FrequencyWords (MIT), корпус OpenSubtitles. Отдельного
словаря правописания у арабского здесь нет — частотный список служит и словарём,
и мерой узнаваемости, как у корейского.

Замер 06.09.2026: строк 50 000 · только-буквенных слов 44 021 · разных плиток 36 ·
медиана длины 5 · баз в 7 букв 6029, в 8 букв 2166.

Запуск:
    ./.venv/bin/python3 build_ar_targets.py
"""
import json
import os
import re
import sys
import urllib.request

ЧАСТОТЫ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/ar/ar_50k.txt"
ПОТОЛОК_РАНГА = 50_000
ПОТОЛОК_БАЗЫ = 20_000
# 🔴 ТРИ ТЫСЯЧИ, А НЕ ДВЕ — РЕШЕНИЕ ДЕНИСА 06.09.2026, И ЦЕНА ЗАМЕРЕНА.
# Замер на английском: 2000 → 3000 раскладок это 272 → 407 КБ, то есть +0,9 МБ на
# семь языков. К вечеру языков стало десять, и цена выросла до ~1,6 МБ. Возражение
# высказано дважды, решение подтверждено — поднимаю.
# ⚠️ Поднятие ПОТОЛОК_БАЗЫ при этом НЕ помогает и не нужно: базы отсортированы по
# частоте, первые N годных берутся из верхушки в любом случае (замер: потолок ×2
# давал совпадение до байта).
МАКС_РАСКЛАДОК = 3_000
МИН_ДЛИНА = 3
ДЛИНА_БАЗЫ = 7          # база всегда семь букв
# 🔴 ПОТОЛОК ЦЕЛИ — СЕМЬ, И ВЫБРАН ОН ПО «НАЙДИ ВСЕ СЛОВА», А НЕ ПО КРОССВОРДУ.
# У корейского потолок опускали ради кроссворда, и это помогло: 81,3% → 91,8% в
# телефонной коробке. У арабского не помогает ВООБЩЕ — замер по 400 уровням дал
# 69,4% и при семи, и при шести. Причина не в настройке, а в языке: средняя длина
# слова на уровне 5,3 против 4,5 у корейского, коротких слов почти нет, и сетка
# выходит стороной 10,7 вместо 9,1. Симуляция потолка 5 оставила годными 4 уровня
# из ста. Раз кроссворду арабский всё равно не даётся (он исключён из режима, см.
# `app/games/anagrams.tsx`), потолок взят богаче: семь даёт 40 645 целей против
# 34 616 при шести.
МАКС_ДЛИНА = 7
МИН_ПОДСЛОВ = 8
МАКС_ПОДСЛОВ_НАЧАЛО = 8
МАКС_ПОДСЛОВ_КОНЕЦ = 22

# Только буквы. Диапазон намеренно НЕ включает харакат (U+064B…U+0652) и татвиль.
БУКВЫ = re.compile(r"^[ء-غف-ي]+$")


def скачать(url: str, имя: str) -> str:
    if not os.path.exists(имя):
        urllib.request.urlretrieve(url, имя)
    return имя


def влезает(слово: str, банк: str) -> bool:
    остаток = list(банк)
    for c in слово:
        if c not in остаток:
            return False
        остаток.remove(c)
    return True


def main() -> int:
    ранг = {}
    with open(скачать(ЧАСТОТЫ, "ar_50k.txt"), encoding="utf-8") as f:
        for i, стр in enumerate(f):
            части = стр.split()
            if части:
                ранг.setdefault(части[0], i)

    цели = sorted({w for w, r in ранг.items()
                   if r < ПОТОЛОК_РАНГА and БУКВЫ.fullmatch(w)
                   and МИН_ДЛИНА <= len(w) <= МАКС_ДЛИНА})

    # ⚠️ БАЗЫ ОТБИРАЮТСЯ ОТДЕЛЬНО ОТ ЦЕЛЕЙ. Потолок длины цели ниже длины базы, и
    # если брать базы из списка целей, их там не окажется вовсе — первый прогон
    # с потолком 6 упал именно на этом: раскладок ноль, и падение пришло не с
    # осмысленным сообщением, а из `длины[0]` по пустому списку.
    базы = sorted((w for w, r in ранг.items()
                   if r < ПОТОЛОК_БАЗЫ and БУКВЫ.fullmatch(w) and len(w) == ДЛИНА_БАЗЫ),
                  key=lambda w: ранг[w])

    раскладки = []
    for база in базы:
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        под.sort(key=lambda x: (-len(x), x))
        доля = len(раскладки) / max(1, МАКС_РАСКЛАДОК - 1)
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * min(1.0, доля))
        раскладки.append({"base": база, "words": sorted(под[:лимит])})
        if len(раскладки) >= МАКС_РАСКЛАДОК:
            break

    for р in раскладки:
        плохие = [w for w in р["words"] if not влезает(w, р["base"])]
        if плохие:
            raise SystemExit(f"не собирается из «{р['base']}»: {плохие}")

    путь = "../frontend/src/constants/allWordsAr.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    плитки = {c for р in раскладки for c in р["base"]}
    print(f"целей {len(цели)} · базы-кандидаты {len(базы)} · раскладок {len(раскладки)} · "
          f"подслов медиана {длины[len(длины) // 2] if длины else 0} "
          f"(мин {длины[0]}, макс {длины[-1]}) · разных плиток {len(плитки)} · "
          f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
