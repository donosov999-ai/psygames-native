#!/usr/bin/env python3
"""
🔴 НАБОР СЛОВ ДЛЯ РЕЖИМА «НАЙДИ ВСЕ СЛОВА» — НЕМЕЦКИЙ.

Собирает раскладки: база из 7–8 букв и слова, которые из её плиток складываются.
Три источника, лицензия каждого прочитана ФАЙЛОМ, а не бейджем:

  · Викиданные, лексемы немецкого (Q188) — CC0, то есть общественное достояние.
    Берутся SPARQL-запросом к query.wikidata.org: лемма + часть речи. Это
    замена морфологии: у русского роль «только начальная форма» играет
    pymorphy3, здесь — сам факт, что слово ЕСТЬ лемма в базе лексем;
  · hermitdave/FrequencyWords — MIT (прочитан `LICENSE`, © 2016 Hermit Dave),
    источник данных назван: корпус OpenSubtitles через OPUS. Даёт частотность;
  · LDNOOBW (список Shutterstock) — CC BY 4.0 (прочитан `LICENSE`), происхождение
    названо в README: рабочий фильтр их автодополнения. Используется ТОЛЬКО как
    отсев, в набор не попадает ни одним словом.

⚠️ ПОЧЕМУ НЕ HUNSPELL. Первым кандидатом был немецкий орфографический словарь
(igerman98 Бьёрна Якке, он же в LibreOffice и в wooorm/dictionaries). Открыт файл
лицензии: «GNU General Public License version 2 or 3». GPL — копилефт, он вирусен
на производную базу так же, как CC BY-SA, и в список разрешённых не входит.
Второй кандидат, michmech/lemmatization-lists (358 473 немецких пары), отклонён по
файлу README: лицензия ODbL — тоже share-alike, и данные там как раз из тех самых
hunspell-словарей OpenOffice.

⚠️ УМЛАУТЫ НЕ НОРМАЛИЗУЮТСЯ: ä, ö, ü, ß — свои плитки, а не «ae/oe/ue/ss».
Решено ЗАМЕРОМ, а не вкусом. Прогнаны три варианта на одних и тех же 7428 целях:

    умлаут = своя плитка          2007 раскладок, медиана 14
    ä→ae, ö→oe, ü→ue, ß→ss        2135 раскладок, медиана 14
    слова с умлаутами выброшены   1799 раскладок, медиана 14

Нормализация даёт +6,4% раскладок и НЕ двигает медиану — то есть платить за неё
нечем: она переписала бы «Büro» как «buero», а «Straße» как «strasse», и немец
увидел бы в игре опечатку. 208 баз из 2007 содержат умлаут, у них медиана 11
против 14 по набору — просадка есть, но она внутри игрового диапазона.

⚠️ ВСЁ В НИЖНЕМ РЕГИСТРЕ, хотя немецкие существительные пишутся с прописной.
Плитки сравниваются посимвольно: банк из «Haus» дал бы плитку «H», и цель «hase»
из него бы не собралась. Регистр — это не орфография набора, а требование движка.

⚠️ ЦЕЛИ ОТ ЧЕТЫРЁХ БУКВ. Трёхбуквенный хвост немецкого — это заимствования и
аббревиатуры: из 267 трёхбуквенных кандидатов топ-30k набрались `sms`, `lkw`,
`dvd`, `ekg`, `gps`, `mrt`, `ddr`, `hiv`, `suv`, `mmm`, `aua`, `buh`, `wau`, `hui`,
плюс английское `top`, `run`, `web`, `cut`, `hot`, `car`. Ровно та же картина, что
у английского Moby, и порог тот же.

Замер 06.09.2026: лемм в Викиданных 39 288 · целей 7344 (из 7428 до отсева:
66 забрала брань, 18 — список имён) · раскладок 2000 · подслов на раскладку:
медиана 14, минимум 8 · 251 КБ · сборка с пустого кэша 18 секунд, файл побайтно
тот же (md5 030d653c…).

Запуск. Зависимостей нет вообще, только стандартная библиотека — в отличие от
русского скрипта, которому нужен pymorphy3:
    python3 build_de_targets.py
"""
import json
import os
import re
import sys
import tempfile
import urllib.parse
import urllib.request

# Викиданные отдают лексемы через SPARQL. Длина леммы ограничена прямо в запросе:
# 3–8 символов — иначе в ответе 242 тысячи строк вместо 41 тысячи, и по сети
# едут композиты вроде «Donaudampfschifffahrt», которые в игру всё равно не идут.
ЛЕКСЕМЫ = """SELECT ?lemma ?cat WHERE {
  ?l <http://purl.org/dc/terms/language> <http://www.wikidata.org/entity/Q188> ;
     <http://wikiba.se/ontology#lemma> ?lemma ;
     <http://wikiba.se/ontology#lexicalCategory> ?cat .
  FILTER(STRLEN(?lemma) >= 3 && STRLEN(?lemma) <= 8)
}"""
ТОЧКА_SPARQL = "https://query.wikidata.org/sparql"
ЧАСТОТЫ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/de/de_50k.txt"
БРАНЬ = "https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/de"

# Части речи Викиданных. Знаменательные пускаем в цели, «имя собственное» —
# наоборот, признак того, что слово надо выбросить.
ЗНАМЕНАТЕЛЬНЫЕ = {"Q1084": "сущ.", "Q34698": "прил.", "Q24905": "глаг.", "Q380057": "нареч."}
ИМЯ_СОБСТВЕННОЕ = "Q147276"

ПОТОЛОК_РАНГА = 30_000        # цели: слово должно быть на слуху, а не просто быть
ПОТОЛОК_БАЗЫ = 30_000         # ⚠️ у английского здесь 10 000, а тут равен потолку
                              # целей — и вот почему. У английского базой могли
                              # стать географические имена (`aberdeen`), которых
                              # системный список имён не знает. Здесь имена уже
                              # отсеяны частью речи Викиданных, а сама база игроку
                              # НЕ показывается: движок берёт из неё только плитки
                              # (см. allWordsLetters). Отдельный потолок ничего бы
                              # не защитил, зато срезал бы набор до 1750 раскладок.
# 🔴 ТРИ ТЫСЯЧИ, А НЕ ДВЕ — РЕШЕНИЕ ДЕНИСА 06.09.2026, И ЦЕНА ЗАМЕРЕНА.
# Замер на английском: 2000 → 3000 раскладок это 272 → 407 КБ, то есть +0,9 МБ на
# семь языков. К вечеру языков стало десять, и цена выросла до ~1,6 МБ. Возражение
# высказано дважды, решение подтверждено — поднимаю.
# ⚠️ Поднятие ПОТОЛОК_БАЗЫ при этом НЕ помогает и не нужно: базы отсортированы по
# частоте, первые N годных берутся из верхушки в любом случае (замер: потолок ×2
# давал совпадение до байта).
МАКС_РАСКЛАДОК = 3_000
МИН_ДЛИНА = 4
МИН_ПОДСЛОВ = 8               # столько же, сколько у английского: при пороге 6 в
                              # набор влезают слабые базы, а кандидатов и так 2341
# 🔴 ЧИСЛО СЛОВ — ОСЬ СЛОЖНОСТИ, А НЕ ОДИН ПОТОЛОК НА ВЕСЬ НАБОР.
# Плоские 14 обрезали лестницу: после сортировки по числу слов верхняя четверть
# набора упиралась ровно в 14,0, то есть все поздние уровни были одинаковы.
# Края померены НА ЭТОМ языке, а не скопированы у соседа (у французского,
# например, запаса нет вовсе): сняв потолок, доступно медиана 16, среднее 18.7,
# максимум 73, больше четырнадцати подслов у 56% баз.
МАКС_ПОДСЛОВ_НАЧАЛО = 8
МАКС_ПОДСЛОВ_КОНЕЦ = 20             # больше на экран не помещается

# ⚠️ ОТСЕВ БРАНИ. Частотность построена по субтитрам, а субтитры — это разговорная
# речь со всей её лексикой: в топ-30k немецкого нецензурного больше тридцати слов.
# Список LDNOOBW ловит 32 из них, но мимо него проходят производные и формы,
# которых в нём просто нет. Ниже — то, что найдено замером по целям и в LDNOOBW
# отсутствует. Сравнение ТОЧНОЕ, не по подстроке: подстрока убила бы невинные
# `marsch`, `barsch`, `scheibe`, `analyse`, `banal`, `kanal`, `drogerie`.
# Граница проведена по «вульгарное и сексуальное», а не по «мрачное»: `krieg`,
# `messer`, `mord`, `teufel`, `sünde` — обычные слова немецкого и остаются.
БРАНЬ_ЕЩЁ = {
    "ficke", "ficker", "verfickt", "fotzen", "huren", "scheiß", "scheißen", "scheißer",
    "pisse", "furz", "furzen", "kotzen", "sperma", "titte", "titten", "hoden", "busen",
    "klitoris", "dildo", "kondom", "tampon", "anal", "oral", "bordell", "nutten",
    "zuhälter", "strip", "strippen", "stripper", "wichse", "geil", "geile", "geilen",
    "sexy", "pervers", "perverse", "spasti", "arschloch", "ärsche", "koks",
}

# ⚠️ ИМЕНА, КОТОРЫЕ ЧАСТЬ РЕЧИ НЕ ЛОВИТ. Правило «имя собственное и ни одного
# знаменательного чтения» пропускает слова, у которых в Викиданных есть ОБА
# чтения: `Lena` там и имя, и существительное; `Hagen` — имя, а строчное `hagen`
# помечено глаголом. Регистр не спасает: цели приведены к нижнему.
# 🔴 Замер по собранному набору: имена попали в 217 раскладок из 2000 — каждая
# девятая, а `anke`, `este`, `lena` из четырёх букв влезают чуть ли не в любую
# базу. Ужесточить правило до «любое чтение-имя — вон» нельзя: спорных слов
# всего 44, и среди них `essen`, `ofen`, `mitte`, `sieg`, `nord`, `burg`, `list`,
# `ekel`, `gießen`, `erlangen`, `russisch`, `weber`, `heide` — то есть обычных
# слов там БОЛЬШЕ, чем имён. Поэтому имена выписаны руками: множество спорных
# конечно и целиком просмотрено.
# Не выброшены `münster` (собор), `jersey` (ткань), `polen` (полить/полюса),
# `este` (эстонец), `weber`, `müller`, `heide`, `dietrich` — это обычные
# существительные, которые лишь СОВПАЛИ с фамилией или городом.
ИМЕНА_ЕЩЁ = {
    "amelie", "anke", "benjamin", "bill", "bordeaux", "faber", "frank", "hagen",
    "hugo", "johannes", "karibik", "lena", "meier", "peter", "schenk", "stefan",
    "stephan", "wilhelm",
}

# Кэш качается во ВРЕМЕННУЮ папку, а не рядом со скриптом. Причина прозаическая:
# в .gitignore проекта перечислены поимённо только файлы русского и английского
# наборов, немецких масок там нет, и скачанное засорило бы `git status`.
КЭШ = os.environ.get("DE_CACHE", os.path.join(tempfile.gettempdir(), "psygames-de-wordlist"))
ВЫХОД = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "..", "frontend", "src", "constants", "allWordsDe.json")
# Викиданные требуют внятный User-Agent и режут запросы без него.
АГЕНТ = "psygames-wordlist/1.0 (https://github.com/donosov999-ai; d.onosov999@gmail.com)"


def скачать(url: str, имя: str) -> str:
    os.makedirs(КЭШ, exist_ok=True)
    путь = os.path.join(КЭШ, имя)
    if not os.path.exists(путь):
        req = urllib.request.Request(url, headers={"User-Agent": АГЕНТ})
        with urllib.request.urlopen(req, timeout=300) as r, open(путь, "wb") as f:
            f.write(r.read())
    return путь


def лексемы() -> dict[str, set[str]]:
    """Лемма (в нижнем регистре) → множество частей речи, в которых она есть."""
    url = ТОЧКА_SPARQL + "?" + urllib.parse.urlencode({"query": ЛЕКСЕМЫ, "format": "json"})
    из_базы: dict[str, set[str]] = {}
    with open(скачать(url, "de_lexemes.json"), encoding="utf-8") as f:
        for строка in json.load(f)["results"]["bindings"]:
            лемма = строка["lemma"]["value"].lower()
            из_базы.setdefault(лемма, set()).add(строка["cat"]["value"].rsplit("/", 1)[1])
    return из_базы


def влезает(слово: str, банк: str) -> bool:
    остаток = list(банк)
    for c in слово:
        if c not in остаток:
            return False
        остаток.remove(c)
    return True


def main() -> int:
    из_базы = лексемы()
    # Слово с частью речи «имя собственное» И БЕЗ единой знаменательной — это
    # только имя, его вон. А вот `ernst` (и имя, и существительное «серьёзность»)
    # остаётся: у него знаменательное чтение есть.
    имена = {w for w, ч in из_базы.items()
             if ИМЯ_СОБСТВЕННОЕ in ч and not (ч & set(ЗНАМЕНАТЕЛЬНЫЕ))} | ИМЕНА_ЕЩЁ
    знаменательные = {w for w, ч in из_базы.items() if ч & set(ЗНАМЕНАТЕЛЬНЫЕ)}

    ранг: dict[str, int] = {}
    with open(скачать(ЧАСТОТЫ, "de_50k.txt"), encoding="utf-8") as f:
        for i, строка in enumerate(f):
            ранг.setdefault(строка.split()[0], i)

    брань = {w.strip().lower() for w in open(скачать(БРАНЬ, "de_bad.txt"), encoding="utf-8") if w.strip()}
    брань |= БРАНЬ_ЕЩЁ

    немецкие_буквы = re.compile(rf"[a-zäöüß]{{{МИН_ДЛИНА},8}}")
    цели = sorted({w for w, r in ранг.items()
                   if r < ПОТОЛОК_РАНГА and w in знаменательные and w not in имена
                   and w not in брань and немецкие_буквы.fullmatch(w)})

    раскладки = []
    for база in (w for w in цели if len(w) in (7, 8) and ранг[w] < ПОТОЛОК_БАЗЫ):
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        под.sort(key=lambda x: (-len(x), x))    # длинные интереснее коротких
        доля = len(раскладки) / max(1, МАКС_РАСКЛАДОК - 1)
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * min(1.0, доля))
        раскладки.append({"base": база, "words": sorted(под[:лимит])})

    # ⚠️ ОБРЕЗАТЬ НАДО ПО ЧАСТОТНОСТИ, А НЕ ПО АЛФАВИТУ. Английский скрипт рвёт
    # цикл, как только наберётся 2000 раскладок, и его набор кончается на
    # `swinging`: букв t–z в базах нет вообще. Здесь кандидатов 2341, и лишние
    # 341 отбираются по редкости базы, а не по тому, что «уже хватит».
    раскладки.sort(key=lambda x: ранг[x["base"]])
    раскладки = sorted(раскладки[:МАКС_РАСКЛАДОК], key=lambda x: x["base"])

    # 🔴 ГЛАВНАЯ ПРОВЕРКА: несобираемая цель делает уровень непроходимым.
    for x in раскладки:
        for w in x["words"]:
            assert влезает(w, x["base"]), f"{w} не собирается из {x['base']}"

    with open(ВЫХОД, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))

    длины = sorted(len(x["words"]) for x in раскладки)
    print(f"лемм в Викиданных {len(из_базы)} · целей {len(цели)} · "
          f"раскладок {len(раскладки)} · подслов медиана "
          f"{длины[len(длины) // 2] if длины else 0} · минимум {длины[0] if длины else 0} · "
          f"{os.path.getsize(ВЫХОД) // 1024} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
