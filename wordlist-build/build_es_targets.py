    основы, имена = словарь(скачать(СЛОВАРЬ, "es_index.dic"))
    имена |= личные_имена()
    глагольные = флаги_спряжения(скачать(АФФИКСЫ, "es_index.aff"))
    if not глагольные:
        print("⚠️ в index.aff не нашлось ни одного флага спряжения — формат сменился",
              file=sys.stderr)
        return 1

    ранг = {}
    with open(скачать(ЧАСТОТЫ, "es_50k.txt"), encoding="utf-8") as f:
        for i, стр in enumerate(f):
            ч = стр.split()
            if ч:
                ранг.setdefault(свернуть(ч[0].lower()), i)

    def годное(w: str, фл: set) -> bool:
        if фл & ИМЕННЫЕ_ФЛАГИ:
            return True
        # Инфинитив: спрягается и оканчивается на -ar/-er/-ir. Одного спряжения
        # мало — надо убедиться, что основа и есть начальная форма.
        return bool(фл & глагольные) and w.endswith(("ar", "er", "ir"))

    цели, ранг_ц = set(), {}
    for w, r in ранг.items():
        if (r >= ПОТОЛОК_ПО_ДЛИНЕ.get(len(w), ПОТОЛОК_РАНГА) or w in имена
                or w in СЛУЖЕБНЫЕ or w in ВЗРОСЛОЕ or w in НЕУЗНАВАЕМЫЕ):
            continue
        фл = основы.get(w)
        if not фл or not годное(w, фл):
            continue
        if not re.fullmatch(rf"[a-zñ]{{{МИН_ДЛИНА},8}}", w):
            continue
        цели.add(w)
        ранг_ц[w] = r
    цели = sorted(цели)

    # ⚠️ БАЗЫ ИДУТ ПО ЧАСТОТЕ, А НЕ ПО АЛФАВИТУ. Английский набор обрывается на
    # `swinging`: он перебирает базы по алфавиту и упирается в потолок 2000, из-за
    # чего вся вторая половина алфавита в игру не попадает вовсе. По частоте
    # потолок отсекает редкое, а не хвост азбуки.
    базы = sorted((w for w in цели if len(w) in (7, 8) and ранг_ц[w] < ПОТОЛОК_БАЗЫ),
                  key=lambda w: ранг_ц[w])

    раскладки = []
    for база in базы:
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        доля = len(раскладки) / max(1, МАКС_РАСКЛАДОК - 1)
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * min(1.0, доля))
        раскладки.append({"base": база, "words": подобрать(под, ранг_ц, лимит)})
        if len(раскладки) >= МАКС_РАСКЛАДОК:
            break
    раскладки.sort(key=lambda p: p["base"])

    # 🔴 ПРОВЕРКА ПЕРЕД ЗАПИСЬЮ. Несобираемая цель делает уровень непроходимым, а
    # заметно это только на живом экране, поэтому проверяем здесь и падаем.
    for p in раскладки:
        assert unicodedata.is_normalized("NFC", p["base"]), p["base"]
        assert 7 <= len(p["base"]) <= 8, p["base"]
        assert len(set(p["words"])) == len(p["words"]), p["base"]
        for w in p["words"]:
            assert влезает(w, p["base"]), f"{w} не собирается из {p['base']}"
            assert unicodedata.is_normalized("NFC", w), w
            assert w != p["base"] and МИН_ДЛИНА <= len(w) <= 8, w

    путь = "../frontend/src/constants/allWordsEs.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    print(f"целей {len(цели)} · баз {len(базы)} · раскладок {len(раскладки)} · "
          f"подслов медиана {statistics.median(длины):.0f} "
          f"(мин {длины[0]}, макс {длины[-1]}) · "
          f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


