#!/usr/bin/env python3
"""
🔴 КОЛЬЦА «КВАДРАТА СЛОВ» — ГОТОВЫМИ ПАКАМИ, А НЕ СБОРКОЙ НА ЛЕТУ.

📍 ЗАЧЕМ. Режим жил на двух языках (ru, en), потому что кольца собирались в
рантайме из фил-вордового пула — а он есть у пяти языков и мал: 136
пятибуквенных слов у русского. Наборы «Найди все слова» дают их куда больше — от
684 у русского до 2898 у корейского, и на все восемь языков.

⚠️ НО ПРОСТО ПОДМЕНИТЬ ИСТОЧНИК НЕЛЬЗЯ — ЗАМЕР 06.09.2026: из 400 слов русского
собирается 90 283 кольца за 6 секунд, из 600 — 451 993 за 32 секунды, у немецкого
из 800 слов 4 107 056 колец за шесть минут. Считать это при открытии экрана —
значит подвесить приложение. Поэтому кольца собираются здесь, отбираются и лежат
готовым JSON, как и наборы слов.

⚠️ ИСТОЧНИК ОГРАНИЧЕН САМЫМИ ЧАСТЫМИ СЛОВАМИ, и это не экономия, а качество:
кольцо из четырёх редких слов человек не соберёт, сколько ему ни думай. Порядок
в наборе уже частотный — берём первые `ИСТОЧНИК` пятибуквенных.

ЧТО В ФАЙЛЕ: список колец, у каждого четыре слова по сторонам (верх, право, низ,
лево) и число ЛИШНИХ слов, собирающихся из его банка, — это ось трудности, по
ней же список и отсортирован. Разбор оси — в `anagrams/core/ring.ts`.

Запуск:
    ./.venv/bin/python3 build_rings.py
"""
import json
import os
import sys
from collections import Counter

ЯЗЫКИ = {"ru": "Ru", "en": "En", "de": "De", "es": "Es",
         "fr": "Fr", "it": "It", "pt": "Pt", "ko": "Ko"}
СТОРОНА = 5
ИСТОЧНИК = 200        # самых частых пятибуквенных слов идёт в перебор
МАКС_КОЛЕЦ = 1_000    # тысяча уровней — заведомо больше, чем проходят; вдвое легче
БАНК_МАКС = 12        # плиток в банке кольца: 16 клеток периметра минус 4 общих угла


def пятибуквенные(набор) -> list:
    """Пятибуквенные слова в порядке набора — то есть по убыванию частоты."""
    из, виден = [], set()
    for р in набор:
        for w in (р["base"], *р["words"]):
            if len(w) == СТОРОНА and w not in виден:
                виден.add(w)
                из.append(w)
    return из


def банк(верх, право, низ, лево) -> str:
    """
    Плитки кольца — РОВНО ТО ЖЕ, что считает `буквыКольца` в движке.

    ⚠️ Здесь стояло «все буквы периметра, углы один раз», и это была другая
    величина: гейт поймал кольцо `beben` с банком 13 при потолке 12. Правило
    такое: для каждой буквы берётся МАКСИМУМ её вхождений среди четырёх слов —
    столько плиток и нужно, чтобы собрать любое из них. Урок ровно тот же, что и
    в «Слове-квадрате»: САЛАТ не набирался при одной плитке «А».
    """
    нужно = {}
    for слово in (верх, право, низ, лево):
        c = Counter(слово)
        for ch, n in c.items():
            нужно[ch] = max(нужно.get(ch, 0), n)
    return "".join(ch * n for ch, n in sorted(нужно.items()))


def собрать(слова: list) -> list:
    """
    Кольца: верх и низ идут слева направо, лево и право — сверху вниз, углы общие.

    ⚠️ Перебор идёт по ПЕРВОЙ БУКВЕ, иначе это четвёртая степень словаря. Слова в
    кольце обязаны быть разными: одно и то же слово дважды — это одна головоломка,
    выданная как две.
    """
    по_первой = {}
    for w in слова:
        по_первой.setdefault(w[0], []).append(w)
    из, ключи = [], set()
    for верх in слова:
        for лево in по_первой.get(верх[0], ()):
            if лево == верх:
                continue
            for право in по_первой.get(верх[-1], ()):
                if право in (верх, лево):
                    continue
                for низ in по_первой.get(лево[-1], ()):
                    if низ in (верх, лево, право) or низ[-1] != право[-1]:
                        continue
                    б = банк(верх, право, низ, лево)
                    if len(б) > БАНК_МАКС:
                        continue
                    # ⚠️ Ключ против симметрий: одно кольцо читается восемью
                    # способами (четыре поворота × отражение), и без ключа набор
                    # был бы забит одной и той же головоломкой.
                    формы = []
                    ч = (верх, право, низ, лево)
                    for _ in range(4):
                        формы.append("|".join(ч))
                        ч = (ч[3][::-1], ч[0], ч[1][::-1], ч[2])
                    ч = (верх[::-1], лево, низ[::-1], право)
                    for _ in range(4):
                        формы.append("|".join(ч))
                        ч = (ч[3][::-1], ч[0], ч[1][::-1], ч[2])
                    к = min(формы)
                    if к in ключи:
                        continue
                    ключи.add(к)
                    из.append((верх, право, низ, лево, б))
                    if len(из) >= МАКС_КОЛЕЦ * 3:
                        return из
    return из


def влезает(слово: str, б: str) -> bool:
    о = list(б)
    for c in слово:
        if c not in о:
            return False
        о.remove(c)
    return True


def main() -> int:
    for яз, Я in ЯЗЫКИ.items():
        путь_н = f"../frontend/src/constants/allWords{Я}.json"
        if not os.path.exists(путь_н):
            print(f"  {яз}: набора нет, пропуск")
            continue
        набор = json.load(open(путь_н, encoding="utf-8"))
        слова = пятибуквенные(набор)[:ИСТОЧНИК]
        кольца = собрать(слова)

        # Трудность: сколько ЛИШНИХ слов языка собирается из того же банка.
        # Каждое даст игроку «мимо» — это и есть трение уровня.
        # ⚠️ СЧИТАЕМ МУЛЬТИМНОЖЕСТВАМИ, А НЕ ПЕРЕБОРОМ БУКВ. Прямая проверка
        # «влезает» на 6000 колец × 6000 слов — это 36 миллионов разборов строк,
        # и сборка не укладывалась в десять минут. Counter считается по одному
        # разу на слово, а вычитание словарей на порядок дешевле.
        все_слова = {w for р in набор for w in р["words"]} | {р["base"] for р in набор}
        счёт = {w: Counter(w) for w in все_слова}
        по_буквам = {}
        for w, c in счёт.items():
            по_буквам.setdefault(frozenset(c), []).append((w, c))
        с_весом = []
        for верх, право, низ, лево, б in кольца:
            свои = {верх, право, низ, лево}
            cб = Counter(б)
            буквы_б = frozenset(cб)
            лишних = 0
            for набор_букв, пара in по_буквам.items():
                if not набор_букв <= буквы_б:
                    continue          # хоть одной буквы нет — всё слово мимо
                for w, c in пара:
                    if w not in свои and not (c - cб):
                        лишних += 1
            с_весом.append((лишних, верх, право, низ, лево))
        с_весом.sort(key=lambda x: (x[0], x[1], x[2], x[3], x[4]))
        отобрано = с_весом[:МАКС_КОЛЕЦ]

        путь = f"../frontend/src/constants/rings{Я}.json"
        with open(путь, "w", encoding="utf-8") as f:
            json.dump([{"t": в, "r": п, "b": н, "l": л, "x": лишних}
                       for лишних, в, п, н, л in отобрано],
                      f, ensure_ascii=False, separators=(",", ":"))
        веса = [x[0] for x in отобрано]
        print(f"  {яз}: слов-источников {len(слова)} · колец найдено {len(кольца)} · "
              f"отобрано {len(отобрано)} · лишних {веса[0]}…{веса[-1]} · "
              f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
