#!/usr/bin/env python3
"""
🔴 ЗАМЕР: СКОЛЬКО НАШИХ РАСКЛАДОК «ВСЕ СЛОВА» ЛОЖИТСЯ В КРОССВОРДНУЮ СЕТКУ.

📍 ЗАЧЕМ. Сравнение с «Магией Слов» (Google Play, снято 05–06.09.2026): там
слова, собранные из общего набора букв, не просто зачёркиваются в списке, а
ВПИСЫВАЮТСЯ в кроссвордную сетку и пересекаются буквами; уже открытые буквы
подсказывают следующее слово. У нас данные под это уже лежат:
`frontend/src/constants/allWords{Ru,En,...}.json` — база из 7–8 букв и 6–14
слов, собираемых из её плиток. Вопрос был замером, а не прикидкой: сколько
раскладок вообще укладывается, какой выходит размер сетки и сколько слов
остаётся за бортом.

⚠️ ЧТО ИМЕННО СЧИТАЕТСЯ УКЛАДКОЙ. Не «слова как-нибудь наложились», а правила
классического криптоворда (criss-cross), те же, по которым устроена «Магия
Слов»:

  1. слово идёт слева направо или сверху вниз, без изломов;
  2. чужая буква на пути принимается ТОЛЬКО если совпала — это пересечение;
  3. клетка перед первой буквой и после последней обязана быть пустой, иначе на
     поле читается склейка вроде «КОТ»+«ОСА» = «КОТОСА»;
  4. пустая клетка слова не касается боком чужой буквы: два слова, идущие
     параллельно вплотную, порождают в поперечнике мусорные пары букв;
  5. каждое слово, кроме первого, пересекается хотя бы с одним уже уложенным —
     отсюда связность сетки следует по построению, её не надо проверять потом.

Правило 4 — то самое, из-за которого «уложилось всё» не бывает бесплатным: без
него в сетку влезает что угодно, но читается она как каша.

🔴 ПОЧЕМУ УКЛАДЧИК ЖАДНЫЙ С ПЕРЕЗАПУСКАМИ, А НЕ ПОЛНЫЙ ПЕРЕБОР. Полный перебор
14 слов по всем позициям и ориентациям — это задача упаковки, она комбинаторно
взрывается, а ответ нужен по 10 тысячам раскладок. Жадность с N случайными
порядками даёт НИЖНЮЮ оценку: настоящая доля укладываемых раскладок не меньше
измеренной. Для вывода «режим на этих данных делается» нижней оценки хватает —
она не может соврать в выгодную сторону.

Запуск:
    wordlist-build/.venv/bin/python3 wordlist-build/probe_crossword.py
    ... --locales ru,en --restarts 24
"""
from __future__ import annotations

import argparse
import json
import random
import statistics
from collections import Counter
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
КОНСТАНТЫ = КОРЕНЬ / "frontend" / "src" / "constants"

ГОР = 0
ВЕР = 1


class Сетка:
    """
    Поле кроссворда. Координаты не ограничены и могут быть отрицательными:
    рамка считается по факту, а не выделяется заранее. Два владельца на клетку
    (`гор` и `вер`) — потому что клетка законно принадлежит двум словам сразу,
    но только РАЗНЫХ направлений; два горизонтальных слова в одной клетке — это
    наложение вдоль строки, и оно запрещено.
    """

    __slots__ = ("буквы", "гор", "вер", "слова")

    def __init__(self) -> None:
        self.буквы: dict[tuple[int, int], str] = {}
        self.гор: set[tuple[int, int]] = set()
        self.вер: set[tuple[int, int]] = set()
        self.слова: list[tuple[str, int, int, int]] = []

    def можно(self, слово: str, r: int, c: int, d: int) -> int | None:
        """
        Число пересечений, если слово встанет сюда, либо None — если нельзя.
        Ноль пересечений — законный ответ (так ставится первое слово); вызывающий
        сам решает, годится ли ему ноль.
        """
        dr, dc = (0, 1) if d == ГОР else (1, 0)
        свои = self.гор if d == ГОР else self.вер
        # Правило 3: торцы. Клетка до начала и после конца обязаны быть пустыми.
        if (r - dr, c - dc) in self.буквы:
            return None
        if (r + dr * len(слово), c + dc * len(слово)) in self.буквы:
            return None
        пересечений = 0
        for i, ch in enumerate(слово):
            rr, cc = r + dr * i, c + dc * i
            if (rr, cc) in свои:
                return None  # вдоль своего же направления слова не наслаиваются
            есть = self.буквы.get((rr, cc))
            if есть is not None:
                if есть != ch:
                    return None  # правило 2: чужая буква принимается только совпав
                пересечений += 1
            else:
                # Правило 4: пустая клетка не касается боком чужой буквы.
                if d == ГОР:
                    if (rr - 1, cc) in self.буквы or (rr + 1, cc) in self.буквы:
                        return None
                else:
                    if (rr, cc - 1) in self.буквы or (rr, cc + 1) in self.буквы:
                        return None
        return пересечений

    def ставить(self, слово: str, r: int, c: int, d: int) -> None:
        dr, dc = (0, 1) if d == ГОР else (1, 0)
        свои = self.гор if d == ГОР else self.вер
        for i, ch in enumerate(слово):
            rr, cc = r + dr * i, c + dc * i
            self.буквы[(rr, cc)] = ch
            свои.add((rr, cc))
        self.слова.append((слово, r, c, d))

    def рамка(self) -> tuple[int, int]:
        """(строк, столбцов) минимального прямоугольника вокруг занятых клеток."""
        if not self.буквы:
            return (0, 0)
        rs = [p[0] for p in self.буквы]
        cs = [p[1] for p in self.буквы]
        return (max(rs) - min(rs) + 1, max(cs) - min(cs) + 1)


def уложить(
    слова: list[str],
    порядок: list[int],
    макс_строк: int | None,
    макс_столбцов: int | None,
) -> tuple[Сетка, list[str]]:
    """
    Один жадный проход в заданном порядке слов. Возвращает сетку и слова,
    которым места не нашлось.

    ⚠️ ДВА ПРОХОДА, А НЕ ОДИН. Слово, не вставшее третьим, часто встаёт
    последним: к тому времени на поле больше букв, и появляются новые точки
    пересечения. Без второго прохода замер занижал бы результат на ровном месте.
    """
    сетка = Сетка()
    первое = слова[порядок[0]]
    сетка.ставить(первое, 0, 0, ГОР)
    осталось = [слова[i] for i in порядок[1:]]

    for _ in range(2):
        не_встали: list[str] = []
        for слово in осталось:
            лучшее = None
            # Кандидаты — только клетки с нужной буквой: пересечение обязательно,
            # значит перебирать пустое поле незачем.
            for (rr, cc), ch in list(сетка.буквы.items()):
                for i, w in enumerate(слово):
                    if w != ch:
                        continue
                    for d in (ГОР, ВЕР):
                        r = rr - i if d == ВЕР else rr
                        c = cc - i if d == ГОР else cc
                        n = сетка.можно(слово, r, c, d)
                        if not n:
                            continue  # None или 0 пересечений — не годится
                        # Оценка: сначала рамка (компактность важнее всего на
                        # телефоне), потом число пересечений.
                        rs = [p[0] for p in сетка.буквы] + [r, r + (len(слово) - 1 if d == ВЕР else 0)]
                        cs = [p[1] for p in сетка.буквы] + [c, c + (len(слово) - 1 if d == ГОР else 0)]
                        h = max(rs) - min(rs) + 1
                        w_ = max(cs) - min(cs) + 1
                        if макс_строк and h > макс_строк:
                            continue
                        if макс_столбцов and w_ > макс_столбцов:
                            continue
                        оценка = (h * w_, -n, abs(h - w_))
                        if лучшее is None or оценка < лучшее[0]:
                            лучшее = (оценка, r, c, d)
            if лучшее is None:
                не_встали.append(слово)
            else:
                сетка.ставить(слово, лучшее[1], лучшее[2], лучшее[3])
        if not не_встали:
            return сетка, []
        if len(не_встали) == len(осталось):
            return сетка, не_встали  # проход ничего не изменил — второй бесполезен
        осталось = не_встали
    return сетка, осталось


def лучшая_укладка(
    слова: list[str],
    перезапусков: int,
    seed: int,
    макс_строк: int | None = None,
    макс_столбцов: int | None = None,
) -> tuple[Сетка, list[str]]:
    """
    Перезапуски с разным порядком слов; берётся максимум уложенных, при равенстве
    — меньшая площадь. Первый порядок — от длинных к коротким: длинное слово
    задаёт хребет сетки, и с него укладка идёт лучше, чем со случайного.
    """
    rnd = random.Random(seed)
    длинные = sorted(range(len(слова)), key=lambda i: -len(слова[i]))
    лучшее: tuple[Сетка, list[str]] | None = None
    for k in range(перезапусков):
        порядок = длинные if k == 0 else rnd.sample(range(len(слова)), len(слова))
        сетка, вне = уложить(слова, порядок, макс_строк, макс_столбцов)
        h, w = сетка.рамка()
        ключ = (len(вне), h * w, max(h, w))
        if лучшее is None:
            лучшее = (сетка, вне, ключ)  # type: ignore[assignment]
        else:
            if ключ < лучшее[2]:  # type: ignore[index]
                лучшее = (сетка, вне, ключ)  # type: ignore[assignment]
        if лучшее[2][0] == 0 and лучшее[2][2] <= 9:  # type: ignore[index]
            break  # всё уложено и уже компактно — дальше искать нечего
    return лучшее[0], лучшее[1]  # type: ignore[index,return-value]


def проверить(сетка: Сетка, слова: list[str]) -> None:
    """
    ТРИПВАЙР, А НЕ ВЕЖЛИВОСТЬ. Замер, которому нельзя верить, хуже отсутствия
    замера: цифра «уложилось 98%» разъедется по трём задачам, и никто её не
    перепроверит. Поэтому каждая укладка пересобирается с нуля и проверяется
    на все пять правил плюс связность.
    """
    поле: dict[tuple[int, int], str] = {}
    for слово, r, c, d in сетка.слова:
        dr, dc = (0, 1) if d == ГОР else (1, 0)
        for i, ch in enumerate(слово):
            p = (r + dr * i, c + dc * i)
            если_есть = поле.get(p)
            assert если_есть is None or если_есть == ch, f"конфликт букв в {p}"
            поле[p] = ch
    assert поле == сетка.буквы, "пересборка поля разошлась с сеткой"

    # Всё, что читается на поле подряд длиной ≥2, обязано быть словом раскладки.
    банк = set(слова)
    for направление, (dr, dc) in ((ГОР, (0, 1)), (ВЕР, (1, 0))):
        for (r, c) in поле:
            if (r - dr, c - dc) in поле:
                continue  # не начало ряда
            цепь = ""
            rr, cc = r, c
            while (rr, cc) in поле:
                цепь += поле[(rr, cc)]
                rr, cc = rr + dr, cc + dc
            if len(цепь) >= 2:
                assert цепь in банк, f"на поле читается посторонняя цепочка {цепь!r}"

    # Связность: слова — вершины, общая клетка — ребро.
    n = len(сетка.слова)
    клетки = []
    for слово, r, c, d in сетка.слова:
        dr, dc = (0, 1) if d == ГОР else (1, 0)
        клетки.append({(r + dr * i, c + dc * i) for i in range(len(слово))})
    видели = {0}
    стек = [0]
    while стек:
        i = стек.pop()
        for j in range(n):
            if j not in видели and клетки[i] & клетки[j]:
                видели.add(j)
                стек.append(j)
    assert len(видели) == n, f"сетка распалась: {len(видели)} из {n}"


def замер(локаль: str, перезапусков: int, предел: int, лимит: int | None) -> None:
    """
    Два замера подряд, и второй важнее первого.

      · СВОБОДНЫЙ — сетка какая вышла. Отвечает на вопрос «вообще ложится ли».
      · В КОРОБКЕ `предел`×`предел` — укладчику запрещено вылезать за рамку ещё
        во время поиска. Отвечает на вопрос, который и стоит на самом деле: что
        из этого влезет в телефон. Свободная сетка в 17 столбцов формально
        «уложилась», а на экране 360 pt это клетка в 20 pt — играть нечем.
    """
    путь = КОНСТАНТЫ / f"allWords{локаль.capitalize()}.json"
    паки = json.loads(путь.read_text(encoding="utf-8"))
    if лимит:
        паки = паки[:лимит]

    вне_всего = Counter()
    рамки = Counter()
    стороны: list[int] = []
    площади: list[int] = []
    уложено_слов = 0
    всего_слов = 0
    полных = 0
    пересечений: list[int] = []
    # Коробка
    к_полных = 0
    к_уложено = 0
    к_вне = Counter()
    к_стороны: list[int] = []

    for i, пак in enumerate(паки):
        слова = [w.upper() for w in пак["words"]]
        сетка, вне = лучшая_укладка(слова, перезапусков, seed=i + 1)
        проверить(сетка, слова)
        h, w = сетка.рамка()
        вне_всего[len(вне)] += 1
        рамки[f"{h}x{w}"] += 1
        стороны.append(max(h, w))
        площади.append(h * w)
        уложено_слов += len(сетка.слова)
        всего_слов += len(слова)
        if not вне:
            полных += 1
        # Пересечений = сумма (длины слов) − число занятых клеток.
        пересечений.append(sum(len(w_) for w_, *_ in сетка.слова) - len(сетка.буквы))

        сетка2, вне2 = лучшая_укладка(слова, перезапусков, seed=i + 1,
                                      макс_строк=предел, макс_столбцов=предел)
        проверить(сетка2, слова)
        h2, w2 = сетка2.рамка()
        к_вне[len(вне2)] += 1
        к_уложено += len(сетка2.слова)
        к_стороны.append(max(h2, w2))
        if not вне2:
            к_полных += 1

    n = len(паки)
    print(f"\n=== {локаль.upper()}: {n} раскладок, {перезапусков} перезапусков ===")
    print("-- СВОБОДНАЯ СЕТКА --")
    print(f"уложилось ЦЕЛИКОМ (все слова в связной сетке): {полных} = {100 * полных / n:.1f}%")
    print(f"слов уложено {уложено_слов} из {всего_слов} = {100 * уложено_слов / всего_слов:.2f}%")
    print("слов осталось вне сетки:",
          ", ".join(f"{k}→{v} ({100 * v / n:.1f}%)" for k, v in sorted(вне_всего.items())))
    print(f"сторона сетки: медиана {statistics.median(стороны):.0f}, "
          f"среднее {statistics.mean(стороны):.2f}, максимум {max(стороны)}")
    print(f"площадь рамки: медиана {statistics.median(площади):.0f}, максимум {max(площади)}")
    print(f"пересечений на сетку: медиана {statistics.median(пересечений):.0f}")
    доля = Counter()
    for s in стороны:
        for порог in (7, 8, 9, 10, 11, 12, 13, 14):
            if s <= порог:
                доля[порог] += 1
    print("сторона ≤ N: " + ", ".join(f"{k}→{100 * v / n:.0f}%" for k, v in sorted(доля.items())))
    топ = ", ".join(f"{k}:{v}" for k, v in рамки.most_common(6))
    print(f"частые рамки: {топ}")
    print(f"-- В КОРОБКЕ {предел}x{предел} --")
    print(f"уложилось ЦЕЛИКОМ: {к_полных} = {100 * к_полных / n:.1f}%")
    print(f"слов уложено {к_уложено} из {всего_слов} = {100 * к_уложено / всего_слов:.2f}%")
    print("слов вне сетки:",
          ", ".join(f"{k}→{v} ({100 * v / n:.1f}%)" for k, v in sorted(к_вне.items())))
    print(f"сторона: медиана {statistics.median(к_стороны):.0f}, максимум {max(к_стороны)}")


def показать(локаль: str, индекс: int, перезапусков: int) -> None:
    """Одна раскладка глазами — чтобы цифры выше можно было проверить руками."""
    паки = json.loads((КОНСТАНТЫ / f"allWords{локаль.capitalize()}.json").read_text(encoding="utf-8"))
    пак = паки[индекс]
    слова = [w.upper() for w in пак["words"]]
    сетка, вне = лучшая_укладка(слова, перезапусков, seed=индекс + 1)
    проверить(сетка, слова)
    h, w = сетка.рамка()
    print(f"\nбаза {пак['base']} · слов {len(слова)} · сетка {h}x{w} · вне сетки {вне}")
    rs = [p[0] for p in сетка.буквы]
    cs = [p[1] for p in сетка.буквы]
    for r in range(min(rs), max(rs) + 1):
        print(" ".join(сетка.буквы.get((r, c), "·") for c in range(min(cs), max(cs) + 1)))


