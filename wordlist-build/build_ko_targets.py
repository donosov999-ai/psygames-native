#!/usr/bin/env python3
"""
🔴 НАБОР СЛОВ ДЛЯ РЕЖИМА «НАЙДИ ВСЕ СЛОВА» — КОРЕЙСКИЙ.

📍 ЗАЧЕМ ОТДЕЛЬНЫЙ СБОРЩИК. Разбор `../WORDLIST_NONLATIN.md` показал: из пяти
нелатинских языков корейский переносится чище всех — но только если плиткой
взять ЧАМО, а не слоговой блок. Блоками медиана подслов выходит 4, и ≥6 подслов
набирается лишь у 29% баз; чамо дают медиану 21 при базе в семь плиток.

⚠️ ПЛИТКА — СОВМЕСТИМОСТНОЕ ЧАМО (U+3131…U+3163), И ЭТО ЗАМЕР, А НЕ ВКУС.
Соблазнительно разложить дальше, до «базовых» составляющих (ㄲ = ㄱ+ㄱ, ㅐ = ㅏ+ㅣ),
и получить банк из 24 плиток размером с латиницу. Замер из разбора: так обратно
собирается лишь 22 946 слов из 49 321 = 46,5% — больше половины не
восстанавливается (내가 → 나ㅣ가, 있어 → 잇ㅅ어, 왜 → 오ㅐ). На совместимостных
чамо — 49 321 из 49 321 = 100,0%.

⚠️ ОДНОЗНАЧНОСТЬ СБОРКИ ОБЕСПЕЧЕНА ЯЗЫКОМ, А НЕ УДАЧЕЙ. «Пустая» согласная ㅇ в
начале слога и разведённые позиции делают разбивку единственной: 사랑 = ㅅㅏㄹㅏㅇ,
а 살앙 = ㅅㅏㄹㅇㅏㅇ — на одну плитку больше.

ЧТО ЛЕЖИТ В JSON. И база, и цели записаны В ЧАМО: символ строки — ровно одна
плитка банка, как в латинских наборах символ — ровно одна буква. Обратно в
привычное написание слово собирает игра (`chamo.ts`, автомат ввода).

Источник: hermitdave/FrequencyWords (MIT), `ko_50k.txt`, корпус OpenSubtitles.
Отдельного словаря правописания у корейского здесь нет — частотный список сам
служит и словарём, и мерой узнаваемости.

Замер 06.09.2026: слов только-хангыль 49 313 из 50 000 · разных плиток живьём 49
(потолок 51: корпус недобирает две конечные связки) · медиана слова 8 чамо ·
целей 22 404 · раскладок 2000 · подслов медиана 14 · 518 КБ · круговой ход
чамо → блоки → чамо точен на всех 49 313 словах корпуса (100,0%).

Запуск (окружение общее с остальными):
    ./.venv/bin/python3 build_ko_targets.py
"""
import json
import os
import re
import sys
import urllib.request

ЧАСТОТЫ = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/ko/ko_50k.txt"
ПОТОЛОК_РАНГА = 50_000        # весь файл: другого словаря у корейского нет
ПОТОЛОК_БАЗЫ = 20_000         # база — узнаваемое слово, иначе в базы лезут редкости
# 🔴 ТРИ ТЫСЯЧИ, А НЕ ДВЕ — РЕШЕНИЕ ДЕНИСА 06.09.2026, И ЦЕНА ЗАМЕРЕНА.
# Замер на английском: 2000 → 3000 раскладок это 272 → 407 КБ, то есть +0,9 МБ на
# семь языков. К вечеру языков стало десять, и цена выросла до ~1,6 МБ. Возражение
# высказано дважды, решение подтверждено — поднимаю.
# ⚠️ Поднятие ПОТОЛОК_БАЗЫ при этом НЕ помогает и не нужно: базы отсортированы по
# частоте, первые N годных берутся из верхушки в любом случае (замер: потолок ×2
# давал совпадение до байта).
МАКС_РАСКЛАДОК = 3_000
МИН_ДЛИНА = 2                 # ⚠️ В ЧАМО, А НЕ В БЛОКАХ: два чамо — это уже слог
# 🔴 ПОТОЛОК ЦЕЛИ — СЕМЬ ЧАМО, И ЭТО РЕШИЛ КРОССВОРД, А НЕ «НАЙДИ ВСЕ СЛОВА».
# При потолке 8 набор богаче (целей 30 898 против 22 404, медиана подслов 15
# против 14), но кроссвордный режим берёт слова из того же пака — и укладка
# перестаёт влезать в телефонную коробку: замер по 400 уровням дал 81,3% в
# 12×12 при потолке 8 и 91,8% при потолке 7, при пороге 85%. Раскладок в обоих
# случаях 2000, так что платим медианой подслов, а не числом уровней.
МАКС_ДЛИНА = 7
МИН_ПОДСЛОВ = 8
МАКС_ПОДСЛОВ_НАЧАЛО = 8       # число слов — ось сложности, как в en/ru
МАКС_ПОДСЛОВ_КОНЕЦ = 22

# Таблицы разложения слога: код = 0xAC00 + (нач*21 + глас)*28 + кон.
НАЧАЛЬНЫЕ = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
ГЛАСНЫЕ = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
КОНЕЧНЫЕ = ["", *"ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ"]


def скачать(url: str, имя: str) -> str:
    if not os.path.exists(имя):
        urllib.request.urlretrieve(url, имя)
    return имя


def в_чамо(слово: str):
    """Слово в слоговых блоках → строка совместимостных чамо. None, если не хангыль."""
    из = []
    for ch in слово:
        k = ord(ch) - 0xAC00
        if not 0 <= k < 11172:
            return None
        из.append(НАЧАЛЬНЫЕ[k // 588])
        из.append(ГЛАСНЫЕ[(k % 588) // 28])
        хвост = КОНЕЧНЫЕ[k % 28]
        if хвост:
            из.append(хвост)
    return "".join(из)


def влезает(слово: str, банк: str) -> bool:
    остаток = list(банк)
    for c in слово:
        if c not in остаток:
            return False
        остаток.remove(c)
    return True


def main() -> int:
    # ⚠️ Список брани хранится слогами, а набор живёт в чамо — переводим ТОЙ ЖЕ
    # функцией, что и корпус, иначе сравнение шло бы между разными формами и
    # молча ничего не находило.
    from adult_words import взрослое
    брань = {в_чамо(w) for w in взрослое('ko')}
    брань.discard(None)

    ранг = {}
    with open(скачать(ЧАСТОТЫ, "ko_50k.txt"), encoding="utf-8") as f:
        for i, стр in enumerate(f):
            части = стр.split()
            if части:
                ранг.setdefault(части[0], i)

    # цели: чамо-форма, длиной от МИН_ДЛИНА до 8 плиток
    чамо_ранг = {}
    for w, r in ранг.items():
        if r >= ПОТОЛОК_РАНГА or not re.fullmatch(r"[가-힣]+", w):
            continue
        ч = в_чамо(w)
        if ч is None or not МИН_ДЛИНА <= len(ч) <= МАКС_ДЛИНА or ч in брань:
            continue
        # одна чамо-форма может прийти от разных написаний — держим самое частое
        if ч not in чамо_ранг or r < чамо_ранг[ч]:
            чамо_ранг[ч] = r
    цели = sorted(чамо_ранг)

    базы = sorted((w for w in цели if len(w) in (7, 8) and чамо_ранг[w] < ПОТОЛОК_БАЗЫ),
                  key=lambda w: чамо_ранг[w])          # самые узнаваемые вперёд

    раскладки = []
    for база in базы:
        под = [w for w in цели if w != база and влезает(w, база)]
        if len(под) < МИН_ПОДСЛОВ:
            continue
        под.sort(key=lambda x: (-len(x), x))
        доля = len(раскладки) / max(1, МАКС_РАСКЛАДОК - 1)
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * min(1.0, доля))
        раскладки.append({"base": база, "words": sorted(под[:лимит])})
        if len(раскладки) >= МАКС_РАСКЛАДОК:
            break

    # 🔴 Проверка того, ради чего всё и делалось.
    for р in раскладки:
        плохие = [w for w in р["words"] if not влезает(w, р["base"])]
        if плохие:
            raise SystemExit(f"не собирается из «{р['base']}»: {плохие}")
        if not 7 <= len(р["base"]) <= 8:
            raise SystemExit(f"база не 7–8 чамо: «{р['base']}»")
    # И отдельно — что стоп-список сработал, а не просто лежит в файле.
    в_наборе = {р["base"] for р in раскладки} | {w for р in раскладки for w in р["words"]}
    if в_наборе & брань:
        raise SystemExit(f"брань дожила до набора: {sorted(в_наборе & брань)}")

    путь = "../frontend/src/constants/allWordsKo.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    плитки = {c for р in раскладки for c in р["base"]}
    print(f"целей {len(цели)} · базы-кандидаты {len(базы)} · раскладок {len(раскладки)} · "
          f"подслов медиана {длины[len(длины) // 2] if длины else 0} "
          f"(мин {длины[0]}, макс {длины[-1]}) · разных плиток {len(плитки)} · "
          f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
