    "героин", "идиот", "идиотизм", "идиотка", "какашка", "кокаин", "кретин",
    "маньяк", "мерзавец", "мерзавка", "моча", "мочиться", "мразь", "наркоман",
    "наркота", "нацист", "негр", "оргазм", "педофил", "подонок", "попка", "псих",
    "психопат", "пьяница", "садист", "сволочь", "секс", "скотина", "сперма",
    "стерва", "стриптиз", "суицид", "сука", "сукин", "сутенёр", "тварь",
    "трахать", "трахнуть", "труп", "тупица", "ублюдок", "урод", "уродец",
    "уродина", "фашист", "хам", "член", "шлюха",
    # Второй проход по тем же 5163 целям, другими корнями: первый список их не
