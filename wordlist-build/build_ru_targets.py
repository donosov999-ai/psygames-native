    for i, р in enumerate(раскладки):
        лимит = round(МАКС_ПОДСЛОВ_НАЧАЛО
                      + (МАКС_ПОДСЛОВ_КОНЕЦ - МАКС_ПОДСЛОВ_НАЧАЛО) * (i / итого))
        р["words"] = sorted(р["words"][:лимит])

    # 🔴 ПРОВЕРКА ПЕРЕД ЗАПИСЬЮ, а не после. Несобираемое слово делает уровень
    # непроходимым, и видно это только на живом экране — дешевле упасть здесь.
    for р in раскладки:
        б = р["base"]
        плохие = [w for w in р["words"] if not влезает(w, б)]
        if плохие:
            raise SystemExit(f"не собирается из «{б}»: {плохие}")
        if len(set(р["words"])) != len(р["words"]):
            raise SystemExit(f"повтор в словах «{б}»")
        if not 7 <= len(б) <= 8:
            raise SystemExit(f"база не 7–8 букв: «{б}»")
    # И отдельно — что стоп-список действительно сработал, а не просто лежит в файле.
    в_наборе = {р["base"] for р in раскладки} | {w for р in раскладки for w in р["words"]}
    if в_наборе & ВЗРОСЛОЕ:
        raise SystemExit(f"брань дожила до набора: {sorted(в_наборе & ВЗРОСЛОЕ)}")

    путь = "../frontend/src/constants/allWordsRu.json"
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(раскладки, f, ensure_ascii=False, separators=(",", ":"))
    длины = sorted(len(x["words"]) for x in раскладки)
    буквы = "".join(sorted({р["base"][0] for р in раскладки}))
    print(f"целей {len(цели)} · раскладок {len(раскладки)} · "
          f"подслов медиана {длины[len(длины) // 2] if длины else 0} "
          f"(мин {длины[0]}, макс {длины[-1]}) · слов уникальных {len(в_наборе)} · "
          f"первых букв базы {len(буквы)} ({буквы}) · "
          f"{os.path.getsize(путь) / 1024:.0f} КБ")
    return 0


