#!/usr/bin/env node
/* psygames-self-decided-gate · VER 1 · 09.09.2026 */
/**
 * НЕ ДАЁТ ВЫПУСТИТЬ МОЛЧА ПЕРЕПИСАННЫЙ ТЕКСТ, КОТОРЫЙ ЧЕЛОВЕК УЖЕ ВИДЕЛ.
 *
 * 🔴 ЗАЧЕМ. 09.09.2026 Денис перечислил тринадцать косяков подряд, и семь из них
 * — один и тот же: решение принималось ЗА НЕГО. Из них четыре видны в словаре:
 *   · «Твоя лучшая серия» вместо «Твой рекорд» — формулировка, которой он не утверждал;
 *   · причина вида питомца, подсказка в коллекции, подпись фигурки — сочинены сами;
 *   · «Поле n×n» на экране лаборатории — убрано, потому что «так лучше»;
 *   · «Пропустить» в подвале онбординга — добавлено само.
 * Дословно: «Сам сочинил формулировки, которых ты не утверждал».
 *
 * ПОЧЕМУ ОБЫЧНАЯ ЗАПИСЬ ВЫПУСКА ЭТО НЕ ЛОВИТ. Она ловит — но как пересказ дел, а
 * не как список решений. В записи 2.52.6 фраза про «лучшую серию» стоит, и всё
 * равно косяк случился: она утоплена в абзаце про питомца наравне с починками, и
 * прочитать её как «я поменял слова, которых ты не видел» нельзя. Разница не в
 * наличии строки, а в том, что ОТДЕЛЬНОГО списка нет, и глазами он не собирается.
 *
 * ЧТО ПРОВЕРЯЕТ. Между прошлым выпущенным тегом и текущим деревом:
 *   · какие ключи ru/en УБРАНЫ — человек видел текст, теперь не увидит;
 *   · какие ПЕРЕПИСАНЫ — текст на месте, слова другие.
 * Новые ключи не считаются: добавить подпись там, где её не было, — не подмена.
 * Каждый убранный и переписанный ключ обязан быть НАЗВАН в записи выпуска —
 * ключом, старым текстом или новым. Как назван, гейт не диктует: он сторожит
 * существо, а не разметку. Формат уже ронял выпуск 2.52.0 (искалось `## [2.52.0]`,
 * стояло `## 2.52.0`), второй раз на те же грабли не встаём.
 *
 * ⚠️ ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕЛАЕТ. Он не спрашивает разрешения и не может. Он делает
 * решение ВИДИМЫМ до тега, а не после отчёта тестировщика. Согласование остаётся
 * человеческим шагом — гейт только не даёт пройти мимо молча.
 *
 * Запуск:  node scripts/self-decided-gate.mjs [--base=<ref>] [--head=<ref>] [--version=<x.y.z>]
 * По умолчанию base = предыдущий тег v*, head = рабочее дерево, version = из app.json.
 * `--head` нужен, чтобы гейт можно было прогнать ПО ИСТОРИИ и увидеть, что он
 * ловит на настоящих выпусках, а не только на подкрученном примере.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const СЛОВАРЬ = 'frontend/src/contexts/LanguageContext.tsx';
const args = Object.fromEntries(
  process.argv.slice(2).map((a) => a.replace(/^--/, '').split('=')).map(([k, v]) => [k, v ?? '1']),
);

const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }).trim();

/** Прошлый ВЫПУЩЕННЫЙ тег. На сборке тега это предыдущий, на main — последний. */
function базоваяТочка(голова) {
  if (args.base) return args.base;
  /**
   * ⚠️ ПЕРВЫЙ ПРОГОН 09.09 ВЗЯЛ БАЗОЙ САМЫЙ СВЕЖИЙ ТЕГ И СРАВНИЛ ДЕРЕВО САМО С
   * СОБОЙ: «убрано 0, переписано 0» — зелено и пусто. Тег может быть НОВЕЕ
   * головы (выпуск собирается с релизной ветки), поэтому «последний тег в
   * репозитории» ≠ «прошлый выпуск для этой головы». Берём только предков.
   */
  const ref = голова || 'HEAD';
  const свои = new Set(git('tag', '--points-at', ref).split('\n').filter(Boolean));
  const теги = git('tag', '--list', 'v*', '--sort=-creatordate').split('\n').filter(Boolean);
  for (const t of теги) {
    if (свои.has(t)) continue;
    try { git('merge-base', '--is-ancestor', t, ref); return t; } catch { /* не предок */ }
  }
  return null;
}

/**
 * Ключ → русский текст. Разбираем строки вида `key: { ru: '…', en: '…' },`.
 * ⚠️ Мерим ТЕКСТ, а не строку файла: сдвиг строк при вставке соседнего ключа не
 * должен читаться как правка. Ровно так врут дифы, если сравнивать номера.
 */
function словарь(содержимое) {
  const m = new Map();
  const re = /^\s*([A-Za-z_][\w$]*)\s*:\s*\{\s*ru:\s*(['"`])((?:\\.|(?!\2)[^\\])*)\2/gm;
  let x;
  while ((x = re.exec(содержимое))) m.set(x[1], x[3]);
  return m;
}

const ГОЛОВА = args.head || null;
const БАЗА = базоваяТочка(ГОЛОВА);
if (!БАЗА) { console.log('🟡 гейт «решено без спроса»: предыдущего тега нет — сравнивать не с чем, пропускаю'); process.exit(0); }
const читать = (ref) => (ref ? git('show', `${ref}:${СЛОВАРЬ}`) : readFileSync(join(ROOT, СЛОВАРЬ), 'utf8'));

let былоТекст;
try { былоТекст = git('show', `${БАЗА}:${СЛОВАРЬ}`); }
catch { console.log(`🟡 в ${БАЗА} нет ${СЛОВАРЬ} — пропускаю`); process.exit(0); }

const было = словарь(былоТекст);
const стало = словарь(читать(ГОЛОВА));
if (было.size < 100 || стало.size < 100) {
  console.error(`🔴 разбор словаря сломан: было ${было.size} ключей, стало ${стало.size}. Гейт, который ничего не нашёл, — не зелёный гейт, а слепой.`);
  process.exit(1);
}

const убраны = [...было.keys()].filter((k) => !стало.has(k));
const переписаны = [...стало.keys()].filter((k) => было.has(k) && было.get(k) !== стало.get(k));

const версия = args.version
  || JSON.parse(ГОЛОВА ? git('show', `${ГОЛОВА}:frontend/app.json`) : readFileSync(join(ROOT, 'frontend/app.json'), 'utf8')).expo.version;
const changelog = ГОЛОВА ? git('show', `${ГОЛОВА}:CHANGELOG.md`) : readFileSync(join(ROOT, 'CHANGELOG.md'), 'utf8');
/** Запись версии: от её заголовка до следующего заголовка любого вида. */
const начало = changelog.search(new RegExp(`^##\\s*\\[?${версия.replace(/\./g, '\\.')}\\]?`, 'm'));
const запись = начало < 0 ? '' : changelog.slice(начало).split(/\n## /)[0];

/**
 * 🔴 СВЕРКА ПО СМЫСЛУ, А НЕ ПО СИМВОЛАМ — иначе гейт краснеет на честной записи.
 * Первый прогон 09.09 назвал ложным «Твоя лучшая серия»: в записи 2.52.6 она
 * названа словами, но с «N дн.» вместо «{n} дн.» — точное вхождение не сошлось.
 * Ложное срабатывание тут дороже пропуска: гейт, который врёт, выключают целиком,
 * и тогда он не ловит уже ничего. Поэтому подстановки вырезаем, регистр и пробелы
 * равняем, а совпадением считаем любой кусок текста от 16 символов.
 */
const ровно = (t) => (t || '').toLowerCase().replace(/\{[^}]*\}/g, '\u0001').replace(/\s+/g, ' ').trim();
const записьРовно = ровно(запись);
const кускиЕсть = (текст) =>
  ровно(текст).split('\u0001').map((c) => c.trim()).filter((c) => c.length >= 16)
    .some((c) => записьРовно.includes(c));
const назван = (ключ) => {
  if (!запись) return false;
  const ст = было.get(ключ), нов = стало.get(ключ);
  return запись.includes(ключ) || (ст && кускиЕсть(ст)) || (нов && кускиЕсть(нов));
};

const молча = [...убраны.map((k) => ['убран', k]), ...переписаны.map((k) => ['переписан', k])].filter(([, k]) => !назван(k));

console.log(`база ${БАЗА} → версия ${версия}`);
console.log(`ключей в словаре: было ${было.size}, стало ${стало.size}`);
console.log(`убрано ${убраны.length}, переписано ${переписаны.length}, из них НЕ названо в записи выпуска: ${молча.length}`);

if (начало < 0) {
  console.error(`\n🔴 записи под ${версия} в CHANGELOG.md нет — назвать решения негде.`);
  process.exit(1);
}
if (молча.length) {
  console.error(`\n🔴 ${молча.length} текстов, которые человек уже видел, изменены МОЛЧА. Назови их в записи ${версия} — ключом или самим текстом:\n`);
  for (const [что, k] of молча.slice(0, 40)) {
    console.error(`  ${что.padEnd(10)} ${k}`);
    console.error(`             было:  ${JSON.stringify(было.get(k) ?? '')}`);
    if (что === 'переписан') console.error(`             стало: ${JSON.stringify(стало.get(k))}`);
  }
  if (молча.length > 40) console.error(`  … и ещё ${молча.length - 40}`);
  console.error(`\n⚠️ Это не «оформи бумагу». Семь косяков из тринадцати 09.09.2026 — решения, принятые за Дениса; четыре из них жили ровно здесь.`);
  process.exit(1);
}
console.log('\n✅ все изменённые и убранные тексты названы в записи выпуска');
