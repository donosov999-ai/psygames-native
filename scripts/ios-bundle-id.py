#!/usr/bin/env python3
"""
Идентификатор, под которым собирается iOS-приложение. Печатает одну строку.

🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ РАДИ ПЯТИ СТРОК.

Во-первых, у идентификатора должен быть ОДИН источник. У проекта три конфига:
базовый `tauri.conf.json` описывает десктоп (`com.odv999.psygames`), а
`tauri.ios.conf.json` и `tauri.android.conf.json` переопределяют его на
`com.psygames.app` — тот, что заведён в аккаунте Apple, к которому привязана
карточка App Store Connect и под которым приложение лежит в Google Play. Скрипт
подписи и скрипт профиля обязаны брать одно и то же, иначе профиль создаётся для
чужого приложения, а узнаёшь об этом через десять минут сборки — на экспорте,
сообщением, где про идентификатор не сказано ни слова.

Во-вторых, эта логика раньше жила питоновской вставкой ВНУТРИ shell-скрипта, и её
поймал собственный гейт `shell-scripts-ascii-vars`: он запрещает кириллические
имена переменных в shell-файлах (в bash такое имя ломает выполнение). Имена были
питоновские и ничего не ломали, но правило написано про файл, а не про язык
вставки, и ослаблять его ради удобства неправильно. Вынос решает и это.
"""
import json
import os
import sys

КОРЕНЬ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src-tauri')


def идентификатор(платформа: str = 'ios') -> str:
    платформенный = os.path.join(КОРЕНЬ, f'tauri.{платформа}.conf.json')
    if os.path.exists(платформенный):
        свой = json.load(open(платформенный, encoding='utf-8')).get('identifier')
        if свой:
            return свой
    return json.load(open(os.path.join(КОРЕНЬ, 'tauri.conf.json'), encoding='utf-8'))['identifier']


if __name__ == '__main__':
    print(идентификатор(sys.argv[1] if len(sys.argv) > 1 else 'ios'))
