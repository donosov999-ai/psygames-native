/// ГЕОМЕТРИЯ ПОЛЯ САМУРАЯ — отдельно от экрана, чтобы гейт мерил её ВЫЗОВОМ.
///
/// 🔴 ПОЧЕМУ У САМУРАЯ ДВА МАСШТАБА, А НЕ ОДИН. Двадцать одна клетка в ряд: на телефоне
/// 390 точек шириной клетка выходит 16 — это не цель для пальца, а картинка. Поэтому
/// масштаба два, и оба нужны:
///   · `карта` — вся фигура из пяти сеток видна целиком, играть нельзя, видно ГДЕ ты;
///   · `рабочий` — клетка не меньше 48 точек (норма цели для пальца), поле листается.
/// Порог 48 — не вкусовщина: клетка меньше пальца и есть жалоба «поле не влезает».
library;

import 'rules.dart';

/// Норма цели для пальца. Ниже неё рабочий масштаб не опускается.
const touchCell = 48.0;

/// Мельче этого пометки в клетке не рисуются: девять пометок — это цифра в треть
/// клетки, то есть на карте вышло бы 5 точек — грязь поверх единственного, ради чего
/// карта нужна.
const pencilMinCell = 30.0;

/// ⚠️ Имена значений латиницей: Dart не пускает кириллицу в идентификаторы (правило
/// «кириллица только в видимом тексте»). `map` — карта, `work` — рабочий масштаб.
enum SamuraiZoom { map, work }

/// Сторона клетки. `heightRoom` — высота, которую реально дал каркас (0 — ещё не
/// измерена).
///
/// ⚠️ КАРТА СЧИТАЕТСЯ И ОТ ВЫСОТЫ, А НЕ ТОЛЬКО ОТ ШИРИНЫ. Замер веб-версии 17.09: поле
/// каркаса 179 точек, а крест по ширине выходил 315 — карта рисовалась поверх крышки с
/// показателями и кнопки масштаба, то есть закрывала собой переход в рабочий режим.
double cellSizeFor(double width, SamuraiZoom zoom, {double heightRoom = 0}) {
  final fit = ((width < 600 ? width : 600) - 36) / samuraiSize;
  if (zoom == SamuraiZoom.work) {
    final doubled = fit * 2;
    return doubled > touchCell ? doubled : touchCell;
  }
  final byHeight = heightRoom > 0 ? heightRoom / samuraiSize : double.infinity;
  final smaller = fit < byHeight ? fit : byHeight;
  return smaller > 12 ? smaller : 12;
}

/// Помещается ли вся фигура в отведённое место на карте.
///
/// ⚠️ ОТВЕТ БЫВАЕТ «НЕТ», И ЭТО НЕ ДЕФЕКТ РАСЧЁТА. Клетка не опускается ниже 12 точек,
/// поэтому при поле каркаса меньше 252 точек (21 × 12) фигура целиком не влезает ни при
/// каком раскладе. Экран в этом случае обязан ЛИСТАТЬ карту, а не обрезать её: замер
/// веб-версии 17.09 давал поле 179 точек, и нижние сетки уходили под кнопки.
bool mapFits(double width, double heightRoom) {
  final cell = cellSizeFor(width, SamuraiZoom.map, heightRoom: heightRoom);
  return cell * samuraiSize <= heightRoom + 0.5 && cell * samuraiSize <= width + 0.5;
}
