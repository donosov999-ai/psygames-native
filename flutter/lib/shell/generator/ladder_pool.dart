/// ПУЛ ИЗ УПОРЯДОЧЕННОЙ ЛЕСТНИЦЫ — ПОДКЛЮЧЕНИЕ ИГРЫ К ГЕНЕРАТОРУ БЕЗ КОПИРОВАНИЯ «СУДОКУ».
///
/// Звено 2 цепочки генератора (задача 543d853c, 30.09.2026). У «Судоку» пул собран из
/// своей меры трудности (ступень техник, полоса банка — `games/sudoku/generator/pool.dart`).
/// У большинства игр такой меры нет, зато есть ЛЕСТНИЦА: упорядоченный список ступеней,
/// где следующая труднее предыдущей. Этого хватает для старта: место ступени в лестнице
/// переводится в шкалу игрока линейно, дальше рейтинг человека учится на живых партиях.
///
/// ⚠️ ЭТО НАЧАЛЬНАЯ ОЦЕНКА, А НЕ ИЗМЕРЕНИЕ. Равные промежутки между ступенями — допущение:
/// у «Сапёра» шаг 9×9 → 16×16 вовсе не равен шагу 16×16 → 30×16. Уточнять рейтинг
/// ШАБЛОНОВ по исходам партий эталон пока не умеет (заявлено в `pool.dart`, в коде
/// нет) — это пункт для звена 3, раздела «Судоку».
///
/// Шаблон здесь — ступень лестницы; правило у всей лестницы одно (`variant` = игра),
/// поэтому запрет «одно правило подряд» внутри одной игры ничего не делает — он для
/// пулов, смешивающих правила, как у «Судоку».
library;

import 'engine.dart';

/// Шкала игрока — та же, что у эталона «Судоку»: 1200 — середина, с неё стартует новичок.
const ratingFloor = 800.0;
const ratingCeil = 2200.0;

/// Рейтинг ступени [index] (с нуля) из [count]: первая — пол шкалы, последняя — потолок.
/// Лестница из одной ступени встаёт на середину: сравнивать её не с чем.
double ratingForStep(int index, int count) {
  if (count <= 1) return (ratingFloor + ratingCeil) / 2;
  return ratingFloor + (ratingCeil - ratingFloor) * index / (count - 1);
}

/// Пул из ступеней лестницы: по шаблону на ступень, в порядке лестницы.
///
/// [stepKeys] — то, что делает ступень ступенью (у головоломок — параметры движка). Имя
/// шаблона строится из ключа, а не из номера: вставят ступень в середину — имена
/// остальных не поедут, и хвост «недавно игранных» не перепутается.
List<Template> ladderPool({required String gameId, required List<String> stepKeys}) => [
      for (var i = 0; i < stepKeys.length; i++)
        Template(
          id: '$gameId:${stepKeys[i]}',
          band: i + 1,
          rating: ratingForStep(i, stepKeys.length),
          variant: gameId,
        ),
    ];
