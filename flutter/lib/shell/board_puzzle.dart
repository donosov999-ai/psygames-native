/// 🔴 ОДИН ДОГОВОР ДОСКИ НА ВСЕ НАШИ ИГРЫ — ТО, ЧТО У ТЭТХЭМА ЕСТЬ ДАРОМ.
///
/// ВОПРОС ДЕНИСА 24.09.2026: «почему на остальные наши игры так одним заходом
/// нельзя? надо чтобы тоже было стандартизировано всё так же, как у Тэтхэма».
///
/// Ответ замером: у Тэтхэма 42 игры стоят за ОДНИМ C-API — один решатель, один
/// формат доски. Поэтому одна интеграция дала разбор 37 режимам. У нас 71
/// упражнение и 37 отдельных ядер, и решатель написан у шести. Общего API нет —
/// оттого и «по одной».
///
/// Здесь он заводится. Игра отдаёт три вещи, и это всё:
///   1. [keyOf] — снимок положения строкой: по нему поиск понимает, что здесь уже был;
///   2. [movesFrom] + [apply] — законные ходы и результат хода;
///   3. [solved] — когда остановиться.
/// Дальше общий решатель ([BoardSolver]) и общий разбор работают сами, ничего не
/// зная про игру.
///
/// ⚠️ ДОГОВОР НАРОЧНО БЕДНЫЙ. Соблазн добавить сюда «подсказку», «оценку позиции»,
/// «вес хода» — и тогда каждая игра обязана их придумать, а половина придумает
/// неверно. Три метода игра отдаёт честно, потому что они у неё УЖЕ есть: у
/// `HanoiState`, `TolState` и поля колб ровно такие `canMove/move/solved` и
/// написаны до всякого разбора.
abstract class BoardPuzzle<S, M> {
  const BoardPuzzle();

  /// Снимок положения. Два одинаковых положения обязаны давать одну строку.
  String keyOf(S state);

  /// Цель достигнута.
  bool solved(S state);

  /// Законные ходы из положения. Пусто — тупик.
  List<M> movesFrom(S state);

  /// Результат хода; null — ход незаконен.
  S? apply(S state, M move);
}
