/// 🔴 РАЗБОР ПО ШАГАМ — ОБЩИЙ ДОГОВОР, ОДИН НА ВСЕ ИГРЫ.
///
/// Решение Дениса 24.09.2026: «решатель и учитель вообще должны быть в каждом
/// упражнении» и «думай, как сделать нативный генератор, чтобы руками не делать
/// более 100 штук». Упражнений 113 — писать учителя на каждое нельзя.
///
/// 🔴 ЗАМЫСЕЛ: УЧИТЕЛЬ = РЕШАТЕЛЬ + РАЗНОСТЬ + ИМЯ ПРИЁМА. Три слоя, и только
/// третий зависит от игры.
///   1. РЕШАТЕЛЬ даёт решение. У головоломок Тэтхэма он уже есть в самом движке:
///      замер 24.09.2026 по всем 42 режимам — `psy_solve` доводит до решения 37.
///   2. РАЗНОСТЬ («что появилось на доске») — общая и правил игры не знает.
///   3. ИМЯ ПРИЁМА — единственное место, где нужна игра; берётся из словаря
///      ПРИЁМОВ, а не игр: приёмов десятки, игр сто тринадцать.
///
/// ⚠️ ЗДЕСЬ ТОЛЬКО ДОГОВОР И ПЛЕЕР. Как выглядит доска, этот слой не знает и знать
/// не должен: шаг несёт непрозрачный [payload], и рисует его та игра, что шаг
/// породила. Иначе каркас пришлось бы учить сорока двум разным доскам.
///
/// Формат шага снят с уже работающего веб-договора
/// (`frontend/src/games/tatham-bridge/teach/types.ts`): второй формат не заводим,
/// иначе рукописные учителя и генератор разъедутся.

/// Что означает рамка поверх доски.
enum LessonBoxKind {
  /// На что смотреть — опора рассуждения.
  hint,

  /// Куда идёт ход.
  place,

  /// Что стереть — ошибка игрока.
  error,
}

/// Рамка в координатах доски самой игры (у Тэтхэма — координаты движка).
class LessonBox {
  const LessonBox(this.x, this.y, this.w, this.h, this.kind);
  final int x, y, w, h;
  final LessonBoxKind kind;
}

/// Один шаг разбора.
class LessonStep {
  const LessonStep({
    required this.box,
    this.techniqueKey,
    this.payload,
  });

  /// Куда смотреть на этом шаге.
  final LessonBox box;

  /// Ключ СЛОВАРЯ с именем приёма («в строке осталось одно место»).
  ///
  /// ⚠️ Ключ, а не готовая строка: экран говорит на двенадцати языках. Пусто —
  /// приём назвать нечем, и плеер честно показывает только ход, без объяснения.
  /// Это хуже рукописного учителя и лучше, чем ничего.
  final String? techniqueKey;

  /// Непрозрачная нагрузка для рисования — её понимает только своя игра.
  final Object? payload;
}

/// Откуда берутся шаги. Реализации: движок Тэтхэма, ядро своей игры, перебор.
abstract class LessonSource {
  /// Шаги от НЫНЕШНЕЙ позиции до решения. Пусто — разбора для этой позиции нет.
  Future<List<LessonStep>> steps();

  /// Почему разбора нет — для реестра охвата и проб, а НЕ для показа человеку.
  ///
  /// 🔴 Пустой список без причины — это пропуск, а не ответ. У пяти аркад Тэтхэма
  /// (Mines, Pegs, Same Game, Sokoban, Cube) решения не существует по устройству
  /// игры, и так и надо сказать — в коде и в пробе.
  ///
  /// ⚠️ Человеку причину не показываем и нового ключа словаря ради неё не заводим:
  /// нет разбора — нет и кнопки. Объяснять отсутствие кнопки, которой не видно,
  /// незачем, а лишний ключ стоил бы перевода на двенадцать языков.
  String? get unavailableReason => null;
}

/// 🔴 ПАРТИЯ С РАЗБОРОМ В УРОВЕНЬ НЕ ЗАСЧИТЫВАЕТСЯ.
///
/// Так это устроено в вебе, и правило не косметическое: разбор показывает решение,
/// и партия после него меряет не человека. Засчитывать её — это ставить лестницу
/// по чужому ходу, а потом удивляться, что следующий уровень не даётся.
///
/// ⚠️ Правило живёт ЗДЕСЬ, а не в экранах — как и правило пресета. Это свойство
/// ЗАПУСКА партии, а не игры; записанное в каждом экране, оно будет забыто в
/// следующем. Ставит отметку плеер, снимает — новая раздача.
class LessonUsed {
  LessonUsed._();

  static bool _inRound = false;

  /// Смотрел ли человек разбор в ТЕКУЩЕЙ партии.
  static bool get inRound => _inRound;

  /// Открыли разбор — партия перестала быть зачётной.
  static void mark() => _inRound = true;

  /// Новая раздача — отметка снимается.
  static void reset() => _inRound = false;
}
