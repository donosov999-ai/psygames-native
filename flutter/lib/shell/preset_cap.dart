/// 🔴 ШАГ ЗАРЯДКИ НЕ ДАЁТ БОЛЬШЕ, ЧЕМ ЧЕЛОВЕК ОСВОИЛ.
///
/// Перенос `frontend/src/services/presetCap.ts` — правило одно на все экраны, и
/// в вебе его сторожит гейт `preset-cap-coverage.test.ts`: он проходит по КАЖДОМУ
/// экрану с пресетом и требует, чтобы число из адреса шло через этот предел.
///
/// 📍 ЗАЧЕМ. Плейлист зарядки задаёт числа один раз на всех. Без предела новичок,
/// у которого освоен уровень 1 (три диска, семь ходов), получал башню на пять —
/// тридцать один ход. Тот же класс дефекта Денис поймал на «20 словах» мнемоники
/// 30.08.2026.
///
/// ⚠️ ПРАВИЛУ МЕСТО В КАРКАСЕ, А НЕ В ЭКРАНЕ: записанное в каждом, оно будет
/// забыто в следующем. Пока каркас его не принял, файл лежит здесь и им же
/// пользуются экраны раздела «Сортировки».
///
/// · [want] — что просит шаг · [atLevel] — что даёт нынешний уровень игрока
/// · [step] — на сколько разрешено прыгнуть выше освоенного (обычно одна ступень)
/// · [atTop] — игрок уже на вершине лестницы: предел снимается, пусть берёт что просит
int capPresetByLevel({required int want, required int atLevel, int step = 1, bool atTop = false}) {
  if (want <= 0) return atLevel;
  if (atTop) return want;
  final ceiling = atLevel + step;
  return want < ceiling ? want : ceiling;
}
