/// 🔴 ПАРАМЕТРЫ АДРЕСА — ЭТО НАСТРОЙКИ ШАГА ЗАРЯДКИ, А НЕ УКРАШЕНИЕ.
///
/// НАЙДЕНО РАЗДЕЛОМ «ПРОСТРАНСТВО» 23.09.2026, замер по 14 перенесённым экранам:
/// `grep -rl "queryParameters" flutter/lib/games/` → НОЛЬ файлов. Хвост адреса до
/// нативного экрана не доходил вовсе: `routeOf` срезает `?…`, когда точного ключа
/// «адрес+хвост» в карте нет.
///
/// 🔴 И ГЛАВНОЕ ПОСЛЕДСТВИЕ, КОТОРОЕ НАЗВАЛИ НЕ СРАЗУ. В вебе партия-пресет НЕ
/// двигает лестницу: `passed = !isPreset && …` стоит в 36 экранах
/// (`frontend/src/hooks/useGamePreset.ts:22`). Нативно такой ветки не было ни у
/// одного экрана — все звали `ladder.win()/fail()` безусловно. Значит шаг зарядки,
/// открывшийся нативно, МОЛЧА менял личный уровень игрока: вверх при удаче, вниз
/// при провале. Перенос увёз правила игры и оставил бухгалтерию игрока.
///
/// 🔴 ПОЧЕМУ ПРАВИЛО ЖИВЁТ ЗДЕСЬ, А НЕ В 36 ЭКРАНАХ. Раздел предложил именно так, и
/// это верно: «при пресете лестница не двигается» — свойство ЗАПУСКА, а не игры.
/// Записанное в каждом экране, оно будет забыто в тридцать седьмом.
///
/// Значения ставит оболочка перед открытием нативного экрана (`HybridApp._openNative`)
/// и снимает после — ровно как `useLocalSearchParams` живёт только на своём экране.
class GamePreset {
  GamePreset._();

  static Map<String, String> _params = const {};

  /// Поставить параметры текущего экрана; пусто — обычный заход из каталога.
  static void set(Map<String, String> params) => _params = Map.unmodifiable(params);
  static void clear() => _params = const {};

  static Map<String, String> get params => _params;

  /// `wu=1` — шаг ПЛЕЙЛИСТА зарядки: лестницу не двигаем.
  ///
  /// ⚠️ Ежедневный вызов шлёт `auto=1`, а НЕ `wu=1`, и это не мелочь: когда он ходил
  /// с `wu=1`, уровни молча не засчитывались — два отчёта Вали на v1.185.0
  /// («уровней 15, но дальше первого я не ухожу»). Поэтому автостарт и пресет — два
  /// разных признака, а не один.
  static bool get isPreset => _params['wu'] == '1';

  /// Стартовать сразу, минуя настройку: и шаг зарядки, и вызов дня.
  static bool get autostart => isPreset || _params['auto'] == '1';

  /// Вечерний шаг: без гонки. Экран с обратным отсчётом обязан его убрать
  /// (отчёт «нельзя таймер» от 18.08.2026).
  static bool get isCalm => _params['calm'] == '1';

  static String str(String key, [String def = '']) {
    final v = _params[key];
    return (v != null && v.isNotEmpty) ? v : def;
  }

  static int num(String key, int def) => int.tryParse(_params[key] ?? '') ?? def;

  static bool flag(String key, [bool def = false]) {
    final v = _params[key];
    if (v == '1' || v == 'true') return true;
    if (v == '0' || v == 'false') return false;
    return def;
  }
}
