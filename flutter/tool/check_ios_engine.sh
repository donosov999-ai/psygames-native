#!/bin/sh
# 🔴 ГЕЙТ «ДВИЖОК ДОЕХАЛ ДО iPhone». Гонять ПОСЛЕ сборки под устройство и ПЕРЕД заливкой:
#     flutter build ipa && tool/check_ios_engine.sh
#
# ЧТО ЛОВИТ. Линковка молчит, когда движок выпадает из бинарника: сборка зелёная, размер
# правдоподобный, а приложение падает на ПЕРВОМ ходе — уже у человека, потому что Dart
# ищет символы по имени в рантайме. Замер чата «Шахматы» 23.09.2026 на том же классе:
# `-force_load` стоял в команде линковки, .a содержал символы, бинарник вышел 294 КБ
# вообще без движка, и ничего красного не загорелось. С флагами `-u` — 993 КБ.
#
# ⚠️ Отличие от пробы tatham_ios_symbols_test: та сверяет СПИСОК с исходником моста и
# работает на любом бегунке. Эта смотрит НАСТОЯЩУЮ таблицу символов готового .app, и без
# сборки под устройство её запустить нельзя. Нужны обе: список может сойтись, а линкер —
# всё равно выбросить код.
set -e
# ⚠️ Путь к бинарнику зависит от того, чем собирали: `flutter build ios` кладёт его
# в build/ios/iphoneos, а `flutter build ipa` — ещё и в архив. Гейт, знающий один
# путь, на другой сборке молча пропустил бы проверку, а это хуже отсутствия гейта.
BIN="${1:-}"
TMPDIR_UNZIP=""
# ⚠️ ПЕРЕДАННЫЙ ПУТЬ — ПОДСКАЗКА, А НЕ ПРИГОВОР. Выкладка передавала гейту
# build/ios/iphoneos/Runner.app/Runner, которого на бегунке не существует, и
# гейт честно отвергал его, не пытаясь искать. Три зелёные сборки отбиты именно
# этим. Нет по указанному пути — ищем сами и говорим об этом вслух.
if [ -n "$BIN" ] && [ ! -f "$BIN" ]; then
  echo "по указанному пути пусто ($BIN) — ищу сам"
  BIN=""
fi
# 🔴 ГЕЙТ СМОТРИТ НА ТОТ АРТЕФАКТ, КОТОРЫЙ УЕДЕТ К ЧЕЛОВЕКУ.
#
# Три прогона подряд я чинил не то: сперва гейт знал два жёстких пути, потом
# искал файл с именем `Runner`, потом любой `.app` — и каждый раз падал на
# зелёной сборке. Причина оказалась проще: после `flutter build ipa` на бегунке
# НЕТ распакованного `.app` вовсе (прогон 35897517101: «найденные .app:» пусто,
# в build/ios только `archive` и `ipa`). Настоящий артефакт — сам .ipa, это
# ровно то, что уедет в TestFlight, и проверять надо его.
#
# ⚠️ Урок дороже самого гейта: я трижды подправлял ПОИСК, ни разу не спросив,
# существует ли то, что я ищу. Сторож, отбивающий зелёную сборку, стоит столько
# же, сколько пропущенная поломка, и злит сильнее.
if [ -z "$BIN" ]; then
  for app in $(find build/ios -maxdepth 8 -type d -name '*.app' 2>/dev/null); do
    name=$(basename "$app" .app)
    if [ -f "$app/$name" ]; then BIN="$app/$name"; break; fi
  done
fi
if [ -z "$BIN" ]; then
  IPA=$(find build/ios -maxdepth 3 -name '*.ipa' 2>/dev/null | head -1)
  if [ -n "$IPA" ]; then
    TMPDIR_UNZIP=$(mktemp -d)
    unzip -q "$IPA" -d "$TMPDIR_UNZIP" || { echo "не распаковался $IPA"; exit 1; }
    for app in "$TMPDIR_UNZIP"/Payload/*.app; do
      name=$(basename "$app" .app)
      [ -f "$app/$name" ] && { BIN="$app/$name"; echo "взят из .ipa: $(basename "$IPA")"; break; }
    done
  fi
fi
[ -n "$BIN" ] && [ -f "$BIN" ] || {
  echo "НЕ НАШЁЛ БИНАРНИК под build/ios — сперва flutter build ios|ipa"
  echo "что там лежит:"; find build/ios -maxdepth 3 2>/dev/null | head -20
  exit 1
}
echo "бинарник: $BIN"

# Список берётся из ТОГО, ЧТО ИЩЕТ DART, а не из моста: в мосте 26 экспортов, а Dart
# зовёт 15 — среди прочих есть psy_midend_statepos, служебная заплата канона, которую
# никто не ищет по имени. Требовать её в бинарнике значило бы приучать обходить гейт.
ENGINE="${PSY_ENGINE:-lib/games/puzzles/engine.dart}"
[ -f "$ENGINE" ] || { echo "НЕТ $ENGINE — гейт не знает, что искать"; exit 2; }
SYMS=$(grep -oE "'psy_[a-z_0-9]+'" "$ENGINE" | tr -d "'" | sort -u)
[ -n "$SYMS" ] || { echo "НЕ НАШЁЛ ИМЁН В $ENGINE — сломался разбор, а не движок"; exit 2; }

MISSING=""
COUNT=0
for s in $SYMS; do
  COUNT=$((COUNT + 1))
  nm -gU "$BIN" 2>/dev/null | grep -q " _$s\$" || MISSING="$MISSING $s"
done

SIZE=$(wc -c < "$BIN" | tr -d ' ')
if [ -n "$MISSING" ]; then
  echo "🔴 ДВИЖОК НЕ ДОЕХАЛ. В бинарнике ($SIZE байт) нет символов:$MISSING"
  echo "   Проверь -Wl,-u для каждого в ios/Flutter/Release.xcconfig и STRIP_STYLE=non-global."
  echo "   ⚠️ Такая сборка соберётся и упадёт на первом ходе у человека."
  exit 1
fi
# ⚠️ ДВА ЧИСЛА, А НЕ ОДНО. Раздел «Судоку» справедливо насторожился на «15
# символов»: у моста экспортов 26, и если в бинарнике их правда 15, то десяти
# нет — а это невидимый отказ, при котором стартовые игры работают, а отдельные
# режимы открываются пустым экраном. Факт: в бинарнике все 26. Проверяем мы 15 —
# ровно те, что Dart ищет ПО ИМЕНИ; остальные одиннадцать зовутся изнутри C и
# выпасть в одиночку не могут. Но молчать об этом нельзя: одно число без второго
# читается как пропажа.
ALL=$(nm -gU "$BIN" 2>/dev/null | grep -c ' _psy_')
echo "✅ движок в бинарнике: проверено $COUNT из $ALL присутствующих psy_*, $SIZE байт"
[ -n "$TMPDIR_UNZIP" ] && rm -rf "$TMPDIR_UNZIP"
exit 0
