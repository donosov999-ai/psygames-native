import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// ХРАПОВИК НА ЗАШИТЫЙ РУССКИЙ ТЕКСТ: ЧИСЛО МОЖЕТ ТОЛЬКО УМЕНЬШАТЬСЯ.
///
/// 🔴 ЧТО ЛОВИТ. В приложении двенадцать языков. Строка, зашитая прямо в экран,
/// знает ровно один: немец, японец, кореец увидят русскую подпись посреди
/// переведённого экрана. Веб-сторона прошла это в августе — гейт
/// `frontend/src/__tests__/ci-i18n-hardcode-guard.test.ts` погасил долг из 14
/// экранов и 106 мест и с тех пор держит ноль. Перенос на Flutter начал заново:
/// замер 23.09.2026 нашёл 789 таких строк на пяти ветках.
///
/// 🔴 ПОЧЕМУ ХРАПОВИК, А НЕ СТЕНА. Ноль сегодня недостижим: 28 экранов уже
/// перенесены, и требование «переведи всё сейчас» остановило бы переезд. Поэтому
/// долг записан пофайлово и может только УМЕНЬШАТЬСЯ, а новый файл обязан
/// приходить с нулём. Так переезд идёт дальше, а долг не растёт.
///
/// ⚠️ И ЭТО НЕ СТЕНА БЕЗ ДВЕРИ. Прежде чем требовать, сделана дорога: словарь
/// берётся у веб-стороны (`flutter/tools/embed-l10n.mjs` вырезает нужные ключи
/// в `assets/l10n/<язык>.json`), читается через `L.t('ключ')`
/// (`lib/shell/l10n.dart`), и один экран переведён целиком как образец —
/// `lib/games/digit_span/screen.dart`, 19 строк → 0.
///
/// ⚠️ ЧТО СЧИТАЕТСЯ. Русский литерал вне комментариев и вне `Key('…')`. Ключи
/// виджетов считаются отдельно и сюда не входят — это другая беда (кириллица в
/// именах, отдельная задача), а не перевод. Метод счёта здесь ровно тот же, что
/// в замере, которым получены числа ниже: сменишь метод — сдвинутся и числа.
void main() {
  /// 🔴 ПРИЁМКА ЧУЖОЙ ВЕТКИ — РОВНО ОДИН РАЗ И ТОЛЬКО ПРИ ВЛИВАНИИ.
  ///
  /// Правило «подписи из словаря» появилось 23.09.2026, когда четыре раздела уже
  /// написали свои экраны. Отбивать их работу правилом, которого в момент работы
  /// не было, нечестно: гейт не имеет права ломать сделанное. Поэтому при вливании
  /// ветки раздела её числа заносятся сюда КАК ЕСТЬ, одной записью, с датой.
  ///
  /// ⚠️ И это единственный случай, когда число здесь растёт. Любая следующая правка
  /// того же файла обязана его УМЕНЬШАТЬ. Поднял число не на вливании — значит
  /// обошёл гейт, а не починил код.
  ///
  /// Принято: 23.09 — ядро, внимание, слова (160); 23.09 — судоку и головоломки (+124);
  /// 23.09 — «Жми и держись» (+19), в тот же день раздел перевёл его сам (−19).
  /// 23.09 — служебные сообщения выведены из счёта, числа пересчитаны методом гейта.
  /// 23.09 — «Пространство» (+224): вращение, ряд, лаборатория, развилка. Замер перед
  /// заносом: на готовые ключи веб-словаря ложится 51 строка из 274, остальным нужны
  /// НОВЫЕ ключи и перевод на 12 языков — это отдельная работа, задача заведена.
  /// 23.09 — та же ветка, развилка «Пространства» переведена сразу (−24, файл ушёл из списка),
  /// и вместе с ней названия четырёх упражнений лаборатории (−4, deal.dart ушёл туда же).
  ///
  /// 23.09 — «Слова», экран кроссворда (+8): файл приехал в main коммитом b2181fd5,
  /// подписи в нём литералами. Заношу приёмкой, а не поднимаю потолок молча:
  /// владелец — раздел «Слова», и гасить их ему. Ключи в общем словаре под это
  /// есть не все, часть требует перевода на 12 языков — это отдельная работа.
  ///
  /// 01.10 — раздел «Судоку» перевёл свои экраны (EN основной, решение Дениса 01.10):
  /// «Судоку» 31→0, «Самурай» 14→0, «Фрактал» 13→0, «Головоломки» 12→0, оболочка 4→2
  /// (подсказки «Пауза»/«Правила»; две оставшиеся — распознавание чужих подписей «Заново»), «Бездна» 13→1 (осталось зерно раздачи — данные, общие с вебом); сумма 691→611.
  /// 01.10 — оболочка: подсказки «Пауза»/«Правила» и «Назад» развилки — из словаря
  /// (EN основной): game_shell 4→2, hub_screen 4→3.
  ///
  /// Долг на 23.09.2026, пофайлово. МЕНЯТЬ ТОЛЬКО В МЕНЬШУЮ СТОРОНУ.
  ///
  /// Перевёл экран — опусти его число. Файла нет в списке — значит он обязан
  /// быть чистым: так новый перенос не добавляет долга молча.
  const debt = <String, int>{
    'main.dart': 16,
    'games/deep/screen.dart': 1,
    'shell/hybrid_app.dart': 3,
    'games/stroop/model.dart': 8,
    'shell/game_shell.dart': 2,
    'shell/hub_screen.dart': 3,
    'shell/tap_latency.dart': 4,
    'shell/web_game_screen.dart': 4,
  };

  // 284 у соседнего раздела минус 65, погашенных «Конфликтом внимания» в этом же коммите,
  // плюс 224 принятых при вливании «Пространства» 23.09, минус 28 — развилка раздела и
  // названия упражнений переведены в том же коммите: они держат КЛЮЧИ, как и веб-сторона.
  // 24.09 — «Слова» перевели все ЧЕТЫРЕ экрана анаграмм целиком (−38, все четыре файла
  // ушли из списка): 733 + 4 принятых строки слова-квадрата − 38. Новых ключей не
  // заводилось ни одного: веб-экран тех же режимов зовёт ровно эти подписи, и перевод
  // на 12 языков у них уже был — `node flutter/tools/embed-l10n.mjs` привёз их сам.
  // 30.09 — «Пространство»: правила четырёх упражнений «Лаборатории» и «Понятно» ушли в
  // словарь (задача 848da95d), spatial_lab 51 → 43: 699 − 8.
  // 30.09 — «Пространство» погасило долг целиком (задача bda168f4): семь файлов ушли из списка,
  // 691 − 208. Подписи каркаса — общим словарём теми же ключами, что зовут веб-экраны игр;
  // текст партии «Вращения» и «Точек» — словарями их модулей (`lib/shell/module_strings.dart`).
  // Новых ключей семь: у каждого перевод на все двенадцать языков в том же коммите.
  // 01.10 — «Объём памяти»: «Матрица памяти» перенесена заново целиком, все подписи — ключи
  // веб-словаря (задачи c1c20b36, 9d7032ab); файл ушёл из списка: −12.
  // 02.10 — оба сведены при вливании: 691 − 208 − 12. Затем цепочка «Судоку» (#123: нативные
  // экраны раздела по-английски, 691 → 611 у себя): все три погашения вместе — 390 по счёту пробы.
  // 02.10 — подсказки каркаса «Назад» развилки (#122): hub_screen 4 → 3.
  // 02.10 — «Сортировки» погасили долг целиком (задача 48ca6466): двенадцать файлов семи
  // экранов ушли из списка (−98) и заголовки пяти экранов в карте перехвата —
  // shell/hybrid_app.dart 8 → 3 (−5). Новых ключей 25, у каждого перевод на все двенадцать
  // языков в том же коммите. Коды отказа пробирок — латиницей: их не видит человек.
  // Сведено с main 07.10: 389 − 98 − 5 = 286.
  // 07.10 — «Поиск» и «Счёт» (задача 4b6f863e, #169): спринт, быстрый счёт и состав числа переведены
  // целиком, −54 (три файла ушли из списка). Готовые ключи веба взяты где были, 12 новых — сразу
  // на 12 языках: 286 − 54.
  // Там же: маджонг, OSpan и трекер объектов (−97, пять файлов ушли из списка). Подписи —
  // в словарь (21 новый ключ на 12 языках); алфавит OSpan, регулярка ввода и замечания проверки
  // договора трекера вынуты из счёта как данные (см. `alphabetList` ниже): 232 − 97.
  // Там же: «Математическая шкала» и «Таблица Шульте» (−53, оба файла ушли из списка),
  // 33 новых ключа на 12 языках; подсказка Шульте — целой фразой на каждое из девяти сочетаний
  // «что × порядок», а не склейкой; алфавит письменности — данные: 135 − 53.
  // 07.10 — там же: «Паттерны» (−42, оба файла ушли из списка). Русские копии подписей классов
  // и правил в модели заменены ключами общего словаря (список patternLabelKeys для сборщика);
  // два ключа виджета прятались в тернарнике внутри Key(…) — разнесены: 82 − 42.
  const total = 40;

  final counts = _scan(Directory('lib'));

  test('🔴 ни в одном файле зашитого текста не стало больше', () {
    final worse = <String>[];
    counts.forEach((path, n) {
      final ceiling = debt[path] ?? 0;
      if (n > ceiling) worse.add('  · $path: было $ceiling, стало $n');
    });
    expect(
      worse,
      isEmpty,
      reason: 'Зашитого русского текста прибавилось. Так экран говорит на одном языке из '
          'двенадцати. Перенеси строки в словарь: ключ завести в '
          'frontend/src/contexts/LanguageContext.tsx, звать через L.t(\'ключ\'), затем '
          'node flutter/tools/embed-l10n.mjs. Образец целиком переведённого экрана — '
          'lib/games/digit_span/screen.dart.\n${worse.join('\n')}',
    );
  });

  test('долг в сумме не вырос', () {
    final now = counts.values.fold<int>(0, (a, b) => a + b);
    expect(now, lessThanOrEqualTo(total),
        reason: 'сумма зашитых строк выросла с $total до $now');
  });

  test('число в пробе не устарело — если долг погашен, опусти его', () {
    // Тот же приём, что у веб-гейта: расхождение больше 20 значит, что константа
    // отстала от жизни и её пора двигать, иначе храповик перестаёт храповиком быть.
    final now = counts.values.fold<int>(0, (a, b) => a + b);
    expect(total - now, lessThanOrEqualTo(20),
        reason: 'долг $now, в пробе $total — опусти число в пробе');
  });
}

/// Считает ровно так же, как замер, давший числа выше.
///
/// ⚠️ ЧТО НЕ СЧИТАЕТСЯ И ПОЧЕМУ. Гейт заявляет «зашитый текст ИНТЕРФЕЙСА», значит
/// и считать он обязан то, что видит игрок. Поэтому из счёта вынуты:
///   · комментарии — вырезаются ДО поиска (иначе русское пояснение рядом с
///     переведённой строкой читается как нарушение);
///   · `Key('…')` — ключи виджетов, их видит только проба (это отдельная беда,
///     кириллица в именах, и чинится она отдельно);
///   · `throw`, `assert`, `debugPrint`, `print` — сообщения РАЗРАБОТЧИКУ. Они
///     обязаны быть внятными на языке того, кто чинит, и в словарь им не место.
///
/// 🔴 Уточнение внесено 23.09.2026 после того, как гейт покраснел на строке
/// `throw ArgumentError('на настольной сборке нужен путь к …')` — на сообщении,
/// которое игрок не увидит никогда. Гейт, считающий не то, что заявляет, рано
/// или поздно требует переводить служебные строки, и его перестают читать.
/// Числа выше пересчитаны этим же методом, а не подогнаны.
Map<String, int> _scan(Directory root) {
  final out = <String, int>{};
  final lineComment = RegExp(r'//.*');
  final blockComment = RegExp(r'/\*.*?\*/', dotAll: true);
  final keyLiteral = RegExp(r"Key\(\s*'[^'\n]*[А-Яа-яЁё][^'\n]*'\s*\)");
  final devMessage = RegExp(
      r"(throw\s+\w+\(|assert\(|debugPrint\(|[^.\w]print\()[^;]*?'[^'\n]*[А-Яа-яЁё][^'\n]*'",
      dotAll: true);
  /*
   * 🔴 КЛЮЧ ЧУЖОГО JSON — НЕ ТЕКСТ ИНТЕРФЕЙСА. Уточнение 24.09.2026.
   *
   * Веб-файл состава развилок описан по-русски: `профили`, `хабы`, `маршрут`,
   * `имя`, `значок`, `описание`. Нативная сторона читает ЭТОТ ЖЕ файл, и обращение
   * `j['профили']` — имя поля в чужих данных, а не подпись на экране. Переводить
   * его некуда и незачем: переведёшь — перестанешь находить поле.
   *
   * Гейт заявляет «зашитый текст ИНТЕРФЕЙСА», значит и считать обязан то, что
   * видит игрок. Так же здесь уже вынуты `throw`, `assert` и `debugPrint` — по
   * той же причине, и с той же оговоркой: числа ниже пересчитаны ЭТИМ методом.
   */
  final mapKey = RegExp(r"\[\s*'[^'\n]*[А-Яа-яЁё][^'\n]*'\s*\]");
  final anyLiteral = RegExp(r"'[^'\n]*[А-Яа-яЁё][^'\n]*'");
  /*
   * 🟢 ДАННЫЕ, А НЕ ПОДПИСИ — ещё три вида. Уточнение 02.10.2026 (задача 4b6f863e, «Поиск»).
   *
   * Задача перевода говорит прямо: законные данные не переводить, а объяснить в пробе.
   * Счёт до уточнения записывал их в долг, и погасить такой долг можно было только
   * обходом — спрятать букву в код символа. Поэтому они вынуты из счёта ЯВНО:
   *   · список ЦЕЛИКОМ из одиночных букв — алфавит упражнения. У «OSpan» это русский
   *     набор букв на запоминание (`lettersRu`); английский — `lettersEn`, выбор по языку
   *     (`ospan/screen.dart`, `_pool`). Одиночная буква вне такого списка — например
   *     единица «с» — по-прежнему считается: она подпись. Сюда же строка-алфавит письменности
   *     — не короче 10 заглавных букв подряд без пробелов (`schulte/screen.dart`: кириллица у
   *     русского языка, латиница у остальных);
   *   · литерал регулярного выражения `RegExp(r'[^А-ЯЁA-Z]')` — класс символов, не текст;
   *   · замечание проверки договора `issues.add('…')` — копится списком и уходит только в
   *     `StateError` (`object_tracker/model.dart`): то же сообщение разработчику, что
   *     `throw` и `assert` выше, только собранное по частям.
   * Замер перед уточнением: все виды встречались ТОЛЬКО в этих четырёх файлах раздела.
   */
  final alphabetList = RegExp(r"\[(\s*'[А-Яа-яЁё]'\s*,)+\s*('[А-Яа-яЁё]'\s*,?\s*)?\]");
  final alphabetString = RegExp(r"'[А-ЯЁ]{10,}'");
  final regexLiteral = RegExp(r"RegExp\(\s*r?'[^'\n]*[А-Яа-яЁё][^'\n]*'");
  final issueNote = RegExp(r"issues\.add\(\s*'[^'\n]*[А-Яа-яЁё][^'\n]*'");
  for (final f in root.listSync(recursive: true).whereType<File>()) {
    if (!f.path.endsWith('.dart')) continue;
    var src = f.readAsStringSync().replaceAll(blockComment, '').replaceAll(lineComment, '');
    var n = anyLiteral.allMatches(src).length -
        keyLiteral.allMatches(src).length -
        mapKey.allMatches(src).length -
        devMessage.allMatches(src).fold<int>(0, (a, m) => a + anyLiteral.allMatches(m[0]!).length) -
        alphabetList.allMatches(src).fold<int>(0, (a, m) => a + anyLiteral.allMatches(m[0]!).length) -
        alphabetString.allMatches(src).length -
        regexLiteral.allMatches(src).length -
        issueNote.allMatches(src).length;
    if (n > 0) out[f.path.replaceFirst('lib/', '')] = n;
  }
  return out;
}
