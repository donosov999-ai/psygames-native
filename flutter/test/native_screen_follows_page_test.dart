import 'package:flutter_test/flutter_test.dart';
import 'package:psygames_flutter/shell/hybrid_app.dart';

/// 🔴 СТРАНИЦА УШЛА ВПЕРЁД — НАТИВНЫЙ ЭКРАН ОБЯЗАН УЙТИ С НЕЙ.
///
/// Нашёл раздел «Сортировки» 24.09.2026 (задача a912f656). Зарядка после партии
/// через две секунды переводит шаг сама, а нативный экран оставался лежать поверх:
/// снимался он только действием человека. Человек видел ту же игру, и ни победа,
/// ни поражение ничего не двигали — под экраном зарядка уже была дальше.
/// Бьёт по зарядке целиком: она встаёт на первом же перенесённом шаге.
///
/// ⚠️ РЕШЕНИЕ ВЫНЕСЕНО ИЗ ОБРАБОТЧИКА РАДИ ЭТОЙ ПРОБЫ. Пока оно было вплетено в
/// приём сообщения от страницы, проверить его можно было только живым телефоном —
/// то есть на деле никак, и дефект доехал до людей.
void main() {
  test('🔴 зарядка перевела шаг на НЕперенесённую игру — экран снимаем', () {
    expect(routeAction('/games/hanoi', null), RouteAction.close);
  });

  test('🔴 зарядка перевела шаг на другую ПЕРЕНЕСЁННУЮ игру — снимаем и открываем новый', () {
    expect(routeAction('/games/hanoi', '/games/schulte'), RouteAction.closeThenOpen);
  });

  test('тот же адрес — ничего не трогаем', () {
    // Роутер сообщает об одном адресе дважды (`replaceState` после `pushState` —
    // обычное дело): второй раз экран пересоздавать нельзя.
    expect(routeAction('/games/hanoi', '/games/hanoi'), RouteAction.keep);
  });

  test('ничего не открыто — перенесённый адрес открываем', () {
    expect(routeAction(null, '/games/hanoi'), RouteAction.open);
  });

  test('ничего не открыто и адрес не наш — ничего', () {
    expect(routeAction(null, null), RouteAction.keep);
  });

  test('🔴 режимы одной игры различаются хвостом — это РАЗНЫЕ экраны', () {
    // Иначе «Небоскрёбы» и «Неравенства» открывали бы одну доску.
    expect(routeAction('/games/sudoku?mode=towers', '/games/sudoku?mode=unequal'),
        RouteAction.closeThenOpen);
  });
}
