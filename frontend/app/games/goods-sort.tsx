/**
 * СТРОГАЯ УКЛАДКА — ПРАВИЛО, КОТОРОЕ МЕНЯЕТ МЫШЛЕНИЕ, А НЕ ДАВИТ.
 *
 * 🔴 ЗАЧЕМ. Разбор жанра (19.08.2026) делит механики на две кучи: одни меняют
 * САМО ДЕРЕВО РЕШЕНИЙ, другие лишь повышают цену ошибки. Из нашего набора
 * замок и заморозка — давление: они запрещают ход, но не меняют, о чём думать.
 * А вот правило «класть можно только к ТАКОМУ ЖЕ товару или в ПУСТУЮ нишу» —
 * ровно то, из-за чего сортировка по контейнерам вообще является трудной
 * задачей: появляются тупики, и приходится считать на два-три хода вперёд.
 *
 * ⚠️ НЕ НА ВСЕХ УРОВНЯХ, И ЭТО ГЛАВНОЕ. Под строгой укладкой доска МОЖЕТ зайти
 * в тупик — это её смысл. Поставь правило везде, и половина партий будет
 * кончаться не победой и не честным проигрышем, а «ходов нет». Поэтому оно
 * приходит через уровень по своей таблице, объявляется правилом уровня заранее,
 * а тупик всегда разбирается отменой хода (она бесплатна) или перемешиванием.
 *
 * ⚠️ И ОБЯЗАТЕЛЬНО С ПРОВЕРКОЙ РЕШАЕМОСТИ. Расклад, выданный под строгой
 * укладкой, обязан иметь решение — гейт перебирает его целиком. Перебор здесь
 * посилен именно потому, что правило режет ветвление: почти все ходы незаконны.
 */
/**
 * СМЕШАННАЯ ЁМКОСТЬ НИШ — ЛОМАЕТ АВТОМАТИЗМ «ТРИ И ВСЁ».
 *
 * 🔴 ЗАЧЕМ. Когда все ниши одинаковы, через десяток уровней рука ходит сама:
 * видишь пару — несёшь третий, не глядя. Разбор жанра называет это прямо:
 * одинаковая ёмкость превращает игру в моторный навык. Ниша на ДВА товара
 * тройку не вместит вовсе — она только перевалочная; ниша на ЧЕТЫРЕ вмещает
 * тройку и ещё один лишний, то есть перестаёт очищаться сама собой.
 *
 * ⚠️ СУММА ЁМКОСТЕЙ НЕ МЕНЯЕТСЯ, И ЭТО НЕ КРАСОТА, А НЕОБХОДИМОСТЬ. Вся
 * арифметика решаемости (`spares`, потолок типов, ёмкость за вычетом запертых)
 * посчитана из «ниш × 3». Урежь общую ёмкость — и уровень станет теснее
 * задуманного, причём молча. Поэтому ниши меняются ПАРАМИ: одной даём 2,
 * другой 4, итог прежний.
 */
export const CAP_MIN = 2;
export const CAP_MAX = 4;

/** Со скольких уровней ёмкость перестаёт быть одинаковой. */
export const MIXED_CAP_FROM = 18;

/**
 * Ёмкости всех ниш уровня. Детерминированно от уровня — расклад случайный, а
 * форма доски обязана быть одна и та же при повторе уровня.
 */
export function capsFor(L: number, slots: number): number[] {
  const caps = Array(slots).fill(CAP);
  if (L < MIXED_CAP_FROM || slots < 6) return caps;
  // Пар тем больше, чем дальше уровень, но не больше трети доски.
  const pairs = Math.min(Math.floor(slots / 6), 1 + Math.floor((L - MIXED_CAP_FROM) / 12));
  // Шаг взаимно прост с типичными размерами доски (9, 12, 15, 16, 18),
  // иначе узкие и широкие ниши садились бы всегда на одни и те же места.
  const step = 5;
  for (let k = 0; k < pairs; k++) {
    const small = (k * 2 * step + L) % slots;
    const big = (small + step) % slots;
    if (small === big || caps[small] !== CAP || caps[big] !== CAP) continue;
    caps[small] = CAP_MIN;
    caps[big] = CAP_MAX;
  }
  return caps;
}

/**
 * 🔴 ЁМКОСТИ БЕРУТСЯ ОТ ЖИВОЙ ДОСКИ, А НЕ ОТ ЧИСЛА, ЛЕЖАЩЕГО РЯДОМ.
 *
 * Боевой краш 30.08.2026 у Дениса, v2.13.1: «доска собрана неверно: ниш 9,
 * ёмкостей 7». Экран считал ёмкости как `capsFor(level, gridRef.current.slots)`
 * и пересчитывал их по смене `cols`/`rows`. Но число ниш задаёт МАСКА ФОРМЫ, а
 * не размер сетки: замер по 60 уровням дал 55 переходов (десктоп) и 33
 * (телефон), где сетка та же, а ниш другое число. L6→L7 — ровно 3×3 и 7→9:
 * доска приезжала на девять ниш, ёмкости оставались на семь, и `makeBoard`
 * честно ронял игру.
 *
 * Здесь длина ответа равна длине доски ПО ПОСТРОЕНИЮ. Это и есть лечение: не
 * «добавить slots в зависимости» (следующий такой ref сломает снова), а брать
 * число ниш оттуда, где оно правда — из самой доски.
 */
export function capsForBoard(L: number, cells: readonly unknown[][]): number[] {
  return capsFor(L, cells.length);
}

export function strictPlacement(L: number): boolean {
  // С 14-го, через два уровня на третий: успевает и надоесть не успевает.
  return L >= 14 && (L - 14) % 3 === 0;
}

/* ───────────────── СКРЫТАЯ ИНФОРМАЦИЯ — шестая механика (§20 плана слияния) ─────────────────
 *
 * Источник: разбор конкурента «Ханойская башня Сорта» (mobirix), §20
 * PSYGAMES_MERGE_PLAN.md. Под верхними товарами ниши стоит «?»: что в глубине —
 * видно только когда снимешь то, что спереди.
 *
 * 🔴 ПОЧЕМУ ЭТО ОТДЕЛЬНАЯ МЕХАНИКА, А НЕ ДЕКОРАЦИЯ. Обычная сортировка
 * ПОЛНОСТЬЮ наблюдаема — весь файл выше на это опирается дословно (см. довод у
 * бесплатной отмены: «все товары на виду, исход хода считается заранее»).
 * Со скрытыми товарами оптимальный план построить нельзя: приходится
 * вскрывать → узнавать → перестраивать. Природа нагрузки меняется с «выполни
 * оптимальный план» на «планируй под неопределённостью и пересматривай» —
 * такого нет ни в одной из шести осей сложности этой игры.
 *
 * ⚠️ РАЗДАЧУ РЕЖИМ НЕ МЕНЯЕТ. §20.5 меряет «цену неопределённости» как
 * разность результата при полной и при скрытой информации на СОПОСТАВИМЫХ
 * досках — доска обязана оставаться той же, меняется только видимость.
 */

/**
 * С какого уровня приходит скрытая информация. Шестнадцатый — между строгой
 * укладкой (14) и смешанной ёмкостью (18): верх лесенки и так вводит по новой
 * механике раз в два уровня, режим встаёт в свой свободный такт.
 */
export const HIDDEN_FROM = 16;

/**
 * Идёт ли на уровне режим скрытой информации. Включение — по уровню, как у
 * всех усложнений этой игры (образец — strictPlacement): никаких переключателей
 * в настройке, механика приходит сама на верхних уровнях.
 *
 * 🔴 РИТМ «ЧЕРЕЗ ДВА НА ТРЕТИЙ» СО СДВИГОМ +2 ОТ СТРОГОЙ УКЛАДКИ — это не
 * вкус, а арифметика: (L−14)%3=0 и (L−16)%3=0 несовместимы, режимы НИКОГДА не
 * совпадают. Стек двух режимов был бы кашей (та же причина, по которой
 * препятствий нет до L6), а тупики строгой укладки вслепую — не сложность,
 * а лотерея: тупик там надо ВИДЕТЬ за два-три хода, скрытость это отменяет.
 *
 * 🔴 ЦЕЛЬ «УЛОЖИСЬ В ХОДЫ» ИСКЛЮЧЕНА (§20.4): лимит ходов — это минимум,
 * объявленный целью, а минимума при неполной информации не существует.
 * Первый реальный отвод — L25: кандидат ритма, но цель moves. Проверка
 * исполняется, а не украшает (мутация «убери отвод» краснит гейт на L25).
 *
 * Правило уровня заведено 02.09.2026 (LevelRule key 'hidden'), тексты — в словаре
 * на двенадцати языках (`lr_goods_sort_hidden_*`). До этого механика шла молча:
 * с шестнадцатого уровня часть товара пряталась под «?», а объяснения не было ни
 * одного — игрок узнавал о ней, натыкаясь.
 */
export function hiddenInfo(L: number): boolean {
  if (L < HIDDEN_FROM || (L - HIDDEN_FROM) % 3 !== 0) return false;
  return goalPlan(L).kind !== 'moves';
}

/**
 * 🔴 КАКИЕ ПРАВИЛА ДЕЙСТВУЮТ НА ЭТОМ УРОВНЕ.
 *
 * Две механики включаются НЕ подряд: «строгая укладка» и «скрытая информация»
 * идут прореженным ритмом (см. `strictPlacement` и `hiddenInfo`), поэтому мало
 * сравнить номер уровня с `fromLevel` — иначе игра пообещала бы правило там,
 * где механики нет, а значок в шапке горел бы вхолостую.
 *
 * Функция экспортируется РАДИ ГЕЙТА: проверять надо сам отбор, а не наличие
 * нужных слов в исходнике. `goods-sort-hidden-rule.test.ts` гоняет её по
 * уровням и сверяет с самими механиками.
 */
/**
 * 🔴 РАСКЛАДКА ШКАФА — ОДНА ФОРМУЛА НА ИГРУ И НА ГЕЙТ.
 *
 * До 02.09.2026 арифметика жила в теле компонента, а гейт `goods-sort-fit`
 * ПОВТОРЯЛ её у себя. Формулы разъехались молча: у гейта осталось `width - 24`,
 * потолок товара 112 и рама 7, у игры уже были `width - 20`, потолок 148 и
 * рама 9. Тест при этом зеленел — он честно проверял формулу, которой в игре
 * нет. Ровно так же незаметно разъезжается любая величина, продублированная
 * «для проверки».
 *
 * Теперь считает одна функция, а гейт зовёт ЕЁ. Разойтись стало нечему.
 *
 * ЧТО ЧЕМ ОГРАНИЧЕНО:
 * · товар — шириной (`capWide` штук в ряд) И высотой (rows рядов на экран);
 * · ниша — высотой товара снизу и доступной высотой сверху;
 * · шкаф — суммой рядов; лишняя высота уходит ВНУТРЬ ниш, а не остаётся
 *   воздухом вокруг (замер 02.09: было 414 из 629 доступных).
 */
export interface GsLayout {
  boardW: number; cellW: number; itemSize: number; itemH: number;
  nicheH: number; shelfH: number;
  /** Доля перекрытия соседних товаров в нише: 0 — встык, 0,3 — как на полке. */
  overlap: number;
  /**
   * Сколько занимает полный ряд товаров ВНУТРИ ниши, с учётом нахлёста.
   * Считается здесь, а не у вызывающего: гейт вписывания однажды уже проверял
   * собственную копию формулы вместо игры (см. `goods-sort-fit`).
   */
  rowW: number;
}

export function gsLayout(
  width: number, availH: number, cols: number, rows: number, capWide = 3,
): GsLayout {
  const CELL_GAP = 2;         // зазор между товарами внутри ниши (styles.cellRow)
  const ITEM_ASPECT = 0.6;    // ширина/высота, снято с самих спрайтов
  const SHELF_GAP = 9, HINT_H = 44, SHELF_PAD = 9;

  const boardW = Math.min(width - 20, 1200);
  const cellW = Math.floor((boardW - SHELF_PAD * 2 - SHELF_GAP * (cols - 1)) / cols);

  /**
   * 🔴 ВЫСОТА ОДНОЙ НИШИ ВЫВОДИТСЯ ИЗ ПОЛЯ, А НЕ ИЗ ТОВАРА.
   *
   * Прежний расчёт шёл наоборот: сначала товар по «availH / rows − 14», потом
   * ниша не меньше «товар + 8». Обе величины по отдельности выглядели разумно,
   * а вместе давали шкаф ВЫШЕ ПОЛЯ: замер гейта на десктопе 1280×800 — короб
   * 465 при поле 440, то есть нижний ряд под обрез. Ровно на этот обрез и был
   * репорт «половина банок обрезана» (18.08.2026); тогда починили ширину, а
   * высота осталась с той же болезнью и просто ждала своего экрана.
   *
   * Теперь порядок обратный и замкнутый: сколько высоты у ниши — столько и
   * товару, а не наоборот. Шкаф не может перерасти поле по построению.
   */
  const perRow = Math.floor((availH - HINT_H - SHELF_GAP * (rows - 1) - SHELF_PAD * 2 - 9) / rows);
  /**
   * 🔴 ТОВАРЫ СТОЯТ ВНАХЛЁСТ, КАК НА НАСТОЯЩЕЙ ПОЛКЕ.
   *
   * Замер 02.09.2026 на iPhone Pro Max (430 px): ниша 124 px, три товара встык
   * по 40 px. Товар был ограничен НЕ высотой и не спрайтом (непрозрачная часть
   * занимает 96–98 % картинки — проверено), а простой арифметикой «три в ряд».
   * Отсюда репорт Вали «ужасно товары мелкие»: на телефоне иначе и не выходило.
   *
   * У эталона жанра предметы на полке перекрываются — потому и крупные. Товар в
   * магазине и стоит внахлёст: заднее видно из-за переднего, а не рядом с ним.
   *
   * Арифметика: ряд занимает `item × (1 + (n − 1) × (1 − OVERLAP))`, значит при
   * трёх штуках и нахлёсте 0,3 делитель 2,4 вместо 3 — товар крупнее на четверть
   * ЛИНЕЙНО и в полтора раза по площади, при той же нише.
   *
   * ⚠️ ПОЧЕМУ 0,3, А НЕ БОЛЬШЕ. Перекрытое надо УЗНАВАТЬ: у молочных бутылок
   * разница в этикетке (§7.3), и накрыв половину, мы вернули бы дефект «шесть
   * одинаковых силуэтов». Треть скрывает бок и оставляет и верх, и этикетку.
   * ⚠️ И перекрытый товар остаётся НАЖИМАЕМЫМ: видимая доля 0,7 × item всё равно
   * шире, чем товар был до нахлёста (0,7 × 50 = 35 против 40 — почти столько же),
   * а передний виден целиком. Это сторожит `tap-target-audit`.
   */
  const OVERLAP = 0.3;
  const рядДелитель = 1 + (capWide - 1) * (1 - OVERLAP);
  const fitsInCell = Math.floor((cellW - CELL_GAP * (capWide - 1)) / рядДелитель);
  const fitsInRow = Math.floor((perRow - 8) * ITEM_ASPECT);
  const itemSize = Math.max(18, Math.min(148, fitsInCell, fitsInRow));
  const itemH = Math.round(itemSize / ITEM_ASPECT);

  // Избыток высоты уходит ВНУТРЬ ниши (товар стоит на доске, над ним видна
  // задняя стенка), но не выше `perRow` — иначе короб снова перерастёт поле.
  const nicheH = Math.max(itemH + 8, Math.min(Math.round(itemH * 2.2), perRow));
  // Высота всего короба: ряды + зазоры между ними + рама сверху/снизу + торец.
  const shelfH = nicheH * rows + SHELF_GAP * (rows - 1) + SHELF_PAD * 2 + 9;

  const шагРяда = itemSize * (1 - OVERLAP) + CELL_GAP;
  const rowW = Math.round(itemSize + (capWide - 1) * шагРяда);

  return { boardW, cellW, itemSize, itemH, nicheH, shelfH, overlap: OVERLAP, rowW };
}

