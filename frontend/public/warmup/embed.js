/**
 * ВСТРАИВАНИЕ СТРАНИЦЫ «ЗАРЯДКИ» В PSYGAMES.
 *
 * 🔴 ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ. Зарядка целиком проработана в отдельном
 * приложении «Умный будильник»: десять наборов, картинки, траектория взгляда,
 * рамка времени по фазам, параллельный режим, предупреждения безопасности.
 * Раньше я переносил это в psygames по частям — переписывал рисовалки на
 * `react-native-svg`. Так переносится геометрия и теряется всё остальное:
 * первым же замером нашлось, что гимнастика глаз получила у меня фигуру
 * дыхания вместо своей движущейся мишени. Пересобранная по кускам вещь не
 * равна перенесённой.
 *
 * Поэтому берётся СТРАНИЦА ЦЕЛИКОМ, готовой сборкой (`web-dist`), и
 * показывается внутри psygames. Этот файл — единственное, что psygames к ней
 * добавляет: убирает чужую обвязку и рассказывает приложению об итоге.
 *
 * ⚠️ ЗДЕСЬ НЕТ НИ ОДНОЙ ПРАВКИ `app.mjs`. Страница приезжает сборкой будильника
 * и будет перезаписана следующей сборкой — правки в ней не живут. Всё, что
 * нужно psygames, делается СНАРУЖИ: скрытием элементов и наблюдением за DOM.
 * Сверху этот файл кладёт `scripts/sync-warmup-page.mjs`.
 */
(function () {
  'use strict';

  var параметры = new URLSearchParams(location.search);
  if (параметры.get('embed') !== '1') return;

  var ЧУЖАЯ_ОБВЯЗКА = [
    '.topbar', // шапка со своим логотипом и переключателями
    '.primary-nav', // вкладки Будильники / Зарядка / История
    '.app-footer',
  ];

  function убратьОбвязку() {
    ЧУЖАЯ_ОБВЯЗКА.forEach(function (селектор) {
      var узлы = document.querySelectorAll(селектор);
      for (var i = 0; i < узлы.length; i++) узлы[i].style.display = 'none';
    });
    // Панели «Будильники» и «История» в psygames не нужны: там свой список игр.
    ['alarms', 'history'].forEach(function (имя) {
      var панель = document.querySelector('[data-panel="' + имя + '"]');
      if (панель) панель.style.display = 'none';
    });
    var зарядка = document.querySelector('[data-panel="recharge"]');
    if (зарядка) {
      зарядка.hidden = false;
      зарядка.style.display = '';
    }
    document.body.classList.add('is-embedded');
  }

  /** Тема и язык приходят от psygames — страница не решает их сама. */
  function принятьНастройки() {
    var тема = параметры.get('theme');
    if (тема) document.documentElement.dataset.theme = тема;
    var язык = параметры.get('lang');
    if (язык) {
      var кнопка = document.getElementById('language-toggle');
      // Переключатель двухпозиционный: жмём, только если язык не тот.
      if (кнопка && (document.documentElement.lang || '').slice(0, 2) !== язык.slice(0, 2)) кнопка.click();
    }
  }

  function отправить(сообщение) {
    var строка = JSON.stringify(сообщение);
    try {
      if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(строка);
    } catch (e) {
      /* нативной обёртки нет — значит, мы в iframe */
    }
    try {
      if (window.parent && window.parent !== window) window.parent.postMessage(строка, '*');
    } catch (e) {
      /* другой источник — не наш случай, страница лежит рядом */
    }
  }

  /**
   * ИТОГ СЕССИИ БЕЗ ПРАВОК В `app.mjs`.
   *
   * Признак завершения — появление блока `.practice-complete`: страница рисует
   * его ровно тогда, когда подсказки кончились (`frame.cues.length === 0`).
   * Признак самой сессии — класс `is-practice-running` на `body`.
   *
   * ⚠️ Флаг «дошло до конца» снимается ПОКАЗОМ блока, а не закрытием слоя:
   * закрытие одинаково и у завершения, и у выхода без записи, и различить их
   * в момент закрытия уже нечем.
   */
  var идёт = false;
  var дошлоДоКонца = false;
  var началось = 0;

  function следить() {
    var сейчасИдёт = document.body.classList.contains('is-practice-running');
    /**
     * 🔴 БЛОК ЗАВЕРШЕНИЯ ЧИТАЕТСЯ КАЖДЫЙ РАЗ, В ТОМ ЧИСЛЕ В МОМЕНТ ЗАКРЫТИЯ.
     *
     * Первая редакция поднимала флаг «дошло до конца» ТОЛЬКО пока сессия идёт,
     * а на закрытии его читала. Замер живой сессии 27.08.2026: пришло
     * `warmup:exit` с длительностью 168 787 мс — то есть полностью пройденная
     * зарядка отдавалась как выход без записи, и сохранялся бы НОЛЬ.
     *
     * Причина: страница в одном проходе и рисует блок завершения, и снимает
     * класс сессии (`renderPractice` → `finishPractice`). Наблюдатель получает
     * оба изменения ОДНОЙ пачкой, и к моменту вызова `сейчасИдёт` уже ложь —
     * ветка с поднятием флага не выполнялась никогда.
     *
     * ⚠️ Ложного «дошло» от прошлой сессии тут быть не может: пока подсказки
     * есть, страница блок завершения не рисует, и на старте флаг гасится.
     */
    var естьЗавершение = !!document.querySelector('.practice-complete');
    if (сейчасИдёт && !идёт) {
      идёт = true;
      дошлоДоКонца = false;
      началось = Date.now();
      // Практика только пошла — значит кнопка сейчас говорит «Пауза».
      подписьХода = подписьКнопки();
      отправить({ type: 'warmup:start', atMs: началось });
    }
    if (идёт && естьЗавершение) дошлоДоКонца = true;
    if (!сейчасИдёт && идёт) {
      идёт = false;
      подписьХода = null;
      отправить({
        type: дошлоДоКонца || естьЗавершение ? 'warmup:done' : 'warmup:exit',
        durationMs: Math.max(0, Date.now() - началось),
      });
    }
  }

  /**
   * 🔴 ПРИЗНАК ПАУЗЫ — ТОЛЬКО ПОДПИСЬ КНОПКИ, И ЕЁ НАДО СНЯТЬ ЖИВЬЁМ.
   *
   * Первая редакция читала класс `is-practice-paused` на `body` и `aria-pressed`
   * у кнопки. Замер 27.08.2026: ни того, ни другого в странице НЕТ — при паузе
   * `body` несёт `is-practice-running is-practice-immersive`, а `aria-pressed`
   * равен `null`. Проверка всегда отвечала «не на паузе», из-за чего СНЯТИЕ
   * паузы молча не срабатывало: приложение вернулось из фона, а практика
   * осталась стоять навсегда. Поймано прогоном, а не чтением.
   *
   * Единственная отметка состояния в разметке — ПОДПИСЬ кнопки (`app.mjs`:
   * `textContent = phase === 'paused' ? t('resume') : t('pause')`). Она
   * переводится, поэтому сравнивать её со словом нельзя. Зато её можно СНЯТЬ
   * живьём: в момент, когда практика только пошла, кнопка гарантированно
   * говорит «Пауза». Это эталон; всё, что от него отличается, — пауза.
   */
  var подписьХода = null;

  function подписьКнопки() {
    var кнопка = document.getElementById('practice-pause');
    return кнопка ? (кнопка.textContent || '').trim() : null;
  }

  function наПаузе() {
    var сейчас = подписьКнопки();
    if (сейчас === null || подписьХода === null) return null;
    return сейчас !== подписьХода;
  }

  /**
   * Пауза приложения обязана гасить часы страницы: у psygames часы игровые, у
   * встроенной страницы свои, и подменить их снаружи нечем. Жмём её же кнопку.
   */
  function держатьПаузу(нужна) {
    var кнопка = document.getElementById('practice-pause');
    if (!кнопка || !идёт) return;
    var сейчас = наПаузе();
    if (сейчас === null || сейчас === нужна) return;
    кнопка.click();
  }

  /**
   * 🔴 ССЫЛКА НА КОНКРЕТНЫЙ НАБОР — `?set=breathing`.
   *
   * В psygames карточки «Дыхание» и «Гимнастика глаз» — двери СЮДА. Без этого
   * нажавший «Дыхание» попадал бы в общий каталог с набором по умолчанию.
   *
   * ⚠️ Разметка снята с самой страницы (`app.mjs`, карточка каталога), а не
   * придумана: первая редакция искала `data-set` и `toggle-set` — таких
   * атрибутов там нет вовсе, и выбор молча не срабатывал бы. На деле карточка
   * помечена `data-set-id`, кнопка — `data-action="select-practice"`, выбранная
   * несёт класс `is-selected`, а базовый набор («Дыхание» всегда включено)
   * держит кнопку `disabled`. По тексту искать нельзя — он переводится.
   */
  function выбратьНабор() {
    var набор = параметры.get('set');
    if (!набор) return;
    var попытки = 0;
    var таймер = setInterval(function () {
      попытки += 1;
      var карточка = document.querySelector('[data-set-id="' + набор + '"]');
      var кнопка = карточка && карточка.querySelector('[data-action="select-practice"]');
      if (кнопка) {
        if (!карточка.classList.contains('is-selected') && !кнопка.disabled) кнопка.click();
        карточка.scrollIntoView({ block: 'center' });
        clearInterval(таймер);
      } else if (попытки > 40) {
        clearInterval(таймер);
      }
    }, 100);
  }

  /** Приём команд от приложения: сейчас это только пауза. */
  function слушатьРодителя() {
    window.addEventListener('message', function (событие) {
      if (typeof событие.data !== 'string') return;
      var разобрано;
      try { разобрано = JSON.parse(событие.data); } catch (e) { return; }
      if (разобрано && разобрано.type === 'warmup:hold') держатьПаузу(Boolean(разобрано.held));
    });
  }

  function запуск() {
    убратьОбвязку();
    слушатьРодителя();
    выбратьНабор();
    принятьНастройки();
    new MutationObserver(следить).observe(document.body, {
      attributes: true,
      childList: true,
      subtree: true,
      attributeFilter: ['class', 'hidden'],
    });
    отправить({ type: 'warmup:ready' });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', запуск);
  } else {
    запуск();
  }
})();
