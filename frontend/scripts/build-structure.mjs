#!/usr/bin/env node
/* psygames-build-structure · VER 1 · 13.09.2026 */
/**
 * ЖИВАЯ СТРУКТУРА: ИГРЫ, РАЗВИЛКИ, ПОТОКИ, ПРОФИЛИ — ОДНИМ ФАЙЛОМ.
 *
 *   node scripts/build-structure.mjs
 *
 * 🔴 ЗАЧЕМ. Просьба Дениса 13.09.2026: «рядом с рефами вообще сделай структуру
 * игры и структуру хабов, дай ссылку — короче, чтобы не читать всем по десять
 * раз». До этого состав пересказывался в одиннадцати ТЗ разделов, и каждая
 * перетасовка развилок оставляла десять устаревших копий: чаты продолжали
 * помнить «все сорок головоломок в puzzles-hub» спустя выпуск после переезда.
 *
 * Поэтому список РОВНО ОДИН и он СОБИРАЕТСЯ, а не пишется: числа берутся из тех
 * же данных, что показывает приложение и редактор плейлистов. Врать ему нечем.
 *
 * ⚠️ ПИШЕТСЯ В ДВА МЕСТА ОДНОЙ КОМАНДОЙ. В репозиторий — для чатов-разделов; в
 * хранилище Obsidian — для Дениса, он читает оттуда с телефона. Копии не
 * расходятся, потому что обе печатает один прогон; править руками ни одну нельзя,
 * об этом сказано в шапке каждой.
 *
 * 🦥 Снимок снимается тем же способом, что у редактора (`build-playlist-editor.mjs`):
 * состав лежит в TypeScript с алиасами `@/`, обычный node его не прочитает, а jest
 * уже умеет и то, и другое. Второй инструмент ради одного снимка не заводится.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync, mkdtempSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { tmpdir, homedir } from 'node:os';
import path from 'node:path';

const ЗДЕСЬ = path.dirname(fileURLToPath(import.meta.url));
const ФРОНТ = path.resolve(ЗДЕСЬ, '..');
const КОРЕНЬ = path.resolve(ФРОНТ, '..');
const ГОТОВО = path.join(КОРЕНЬ, 'STRUCTURE.md');
const ОБСИДИАН = path.join(homedir(), 'Documents/Obsidian Vault/PsyGames/Структура игр и развилок.md');
const РЕДАКТОР = path.join(homedir(), 'Downloads/Code claude/psygames-playlist-editor/playlist-editor.html');

/* ── снимок состава ─────────────────────────────────────────────────────── */
const врем = mkdtempSync(path.join(tmpdir(), 'psygames-structure-'));
const снимокПуть = path.join(врем, 'data.json');
console.log('⏳ снимаю состав (jest)…');
try {
  execFileSync('npx', ['jest', 'src/__tests__/playlist-editor-data.test.ts', '--silent'], {
    cwd: ФРОНТ, env: { ...process.env, PLAYLIST_EDITOR_OUT: снимокПуть }, stdio: 'inherit',
  });
} catch {
  console.error('🔴 снимок не снялся: проба playlist-editor-data упала.');
  process.exit(1);
}
if (!existsSync(снимокПуть)) { console.error('🔴 проба прошла, а файла снимка нет:', снимокПуть); process.exit(1); }
const снимок = JSON.parse(readFileSync(снимокПуть, 'utf8'));
const файл = JSON.parse(readFileSync(path.join(ФРОНТ, 'src/constants/defaultPlaylists.json'), 'utf8'));

/* ── что во что превращается ────────────────────────────────────────────── */
const ИМЯ_ИГРЫ = new Map(снимок.игры.map((и) => [и.route, и.имя]));
const ИМЯ_РЕЖИМА = new Map((снимок.тэтхэма ?? []).map((т) => [т.режим, т.имя]));
/** Развилки: файл главнее кода — в приложении работает именно он. */
const хабыФайла = файл.профили?.odv999?.хабы ?? {};
const ХАБЫ = {};
for (const маршрут of new Set([...Object.keys(снимок.хабы), ...Object.keys(хабыФайла)])) {
  ХАБЫ[маршрут] = (хабыФайла[маршрут] ?? снимок.хабы[маршрут] ?? []).map((э) => {
    const r = typeof э === 'string' ? э : (э.маршрут ?? э.route);
    const [путь, запрос = ''] = r.split('?');
    const режим = new URLSearchParams(запрос).get('mode');
    const своё = путь === '/games/puzzles' ? (ИМЯ_РЕЖИМА.get(режим ?? 'Unruly') ?? режим ?? 'Unruly') : null;
    return { маршрут: r, путь, режим, имя: своё ?? ИМЯ_ИГРЫ.get(путь) ?? путь };
  });
}
const ПОДПИСЬ_ХАБА = new Map(снимок.игры.filter((и) => ХАБЫ[и.route]).map((и) => [и.route, и.имя]));

const строки = [];
const П = (...x) => строки.push(...x);
const дата = new Date().toISOString().slice(0, 16).replace('T', ' ');
let коммит = '—';
try { коммит = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: КОРЕНЬ }).toString().trim(); } catch { /* не репозиторий */ }

П(`<!-- STRUCTURE.md · СОБИРАЕТСЯ, РУКАМИ НЕ ПРАВИТЬ · ${дата} · коммит ${коммит} -->`);
П('# PsyGames — структура: игры, развилки, потоки, профили', '');
П(`> 🔴 **ЭТОТ ФАЙЛ СОБИРАЕТСЯ, А НЕ ПИШЕТСЯ.** Пересобрать: \`node frontend/scripts/build-structure.mjs\``);
П('> из корня репозитория. Правка руками пропадёт при следующей сборке — и, что хуже,');
П('> соврёт до неё. Числа сняты из тех же данных, что показывает приложение.');
П('>');
П(`> Снято ${дата} на коммите \`${коммит}\`. Копия для Дениса лежит в Obsidian:`);
П('> `PsyGames/Структура игр и развилок.md` — обе печатает один прогон.');
П('');
П('> ⚙️ **Состав правится не здесь и не в коде, а ФАЙЛОМ настроек.**');
П('> Заводской состав — `frontend/src/constants/defaultPlaylists.json` (едет в сборке);');
П(`> мышью — редактор \`tools/playlist-editor.html\` (у Дениса: [открыть](file://${encodeURI(РЕДАКТОР)})).`);
П('');

/* ── развилки ───────────────────────────────────────────────────────────── */
П('## Развилки — что внутри каждой', '');
П(`Развилок ${Object.keys(ХАБЫ).length}. Карточка «(группа)» — вход в другую развилку.`, '');
for (const [маршрут, карточки] of Object.entries(ХАБЫ).sort()) {
  const имя = ПОДПИСЬ_ХАБА.get(маршрут) ?? маршрут;
  П(`### ${имя} · \`${маршрут}\` — ${карточки.length}`, '');
  for (const к of карточки) {
    const группа = ХАБЫ[к.путь] ? ' (группа)' : '';
    const реж = к.режим ? ` \`?mode=${к.режим}\`` : '';
    П(`- **${к.имя}**${группа} — \`${к.путь}\`${реж}`);
  }
  П('');
}

/* ── головоломки Тэтхэма ────────────────────────────────────────────────── */
const гдеРежим = new Map();
for (const [маршрут, карточки] of Object.entries(ХАБЫ)) {
  for (const к of карточки) if (к.путь === '/games/puzzles') гдеРежим.set(к.режим ?? 'Unruly', ПОДПИСЬ_ХАБА.get(маршрут) ?? маршрут);
}
П('## Головоломки Тэтхэма — режим → развилка', '');
П(`Все они — ОДИН экран \`/games/puzzles\`, режим выбирается \`?mode=<имя>\`; лестница у каждой`);
П('своя (`puzzles_<режим>`), `game_type` общий. Разнесено по развилкам 13.09.2026.', '');
П('| режим | название | развилка |', '|---|---|---|');
for (const [режим, хаб] of [...гдеРежим].sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]))) {
  П(`| \`${режим}\` | ${ИМЯ_РЕЖИМА.get(режим) ?? режим} | ${хаб} |`);
}
П('', `Всего разложено: **${гдеРежим.size}**.`, '');

/* ── игры ───────────────────────────────────────────────────────────────── */
const вРазвилках = new Map();
for (const [маршрут, карточки] of Object.entries(ХАБЫ)) {
  for (const к of карточки) {
    if (!вРазвилках.has(к.путь)) вРазвилках.set(к.путь, []);
    вРазвилках.get(к.путь).push(ПОДПИСЬ_ХАБА.get(маршрут) ?? маршрут);
  }
}
П('## Игры каталога', '');
П(`Карточек в каталоге: **${снимок.игры.length}**. «Развилки» — где игра показана человеку;`);
П('пусто значит, что вход к ней только из профиля, главной или зарядки.', '');
const поРазделам = {};
for (const и of снимок.игры) (поРазделам[и.раздел ?? '—'] ||= []).push(и);
for (const [раздел, игры] of Object.entries(поРазделам).sort()) {
  П(`### Раздел \`${раздел}\` — ${игры.length}`, '');
  П('| игра | id | маршрут | развилки |', '|---|---|---|---|');
  for (const и of игры.sort((a, b) => a.имя.localeCompare(b.имя))) {
    const где = [...new Set(вРазвилках.get(и.route) ?? [])].join(', ');
    П(`| ${и.имя} | \`${и.id}\` | \`${и.route}\` | ${где || '—'} |`);
  }
  П('');
}

/* ── потоки и профили ───────────────────────────────────────────────────── */
const наборы = файл.наборы ?? [];
П('## Потоки — непрерывные серии', '');
П('У каждой развилки три длины; в потоке разрешены ТОЛЬКО игры этой развилки');
П('(гейт `default-playlists-ship`). У профиля — свои три, по его теме.', '');
П('| серия | 5 мин | 10 мин | 15 мин |', '|---|---|---|---|');
const ключи = [...new Set(наборы.map((н) => н.id.replace(/-(5|10|15)$/, '')))];
for (const к of ключи) {
  const шт = [5, 10, 15].map((м) => наборы.find((н) => н.id === `${к}-${м}`)?.шаги.length ?? '—');
  const имя = наборы.find((н) => н.id.startsWith(к))?.название.replace(/ · \d+ мин$/, '') ?? к;
  П(`| ${имя} \`${к}\` | ${шт[0]} | ${шт[1]} | ${шт[2]} |`);
}
П('', `Всего серий: **${наборы.length}**.`, '');

П('## Профили', '');
П('| профиль | игр | развилок задано файлом | своих серий |', '|---|---|---|---|');
for (const [id, пр] of Object.entries(файл.профили ?? {})) {
  const игр = Array.isArray(пр.игры) ? пр.игры.length : (снимок.профили?.find((p) => p.id === id)?.игры?.length ?? '—');
  П(`| \`${id}\` | ${игр} | ${Object.keys(пр.хабы ?? {}).length} | ${(пр.наборы ?? []).length} |`);
}
П('');

const текст = строки.join('\n');
writeFileSync(ГОТОВО, текст, 'utf8');
mkdirSync(path.dirname(ОБСИДИАН), { recursive: true });
writeFileSync(ОБСИДИАН, текст, 'utf8');
console.log(`✅ ${path.relative(КОРЕНЬ, ГОТОВО)}`);
console.log(`✅ ${ОБСИДИАН}`);
console.log(`   развилок ${Object.keys(ХАБЫ).length} · игр ${снимок.игры.length} · головоломок ${гдеРежим.size} · серий ${наборы.length}`);
