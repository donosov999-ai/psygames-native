#!/usr/bin/env node
/* psygames-ref-actuality · VER 1 · 27.08.2026 */
/**
 * БЛОК АКТУАЛИЗАЦИИ РЕФА: ЗАЯВЛЕНО ПРОТИВ ФАКТА.
 *
 * ━━━ ЗАЧЕМ ━━━
 * `PROJECT_REF.md` вырос до 116 КБ и 1323 строк. Реф такого размера читают
 * выборочно, а верят ему целиком — и это худшее сочетание: устаревшая строка
 * выглядит ровно так же, как верная.
 *
 * 🔴 ЖИВОЙ СЛУЧАЙ, 26.08.2026. В §5 рефа СТОЯЛО дословно: «Строго без --delete —
 * иначе снесёт бинарники в /downloads, каталог /play» и «zsh не разбивает $SSHOPT
 * на аргументы». Я не прочитал ни то, ни другое и снёс 227 МБ прода ровно этими
 * двумя способами сразу. Реф знал. Реф не спросили.
 * Отсюда правило: реф обязан уметь САМ сказать, где он разошёлся с жизнью, —
 * командой, а не доверием к тексту.
 *
 * ⚠️ ЭТО НЕ ПРОВЕРКА ЗДОРОВЬЯ. Красная строка здесь означает «реф врёт», а не
 * «система сломана». Здоровьем конвейера отзывов занимается feedback-health.mjs.
 *
 * ЗАПУСК:  node scripts/ref-actuality.mjs
 *          … --json   машиночитаемо
 * КОД: 0 — реф совпал с жизнью · 1 — есть расхождения · 2 — не смог проверить.
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FRONT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(FRONT, '..');
const REF = join(REPO, 'PROJECT_REF.md');
const JSON_OUT = process.argv.includes('--json');

const строки = [];
const добавить = (что, заявлено, факт, ok, пояснение = '') =>
  строки.push({ что, заявлено: String(заявлено), факт: String(факт), ok, пояснение });

const читать = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : '');
const ref = читать(REF);
if (!ref) {
  console.error('❌ PROJECT_REF.md не найден — он локальный и в .gitignore, это ожидаемо на чужой машине');
  process.exit(2);
}

/** Первое число перед словом — «61 тренажёр» → 61. */
const числоПеред = (текст, слово) => {
  const m = new RegExp(`(\\d+)\\s+${слово}`).exec(текст);
  return m ? Number(m[1]) : null;
};

// ─── 1. Версия: три манифеста + то, что отдаёт прод ───────────────────────
const версии = {
  'app.json': JSON.parse(читать(join(FRONT, 'app.json')) || '{}').expo?.version,
  'package.json': JSON.parse(читать(join(FRONT, 'package.json')) || '{}').version,
  'tauri.conf.json': JSON.parse(читать(join(REPO, 'src-tauri/tauri.conf.json')) || '{}').version,
};
const разных = [...new Set(Object.values(версии))];
добавить('версия в трёх манифестах', 'одна и та же', Object.entries(версии).map(([k, v]) => `${k}=${v}`).join(' '), разных.length === 1,
  разных.length === 1 ? '' : '🔴 в Info.plist попадает tauri.conf.json — именно её видит человек');

let прод = null;
try {
  прод = execFileSync('curl', ['-fsS', '--max-time', '15', 'https://psy-games.pro/play/version.json'], { encoding: 'utf8' });
} catch { /* сеть может быть недоступна — это не провал рефа */ }
if (прод) {
  const v = (JSON.parse(прод).version || '').trim();
  /**
   * ⚠️ СВЕРЯЕМ С ПОСЛЕДНИМ ТЕГОМ, А НЕ С РАБОЧИМ ДЕРЕВОМ. В дереве версия уходит
   * вперёд сразу, как её подняли, а `version.json` обязан называть то, что
   * ВЫПУЩЕНО. Первая редакция сравнивала с app.json и краснела на каждой
   * невыпущенной правке — то есть почти всегда.
   */
  let тег = '';
  try { тег = execFileSync('git', ['describe', '--tags', '--abbrev=0'], { cwd: REPO, encoding: 'utf8' }).trim().replace(/^v/, ''); } catch { /* тегов может не быть */ }
  добавить('версия, которую приложение считает свежей', тег ? `последний тег ${тег}` : '(тегов нет)', v,
    !тег || v === тег,
    v === тег ? '' : '🔴 приложение сравнивает СВОЮ версию с этой: отстала — предложим уже стоящее, опередила — не предложим никогда');
} else {
  добавить('версия на проде', 'проверяется', 'сеть недоступна', true, 'пропущено, не ошибка');
}

// ─── 2. Игры: сколько заявлено в рефе против того, что лежит ──────────────
/**
 * ⚠️ СРАВНИВАТЬ С РЕЕСТРОМ, А НЕ С ЧИСЛОМ ФАЙЛОВ. Первая редакция считала .tsx в
 * app/games и получала 73 против заявленных 61 — и кричала «реф врёт», хотя реф
 * прав: 61 это записи в реестре, а файлов больше (служебные экраны, режимы,
 * варианты одной игры). Проверка, кричащая впустую, обесценивает себя за день.
 */
const реестр = читать(join(FRONT, 'src/constants/games.ts'));
const вРеестре = (реестр.match(/^\s{2}\{\s*id:/gm) || реестр.match(/\bid:\s*'/g) || []).length;
const экраны = readdirSync(join(FRONT, 'app/games')).filter((f) => f.endsWith('.tsx')).length;
const заявленоИгр = числоПеред(ref, 'тренажёр');
добавить('тренажёров в реестре', заявленоИгр ?? '—', `${вРеестре} в реестре · ${экраны} файлов-экранов`,
  заявленоИгр != null && Math.abs(вРеестре - заявленоИгр) <= 2,
  'файлов всегда больше: служебные экраны и режимы внутри игр в реестр не попадают');

// ─── 3. Языки ─────────────────────────────────────────────────────────────
/**
 * ⚠️ ДВА РАЗНЫХ ЧИСЛА, И ОБА ВЕРНЫ: у приложения 12 локалей, у промо-сайта 7.
 * Первая редакция брала из рефа первое попавшееся «N язык» и сравнивала с
 * приложением — то есть сверяла сайт с приложением. Проверяем ПРИЛОЖЕНИЕ против
 * той строки рефа, где сказано про приложение.
 */
/**
 * ⚠️ ФАЙЛОВ ДЕСЯТЬ, А ЯЗЫКОВ ДВЕНАДЦАТЬ. `en` и `ru` лежат не отдельными файлами,
 * а прямо в `LanguageContext` — считать только каталог значит недосчитать два и
 * объявить расхождение там, где его нет.
 */
const i18nDir = join(FRONT, 'src/contexts/translations');
const БАЗОВЫЕ = 2;   // en + ru, внутри LanguageContext
const локалей = existsSync(i18nDir)
  ? readdirSync(i18nDir).filter((f) => /^[a-z]{2}(-[A-Za-z]+)?\.tsx?$/.test(f)).length + БАЗОВЫЕ
  : null;
// «7 языков» в рефе — про промо-сайт, «12 языков» — про приложение. Берём наибольшее
// из встречающихся: у приложения локалей заведомо не меньше, чем у сайта.
const всеЧисла = [...ref.matchAll(/(\d+)\s+язык/g)].map((m) => Number(m[1]));
const заявленоЯз = всеЧисла.length ? Math.max(...всеЧисла) : null;
добавить('языков в приложении', заявленоЯз ?? '—',
  локалей == null ? 'каталог переводов не найден' : `${локалей} (${локалей - БАЗОВЫЕ} файлов + en/ru внутри контекста)`,
  локалей != null && заявленоЯз != null && локалей === заявленоЯз,
  'у сайта своё число (7) — это не расхождение, это другой продукт');

// ─── 4. Голосовые: жив ли конвейер ПО ФАКТУ, а не по наличию cron ─────────
const KEY = process.env.SUPABASE_SERVICE_KEY;
if (KEY) {
  try {
    const q = (path) => {
      const r = execFileSync('curl', ['-fsS', '--max-time', '20',
        `https://iuvvheeocobhiothfgei.supabase.co/rest/v1/${path}`,
        '-H', `apikey: ${KEY}`, '-H', `Authorization: Bearer ${KEY}`], { encoding: 'utf8' });
      return JSON.parse(r);
    };
    const застряло = q('app_feedback?select=id&is_robot=eq.false&audio_path=not.is.null&transcript=is.null&limit=5');
    добавить('очередь расшифровки голосовых', 'пусто', `${застряло.length} нерасшифрованных`, застряло.length === 0,
      'проверка по ФАКТУ записей, а не по наличию cron: cron может стоять и не работать');
  } catch (e) {
    добавить('очередь расшифровки голосовых', 'пусто', `не спросить: ${String(e.message).slice(0, 40)}`, true, 'пропущено');
  }
} else {
  добавить('очередь расшифровки голосовых', 'пусто', 'нет SUPABASE_SERVICE_KEY', true, 'запусти с ключом, чтобы проверить');
}

// ─── 5. Дата самого рефа ──────────────────────────────────────────────────
const датаВРефе = /Обновлено (\d{2}\.\d{2}\.\d{4})/.exec(ref)?.[1] ?? null;
// ⚠️ Между звёздочкой и датой стоит markdown-жирный: `★ **27.08.2026 · …**`.
// Первая редакция искала `★\s*дата` и не находила ничего — то есть врала про
// отсутствие журнала, который лежал в трёх строках ниже.
const журнал = /★\s*\**\s*(\d{2}\.\d{2}\.\d{4})/.exec(ref)?.[1] ?? null;
добавить('дата в шапке рефа', датаВРефе ?? 'нет', журнал ?? 'журнала правок нет', Boolean(журнал),
  журнал ? 'верхняя запись §0' : '🔴 §0 отсутствует — понять, что устарело, нечем');

// ─── 5а. Перенесённая «Зарядка»: не разъехалась ли с будильником ──────────
/**
 * 🔴 ЭТО САМОЕ ТИХОЕ РАСХОЖДЕНИЕ ИЗ ВСЕХ. «Зарядка» в приложении — не код, а
 * КОПИЯ страницы «Умного будильника» (§4а рефа). Будильник живёт своей жизнью:
 * его правят, пересобирают, и копия у нас стареет БЕЗ ЕДИНОГО ПРИЗНАКА —
 * страница продолжает открываться и работать, просто она вчерашняя.
 *
 * Сравниваем не даты (их правит любое касание), а СОДЕРЖИМОЕ разметки и
 * приложения страницы: разошлось — значит пора `node scripts/sync-warmup-page.mjs`.
 */
{
  const СТРАНИЦА = join(FRONT, 'public', 'warmup');
  const ЛАБА = join(REPO, '..', 'psygames-game-lab', 'smart-alarm', 'web-dist');
  const своё = ['embed.js', 'embed.css'];
  const наМесте = ['index.html', 'styles.css', ...своё].filter((и) => existsSync(join(СТРАНИЦА, и)));
  добавить(
    'страница «Зарядки» на месте',
    'index.html + styles.css + embed.js + embed.css',
    `${наМесте.length} из 4`,
    наМесте.length === 4,
    наМесте.length === 4 ? '' : 'запусти node scripts/sync-warmup-page.mjs',
  );

  if (!existsSync(ЛАБА)) {
    добавить(
      'копия совпадает с будильником',
      'та же сборка',
      'сборки будильника нет на этой машине',
      true,
      'проверяется только там, где лежит psygames-game-lab',
    );
  } else {
    const разошлись = ['index.html', 'styles.css'].filter((и) => {
      const наша = читать(join(СТРАНИЦА, и));
      const их = читать(join(ЛАБА, и));
      if (!наша || !их) return true;
      // Своё встраивание и подменённые картинки — НЕ расхождение: их вносит перенос.
      // ⚠️ Убираем СТРОКУ ЦЕЛИКОМ, а не только тег: первая редакция вырезала
      // тег и оставляла его отступ пустой строкой — и честное совпадение
      // показывалось расхождением. Ложная тревога у сторожа хуже молчания:
      // её перестают читать.
      const нормально = (т) => т
        .split('\n')
        .filter((строка) => !/embed\.(css|js)/.test(строка))
        .join('\n')
        .replace(/\.png/g, '.webp');
      return нормально(наша) !== нормально(их);
    });
    добавить(
      'копия совпадает с будильником',
      'та же сборка',
      разошлись.length ? `разошлись: ${разошлись.join(', ')}` : 'совпадает',
      разошлись.length === 0,
      разошлись.length ? 'будильник ушёл вперёд — node scripts/sync-warmup-page.mjs' : '',
    );
  }
}

// ─── вывод ────────────────────────────────────────────────────────────────
const разошлось = строки.filter((s) => !s.ok);
if (JSON_OUT) {
  console.log(JSON.stringify({ совпало: разошлось.length === 0, строки }, null, 2));
} else {
  for (const s of строки) {
    console.log(`${s.ok ? '✅' : '🔴'} ${s.что}`);
    console.log(`     заявлено: ${s.заявлено}`);
    console.log(`     факт:     ${s.факт}`);
    if (s.пояснение) console.log(`     ${s.пояснение}`);
  }
  console.log('');
  console.log(разошлось.length
    ? `🔴 РЕФ РАЗОШЁЛСЯ С ЖИЗНЬЮ в ${разошлось.length} местах: ${разошлось.map((s) => s.что).join(', ')}`
    : '✅ реф совпадает с жизнью по всем проверенным местам');
}
process.exit(разошлось.length ? 1 : 0);
