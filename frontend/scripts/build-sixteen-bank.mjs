/**
 * Банк позиций «Шестнадцати» 3×3 с ТОЧНОЙ дистанцией: полный BFS по 181 440 состояниям
 * (достижимы только чётные перестановки), по 12 позиций на каждую дистанцию 1..8 —
 * столько, сколько есть на дистанции 1. Позиции берутся равномерно по очереди BFS,
 * чтобы банк не состоял из соседей одной ветки. Запуск: node scripts/build-sixteen-bank.mjs
 */
import { writeFileSync } from 'node:fs';
import { sixteenDistances, SIXTEEN_3_MOVES } from '../src/games/spatial-core/sixteen-solver.mjs';

const table = sixteenDistances({ maxDepth: 8 });
if (table.exhausted || table.entries.size !== 181440) throw new Error(`BFS неполон: ${table.entries.size}`);
const byDistance = new Map();
for (const [key, entry] of table.entries) {
  if (entry.distance === 0) continue;
  if (!byDistance.has(entry.distance)) byDistance.set(entry.distance, []);
  byDistance.get(entry.distance).push(key);
}
const PER = 12, bank = [];
for (const [distance, keys] of [...byDistance].sort((a, b) => a[0] - b[0])) {
  const step = Math.max(1, Math.floor(keys.length / PER));
  for (let i = 0; i < keys.length && bank.filter((b) => b.distance === distance).length < PER; i += step) {
    const solution = table.solution(keys[i]).map((c) => SIXTEEN_3_MOVES.findIndex((m) => m.kind === c.kind && m.index === c.index && m.amount === c.amount));
    bank.push({ key: keys[i], distance, solution });
  }
}
const out = `/* psygames-spatial-core-sixteen-bank · VER 1 · 17.09.2026 */
/* psygames-spatial-claude-mac · задача afb6ab5b · not an app release */
// Generated by frontend/scripts/build-sixteen-bank.mjs; exact BFS across all 181440 reachable 3x3 states.
export const SIXTEEN_BANK=${JSON.stringify(bank)};
`;
writeFileSync(new URL('../src/games/spatial-core/sixteen-bank.mjs', import.meta.url), out);
console.log(`банк: ${bank.length} позиций, дистанции ${[...new Set(bank.map((b) => b.distance))].join(',')}`);
