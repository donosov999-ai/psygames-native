import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require_ = createRequire(import.meta.url);
const ЗДЕСЬ = path.dirname(fileURLToPath(import.meta.url));
const МОСТ = path.join(ЗДЕСЬ, '../src/games/tatham-bridge/tatham.js');

const ЦЕЛИ = process.argv.slice(2).length ? process.argv.slice(2) : ['Bridges', 'Same Game'];
const ЗЕРНО = 777;
const СЕТКА = 5;                      // 5×5 = 25 точек, как в строгом прогоне 11.09
const ПОДЕЙСТВОВАЛО = 1;              // PKR_SOME_EFFECT, tatham-src/puzzles.h:324
const CURSOR_SELECT = 525;
const CURSOR_SELECT2 = 526;

const M = await (require_(МОСТ))();
const строка = (p) => { if (!p) return ''; const s = M.UTF8ToString(p); M.ccall('psy_free', null, ['number'], [p]); return s; };
const вызов = (имя, тип, типы = [], арг = []) => M.ccall(имя, тип, типы, арг);

/** Рисунок доски строкой — то, что игрок видит. Сравниваем её, а не ответ движка. */
const рисунок = () => строка(вызов('psy_draw', 'number'));
const статус = () => вызов('psy_status', 'number');

function движки() {
  const n = вызов('psy_count', 'number');
  const из = [];
  for (let i = 0; i < n; i += 1) из.push({ индекс: i, имя: вызов('psy_name', 'string', ['number'], [i]) });
  return из;
}

function открыть(индекс, параметры = '') {
  const ок = вызов('psy_open', 'number', ['number', 'string', 'number'], [индекс, параметры, ЗЕРНО]);
  return ок === 1;
}

const указатель = (x, y, вид, правой) =>
  вызов('psy_pointer', 'number', ['number', 'number', 'number'], [Math.round(x), Math.round(y), вид + (правой ? 3 : 0)]);
const клавиша = (код) => вызов('psy_key', 'number', ['number'], [код]);
const курсор = (сторона) => вызов('psy_cursor', 'number', ['number'], [сторона]);

/**
 * 🔴 СНИМОК «ДО» БЕРЁТСЯ ПОСЛЕ ПОДГОТОВКИ, А НЕ ДО НЕЁ — И ЭТО НЕ ПРИДИРКА.
 *
 * 📍 Первая редакция этого скрипта показала, что у обеих игр РАБОТАЕТ ВСЁ:
 * тычок, протяжка, правая, стрелки, выбор, цифра, пробел — сплошь «ХОД». Так не
 * бывает. Причина: КУРСОР РИСУЕТСЯ НА ДОСКЕ, а проверки выбора и цифры сперва
 * водили курсор стрелками и только потом жали клавишу. Рисунок менялся от
 * ПЕРЕМЕЩЕНИЯ КУРСОРА, а засчитывалось это клавише.
 *
 * Теперь `подготовка` выполняется, затем снимается «до», и только потом идёт
 * само действие. Ровно та же ловушка, что записана у меня в памяти как «проба
 * зелёная, потому что действие не произошло», только наизнанку: действие не
 * произошло, а признак появился от соседа.
 */
function проба(индекс, действие, подготовка = null) {
  открыть(индекс);
  if (подготовка) подготовка();
  const до = рисунок();
  const ответ = действие();
  const после = рисунок();
  return { изменилось: до !== после, ответ: ответ === ПОДЕЙСТВОВАЛО, статус: статус(), после };
}

/**
 * 🔴 ПРАВАЯ КНОПКА СЧИТАЕТСЯ ОТЛИЧИЕМ ОТ ЛЕВОЙ, А НЕ «ХОТЬ ЧТО-ТО СДЕЛАЛА».
 *
 * Так же меряли и прежние двадцать восемь записей `ВТОРОЕ_ДЕЙСТВИЕ`: левая
 * против правой в ОДНОЙ точке, сравнение рисунка. Кнопка, повторяющая левую,
 * игроку не нужна — она не добавляет ни одного хода.
 */
/**
 * 🔴 «РИСУНОК ИЗМЕНИЛСЯ» И «СДЕЛАН ХОД» — РАЗНЫЕ ВЕЩИ, И ДЛЯ КЛАВИШ ВАЖНА ВТОРАЯ.
 *
 * 📍 Вторая редакция скрипта развела курсор и клавишу снимком «до» после
 * сведения курсора — и всё равно врала: у «Мостов» цифра `1` ПЕРЕВОДИТ КУРСОР на
 * остров с таким числом. Рисунок меняется, хода нет. Признак хода — отмена:
 * перемещение курсора в цепочку отмены не попадает, ход попадает. Поэтому после
 * действия жмём `psy_undo` и смотрим, вернулось ли что-нибудь.
 */
function ходЛи(индекс, действие, подготовка = null) {
  открыть(индекс);
  if (подготовка) подготовка();
  const до = рисунок();
  действие();
  const после = рисунок();
  const откат = вызов('psy_undo', 'number');
  return { изменилось: до !== после, ход: откат === ПОДЕЙСТВОВАЛО };
}

function праваяОтличается(индекс, x, y) {
  const левая = проба(индекс, () => { указатель(x, y, 0, false); return указатель(x, y, 2, false); });
  const правая = проба(индекс, () => { указатель(x, y, 0, true); return указатель(x, y, 2, true); });
  return правая.изменилось && правая.после !== левая.после;
}

function точки() {
  const ш = вызов('psy_width', 'number');
  const в = вызов('psy_height', 'number');
  const из = [];
  for (let r = 1; r <= СЕТКА; r += 1) {
    for (let c = 1; c <= СЕТКА; c += 1) из.push([(ш * c) / (СЕТКА + 1), (в * r) / (СЕТКА + 1)]);
  }
  return из;
}

console.log(`\nЗАМЕР ВВОДА · зерно ${ЗЕРНО} · сетка ${СЕТКА}×${СЕТКА} = ${СЕТКА * СЕТКА} точек`);
console.log('«подействовало» = РИСУНОК ИЗМЕНИЛСЯ, а не «движок ответил да»\n');

const все = движки();
for (const имя of ЦЕЛИ) {
  const дв = все.find((d) => d.имя === имя);
  if (!дв) { console.log(`🔴 ${имя}: движка с таким именем нет (есть: ${все.map((d) => d.имя).join(', ')})`); continue; }
  if (!открыть(дв.индекс)) { console.log(`🔴 ${имя}: доска не раздалась`); continue; }
  const сетка = точки();

  const счёт = { тычок: 0, тычокПравой: 0, протяжка: 0, протяжкаПравой: 0 };
  for (const [x, y] of сетка) {
    if (проба(дв.индекс, () => { указатель(x, y, 0, false); return указатель(x, y, 2, false); }).изменилось) счёт.тычок += 1;
    if (праваяОтличается(дв.индекс, x, y)) счёт.тычокПравой += 1;
  }
  /* Протяжка: из каждой точки сетки в каждую соседнюю по строке — так ходят мосты. */
  let парПротяжки = 0;
  for (let i = 0; i < сетка.length; i += 1) {
    for (const j of [i + 1, i + СЕТКА]) {
      if (j >= сетка.length) continue;
      const [x1, y1] = сетка[i];
      const [x2, y2] = сетка[j];
      парПротяжки += 1;
      if (проба(дв.индекс, () => {
        указатель(x1, y1, 0, false); указатель((x1 + x2) / 2, (y1 + y2) / 2, 1, false);
        return указатель(x2, y2, 2, false);
      }).изменилось) счёт.протяжка += 1;
      const левПрот = проба(дв.индекс, () => {
        указатель(x1, y1, 0, false); указатель((x1 + x2) / 2, (y1 + y2) / 2, 1, false);
        return указатель(x2, y2, 2, false);
      });
      const прПрот = проба(дв.индекс, () => {
        указатель(x1, y1, 0, true); указатель((x1 + x2) / 2, (y1 + y2) / 2, 1, true);
        return указатель(x2, y2, 2, true);
      });
      if (прПрот.изменилось && прПрот.после !== левПрот.после) счёт.протяжкаПравой += 1;
    }
  }

  /* Стрелки: курсор виден? Это и есть их работа — водить, а не ходить. */
  const стрелки = проба(дв.индекс, () => { курсор(0); курсор(1); курсор(2); return курсор(3); });
  /* Клавиши — ПОСЛЕ того, как курсор уже сведён: иначе засчитаем перемещение. */
  const свести = () => { курсор(1); курсор(3); };
  const выбор = ходЛи(дв.индекс, () => клавиша(CURSOR_SELECT), свести);
  const выбор2 = ходЛи(дв.индекс, () => клавиша(CURSOR_SELECT2), свести);
  const цифра = ходЛи(дв.индекс, () => клавиша(0x31), свести);
  const пробел = ходЛи(дв.индекс, () => клавиша(32), свести);

  console.log(`── ${имя} (движок ${дв.индекс}) ──`);
  console.log(`  тычок левой        ${счёт.тычок}/${сетка.length}`);
  console.log(`  правая ОТЛИЧАЕТСЯ ${счёт.тычокПравой}/${сетка.length}`);
  console.log(`  протяжка левой     ${счёт.протяжка}/${парПротяжки}`);
  console.log(`  протяжка правой ОТЛ ${счёт.протяжкаПравой}/${парПротяжки}`);
  console.log(`  стрелки водят      ${стрелки.изменилось ? 'да' : 'нет'}`);
  console.log(`  выбор (SELECT)     ${выбор.ход ? 'ХОД' : выбор.изменилось ? 'только курсор' : 'нет'}`);
  console.log(`  выбор2 (SELECT2)   ${выбор2.ход ? 'ХОД' : выбор2.изменилось ? 'только курсор' : 'нет'}`);
  console.log(`  цифра «1»          ${цифра.ход ? 'ХОД' : цифра.изменилось ? 'только курсор' : 'нет'}`);
  console.log(`  пробел             ${пробел.ход ? 'ХОД' : пробел.изменилось ? 'только курсор' : 'нет'}`);
  console.log('');
}
