/** Снимок геометрии одной пробы. Возвращает null, если мерить нечего. */
const снять = () => {
  const bar = document.querySelector('[data-testid="game-toolbar"]');
  const br = bar ? bar.getBoundingClientRect() : null;
  const низПоля = br ? br.top : window.innerHeight;
  const кандидаты = [...document.querySelectorAll('*')]
    .map((el) => ({ r: el.getBoundingClientRect(), s: getComputedStyle(el) }))
    .filter((o) => o.r.top > 200 && o.r.bottom <= низПоля + 2 && o.r.width > 150 && o.r.height > 60
      && o.s.backgroundColor && o.s.backgroundColor !== 'rgba(0, 0, 0, 0)');
  кандидаты.sort((a, b) => b.r.width * b.r.height - a.r.width * a.r.height);
  const box = кандидаты[0] ? кандидаты[0].r : null;
  /**
   * Кнопка ответа — самая НИЖНЯЯ нажимаемая штука внутри полосы. Берём именно
   * низ: до него дотягивается палец, и именно он у остальных игр стоит на 802.
   */
  const кнопки = bar ? [...bar.querySelectorAll('*')].filter((el) => {
    const r = el.getBoundingClientRect();
    const s = getComputedStyle(el);
    return r.width >= 40 && r.height >= 32
      && (el.getAttribute('role') === 'button' || el.tabIndex >= 0 || s.cursor === 'pointer');
  }) : [];
  const низКнопки = кнопки.length
    ? Math.round(Math.max(...кнопки.map((el) => el.getBoundingClientRect().bottom)))
    : null;
  /**
   * 🔴 ВЕРХ БЛОКА — 10.09.2026. Гейт мерил только НИЗ, и переполнение уходило
   * ВВЕРХ незамеченным: крестовина «выбор-реакции» занимала 208 px при полосе
   * 120, низ стоял на каноне 834, полоса показывала 141 — все три числа
   * зелёные, а верхняя кнопка лежала поверх подсказки.
   */
  const верхКнопки = кнопки.length
    ? Math.round(Math.min(...кнопки.map((el) => el.getBoundingClientRect().top)))
    : null;
  return {
    полоса: br ? Math.round(br.height) : null,
    низПолосы: br ? Math.round(br.bottom) : null,
    низКнопки,
    верхКнопки,
    высотаБлока: (низКнопки !== null && верхКнопки !== null) ? низКнопки - верхКнопки : null,
    центр: box ? Math.round(box.y + box.height / 2) : null,
    окно: [document.documentElement.clientWidth, document.documentElement.clientHeight],
    упал: /Что-то сломалось|is not defined|Something went wrong/.test(document.body.innerText),
  };
};

