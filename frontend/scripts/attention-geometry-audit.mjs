async function маршруты() {
  // С ДИСКА, а не из списка в коде: список в скрипте молча устаревает, когда
  // в разделе появляется новая проба (у меня зона выросла с 5 до 10 за день).
  const файлы = await fs.readdir(path.join(ROOT, 'app/games'));
  const есть = new Set(файлы.filter((f) => f.endsWith('.tsx')).map((f) => f.replace(/\.tsx$/, '')));
  const пропали = РАЗДЕЛ.filter((g) => !есть.has(g));
  if (пропали.length) {
    console.log(`🔴 экранов раздела нет на диске: ${пропали.join(', ')} — список устарел`);
    process.exit(1);
  }
  const выбор = ONLY ? РАЗДЕЛ.filter((g) => ONLY.includes(g)) : РАЗДЕЛ;
  // Экраны «только полоса» тоже обязаны быть на диске: устаревший список молчит.
  const полосные = (ТЕКУЩИЙ.полосаВОдинРяд ? (ТЕКУЩИЙ.экраныПолосы ?? []) : []).filter((g) => (ONLY ? ONLY.includes(g) : true));
  const нетПолосных = полосные.filter((g) => !есть.has(g));
  if (нетПолосных.length) {
    console.log(`🔴 экранов «только полоса» нет на диске: ${нетПолосных.join(', ')} — список устарел`);
    process.exit(1);
  }
  const все = [...выбор.map((игра) => ({ игра, полный: true })), ...полосные.map((игра) => ({ игра, полный: false }))];
  // Пусто — это провал: значит --only не совпал ни с одним экраном раздела.
  if (!все.length) { console.log('🔴 пустой выбор маршрутов'); process.exit(1); }
  return все;
}

