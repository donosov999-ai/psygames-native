import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const CSV_URL = 'https://raw.githubusercontent.com/ivankra/hsk30/master/hsk30.csv';
const КЭШ = join(__dirname, '../.cache/hsk30.csv');
const OUT_СЛОВАРЬ = join(__dirname, '../src/constants/zhPinyin.generated.ts');
const OUT_БАНК = join(__dirname, '../src/constants/zhToneBank.generated.ts');

/** Диакритика пиньиня → номер тона. Нейтральный (без знака) = 5. */
const ТОНЫ = {
  1: 'āēīōūǖĀĒĪŌŪǕ',
  2: 'áéíóúǘÁÉÍÓÚǗ',
  3: 'ǎěǐǒǔǚǍĚǏǑǓǙ',
  4: 'àèìòùǜÀÈÌÒÙǛ',
};

/** Тон ОДНОГО слога по его диакритике. */
function тонСлога(слог) {
  for (const [n, буквы] of Object.entries(ТОНЫ)) {
    for (const б of слог) if (буквы.includes(б)) return Number(n);
  }
  return 5;
}

/**
 * 🔴 РЕЖЕМ ПИНЬИНЬ НА СЛОГИ. КОДА `-n` И `-ng` — ГЛАВНАЯ ЛОВУШКА.
 *
 * Слоги в источнике слитные («jīntiān»), а тон нужен каждому. Первая редакция
 * рвала слог на согласной после гласной без разбора — и `sān` превращалось в
 * «sā» + «n», то есть слово из одного знака получало ДВА тона [1, 5]. Замер по
 * инварианту «иероглифов столько же, сколько слогов» показал 55 таких слов из
 * 189; глазами это не видно, потому что пиньинь на экране остаётся правильным,
 * врут только тоны.
 *
 * Правило: слог кончается на гласной, но `n`, `ng` и `r` могут быть его хвостом —
 * если дальше идёт согласная или конец слова. Если после `n` стоит гласная, то
 * это уже начало следующего слога (nǐ + hǎo, а не nǐh + ǎo).
 */
const ГЛАСНЫЕ = 'aeiouüāēīōūǖáéíóúǘǎěǐǒǔǚàèìòùǜAEIOUÜ';
const гласная = (с) => !!с && ГЛАСНЫЕ.includes(с);

function слоги(pinyin) {
  const чистый = pinyin.replace(/[’'·]/g, ' ').replace(/-/g, ' ').trim();
  if (/\s/.test(чистый)) return чистый.split(/\s+/).filter(Boolean);
  const части = [];
  let тек = '';
  let былаГласная = false;
  for (let i = 0; i < чистый.length; i++) {
    const с = чистый[i];
    if (гласная(с)) { тек += с; былаГласная = true; continue; }
    if (!былаГласная) { тек += с; continue; }          // ещё в начале слога
    const след = чистый[i + 1];
    if (с === 'n') {
      if (след === 'g' && !гласная(чистый[i + 2])) { тек += 'ng'; i++; части.push(тек); тек = ''; былаГласная = false; continue; }
      if (!гласная(след)) { тек += 'n'; части.push(тек); тек = ''; былаГласная = false; continue; }
    }
    if (с === 'r' && !гласная(след)) { тек += 'r'; части.push(тек); тек = ''; былаГласная = false; continue; }
    части.push(тек); тек = с; былаГласная = false;      // согласная начала новый слог
  }
  if (тек) части.push(тек);
  return части.length ? части : [чистый];
}

async function csv() {
  if (existsSync(КЭШ)) return readFileSync(КЭШ, 'utf8');
  const отв = await fetch(CSV_URL);
  if (!отв.ok) throw new Error(`не скачался hsk30.csv: ${отв.status}`);
  const текст = await отв.text();
  try { writeFileSync(КЭШ, текст, 'utf8'); } catch { /* нет каталога .cache — не беда */ }
  return текст;
}

/**
 * Разбор CSV с кавычками. ⚠️ Первая редакция резала строку по запятой — и молча
 * съезжала на колонку: в файле есть поле `Variants` с JSON внутри кавычек, а там
 * запятых десятки. Поймано сверкой с `csv.DictReader` питона, а не чтением.
 */
function разобрать(текст) {
  const поля = (строка) => {
    const из = []; let тек = ''; let вКавычках = false;
    for (let i = 0; i < строка.length; i++) {
      const с = строка[i];
      if (вКавычках) {
        if (с === '"') { if (строка[i + 1] === '"') { тек += '"'; i++; } else вКавычках = false; }
        else тек += с;
      } else if (с === '"') вКавычках = true;
      else if (с === ',') { из.push(тек); тек = ''; }
      else тек += с;
    }
    из.push(тек);
    return из;
  };
  const строки = текст.trim().split('\n');
  const шапка = поля(строки[0]);
  return строки.slice(1).map((с) => Object.fromEntries(шапка.map((к, i) => [к, поля(с)[i] ?? ''])));
}

const данные = разобрать(await csv());
/** Читаем ТОЛЬКО эти колонки. `CEDICT` не трогаем — см. шапку. */
const поИероглифам = new Map();
for (const с of данные) {
  if (!с.Simplified || !с.Pinyin) continue;
  /**
   * ⚠️ ВАРИАНТЫ ЛЕЖАТ ЧЕРЕЗ `|`, И ЭТО НЕ МЕЛОЧЬ. Строка HSK 1 выглядит как
   * `妈妈|妈` с пиньинем `māma|mā`: одна запись даёт и слово, и одиночный
   * иероглиф. Поиск по целой строке не находил ни того, ни другого — пять слов
   * приложения (妈妈, 爸爸, 哥哥, 姐姐, 奶酪) считались отсутствующими, и я чуть
   * не собрал их вручную вместо того, чтобы взять готовое.
   */
  const формы = с.Simplified.split('|');
  const звучания = с.Pinyin.split('|');
  формы.forEach((форма, i) => {
    const pinyin = звучания[i] ?? звучания[0];
    if (!форма || !pinyin) return;
    if (!поИероглифам.has(форма)) поИероглифам.set(форма, { pinyin, pos: с.POS, level: с.Level });
  });
}

// ── 1. Слова, которые уже есть в приложении ──────────────────────────────────
const исходники = ['src/constants/translationVocab.ts', 'src/constants/clozePhrases.ts']
  .map((п) => join(__dirname, '..', п))
  .filter(existsSync)
  .map((п) => readFileSync(п, 'utf8'))
  .join('\n');
const нужные = [...new Set([...исходники.matchAll(/zh:\s*'([^']+)'/g)].map((m) => m[1]))].sort();

/**
 * Дописано руками — этих слов в списке HSK 3.0 нет вовсе, а в словаре приложения
 * они есть. Помечаются `composed: true` наравне с посимвольной сборкой: в файл
 * попадает наш вывод, а не данные источника.
 *
 * 奶酪 — 酪 отсутствует в HSK целиком (奶 есть, HSK 1, nǎi). Пиньинь nǎilào,
 * тоны 3-4 — стандартное чтение, сверено со звучанием 牛奶 (niúnǎi) в том же
 * источнике.
 */
const ВРУЧНУЮ = {
  '奶酪': { pinyin: 'nǎilào', tones: [3, 4], level: '—' },
};

/** Второй слог удвоений родства — нейтральный: 妈妈 māma, а не māmā. */
const РОДСТВО = new Set(['妈妈', '爸爸', '哥哥', '姐姐', '弟弟', '妹妹', '爷爷', '奶奶']);

const словарь = [];
const пропущены = [];
for (const слово of нужные) {
  const прямо = поИероглифам.get(слово);
  if (прямо) {
    const части = слоги(прямо.pinyin);
    словарь.push({ zh: слово, pinyin: прямо.pinyin, tones: части.map(тонСлога), level: прямо.level, composed: false });
    continue;
  }
  // Составляем посимвольно — и честно помечаем, что это наша сборка.
  const ручное = ВРУЧНУЮ[слово];
  if (ручное) { словарь.push({ zh: слово, ...ручное, composed: true }); continue; }
  const части = [...слово].map((з) => поИероглифам.get(з));
  if (части.some((ч) => !ч)) { пропущены.push(слово); continue; }
  const собранный = части.map((ч) => ч.pinyin).join('');
  const тона = части.map((ч) => тонСлога(ч.pinyin));
  if (РОДСТВО.has(слово)) тона[тона.length - 1] = 5;
  словарь.push({ zh: слово, pinyin: собранный, tones: тона, level: части[0].level, composed: true });
}

// ── 2. Банк односложных для упражнения на тон ────────────────────────────────
const банк = { 1: [], 2: [], 3: [], 4: [] };
for (const с of данные) {
  if (!с.Simplified || !с.Pinyin) continue;
  if (!['1', '2', '3'].includes(с.Level)) continue;           // HSK 1–3: самые частотные
  const формы = с.Simplified.split('|');
  const звучания = с.Pinyin.split('|');
  формы.forEach((форма, i) => {
    if (форма.length !== 1) return;                            // банк односложный
    const pinyin = звучания[i] ?? звучания[0];
    /**
     * ⚠️ ДВА ЧТЕНИЯ — ЛОВУШКА, А НЕ БОГАТСТВО. У части иероглифов источник даёт
     * альтернативы через косую: 谁 `shéi/shuí`, 熟 `shú/shóu`. В упражнении на
     * тон такой слог означал бы ДВА правильных ответа, а на экране показан один.
     * Выбрасываем: банк и без них велик. Поймано круговым прогоном
     * «снять знак → поставить обратно», а не глазами.
     */
    if (pinyin.includes('/')) return;
    const т = тонСлога(pinyin);
    if (т === 5) return;                                       // нейтральный слог в задании не спрашиваем
    if (банк[т].some((з) => з.pinyin === pinyin)) return;      // один слог одного звучания — один раз
    банк[т].push({ zh: форма, pinyin });
  });
}

