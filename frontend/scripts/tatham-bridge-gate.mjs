const беды = [];
/**
 * ⚠️ Модуль собран ЕДИНЫМ файлом (`SINGLE_FILE=1`): wasm лежит внутри `tatham.js`
 * в base64, отдельного `.wasm` НЕТ и быть не должно. Так Metro кладёт его в бандл
 * как обычный модуль — без ассета и без загрузки по сети. Цена: 459 КБ бинаря
 * превращаются в 530 КБ текста.
 */
if (!existsSync(МОСТ)) {
  console.error('❌ мост не собран: нет tatham.js');
  console.error('   пересобрать: source ~/dev/emsdk/emsdk_env.sh && frontend/src/games/tatham-bridge/build.sh');
  process.exit(1);
}

const M = await require_(МОСТ)();
const n = M.ccall('psy_count', 'number', [], []);
if (n !== Object.keys(СТУПЕНИ).length) {
  беды.push(`движков в модуле ${n}, а в замере ${Object.keys(СТУПЕНИ).length} — состав сменился молча`);
}

for (let i = 0; i < n; i++) {
  const имя = M.ccall('psy_name', 'string', ['number'], [i]);

  // 1. движок ВЫДАЁТ доску, а не просто линкуется
  const p = M.ccall('psy_generate', 'number', ['number', 'string', 'number'], [i, '', 12345]);
  const описание = p ? M.UTF8ToString(p) : '';
  if (p) M.ccall('psy_free', null, ['number'], [p]);
  if (!/^[^:]+:.+/.test(описание)) {
    беды.push(`${имя}: доска не сгенерирована — «${описание.slice(0, 30)}»`);
  }

  // 2. доска отдаётся текстом — то, по чему рисует наша сторона
  const умеет = M.ccall('psy_has_board', 'number', ['number'], [i]) === 1;
  if (умеет === БЕЗ_ТЕКСТА.has(имя)) {
    беды.push(`${имя}: показывает текстом ${умеет}, а в замере записано обратное`);
  }
  if (умеет) {
    const b = M.ccall('psy_board', 'number', ['number', 'string', 'number'], [i, '', 42]);
    const доска = b ? M.UTF8ToString(b) : '';
    if (b) M.ccall('psy_free', null, ['number'], [b]);
    const строк = доска.split('\n').filter(Boolean).length;
    if (строк < 3) беды.push(`${имя}: доска текстом пуста или в ${строк} строк`);
  }

  // 3. лестница автора на месте
  const было = СТУПЕНИ[имя];
  const стало = M.ccall('psy_presets', 'number', ['number'], [i]);
  if (было === undefined) беды.push(`${имя}: движка не было в замере 10.09.2026`);
  else if (было !== стало) беды.push(`${имя}: ступеней автора было ${было}, стало ${стало}`);
}

/*
 * 🔴 ИГРАБЕЛЬНЫЙ КРУГ — то, ради чего писался слой рисования.
 * Замер 10.09.2026: `text_format` даёт РОВНУЮ сетку только у Unruly, остальные печатают
 * дамп с рамками и разной шириной строк. Поэтому доска берётся не текстом, а вектором:
 * его же `drawing_api` записывает примитивы, и рисуются ВСЕ 20, включая Keen и Map,
 * которые текстом себя не показывают вовсе.
 * Здесь проверяется весь круг: открылось — нарисовалось — решатель довёл до победы.
 */
for (let i = 0; i < n; i++) {
  const имя = M.ccall('psy_name', 'string', ['number'], [i]);
  if (!M.ccall('psy_open', 'number', ['number', 'string', 'number'], [i, '', 42])) {
    беды.push(`${имя}: партия не открылась`); continue;
  }
  const ш = M.ccall('psy_width', 'number', [], []);
  const в = M.ccall('psy_height', 'number', [], []);
  if (ш < 32 || в < 32) беды.push(`${имя}: поле ${ш}×${в} — размер не задан`);

  const примитивов = (M.UTF8ToString(M.ccall('psy_draw', 'number', [], [])) || '').split('\n').filter(Boolean).length;
  if (примитивов < 4) беды.push(`${имя}: нарисовано ${примитивов} примитивов — доски нет`);

  // решатель автора обязан доводить партию до победы: на нём стоят подсказки
  const решён = M.ccall('psy_can_solve', 'number', ['number'], [i]) === 1;
  if (решён === БЕЗ_РЕШАТЕЛЯ.has(имя)) {
    беды.push(`${имя}: can_solve=${решён}, а в замере записано обратное`);
  }
  const рисунокДо = M.UTF8ToString(M.ccall('psy_draw', 'number', [], [])) || '';
  const вышло = M.ccall('psy_solve', 'number', [], []) === 1;
  const победил = M.ccall('psy_status', 'number', [], []) === 1;
  if (победил === РЕШАТЕЛЬ_НЕ_ЗАКАНЧИВАЕТ.has(имя)) {
    беды.push(`${имя}: решатель ${победил ? 'довёл' : 'не довёл'} до победы — обратное замеру`);
  }

  /*
   * 🔴 РЕШЕНИЕ ОБЯЗАНО БЫТЬ ВИДНО НА ДОСКЕ, А НЕ ТОЛЬКО В СТАТУСЕ.
   *
   * Замер 10.09.2026: у Untangle `psy_status` уже говорил «победа», а рисунок не менялся
   * НИ НА ОДИН примитив из 29 — человек жал «Показать решение» и видел ту же путаницу.
   * Причина: `midend_redraw` рисует ПРОМЕЖУТОЧНЫЙ кадр анимации, а время двигает только
   * `midend_timer`, который у нас заглушён. Теперь `psy_draw` доигрывает анимацию.
   *
   * Порог — единица, и это не осторожность, а замер: самый скромный видимый ответ у
   * Inertia (1 примитив — линия маршрута), дальше Flood 4, Guess 9, Sixteen 15.
   * Всё, что меньше единицы, значит «кнопка не делает ничего».
   */
  if (вышло) {
    const рисунокПосле = M.UTF8ToString(M.ccall('psy_draw', 'number', [], [])) || '';
    const было = new Map();
    for (const л of рисунокДо.split('\n')) было.set(л, (было.get(л) || 0) + 1);
    let новых = 0;
    for (const л of рисунокПосле.split('\n')) {
      const c = было.get(л) || 0;
      if (c > 0) было.set(л, c - 1); else новых++;
    }
    if (новых < 1) беды.push(`${имя}: решатель отработал, а рисунок не изменился — кнопка «Показать решение» пустая`);
  }
}

/*
 * 🔴 КАЖДАЯ ИЗ СОРОКА ОБЯЗАНА ОТКЛИКАТЬСЯ НА ЖЕСТ ИЗМЕНЕНИЕМ КАРТИНКИ.
 *
 * 📍 Денис 10.09.2026: «игры что перенёс не работают или сломана игровая механика,
 * почти все», «движки рабочие мы брали, а щас кривые, походу ты спортил их».
 * Замер показал обратное — целы все сорок, ломали их наши слои ввода. Эта проба
 * стоит здесь, чтобы утверждение «движки целы» перестало быть словом.
 *
 * ⚠️ КРИТЕРИЙ — РИСУНОК, А НЕ ОТВЕТ ДВИЖКА. `PKR_SOME_EFFECT` приходит и на чисто
 * интерфейсные пустяки: щелчок мимо доски прячет клавиатурный курсор и считается
 * «использованным». На этом моя первая проба и попалась: она останавливалась на
 * первом «принято» и объявила десять игр немыми, хотя немых не было ни одной.
 *
 * Лестница жестов идёт от дешёвого к редкому, и последняя ступень — не украшение:
 * «Уголки» (Pegs) отзываются ТОЛЬКО на прыжок колышка ЧЕРЕЗ клетку, обычная
 * протяжка на соседнюю для них не ход.
 */
{
  const немые = [];
  const рисовать = () => (M.UTF8ToString(M.ccall('psy_draw', 'number', [], [])) || '').split('\n').filter(Boolean);
  const разница = (a, b) => {
    const было = new Map();
    for (const л of a) было.set(л, (было.get(л) || 0) + 1);
    let k = 0;
    for (const л of b) { const c = было.get(л) || 0; if (c > 0) было.set(л, c - 1); else k++; }
    return k;
  };
  for (let i = 0; i < n; i++) {
    const имя = M.ccall('psy_name', 'string', ['number'], [i]);
    if (!M.ccall('psy_open', 'number', ['number', 'string', 'number'], [i, '', 42])) continue;
    const ш = M.ccall('psy_width', 'number', [], []);
    const в = M.ccall('psy_height', 'number', [], []);
    let до = рисовать();
    let отозвалась = false;
    const жест = (x, y, x2, y2, правой) => {
      const сдвиг = правой ? 3 : 0;
      M.ccall('psy_pointer', 'number', ['number', 'number', 'number'], [x, y, 0 + сдвиг]);
      if (x2 !== x || y2 !== y) M.ccall('psy_pointer', 'number', ['number', 'number', 'number'], [x2, y2, 1 + сдвиг]);
      M.ccall('psy_pointer', 'number', ['number', 'number', 'number'], [x2, y2, 2 + сдвиг]);
      const после = рисовать();
      const d = разница(до, после);
      до = после;
      return d > 0;
    };
    const С = 9;
    for (let гy = 1; гy <= С && !отозвалась; гy++) for (let гx = 1; гx <= С && !отозвалась; гx++) {
      const x = Math.round(ш * гx / (С + 1)), y = Math.round(в * гy / (С + 1));
      if (жест(x, y, x, y, false)) отозвалась = true;
    }
    for (let гy = 1; гy <= 4 && !отозвалась; гy++) for (let гx = 1; гx <= 4 && !отозвалась; гx++) {
      const x = Math.round(ш * гx / 5), y = Math.round(в * гy / 5);
      if (жест(x, y, Math.round(ш * (гx + 1) / 5), y, false)) { отозвалась = true; break; }
      if (жест(x, y, x, y, true)) отозвалась = true;
    }
    // прыжок через клетку — единственный ход «Уголков»
    const кл = ш / 7;
    for (let r = 0; r < 7 && !отозвалась; r++) for (let c = 0; c + 2 < 7 && !отозвалась; c++) {
      if (жест(Math.round((c + 0.5) * кл), Math.round((r + 0.5) * кл),
               Math.round((c + 2.5) * кл), Math.round((r + 0.5) * кл), false)) отозвалась = true;
    }
    if (!отозвалась) немые.push(имя);
  }
  if (немые.length) беды.push(`картинка не меняется ни одним жестом: ${немые.join(', ')}`);
}

/*
 * 🔴 НИ ОДНА ДОСКА НЕ ЖМЁТСЯ В ТРЕТЬ ЭКРАНА.
 *
 * Замер 10.09.2026 на первой ступени лестницы, телефон 360 точек (под доску 328):
 * «Мозаика» занимала 62 % ширины, следующая за ней 93 %, остальные 94–100 %. Виновата
 * не доска, а потолок увеличения: её поле 128 точек против 190–450 у прочих, поэтому в
 * потолок упиралась она одна.
 *
 * Потолок читается ИЗ САМОГО КОМПОНЕНТА, а не повторяется здесь числом: повтор
 * разошёлся бы с кодом молча, и гейт сторожил бы вчерашнее значение.
 *
 * Порог 90 % — под самым скромным честным результатом (94 %), а не «побольше на глаз».
 */
{
  const исходник = (await import('node:fs')).readFileSync(
    path.join(ЗДЕСЬ, '../src/components/PuzzleCanvas.tsx'), 'utf8');
  const потолок = Number(/МАКС_УВЕЛИЧЕНИЕ = ([\d.]+)/.exec(исходник)?.[1]);
  if (!потолок) беды.push('в PuzzleCanvas.tsx не нашёлся МАКС_УВЕЛИЧЕНИЕ — потолок увеличения переименован или убран');
  else {
    const ЭКРАН = 360 - 32;               // телефон 360 точек минус поля экрана
    const ПОЛ = 90;                       // процентов ширины
    const жмётся = [];
    for (let i = 0; i < n; i++) {
      const имя = M.ccall('psy_name', 'string', ['number'], [i]);
      if (M.ccall('psy_presets', 'number', ['number'], [i]) < 1) continue;   // у этих лестница своя
      const p = M.ccall('psy_preset_params', 'number', ['number', 'number'], [i, 0]);
      const пар = p ? M.UTF8ToString(p) : '';
      if (p) M.ccall('psy_free', null, ['number'], [p]);
      if (!M.ccall('psy_open', 'number', ['number', 'string', 'number'], [i, пар, 42])) continue;
      const ш = M.ccall('psy_width', 'number', [], []);
      const доля = Math.round((ш * Math.min(ЭКРАН / ш, потолок)) / ЭКРАН * 100);
      if (доля < ПОЛ) жмётся.push(`${имя} ${доля}% (доска ${ш})`);
    }
    if (жмётся.length) беды.push(`доска занимает меньше ${ПОЛ}% ширины при потолке ${потолок}: ${жмётся.join(', ')}`);
  }
}

/*
 * 🔴 НИ ОДИН РЕЖИМ НЕ ПОКАЗЫВАЕТ «УРОВЕНЬ 1/0». Замер 10.09.2026 на симуляторе iPhone:
 * у «Сапёра» счётчик в шапке обещал НОЛЬ ступеней — `psy_presets` у Mines и Loopy
 * возвращает 0, меню пресетов у них устроено иначе. Лестница им набрана размером поля
 * в `names.ts` (`СВОЯ_ЛЕСТНИЦА`), и здесь проверяется, что она есть и РАБОТАЕТ:
 * каждая её ступень обязана открыть доску и нарисовать её.
 */
{
  const имена = ЗДЕСЬ && (await import('node:fs')).readFileSync(
    path.join(ЗДЕСЬ, '../src/games/tatham-bridge/names.ts'), 'utf8');
  const блок = /СВОЯ_ЛЕСТНИЦА[^=]*= \{([\s\S]*?)\n\};/.exec(имена)?.[1] ?? '';
  const пары = [...блок.matchAll(/(\w[\w ]*):\s*\[([\s\S]*?)\]/g)];
  const безЛестницы = [];
  for (let i = 0; i < n; i++) {
    const имя = M.ccall('psy_name', 'string', ['number'], [i]);
    if (M.ccall('psy_presets', 'number', ['number'], [i]) > 0) continue;
    const своя = пары.find(([, к]) => к.trim() === имя.trim());
    if (!своя) { безЛестницы.push(`${имя}: ступеней автора 0 и своей лестницы нет — покажет «1/0»`); continue; }
    const параметры = [...своя[2].matchAll(/параметры: '([^']+)'/g)].map((m) => m[1]);
    if (параметры.length < 3) безЛестницы.push(`${имя}: своя лестница из ${параметры.length} ступеней — это не лестница`);
    for (const п of параметры) {
      if (!M.ccall('psy_open', 'number', ['number', 'string', 'number'], [i, п, 7])) {
        безЛестницы.push(`${имя}: ступень «${п}» не открывается`); continue;
      }
      const пр = (M.UTF8ToString(M.ccall('psy_draw', 'number', [], [])) || '').split('\n').filter(Boolean).length;
      if (пр < 4) безЛестницы.push(`${имя}: ступень «${п}» нарисовала ${пр} примитивов`);
    }
  }
  беды.push(...безЛестницы);
}

