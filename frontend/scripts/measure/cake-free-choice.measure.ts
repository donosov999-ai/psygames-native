/**
 * ЗАМЕР: что новые правила («любой кусок») сделали с лестницей тортов.
 *
 * Решение Дениса 16.09.2026: кусок берётся любой, а не верхний. Ход стал
 * свободнее, значит игра ЛЕГЧЕ — и это надо не предположить, а померить по трём
 * величинам сразу, потому что каждая из них держит своё обещание игроку:
 *   · доказуемость — значок «уровень проверен»;
 *   · минимум ходов — пороги звёзд;
 *   · узлы поиска — цена подсказки прямо в партии.
 *
 * ⚠️ И ОТДЕЛЬНО — СОСТОЯНИЯ. Порядок кусков в тарелке больше ничего не значит,
 * ключ состояния сортируется. Если число узлов НЕ упало, значит сортировка ключа
 * не работает, и это дороже любой другой находки здесь.
 */
import { deal, levelCfg } from '@/src/games/cake-sort/core/level';
import { minMoves, solve } from '@/src/games/cake-sort/core/solver';

describe('СМЁТ свободного выбора куска', () => {
  jest.setTimeout(3_600_000);

  it('доказуемость, минимум ходов и узлы по лестнице', () => {
    const уровни = [1, 3, 5, 8, 12, 20, 30, 42, 60, 84];
    const строки: string[] = [];
    for (const L of уровни) {
      const cfg = levelCfg(L);
      const d = deal(L);
      const t0 = Date.now();
      const r = solve(d.board, 200_000);
      const мс = Date.now() - t0;
      const мм = minMoves(d.board, 200_000);
      строки.push(
        `L${String(L).padStart(3)} · тарелок ${String(cfg.plates).padStart(2)} видов ${String(cfg.types).padStart(2)}`
        + ` · доказано ${r.solvable ? 'да ' : 'НЕТ'} · узлов ${String(r.nodes).padStart(7)} · ${String(мс).padStart(5)} мс`
        + ` · минимум ${мм.moves ?? '—'}`,
      );
    }
    console.log(['', 'СВОБОДНЫЙ ВЫБОР КУСКА:', ...строки].join('\n'));
    expect(строки.length).toBe(уровни.length);
  });
});
