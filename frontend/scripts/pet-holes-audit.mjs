#!/usr/bin/env node
/* psygames-pet-holes-audit · VER 1 · 10.09.2026 */
/**
 * ДЫРЫ ВНУТРИ ПИТОМЦА: прозрачные острова, окружённые телом. ОТЧЁТ, НЕ ГЕЙТ.
 *
 * 🔴 ПОВОД. Денис 10.09.2026: «дыры убрал что были?». Замер по 347 кадрам нашёл 42
 * прозрачных острова в 34 кадрах. Большинство — ЗАКОННЫЕ: просвет между поднятым
 * хвостом и телом кота (проверено глазами на lookaround2, wiggle3, cheer3,
 * scratch1, surprise3). Настоящий дефект был у робота в кадрах праздника: щёки и
 * открытый рот просвечивали насквозь — цветовой ключ съел их вместе с фоном при
 * нарезке. На светлом фоне это незаметно, поэтому прожило до сих пор.
 *
 * ⚠️ ПОЧЕМУ ЭТО СКРИПТ, А НЕ ПРОБА JEST. Разбор связных областей требует numpy и
 * scipy — их нет в окружении проб. Здесь та же логика на чистом JS: заливка от края
 * помечает фон, остаток внутри силуэта и есть дыры.
 *
 * 🔴 ПОЧЕМУ ЭТО ОТЧЁТ, А НЕ ГЕЙТ — И ЭТО ЗАМЕР, А НЕ ЛЕНЬ.
 *
 * Отличить дефект от законного просвета автоматически я не смог, и проверил две
 * гипотезы, обе отвергнуты числом:
 *   1) «Дефект замкнут телом со всех сторон». Нет: петля закрученного хвоста кота
 *      замкнута на 100 % ровно так же — 37 кадров попали бы в красное зря.
 *   2) «У дефекта ободок ярче, потому что ключ съел краску внутри ровной заливки,
 *      а законный просвет обведён тёмным контуром». Нет: робот дал 1,17–1,21 от
 *      яркости тела, хвост кота 1,10–1,25 — диапазоны пересекаются.
 * Робота я опознал иначе: сверкой с ЧИСТЫМИ кадрами того же облика — симметричная
 * пара пятен на месте румянца, который в других состояниях нарисован (243,130,179).
 * Это приём под конкретный случай, а не общее правило, и гейт из него не выйдет.
 *
 * Поэтому скрипт печатает список и всегда выходит с нулём. Судить — глазами: собрать
 * кадр на тёмном И на светлом фоне; сквозная дыра меняет цвет вместе с фоном,
 * нарисованная тень — нет.
 *
 * Запуск: node scripts/pet-holes-audit.mjs
 */
import { readdirSync, readFileSync, existsSync } from 'fs';
import { join } from 'path';
import { execFileSync } from 'child_process';

const БАЗА = 'assets/images/pet';
const ПОРОГ_АЛЬФЫ = 24;
const МИН_ПЛОЩАДЬ = 200;
const ЗАМКНУТОСТЬ = 0.97;      // доля периметра дыры, лежащая на плотном теле

/** Прочитать webp/png в {w,h,alpha} через sips → png → ручной разбор — дорого.
 *  Дешевле: спросить у python3, если он есть с Pillow; иначе честно сказать. */
function альфа(путь) {
  const код = `
from PIL import Image
import sys
im = Image.open(sys.argv[1]).convert('RGBA')
w,h = im.size
a = im.getchannel('A').tobytes()
sys.stdout.buffer.write(bytes([w>>8, w&255, h>>8, h&255]) + a)
`;
  const out = execFileSync('/usr/bin/python3', ['-c', код, путь], { maxBuffer: 1 << 28 });
  const w = (out[0] << 8) | out[1], h = (out[2] << 8) | out[3];
  return { w, h, a: out.subarray(4) };
}

function дыры({ w, h, a }) {
  const тело = new Uint8Array(w * h);
  for (let i = 0; i < w * h; i++) тело[i] = a[i] >= ПОРОГ_АЛЬФЫ ? 1 : 0;
  // заливка пустоты от края
  const фон = new Uint8Array(w * h);
  const стек = [];
  for (let x = 0; x < w; x++) { стек.push(x, (h - 1) * w + x); }
  for (let y = 0; y < h; y++) { стек.push(y * w, y * w + w - 1); }
  while (стек.length) {
    const i = стек.pop();
    if (i < 0 || i >= w * h || фон[i] || тело[i]) continue;
    фон[i] = 1;
    const x = i % w, y = (i / w) | 0;
    if (x > 0) стек.push(i - 1);
    if (x < w - 1) стек.push(i + 1);
    if (y > 0) стек.push(i - w);
    if (y < h - 1) стек.push(i + w);
  }
  // связные острова пустоты, не помеченные фоном
  const метка = new Int32Array(w * h).fill(-1);
  const найдено = [];
  for (let s = 0; s < w * h; s++) {
    if (тело[s] || фон[s] || метка[s] >= 0) continue;
    const id = найдено.length; const очередь = [s]; метка[s] = id;
    let площадь = 0, периметр = 0, наТеле = 0, суммаY = 0;
    while (очередь.length) {
      const i = очередь.pop(); площадь++; суммаY += (i / w) | 0;
      const x = i % w, y = (i / w) | 0;
      for (const [dx, dy] of [[1,0],[-1,0],[0,1],[0,-1]]) {
        const nx = x + dx, ny = y + dy;
        if (nx < 0 || ny < 0 || nx >= w || ny >= h) continue;
        const j = ny * w + nx;
        if (тело[j]) { периметр++; наТеле++; continue; }
        if (фон[j]) { периметр++; continue; }
        if (метка[j] < 0) { метка[j] = id; очередь.push(j); }
      }
    }
    найдено.push({ площадь, замкнутость: периметр ? наТеле / периметр : 0, центрY: суммаY / площадь / h });
  }
  return найдено.filter((д) => д.площадь >= МИН_ПЛОЩАДЬ);
}

let всего = 0, дефектов = 0;
const беда = [];
for (const облик of readdirSync(БАЗА)) {
  const папка = join(БАЗА, облик);
  if (!existsSync(папка)) continue;
  for (const имя of readdirSync(папка)) {
    if (!/\.(webp|png)$/i.test(имя)) continue;
    всего++;
    for (const д of дыры(альфа(join(папка, имя)))) {
      if (д.замкнутость >= ЗАМКНУТОСТЬ) {
        дефектов++;
        беда.push(`${облик}/${имя}: ${д.площадь} px, замкнута телом на ${(д.замкнутость * 100).toFixed(0)}%`);
      }
    }
  }
}
console.log(`кадров проверено: ${всего}`);
if (дефектов) {
  console.log(`островов, замкнутых телом: ${дефектов} — СУДИТЬ ГЛАЗАМИ, см. шапку файла`);
  беда.slice(0, 40).forEach((s) => console.log('   ' + s));
  console.log('\nБольшинство у кота — петля закрученного хвоста, это законно.');
  console.log('Настоящий дефект чинить заливкой цветом ИЗ ЧИСТЫХ КАДРОВ того же облика, не белым.');
} else {
  console.log('островов, замкнутых телом, нет');
}
