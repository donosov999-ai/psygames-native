/**
 * 🔴 РАЗГОН СЧЁТА ОТ СЕРИИ — КОНЕЦ ПАРТИИ ДОРОЖЕ НАЧАЛА.
 *
 * Пункт 2.3 карты геймификации, выбран Денисом 02.09.2026. До него последняя
 * сборка в партии стоила ровно столько же, сколько первая: у игрока не было
 * причины доигрывать хорошо начатую партию, а сорванная серия ничего не отнимала.
 *
 * ⚠️ ГРАНИЦА ИЗ §12.2, КОТОРУЮ НЕЛЬЗЯ ПЕРЕЙТИ. Серия годится как ОЩУЩЕНИЕ, но
 * НЕ как источник валюты: при адаптивной сложности плата за качество исполнения —
 * худшая из измеренных схем (d = −0,80). Поэтому множитель трогает ОЧКИ ПАРТИИ и
 * всплывашку «+N», а монеты по-прежнему считаются отдельно: явка + приращение
 * рейтинга + звёзды по норма-референсу (§14).
 *
 * ПОЧЕМУ НЕЛИНЕЙНО И С ПОТОЛКОМ. Линейный множитель («×n за серию n») превращает
 * длинную партию в лотерею: на серии 20 один ход стоит двадцати, и весь предыдущий
 * счёт обесценивается. Корень растёт быстро на первых шагах — там, где игроку
 * важно почувствовать разницу, — и почти замирает дальше; потолок 3× ставит точку.
 *
 *   серия  1   2   3     4     5     7     10    15    20    50
 *   ×      1   1   1,2   1,3   1,5   1,7   2,0   2,4   2,7   3,0
 */

/** Множитель за серию. Ниже трёх подряд — единица: разгон должен быть заслужен. */
export function streakMultiplier(streak: number): number {
  if (!Number.isFinite(streak) || streak < 3) return 1;
  // 1 + (√серия − √2) × 0,55, срезано на 3×. Двойка в корне — точка старта разгона.
  const raw = 1 + (Math.sqrt(streak) - Math.SQRT2) * 0.55;
  return Math.min(3, Math.round(raw * 10) / 10);
}

/**
 * Очки за ход с учётом серии. Игра зовёт ЕЁ вместо `score + base` — тогда разгон
 * приходит в игру одной строкой, а правило разгона остаётся в одном месте.
 *
 * ⚠️ Округление вверх: на маленькой базе (1–2 очка) округление вниз съедало бы
 * весь разгон, и множитель существовал бы только в описании.
 */
export function scoreWithStreak(base: number, streak: number): number {
  if (!Number.isFinite(base) || base <= 0) return 0;
  return Math.ceil(base * streakMultiplier(streak));
}
