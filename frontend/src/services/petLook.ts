/**
 * petLook — какой ВНЕШНОСТЬЮ показать питомца по тому, как о нём заботятся.
 *
 * ЗАЧЕМ. Денис 05.09.2026: «чтобы можно было менять внешность, если жрёт много,
 * или не кормят, или не моют, или играют — короче, чтобы забота меняла вид».
 * До этого забота на вид не влияла никак: кот выглядел одинаково и на второй
 * день, и после месяца простоя, а «рост» подменял кота роботом и созвездием —
 * то есть заменял ПЕРСОНАЖА, а не показывал, что он вырос. Денис на это сказал
 * прямо: «да надо взрослеющего кота».
 *
 * ЧТО НАРИСОВАНО. Лист `synapse2-care-v2-7x8` — восемь ШКАЛ по семь ступеней:
 * клетка 1 один край, клетка 7 другой, поза во всех одна и та же. Это не
 * анимация: игра берёт из ряда ОДИН кадр и показывает его вместо покоя.
 *
 * 🔴 ПОКАЗЫВАЕМ ОДНУ ШКАЛУ — САМУЮ ЗАПУЩЕННУЮ. Восемь шкал одновременно на
 * одном коте не покажешь, а показывать их по кругу — значит, что вид перестанет
 * что-либо означать. Поэтому кот показывает то, чего ему НЕ ХВАТАЕТ БОЛЬШЕ
 * ВСЕГО: не мыли неделю — выйдет грязным, не кормили — тощим, забросили —
 * унылым. Когда всё в порядке, показывать нечего, и кот показывает возраст:
 * насколько вырос. Так вид работает подсказкой, а не украшением.
 *
 * ⚠️ ВЕС — ШКАЛА С СЕРЕДИНОЙ, а не с «хорошим краем». Худой плох и толстый
 * плох, норма посередине (ступень 3). Остальные шкалы однонаправленные.
 */
import type { PetStage } from '@/src/services/pet';

/** Ступеней в каждом ряду листа заботы. Совпадает с шириной сетки 7×8. */
export const LOOK_STAGES = 7;

/** Ряды листа заботы, в порядке рядов сверху вниз. */
export type PetLookAxis =
  | 'weight' | 'clean' | 'mood' | 'energy' | 'health' | 'age' | 'coat' | 'glow';

/** Всё, что игра знает о заботе. Считается из хранилища, здесь только правила. */
export interface PetCare {
  /** Сколько дней из последних 14 питомца кормили. */
  fedDays: number;
  /** Дней с последнего мытья. Ни разу не мыли — большое число. */
  daysSinceWash: number;
  /** Дней с последней тренировки. Ни одной — большое число. */
  daysSincePlay: number;
  /** Стадия роста 1..3 (по числу тренировок). */
  stage: PetStage;
  /** Средняя по четырём шкалам навыков, 0..100. */
  skillAvg: number;
}

/** Что показать: ряд листа, ступень 0..6 и человеческая причина. */
export interface PetLook {
  axis: PetLookAxis;
  stage: number;
  /** Ключ причины — для подписи на экране питомца и для проб. */
  reason: 'hungry' | 'overfed' | 'dirty' | 'lonely' | 'neglected' | 'growing';
}

/** Загнать в 0..6. */
function ступень(v: number): number {
  return Math.max(0, Math.min(LOOK_STAGES - 1, Math.round(v)));
}

/**
 * Вес: 0 кормлений за две недели — самый тощий край, каждый день — самый толстый.
 * Норма (ступень 3) приходится на 7 кормлений из 14, то есть «через день».
 */
export function весПоКормлению(fedDays: number): number {
  const дней = Math.max(0, Math.min(14, fedDays));
  return ступень((дней / 14) * (LOOK_STAGES - 1));
}

/**
 * НАСКОЛЬКО ЗАПУЩЕНА КАЖДАЯ ШКАЛА, 0 — всё хорошо, 1 — край.
 *
 * Пороги выбраны так, чтобы вид менялся на человеческом сроке: неделя без мытья,
 * неделя без тренировок. Меньше суток ничего не меняет — иначе кот дёргался бы
 * внешностью по нескольку раз на дню.
 */
function запущенность(care: PetCare): { axis: PetLookAxis; сила: number; stage: number; reason: PetLook['reason'] }[] {
  const вес = весПоКормлению(care.fedDays);
  // Расстояние веса от нормы (ступень 3), нормированное на половину шкалы.
  const откНормы = Math.abs(вес - 3) / 3;
  return [
    {
      axis: 'weight', сила: откНормы, stage: вес,
      reason: вес < 3 ? 'hungry' : 'overfed',
    },
    {
      axis: 'clean', сила: Math.min(1, care.daysSinceWash / 7),
      stage: ступень(Math.min(1, care.daysSinceWash / 7) * (LOOK_STAGES - 1)),
      reason: 'dirty',
    },
    {
      axis: 'mood', сила: Math.min(1, care.daysSincePlay / 7),
      stage: ступень(Math.min(1, care.daysSincePlay / 7) * (LOOK_STAGES - 1)),
      reason: 'lonely',
    },
    {
      // Здоровье страдает от совсем долгого забвения — две недели без тренировок.
      axis: 'health', сила: Math.min(1, Math.max(0, care.daysSincePlay - 7) / 7),
      stage: ступень(Math.min(1, Math.max(0, care.daysSincePlay - 7) / 7) * (LOOK_STAGES - 1)),
      reason: 'neglected',
    },
  ];
}

/**
 * Вид питомца по заботе.
 *
 * Порог 0.34 — примерно две ступени из шести: раньше него разница на картинке
 * не читается, и кот бы «портился» от одного пропущенного дня.
 */
export function petLook(care: PetCare): PetLook {
  const ПОРОГ = 0.34;
  /**
   * ⚠️ ПРИ РАВНОЙ ЗАПУЩЕННОСТИ ПОБЕЖДАЕТ БОЛЕЕ ТЯЖЁЛАЯ ШКАЛА. Список в
   * `запущенность` идёт по возрастанию тяжести, и сравнение здесь нестрогое —
   * поэтому последняя из равных и выигрывает.
   *
   * Проба поймала это на живом случае: две недели без тренировок дают максимум
   * СРАЗУ у двух шкал — уныния и здоровья. Строгое сравнение оставляло первую, и
   * кот, заброшенный на полмесяца, выглядел просто скучающим. Полмесяца — это
   * уже не скука.
   */
  let худшая: { axis: PetLookAxis; сила: number; stage: number; reason: PetLook['reason'] } | null = null;
  for (const к of запущенность(care)) {
    if (к.сила >= ПОРОГ && (!худшая || к.сила >= худшая.сила)) худшая = к;
  }
  if (худшая) return { axis: худшая.axis, stage: худшая.stage, reason: худшая.reason };

  /**
   * Всё в порядке — показываем возраст. Стадий роста три, ступеней в ряду семь:
   * раскладываем стадию по краям и середине (0, 3, 6), чтобы разница между
   * стадиями была видна, а не терялась в соседних кадрах.
   */
  const поВозрасту = [0, 3, 6][Math.max(0, Math.min(2, care.stage - 1))];
  return { axis: 'age', stage: поВозрасту, reason: 'growing' };
}

/**
 * Сила свечения — отдельно от `petLook`: она не «нужда», а награда за прогресс,
 * и показывается не вместо покоя, а поверх (портрет на /pet).
 */
export function свечениеПоНавыкам(skillAvg: number): number {
  return ступень((Math.max(0, Math.min(100, skillAvg)) / 100) * (LOOK_STAGES - 1));
}
