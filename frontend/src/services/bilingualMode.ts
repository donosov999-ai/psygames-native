/**
 * 🔴 РЕЖИМ БИЛИНГВО ВНУТРИ САМОГО УПРАЖНЕНИЯ — ДВА ЯЗЫКА В ОДНОЙ ПАРТИИ.
 *
 * 📍 ПРАВКА ДЕНИСА 09.09.2026, дословно: «зарядка это финальный режим билингво;
 * я просил, чтобы В УПРАЖНЕНИЯХ появился режим билингво, в которых это
 * возможно, где переводы надо находить — особенно».
 *
 * ЧТО БЫЛО. Чередование языков existed ТОЛЬКО между шагами зарядки
 * (`languageFlow`): шаг на английском, следующий на испанском. Внутри самой
 * партии язык был один на весь заход — замер 09.09 по пяти словарным экранам:
 * у каждого ровно один `targetLang`, заведённый на всю сессию, и ни одного
 * места, где в одной партии встречаются два иностранных языка.
 *
 * ЧТО ЗДЕСЬ. То же правило чередования, но на уровне ЭЛЕМЕНТА: карточка,
 * фраза, слово. Родной язык остаётся якорем смысла и целью не бывает — ровно
 * как в потоке.
 *
 * 🔴 ПОЧЕМУ РЯД БЕРЁТСЯ ИЗ `languageFlow`, А НЕ ПИШЕТСЯ ЗАНОВО. Доля повторов
 * в ряду — не украшение: без повторов разность «переключения минус повторы»
 * возвращает ровно ноль, и цена переключения не считается вовсе (разбор в
 * шапке `languageFlow`). Вторая копия ряда разошлась бы с первой при первой же
 * правке, и мерить стало бы нечего. Правило одно, применяется на двух
 * масштабах: к шагам зарядки и к элементам внутри упражнения.
 */
import { ПОСЛЕДОВАТЕЛЬНОСТЬ, ЯЗЫКИ_ПОТОКА, языкиДляИнтерфейса } from '@/src/services/languageFlow';

/** Имя параметра и ключа хранилища. Одно на все упражнения. */
export const БИЛИНГВО = 'bilingual';

/**
 * Языки чередования для этого интерфейса. Тонкая обёртка над потоком — чтобы
 * упражнения не звали `languageFlow` напрямую и пара считалась одним способом.
 */
export function параЯзыков(интерфейс: string): [string, string] {
  return языкиДляИнтерфейса(интерфейс);
}

/**
 * Язык каждого элемента партии: `рядЯзыков(10, 'ru')` → десять языков подряд по
 * узору потока. Длина любая, ряд идёт по кругу.
 *
 * ⚠️ Ряд НЕ перемешивается. Узор «два подряд, потом смена» и есть измеряемая
 * величина; случайный порядок дал бы ту же долю повторов, но переключения
 * перестали бы быть сравнимыми между партиями.
 */
export function рядЯзыков(сколько: number, интерфейс: string): string[] {
  const [первый, второй] = параЯзыков(интерфейс);
  const из: string[] = [];
  for (let i = 0; i < Math.max(0, сколько); i += 1) {
    const шаг = ПОСЛЕДОВАТЕЛЬНОСТЬ[i % ПОСЛЕДОВАТЕЛЬНОСТЬ.length]!;
    из.push(шаг === ЯЗЫКИ_ПОТОКА[0] ? первый : второй);
  }
  return из;
}

/**
 * Разложить элементы двух языков по ряду чередования.
 *
 * @param поЯзыку  готовые элементы каждого языка, по порядку
 * @returns        один список в порядке ряда; когда элементы языка кончились,
 *                 берётся элемент другого — партия не должна обрываться на
 *                 полпути только потому, что в одном языке материал короче.
 *
 * ⚠️ ИМЕННО ЗДЕСЬ ЖИВЁТ ЧЕСТНОСТЬ РЕЖИМА. Если один язык кончился и добор идёт
 * из второго, ДОЛЯ переключений падает — партия к концу становится
 * одноязычной. Поэтому возвращается и `сколькоСмен`: экран обязан знать, была
 * ли партия на самом деле двуязычной, а не считать это по факту включённого
 * режима.
 */
export function разложитьПоРяду<T>(
  поЯзыку: Record<string, T[]>,
  сколько: number,
  интерфейс: string,
  /**
   * 🔴 ЯВНАЯ ПАРА. Без неё ряд строился от ЯЗЫКА ИНТЕРФЕЙСА и просил языки,
   * которых в материале нет: выбрал человек немецкий вторым — ряд просит
   * испанский, не находит и уходит в запасной путь, то есть выдаёт блоками
   * вместо чередования. Снаружи это выглядит как «поставил билингво, а суётся
   * один язык», и ровно так это и было названо (Денис, 10.09.2026).
   */
  пара?: readonly string[],
): { элементы: { элемент: T; язык: string }[]; сколькоСмен: number } {
  const ряд = пара && пара.length >= 2
    ? рядЯзыковПары(сколько, пара[0]!, пара[1]!)
    : рядЯзыков(сколько, интерфейс);
  const остаток: Record<string, T[]> = {};
  for (const [k, v] of Object.entries(поЯзыку)) остаток[k] = [...v];
  const элементы: { элемент: T; язык: string }[] = [];
  for (const хотим of ряд) {
    let язык = хотим;
    if (!остаток[язык]?.length) {
      const другой = Object.keys(остаток).find((k) => остаток[k]?.length);
      if (!другой) break;                       // материал кончился весь — партия короче
      язык = другой;
    }
    элементы.push({ элемент: остаток[язык]!.shift()!, язык });
  }
  let смен = 0;
  for (let i = 1; i < элементы.length; i += 1) if (элементы[i]!.язык !== элементы[i - 1]!.язык) смен += 1;
  return { элементы, сколькоСмен: смен };
}

/** Одно значение, показанное на трёх языках подряд. */
export interface Тройка {
  /** Ключ значения — `en` из словаря, для журнала и запрета повторов. */
  ключ: string;
  /** Слова по порядку показа: родной, затем два иностранных. */
  шаги: { язык: string; слово: string }[];
}

/**
 * 🔴 ТРОЙКА: ОДНО СЛОВО ТРИ РАЗА — РОДНОЙ, ПОТОМ ДВА ИНОСТРАННЫХ.
 *
 * 📍 РЕШЕНИЕ ДЕНИСА 10.09.2026, дословно: «слова арбуз, ватермелон и как там на
 * испанском — суём три раза одно слово: первое надо угадать на родном, 2 и 3 раз
 * мы просто вспоминаем перевод и вбиваем его».
 *
 * ⚠️ ЭТО ДРУГОЕ УСТРОЙСТВО, ЧЕМ ЧЕРЕДОВАНИЕ ВЫШЕ, И РАЗНИЦА НАМЕРЕННАЯ.
 * `рядЯзыков` мешает РАЗНЫЕ значения, чтобы мерить цену переключения. Тройка
 * держит ОДНО значение и мерит другое — достаётся ли перевод из памяти сразу
 * после того, как значение уже поднято. Первый заход честно решается как
 * анаграмма, второй и третий — припоминание.
 *
 * ⚠️ РОДНОЙ ИДЁТ ПЕРВЫМ, И БЕЗ НЕГО ТРОЙКИ НЕТ. Если начать с иностранного,
 * человек решает анаграмму на языке, которого не знает, — это не припоминание,
 * а угадывание букв.
 */
export function тройки(
  записи: readonly Record<string, unknown>[],
  интерфейс: string,
  сколько: number,
  годится: (слово: string) => boolean,
): Тройка[] {
  const [первый, второй] = параЯзыков(интерфейс);
  const языки = [интерфейс, первый, второй];
  const из: Тройка[] = [];
  for (const з of записи) {
    if (из.length >= сколько) break;
    const слова = языки.map((l) => з[l]);
    if (!слова.every((w) => typeof w === 'string' && годится(w as string))) continue;
    из.push({
      ключ: String(з.en ?? слова[0]),
      шаги: языки.map((l, i) => ({ язык: l, слово: String(слова[i]) })),
    });
  }
  return из;
}

/**
 * 🔴 ТО ЖЕ ЧЕРЕДОВАНИЕ, НО НА ЯВНОЙ ПАРЕ ЯЗЫКОВ.
 *
 * 📍 ОТЧЁТ ТЕСТИРОВЩИКА `2aa5892c` на v2.53.0: «Как выбрать второй язык-то для
 * двух языков сразу». Первая редакция считала пару от ЯЗЫКА ИНТЕРФЕЙСА и молча
 * отменяла выбор в пикере. Теперь пару задаёт экран, а узор остаётся общим.
 */
export function рядЯзыковПары(сколько: number, первый: string, второй: string): string[] {
  const из: string[] = [];
  for (let i = 0; i < Math.max(0, сколько); i += 1) {
    const шаг = ПОСЛЕДОВАТЕЛЬНОСТЬ[i % ПОСЛЕДОВАТЕЛЬНОСТЬ.length]!;
    из.push(шаг === ЯЗЫКИ_ПОТОКА[0] ? первый : второй);
  }
  return из;
}

/** Тройка на явной паре: родной + два выбранных. Разбор — у `тройки`. */
export function тройкиПары(
  записи: readonly Record<string, unknown>[],
  родной: string,
  первый: string,
  второй: string,
  сколько: number,
  годится: (слово: string) => boolean,
): Тройка[] {
  const языки = [родной, первый, второй];
  const из: Тройка[] = [];
  for (const з of записи) {
    if (из.length >= сколько) break;
    const слова = языки.map((l) => з[l]);
    if (!слова.every((w) => typeof w === 'string' && годится(w as string))) continue;
    /** ⚠️ Пара из одинаковых языков — не пара: тройка выродилась бы в повтор. */
    if (new Set(языки).size < 3) continue;
    из.push({
      ключ: String(з.en ?? слова[0]),
      шаги: языки.map((l, i) => ({ язык: l, слово: String(слова[i]) })),
    });
  }
  return из;
}

/**
 * 🔴 ПИЛЮЛЯ ЯЗЫКА В ШАПКЕ: ОДИН КОД НЕ ОТЛИЧАЕТ РЕЖИМ ОТ ОБЫЧНОЙ ПАРТИИ.
 *
 * 📍 ЗАМЕР ПО КАДРУ ИЗ ПРОДА 10.09.2026. Денис включил режим, увидел первую
 * карточку и написал «а как так нихуя в проде нет». Режим РАБОТАЛ: на его же
 * втором кадре и переключатель включён, и пара «English и Español», и счёт
 * 1/37 = 20 новых по двум языкам плюс 17 к повтору. Но ПЕРВЫЙ раунд ряда — это
 * первый язык пары, то есть английский, и партия выглядела один в один как
 * обычная: `house` и русские варианты. Испанское приходило со второго слова.
 *
 * Значит одной буквы мало: пилюля обязана показывать, что языков ДВА, с первого
 * же кадра. Текущий — прописными, второй — строчными: и режим виден, и какой
 * сейчас, без второй пилюли в и без того тесной шапке.
 */
export function паройЯзыков(текущий: string, пара: readonly string[]): string {
  const он = текущий.toUpperCase();
  if (пара.length < 2) return он;
  const другой = пара.find((l) => l.toLowerCase() !== текущий.toLowerCase());
  return другой ? `${он}·${другой.toLowerCase()}` : он;
}

/**
 * 🔴 ВТОРОЙ ЯЗЫК, ГАРАНТИРОВАННО ОТЛИЧНЫЙ ОТ ПЕРВОГО И ОТ РОДНОГО.
 *
 * 📍 ТА ЖЕ МИНА, ЧТО ВЗОРВАЛАСЬ В АНАГРАММАХ 10.09.2026. Умолчание второго
 * языка берётся от интерфейса: у русского это `es`. Стоит человеку выбрать
 * первым тоже испанский — пара вырождается в один язык, и «два языка сразу»
 * честно выдаёт один. Снаружи это ровно та жалоба, с которой всё началось.
 *
 * ⚠️ Родной тоже исключён: цель, совпавшая с языком интерфейса, дала бы
 * «переведи русский на русский».
 */
export function вторымНеПервый(родной: string, первый: string, желаемый: string): string {
  if (желаемый !== первый && желаемый !== родной) return желаемый;
  const пара = параЯзыков(родной);
  return пара.find((l) => l !== первый && l !== родной) ?? пара[1];
}
