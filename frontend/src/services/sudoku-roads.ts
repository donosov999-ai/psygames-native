/**
 * ДОРОГИ СЛОЖНОСТИ СУДОКУ — ТРИ ОТДЕЛЬНЫЕ ЛЕСТНИЦЫ, А НЕ СКИДКА К ОДНОЙ.
 *
 * 🔴 ЗАЧЕМ. Лестница судоку одна на всех: 57 ступеней, и человек либо идёт по ней,
 * либо стоит. Сказать «сегодня то же самое, но полегче» было нельзя вовсе, а сказать
 * «дай пожёстче, не двигая мой уровень» — тем более. Первая версия этой правки делала
 * ползунок-модификатор поверх ступени, и Денис её отменил дословно так: «уровни со
 * сдвигом сложности прогресс должен считаться отдельной лестницей, или вообще отдельной
 * дорогой… По сути это разные пути: или ты идёшь на лёгком, или на сложном. В игре
 * обычно когда ты запускаешь игру ты видишь уровень, потом ты его сменить не можешь —
 * в том же Мортал Комбат».
 *
 * Отсюда всё устройство файла:
 *   · дорог три — `easy` (полегче) · `normal` (обычная) · `hard` (пожёстче);
 *   · у каждой СВОЙ счётчик уровня в хранилище, а не один со скидкой;
 *   · дорога выбирается ДО партии и внутри партии не меняется (экран берёт её в
 *     `startGame` и кладёт в снимок незаконченной партии);
 *   · запись партии несёт дорогу, иначе история сравнит лёгкую партию с тяжёлой.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * 🔴 ПЕРЕНОС ПРОЙДЕННОГО — ТОЛЬКО ВНИЗ ПО СЛОЖНОСТИ. Правило Дениса дословно:
 * «пройденное засчитывается в более лёгкой партии — это логично, и новая дорога
 * считается как лёгкая».
 *
 *   ВНИЗ ПЕРЕНОСИТСЯ. Взял уровень 12 на тяжёлой — двенадцатый засчитан и на лёгкой:
 *   если человек решил это в тяжёлых условиях, в лёгких он это решает тем более, и
 *   заставлять переигрывать значит издеваться.
 *
 *   ВВЕРХ НЕ ПЕРЕНОСИТСЯ НИКОГДА. Пройденное на лёгкой не двигает тяжёлую ни на
 *   ступень. Именно это закрывает дыру, ради которой запрет вообще нужен: прогнать
 *   лестницу «полегче» и получить тяжёлую пройденной нельзя.
 *
 *   НОВАЯ ДОРОГА ОТКРЫВАЕТСЯ ПО ТОМУ ЖЕ ПРАВИЛУ: ни разу не игранная лёгкая сразу
 *   стоит там, куда человек дошёл на тяжёлой, а ни разу не игранная тяжёлая — на
 *   первом уровне, сколько бы ни было пройдено на лёгкой.
 *
 * ⚠️ СЧИТАЕМ ПРИ ЧТЕНИИ, А НЕ ПЕРЕНОСИМ РАЗОВО ПРИ ПЕРЕКЛЮЧЕНИИ. Разовый перенос
 * разъедется в первый же вечер: человек переключился на лёгкую (перенесли 12), потом
 * вернулся на тяжёлую и добил её до 20 — лёгкая осталась бы на двенадцати навсегда,
 * потому что событие переключения уже прошло. Поэтому в хранилище лежит СОБСТВЕННЫЙ
 * счётчик каждой дороги, а показываемый уровень выводится функцией из всех трёх.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠️ ЧЕМ ДОРОГИ ОТЛИЧАЮТСЯ НА САМОМ ДЕЛЕ — ТЕХНИКОЙ, А НЕ ЧИСЛОМ ДЫРОК.
 *
 * Соблазн сделать «полегче» как «меньше пустых клеток» велик и почти бесполезен:
 * в режиме уровней доску копает `digByLogic`, и лимит пустых там держится только на
 * уровнях 1–8 и в sandwich, а дальше глубину задаёт ЛОГИКА (см. `cap` в sudoku-grade).
 * Настоящая ось сложности — какую технику приходится применить, чтобы продвинуться;
 * ровно на этом стоит вся градация уровней (жалобы Вали «34-й легче 19-го» чинились
 * именно полосой техник, а не дырками).
 *
 * Поэтому дорога сдвигает ПОЛОСУ ТЕХНИК `targetTier` на ступень вниз или вверх, а
 * число пустых и лимит подсказок идут довеском — они всё ещё работают на 1–8, в
 * sandwich и на запасном пути генератора.
 */
import { LevelCfg, levelConfig } from '@/src/services/sudoku-core';
import { targetTier } from '@/src/services/sudoku-grade';

/**
 * Дороги ОТ ЛЁГКОЙ К ТЯЖЁЛОЙ. Порядок здесь — не оформление: из него выводится, какие
 * дороги считаются «тяжелее» текущей, а значит и весь перенос пройденного.
 */
export const SUDOKU_ROADS = ['easy', 'normal', 'hard'] as const;
export type SudokuRoad = (typeof SUDOKU_ROADS)[number];

/**
 * Дорога по умолчанию — та самая единственная лестница, которая была до этой правки.
 * Её счётчик лежит под прежним ключом, поэтому прогресс никто не теряет.
 */
export const DEFAULT_SUDOKU_ROAD: SudokuRoad = 'normal';

/** Собственные счётчики дорог: сколько уровней взято НА КАЖДОЙ, без переноса. */
export type RoadLevels = Partial<Record<SudokuRoad, number>>;

export function isSudokuRoad(v: unknown): v is SudokuRoad {
  return typeof v === 'string' && (SUDOKU_ROADS as readonly string[]).includes(v);
}

/**
 * Ключ AsyncStorage для собственного счётчика дороги.
 *
 * ⚠️ У ОБЫЧНОЙ ДОРОГИ КЛЮЧ ПРЕЖНИЙ — `psygames_sudoku_level_<профиль>`. Это не
 * экономия строчки: под ним лежит прогресс всех, кто играл до появления дорог, и
 * новый ключ означал бы, что в день обновления человек с пятидесятого уровня
 * открывает судоку на первом.
 */
export function sudokuLevelKey(profileId: string, road: SudokuRoad): string {
  const base = `psygames_sudoku_level_${profileId}`;
  return road === DEFAULT_SUDOKU_ROAD ? base : `${base}_${road}`;
}

/** Ключ выбранной дороги: заход на экран возвращает человека туда, где он был. */
export function sudokuRoadKey(profileId: string): string {
  return `psygames_sudoku_road_${profileId}`;
}

/** Дороги ТЯЖЕЛЕЕ этой. Из них и только из них пройденное переносится сюда. */
export function roadsHarderThan(road: SudokuRoad): SudokuRoad[] {
  const i = SUDOKU_ROADS.indexOf(road);
  return i < 0 ? [] : SUDOKU_ROADS.slice(i + 1);
}

const own = (levels: RoadLevels, road: SudokuRoad): number => {
  const n = Number(levels[road]);
  return Number.isFinite(n) && n >= 1 ? Math.floor(n) : 1;
};

/**
 * ДОСТИГНУТЫЙ ПОТОЛОК ДОРОГИ = максимум из её собственного счётчика и счётчиков всех
 * дорог ТЯЖЕЛЕЕ неё. Ниже первого уровня не опускается: лестница начинается с единицы.
 *
 * Считается каждый раз заново — см. «⚠️ СЧИТАЕМ ПРИ ЧТЕНИИ» в шапке файла.
 */
export function effectiveRoadLevel(levels: RoadLevels, road: SudokuRoad): number {
  let best = own(levels, road);
  for (const harder of roadsHarderThan(road)) best = Math.max(best, own(levels, harder));
  return best;
}

/** То же по всем трём разом — экран показывает уровень каждой дороги ДО выбора. */
export function effectiveRoadLevels(levels: RoadLevels): Record<SudokuRoad, number> {
  const out = {} as Record<SudokuRoad, number>;
  for (const r of SUDOKU_ROADS) out[r] = effectiveRoadLevel(levels, r);
  return out;
}

/**
 * Записать взятый уровень в СОБСТВЕННЫЙ счётчик дороги.
 *
 * ⚠️ Пишем максимум, а не `level + 1`: на пройденный уровень можно вернуться по
 * тропинке, и переигровка тройки при взятых двадцати иначе срезала бы семнадцать
 * ступеней (та же грабля, что уже стояла на одной лестнице).
 *
 * ⚠️ Пишем ТОЛЬКО свою дорогу. Соблазн заодно подтянуть лёгкие велик, но именно он
 * и есть «разовый перенос», который разъедется: лёгкие подтянет чтение.
 */
export function reachRoadLevel(levels: RoadLevels, road: SudokuRoad, level: number): RoadLevels {
  const next = Math.max(1, Math.floor(level));
  return { ...levels, [road]: Math.max(own(levels, road), next) };
}

/**
 * Полоса техник дороги: сдвиг полосы уровня на ступень вниз (полегче) или вверх
 * (пожёстче).
 *
 * Границы не выдуманы: 1 — голые одиночки, ниже техники нет вовсе; 6 — X-wing, и
 * седьмой ступенью в лестнице техник идёт `guess`, то есть перебор. Выпустить доску,
 * которая логикой не берётся, — это не «пожёстче», это сломанная задача.
 */
export function roadTier(level: number, road: SudokuRoad): { min: number; max: number } {
  const { min, max } = targetTier(level);
  if (road === 'easy') return { min: Math.max(1, min - 1), max: Math.max(1, max - 1) };
  if (road === 'hard') return { min: Math.min(6, min + 1), max: Math.min(6, max + 1) };
  return { min, max };
}

/**
 * Параметры партии на дороге. Размер поля и правило варианта дорога НЕ трогает:
 * иначе это была бы не «та же ступень полегче», а другая ступень, и лестницы дорог
 * перестали бы быть сравнимыми между собой (а перенос пройденного вниз опирается
 * ровно на их сравнимость).
 */
export function roadLevelConfig(level: number, road: SudokuRoad): LevelCfg {
  const cfg = levelConfig(level);
  if (road === DEFAULT_SUDOKU_ROAD) return cfg;
  // Шаг по пустым клеткам — примерно четыре ступени лестницы (там +1 клетка за уровень):
  // меньше не чувствуется рукой, больше на 6×6 выело бы половину доски.
  const step = cfg.size === 6 ? 3 : 4;
  const floor = cfg.size === 6 ? 8 : 30;    // ниже доска перестаёт быть задачей
  const ceil = cfg.size === 6 ? 26 : 62;    // выше — сплошные дырки, см. MAX_BLANKS_9
  const blanks = road === 'easy'
    ? Math.max(floor, cfg.blanks - step)
    : Math.min(ceil, cfg.blanks + step);
  // Подсказка — вторая валюта партии. На лёгкой её на одну больше, на тяжёлой на одну
  // меньше; ноль допустим и означает ровно то, что написано: подсказок нет.
  const hintMax = road === 'easy' ? cfg.hintMax + 1 : Math.max(0, cfg.hintMax - 1);
  return { ...cfg, blanks, hintMax };
}

/** Ключи словаря: подпись дороги. Возвращаются отсюда, чтобы гейт сверял их механически. */
export const SUDOKU_ROAD_NAME_KEY: Readonly<Record<SudokuRoad, string>> = {
  easy: 'sudokuRoadEasy',
  normal: 'sudokuRoadNormal',
  hard: 'sudokuRoadHard',
};

/**
 * ЧТО ЗАПИСЫВАЕТСЯ В ПАРТИЮ.
 *
 * ⚠️ ОБЫЧНАЯ ДОРОГА И ПАРТИЯ ДО ПОЯВЛЕНИЯ ДОРОГ — ОДНА И ТА ЖЕ ЗАДАЧА. Параметры
 * обычной дороги — это ровно `levelConfig(level)`, то есть то, во что человек играл
 * вчера. Значит в ключе задачи (`taskKey` в trainingHistory) они обязаны совпадать,
 * иначе в день обновления вся история судоку станет «новой сложностью» и человек
 * потеряет сравнение с прошлым разом на ровном месте.
 *
 * Поэтому нормализация: и отсутствующая дорога, и явная `normal` дают пустую строку.
 * В самой записи партии дорога пишется ВСЕГДА и явно — читать `details` должно быть
 * можно без знания того, что «пусто значит обычная».
 */
export function roadTaskPart(road: unknown): string {
  return isSudokuRoad(road) && road !== DEFAULT_SUDOKU_ROAD ? road : '';
}
