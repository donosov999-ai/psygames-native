/**
 * 🔴 ЯЗЫК СДВИГАЕТСЯ НА ОДИН С КАЖДЫМ КРУГОМ ИГР — БЕЗ ЭТОГО РЯД МЁРТВ.
 *
 * ⚠️ ЗАМЕР 09.09.2026, И ОН ОТМЕНЯЕТ ТО, ЧТО Я ДУМАЛ ОБ ЭТОМ ФАЙЛЕ. Игр шесть и
 * мест в ряду шесть, а `темаШаги` берёт темы по кругу. Значит игра номер `k`
 * ВСЕГДА попадала на место `k` ряда — и получала один и тот же язык до конца
 * жизни. Распечатка двадцатиминутной зарядки (16 шагов) до правки:
 *
 *   vocab_srs en · cloze en · semantic_sort es · lexical_decision en ·
 *   anagrams es · semantic_sort es · и дальше ровно то же самое трижды
 *
 * То есть анаграммы НИКОГДА не были английскими, а пропущенное слово — никогда
 * испанским. Денис 07.09.2026 спрашивал ровно про это: «что если давать
 * анаграммы на трёх языках, и с другими упражнениями?» — а получалось на одном.
 *
 * 🔴 И ЭТО ЛОМАЛО НЕ ТОЛЬКО РАЗНООБРАЗИЕ. Из той же распечатки: повтор языка
 * выпадал только на пары `vocab_srs→cloze` и `anagrams→semantic_sort`,
 * переключение — только на остальные четыре. Ни одна пара игр не встречалась и
 * так и так. Разность «переключения минус повторы» тогда сравнивает РАЗНЫЕ
 * ПЕРЕХОДЫ МЕЖДУ ИГРАМИ, а не переключение языка: цена смены упражнения сидит
 * внутри неё целиком. Ряд с повторами был собран (см. выше) именно чтобы этой
 * цены не было — и она вернулась с другой стороны.
 *
 * ЧТО ДЕЛАЕТ СДВИГ. Позиция в ряду растёт не только по шагу, но и по номеру
 * круга: `i + ⌊i / ИГРЫ.length⌋ × СДВИГ`. Игра `g` на круге `c` попадает тогда
 * на место `(ИГРЫ.length + СДВИГ) × c + g`, и все места она обходит ровно
 * тогда, когда `ИГРЫ.length + СДВИГ` взаимно просто с длиной ряда. Тем поэтому
 * `ИГРЫ.length × ПОСЛЕДОВАТЕЛЬНОСТЬ.length` = 36, а не шесть: они выписаны
 * целиком, чтобы `темаШаги` не пришлось учить про язык.
 *
 * 🔴 СДВИГ СЧИТАЕТСЯ, А НЕ ВПИСАН ЧИСЛОМ — И ЭТО НЕ УКРАШЕНИЕ. При нынешних
 * шести играх и шести местах верна единица: gcd(6+1, 6) = 1. Но стоит завести
 * СЕДЬМОЕ упражнение (кандидаты есть: `word-pairs` и `listening-span` уже умеют
 * `targetLang` и черпают из того же словаря на 12 языков), как единица станет
 * ХУЖЕ НУЛЯ: gcd(7+1, 6) = 2, каждая игра обойдёт лишь три места из шести,
 * а без сдвига — все шесть. Вписанная единица сломала бы ряд молча, при правке
 * в СОСЕДНЕМ месте файла. Поэтому берётся наименьший подходящий сдвиг.
 *
 * ЗАМЕР ПОСЛЕ (тот же прогон, 16 шагов): одноязычных упражнений НЕТ НИ ОДНОГО,
 * три пары игр встречаются и как переключение и как повтор, доля повторов
 * 4 из 15. Кольцо самого ряда не тронуто — 2 повтора на 4 переключения, как и
 * было (`долиПовторов` сторожит).
 *
 * ⚠️ ПОРЯДОК ЯЗЫКОВ В РЯДУ ТОЖЕ ПОМЕНЯН, И ЭТО НЕ КОСМЕТИКА. Со старым
 * `en,en,es,en,es,es` анаграммы за 16 шагов попадали на места 4 и 5 — оба `es`,
 * то есть оставались одноязычными даже со сдвигом. `en,en,es,es,en,es` даёт им
 * места 4 и 5 = `en,es`. Доля повторов у обоих одинаковая (2 из 6), выбран
 * второй по замеру, а не по вкусу: у первого на двадцати минутах одно
 * упражнение оставалось на одном языке, у второго — ни одного.
 * ⚠️ Цена выбора: на пяти минутах (4 шага) остаётся одно переключение вместо
 * двух. Четыре шага — это `en,en,es,es`; переключение есть, и это минимум,
 * ниже которого мерить нечего.
 */
const НОД = (a: number, b: number): number => (b === 0 ? a : НОД(b, a % b));

/**
 * Наименьший сдвиг, при котором каждая игра обходит ВСЕ места ряда.
 * Ноль тоже годится — и при семи играх на шесть мест он и окажется ответом.
 *
 * Вынесено наружу, чтобы правило проверялось пробой НА ДРУГИХ ДЛИНАХ, а не
 * только на нынешних: гейт, померивший лишь сегодняшние шесть на шесть,
 * промолчит ровно в тот день, когда игр станет семь.
 */
export function сдвигДля(игр: number, мест: number): number {
  for (let s = 0; s < Math.max(1, мест); s += 1) {
    if (НОД(игр + s, мест) === 1) return s;
  }
  return 0;   // ряд из одного языка — сдвигать нечего, чередования там нет по построению
}

const СДВИГ: number = сдвигДля(ИГРЫ.length, ПОСЛЕДОВАТЕЛЬНОСТЬ.length);

function позицияРяда(i: number): number {
  const круг = Math.floor(i / ИГРЫ.length);
  return (i + круг * СДВИГ) % ПОСЛЕДОВАТЕЛЬНОСТЬ.length;
}

/**
 * Темы для `собратьТемуЗарядки`: игра + её собственный уровень + язык шага.
 * Уровни приходят снаружи — сервис остаётся чистым и гоняется пробами.
 */
export function языковыеТемы(
  уровни: Readonly<Record<string, number>>,
  интерфейс = 'ru',
): ТемаЗарядки[] {
  const [первый, второй] = языкиДляИнтерфейса(интерфейс);
  const темы: ТемаЗарядки[] = [];
  for (let i = 0; i < ИГРЫ.length * ПОСЛЕДОВАТЕЛЬНОСТЬ.length; i += 1) {
    const и = ИГРЫ[i % ИГРЫ.length]!;
    const шаг = ПОСЛЕДОВАТЕЛЬНОСТЬ[позицияРяда(i)]!;
    темы.push({
      game_id: и.id,
      game_route: и.route,
      секунд: и.секунд,
      уровень: Math.max(1, уровни[и.ключУровня] ?? 1),
      // Ряд задаёт УЗОР чередования, а какие именно языки — решает интерфейс.
      настройки: { targetLang: шаг === ЯЗЫКИ_ПОТОКА[0] ? первый : второй },
    });
  }
  return темы;
}

/** Две игры подряд одинаковыми не бывают — проверяется пробой, держится здесь. */
export function игрыПодряд(): string[] {
  return ИГРЫ.map((и) => и.id);
}
