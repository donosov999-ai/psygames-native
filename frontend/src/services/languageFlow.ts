const НОД = (a: number, b: number): number => (b === 0 ? a : НОД(b, a % b));

/**
 * Наименьший сдвиг, при котором каждая игра обходит ВСЕ места ряда.
 * Ноль тоже годится — и при семи играх на шесть мест он и окажется ответом.
 *
 * Вынесено наружу, чтобы правило проверялось пробой НА ДРУГИХ ДЛИНАХ, а не
 * только на нынешних: гейт, померивший лишь сегодняшние шесть на шесть,
 * промолчит ровно в тот день, когда игр станет семь.
 */
/**
 * 🔴 НАИМЕНЬШИЙ ПОДХОДЯЩИЙ СДВИГ — НЕ ЛУЧШИЙ. Замер 11.09.2026.
 *
 * Условие `gcd(игр + s, мест) = 1` даёт полный обход мест, но обход этот
 * АСИМПТОТИЧЕСКИЙ: он завершается за `мест` кругов, а зарядка живёт 4…16 шагов
 * и до конца обхода не доживает. На коротком отрезке важно другое — попадают ли
 * ДВА СОСЕДНИХ захода одной игры на РАЗНЫЕ языки. При сдвиге 0 игра переезжает
 * на соседнее место ряда, а в ряду `en·es·en·en·es·es` соседние места сплошь и
 * рядом одного языка — и игра запирается.
 *
 * 📍 ЗАМЕР (семь игр на шесть мест; «заперты» = игра встретилась ≥2 раз и все
 * разы на одном языке; знаменатель — сколько игр вообще встретилось):
 *
 *   сдвиг 0 (наименьший):  5мин 0/4 · 10мин 0/7 · 15мин 🔴2/7 · 20мин 2/7
 *   сдвиг 4:               5мин 0/4 · 10мин 0/7 · 15мин  1/7 · 20мин 2/7
 *   сдвиг 6:               5мин 0/4 · 10мин 0/7 · 15мин  2/7 · 20мин 2/7
 *
 * Допустимых сдвигов ровно три — 0, 4, 6, — и «первый попавшийся» оказался
 * худшим из них. Поэтому отбор идёт не по порядку номеров, а по замеру.
 *
 * ⚠️ БЕЗ `ряд` ПОВЕДЕНИЕ ПРЕЖНЕЕ — наименьший подходящий. Так вызывает проба
 * «сдвиг даёт полный обход при ЛЮБОМ числе игр и мест»: она проверяет ЧИСТОЕ
 * арифметическое свойство на длинах 1..12, где никакого ряда языков нет.
 * Свойство обхода одинаково верно для любого допустимого сдвига, так что выбор
 * по замеру его не трогает.
 */
export function сдвигДля(игр: number, мест: number, ряд?: readonly string[]): number {
  const подходят: number[] = [];
  for (let s = 0; s < Math.max(1, мест); s += 1) {
    if (НОД(игр + s, мест) === 1) подходят.push(s);
  }
  if (подходят.length === 0) return 0;   // ряд из одного языка — чередования нет по построению
  if (!ряд || ряд.length !== мест) return подходят[0]!;
  return подходят.reduce((лучший, s) => (запертых(игр, s, ряд) < запертых(игр, лучший, ряд) ? s : лучший), подходят[0]!);
}

/**
 * Сколько игр заперты на ОДНОМ языке за реальные длины зарядки, при данном
 * сдвиге. Считается по тем же формулам, что и `позицияРяда`, — иначе замер
 * мерил бы не то, что собирает поток.
 */
function запертых(игр: number, сдвиг: number, ряд: readonly string[]): number {
  let сумма = 0;
  for (const шагов of ШАГОВ_НА_ЗАРЯДКУ) {
    const поИгре = new Map<number, Set<string>>();
    const сколько = new Map<number, number>();
    for (let i = 0; i < шагов; i += 1) {
      const g = i % Math.max(1, игр);
      const поз = (i + Math.floor(i / Math.max(1, игр)) * сдвиг) % ряд.length;
      (поИгре.get(g) ?? поИгре.set(g, new Set()).get(g)!).add(ряд[поз]!);
      сколько.set(g, (сколько.get(g) ?? 0) + 1);
    }
    for (const [g, языки] of поИгре) if ((сколько.get(g) ?? 0) >= 2 && языки.size < 2) сумма += 1;
  }
  return сумма;
}

/**
 * Длины зарядки в ШАГАХ — те, что реально собираются (5/10/15/20 минут при
 * средних ~70 с на шаг). Не длительности в минутах: отбор сдвига зависит от
 * числа шагов, а не от секунд.
 */
const ШАГОВ_НА_ЗАРЯДКУ: readonly number[] = [4, 8, 12, 16];

const СДВИГ: number = сдвигДля(ИГРЫ.length, ПОСЛЕДОВАТЕЛЬНОСТЬ.length, ПОСЛЕДОВАТЕЛЬНОСТЬ);

function позицияРяда(i: number): number {
  const круг = Math.floor(i / ИГРЫ.length);
  return (i + круг * СДВИГ) % ПОСЛЕДОВАТЕЛЬНОСТЬ.length;
}

/**
 * Темы для `собратьТемуЗарядки`: игра + её собственный уровень + язык шага.
 * Уровни приходят снаружи — сервис остаётся чистым и гоняется пробами.
 */
export function языковыеТемы(
  уровни: Readonly<Record<string, number>>,
  интерфейс = 'ru',
): ТемаЗарядки[] {
  const [первый, второй] = языкиДляИнтерфейса(интерфейс);
  const темы: ТемаЗарядки[] = [];
  for (let i = 0; i < ИГРЫ.length * ПОСЛЕДОВАТЕЛЬНОСТЬ.length; i += 1) {
    const и = ИГРЫ[i % ИГРЫ.length]!;
    const шаг = ПОСЛЕДОВАТЕЛЬНОСТЬ[позицияРяда(i)]!;
    темы.push({
      game_id: и.id,
      game_route: и.route,
      секунд: и.секунд,
      уровень: Math.max(1, уровни[и.ключУровня] ?? 1),
      // Ряд задаёт УЗОР чередования, а какие именно языки — решает интерфейс.
      настройки: { targetLang: шаг === ЯЗЫКИ_ПОТОКА[0] ? первый : второй, ...(и.ещё ?? {}) },
    });
  }
  return темы;
}

/** Две игры подряд одинаковыми не бывают — проверяется пробой, держится здесь. */
export function игрыПодряд(): string[] {
  return ИГРЫ.map((и) => и.id);
}
