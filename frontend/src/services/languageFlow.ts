import type { ТемаЗарядки } from '@/src/services/chessWarmup';

/** Иностранные языки потока. Русский — база, целью не бывает (см. шапку). */
export const ЯЗЫКИ_ПОТОКА = ['en', 'es'] as const;
export type ЯзыкПотока = (typeof ЯЗЫКИ_ПОТОКА)[number];

/**
 * 🔴 ПОСЛЕДОВАТЕЛЬНОСТЬ ЯЗЫКОВ — С ПОВТОРАМИ, И ЭТО ГЛАВНОЕ В ФАЙЛЕ.
 *
 * Чистое чередование `en → es → en → es` даёт ОДНИ переключения, повторов ноль,
 * и цена переключения снова не считается. Доля повторов около трети: меньше —
 * оценка шумная, больше — теряется само смешивание.
 *
 * ⚠️ Список замкнут в кольцо: `темаШаги` берёт темы по кругу (`i % длина`),
 * поэтому переход с последнего на первый — такой же настоящий переход, и он
 * учитывается в доле.
 *
 * ⚠️ ПОРЯДОК ВНУТРИ РЯДА ВЫБРАН ЗАМЕРОМ, А НЕ НА ГЛАЗ — разбор у `позицияРяда`.
 * Доля повторов у `en,en,es,en,es,es` и у нынешнего одинаковая, но со сдвигом по
 * кругам первый оставлял анаграммы на одном языке даже за двадцать минут.
 */
export const ПОСЛЕДОВАТЕЛЬНОСТЬ: readonly ЯзыкПотока[] =
  ['en', 'en', 'es', 'es', 'en', 'es'] as const;

/**
 * 🔴 ЗАПАСНОЙ ЯЗЫК — ТОЛЬКО ДЛЯ АНГЛИЙСКОГО И ИСПАНСКОГО ИНТЕРФЕЙСА.
 *
 * 📍 ЗАМЕР ЖИВЬЁМ 09.09.2026 по всем двенадцати интерфейсам. Каждая из четырёх
 * игр при совпадении цели с языком интерфейса подставляет другой язык:
 * `targetLang === language ? (language === 'en' ? 'es' : 'en') : targetLang`.
 * Следствие: на английском интерфейсе ОБА шага ряда (`en` и `es`) дают `es`, на
 * испанском — оба дают `en`. Поток становится ОДНОЯЗЫЧНЫМ, и вместе с ним
 * умирает то, ради чего он собран: `switchCostMs` без переключений возвращает
 * ровно ноль.
 *
 * ⚠️ ЭТО ПРОДУКТОВОЕ РЕШЕНИЕ, А НЕ ТЕХНИЧЕСКОЕ, И ОНО ПОМЕЧЕНО КАК ТАКОЕ.
 * Денис 08.09.2026: «делай только английский испанский». Для англоговорящего
 * это физически один иностранный: его родной уже занят интерфейсом. Чтобы
 * механизм остался жив, вторым берётся немецкий — он есть в словаре на всех
 * записях (`VOCAB_LANGS`), и это самый крупный из оставшихся европейских.
 * Менять — одна строка здесь.
 */
export const ЗАПАСНОЙ_ЯЗЫК = 'de';

/**
 * Два ИНОСТРАННЫХ языка для этого интерфейса: язык интерфейса среди них не
 * бывает — иначе игра подменит его сама, и оба шага сойдутся в один.
 */
export function языкиДляИнтерфейса(интерфейс: string): [string, string] {
  const свои = ЯЗЫКИ_ПОТОКА.filter((л) => л !== интерфейс);
  if (свои.length === 2) return [свои[0]!, свои[1]!];
  return [свои[0] ?? ЯЗЫКИ_ПОТОКА[0], ЗАПАСНОЙ_ЯЗЫК];
}

export interface ДоляПовторов {
  переключений: number;
  повторов: number;
  /** Доля повторов среди всех переходов, 0..1. */
  доля: number;
}

/** Сколько в кольце переключений и сколько повторов. Считает и переход с конца в начало. */
export function долиПовторов(ряд: readonly string[] = ПОСЛЕДОВАТЕЛЬНОСТЬ): ДоляПовторов {
  if (ряд.length < 2) return { переключений: 0, повторов: 0, доля: 0 };
  let пер = 0; let пов = 0;
  for (let i = 0; i < ряд.length; i += 1) {
    const сейчас = ряд[i]!;
    const дальше = ряд[(i + 1) % ряд.length]!;
    if (сейчас === дальше) пов += 1; else пер += 1;
  }
  return { переключений: пер, повторов: пов, доля: пов / (пер + пов) };
}

