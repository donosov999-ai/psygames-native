/** Игры, чьи уровни нужны потоку. Экран читает их своими хуками. */
export const КЛЮЧИ_УРОВНЕЙ: readonly string[] =
  [...new Set(ИГРЫ.map((и) => и.ключУровня))];

/**
 * Темы для `собратьТемуЗарядки`: игра + её собственный уровень + язык шага.
 * Уровни приходят снаружи — сервис остаётся чистым и гоняется пробами.
 */
export function языковыеТемы(уровни: Readonly<Record<string, number>>): ТемаЗарядки[] {
  return ИГРЫ.map((и, i) => ({
    game_id: и.id,
    game_route: и.route,
    секунд: и.секунд,
    уровень: Math.max(1, уровни[и.ключУровня] ?? 1),
    настройки: { targetLang: ПОСЛЕДОВАТЕЛЬНОСТЬ[i % ПОСЛЕДОВАТЕЛЬНОСТЬ.length]! },
  }));
}

/** Две игры подряд одинаковыми не бывают — проверяется пробой, держится здесь. */
export function игрыПодряд(): string[] {
  return ИГРЫ.map((и) => и.id);
}
