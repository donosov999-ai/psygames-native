/** Куда уходит нажатие цифры. */
export type PencilRoute = 'ignore' | 'pencil' | 'digit';

/**
 * Решение «куда уходит нажатие цифры»: в карандашный слой, в клетку или никуда.
 *
 * ⚠️ ГЛАВНОЕ ЗДЕСЬ — ЧТО КАРАНДАШ НЕ СТАНОВИТСЯ ХОДОМ. Ход тратит ошибку, ложится
 * в ленту отмены и проверяет доску на победу; пометка не делает ничего из этого —
 * это бухгалтерия игрока, а не ход. Развилка одна на все судоку именно поэтому:
 * стоит одному экрану уронить `return` в карандашной ветке, и карандаш начнёт
 * считать ошибки, а лента отмены — забиваться несделанными ходами.
 *
 * `blocked` — партия кончилась (проигрыш, итог): не пишем ни цифру, ни пометку.
 */
export function routeDigitPress(o: {
  pencil: boolean;
  hasSelection: boolean;
  given: boolean;
  blocked?: boolean;
}): PencilRoute {
  if (o.blocked || !o.hasSelection || o.given) return 'ignore';
  return o.pencil ? 'pencil' : 'digit';
}

/**
 * Ввод в карандашный слой одной клетки: 0 (стирающая клавиша) чистит клетку ЦЕЛИКОМ,
 * любая цифра — переключается.
 *
 * Ластик именно на всю клетку: снимать девять пометок по одной — девять нажатий там,
 * где на бумаге одно движение. Снять одну — повторный тап по той же цифре.
 */
export function pencilInput(marks: PencilMarks, N: number, r: number, c: number, digit: number): PencilMarks {
  return digit === 0 ? clearPencilMarks(marks, N, r, c) : togglePencilMark(marks, N, r, c, digit);
}

/**
 * Что реально видно в клетке: поставленная цифра ГАСИТ пометки, но НЕ СТИРАЕТ их.
 *
 * ⚠️ Разница не косметическая, она про отмену. Стирай цифра пометки — откат хода вернул
 * бы клетку, но не вернул бы стёртое, и отмена оказалась бы половинчатой. Здесь же
 * цифру убрали (сами или отменой) — кандидаты снова на месте, ровно те, что были.
 */
export function visiblePencilDigits(mask: number, value: number): number[] {
  return value !== 0 ? [] : pencilDigits(mask);
}
