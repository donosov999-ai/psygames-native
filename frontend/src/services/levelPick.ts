/**
 * levelPick — единственное правило, по которому тропинка решает, куда пускать.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Правило живёт внутри usePersistentLevel, а хук без
 * рендерера не проверить — в проекте нет react-test-renderer, и гейт свёлся бы к
 * поиску строки в исходнике. Такой гейт уже один раз соглашался с моей же ошибкой
 * (замеры макушки питомца). Чистая функция проверяется по-настоящему.
 */

/**
 * Какой уровень станет выбранным при нажатии на узел тропинки.
 *
 * @param n     номер нажатого узла
 * @param best  достигнутый потолок
 * @returns     уровень переигровки либо null — «играем на своём потолке»
 *
 * Выше потолка выбора нет: тропинка показывает путь, но не работает лифтом через
 * сложность. Нажатие на свой же потолок снимает переигровку — это способ вернуться.
 */
export function pickTarget(n: number, best: number): number | null {
  const lv = Math.max(1, Math.round(n));
  return lv >= best ? null : lv;
}
