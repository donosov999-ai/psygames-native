/**
 * ЧТО ДЕЛАТЬ С УРОВНЕМ ПОСЛЕ ПАРТИИ — одним правилом, а не по памяти в каждом экране.
 *
 * 🔴 ЗАЧЕМ. Шаг зарядки (`isPreset`) — это не личная партия: он короткий, идёт в
 * заданном плейлистом окружении и нужен для разминки, а не для замера. Двигать
 * от него персональный уровень нечестно в обе стороны: вверх — потому что
 * «прошёл» там означает не то же самое, вниз — потому что человек получает
 * понижение за игру, которая ему просто попалась в наборе.
 *
 * ⚠️ ПРАВИЛО НЕ УНИВЕРСАЛЬНО, И ЭТО НАРОЧНО. Есть игры, где шаг зарядки играет
 * РОВНО ТУ ЖЕ доску, что и личная партия (маджонг, сортировка: `loadLevel(lvl.level)`),
 * и там прохождение — честный прогресс; они сохраняют его намеренно, см.
 * `warmup-persistent-level.test.ts`. Этот помощник — для второго семейства: игр,
 * где «прошёл» в зарядке несравнимо с «прошёл» на тропинке.
 *
 * ⚠️ ФАЗА ИДЁТ В КОМПЛЕКТЕ С `passed`, а не отдельным решением. Стоит выключить
 * прохождение в пресете и оставить экран «уровень пройден» — и человек на шаге
 * зарядки увидит «почти, ещё раз», хотя ничего не провалил. Поэтому решение здесь
 * одно и возвращает обе половины сразу.
 */

export interface LevelOutcomeInput {
  /** Партия идёт как шаг плейлиста зарядки (`useGamePreset().isPreset`). */
  isPreset: boolean;
  /** Взял ли человек планку уровня — по мерке самой игры. */
  cleared: boolean;
  /**
   * Партию оборвали руками, не доиграв.
   *
   * 🔴 ЗАЧЕМ ОТДЕЛЬНОЕ СОСТОЯНИЕ. Обрыв — это НЕ провал и НЕ победа, и оба
   * толкования уже успели навредить: в тесте внимания «СТОП» после первой цели
   * давал уровень за десять секунд вместо девяноста (точность 1/1), а в
   * «вероятностном выборе» та же кнопка засчитывалась провалом — человек,
   * которому позвонили, терял ступень ни за что.
   *
   * Правило живёт ЗДЕСЬ, а не в экранах: иначе следующая игра решит по-своему,
   * и мы получим третий знак у той же кнопки.
   */
  aborted?: boolean;
}

export interface LevelOutcome {
  /** Записывать ли партию как пройденную (уходит и в `saveSession`, и в баннер). */
  passed: boolean;
  /** Поднять потолок уровня. */
  raiseLevel: boolean;
  /** Засчитать провал (гистерезис понижения). */
  lowerLevel: boolean;
  /** Какой экран показать: баннер уровня или итог партии. */
  phase: 'cleared' | 'result';
}

/**
 * Пример: `const out = levelOutcome({ isPreset, cleared: finalSpan >= need });`
 * — дальше `out.raiseLevel && lvl.reach(n + 1)`, `out.lowerLevel && lvl.fail()`,
 * `setPhase(out.phase)`.
 */
export function levelOutcome({ isPreset, cleared, aborted }: LevelOutcomeInput): LevelOutcome {
  if (aborted) {
    // Оборванная партия уровень не двигает: досчитать её за человека нельзя,
    // а гадать нечестно.
    return { passed: false, raiseLevel: false, lowerLevel: false, phase: 'result' };
  }
  if (isPreset) {
    // Шаг зарядки не трогает уровень ни вверх, ни вниз и заканчивается итогом
    // партии: зарядка сама уводит на следующий шаг через пару секунд.
    return { passed: false, raiseLevel: false, lowerLevel: false, phase: 'result' };
  }
  return { passed: cleared, raiseLevel: cleared, lowerLevel: !cleared, phase: 'cleared' };
}
