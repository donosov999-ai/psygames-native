/** Ступень лестницы (индекс в `RATING_LADDER`) для уровня. */
function ladderStep(level: number): number {
  const lv = Math.max(1, Math.floor(Number.isFinite(level) ? level : 1));
  for (let i = 0; i < RATING_LADDER.length; i++) {
    if (lv <= (RATING_LADDER[i] as LadderRow).upTo) return i;
  }
  return RATING_LADDER.length - 1;
}

/**
 * Полоса рейтинга уровня. `shift` — сдвиг на ступень лестницы: −1 «полегче», +1
 * «пожёстче». Дороги сдвигают ровно так же, как `roadTier` сдвигает полосу техник,
 * и по той же причине: иначе «полегче» было бы обещанием без вещества.
 */
export function bankRatingForLevel(level: number, shift = 0): number {
  const i = Math.min(RATING_LADDER.length - 1, Math.max(0, ladderStep(level) + Math.round(shift)));
  return (RATING_LADDER[i] as LadderRow).rating;
}

let POOLS: Map<number, BankRow[]> | null = null;

/** Доски полосы. Индекс строится один раз на весь запуск. */
export function bankPool(rating: number): readonly BankRow[] {
  if (!POOLS) {
    POOLS = new Map();
    for (const row of BANK.rows) {
      const key = bandKey(row.r);
      const list = POOLS.get(key);
      if (list) list.push(row);
      else POOLS.set(key, [row]);
    }
  }
  return POOLS.get(bandKey(rating)) ?? [];
}

/** Доска банка в наших типах: сама задача, её решение и рейтинг, по которому она выбрана. */
export interface BankBoard {
  readonly puzzle: Cell[][];
  readonly solution: Cell[][];
  /** Рейтинг Sukaku Explainer — тот самый, по которому доска попала в свою полосу. */
  readonly rating: number;
  /** Место доски в полосе и размер полосы — для разбора и для проб. */
  readonly index: number;
  readonly poolSize: number;
  /** Пустых клеток на доске. У банка их 44–58, а не столько, сколько просит `levelConfig`. */
  readonly blanks: number;
}

function parseBoard(p: string): Cell[][] {
  const grid: Cell[][] = [];
  for (let r = 0; r < BANK_N; r++) {
    const row: Cell[] = [];
    for (let c = 0; c < BANK_N; c++) row.push(p.charCodeAt(r * BANK_N + c) - 48);
    grid.push(row);
  }
  return grid;
}

/**
 * Решение доски. Считается перебором ядра, а не берётся из банка: банк хранит только
 * задачи, а сверять ввод игрока не с чем, кроме решения.
 *
 * ⚠️ Перебор в ядре ходит по кандидатам в случайном порядке, но результат от этого не
 * зависит: у каждой доски банка решение РОВНО ОДНО (проверено при закладке и заново
 * нашим собственным перебором в гейте), а значит найдётся именно оно, каким бы ни был
 * порядок обхода. Случайность здесь влияет на скорость, а не на ответ.
 */
function solutionOf(puzzle: Cell[][]): Cell[][] {
  const grid = puzzle.map((row) => [...row]);
  if (!solve(grid, BANK_N, BANK_BR, BANK_BC, 'none')) {
    throw new Error('sudoku-bank: доска банка не решается — банк повреждён');
  }
  return grid;
}

/** Доска банка БЕЗ решения: сама задача, её рейтинг и место в полосе. */
export type BankPick = Omit<BankBoard, 'solution'>;

/**
 * 🔴 ЕДИНСТВЕННЫЙ ВЫБОР ДОСКИ. Уровень выбирает ПОЛОСУ, зерно — доску внутри полосы.
 *
 * Одно и то же зерно на одном и том же уровне даёт одну и ту же доску: человек,
 * вернувшийся на пройденный уровень, получит ровно ту задачу, что и в первый раз.
 * Разные зёрна на одном уровне почти наверняка дают разные доски — в полосе сорок штук.
 *
 * ⚠️ БЕЗ РЕШЕНИЯ — И ЭТО НЕ ЭКОНОМИЯ РАДИ ЭКОНОМИИ. Решение считается перебором
 * (12 мс на трудной доске), а карточка уровня спрашивает «сколько тут пустых клеток»
 * на каждой перерисовке экрана настроек. Перебор в такт перерисовке — это заметный
 * подтормаживающий экран ради числа, которое читается из строки банка даром.
 */
export function bankPickForLevel(level: number, seed: string, shift = 0): BankPick {
  const rating = bankRatingForLevel(level, shift);
  const pool = bankPool(rating);
  if (pool.length === 0) throw new Error(`sudoku-bank: полоса ${rating} пуста`);
  const lv = Math.max(1, Math.floor(Number.isFinite(level) ? level : 1));
  // Уровень входит в зерно намеренно: без него весь путь игрока раздавался бы одним и
  // тем же местом в полосе, и доски соседних уровней стояли бы рядом в исходном банке.
  const rng = makeRng(`sudoku-bank|${normalizeSeed(seed)}|L${lv}|R${bandKey(rating)}`);
  const index = Math.min(pool.length - 1, Math.max(0, Math.floor(rng() * pool.length)));
  const row = pool[index] as BankRow;
  const puzzle = parseBoard(row.p);
  let blanks = 0;
  for (let r = 0; r < BANK_N; r++) for (let c = 0; c < BANK_N; c++) if ((puzzle[r] as Cell[])[c] === 0) blanks++;
  return { puzzle, rating: row.r, index, poolSize: pool.length, blanks };
}

/** 🔴 ЕДИНСТВЕННЫЙ ВХОД ЗА ДОСКОЙ ДЛЯ ПАРТИИ: тот же выбор плюс решение. */
export function bankBoardForLevel(level: number, seed: string, shift = 0): BankBoard {
  const pick = bankPickForLevel(level, seed, shift);
  return { ...pick, solution: solutionOf(pick.puzzle) };
}
