/** Запись банка: `p` — 81 цифра доски (ноль = пусто), `r` — рейтинг Sukaku Explainer. */
interface BankRow {
  readonly p: string;
  readonly r: number;
}

interface BankFile {
  readonly _source: string;
  readonly _license: string;
  readonly _rating_by: string;
  readonly _sampled: string;
  readonly _method: string;
  readonly _validated: string;
  readonly bands: readonly number[];
  readonly rows: readonly BankRow[];
}

const BANK = bankFile as BankFile;

