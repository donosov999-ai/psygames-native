/** Размер классической доски. Всё, что лежит в банке, — только эта. */
export const BANK_N = 9;
export const BANK_BR = 3;
export const BANK_BC = 3;

/**
 * Ключ полосы: рейтинг в десятых долях целым числом. Сравнивать дробные рейтинги
 * на равенство можно, но незачем — целый ключ снимает вопрос о представлении чисел
 * раз и навсегда.
 */
const bandKey = (rating: number): number => Math.round(rating * 10);

