export const N = 9;
const CELLS = N * N;
const ALL = 0x1ff;

/**
 * Историческое имя порога: 17 — доказанный минимум подсказок, при котором судоку 9×9
 * ещё имеет единственное решение. Сам порог открытия теперь считается от РЕАЛЬНОГО
 * числа дырок конкретной сетки (см. FractalChild.unlockCells): число дырок больше не
 * задаётся сверху, его определяет логика, и фиксированные 17 могли бы оказаться
 * недостижимыми (порог выше числа выколотых клеток = сетка не открывается никогда).
 */
export const UNLOCK_CELLS = 17;

/** Клетка, чьё значение уходит родителю. Центр — потому что он дальше всех от краёв. */
export const FEED_CELL: readonly [number, number] = [4, 4];
const FEED_INDEX = FEED_CELL[0] * N + FEED_CELL[1];

export type Board = number[][];

/** Одна дочерняя сетка партии. */
export interface FractalChild {
  solution: Board;
  puzzle: Board;
  /** Клетка КОРНЯ, которую эта сетка открывает. */
  feedsCell: [number, number];
  /** Сколько клеток реально выколото — число получается из логики, а не задаётся. */
  blanks: number;
  /** Порог открытия именно этой сетки. Всегда ≤ blanks, иначе открыть её нельзя. */
  unlockCells: number;
  /** Самая сложная техника, без которой сетку не добить. */
  tier: number;
}

/**
 * ПОРТАЛ — ОДНА КЛЕТКА, ЖИВУЩАЯ В ДВУХ ПАЗЛАХ СРАЗУ.
 *
 * Не связь между клетками одной доски (такое в жанре есть: клоны, «квадруплеты»,
 * пересечения самурая) — а стык ДВУХ РАЗНЫХ сеток, у которых нет ни одной общей
 * строки, колонки или блока. Цифра в клетке `a` дочерней `from` и цифра в клетке `b`
 * дочерней `to` — это одна и та же цифра. В задании она НЕ НАПЕЧАТАНА ни там, ни там.
 *
 * ⚠️ ЧТО ИМЕННО ПЕРЕНОСИТ ПОРТАЛ — НЕ ЦИФРУ, А ОГРАНИЧЕНИЕ. Ради цифры портал был бы
 * лишним: доставка готового ответа с соседней доски — это подсказка, а не приём. Здесь
 * обе стороны выколоты так, что КАЖДАЯ порознь неоднозначна: в сетке `from` клетка
 * допускает, скажем, 2, 5 или 7, в сетке `to` — 5 или 8. Ни одна доска ответа не знает.
 * Пересечение допустимых наборов даёт 5 — и это вывод, которого нет НИ В ОДНОМ из двух
 * пазлов, он существует только между ними. Ради него всё и затевалось.
 *
 * ⚠️ ЕДИНСТВЕННОСТЬ РЕШЕНИЯ ЭТИМ НЕ ЛОМАЕТСЯ, А ДОКАЗЫВАЕТСЯ (см. portalPairOk):
 * число решений пары = Σ по цифрам v от (решений `from` при a=v) × (решений `to` при
 * b=v). Генератор берёт пару, только если это ровно 1. Порталы не пересекаются
 * клетками — у каждой дочерней не больше одного конца, — поэтому решения партии
 * перемножаются по независимым парам, и «одно на пару» даёт одно на партию.
 */
export interface FractalPortal {
  /** Номера двух дочерних сеток, которые сшивает портал. */
  from: number;
  to: number;
  /** Клетка внутри сетки from: [строка, столбец]. */
  fromCell: [number, number];
  /** Клетка внутри сетки to. */
  toCell: [number, number];
  /** Цифра, общая для обеих клеток. Хранится ради подсветки ошибки и гейтов. */
  digit: number;
}

export interface FractalPuzzle {
  /** Корневая сетка: то, что человек собирает в итоге. */
  root: {
    solution: Board;
    puzzle: Board;
    blanks: number;
    tier: number;
    /**
     * Правда ли корень НЕЛЬЗЯ добить без цифр снизу. Если бы можно было, девять
     * дочерних оказались бы декорацией: игрок закрыл бы корень напрямую.
     */
    needsChildren: boolean;
  };
  children: FractalChild[];
  /**
   * Порталы партии. Пусто на первой ступени (уровни 1–5): новую механику не сваливают
   * на человека, который ещё не понял старую.
   */
  portals: FractalPortal[];
  level: number;
}

// ─────────────────────── таблицы и зоны (считаются один раз) ───────────────────────

const BIT_TO_DIGIT = new Int8Array(512);
for (let d = 1; d <= N; d++) BIT_TO_DIGIT[1 << (d - 1)] = d;

const POPCOUNT = new Int8Array(512);
for (let m = 1; m < 512; m++) POPCOUNT[m] = POPCOUNT[m >> 1] + (m & 1);

const boxOf = (i: number) => (((i / 27) | 0) * 3) + (((i % 9) / 3) | 0);

/**
 * Маски позиций внутри зоны для техники «связанные кандидаты»: три позиции подряд
 * (в блоке — строка блока, в строке — клетки одного блока) и три через две
 * (в блоке — столбец блока). Считаются один раз, чтобы техника не собирала массивы.
 */
const TRIPLE_ROW = [0b000000111, 0b000111000, 0b111000000];
const TRIPLE_COL = [0b001001001, 0b010010010, 0b100100100];

/** Рабочий буфер техники «голая пара/тройка» — чтобы не аллоцировать массив на вызов. */
const SUBSET_BUF = new Int8Array(9);

/**
 * Буферы верхних техник. Маска ПОЗИЦИЙ (0..8) внутри зоны/линии, а не массив клеток:
 * техники зовутся десятки тысяч раз за партию, и push/filter здесь стоили бы дороже
 * самой логики — ровно та же причина, по которой на маски переведена `locked`.
 */
const HIDDEN_SPOTS = new Int32Array(9);   // позиции каждой цифры внутри зоны
const LINE_SPOTS = new Int32Array(9);     // позиции цифры внутри каждой строки (столбца)

/** 27 зон: девять строк, девять столбцов, девять блоков. */
const UNITS: number[][] = (() => {
  const u: number[][] = [];
  for (let r = 0; r < N; r++) u.push(Array.from({ length: N }, (_, c) => r * N + c));
  for (let c = 0; c < N; c++) u.push(Array.from({ length: N }, (_, r) => r * N + c));
  for (let br = 0; br < 3; br++) for (let bc = 0; bc < 3; bc++) {
    const cells: number[] = [];
    for (let i = 0; i < 3; i++) for (let j = 0; j < 3; j++) cells.push((br * 3 + i) * N + bc * 3 + j);
    u.push(cells);
  }
  return u;
})();

/** 20 «соседей» клетки: своя строка, свой столбец, свой блок. */
const PEERS: Int8Array[] = (() => {
  const p: Int8Array[] = [];
  for (let i = 0; i < CELLS; i++) {
    const r = (i / N) | 0, c = i % N, b = boxOf(i);
    const set = new Set<number>();
    for (let k = 0; k < N; k++) { set.add(r * N + k); set.add(k * N + c); }
    for (let k = 0; k < CELLS; k++) if (boxOf(k) === b) set.add(k);
    set.delete(i);
    p.push(Int8Array.from(set));
  }
  return p;
})();

// ─────────────────────── быстрый перебор: сколько решений ───────────────────────

/**
 * Число решений, но не больше limit. Битовые маски + выбор клетки с наименьшим числом
 * кандидатов: 0.037 мс на прогон против 2.65 мс у штатного countSolutions ядра
 * (замер 19.08 на 200 досках, вердикты совпали 200/200). Разница в 70 раз и решает,
 * можно ли честно генерировать на телефоне.
 */
export function countSolutionsFast(flat: Int8Array, limit = 2): number {
  const grid = Int8Array.from(flat);
  const rows = new Int32Array(N), cols = new Int32Array(N), box = new Int32Array(N);
  for (let i = 0; i < CELLS; i++) {
    const v = grid[i];
    if (!v) continue;
    const m = 1 << (v - 1), r = (i / N) | 0, c = i % N, b = boxOf(i);
    if ((rows[r] | cols[c] | box[b]) & m) return 0;   // уже противоречие
    rows[r] |= m; cols[c] |= m; box[b] |= m;
  }
  let count = 0;
  const walk = (): boolean => {   // true = хватит, дошли до limit
    let bi = -1, bm = 0, bn = N + 1;
    for (let i = 0; i < CELLS; i++) {
      if (grid[i]) continue;
      const m = ALL & ~(rows[(i / N) | 0] | cols[i % N] | box[boxOf(i)]);
      if (m === 0) return false;
      const n = POPCOUNT[m];
      if (n < bn) { bn = n; bi = i; bm = m; if (n === 1) break; }
    }
    if (bi < 0) return ++count >= limit;
    const r = (bi / N) | 0, c = bi % N, b = boxOf(bi);
    let m = bm;
    while (m) {
      const t = m & -m; m ^= t;
      grid[bi] = BIT_TO_DIGIT[t]; rows[r] |= t; cols[c] |= t; box[b] |= t;
      const stop = walk();
      grid[bi] = 0; rows[r] ^= t; cols[c] ^= t; box[b] ^= t;
      if (stop) return true;
    }
    return false;
  };
  walk();
  return count;
}

/**
 * Достроить доску до решения. Тот же обход, что в countSolutionsFast, только останов
 * на первом же ответе и с возвратом заполненной сетки.
 *
 * ⚠️ ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ fill(). Замер 19.08: fill() перебирает клетки ПОДРЯД
 * и на доске в 56 дырок (заготовка верхней ступени) уходит в глубокий откат — партия
 * тридцатого уровня собиралась 2029 мс при жалких 120 прогонах логики, то есть всё
 * время уходило именно сюда. Выбор клетки с наименьшим числом кандидатов убирает
 * откаты: те же партии — 60–90 мс. Ровно та же разница, из-за которой здесь свой
 * countSolutionsFast вместо штатного перебора ядра.
 */
export function solveFast(flat: Int8Array): Int8Array | null {
  const grid = Int8Array.from(flat);
  const rows = new Int32Array(N), cols = new Int32Array(N), box = new Int32Array(N);
  for (let i = 0; i < CELLS; i++) {
    const v = grid[i];
    if (!v) continue;
    const m = 1 << (v - 1), r = (i / N) | 0, c = i % N, b = boxOf(i);
    if ((rows[r] | cols[c] | box[b]) & m) return null;
    rows[r] |= m; cols[c] |= m; box[b] |= m;
  }
  const walk = (): boolean => {
    let bi = -1, bm = 0, bn = N + 1;
    for (let i = 0; i < CELLS; i++) {
      if (grid[i]) continue;
      const m = ALL & ~(rows[(i / N) | 0] | cols[i % N] | box[boxOf(i)]);
      if (m === 0) return false;
      const n = POPCOUNT[m];
      if (n < bn) { bn = n; bi = i; bm = m; if (n === 1) break; }
    }
    if (bi < 0) return true;   // пустых не осталось — доска собрана
    const r = (bi / N) | 0, c = bi % N, b = boxOf(bi);
    let m = bm;
    while (m) {
      const t = m & -m; m ^= t;
      grid[bi] = BIT_TO_DIGIT[t]; rows[r] |= t; cols[c] |= t; box[b] |= t;
      if (walk()) return true;
      grid[bi] = 0; rows[r] ^= t; cols[c] ^= t; box[b] ^= t;
    }
    return false;
  };
  return walk() ? grid : null;
}

