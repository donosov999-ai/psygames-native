/**
 * ТЕКСТ ОТПРАВКИ: СОСТОЯНИЕ ПРОТИВ ЖИВОГО ПОЛЯ.
 *
 * 🔴 ЗАЧЕМ. Замер 06.09.2026 по базе отзывов: на iOS каждый ВОСЬМОЙ отчёт
 * приходил ОДНИМ СЛОВОМ — 10 из 84 (12%), против 1 из 153 на Android (1%) и
 * 0 из 54 в вебе. Слова не случайные: «I», «The» — начала английских фраз, то
 * есть в базу уезжало ПЕРВОЕ СЛОВО набранного, а остальное терялось. Человек
 * при этом видел в поле весь свой текст и был уверен, что рассказал.
 *
 * Точную причину без живого айфона не поймать (подозрение на предиктивный ввод
 * iOS, который дописывает слово мимо `onChangeText`). Поэтому чинится КЛАСС
 * дефекта: перед отправкой берётся БОЛЬШЕЕ из двух — состояние и то, что
 * реально лежит в поле. Хуже, чем было, не станет ни в одном случае: нет поля
 * — уедет состояние, отстало состояние — уедет набранное.
 *
 * ⚠️ БОЛЬШЕЕ, А НЕ «ПОЛЕ ВСЕГДА». Поле может быть уже очищено (после
 * доставки), может быть недоступно в нативной сборке без DOM, и может нести
 * пробелы вместо текста. Сравнение по длине без пробелов — единственное, что
 * верно во всех трёх случаях.
 */
export function текстОтправки(состояние: string, поле: unknown): string {
  const изПоля = typeof поле === 'string' ? поле : '';
  return изПоля.trim().length > состояние.trim().length ? изПоля : состояние;
}
