/**
 * ОБЩАЯ ПАУЗА ИГРЫ, ПОКА ЧЕЛОВЕК ПИШЕТ ОТЗЫВ.
 *
 * 🔴 ЗАЧЕМ. Репорт тестировщицы 18.08.2026 дословно: «И пока я писала отзыв,
 * игра моя закончилась оказывается, когда пишешь отзыв таймер продолжает
 * работать. Несправедливость».
 *
 * Это хуже обычного бага. Отзывы — ЕДИНСТВЕННЫЙ канал, по которому мы вообще
 * узнаём о проблемах, и мы сделали так, что пожаловаться стоит человеку партии.
 * Пока это чинится не полностью — цена репорта прямо гасит желание его писать.
 *
 * ⚠️ ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ПРОПС. Виджет отзыва живёт в корне
 * приложения, а таймеры — внутри 60+ экранов игр. Тянуть через дерево пропсов
 * значит править каждый экран и забыть половину. Здесь — один счётчик и
 * подписка: кто умеет замирать, тот подписывается сам.
 *
 * СЧЁТЧИК, А НЕ ФЛАГ: поверх отзыва может открыться ещё что-то (подтверждение,
 * системный диалог), и снятие одной паузы не должно отпускать все.
 */
type Listener = (paused: boolean) => void;

let _depth = 0;
const _listeners = new Set<Listener>();

function emit() {
  const p = _depth > 0;
  // Учёт простоя ведём ЗДЕСЬ, а не в подписчиках: часы обязаны замереть даже
  // если ни одна игра сейчас не открыта — иначе после возврата в игру
  // накопленная пауза потеряется.
  if (p) { if (_pausedAt === null) _pausedAt = Date.now(); }
  else if (_pausedAt !== null) { _pausedTotal += Date.now() - _pausedAt; _pausedAt = null; }
  _listeners.forEach((l) => { try { l(p); } catch { /* слушатель умер — не наша беда */ } });
}

/** Игра замирает. Вернёт функцию снятия — вызывать ровно один раз. */
export function holdGame(): () => void {
  _depth += 1;
  if (_depth === 1) emit();
  let released = false;
  return () => {
    if (released) return;      // двойное снятие не должно уводить счётчик в минус
    released = true;
    _depth = Math.max(0, _depth - 1);
    if (_depth === 0) emit();
  };
}

/** Идёт ли сейчас пауза. */
export function isGameHeld(): boolean { return _depth > 0; }

/** Подписка на паузу. Возвращает отписку. */
export function onGameHold(l: Listener): () => void {
  _listeners.add(l);
  return () => { _listeners.delete(l); };
}

/**
 * 🔴 ПРОСЬБА «ОТКРОЙ МЕНЮ ПАУЗЫ» — ДЛЯ ИГРЫ, КОТОРАЯ НА ВРЕМЯ ПАРТИИ ЗАКРЫВАЕТ ШАПКУ.
 *
 * Повод — Денис 16.09.2026: «для раннера — чтобы когда игра запускается, был
 * полноэкранный режим». Дорога ложится слоем поверх всего каркаса, и кнопка паузы
 * каркаса оказывается под ним. Игре нужна своя кнопка — но пауза обязана остаться
 * ПАУЗОЙ КАРКАСА.
 *
 * ⚠️ ПОЧЕМУ НЕ `holdGame()` ИЗ ИГРЫ. Меню паузы видно, пока держит хоть кто-то, а
 * его кнопки снимают только СВОЮ задержку каркаса (`pauseHoldRef`) и закрывают меню
 * сами. Задержка, взятая игрой, после «Продолжить» осталась бы висеть: меню закрыто,
 * часы стоят, игра замёрзла — ровно класс отчёта «Релакс» от 15.09.2026. А пункт
 * «Выйти» с вопросом «вы уверены?» вообще не зовёт `onPress` игры, и снять её там
 * было бы нечем. Поэтому игра только ПРОСИТ, а задержку берёт каркас тем же путём,
 * что его кнопка «II».
 *
 * Возвращает `false`, если просить некого (каркас не смонтирован) — игра тогда
 * не делает вид, что пауза случилась.
 */
type PauseMenuRequest = () => void;
/**
 * ⚠️ ОТВЕЧАЕТ ТОЛЬКО ВЕРХНИЙ КАРКАС, А НЕ ВСЕ ПОДПИСАННЫЕ.
 *
 * Экран, открытый через `router.push`, не размонтирует предыдущий: так
 * судоку открывает «Самурая», фрактал — «Глубину». Каркасов тогда смонтировано
 * два, и оба подписаны. Разошли просьбу всем — задержку возьмёт и скрытый
 * каркас. «Продолжить» в видимом меню снимет только свою, чужая останется, и
 * игра замёрзнет при закрытом меню. Это ровно тот класс, от которого просьба
 * заведена. Поэтому стопка: отвечает последний смонтированный, то есть видимый.
 */
const _menuRequests: PauseMenuRequest[] = [];

export function requestPauseMenu(): boolean {
  const верхний = _menuRequests[_menuRequests.length - 1];
  if (!верхний) return false;
  try { верхний(); } catch { /* слушатель умер — не наша беда */ }
  return true;
}

export function onPauseMenuRequest(l: PauseMenuRequest): () => void {
  _menuRequests.push(l);
  return () => {
    const i = _menuRequests.lastIndexOf(l);
    if (i >= 0) _menuRequests.splice(i, 1);
  };
}

/**
 * ИГРОВЫЕ ЧАСЫ. То же самое `Date.now()`, но во время паузы они стоят.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНО ОТ `useHeldClock`. Хук хорош внутри одного компонента, но
 * замена в 37 экранах, где время считается по-разному (где-то от старта раунда,
 * где-то от старта партии, где-то два отсчёта сразу), потребовала бы разбирать
 * каждый. `gameNow()` подставляется вместо `Date.now()` один в один — и точка
 * старта, и текущий момент едут по одним часам, значит разность автоматически
 * становится игровым временем.
 *
 * ⚠️ ОБА КОНЦА ОБЯЗАНЫ БЫТЬ НА ОДНИХ ЧАСАХ. `gameNow() - startedAtWallClock`
 * даст мусор: начало по настенным, конец по игровым. Меняя файл, меняем ВСЕ
 * `Date.now()`, которые участвуют в измерении времени, а не первый попавшийся.
 *
 * Часы монотонные: они не отматывают назад, а лишь не идут, пока держат паузу.
 */
let _pausedTotal = 0;
let _pausedAt: number | null = null;

export function gameNow(): number {
  /**
   * 🔴 ОДНО ЧТЕНИЕ НАСТЕННЫХ ЧАСОВ, А НЕ ДВА. Было `Date.now()` в простое и ещё раз
   * в ответе: если между чтениями проходила миллисекунда, часы НА ПАУЗЕ сдвигались
   * на 1 мс. Под нагрузкой CI это и происходило — проба pause-menu-everywhere
   * («пока меню открыто, часы партии стоят») падала «сдвиг часов 1 мс, стоят: false»
   * только в полном прогоне и держала выпуск 2.54.13. Задача ecfa89b6.
   */
  const now = Date.now();
  const held = _pausedTotal + (_pausedAt !== null ? now - _pausedAt : 0);
  return now - held;
}

/**
 * 🔴 ТАЙМЕРЫ ПАРТИИ, КОТОРЫЕ СТОЯТ НА ПАУЗЕ: `gameTimeout` / `gameInterval`.
 *
 * ПОВОД — замер раздела «Внимание» 16.09.2026, Струп L1: меню паузы открыто, а счётчик
 * проб идёт 2/20 → 3/20 → 4/20 за 5 секунд, и каждая пропущенная проба пишется ошибкой.
 * Человек стоит на паузе и проигрывает.
 *
 * ⚠️ ПОЧЕМУ ЧАСОВ `gameNow()` МАЛО. Они честно вычитают паузу из ВРЕМЕНИ РЕАКЦИИ, но
 * пробы сменяет обычный `setTimeout`, а он про паузу не знает ничего. Подписаны на
 * паузу 2 экрана из 95 (`chess-blind`, `number-run`), `setTimeout` стоит в 61, а
 * `setInterval` — в 41. Чинить каждый экран своим способом — девяносто разных
 * реализаций одного правила, поэтому правило живёт здесь, одно.
 *
 * КАК МЕНЯТЬ — построчно, форма та же, что у `setTimeout`:
 *     ref.current = setTimeout(fn, ms)   →   ref.current = gameTimeout(fn, ms)
 *     clearTimeout(ref.current)          →   clearGameTimer(ref.current)
 *
 * Срок считается по ИГРОВЫМ часам: на паузе таймер снят, после «Продолжить» ставится
 * заново ровно на остаток. Таймер, заведённый во время паузы, начнёт идти после неё.
 * Для анимаций интерфейса (вспышка ответа, тряска) это не нужно — только для того,
 * что меняет партию: смена пробы, окно ответа, обратный отсчёт, появление целей.
 */
export interface GameTimer {
  /** Снять таймер. Повторный вызов ничего не делает. */
  cancel(): void;
}

function gameTimer(fn: () => void, ms: number, repeat: boolean): GameTimer {
  const period = Math.max(0, Number.isFinite(ms) ? ms : 0);
  let due = gameNow() + period;
  let timer: ReturnType<typeof setTimeout> | null = null;
  let off: (() => void) | null = null;
  let done = false;

  const disarm = () => {
    if (timer !== null) { clearTimeout(timer); timer = null; }
  };
  const finish = () => {
    done = true;
    disarm();
    if (off) { off(); off = null; }
  };
  const arm = () => {
    disarm();
    if (done || isGameHeld()) return;
    timer = setTimeout(fire, Math.max(0, due - gameNow()));
  };
  function fire(): void {
    timer = null;
    if (done) return;
    // Сработал раньше срока по игровым часам (пауза пришлась между постановкой
    // и срабатыванием) или прямо на паузе — не стреляем, ждём остаток.
    if (isGameHeld()) return;
    if (gameNow() < due) { arm(); return; }
    if (repeat) { due += period > 0 ? period : 1; arm(); } else finish();
    fn();
  }

  off = onGameHold((held) => { if (held) disarm(); else arm(); });
  arm();
  return { cancel: finish };
}

/** Как `setTimeout`, но на паузе стоит и после неё дожидается остатка. */
export function gameTimeout(fn: () => void, ms: number): GameTimer {
  return gameTimer(fn, ms, false);
}

/**
 * Как `setInterval`, но на паузе стоит. Тики отсчитываются от срока, а не от момента
 * срабатывания: медленный кадр не сдвигает всю дальнейшую сетку.
 */
export function gameInterval(fn: () => void, ms: number): GameTimer {
  return gameTimer(fn, ms, true);
}

/** Как `clearTimeout`: принимает и пустой ref. */
export function clearGameTimer(t: GameTimer | null | undefined): void {
  t?.cancel();
}

/** Сколько всего простояли на паузе — для отладки и тестов. */
export function heldTotalMs(): number {
  return _pausedTotal + (_pausedAt !== null ? Date.now() - _pausedAt : 0);
}

/** Сброс часов — только для тестов, в приложении не звать. */
export function __resetGameClock(): void { _pausedTotal = 0; _pausedAt = null; }
