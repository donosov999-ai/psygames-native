/**
 * seed — воспроизводимая случайность: одна и та же строка даёт одну и ту же доску.
 *
 * ЗАЧЕМ ДВА РАЗНЫХ ПРИМЕНЕНИЯ, И ВТОРОЕ ВАЖНЕЕ ПЕРВОГО.
 *
 * 1. Соревнование без сервера. Поделился строкой — у друга та же доска, и результаты
 *    сравнимы. Ни регистрации, ни бэкенда: строка и есть вся синхронизация.
 *
 * 2. ⚠️ ЗАГОТОВКИ ДЛЯ МЕГА-БОССОВ. Доска самурая собирается перебором пяти сцепленных
 *    сеток, фрактала — десяти. На телефоне это заметная пауза, а на слабом — не пауза,
 *    а подозрение, что приложение зависло. С сидом доску можно собрать заранее, положить
 *    рядом одну строку вместо гигантского JSON и восстановить её на устройстве за то же
 *    время. Без этого длинные режимы упираются в генерацию.
 *
 * ПОЧЕМУ СВОЙ ГЕНЕРАТОР, А НЕ Math.random. Math.random невозможно засеять — его нельзя
 * попросить повторить последовательность. Здесь mulberry32: тридцать строк, проверяемый,
 * и одинаковый на всех платформах. Криптостойкость не нужна и была бы вредна — нам нужна
 * ровно предсказуемость.
 */

/** Строка → 32-битное зерно. FNV-1a: короткий, равномерный, без зависимостей. */
export function hashSeed(seed: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

export type Rng = () => number;

/** Генератор из строки. Одна строка — одна и та же последовательность, всегда. */
export function makeRng(seed: string): Rng {
  let a = hashSeed(seed) || 1;   // ноль запирает mulberry32 на месте
  return () => {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Тасовка Фишера-Йетса на заданном генераторе. Исходный массив не трогаем. */
export function seededShuffle<T>(arr: readonly T[], rng: Rng): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * Словарь для читаемых сидов. Короткие, различимые на слух и без похожих пар — строку
 * будут диктовать голосом и набирать руками, а не копировать.
 */
const WORDS = [
  'сокол', 'кедр', 'янтарь', 'риф', 'муссон', 'кварц', 'вереск', 'фьорд',
  'агат', 'бриз', 'дюна', 'иней', 'лагуна', 'нефрит', 'оникс', 'пламя',
] as const;

/** Человекочитаемый сид вида «кедр-муссон-47». Читается вслух и набирается без ошибок. */
export function makeReadableSeed(rng: Rng = Math.random): string {
  const a = WORDS[Math.floor(rng() * WORDS.length)];
  const b = WORDS[Math.floor(rng() * WORDS.length)];
  const n = Math.floor(rng() * 90) + 10;
  return `${a}-${b}-${n}`;
}

/**
 * Привести введённое к каноническому виду: регистр, пробелы и лишние дефисы человек
 * наберёт по-своему, а доска обязана получиться та же. Без этого «Кедр-Муссон-47»
 * и «кедр муссон 47» дали бы разные задачи, и обмен сидами сломался бы молча.
 */
export function normalizeSeed(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/[\s_]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-|-$/g, '');
}
