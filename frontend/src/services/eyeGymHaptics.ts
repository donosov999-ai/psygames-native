/** Момент подхода, на который положен отклик. */
export type EyeGymMoment = 'start' | 'stepChange' | 'finish';

/** Сила отклика: разная, иначе три события сливаются в одно ощущение. */
export type EyeGymStrength = 'medium' | 'tap' | 'success';

export const EYE_GYM_HAPTICS: Record<EyeGymMoment, EyeGymStrength> = {
  start: 'medium',      // начали — заметный толчок
  stepChange: 'tap',    // сменилось упражнение — короткий тычок
  finish: 'success',    // закончили — узнаваемый узор успеха
};

/**
 * Нужен ли тычок при переходе на шаг `next`.
 *
 * ⚠️ На ПЕРВОМ шаге — нет: там только что отработал отклик начала, и два
 * подряд читаются как сбой, а не как два события. Отсюда `prev < 0`.
 */
export function eyeGymStepBuzzes(prev: number, next: number): boolean {
  if (prev === next) return false;   // тот же шаг — перерисовка, не переход
  return prev >= 0;
}
