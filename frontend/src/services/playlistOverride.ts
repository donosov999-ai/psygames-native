const ИЗВЕСТНЫЕ_ИГРЫ = new Set(GAMES.map((g) => g.id));
const МАРШРУТ_ИГРЫ = new Map(GAMES.map((g) => [g.id, g.route]));
/** Экраны, которые в приложении действительно есть, — по ним сверяются карточки из файла. */
const ИЗВЕСТНЫЕ_МАРШРУТЫ = new Set(GAMES.map((g) => g.route));

/** Шаг зарядки принимается, только если его игра есть в сборке. */
function отобратьШаги(
  шаги: unknown,
  профиль: string,
  когда: string,
  отброшено: string[],
): PlaylistStep[] | undefined {
  if (!Array.isArray(шаги)) return undefined;
  const годные: PlaylistStep[] = [];
  for (const шаг of шаги) {
    const id = (шаг as PlaylistStep)?.game_id;
    if (typeof id !== 'string' || !ИЗВЕСТНЫЕ_ИГРЫ.has(id)) {
      отброшено.push(`${профиль} · ${когда}: нет такой игры «${String(id)}»`);
      continue;
    }
    /**
     * 🔴 МАРШРУТ БЕРЁТСЯ ИЗ КАТАЛОГА, А НЕ ИЗ ФАЙЛА.
     *
     * Две причины, обе замерены 13.09.2026.
     * · Прибитый в файле маршрут ПРОТУХАЕТ: переедет экран в новой сборке — и
     *   старый файл поведёт человека в «Unmatched Route», причём молча.
     * · Размер. В сетке 7 × 4 × 3 на тринадцать профилей 11 454 шага, и маршрут
     *   в каждом — треть файла: 1,29 МБ против 0,95 МБ после отказа от него.
     *   Файл лежит в AsyncStorage, а на вебе это localStorage с лимитом около
     *   пяти мегабайт на источник — запас тут не лишний.
     *
     * `game_id` уже проверен по каталогу строкой выше, значит маршрут известен.
     */
    годные.push({ ...(шаг as PlaylistStep), game_route: МАРШРУТ_ИГРЫ.get(id)! });
  }
  return годные;
}

/**
 * Разобрать раздел развилок.
 *
 * 🔴 ЭЛЕМЕНТ — ЛИБО МАРШРУТ, ЛИБО ОПИСАНИЕ КАРТОЧКИ (13.09.2026). Маршрут строкой
 * означает заводскую карточку и проверяется по реестру; объект `{маршрут, имя,
 * описание, значок}` описывает новую — так сорок две головоломки Тэтхэма
 * раскладываются по развилкам файлом, без правки кода. Вопрос Дениса, из-за
 * которого это и сделано: «почему добавка в хабы — это код? это же фильтр
 * отображения, как и состав профиля».
 */
function разобратьХабы(
  сырые: unknown,
  чей: string,
  отброшено: string[],
): Record<string, ЭлементХаба[]> | null {
  if (!сырые || typeof сырые !== 'object') return null;
  const принятые: Record<string, ЭлементХаба[]> = {};
  for (const [хаб, маршруты] of Object.entries(сырые as Record<string, unknown>)) {
    const заводские = заводскиеКарточкиХаба(хаб);
    if (заводские.length === 0) { отброшено.push(`${чей}: нет развилки «${хаб}»`); continue; }
    if (!Array.isArray(маршруты)) { отброшено.push(`${чей} · ${хаб}: список не читается`); continue; }
    const годные: ЭлементХаба[] = [];
    for (const м of маршруты) {
      /* Строка — заводская карточка: маршрут обязан быть в реестре. */
      if (typeof м === 'string') {
        if (заводские.some((c) => c.route === м)) { годные.push(м); continue; }
        отброшено.push(`${чей} · ${хаб}: нет карточки «${м}»`);
        continue;
      }
      /* Объект — карточка, описанная файлом: нужен маршрут и словарный ключ имени. */
      const о = м as { маршрут?: unknown; имя?: unknown; описание?: unknown; значок?: unknown };
      const путь = typeof о?.маршрут === 'string' ? о.маршрут.trim() : '';
      const имя = typeof о?.имя === 'string' ? о.имя.trim() : '';
      if (!путь || !путь.startsWith('/games/')) {
        отброшено.push(`${чей} · ${хаб}: у карточки нет маршрута вида /games/…`);
        continue;
      }
      /**
       * 🔴 МАРШРУТ ОБЯЗАН ВЕСТИ К СУЩЕСТВУЮЩЕЙ ИГРЕ. Придумать экран файлом нельзя:
       * человек нажал бы карточку и получил «Unmatched Route» — та же пустота, от
       * которой защищала прежняя проверка по реестру, только в другом месте.
       */
      const базовый = путь.split('?')[0];
      if (!ИЗВЕСТНЫЕ_МАРШРУТЫ.has(базовый)) {
        отброшено.push(`${чей} · ${хаб}: нет экрана «${базовый}»`);
        continue;
      }
      if (!имя) { отброшено.push(`${чей} · ${хаб}: у карточки «${путь}» нет ключа имени`); continue; }
      годные.push({
        маршрут: путь, имя,
        ...(typeof о.описание === 'string' && о.описание ? { описание: о.описание } : null),
        ...(typeof о.значок === 'string' && о.значок ? { значок: о.значок } : null),
      });
    }
    if (годные.length === 0) {
      отброшено.push(`${чей} · ${хаб}: не осталось ни одной карточки — оставлен заводской`);
      continue;
    }
    принятые[хаб] = годные;
  }
  return Object.keys(принятые).length > 0 ? принятые : null;
}

/**
 * Разобрать файл настроек. Ничего не сохраняет — только проверяет и отвечает,
 * что принято и что отброшено.
 */
export function разобрать(текст: string): РазборСостава {
  const отброшено: string[] = [];
  let файл: ФайлСостава;
  try {
    файл = JSON.parse(текст);
  } catch {
    return { состав: null, наборы: [], порядок: null, хабы: null, замки: null, коллекция: null, ошибка: 'Это не файл настроек: не удалось прочитать JSON.', отброшено, профилейПринято: 0 };
  }
  if (файл?.app !== МЕТКА_ФАЙЛА) {
    return {
      состав: null,
      наборы: [],
      порядок: null,
      хабы: null,
      замки: null,
      коллекция: null,
      ошибка: `Это файл другого рода (${String(файл?.app ?? 'без метки')}). Нужен файл состава профилей.`,
      отброшено,
      профилейПринято: 0,
    };
  }
  if (файл.format !== ВЕРСИЯ_ФОРМАТА) {
    return {
      состав: null,
      наборы: [],
      порядок: null,
      хабы: null,
      замки: null,
      коллекция: null,
      ошибка: `Формат файла ${String(файл.format)}, приложение понимает ${ВЕРСИЯ_ФОРМАТА}.`,
      отброшено,
      профилейПринято: 0,
    };
  }
  if (!файл.профили || typeof файл.профили !== 'object') {
    return { состав: null, наборы: [], порядок: null, хабы: null, замки: null, коллекция: null, ошибка: 'В файле нет раздела «профили».', отброшено, профилейПринято: 0 };
  }

  /* Свои наборы разбираются ПЕРВЫМИ: профили на них ссылаются, и ссылку на
     несуществующий набор надо назвать, а не проглотить. */
  const наборы: НаборУпражнений[] = [];
  const естьНабор = new Set<string>();
  if (Array.isArray(файл.наборы)) {
    for (const сырой of файл.наборы) {
      const id = (сырой as НаборУпражнений)?.id;
      const название = (сырой as НаборУпражнений)?.название;
      if (typeof id !== 'string' || !id.trim()) {
        отброшено.push('набор без id — пропущен');
        continue;
      }
      if (естьНабор.has(id)) {
        отброшено.push(`набор «${id}»: такой id уже был — пропущен`);
        continue;
      }
      const шаги = отобратьШаги((сырой as НаборУпражнений)?.шаги, `набор «${id}»`, 'шаги', отброшено);
      if (!шаги || шаги.length === 0) {
        отброшено.push(`набор «${id}»: не осталось ни одного упражнения — пропущен`);
        continue;
      }
      наборы.push({ id, название: typeof название === 'string' && название.trim() ? название : id, шаги });
      естьНабор.add(id);
    }
  }

  const состав: Record<string, СоставПрофиля> = {};
  for (const [идПрофиля, сырой] of Object.entries(файл.профили)) {
    const принято: СоставПрофиля = {};

    if (сырой?.игры !== undefined) {
      if (сырой.игры === 'all') {
        принято.игры = 'all';
      } else if (Array.isArray(сырой.игры)) {
        const годные = сырой.игры.filter((id) => {
          const ок = typeof id === 'string' && ИЗВЕСТНЫЕ_ИГРЫ.has(id);
          if (!ок) отброшено.push(`${идПрофиля} · состав: нет такой игры «${String(id)}»`);
          return ок;
        });
        /**
         * 🔴 ПУСТОЙ СПИСОК НЕ ПРИНИМАЕТСЯ. Профиль без единой игры выглядит как
         * сломанное приложение, а не как выбор. Если человек правда хочет пустоту —
         * это отдельное решение, а не побочный итог опечатки во всех строках.
         */
        if (годные.length === 0) {
          отброшено.push(`${идПрофиля} · состав: список пуст — оставлен заводской`);
        } else {
          принято.игры = годные;
        }
      } else {
        отброшено.push(`${идПрофиля} · состав: непонятное значение — оставлен заводской`);
      }
    }

    if (Array.isArray(сырой?.убрать)) {
      const годные = сырой.убрать.filter((id) => {
        const ок = typeof id === 'string' && ИЗВЕСТНЫЕ_ИГРЫ.has(id);
        if (!ок) отброшено.push(`${идПрофиля} · убрать: нет такой игры «${String(id)}»`);
        return ок;
      });
      if (годные.length > 0) принято.убрать = годные;
    }

    if (typeof сырой?.зарядка_включена === 'boolean') принято.зарядка_включена = сырой.зарядка_включена;

    const утро = отобратьШаги(сырой?.утро, идПрофиля, 'утро', отброшено);
    if (утро) принято.утро = утро;
    const день = отобратьШаги(сырой?.день, идПрофиля, 'день', отброшено);
    if (день) принято.день = день;
    const вечер = отобратьШаги(сырой?.вечер, идПрофиля, 'вечер', отброшено);
    if (вечер) принято.вечер = вечер;
    const ночь = отобратьШаги(сырой?.ночь, идПрофиля, 'ночь', отброшено);
    if (ночь) принято.ночь = ночь;

    if (сырой?.по_дням && typeof сырой.по_дням === 'object') {
      const дни: Partial<Record<Weekday, PlaylistStep[]>> = {};
      const ИМЯ_ДНЯ = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'];
      for (const [ключДня, шаги] of Object.entries(сырой.по_дням)) {
        const день = Number(ключДня);
        if (!Number.isInteger(день) || день < 0 || день > 6) {
          отброшено.push(`${идПрофиля} · по дням: «${ключДня}» — не день недели (нужно 0…6)`);
          continue;
        }
        const годные = отобратьШаги(шаги, идПрофиля, `${ИМЯ_ДНЯ[день]}`, отброшено);
        if (годные) дни[день as Weekday] = годные;
      }
      if (Object.keys(дни).length > 0) принято.по_дням = дни;
    }

    /**
     * Сетка: день → слот → длина. Каждый неверный ключ называется вслух — молчание
     * здесь читалось бы как «редактор не сохранил», а не как «в файле опечатка».
     */
    if (сырой?.сетка && typeof сырой.сетка === 'object') {
      const сетка: NonNullable<СоставПрофиля['сетка']> = {};
      const ИМЯ_ДНЯ = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'];
      for (const [ключДня, слоты] of Object.entries(сырой.сетка as Record<string, unknown>)) {
        const д = Number(ключДня);
        if (!Number.isInteger(д) || д < 0 || д > 6) {
          отброшено.push(`${идПрофиля} · сетка: «${ключДня}» — не день недели (нужно 0…6)`);
          continue;
        }
        if (!слоты || typeof слоты !== 'object') continue;
        for (const [имяСлота, длины] of Object.entries(слоты as Record<string, unknown>)) {
          if (!(имяСлота in СЛОТ_ПО_ИМЕНИ)) {
            отброшено.push(`${идПрофиля} · сетка ${ИМЯ_ДНЯ[д]}: «${имяСлота}» — не слот (бывают ${Object.keys(СЛОТ_ПО_ИМЕНИ).join(', ')})`);
            continue;
          }
          if (!длины || typeof длины !== 'object') continue;
          for (const [ключДлины, шаги] of Object.entries(длины as Record<string, unknown>)) {
            if (!ДЛИНЫ.includes(ключДлины)) {
              отброшено.push(`${идПрофиля} · сетка ${ИМЯ_ДНЯ[д]}/${имяСлота}: «${ключДлины}» — не длина (бывают ${ДЛИНЫ.join(', ')})`);
              continue;
            }
            const годные = отобратьШаги(шаги, идПрофиля, `сетка ${ИМЯ_ДНЯ[д]}/${имяСлота}/${ключДлины}`, отброшено);
            if (!годные || годные.length === 0) continue;
            ((сетка[ключДня] ||= {})[имяСлота] ||= {})[ключДлины] = годные;
          }
        }
      }
      if (Object.keys(сетка).length > 0) принято.сетка = сетка;
    }

    if (Array.isArray(сырой?.наборы)) {
      const годные = сырой.наборы.filter((id) => {
        const ок = typeof id === 'string' && естьНабор.has(id);
        if (!ок) отброшено.push(`${идПрофиля} · наборы: нет набора «${String(id)}»`);
        return ок;
      });
      if (годные.length > 0) принято.наборы = годные;
    }

    const пр = сырой?.уровень_в_зарядке as ПравилоУровня | undefined;
    if (пр && typeof пр === 'object') {
      const ВИДЫ = ['первый', 'освоенный', 'минус', 'процент'];
      if (!ВИДЫ.includes((пр as { как?: string }).как ?? '')) {
        отброшено.push(`${идПрофиля} · уровень в зарядке: «${String((пр as { как?: string }).как)}» — бывает ${ВИДЫ.join(', ')}`);
      } else if ((пр.как === 'минус' || пр.как === 'процент')
                 && (typeof (пр as { сколько?: unknown }).сколько !== 'number'
                     || !Number.isFinite((пр as { сколько: number }).сколько)
                     || (пр as { сколько: number }).сколько < 0)) {
        отброшено.push(`${идПрофиля} · уровень в зарядке: «${пр.как}» требует число «сколько» от 0`);
      } else {
        принято.уровень_в_зарядке = пр;
      }
    }

    if (Array.isArray(сырой?.главная)) {
      const годные = сырой.главная.filter((id) => {
        const ок = typeof id === 'string' && естьТакойБлок(id);
        if (!ок) отброшено.push(`${идПрофиля} · главная: нет блока «${String(id)}» (есть: ${БЛОКИ_ГЛАВНОЙ.map((б) => б.id).join(', ')})`);
        return ок;
      });
      if (годные.length === 0) отброшено.push(`${идПрофиля} · главная: не осталось ни одного блока — оставлена заводская`);
      else принято.главная = годные;
    }

    const хабыПрофиля = разобратьХабы(сырой?.хабы, `${идПрофиля} · развилки`, отброшено);
    if (хабыПрофиля) принято.хабы = хабыПрофиля;

    if (Object.keys(принято).length > 0) состав[идПрофиля] = принято;
  }

  /* Общий (не профильный) состав развилок — запасной слой: действует там, где у
     профиля своего списка нет. */
  const хабы = разобратьХабы(файл.хабы, 'хабы', отброшено);

  /* ── БАЛАНС: пороги замков и фигурок ───────────────────────────────────── */
  let замки: Record<string, number> | null = null;
  if (файл.замки && typeof файл.замки === 'object') {
    const принятые: Record<string, number> = {};
    for (const [ключ, знач] of Object.entries(файл.замки)) {
      if (!FEATURE_LADDER.some((l) => l.key === ключ)) {
        отброшено.push(`замки: нет приёма «${ключ}» (есть: ${FEATURE_LADDER.map((l) => l.key).join(', ')})`);
        continue;
      }
      if (typeof знач !== 'number' || !Number.isInteger(знач) || знач < 1) {
        отброшено.push(`замки · ${ключ}: «${String(знач)}» — нужен целый уровень от 1`);
        continue;
      }
      принятые[ключ] = знач;
    }
    if (Object.keys(принятые).length > 0) замки = принятые;
  }

  let коллекция: Record<string, number> | null = null;
  if (файл.коллекция && typeof файл.коллекция === 'object') {
    const принятые: Record<string, number> = {};
    for (const [ключ, знач] of Object.entries(файл.коллекция)) {
      if (!FIGURES.some((ф) => ф.key === ключ)) {
        отброшено.push(`коллекция: нет фигурки «${ключ}»`);
        continue;
      }
      if (typeof знач !== 'number' || !Number.isFinite(знач) || знач < 1) {
        отброшено.push(`коллекция · ${ключ}: «${String(знач)}» — нужно число звёзд от 1`);
        continue;
      }
      принятые[ключ] = Math.floor(знач);
    }
    /**
     * 🔴 ПОРОГИ ОБЯЗАНЫ ВОЗРАСТАТЬ — ЭТО НЕ ПРИДИРКА, А УСЛОВИЕ МЕХАНИКИ.
     * «Сколько фигурок уже есть» считается как число порогов ниже счёта, а
     * «следующая» — как элемент по этому номеру. Список вразнобой даёт неверную
     * следующую фигурку и полосу, которая едет назад. Проверяем ИТОГОВУЮ лестницу:
     * заводские пороги плюс принятые правки.
     */
    if (Object.keys(принятые).length > 0) {
      const итог = FIGURES.map((ф) => принятые[ф.key] ?? ф.at);
      const сломано = итог.findIndex((v, i) => i > 0 && v <= итог[i - 1]);
      if (сломано > 0) {
        отброшено.push(
          `коллекция: лестница перестала расти на «${FIGURES[сломано].key}» (${итог[сломано - 1]} → ${итог[сломано]}) — оставлены заводские пороги`,
        );
      } else {
        коллекция = принятые;
      }
    }
  }

  /* ── ПОРЯДОК ПРОФИЛЕЙ ───────────────────────────────────────────────────── */
  let порядок: string[] | null = null;
  if (Array.isArray(файл.порядок_профилей)) {
    const видели = new Set<string>();
    const годные = файл.порядок_профилей.filter((ид) => {
      if (typeof ид !== 'string') { отброшено.push(`порядок: не имя профиля — «${String(ид)}»`); return false; }
      if (видели.has(ид)) { отброшено.push(`порядок: «${ид}» назван дважды — вторая запись пропущена`); return false; }
      видели.add(ид);
      return true;
    });
    if (годные.length > 0) порядок = годные;
  }

  return { состав, наборы, порядок, хабы, замки, коллекция, отброшено, профилейПринято: Object.keys(состав).length };
}

/**
 * Расставить профили по порядку из файла. Названные — в заданном порядке,
 * остальные следом в заводском. Ни один профиль не теряется: это условие проверяет
 * проба, потому что пропажа профиля выглядит как поломка приложения, а не как
 * настройка.
 */
export function поПорядку<T extends { id: string }>(профили: readonly T[], порядок: readonly string[] | null): T[] {
  if (!порядок || порядок.length === 0) return [...профили];
  const поИд = new Map(профили.map((п) => [п.id, п]));
  const итог: T[] = [];
  for (const ид of порядок) {
    const п = поИд.get(ид);
    if (п) { итог.push(п); поИд.delete(ид); }
  }
  for (const п of профили) if (поИд.has(п.id)) итог.push(п);
  return итог;
}

/** Наложить состав на заводской профиль. Чистая функция — её и проверяет проба. */
export function наложить(профиль: ProfileDef, состав: Record<string, СоставПрофиля> | null): ProfileDef {
  const мой = состав?.[профиль.id];
  if (!мой) return профиль;
  return {
    ...профиль,
    ...(мой.игры !== undefined ? { allowed_games: мой.игры } : null),
    ...(мой.убрать !== undefined ? { closed_games: мой.убрать } : null),
    ...(мой.зарядка_включена !== undefined ? { warmup_enabled: мой.зарядка_включена } : null),
    ...(мой.утро !== undefined ? { morning_playlist: мой.утро } : null),
    ...(мой.вечер !== undefined ? { evening_playlist: мой.вечер } : null),
    ...(мой.по_дням !== undefined ? { custom_playlists: мой.по_дням } : null),
  };
}

/** Что лежит в хранилище: принятая часть файла целиком. */
export interface СохранённыйСостав {
  профили: Record<string, СоставПрофиля>;
  наборы: НаборУпражнений[];
  порядок: string[] | null;
  хабы: Record<string, ЭлементХаба[]> | null;
  замки: Record<string, number> | null;
  коллекция: Record<string, number> | null;
}

/** Прочитать сохранённый состав. Любая беда с хранилищем = «состава нет». */
export async function загрузить(): Promise<СохранённыйСостав | null> {
  try {
    const текст = await AsyncStorage.getItem(КЛЮЧ_СОСТАВА);
    if (!текст) return null;
    const прочитано = JSON.parse(текст) as Partial<СохранённыйСостав>;
    if (!прочитано?.профили || typeof прочитано.профили !== 'object') return null;
    return {
      профили: прочитано.профили,
      наборы: Array.isArray(прочитано.наборы) ? прочитано.наборы : [],
      порядок: Array.isArray(прочитано.порядок) ? прочитано.порядок : null,
      хабы: прочитано.хабы ?? null,
      замки: прочитано.замки ?? null,
      коллекция: прочитано.коллекция ?? null,
    };
  } catch {
    return null;
  }
}

export async function сохранить(состав: СохранённыйСостав): Promise<void> {
  await AsyncStorage.setItem(КЛЮЧ_СОСТАВА, JSON.stringify(состав));
}

/** Снять переопределение — вернуться к заводскому составу из сборки. */
export async function сбросить(): Promise<void> {
  await AsyncStorage.removeItem(КЛЮЧ_СОСТАВА);
}
