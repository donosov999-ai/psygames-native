/**
 * Имена слотов в файле — русские, внутри приложения — английские (`WarmupSlot`).
 * Перевод в одном месте: два написания одного и того же разъезжаются молча.
 */
const СЛОТ_ПО_ИМЕНИ: Record<string, WarmupSlot> = {
  утро: 'morning', день: 'day', вечер: 'evening', ночь: 'night',
};

const ДЛИНЫ = ['5', '10', '15'];

/**
 * Сетка из файла → вид, понятный зарядке. Пустая сетка отдаёт `null`, а не пустой
 * объект: «файл про это молчал» и «файл велел пусто» — разные вещи, и путать их
 * значит выключить заводские наборы неназванным ключом.
 */
export function вСеткуЗарядки(сетка: СоставПрофиля['сетка'] | null | undefined): СеткаНаборов | null {
  if (!сетка) return null;
  const out: СеткаВнутри = {};
  let есть = false;
  for (const [ключДня, слоты] of Object.entries(сетка)) {
    const д = Number(ключДня) as Weekday;
    for (const [имя, длины] of Object.entries(слоты ?? {})) {
      const слот = СЛОТ_ПО_ИМЕНИ[имя];
      if (!слот) continue;
      for (const [ключДлины, шаги] of Object.entries(длины ?? {})) {
        if (!шаги || !шаги.length) continue;
        const длина = Number(ключДлины) as Длительность;
        ((out[д] ||= {})[слот] ||= {})[длина] = шаги;
        есть = true;
      }
    }
  }
  return есть ? out : null;
}
type СеткаВнутри = Record<number, Partial<Record<WarmupSlot, Partial<Record<Длительность, PlaylistStep[]>>>>>;

