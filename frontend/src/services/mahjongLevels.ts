/**
 * Уровни маджонга: слои, пары и — главное — ЛИМИТ ПЕРЕТАСОВОК.
 *
 * ЗАЧЕМ ПРАВКА. Тестер: «А можно чуть сложнее?))». Разбор показал две дыры:
 *
 * 1. Кнопка «Перемешать» была БЕСКОНЕЧНОЙ и бесплатной. Любой уровень пробивался
 *    перетасовками, пока не выпадет удобная пара, — то есть сложность раскладки
 *    ничего не решала. Это не «чуть проще», это отсутствие сопротивления.
 * 2. Выше 15 уровня росло только КОЛИЧЕСТВО пар, а слоёв оставалось три. Больше
 *    плиток на том же числе слоёв — это дольше, а не сложнее: перекрытий столько же.
 *
 * ЧТО СЛОЖНО В МАДЖОНГЕ на самом деле — не число плиток, а сколько их заблокировано:
 * плитку нельзя взять, если на ней что-то лежит ИЛИ зажаты оба бока. Слои дают
 * первое, теснота — второе. Поэтому вверх растим слои, а не количество.
 *
 * ⚠️ ПЕРВЫЕ ТРИ УРОВНЯ — БЕЗ ЛИМИТА. Там человек ещё разбирается в правиле
 * свободной плитки; отбирать перетасовку на обучении значит наказывать за незнание.
 *
 * 🔴 ЧТО ЗДЕСЬ НЕ ЖИВЁТ (правка 23.08.2026). ФОРМА доски задаётся не тут. Раньше её
 * рисовали формулами (семь силуэтов), теперь берут из библиотеки 84 раскладок,
 * нарисованных вручную, — `src/games/mahjong/layouts.ts` (данные ffalt/mah, MIT).
 * ⚠️ Все раскладки библиотеки — ровно 144 плитки, разброса по размеру там нет.
 * Поэтому `pairs` из этого файла остаётся ЕДИНСТВЕННЫМ источником роста: раскладка
 * ужимается под заказанное здесь число пар, а к 28 уровню выкладывается целиком.
 * Сломать монотонность `pairs` — значит сломать лесенку целиком; сторожат это
 * `mahjong-levels.test.ts` и `mahjong-layouts.test.ts`.
 */

/** Классический набор маджонга: 144 плитки = 72 пары. Больше не бывает. */
export const FULL_SET_PAIRS = 72;

/** Сколько перетасовок доступно; -1 = без ограничения. */
export type ShuffleBudget = number;

export interface MahjongLevelCfg {
  layers: number;
  pairs: number;
  cols: number;
  /** Лимит перетасовок на уровень; -1 = без лимита (первые уровни). */
  shuffles: ShuffleBudget;
}

/**
 * 🔴 ПЕРВЫЕ УРОВНИ БЫЛИ НЕ МАДЖОНГОМ. Второй уровень выдавал `{слоёв: 1, пар: 5}` —
 * десять плиток в один слой, выложенных прямоугольником. В такой раскладке нет ни
 * одного перекрытия, то есть нет ровно того, из чего маджонг состоит: свободна там
 * любая плитка, и «свободную выбирают» превращается в «тапни две одинаковые».
 * Человек, открывший игру, видит не упрощённый маджонг, а другую игру — и уходит.
 *
 * Обучение слоям никуда не делось, но идёт оно НА НАСТОЯЩЕЙ горке: два слоя с
 * первого уровня, три с четвёртого. Плоских раскладок нет вовсе.
 */
/**
 * 🔴 ДОКУДА ЛЕСТНИЦА РЕАЛЬНО РАСТЁТ — СЧИТАЕТСЯ ИЗ `mahjongLevel`, А НЕ ВПИСАНО ЧИСЛОМ.
 *
 * ЧТО ЛОМАЛОСЬ. Экран передавал карте уровней `maxLevel={Math.max(15, level,
 * lvl.best)}`, то есть на старте ПЯТНАДЦАТЬ, и карта честно писала игроку
 * «Уровень 1/15». Настоящая лестница идёт до 28-го: до него `mahjongLevel`
 * каждый раз отдаёт новый набор (слои, пары, колонки, перетасовки), после —
 * одно и то же. Человек читал «осталось 14», когда впереди 27.
 *
 * ⚠️ Число ЗДЕСЬ НЕ ВПИСАНО НАМЕРЕННО. Впиши я `28` константой — следующая
 * правка лестницы разошлась бы с подписью молча, а это ровно тот дефект,
 * который я и чиню. Считается перебором: последний уровень, на котором
 * настройки ещё МЕНЯЮТСЯ.
 */
export const MAHJONG_LEVELS: number = (() => {
  let последний = 1;
  let прежняя = JSON.stringify(mahjongLevel(1));
  for (let L = 2; L <= 200; L += 1) {
    const текущая = JSON.stringify(mahjongLevel(L));
    if (текущая !== прежняя) { последний = L; прежняя = текущая; }
  }
  return последний;
})();

export function mahjongLevel(L: number): MahjongLevelCfg {
  const n = Math.max(1, Math.floor(L) || 1);
  if (n <= 3) return { layers: 2, pairs: 8 + n * 2, cols: 8, shuffles: -1 };        // 10..14 пар, два слоя, учимся
  if (n <= 8) return { layers: 3, pairs: 14 + (n - 3) * 2, cols: 9, shuffles: 3 };  // 16..24 пары, три слоя
  if (n <= 14) return { layers: 4, pairs: 24 + (n - 8) * 3, cols: 10, shuffles: 2 };// 27..42 пары, четыре слоя
  if (n <= 22) return { layers: 5, pairs: 42 + (n - 14) * 3, cols: 11, shuffles: 1 };// 45..66 пар, пять слоёв
  // Потолок — классический набор: 144 плитки, то есть 72 пары. Выше расти нечему,
  // дальше сложность несут слои и теснота, а не количество.
  return { layers: 5, pairs: Math.min(FULL_SET_PAIRS, 66 + (n - 22)), cols: 12, shuffles: 1 };
}

/**
 * СКРЫТАЯ ИНФОРМАЦИЯ — КАЖДЫЙ ТРЕТИЙ УРОВЕНЬ С ДЕСЯТОГО (задача ec15d176, §20).
 *
 * Почему каждый третий, а не «с N навсегда»: шестая разность §18.8 — «цена
 * неопределённости» — считается сравнением полного и скрытого режимов на
 * СОСЕДНИХ уровнях одной сессии. Тот же график, что у goods-sort (HIDDEN_FROM=16,
 * каждый третий) — обе игры дают разность одним способом.
 *
 * Почему с десятого: скрытие имеет вес с четырёх слоёв (9–14), но на девятом
 * показывается правило четырёх слоёв, а правило на уровне может быть только одно
 * (activeLevelRule берёт последнее подошедшее). Десятый — первый уровень глубокой
 * доски со свободным окном под правило.
 */
export const MAHJONG_HIDDEN_FROM = 10;

export function mahjongHidden(L: number): boolean {
  return L >= MAHJONG_HIDDEN_FROM && (L - MAHJONG_HIDDEN_FROM) % 3 === 0;
}

/** Кончились ли перетасовки. -1 (без лимита) не кончается никогда. */
export function shufflesLeft(budget: ShuffleBudget, used: number): number {
  return budget < 0 ? -1 : Math.max(0, budget - used);
}

export function canShuffle(budget: ShuffleBudget, used: number): boolean {
  return budget < 0 || used < budget;
}
