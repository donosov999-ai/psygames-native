/**
 * Уровни маджонга: слои, пары и — главное — ЛИМИТ ПЕРЕТАСОВОК.
 *
 * ЗАЧЕМ ПРАВКА. Тестер: «А можно чуть сложнее?))». Разбор показал две дыры:
 *
 * 1. Кнопка «Перемешать» была БЕСКОНЕЧНОЙ и бесплатной. Любой уровень пробивался
 *    перетасовками, пока не выпадет удобная пара, — то есть сложность раскладки
 *    ничего не решала. Это не «чуть проще», это отсутствие сопротивления.
 * 2. Выше 15 уровня росло только КОЛИЧЕСТВО пар, а слоёв оставалось три. Больше
 *    плиток на том же числе слоёв — это дольше, а не сложнее: перекрытий столько же.
 *
 * ЧТО СЛОЖНО В МАДЖОНГЕ на самом деле — не число плиток, а сколько их заблокировано:
 * плитку нельзя взять, если на ней что-то лежит ИЛИ зажаты оба бока. Слои дают
 * первое, теснота — второе. Поэтому вверх растим слои, а не количество.
 *
 * ⚠️ ПЕРВЫЕ ПЯТЬ УРОВНЕЙ — БЕЗ ЛИМИТА. Там человек ещё разбирается в правиле
 * свободной плитки; отбирать перетасовку на обучении значит наказывать за незнание.
 */

/** Сколько перетасовок доступно; -1 = без ограничения. */
export type ShuffleBudget = number;

export interface MahjongLevelCfg {
  layers: number;
  pairs: number;
  cols: number;
  /** Лимит перетасовок на уровень; -1 = без лимита (первые уровни). */
  shuffles: ShuffleBudget;
}

export function mahjongLevel(L: number): MahjongLevelCfg {
  const n = Math.max(1, Math.floor(L) || 1);
  if (n <= 5) return { layers: 1, pairs: 3 + n, cols: 6, shuffles: -1 };           // 4..8 пар, плоско, учимся
  if (n <= 10) return { layers: 2, pairs: 9 + (n - 6), cols: 7, shuffles: 3 };     // 9..13 пар, два слоя
  if (n <= 15) return { layers: 3, pairs: 14 + (n - 11), cols: 8, shuffles: 2 };   // 14..18 пар, три слоя
  if (n <= 22) return { layers: 4, pairs: 18 + (n - 15), cols: 8, shuffles: 1 };   // 19..25 пар, ЧЕТЫРЕ слоя
  return { layers: 5, pairs: 25 + (n - 22), cols: 9, shuffles: 1 };                // дальше пять слоёв
}

/** Кончились ли перетасовки. -1 (без лимита) не кончается никогда. */
export function shufflesLeft(budget: ShuffleBudget, used: number): number {
  return budget < 0 ? -1 : Math.max(0, budget - used);
}

export function canShuffle(budget: ShuffleBudget, used: number): boolean {
  return budget < 0 || used < budget;
}
