/**
 * Время для ШАПКИ — коротко. Одна функция на все игры.
 *
 * 🔴 ЗАЧЕМ. Отчёт 03.09.2026 (судоку, v2.34.2): «табло, не видно цифры». В шапке
 * шесть счётчиков, и один из них писал `295.3с` — шесть знаков там, где хватает
 * трёх. Десятая доля секунды в шапке не нужна никому: по ней не играют, её не
 * запоминают, а место она занимает наравне со значащими цифрами.
 *
 * ⚠️ Это НЕ про точность замера. Секунды с долями по-прежнему пишутся в итог
 * партии и в сессию — там они и нужны. Коротко только в шапке.
 *
 * Правило: до минуты — целые секунды (`47с`), дальше — минуты и секунды (`4:55`),
 * после часа — часы (`1:04:55`). Так строка не растёт со временем партии, а
 * человек читает её привычно.
 */
export function hudTime(секунды: number, суффиксСекунд = 'с'): string {
  // ⚠️ NaN проходит сквозь Math.max и Math.floor нетронутым и попадает на экран
  // словом «NaNс». Час партии в шапке — мелочь, а «NaN» человек читает как поломку.
  const t = Number.isFinite(секунды) ? Math.max(0, Math.floor(секунды)) : 0;
  if (t < 60) return `${t}${суффиксСекунд}`;
  const м = Math.floor(t / 60);
  const с = t % 60;
  if (м < 60) return `${м}:${String(с).padStart(2, '0')}`;
  const ч = Math.floor(м / 60);
  return `${ч}:${String(м % 60).padStart(2, '0')}:${String(с).padStart(2, '0')}`;
}
