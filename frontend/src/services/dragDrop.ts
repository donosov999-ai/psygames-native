/**
 * Куда положили товар: точка отпускания жеста.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ РАДИ ЧЕТЫРЁХ СТРОК. Правило родилось из дефекта, который
 * прожил в игре незамеченным: перетаскивание «работало» — товар поднимался, ехал за
 * пальцем, — а ход не делался. Внутри экрана это правило нечем проверить: жест живёт
 * в `PanResponder`, который создаётся один раз внутри компонента. Вынесенное сюда,
 * оно проверяется тестом с событием без координат — и дефект больше не вернётся
 * молча.
 *
 * СУТЬ. Событие отпускания (`touchend` на телефоне, `mouseup` в браузере) списка
 * касаний уже не несёт: палец снят с экрана. React Native подставляет `pageX/pageY`
 * не везде одинаково, и в вебе там приходит ноль — то есть левый верхний угол окна.
 * Для игры это «мимо доски», и ход молча не делается.
 *
 * Поэтому цель берём из последней точки движения — места, где палец был за миг до
 * отрыва. Событие отпускания остаётся запасным на случай жеста вовсе без движения.
 */
export type Точка = { x: number; y: number };

export function dropPoint(
  release: { pageX?: number; pageY?: number } | null | undefined,
  lastMove: Точка | null,
): Точка | null {
  const x = release?.pageX ?? 0;
  const y = release?.pageY ?? 0;
  // Ноль по ОБЕИМ осям — признак события без координат. Настоящее касание левого
  // верхнего угла даёт хотя бы единицы пикселей, а шкаф туда и не достаёт.
  if (x || y) return { x, y };
  return lastMove;
}
