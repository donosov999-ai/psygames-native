/** Меньше скольких слов текст считается обрывком. */
export const МИН_СЛОВ = 3;
/** И короче скольких символов. Оба условия сразу — иначе «не видно» попадёт под нож. */
export const МИН_СИМВОЛОВ = 12;

/**
 * Похоже ли, что диктовка не дописала.
 *
 * @param текст   что в поле
 * @param естьЗапись есть ли голосовая заметка — с ней смысл несёт запись, а не текст
 */
export function похожеНаОбрывок(текст: string, естьЗапись: boolean): boolean {
  if (естьЗапись) return false;                 // смысл в записи, текст может быть любым
  const чистый = текст.trim();
  if (!чистый) return false;                    // пустое поле ловит другое условие
  const слов = чистый.split(/\s+/).filter(Boolean).length;
  return слов < МИН_СЛОВ && чистый.length < МИН_СИМВОЛОВ;
}

/**
 * НАДО ЛИ ПЕРЕСПРОСИТЬ ПЕРЕД ОТПРАВКОЙ.
 *
 * 🔴 ОДНО ВЫРАЖЕНИЕ НА ДВА МЕСТА. Виджет решает это дважды: чем рисовать —
 * кнопкой или развилкой, и пускать ли отправку. Пока условия стояли двумя
 * копиями, они могли разъехаться: правишь одну — вторая остаётся, и заслон
 * либо молчит при видимой развилке, либо держит при отсутствующей.
 *
 * @param согласиеДля текст, которому человек уже сказал «отправить как есть».
 *   Согласие принадлежит СООБЩЕНИЮ, а не сеансу: исправил строку — спрашиваем
 *   снова, потому что это другое сообщение. Булев флаг на его месте пережил свою
 *   отправку и до конца вечера пропускал каждый следующий обрывок молча.
 */
export function нужноПереспросить(
  текст: string, естьЗапись: boolean, согласиеДля: string | null,
): boolean {
  return похожеНаОбрывок(текст, естьЗапись) && согласиеДля !== текст.trim();
}
