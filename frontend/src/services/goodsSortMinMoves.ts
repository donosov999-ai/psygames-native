/**
 * 🔴 ЧЕСТНЫЙ МИНИМУМ ХОДОВ ВМЕСТО ОЦЕНКИ (пункт 6.5 карты дорог).
 *
 * По эталону ходов считаются ЗВЁЗДЫ и `moves_over_min` в записи сессии — то есть
 * оценка игрока. А сам эталон до сих пор был прикидкой: `types × 3` («каждой тройке
 * до трёх перекладываний») либо лимит уровня. Прикидка не обязана иметь отношения к
 * тому, за сколько доска решается на самом деле: на просторной доске минимум заметно
 * меньше, на тесной — больше, и звезда выдавалась не за игру, а за формулу.
 *
 * ⚠️ ПОЧЕМУ A*, А НЕ ПОЛНЫЙ ПЕРЕБОР. Замер 02.09.2026: обход в ширину не дошёл до дна
 * НИ НА ОДНОМ уровне из тридцати — дерево партии не влезает ни в какой бюджет.
 * A* с допустимой эвристикой режет то же дерево на порядки, потому что почти все
 * ветви оказываются заведомо хуже уже найденной.
 *
 * ЭВРИСТИКА (не переоценивает — иначе A* перестанет находить минимум): для каждого
 * вида товара считаем, в скольких нишах он лежит. Чтобы собрать его в одну, нужно
 * минимум «ниш − 1» переносов. Сумма по видам и есть нижняя граница: один перенос
 * уменьшает разбросанность самое большее на единицу.
 *
 * ⚠️ БЮДЖЕТ ОБЯЗАТЕЛЕН. Функция зовётся при раздаче уровня, то есть на глазах у
 * человека. Не уложились — честно возвращаем `null`, и вызывающий берёт прежнюю
 * оценку: «не знаю» лучше, чем выдуманное число (тот же урок, что с решателем строгой
 * укладки — «бюджет кончился» ≠ «нерешаемо»).
 */

export interface MinMovesResult {
  /** Найденный минимум ходов; null — не уложились в бюджет. */
  moves: number | null;
  /** Сколько состояний просмотрено — для ратчета стоимости. */
  nodes: number;
}

/** Ключ состояния: ниши сортируем, потому что доска — множество, а не список. */
function ключ(доска: number[][]): string {
  return доска.map((c) => c.join(',')).sort().join('|');
}

/** Нижняя граница: сколько переносов нужно минимум, чтобы свести все виды. */
function эвристика(доска: number[][]): number {
  const ниши = new Map<number, number>();
  for (const ниша of доска) {
    const виды = new Set(ниша);
    for (const v of viды(виды)) ниши.set(v, (ниши.get(v) ?? 0) + 1);
  }
  let h = 0;
  for (const n of ниши.values()) h += n - 1;
  return h;
}
function viды(s: Set<number>): number[] { return Array.from(s); }

/** Схлопывание тройки сверху ниши — то же правило, что в самой игре. */
function схлопнуть(ниша: number[]): void {
  while (ниша.length >= 3) {
    const t = ниша[ниша.length - 1];
    if (ниша[ниша.length - 2] === t && ниша[ниша.length - 3] === t) ниша.splice(-3, 3);
    else break;
  }
}

export function minMoves(start: number[][], caps: number[], budget = 40000): MinMovesResult {
  const начало = start.map((c) => [...c]);
  начало.forEach(схлопнуть);
  const пусто = (b: number[][]) => b.every((c) => c.length === 0);
  if (пусто(начало)) return { moves: 0, nodes: 0 };

  // Очередь по f = g + h. Держим по корзинам: значения мелкие и целые, куча не нужна.
  const корзины: { b: number[][]; g: number }[][] = [];
  const положить = (b: number[][], g: number) => {
    const f = g + эвристика(b);
    (корзины[f] ??= []).push({ b, g });
  };
  const видели = new Map<string, number>([[ключ(начало), 0]]);
  положить(начало, 0);

  let nodes = 0;
  for (let f = 0; f < корзины.length || f < 400; f++) {
    const пачка = корзины[f];
    if (!пачка) continue;
    while (пачка.length) {
      const { b, g } = пачка.pop()!;
      if (пусто(b)) return { moves: g, nodes };
      if (++nodes > budget) return { moves: null, nodes };
      const k0 = ключ(b);
      if ((видели.get(k0) ?? Infinity) < g) continue;

      for (let from = 0; from < b.length; from++) {
        if (!b[from].length) continue;
        const item = b[from][b[from].length - 1];
        for (let to = 0; to < b.length; to++) {
          if (to === from) continue;
          if (b[to].length >= (caps[to] ?? 3)) continue;
          const nb = b.map((c) => [...c]);
          nb[from].pop();
          nb[to].push(item);
          схлопнуть(nb[to]);
          const k = ключ(nb);
          const было = видели.get(k);
          if (было !== undefined && было <= g + 1) continue;
          видели.set(k, g + 1);
          положить(nb, g + 1);
        }
      }
    }
  }
  return { moves: null, nodes };
}
