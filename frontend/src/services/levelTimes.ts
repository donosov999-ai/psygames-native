  hanoi: 'башня собрана на другом стержне; экран сам вычитает время из очков',
  trail_making: 'все узлы соединены по порядку — время и есть результат пробы Trail Making',
  goods_sort: 'все товары разложены по полкам',
  dots_connect: 'все точки соединены одной линией',
  one_line: 'фигура обведена одним росчерком',
