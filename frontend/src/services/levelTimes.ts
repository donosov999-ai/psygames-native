/**
 * Показывать ли время под узлами этой карты.
 * `countsRuns` перекрывает список: у методики время не показываем никогда.
 */
export function showsBestTime(gameId: string, countsRuns?: boolean): boolean {
  if (countsRuns) return false;
  return Object.prototype.hasOwnProperty.call(TIMED_GAMES, gameId);
}

/**
 * Время партии считается настоящим, если оно похоже на время партии.
 *
 * ⚠️ Границы те же, что у статистики (`getStats`): в истории попадался мусор от
 * старого бага со стартом в нуле — `time_seconds ≈ 1.78e9` (это Date.now()/1000).
 * Одна такая запись не должна ни ломать минимум, ни рисовать «0:00»: партия
 * короче секунды в этих играх физически невозможна.
 */
function isRealTime(v: unknown): v is number {
  return typeof v === 'number' && Number.isFinite(v) && v >= 1 && v <= 86400;
}

/**
 * Лучшее (минимальное) время по каждому уровню — чистая функция над историей.
 *
 * ⚠️ `passed === true` — это ДВА фильтра сразу, и второй неочевиден. Признак
 * ставят только партии по лесенке уровней: свободная партия и шаг зарядки
 * пишут `passed: false` (см. `levelOutcome` и `!isPreset && useLevel…` в
 * экранах). Значит в минимум не попадёт ни быстрый прогон Шульте 4×4 из
 * свободного режима, ни разминочный шаг с чужими настройками — а именно они и
 * сделали бы «рекорд уровня» недостижимым навсегда.
 *
 * ⚠️ ЧУЖИЕ РАУНДЫ НЕ БЕРЁМ. История — один общий массив на устройство. Без
 * фильтра по профилю на семейном планшете Алекс (7 лет) увидел бы под своими
 * узлами рекорды взрослого. Раунды без метки владельца (записанные до её
 * появления) не используем совсем: приписать их некому.
 */
export function bestTimesFrom(
  sessions: GameSession[],
  gameId: string,
  profileId: string,
): LevelTimes {
  const out: LevelTimes = {};
  if (!profileId) return out;
  for (const s of sessions) {
    // Игру спрашиваем у каталога, а не берём `game_type` на веру: партии самурая,
    // записанные до разведения корзин, лежат под именем `sudoku`, и без разбора
    // рекорд классической судоку собирался бы отчасти из чужой игры. Разбор стоит и
    // на границе чтения (`migrateSession` в api), но эта функция чистая и вызывается
    // гейтом напрямую — зелёная чистая функция, держащаяся на чужой миграции,
    // доказывала бы не то, что нужно.
    if (!s || sessionGameType(s) !== gameId) continue;
    if (s.profile_id !== profileId) continue;
    if (s.passed !== true) continue;
    if (!isRealTime(s.time_seconds)) continue;
    const level = Number((s.details as any)?.level);
    if (!Number.isFinite(level) || level < 1) continue;
    const prev = out[level];
    if (prev === undefined || s.time_seconds < prev) out[level] = s.time_seconds;
  }
  return out;
}

/**
 * Лучшие времена уровней для карты. Пустой ответ — нормальный: у игры может не
 * быть ни одной зачётной партии, и подпись тогда просто не появляется.
 */
export async function getLevelBestTimes(gameId: string, profileId: string): Promise<LevelTimes> {
  if (!showsBestTime(gameId)) return {};
  try {
    return bestTimesFrom(await getSessions(), gameId, profileId);
  } catch {
    return {};
  }
}

/**
 * Время под узлом — часами: `2:40`, а не «160 секунд» и не «2.6667 минуты».
 *
 * ⚠️ ФОРМАТ БЕЗ СЛОВ — И ЭТО НАРОЧНО. Подпись живёт в колонке шириной 62 px под
 * узлом; слово «секунд» туда не влезет ни на одном из двенадцати языков, а
 * `M:SS` читается одинаково всюду и не требует ключа в словаре. Слово, где оно
 * нужно, добавляет скринридер — там есть готовый ключ `bestTime`.
 */
export function formatBestTime(seconds: number): string {
  const total = Math.max(0, Math.round(seconds));
  const m = Math.floor(total / 60);
  const s = total % 60;
  return `${m}:${String(s).padStart(2, '0')}`;
}
