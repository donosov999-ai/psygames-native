import { useEffect, useState } from 'react';
import type { PetMood } from '@/src/components/pet/GamePet';

/**
 * НАСТРОЕНИЕ ПИТОМЦА — ОДНА ВЕЛИЧИНА НА ПРИЛОЖЕНИЕ.
 *
 * 🔴 ЗАЧЕМ ПОЯВИЛОСЬ. Питомец переехал из плашки счётчиков к кнопке справки
 * (жалоба Дениса 03.09.2026: «он переезжает у нас туда во всех местах»). Плашка и
 * справка — разные поддеревья, и передать настроение пропом стало нельзя.
 *
 * ⚠️ БЕЗ ЭТОГО ПЕРЕЕЗД БЫЛ БЫ ТИХОЙ ПОТЕРЕЙ. Питомец отвечал на ход: верно —
 * прыжок, ошибка — сон, уровень взят — помахивание. Оставить его картинкой значило
 * бы убрать ответ на действие и не сказать об этом никому: снаружи это выглядит
 * как «маскот сломался», а в задачах — как выполненный переезд.
 *
 * Устроено как `setCalmHush` в feedback.ts: величина в модуле плюс подписка. Ни
 * контекста, ни провайдера — настроение живёт секунды и не стоит перерисовки
 * половины дерева.
 */
let _mood: PetMood = 'idle';
const слушатели = new Set<(m: PetMood) => void>();

/** Игра сообщает настроение. Пустое значение возвращает питомца в покой. */
export function setGameMood(m: PetMood | undefined) {
  const v = m ?? 'idle';
  if (v === _mood) return;
  _mood = v;
  слушатели.forEach((f) => f(v));
}

export function gameMoodNow(): PetMood { return _mood; }

/** Подписка для того, кто рисует питомца. */
export function useGameMood(): PetMood {
  const [m, setM] = useState<PetMood>(_mood);
  useEffect(() => {
    слушатели.add(setM);
    /**
     * ⚠️ Догонять значение в эффекте НЕ НУЖНО: начальное состояние уже читает `_mood`
     * при монтировании, а всё, что изменится после, придёт подпиской. Безусловный
     * `setState` прямо в эффекте линтер запрещает справедливо — это лишняя
     * перерисовка на каждом монтировании ради случая, которого нет.
     */
    return () => { слушатели.delete(setM); };
  }, []);
  return m;
}
