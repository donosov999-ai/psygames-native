export const TAB_BAR_H = 58;

export interface TabDef {
  /** Маршрут вкладки. */
  route: string;
  /** Имя значка Ionicons. */
  icon: string;
  /** Ключ подписи в словаре. */
  labelKey: string;
}

/**
 * Пять вкладок. Порядок — слева направо, и он не случайный: сначала «что делать
 * сегодня», потом «что вообще есть», потом «во что вложился».
 */
export const TABS: readonly TabDef[] = [
  { route: '/',              icon: 'home',            labelKey: 'home' },
  { route: '/games',         icon: 'game-controller', labelKey: 'tabGames' },
  { route: '/warmup-picker', icon: 'flash',           labelKey: 'warmupPickerTitle' },
  { route: '/statistics',    icon: 'stats-chart',     labelKey: 'progress' },
  { route: '/pet',           icon: 'paw',             labelKey: 'tabPet' },
] as const;

/**
 * Где полосы быть НЕ должно.
 *
 * 🔴 ВНУТРИ ИГРЫ — ГЛАВНОЕ. Доска считается от высоты экрана; отнять у неё 58 px
 * молча значит ужать поле там, где его и так мало (репорт по матрице: правила
 * ложились поверх горящей сетки). Плюс служебные экраны комплекса, где внизу
 * стоят кнопки решения, и онбординг, где отвлекать нечем.
 *
 * ⚠️ `/games/` СО СЛЕШЕМ. Без него каталог `/games` — сам вкладка — прятал бы
 * полосу под собой, то есть вкладка «Игры» была бы единственной, из которой
 * некуда уйти.
 */
export function tabBarVisible(pathname: string): boolean {
  return !(
    pathname.startsWith('/games/')
    || pathname.startsWith('/onboarding')
    || pathname.startsWith('/warmup-bridge')
    || pathname.startsWith('/warmup-complete')
    || pathname.startsWith('/assessment-result')
  );
}

/**
 * Какая вкладка сейчас подсвечена. `null` — ни одна: человек на экране, который
 * вкладкой не является (магазин, настройки, достижения), и подсвечивать там
 * нечего. Врать подсветкой хуже, чем не подсвечивать.
 */
export function activeTab(pathname: string): string | null {
  if (pathname === '/' || pathname === '') return '/';
  // Длинные маршруты проверяются раньше коротких — иначе '/' совпало бы со всем.
  const найдено = TABS.filter((t) => t.route !== '/')
    .filter((t) => pathname === t.route || pathname.startsWith(t.route + '/'))
    .sort((a, b) => b.route.length - a.route.length)[0];
  return найдено ? найдено.route : null;
}
