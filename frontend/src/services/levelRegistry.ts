/**
 * РЕЕСТР ЖИВЫХ ЛЕСТНИЦ — чтобы каркас мог менять уровень из меню паузы.
 *
 * 🔴 ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ЭКСПОРТ ИЗ `usePersistentLevel`.
 * Первая редакция держала реестр прямо в хуке, и `GameShell` импортировал функцию
 * оттуда. Замер: три пробы шахмат легли с `текущаяЛестница is not a function` —
 * они подменяют модуль хука целиком (`jest.mock`), и подмена, разумеется, не знает
 * про новый экспорт. То есть каркас стал зависеть от того, что у КАЖДОЙ пробы,
 * трогающей уровень, окажется полная подмена хука.
 *
 * Реестр — не забота хука: это общий стол, куда экран кладёт «вот моя лестница»,
 * а каркас берёт. Отдельный модуль подменять незачем, и связь исчезает.
 *
 * ⚠️ Берём ПОСЛЕДНЮЮ зарегистрированную: экран игры монтируется последним и он же
 * активен. Второй экземпляр хука по угаданному ключу не годится вовсе — получилось
 * бы второе состояние поверх того же ключа хранилища, и правка уровня выглядела бы
 * рабочей, ничего не меняя.
 */

/** То, что каркасу нужно от лестницы: где стоим, докуда дошли, как переставить. */
export interface ЖиваяЛестница {
  level: number;
  best: number;
  loaded: boolean;
  pick: (n: number) => void;
}

interface Слот { id: string; api: ЖиваяЛестница }

const живые: Слот[] = [];

/** Записать живой экземпляр. Возвращает снятие записи — звать при размонтировании. */
export function завестиЛестницу(id: string, api: ЖиваяЛестница): { обновить: (a: ЖиваяЛестница) => void; снять: () => void } {
  const слот: Слот = { id, api };
  живые.push(слот);
  return {
    обновить: (a: ЖиваяЛестница) => { слот.api = a; },
    снять: () => {
      const i = живые.indexOf(слот);
      if (i >= 0) живые.splice(i, 1);
    },
  };
}

/** Лестница активного экрана либо `null`, если её никто не завёл. */
export function текущаяЛестница(): ЖиваяЛестница | null {
  return живые.length ? живые[живые.length - 1].api : null;
}
