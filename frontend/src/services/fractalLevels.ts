/**
 * Уровни фрактальной судоку.
 *
 * ЗАЧЕМ. Игра вышла без уровней вообще — сразу «hard» и всегда одинаково. Это моя же
 * дыра: выкатил новую игру мимо формата, на который сам жалуюсь.
 *
 * ⚠️ ОСЬ СЛОЖНОСТИ — ТЕХНИКА РЕШЕНИЯ, А НЕ ЧИСЛО ДЫРОК. Первая версия крутила ровно
 * «сколько выколото» (38→56) и «сколько верных клеток набрать» (17→34). Это та же
 * ошибка, на которой сломался обычный судоку: репорты Вали «с 30 по 34 сложность не
 * меняется» — и оттуда ушли в градацию по технике (sudoku-grade.ts, targetTier).
 * Здесь то же самое: уровень поднимает ПОТОЛОК ТЕХНИК, которыми пазл добивается.
 *
 * Число дырок остаётся, но как ПОТОЛОК, а не как цель: на первых уровнях доска в
 * полсотни дырок просто пугает, хотя решается одними голыми одиночками. Настоящий
 * стопор — логика: генератор выкалывает клетку, только пока пазл берётся техниками
 * не выше потолка уровня (fractal-sudoku.ts, digByLogic).
 *
 * ⚠️ ПОРОГ ОТКРЫТИЯ ЗАДАЁТСЯ ДОЛЕЙ, А НЕ ЧИСЛОМ. Дырок теперь столько, сколько
 * разрешила логика, — заранее их число неизвестно. Фиксированный порог (было 17→34)
 * мог бы оказаться выше числа дырок конкретной сетки, и она не открылась бы НИКОГДА:
 * партия непроходима. Доля от реального числа дырок такого не допускает.
 *
 * ⚠️ И ПОРОГ НЕ ДОРАСТАЕТ ДО ПОЛНОГО РЕШЕНИЯ. Открывать корневую клетку только за
 * полностью решённую дочернюю значит превратить фрактал в девять судоку подряд без
 * единой промежуточной награды — ровно то, ради чего порог и заведён. Потолок 0.70.
 *
 * ═══ ВТОРАЯ ОСЬ: СКОЛЬКО СЕТОК ТРЕБУЮТ ВЕРХНЕЙ ТЕХНИКИ (правка 19.08.2026) ═══
 *
 * ⚠️ ЧТО БЫЛО НЕ ТАК. Ступеней техники было четыре на тридцать уровней, и внутри
 * ступени уровни отличались ТОЛЬКО долей захода в дочернюю: уровни 14–21 были одной и
 * той же задачей с разной длиной. Это второй знак после запятой, а не сложность. И
 * выше четвёртой ступени расти было некуда вовсе — уровни 22–30 упирались в потолок.
 *
 * Теперь ступеней шесть (добавлены скрытая пара и X-wing), по пять уровней на ступень,
 * и внутри ступени растёт ЧИСЛО СЕТОК, которым верхняя техника действительно нужна:
 * 1 → 3 → 5 → 7 → 9 из девяти. Остальные копаются с потолком на ступень ниже, то есть
 * заведомо легче. Первый уровень ступени — «покажите приём один раз», последний —
 * «девять раз подряд, и деться от него некуда». Это содержание, а не длина.
 *
 * Доля захода (unlockShare) осталась и растёт по-прежнему — но теперь она не
 * единственное, чем уровни внутри ступени отличаются.
 */

/**
 * Тридцать уровней и шесть ступеней техники — ровно по пять уровней на ступень.
 * Раньше ступеней было четыре, и на уровнях 22–30 расти было НЕКУДА: лестница
 * кончалась, а уровни продолжались.
 */
export const FRACTAL_MAX_LEVEL = 30;

/** Ступеней ровно столько, сколько техник умеет решатель (fractal-sudoku, FRACTAL_TIERS). */
export const FRACTAL_TIER_STEPS = 6;
/** Уровней на одну ступень техники. */
export const FRACTAL_PER_STEP = FRACTAL_MAX_LEVEL / FRACTAL_TIER_STEPS;

/** Дочерних сеток в партии — по одной на блок корня. */
export const FRACTAL_CHILDREN = 9;

/**
 * Потолок дырок ДЕЙСТВУЕТ ТОЛЬКО НА ПЕРВОЙ СТУПЕНИ (уровни 1–5, голые одиночки).
 * Дальше его нет (NO_CAP): границу ставит логика, генератор выкалывает до упора, пока
 * пазл берётся техниками уровня. Это ровно приём обычного судоку — там лимит дырок
 * держат до 8-го уровня, а дальше «глубину задаёт ЛОГИКА» (sudoku-grade.ts, digByLogic):
 * иначе лимит упирается в потолок и сложность перестаёт расти.
 *
 * ⚠️ На первой ступени верхняя техника единственная, и «сколько сеток её требуют» там
 * ничего не значит — все девять. Поэтому уровни 1–5 разводит именно потолок дырок:
 * доска в 36 дырок и доска в 46 дырок на одних голых одиночках — разная работа.
 */
const NO_CAP = 64;
const CHILD_BLANKS_MIN = 36;   // первый уровень: опор много, доска не пугает
const CHILD_BLANKS_MAX = 46;
/**
 * У корня потолок дырок действует ВСЕГДА, в отличие от дочерних. Причина не в
 * сложности, а в том, что видит человек: девять клеток корня приходят снизу, и до их
 * прихода корень стоит почти пустой. Выкопанный до упора (55+ дырок) он выглядит не
 * задачей, а пустым полем — играть в это не сядешь. С потолком 38→52 на старте видно
 * тридцать с лишним подсказок, а после девяти цифр снизу это обычная плотная судоку.
 */
const ROOT_BLANKS_MIN = 38;
const ROOT_BLANKS_MAX = 52;
/**
 * ⚠️ ПОТОЛОК ТЕХНИКИ У КОРНЯ НИЖЕ, ЧЕМ У ДОЧЕРНИХ, И ЭТО НЕ НЕДОСМОТР. Корень копается
 * под двумя ограничениями разом: девять «кормящих» клеток защищены от выкалывания, а
 * число дырок ограничено сверху (см. выше). Верхние две ступени в таких рамках берутся
 * только заготовками (замер: вслепую — 0.5% досок), а заготовку под защищённые клетки
 * не подложишь: её решение задано заранее, а корневое рождается в партии. Поэтому
 * глубокие техники живут в дочерних — там человек и проводит почти всё время партии.
 */
const ROOT_MAX_TIER = 4;
const UNLOCK_SHARE_MIN = 0.35; // на первом уровне цифра уходит наверх примерно за треть сетки
const UNLOCK_SHARE_MAX = 0.70; // на последнем — больше двух третей, но всё ещё не «реши целиком»

export interface FractalLevelCfg {
  level: number;
  /** Потолок техники для дочерних сеток: 1 голые одиночки … 6 X-wing. */
  tier: number;
  /** Потолок техники для корня. */
  rootTier: number;
  /**
   * Сколько из девяти дочерних обязаны РЕАЛЬНО требовать верхнюю технику ступени.
   * Остальные копаются с потолком на ступень ниже — то есть заведомо легче.
   * Это и есть вторая ось: внутри ступени 1 → 3 → 5 → 7 → 9.
   */
  topTierCount: number;
  /** Потолок дырок в дочерней. Ограничитель, а не цель — сколько выйдет, решает логика. */
  childBlanksCap: number;
  /** Потолок дырок в корне. */
  rootBlanksCap: number;
  /** Какую долю выколотых клеток надо набрать верными, чтобы дочерняя отдала цифру наверх. */
  unlockShare: number;
}

export function clampFractalLevel(level: number): number {
  if (!Number.isFinite(level)) return 1;
  return Math.max(1, Math.min(FRACTAL_MAX_LEVEL, Math.floor(level)));
}

function lerp(a: number, b: number, k: number): number {
  return Math.round(a + k * (b - a));
}

/**
 * Ступень техники по уровню: по пять уровней на ступень, шесть ступеней на тридцать
 * уровней. Раньше границы стояли «по смыслу» (1–6, 7–13, 14–21, 22–30) и последняя
 * ступень тянулась девять уровней подряд — просто потому, что дальше техник не было.
 */
export function fractalTier(level: number): number {
  const n = clampFractalLevel(level);
  return Math.min(FRACTAL_TIER_STEPS, Math.ceil(n / FRACTAL_PER_STEP));
}

/**
 * Сколько дочерних сеток обязаны требовать верхнюю технику ступени.
 *
 * Внутри ступени: 1 → 3 → 5 → 7 → 9. На первой ступени всегда девять — там верхняя
 * техника единственная, и «часть сеток попроще» означало бы сетки вообще без логики.
 */
export function fractalTopTierCount(level: number): number {
  const n = clampFractalLevel(level);
  if (fractalTier(n) === 1) return FRACTAL_CHILDREN;
  const inStep = (n - 1) % FRACTAL_PER_STEP;                     // 0…4 внутри ступени
  return 1 + Math.round((inStep / (FRACTAL_PER_STEP - 1)) * (FRACTAL_CHILDREN - 1));
}

/**
 * Потолок техники для КАЖДОЙ из девяти дочерних: первые topTierCount — верхняя ступень
 * уровня, остальные на ступень ниже. Порядок здесь канонический (сначала трудные);
 * по каким плиткам карты они разойдутся, решает генератор — иначе трудные всегда
 * оказывались бы в левом верхнем углу.
 */
export function fractalChildTiers(level: number): number[] {
  const tier = fractalTier(level);
  const top = fractalTopTierCount(level);
  return Array.from({ length: FRACTAL_CHILDREN }, (_, i) => (i < top ? tier : Math.max(1, tier - 1)));
}

export function fractalLevel(level: number): FractalLevelCfg {
  const n = clampFractalLevel(level);
  const k = (n - 1) / (FRACTAL_MAX_LEVEL - 1);
  const tier = fractalTier(n);
  const inFirstStep = (n - 1) / (FRACTAL_PER_STEP - 1);   // доля пройденного внутри первой ступени
  return {
    level: n,
    tier,
    rootTier: Math.min(tier, ROOT_MAX_TIER),
    topTierCount: fractalTopTierCount(n),
    childBlanksCap: tier === 1 ? lerp(CHILD_BLANKS_MIN, CHILD_BLANKS_MAX, inFirstStep) : NO_CAP,
    rootBlanksCap: lerp(ROOT_BLANKS_MIN, ROOT_BLANKS_MAX, k),
    unlockShare: UNLOCK_SHARE_MIN + k * (UNLOCK_SHARE_MAX - UNLOCK_SHARE_MIN),
  };
}
