/**
 * Уровни гимнастики для глаз.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Уровень здесь — не украшение, а два реальных параметра
 * нагрузки: сколько длится проработка и как быстро бежит точка. Держать эту
 * арифметику в экране значит спрятать её от теста; вынесенная — проверяется
 * (монотонность, границы, отсутствие рывков).
 *
 * ЧЕСТНО О ГРАНИЦАХ. Это упражнение НЕ бесконечно масштабируется: глазодвигательная
 * нагрузка выше определённой не тренирует, а утомляет. Поэтому потолок 15 уровней,
 * и оба параметра упираются ровно в те значения, которые и так есть в ручных
 * настройках («5 минут», «быстро») — уровни доводят человека до верхней ручной
 * настройки постепенно, а не выдумывают новую высоту.
 *
 * Ручные настройки при этом никуда не деваются: они — свободный режим.
 */

export const EYE_GYM_MAX_LEVEL = 15;

/** Крайние значения = верх и низ РУЧНЫХ настроек экрана, новых не изобретаем. */
const SCALE_MIN = 0.4;   // «1 минута»
const SCALE_MAX = 1.7;   // «5 минут»
const SPEED_MIN = 0.7;   // «медленно»
const SPEED_MAX = 1.4;   // «быстро»

export interface EyeGymLevelCfg {
  /** Множитель длительности шагов (0.4 ≈ 1 мин, 1 ≈ 3 мин, 1.7 ≈ 5 мин). */
  scale: number;
  /** Скорость точки (0.7 медленно · 1 норма · 1.4 быстро). */
  speed: number;
}

export function clampEyeGymLevel(level: number): number {
  if (!Number.isFinite(level)) return 1;
  return Math.max(1, Math.min(EYE_GYM_MAX_LEVEL, Math.floor(level)));
}

/**
 * Ровный подъём от нижней ручной настройки к верхней за 15 уровней.
 *
 * Округляем до сотых: иначе в отладке и в сессии оседают хвосты вида
 * 0.9928571428571429, а по ним потом невозможно понять, какой был уровень.
 */
export function eyeGymLevel(level: number): EyeGymLevelCfg {
  const n = clampEyeGymLevel(level);
  const k = (n - 1) / (EYE_GYM_MAX_LEVEL - 1);   // 0 на первом, 1 на последнем
  return {
    scale: Math.round((SCALE_MIN + k * (SCALE_MAX - SCALE_MIN)) * 100) / 100,
    speed: Math.round((SPEED_MIN + k * (SPEED_MAX - SPEED_MIN)) * 100) / 100,
  };
}

/**
 * Сколько минут займёт уровень — для подписи на тропинке: «2′» понятнее номера.
 *
 * ⚠️ Возвращаем ЧИСЛО, а не готовую строку. Строку собирает экран, у которого есть
 * язык: приложение живёт на 12 языках, и зашитое здесь «мин» показалось бы японцу
 * и арабу тоже по-русски.
 */
export function eyeGymLevelMinutes(level: number, baseTotalSec: number): number {
  return Math.max(1, Math.round((baseTotalSec * eyeGymLevel(level).scale) / 60));
}
