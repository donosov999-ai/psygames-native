/**
 * «КОЛЫШКИ»: ХОДОВ БОЛЬШЕ НЕТ — И ЭКРАН ОБ ЭТОМ ГОВОРИТ.
 *
 * 📍 Денис 11.09.2026 про головоломки: «в конце ничего не происходит». У «Колышков»
 * это буквально: партия упирается в тупик за 18 ходов из 31, `psy_status` равен нулю,
 * строка состояния пуста (`pegs.c` не зовёт `status_bar` ни разу), и человек сидит
 * перед мёртвой доской без конца и без подсказки.
 *
 * 🔴 ЧТО СТОРОЖИТ ЭТА ПРОБА. Не «есть функция», а РЕШЕНИЕ по доске: где ход есть —
 * молчать, где хода нет — звать «Отменить / Заново». Доски собраны разметкой самого
 * движка (`pegs.c:game_text_format`): `*` колышек, `-` пустая лунка, пробел — вне
 * доски. Круги рисуются ровно как в `pegs.c:draw_tile`.
 */
import { разложитьКолышки, естьХодКолышков, молчаливыйТупик } from '@/src/games/tatham-bridge/deadend';
import type { Партия, Примитив } from '@/src/games/tatham-bridge/play';

const КЛЕТКА = 33;                 // PREFERRED_TILE_SIZE у автора
const КРАЙ = KЛЕТКА_КРАЙ();
function KЛЕТКА_КРАЙ() { return Math.floor(КЛЕТКА / 2); }   // BORDER = TILESIZE/2

/** Нарисовать доску так, как её рисует `pegs.c:draw_tile`. */
function доска(карта: string[], подКурсором?: [number, number]): Примитив[] {
  const из: Примитив[] = [];
  карта.forEach((строка, y) => {
    [...строка].forEach((знак, x) => {
      if (знак !== '*' && знак !== '-') return;
      const cx = КРАЙ + x * КЛЕТКА + Math.floor(КЛЕТКА / 2);
      const cy = КРАЙ + y * КЛЕТКА + Math.floor(КЛЕТКА / 2);
      const курсор = !!подКурсором && подКурсором[0] === x && подКурсором[1] === y;
      if (знак === '*') {
        const ц = курсор ? 4 : 3;                                  // COL_CURSOR / COL_PEG
        из.push({ вид: 'круг', x: cx, y: cy, r: Math.floor(КЛЕТКА / 3), заливка: ц, контур: ц });
        из.push({ вид: 'круг', x: cx, y: cy, r: Math.floor(КЛЕТКА / 4), заливка: ц, контур: ц });
      } else {
        const ц = курсор ? 1 : 2;                                  // COL_HIGHLIGHT / COL_LOWLIGHT
        из.push({ вид: 'круг', x: cx, y: cy, r: Math.floor(КЛЕТКА / 4), заливка: ц, контур: ц });
      }
    });
  });
  return из;
}

const партия = (примитивы: Примитив[], статус = 0): Партия =>
  ({ ширина: 300, высота: 300, палитра: [], примитивы, статус, ход: null, подорвался: false, тупик: false }) as Партия;

/** Есть ли по рисунку хоть один ход. `null` разбора считаем «не знаем» = ход как бы есть. */
const ходЕсть = (карта: string[], подКурсором?: [number, number]): boolean | null => {
  const поле = разложитьКолышки(доска(карта, подКурсором));
  return поле ? естьХодКолышков(поле) : null;
};

describe('«Колышки»: молчаливый тупик', () => {
  it('🔴 прыжок через соседа в пустую лунку — это ход, и тупика нет', () => {
    expect(ходЕсть(['**-**'])).toBe(true);
    expect(молчаливыйТупик('Pegs', партия(доска(['**-**'])))).toBe('');
  });

  it('🔴 через ПУСТУЮ клетку не прыгают: `*-*` и `*--` — тупик', () => {
    // Средняя клетка обязана быть колышком: перепрыгивают соседа, а не пустоту.
    expect(ходЕсть(['*-*--'])).toBe(false);
    // `*--`: сосед — лунка, посадка — лунка. Без проверки середины это читалось бы
    // как ход, поэтому случай стоит здесь отдельной строкой.
    expect(ходЕсть(['*--  ', '     ', '-    '])).toBe(false);
    expect(молчаливыйТупик('Pegs', партия(доска(['*-*--'])))).toBe('puzzleNoMoves');
  });

  it('🔴 по диагонали не прыгают', () => {
    expect(ходЕсть(['*   ', ' *  ', '  - ', '   -'])).toBe(false);
  });

  it('🔴 посадка обязана быть КЛЕТКОЙ ДОСКИ, а не пустым местом за её краем', () => {
    // `-  **`: у правого колышка сосед-колышек есть, а клетки за ним на доске нет.
    expect(ходЕсть(['-  **'])).toBe(false);
    expect(молчаливыйТупик('Pegs', партия(доска(['-  **'])))).toBe('puzzleNoMoves');
  });

  it('🔴 победа — не тупик: один колышек, ходов нет, но статус говорит «решено»', () => {
    const один = доска(['-  -*']);
    expect(ходЕсть(['-  -*'])).toBe(false);
    expect(молчаливыйТупик('Pegs', партия(один, 1))).toBe('');
  });

  it('🔴 курсор на клетке меняет ЦВЕТ, но не смысл', () => {
    // Колышек под курсором рисуется COL_CURSOR, лунка — COL_HIGHLIGHT.
    expect(ходЕсть(['**-**'], [0, 0])).toBe(true);
    expect(ходЕсть(['**-**'], [2, 0])).toBe(true);
    expect(ходЕсть(['*-*--'], [1, 0])).toBe(false);
  });

  it('🔴 колышек под пальцем не ломает решётку', () => {
    // Пока палец ведёт колышек, движок рисует его ещё раз в произвольной точке.
    // Если шаг решётки считать минимальным промежутком, этот круг делает клетку втрое
    // мельче, соседи считаются через три клетки, и живая доска объявляется тупиком.
    const с = доска(['**-**']);
    const лишний = КРАЙ + Math.floor(КЛЕТКА / 3);
    с.push({ вид: 'круг', x: лишний, y: КРАЙ + 16, r: 11, заливка: 3, контур: 3 });
    const поле = разложитьКолышки(с);
    expect(поле).not.toBeNull();
    expect(естьХодКолышков(поле!)).toBe(true);
  });

  it('🔴 остальные 41 режим этот признак не трогает', () => {
    expect(молчаливыйТупик('Untangle', партия(доска(['*-*--'])))).toBe('');
    expect(молчаливыйТупик('Sokoban', партия(доска(['*-*--'])))).toBe('');
    expect(молчаливыйТупик('Pegs', null)).toBe('');
  });
});
