/**
 * 🔴 ОТВЕТ ИГРОКА ЖИВЁТ В КАРКАСЕ, А НЕ В ПОЛЕ.
 *
 * ОТКУДА. Задача Дениса 07.09.2026: при сборке «Зарядки» игры идут подряд, и
 * кнопка ответа прыгает по экрану — «интерфейс скачущий будет раздражать».
 *
 * 📍 ЗАМЕР (свой скрипт memory-hearing-chat/measure-geometry.mjs, Playwright,
 * все 94 игры, 375×812, по якорям `data-testid` каркаса):
 *   · ответ В КАРКАСЕ  — 39 игр: низ панели 812 у ВСЕХ, разброс 0;
 *   · ответ ВНЕ каркаса — 40 настоящих игр (плюс 15 хабов, где партии нет):
 *     панель оказывается там, где кончился контент, — 461…1530.
 * То есть каркас держит низ идеально, а разъезд дают обходы каркаса.
 *
 * ЧТО СТОРОЖИТ ЭТА ПРОБА. Для игр раздела «Память и слух»: слот `toolbar`
 * каркаса должен быть заполнен, то есть в дереве обязан быть узел с
 * `testID="game-toolbar"`. Проверяется РЕНДЕРОМ, а не поиском строки в
 * исходнике: `toolbar={...}` можно написать и передать `undefined` — как в
 * `sudoku.tsx`, где стоит явное `toolbar={undefined}`.
 *
 * ✅ ДОЛГ РАЗДЕЛА ЗАКРЫТ 07.09.2026: восемь игр из восьми держат ответ в каркасе.
 * Последними переехали `memory-palace` и `faces-names` — у обеих кнопки жили
 * внутри модуля, и перенос потребовал отдать действие фазы наружу описанием.
 * Состав раздела проба теперь берёт из `HUB_CONTENTS`, а не из ручной строки:
 * новая игра в хабе сразу попадает под гейт.
 */
/*
 * Исходник экрана берём готовым хелпером, а не читаем файл сами: часть игр —
 * тонкие маршруты-делегаты, и прямое чтение `app/games/<игра>.tsx` краснело бы
 * на верном коде (объяснение — в шапке самого хелпера).
 */
import { исходникЭкрана } from './helpers/screenSource';
import { HUB_CONTENTS } from '@/src/constants/hubContents';

/**
 * 🔴 СОСТАВ РАЗДЕЛА БЕРЁТСЯ ИЗ ХАБОВ, А НЕ ИЗ РУЧНОГО СПИСКА.
 *
 * Ручной список 07.09.2026 уже подвёл: `memory-palace` пришлось вычёркивать из
 * долга отдельной правкой, и ровно так же новая игра раздела могла бы появиться
 * мимо этой пробы — просто потому, что её никто сюда не вписал. Теперь раздел
 * «Память и слух» — это ровно то, что показано в двух его хабах: «Мнемоника» и
 * «Слух». Добавили игру в хаб — проба немедленно требует её ответ в каркасе.
 */
const ИГРЫ_РАЗДЕЛА: string[] = ['/games/mnemonics-hub', '/games/hearing-hub']
  .flatMap((хаб) => HUB_CONTENTS[хаб] ?? [])
  .map((карточка) => карточка.route.replace('/games/', ''));

/**
 * Долг: ответ пока рисуется модулем, а не каркасом. Каждая строка — с причиной,
 * чтобы список не превратился в молчаливое «так и надо».
 *
 * 🔴 СЕЙЧАС ПУСТ, И ЭТО ПРОВЕРЕНО ПРОБОЙ, А НЕ ОБЪЯВЛЕНО. Обе игры вычеркнуты
 * отсюда не по памяти: и на `memory-palace`, и на `faces-names` проба «игры из
 * долга действительно ещё не в каркасе» краснела сразу после переноса и сама
 * требовала обновить список. Список долга не должен пережить своё исполнение.
 */
const ДОЛГ: Record<string, string> = {
  'rhythm-pitch':
    'пришла 12.09.2026 из каталога, где не входила ни в одну развилку (задача 4332ce4e); ' +
    'ответ игрока рисует сам модуль, слот toolbar каркаса пуст. У карточки стоит sandbox: true — ' +
    'динамика сырая, переезд дал ей дом, но не качество. Каркас берётся вместе с доведением игры.',
};

describe('Память и слух · ответ игрока в каркасе', () => {
  it('есть что проверять: состав раздела виден и долг назван поимённо', () => {
    // ДЕСЯТЬ игр: пять в «Мнемонике», пять в «Слухе». Было восемь — 12.09.2026
    // раздел вырос на два экрана, которые не входили НИ В ОДНУ развилку
    // (задача 4332ce4e): «Ритм и высота» → «Слух», RMET → «Мнемотехники».
    // Число остаётся ЛИТЕРАЛОМ: взять его из HUB_CONTENTS значило бы двигать оба
    // конца сразу, и порезанный хаб стал бы «нормой».
    expect(ИГРЫ_РАЗДЕЛА).toHaveLength(10);
    for (const [игра, причина] of Object.entries(ДОЛГ)) {
      expect(причина.length).toBeGreaterThan(20);   // причина, а не отписка
      expect(ИГРЫ_РАЗДЕЛА).toContain(игра);         // долг — про игру раздела
    }
  });

  /**
   * 🔴 Сам гейт: в исходнике игры слот `toolbar` заполняется НЕ пустым значением.
   * Проверяем текстом файла на пролёт `toolbar={` + запрет `toolbar={undefined}`:
   * рендер каждой игры до игровой фазы требует поднятого стора и таймеров, а
   * этот признак ловит ровно тот обход, который встречается на практике (явное
   * `toolbar={undefined}` стоит в `sudoku.tsx` — это не выдумка).
   */
  it('🔴 игры раздела заполняют слот toolbar', () => {
    const без: string[] = [];
    for (const игра of ИГРЫ_РАЗДЕЛА) {
      if (игра in ДОЛГ) continue;
      if (!/toolbar=\{(?!undefined)/.test(исходникЭкрана(игра))) без.push(игра);
    }
    expect({ без_тулбара: без }).toEqual({ без_тулбара: [] });
  });

  /** Долг обязан сокращаться: если игра переведена — убрать её из списка. */
  it('игры из долга действительно ещё не в каркасе', () => {
    const уже: string[] = [];
    for (const игра of Object.keys(ДОЛГ)) {
      if (/toolbar=\{(?!undefined)/.test(исходникЭкрана(игра))) уже.push(игра);
    }
    // Если сюда попала игра — её пора вынести из ДОЛГА.
    expect({ переведены_но_числятся_в_долге: уже }).toEqual({ переведены_но_числятся_в_долге: [] });
  });
});
