/**
 * 🎓 РАЗБОР «ПРОЧТИ ЭМОЦИЮ» ВЫБИРАЕТ ТО, ЧТО ЗАСЧИТАЕТ ИГРА, И ОПИСЫВАЕТ СОСЕДЕЙ ИХ ЖЕ ПРИЗНАКАМИ.
 *
 * Материал — сами пункты игры (`ITEMS` из экрана), а не копия: разойдись они, разбор учил бы
 * другой игре. Язык слов — как в игре: русские на русском, на остальных языках английские.
 */
import { ITEMS } from '@/app/games/rmet';
import { собратьРазборЭмоций, соседиПункта } from '@/src/games/rmet/teach';

/** Сеянный генератор: пример в разборе случайный, проба обходит тридцать раскладов. */
function сеянный(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (Math.imul(s, 1103515245) + 12345) >>> 0;
    return s / 4294967296;
  };
}

const ЯЗЫКИ = ['ru', 'en', 'de'] as const;
const слова = (язык: string, i: number) => {
  const п = ITEMS[i]!;
  return язык === 'ru'
    ? { верное: п.correct_ru, подсказка: п.hint_ru, варианты: п.options_ru }
    : { верное: п.correct_en, подсказка: п.hint_en, варианты: п.options_en };
};

describe('разбор «Прочти эмоцию»', () => {
  it.each(ЯЗЫКИ)('🔴 %s: выбор в разборе — ровно тот ответ, который засчитает игра', (язык) => {
    let выборов = 0;
    for (let seed = 1; seed <= 30; seed++) {
      const { карточки } = собратьРазборЭмоций(ITEMS, язык, null, сеянный(seed));
      for (const к of карточки.filter((к) => к.вид === 'выбор')) {
        const { верное, варианты } = слова(язык, к.пункт!);
        // Игра: chosen === (language === 'ru' ? correct_ru : correct_en).
        expect(к.выбрано).toBe(верное);
        expect(варианты).toContain(к.выбрано);
        выборов++;
      }
    }
    expect(выборов).toBe(60);
  });

  it.each(ЯЗЫКИ)('🔴 %s: соседа описывают признаки ЕГО пункта, и он — вариант этого задания', (язык) => {
    let сравнений = 0;
    for (let seed = 1; seed <= 30; seed++) {
      const { карточки } = собратьРазборЭмоций(ITEMS, язык, null, сеянный(seed));
      for (const к of карточки.filter((к) => к.вид === 'сравнение')) {
        const пример = слова(язык, к.пункт!);
        const сосед = слова(язык, к.сосед!);
        expect(к.поля!.word).toBe(сосед.верное);
        expect(к.поля!.cues).toBe(сосед.подсказка);
        expect(пример.варианты).toContain(сосед.верное);
        expect(сосед.верное).not.toBe(пример.верное);
        сравнений++;
      }
    }
    expect(сравнений).toBeGreaterThanOrEqual(60);
  });

  it('🔴 пример не совпадает с текущим заданием — иначе разбор просто показал бы ответ', () => {
    for (const язык of ЯЗЫКИ) {
      for (let текущее = 0; текущее < ITEMS.length; текущее++) {
        for (let seed = 1; seed <= 20; seed++) {
          const { примеры } = собратьРазборЭмоций(ITEMS, язык, текущее, сеянный(seed));
          expect(примеры).not.toContain(текущее);
        }
      }
    }
  });

  it.each(ЯЗЫКИ)('%s: между вступлением и итогом каждая карточка называет приём', (язык) => {
    const ПРИЁМЫ = new Set(['teachRmetCues', 'teachRmetCompare', 'teachRmetPick']);
    const { карточки } = собратьРазборЭмоций(ITEMS, язык, null, сеянный(7));
    expect(карточки[0]!.ключ).toBe('teachRmetEyes');
    expect(карточки[карточки.length - 1]!.вид).toBe('готово');
    const середина = карточки.slice(1, -1);
    const названо = середина.filter((к) => ПРИЁМЫ.has(к.ключ)).length;
    expect(`${названо} из ${середина.length}`).toBe(`${середина.length} из ${середина.length}`);
  });

  it.each(ЯЗЫКИ)('%s: годных пунктов хватает на два примера даже без текущего задания', (язык) => {
    // Замер 30.09.2026: русских годных 11 из 18, английских 6. Меньше трёх — и при исключённом
    // текущем задании разбор молча сжался бы до одного примера.
    const годных = ITEMS.filter((_, i) => соседиПункта(ITEMS, i, язык).length > 0).length;
    expect(годных).toBeGreaterThanOrEqual(3);
    for (let текущее = 0; текущее < ITEMS.length; текущее++) {
      expect(собратьРазборЭмоций(ITEMS, язык, текущее, сеянный(3)).примеры).toHaveLength(2);
    }
  });
});
