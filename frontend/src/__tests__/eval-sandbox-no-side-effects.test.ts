import { __evalInДляПроверки as evalIn } from './solid-fill-contrast.test';

describe('песочница вычисления цвета', () => {
  it('🔴 setInterval внутри выражения НЕ заводит настоящий таймер', () => {
    const настоящий = global.setInterval;
    let заведено = 0;
    (global as any).setInterval = (...a: any[]) => { заведено += 1; return настоящий(...(a as [any, any])); };
    try {
      // Ровно та строка, что уронила выпуск.
      evalIn({}, 'setInterval(() => setNow(gameNow()), 100)');
    } finally {
      global.setInterval = настоящий;
    }
    expect(заведено).toBe(0);
  });

  it('выражение с таймером не бросает, а возвращает пустоту', () => {
    expect(evalIn({}, 'setTimeout(() => неизвестнаяФункция(), 5)')).toBeUndefined();
    expect(evalIn({}, 'requestAnimationFrame(() => неизвестнаяФункция())')).toBeUndefined();
  });

  it('fetch внутри выражения не уходит в сеть', () => {
    const настоящий = (global as any).fetch;
    let вызовов = 0;
    (global as any).fetch = () => { вызовов += 1; return Promise.resolve(); };
    try { evalIn({}, 'fetch("https://example.com")'); } finally { (global as any).fetch = настоящий; }
    expect(вызовов).toBe(0);
  });

  it('⚠️ настоящие вычисления цвета НЕ сломаны — глушится только побочное', () => {
    const scope = { textOn: (c: string) => (c === '#000000' ? '#FFFFFF' : '#111111'), GRADIENT: ['#000000'] };
    expect(evalIn(scope, 'textOn(GRADIENT[0])')).toBe('#FFFFFF');
  });

  it('имя из модуля важнее глушилки: свой fetch не перекрывается', () => {
    expect(evalIn({ fetch: () => '#ABCDEF' }, 'fetch()')).toBe('#ABCDEF');
  });
});
