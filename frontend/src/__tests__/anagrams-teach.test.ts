/**
 * РАЗБОР АНАГРАММ РАБОТАЕТ НА НАСТОЯЩИХ ДАННЫХ ИГРЫ.
 *
 * 🔴 ГЛАВНОЕ УТВЕРЖДЕНИЕ: разбор СОБИРАЕТ ЗАГАДАННОЕ СЛОВО из тех самых плиток,
 * что лежат на колесе, — каждую ровно один раз. Разбор, который «объясняет», но
 * не складывается в слово, хуже отсутствия разбора: он учит неверному ходу.
 *
 * 🔴 И СЛОВА БЕРУТСЯ ИЗ БАНКА САМОЙ ИГРЫ, а не выдуманы пробой: `банкКлассики` —
 * тот же источник, из которого экран раздаёт слова. Поэтому проба идёт по десяти
 * языкам: приёмы считаются по банку, и их верность не зависит от того, знаю ли я
 * язык. Там, где знаю (ru/en), сверяю и смысл.
 */
import { разборСлова, текстШагаАнаграмм, КЛЮЧИ_РАЗБОРА_АНАГРАММ } from '@/src/games/anagrams/anagrams-teach';
import { банкКлассики, allWordsLocales } from '@/src/games/anagrams/core/allWords';

/** Колесо игры: те же буквы, что у цели, в другом порядке. */
const колесоИз = (слово: string) => [...слово.toUpperCase()].reverse();

describe('разбор классических анаграмм', () => {
  it('🔴 разбор складывает ЗАГАДАННОЕ слово, каждую плитку ровно один раз — все десять языков', () => {
    const плохо: string[] = [];
    for (const locale of allWordsLocales()) {
      for (const len of [4, 5, 6, 7, 8]) {
        const банк = банкКлассики(locale, len);
        if (банк.length < 4) continue;
        // Берём слова из РАЗНЫХ мест банка, а не первые подряд.
        const проба = [0, 1, Math.floor(банк.length / 3), Math.floor(банк.length / 2), банк.length - 1]
          .map((i) => банк[i]!).filter(Boolean);
        for (const w of проба) {
          const цель = w.toUpperCase();
          const колесо = колесоИз(цель);
          const шаги = разборСлова(цель, колесо, locale);
          if (!шаги.length) { плохо.push(`${locale}/${len}: «${цель}» разбора нет`); continue; }

          const собрано = шаги.map((ш) => ш.ставим.map((i) => колесо[i]!).join('')).join('');
          if (собрано !== цель) плохо.push(`${locale}/${len}: «${цель}» собралось «${собрано}»`);

          const все = шаги.flatMap((ш) => ш.ставим);
          if (new Set(все).size !== все.length) плохо.push(`${locale}/${len}: «${цель}» плитка взята дважды`);
          if (все.length !== [...цель].length) плохо.push(`${locale}/${len}: «${цель}» плиток ${все.length}`);

          const последний = шаги[шаги.length - 1]!;
          if (последний.собрано !== цель) плохо.push(`${locale}/${len}: «${цель}» итог «${последний.собрано}»`);
        }
      }
    }
    expect(плохо.slice(0, 12)).toEqual([]);
  });

  it('🔴 слова разбора засчитываются игрой: они есть в банке той же длины', () => {
    for (const locale of ['ru', 'en']) {
      const банк = банкКлассики(locale, 6).map((w) => w.toUpperCase());
      const цель = банк[10]!;
      expect(разборСлова(цель, колесоИз(цель), locale).length).toBeGreaterThan(1);
      expect(банк).toContain(цель);   // игра примет это слово
    }
  });

  it('🔴 первый шаг — ОСМОТР: ничего не ставит и называет самую редкую букву слова', () => {
    const банк = банкКлассики('ru', 6).map((w) => w.toUpperCase());
    const цель = банк[3]!;
    const шаги = разборСлова(цель, колесоИз(цель), 'ru');
    expect(шаги[0]!.приём).toBe('осмотр');
    expect(шаги[0]!.ставим).toEqual([]);
    expect([...цель]).toContain(шаги[0]!.кусок);

    // Названа действительно САМАЯ редкая буква слова по банку, а не первая попавшаяся.
    const счёт = (б: string) => банк.reduce((n, w) => (w.includes(б) ? n + 1 : n), 0);
    const минимум = Math.min(...[...new Set([...цель])].map(счёт));
    expect(шаги[0]!.слов).toBe(минимум);
    expect(шаги[0]!.изСкольких).toBe(банк.length);
  });

  it('🔴 числа приёмов посчитаны ПО БАНКУ, а не подставлены', () => {
    const банк = банкКлассики('en', 7).map((w) => w.toUpperCase());
    const цель = банк[5]!;
    const шаги = разборСлова(цель, колесоИз(цель), 'en');
    const начало = шаги.find((ш) => ш.приём === 'начало')!;
    const окончание = шаги.find((ш) => ш.приём === 'окончание')!;
    expect(начало.слов).toBe(банк.filter((w) => w.startsWith(начало.кусок)).length);
    expect(окончание.слов).toBe(банк.filter((w) => w.endsWith(окончание.кусок)).length);
    expect(начало.слов).toBeGreaterThan(0);      // само слово — уже одно такое
  });

  it('🔴 чужое слово разбора не получает — буквы обязаны совпасть с колесом', () => {
    expect(разборСлова('СЛОВО', колесоИз('ДРУГОЕ'), 'ru')).toEqual([]);
    expect(разборСлова('ДА', колесоИз('ДА'), 'ru')).toEqual([]);   // короче трёх букв
  });

  it('🔴 текст шага подставляет и кусок, и оба числа', () => {
    const банк = банкКлассики('ru', 6).map((w) => w.toUpperCase());
    const цель = банк[7]!;
    const шаги = разборСлова(цель, колесоИз(цель), 'ru');
    const t = (k: string) => `${k}:{piece}|{n}|{total}`;
    for (const ш of шаги) {
      const текст = текстШагаАнаграмм(ш, t);
      expect(текст).toContain(ш.кусок);
      expect(текст).toContain(String(ш.слов));
      expect(текст).toContain(String(ш.изСкольких));
      expect(текст).not.toContain('{');
    }
    expect(КЛЮЧИ_РАЗБОРА_АНАГРАММ.length).toBe(4);
  });
});
