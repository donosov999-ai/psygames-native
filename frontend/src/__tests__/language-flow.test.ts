/**
 * ЯЗЫКОВОЙ ПОТОК: ЯЗЫК МЕНЯЕТСЯ, НО НЕ КАЖДЫЙ ШАГ.
 *
 * ⚠️ Проверяется ИСПОЛНЕНИЕМ — темы собираются и пересчитываются, а не ищутся
 * словом в исходнике: гейт-чтец зеленеет и от строки в комментарии.
 */
import {
  ЯЗЫКИ_ПОТОКА, ПОСЛЕДОВАТЕЛЬНОСТЬ, долиПовторов, языковыеТемы, игрыПодряд, КЛЮЧИ_УРОВНЕЙ,
} from '@/src/services/languageFlow';
import { темаШаги, ДЛИТЕЛЬНОСТИ } from '@/src/services/chessWarmup';
import { имяИгры } from '@/src/components/WarmupCard';
import { GAMES } from '@/src/constants/games';

declare const __dirname: string;
declare function require(id: string): any;

const уровни = { vocab_srs: 4, cloze: 7, semantic_sort: 2, lexical_decision: 9 };

describe('языковой поток', () => {
  it('языков ровно два — английский и испанский (решение Дениса 08.09.2026)', () => {
    expect([...ЯЗЫКИ_ПОТОКА]).toEqual(['en', 'es']);
  });

  it('🔴 русский целью НЕ бывает — он база и якорь смысла', () => {
    expect(ПОСЛЕДОВАТЕЛЬНОСТЬ).not.toContain('ru');
    const языки = языковыеТемы(уровни).map((т) => т.настройки!.targetLang);
    expect(языки).not.toContain('ru');
  });

  /**
   * 🔴 САМАЯ ВАЖНАЯ ПРОБА НАБОРА. Чистое чередование `en → es → en` даёт одни
   * переключения, и `switchCostMs` вернёт РОВНО НОЛЬ: он вычитает время повторов
   * из времени переключений и при пустом подмножестве отдаёт 0 (разбор в шапке
   * `switching-task.tsx:103`). Без повторов мерить нечего.
   *
   * Числа — литералами, а не через саму последовательность: проба, написанная
   * через проверяемое, зеленеет и на перевёрнутом ряде.
   */
  it('🔴 повторы есть, и их около трети — иначе цена переключения не считается', () => {
    const д = долиПовторов();
    expect(`переключений ${д.переключений} · повторов ${д.повторов}`)
      .toBe('переключений 4 · повторов 2');
    expect(Math.round(д.доля * 100)).toBe(33);
  });

  it('счёт замкнут в кольцо — переход с последнего шага на первый тоже переход', () => {
    // en,en → повтор. Если бы кольцо не считалось, повтор был бы один.
    expect(долиПовторов(['en', 'en', 'es']).повторов).toBe(1);
    expect(долиПовторов(['en', 'es', 'es']).повторов).toBe(1);
    // Всё одно и то же — переключений нет вовсе.
    expect(долиПовторов(['es', 'es', 'es'])).toEqual({ переключений: 0, повторов: 3, доля: 1 });
  });

  it('короткий ряд не роняет счёт', () => {
    expect(долиПовторов([])).toEqual({ переключений: 0, повторов: 0, доля: 0 });
    expect(долиПовторов(['en'])).toEqual({ переключений: 0, повторов: 0, доля: 0 });
  });

  it('🔴 две одинаковые игры подряд не стоят — это два круга одной, а не зарядка', () => {
    const и = игрыПодряд();
    const пары: string[] = [];
    for (let k = 0; k < и.length; k += 1) {
      if (и[k] === и[(k + 1) % и.length]) пары.push(`${k}:${и[k]}`);
    }
    expect(пары).toEqual([]);
  });

  it('у каждого шага свой уровень из СОБСТВЕННОЙ лестницы игры', () => {
    const т = языковыеТемы(уровни);
    const пары = т.map((x) => `${x.game_id}=${x.уровень}`);
    expect(пары).toEqual([
      'vocab_srs=4', 'cloze=7', 'semantic_sort=2', 'lexical_decision=9',
      'vocab_srs=4', 'semantic_sort=2',
    ]);
  });

  it('уровня нет — берётся первый, а не ноль и не отрицательный', () => {
    expect(языковыеТемы({}).every((т) => т.уровень === 1)).toBe(true);
    expect(языковыеТемы({ vocab_srs: -5 }).every((т) => т.уровень >= 1)).toBe(true);
  });

  it('ключи уровней перечислены и без дублей', () => {
    expect([...КЛЮЧИ_УРОВНЕЙ].sort())
      .toEqual(['cloze', 'lexical_decision', 'semantic_sort', 'vocab_srs']);
  });

  /**
   * 🔴 ЯЗЫК ДОХОДИТ ДО ШАГА ЗАРЯДКИ. Проверяется через настоящую сборку
   * `темаШаги`, а не через сами темы: между ними лежит подрезка по времени, и
   * она могла бы оставить только один язык.
   */
  it('🔴 в собранной зарядке ЕСТЬ ОБА языка на любой длительности', () => {
    for (const мин of ДЛИТЕЛЬНОСТИ) {
      const шаги = темаШаги(языковыеТемы(уровни), мин);
      const языки = new Set(шаги.map((ш) => String(ш.settings?.targetLang)));
      expect(`${мин} мин: языков ${[...языки].sort().join(',')}`)
        .toBe(`${мин} мин: языков en,es`);
    }
  });

  it('🔴 и повторы доживают до собранной зарядки, а не срезаются подрезкой', () => {
    for (const мин of ДЛИТЕЛЬНОСТИ) {
      const ряд = темаШаги(языковыеТемы(уровни), мин).map((ш) => String(ш.settings?.targetLang));
      let пов = 0;
      for (let i = 1; i < ряд.length; i += 1) if (ряд[i] === ряд[i - 1]) пов += 1;
      expect(`${мин} мин: повторов ${пов > 0}`).toBe(`${мин} мин: повторов true`);
    }
  });

  it('уровень едет в игру вместе с языком, а не вместо него', () => {
    const шаг = темаШаги(языковыеТемы(уровни), 10)[0]!;
    expect(шаг.settings).toEqual({ level: 4, targetLang: 'en' });
  });

  /**
   * 🔴 СОСТАВ ЗАРЯДКИ ЧИТАЕТСЯ ЧЕЛОВЕКОМ, А НЕ МАШИНОЙ.
   *
   * До 08.09.2026 карточка звала `t(game_id)`, и это работало только там, где
   * идентификатор случайно совпал с ключом словаря. У пяти игр из девяти они
   * разные, и человек видел `vocab_srs`, `chess_blind`, `phonemic_fluency`.
   * Проба ловит класс: ни одно имя в составе не должно выглядеть как id.
   */
  it('🔴 в составе стоят имена игр, а не идентификаторы', () => {
    // ⚠️ `t` — тождественная: проверяется ЛОГИКА поиска имени, а не перевод.
    // Что ключ есть в словаре, сторожит проба ниже и dictionary-duplicates.
    const t = (k: string) => k;
    for (const тема of языковыеТемы(уровни)) {
      const g = GAMES.find((x) => x.id === тема.game_id)!;
      // Имя обязано прийти ИЗ nameKey каталога. У `cloze` он совпадает с id — это
      // законно; ломается не совпадение, а поиск по id вместо nameKey.
      expect(`${тема.game_id} → ${имяИгры(тема.game_id, t)}`).toBe(`${тема.game_id} → ${g.nameKey}`);
      expect(`${тема.game_id}: подчёркиваний ${имяИгры(тема.game_id, t).includes('_')}`)
        .toBe(`${тема.game_id}: подчёркиваний false`);
    }
  });

  it('🔴 и у ВСЕХ игр каталога имя разрешается — не только у моих', () => {
    const t = (k: string) => k;
    const немые = GAMES.filter((g) => имяИгры(g.id, t) === g.id && g.nameKey !== g.id).map((g) => g.id);
    expect(немые).toEqual([]);
  });

  it('🔴 и каждый nameKey из состава ЕСТЬ в базовом словаре', () => {
    const { readFileSync } = require('fs');
    const { join } = require('path');
    const словарь = readFileSync(join(__dirname, '..', 'contexts', 'LanguageContext.tsx'), 'utf8');
    for (const тема of языковыеТемы(уровни)) {
      const g = GAMES.find((x) => x.id === тема.game_id)!;
      expect(`${g.id}: ключ ${g.nameKey} в словаре ${словарь.includes(`${g.nameKey}:`)}`)
        .toBe(`${g.id}: ключ ${g.nameKey} в словаре true`);
    }
  });

  it('игра не из каталога — показываем id, а не пустоту', () => {
    const t = () => '';
    expect(имяИгры('такой_игры_нет', t)).toBe('такой_игры_нет');
  });
});
