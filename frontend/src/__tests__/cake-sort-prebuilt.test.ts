/**
 * 🔴 ВШИТЫЙ УРОВЕНЬ ОБЯЗАН СОВПАДАТЬ С ТЕМ, ЧТО РАЗДАСТ ИГРА.
 *
 * Файл `levels.json` несёт доску и её точный минимум ходов, посчитанные офлайн
 * с бюджетом в тринадцать раз больше, чем позволяет устройство. Из этого следует
 * ровно одна опасность: ДВЕ ПРАВДЫ ОБ ОДНОМ УРОВНЕ. Игрок видит доску, которую
 * раздал `deal(L)`, а звёзды считаются по минимуму, посчитанному для ДРУГОЙ
 * доски, — и никакой формулой это не видно, только сверкой.
 *
 * ⚠️ Сверяется СОСТАВ доски, а не факт наличия записи: запись есть всегда, и
 * проверка «файл не пуст» зеленела бы на любом мусоре.
 */
import { prebuilt, prebuiltMin, prebuiltPath, PREBUILT_COUNT } from '@/src/games/cake-sort/core/prebuilt';
import { deal } from '@/src/games/cake-sort/core/level';
import { makeBoard, allSectors, moveType, isCleared, CIRCLE } from '@/src/games/cake-sort/core/plate';
import { prebuiltSolution } from '@/src/games/cake-sort/core/solutions';
import { solve, minMoves } from '@/src/games/cake-sort/core/solver';
import { referenceFor, starsFor, moveReference } from '@/src/games/cake-sort/core/stars';

jest.setTimeout(600000);

/**
 * 🔴 СКОЛЬКО УРОВНЕЙ ВООБЩЕ МОГУТ ПОЛУЧИТЬ ТОЧНЫЙ МИНИМУМ — ЗАМЕР, А НЕ ЖЕЛАНИЕ.
 *
 * Здесь стояла восьмёрка: столько доходило до дна на прежних досках. После того
 * как очередь входящих стала настоящей, материал уровня вырос (L7 — 42 сектора
 * против 36), и граница сдвинулась на L6.
 *
 * ⚠️ Проверено, что её нельзя выкупить бюджетом: L7 не доходит до дна и при
 * 400 000 узлов (11 с, 643 МБ кучи) — замер 07.09.2026. То есть пятёрка ниже это
 * не «ослабленный гейт», а перемеренная граница; поднять её обратно можно только
 * уменьшив уровни, то есть отменив саму очередь.
 *
 * 🔴 ПЕРЕМЕРЕНО 16.09.2026: ПЯТЬ → ЧЕТЫРЕ, ИЗ-ЗА СВОБОДНОГО ВЫБОРА КУСКА.
 * Ход берёт любой вид с тарелки, ветвление шире, и A* дорожает на порядок.
 * 📍 Замер (`scripts/measure/cake-exact-min-budget.measure.ts`, бюджет 400 000):
 *   L3 — минимум 15, 25 489 узлов · L4 — 15, 18 206 узлов ·
 *   L5 и L6 — НЕ ДОСТАЛ, 400 001 узел (23 и 52 с).
 * Выкупить бюджетом нельзя по той же причине, что и раньше: следующий уровень
 * добавляет вид начинки.
 *
 * ⚠️ И это НЕ ослабляет звёзды: где минимума нет, эталон — длина предъявленной
 * партии (`path`), и три звезды достижимы построением на всех 120 уровнях —
 * гейт `cake-stars-reachable`.
 */
const МИНИМУМОВ_НЕ_МЕНЬШЕ = 4;

describe('вшитые уровни', () => {
  it('есть что проверять — файл не пуст', () => {
    expect(PREBUILT_COUNT).toBeGreaterThanOrEqual(12);
  });

  /**
   * ⚠️ ВЫБОРКОЙ, А НЕ ПО ВСЕМ СТА ДВАДЦАТИ (задача af4c7ff1). `deal(L)` внутри
   * себя ДОКАЗЫВАЕТ решаемость поиском, а поиск дорожает с ветвлением: замер
   * 23.09.2026 — L5 4,2 с, L10 25,0 с на бюджете 20000. Сверка всей лестницы
   * стоила сотни секунд ради инварианта «файл не разошёлся с генератором»,
   * который ломается КОДОМ, а не отдельным уровнем: разойдись генератор — это
   * увидит любая из двадцати точек выборки.
   * Граница названа: за пределами выборки расхождение файла с генератором эта
   * проба не поймает.
   */
  it('🔴 вшитая доска совпадает с тем, что раздаёт игра на том же уровне', () => {
    const расхождения: string[] = [];
    const выборка = [1, 2, 3, 5, 8, 12, 17, 23, 30, 38, 47, 57, 68, 80, 93, 107, PREBUILT_COUNT];
    for (const L of выборка) {
      const у = prebuilt(L);
      if (!у) { расхождения.push(`L${L}: записи нет`); continue; }
      const { board, cfg } = deal(L);
      if (JSON.stringify(у.plates) !== JSON.stringify(board.plates)) расхождения.push(`L${L}: тарелки не те`);
      if (JSON.stringify(у.queue) !== JSON.stringify(board.queue)) расхождения.push(`L${L}: очередь не та`);
      if (у.types !== cfg.types) расхождения.push(`L${L}: видов ${у.types} против ${cfg.types}`);
    }
    expect(расхождения).toEqual([]);
  });

  /**
   * 🔴 РЕШАЕМОСТЬ ДОКАЗЫВАЕТСЯ ПРОИГРЫВАНИЕМ ЗАПИСАННОГО РЕШЕНИЯ, А НЕ ПОИСКОМ
   * (задача af4c7ff1). Это и дешевле (33 мс против сотен секунд на сто двадцать
   * уровней), и доказательнее: видно конкретную последовательность ходов, а не
   * «поиск что-то нашёл». Решения лежат в `core/solutions.json`, их пишет
   * `tools/record-solutions.gen.ts` и сторожит `cake-sort-solutions.test.ts`.
   */
  it('🔴 каждая вшитая доска решаема и кратна кругу', () => {
    const плохо: string[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      const у = prebuilt(L) as { plates: number[][]; queue: number[][] };
      const b = makeBoard(у.plates, у.queue);
      if (allSectors(b).length % CIRCLE !== 0) плохо.push(`L${L}: секторов не кратно кругу`);
      const решение = prebuiltSolution(L);
      if (!решение) { плохо.push(`L${L}: решение не записано`); continue; }
      let стол = b;
      let сломалось = -1;
      for (let i = 0; i < решение.length && сломалось < 0; i += 1) {
        const m = решение[i] as { from: number; type: number; to: number };
        const следующая = moveType(стол, m.from, m.type, m.to);
        if (!следующая) { сломалось = i; break; }
        стол = следующая;
      }
      if (сломалось >= 0) плохо.push(`L${L}: ход ${сломалось + 1} записанного решения незаконен`);
      else if (!isCleared(стол)) плохо.push(`L${L}: записанное решение стол не разобрало`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 ВШИТЫЙ МИНИМУМ — НАСТОЯЩИЙ, А НЕ ОКРУГЛЁННАЯ ОЦЕНКА. Сверяем с живым A*
   * там, где он успевает: если файл несёт другое число, звёзды врут молча.
   */
  it('🔴 вшитый минимум совпадает с живым расчётом там, где расчёт успевает', () => {
    const врут: string[] = [];
    let сверено = 0;
    for (let L = 1; L <= Math.min(6, PREBUILT_COUNT); L += 1) {
      const вшит = prebuiltMin(L);
      if (вшит === null) continue;
      const живой = minMoves(deal(L).board, 400000);
      if (живой.moves === null) continue;
      сверено += 1;
      if (живой.moves !== вшит) врут.push(`L${L}: в файле ${вшит}, живой расчёт ${живой.moves}`);
    }
    expect(врут).toEqual([]);
    // Обе стороны непусты: если сверять было нечего, проверка зелена вслепую.
    expect(сверено).toBeGreaterThanOrEqual(3);
  });

  /**
   * 🔴 И ГЛАВНОЕ, РАДИ ЧЕГО ВСЁ: ТАМ, ГДЕ МИНИМУМ ЕСТЬ, ЗВЁЗДЫ ИДУТ ПО НЕМУ.
   * Идеальная игра обязана давать три звезды — иначе высшая оценка недостижима,
   * ровно тот дефект, который сортировка товаров пережила на 95 % досок.
   */
  it('🔴 идеальная игра даёт три звезды на каждом уровне со вшитым минимумом', () => {
    const мимо: string[] = [];
    let проверено = 0;
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      const m = prebuiltMin(L);
      if (m === null) continue;
      проверено += 1;
      const у = prebuilt(L) as { types: number; queue: number[][] };
      // Кругов на уровне — виды на столе плюс стопки очереди; эталон считается по ним.
      const кругов = у.types + у.queue.length;
      if (starsFor(m, кругов, m) !== 3) мимо.push(`L${L}: минимум ${m} не даёт трёх звёзд`);
      // И эталон обязан браться от минимума, а не от калибровки.
      if (referenceFor(кругов, m) !== m) мимо.push(`L${L}: эталон не равен минимуму`);
    }
    expect(мимо).toEqual([]);
    expect(проверено).toBeGreaterThanOrEqual(МИНИМУМОВ_НЕ_МЕНЬШЕ);
  });

  /**
   * 🔴 «НЕ ЗНАЮ» ОБЯЗАНО БЫТЬ `null`, А НЕ ЧИСЛОМ. Ветка отсутствия минимума
   * опаснее всех: подставь она единицу — эталон станет равен одному ходу, и три
   * звезды окажутся недостижимы на всех таких уровнях разом. Мутация «вернуть 1
   * вместо null» пережила первую редакцию этой пробы, потому что в файле почти у
   * всех уровней минимум есть. Подаём вход руками.
   */
  it('🔴 у уровня без записи минимум — null, а не выдуманное число', () => {
    expect(prebuiltMin(99999)).toBeNull();
    expect(prebuilt(99999)).toBeNull();
    // И эталон в этом случае берёт калибровку, а не единицу.
    // ⚠️ Сравнение с самой калибровкой, а не «больше 20»: число 20 держалось на
    // прежних 5,6 хода на круг и краснело бы на любой честной перекалибровке.
    const э = referenceFor(5, prebuiltMin(99999));
    expect(э).toBe(moveReference(5));
    expect(э).toBeGreaterThan(5);
    // Три звезды при таком эталоне достижимы — а при подставленной единице нет.
    expect(starsFor(э, 5, prebuiltMin(99999))).toBe(3);
  });

  /**
   * 🔴 ГРАНИЦА ТОЧНОГО МИНИМУМА — РЕЗКАЯ, И ЭТО ЗАМЕР, А НЕ ДОГАДКА.
   *
   * Первая редакция требовала «минимум есть у большинства» — я это предположил.
   * Прогон опроверг: при офлайн-бюджете 400 000 узлов минимум считается ровно
   * для **L1…L10** и дальше НИКОГДА. Не «редеет», не «через один» — обрывается.
   * Поиск экспоненциален, и следующий уровень добавляет вид начинки, то есть
   * умножает пространство состояний.
   *
   * Проверяем настоящую форму: непрерывный отрезок с начала, за которым только
   * пусто. Дырка посреди отрезка означала бы, что генератор считал не то, что
   * раздаёт игра.
   */
  it('🔴 минимум идёт непрерывным отрезком с первого уровня и обрывается', () => {
    const есть: number[] = [];
    const нет: number[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) (prebuiltMin(L) !== null ? есть : нет).push(L);
    expect(есть.length).toBeGreaterThanOrEqual(МИНИМУМОВ_НЕ_МЕНЬШЕ);
    // Отрезок начинается с первого уровня и идёт подряд.
    expect(есть).toEqual(Array.from({ length: есть.length }, (_, i) => i + 1));
    // За ним — только пусто, без дырок посреди.
    expect(нет.every((L) => L > (есть[есть.length - 1] as number))).toBe(true);
  });

  /**
   * ⚠️ И ТАМ, ГДЕ МИНИМУМА НЕТ, ЗВЁЗДЫ ИДУТ ОТ КАЛИБРОВКИ — хуже минимума, но
   * честнее выдумки. Проверяем, что эталон при этом остаётся достижимым.
   */
  it('🔴 выше границы эталон берётся от записанной партии и остаётся достижимым', () => {
    const плохо: string[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      if (prebuiltMin(L) !== null) continue;
      const у = prebuilt(L) as { types: number; queue: number[][] };
      const кругов = у.types + у.queue.length;
      /*
       * ⚠️ С 16.09.2026 эталон выше границы — длина записанной партии, а не
       * калибровка по видам: одно число на круг честным не бывает (разбор —
       * `referenceFor`). Проверяем то, что берёт экран.
       */
      const э = referenceFor(кругов, null, prebuiltPath(L));
      if (э <= 0) плохо.push(`L${L}: эталон ${э}`);
      if (э !== prebuiltPath(L)) плохо.push(`L${L}: эталон ${э} не равен записанной партии ${prebuiltPath(L)}`);
      if (starsFor(э, кругов, null, prebuiltPath(L)) !== 3) плохо.push(`L${L}: игра ровно по эталону не даёт трёх звёзд`);
    }
    expect(плохо).toEqual([]);
  });
});
