/**
 * 🔴 СЧЁТЧИК ПРОЙДЕННОГО НАЗЫВАЕТ, ЧЕЙ ОН, КОГДА ИГРОК НЕ В УРОВНЯХ.
 *
 * Отчёт ee0889e7 (12.09.2026, iOS 2.54.5), дословно: «Свободная игра и что под ней
 * зачем эта строка». На экране подряд стояли «Свободная игра», «Пройдено: 0/50» и
 * кнопка «Начать уровни» — три вещи из разных смыслов. Счётчик относится к режиму
 * УРОВНЕЙ и в свободной игре не двигается никогда, а читался как показание того,
 * что человек делает сейчас.
 *
 * ⚠️ ПОПУТНО ВСКРЫЛОСЬ БОЛЬШЕЕ, и это записано отдельной находкой: весь экран
 * лаборатории говорит по-русски со всеми двенадцатью языками — строки вшиты
 * литералами мимо словаря. Гейт `ci-i18n-hardcode-guard` их не видит по устройству:
 * он ловит тернарники `language === 'ru' ? … : …`, а не простые литералы.
 * Поэтому новые строки этой починки заведены КАК ПОЛОЖЕНО — через словарь на 12
 * языков, а не дописаны пятым литералом.
 */
import { translateFor, LANGUAGES } from '@/src/contexts/LanguageContext';

const КЛЮЧИ = ['spatialFreePlay', 'spatialFreePlayHint', 'spatialDoneInLevels', 'spatialDone'];
/** Десять языков поверх базовых ru/en — у каждого свой файл. */
const ОВЕРЛЕИ = ['es', 'de', 'zh', 'hi', 'pt', 'fr', 'it', 'ja', 'ko', 'ar'];

declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');

describe('строка режима лаборатории объясняет, чей это счёт', () => {
  /**
   * 🔴 ПРОВЕРЯЕМ ФАЙЛЫ ОВЕРЛЕЕВ, А НЕ `translateFor`, И ВОТ ПОЧЕМУ.
   * Первый вид этой пробы спрашивал `translateFor(язык, ключ)` и был СЛЕП: у него
   * есть запасной ход на базовые ru/en, поэтому убери перевод из немецкого файла —
   * функция вернёт английскую строку, и проба останется зелёной. Проверено мутацией
   * 16.09.2026: ключ удалён из `de.ts`, проба не заметила.
   * Значит спрашивать надо сами файлы, как это делает `i18n-coverage`.
   */
  it('🔴 все четыре ключа есть в КАЖДОМ файле перевода, а не только в базе', () => {
    const нет: string[] = [];
    for (const язык of ОВЕРЛЕИ) {
      const файл = path.join(__dirname, '..', 'contexts', 'translations', `${язык}.ts`);
      const текст = fs.readFileSync(файл, 'utf8');
      for (const ключ of КЛЮЧИ) if (!текст.includes(`"${ключ}"`)) нет.push(`${язык}: нет ${ключ}`);
    }
    expect(нет.slice(0, 5)).toEqual([]);
  });

  it('и в базовом словаре тоже — иначе русский с англичанином увидят имя ключа', () => {
    const нет = КЛЮЧИ.filter((к) => translateFor('ru', к) === к || translateFor('en', к) === к);
    expect(нет).toEqual([]);
  });

  it('🔴 «в уровнях пройдено» и «пройдено» — РАЗНЫЕ подписи, иначе чинить было нечего', () => {
    const плохо: string[] = [];
    for (const { code } of LANGUAGES) {
      const один = translateFor(code, 'spatialDone'), другой = translateFor(code, 'spatialDoneInLevels');
      if (один === другой) плохо.push(`${code}: подписи совпали — «${один}»`);
    }
    expect(плохо).toEqual([]);
  });

  it('подсказка свободной игры говорит, ГДЕ начать уровни, а не только что тут не считается', () => {
    const ru = translateFor('ru', 'spatialFreePlayHint');
    expect(ru).toMatch(/уровн/i);
  });
});
