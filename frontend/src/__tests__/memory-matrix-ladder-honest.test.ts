/**
 * 🔴 ЛЕСТНИЦА НЕ СМЕЕТ ОБЕЩАТЬ РОСТ, КОТОРОГО ПОЛЕ НЕ ВЫДАЁТ.
 *
 * ЗАЧЕМ. Число уровня — это то, чем игрок меряется в лидерборде и рекорд-строке.
 * Если два соседних уровня требуют одного и того же, разница между ними —
 * не достижение, а лишний проход.
 *
 * 🔴 ЧТО НАЙДЕНО 06.09.2026. Сложность `memory-matrix` считается в ДВУХ местах,
 * и они разошлись:
 *
 *   levelParams()  →  baseFlashes = 3 + floor(level / 1.5)   — растёт без потолка
 *   newRound()     →  need = min(floor((total-1)/2), …)      — зажат 17 при двух сериях
 *
 * `levelParams` — то, что читают гейты и правила уровня. `newRound` — то, что
 * человек видит на поле. Замер прогоном обеих формул, L1…L60, сетка 6×6:
 *
 *   L20 → 16 клеток   L21 → 17   L30 → 17   L40 → 17   L50 → 17   L60 → 17
 *   при этом levelParams обещает   L30 → 23   L40 → 29   L60 → 43
 *
 * То есть с L21 по L60 — 39 уровней, неотличимых на ощупь, и каждый требует
 * прохождения. Это ровно тот дефект, что описан в ТЗ §4.4 на примере «Соедини
 * точки»: уровни выглядят растущими, пока смотришь на ОБЪЯВЛЕНИЕ сложности, а
 * не на ИСПОЛНЕНИЕ. Гейт `level-rule-threshold` его не видит по той же причине —
 * он сверяет пороги правил по `levelParams`.
 *
 * ⚠️ `memory-matrix` стоит в ДВУХ развилках («Объём памяти» и «Зрительная
 * память»), поэтому починка видна в двух местах.
 *
 * ЧТО ПРОВЕРЯЕТ ЭТА ПРОБА. Не «сколько клеток правильно» — это вопрос замысла,
 * а инвариант, верный при ЛЮБОМ решении: пока `levelParams` объявляет рост,
 * поле обязано этот рост выдавать. Инвариант держится и если поставить честный
 * потолок лестницы, и если поднять сетку до 7×7.
 */
import { levelParams } from '@/app/games/memory-matrix';

/**
 * Точная копия расчёта из `newRound()` — memory-matrix.tsx:166-170.
 * ⚠️ Копия, а не импорт: `newRound` живёт внутри компонента и наружу не выведен.
 * Разъедется — разойдётся и эта проба, поэтому строки-источник названы выше.
 */
function клетокНаПоле(level: number, round: number, mode: 'static' | 'sequential'): number {
  const p = levelParams(level);
  const total = p.gridSize * p.gridSize;
  const two = p.seriesCount === 2 && mode === 'static';
  return Math.min(
    two ? Math.floor((total - 1) / 2) : total - 1,
    p.baseFlashes + Math.floor((round - 1) / 3),
  );
}

/** Последний уровень, на котором хоть что-то менялось. */
function рострКончается(fn: (l: number) => string, доL = 60): number {
  let last = 1;
  let prev = fn(1);
  for (let L = 2; L <= доL; L++) {
    const cur = fn(L);
    if (cur !== prev) last = L;
    prev = cur;
  }
  return last;
}

describe('memory-matrix: лестница честна перед полем', () => {
  it('замер зафиксирован: где кончается рост в каждом режиме', () => {
    const статик = рострКончается((L) => [1, 2, 3, 4, 5].map((r) => клетокНаПоле(L, r, 'static')).join(','));
    const последов = рострКончается((L) => [1, 2, 3, 4, 5].map((r) => клетокНаПоле(L, r, 'sequential')).join(','));
    expect(`static=${статик} sequential=${последов}`).toBe('static=21 sequential=48');
  });

  it('зажим поля — не выдумка пробы, а 17 клеток при двух сериях на 6×6', () => {
    expect(levelParams(21).seriesCount).toBe(2);
    expect(levelParams(21).gridSize).toBe(6);
    expect(клетокНаПоле(60, 1, 'static')).toBe(17);
  });

  /**
   * 🔴 ГЛАВНОЕ. Обещание лестницы против того, что кладут на поле.
   *
   * ⚠️ `it.failing` — дефект ЖИВ и ждёт решения Дениса (честный потолок L21 либо
   * сетка 7×7); оба ответа этот инвариант восстанавливают. Проба держит набор
   * зелёным, пока дефект жив, и САМА краснеет в день починки, требуя снять
   * `.failing`. Это будильник на приёмку, а не заглушка.
   */
  it.failing('🔴 растёт обещание — растёт и поле: ни одного уровня, где обещали больше, а дали столько же', () => {
    const враньё: string[] = [];
    for (let L = 2; L <= 60; L++) {
      const обещаноБольше = levelParams(L).baseFlashes > levelParams(L - 1).baseFlashes;
      const наПолеБольше = клетокНаPоле(L) > клетокНаPоле(L - 1);
      if (обещаноБольше && !наПолеБольше) {
        враньё.push(`L${L}: обещано ${levelParams(L).baseFlashes}, на поле ${клетокНаPоле(L)}`);
      }
    }
    expect(`уровней с пустым обещанием: ${враньё.length}`).toBe('уровней с пустым обещанием: 0');
  });
});

/** Клеток в первом раунде режима static — тот режим, что включается сам с L11. */
function клетокНаPоле(level: number): number {
  return клетокНаПоле(level, 1, 'static');
}
