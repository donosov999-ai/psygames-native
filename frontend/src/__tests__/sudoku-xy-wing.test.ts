/**
 * XY-WING СРАБАТЫВАЕТ, А НЕ ЛЕЖИТ МЁРТВЫМ КОДОМ.
 *
 * 🔴 ЗАЧЕМ ИМЕННО ТАКАЯ ПРОБА. Техника, добавленная в лестницу, легко оказывается
 * никогда не вызванной: условие не выполняется, ошибка в поиске, не зарегистрирована
 * в списке. Проверять это через поле `hardest` НЕЛЬЗЯ — я на этом споткнулся 09.09:
 * `hardest` показывает самую сложную ПРИМЕНЁННУЮ технику, а на нерешённой доске она
 * всегда `guess`, и XY-Wing не проявился бы, даже срабатывая на каждой доске.
 *
 * Работает разность на ОДНОМ И ТОМ ЖЕ корпусе: с техникой оценщик проходит дальше.
 * Замер 09.09 по 46 банковским доскам (уровни 58–80, профили p1/p2):
 *   с XY-Wing   — 901 шаг, цена 1955
 *   без него    — 873 шага, цена 1850
 * Разность 28 шагов и 105 цены — техника выстреливает.
 *
 * ⚠️ ЧТО ЭТА ПРОБА НЕ ДОКАЗЫВАЕТ. Она не проверяет ПРАВИЛЬНОСТЬ исключений: неверная
 * техника тоже «проходит дальше», просто врёт. Правильность держат гейты
 * единственности решения и совпадения ступени с доской — они прогоняются рядом.
 */
import { bankBoardForLevel } from '@/src/services/sudoku-bank';
import { gradePuzzle } from '@/src/services/sudoku-grade';
import { dimsForSize } from '@/src/services/sudoku-core';

/** Корпус фиксирован: уровни 58–80 × два профиля. Меняешь корпус — перемеряй числа. */
const УРОВНИ = Array.from({ length: 23 }, (_, i) => 58 + i);
const ПРОФИЛИ = ['p1', 'p2'];

/** Замер 09.09.2026 БЕЗ xy_wing: 873 шага. С ним — 901. Порог между ними. */
const ПОЛ_ШАГОВ = 890;

const d = dimsForSize(9);
const итог = (() => {
  let шагов = 0; let цена = 0; let досок = 0;
  for (const L of УРОВНИ) {
    for (const pid of ПРОФИЛИ) {
      const b = bankBoardForLevel(L, pid, 0);
      const g = gradePuzzle(b.puzzle, { N: d.N, BR: d.BR, BC: d.BC, variant: 'none' });
      досок += 1; шагов += g.steps; цена += g.cost;
    }
  }
  return { шагов, цена, досок };
})();

test('есть что мерить — корпус не пуст', () => {
  expect(`досок ${итог.досок}`).toBe('досок 46');
});

test(`🔴 XY-Wing выстреливает: шагов ${итог.шагов} при пороге ${ПОЛ_ШАГОВ} (без него было 873)`, () => {
  expect(`шагов ${Math.max(итог.шагов, ПОЛ_ШАГОВ)} ≥ ${ПОЛ_ШАГОВ}`)
    .toBe(`шагов ${итог.шагов} ≥ ${ПОЛ_ШАГОВ}`);
});

test('🔴 техника зарегистрирована в лестнице и имеет ступень', () => {
  const { TECHNIQUE_TIER } = require('@/src/services/sudoku-grade') as {
    TECHNIQUE_TIER: Record<string, number>;
  };
  expect(`xy_wing ступень ${TECHNIQUE_TIER.xy_wing}`).toBe('xy_wing ступень 7');
  expect(`выше X-Wing: ${TECHNIQUE_TIER.xy_wing > TECHNIQUE_TIER.x_wing}`).toBe('выше X-Wing: true');
  expect(`ниже догадки: ${TECHNIQUE_TIER.xy_wing < TECHNIQUE_TIER.guess}`).toBe('ниже догадки: true');
});
