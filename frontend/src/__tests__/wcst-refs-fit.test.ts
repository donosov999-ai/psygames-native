/**
 * ЧЕТЫРЕ ЭТАЛОНА WCST ЧИТАЮТСЯ ОДНИМ ВЗГЛЯДОМ — ОДНОЙ СТРОКОЙ ЛИБО 2 + 2.
 *
 * 🔴 ЧТО ЛОМАЛОСЬ. `refCard` имел зашитый `width: 80`. Четыре карточки просят
 * 4·80 + 3·8 = 344 px, а слот тулбара в GameShell держит симметричный отступ
 * FAB_GUTTER = 66 с обеих сторон под плавающую кнопку отзыва: на телефоне 390
 * остаётся 258. Ряд не влезал, `flexWrap` уносил четвёртую карточку вниз, и
 * выходило 3 + 1 — снято скриншотом живой игры 07.09.2026.
 *
 * ⚠️ ПОЧЕМУ ЭТО НЕ ПРО КРАСОТУ. В методике четыре эталона РАВНОПРАВНЫ: человек
 * сверяет карточку со всеми сразу. Вынесенный вниз читается как «особый», хотя он
 * такой же, и это подсказка, которой в пробе быть не должно.
 *
 * Отступ в GameShell — общий слой, менять не нам, да и незачем: там же в
 * комментарии к FAB_GUTTER сказано прямо — «игры, считающие размеры от неё,
 * обязаны считать от ширины экрана, а не от зашитых чисел». Зашитая 80 и была
 * ошибкой. Здесь закреплено, что её больше нет.
 */
import { refCardWidth } from '@/app/games/wcst';

/** Норма попадания пальцем (Material), её же держит tap-target-audit --mode=field. */
const MIN_TAP = 48;
/** GameShell: FAB_GUTTER 66 слева и справа. */
const GUTTER = 132;
const GAP = 8;

const ЭКРАНЫ = [320, 360, 375, 390, 414, 428, 768];

describe('WCST: четыре эталона помещаются в тулбар', () => {
  it('есть что проверять — функция отвечает на всех ширинах', () => {
    for (const w of ЭКРАНЫ) expect(typeof refCardWidth(w).w).toBe('number');
  });

  it('🔴 ряд НИКОГДА не вылезает за доступную ширину', () => {
    const плохие = ЭКРАНЫ.map((W) => {
      const { w, ряд } = refCardWidth(W);
      const занято = ряд === 4 ? 4 * w + 3 * GAP : 2 * w + GAP;
      return { W, занято, доступно: W - GUTTER };
    }).filter((x) => x.занято > x.доступно);
    expect(плохие).toEqual([]);
  });

  it('🔴 карточка не мельче нормы попадания пальцем', () => {
    const мелкие = ЭКРАНЫ.map((W) => ({ W, w: refCardWidth(W).w })).filter((x) => x.w < MIN_TAP);
    expect(мелкие).toEqual([]);
  });

  /**
   * 🔴 ГЛАВНОЕ: НИКОГДА 3 + 1. Разрешены только две раскладки — все четыре в строку
   * или две пары. Проба закреплена на возвращаемом `ряд`, потому что именно он
   * задаёт `maxWidth` контейнера, а без него `flexWrap` сам выберет 3 + 1.
   */
  it('🔴 раскладка только 4 в строку или 2 + 2 — третьего не дано', () => {
    const плохие = ЭКРАНЫ.map((W) => ({ W, ряд: refCardWidth(W).ряд })).filter((x) => x.ряд !== 4 && x.ряд !== 2);
    expect(плохие).toEqual([]);
  });

  it('на телефоне 390 (замер живой игры) все четыре в строку', () => {
    const r = refCardWidth(390);
    expect(`${r.ряд} в строке, карточка ${r.w}`).toBe(`4 в строке, карточка ${r.w}`);
    expect(4 * r.w + 3 * GAP).toBeLessThanOrEqual(390 - GUTTER);
  });

  /**
   * 🔴 И ЭТО НЕ ЗЕЛЁНОЕ ВСЛЕПУЮ: на широком экране карточка обязана дорасти до
   * прежних 80 и НЕ растягиваться дальше. Проба ловит и «всё сжал до минимума»,
   * и «растянул на весь экран» — обе прошли бы мимо трёх проверок выше.
   */
  it('🔴 на широком экране карточка возвращается к 80, но не больше', () => {
    expect(refCardWidth(768).w).toBe(80);
    expect(refCardWidth(1200).w).toBe(80);
    // и на узком она действительно МЕНЬШЕ — значит функция считает, а не отдаёт 80
    expect(refCardWidth(360).w).toBeLessThan(80);
  });

  it('высота едет за шириной — пропорция карточки сохраняется', () => {
    for (const W of ЭКРАНЫ) {
      const { w, h } = refCardWidth(W);
      expect(Math.abs(h / w - 102 / 80)).toBeLessThan(0.03);
    }
  });
});
