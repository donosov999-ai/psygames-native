import { GS_RULES, THRESHOLD_RULES } from '@/src/games/goods-sort/core/level';
import * as лист from '@/src/games/goods-sort/core/level';

declare const __dirname: string;
declare function require(id: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');

/*
 * ⚠️ Исходник читается ТОЛЬКО ради полноты: «не завёл ли кто новый порог, забыв
 * про карту». Сами значения берутся ИСПОЛНЕНИЕМ — из загруженного модуля.
 */
const ЛИСТ: string = readFileSync(
  join(__dirname, '..', 'games', 'goods-sort', 'core', 'level.ts'), 'utf8');

/**
 * Почему у порога нет правила. Ключи обязаны совпадать с `null`-записями в
 * `THRESHOLD_RULES`: список долгов ведётся в одном месте, а причины — здесь.
 */
const ПОЧЕМУ_ДОЛГ: Record<string, string> = {
  MIXED_CAP_FROM: 'с 18-го на доске появляются ниши РАЗНОЙ вместимости (на 2 и на 4). Механика видимая и необъяснённая; уровень 18 свободен, правило написать можно и нужно — не сделано, потому что это правка чужой давней ступени, а не часть текущей задачи.',
  SINGLE_CAP_FROM: 'с 26-го появляется ниша РОВНО НА ОДИН товар. Уровень 26 занят правилом «примёрзший ряд», а два правила на один порог запрещены соседним гейтом. Нужен сдвиг порога либо объединённое правило — решение меняет кривую сложности и принимается отдельно, с замером.',
};

/** Имена всех порогов-констант из исходника листа. */
function имена(): string[] {
  return [...ЛИСТ.matchAll(/^export const ([A-Z_]+_FROM) = \d+;/gm)].map((m) => m[1] as string);
}

describe('у каждого порога механики есть правило', () => {
  const все = имена();

  it('есть что проверять: пороги в листе нашлись', () => {
    expect(все.length).toBeGreaterThanOrEqual(5);
    expect(все).toContain('SCROLL_FROM');
  });

  /**
   * 🔴 КАРТА ПОЛНА. Завёл порог и не вписал его в `THRESHOLD_RULES` — гейт
   * краснеет здесь, а не молчит. Это и есть та дыра, через которую утекла
   * витрина: проверять было нечего, потому что записи не существовало.
   */
  it('🔴 каждый порог назван в карте, и карта не выдумывает лишних', () => {
    const забыты = все.filter((имя) => !(имя in THRESHOLD_RULES));
    expect(забыты).toEqual([]);
    const лишние = Object.keys(THRESHOLD_RULES).filter((имя) => !все.includes(имя));
    expect(лишние).toEqual([]);
  });

  /**
   * 🔴 СВЯЗЬ ПРОВЕРЯЕТСЯ ЗНАЧЕНИЕМ, А НЕ СОВПАДЕНИЕМ УРОВНЕЙ. Первая редакция
   * сверяла «есть ли ЛЮБОЕ правило на этом уровне» и тут же соврала на
   * `SINGLE_CAP_FROM = 26`: правило там есть, но оно про примёрзший ряд.
   */
  it('🔴 у названного правила порог совпадает со значением константы', () => {
    const плохо: string[] = [];
    for (const [имя, ключ] of Object.entries(THRESHOLD_RULES)) {
      if (!ключ) continue;
      const значение = (лист as unknown as Record<string, number>)[имя];
      expect(typeof значение).toBe('number');
      const правило = GS_RULES.find((r) => r.key === ключ);
      if (!правило) { плохо.push(`${имя}: правила «${ключ}» нет в списке`); continue; }
      if (правило.fromLevel !== значение) плохо.push(`${имя} = ${значение}, а правило «${ключ}» с ${правило.fromLevel}`);
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 у витрины правило есть — тот самый промах, ради которого гейт заведён', () => {
    expect(THRESHOLD_RULES.SCROLL_FROM).toBe('showcase');
    const r = GS_RULES.find((x) => x.key === 'showcase');
    expect(r?.fromLevel).toBe(лист.SCROLL_FROM);
  });

  it('🔴 у каждого долга названа причина, и она не пустая', () => {
    const долги = Object.entries(THRESHOLD_RULES).filter(([, к]) => к === null).map(([и]) => и);
    expect(долги.length).toBeGreaterThan(0);          // иначе пункт вырожден
    const немые = долги.filter((и) => (ПОЧЕМУ_ДОЛГ[и] ?? '').trim().length < 60);
    expect(немые).toEqual([]);
    // И причина не висит на пороге, у которого правило уже появилось.
    const лишние = Object.keys(ПОЧЕМУ_ДОЛГ).filter((и) => THRESHOLD_RULES[и] !== null);
    expect(лишние).toEqual([]);
  });
});
