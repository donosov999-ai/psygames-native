/**
 * НИ ОДНА РАЗВИЛКА НЕ ОТКРЫВАЕТСЯ ПУСТОЙ НИ В ОДНОМ ПРОФИЛЕ.
 *
 * 🔴 ПОВОД. 09.09.2026 «Ментальная ротация» открывалась пустой у ДЕСЯТИ профилей из
 * тринадцати: заголовок «Выбери упражнение» на месте, карточек под ним ноль. Обе игры
 * развилки я прописал только в набор «Шахматиста» и проверял под ним же — а фильтр
 * наборов в проекте существует ровно для того, чтобы у разных профилей был разный
 * состав. Денис нашёл это руками, словами «не запускается, ошибка».
 *
 * Правило, которое здесь закрепляется: если развилка ВИДНА в каталоге профиля, внутри
 * неё обязана быть хотя бы одна карточка. Обе половины считает одна и та же функция,
 * что и экран (`filterAllowedGames` + `visibleHubCards`), поэтому расходиться нечему.
 */
import { PROFILES, filterAllowedGames } from '@/src/constants/profiles';
import { HUB_CONTENTS, visibleHubCards } from '@/src/constants/hubContents';

declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = path.join(__dirname, '../..');

/**
 * Исходник экрана развилки ВМЕСТЕ С ТЕМИ ЕГО СОСТАВНЫМИ ЧАСТЯМИ, что относятся к
 * развилке. Спуск рекурсивный и это не роскошь: тонкие экраны делегируют в
 * `HubScreen`, а `HubScreen` — в `HubEmpty`. При спуске на один этаж проба
 * покраснела на тринадцати здоровых экранах, потому что искала ключи там, где их
 * уже не было. (Тот же приём в `ladder-reaches-back`, только там хватает одного этажа.)
 */
function исходникРазвилки(hubRoute: string): { файл: string; текст: string } {
  const имя = hubRoute.replace('/games/', '');
  const корень = path.join(КОРЕНЬ, 'app/games', имя + '.tsx');
  const собрано: string[] = [];
  const видели = new Set<string>();
  const спуск = (файл: string, глубина: number) => {
    if (глубина > 3 || видели.has(файл) || !fs.existsSync(файл)) return;
    видели.add(файл);
    const текст: string = fs.readFileSync(файл, 'utf8');
    собрано.push(текст);
    for (const m of текст.matchAll(/from '@\/src\/components\/(\w+)'/g)) {
      const имяК = m[1];
      // спускаемся только к частям САМОЙ развилки и только к реально отрисованным
      if (!/Hub|Empty/.test(имяК)) continue;
      if (!new RegExp('<' + имяК + '\\b').test(текст)) continue;
      спуск(path.join(КОРЕНЬ, 'src/components', имяК + '.tsx'), глубина + 1);
    }
  };
  спуск(корень, 0);
  const имена = [...видели].map((f: string) => path.basename(f));
  return { файл: имена.join(' + '), текст: собрано.join('\n/* этажом ниже */\n') };
}

describe('развилки в профилях', () => {
  it('есть что проверять: профилей больше десяти, развилок больше пяти', () => {
    expect(PROFILES.length).toBeGreaterThan(10);
    expect(Object.keys(HUB_CONTENTS).length).toBeGreaterThan(5);
  });

  it('🔴 видна в каталоге — значит внутри есть хотя бы одно упражнение', () => {
    const пустые: string[] = [];
    for (const p of PROFILES as any[]) {
      const открыто = filterAllowedGames(p);
      const можно = new Set(открыто.map((g: any) => g.route));
      for (const hub of Object.keys(HUB_CONTENTS)) {
        if (!можно.has(hub)) continue;                    // развилка закрыта — проверять нечего
        const карточек = visibleHubCards(hub, можно, (k: string) => k).length;
        if (карточек === 0) пустые.push(`${p.id} → ${hub}: 0 карточек`);
      }
    }
    expect(пустые).toEqual([]);
  });

  /**
   * 🔴 ПЯТЬ, А НЕ ТРИ — решение Дениса 11.09.2026 («что ещё можно добавить в хаб
   * ментальной ротации» → «делай Slide, Sokoban»). Прежний литерал 3 закреплял его же
   * решение от 09.09; здесь он поднят НАМЕРЕННО и с датой, а не подогнан под красную пробу.
   *
   * ⚠️ ЧИСЛО ОСТАЁТСЯ ЛИТЕРАЛОМ, И ЭТО ГЛАВНОЕ В ПРОБЕ. Соблазн написать
   * `HUB_CONTENTS['/games/spatial-hub'].length` велик и неверен: порог, взятый из
   * проверяемого, двигает оба конца сразу — тихо пропавшая карточка станет «нормой», и
   * гейт ослепнет ровно к тому дефекту, ради которого заведён (развилка открывалась
   * пустой у десяти профилей из тринадцати).
   * Меняя состав развилки — меняй и это число руками, вместе с датой и поводом.
   */
  /**
   * 🔴 ПЕРЕПИСАНО 12.09.2026: СЧЁТЧИК ЗАМЕНЁН ПОИМЁННЫМ СПИСКОМ, И ЭТО УСИЛЕНИЕ.
   * В развилку переехали четыре экрана из расформированных «Маршрутов» и
   * «Зрительной памяти» (задачи 81486a4a и 43bc1ca2) — карточек стало 9.
   * Поднять литерал 5 → 9 было бы НЕВЕРНО: обещание Дениса 09.09 и 11.09
   * касалось ПЯТИ НАЗВАННЫХ экранов, а новосёлы приходят со своей видимостью по
   * профилям, и открывать их всем тринадцати никто не решал.
   * Список по именам строже счётчика: пропажа «Сокобана» при живом «Навигаторе»
   * счётчику незаметна, а здесь покраснеет с именем.
   */
  const РОТАЦИЯ_ВСЕМ = [
    '/games/mental-rotation',
    '/games/spatial-lab?mode=twiddle',
    '/games/spatial-lab?mode=net',
    '/games/puzzles?mode=Slide',
    '/games/puzzles?mode=Sokoban',
  ];

  it('🔴 «Ментальная ротация» — во всех профилях и в полном составе (решения Дениса 09.09 и 11.09.2026)', () => {
    const плохо: string[] = [];
    for (const p of PROFILES as any[]) {
      const можно = new Set(filterAllowedGames(p).map((g: any) => g.route));
      if (!можно.has('/games/spatial-hub')) { плохо.push(`${p.id}: развилки нет вовсе`); continue; }
      const видно = new Set(
        visibleHubCards('/games/spatial-hub', можно, (k: string) => k).map((c: any) => c.route),
      );
      const нет = РОТАЦИЯ_ВСЕМ.filter((r) => !видно.has(r));
      if (нет.length) плохо.push(`${p.id}: не хватает ${нет.join(', ')}`);
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 «Судоку» — во всех профилях есть хотя бы классическая доска (решение Дениса 09.09.2026)', () => {
    const плохо: string[] = [];
    for (const p of PROFILES as any[]) {
      const можно = new Set(filterAllowedGames(p).map((g: any) => g.route));
      const карточек = visibleHubCards('/games/sudoku-hub', можно, (k: string) => k).length;
      if (!можно.has('/games/sudoku-hub') || карточек === 0) {
        плохо.push(`${p.id}: развилка ${можно.has('/games/sudoku-hub')}, карточек ${карточек}`);
      }
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 ВТОРАЯ ПОЛОВИНА ПРАВИЛА, БЕЗ КОТОРОЙ ПЕРВАЯ СЛЕПА НАИЗНАНКУ.
   *
   * Первая проба смотрит только на развилки, ВИДНЫЕ в каталоге. А закрытая
   * развилка остаётся ДОСТИЖИМОЙ — по ссылке, из поиска, из зарядки, — и до
   * 09.09.2026 открывалась белым местом под заголовком «Выбери упражнение».
   * Замер того дня на собранной сборке (обход всех 17 развилок под тремя
   * профилями): пустыми открывались 6 развилок из 17 у «Бесплатного» и 4 из 17
   * у «Детей». Именно это Денис назвал «не запускается, ошибка».
   *
   * Поэтому у КАЖДОГО экрана развилки обязано быть состояние «здесь пусто» с
   * выходом. Проверяется по исходнику экрана, а у тонких экранов — по делегату
   * этажом ниже (тот же приём, что в `ladder-reaches-back`).
   */
  it('🔴 у каждой развилки есть состояние «пусто» с выходом, а не белое место', () => {
    const плохо: string[] = [];
    for (const hub of Object.keys(HUB_CONTENTS)) {
      const { файл, текст } = исходникРазвилки(hub);
      const естьТекст = /hubEmptyTitle/.test(текст);
      const естьВыход = /hubEmptyAction/.test(текст);
      if (!естьТекст || !естьВыход) {
        плохо.push(`${hub} (${файл}): объяснение ${естьТекст}, выход ${естьВыход}`);
      }
    }
    expect(плохо).toEqual([]);
  });

  it('чтение исходников развилок работает — иначе проба выше зелена вслепую', () => {
    const { файл, текст } = исходникРазвилки('/games/spatial-hub');
    expect(`длина исходника: ${текст.length > 2000} · делегат подтянут: ${/HubScreenProps/.test(текст)} · второй этаж: ${файл.split(' + ').length >= 3}`)
      .toBe('длина исходника: true · делегат подтянут: true · второй этаж: true');
  });

  it('проба не зелена вслепую: подменный профиль без этих игр ловится', () => {
    const пустой = { id: 'проба', allowed_games: ['sudoku'], allow_sandbox: false } as any;
    const можно = new Set(filterAllowedGames(пустой).map((g: any) => g.route));
    // Развилка закрыта — первый тест её пропустит; проверяем, что состав действительно считается.
    expect(visibleHubCards('/games/spatial-hub', new Set(['/games/spatial-hub']), (k: string) => k).length).toBe(0);
    expect(можно.has('/games/spatial-hub')).toBe(true);   // ← ALWAYS_ALLOWED открывает её и здесь
  });
});
