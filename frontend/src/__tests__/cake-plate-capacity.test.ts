/**
 * 🔴 КРУГ ТАРЕЛКИ — СВОЙСТВО ДОСКИ, А НЕ КОНСТАНТА ИГРЫ.
 *
 * 📍 ЗАЧЕМ ЗАВЕДЕНО. Замер лестницы Тортов 09.09.2026 (`deal(L)` детерминирован,
 * одна доска на уровень): `types` замирает на L17 — потолок 11, столько цветов в
 * палитре; `plates` на L42 — `PLATES_MAX = 20`; и с L42 СТАРТОВЫЙ СТОЛ СОВПАДАЕТ
 * на каждом уровне до L200: 11 занятых тарелок, 9 пустых, 66 секторов, 99
 * законных ходов. Растёт одна очередь — 5 полок на L42 против 25 на L200. То
 * есть уровень выше сорок второго становится ДЛИННЕЕ, а не труднее.
 *
 * Разная вместимость тарелки — первая ось, меняющая саму форму стола. Приём не
 * выдуман: он проверен у соседа (`capsFor` в сортировке товаров, ниши на 1/2/3/4).
 *
 * ⚠️ ЭТА ПРОБА — ПРО МЕХАНИЗМ, А НЕ ПРО ЛЕСТНИЦУ. Ни один уровень пока не
 * заказывает круг, отличный от шести, и первое требование здесь — что доска БЕЗ
 * своих кругов ведёт себя ровно как прежде. Ось включится отдельным шагом, и
 * тогда рядом встанет проба про уровни.
 */
import {
  CIRCLE, capOf, queueCapOf, makeBoard, roomIn, canPlace, collapse, moveTop,
  completeIn, completeAt,
} from '@/src/games/cake-sort/core/plate';
import { lowerBound, minMoves, solve } from '@/src/games/cake-sort/core/solver';
import { deal } from '@/src/games/cake-sort/core/level';

describe('вместимость тарелки', () => {
  it('есть что проверять — круг по умолчанию настоящий', () => {
    expect(CIRCLE).toBe(6);
  });

  /**
   * 🔴 ПЕРВОЕ И ГЛАВНОЕ: доска без своих кругов не изменилась ни в чём. Это не
   * формальность — вся лестница, все вшитые уровни и значок «уровень проверен»
   * посчитаны на прежнем поведении.
   */
  it('🔴 доска БЕЗ своих кругов ведёт себя ровно как до правки', () => {
    const b = makeBoard([[1, 1, 1], [], [2]]);
    expect(b.caps).toBeUndefined();
    expect(capOf(b, 0)).toBe(CIRCLE);
    expect(roomIn(b, 0)).toBe(CIRCLE - 3);
    expect(roomIn(b, 1)).toBe(CIRCLE);
    // Круг замыкается ровно шестью и только однородными.
    expect(completeIn([1, 1, 1, 1, 1, 1])).toBe(1);
    expect(completeIn([1, 1, 1, 1, 1, 2])).toBeNull();
    expect(completeIn([1, 1, 1, 1, 1])).toBeNull();
    // И ход по такой доске не приделывает ей поле, которого не было.
    const после = moveTop(makeBoard([[1], [1]]), 0, 1);
    expect(после?.caps).toBeUndefined();
  });

  it('🔴 нижняя оценка на живых уровнях не сдвинулась ни на единицу', () => {
    // Числа сняты ДО правки, на том же детерминированном `deal(L)`.
    const было: Record<number, number> = { 20: 49, 42: 61, 63: 71, 100: 89, 200: 147 };
    for (const L of Object.keys(было).map(Number)) {
      expect(lowerBound(deal(L).board)).toBe(было[L]);
    }
  });

  it('🔴 круг тарелки берётся у ДОСКИ: восемь замыкают восьмёрку и не замыкают шестёрку', () => {
    const восьмёрка = makeBoard([[1, 1, 1, 1, 1, 1, 1, 1]], [], [8]);
    expect(capOf(восьмёрка, 0)).toBe(8);
    expect(completeAt(восьмёрка, 0)).toBe(1);
    // Та же тарелка при круге шесть — вообще незаконная доска, и это видно сразу.
    expect(() => makeBoard([[1, 1, 1, 1, 1, 1, 1, 1]])).toThrow(/секторов 8 при круге 6/);
    // Шесть секторов НЕ замыкают круг на восемь: тарелка полна лишь на три четверти.
    const шесть = makeBoard([[1, 1, 1, 1, 1, 1]], [], [8]);
    expect(completeAt(шесть, 0)).toBeNull();
    expect(roomIn(шесть, 0)).toBe(2);
    expect(canPlace(шесть, 0, 1)).toBe(true);
    expect(canPlace(шесть, 0, 2)).toBe(false);
  });

  /**
   * 🔴 ВМЕСТИМОСТЬ ЕДЕТ СО СВОЕЙ ТАРЕЛКОЙ, А НЕ С МЕСТОМ. Иначе тарелка на
   * восемь, встав на место шестёрки, замкнулась бы шестью секторами — правило
   * игры менялось бы от того, куда она попала.
   */
  it('🔴 пришедшая из очереди тарелка приносит СВОЙ круг', () => {
    const b = makeBoard([[1, 1, 1, 1, 1, 1, 1, 1], []], [[2, 2]], [8, 6], [6]);
    const { board, cleared } = collapse(b);
    expect(cleared).toEqual([1]);
    expect(board.plates[0]).toEqual([2, 2]);
    // Место было на восемь, приехала тарелка на шесть — круг стал шесть.
    expect(capOf(board, 0)).toBe(6);
    expect(board.queue).toHaveLength(0);
  });

  it('🔴 опустевшее без очереди место круг НЕ теряет — он задан уровнем', () => {
    const b = makeBoard([[1, 1, 1, 1, 1, 1, 1, 1], []], [], [8, 8]);
    const { board } = collapse(b);
    expect(board.plates[0]).toEqual([]);
    expect(capOf(board, 0)).toBe(8);
    expect(capOf(board, 1)).toBe(8);
  });

  /**
   * 🔴 КРУГ ВХОДИТ В КЛЮЧ СОСТОЯНИЯ РЕШАТЕЛЯ.
   *
   * Две доски с одинаковым содержимым и разными кругами — РАЗНЫЕ задачи: восемь
   * секторов одного вида решаются на тарелке в восемь и не решаются на шестёрке.
   * Ровно эта ловушка стоила дня у переливалки: ключ собирался по содержимому
   * сосудов без высоты, и решатель объявлял виденным то, чего не видел.
   */
  it('🔴 решатель различает доски, отличающиеся ТОЛЬКО кругом', () => {
    const восемь = makeBoard([[1, 1, 1, 1, 1, 1], [1, 1]], [], [8, 8]);
    const шесть = () => makeBoard([[1, 1, 1, 1, 1, 1], [1, 1]], [], [6, 6]);
    // На восьмёрке два сектора переезжают и круг замыкается — стол разобран.
    expect(solve(восемь, 20000).solvable).toBe(true);
    // На шестёрке первая тарелка уже полна, двум оставшимся деться некуда.
    expect(solve(шесть(), 20000).solvable).toBe(false);
  });

  /**
   * 🔴 И ТА ЖЕ ПРОВЕРКА — НА ДОСКЕ, ГДЕ КРУГ РЕШАЕТ ВНУТРИ ОДНОГО ПОИСКА.
   *
   * ⚠️ ЭТОТ ПУНКТ ЗАВЕДЁН ПО ВЫЖИВШЕЙ МУТАЦИИ, а не «на всякий случай». Проба
   * выше сравнивает ДВЕ разные доски, и её мутация «убрать круг из ключа
   * решателя» пережила: два состояния там расходятся содержимым, ключ ни при чём.
   * Круг в ключе решает там, где ОДИН поиск приходит в два состояния с ОДНИМ И
   * ТЕМ ЖЕ содержимым тарелок и РАЗНЫМИ кругами — ключ сортирует тарелки как
   * множество, и без круга они сливаются в одно.
   *
   * 📍 Доска найдена перебором 99 маленьких раскладов со своими кругами: шесть
   * секторов вида 1 лежат по три на тарелках с кругами 6 и 8. Собрать круг можно
   * ТОЛЬКО на шестёрке; сложи их на восьмёрку — получится шесть из восьми, и
   * тарелка не замкнётся. С кругом в ключе решатель находит решение за 7 узлов,
   * без круга — объявляет тупик на 4-м, выбросив настоящее решение.
   *
   * Это ровно та ловушка, что стоила дня у переливалки: ключ собирался по
   * содержимому сосудов без высоты и без камней.
   */
  it('🔴 круг входит в ключ: иначе решатель теряет решение внутри одного поиска', () => {
    const доска = () => makeBoard([[1, 1, 1], [1, 1, 1]], [[]], [6, 8], [4]);
    const r = solve(доска(), 20000);
    expect(r.exhausted).toBe(false);
    expect(r.solvable).toBe(true);
  });

  /**
   * 🔴 НИЖНЯЯ ОЦЕНКА ОБЯЗАНА ОСТАТЬСЯ ДОПУСТИМОЙ И НА СМЕШАННЫХ КРУГАХ.
   *
   * Завышенная оценка ломает две вещи разом: A* перестаёт находить оптимум, а
   * звёзды начинают выдаваться за игру хуже настоящей. Поэтому делим на САМЫЙ
   * БОЛЬШОЙ круг доски — занизить безопасно, завысить нет.
   */
  it('🔴 нижняя оценка не превышает настоящего минимума на смешанных кругах', () => {
    const доски = [
      makeBoard([[1, 1, 1], [1, 1, 1], [2, 2], [], []], [], [8, 6, 4, 8, 4]),
      makeBoard([[1, 1], [2], [1], [2, 2, 2], []], [], [4, 4, 6, 6, 8]),
      makeBoard([[3, 3, 3, 3], [3], [1, 1], [1, 1], []], [], [8, 8, 4, 4, 6]),
    ];
    const плохо: string[] = [];
    доски.forEach((b, i) => {
      const r = minMoves(b, 200000);
      if (r.moves === null) return;              // бюджет — не приговор, просто нет данных
      if (lowerBound(b) > r.moves) плохо.push(`доска ${i}: оценка ${lowerBound(b)} > минимума ${r.moves}`);
    });
    expect(плохо).toEqual([]);
  });

  it('🔴 круг очереди спрашивается у доски, а не берётся по умолчанию', () => {
    const b = makeBoard([[]], [[1, 1]], [6], [4]);
    expect(queueCapOf(b, 0)).toBe(4);
    expect(queueCapOf(b, 1)).toBe(CIRCLE);       // за концом списка — умолчание
    expect(queueCapOf(makeBoard([[]], [[1]]), 0)).toBe(CIRCLE);
  });
});
