/**
 * 🔴 ОДИНАКОВЫЕ ПОДРЯД ПЕРЕНОСЯТСЯ ТОЛЬКО ВМЕСТЕ — НА ВСЕХ УРОВНЯХ.
 *
 * РЕШЕНИЕ ДЕНИСА 16.09.2026, дословно: «по гайкам, сосудам и шарикам механика
 * должна быть такая, что если две или несколько одинаковых в сосуде
 * последовательно — переносятся они вместе только, а не что таскаем по 1 шт».
 *
 * ЧТО БЫЛО. С L34 шла ось «строгий налив»: за ход уходила ОДНА порция. Ось была
 * настоящей и замеренной (треть-половина ходов строгого решения — ходы, которых
 * обычное правило выразить не может), но в партии читалась как поломка.
 *
 * ⚠️ ЧТО ЭТА ПРОБА СТОРОЖИТ ТЕПЕРЬ — ОБРАТНОЕ ПРЕЖНЕМУ. Прежняя редакция (VER 1)
 * требовала, чтобы с L34 поле приходило строгим, доска ужималась с 12 цветов до 8
 * и эталон рос на пятую часть. Все три утверждения стали ложью по решению, и
 * переписаны осознанно, а не ослаблены: разменивать объём больше не на что.
 *
 * ⚠️ МЕХАНИЗМ `strict` В ЯДРЕ ОСТАВЛЕН И СТОРОЖИТСЯ ЗДЕСЬ ЖЕ — отдельным пунктом.
 * Вернут ось режимом — её не придётся строить и мерить заново.
 */
import {
  levelParams, generateLevel, levelMoveReference, moveReference,
  строгийНалив, СТРОГО_С, СТРОГИЙ_НАЛИВ_ВКЛЮЧЁН,
} from '@/src/games/water-sort/core/generate';
import { canPour, pour, pourAmount, topRun, makeField, type Field } from '@/src/games/water-sort/core/tubes';
import { WATER_SORT_RULES } from '@/app/games/water-sort';

jest.mock('expo-router', () => ({
  useRouter: () => ({ push: () => {}, replace: () => {}, back: () => {} }),
  useLocalSearchParams: () => ({}),
  router: { canGoBack: () => false, back: () => {}, replace: () => {} },
  useFocusEffect: () => {},
}));

/** Детерминированный бросок: одни и те же позиции на каждом прогоне. */
function броски(seed: number) {
  let s = seed >>> 0;
  return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; };
}

/** Свободное место в сосуде — считаем здесь, не импортом, чтобы проба не повторяла ядро. */
const место = (f: Field, i: number) => f.cap - (f.tubes[i]?.length ?? 0);

describe('одинаковые подряд переносятся только вместе', () => {
  it('🔴 выключатель выключен — и ни один уровень не строгий', () => {
    expect(СТРОГИЙ_НАЛИВ_ВКЛЮЧЁН).toBe(false);
    const строгие: number[] = [];
    for (let L = 1; L <= 120; L += 1) if (строгийНалив(L)) строгие.push(L);
    expect(строгие).toEqual([]);
  });

  /**
   * 🔴 ГЛАВНОЕ, И ПРОВЕРЯЕТСЯ ИСПОЛНЕНИЕМ, А НЕ ФЛАГОМ.
   *
   * «Флаг не стоит» ничего не доказывает, если поле приходит строгим другим
   * путём. Поэтому берутся НАСТОЯЩИЕ раздачи бывших строгих уровней, из каждой
   * делается дюжина случайных ходов, и на каждой позиции по каждой разрешённой
   * паре утверждается: ушло ровно столько, сколько лежит верхним рядом и влезает.
   */
  it('🔴 на бывших строгих уровнях за ход уходит весь верхний ряд, сколько влезет', () => {
    const врут: string[] = [];
    let проверено = 0;
    let рядыОтДвух = 0;
    for (const L of [СТРОГО_С, СТРОГО_С + 6, СТРОГО_С + 16]) {
      const бросок = броски(L);
      let f = generateLevel(L, бросок).field;
      expect(f.strict ?? false).toBe(false);
      for (let шаг = 0; шаг < 12; шаг += 1) {
        const пары: [number, number][] = [];
        for (let a = 0; a < f.tubes.length; a += 1) {
          for (let b = 0; b < f.tubes.length; b += 1) if (a !== b && canPour(f, a, b)) пары.push([a, b]);
        }
        for (const [a, b] of пары) {
          const ряд = topRun(f.tubes[a]!);
          const ждём = Math.min(ряд, место(f, b));
          const ушло = pourAmount(f, a, b);
          проверено += 1;
          if (ждём >= 2) рядыОтДвух += 1;
          if (ушло !== ждём) врут.push(`L${L} шаг ${шаг} ${a}→${b}: ряд ${ряд}, места ${место(f, b)}, ушло ${ушло}`);
        }
        if (!пары.length) break;
        const [a, b] = пары[Math.floor(бросок() * пары.length)] as [number, number];
        f = pour(f, a, b) ?? f;
      }
    }
    // Премиса: есть что проверять, и среди этого — ходы с рядом от двух.
    expect(проверено).toBeGreaterThan(50);
    expect(рядыОтДвух).toBeGreaterThan(0);
    expect(врут.slice(0, 5)).toEqual([]);
  }, 300_000);

  it('🔴 карточка «строгий налив» не объявляется, пока ось выключена', () => {
    expect(WATER_SORT_RULES.some((r) => r.key === 'strict')).toBe(false);
  });

  it('с бывшего порога доска больше не ужимается — ужимать не в обмен на что', () => {
    expect(levelParams(СТРОГО_С).colors).toBe(levelParams(СТРОГО_С - 1).colors);
    expect(levelParams(СТРОГО_С + 16).colors).toBe(levelParams(СТРОГО_С - 1).colors);
  });

  it('эталон ходов на бывших строгих уровнях — обычный, без надбавки', () => {
    const p = levelParams(СТРОГО_С);
    expect(levelMoveReference(СТРОГО_С)).toBe(moveReference(p.colors, p.cap, false));
  });
});

describe('механизм строгого налива в ядре исправен — на случай возврата оси', () => {
  /**
   * ⚠️ Без этого пункта механизм сгнил бы молча: выключенная ось не
   * исполняется ни одной партией, и сломанный `pourAmount` при `strict`
   * не заметил бы никто до дня, когда её включат.
   */
  it('на строгом поле уходит одна порция, на обычном — весь ряд', () => {
    /*
     * ⚠️ Источник НЕОДНОРОДНЫЙ нарочно: однородный столбик в пустой сосуд
     * запрещён («так ничего не изменится»), и `pourAmount` отдал бы ноль —
     * проба сравнивала бы ноль с единицей и зеленела бы не о том.
     * Верх сосуда — КОНЕЦ массива: сверху лежат три порции цвета 0.
     */
    const обычное = makeField([[1, 0, 0, 0], [], [1]], 4);
    expect(pourAmount(обычное, 0, 1)).toBe(3);
    const строгое: Field = { ...обычное, strict: true };
    expect(pourAmount(строгое, 0, 1)).toBe(1);
  });
});
