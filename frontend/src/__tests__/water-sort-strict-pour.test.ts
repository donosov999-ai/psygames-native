/**
 * 🔴 СТРОГИЙ НАЛИВ — ОСЬ «СТРОГОСТЬ ПОРЯДКА», КОТОРОЙ У ПЕРЕЛИВАЛКИ НЕ БЫЛО.
 *
 * До 07.09.2026 лестница переливалки кончалась на L33: двенадцать цветов —
 * потолок палитры, пятая порция — потолок высоты, а последний приём (вторая
 * отложенная пробирка) вставал там же. Дальше расклад повторялся навсегда.
 * Расти вширь нечем, значит ось обязана быть КАЧЕСТВЕННОЙ.
 *
 * ЗАМЕР, ОПРАВДЫВАЮЩИЙ ОСЬ (по 4 партии). Возражение звучало так: «лить по
 * одной — это не мысль, а лишние касания». Проверено на решениях: порция уходит
 * НЕ туда, куда ушёл бы весь ряд, в 32–50% ходов (L14 — 35%, L20 — 32%,
 * L26 — 50%). То есть треть-половина ходов — решения, которых обычное правило
 * выразить не может.
 *
 * ЦЕНА ТОЖЕ ЗАМЕРЕНА, и за неё платится объёмом: путь перебора удлиняется вдвое
 * (L14 75 → 155 ходов), поэтому на пороге доска ужимается с двенадцати цветов до
 * восьми и растёт обратно. Ось не добавлена поверх прежней вершины — она на
 * часть вершины обменяна.
 */
import {
  levelParams, generateLevel, moveReference, levelMoveReference, moveLimitFor,
  строгийНалив, СТРОГО_С,
} from '@/src/games/water-sort/core/generate';

describe('строгий налив доезжает до поля', () => {
  /**
   * 🔴 ГЛАВНОЕ: ПРИЗНАК ОБЯЗАН ЛЕЖАТЬ НА САМОМ ПОЛЕ.
   *
   * 📍 Пункт заведён по ВЫЖИВШЕЙ МУТАЦИИ «строгость не доходит до поля»: убери
   * `strict: true` из генератора — и ни одна проба не покраснела бы. А цена
   * такой потери максимальная: генератор доказывал бы решаемость по одному
   * правилу, игрок играл бы по другому, и значок «уровень проверен» стал бы
   * обещанием про другую игру.
   */
  it('🔴 с порога уровни приходят со строгим наливом, до порога — без', () => {
    for (const L of [СТРОГО_С, СТРОГО_С + 4, СТРОГО_С + 12]) {
      expect(generateLevel(L).field.strict).toBe(true);
    }
    for (const L of [1, 10, СТРОГО_С - 1]) {
      expect(generateLevel(L).field.strict ?? false).toBe(false);
    }
  }, 180_000);

  it('признак уровня и признак поля говорят одно и то же', () => {
    for (let L = 1; L <= 60; L += 1) {
      expect(строгийНалив(L)).toBe(L >= СТРОГО_С);
    }
  });
});

describe('ось обменяна на объём, а не добавлена сверху', () => {
  /**
   * 🔴 РАЗМЕН ОБЯЗАН СОСТОЯТЬСЯ. Мутация «доска не ужимается под ось» пережила
   * проверку: гейт лестницы разрешал падение объёма на пороге, но не требовал
   * его. Разрешение без требования — это не правило, а лазейка.
   */
  it('🔴 на пороге доска действительно ужимается', () => {
    const до = levelParams(СТРОГО_С - 1);
    const на = levelParams(СТРОГО_С);
    expect(на.colors).toBeLessThan(до.colors);
  });

  it('🔴 и растёт обратно, а не остаётся ужатой навсегда', () => {
    const на = levelParams(СТРОГО_С);
    const потом = levelParams(СТРОГО_С + 16);
    expect(потом.colors).toBeGreaterThan(на.colors);
    // Возврат именно к прежней вершине, а не к произвольному числу.
    expect(потом.colors).toBe(levelParams(СТРОГО_С - 1).colors);
  });

  /**
   * ⚠️ И порог «расклад раздали почти собранным» тоже удвоен. Он меряется путём
   * перебора В ГЛУБИНУ, а тот при строгом наливе примерно удваивается: мерить
   * прежним числом значило бы пропускать вдвое более слабые доски.
   */
  it('🔴 порог «доска не пустая» удвоен вместе с длиной пути', () => {
    const обычный = levelParams(СТРОГО_С - 1).minMoves;
    const строгий = levelParams(СТРОГО_С).minMoves;
    expect(строгий).toBeGreaterThanOrEqual(обычный * 2);
  });
});

describe('эталон ходов знает про строгость', () => {
  /**
   * 🔴 ЭТАЛОН ПОДНЯТ НА ПЯТУЮ ЧАСТЬ, А НЕ УДВОЕН — И ЭТО ДВЕ РАЗНЫЕ ВЕЛИЧИНЫ.
   *
   * Путь перебора В ГЛУБИНУ при строгом наливе удваивается. Настоящий минимум —
   * обход В ШИРИНУ — растёт куда скромнее: замер полным обходом, по 3 раздачи на
   * размер, дал 1,06…1,27 (3×3 → 1,24; 4×4 → 1,23; 5×3 → 1,06; 5×4 → 1,19).
   * Среднее около 1,17, взято 1,2 с запасом в пользу игрока.
   *
   * ⚠️ Взять сюда двойку значило бы выдавать три звезды за вдвое худшую игру.
   *
   * 📍 Пункт заведён по ВЫЖИВШЕЙ МУТАЦИИ «эталон не учитывает строгость».
   */
  it('🔴 на строгом уровне эталон выше обычного при тех же цветах и высоте', () => {
    const p = levelParams(СТРОГО_С);
    const обычный = moveReference(p.colors, p.cap, false);
    const строгий = moveReference(p.colors, p.cap, true);
    expect(строгий).toBeGreaterThan(обычный);
    // И именно на пятую часть, а не на сколько попало.
    expect(строгий / обычный).toBeGreaterThan(1.1);
    expect(строгий / обычный).toBeLessThan(1.3);
  });

  it('🔴 эталон уровня берёт строгость сам, без напоминания', () => {
    const p = levelParams(СТРОГО_С);
    expect(levelMoveReference(СТРОГО_С)).toBe(moveReference(p.colors, p.cap, true));
  });

  /**
   * ⚠️ И ЛИМИТ ХОДОВ СЧИТАЕТСЯ ОТ ТОГО ЖЕ ЭТАЛОНА. Считай он от обычного —
   * запас над минимумом на строгих уровнях молча сжался бы на пятую часть.
   */
  it('лимит ходов на строгом уровне выше эталона с запасом', () => {
    const лимит = moveLimitFor(СТРОГО_С);
    if (лимит === 0) return;   // под скрытым слоем лимита нет — это отдельное правило
    expect(лимит / levelMoveReference(СТРОГО_С)).toBeGreaterThan(1.3);
  });
});

