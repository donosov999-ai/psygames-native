import { dropPoint } from '@/src/services/dragDrop';

/**
 * Дефект 02.09.2026 (Денис): «тащишь — вроде тащится, но не ставится».
 * Событие отпускания приходило без координат, цель считалась «мимо доски».
 */
describe('точка отпускания перетаскивания', () => {
  it('берёт координаты события, когда они есть', () => {
    expect(dropPoint({ pageX: 120, pageY: 340 }, { x: 5, y: 5 })).toEqual({ x: 120, y: 340 });
  });

  it('🔴 берёт последнюю точку движения, когда событие пришло с нулями (веб)', () => {
    expect(dropPoint({ pageX: 0, pageY: 0 }, { x: 210, y: 480 })).toEqual({ x: 210, y: 480 });
  });

  it('берёт последнюю точку движения, когда координат в событии нет вовсе', () => {
    expect(dropPoint({}, { x: 210, y: 480 })).toEqual({ x: 210, y: 480 });
    expect(dropPoint(null, { x: 7, y: 8 })).toEqual({ x: 7, y: 8 });
  });

  it('ноль по одной оси — это настоящая координата, а не пустое событие', () => {
    expect(dropPoint({ pageX: 0, pageY: 300 }, { x: 9, y: 9 })).toEqual({ x: 0, y: 300 });
  });

  it('жест без движения и без координат — цели нет, ход не делается', () => {
    expect(dropPoint({ pageX: 0, pageY: 0 }, null)).toBeNull();
  });
});
