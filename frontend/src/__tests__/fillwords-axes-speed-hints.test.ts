/**
 * ЛЕСТНИЦА ФИЛВОРДОВ РАСТЁТ ПОСЛЕ 94-го УРОВНЯ — ОСЯМИ, А НЕ НОВЫМИ СЛОВАМИ.
 *
 * 📍 ПРАВИЛО ДЕНИСА 06.09.2026: «никаких потолков нет нигде, всегда можно растить
 * сложность, вопрос подхода». До него здесь стоял мой вывод «объёмные оси
 * исчерпаны, без новых данных лестница дальше 94-го не растёт». Замеры были
 * верны — длина слова ×5,63 на букву, ширина поля ×1,10, запрет диагоналей ×0,01
 * — но перебрана была одна ось из десяти, и вывод оказался не потолком, а
 * недоискан­ной осью.
 *
 * ЗАМЕР ДО: 30 различимых настроек, последняя новая на 94-м; уровни 95–5000
 * (98,1%) одинаковы.
 * ЗАМЕР ПОСЛЕ: 49 настроек, последняя новая на 202-м.
 */
import { FILLWORDS_LOCALES, fillwordsLevel, generateFillwords, полДлиныЯзыка } from '@/src/games/fillwords/core';

function ключ(L: number): string {
  const c = fillwordsLevel(L);
  return `${c.rows}x${c.cols}/${c.minWordLen}-${c.maxWordLen}/${c.timeLimitSec}/${c.hints}`;
}

it('после 94-го уровня появляются НОВЫЕ настройки', () => {
  const до94 = new Set<string>();
  for (let L = 1; L <= 94; L++) до94.add(ключ(L));
  const новые = new Set<string>();
  for (let L = 95; L <= 300; L++) { const k = ключ(L); if (!до94.has(k)) новые.add(k); }
  // Раньше здесь был ровно ноль: уровни 95+ повторяли 94-й до пятитысячного.
  expect(новые.size).toBeGreaterThanOrEqual(18);
});

it('всего различимых настроек стало больше тридцати', () => {
  const все = new Set<string>();
  for (let L = 1; L <= 5000; L++) все.add(ключ(L));
  expect(все.size).toBeGreaterThanOrEqual(49);
});

/**
 * 🔴 ЛЕСТНИЦА, А НЕ ОБРЫВ: НИ ОДНА ОСЬ НЕ ХОДИТ ВСПЯТЬ.
 *
 * Проверяется по ВСЕЙ глубине, а не по первым уровням: прошлые ошибки раздела
 * ровно так и прятались — замирание начиналось за границей выборки пробы.
 */
it('секунд на клетку не растёт, подсказок не прибавляется, поле не уменьшается', () => {
  /*
    ⚠️ МЕРИТЬ НАДО СЕКУНДЫ НА КЛЕТКУ, А НЕ ОБЩЕЕ ВРЕМЯ. Первая версия пробы
    требовала, чтобы `timeLimitSec` не рос, и покраснела на шестнадцати уровнях —
    но неверна была ПОСЫЛКА, а не код: поле растёт с 5×5 до 16×9, и на 144 клетки
    времени нужно больше, чем на 25, при любой скорости. Осью служит ПЛОТНОСТЬ
    времени: 3,0 с/клетку на первом уровне против 1,0 на двухсотом.
  */
  const наКлетку = (c: { rows: number; cols: number; timeLimitSec: number }) =>
    c.timeLimitSec / (c.rows * c.cols);
  const плохо: string[] = [];
  for (let L = 2; L <= 1000; L++) {
    const п = fillwordsLevel(L - 1), т = fillwordsLevel(L);
    // Округление до целых секунд даёт дрожание в сотых — допуск ровно на него.
    if (наКлетку(т) > наКлетку(п) + 0.01) {
      плохо.push(`ур.${L}: с/клетку выросло ${наКлетку(п).toFixed(3)} → ${наКлетку(т).toFixed(3)}`);
    }
    if (т.hints > п.hints) плохо.push(`ур.${L}: подсказок прибавилось ${п.hints} → ${т.hints}`);
    if (т.rows < п.rows || т.cols < п.cols) плохо.push(`ур.${L}: поле уменьшилось`);
    if (т.minWordLen < п.minWordLen) плохо.push(`ур.${L}: пол длины упал`);
  }
  expect(плохо).toEqual([]);
});

/**
 * ⚠️ ГРАНИЦЫ ОСЕЙ — ЧИСЛОМ, ИНАЧЕ «РАСТЁТ» МОЖНО ОБЪЯВИТЬ И ПРО УХОД В НОЛЬ.
 * Время не опускается ниже 1,0 с на клетку, подсказки не уходят в минус.
 */
it('оси упираются в объявленные границы, а не уезжают вниз без дна', () => {
  const c = fillwordsLevel(5000);
  expect(c.timeLimitSec).toBe(Math.round(c.rows * c.cols * 1.0));
  expect(c.hints).toBe(0);
  for (let L = 1; L <= 5000; L += 7) {
    const x = fillwordsLevel(L);
    expect(x.hints).toBeGreaterThanOrEqual(0);
    expect(x.timeLimitSec).toBeGreaterThanOrEqual(Math.round(x.rows * x.cols * 1.0));
  }
});

/** Ось включается ПОСЛЕ предыдущей, а не вместе с ней — иначе скачок вместо ступени. */
it('оси идут по очереди: до 94-го время не трогается, до 142-го подсказки целы', () => {
  expect(fillwordsLevel(94).timeLimitSec).toBe(fillwordsLevel(95).timeLimitSec);
  expect(fillwordsLevel(142).hints).toBe(3);
  expect(fillwordsLevel(203).hints).toBe(0);
});

/**
 * ФРАНЦУЗСКИЙ И ИТАЛЬЯНСКИЙ ИГРАЮТСЯ, ХОТЯ ТРЁХБУКВЕННЫХ СЛОВ У НИХ НЕТ.
 *
 * 🔴 ЧТО БЫЛО. Порог пригодности требовал восьми слов на КАЖДОЙ из длин 3, 4, 5 —
 * жёстко, для всех языков. У fr и it трёхбуквенных ровно ноль, и режим им не
 * предлагался при 3868 и 4707 словах в пуле.
 *
 * ⚠️ И ЭТО НЕ ПРОБЕЛ СБОРЩИКА, А ЕГО ЗАМЕР. `wordlist-build/build_fr_targets.py`,
 * МИН_ДЛИНА = 4: «при пороге в три буквы 19% выданных слов (4393 из 22 964) —
 * трёхбуквенные, и их хвост негодный: ana, sin, sas, ais, abc, lol, zip, psi;
 * раскладка assassin при пороге 3 даёт четыре мусорных слова из шести». Ронять
 * порог сборщика ради филвордов значило бы испортить анаграммы — те же наборы.
 *
 * Стало: пол длины — свойство ЯЗЫКА (`полДлиныЯзыка`), опорные длины считаются от
 * него. У ru/en/de/es/pt пол 3, у fr/it — 4. Языков в филвордах 5 → 7.
 */
it('fr и it поддержаны и собирают поле на всей лестнице', () => {
  for (const l of ['fr', 'it']) {
    expect(FILLWORDS_LOCALES).toContain(l);
    expect(полДлиныЯзыка(l)).toBe(4);
    for (const L of [1, 5, 20, 50, 94, 150, 202]) {
      const c = fillwordsLevel(L);
      const p = generateFillwords({ rows: c.rows, cols: c.cols, locale: l, seed: L * 17 + 3,
        maxWordLen: c.maxWordLen, minWordLen: c.minWordLen });
      // Пустая клетка означала бы поле, которое нельзя разобрать.
      expect(p.letters.every((ch) => ch)).toBe(true);
      // И ни одно слово не короче пола языка — иначе генератор взял бы то, чего нет.
      for (const w of p.words) expect([...w.word].length).toBeGreaterThanOrEqual(4);
    }
  }
});

it('у языков с трёхбуквенными словами пол остался прежним', () => {
  for (const l of ['ru', 'en', 'de', 'es', 'pt']) expect(полДлиныЯзыка(l)).toBe(3);
});
