/**
 * ЗАВОДСКОЙ СОСТАВ ЕДЕТ В СБОРКЕ И РАЗБИРАЕТСЯ БЕЗ ПОТЕРЬ.
 *
 * 🔴 ПОВОД. 13.09.2026 Денис поставил 2.54.8 из Google Play и увидел прежнюю
 * развилку: сорок головоломок одной кучей. Причина — файл состава, собранный на
 * все тринадцать профилей, лежал только у него на Маке, а в сборке файла по
 * умолчанию не было вовсе. Обновление привезло механизм без содержимого.
 * Его слова: «это же дефолтный файл должен быть — мне нахуй для себя собирать
 * 13 профилей?»
 *
 * ⚠️ ПРОБА СМОТРИТ НА РАЗБОР, А НЕ НА НАЛИЧИЕ ФАЙЛА. Файл, который приложение не
 * может прочитать, ничем не лучше отсутствующего: отброшенная строка — это молча
 * пропавшая игра или целый профиль.
 */
import { заводскойСостав, разобрать } from '@/src/services/playlistOverride';

declare function require(id: string): any;
const ФАЙЛ = require('@/src/constants/defaultPlaylists.json');

describe('заводской состав из сборки', () => {
  it('🔴 файл в сборке есть и разбирается БЕЗ отброшенных строк', () => {
    const р = разобрать(JSON.stringify(ФАЙЛ));
    expect(`ошибка: ${р.ошибка ?? 'нет'}`).toBe('ошибка: нет');
    expect(р.отброшено).toEqual([]);
    expect(р.профилейПринято).toBeGreaterThanOrEqual(13);
  });

  it('🔴 пустое хранилище отдаёт заводской состав, а не пустоту', () => {
    const с = заводскойСостав();
    expect(с).not.toBeNull();
    expect(Object.keys(с!.профили).length).toBeGreaterThanOrEqual(13);
  });

  it('🔴 развилка головоломок расфасована, а не лежит кучей', () => {
    const с = заводскойСостав()!;
    const хабы = с.профили.free?.хабы ?? {};
    const вГоловоломках = (хабы['/games/puzzles-hub'] ?? []).length;
    expect(`в «Головоломках» карточек: ${вГоловоломках}`).toBe('в «Головоломках» карточек: 4');
    /* И головоломки действительно уехали по темам — иначе расфасовка мнимая. */
    const поТемам = ['/games/sudoku-hub', '/games/spatial-hub', '/games/sorting-hub',
                     '/games/counting-hub', '/games/search-hub']
      .map((х) => (хабы[х] ?? []).filter((э) => typeof э !== 'string').length);
    expect(поТемам).toEqual([7, 8, 9, 7, 5]);
  });

  it('зарядка и свои серии тоже приехали: сетка на все дни и потоки', () => {
    const с = заводскойСостав()!;
    expect(Object.keys(с.профили.chess?.сетка ?? {}).length).toBe(7);
    expect(с.наборы.length).toBe(78);
  });
});
