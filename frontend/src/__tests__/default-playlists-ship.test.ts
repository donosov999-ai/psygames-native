/**
 * 🔴 КАКОЙ РАЗВИЛКЕ КАКОЙ ПОТОК. Ключ серии — её собственное имя, а не кусок
 * маршрута: `/games/attention-conflict` зовётся `conflict`, `/games/span` —
 * `span`. Выводить одно из другого значило бы держать правило в регулярке, где
 * его никто не прочитает.
 */
const РАЗВИЛКА_ПОТОКА: Record<string, string> = {
  span: '/games/span', mnemonics: '/games/mnemonics-hub', chess: '/games/chess-hub',
  conflict: '/games/attention-conflict', search: '/games/search-hub', sudoku: '/games/sudoku-hub',
  puzzles: '/games/puzzles-hub', spatial: '/games/spatial-hub', sorting: '/games/sorting-hub',
  counting: '/games/counting-hub', words: '/games/words-hub', hearing: '/games/hearing-hub',
  languages: '/games/languages-hub',
};

describe('поток развилки — только её игры', () => {
  /**
   * 🔴 ПОВОД. 13.09.2026 Денис открыл «Шахматы вслепую · 5 мин» и увидел там
   * ментальную ротацию, матрицу памяти, судоку и башню Лондона: «поток должен
   * быть чистые шахматы, намешал там говна разного», «чисто шахматный хаб».
   * Пулы потоков я набирал руками «по смыслу» — и в восьми развилках из тринадцати
   * оказались чужие игры, 87 шагов на все три длины.
   *
   * ⚠️ Проба считает ОХВАТ, а не наличие: «поток есть» и «поток из своих» — разные
   * утверждения, и второе не проверялось ничем.
   */
  const маршрут = (э: ЭлементХаба): string => (typeof э === 'string' ? э : э.маршрут);

  /** Состав развилки: файл главнее кода, групповая карточка раскрывается внутрь. */
  function состав(хаб: string, изФайла: Record<string, ЭлементХаба[]>, глубина = 0): Set<string> {
    const карточки = изФайла[хаб]?.map(маршрут) ?? (HUB_CONTENTS[хаб] ?? []).map((c) => c.route);
    const вышло = new Set<string>();
    for (const р of карточки) {
      const под = HUB_CONTENTS[р] ? р : null;
      if (под && глубина < 2) for (const x of состав(под, изФайла, глубина + 1)) вышло.add(x);
      else вышло.add(р);
    }
    return вышло;
  }

  it('🔴 ни один поток развилки не тащит чужую игру', () => {
    const с = заводскойСостав()!;
    const изФайла = (с.профили.odv999?.хабы ?? {}) as Record<string, ЭлементХаба[]>;
    const наборы = new Map(с.наборы.map((н) => [н.id, н]));
    const чужие: string[] = [];
    for (const [ключ, хаб] of Object.entries(РАЗВИЛКА_ПОТОКА)) {
      const свои = состав(хаб, изФайла);
      for (const мин of [5, 10, 15]) {
        const н = наборы.get(`поток-хаб-${ключ}-${мин}`);
        if (!н) continue;
        for (const ш of н.шаги) {
          /* Сорок две головоломки Тэтхэма живут под ОДНИМ маршрутом, и режим —
             единственное, чем они различаются. Поэтому им сверка строгая: голая
             карточка `/games/puzzles` — это `ПО_УМОЛЧАНИЮ` и только он. Иначе
             развилка с одной такой карточкой пропустила бы любую из сорока двух,
             и проба ослепла бы ровно там, где сложнее всего.
             Остальным режим — подвид одной игры («Лаборатория» twiddle/net,
             судоку towers): годится и точная карточка с режимом, и голая. */
          const сРежимом = ш.mode ? `${ш.game_route}?mode=${encodeURIComponent(ш.mode)}` : null;
          const годен = ш.game_id === 'puzzles'
            ? свои.has((ш.mode ?? ПО_УМОЛЧАНИЮ) === ПО_УМОЛЧАНИЮ ? '/games/puzzles' : сРежимом!)
            : свои.has(ш.game_route) || (сРежимом !== null && свои.has(сРежимом));
          if (!годен) чужие.push(`${ключ}-${мин}: ${сРежимом ?? ш.game_route}`);
        }
      }
    }
    expect(чужие).toEqual([]);
  });

  it('поток чисто шахматный: две игры развилки и ничего больше', () => {
    const с = заводскойСостав()!;
    const н = с.наборы.find((x) => x.id === 'поток-хаб-chess-15')!;
    expect([...new Set(н.шаги.map((ш) => ш.game_id))].sort()).toEqual(['chess_blind', 'scholars_mate']);
  });

  /**
   * 🔴 «ДЕТСКИЙ МАТ» В ПОТОКЕ ИДЁТ МИКСОМ, А НЕ ОТРАБОТКОЙ ОДНОГО УЗОРА.
   *
   * Денис 13.09.2026: «детский мат в одной фазе слишком простой, когда
   * переключение — это сложнее». Отработка узора меряет скорость знакомого,
   * микс требует сперва УЗНАТЬ картинку среди девятнадцати.
   *
   * ⚠️ И ЗЕРНО У КАЖДОГО ШАГА СВОЁ. Экран монтируется на каждом шаге заново,
   * `attempt` там всегда 0 — без `seed` девять шагов микса сдали бы одну и ту же
   * колоду, и «переключение» оказалось бы девятью одинаковыми раздачами.
   */
  it('🔴 в потоке микс узоров, и раздача у каждого шага своя', () => {
    const с = заводскойСостав()!;
    for (const мин of [5, 10, 15]) {
      const н = с.наборы.find((x) => x.id === `поток-хаб-chess-${мин}`)!;
      const маты = н.шаги.filter((ш) => ш.game_id === 'scholars_mate');
      expect(маты.length).toBeGreaterThan(0);
      /* Ни одной отработки единственного узора. */
      expect(маты.filter((ш) => ш.settings?.motif !== undefined)).toEqual([]);
      /* Микс — основной режим, а не один шаг из дюжины. */
      expect(маты.filter((ш) => ш.settings?.mix === 1).length * 2).toBeGreaterThanOrEqual(маты.length);
      /* Зёрна все разные. */
      const зёрна = маты.map((ш) => ш.settings?.seed);
      expect(зёрна.filter((z) => z === undefined)).toEqual([]);
      expect(new Set(зёрна).size).toBe(зёрна.length);
    }
  });
});

/**
 * 🔴 СЕРИЯ ХАБА — ВСЕ ИГРЫ РАЗВИЛКИ ОДНОЙ ЗАРЯДКОЙ (задача 12470af9, VER 2).
 *
 * 📍 Денис 16.09.2026: «в каждый хаб добавить серию (зарядку) из всех игр». 17.09.2026:
 * «собрать как есть, в редакторе я потом галочками поправлю, что идёт и в каком виде».
 * Серии собирает `scripts/build-hub-series.mjs` по шагу на каждый экран развилки.
 *
 * ⚠️ ПОЛНОТУ ПРОБА НЕ ТРЕБУЕТ — и это решение, а не недосмотр. После сборки Денис убирает
 * игры галочками; проба, требующая «все экраны до одного», краснела бы на каждой его правке
 * и воевала бы с рабочим инструментом. Сторожим то, что правка в редакторе сломать не должна:
 * серия есть у каждой развилки, не пустая, в ней только игры этой развилки и она назначена
 * хотя бы одному профилю. Полноту на сборке печатает сам сборщик.
 */
describe('серия хаба — все игры развилки', () => {
  const маршрут = (э: ЭлементХаба): string => (typeof э === 'string' ? э : э.маршрут);
  /** Экраны развилки: группа раскрывается, карточка-набор — в свои режимы. */
  function экраны(хаб: string, изФайла: Record<string, ЭлементХаба[]>, глубина = 0): Set<string> {
    const карточки = изФайла[хаб]?.map(маршрут) ?? (HUB_CONTENTS[хаб] ?? []).map((c) => c.route);
    const вышло = new Set<string>();
    for (const р of карточки) {
      const путь = р.split('?')[0]!;
      if ((изФайла[путь] || HUB_CONTENTS[путь]) && путь !== хаб && глубина < 2) {
        for (const x of экраны(путь, изФайла, глубина + 1)) вышло.add(x);
        continue;
      }
      вышло.add(р);
      const набор = GAME_SUITES.find((н) => suiteEntryRoute(н) === р || suiteEntryRoute(н) === путь);
      if (набор) for (const м of набор.modes) вышло.add(м.route);
    }
    return вышло;
  }
  /** Экран шага: головоломки различаются режимом, у прочих режим — подвид одной игры. */
  const годен = (ш: { game_id: string; game_route: string; mode?: string }, свои: Set<string>): boolean => {
    if (ш.game_id === 'puzzles') {
      const режим = ш.mode ?? ПО_УМОЛЧАНИЮ;
      return свои.has(режим === ПО_УМОЛЧАНИЮ ? '/games/puzzles' : `/games/puzzles?mode=${encodeURIComponent(режим)}`)
        || свои.has(`/games/puzzles?mode=${режим}`);
    }
    return свои.has(ш.game_route) || (ш.mode !== undefined && свои.has(`${ш.game_route}?mode=${encodeURIComponent(ш.mode)}`));
  };

  it('🔴 у каждой из 13 развилок есть непустая серия, и в ней только игры этой развилки', () => {
    const с = заводскойСостав()!;
    const изФайла = (с.профили.odv999?.хабы ?? {}) as Record<string, ЭлементХаба[]>;
    const беды: string[] = [];
    for (const [ключ, хаб] of Object.entries(РАЗВИЛКА_ПОТОКА)) {
      const н = с.наборы.find((x) => x.id === `серия-хаб-${ключ}`);
      if (!н) { беды.push(`${ключ}: серии нет`); continue; }
      if (н.шаги.length === 0) { беды.push(`${ключ}: серия пустая`); continue; }
      const свои = экраны(хаб, изФайла);
      for (const ш of н.шаги) if (!годен(ш, свои)) беды.push(`${ключ}: чужая игра ${ш.game_route}${ш.mode ? `?mode=${ш.mode}` : ''}`);
    }
    expect(беды).toEqual([]);
  });

  it('🔴 каждая серия назначена хотя бы одному профилю — иначе её не видно в выборе зарядки', () => {
    const с = заводскойСостав()!;
    const назначены = new Set(Object.values(ФАЙЛ.профили as Record<string, { наборы?: string[] }>).flatMap((п) => п.наборы ?? []));
    const ничьи = Object.keys(РАЗВИЛКА_ПОТОКА).map((к) => `серия-хаб-${к}`)
      .filter((id) => с.наборы.some((н) => н.id === id) && !назначены.has(id));
    expect(`серии без профиля: ${ничьи.join(', ') || 'нет'}`).toBe('серии без профиля: нет');
  });
});

/**
 * 🔴 `STRUCTURE.md` СОБИРАЕТСЯ — ЗНАЧИТ, ОБЯЗАН БЫТЬ ПЕРЕСОБРАН.
 *
 * Просьба Дениса 13.09.2026: держать структуру ОДНИМ файлом, чтобы её не
 * пересказывали в одиннадцати ТЗ. Но «собирается» — это обещание, а не факт:
 * забыл прогнать `node frontend/scripts/build-structure.mjs` — и единственный
 * источник соврал увереннее любой копии, потому что на нём написано «собрано».
 *
 * Проба сверяет ЧИСЛА В ЗАГОЛОВКАХ развилок с настоящим составом. Полный разбор
 * файла здесь не нужен: разъезжается прежде всего количество карточек, а это
 * ловится одной строкой и без второго генератора.
 */
describe('STRUCTURE.md не отстал от состава', () => {
  it('🔴 число карточек в каждой развилке совпадает с файлом состава', () => {
    const { readFileSync } = require('fs');
    const { join } = require('path');
    const текст = readFileSync(join(__dirname, '../../..', 'STRUCTURE.md'), 'utf8') as string;
    const вФайле = new Map<string, number>();
    /* ⚠️ Заголовок бывает ДВУХ видов, и оба верны:
       «— 7» у развилки без наборов и «— 9 карточек · 18 экранов» у той, где
       карточка открывает набор режимов (правка сборщика 16.09.2026 — до неё
       документ выдавал карточки за экраны). Здесь сверяется число КАРТОЧЕК,
       поэтому берётся первое число в обоих видах. */
    for (const м of текст.matchAll(/^### .+ · `(\/games\/[^`]+)` — (\d+)(?: карточек · \d+ экранов)?$/gm)) {
      вФайле.set(м[1]!, Number(м[2]));
    }
    expect(`развилок в STRUCTURE.md: ${вФайле.size}`).toBe(`развилок в STRUCTURE.md: ${Object.keys(HUB_CONTENTS).length}`);

    const с = заводскойСостав()!;
    const изФайла = (с.профили.odv999?.хабы ?? {}) as Record<string, ЭлементХаба[]>;
    const разошлись: string[] = [];
    for (const хаб of Object.keys(HUB_CONTENTS)) {
      const надо = (изФайла[хаб] ?? HUB_CONTENTS[хаб] ?? []).length;
      const есть = вФайле.get(хаб);
      if (есть !== надо) разошлись.push(`${хаб}: в STRUCTURE.md ${есть ?? '—'}, на деле ${надо}`);
    }
    expect(разошлись).toEqual([]);
  });
});
