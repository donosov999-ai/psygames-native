/**
 * ОТСЕЧЕНИЯ РЕШАТЕЛЯ — ХРАПОВИК ПРОТИВ ТИХОЙ ПОТЕРИ ОТВЕТА.
 *
 * 🔴 ЧЕМ ОПАСНЫ ИМЕННО ЭТИ ПРАВКИ. Отсечение, срезающее лишнюю ветку, и
 * отсечение, срезающее ЕДИНСТВЕННОЕ решение, выглядят в коде одинаково: обе —
 * строчка `continue`. Разница видна только на доске, где решение живёт ровно в
 * отрезанной ветке. Оба приёма взяты у доноров жанра, где ёмкость ниш ОДНА на
 * всю доску; у нас их три, и обе строки пришлось сузить:
 *   · пустые ниши эквивалентны только при РАВНОЙ ёмкости — иначе «пустая на два»
 *     и «пустая на четыре» слиплись бы в одну ветку;
 *   · собранную нишу нельзя переносить в пустую, только если та НЕ ПРОСТОРНЕЕ —
 *     переезд из ниши на два в пустую на четыре бывает единственным ходом к тройке.
 * Здесь стоят доски, на которых обе поправки проверяются поимённо: снимешь
 * условие — тест покраснеет с ответом «нерешаема» там, где решение есть.
 *
 * Плюс ратчет стоимости: перебор на эталонных досках не должен дорожать молча.
 */
import { makeBoard, type Board } from '@/src/games/goods-sort/core/board';
import { solveStrict, solvableStrict } from '@/src/games/goods-sort/core/solver';
import { dealBoard, capsForBoard } from '@/app/games/goods-sort';

const B = (cells: number[][], caps: number[]): Board => makeBoard(cells, caps);

describe('отсечения не съедают решение', () => {
  it('🔴 собранную нишу МОЖНО переносить в БОЛЕЕ ПРОСТОРНУЮ пустую', () => {
    /**
     * Три единицы: две лежат в нише на ДВА (она однородна и полна), третья — в
     * такой же тесной нише. Тройка физически складывается только в нише на
     * четыре, то есть обе однородные ниши обязаны переехать в просторную пустую.
     * Сделай запрет «собранное в пустую не переносить» безусловным, как у донора
     * с единой ёмкостью, — и решаемая доска станет «нерешаемой».
     */
    const board = B([[1, 1], [1], []], [2, 2, 4]);
    expect(solvableStrict(board)).toBe(true);
  });

  it('🔴 пустые ниши РАЗНОЙ ёмкости — разные ветки, а не одна', () => {
    /**
     * Две пустые подряд: тесная на два (индекс 0) и просторная на четыре
     * (индекс 1). Тройка собирается только в просторной. Схлопни симметрию до
     * «одной первой пустой», не глядя на ёмкость, — перебор уйдёт в тесную и
     * решения не найдёт.
     */
    const board = B([[], [], [1, 1], [1]], [2, 4, 2, 2]);
    expect(solvableStrict(board)).toBe(true);
  });

  it('нерешаемое остаётся нерешаемым — отсечения не выдумывают решений', () => {
    // Три типа по два экземпляра, тройке взяться неоткуда, свободного места нет.
    expect(solvableStrict(B([[1, 2], [2, 3], [3, 1]], [2, 2, 2]))).toBe(false);
  });

  it('перебор доходит до ответа, а не упирается в потолок на ровном месте', () => {
    const r = solveStrict(B([[1, 1], [1], []], [2, 2, 4]), 20000);
    expect(`исчерпан ${r.exhausted}`).toBe('исчерпан false');
    expect(r.nodes).toBeGreaterThan(0);
  });
});

describe('ратчет стоимости: перебор не дорожает молча', () => {
  const POOL = Array.from({ length: 23 }, (_, i) => i);
  /** Детерминированный Math.random: иначе «стало дороже» меряется на других досках. */
  const seeded = (seed: number) => {
    let a = seed >>> 0;
    return () => {
      a |= 0; a = (a + 0x6D2B79F5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  };

  it('🔴 узлов на шестидесяти эталонных досках не больше замеренного', () => {
    const real = Math.random;
    let nodes = 0;
    let unknown = 0;
    for (const L of [14, 20, 30, 44, 56]) {
      for (let i = 0; i < 12; i++) {
        Math.random = seeded(L * 1000 + i);
        const d = dealBoard(L, POOL, false);
        Math.random = real;
        const r = solveStrict(makeBoard(d.cells, capsForBoard(L, d.cells)), 20000);
        nodes += r.nodes;
        if (r.exhausted) unknown += 1;
      }
    }
    Math.random = real;
    /**
     * Замер 30.08.2026: до отсечений 96 671 узел, после — 82 516. Потолок взят с
     * запасом в пять процентов от «после»: правка, вернувшая старую цену,
     * покраснеет здесь, а не через месяц в виде подвисшего экрана.
     */
    expect(`узлов ${nodes} ≤ 86 000: ${nodes <= 86_000}`).toBe(`узлов ${nodes} ≤ 86 000: true`);
    // Четыре доски L30 упираются в потолок и это ИЗВЕСТНО: они нерешаемы,
    // доказано отдельным прогоном при бюджете 200 000 (64–111 тыс. узлов).
    expect(unknown).toBeLessThanOrEqual(4);
  });
});
