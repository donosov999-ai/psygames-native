/**
 * 🔴 В ПОДСКАЗКЕ КОЛЛЕКЦИИ РОВНО ОДНО ЧИСЛО.
 *
 * Отчёт 972a4657 (11.09.2026, iOS 2.53.8): человек не смог понять, как получить
 * «Фонарь». На кадре подсказка говорила «opens at ⭐1550, 1535 ⭐ to go» — порог
 * и остаток рядом, и это читается как противоречие: так 1550 или 1535?
 *
 * Порог у фигурки и так написан на карточке (`collectionLocked`). Поэтому в
 * подсказке остаётся ТОЛЬКО остаток: каждое число живёт в одном месте.
 *
 * ⚠️ Проба смотрит ВО ВСЕ языки, а не в ru/en: беда была текстовая, а тексты
 * живут в одиннадцати файлах — правка «на своём языке» тут ничего не значит.
 *
 * 🔴 КОДЫ ЯЗЫКОВ БЕРУТСЯ ЧЕРЕЗ `.map(l => l.code)`. `LANGUAGES` — МАССИВ
 * `{code, name}`, и `Object.keys` отдаёт ИНДЕКСЫ «0»…«11». Первая редакция этой
 * пробы так и делала: `translateFor('0', …)` молча возвращает английский
 * фолбэк, где подстановки порога нет никогда, — и проба была зелёной при
 * заведомо испорченном переводе. Поймано контрольной мутацией, не чтением.
 */
import { LANGUAGES, translateFor } from '@/src/contexts/LanguageContext';

const КЛЮЧ = 'collectionHowToOpen';

describe('подсказка коллекции: одно число, а не два', () => {
  const языки = (LANGUAGES as { code: string }[]).map((l) => l.code);

  it('языков в проверке больше десяти — иначе это не «во всех»', () => {
    expect(языки.length).toBeGreaterThanOrEqual(11);
  });

  it('🔴 ни в одном языке нет подстановки порога {at}', () => {
    const сПорогом = языки.filter((я) => translateFor(я, КЛЮЧ).includes('{at}'));
    expect(сПорогом).toEqual([]);
  });

  it('🔴 остаток {n} на месте во всех языках — иначе подсказка перестала говорить', () => {
    const безОстатка = языки.filter((я) => !translateFor(я, КЛЮЧ).includes('{n}'));
    expect(безОстатка).toEqual([]);
  });

  it('имя фигурки подставляется во всех языках', () => {
    const безИмени = языки.filter((я) => !translateFor(я, КЛЮЧ).includes('{name}'));
    expect(безИмени).toEqual([]);
  });

  it('в готовой фразе остаётся ровно одно число', () => {
    const плохие: string[] = [];
    for (const я of языки) {
      const фраза = translateFor(я, КЛЮЧ)
        .replace('{name}', 'X')
        .replace('{n}', '1535');
      const числа = фраза.match(/\d+/g) ?? [];
      if (числа.length !== 1) плохие.push(`${я}: ${числа.length} чисел — «${фраза}»`);
    }
    expect(плохие).toEqual([]);
  });
});
