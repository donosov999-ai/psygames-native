/**
 * СТУПЕНЬ ОБЯЗАНА ОТВЕЧАТЬ «БЕЗ ЧЕГО ДОСКА НЕ РЕШАЕТСЯ», А НЕ «ЧТО СРАБОТАЛО».
 *
 * 🔴 ЧТО БЫЛО. Цепочка неравенств, сумма сэндвича и граница видимости небоскрёбов —
 * техники ступени 4, но жили они внутри `refilter` и работали ВСЕГДА, при любом
 * `tierCap`. Два следствия, оба замерены 06.09.2026 на боевом пути:
 *   · спросить «решается ли доска БЕЗ вариантной техники» было НЕЛЬЗЯ — ответ всегда
 *     выходил «да»: цена подсказками при `tierCap=1` равнялась 0 у 64 досок из 64;
 *   · `tier = 4` означал «фильтр варианта что-то отсёк», а не «без техники не обойтись»,
 *     и потому одинаково стоял на 11 ступенях из 16 у двух вариантных режимов.
 *
 * Здесь сторожится починка: `tierCap` отсекает вариантный ВЫВОД, оставляя вариантное
 * ПРАВИЛО (проверку против уже известных соседей) на месте — оно дано игроку даром.
 *
 * ⚠️ Гейт меряет ПОВЕДЕНИЕ на собранной доске, а не ищет слова в исходнике.
 */
import { gradePuzzle, liftByClueRemoval, лучшеПодПолосу } from '@/src/services/sudoku-grade';
import { Cell, dimsForSize, generateCages, generatePuzzle, KILLER_LADDER, TowersMap, UnequalMap } from '@/src/services/sudoku-core';
import { TOWERS_LADDER } from '@/src/services/sudoku-modes';

const { N, BR, BC } = dimsForSize(6);

describe('ступень — величина, а не отметка о срабатывании', () => {
  it('🔴 под потолком 1 вариантная техника НЕ МОЖЕТ оказаться самой сложной', () => {
    /**
     * 🔴 ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ ПРОВЕРКИ ПЕРЕЖИЛА МУТАЦИЮ — и я оставляю разбор, потому
     * что ошибка типовая. Она искала доску, где полный решатель справляется, а голые
     * одиночки нет, и объявляла это доказательством отсечения. Но такая доска есть
     * ВСЕГДА: `tierCap=1` отсекает и обычные техники (скрытую одиночку, locked), и
     * разница возникала из-за НИХ. Вернул дефект (`выводВарианта = true`) — проба
     * осталась зелёной, то есть мерила «есть доски сложнее первой ступени».
     *
     * Здесь меряется ровно заявленное и наблюдаемое: под потолком 1 вариантный вывод
     * выключен, значит `hardest` НЕ МОЖЕТ быть вариантной техникой ни на одной доске.
     * При возвращённом дефекте `towers_clue` немедленно всплывает.
     */
    let сКраем = 0;
    let подПотолком = 0;
    for (let i = 0; i < 40; i++) {
      const g = generatePuzzle(18, N, BR, BC, 'towers');
      const towers = (g as unknown as { towers?: TowersMap }).towers;
      const ctx = { N, BR, BC, variant: 'towers' as const, towers };
      if (gradePuzzle(g.puzzle, ctx).hardest === 'towers_clue') сКраем++;
      if (gradePuzzle(g.puzzle, ctx, 1).hardest === 'towers_clue') подПотолком++;
    }
    // Проверка живая: без потолка край становится сложнейшей техникой на части досок.
    expect(`край работает без потолка: ${сКраем > 0}`).toBe('край работает без потолка: true');
    // А под потолком 1 — ни на одной.
    expect(`край под потолком 1: ${подПотолком} досок`).toBe('край под потолком 1: 0 досок');
  });

  it('🔴 длина и цена вывода считаются у КАЖДОЙ доски, включая нерешённую', () => {
    /**
     * Величина, которой не хватало: `tier` — ярлык, `steps`/`cost` — числа.
     * ⚠️ ГЛУБИНА ЗДЕСЬ МЕЛКАЯ НАРОЧНО. Первая редакция брала 18 выколотых — а при
     * такой копке доска не берётся логикой почти в половине случаев (замер: 22 из 40),
     * и на нерешаемой `steps` законно остаётся нулём. Проба мигнула ровно так на
     * первом же прогоне. Мигающая проба приучает не смотреть на красное, поэтому
     * условие сделано детерминированным: на восьми дырках решатель работает всегда.
     */
    const g = generatePuzzle(8, N, BR, BC, 'towers');
    const towers = (g as unknown as { towers?: TowersMap }).towers;
    const r = gradePuzzle(g.puzzle, { N, BR, BC, variant: 'towers', towers });
    expect(typeof r.steps).toBe('number');
    expect(typeof r.cost).toBe('number');
    expect(`доска на 8 дырок решена: ${r.solved}`).toBe('доска на 8 дырок решена: true');
    expect(r.steps).toBeGreaterThan(0);
    // цена не ниже длины: каждый шаг стоит минимум ступень 1
    expect(r.cost).toBeGreaterThanOrEqual(r.steps);

    // и у НЕРЕШЁННОЙ доски величины тоже есть — пустая сетка логикой не берётся
    const пусто: Cell[][] = Array.from({ length: N }, () => Array(N).fill(0) as Cell[]);
    const нерешённая = gradePuzzle(пусто, { N, BR, BC, variant: 'none' });
    expect(нерешённая.solved).toBe(false);
    expect(typeof нерешённая.steps).toBe('number');
    expect(typeof нерешённая.cost).toBe('number');
  });

  it('🔴 то же у неравенств: цепочка под потолком 1 не всплывает', () => {
    const d9 = dimsForSize(9);
    let сЦепью = 0;
    let подПотолком = 0;
    for (let i = 0; i < 12; i++) {
      const g = generatePuzzle(50, d9.N, d9.BR, d9.BC, 'unequal');
      const unequal = (g as unknown as { unequal?: UnequalMap }).unequal;
      const ctx = { N: d9.N, BR: d9.BR, BC: d9.BC, variant: 'unequal' as const, unequal };
      if (gradePuzzle(g.puzzle, ctx).hardest === 'unequal_chain') сЦепью++;
      if (gradePuzzle(g.puzzle, ctx, 1).hardest === 'unequal_chain') подПотолком++;
    }
    expect(`цепочка работает без потолка: ${сЦепью > 0}`).toBe('цепочка работает без потолка: true');
    expect(`цепочка под потолком 1: ${подПотолком} досок`).toBe('цепочка под потолком 1: 0 досок');
  });
});

describe('цена вывода — второй ключ отбора', () => {
  /**
   * Правило отбора вынесено в чистую функцию именно ради этой проверки: раньше оно
   * жило внутри сборщика, и проверить его можно было только прогоном генератора —
   * то есть случайностью. Здесь подделанные доски, ответ детерминированный.
   */
  const доска = (tier: number, cost: number, solved = true) =>
    ({ grade: { solved, tier, cost, steps: 1, hardest: 'naked_single' as const } });
  const dist = (t: number) => (t < 4 ? 4 - t : t > 5 ? t - 5 : 0);   // полоса 4..5
  const вПролёте = (g: { solved: boolean; tier: number }) => !g.solved || g.tier > 5;

  it('🔴 при РАВНОЙ ступени побеждает доска дороже', () => {
    expect(лучшеПодПолосу(доска(4, 120), доска(4, 60), dist, вПролёте)).toBe(true);
    expect(лучшеПодПолосу(доска(4, 60), доска(4, 120), dist, вПролёте)).toBe(false);
    // равная цена — не повод меняться: лишняя пересборка ничего не даёт
    expect(лучшеПодПолосу(доска(4, 60), доска(4, 60), dist, вПролёте)).toBe(false);
  });

  it('🔴 но цена НЕ ПЕРЕБИВАЕТ полосу — иначе дорогая доска мимо цели победила бы', () => {
    // ближе к полосе важнее цены: tier 4 в полосе против tier 2 вне её
    expect(лучшеПодПолосу(доска(2, 999), доска(4, 10), dist, вПролёте)).toBe(false);
    // доска выше потолка проигрывает любой доске в полосе, как бы дорога ни была
    expect(лучшеПодПолосу(доска(6, 999), доска(4, 10), dist, вПролёте)).toBe(false);
    // и наоборот: доска в полосе вытесняет ту, что выше потолка
    expect(лучшеПодПолосу(доска(4, 10), доска(6, 999), dist, вПролёте)).toBe(true);
  });

  it('первый кандидат берётся всегда — сравнивать не с чем', () => {
    expect(лучшеПодПолосу(доска(1, 1), null, dist, вПролёте)).toBe(true);
  });
});

describe('небоскрёбы: вариант обязан заслуживать своё имя на ВСЕЙ лестнице', () => {
  /**
   * 🔴 ГЕЙТ РОДИЛСЯ ИЗ ДЫРЫ В ДРУГОМ ГЕЙТЕ. `sudoku-towers` проверяет нужность края
   * при одной глубине (BLANKS = 18) и в своей же шапке пишет, что на мелкой копке
   * подсказки декоративны. А лестница гоняла 12…20 — пять ступеней НИЖЕ рабочей точки,
   * то есть половина режима не проверялась ничем. Замер 07.09.2026, 40 досок на
   * ступень: без края решалось 39/40 на первой ступени против 7/40 на последней.
   *
   * Сторожим ось целиком: доля досок, решаемых БЕЗ края, обязана заметно падать от
   * первой ступени к последней. Это и значит «вариант заслуживает своё имя».
   */
  const d6 = dimsForSize(6);
  const безКрая = (blanks: number, tries = 30) => {
    let n = 0;
    for (let i = 0; i < tries; i++) {
      const g = generatePuzzle(blanks, d6.N, d6.BR, d6.BC, 'towers');
      if (gradePuzzle(g.puzzle, { N: d6.N, BR: d6.BR, BC: d6.BC, variant: 'none' }).solved) n++;
    }
    return n / tries;
  };

  it('🔴 на верхней ступени край нужен ВДВОЕ чаще, чем на нижней', () => {
    const ladder = TOWERS_LADDER;
    const низ = безКрая(ladder[0].blanks);
    const верх = безКрая(ladder[ladder.length - 1].blanks);
    // Порог мягкий (замер даёт разницу в пять-шесть раз), чтобы проба не мигала на шуме.
    expect(`верх ${верх.toFixed(2)} против низа ${низ.toFixed(2)}: край стал нужнее вдвое — ${верх <= низ / 2}`)
      .toBe(`верх ${верх.toFixed(2)} против низа ${низ.toFixed(2)}: край стал нужнее вдвое — true`);
  });

  it('🔴 верхняя ступень остаётся РЕШАЕМОЙ — глубина не может расти бесконечно', () => {
    // Доска, которую логикой не взять, — не трудный уровень, а сломанная задача.
    const blanks = TOWERS_LADDER[TOWERS_LADDER.length - 1].blanks;
    let решено = 0;
    for (let i = 0; i < 30; i++) {
      const g = generatePuzzle(blanks, d6.N, d6.BR, d6.BC, 'towers');
      const towers = (g as unknown as { towers?: TowersMap }).towers;
      if (gradePuzzle(g.puzzle, { N: d6.N, BR: d6.BR, BC: d6.BC, variant: 'towers', towers }).solved) решено++;
    }
    expect(`решаемых на верхней ступени ${решено}/30 — не меньше пятой части: ${решено >= 6}`)
      .toBe(`решаемых на верхней ступени ${решено}/30 — не меньше пятой части: true`);
  });
});

describe('карта клеток-сумм согласована сама с собой', () => {
  /**
   * 🔴 МИНА, КОТОРАЯ ЖДАЛА ПЕРВОГО ЧИТАТЕЛЯ (найдена и снята 07.09.2026).
   * `liftByClueRemoval` снимает группу-сумму, чтобы поднять ступень доски. Прежняя
   * редакция гасила `cageOf` и `cells`, но `sum`/`anchor` оставляла — на карте
   * оставалась МЕТКА БЕЗ КЛЕТОК. Игрок этого не видел (вся отрисовка идёт через
   * `cageOf[r][c] >= 0`), движок тоже переживал, а вот проба `sudoku-thermocage`
   * падала примерно раз в три полных прогона: она отсеивала только `undefined`.
   *
   * Здесь сторожится САМА КАРТА, а не её потребитель: сколько бы групп ни сняли,
   * у живой группы клетки и метка обязаны сходиться, а у снятой — не остаётся ни
   * клеток, ни числа.
   */
  const d9 = dimsForSize(9);

  it('🔴 после снятия групп не остаётся суммы без клеток', () => {
    let проверено = 0;
    for (let i = 0; i < 8; i++) {
      const g = generatePuzzle(50, d9.N, d9.BR, d9.BC, 'thermocage');
      const cages = (g as unknown as { cages?: { cells: [number, number][][]; sum: number[]; cageOf: number[][] } }).cages;
      if (!cages) continue;
      const поднято = liftByClueRemoval(
        g as never, d9.N, d9.BR, d9.BC, 'thermocage', 6, 6, Date.now() + 1500,
      );
      const c = (поднято.gen as unknown as { cages?: { cells: [number, number][][]; sum: number[]; cageOf: number[][] } }).cages;
      if (!c) continue;
      проверено++;
      const битые: string[] = [];
      for (let id = 0; id < c.cells.length; id++) {
        const клеток = c.cells[id]?.length ?? 0;
        const метка = c.sum[id] ?? 0;
        // снятая группа: ни клеток, ни числа
        if (клеток === 0 && метка !== 0) битые.push(`группа ${id}: клеток нет, метка ${метка}`);
        // живая группа: сумма клеток по решению совпадает с меткой
        if (клеток > 0) {
          const сумма = c.cells[id].reduce((a, [r, q]) => a + g.solution[r][q], 0);
          if (сумма !== метка) битые.push(`группа ${id}: сумма ${сумма}, метка ${метка}`);
        }
      }
      expect(битые).toEqual([]);
    }
    // Проверка живая: доски, на которых нечего было проверять, не считаются.
    expect(`досок с картой сумм: ${проверено > 0}`).toBe('досок с картой сумм: true');
  }, 120000);
});

describe('киллер: лестница растит нужность сумм, а не только число дырок', () => {
  /**
   * 🔴 ЗАЧЕМ ЭТОТ ГЕЙТ. Режим жил на трёх кнопках, и замер 07.09.2026 показал, что
   * на «Легко» клетки-суммы декоративны: 12 досок из 12 решались БЕЗ них вообще —
   * то есть киллер там не киллер. Ровно та же болезнь, что была у небоскрёбов, и
   * ровно так же её не видел ни один гейт: проб по киллеру не было ни одной.
   *
   * Сторожим то же, что у башен: снизу вверх суммы должны становиться НУЖНЕЕ.
   */
  const d9 = dimsForSize(9);
  const безСумм = (blanks: number, tries = 14) => {
    let n = 0;
    for (let i = 0; i < tries; i++) {
      const g = generatePuzzle(blanks, d9.N, d9.BR, d9.BC, 'none');
      if (gradePuzzle(g.puzzle, { N: d9.N, BR: d9.BR, BC: d9.BC, variant: 'none' }).solved) n++;
    }
    return n / tries;
  };

  it('🔴 на верхней ступени суммы нужнее, чем на нижней', () => {
    const низ = безСумм(KILLER_LADDER[0]);
    const верх = безСумм(KILLER_LADDER[KILLER_LADDER.length - 1]);
    // Порог мягкий: замер даёт 16/16 внизу против 11–12/16 наверху, шум выборки велик.
    expect(`верх ${верх.toFixed(2)} не выше низа ${низ.toFixed(2)}: ${верх < низ}`)
      .toBe(`верх ${верх.toFixed(2)} не выше низа ${низ.toFixed(2)}: true`);
  });

  it('🔴 лестница растёт и не топчется: каждая ступень глубже предыдущей', () => {
    const шаги = [...KILLER_LADDER];
    const плоские: string[] = [];
    for (let i = 1; i < шаги.length; i++) if (шаги[i] <= шаги[i - 1]) плоские.push(`ст.${i + 1}: ${шаги[i]} не глубже ${шаги[i - 1]}`);
    expect(плоские).toEqual([]);
    // и вход не пустой: первая ступень мельче последней заметно
    expect(`размах ${шаги[шаги.length - 1] - шаги[0]} клеток`).toBe('размах 16 клеток');
  });

  it('🔴 доска верхней ступени всё ещё берётся логикой — с суммами', () => {
    const blanks = KILLER_LADDER[KILLER_LADDER.length - 1];
    let решено = 0;
    for (let i = 0; i < 12; i++) {
      const g = generatePuzzle(blanks, d9.N, d9.BR, d9.BC, 'none');
      const cages = generateCages(g.solution, d9.N);
      if (gradePuzzle(g.puzzle, { N: d9.N, BR: d9.BR, BC: d9.BC, variant: 'none', cages }).solved) решено++;
    }
    expect(`решаемых на верхней ступени ${решено}/12: ${решено >= 9}`)
      .toBe(`решаемых на верхней ступени ${решено}/12: true`);
  });
});
