declare const __dirname: string;
declare function require(id: string): any;

const { execFileSync } = require('node:child_process');
const { existsSync } = require('node:fs');
const path = require('node:path');

const ЯДРО = path.join(__dirname, '../games/number-run');
const ФАЙЛЫ = ['runner-core.test.mjs', 'runner-campaign.test.mjs'];

/**
 * Пол числа проверок. Нужен против самого опасного исхода: `node --test` на
 * пустом наборе выходит с кодом 0, и «зелено» означало бы «ничего не запущено».
 * ⚠️ Поднимать вместе с набором, опускать — только осознанно.
 * 16.09.2026: 45 → 55 (построения маршрута VER 4, пол 40 → 52).
 */
const ПОЛ_ПРОВЕРОК = 52;

describe('🔴 «Числовой забег»: пробы ядра выполняются в общем прогоне', () => {
  it('есть что запускать — оба файла на месте', () => {
    // Переименуют или перенесут — обёртка покраснеет, а не позеленеет вхолостую.
    const пропали = ФАЙЛЫ.filter((ф) => !existsSync(path.join(ЯДРО, ф)));
    expect(`пропали: ${пропали.join(', ') || '—'}`).toBe('пропали: —');
  });

  it('🔴 45 проверок автора проходят, и их не меньше пола', () => {
    let вывод = '';
    let код = 0;
    try {
      вывод = execFileSync('node', ['--test', ...ФАЙЛЫ], {
        cwd: ЯДРО, encoding: 'utf8', timeout: 120000,
      }) as string;
    } catch (e: any) {
      код = e.status ?? 1;
      вывод = `${e.stdout ?? ''}${e.stderr ?? ''}`;
    }

    const прошло = Number(/^# pass (\d+)$/m.exec(вывод)?.[1] ?? /ℹ pass (\d+)/.exec(вывод)?.[1] ?? 0);
    const упало = Number(/^# fail (\d+)$/m.exec(вывод)?.[1] ?? /ℹ fail (\d+)/.exec(вывод)?.[1] ?? 0);

    // Сообщение об ошибке обязано нести причину: иначе красный гейт заставит
    // человека лезть за ней руками, а это тот же слепой гейт, только медленнее.
    const хвост = вывод.split('\n').filter((s) => /not ok|Error|Assertion/.test(s)).slice(0, 6).join(' | ');
    expect(`код ${код}, упало ${упало}${хвост ? ' · ' + хвост : ''}`).toBe('код 0, упало 0');
    expect(`прошло ${прошло} ≥ ${ПОЛ_ПРОВЕРОК}: ${прошло >= ПОЛ_ПРОВЕРОК}`)
      .toBe(`прошло ${прошло} ≥ ${ПОЛ_ПРОВЕРОК}: true`);
  });
});
