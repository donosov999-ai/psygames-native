/**
 * 🔴 КРУГ БУКВ — ПРОВЕРЯЕМ ЧИСЛАМИ, А НЕ ГЛАЗАМИ.
 *
 * Просьба Дениса 06.09.2026: «надо круг с буквами для введения у них перенять,
 * им удобнее вводить». Удобство ввода — это два числа: попадает ли палец в
 * букву и не попадает ли сразу в две. Оба проверяются здесь.
 */
import { точкиКруга, радиусПопадания, буквоПод, шагЛинии, словоИзЛинии } from '@/src/components/letterWheel/geometry';

const РАЗМЕРЫ = [220, 260, 300, 340, 420];
const ЧИСЛА = [3, 4, 5, 6, 7, 8, 9];

describe('круг букв: геометрия', () => {
  it('первая буква стоит СВЕРХУ, дальше по часовой', () => {
    const p = точкиКруга(4, 300);
    expect(Math.round(p[0]!.x)).toBe(150);
    expect(p[0]!.y).toBeLessThan(150);          // верх
    expect(p[1]!.x).toBeGreaterThan(150);       // право
    expect(p[2]!.y).toBeGreaterThan(150);       // низ
    expect(p[3]!.x).toBeLessThan(150);          // лево
  });

  it('все буквы внутри поля и не наезжают на край', () => {
    const плохо: string[] = [];
    for (const s of РАЗМЕРЫ) for (const n of ЧИСЛА) {
      const r = радиусПопадания(n, s);
      for (const p of точкиКруга(n, s)) {
        if (p.x - r < 0 || p.y - r < 0 || p.x + r > s || p.y + r > s) плохо.push(`${n} букв на ${s}: (${Math.round(p.x)},${Math.round(p.y)}) r=${Math.round(r)}`);
      }
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 одно касание попадает РОВНО в одну букву, а не в две', () => {
    const плохо: string[] = [];
    for (const s of РАЗМЕРЫ) for (const n of ЧИСЛА) {
      const p = точкиКруга(n, s); const r = радиусПопадания(n, s);
      for (let i = 0; i < n; i++) for (let j = i + 1; j < n; j++) {
        const d = Math.hypot(p[i]!.x - p[j]!.x, p[i]!.y - p[j]!.y);
        if (d < 2 * r) плохо.push(`${n} букв на ${s}: ${i} и ${j} перекрыты (${Math.round(d)} < ${Math.round(2 * r)})`);
      }
    }
    expect(плохо).toEqual([]);
  });

  it('цель нажатия не мельче 44 точек по норме — кроме самых тесных кругов', () => {
    const мелкие: string[] = [];
    for (const s of РАЗМЕРЫ) for (const n of ЧИСЛА) {
      if (2 * радиусПопадания(n, s) < 44) мелкие.push(`${n} букв на ${s}: ${Math.round(2 * радиусПопадания(n, s))}`);
    }
    expect(мелкие).toEqual([]);
  });

  it('палец в центре буквы её находит, а между букв — нет', () => {
    const p = точкиКруга(6, 300); const r = радиусПопадания(6, 300);
    for (let i = 0; i < 6; i++) expect(буквоПод(p, p[i]!.x, p[i]!.y, r)).toBe(i);
    expect(буквоПод(p, 150, 150, r)).toBe(-1);   // центр круга — ничей
  });
});

describe('круг букв: ведение линии', () => {
  it('новая буква удлиняет линию', () => {
    expect(шагЛинии([], 2)).toEqual([2]);
    expect(шагЛинии([2], 0)).toEqual([2, 0]);
  });

  it('та же буква ничего не меняет', () => {
    const л = [2, 0];
    expect(шагЛинии(л, 0)).toBe(л);            // тот же объект — перерисовки нет
  });

  it('🔴 возврат на предпоследнюю стирает хвост: так исправляют, не отпуская палец', () => {
    expect(шагЛинии([2, 0, 5], 0)).toEqual([2, 0]);
  });

  it('🔴 одну плитку дважды не берут', () => {
    const л = [2, 0, 5];
    expect(шагЛинии(л, 2)).toBe(л);
  });

  it('пустое касание линию не трогает', () => {
    const л = [1];
    expect(шагЛинии(л, -1)).toBe(л);
  });

  it('слово читается по линии', () => {
    expect(словоИзЛинии(['К', 'О', 'Т', 'С'], [0, 1, 2])).toBe('КОТ');
    expect(словоИзЛинии(['К', 'О', 'Т', 'С'], [])).toBe('');
  });
});
