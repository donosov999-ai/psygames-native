import { levelParams, CORSI_VOLUME_TOP } from '@/app/games/corsi';

/** Подпись уровня = всё, что человек может почувствовать. Совпали подписи — совпали уровни. */
const подпись = (l: number) => JSON.stringify(levelParams(l));

describe('corsi: лестница различает соседние уровни', () => {
  it('замер ДО зафиксирован: объём и скорость кончаются на CORSI_VOLUME_TOP', () => {
    const top = levelParams(CORSI_VOLUME_TOP);
    expect(`${top.startSpan} клеток, шаг ${top.tickMs}, вспышка ${top.flashMs}, обратный ${top.reverse}`)
      .toBe('8 клеток, шаг 480, вспышка 280, обратный true');
    // и выше по прежним осям не растёт — иначе замер ДО был бы про другое
    expect(levelParams(60).startSpan).toBe(top.startSpan);
    expect(levelParams(60).tickMs).toBe(top.tickMs);
    expect(levelParams(60).flashMs).toBe(top.flashMs);
  });

  it('ниже верха лестница НЕ тронута — задержки в прежней полосе нет', () => {
    for (let L = 1; L <= CORSI_VOLUME_TOP; L++) {
      expect(`L${L} holdMs=${levelParams(L).holdMs}`).toBe(`L${L} holdMs=0`);
    }
  });

  /**
   * 🔴 ГЛАВНОЕ. Ни одной пары соседей с одинаковой подписью на всём пробеге.
   */
  it('🔴 ни одного уровня-клона на L1…L60', () => {
    const клоны: string[] = [];
    for (let L = 2; L <= 60; L++) {
      if (подпись(L) === подпись(L - 1)) клоны.push(`L${L}=L${L - 1}`);
    }
    expect(`клонов: ${клоны.length}${клоны.length ? ' — ' + клоны.slice(0, 6).join(', ') : ''}`)
      .toBe('клонов: 0');
  });

  it('🔴 выше верха растёт именно задержка, монотонно', () => {
    for (let L = CORSI_VOLUME_TOP + 1; L <= 60; L++) {
      const было = levelParams(L - 1).holdMs;
      expect(`L${L}: ${levelParams(L).holdMs}`).toBe(`L${L}: ${было + 700}`);
    }
  });

  it('у задержки нет потолка — на L60 она заметно больше, чем на L20', () => {
    expect(levelParams(60).holdMs).toBeGreaterThan(levelParams(20).holdMs * 3);
  });
});
