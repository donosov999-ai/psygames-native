/**
 * «ПАУЗА» ПЕРЕВЕДЕНА ЦЕЛИКОМ — И ЭТО ПРОВЕРЯЕТСЯ, А НЕ ОБЕЩАЕТСЯ.
 *
 * 🔴 ЧТО БЫЛО. Задача b019f547 числилась как «268 из 339 реплик». Замер
 * 04.09.2026 дал другое: строк 371, переведено 268, без перевода 103 — и не
 * случайных. Переведены были ЗАГОЛОВКИ программ, а без перевода остались почти
 * все ТЕЛЕСНЫЕ указания: «плавно выдохните», «умеренно напрягите живот», «только
 * комфортная задержка». То есть на десяти языках человек видел красивое название
 * программы и английский фолбэк ровно в тот момент, когда выполняет движение.
 *
 * ⚠️ ЭТО НЕ ЛОВИЛОСЬ НИЧЕМ. Движок молча подставляет английский, если перевода
 * нет: экран выглядит исправным, ошибок в консоли нет, тесты зелёные. Поэтому
 * полнота меряется здесь — по СПИСКУ ИСТОЧНИКА, а не по числу ключей в словаре.
 *
 * ⚠️ И НАБОР ЯЗЫКОВ ТОЖЕ. Строка с девятью языками вместо десяти выглядит
 * переведённой и падает на одном языке из десяти. Такой промах уже случился при
 * этой самой правке: у одного предупреждения выпал корейский.
 */
import { PAUSE_I18N } from '@/src/games/pause/core/i18nSteps';
import { PRACTICE_CATALOG, PAUSE_STRINGS, WARNING_TEXT } from '@/src/games/pause/core/engine';

/** Языки поверх ru/en. Их ровно десять, и меньше быть не может. */
const ЯЗЫКИ = ['de', 'es', 'fr', 'it', 'pt', 'ar', 'hi', 'ja', 'ko', 'zh'];

function русскиеСтроки(): Set<string> {
  const из = new Set<string>();
  const собрать = (o: unknown): void => {
    if (!o || typeof o !== 'object') return;
    for (const v of Object.values(o as Record<string, unknown>)) {
      if (typeof v === 'string') { if (/[А-Яа-яЁё]/.test(v)) из.add(v); }
      else собрать(v);
    }
  };
  собрать(PRACTICE_CATALOG); собрать(PAUSE_STRINGS); собрать(WARNING_TEXT);
  return из;
}

describe('переводы «Паузы»', () => {
  it('🔴 у КАЖДОЙ русской строки каталога есть перевод', () => {
    const нет = [...русскиеСтроки()].filter((s) => !PAUSE_I18N[s]);
    expect(нет.slice(0, 6)).toEqual([]);
  });

  it('🔴 в каждом переводе все десять языков, а не девять', () => {
    const неполные = Object.entries(PAUSE_I18N)
      .filter(([, v]) => ЯЗЫКИ.some((я) => !(v as Record<string, string>)[я]))
      .map(([k, v]) => `${k.slice(0, 40)} → есть ${Object.keys(v).length}`);
    expect(неполные.slice(0, 6)).toEqual([]);
  });

  it('🔴 словарь не разошёлся с каталогом: мёртвых ключей нет', () => {
    const живые = русскиеСтроки();
    const мёртвые = Object.keys(PAUSE_I18N).filter((k) => !живые.has(k));
    // мёртвый ключ означает, что русский текст шага поменяли, а перевод остался
    // от прежней фразы — движок покажет старый смысл на десяти языках
    expect(мёртвые.slice(0, 6)).toEqual([]);
  });

  it('🔴 медицинский тон не смягчён: указания остались указаниями', () => {
    const боль = PAUSE_I18N['Остановитесь при боли, головокружении, онемении или выраженном дискомфорте.'];
    expect(боль).toBeTruthy();
    // «остановитесь» обязано остаться повелительным, а не «можно прекратить»
    expect(боль!.en ?? '').toBe('');           // ключ только для неанглийских
    expect(боль!.de).toMatch(/[Hh]ören Sie|[Ss]toppen/);
    expect(боль!.es).toMatch(/[Dd]eténgase|[Pp]are/);
  });
});
