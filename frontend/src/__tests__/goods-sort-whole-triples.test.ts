/**
 * 🔴 УРОВЕНЬ, КОТОРЫЙ НЕЛЬЗЯ ВЫИГРАТЬ, — И ПОЧЕМУ ЕГО НИКТО НЕ ЗАМЕТИЛ.
 *
 * Тройка в «Сортировке товаров» — три ОДИНАКОВЫХ товара (`tripleIn`, исключений
 * нет даже у джокера). Значит вид, которого на раскладе не кратно трём, не
 * исчезнет уже никогда: цель «разобрать всё» недостижима, и человек упирается в
 * доску, которую невозможно закончить.
 *
 * 📍 ЗАМЕР 24.09.2026 ПО ВЫГРУЖЕННОЙ ЛЕСТНИЦЕ (`flutter/assets/levels/goods_sort.json`,
 * зерно 20260923): СЕМЬ уровней из 60 на узкой сетке (L21 вид 4×2, L29, L31,
 * L35 сразу два вида, L57 и повторы хвоста) и ВОСЕМЬ из 60 на широкой.
 *
 * 🔴 ПРИЧИНА БЫЛА В `generate`, И ОНА МОЛЧАЛА. Раздача кладёт товар не по всем
 * нишам, а по подмножеству `used` (остальные обязаны остаться пустыми — запас и
 * места под препятствия). `used` — это ЧИСЛО ниш, а вместимости у них разные
 * (1, 2, 3, 4). Набралось много мелких — места на `types × CAP` товаров в
 * подмножестве не хватило, и товар, обошедший полный круг, ТИХО исчезал: ветки
 * «не положили» у цикла не было. Общей вместимости доски при этом хватало с
 * избытком — 42 места на 30 товаров.
 *
 * ⚠️ И ПОЧЕМУ ЭТО НЕ ПОЙМАЛА ПРОВЕРКА РЕШАЕМОСТИ. `provenUnsolvable` дорогой и
 * зовётся ТОЛЬКО под `strictPlacement(L)`. Все найденные битые доски — МЯГКИЕ,
 * то есть не проверялись вовсе. Здесь проверка арифметическая: один проход по
 * товарам, работает на любом уровне.
 */
// Лист без React: раздача — чистая функция, экран поднимать незачем.
import { CAP, dealBoard, GOOD_SETS, целымиТройками } from '@/src/games/goods-sort/core/level';
import { tripleIn } from '@/src/games/goods-sort/core/board';

declare function require(id: string): any;
declare const __dirname: string;

const МИКС = GOOD_SETS.find((s) => s.key === 'mix')!.pool;

/**
 * ⚠️ ЧТО ЭТОТ ГЕЙТ ДОКАЗЫВАЕТ, А ЧТО НЕТ — ПРОВЕРЕНО МУТАЦИЯМИ 24.09.2026.
 * Защит теперь ДВЕ: подмножество ниш в `generate` растёт под товар, и `dealtWrong`
 * перераздаёт доску, если кратность трём нарушена. Снял ОДНУ любую — гейт остался
 * зелёным: вторая справляется в одиночку. Снял ОБЕ — покраснел сразу и назвал
 * двенадцать ступеней из шестидесяти. То есть это СЕТЬ, а не различитель: он
 * говорит «битых раскладок нет», но не говорит, какая из двух защит сработала.
 *
 * 📍 И он же показал, что дефект шире выгрузки: в JSON с зерном 20260923 битых
 * уровней семь, а при снятых защитах ломаются L18, L21, L22, L25, L26, L27, L28,
 * L29, L31 и дальше — просто тому зерну на них не выпало. Судить о размере беды
 * по одной выгрузке было бы недомером.
 */

/** Сколько раз перераздать каждую ступень: раздача случайна, один заход не замер. */
const ЗАХОДОВ = 3;

describe('раздача товаров: каждый вид целыми тройками', () => {
  it('🔴 ни одной битой раскладки на 60 ступенях × две сетки', () => {
    const битые: string[] = [];
    for (const narrow of [true, false]) {
      for (let L = 1; L <= 60; L += 1) {
        for (let n = 0; n < ЗАХОДОВ; n += 1) {
          const d = dealBoard(L, МИКС, narrow);
          if (!целымиТройками(d.cells, d.queue, d.back)) {
            const счёт = new Map<number, number>();
            for (const c of d.cells) for (const t of c) счёт.set(t, (счёт.get(t) ?? 0) + 1);
            for (const s of d.queue ?? []) for (const t of s.cell) счёт.set(t, (счёт.get(t) ?? 0) + 1);
            for (const b of d.back ?? []) for (const t of b) счёт.set(t, (счёт.get(t) ?? 0) + 1);
            const плохие = [...счёт.entries()].filter(([, n2]) => n2 % CAP !== 0);
            битые.push(`${narrow ? 'узкая' : 'широкая'} L${L}: ${плохие.map(([t, n2]) => `вид ${t}×${n2}`).join(', ')}`);
          }
        }
      }
    }
    expect(битые).toEqual([]);
  });

  /**
   * ⚠️ ВСТРЕЧНАЯ СТОРОНА. Без неё проверка зеленела бы и на функции, которая
   * всегда отвечает «да», — а именно такой она и была бы, забудь мы про очередь
   * и задние ряды.
   */
  it('🔴 битую раскладку проверка НАЗЫВАЕТ битой — и видит очередь с задним рядом', () => {
    expect(целымиТройками([[1, 1, 1], [2, 2, 2]])).toBe(true);
    expect(целымиТройками([[1, 1, 1], [2, 2]])).toBe(false);

    // Недостающий третий лежит в очереди — расклад целый, хотя доска сама по себе нет.
    expect(целымиТройками([[1, 1]], [{ cell: [1], cap: 3 }])).toBe(true);
    // …и в заднем ряду.
    expect(целымиТройками([[1, 1]], [], [[1]])).toBe(true);
    // А вот теперь правда не хватает.
    expect(целымиТройками([[1, 1]], [], [[2, 2, 2]])).toBe(false);
  });
});

/**
 * 🔴 ТЕПЕРЬ ТО ЖЕ САМОЕ — ПО ФАЙЛУ, КОТОРЫЙ ЕДЕТ В СБОРКУ (25.09.2026).
 *
 * Выше проверяется РАЗДАЧА, то есть генератор. Между генератором и телефоном
 * лежит запись в `flutter/assets/levels/goods_sort.json`, и приложение читает
 * ИМЕННО ЕЁ: экран `flutter/lib/games/goods_sort/` не зовёт `dealBoard` вовсе.
 * Значит зелёный гейт на генераторе ничего не говорит про то, что у человека в
 * руках — ровно та щель, из-за которой держится правило «эталон замораживает
 * перенос, а не источник».
 *
 * 📍 ЗАМЕР 25.09.2026 ПО ФАЙЛУ (зерно 20260923, порог схлопывания 30): готовых
 * троек 0, не кратных трём 0, со схлопыванием 20 ступеней из 60, первая — L31.
 * До заслона в `dealCollapse` файл ИХ СОДЕРЖАЛ: на L38 и L41 приезжали
 * `[12,5,12,12]`, `[9,12,9,9]`, `[11,11,11,9]`.
 */
describe('выгруженная лестница товаров: файл, который едет в сборку', () => {
  const fs = require('fs');
  const path = require('path');
  const файл = path.resolve(__dirname, '../../../flutter/assets/levels/goods_sort.json');
  const данные = JSON.parse(fs.readFileSync(файл, 'utf8')) as {
    levels: Ступень[]; wide: Ступень[];
  };
  type Ступень = {
    level: number; collapse: boolean;
    cells: number[][]; queue: { cell: number[] }[]; back: number[][];
  };
  const лестницы: [string, Ступень[]][] = [['узкая', данные.levels], ['широкая', данные.wide]];

  const части = (lv: Ступень): [string, number[][]][] => [
    ['доска', lv.cells],
    ['очередь', (lv.queue ?? []).map((s) => s.cell)],
    ['за спиной', lv.back ?? []],
  ];

  it('есть что проверять — файл на месте и лестницы полные', () => {
    expect(данные.levels.length).toBeGreaterThan(50);
    expect(данные.wide.length).toBe(данные.levels.length);
    // И механика в файле правда есть: иначе проверки ниже сторожили бы пустоту.
    expect(данные.levels.filter((l) => l.collapse).length).toBeGreaterThan(0);
    expect(данные.levels.some((l) => (l.queue ?? []).length > 0)).toBe(true);
    expect(данные.levels.some((l) => (l.back ?? []).some((b) => b.length > 0))).toBe(true);
  });

  it('🔴 ни одна ступень в файле не приезжает с готовой тройкой', () => {
    const плохие: string[] = [];
    for (const [имя, лестница] of лестницы) {
      for (const lv of лестница) {
        for (const [где, группа] of части(lv)) {
          for (const cell of группа) {
            if (cell.length > 0 && tripleIn(cell) !== null) {
              плохие.push(`${имя} L${lv.level} ${где}: [${cell.join(',')}]`);
            }
          }
        }
      }
    }
    expect(плохие).toEqual([]);
  });

  it('🔴 в файле каждый вид лежит целыми тройками — вместе с очередью и задними рядами', () => {
    const битые: string[] = [];
    for (const [имя, лестница] of лестницы) {
      for (const lv of лестница) {
        const счёт = new Map<number, number>();
        for (const [, группа] of части(lv)) {
          for (const cell of группа) for (const t of cell) счёт.set(t, (счёт.get(t) ?? 0) + 1);
        }
        const лишние = [...счёт.entries()].filter(([, n]) => n % CAP !== 0);
        if (лишние.length > 0) битые.push(`${имя} L${lv.level}: ${лишние.map(([t, n]) => `вид ${t}×${n}`).join(', ')}`);
      }
    }
    expect(битые).toEqual([]);
  });
});
