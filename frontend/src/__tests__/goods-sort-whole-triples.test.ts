// Лист без React: раздача — чистая функция, экран поднимать незачем.
import { CAP, dealBoard, GOOD_SETS, целымиТройками } from '@/src/games/goods-sort/core/level';

const МИКС = GOOD_SETS.find((s) => s.key === 'mix')!.pool;

/**
 * ⚠️ ЧТО ЭТОТ ГЕЙТ ДОКАЗЫВАЕТ, А ЧТО НЕТ — ПРОВЕРЕНО МУТАЦИЯМИ 24.09.2026.
 * Защит теперь ДВЕ: подмножество ниш в `generate` растёт под товар, и `dealtWrong`
 * перераздаёт доску, если кратность трём нарушена. Снял ОДНУ любую — гейт остался
 * зелёным: вторая справляется в одиночку. Снял ОБЕ — покраснел сразу и назвал
 * двенадцать ступеней из шестидесяти. То есть это СЕТЬ, а не различитель: он
 * говорит «битых раскладок нет», но не говорит, какая из двух защит сработала.
 *
 * 📍 И он же показал, что дефект шире выгрузки: в JSON с зерном 20260923 битых
 * уровней семь, а при снятых защитах ломаются L18, L21, L22, L25, L26, L27, L28,
 * L29, L31 и дальше — просто тому зерну на них не выпало. Судить о размере беды
 * по одной выгрузке было бы недомером.
 */

/** Сколько раз перераздать каждую ступень: раздача случайна, один заход не замер. */
const ЗАХОДОВ = 3;

describe('раздача товаров: каждый вид целыми тройками', () => {
  it('🔴 ни одной битой раскладки на 60 ступенях × две сетки', () => {
    const битые: string[] = [];
    for (const narrow of [true, false]) {
      for (let L = 1; L <= 60; L += 1) {
        for (let n = 0; n < ЗАХОДОВ; n += 1) {
          const d = dealBoard(L, МИКС, narrow);
          if (!целымиТройками(d.cells, d.queue, d.back)) {
            const счёт = new Map<number, number>();
            for (const c of d.cells) for (const t of c) счёт.set(t, (счёт.get(t) ?? 0) + 1);
            for (const s of d.queue ?? []) for (const t of s.cell) счёт.set(t, (счёт.get(t) ?? 0) + 1);
            for (const b of d.back ?? []) for (const t of b) счёт.set(t, (счёт.get(t) ?? 0) + 1);
            const плохие = [...счёт.entries()].filter(([, n2]) => n2 % CAP !== 0);
            битые.push(`${narrow ? 'узкая' : 'широкая'} L${L}: ${плохие.map(([t, n2]) => `вид ${t}×${n2}`).join(', ')}`);
          }
        }
      }
    }
    expect(битые).toEqual([]);
  });

  /**
   * ⚠️ ВСТРЕЧНАЯ СТОРОНА. Без неё проверка зеленела бы и на функции, которая
   * всегда отвечает «да», — а именно такой она и была бы, забудь мы про очередь
   * и задние ряды.
   */
  it('🔴 битую раскладку проверка НАЗЫВАЕТ битой — и видит очередь с задним рядом', () => {
    expect(целымиТройками([[1, 1, 1], [2, 2, 2]])).toBe(true);
    expect(целымиТройками([[1, 1, 1], [2, 2]])).toBe(false);

    // Недостающий третий лежит в очереди — расклад целый, хотя доска сама по себе нет.
    expect(целымиТройками([[1, 1]], [{ cell: [1], cap: 3 }])).toBe(true);
    // …и в заднем ряду.
    expect(целымиТройками([[1, 1]], [], [[1]])).toBe(true);
    // А вот теперь правда не хватает.
    expect(целымиТройками([[1, 1]], [], [[2, 2, 2]])).toBe(false);
  });
});
