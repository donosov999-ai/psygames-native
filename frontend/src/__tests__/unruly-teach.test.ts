/**
 * 🔴 РАЗБОР ПО ШАГАМ ОБЯЗАН ПРИВОДИТЬ К РЕШЕНИЮ ДВИЖКА, И КАЖДЫЙ ШАГ ОБЯЗАН БЫТЬ ВЕРНЫМ.
 *
 * Пилот обучения «как играть правильно» (Денис 17.09.2026: «решатель по шагам рисует решение и
 * пишет объяснение — почему тут ставим»). Если разбор хоть раз поставит не тот цвет, он научит
 * ошибке; если встанет на полдороге, человек останется с недорешённой доской и словами «дальше
 * ничего». Поэтому проба меряет разбор на НАСТОЯЩИХ досках движка, снятых с моста
 * (`scripts/capture-unruly-boards.mjs`, по две раздачи на каждую из семи ступеней), и сверяет
 * с решением, которое дал сам движок (`psy_solve`), а не с моим же решателем.
 */
import { LANGUAGES, translateFor } from '@/src/contexts/LanguageContext';
import { разобрать as разобратьРисунок } from '@/src/games/tatham-bridge/play';
import type { Клетка } from '@/src/games/tatham-bridge/unruly';
import {
  разобрать, следующийШаг, расхождения, доскаСРисунка, размерИзПараметров, текстШага,
  КЛЮЧИ_РАЗБОРА, type ПриёмРазбора,
} from '@/src/games/tatham-bridge/unruly-teach';
import снимок from './unruly-teach-boards.generated.json';

interface Доска { параметры: string; зерно: number; ширина: number; начало: Клетка[][]; решение: Клетка[][] }
const доски = снимок.доски as unknown as Доска[];
const рисунки = снимок.рисунки as unknown as (Доска & { рисунок: string[] })[];

describe('разбор «Чёт-нечет» по шагам', () => {
  it('снимок живой: семь ступеней лестницы движка, по две раздачи', () => {
    expect(new Set(доски.map((д) => д.параметры)).size).toBe(7);
    expect(доски).toHaveLength(14);
  });

  it.each(доски.map((д) => [`${д.параметры}#${д.зерно}`, д] as const))(
    '🔴 %s: разбор доводит доску до решения движка, каждый шаг ставит верный цвет в пустую клетку',
    (_, д) => {
      let поле = д.начало.map((r) => [...r]);
      const шаги = разобрать(поле).шаги;
      expect(шаги.length).toBeGreaterThan(0);
      for (const шаг of шаги) {
        expect(шаг.ставим.length).toBeGreaterThan(0);
        for (const с of шаг.ставим) {
          expect({ клетка: [с.x, с.y], было: поле[с.y]![с.x] }).toEqual({ клетка: [с.x, с.y], было: null });
          expect({ клетка: [с.x, с.y], ставим: с.v }).toEqual({ клетка: [с.x, с.y], ставим: д.решение[с.y]![с.x] });
        }
        поле = поле.map((r) => [...r]);
        for (const с of шаг.ставим) поле[с.y]![с.x] = с.v;
      }
      expect(поле).toEqual(д.решение);
      expect(следующийШаг(поле)).toBeNull();
    },
  );

  it('на ступенях Normal нужен перебор линии, на остальных хватает пары, зазора и счёта — все четыре приёма в деле', () => {
    const приёмы = (д: Доска) => new Set<ПриёмРазбора>(разобрать(д.начало).шаги.map((ш) => ш.приём));
    const всего = new Set<ПриёмРазбора>(доски.flatMap((д) => [...приёмы(д)]));
    expect([...всего].sort()).toEqual(['зазор', 'пара', 'перебор', 'счёт']);
    // Без перебора ступени Normal не решаются: иначе приём стоял бы в разборе мёртвым грузом.
    const безПеребора = (д: Доска) => {
      let поле = д.начало.map((r) => [...r]);
      for (;;) {
        const ш = следующийШаг(поле);
        if (!ш || ш.приём === 'перебор') break;
        поле = поле.map((r) => [...r]);
        for (const с of ш.ставим) поле[с.y]![с.x] = с.v;
      }
      return поле.every((r) => r.every((c) => c !== null));
    };
    expect(доски.filter((д) => /dn$/.test(д.параметры)).some((д) => !безПеребора(д))).toBe(true);
  });

  it('🔴 доска снимается с рисунка движка тем же разбором, что у экрана; неполный рисунок — не доска', () => {
    expect(рисунки).toHaveLength(2);
    for (const р of рисунки) {
      const { w, h } = размерИзПараметров(р.параметры)!;
      const примитивы = разобратьРисунок(р.рисунок.join('\n'));
      expect(доскаСРисунка(примитивы, р.ширина, w, h)).toEqual(р.начало);
      // Контроль: без прямоугольников последней клетки доска не собирается.
      const плитка = р.ширина / (w + 1);
      const безУгла = примитивы.filter((п) => !(п.вид === 'прямоугольник' && п.x >= (w - 1) * плитка + плитка / 2 && п.y >= (h - 1) * плитка + плитка / 2 && п.ш < плитка * 2));
      expect(доскаСРисунка(безУгла, р.ширина, w, h)).toBeNull();
    }
  });

  it('ошибки человека находятся сверкой с решением: чужой цвет в клетке — расхождение', () => {
    const д = доски[0]!;
    const пустая = д.начало.flatMap((r, y) => r.flatMap((c, x) => (c === null ? [{ x, y }] : [])))[0]!;
    const верный = д.решение[пустая.y]![пустая.x] as 0 | 1;
    const поле = д.начало.map((r) => [...r]);
    поле[пустая.y]![пустая.x] = верный;
    expect(расхождения(поле, д.решение)).toEqual([]);
    поле[пустая.y]![пустая.x] = (1 - верный) as 0 | 1;
    expect(расхождения(поле, д.решение)).toEqual([{ ...пустая, v: 1 - верный }]);
  });

  it('🔴 объяснение есть на всех двенадцати языках, со своими подстановками, и ни одна не остаётся сырой', () => {
    const языки = (LANGUAGES as { code: string }[]).map((l) => l.code);
    expect(языки).toHaveLength(12);
    const подстановки: Record<string, string[]> = {
      teachStepOf: ['{i}', '{n}'], teachRow: ['{n}'], teachCol: ['{n}'],
      teachUnrulyPair: ['{line}'], teachUnrulyGap: ['{line}'], teachUnrulyCount: ['{line}'],
      teachUnrulyLineOne: ['{line}'], teachUnrulyLineMany: ['{line}', '{k}'],
    };
    const пропуски: string[] = [];
    for (const я of языки) {
      for (const к of КЛЮЧИ_РАЗБОРА) {
        const текст = translateFor(я, к);
        if (текст === к) пропуски.push(`${я}:${к} — нет ключа`);
        // Не английский фолбэк: у каждого языка свой текст.
        if (я !== 'en' && текст === translateFor('en', к)) пропуски.push(`${я}:${к} — английский фолбэк`);
        for (const п of подстановки[к] ?? []) if (!текст.includes(п)) пропуски.push(`${я}:${к} — нет ${п}`);
      }
    }
    expect(пропуски).toEqual([]);
    // Сборка текста: номер линии человеческий (с единицы), подстановок не остаётся.
    const шаги = разобрать(доски[13]!.начало).шаги;
    for (const я of языки) {
      for (const шаг of шаги.slice(0, 40)) {
        const текст = текстШага(шаг, (к) => translateFor(я, к));
        expect(текст).not.toMatch(/\{(line|k|n)\}/);
      }
    }
    const первый = шаги[0]!;
    expect(текстШага(первый, (к) => translateFor('ru', к))).toContain(
      `${первый.линия.вид === 'строка' ? 'Строка' : 'Столбец'} ${первый.линия.номер + 1}:`,
    );
  });
});
