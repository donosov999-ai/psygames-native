/**
 * ЕДИНЫЙ СТАНДАРТ ИГРОВОЙ МЕХАНИКИ. Каждое упражнение устроено одинаково.
 *
 * ЗАЧЕМ. Денис дословно: «нам важно сделать единый формат работы с каждым
 * упражнением, будь то дыхание, парные картинки или Шульте — уровни, свободный
 * режим, тропинка прогресса, боссы, геймификация» и «единый стандарт для всех,
 * шаблонизируем игровую механику».
 *
 * До этого формат разъезжался молча: игра могла завести свой экран итога, свою
 * плашку, свой счётчик — и тихо выпасть из общей бухгалтерии. Так и случилось с
 * маджонгом, сортировкой и парными картинками: у них не писались звёзды, не
 * считалась серия, не тикала глаз-разрядка, и правило режима приходилось
 * прописывать руками — именно они вылетали в вечерней зарядке.
 *
 * ТРИ ОБЯЗАТЕЛЬНЫХ ЧАСТИ (это и есть шаблон):
 *   1. ПРОГРЕСС — usePersistentLevel: число, которое растёт и переживает сессию.
 *      Это либо ступень сложности, либо счётчик прохождений — снаружи одинаково.
 *   2. ТРОПИНКА — LevelProgressMap на экране настроек: человек видит путь.
 *   3. ИТОГ — LevelCleared: единственное место, где пишутся звёзды по уровням,
 *      тикает серия чистых и наступает глаз-разрядка. Свой экран поздравления
 *      означает выпадение из всего этого.
 *
 * ⚠️ ЧЕГО ГЕЙТ НЕ ТРЕБУЕТ. Боссов — они уместны там, где есть правило, которое
 * можно резко сломать; в дыхании ломать нечего. И присутствия в зарядке: она
 * короткий ежедневный набор, а не весь каталог.
 */
declare const __dirname: string;
declare function require(m: string): any;
const { readFileSync, readdirSync, existsSync } = require('fs');
const { join } = require('path');

const GAMES_DIR = join(__dirname, '../../app/games');
const CATALOG = join(__dirname, '../constants/games.ts');

/**
 * Карточки-хабы: они не упражнения, а развилки на настоящие игры. Прогресса у них
 * нет и быть не должно — он у тех трёх-четырёх, куда хаб уводит.
 */
const HUBS = new Set(['span.tsx', 'attention-conflict.tsx']);

/** Экраны игр из каталога — берём маршруты, а не всё подряд в папке. */
function catalogScreens(): string[] {
  const src: string = readFileSync(CATALOG, 'utf8');
  const out = new Set<string>();
  const re = /route:\s*'\/games\/([a-z0-9-]+)'/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(src))) {
    const f = `${m[1]}.tsx`;
    if (!HUBS.has(f) && existsSync(join(GAMES_DIR, f))) out.add(f);
  }
  return [...out].sort();
}

const read = (f: string): string => readFileSync(join(GAMES_DIR, f), 'utf8');

describe('единый стандарт игровой механики', () => {
  const screens = catalogScreens();

  it('есть что проверять — иначе тест зелен вслепую', () => {
    expect(screens.length).toBeGreaterThan(55);
  });

  it('у каждой игры есть прогресс, который переживает сессию', () => {
    // Судоку хранит уровень СВОИМ ключом `psygames_sudoku_level_<профиль>` — она
    // старше хука. Формат тот же, стандарту соответствует по сути, поэтому
    // принимаем оба способа: хук или собственный ключ уровня.
    const without = screens.filter((f) => {
      const src = read(f);
      return !/usePersistentLevel\s*\(/.test(src) && !/_level_\$\{/.test(src);
    });
    expect(without).toEqual([]);
  });

  it('каждая игра показывает тропинку на экране настроек', () => {
    const without = screens.filter((f) => !/<LevelProgressMap/.test(read(f)));
    expect(without).toEqual([]);
  });

  it('каждая игра заканчивает раунд ОБЩИМ экраном — иначе звёзды и серия не пишутся', () => {
    const without = screens.filter((f) => !/<LevelCleared/.test(read(f)));
    expect(without).toEqual([]);
  });

  /**
   * РЕЗЕРВ ПРОГРЕССА В СЕССИИ — теперь требование, а не храповик.
   *
   * getMaxLevelFromSessions восстанавливает достигнутое из `details.level`, когда
   * ключ прогресса потерян: сброс профиля, смена профиля, обновление приложения.
   * Игра, которая его не пишет, при этом обнуляется. Таких было 20, все дописаны.
   *
   * ⚠️ ПЕРЕУСТАНОВКУ ЭТО НЕ ЛЕЧИТ, и раньше здесь было написано, что лечит.
   * История сессий читается ЛОКАЛЬНАЯ: в облако они только пишутся, обратного
   * чтения в коде нет. Снесли приложение — ушла и она. Подробности и проверка —
   * в profile-level-isolation.test.ts.
   *
   * ⚠️ ПРИНИМАЕМ И СОКРАЩЁННУЮ ЗАПИСЬ. Судоку пишет уровень как `{ level, variant }`
   * внутри условного разворота — прежний шаблон искал только `level:` и объявил её
   * нарушителем. Ложное срабатывание собственного гейта: правило было верным,
   * а распознавание — узким.
   *
   * ⚠️ И ЕЩЁ РАЗ, 19.08.2026, ПО ТОЙ ЖЕ ПРИЧИНЕ. Фрактальная судоку перевела уровень
   * партии из ref в состояние (`playedLevel`) — правку требовало правило React про
   * чтение ref в рендере. Уровень она пишет как писала, но перечисление ИМЁН
   * переменных её не узнало. Имена в шаблон больше не вписываем поштучно: принимаем
   * любой идентификатор, кончающийся на Level. Литерал по-прежнему не принимается —
   * проверка требует переменную, а не зашитую единицу.
   */
  it('каждая игра пишет уровень в сессию — иначе прогресс не переживёт сброс профиля', () => {
    const WRITES_LEVEL = /level:\s*(doneLevel|doneRun|done|lvl\.level|levelRef\.current|level|[A-Za-z_$][\w$]*Level)\b|\{\s*level\s*[,}]/;
    const without = screens.filter((f) => !WRITES_LEVEL.test(read(f)));
    expect(without).toEqual([]);
  });

  /**
   * РАЗМЕР КАТАЛОГА НИГДЕ НЕ ПИШЕТСЯ РУКАМИ.
   *
   * В карточке профиля стояло «Все 48 тренажёров» — столько их было когда-то.
   * Каталог дорос до 63, строка осталась, и человек видел цифру меньше правды
   * прямо в приложении. Это не опечатка, а класс ошибки: любое число, вбитое
   * рядом со словом «тренажёр», устаревает молча — каталог растёт, строка нет.
   *
   * ⚠️ Тексты витрин магазинов сюда НЕ входят: они живут в store/ и правятся под
   * релиз руками, там число сверяется отдельно при подаче.
   */
  it('число тренажёров нигде не вбито строкой — только из каталога', () => {
    const UI = [join(__dirname, '../components'), join(__dirname, '../../app')];
    const bad: string[] = [];
    const walk = (dir: string) => {
      for (const e of readdirSync(dir, { withFileTypes: true })) {
        const p = join(dir, e.name);
        if (e.isDirectory()) { walk(p); continue; }
        if (!/\.tsx?$/.test(e.name)) continue;
        // Комментарии вырезаем ЦЕЛИКОМ, а не по началу строки: пояснение про
        // «23 тренажёра» живёт внутри JSX-комментария, и построчная проверка
        // приняла бы его за текст для человека. Гейт поймал сам себя — правильно
        // ловить, но не то: число в комментарии это история, а не подпись.
        const src: string = readFileSync(p, 'utf8')
          .replace(/\/\*[\s\S]*?\*\//g, '')
          .replace(/\/\/[^\n]*/g, '');
        for (const m of src.matchAll(/\d{2,3}\s*(?:тренажёр|тренажер|упражнен|игр)[а-яё]*/gi)) {
          bad.push(`${e.name}: «${m[0]}»`);
        }
      }
    };
    UI.forEach(walk);
    expect(bad).toEqual([]);
  });

  /**
   * ЧИСЛО В ОПИСАНИИ ПРОФИЛЯ FREE СОВПАДАЕТ СО СПИСКОМ.
   *
   * «9 тренажёров · подобранный набор для старта» — сейчас правда, в списке ровно
   * девять. Но число вбито строкой, причём в двух местах: в профиле и в словаре на
   * 12 языков. Добавят десятую игру в набор — описание соврёт на всех языках сразу,
   * и заметит это пользователь, а не мы. Число само по себе не проверить: оно живёт
   * в тексте. Зато можно сверить его со списком, что и делаем.
   */
  it('описание профиля FREE не расходится с его набором игр', () => {
    const src: string = readFileSync(join(__dirname, '../constants/profiles.ts'), 'utf8');
    const seg = src.slice(src.indexOf('🎁 FREE'));
    const list = seg.match(/allowed_games:\s*\[([\s\S]*?)\]/);
    const desc = seg.match(/description:\s*'(\d+)\s*тренажёр/);
    expect(list && desc).toBeTruthy();
    const real = list![1].split(',').filter((s) => /'[a-z0-9_]+'/.test(s)).length;
    expect(`в наборе ${real}, в подписи ${desc![1]}`).toBe(`в наборе ${real}, в подписи ${real}`);
  });

  it('хабы стандарту не подчиняются — им нечего показывать', () => {
    for (const f of HUBS) {
      if (!existsSync(join(GAMES_DIR, f))) continue;
      expect(/usePersistentLevel\s*\(/.test(read(f))).toBe(false);
    }
  });
});
