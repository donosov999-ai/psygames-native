const ASKS_MARKS = ['confirmExit', 'useExitGuard'];

/**
 * ⚠️ КОММЕНТАРИИ СРЕЗАЕМ ПЕРЕД ПОИСКОМ. Проверено поломкой 19.08.2026: сняли у самурая
 * проп и написали рядом «// confirmExit снят» — гейт остался зелёным, потому что слово
 * в файле есть. Так проверка и умирает: рассказ о механизме считается механизмом.
 * Тот же класс, что «строка объявлена и переведена, но не выводится ни разу».
 *
 * ⚠️ И ЭТО КАСАЕТСЯ ВСЕХ ТРЁХ ПРИЗНАКОВ, а не только вопроса при выходе. Та же поломка,
 * повторённая на слое сохранения (вызовы вырезаны, а рядом строка «слой партии отключён,
 * но упомянут: saveResume»), 19.08.2026 гейт НЕ поймал: срез комментариев стоял только у
 * `asks`. Дыра закрыта — теперь через `code` идут и `saves`, и обещание `resumable`.
 */
const code = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const saves = (src: string) => SAVES_MARKS.some((m) => code(src).includes(m));
const asks = (src: string) => ASKS_MARKS.some((m) => code(src).includes(m));
/** Обещание «партия сохранится» — только настоящий проп каркаса, не упоминание в комментарии. */
const promises = (src: string) => /\bresumable\b/.test(code(src));

