/**
 * ТРИ МЕРЫ ПРОХОДА СЧИТАЮТСЯ ПО ПАРТИИ, А НЕ ОБЪЯВЛЕНЫ КОНСТАНТОЙ.
 *
 * 🔴 ЗАЧЕМ. У трёх проб раздела главной величины не было вовсе или писалась не та:
 * WCST не писал «ходов до перехвата правила» (только perseverative — это про другое:
 * упорство в СТАРОМ правиле, а не скорость поимки нового); мишени не писали ошибки
 * ТОРМОЖЕНИЯ, хотя для go/no-go это главный показатель; CPT писал падение СКОРОСТИ
 * под именем vigilance_decrement, а классический decrement — падение ТОЧНОСТИ.
 *
 * ⚠️ Проба кормит функции придуманными партиями с ЗАРАНЕЕ ИЗВЕСТНЫМ ответом. Так
 * ловится подмена вычисления константой: константа не может дать разный ответ на
 * растущей и падающей партии, а формула обязана.
 */
import { vigilanceAccuracySlope, ruleCatchStats, commissionRate } from '@/src/games/attention/measures';

/** Партия целей: доля пойманных задаётся по четвертям. */
const targets = (rates: number[], perQ = 5) =>
  rates.flatMap((r, q) =>
    Array.from({ length: perQ }, (_, i) => ({
      responded: i < Math.round(r * perQ),
      trialIndex: q * perQ + i,
    })));

describe('CPT: падение ТОЧНОСТИ — отдельная величина от падения скорости', () => {
  it('внимание падает → наклон отрицательный', () => {
    const { slope, byQuartile } = vigilanceAccuracySlope(targets([1, 0.8, 0.6, 0.4]));
    expect(byQuartile).toEqual([1, 0.8, 0.6, 0.4]);
    expect(slope).toBeLessThan(0);
  });

  it('внимание держится → наклон ноль', () => {
    const { slope } = vigilanceAccuracySlope(targets([0.8, 0.8, 0.8, 0.8]));
    expect(slope).toBe(0);
  });

  /**
   * 🔴 БЕЗ ЭТОГО СЛУЧАЯ ДВА ПРЕДЫДУЩИХ НИЧЕГО НЕ СТОЯТ: константа прошла бы «ноль»,
   * а «меньше нуля» — половину случаев наугад. Здесь требуется РАЗНЫЙ ответ на
   * разных партиях, чего подмена константой дать не может.
   */
  it('🔴 растущая и падающая партии дают РАЗНЫЕ знаки', () => {
    const вниз = vigilanceAccuracySlope(targets([1, 0.8, 0.6, 0.4])).slope!;
    const вверх = vigilanceAccuracySlope(targets([0.4, 0.6, 0.8, 1])).slope!;
    expect(`${вниз < 0} / ${вверх > 0} / ${вниз !== вверх}`).toBe('true / true / true');
  });

  it('целей мало → null, а не выдуманное число', () => {
    expect(vigilanceAccuracySlope(targets([1, 1, 1, 1], 1)).slope).toBeNull();
    expect(vigilanceAccuracySlope([]).slope).toBeNull();
  });
});

describe('WCST: ходов до перехвата нового правила', () => {
  it('среднее и число сдвигов считаются по списку', () => {
    expect(ruleCatchStats([1, 3, 5])).toEqual({ mean: 3, shifts: 3, trials: [1, 3, 5] });
  });

  /**
   * Сдвигов не было — величины НЕТ, и это null, а не ноль. Ноль означал бы
   * «поймал мгновенно», то есть отличный результат там, где замера не было вовсе.
   */
  it('🔴 сдвигов не было → null, а не 0 (иначе пустое читается как идеальное)', () => {
    expect(ruleCatchStats([])).toEqual({ mean: null, shifts: 0, trials: null });
  });

  /**
   * 🔴 «НЕ ПОЙМАЛ НИ РАЗУ» И «СДВИГОВ НЕ БЫЛО» — ПРОТИВОПОЛОЖНЫЕ ИСХОДЫ, А СПИСОК
   * ПОЙМАННЫХ У НИХ ОДИНАКОВЫЙ (пустой). Различает их только число случившихся
   * сдвигов, поэтому экран пишет его отдельным полем `rule_shifts_total`, а не
   * выводит из длины списка. Здесь закреплено, что из пустого списка вывести
   * различие НЕЛЬЗЯ — то есть второе поле обязано существовать.
   */
  it('🔴 по пустому списку не отличить «не поймал» от «сдвигов не было»', () => {
    const неПоймал = ruleCatchStats([]);
    const небылоСдвигов = ruleCatchStats([]);
    expect(неПоймал).toEqual(небылоСдвигов);   // различия нет — значит нужно поле рядом
  });

  it('число сдвигов идёт рядом со средним — по одному и по пяти разная надёжность', () => {
    expect(ruleCatchStats([4]).shifts).toBe(1);
    expect(ruleCatchStats([4, 4, 4, 4, 4]).shifts).toBe(5);
    expect(ruleCatchStats([4]).mean).toBe(ruleCatchStats([4, 4, 4, 4, 4]).mean);   // среднее одно
  });
});

describe('Мишени: доля ошибок торможения', () => {
  it('делится на ФАКТИЧЕСКИ показанные не-мишени', () => {
    expect(commissionRate(3, 12)).toBe(0.25);
  });

  it('🔴 не-мишеней не показано → null: делить не на что', () => {
    expect(commissionRate(0, 0)).toBeNull();
  });

  /** Та же ошибка на разном числе проб — разная доля. Константа так не умеет. */
  it('🔴 знаменатель влияет на ответ', () => {
    expect(`${commissionRate(3, 12)} ≠ ${commissionRate(3, 30)}`).toBe('0.25 ≠ 0.1');
  });
});
