/**
 * 🔴 ТРЕТЬЯ ОСЬ WCST: КАРТА, ЧЕЙ ВЫБОР ВЫДАЁТ ПРАВИЛО.
 *
 * ПОВОД. У лестницы было две оси — объём (меняется на L5 и L9) и серия (через
 * уровень). Пять переходов из одиннадцати не меняли НИЧЕГО: L2=L1, L4=L3, L6=L5,
 * L8=L7, L10=L9 совпадали по всем параметрам. Игрок проходил ступень, за которой
 * ничего не стояло.
 *
 * 📌 Решение Дениса 10.09.2026 дословно: «надо не мёртвые переходы убрать, а
 * ДОРАБОТАТЬ». Убрать значило бы срезать лестницу с двенадцати ступеней до семи —
 * ровно то, что запрещает правило «потолков нет нигде».
 *
 * ⚠️ И ось нашлась не выдуманная. У каждого эталона свои цвет, форма и число,
 * поэтому каждый признак карты указывает ровно на один эталон. Отсюда три случая:
 *   три РАЗНЫХ эталона — чтобы ответить, надо знать правило (разводящая карта);
 *   два эталона        — одно правило неотличимо от другого;
 *   ОДИН эталон        — любое правило даёт тот же ответ.
 * Неоднозначность — ТРЕТЬЕ измерение оценки в самом WCST, рядом с
 * «верно/неверно» и «персеверация/нет». Придумана не здесь.
 *
 * ЗАМЕР ГЕНЕРАТОРА ДО ПРАВКИ (200 000 карт): разводящих 37,3 % · двух эталонов
 * 56,4 % · ОДНОГО эталона 6,2 %. На партии в 40 проб это 2,5 пробы, где ошибиться
 * НЕЛЬЗЯ, и 25 проб, по которым не понять, каким правилом играли. А
 * `rule_catch_mean` — мера прохода этой пробы — считает ходы до перехвата правила
 * именно по ним. Ось делает партию труднее И чище одновременно.
 */
import { levelParams, makeTarget, refSpread, MAX_LEVEL, CLASSIC_DISC_SHARE } from '@/app/games/wcst';

const УРОВНИ = Array.from({ length: MAX_LEVEL }, (_, i) => i + 1);
const N = 20000;   // карт на замер: ошибка доли ≈ 0,3 п.п.

/** Доля разводящих карт в ФАКТИЧЕСКОЙ раздаче — прогоном генератора, не из параметра. */
function фактическаяДоля(share: number): number {
  let три = 0;
  for (let i = 0; i < N; i++) if (refSpread(makeTarget(share)) === 3) три++;
  return три / N;
}

describe('WCST: разводящие карты — третья ось лестницы', () => {
  it('есть что проверять — иначе набор зелен вслепую', () => {
    expect(MAX_LEVEL).toBeGreaterThanOrEqual(12);
    expect(`поле в параметрах: ${'discriminatingShare' in levelParams(1)}`).toBe('поле в параметрах: true');
  });

  it('🔴 мёртвых переходов не осталось: каждый уровень отличается от предыдущего', () => {
    const дубли: string[] = [];
    for (let L = 2; L <= MAX_LEVEL; L++) {
      if (JSON.stringify(levelParams(L)) === JSON.stringify(levelParams(L - 1))) {
        дубли.push(`L${L} = L${L - 1}`);
      }
    }
    expect(дубли).toEqual([]);
  });

  it('доля растёт монотонно и доходит до единицы', () => {
    const доли = УРОВНИ.map((L) => levelParams(L).discriminatingShare);
    const откаты = доли.filter((v, i) => i > 0 && v < доли[i - 1]);
    expect(откаты).toEqual([]);
    expect(`L1 ${доли[0].toFixed(2)} → L${MAX_LEVEL} ${доли[доли.length - 1].toFixed(2)}`)
      .toBe(`L1 0.40 → L${MAX_LEVEL} 1.00`);
  });

  /**
   * 🔴 ГЛАВНАЯ ПРОБА: параметр обязан доехать до РАЗДАЧИ, а не остаться числом.
   * Механизм, который есть в коде и не доезжает до игрока, выглядит сделанным.
   * Поэтому здесь прогоняется сам генератор, а не сверяется константа.
   */
  it('🔴 доля из параметров доезжает до раздачи', () => {
    const плохо: string[] = [];
    for (const L of [1, 6, MAX_LEVEL]) {
      const ждём = levelParams(L).discriminatingShare;
      const факт = фактическаяДоля(ждём);
      if (Math.abs(факт - ждём) > 0.02) плохо.push(`L${L}: ждали ${ждём.toFixed(2)}, раздача ${факт.toFixed(2)}`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * На верхнем уровне пустых проб быть не должно вовсе: там каждая карта обязана
   * требовать правила. Это и есть «чище», ради которого ось выбрана.
   */
  it('🔴 на верхнем уровне не остаётся проб, где ошибиться нельзя', () => {
    let пустых = 0;
    const share = levelParams(MAX_LEVEL).discriminatingShare;
    for (let i = 0; i < N; i++) if (refSpread(makeTarget(share)) === 1) пустых++;
    expect(`пустых проб на L${MAX_LEVEL}: ${пустых}`).toBe(`пустых проб на L${MAX_LEVEL}: 0`);
  });

  /**
   * ⚠️ Классический режим не подстраивается: там канон, и колода должна
   * оставаться такой, какой её задумали. Доля по умолчанию — ноль.
   */
  it('🔴 классический режим раздаёт ровно как раньше — по умолчанию доля равномерной раздачи', () => {
    // Ноль здесь был бы НЕ «как раньше», а «ни одной разводящей карты»: доля
    // равномерной раздачи 24/64, и умолчание обязано совпадать с ней, иначе
    // канон Хитона тихо подменяется.
    expect(CLASSIC_DISC_SHARE).toBe(0.375);
    const сколько = (n: number, спред: number) => {
      let к = 0;
      for (let i = 0; i < n; i++) if (refSpread(makeTarget()) === спред) к++;
      return к / n;
    };
    // Три доли сразу: 24/64 · 36/64 · 4/64 — совпасть случайно все три не могут.
    const пары: [number, number][] = [[3, 24 / 64], [2, 36 / 64], [1, 4 / 64]];
    const мимо = пары
      .map(([спред, ждём]) => ({ спред, ждём, факт: сколько(N, спред) }))
      .filter((r) => Math.abs(r.факт - r.ждём) > 0.015)
      .map((r) => `спред ${r.спред}: ждали ${r.ждём.toFixed(4)}, раздача ${r.факт.toFixed(4)}`);
    expect(мимо).toEqual([]);
  });
});
