/**
 * ОБЛАЧКО-ПОДСКАЗКА НЕ ВИСИТ НАД САМОЗАПУСТИВШЕЙСЯ ПАРТИЕЙ.
 *
 * 🔴 ЧТО БЫЛО СЛОМАНО. Два отчёта тестировщика 10.09.2026 (v2.52.12, профиль nzt48,
 * iPhone iOS 18.7): «Зарядке кубики Корси стартовали — пришлось пропустить» и
 * «ни одно упражнение зарядки похоже не стартует». Замером на собранном веб-бандле:
 * шаг зарядки открывается с `?wu=1` и НАЧИНАЕТСЯ САМ, а одноразовое облачко «Не
 * понимаешь, как играть?» держится над полем 12 секунд (`GameHelpOverlay`). Показ
 * последовательности в Корси — 3 × 800 мс = 2,4 с, то есть весь стимул проходит ПОД
 * облачком: человека спрашивают о том, чего ему не показали. У SDMT оно закрывает
 * таблицу символов, без которой отвечать нечем.
 *
 * ⚠️ ПОЧЕМУ ПРОВЕРЯЕТСЯ ИМЕННО `useGlobalSearchParams`. Первая починка читала `wu`
 * через `useLocalSearchParams` и прошла тихо мимо: оверлей висит ОДИН на всё
 * приложение в `app/_layout.tsx`, а локальный хук отдаёт параметры своего сегмента —
 * корня, где `wu` нет никогда. Контроль на бандле показал облачко на месте. Поэтому
 * здесь сверяется не «есть отвод», а КАКИМ хуком он читает параметр.
 */
declare const __dirname: string;
// eslint-disable-next-line @typescript-eslint/no-require-imports
const fs = require('fs');
// eslint-disable-next-line @typescript-eslint/no-require-imports
const path = require('path');

const ОВЕРЛЕЙ = path.join(__dirname, '../components/GameHelpOverlay.tsx');
const исходник: string = fs.readFileSync(ОВЕРЛЕЙ, 'utf8');

describe('облачко-подсказка и самозапуск партии', () => {
  it('есть что проверять — облачко и его флаг на месте', () => {
    expect(исходник).toContain('HELP_COACH_KEY');
    expect(исходник).toMatch(/setCoach\(true\)/);
  });

  it('🔴 параметр экрана читается ГЛОБАЛЬНЫМ хуком — локальный в корневом слое пуст', () => {
    expect(исходник).toContain('useGlobalSearchParams');
    // ⚠️ Ищем ВЫЗОВ, а не упоминание: в шапке над правкой local-хук назван поимённо,
    // потому что именно на нём починка прошла мимо. Запрет на слово убил бы объяснение.
    expect(исходник).not.toMatch(/useLocalSearchParams\s*[<(]/);
  });

  it('🔴 показ облачка отведён при самозапуске (зарядка `wu=1` и вызов дня `auto=1`)', () => {
    // Условие входа в эффект обязано упоминать оба признака самозапуска.
    const эффект = исходник.slice(исходник.indexOf('HELP_COACH_KEY'), исходник.indexOf('Само-скрытие'));
    expect(эффект).toMatch(/wu\b/);
    expect(эффект).toMatch(/auto\b/);
    expect(эффект).toMatch(/if \(!hasHelp \|\| самозапуск\) return;/);
  });

  it('🔴 отвод НЕ тратит флаг: в обычном заходе облачко ещё покажется', () => {
    // setItem флага стоит ПОСЛЕ проверки самозапуска, внутри той же ветки, что setCoach.
    const i = исходник.indexOf('AsyncStorage.setItem(HELP_COACH_KEY');
    const j = исходник.indexOf('if (!hasHelp || самозапуск) return;');
    expect(j).toBeGreaterThan(0);
    expect(i).toBeGreaterThan(j);
  });
});
