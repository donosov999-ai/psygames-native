/* choice-rt-hick-slope · VER 1 · 16.09.2026 */
import { наклонХика } from '@/src/games/attention/hick';
import { levelParams, levelCondition, направленияБлока, падУровня } from '@/app/games/choice-rt';
import { SESSION_MEASURE } from '@/src/games/attention/load';

/* Чтение исходника — приём раздела; окружение Node объявляем как в соседних пробах. */
declare const __dirname: string;
declare function require(m: string): any;

/**
 * 🔴 ЧТО СТЕРЕЖЁТ. «Выбор-реакция» была ЕДИНСТВЕННЫМ экраном развилки без
 * клинического показателя. Канонная мера парадигмы — наклон Хика, и он требует
 * РАЗНОГО числа альтернатив при ПРОЧИХ РАВНЫХ.
 *
 * ЗАМЕР ДО (13.09.2026): число вариантов было осью УРОВНЯ — 2 на L1-5, 3 на
 * L6-10, 4 дальше. Внутри партии оно не менялось ни разу, значит точек для
 * прямой было РОВНО ОДНА, и наклон не считался в принципе. Вдобавок между
 * уровнями вместе с числом вариантов менялось окно ответа — две величины сразу.
 *
 * ЗАМЕР ПОСЛЕ: блоки внутри партии, минимум два разных n на КАЖДОМ уровне,
 * окно при этом одно на всю партию.
 */
describe('choice-rt: наклон Хика считается, и условия его действительности целы', () => {
  it('🔴 на КАЖДОМ уровне внутри партии не меньше двух разных n', () => {
    /* Это и есть снятая блокировка: было по одному n на партию. */
    const мало = [];
    for (let l = 1; l <= 15; l++) {
      const n = new Set(levelParams(l).hickBlocks).size;
      if (n < 2) мало.push(`L${l}: ${n}`);
    }
    expect(мало).toEqual([]);
  });

  it('🔴 окно ответа ОДНО на всю партию — иначе точки несравнимы', () => {
    /* Условие действительности: наклон, снятый при разных окнах, недействителен.
       Окно задаётся уровнем и внутри партии не пересчитывается — проверяем, что
       levelCondition отдаёт ОДНО число, а не набор. */
    for (let l = 1; l <= 15; l++) {
      expect(typeof levelCondition(l).windowMs).toBe('number');
    }
  });

  it('🔴 моторика постоянна: наборы вложены друг в друга', () => {
    /* Если бы при двух вариантах кнопки стояли иначе, чем при четырёх, в замер
       влез бы закон Фиттса. Вложенность наборов — то, что даёт крестовине
       рисовать все четыре позиции всегда. */
    const н2 = направленияБлока(2), н3 = направленияБлока(3), н4 = направленияБлока(4);
    expect(н3.slice(0, 2)).toEqual(н2);
    expect(н4.slice(0, 3)).toEqual(н3);
    expect(н4.length).toBe(4);
  });

  it('🔴 раскладка пада прибита к ПАРТИИ, а не к текущему блоку', () => {
    /* 🔴 ЭТО И ЕСТЬ ДЕФЕКТ, КОТОРЫЙ ПРОВЕРКА ВЛОЖЕННОСТИ ПРОПУСТИЛА (16.09.2026).
       Вложенность наборов ничего не говорит о том, ЧЕМ рисуется набор. А пад
       выбирал раскладку по числу ЖИВЫХ кнопок: два варианта — ряд из кругов 88,
       три-четыре — крест из кругов 55. Пока n было осью уровня, внутри партии
       это не менялось; с блоками Хика менялось бы каждые несколько проб, и в
       наклон вместо цены перебора попадала бы разница моторики (MT = a +
       b·log2(2D/W), Fitts 1954: и W, и D тут разные).
       Требование: раскладка одна на партию и покрывает самый большой блок, а
       живой набор любого блока — её подмножество. */
    for (let l = 1; l <= 15; l++) {
      const пад = падУровня(l);
      const блоки = levelParams(l).hickBlocks;
      expect(пад.length).toBe(Math.max(...блоки));
      for (const n of блоки) {
        expect(направленияБлока(n).every((d) => пад.includes(d))).toBe(true);
      }
    }
  });

  it('🔴 размер кнопки считается от раскладки партии, а не от живых', () => {
    /* Замок на само МЕСТО ПОКАЗА: проверка выше зелёная и при `activeDirs.length
       === 2` в стиле кнопки, потому что она не знает, чем меряет пад. Здесь
       прямо запрещено брать размер и ветку раскладки от текущего набора. */
    const src: string = require('fs').readFileSync(
      require('path').join(__dirname, '../../app/games/choice-rt.tsx'), 'utf8');
    const падБлок = src.slice(src.indexOf('const padBtn'), src.indexOf('// playing-фаза'));
    expect(падБлок).not.toMatch(/activeDirs\.length/);
    expect(падБлок).toMatch(/padDirs\.length === 2/);
  });

  it('🔴 наклон восстанавливается на данных с ИЗВЕСТНЫМ ответом', () => {
    /* Контроль: складываем точки по закону RT = 300 + 120·log2(n) и требуем
       обратно 120. Без него проба зеленела бы на любой формуле. */
    const точки = [];
    for (const n of [2, 3, 4]) {
      const rt = 300 + 120 * Math.log2(n);
      for (let i = 0; i < 10; i++) точки.push({ n, rt });
    }
    const р = наклонХика(точки);
    expect(р.slopeMsPerBit).toBe(120);
    expect(р.interceptMs).toBe(300);
    expect(р.distinctN).toBe(3);
  });

  it('🔴 при ОДНОМ n наклон = null, а не ноль', () => {
    /* Ноль означал бы «перебор вариантов бесплатен» — сильное клиническое
       утверждение на пустом месте. Отсутствие данных обязано выглядеть как
       отсутствие. Тот же принцип, что у ssrt_ms и vigilanceAccuracySlope. */
    const один = Array.from({ length: 20 }, () => ({ n: 2, rt: 420 }));
    const р = наклонХика(один);
    expect(р.slopeMsPerBit).toBeNull();
    expect(р.distinctN).toBe(1);
    expect(наклонХика([]).slopeMsPerBit).toBeNull();
  });

  it('среднее по каждому n идёт рядом — наклон можно перепроверить', () => {
    const р = наклонХика([{ n: 2, rt: 400 }, { n: 2, rt: 500 }, { n: 4, rt: 700 }]);
    expect(р.byN).toEqual([
      { n: 2, meanRt: 450, trials: 2 },
      { n: 4, meanRt: 700, trials: 1 },
    ]);
  });

  it('🔴 мера прохода раздела указывает на наклон, а не на среднее время', () => {
    /* Пока поле называлось mean_rt, экран считался «без показателя»: среднее
       время зависит и от числа кнопок, и от окна, и от начертания сразу. */
    expect(SESSION_MEASURE['choice-rt'].field).toBe('hick_slope_ms_per_bit');
  });
});
