/**
 * 🔴 ПРИШЕДШАЯ СВЕРХУ ПОЛКА ТОЖЕ ЕДЕТ, А НЕ ВОЗНИКАЕТ ИЗ НИОТКУДА.
 *
 * 📍 ЗАМЕР 11.09.2026 по ядру. Когда полка собрана целиком, она уходит с доски
 * (`ниши.splice`), столбец осаживается, а СВЕРХУ встаёт новая из очереди
 * (`ниши.unshift`) и получает свежий номер (`н.id = следующий++`). Прежний
 * расчёт оседания искал номер полки в списке «до» — у новой полки такого номера
 * там не бывает НИКОГДА, — и молча её пропускал. Столбец ехал красиво, а верхняя
 * ниша появлялась одним кадром.
 *
 * ⚠️ ПОЧЕМУ РАСЧЁТ ВЫНЕСЕН В ЯДРО. Он жил строками внутри компонента, и
 * проверить его можно было только монтированием экрана и подбором такого хода,
 * который закроет полку. Дорого, хрупко — и потому не проверялось: половина
 * случая прожила без движения и без единой красной пробы.
 *
 * ⚠️ ОБРАТНАЯ СТОРОНА СТОРОЖИТСЯ ОТДЕЛЬНО: сравнение двух РАЗНЫХ досок не двигает
 * никого. Первая редакция сторожила ещё и «первую раздачу» оговоркой про ушедшую
 * полку — мутация «снять оговорку» её пережила, и разбор показал, что случая не
 * существует: длина столбца постоянна, номера уникальны, новый номер бывает
 * только взамен ушедшего. Оговорка снята вместе с непроверяемой пробой.
 */
import { картаОседания } from '@/src/games/goods-sort/core/level';

/** Столбцы для доски `cols` в ширину: место `i` лежит в столбце `i % cols`. */
const столбцыДля = (мест: number, cols: number) => Array.from({ length: мест }, (_, i) => i % cols);

describe('оседание столбца', () => {
  const cols = 3;
  const ст = столбцыДля(9, cols);

  it('ничего не изменилось — никто не едет', () => {
    const было = [10, 11, 12, 13, 14, 15, 16, 17, 18];
    expect(картаОседания(было, было, ст)).toEqual({});
  });

  it('полка закрылась — столбец над ней проехал ровно один ряд', () => {
    //          места:   0   1   2   3   4   5   6   7   8
    const было = [10, 11, 12, 13, 14, 15, 16, 17, 18];
    // В столбце 0 (места 0,3,6) закрылась НИЖНЯЯ полка 16: 10 и 13 съезжают вниз,
    // сверху приходит новая полка 19.
    const стало = [19, 11, 12, 10, 14, 15, 13, 17, 18];
    const карта = картаОседания(было, стало, ст);
    expect(карта).toEqual({ 0: 1, 3: 1, 6: 1 });
  });

  it('пришедшая полка едет, даже когда съезжать больше нечему', () => {
    // Столбец из одного места: полка закрылась, сверху пришла новая.
    const карта = картаОседания([7], [8], [0]);
    expect(карта).toEqual({ 0: 1 });
  });

  /**
   * ⚠️ ЗДЕСЬ БЫЛА ПРОБА «на первой раздаче не едет никто» — и она ничего не
   * проверяла: сравнивала список сам с собой, поэтому ветка прихода в ней не
   * исполнялась вовсе. Мутация «снять оговорку про ушедшую полку» её пережила,
   * и разбор показал, что оговорка защищала от невозможного: длина столбца
   * постоянна, номера уникальны, новый номер бывает только взамен ушедшего.
   * Оговорка снята, а вместо пустой пробы стоит настоящая граница — сравнение
   * двух РАЗНЫХ досок, которое действительно случается.
   */
  it('сравнение двух разных досок не двигает никого', () => {
    expect(картаОседания([1, 2, 3], [4, 5], [0, 0, 0])).toEqual({});
  });

  it('перескок между столбцами — не оседание', () => {
    // Полка 10 переехала из столбца 0 в столбец 1: это перетасовка.
    const было = [10, 11, 12, 13, 14, 15];
    const стало = [13, 10, 12, 11, 14, 15];
    const карта = картаОседания(было, стало, столбцыДля(6, 3));
    expect(карта).toEqual({});
  });

  it('доски разной длины не сравниваются', () => {
    expect(картаОседания([1, 2, 3], [1, 2], [0, 0, 0])).toEqual({});
    expect(картаОседания([], [], [])).toEqual({});
  });

  it('проехал два ряда — сдвиг на два, а не на один', () => {
    // Столбец 0 = места 0,2,4. Закрылась нижняя (14), приехали две новые сверху.
    const было = [10, 11, 12, 13, 14, 15];
    const стало = [20, 11, 21, 13, 10, 15];
    const карта = картаОседания(было, стало, [0, 1, 0, 1, 0, 1]);
    expect(карта[4]).toBe(2);      // полка 10 уехала с места 0 на место 4
    expect(карта[0]).toBe(1);      // и две новые пришли сверху
    expect(карта[2]).toBe(1);
  });
});
