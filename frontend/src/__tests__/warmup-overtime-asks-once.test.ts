/**
 * 🔴 ВРЕМЯ ВЫШЛО, А ПОДХОДЫ ОСТАЛИСЬ — СПРАШИВАЕМ, НО ТОЛЬКО ОДИН РАЗ.
 *
 * 📍 РЕШЕНИЕ ДЕНИСА 09.09.2026, дословно: «мы не можем контролировать у каждого
 * скорость ответов, нам главное чтобы по шагам». Длина зарядки задана числом
 * подходов; минуты на кнопке — оценка по медиане живых партий. У того, кто
 * отвечает медленнее медианы, обещанные десять минут кончаются на седьмом
 * подходе из двенадцати.
 *
 * Обрывать нельзя — человек не доиграл то, что ему обещали. Молчать тоже нельзя
 * — он планировал десять минут, а идёт двадцать. Отсюда вопрос ОДИН РАЗ.
 *
 * ⚠️ ЗДЕСЬ ПРОВЕРЯЕТСЯ ПРАВИЛО, А НЕ ЭКРАН. Само условие живёт в
 * `WarmupContext` тремя множителями (комплекс идёт · шаги остались · время
 * вышло · ещё не спрашивали), и ошибиться можно в каждом. Экранная часть
 * проверяется отдельно чтением исходника моста: отсчёт обязан ВСТАТЬ, пока
 * висит вопрос, иначе он уйдёт на следующую игру под ним.
 */
declare const __dirname: string;
declare function require(id: string): any;

const читать = (rel: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, rel), 'utf8') as string;
/** Комментарии срезаются: проверка обязана смотреть на КОД, а не на пояснения. */
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

/** Повторяет условие из `WarmupContext` — чтобы гонять его на выдуманных состояниях. */
function перебор(o: {
  active: boolean; шагов: number; сыграно: number; обещаноМин: number;
  прошлоМс: number; спрошеноУ: string | null; warmupId: string | null;
}): boolean {
  const осталось = Math.max(0, o.шагов - o.сыграно);
  return o.active && осталось > 0 && o.спрошеноУ !== o.warmupId
    && o.прошлоМс > o.обещаноМин * 60_000;
}

const БАЗА = {
  active: true, шагов: 12, сыграно: 7, обещаноМин: 10,
  прошлоМс: 11 * 60_000, спрошеноУ: null as string | null, warmupId: 'к1',
};

describe('перебор времени спрашивает один раз', () => {
  it('🔴 время вышло и подходы остались — спрашиваем', () => {
    expect(перебор(БАЗА)).toBe(true);
  });

  it('время не вышло — молчим', () => {
    expect(перебор({ ...БАЗА, прошлоМс: 9 * 60_000 })).toBe(false);
    // Ровно на границе тоже молчим: «больше», а не «не меньше».
    expect(перебор({ ...БАЗА, прошлоМс: 10 * 60_000 })).toBe(false);
  });

  it('🔴 подходов не осталось — молчим, даже если время вышло', () => {
    expect(перебор({ ...БАЗА, сыграно: 12 })).toBe(false);
    expect(перебор({ ...БАЗА, сыграно: 13 })).toBe(false);
  });

  it('комплекс не идёт — молчим', () => {
    expect(перебор({ ...БАЗА, active: false })).toBe(false);
  });

  it('🔴 уже спросили у ЭТОГО комплекса — второй раз не спрашиваем', () => {
    expect(перебор({ ...БАЗА, спрошеноУ: 'к1' })).toBe(false);
  });

  /**
   * 🔴 САМАЯ ВАЖНАЯ ПРОБА НАБОРА. Если бы «спрошено» хранилось булевым флагом,
   * его пришлось бы сбрасывать в семи функциях запуска, и забытый сброс означал
   * бы, что после первого «доиграю» вопрос не появится НИКОГДА. Идентификатор
   * комплекса сбрасывать не нужно: новый комплекс — новый `warmupId`.
   */
  it('🔴 у СЛЕДУЮЩЕГО комплекса спрашиваем снова', () => {
    expect(перебор({ ...БАЗА, спрошеноУ: 'к1', warmupId: 'к2' })).toBe(true);
  });

  it('условие в контексте — то же самое, а не своя копия', () => {
    const src = код(читать('../contexts/WarmupContext.tsx'));
    expect(src).toMatch(/const overtime = state\.active/);
    expect(src).toMatch(/stepsLeft > 0/);
    expect(src).toMatch(/спрошеноУ !== state\.warmupId/);
    expect(src).toMatch(/duration_min \* 60_000/);
    // Булев флаг здесь был бы дефектом — см. разбор выше.
    expect(src).not.toMatch(/setСпрошено\(true\)/);
  });

  /**
   * 🔴 ОТСЧЁТ ОБЯЗАН ВСТАТЬ. Мост сам уводит на следующую игру по нулю отсчёта.
   * Если он тикает под вопросом, человек нажмёт «Закончить» уже на чужом экране.
   */
  it('🔴 пока висит вопрос — отсчёт остановлен и переход не делается', () => {
    const src = код(читать('../../app/warmup-bridge.tsx'));
    expect(src).toMatch(/if \(!warmup\.overtime \|\| !intervalRef\.current\) return;/);
    expect(src).toMatch(/if \(warmup\.overtime \|\| countdown !== 0/);
  });

  it('🔴 ответ «доиграть» помечает комплекс спрошенным, иначе вопрос вернётся', () => {
    const src = код(читать('../../app/warmup-bridge.tsx'));
    expect(src).toMatch(/warmup\.dismissOvertime\(\)/);
  });

  /**
   * ⚠️ НИ СЛОВА УПРЁКА. Человек не виноват, что отвечает в своём темпе; текст
   * говорит о ВРЕМЕНИ, а не о нём. Слова ниже запрещены во всех двенадцати.
   */
  it('🔴 в тексте вопроса нет упрёка ни на одном языке', () => {
    const запрет = /затян|медленн|slow|too long|долго|langsam|lent[oa]|遅い|느리/i;
    const files = ['../contexts/LanguageContext.tsx',
      ...['es', 'pt', 'de', 'fr', 'it', 'zh', 'ja', 'ko', 'hi', 'ar']
        .map((c) => `../contexts/translations/${c}.ts`)];
    const плохо: string[] = [];
    for (const f of files) {
      const m = читать(f).match(/warmupOvertime[^\n]*\n?[^\n]*/);
      if (m && запрет.test(m[0])) плохо.push(f);
    }
    expect(`с упрёком: ${плохо.join(', ') || '—'}`).toBe('с упрёком: —');
  });

  it('перевод есть во всех двенадцати языках', () => {
    const нет: string[] = [];
    if (!читать('../contexts/LanguageContext.tsx').includes('warmupOvertime')) нет.push('база');
    for (const c of ['es', 'pt', 'de', 'fr', 'it', 'zh', 'ja', 'ko', 'hi', 'ar']) {
      if (!читать(`../contexts/translations/${c}.ts`).includes('warmupOvertime')) нет.push(c);
    }
    expect(`без перевода: ${нет.join(',') || '—'}`).toBe('без перевода: —');
  });
});
