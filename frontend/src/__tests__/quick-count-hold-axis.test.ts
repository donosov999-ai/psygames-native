/**
 * 🔴 ОСЬ «ЗАДЕРЖКА» ПРОДОЛЖАЕТ ЛЕСТНИЦУ, А НЕ ПЕРЕПИСЫВАЕТ ЕЁ.
 *
 * ЗАМЕР ДО (06.09.2026, разметка семи игр по десяти осям роста). У быстрого
 * счёта были заняты ДВЕ оси: объём и скорость. Обе кончаются на 31-м уровне —
 * показ упирается в пол 300 мс уже на 15-м, `minN`/`maxN` перестают меняться на
 * 31-м из-за `MAX_DOTS`. На 400 уровнях это 24 разные настройки и 369 уровней
 * подряд с одной и той же. Не потолок игры, а конец двух осей из десяти.
 *
 * ЗАМЕР ПОСЛЕ: лестница 31 → 41, настроек 24 → 34, уровни 1..31 побайтно те же.
 *
 * 🔴 ГЛАВНОЕ, ЧТО ОХРАНЯЕТ ЭТОТ ГЕЙТ — НЕ РОСТ, А НЕПРИКОСНОВЕННОСТЬ ПРОЙДЕННОГО.
 * Ось легко было включить с первого уровня: так «богаче». Но тогда трудность
 * уровней, которые люди УЖЕ прошли, изменилась бы задним числом, и их прогресс
 * обесценился бы молча — никакая проба этого не заметила бы, потому что все
 * формулы остались бы «правильными». Поэтому первая же строка ниже проверяет,
 * что на 1..31 задержки нет вовсе.
 */
import { levelParams, QUICK_COUNT_LEVELS } from '@/app/games/quick-count';

declare const __dirname: string;
declare function require(m: string): any;

/** Последний уровень, на котором настройки ещё меняются. */
function вершина(предел = 400): number {
  let последний = 1;
  let прежняя = JSON.stringify(levelParams(1));
  for (let L = 2; L <= предел; L += 1) {
    const текущая = JSON.stringify(levelParams(L));
    if (текущая !== прежняя) { последний = L; прежняя = текущая; }
  }
  return последний;
}

/** Уровень, с которого ось включается, — по документации самой игры. */
const ПОСЛЕДНИЙ_БЕЗ_ЗАДЕРЖКИ = 31;

describe('🔴 быстрый счёт: ось «задержка»', () => {
  it('🔴 уровни 1..31 не тронуты — задержки там нет вовсе', () => {
    // Если это покраснеет, значит ось поехала вниз по лестнице и переписала
    // трудность уже пройденного. Это дороже любого выигрыша от роста.
    const сзадержкой: string[] = [];
    for (let L = 1; L <= ПОСЛЕДНИЙ_БЕЗ_ЗАДЕРЖКИ; L += 1) {
      if (levelParams(L).holdMs !== 0) сзадержкой.push(`L${L}: holdMs=${levelParams(L).holdMs}`);
    }
    expect(сзадержкой).toEqual([]);
  });

  it('🔴 лестница выросла: настроек стало больше, вершина ушла за 31', () => {
    const верх = вершина();
    expect(верх).toBeGreaterThan(ПОСЛЕДНИЙ_БЕЗ_ЗАДЕРЖКИ);
    const настроек = new Set(
      Array.from({ length: 400 }, (_, i) => JSON.stringify(levelParams(i + 1))),
    ).size;
    // Числа не вписаны: сравнивается «стало больше», а не «стало ровно 41».
    // Вырастет следующая ось — строка останется зелёной, а не потребует правки.
    expect(настроек).toBeGreaterThan(24);
  });

  it('🔴 объявленный потолок игры поехал за осью сам', () => {
    // Ради этого A1 и считал потолок из levelParams, а не вписывал числом:
    // ось выросла — подпись «Уровень N/M» на экране выросла вместе с ней,
    // без единой правки в экране.
    expect(QUICK_COUNT_LEVELS).toBe(вершина());
  });

  it('🔴 задержка не убывает — лестница не откатывается назад', () => {
    const откаты: string[] = [];
    for (let L = 2; L <= 400; L += 1) {
      const было = levelParams(L - 1).holdMs;
      const стало = levelParams(L).holdMs;
      if (стало < было) откаты.push(`L${L}: ${было} → ${стало} мс`);
    }
    expect(откаты).toEqual([]);
  });

  it('потолок принадлежит ОСИ, а не лестнице — и он назван', () => {
    // Задержка упирается в 2000 мс: дольше — это уже проба на объём памяти,
    // соседний раздел. Кончится эта ось — лестницу продолжит следующая
    // (свободны 4, 5, 6, 7, 8, 9, 10), а не «дальше расти некуда».
    const потолок = levelParams(400).holdMs;
    expect(потолок).toBe(2000);
    expect(levelParams(вершина()).holdMs).toBe(потолок);
  });
});

describe('проводка: фаза удержания и правда есть на экране', () => {
  /**
   * ⚠️ ПРОВЕРКА ИСХОДНИКА, НАЗЫВАЮ СВОИМ ИМЕНЕМ. Числа выше доказывают, что ось
   * посчитана; но `holdMs` без фазы, которая его выдерживает, — просто поле в
   * объекте. Отрендерить экран в jsdom дороже, чем эта строка стоит.
   */
  const текст: string = require('fs').readFileSync(
    require('path').join(__dirname, '../../app/games/quick-count.tsx'), 'utf8',
  );

  it('🔴 фаза hold объявлена, выдерживается и рисуется', () => {
    expect(текст).toMatch(/'flash' \| 'hold' \| 'answer'/);          // фаза есть в типе
    expect(текст).toMatch(/setPhase\('hold'\)/);                      // в неё входят
    expect(текст).toMatch(/setTimeout\(\(\) => setPhase\('answer'\), p\.holdMs\)/); // и выходят по holdMs
    expect(текст).toMatch(/phase === 'hold' \?/);                     // и рисуют
  });

  it('🔴 при нулевой задержке шаг проскакивается — старые уровни идут как раньше', () => {
    // Без этой ветки на 1..31 появился бы setTimeout(…, 0): лишний кадр и
    // мигание там, где раньше не было ничего.
    expect(текст).toMatch(/if \(p\.holdMs <= 0\) \{ setPhase\('answer'\); return; \}/);
  });
});
