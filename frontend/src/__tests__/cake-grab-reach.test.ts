/**
 * КУСОК БЕРЁТСЯ С ТАРЕЛКИ, А НЕ С ЕЁ СЕРЕДИНЫ.
 *
 * 🔴 ЗАЧЕМ. Отчёт тестировщиков `54748daf`: «плохо хватался с тарелок».
 *
 * 📍 ЗАМЕР 08.09.2026 — доля площади клетки, где касание засчитывалось:
 *
 *   стол                        было    зазор   по клетке
 *   360 точек · 5 столбцов      61,5 %  75,1 %   100 %
 *   390 · 4                     65,9 %  76,4 %   100 %
 *   414 · 3                     69,3 %  77,1 %   100 %
 *   планшет 768 · 3             73,5 %  78,0 %   100 %
 *
 * То есть больше трети касаний ПО ТАРЕЛКЕ уходили в никуда. При хвате промах
 * означает, что жест не начинается вовсе: кусок не поднимается, палец тянет
 * пустоту — ровно то, на что пожаловались.
 *
 * ⚠️ У ХВАТА И СБРОСА РАЗНАЯ СТРОГОСТЬ, И ЭТО НАМЕРЕННО. Сброс остаётся по кругу
 * (с зазором): цель подсвечена, и угол между четырьмя тарелками честно значит
 * «ни в одну». Хват идёт по клетке: ошибиться там почти нечем.
 */
import { tableLayout, plateAtPoint, plateForGrab, PLATE_GAP } from '@/src/games/cake-sort/core/layout';

/**
 * Доля точек КЛЕТКИ ПЕРВОЙ ТАРЕЛКИ, где функция возвращает тарелку.
 *
 * ⚠️ Сканируем от `PLATE_GAP / 2`, а не от нуля: до первой тарелки лежит отступ
 * стола, и он честно «не тарелка». Считать его — занижать охват на ровном месте
 * (первый замер дал 89 % вместо 100 % именно поэтому).
 */
function охват(fn: typeof plateAtPoint, w: number, cols: number): number {
  const L = tableLayout(w, cols);
  const шаг = L.plate + PLATE_GAP;
  const от = PLATE_GAP / 2;
  let hit = 0; let all = 0;
  for (let x = от; x < от + шаг; x += 0.5) {
    for (let y = от; y < от + шаг; y += 0.5) {
      all += 1;
      if (fn(x, y, cols, L.plate, cols * 3) !== null) hit += 1;
    }
  }
  return (100 * hit) / all;
}

describe('🔴 хват достаёт до края тарелки', () => {
  const СТОЛЫ: [number, number][] = [[360, 5], [390, 4], [414, 3], [768, 3]];

  it('🔴 берётся вся клетка — ни одна точка тарелки не пропадает', () => {
    for (const [w, cols] of СТОЛЫ) {
      const o = охват(plateForGrab, w, cols);
      expect(`стол ${w}×${cols}: охват хвата ${o.toFixed(1)} %`).toBe(`стол ${w}×${cols}: охват хвата 100.0 %`);
    }
  });

  it('🔴 КОНТРПРОБА: строгий круг этой планки не берёт и близко', () => {
    // Пороги литералами: взять их у проверяемого — двигать оба конца разом.
    for (const [w, cols] of СТОЛЫ) {
      const o = охват(plateAtPoint, w, cols);
      expect(`стол ${w}×${cols}: круг ${o.toFixed(1)} % — меньше 80 и больше 70: ${o < 80 && o > 70}`)
        .toBe(`стол ${w}×${cols}: круг ${o.toFixed(1)} % — меньше 80 и больше 70: true`);
    }
    // Предел круга, вписанного в клетку, — π/4 ≈ 78,5 %: выше него не подняться.
    expect(Math.round((Math.PI / 4) * 1000) / 10).toBe(78.5);
  });

  it('сброс остался строгим: угол между тарелками — не тарелка', () => {
    const L = tableLayout(390, 4);
    const шаг = L.plate + PLATE_GAP;
    // Точка ровно в углу клетки — дальше всего от центра.
    const угол = PLATE_GAP / 2 + шаг - 0.5;
    expect(plateAtPoint(угол, угол, 4, L.plate, 12)).toBeNull();
    // …а хват её берёт
    expect(plateForGrab(угол, угол, 4, L.plate, 12)).not.toBeNull();
  });

  it('обе функции одинаково отвергают точку ВНЕ стола', () => {
    const L = tableLayout(390, 4);
    for (const fn of [plateAtPoint, plateForGrab]) {
      expect(fn(-20, 10, 4, L.plate, 12)).toBeNull();
      expect(fn(10, -20, 4, L.plate, 12)).toBeNull();
      expect(fn(10_000, 10, 4, L.plate, 12)).toBeNull();     // правее последнего столбца
      expect(fn(10, 10_000, 4, L.plate, 12)).toBeNull();     // ниже последней тарелки
    }
  });

  it('и одинаково называют тарелку в центре — расходиться им нельзя', () => {
    const L = tableLayout(390, 4);
    const шаг = L.plate + PLATE_GAP;
    for (let r = 0; r < 3; r += 1) {
      for (let c = 0; c < 4; c += 1) {
        const cx = PLATE_GAP / 2 + c * шаг + L.plate / 2;
        const cy = PLATE_GAP / 2 + r * шаг + L.plate / 2;
        const ожидание = r * 4 + c;
        expect(plateAtPoint(cx, cy, 4, L.plate, 12)).toBe(ожидание);
        expect(plateForGrab(cx, cy, 4, L.plate, 12)).toBe(ожидание);
      }
    }
  });
});
