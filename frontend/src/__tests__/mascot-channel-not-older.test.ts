/**
 * КАНАЛ НЕ ЗАТИРАЕТ ВШИТЫЕ КАДРЫ, ЕСЛИ САМ СТАРШЕ ИХ.
 *
 * 🔴 ПОВОД — снимок Дениса 10.09.2026: «у меня старый дырявый питомец… вроде у Вали
 * на этом же экране новый». Так и было, и вот механизм.
 *
 * Канал ПЕРЕБИВАЕТ вшитые кадры (`PetSprite`: есть пак — рисуется он), но отдаёт
 * пять состояний из тридцати пяти. Живой замер канала в тот же день:
 *   channels/stable.json → 200, поле `updated` = 2026-09-05
 *   пак synapse-cat → версия 1.0.5
 * А кот в приложении перерисован ПОЗЖЕ, 09.09 (`97e8012f`). То есть канал раздавал
 * заведомо устаревший рисунок и молча затирал им свежий — на пяти состояниях из
 * тридцати пяти, отчего экран становился смесью старого с новым.
 *
 * ⚠️ И это НЕ разово: пак ложится в AsyncStorage. Устройство, один раз успевшее его
 * забрать, показывает старого кота и дальше («он долго держится уже»); у кого
 * загрузка не прошла — видит вшитого нового. Отсюда разница между двумя телефонами.
 *
 * Проба читает КОНСТАНТУ ИЗ ИСХОДНИКА, а не держит дату у себя: своя копия была бы
 * слепа к правке кода — на этом я сегодня уже спотыкался дважды.
 */
declare const __dirname: string;
const { readFileSync } = require('fs');   // eslint-disable-line @typescript-eslint/no-require-imports
const { join } = require('path');         // eslint-disable-line @typescript-eslint/no-require-imports

const ИСХОДНИК = join(__dirname, '../services/mascotChannel.ts');
const код = () => readFileSync(ИСХОДНИК, 'utf8');

describe('маскот-канал не старше вшитых кадров', () => {
  it('есть что проверять — константа даты объявлена', () => {
    expect(код()).toMatch(/const ВШИТЫЕ_КАДРЫ_ОТ = '\d{4}-\d{2}-\d{2}'/);
  });

  it('🔴 дата канала сравнивается с датой вшитых кадров', () => {
    // Сравнение обязано быть, иначе старый пак снова победит свежие кадры.
    expect(код()).toMatch(/датаКанала\s*<\s*ВШИТЫЕ_КАДРЫ_ОТ/);
  });

  it('🔴 старый канал не только игнорируется, но и чистит кэш', () => {
    // Без этого устройство, успевшее забрать старый пак, не вернётся на свежие
    // кадры само — ровно случай Дениса «он долго держится уже».
    const с = код();
    const i = с.indexOf('датаКанала < ВШИТЫЕ_КАДРЫ_ОТ');
    const ветка = с.slice(i, i + 700);
    expect(ветка).toContain('removeItem(CACHE_KEY)');
    expect(ветка).toContain('готовые = {}');
  });

  it('🔴 дата вшитых кадров не старше самой свежей перерисовки облика', () => {
    // Кот перерисован 09.09.2026 (97e8012f). Если константа отстанет, канал снова
    // получит право затирать — поэтому её поднимают ТЕМ ЖЕ коммитом, что и кадры.
    const m = код().match(/const ВШИТЫЕ_КАДРЫ_ОТ = '(\d{4}-\d{2}-\d{2})'/);
    expect(m).toBeTruthy();
    expect(`дата ${m![1]} ≥ 2026-09-09: ${m![1] >= '2026-09-09'}`)
      .toBe(`дата ${m![1]} ≥ 2026-09-09: true`);
  });
});
