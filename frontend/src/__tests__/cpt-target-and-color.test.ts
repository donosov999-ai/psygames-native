/**
 * 🔴 ТРИ НОВЫЕ ОСИ CPT — И ГЛАВНОЕ, ЧЕГО ОНИ НЕ ДОЛЖНЫ СДЕЛАТЬ.
 *
 * 📌 Слово Дениса 10.09.2026: «можно менять правила, чтобы искал не Х, а другую
 * букву; или показывать похожее на Х; или задать, что Х должен быть
 * определённого цвета — например, красный».
 *
 * ПОВОД. Я принёс развилку: двигать доли к канону AX-CPT 70/10/10/10 — но тогда
 * цель перестаёт быть РЕДКОЙ, а на редкости держится вся логика «пропуск =
 * падение внимания». Развилка была ложной: перебрана одна ось, и на ней объявлен
 * тупик. Все три оси ниже растят трудность, НЕ трогая долю целей — и первая же
 * проба этого файла стережёт именно это.
 *
 * ⚠️ ТРИ МЕСТА, ГДЕ ЭТО ЛЕГКО СЛОМАТЬ ТИХО:
 * 1. Цветовой лур подменяет пробу. Подмени он ЦЕЛЬ или подсказку A — доля целей
 *    просядет, а на глаз это будет «почти та же».
 * 2. Список двойников подобран под X и содержит K. Смени мишень на K, оставив
 *    список общим, — и генератор станет выдавать мишень под видом дистрактора.
 * 3. Если красными бывают ТОЛЬКО мишени, составное правило вырождается в «жми на
 *    красное», то есть в совсем другую пробу.
 */
import { levelParams, levelCondition, makeTrial, TARGET_RATE, CONFUSABLES, TARGETS } from '@/app/games/cpt';

const УРОВНИ = Array.from({ length: 15 }, (_, i) => i + 1);
const N = 40000;

/** Прогон потока уровня: возвращает доли, посчитанные по РЕАЛЬНОЙ раздаче. */
function поток(level: number) {
  let prev = '';
  let целей = 0, красныхЦелей = 0, луров = 0, красныхНеЦелей = 0, всего = 0;
  for (let i = 0; i < N; i++) {
    const t = makeTrial(level, prev);
    prev = t.letter;
    всего++;
    if (t.isTarget) { целей++; if (t.color === 'red') красныхЦелей++; }
    else {
      if (t.letter === levelParams(level).target) луров++;
      if (t.color === 'red') красныхНеЦелей++;
    }
  }
  return {
    доляЦелей: целей / всего,
    целейВсего: целей,
    красныхЦелей,
    доляЛуров: луров / всего,
    доляКрасныхНеЦелей: красныхНеЦелей / всего,
  };
}

describe('CPT: мишень, двойники и цвет', () => {
  it('есть что проверять — иначе набор зелен вслепую', () => {
    const p = levelParams(15);
    expect(`${'target' in p} ${'colorRule' in p}`).toBe('true true');
    expect(TARGETS.length).toBeGreaterThanOrEqual(3);
  });

  /**
   * 🔴 САМАЯ ВАЖНАЯ ПРОБА ФАЙЛА. Ради неё оси и выбирались такими.
   * Доля целей обязана равняться TARGET_RATE на ВСЕХ уровнях — и там, где
   * мишень сменилась, и там, где включилось правило цвета.
   */
  it('🔴 доля целей не тронута ни сменой мишени, ни цветом', () => {
    const мимо: string[] = [];
    for (const L of [1, 5, 9, 12, 15]) {
      const r = поток(L);
      if (Math.abs(r.доляЦелей - TARGET_RATE) > 0.02) {
        мимо.push(`L${L}: ${r.доляЦелей.toFixed(3)} против ${TARGET_RATE}`);
      }
    }
    expect(мимо).toEqual([]);
  });

  it('🔴 мишень с L9 — уже НИКОГДА не X: привычка жать на X перестаёт работать', () => {
    const иксы = УРОВНИ.filter((L) => L >= 9 && levelParams(L).target === 'X');
    expect(`уровни с L9, где мишень всё ещё X: ${иксы.join(', ') || '—'}`)
      .toBe('уровни с L9, где мишень всё ещё X: —');
    expect(levelParams(1).target).toBe('X');   // низ лестницы — канон
  });

  /**
   * 🔴 Двойники у каждой мишени СВОИ. Общий список содержал бы саму мишень:
   * подобранный под X, он включает K — а K тоже мишень.
   */
  it('🔴 мишень не входит в собственный список двойников', () => {
    const беда = TARGETS
      .map((t) => ({ t, есть: (CONFUSABLES[t] ?? []).includes(t), сколько: (CONFUSABLES[t] ?? []).length }))
      .filter((r) => r.есть || r.сколько < 3)
      .map((r) => `${r.t}: сам в списке ${r.есть}, двойников ${r.сколько}`);
    expect(беда).toEqual([]);
    // у каждой мишени лестницы список обязан существовать вовсе
    const без = УРОВНИ.map((L) => levelParams(L).target).filter((t) => !CONFUSABLES[t]);
    expect(без).toEqual([]);
  });

  /**
   * 🔴 Ось «похожести» была НАПИСАНА и почти везде выключена: ноль на L1–L10.
   * Это отдельный вид потолка — механизм есть, до большинства уровней не доезжает.
   */
  it('🔴 двойники включены не только на верхней трети', () => {
    const сНулём = УРОВНИ.filter((L) => levelParams(L).confusableRatio === 0);
    expect(`уровни без двойников: ${сНулём.join(', ')}`).toBe('уровни без двойников: 1, 2');
    const ряд = УРОВНИ.map((L) => levelParams(L).confusableRatio);
    expect(ряд.filter((v, i) => i > 0 && v < ряд[i - 1])).toEqual([]);
  });

  it('🔴 при правиле цвета истинная мишень ВСЕГДА красная', () => {
    const r = поток(15);
    expect(`целей ${r.целейВсего > 0}, из них не красных ${r.целейВсего - r.красныхЦелей}`)
      .toBe(`целей true, из них не красных 0`);
  });

  it('🔴 цветовые луры существуют, и красными бывают не только мишени', () => {
    const r = поток(15);
    // лур — мишенная буква не того цвета; без него правило цвета ничем не проверить
    expect(`луров больше нуля: ${r.доляЛуров > 0.02}`).toBe('луров больше нуля: true');
    // и красные не-цели: иначе «жми на красное» решало бы задачу без чтения буквы
    expect(`красных не-целей больше нуля: ${r.доляКрасныхНеЦелей > 0.05}`)
      .toBe('красных не-целей больше нуля: true');
  });

  it('на уровнях без правила цвета всё идёт одним цветом, как раньше', () => {
    let не_ink = 0;
    let prev = '';
    for (let i = 0; i < 5000; i++) { const t = makeTrial(5, prev); prev = t.letter; if (t.color !== 'ink') не_ink++; }
    expect(`цветных букв на L5: ${не_ink}`).toBe('цветных букв на L5: 0');
  });

  it('условие партии несёт мишень и правило цвета', () => {
    const k = Object.keys(levelCondition(15));
    expect(k).toContain('target');
    expect(k).toContain('colorRule');
    expect(levelCondition(15).target).toBe(levelParams(15).target);
  });
});
