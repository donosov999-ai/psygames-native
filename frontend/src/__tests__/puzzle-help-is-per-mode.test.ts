/**
 * 🔴 СПРАВКА У КАЖДОГО РЕЖИМА СВОЯ, БЕЗ ЧУЖИХ ИГР.
 *
 * ЗАМЕР 16.09.2026, до починки: открыть «Сокобан» → «Правила» → окно с заголовком
 * «Чёт-нечет» и общим текстом про сорок головоломок с примерами про «Магниты» и
 * «Мины». Так во ВСЕХ 42 режимах, кроме самой Unruly.
 * Причина: все 42 живут на одном маршруте `/games/puzzles`, режим стоит в `?mode=`,
 * а глобальная справка выбирает статью по `pathname` — режим до неё не доходит.
 * Денис 16.09: «надо чтобы разное было, у каждого своё, без лишнего описания чужих игр».
 *
 * ПОЧИНЕНО НЕ ПОДМЕНОЙ КЛЮЧА В ОБЩЕЙ КАРТЕ (туда `?mode=` не доходит), а готовым
 * каналом `gameContextHelp`: экран публикует правила текущего режима и флагом
 * `replacesIntro` просит убрать чужую статью и назвать окно своим именем.
 *
 * ⚠️ ЧЕГО ЭТА ПРОБА НЕ ДЕЛАЕТ И ПОЧЕМУ. Она не открывает окно справки: под jest
 * мост молчит, партию не собрать. Живьём проверено на стенде и снято кадром —
 * «Пятнашки» показывают своё имя и свои правила. Здесь закреплено то, что ломается
 * тихо: список режимов со своей справкой и НАЛИЧИЕ текста у каждого на 12 языках.
 */
import { КЛЮЧ_СПРАВКИ, КЛЮЧ_ИМЕНИ } from '@/src/games/tatham-bridge/names';
import { translateFor, LANGUAGES } from '@/src/contexts/LanguageContext';

declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');

/** Десять языков поверх базовых ru/en — у каждого свой файл. */
const ОВЕРЛЕИ = ['es', 'de', 'zh', 'hi', 'pt', 'fr', 'it', 'ja', 'ko', 'ar'];

/** Режимы развилки «Пространство» — те, за кого отвечает этот чат. */
const МОИ = ['Slide', 'Sokoban', 'Net', 'Netslide', 'Twiddle', 'Cube', 'Flip', 'Sixteen', 'Fifteen', 'Untangle'];

describe('у каждого режима своя справка', () => {
  it('🔴 все десять режимов раздела имеют свой ключ справки', () => {
    const без = МОИ.filter((м) => !КЛЮЧ_СПРАВКИ[м]);
    expect(без).toEqual([]);
  });

  /**
   * 🔴 САМОЕ ВАЖНОЕ ЗДЕСЬ. Ключ без перевода словарь возвращает СВОИМ ЖЕ ИМЕНЕМ —
   * человек увидел бы `puzzlesMinesHelp` вместо правил. Поэтому в карту попадают
   * только те, у кого текст РЕАЛЬНО написан, и проба это сторожит с обеих сторон.
   */
  it('🔴 у каждого ключа из карты есть текст в базовом словаре', () => {
    const пусто: string[] = [];
    for (const [режим, ключ] of Object.entries(КЛЮЧ_СПРАВКИ)) {
      for (const язык of ['ru', 'en']) {
        if (translateFor(язык, ключ) === ключ) пусто.push(`${режим}: нет ${язык}`);
      }
    }
    expect(пусто).toEqual([]);
  });

  it('🔴 и в каждом из десяти файлов перевода — базовый запасной ход тут не годится', () => {
    const нет: string[] = [];
    for (const язык of ОВЕРЛЕИ) {
      const текст = fs.readFileSync(path.join(__dirname, '..', 'contexts', 'translations', `${язык}.ts`), 'utf8');
      for (const ключ of Object.values(КЛЮЧ_СПРАВКИ)) {
        if (!текст.includes(`"${ключ}"`)) нет.push(`${язык}: нет ${ключ}`);
      }
    }
    expect(нет.slice(0, 5)).toEqual([]);
  });

  it('🔴 тексты РАЗНЫЕ — иначе «у каждого своё» осталось бы обещанием', () => {
    const тексты = Object.values(КЛЮЧ_СПРАВКИ).map((к) => translateFor('ru', к));
    expect(new Set(тексты).size).toBe(тексты.length);
  });

  /**
   * Денис 16.09 дословно: «без лишнего описания чужих игр». Проверяем буквально:
   * в правилах одного режима не должно стоять имя другого.
   */
  it('🔴 в справке режима не упомянуты чужие игры', () => {
    const имена = Object.entries(КЛЮЧ_ИМЕНИ).map(([режим, ключ]) => [режим, translateFor('ru', ключ)] as const);
    const чужие: string[] = [];
    for (const [режим, ключ] of Object.entries(КЛЮЧ_СПРАВКИ)) {
      const текст = translateFor('ru', ключ);
      for (const [другой, имя] of имена) {
        if (другой === режим || !имя || имя.length < 5) continue;
        if (текст.includes(имя)) чужие.push(`${режим}: в правилах упомянут «${имя}»`);
      }
    }
    expect(чужие).toEqual([]);
  });

  it('у режима со своей справкой есть и имя для заголовка окна', () => {
    const без = Object.keys(КЛЮЧ_СПРАВКИ).filter((м) => !КЛЮЧ_ИМЕНИ[м]);
    expect(без).toEqual([]);
  });
});
