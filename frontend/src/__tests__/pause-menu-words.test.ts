declare const __dirname: string;
declare function require(id: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');
const ROOT = join(__dirname, '../..');
const читать = (p: string) => readFileSync(join(ROOT, p), 'utf8') as string;

/** Комментарии — не код: рассказ о меню не должен засчитываться за меню. */
function безКомментариев(s: string): string {
  return s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}

const ЭКРАНЫ = ['app/games/anagrams.tsx', 'app/games/proofreading.tsx'];

it('🔴 меню паузы подано в КАЖДОМ вызове каркаса, а не в первом попавшемся', () => {
  const плохо: string[] = [];
  for (const п of ЭКРАНЫ) {
    const код = безКомментариев(читать(п));
    const вызовов = (код.match(/<GameShell\b/g) || []).length;
    const сМеню = (код.match(/pauseActions=\{/g) || []).length;
    if (вызовов === 0) плохо.push(`${п}: каркас не вызывается вовсе — проверять нечего`);
    else if (сМеню !== вызовов) плохо.push(`${п}: вызовов каркаса ${вызовов}, с меню паузы ${сМеню}`);
  }
  expect(плохо).toEqual([]);
});

it('🔴 в меню есть перезапуск, и он зовёт настоящий старт партии', () => {
  const плохо: string[] = [];
  for (const п of ЭКРАНЫ) {
    const код = безКомментариев(читать(п));
    const m = /const действияПаузы = \[([\s\S]*?)\n  \];/.exec(код);
    if (!m) { плохо.push(`${п}: список действий паузы не найден`); continue; }
    const тело = m[1]!;
    if (!/id: 'restart'/.test(тело)) плохо.push(`${п}: в меню нет перезапуска — ровно то, на что жаловались`);
    // Перезапуск обязан звать старт партии, а не быть заглушкой.
    if (!/onPress:[^\n]*(startGame|beginSeries)/.test(тело)) {
      плохо.push(`${п}: «Заново» ничего не запускает`);
    }
    if (!/id: 'resume'/.test(тело)) плохо.push(`${п}: нельзя вернуться в партию`);
  }
  expect(плохо).toEqual([]);
});
