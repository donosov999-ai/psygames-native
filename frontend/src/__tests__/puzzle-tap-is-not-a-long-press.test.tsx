import React from 'react';
import renderer, { act } from 'react-test-renderer';
import PuzzleCanvas from '@/src/components/PuzzleCanvas';
import type { Партия } from '@/src/games/tatham-bridge/play';

const партия = {
  ширина: 352, высота: 352,
  палитра: ['255,255,255', '148,196,190', '0,102,99', '20,20,20', '236,236,236'],
  примитивы: [{ вид: 'прямоугольник', x: 0, y: 0, ш: 352, в: 352, цвет: 0 }],
  статус: 0,
} as unknown as Партия;

/** Касание: удержали `мс` и отпустили там же. Возвращает список вызовов onЖест. */
function касание(мс: number) {
  const вызовы: [number, number, string, boolean][] = [];
  let дерево: renderer.ReactTestRenderer;
  act(() => {
    дерево = renderer.create(
      <PuzzleCanvas
        партия={партия}
        ширина={352}
        onЖест={(x, y, ж, п) => { вызовы.push([x, y, ж, п]); }}
        фон="#ffffff"
      />,
    );
  });
  const доска = дерево!.root.findAll(
    (у) => typeof (у.props as any)?.onResponderGrant === 'function', { deep: true },
  )[0];
  const событие = { nativeEvent: { locationX: 100, locationY: 100 } };
  act(() => { (доска.props as any).onResponderGrant(событие); });
  act(() => { jest.advanceTimersByTime(мс); });
  act(() => { (доска.props as any).onResponderRelease(событие); });
  act(() => { дерево!.unmount(); });
  return вызовы;
}

const правых = (в: ReturnType<typeof касание>) => в.filter((з) => з[3] === true).length;

describe('тычок по доске головоломки не превращается во второе действие', () => {
  beforeEach(() => { jest.useFakeTimers(); });
  afterEach(() => { jest.useRealTimers(); });

  it('быстрый тычок (120 мс) — левая кнопка', () => {
    const в = касание(120);
    expect(в.length).toBeGreaterThan(0);
    expect(правых(в)).toBe(0);
  });

  it('🔴 неторопливый тычок (450 мс) — всё ещё левая: фреймворк зовёт долгим только с 500 мс', () => {
    const в = касание(450);
    expect(правых(в)).toBe(0);
  });

  it('🔴 граница: 499 мс — ещё тычок', () => {
    expect(правых(касание(499))).toBe(0);
  });

  /**
   * КОНТРОЛЬ С ИЗВЕСТНЫМ ОТВЕТОМ (`PROJECT_REF_RULES §15`): без него проба
   * зеленела бы и на холсте, который правую кнопку не шлёт ВООБЩЕ.
   */
  it('контроль: настоящее долгое нажатие (700 мс) правую кнопку всё-таки шлёт', () => {
    const в = касание(700);
    expect(правых(в)).toBeGreaterThan(0);
    expect(в.some((з) => з[2] === 'нажал' && з[3] === true)).toBe(true);
  });
});
