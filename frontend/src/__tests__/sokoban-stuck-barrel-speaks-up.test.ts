/**
 * «СОКОБАН»: БОЧКА В УГЛУ — ЭТО КОНЕЦ, И ЭКРАН ОБ ЭТОМ ГОВОРИТ.
 *
 * 📍 Отчёт 59b99133 (17.09.2026, 2.54.17, iPhone, уровень 2/5, 64 хода): «Если я
 * загнал фигуру так, что не могу вытолкнуть бочку, — партия проиграна или есть способ
 * её вытолкать по диагонали?». Способа нет: бочку только ТОЛКАЮТ и только по прямой.
 * Над полем уже висит предупреждение «Загонишь бочку в угол — не вытащишь», а в самый
 * момент тупика экран молчит — человек спрашивает у нас то, что должна сказать игра.
 *
 * 🔴 ЧТО СТОРОЖИТ ЭТА ПРОБА. Границу между «застряла» и «ещё играем», а не наличие
 * функции. Доски собраны общепринятой разметкой «Сокобана»: `#` стена, `$` бочка,
 * `.` метка, `*` бочка на метке, `@` человек, пробел — пол. Клетки рисуются ровно
 * как в `unfinished/sokoban.c:draw_tile`.
 */
import { разложитьСокобан, засевшаяБочка, молчаливыйТупик } from '@/src/games/tatham-bridge/deadend';
import type { Партия, Примитив } from '@/src/games/tatham-bridge/play';

const КЛЕТКА = 32;
const КРАЙ = 16;
const КАЙМА = Math.floor(КЛЕТКА / 10);   // HIGHLIGHT_WIDTH

/** Нарисовать поле так, как его рисует `sokoban.c:draw_tile`. */
function поле(карта: string[]): Примитив[] {
  const из: Примитив[] = [];
  карта.forEach((строка, y) => {
    [...строка].forEach((знак, x) => {
      const tx = x * КЛЕТКА + КРАЙ;
      const ty = y * КЛЕТКА + КРАЙ;
      // Фон клетки рисуется У КАЖДОЙ клетки поля — по нему строится решётка.
      из.push({ вид: 'прямоугольник', x: tx + 1, y: ty + 1, ш: КЛЕТКА - 1, в: КЛЕТКА - 1, цвет: 0 });
      const cx = tx + Math.floor(КЛЕТКА / 2);
      const cy = ty + Math.floor(КЛЕТКА / 2);
      if (знак === '#') {
        из.push({ вид: 'прямоугольник', x: tx + 1 + КАЙМА, y: ty + 1 + КАЙМА, ш: КЛЕТКА - 2 * КАЙМА, в: КЛЕТКА - 2 * КАЙМА, цвет: 11 });
        return;
      }
      if (знак === '.' || знак === '*') {
        из.push({ вид: 'круг', x: cx, y: cy, r: Math.floor((КЛЕТКА * 3) / 7), заливка: 1, контур: 8 });
      }
      if (знак === '$' || знак === '*') {
        из.push({ вид: 'круг', x: cx, y: cy, r: Math.floor(КЛЕТКА / 3), заливка: 4, контур: 8 });
      }
      if (знак === '@') {
        из.push({ вид: 'круг', x: cx, y: cy, r: Math.floor(КЛЕТКА / 3), заливка: 5, контур: 8 });
      }
    });
  });
  return из;
}

const партия = (примитивы: Примитив[], статус = 0): Партия =>
  ({ ширина: 300, высота: 300, палитра: [], примитивы, статус, ход: null, подорвался: false, тупик: false }) as Партия;

/** Застряла ли бочка по рисунку. `null` — разбор не состоялся. */
const застряла = (карта: string[]): boolean | null => {
  const п = разложитьСокобан(поле(карта));
  return п ? засевшаяБочка(п) : null;
};

describe('«Сокобан»: застрявшая бочка', () => {
  it('🔴 бочка в углу двух стен — застряла', () => {
    expect(застряла([
      '#####',
      '#$  #',
      '# @ #',
      '#  .#',
      '#####',
    ])).toBe(true);
  });

  it('🔴 все четыре угла считаются одинаково', () => {
    const углы = [
      ['#####', '#   #', '#   #', '#  $#', '#####'],   // стена справа и снизу
      ['#####', '#  $#', '#   #', '#   #', '#####'],   // стена справа и сверху
      ['#####', '#   #', '#   #', '#$  #', '#####'],   // стена слева и снизу
    ];
    for (const у of углы) expect(застряла(у)).toBe(true);
  });

  it('🔴 бочка НА МЕТКЕ в углу — не беда, а как раз то, что нужно', () => {
    // Метки часто и стоят по углам: объявить тут конец — значит объявить его на победе.
    expect(застряла([
      '#####',
      '#*  #',
      '# @ #',
      '#   #',
      '#####',
    ])).toBe(false);
  });

  it('🔴 одна стена — не угол: такую бочку ещё катают вдоль стены', () => {
    expect(застряла([
      '#####',
      '#   #',
      '#$@ #',
      '#  .#',
      '#####',
    ])).toBe(false);
  });

  it('🔴 бочка посреди пола — не застряла', () => {
    expect(застряла([
      '#####',
      '#   #',
      '# $ #',
      '# @.#',
      '#####',
    ])).toBe(false);
  });

  it('🔴 за краем поля стены НЕТ — молчим, а не пугаем', () => {
    // Осторожность нарочная: ложная тревога дороже пропуска. Тут у бочки стена только
    // снизу, слева — край рисунка, и объявлять конец не за что.
    expect(застряла([
      '$   .',
      '#    ',
      '  @  ',
      '     ',
      '     ',
    ])).toBe(false);
  });

  it('🔴 ключ подписи уходит в экран, а победа его гасит', () => {
    const мёртвая = поле(['#####', '#$  #', '# @ #', '#  .#', '#####']);
    expect(молчаливыйТупик('Sokoban', партия(мёртвая))).toBe('puzzleBarrelStuck');
    expect(молчаливыйТупик('Sokoban', партия(мёртвая, 1))).toBe('');
    // Чужому режиму этот рисунок ничего не говорит.
    expect(молчаливыйТупик('Pegs', партия(мёртвая))).toBe('');
    expect(молчаливыйТупик('Sokoban', null)).toBe('');
  });

  it('🔴 поле меньше девяти клеток в разбор не идёт', () => {
    expect(разложитьСокобан(поле(['#$', '#.']))).toBeNull();
  });
});
