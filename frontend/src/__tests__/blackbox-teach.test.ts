/**
 * 🔴 РАЗБОР «ЧЁРНОГО ЯЩИКА» ОБЯЗАН СЧИТАТЬ ЛУЧ КАК ДВИЖОК И ОСТАНАВЛИВАТЬСЯ ТОЛЬКО ТОГДА, КОГДА ОТМЕТКА
 * ТОЧНО БУДЕТ ЗАСЧИТАНА.
 *
 * Раскатка обучения (Денис 17.09.2026: «обучение зашло — раскатывай везде по всем играм»). Раздачи —
 * настоящие, сняты с моста (`scripts/capture-blackbox-boards.mjs`): шары из решения движка и ответы
 * САМОГО движка на все входы. Движок засчитывает раскладку, если она отвечает на каждый луч так же,
 * как настоящая (`blackbox.c`, check_guesses), — это и проверяется полным перебором.
 */
import { LANGUAGES, translateFor } from '@/src/contexts/LanguageContext';
import { разобрать as разобратьРисунок, type Партия } from '@/src/games/tatham-bridge/play';
import {
  параметрыИзСтроки, входы, луч, согласные, план, доскаСРисунка, текстШага, центр,
  КЛЮЧИ_РАЗБОРА_ЯЩИКА, type ПараметрыЯщика, type Итог,
} from '@/src/games/tatham-bridge/blackbox-teach';
import { учительBlackBox } from '@/src/games/tatham-bridge/teach/blackbox';
import { УЧИТЕЛЯ } from '@/src/games/tatham-bridge/teach';
import снимок from './blackbox-teach-boards.generated.json';

interface Раздача {
  параметры: string; зерно: number; ширина: number; шары: number[]; ответы: string[];
  рисунокЧеловека: string[]; отметка: number; рисунокРешения?: string[];
}
const раздачи = снимок.раздачи as unknown as Раздача[];
const партия = (рисунок: string[], ширина: number): Партия => ({ примитивы: разобратьРисунок(рисунок.join('\n')), ширина, высота: ширина } as unknown as Партия);

/** Все ответы раскладки на все входы — по ним движок и судит отметку. */
const ответыВсех = (п: ПараметрыЯщика, шары: Iterable<number>) => {
  const все = входы(п.w, п.h), набор = new Set(шары);
  return все.map((_, i) => String(луч(п, набор, i, все))).join('|');
};

describe('разбор «Чёрного ящика» по шагам', () => {
  it('снимок живой: три первые ступени движка, по три раздачи', () => {
    expect(new Set(раздачи.map((р) => р.параметры))).toEqual(new Set(['w5h5m3M3', 'w8h8m5M5', 'w8h8m3M6']));
    expect(раздачи).toHaveLength(9);
  });

  it('🔴 луч считается как у движка: все входы девяти раздач', () => {
    const расхождения: string[] = [];
    let входов = 0;
    for (const р of раздачи) {
      const п = параметрыИзСтроки(р.параметры)!;
      const все = входы(п.w, п.h);
      const шары = new Set(р.шары);
      все.forEach((_, i) => {
        входов++;
        const итог: Итог = луч(п, шары, i, все);
        const знак = р.ответы[i]!;
        const сходится = typeof итог === 'number' ? /^\d+$/.test(знак) && р.ответы[итог] === знак : знак === итог;
        if (!сходится) расхождения.push(`${р.параметры}#${р.зерно} вход ${i}: движок ${знак}, разбор ${итог}`);
      });
    }
    expect(входов).toBe(3 * 20 + 6 * 32);
    expect(расхождения).toEqual([]);
  });

  it.each(раздачи.map((р) => [`${р.параметры}#${р.зерно}`, р] as const))(
    '🔴 %s: план стреляет, пока согласные раскладки различимы, и отмечает раскладку, которую движок засчитает',
    (_, р) => {
      const п = параметрыИзСтроки(р.параметры)!;
      const все = входы(п.w, п.h);
      const шары = new Set(р.шары);
      const t0 = Date.now();
      const шаги = план(п, шары, []);
      const мс = Date.now() - t0;
      expect(мс).toBeLessThan(3000);
      const последний = шаги[шаги.length - 1]!;
      expect(последний.вид).toBe('шары');
      expect(шаги.slice(0, -1).every((ш) => ш.вид === 'выстрел')).toBe(true);
      const выстрелы = шаги.filter((ш) => ш.вид === 'выстрел').map((ш) => ({ i: ш.вход!, итог: луч(п, шары, ш.вход!, все) }));
      expect(new Set(выстрелы.map((в) => в.i)).size).toBe(выстрелы.length);
      // Полный перебор: ВСЕ раскладки, согласные с выстрелами, отвечают на любой луч как настоящая.
      const { раскладки, полон } = согласные(п, выстрелы, все, 20000);
      expect(полон).toBe(true);
      const эталон = ответыВсех(п, шары);
      expect(раскладки.filter((к) => ответыВсех(п, к) !== эталон)).toEqual([]);
      expect(раскладки.map((к) => к.join()).includes(р.шары.join())).toBe(true);
    },
  );

  it('🔴 доска снимается с рисунка: выстрелы человека с ответами, его отметка и шары решения', () => {
    for (const р of раздачи) {
      const п = параметрыИзСтроки(р.параметры)!;
      const все = входы(п.w, п.h);
      const доска = доскаСРисунка(разобратьРисунок(р.рисунокЧеловека.join('\n')), р.ширина, п)!;
      expect(доска.отмечено).toEqual([р.отметка]);
      expect(доска.выстрелы.length).toBeGreaterThanOrEqual(3);
      for (const в of доска.выстрелы) expect(в.итог).toEqual(луч(п, new Set(р.шары), в.i, все));
      if (р.рисунокРешения) expect(доскаСРисунка(разобратьРисунок(р.рисунокРешения.join('\n')), р.ширина, п)!.шары).toEqual(р.шары);
    }
  });

  it.each(раздачи.filter((р) => р.рисунокРешения).map((р) => [р.параметры, р] as const))(
    '🔴 %s: карточки учителя с позиции человека, прокликанные по модели кнопок, кончаются засчитанной отметкой',
    (_, р) => {
      const п = параметрыИзСтроки(р.параметры)!;
      const все = входы(п.w, п.h);
      const плитка = р.ширина / (п.w + 3);
      const карточки = учительBlackBox.урок({ партия: партия(р.рисунокЧеловека, р.ширина), решение: партия(р.рисунокРешения!, р.ширина), параметры: р.параметры })!;
      expect(карточки.length).toBeGreaterThan(1);
      const доска = доскаСРисунка(разобратьРисунок(р.рисунокЧеловека.join('\n')), р.ширина, п)!;
      const выстрелено = new Set(доска.выстрелы.map((в) => в.i));
      const отмечено = new Set(доска.отмечено);
      let проверено = false;
      for (const карточка of карточки) {
        for (const н of карточка.нажатия) {
          const gx = Math.round((н.x - плитка) / плитка), gy = Math.round((н.y - плитка) / плитка);
          expect([н.x, н.y]).toEqual([центр(gx, плитка), центр(gy, плитка)]);
          if (gx === 0 && gy === 0) { проверено = true; continue; }
          const i = все.findIndex((в) => в.gx === gx && в.gy === gy);
          if (i >= 0) { expect(выстрелено.has(i)).toBe(false); выстрелено.add(i); continue; }
          const к = (gy - 1) * п.w + (gx - 1);
          if (отмечено.has(к)) отмечено.delete(к); else отмечено.add(к);
        }
      }
      expect(проверено).toBe(true);
      expect(отмечено.size).toBeGreaterThanOrEqual(п.мин);
      expect(отмечено.size).toBeLessThanOrEqual(п.макс);
      expect(ответыВсех(п, отмечено)).toBe(ответыВсех(п, р.шары));
      // Лишняя отметка человека снята и подсвечена как ошибка.
      expect(карточки[карточки.length - 1]!.рамки.some((рам) => рам.вид === 'ошибка')).toBe(true);
      expect(отмечено.has(р.отметка)).toBe(р.шары.includes(р.отметка));
    },
  );

  it('учитель зарегистрирован для экрана головоломок; без решения движка молчит', () => {
    expect(УЧИТЕЛЯ['Black Box']).toBe(учительBlackBox);
    const р = раздачи[0]!;
    expect(учительBlackBox.урок({ партия: партия(р.рисунокЧеловека, р.ширина), решение: null, параметры: р.параметры })).toBeNull();
  });

  it('🔴 объяснение есть на всех двенадцати языках, со своими подстановками, и ни одна не остаётся сырой', () => {
    const языки = (LANGUAGES as { code: string }[]).map((l) => l.code);
    expect(языки).toHaveLength(12);
    const подстановки: Record<string, string[]> = {
      teachBoxNext: ['{answer}', '{k}', '{r}'], teachBoxNextMany: ['{answer}', '{k}', '{r}'], teachBoxPlace: ['{answer}', '{b}'],
    };
    const пропуски: string[] = [];
    for (const я of языки) for (const к of КЛЮЧИ_РАЗБОРА_ЯЩИКА) {
      const текст = translateFor(я, к);
      if (текст === к) пропуски.push(`${я}:${к} — нет ключа`);
      if (я !== 'en' && текст === translateFor('en', к)) пропуски.push(`${я}:${к} — английский фолбэк`);
      for (const п of подстановки[к] ?? []) if (!текст.includes(п)) пропуски.push(`${я}:${к} — нет ${п}`);
    }
    expect(пропуски).toEqual([]);
    const р = раздачи[3]!;
    const п = параметрыИзСтроки(р.параметры)!;
    const шаги = план(п, new Set(р.шары), []);
    for (const я of языки) for (const шаг of шаги) expect(текстШага(шаг, (к) => translateFor(я, к))).not.toMatch(/\{(answer|k|r|b)\}/);
    expect(текстШага(шаги[0]!, (к) => translateFor('ru', к))).toContain('Шары спрятаны');
    const последний = шаги[шаги.length - 1]!;
    expect(текстШага(последний, (к) => translateFor('ru', к))).toContain(`отмечаем шары (${р.шары.length})`);
  });
});
