/**
 * 🔴 ОСЬ 5 — ПРИМАНКИ РАСТУТ ПО УРОВНЮ, А НЕ ПО ГЛУБИНЕ.
 *
 * ЗАМЕР ДО (07.09.2026). Приманки в игре БЫЛИ — генератор умеет их сам,
 * `lureRateFor(n) = min(0.2, 0.1 + (n-2)*0.05)`. Но доля привязана к ГЛУБИНЕ и
 * упирается в 0.2 уже при n=4 (это L11), а сама глубина упирается в 6 на L13.
 * То есть штатные приманки застывают РАНЬШЕ, чем кончается лестница, и осью роста
 * служить не могут.
 * ⚠️ Это важный случай «готовое есть, но не годится»: я нашёл готовый механизм и
 * чуть не записал ось как сделанную. Померил — застывает на L11.
 *
 * ЗАМЕР ПОСЛЕ. Доля приманок считается от уровня и продолжает расти выше L13.
 */
import { levelParams, NB_VOLUME_TOP } from '@/app/games/n-back';
import { lureRateFor } from '@/src/games/nback/sequence';

describe('n-back: приманки как ось роста', () => {
  it('замер ДО: штатная доля привязана к глубине и застывает на n=4', () => {
    expect(lureRateFor(4)).toBeCloseTo(0.2, 5);
    expect(lureRateFor(5)).toBeCloseTo(0.2, 5);
    expect(lureRateFor(6)).toBeCloseTo(0.2, 5);   // глубже некуда, доля та же
  });

  it('🔴 доля приманок растёт выше плато глубины, монотонно — до физического предела', () => {
    for (let L = NB_VOLUME_TOP + 1; L <= 26; L++) {
      const было = levelParams(L - 1).lureRate ?? 0;
      const стало = levelParams(L).lureRate ?? 0;
      expect(`L${L}: ${стало > было}`).toBe(`L${L}: true`);
    }
  });

  /**
   * 🔴 ПРЕДЕЛ ОСИ — НЕ ПОТОЛОК СЛОЖНОСТИ. Позиции делятся между целями и приманками;
   * доля выше половины оставила бы блок без чистых позиций, и проба перестала бы
   * измерять. Это физика ЭТОЙ оси. Мой же гейт её и нашёл: сначала я проверял рост
   * до L40 и получил «L27: false».
   * Проба стережёт, что плато от этого НЕ возникает: выше предела лестницу
   * продолжает ось 3 — интервал между стимулами.
   */
  it('🔴 выше предела приманок уровни всё равно различимы — держит интервал', () => {
    const одинаковые: string[] = [];
    for (let L = 27; L <= 60; L++) {
      if (JSON.stringify(levelParams(L)) === JSON.stringify(levelParams(L - 1))) одинаковые.push(`L${L}`);
    }
    expect(`клонов выше предела приманок: ${одинаковые.length}`).toBe('клонов выше предела приманок: 0');
    expect(levelParams(60).gapMs).toBeGreaterThan(levelParams(27).gapMs);
  });

  it('ниже плато доля прежняя — игрокам в старой полосе сложность не меняли', () => {
    for (let L = 9; L <= NB_VOLUME_TOP; L++) {
      expect(`L${L}: ${levelParams(L).lureRate}`).toBe(`L${L}: 0.2`);
    }
  });

  it('доля остаётся долей: не уезжает за разумное и не отрицательна', () => {
    for (let L = 1; L <= 200; L++) {
      const r = levelParams(L).lureRate ?? 0;
      expect(r >= 0 && r <= 0.5).toBe(true);
    }
  });
});
