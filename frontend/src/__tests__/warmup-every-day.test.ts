/**
 * Зарядка есть КАЖДЫЙ день недели.
 *
 * ЗАЧЕМ. Со времён первого коммита среда была пустой: её отвели под Brain Workshop,
 * внешнюю программу, которой пользуется Денис лично. Личный график утёк в общее
 * расписание — и любой профиль без своего утреннего набора (например НЗТ-48)
 * получал по средам пустоту и подпись про незнакомую ему программу.
 *
 * Решение Дениса 03.08.2026 дословно: «у нас нет навязанных дней отдыха, зарядки
 * идут каждый день». Фиксируем тестом, потому что пустой день не падает и не
 * ломает типы — он просто молча ничего не показывает, и заметить это можно
 * только открыв приложение в нужный день недели.
 */
import { buildMorningWarmupPlaylist, Weekday } from '../services/warmup';

const DAYS: Weekday[] = [0, 1, 2, 3, 4, 5, 6];
const NAMES = ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'];

describe('утренняя зарядка по дням недели', () => {
  it('ни один день не пустой', () => {
    const empty = DAYS
      .filter((d) => buildMorningWarmupPlaylist({ duration: 5, weekday: d }).steps.length === 0)
      .map((d) => NAMES[d]);
    expect(empty).toEqual([]);
  });

  it('ни один день не помечен треком «без нагрузки»', () => {
    const resting = DAYS
      .filter((d) => buildMorningWarmupPlaylist({ duration: 5, weekday: d }).track === 'rest')
      .map((d) => NAMES[d]);
    expect(resting).toEqual([]);
  });
});
