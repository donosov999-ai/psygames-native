declare const __dirname: string;
const { readFileSync } = require('fs');   // eslint-disable-line @typescript-eslint/no-require-imports
const { join } = require('path');         // eslint-disable-line @typescript-eslint/no-require-imports

const код = () => readFileSync(join(__dirname, '../components/PuzzleCanvas.tsx'), 'utf8');

describe('доска головоломки владеет касанием', () => {
  it('есть что проверять — холст на месте', () => {
    expect(код()).toContain('onStartShouldSetResponder');
  });

  it('🔴 выделение текста на доске отключено', () => {
    const с = код();
    expect(с).toContain("userSelect: 'none'");
    // Safari в WebView слушает свой префикс — без него выделение остаётся.
    expect(с).toContain("WebkitUserSelect: 'none'");
  });

  it('🔴 прокрутка и щипок под пальцем на доске отключены', () => {
    expect(код()).toContain("touchAction: 'none'");
  });

  it('🔴 холст принимает полный жест, а не только тычок', () => {
    const с = код();
    for (const событие of ['onResponderGrant', 'onResponderMove', 'onResponderRelease']) {
      expect(с).toContain(событие);
    }
  });
});

/**
 * МЕДЛЕННАЯ ПРОТЯЖКА НЕ ТЕРЯЕТ ХОД.
 *
 * 📍 Замер 11.09.2026: палец, подержанный на месте дольше 420 мс и ПОТОМ поехавший,
 * уводил всю протяжку правой кнопкой — «Колышки» 0 ходов из 48 и «Прямоугольники»
 * 0 из 48 против 1 и 34 обычной протяжкой. Неторопливый человек просто не мог сыграть.
 *
 * Здесь проверяется ПОСЛЕДОВАТЕЛЬНОСТЬ, которую холст шлёт движку, а не картинка:
 * после срабатывания долгого нажатия и последующего движения он обязан отпустить
 * правую в исходной точке и переоткрыть жест ЛЕВОЙ.
 */
describe('медленная протяжка', () => {
  it('🔴 после долгого нажатия движение переводит жест в ЛЕВУЮ, а не тянет правой', () => {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const fs2 = require('fs');
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const path2 = require('path');
    const источник: string = fs2.readFileSync(
      path2.resolve(__dirname, '../components/PuzzleCanvas.tsx'), 'utf8');
    // отпускаем правую там же, где нажали…
    expect(источник).toMatch(/onЖест\(ж\.x, ж\.y, 'отпустил', true\)/);
    // …и заново открываем жест левой от исходной точки
    expect(источник).toMatch(/ж\.правой = false;[\s\S]{0,80}onЖест\(ж\.x, ж\.y, 'нажал', false\)/);
  });
});

/**
 * ━━━ ОБРЫВ ЖЕСТА НЕ ДЕЛАЕТ ХОД (добавлено 12.09.2026) ━━━
 *
 * 🔴 ПОВОД — аудит сорока головоломок, `psygames-codex-mac`, 12.09.2026:
 * `/Users/denisonosov/dev/psygames-game-lab/audit/puzzles-40-2026-09-12/FINDINGS.md`,
 * пункт P1-04. Трасса обработчика (`gesture-contract.json`): «cancel до таймера:
 * down-left → up-left» — то есть прерванное касание уходило в движок ЩЕЛЧКОМ.
 * Причина простая: `onResponderTerminate` был привязан к тому же `отпустить`,
 * что и успешное отпускание, а `отпустить` дописывает «нажал» за короткий тычок.
 *
 * Обрыв шлёт система — когда жест перехватывает прокрутка или уходит страница.
 * Значит это не экзотика, а обычный ход событий на телефоне, и он делал ходы,
 * которых человек не делал. Задет общий холст, то есть ВСЕ сорок головоломок.
 *
 * ⚠️ ГЕЙТ ПО ИСХОДНИКУ, И Я ЭТО НЕ ПРЯЧУ. Обработчики живут внутри компонента в
 * `useCallback`; чтобы прогнать их поведением, надо вынести их в отдельную
 * фабрику и вызвать напрямую. Это стоящая работа, но она меняет горячий общий
 * холст, и делать её одним заходом с починкой — менять две вещи сразу.
 * ДОЛГ: вынести фабрику жестов и заменить эту пробу поведенческой.
 */
describe('обрыв жеста не превращается в ход', () => {
  it('🔴 обрыв и отпускание — РАЗНЫЕ обработчики', () => {
    const с = код();
    expect(с).toContain('onResponderRelease={отпустить}');
    expect(с).toContain('onResponderTerminate={оборвать}');
    // Главное утверждение: обрыв больше не зовёт отпускание.
    expect(с).not.toContain('onResponderTerminate={отпустить}');
  });

  it('🔴 обработчик обрыва не шлёт «нажал»', () => {
    const с = код();
    const н = с.indexOf('const оборвать');
    expect(н).toBeGreaterThan(-1);
    const тело = с.slice(н, с.indexOf('}, [onЖест, снятьТаймер]);', н));
    // Ни при каком условии обрыв не имеет права начать новое нажатие:
    // именно эта строка и рождала щелчок из отмены.
    expect(тело).not.toContain("'нажал'");
    // А отпустить начатую протяжку обязан — иначе движок останется с зажатой кнопкой.
    expect(тело).toContain("'отпустил'");
  });

  it('отпускание в ПОСЛЕДНЕЙ точке протяжки, а не в начальной', () => {
    const с = код();
    // Точка обновляется на каждом «ведёт» — иначе обрыв отпустит там, откуда палец ушёл.
    expect(с).toContain('ж.посX = x; ж.посY = y;');
    expect(с).toContain("onЖест(ж.посX, ж.посY, 'отпустил', ж.правой)");
  });
});
