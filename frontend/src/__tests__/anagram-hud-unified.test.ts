declare const __dirname: string;
declare function require(id: string): { readFileSync: (p: string, e: string) => string };
const { readFileSync } = require('fs');
// eslint-disable-next-line @typescript-eslint/no-require-imports -- путь к исходникам экранов
const { join } = require('path');

const ROOT = join(__dirname, '../..');
const читать = (p: string) => readFileSync(join(ROOT, p), 'utf8');

/** Комментарии — не код: рассказ о механизме не должен засчитываться за механизм. */
function безКомментариев(s: string): string {
  let out = '', i = 0;
  while (i < s.length) {
    const c = s[i], n = s[i + 1];
    if (c === '/' && n === '*') { const e = s.indexOf('*/', i + 2); out += ' '; i = e < 0 ? s.length : e + 2; continue; }
    if (c === '/' && n === '/') { const e = s.indexOf('\n', i); out += ' '; i = e < 0 ? s.length : e; continue; }
    out += c; i++;
  }
  return out;
}

const РЕЖИМЫ = [
  'src/games/anagrams/WordSquareGame.tsx',
  'src/games/anagrams/AllWordsGame.tsx',
  'src/games/anagrams/CrosswordGame.tsx',
] as const;

it('каждый режим отдаёт числа наверх через onСчёт', () => {
  const плохо: string[] = [];
  for (const п of РЕЖИМЫ) {
    const код = безКомментариев(читать(п));
    if (!/onСчёт\?\.\(\{/.test(код)) плохо.push(`${п}: не вызывает onСчёт`);
  }
  expect(плохо).toEqual([]);
});

it('экран передаёт отчёт каркасу для всех трёх режимов', () => {
  const код = безКомментариев(читать('app/games/anagrams.tsx'));
  // Три обёртки GameShell вокруг отдельных режимов плюс классика — у всех hud.
  const шеллов = (код.match(/<GameShell/g) || []).length;
  const сHud = (код.match(/hud=\{/g) || []).length;
  expect(шеллов).toBeGreaterThanOrEqual(4);
  expect(сHud).toBe(шеллов);
  expect((код.match(/onСчёт=\{/g) || []).length).toBe(РЕЖИМЫ.length);
});

it('режимы больше не рисуют счётчики своей строкой внизу колонки', () => {
  const плохо: string[] = [];
  for (const п of РЕЖИМЫ) {
    const код = безКомментариев(читать(п));
    // Именно эта строка уезжала за край экрана на телефоне.
    if (/стили\.счёт/.test(код)) плохо.push(`${п}: счётчики всё ещё в своей вёрстке`);
  }
  expect(плохо).toEqual([]);
});
