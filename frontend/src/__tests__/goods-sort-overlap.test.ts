/**
 * 🔴 ТОВАРЫ ВНАХЛЁСТ: РИСОВАНИЕ И ПАЛЕЦ ОБЯЗАНЫ СЧИТАТЬ ОДИНАКОВО.
 *
 * Замер 02.09.2026 (iPhone Pro Max, 430 px): ниша 124 px, три товара встык по
 * 40 px. Товар был ограничен не высотой и не спрайтом (непрозрачная часть 96–98 %
 * картинки — проверено), а арифметикой «три в ряд». Отсюда репорт Вали «ужасно
 * товары мелкие»: на телефоне иначе не выходило. У эталона предметы на полке
 * перекрываются — потому и крупные.
 *
 * ⚠️ ОПАСНОСТЬ ЗДЕСЬ НЕ В КРАСОТЕ, А В ЖЕСТЕ. Рисование сдвигает товар
 * отрицательным отступом, а `itemAtX` переводит координату пальца в индекс. Стоит
 * им разойтись — палец берёт НЕ ТОТ товар, причём ошибка растёт к правому краю
 * ниши: жест «почти работает», и глазами это не ловится.
 */
// Лист без React: 14 мс против 3298 мс у экрана (замер 06.09.2026).
import { gsLayout, itemAtX } from '@/src/games/goods-sort/core/level';

describe('товары внахлёст', () => {
  it('нахлёст правда есть и умеренный', () => {
    const l = gsLayout(430, 600, 3, 3, 3);
    expect(l.overlap).toBeGreaterThan(0.15);
    // Больше трети — перекрытая этикетка, и молочные бутылки снова неразличимы (§7.3).
    expect(l.overlap).toBeLessThanOrEqual(0.35);
  });

  it('🔴 товар от нахлёста ВЫРОС на экранах, где его держала ширина', () => {
    /**
     * ⚠️ Сравнивать надо ТАМ, ГДЕ ТОВАР ДЕРЖАЛА ИМЕННО ШИРИНА. На большом экране
     * его ограничивает высота ряда, и нахлёст там не прибавляет ничего — первая
     * редакция теста этого не учла и краснела на 1280 px, требуя роста от
     * величины, упёртой в другое ограничение.
     */
    const выросло: number[] = [];
    for (const w of [360, 390, 430]) {                 // телефоны: держит ширина
      const l = gsLayout(w, 700, 3, 3, 3);
      const встык = Math.floor((l.cellW - 2 * 2) / 3);
      expect(l.itemSize).toBeGreaterThan(встык);       // ради этого всё и делалось
      выросло.push(l.itemSize / встык);
    }
    // Рост около четверти — столько даёт нахлёст 0,3 при трёх штуках в ряд.
    expect(Math.min(...выросло)).toBeGreaterThan(1.15);

    for (const w of [360, 390, 430, 768, 1280]) {      // а влезать обязано везде
      const l = gsLayout(w, 700, 3, 3, 3);
      expect(l.rowW).toBeLessThanOrEqual(l.cellW);
    }
  });

  it('🔴 палец берёт тот товар, который нарисован под ним', () => {
    const l = gsLayout(430, 700, 3, 3, 3);
    const шаг = l.itemSize * (1 - l.overlap) + 2;
    const left = (l.cellW - l.rowW) / 2;
    const промахи: string[] = [];
    for (let idx = 0; idx < 3; idx++) {
      // Видимая полоса товара: от его левого края до начала следующего (сосед
      // нарисован ПОД ним). У последнего — до правого края самого товара.
      const x0 = left + idx * шаг;
      const x1 = idx < 2 ? x0 + шаг : x0 + l.itemSize;
      for (const x of [x0 + 2, (x0 + x1) / 2, x1 - 2]) {
        const got = itemAtX(x, 3, l.cellW, l.itemSize, 2, l.overlap);
        if (got !== idx) промахи.push(`x=${Math.round(x)} → ${got}, ждали ${idx}`);
      }
    }
    expect(промахи).toEqual([]);
  });

  it('за краями ряда берётся ближний товар, а не пустота', () => {
    const l = gsLayout(430, 700, 3, 3, 3);
    expect(itemAtX(0, 3, l.cellW, l.itemSize, 2, l.overlap)).toBe(0);
    expect(itemAtX(l.cellW, 3, l.cellW, l.itemSize, 2, l.overlap)).toBe(2);
    expect(itemAtX(10, 0, l.cellW, l.itemSize, 2, l.overlap)).toBeNull();
  });

  it('⚠️ без нахлёста поведение прежнее — старые вызовы не сломаны', () => {
    // `overlap` по умолчанию 0: любой вызов, который его не передаёт, считает встык.
    const cellW = 124, item = 40;
    expect(itemAtX(cellW / 2, 3, cellW, item)).toBe(1);
    expect(itemAtX(2, 3, cellW, item)).toBe(0);
  });
});
