/**
 * 🔴 ФИГУРА НЕ СЛИВАЕТСЯ С ТЕМ, НА ЧЁМ ЛЕЖИТ.
 *
 * Отчёт Дениса 05.09.2026 (`a4cbdc5c`), дословно: «в чёрных надо убрать чёрную
 * заливку, снизу ни хрена не видно что за чёрные фигуры».
 *
 * 📍 ПРИЧИНА БЫЛА ИСТОРИЧЕСКОЙ. Плашка выбора красилась по стороне: белым —
 * светлая, чёрным — тёмная `#1e293b`. Это было верно, пока фигуры рисовались
 * ТЕКСТОМ: светлый глиф на тёмном читался. С 03.09.2026 фигуры — настоящие
 * картинки Cburnett, где чёрная фигура и ЕСТЬ чёрная заливка. Чёрный конь на
 * тёмной плашке пропадал целиком.
 *
 * 🔴 А ВОТ ЧЕМ ЭТА ПРОБА БЫЛА ПРИЗРАКОМ — И ЭТО ВАЖНЕЕ САМОЙ ПОЧИНКИ.
 *
 * Она описывала чёрную фигуру как «заливка #000000, контур #ffffff» — то есть
 * приписывала ей БЕЛУЮ ОБВОДКУ. Такой обводки нет: замер 06.09.2026 по всем
 * двенадцати строкам `CHESS_PIECE_SVG` — первый `stroke` у КАЖДОЙ фигуры,
 * чёрной и белой, равен `#000000`; белый в чёрных фигурах встречается только на
 * ВНУТРЕННИХ линиях (у пешки `BP` его нет вовсе). Белая обводка была выдумкой
 * модели, а `Math.max` брал контраст именно по ней.
 *
 * Цена выдумки замерена мутацией 06.09.2026: возвращаю плашке ровно тот цвет,
 * на который жаловался Денис (`#1e293b`), — и все четыре пробы ОСТАЮТСЯ
 * ЗЕЛЁНЫМИ. То есть гейт, написанный против этого дефекта, не ловил его.
 *
 * Теперь цвета берутся ИЗ САМОЙ КАРТИНКИ, а не из представления о ней.
 */
import { contrastRatio } from '@/src/services/onGradientText';
import { CHESS_PIECE_SVG } from '@/src/games/chess-blind/core/pieces';

declare function require(m: string): any;
const fs = require('fs');
const path = require('path');
declare const __dirname: string;

const ЭКРАН = path.join(__dirname, '../../app/games/chess-blind.tsx');
const код: string = fs.readFileSync(ЭКРАН, 'utf8');

const норм = (c: string) => (c.length === 3 ? `#${c.split('').map((k) => k + k).join('')}` : `#${c}`);

/**
 * Силуэт фигуры — то, чем она отделяется от подложки: ЗАЛИВКА тела и ВНЕШНЯЯ
 * обводка. Обе берутся из строки картинки.
 *
 * ⚠️ Первая объявленная в файле обводка — это стиль внешней группы, то есть
 * контур силуэта; белые `stroke` внутренних линий идут ниже и на отделение от
 * фона не работают. Заливка — первая настоящая (`fill:none` не считается: это
 * группа-обёртка, у неё заливки нет).
 */
function силуэт(svg: string): { заливка: string; контур: string } {
  const контур = /stroke[:=]"?#?([0-9a-fA-F]{3,6})/.exec(svg);
  const заливка = /fill[:=]"?#?([0-9a-fA-F]{3,6})/.exec(svg);
  if (!контур || !заливка) throw new Error('в картинке нет ни обводки, ни заливки');
  return { заливка: норм(заливка[1]!), контур: норм(контур[1]!) };
}

/**
 * Читаемость даёт ЛЮБАЯ из двух половин силуэта: белая фигура на светлом поле
 * держится чёрным контуром, чёрная на светлом — своей заливкой.
 *
 * ⚠️ Первая редакция мерила одну заливку и объявила дефектом обычную шахматную
 * доску: белая фигура на светлом поле даёт 1,2. Доска не виновата — неполной
 * была модель. Но и вторая редакция была неполной, только в другую сторону:
 * она добавила фигуре обводку, которой у той нет.
 */
const читаемость = (ф: { заливка: string; контур: string }, фон: string) =>
  Math.max(contrastRatio(ф.заливка, фон), contrastRatio(ф.контур, фон));

/** 3:1 — порог для крупной графики; фигура 40–44 px это она и есть. */
const ПОРОГ = 3;

describe('«Доска в уме»: фигура читается на своей подложке', () => {
  it('есть что проверять: набор фигур на месте и заливки в нём именно такие', () => {
    expect(Object.keys(CHESS_PIECE_SVG).length).toBeGreaterThanOrEqual(12);
    expect(CHESS_PIECE_SVG.WK).toContain('fill="#fff"');
    expect(CHESS_PIECE_SVG.BK).toMatch(/fill="#000"|fill:#000/);
  });

  /**
   * 🔴 МОДЕЛЬ СВЕРЕНА С КАРТИНКОЙ. Без этой пробы предыдущая редакция гейта
   * годами считала бы контраст по несуществующей белой обводке.
   */
  it('🔴 у чёрных фигур НЕТ белой внешней обводки — модель не выдумана', () => {
    const сбелойОбводкой = Object.entries(CHESS_PIECE_SVG)
      .filter(([k]) => k.startsWith('B'))
      .filter(([, svg]) => силуэт(svg).контур.toLowerCase() !== '#000000')
      .map(([k]) => k);
    expect(`чёрных фигур с белым контуром: ${сбелойОбводкой.length} → ${сбелойОбводкой.join(',')}`)
      .toBe('чёрных фигур с белым контуром: 0 → ');
    // И заливка у них действительно чёрная — иначе мерить было бы нечего.
    for (const k of Object.keys(CHESS_PIECE_SVG).filter((x) => x.startsWith('B'))) {
      expect(`${k}: ${силуэт(CHESS_PIECE_SVG[k]!).заливка}`).toBe(`${k}: #000000`);
    }
  });

  it('🔴 плашка выбора не красится по стороне — иначе чёрная фигура тонет', () => {
    expect(код).not.toMatch(/backgroundColor:\s*opt\.white\s*\?/);
  });

  it('🔴 КАЖДАЯ из двенадцати фигур контрастна на плашке выбора', () => {
    const плашка = /backgroundColor:\s*'(#[0-9a-fA-F]{6})',\s*\n\s*borderColor:\s*рамка/.exec(код)?.[1];
    expect(плашка).toBeTruthy();
    const слабые = Object.entries(CHESS_PIECE_SVG)
      .map(([k, svg]) => [k, читаемость(силуэт(svg), плашка!)] as const)
      .filter(([, к]) => к <= ПОРОГ)
      .map(([k, к]) => `${k}:${к.toFixed(1)}`);
    expect(`фигур слабее ${ПОРОГ}:1 на плашке ${плашка}: ${слабые.length} → ${слабые.join(' ')}`)
      .toBe(`фигур слабее ${ПОРОГ}:1 на плашке ${плашка}: 0 → `);
  });

  it('🔴 и на самой доске: каждая фигура читается на светлом и на тёмном поле', () => {
    const светлое = /BOARD_LIGHT = '(#[0-9a-fA-F]{6})'/.exec(код)?.[1];
    const тёмное = /BOARD_DARK = '(#[0-9a-fA-F]{6})'/.exec(код)?.[1];
    expect(светлое && тёмное).toBeTruthy();
    const слабые: string[] = [];
    for (const поле of [светлое!, тёмное!]) {
      for (const [k, svg] of Object.entries(CHESS_PIECE_SVG)) {
        const к = читаемость(силуэт(svg), поле);
        if (к <= ПОРОГ) слабые.push(`${k} на ${поле}: ${к.toFixed(1)}`);
      }
    }
    expect(слабые).toEqual([]);
  });
});
