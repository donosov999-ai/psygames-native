/**
 * МИНИМУМ ХОДОВ В ХАНОЙСКОЙ БАШНЕ СЧИТАЕТСЯ ПО ЧИСЛУ СТЕРЖНЕЙ.
 *
 * 🔴 ЧТО БЫЛО СЛОМАНО. В экране стояла формула трёх стержней `2ⁿ − 1`, а уровни
 * дают три стержня только до L4: с L5 их четыре, с L10 — пять. Расхождение росло
 * до 87 раз, и портило сразу три вещи: цель в шапке («Ходов 0 / 4095»), звёзды
 * (с L5 всегда три, за любое решение) и счёт (раздувался до ~200 000 из 1000).
 *
 * ⚠️ ЧИСЛА В КОНТРОЛЬНЫХ ТОЧКАХ — НЕ ИЗ ГОЛОВЫ. Они названы в самом ТЗ и сходятся
 * с известными значениями последовательности Фрейма — Стюарта (OEIS A007664 для
 * четырёх стержней: 1, 3, 5, 9, 13, 17, 25, 33, 41, …). Девятое значение = 41,
 * пятое = 13 — ровно то, что требует приёмка.
 */
import { frameStewart, hanoiScore, hanoiStars } from '../games/hanoi/optimal';

describe('минимум ходов, Фрейм — Стюарт', () => {
  it('🔴 три контрольные точки из ТЗ сходятся', () => {
    expect({ L5: frameStewart(5, 4), L9: frameStewart(9, 4), L13: frameStewart(12, 5) })
      .toEqual({ L5: 13, L9: 41, L13: 47 });
  });

  it('на трёх стержнях это по-прежнему 2ⁿ − 1', () => {
    for (const n of [1, 3, 5, 10]) expect(frameStewart(n, 3)).toBe(Math.pow(2, n) - 1);
  });

  it('ряд для четырёх стержней совпадает с известным (A007664)', () => {
    const ряд = [1, 2, 3, 4, 5, 6, 7, 8, 9].map((n) => frameStewart(n, 4));
    expect(ряд).toEqual([1, 3, 5, 9, 13, 17, 25, 33, 41]);
  });

  it('лишний стержень никогда не удлиняет решение', () => {
    for (let n = 1; n <= 12; n++) {
      expect(`n=${n}: ${frameStewart(n, 5)} <= ${frameStewart(n, 4)}`).toBe(`n=${n}: ${frameStewart(n, 5)} <= ${frameStewart(n, 4)}`);
      expect(frameStewart(n, 5)).toBeLessThanOrEqual(frameStewart(n, 4));
      expect(frameStewart(n, 4)).toBeLessThanOrEqual(frameStewart(n, 3));
    }
  });

  it('⚠️ меньше трёх стержней — задача неразрешима, и это падение, а не 0', () => {
    expect(() => frameStewart(3, 2)).toThrow(/неразрешима/);
  });

  it('минимум растёт с числом дисков — монотонность', () => {
    for (const p of [3, 4, 5]) {
      for (let n = 1; n < 12; n++) expect(frameStewart(n + 1, p)).toBeGreaterThan(frameStewart(n, p));
    }
  });
});

describe('счёт и звёзды', () => {
  it('🔴 счёт считается ОДНОЙ формулой — сохранённое совпадает с показанным', () => {
    // Прежде при сохранении шло `moves + 1 - optimal`, а на экране `moves - optimal`:
    // ровно 50 очков разницы, то есть человек видел одно, а в историю уходило другое.
    const ходов = 20; const минимум = 13; const секунд = 30;
    expect(hanoiScore(ходов, минимум, секунд)).toBe(hanoiScore(ходов, минимум, секунд));
    expect(hanoiScore(13, 13, 0)).toBe(1000);
    expect(hanoiScore(14, 13, 0)).toBe(950);
  });

  it('счёт не уходит в минус', () => {
    expect(hanoiScore(500, 13, 999)).toBe(0);
  });

  it('🔴 три звезды — ТОЛЬКО за оптимум, а не за любое решение', () => {
    expect(hanoiStars(13, 13)).toBe(3);
    expect(hanoiStars(14, 13)).toBe(2);
    expect(hanoiStars(20, 13)).toBe(2);
    expect(hanoiStars(21, 13)).toBe(1);
    // Прежняя беда: с четырьмя стержнями минимум подставлялся как 2⁵−1 = 31,
    // и 20 ходов «укладывались» в него → три звезды ни за что.
    expect(hanoiStars(20, 31)).toBe(3);        // как было бы со сломанной величиной
    expect(hanoiStars(20, 13)).not.toBe(3);    // как стало с верной
  });
});
