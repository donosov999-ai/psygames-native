/**
 * НИЖНИЕ ТУЛБАРЫ ВСЕХ РЕЖИМОВ АНАГРАММ — ОДНОЙ ГЕОМЕТРИИ.
 *
 * 📍 ПРОСЬБА ДЕНИСА 07.09.2026: «нижние тулбары с кнопками примерно к одной
 * геометрии и виду, пляшет всё». Повод — «Зарядка», которая мешает разные игры
 * подряд: скачущий интерфейс между ними раздражает сильнее, чем неидеальный в
 * каждой по отдельности.
 *
 * 🔴 ЗАМЕР ДО, живьём на 375×812: высоты кнопок 44, 48, 53 и 66 в одном разделе.
 * В коде — ЧЕТЫРЕ отдельных определения одного и того же стиля:
 *   AllWordsGame   — minHeight 44, minWidth 110, radius 12, border 1, padH 18;
 *   CrosswordGame  — то же, скопированное отдельно;
 *   WordSquareGame — minHeight 44, minWidth 140 (шире прочих), radius 12;
 *   экран классики — minHeight 48, radius 16, border 1.5, padH 24.
 *
 * ЗАМЕР ПОСЛЕ, там же: у всех трёх режимов высота кнопок ровно 48; полосы
 * помещаются в экран (кроссворд 54…321, «все слова» 46…329, квадрат 121…254).
 *
 * ⚠️ ВЫСОТА 48, А НЕ 44, И ЭТО ЗАМЕР: 48 — порог Material и то же число, которым
 * меряет поле общий аудит `scripts/tap-target-audit.mjs` (второй проход, порог
 * 48×48). 44 — нижняя граница Apple; она проходит ревью, но у нас уже 64
 * элемента долга по мелким целям, и добавлять к ним нечего.
 */
import { StyleSheet } from 'react-native';
import { стилиРежима, ВЫСОТА_КНОПКИ } from '@/src/games/anagrams/modeStyles';

declare const __dirname: string;
// 07.09.2026: было `{ readFileSync: … }` — тогда `require('path')` получал
// тот же тип, и `join` не находился. Объявление одно на все модули.
declare function require(id: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');
const ROOT = join(__dirname, '../..');
const читать = (p: string) => readFileSync(join(ROOT, p), 'utf8');

const РЕЖИМЫ = [
  'src/games/anagrams/WordSquareGame.tsx',
  'src/games/anagrams/AllWordsGame.tsx',
  'src/games/anagrams/CrosswordGame.tsx',
] as const;

it('кнопка режимов ростом не ниже порога полевого аудита', () => {
  const к = StyleSheet.flatten(стилиРежима.кнопка) as Record<string, string | number>;
  expect(ВЫСОТА_КНОПКИ).toBe(48);
  expect(Number(к.minHeight)).toBe(ВЫСОТА_КНОПКИ);
});

/**
 * 🔴 ШИРИНУ НАЗНАЧАЕТ ПОЛОСА, А НЕ КНОПКА.
 *
 * 📍 Прежняя редакция этой проверки требовала `minWidth` и считала, влезут ли
 * две кнопки в 320. Замер живьём 07.09.2026 показал, что считалось не то:
 * каркас отдаёт нижней полосе НЕ ширину экрана, а 243 точки — по 66 с каждого
 * края уходит под справку и чат (`HELP_CORNER_SPACE`). Двум кнопкам при
 * `minWidth: 110` и отступах по 24 нужно 264, и они вставали В ДВА РЯДА:
 * «Сбросить» на 68 от низа, «Проверить» на 10. После правки обе на 10, по 105
 * точек, левые края 77 и 193 — и так же в кроссворде.
 *
 * ⚠️ Считать «влезает ли» по ширине ЭКРАНА — та же ошибка, что мерить не тот
 * объект: 375 против живых 243. Поэтому здесь стоит ширина полосы, а не экрана.
 */
it('ряд тянется на всю полосу, а кнопки делят её поровну', () => {
  const д = StyleSheet.flatten(стилиРежима.действия) as Record<string, string | number>;
  expect(д.flexWrap).toBe('wrap');
  expect(д.maxWidth).toBe('100%');
  expect(д.alignSelf).toBe('stretch');            // нечего делить, если ряд по содержимому

  const к = StyleSheet.flatten(стилиРежима.кнопка) as Record<string, string | number>;
  expect(Number(к.flexGrow)).toBe(1);
  expect(Number(к.flexBasis)).toBe(0);
  // Жёсткий пол ширины возвращает перенос — именно он и ломал ряд.
  expect(Number(к.minWidth ?? 0)).toBe(0);

  // Полоса каркаса на самом узком телефоне и то, что от неё достаётся кнопке.
  const ПОЛОСА = 375 - 66 * 2;
  const наКнопку = (ПОЛОСА - Number(д.gap)) / 2;
  const подПодпись = наКнопку - Number(к.paddingHorizontal) * 2;
  // Самая длинная живая подпись — «Проверить»/«Comprobar», 83 px шрифтом 700/15.
  expect(подПодпись).toBeGreaterThanOrEqual(83);
});

/**
 * 🔴 ОПРЕДЕЛЕНИЕ ОДНО НА ТРИ РЕЖИМА. Три копии одного стиля расходятся молча и
 * по одной — в этом разделе я на такое наступал трижды за два дня (копия расчёта
 * лестницы, копия отбора банка, копия формулы времени). Здесь следим, чтобы
 * копия не завелась снова: свой `minHeight` у режима означает, что он отвязался.
 */
it('ни один режим не заводит собственную геометрию кнопки', () => {
  /*
   * 📍 07.09.2026 премиса изменилась: режимы больше НЕ РИСУЮТ кнопок — они
   * отдают действия каркасу, а рисует их экран. Поэтому «берёт ли режим общий
   * стиль» проверять больше нечего (он его и не импортирует), а вот «не завёл
   * ли снова свою геометрию» — по-прежнему да, и теперь это единственный
   * способ, которым копия может вернуться.
   */
  const плохо: string[] = [];
  for (const п of РЕЖИМЫ) {
    const код = читать(п);
    if (/minHeight:\s*4[0-9]/.test(код)) плохо.push(`${п}: завёл свою высоту кнопки`);
    if (/стилиРежима\.действия/.test(код)) плохо.push(`${п}: снова рисует свой ряд кнопок`);
  }
  // Единственный потребитель общей геометрии — экран, и он обязан её брать.
  if (!/from '@\/src\/games\/anagrams\/modeStyles'/.test(читать('app/games/anagrams.tsx'))) {
    плохо.push('app/games/anagrams.tsx: не берёт общую геометрию кнопок');
  }
  expect(плохо).toEqual([]);
});
