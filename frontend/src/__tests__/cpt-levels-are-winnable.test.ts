/**
 * КАЖДЫЙ УРОВЕНЬ ВНИМАНИЯ ОБЯЗАН БЫТЬ ВЗЯТ ХОТЬ КЕМ-ТО.
 *
 * 🔴 ЧТО БЫЛО. Партия засчитывается, только если сыграно не меньше
 * `MIN_TRIALS_FOR_LEVEL` проб — иначе взводится `aborted` и уровень не двигается
 * (правило заведено против «дождался первой цели и нажал СТОП»). Порог стоял 40,
 * а обоснование в комментарии считало, что проба стоит ОДИН ISI. Она стоит ДВА:
 * пауза до буквы плюс окно ответа той же длины. Настоящий счёт за 90 секунд —
 * 30 проб на первом уровне, 33 на втором, 37 на третьем. Все три ниже порога,
 * то есть подняться с первого уровня было физически нельзя.
 *
 * ⚠️ ПОЧЕМУ ГЕЙТ СЧИТАЕТ САМ, А НЕ ЧИТАЕТ КОММЕНТАРИЙ. Дефект и родился из счёта
 * на глаз в комментарии. Здесь число берётся из тех же `levelParams`, которыми
 * играет экран, и сверяется с тем же порогом, которым он судит.
 */
import { levelParams, trialsThatFit, MIN_TRIALS_FOR_LEVEL } from '@/app/games/cpt';

const LEVELS = Array.from({ length: 15 }, (_, i) => i + 1);

describe('внимание: уровни проходимы', () => {
  it('проба стоит ДВА ISI — счёт совпадает с формулой экрана', () => {
    const p = levelParams(1);
    expect(trialsThatFit(1)).toBe(Math.floor((p.durationSec * 1000) / (p.isiMs * 2)));
  });

  it('на КАЖДОМ уровне проб влезает не меньше порога зачёта', () => {
    const bad = LEVELS.filter((l) => trialsThatFit(l) < MIN_TRIALS_FOR_LEVEL)
      .map((l) => `L${l}: ${trialsThatFit(l)} < ${MIN_TRIALS_FOR_LEVEL}`);
    expect(`уровней, которые нельзя взять: ${bad.length ? bad.join(', ') : 'нет'}`)
      .toBe('уровней, которые нельзя взять: нет');
  });

  /**
   * ⚠️ ЗАПАС, А НЕ ВПРИТЫК. Ровное совпадение означает, что любая заминка —
   * подвисший кадр, поздний тап — снимает зачёт. Требуем пятую часть сверху.
   */
  it('на самом медленном уровне есть запас, а не впритык', () => {
    const worst = Math.min(...LEVELS.map(trialsThatFit));
    expect(`минимум проб ${worst}, порог ${MIN_TRIALS_FOR_LEVEL}, запас ${worst - MIN_TRIALS_FOR_LEVEL}`)
      .toBe(`минимум проб ${worst}, порог ${MIN_TRIALS_FOR_LEVEL}, запас ${worst - MIN_TRIALS_FOR_LEVEL}`);
    expect(worst).toBeGreaterThanOrEqual(Math.ceil(MIN_TRIALS_FOR_LEVEL * 1.2));
  });

  /**
   * ⚠️ И ПОРОГ НЕ ДОЛЖЕН ОБЕСЦЕНИТЬСЯ. Смысл правила — отсечь «дождался первой
   * цели и вышел». Порог ниже десяти проб этого уже не делает.
   */
  it('порог остаётся осмысленным, а не превращается в ноль', () => {
    expect(MIN_TRIALS_FOR_LEVEL).toBeGreaterThanOrEqual(10);
  });
});
