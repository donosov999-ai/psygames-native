/**
 * 🔴 ОТКЛИК В РУКУ — ЕДИНСТВЕННЫЙ КАНАЛ, КОТОРЫМ «ГИМНАСТИКА ДЛЯ ГЛАЗ» МОЖЕТ
 * СКАЗАТЬ О СОБЫТИИ, НЕ ОТВЛЕКАЯ ВЗГЛЯД ОТ ТОЧКИ.
 *
 * Просьба тестировщицы 05.09.2026: «нужен какой-то сенсорный отклик… лучше
 * сенсорный отклик в начале и в конце» (задача cc712875). Отклик в экране был,
 * но не проверялся ничем: молчащая вибрация выглядит так же, как работающая, а
 * при переезде экрана на Flutter такой слой исчезает молча.
 */
import { EYE_GYM_HAPTICS, eyeGymStepBuzzes } from '@/src/services/eyeGymHaptics';

describe('«Гимнастика для глаз»: отклик в руку', () => {
  it('🔴 три момента названы: начало, смена упражнения, конец', () => {
    expect(Object.keys(EYE_GYM_HAPTICS).sort()).toEqual(
      ['finish', 'start', 'stepChange'],
    );
  });

  it('🔴 сила у трёх моментов разная — иначе они сливаются в одно ощущение', () => {
    const силы = Object.values(EYE_GYM_HAPTICS);
    expect(new Set(силы).size).toBe(силы.length);
  });

  it('🔴 на первом шаге тычка нет: только что отработал отклик начала', () => {
    expect(eyeGymStepBuzzes(-1, 0)).toBe(false);
  });

  it('🔴 переход со второго упражнения на третье отзывается', () => {
    expect(eyeGymStepBuzzes(1, 2)).toBe(true);
  });

  it('перерисовка того же шага молчит: рендер зовётся десятки раз в секунду', () => {
    expect(eyeGymStepBuzzes(3, 3)).toBe(false);
  });

  it('🔴 подход из десяти упражнений даёт ровно девять тычков', () => {
    let тычков = 0;
    let прошлый = -1;
    for (let шаг = 0; шаг < 10; шаг += 1) {
      // Каждый шаг держится несколько кадров — отклик обязан быть один.
      for (let кадр = 0; кадр < 30; кадр += 1) {
        if (eyeGymStepBuzzes(прошлый, шаг)) тычков += 1;
        прошлый = шаг;
      }
    }
    expect(тычков).toBe(9);
  });
});
