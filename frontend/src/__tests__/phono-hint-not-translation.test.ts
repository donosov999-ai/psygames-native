/**
 * 🔴 R7: ЗАСТРЯЛ → ПОДСКАЗКА ФОНОЛОГИЧЕСКАЯ, А НЕ ПЕРЕВОД.
 *
 * 📍 ЗАМЕР 09.09.2026 (PROJECT_REF §3.3): такой подсказки не было НИ В ОДНОЙ из
 * игр раздела, а `vocabSrsHint` давал ровно перевод — то, что R7 запрещает.
 * Правило не про вежливость: подсказка переводом переключает задачу со
 * ЗВУЧАНИЯ на ЗНАЧЕНИЕ, и упражнение перестаёт тренировать то, ради чего заведено.
 */
import { слогДо, ОШИБОК_ДО_ПОДСКАЗКИ } from '@/src/games/dictation/core/phonoHint';

declare const __dirname: string;
declare function require(id: string): any;
const читать = (rel: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, rel), 'utf8') as string;
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

const открыть = (текст: string, pos: number): string => [...текст].slice(0, слогДо(текст, pos)).join('');

describe('подсказка про звучание, а не про смысл', () => {
  it('🔴 открывает приступ и первый гласный, а не букву', () => {
    expect(открыть('stone', 0)).toBe('sto');
    expect(открыть('bread', 0)).toBe('brea');
    expect(открыть('камень', 0)).toBe('ка');
  });

  it('🔴 слог берётся у ТЕКУЩЕГО слова, а не у первого во фразе', () => {
    // Курсор на «м» в «мост» — открыть надо начало этого слова, не «через».
    const ф = 'через реку построен мост';
    expect(открыть(ф, ф.indexOf('мост'))).toBe('через реку построен мо');
    expect(открыть(ф, ф.indexOf('реку'))).toBe('через ре');
  });

  /**
   * 🔴 ЦЕЛИКОМ СЛОВО НЕ ОТКРЫВАЕТСЯ НИКОГДА — иначе это уже не подсказка, а
   * ответ, а в диктанте ответ означает списывание.
   */
  it('🔴 всё слово не открывается ни при каких буквах', () => {
    for (const w of ['aa', 'oo', 'ау', 'дом', 'eye', 'sea', 'iou']) {
      expect(`${w}: ${открыть(w, 0).length < [...w].length}`).toBe(`${w}: true`);
    }
  });

  /**
   * ⚠️ ПИСЬМЕННОСТЬ БЕЗ БУКВ-ГЛАСНЫХ — ПОЛОВИНА НАШИХ ЯЗЫКОВ, а не крайний
   * случай: zh, ja, ko, hi, ar. Слог там — знак, открываем ровно один.
   */
  it('🔴 в письменности без гласных букв открывается один знак', () => {
    expect(открыть('石头', 0)).toBe('石');
    expect(открыть('पत्थर', 0)).toBe('प');
  });

  it('за пределами строки подсказки нет, и это не падение', () => {
    expect(() => слогДо('дом', 99)).not.toThrow();
    expect(() => слогДо('', 0)).not.toThrow();
    expect(слогДо('дом', -1)).toBe(0);
  });

  it('🔴 подсказка приходит не сразу, а после нескольких ошибок подряд', () => {
    expect(ОШИБОК_ДО_ПОДСКАЗКИ).toBeGreaterThanOrEqual(2);
  });

  /**
   * 🔴 ТОЛЬКО ТАМ, ГДЕ ЗАСТРЕВАНИЕ ВООБЩЕ БЫВАЕТ. В словаре образец виден
   * целиком — подсказка там была бы шумом, а счётчик ошибок жил бы зря.
   */
  it('🔴 подсказка включена только при скрытом образце', () => {
    const src = код(читать('../games/vocab-srs/TypingAnswer.tsx'));
    expect(src).toMatch(/if \(hideUntyped\) \{/);
    expect(src).toMatch(/i >= открытоДо\.current/);
    expect(src).toMatch(/счёт >= ОШИБОК_ДО_ПОДСКАЗКИ/);
  });

  /**
   * 🔴 И ГЛАВНОЕ ПО R7: ПЕРЕВОДА В ПОДСКАЗКЕ НЕТ. Открывается кусок САМОГО
   * набираемого текста — то есть его звучание, а не значение.
   */
  it('🔴 подсказка берётся из набираемого слова, а не из словаря', () => {
    const src = код(читать('../games/vocab-srs/TypingAnswer.tsx'));
    expect(src).toMatch(/слогДо\(word, ст\.pos\)/);
    expect(src).not.toMatch(/TRANSLATION_VOCAB|перевод|translation/i);
  });
});
