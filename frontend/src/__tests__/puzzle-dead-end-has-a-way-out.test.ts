/**
 * ПОДРЫВ — НЕ ТУПИК: ВЫХОД ЛЕЖИТ НА ДОСКЕ, А НЕ В МЕНЮ ПАУЗЫ.
 *
 * 📍 Денис 11.09.2026, снимок «Сапёра» с подорванной клеткой: «в конце не двигается,
 * выходит только через кнопку паузы».
 *
 * ⚠️ И это НЕ проигрыш — так решил автор движка, и написал прямо в исходнике:
 *   `mines.c:5606`   «партия проиграна, только если игрок вскрыл мины решателем;
 *                     иначе предполагаем, что он отменит ход и продолжит»;
 *   `inertia.c:2191` «мы никогда не сообщаем о проигрыше — умерший скорее всего
 *                     захочет отменить и играть дальше».
 * Поэтому `psy_status` остаётся НУЛЁМ, и признак приходится брать из строки
 * состояния. Замер 11.09.2026: 300 открытий на трёх зёрнах «Сапёра» — статус 0 во
 * всех трёх, строка «[0:04] DEAD!  Deaths: 1».
 */
import { подорвался, ходПартии } from '@/src/games/tatham-bridge/status';

describe('подрыв на доске', () => {
  it('🔴 живые строки «Сапёра» и «Инерции» опознаются как подрыв', () => {
    const живые = [
      '[0:04] DEAD!  Deaths: 1',      // Сапёр, замер 11.09.2026
      '[0:44] DEAD!  Deaths: 1',
      'DEAD!   Deaths: 1',            // Инерция
      'DEAD!',
    ];
    expect(живые.filter((s) => !подорвался(s))).toEqual([]);
  });

  it('🔴 обычный ход подрывом НЕ считается', () => {
    const мирные = [
      '[0:00] Marked: 0 / 10',
      'Gems: 16',
      'Balls marked: 0 / 5',
      'Clues left: 44',
      'COMPLETED!',
      'Auto-solved.',
      '',
    ];
    expect(мирные.filter((s) => подорвался(s))).toEqual([]);
  });

  /**
   * ⚠️ Контроль с известным ответом: строка подрыва не должна попасть в счётчик
   * шапки. «DEAD!   Deaths: 1» содержит число, и жадный разбор вписал бы «1» под
   * какой-нибудь подписью — человек увидел бы в шапке бодрое «Счёт 1» после взрыва.
   */
  it('🔴 строка подрыва не превращается в счётчик шапки', () => {
    expect(ходПартии('DEAD!   Deaths: 1')).toBeNull();
    expect(ходПартии('[0:00] DEAD!  Deaths: 1')).toBeNull();
  });
});
