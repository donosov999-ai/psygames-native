declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');

const ЭКРАН = fs.readFileSync(path.join(__dirname, '../../app/games/sudoku.tsx'), 'utf8') as string;
const ЗНАЧОК = fs.readFileSync(path.join(__dirname, '../components/GameAuxAction.tsx'), 'utf8') as string;

/** Кусок разметки одной кнопки — значка ряда с этой подписью, от `<GameAuxAction` до `/>`. */
function кнопка(ключ: string): string {
  const i = ЭКРАН.indexOf(`label={t('${ключ}')}`);
  if (i < 0) return '';
  const от = ЭКРАН.lastIndexOf('<GameAuxAction', i);
  return ЭКРАН.slice(от, ЭКРАН.indexOf('/>', i) + 2);
}

const ПЕРЕКЛЮЧАТЕЛИ: { имя: string; состояние: RegExp }[] = [
  { имя: 'sudokuPencilMode', состояние: /pencil\b/ },
  { имя: 'sudokuColorMode', состояние: /paintColor/ },
];

describe('состояние режима видно не только цветом', () => {
  it('есть что мерить — обе кнопки на месте', () => {
    const пустые = ПЕРЕКЛЮЧАТЕЛИ.filter((п) => кнопка(п.имя).length === 0).map((п) => п.имя);
    expect(`не найдены: ${пустые.join(' ') || 'нет'}`).toBe('не найдены: нет');
  });

  it('🔴 ЗНАЧОК зависит от состояния, а не постоянный', () => {
    const плохо = ПЕРЕКЛЮЧАТЕЛИ.filter((п) => {
      const б = кнопка(п.имя);
      const значок = /icon=\{([^}]*)\}|icon="([^"]*)"/.exec(б);
      return !значок || !значок[1] || !п.состояние.test(значок[1]);
    }).map((п) => п.имя);
    expect(`значок постоянный у: ${плохо.join(' ') || 'нет'}`).toBe('значок постоянный у: нет');
  });

  it('🔴 ЗАЛИВКА зависит от состояния: переключатель передаёт его в `active`', () => {
    const плохо = ПЕРЕКЛЮЧАТЕЛИ.filter((п) => {
      const б = кнопка(п.имя);
      const активен = /active=\{([^}]*)\}/.exec(б);
      return !/<GameAuxAction/.test(б) || !активен || !п.состояние.test(активен[1] ?? '');
    }).map((п) => п.имя);
    expect(`состояние не доходит до заливки у: ${плохо.join(' ') || 'нет'}`).toBe('состояние не доходит до заливки у: нет');
  });

  it('🔴 включённый значок — ЗАЛИТАЯ кнопка и белый значок, а не оттенок; скринридер слышит selected', () => {
    expect(`заливка по состоянию: ${/backgroundColor: включён \? заливка : colors\.surface/.test(ЗНАЧОК)}`)
      .toBe('заливка по состоянию: true');
    expect(`белый значок по состоянию: ${/color=\{включён \? '#FFF'/.test(ЗНАЧОК)}`)
      .toBe('белый значок по состоянию: true');
    expect(`selected в доступности у переключателя: ${/active === undefined \? \{[^}]*\} : \{[^}]*selected: включён/.test(ЗНАЧОК)}`).toBe('selected в доступности у переключателя: true');
  });

  it('🔴 включённый режим не раздвигает ряд: подсказка режима — в строке над доской, а не в ряду кнопок', () => {
    /**
     * Замер 16.09.2026, окно 390×900: строка `sudokuPencilHint` появлялась ВНУТРИ блока кнопок и растягивала
     * его до 532 при родителе 390 — «Цвет» кончался на 152 точки за краем. С 17.09.2026 блок кнопок —
     * `GameAuxBar` каркаса из четырёх значков, а объяснение режима живёт в строке над доской (фокус `pencil`).
     */
    const i = ЭКРАН.indexOf('const hintEl =');
    expect(`ряд кнопок найден: ${i >= 0}`).toBe('ряд кнопок найден: true');
    const ряд = ЭКРАН.slice(i, ЭКРАН.indexOf(';', i));
    expect(`ряд — GameAuxBar: ${/<GameAuxBar>/.test(ряд)}`).toBe('ряд — GameAuxBar: true');
    expect(`подсказка карандаша внутри ряда: ${/sudokuPencilHint/.test(ряд)}`).toBe('подсказка карандаша внутри ряда: false');
    expect(`фокус карандаша у строки над доской: ${/pencil \? \{ kind: 'pencil' \}/.test(ЭКРАН)}`).toBe('фокус карандаша у строки над доской: true');
  });
});
