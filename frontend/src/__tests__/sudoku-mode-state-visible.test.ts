declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');

const ЭКРАН = fs.readFileSync(path.join(__dirname, '../../app/games/sudoku.tsx'), 'utf8') as string;

/** Кусок разметки одной кнопки — от её объявления до закрывающей скобки. */
function кнопка(имя: string): string {
  const i = ЭКРАН.indexOf(`const ${имя} = (`);
  if (i < 0) return '';
  return ЭКРАН.slice(i, ЭКРАН.indexOf('/>', i) + 2);
}

const ПЕРЕКЛЮЧАТЕЛИ: { имя: string; состояние: RegExp }[] = [
  { имя: 'pencilBtn', состояние: /pencil\b/ },
  { имя: 'paintBtn', состояние: /paintColor/ },
];

describe('состояние режима видно не только цветом', () => {
  it('есть что мерить — обе кнопки на месте', () => {
    const пустые = ПЕРЕКЛЮЧАТЕЛИ.filter((п) => кнопка(п.имя).length === 0).map((п) => п.имя);
    expect(`не найдены: ${пустые.join(' ') || 'нет'}`).toBe('не найдены: нет');
  });

  it('🔴 ЗНАЧОК зависит от состояния, а не постоянный', () => {
    const плохо = ПЕРЕКЛЮЧАТЕЛИ.filter((п) => {
      const б = кнопка(п.имя);
      const значок = /icon=\{([^}]*)\}|icon="([^"]*)"/.exec(б);
      return !значок || !значок[1] || !п.состояние.test(значок[1]);
    }).map((п) => п.имя);
    expect(`значок постоянный у: ${плохо.join(' ') || 'нет'}`).toBe('значок постоянный у: нет');
  });

  it('🔴 ПОДПИСЬ зависит от состояния, а не постоянная', () => {
    const плохо = ПЕРЕКЛЮЧАТЕЛИ.filter((п) => {
      const б = кнопка(п.имя);
      const подпись = /label=\{([^}]*(?:\}[^}]*)*)\}/.exec(б);
      return !подпись || !/включено\(/.test(подпись[1] ?? '');
    }).map((п) => п.имя);
    expect(`подпись постоянная у: ${плохо.join(' ') || 'нет'}`).toBe('подпись постоянная у: нет');
  });

  it('🔴 признак включённого — видимый знак, а не пробел', () => {
    const м = /const включено = \(вкл: boolean, слово: string\): string => \(вкл \? `([^`]*)\$\{слово\}`/.exec(ЭКРАН);
    expect(`приставка найдена: ${м ? 'да' : 'нет'}`).toBe('приставка найдена: да');
    expect(`приставка не пуста: ${((м?.[1] ?? '').trim().length > 0)}`).toBe('приставка не пуста: true');
  });
});
