/**
 * 🔴 ЗАПРОС К APP STORE CONNECT ОБЯЗАН ПЕРЕЖИВАТЬ ПУСТОЙ ОТВЕТ.
 *
 * Сборка v2.34.0 упала на шаге «Сертификат и профиль»: Apple отвечает на `DELETE`
 * кодом 204 БЕЗ ТЕЛА, а `запрос()` звал `json.loads` безусловно —
 * `JSONDecodeError: Expecting value: line 1 column 1`.
 *
 * Дефект прятался за состоянием чужого аккаунта: пока профиля с нужным именем не
 * существовало, ветка удаления не выполнялась, и живой прогон 02.09.2026 прошёл
 * зелёным. То есть проверить это можно только чтением кода — потому гейт и здесь,
 * а не в виде прогона.
 *
 * ⚠️ Проверяем СМЫСЛ: разбор JSON не должен стоять на пути ответа, у которого тела
 * может не быть. Признак — выход из функции до разбора, когда тело пустое.
 */
declare const __dirname: string;
declare function require(id: string): any;

const fs = require('fs');
const path = require('path');
const ФАЙЛ = path.join(__dirname, '../../../scripts/ios-provision.py');

describe('скрипт подписи iOS переживает ответ без тела', () => {
  const src: string = fs.existsSync(ФАЙЛ) ? fs.readFileSync(ФАЙЛ, 'utf8') : '';

  it('есть что проверять — скрипт на месте', () => {
    expect(`скрипт найден: ${src.length > 500}`).toBe('скрипт найден: true');
    expect(src).toContain('def запрос');
  });

  it('🔴 пустое тело возвращается пустым словарём, а не идёт в json.loads', () => {
    const тело = /def запрос[\s\S]*?\n\ndef /.exec(src)?.[0] ?? src;
    // есть ранний выход на пустом теле
    const ранний = /if not [^\n]*\.strip\(\):\s*\n\s*return \{\}/.test(тело);
    expect(`ранний выход на пустом теле: ${ранний}`).toBe('ранний выход на пустом теле: true');
    // и разбор идёт ПОСЛЕ этой проверки
    const iПроверка = тело.search(/if not [^\n]*\.strip\(\):/);
    const iРазбор = тело.lastIndexOf('json.loads');
    expect(`разбор после проверки: ${iПроверка >= 0 && iРазбор > iПроверка}`)
      .toBe('разбор после проверки: true');
  });

  it('🔴 старые сертификаты отзываются: лимит аккаунта конечен', () => {
    expect(src).toContain("запрос(tok, 'DELETE', f\"/certificates/");
  });
});
