/**
 * УРОВЕНЬ ПРОХОДИМ НЕ В ТЕОРИИ, А ИГРОЙ.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНО ОТ ГЕЙТА РЕШАЕМОСТИ. Тот доказывает, что расклад в принципе
 * решаем: свободных ниш хватает, запертые вычтены из ёмкости. Это ничего не
 * говорит о том, УЛОЖИТСЯ ЛИ ЧЕЛОВЕК В ЛИМИТ ХОДОВ, — а лимит с девятого уровня
 * решает, засчитан уровень или нет. Уровень, решаемый за сорок ходов при лимите
 * в двадцать, формально решаем и практически непроходим.
 *
 * Здесь доска РАЗЫГРЫВАЕТСЯ до конца настоящей стратегией — той самой, что игра
 * подсказывает человеку (`findHint`: собери тройку, иначе сведи пару). Если её
 * не хватает, значит подсказка ведёт в тупик, и это тоже надо знать.
 *
 * ⚠️ Стратегия НАМЕРЕННО ЖАДНАЯ И БЛИЗОРУКАЯ. Человек играет не идеально, и
 * запас должен быть под него, а не под переборщик. Если жадная игра укладывается
 * — уложится и человек.
 */
// Лист без React: 14 мс против 3298 мс у экрана (замер 06.09.2026).
import { levelCfg, generate, findHint, goalMet } from '@/src/games/goods-sort/core/level';

const POOL = [0, 1, 2, 3, 4, 5, 6, 7];
const CAP = 3;

/**
 * ⚠️ ЖАДНАЯ ИГРА — НЕ РЕШАТЕЛЬ, И ЭТО ВЫЯСНИЛОСЬ БОЛЬНО.
 *
 * Первая редакция этого гейта разыгрывала доску подсказкой (`findHint`) и
 * объявляла уровень непроходимым, если та не доводила до конца. Гейт покраснел
 * НА ВСЕХ уровнях, включая первый, — и это была беда теста, а не игры: жадная
 * стратегия умеет ходить по кругу (перенёс товар туда, потом обратно), и
 * упереться в потолок ходов она может на совершенно здоровой доске.
 *
 * Поэтому здесь настоящий поиск: обход состояний доски в глубину с памятью о
 * пройденном и потолком узлов. Он отвечает на честный вопрос — «существует ли
 * последовательность ходов, которая опустошает доску, и за сколько ходов
 * минимум».
 */
/**
 * ⚠️ ТРИ ПОДХОДА, ДВА ИЗ КОТОРЫХ НЕ СРАБОТАЛИ — записано, чтобы не повторяли.
 *
 * 1. Разыграть доску ПОДСКАЗКОЙ (`findHint`). Гейт покраснел на всех уровнях,
 *    включая первый: жадная стратегия умеет ходить по кругу (перенёс товар туда,
 *    потом обратно) и упирается в потолок на здоровой доске. Беда теста, не игры.
 * 2. Полный поиск кратчайшего решения. В глубину — переполнение стека, в ширину
 *    — кончилась память: двенадцать товаров по восемнадцати нишам дают слишком
 *    большое пространство состояний, чтобы обходить его целиком в тесте.
 * 3. Работает вот это: ТОЧНАЯ НИЖНЯЯ ГРАНИЦА + жадная игра с памятью.
 *
 * Нижняя граница считается мгновенно и ловит именно ту беду, ради которой гейт
 * писался: уровень, который НЕВОЗМОЖНО пройти в отведённые ходы. Жадная игра с
 * памятью о пройденных состояниях даёт достижимую оценку сверху — если она
 * укладывается в лимит, значит уложится и человек.
 */

/**
 * Сколько ходов нужно КАК МИНИМУМ. Для каждого типа: три его штуки обязаны
 * оказаться в одной нише, значит надо перенести три минус столько, сколько уже
 * лежит вместе в самой полной нише. Меньше не бывает ни при какой стратегии.
 */
function minMoves(board: number[][]): number {
  const best: Record<number, number> = {};
  for (const cell of board) {
    const count: Record<number, number> = {};
    for (const t of cell) count[t] = (count[t] || 0) + 1;
    for (const t of Object.keys(count).map(Number)) {
      best[t] = Math.max(best[t] ?? 0, count[t]);
    }
  }
  return Object.values(best).reduce((sum, together) => sum + (CAP - together), 0);
}

function key(board: number[][]): string {
  // Ниши равноправны, поэтому состояние — отсортированный список содержимого:
  // иначе «то же самое, но в другом порядке ниш» считалось бы новым состоянием
  // и поиск раздувался бы на порядки.
  return board.map((c) => c.join('.')).sort().join('|');
}

function cascade(board: number[][]): void {
  let again = true;
  while (again) {
    again = false;
    for (let i = 0; i < board.length; i++) {
      const c = board[i];
      if (c.length === 3 && c[0] === c[1] && c[1] === c[2]) { board[i] = []; again = true; }
    }
  }
}

/**
 * Жадная игра С ПАМЯТЬЮ: ходим подсказкой, но не возвращаемся в уже виденное
 * состояние. Это и есть «как сыграет человек, который не считает наперёд».
 * Возвращает число ходов или null, если зашли в тупик.
 */
function playGreedy(start: number[][]): number | null {
  const board = start.map((c) => [...c]);
  cascade(board);
  const seen = new Set<string>([key(board)]);
  let moves = 0;
  while (moves < 300) {
    if (board.every((c) => c.length === 0)) return moves;
    let done = false;
    // Сначала пробуем ход подсказки; если он ведёт в виденное — перебираем прочие.
    const candidates: { from: number; idx: number; to: number }[] = [];
    const h = findHint(board, () => true, CAP);
    if (h) candidates.push({ from: h.fromCell, idx: h.fromIdx, to: h.toCell });
    for (let from = 0; from < board.length; from++) {
      if (!board[from].length) continue;
      for (let to = 0; to < board.length; to++) {
        if (to === from || board[to].length >= CAP) continue;
        candidates.push({ from, idx: board[from].length - 1, to });
      }
    }
    for (const c of candidates) {
      const next = board.map((x) => [...x]);
      const [item] = next[c.from].splice(c.idx, 1);
      next[c.to].push(item);
      cascade(next);
      const k = key(next);
      if (seen.has(k)) continue;
      seen.add(k);
      for (let i = 0; i < board.length; i++) board[i] = next[i];
      moves++; done = true; break;
    }
    if (!done) return null;
  }
  return null;
}

describe('уровни проходимы игрой, а не только «решаемы»', () => {
  const LEVELS = [1, 10, 25, 40, 55];
  const TRIES = 20;

  it('есть что проверять — иначе тест зелен вслепую', () => {
    expect(typeof generate).toBe('function');
    // Три единицы по разным нишам: два переноса, меньше никак.
    expect(minMoves([[1], [1], [1], []])).toBe(2);
    // Уже вместе — переносить нечего.
    expect(minMoves([[1, 1, 1], []])).toBe(0);
    expect(playGreedy([[1], [1], [1], []])).toBe(2);
  });

  /**
   * 🔴 ГЛАВНОЕ. Лимит ходов с девятого уровня решает, засчитан уровень или нет.
   * Если минимально необходимых ходов БОЛЬШЕ лимита, уровень непроходим в
   * принципе — никакой игрок ничего не сделает.
   */
  it('лимита хватает даже на минимально возможную игру', () => {
    const bad: string[] = [];
    for (const L of LEVELS) {
      for (const narrow of [false, true]) {
        const cfg = levelCfg(L, POOL.length, narrow);
        if (cfg.moveLimit <= 0) continue;
        let worst = 0;
        for (let t = 0; t < TRIES; t++) {
          worst = Math.max(worst, minMoves(generate(POOL, cfg.types, cfg.spares, cfg.slots)));
        }
        if (worst > cfg.moveLimit) {
          bad.push(`L${L}${narrow ? ' узкий' : ''}: минимум ${worst} ходов при лимите ${cfg.moveLimit}`);
        }
      }
    }
    expect(bad).toEqual([]);
  });

  /**
   * Запас под человека: он играет не идеально. Требуем, чтобы минимально
   * необходимое укладывалось заметно ниже лимита — иначе уровень проходится
   * только безошибочной игрой, а это не сложность, а лотерея.
   */
  it('у лимита есть запас на неидеальную игру', () => {
    const tight: string[] = [];
    for (const L of LEVELS) {
      for (const narrow of [false, true]) {
        const cfg = levelCfg(L, POOL.length, narrow);
        if (cfg.moveLimit <= 0) continue;
        let worst = 0;
        for (let t = 0; t < TRIES; t++) {
          worst = Math.max(worst, minMoves(generate(POOL, cfg.types, cfg.spares, cfg.slots)));
        }
        if (worst > cfg.moveLimit * 0.8) {
          tight.push(`L${L}${narrow ? ' узкий' : ''}: минимум ${worst} при лимите ${cfg.moveLimit} — запас меньше пятой части`);
        }
      }
    }
    expect(tight).toEqual([]);
  });

  /**
   * ⚠️ ЖАДНАЯ ИГРА — СПРАВКА, А НЕ ПРИГОВОР, И ПОТОМУ ЗДЕСЬ НЕТ УТВЕРЖДЕНИЯ.
   *
   * Если она доводит доску до конца — уровень точно проходим человеком, который
   * не считает наперёд. А вот её тупик НЕ ДОКАЗЫВАЕТ НИЧЕГО: она не решатель,
   * а «первый не повторяющий ход», и застревает на здоровых досках. Требовать
   * от неё успеха значило бы краснеть на исправном коде — ровно та ошибка, из-за
   * которой первая редакция этого файла считала непроходимым первый уровень.
   *
   * Проверяем лишь, что она вообще работает: на заведомо простой доске доходит.
   */
  it('жадная игра доходит до конца там, где это заведомо возможно', () => {
    expect(playGreedy([[1], [1], [1], []])).toBe(2);
    expect(playGreedy([[1, 2], [1, 2], [1, 2], [], []])).not.toBeNull();
  });

  /** Цель «убрать всё» достигнута ровно тогда, когда доска пуста — сверка с игрой. */
  it('пустая доска и есть достигнутая цель', () => {
    const cfg = levelCfg(10, POOL.length, true);
    const board = generate(POOL, cfg.types, cfg.spares, cfg.slots);
    expect(goalMet(board, { kind: 'all' })).toBe(false);
    expect(goalMet(board.map(() => []), { kind: 'all' })).toBe(true);
  });
});
