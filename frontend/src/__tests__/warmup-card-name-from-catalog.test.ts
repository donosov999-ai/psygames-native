/**
 * ИМЯ ИГРЫ НА КАРТОЧКЕ ЗАРЯДКИ БЕРЁТСЯ ИЗ КАТАЛОГА — У КАЖДОЙ ИГРЫ, А НЕ У МОИХ.
 *
 * 🔴 ПОВОД. 08.09.2026 в `WarmupCard` стояло `t(game_id)`, и работало это ровно
 * у тех игр, где `id` случайно совпал с ключом словаря. У остальных строка
 * состава показывала человеку сырой идентификатор с подчёркиваниями
 * (`vocab_srs`, `semantic_sort`, `chess_blind`, `scholars_mate`). В шахматной и
 * словесной карточках это висело с 06.09 и заметили только на третьей —
 * языковой. Починка в `имяИгры` общая, а сторожила её до сих пор только проба
 * языкового раздела (`language-flow.test.ts`), то есть ровно тот случай, где
 * дефект И ТАК заметили.
 *
 * 📍 ЗАМЕР 11.09.2026, почему это стоит гейта на ВЕСЬ каталог:
 *   игр в каталоге                       99
 *   у которых `id` совпадает с `nameKey` 29
 *   🔴 у которых РАСХОДЯТСЯ               70
 * То есть под старым способом сырой идентификатор показывался бы у семидесяти
 * игр из девяноста девяти. Совпадение у оставшихся двадцати девяти — случайность
 * именования, а не правило, и полагаться на неё нельзя.
 *
 * ⚠️ ЭТО ПРОБА ОБЩЕГО СЛОЯ, НО ЧИСТО ДОБАВОЧНАЯ: поведение она не меняет, только
 * закрепляет уже верное. Заведена разделом «Языки» (пункт 11 его очереди), потому
 * что дефект нашли здесь, а функция общая для всех зарядок.
 */
import { имяИгры } from '@/src/components/WarmupCard';
import { GAMES } from '@/src/constants/games';

/** Резолвер-тождество: возвращает сам ключ, поэтому в ответе видно, ЧТО спросили. */
const ключКакЕсть = (k: string) => k;

describe('имя игры на карточке зарядки', () => {
  it('есть что проверять: каталог непустой и расхождение id/nameKey массовое', () => {
    expect(GAMES.length).toBeGreaterThan(50);
    const расходятся = (GAMES as any[]).filter((g) => g.id !== g.nameKey).length;
    expect(`расходятся ${расходятся > 50}`).toBe('расходятся true');
  });

  it('🔴 у КАЖДОЙ игры каталога имя приходит из nameKey, а не из id', () => {
    const плохо = (GAMES as any[])
      .filter((g) => имяИгры(g.id, ключКакЕсть) !== g.nameKey)
      .map((g) => `${g.id} → ${имяИгры(g.id, ключКакЕсть)} (ждали ${g.nameKey})`);
    expect(плохо.slice(0, 5)).toEqual([]);
  });

  /**
   * Подчёркивание в имени — признак того, что на экран уехал идентификатор.
   * Проверяется отдельно от предыдущей: там сверка с `nameKey`, здесь — с тем,
   * что человек УВИДИТ, даже если `nameKey` однажды заведут с подчёркиванием.
   */
  it('🔴 ни одно имя не содержит подчёркивания', () => {
    const сырые = (GAMES as any[])
      .filter((g) => имяИгры(g.id, ключКакЕсть).includes('_'))
      .map((g) => g.id);
    expect(сырые.slice(0, 5)).toEqual([]);
  });

  /**
   * ⚠️ Фолбэк на сам `id` — решение, а не недосмотр: игра могла уехать из
   * каталога, и пустая строка состава хуже некрасивой (так написано в
   * `WarmupCard.tsx`). Закрепляем, чтобы «починка» его не убрала.
   */
  it('незнакомый id возвращается как есть — фолбэк сознательный', () => {
    expect(имяИгры('нет_такой_игры', ключКакЕсть)).toBe('нет_такой_игры');
  });

  it('проба не зелена вслепую: словарь без перевода роняет имя на id', () => {
    const пустой = () => '';
    const g = (GAMES as any[])[0]!;
    expect(`${g.id} → ${имяИгры(g.id, пустой)}`).toBe(`${g.id} → ${g.id}`);
  });
});
