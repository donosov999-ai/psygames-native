/**
 * 🔴 ТРЕТЬЯ ОСЬ ПЕРЕКЛЮЧЕНИЯ ЗАДАЧ: ПЛОТНОСТЬ ПОМЕХ ВОКРУГ СТИМУЛА.
 *
 * ПОВОД. Замер лестниц раздела 10.09.2026: у этой пробы нагрузка росла ×4,0 при
 * ДВУХ осях — беднее всех десяти. Расти дальше было нечем.
 *
 * ⚠️ ГЛАВНОЕ, ЧТО СТЕРЕЖЁТСЯ ЗДЕСЬ, — НЕ РОСТ, А НЕЙТРАЛЬНОСТЬ.
 * Мера прохода этой пробы — РАЗНОСТЬ: `switch_cost_ms` = RT(смена) − RT(повтор).
 * Любая ось, которая действует на смены и повторы ПО-РАЗНОМУ, попадает прямо в
 * эту разность и портит её. Именно поэтому отвергнуты три очевидные оси:
 * интервал подготовки, предсказуемость чередования и третья задача — разбор в
 * шапке `DECOY_GLYPHS`.
 * Помехи годятся ровно тем, что они свойство СТИМУЛА, а не перехода: удлиняют
 * обе половины разности одинаково и из неё сокращаются. Проба ниже это и мерит.
 */
import { levelParams, levelCondition, makeTrial } from '@/app/games/switching-task';
import { switchingLoad } from '@/src/games/attention/load';

const УРОВНИ = Array.from({ length: 15 }, (_, i) => i + 1);
const N = 6000;

/** Прогон настоящего потока проб: следующая задача зависит от предыдущей. */
function поток(level: number, n = N) {
  let last: number | null = null;
  const смены: number[] = [], повторы: number[] = [];
  const всеЗнаки: string[] = [];
  for (let i = 0; i < n; i++) {
    const t = makeTrial('mix', level, last);
    last = t.taskIdx;
    всеЗнаки.push(...t.decoys);
    (t.isSwitch ? смены : повторы).push(t.decoys.length);
  }
  const среднее = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
  return { смены: среднее(смены), повторы: среднее(повторы), знаки: всеЗнаки, сменПроб: смены.length };
}

describe('переключение задач: помехи вокруг стимула', () => {
  it('есть что проверять — иначе набор зелен вслепую', () => {
    expect(`поле помех: ${'decoys' in levelParams(15)}`).toBe('поле помех: true');
    expect(поток(15, 200).знаки.length).toBeGreaterThan(0);
  });

  /**
   * 🔴 САМАЯ ВАЖНАЯ ПРОБА ФАЙЛА. Помех обязано быть поровну на сменах и
   * повторах — иначе ось попадёт в измеряемую разность.
   */
  it('🔴 помехи не различают смену и повтор — иначе ось потечёт в switch_cost', () => {
    const мимо: string[] = [];
    for (const L of [5, 10, 15]) {
      const r = поток(L);
      if (r.сменПроб < 100) { мимо.push(`L${L}: смен всего ${r.сменПроб} — мерить не на чем`); continue; }
      if (Math.abs(r.смены - r.повторы) > 0.001) {
        мимо.push(`L${L}: на сменах ${r.смены.toFixed(3)}, на повторах ${r.повторы.toFixed(3)}`);
      }
    }
    expect(мимо).toEqual([]);
  });

  /**
   * 🔴 Знак-помеха не должен быть буквой или цифрой: и то и другое «афиширует»
   * одну из двух задач и добавляет к пробе смысловой конфликт вместо чистого
   * перцептивного — то есть снова меняет саму разность.
   */
  it('🔴 ни одна помеха не является буквой или цифрой', () => {
    const плохие = [...new Set(поток(15).знаки)].filter((g) => /[0-9a-zA-Zа-яА-Я]/.test(g));
    expect(`знаки, афиширующие задачу: ${плохие.join(', ') || '—'}`)
      .toBe('знаки, афиширующие задачу: —');
  });

  it('🔴 число помех в раздаче совпадает с объявленным на каждом уровне', () => {
    const мимо: string[] = [];
    for (const L of УРОВНИ) {
      const ждём = levelParams(L).decoys;
      let last: number | null = null;
      for (let i = 0; i < 300; i++) {
        const t = makeTrial('num2', L, last); last = t.taskIdx;
        if (t.decoys.length !== ждём) { мимо.push(`L${L}: ждали ${ждём}, в раздаче ${t.decoys.length}`); break; }
      }
    }
    expect(мимо).toEqual([]);
  });

  it('лестница помех растёт и доходит до предела; первые ступени чисты', () => {
    const ряд = УРОВНИ.map((L) => levelParams(L).decoys);
    expect(ряд.filter((v, i) => i > 0 && v < ряд[i - 1])).toEqual([]);
    expect(`L1 ${ряд[0]} · L15 ${ряд[14]} · разных значений ${new Set(ряд).size}`)
      .toBe('L1 0 · L15 4 · разных значений 3');
  });

  /**
   * 🔴 Мера уровня обязана ВИДЕТЬ помехи. L3 и L4 отличаются только ими и окном
   * (объём там одинаков), значит отношение нагрузок равно отношению окон,
   * умноженному на шаг помех.
   * ⚠️ Шаг 1.5 стоит ЧИСЛОМ, а не импортом из проверяемого модуля: импорт двигал
   * бы обе стороны разом и проба ослепла бы.
   */
  it('🔴 мера уровня учитывает помехи, а не только окно и объём', () => {
    const p3 = levelParams(3), p4 = levelParams(4);
    expect(`объём одинаков: ${p3.trials === p4.trials}`).toBe('объём одинаков: true');
    expect(`помехи ${p3.decoys} → ${p4.decoys}`).toBe('помехи 0 → 2');
    const ждём = (p3.windowMs / p4.windowMs) * 1.5;
    const факт = switchingLoad(4) / switchingLoad(3);
    expect(`${факт.toFixed(3)}`).toBe(`${ждём.toFixed(3)}`);
  });

  it('условие партии несёт помехи — иначе два прохода несравнимы', () => {
    expect(Object.keys(levelCondition(1))).toContain('decoys');
    expect(levelCondition(15).decoys).toBe(levelParams(15).decoys);
  });
});
