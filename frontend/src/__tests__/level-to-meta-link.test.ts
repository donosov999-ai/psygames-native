declare const __dirname: string;
declare function require(id: string): any;

const fs = require('fs');
const path = require('path');
const src: string = fs.readFileSync(
  path.join(__dirname, '../components/LevelCleared.tsx'), 'utf8',
);

describe('партия связана с копилкой', () => {
  it('есть что проверять: блок начисления на месте', () => {
    expect(src).toContain('earnBadge');
    expect(src).toContain('earn?.total');
  });

  it('🔴 итог копилки показан рядом с начислением', () => {
    const at = src.indexOf('earnBadge');
    const блок = src.slice(at, at + 1400);
    expect(`итог показан: ${/баланс/.test(блок)}`).toBe('итог показан: true');
  });

  it('🔴 итог берётся из кошелька, а не складывается на экране', () => {
    expect(src).toContain('getTokens');
    // нет самодельной арифметики вида «баланс + earn.total»
    const самодел = /setБаланс\([^)]*earn[^)]*\+|\+\s*\(?earn\?\.total/.test(src);
    expect(`самодельная арифметика: ${самодел}`).toBe('самодельная арифметика: false');
  });
});
