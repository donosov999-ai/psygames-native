/**
 * 🔴 ОСЬ 7 — СХОДСТВО. Отвлекающие слова подбираются ПОХОЖИМИ на услышанные.
 *
 * ЗАЧЕМ. Объём кончился на L9 (span=8 — потолок слухового охвата), скорость на дне
 * (gapMs=500). Ось 3 (задержка) уже введена; вторая ось — фонологическое сходство:
 * похожие слова труднее удержать раздельно, и это классика памяти на слух.
 *
 * ⚠️ МЕНЯЕТСЯ НЕ ТО, ЧТО ЗВУЧИТ, А ТО, СРЕДИ ЧЕГО ИЩУТ. Озвученные слова остаются
 * случайными и свежими; похожими становятся ЛИШНИЕ слова в сетке. Подменять сами
 * озвученные значило бы менять пробу, а не её трудность.
 */
import { levelParams, LSPAN_VOLUME_TOP, похожесть, подобратьОтвлекающие } from '@/app/games/listening-span';

const ПУЛ = ['casa', 'cama', 'copa', 'boca', 'mesa', 'mano', 'perro', 'pero', 'gato', 'pato', 'luz', 'cruz', 'sol', 'col', 'mar', 'par'];

describe('listening-span: похожие отвлекающие', () => {
  it('мера сходства ведёт себя как мера: сама с собой 1, разные — меньше', () => {
    expect(похожесть('casa', 'casa')).toBe(1);
    expect(похожесть('casa', 'cama')).toBeGreaterThan(похожесть('casa', 'perro'));
    expect(похожесть('', 'casa')).toBe(0);
  });

  it('ниже плато доля нулевая — прежняя полоса не тронута', () => {
    for (let L = 1; L <= LSPAN_VOLUME_TOP; L++) {
      expect(`L${L} доля=${levelParams(L).similarShare}`).toBe(`L${L} доля=0`);
    }
  });

  it('🔴 выше плато доля растёт, пока не дойдёт до всех отвлекающих', () => {
    expect(levelParams(LSPAN_VOLUME_TOP + 1).similarShare).toBeCloseTo(0.1, 5);
    expect(levelParams(LSPAN_VOLUME_TOP + 10).similarShare).toBeCloseTo(1, 5);
    for (let L = LSPAN_VOLUME_TOP + 1; L <= LSPAN_VOLUME_TOP + 10; L++) {
      expect(`L${L}: ${levelParams(L).similarShare > levelParams(L - 1).similarShare}`).toBe(`L${L}: true`);
    }
  });

  /**
   * 🔴 ГЛАВНОЕ И САМОЕ ЛОМКОЕ: слово не может быть и услышанным, и лишним.
   * Иначе у задачи нет однозначного ответа, и проба перестаёт мерить вообще.
   */
  it('🔴 отвлекающие никогда не пересекаются с озвученными', () => {
    const озвучено = ['casa', 'perro', 'mar'];
    for (const доля of [0, 0.5, 1]) {
      const d = подобратьОтвлекающие(ПУЛ, озвучено, 3, доля);
      expect(`доля ${доля}: пересечений ${d.filter((w) => озвучено.includes(w)).length}`)
        .toBe(`доля ${доля}: пересечений 0`);
      expect(`доля ${доля}: набрано ${d.length}`).toBe(`доля ${доля}: набрано 3`);
    }
  });

  it('🔴 при доле 1 отвлекающие ДЕЙСТВИТЕЛЬНО ближе, чем при доле 0', () => {
    const озвучено = ['casa', 'perro', 'mar'];
    const близость = (ws: string[]) =>
      ws.reduce((s, w) => s + Math.max(...озвучено.map((t) => похожесть(w, t))), 0) / ws.length;
    const похожие = близость(подобратьОтвлекающие(ПУЛ, озвучено, 3, 1));
    // при доле 0 порядок случайный — берём среднее по многим прогонам, иначе замер шумит
    let случайные = 0;
    for (let i = 0; i < 40; i++) случайные += близость(подобратьОтвлекающие(ПУЛ, озвучено, 3, 0));
    случайные /= 40;
    expect(`похожие ${похожие > случайные}`).toBe('похожие true');
  });
});
