/**
 * УРОВЕНЬ НЕ ТРЕБУЕТ СТУПЕНИ, КОТОРУЮ ЕГО ВАРИАНТ НЕ ВЫДАЁТ.
 *
 * 🔴 ЧТО БЫЛО. Полоса верхних уровней (38+) требовала у ВСЕХ двенадцати вариантов
 * одного и того же — ровно шестую ступень на последней ступеньке. Замер 26.08.2026
 * по последнему уровню каждой полосы (8 досок, бюджет 6000 мс — втрое больше
 * боевых, цель снята, просили максимум):
 *   сэндвич     4×8            — четвёрка ВОСЕМЬ РАЗ ИЗ ВОСЬМИ, шестёрки нет
 *   стрелка     3×1 4×4 5×3    — шестёрки нет
 *   термоклетка 3×2 4×4 5×2    — шестёрки нет
 *   термометр   4×6 5×1 6×1    — шестёрка 1 раз из 8
 *   джигсо      2×1 3×3 4×2 5×1 6×1 — 1 раз из 8
 * Три полосы из двенадцати обещали недостижимое, ещё две — почти недостижимое.
 * Видимое следствие: сборщик тратил все заходы впустую и отдавал что получилось,
 * а уровни переставали отличаться друг от друга.
 *
 * ⚠️ ЭТО НЕ «ОПУСТИЛИ ПЛАНКУ». Опущен только ПОЛ — «мимо, пересобери». Потолок
 * («слишком сложно, отвергни») остался прежним, поэтому редкая трудная доска
 * по-прежнему принимается: замер после правки показал шестёрки у термометра и
 * джигсо, и они засчитаны, а не выброшены.
 *
 * ⚠️ ПОЧЕМУ ГЕЙТ НЕ ГОНЯЕТ ГЕНЕРАТОР. Достижимость ступени — величина
 * вероятностная, и проверка «собери доску шестой ступени» была бы шаткой по
 * построению: она краснела бы от невезения, а не от поломки. Поэтому здесь
 * сторожится УСТРОЙСТВО: объявленный пол каждого уровня не выше потолка своего
 * варианта. Числа потолков живут в `sudoku-grade.ts` и снабжены раскладками
 * замера; сам замер повторяется руками, когда меняется генератор.
 */
import { targetTier, effectiveBand } from '@/src/services/sudoku-grade';
import { levelConfig } from '@/src/services/sudoku-core';

/**
 * Потолки, замеренные 26.08.2026 — КОПИЯ, а не импорт, и это нарочно.
 * Гейт, читающий ту же таблицу, что и код, доказывал бы лишь «таблица равна себе».
 * Здесь она выписана заново из распечатки замера, поэтому расхождение кода с
 * замером станет красным.
 */
const MEASURED_CEILING: Record<string, number> = {
  diagonal: 5, antiknight: 6, hyper: 4, nonconsec: 4, antiking: 4,
  evenodd: 4, kropki: 5, sandwich: 4, thermo: 5, arrow: 5,
  /**
   * jigsaw 5 → 6, распечатка замера 27.08.2026 (боевой бюджет 1100 мс, L53,
   * 20 досок, ПОСЛЕ появления liftByClueRemoval):
   *   тиры [4,4,5,6,6,5,4,6,5,5,6,4,6,4,6,4,4,6,4,4] — шестёрок 7 из 20.
   * Критерий словаря «хотя бы две доски» выполнен с запасом; до подъёма
   * снятием подсказок шестёрка была 2/20 и потолок честно стоял на 5.
   */
  jigsaw: 6, thermocage: 5,
  /**
   * КОМБО-ПОЯС 81–92 — ВПИСАН 16.09.2026. До этого его здесь НЕ БЫЛО, а проба ниже
   * пропускала вариант без потолка молча (`continue`), и двенадцать уровней не
   * сторожил никто: LAST_LEVEL стоял 80.
   *
   * Распечатка БОЕВОГО замера (scripts/measure/combo-tiers-combat.measure.ts: путь
   * экрана — logicalBuilder, 2200 мс, runSteps, look; по 15 досок, два прогона):
   *   L81 thermoknight цель 4–5: 3×7 4×4 5×4 | 3×7 4×7 5×1 — в цели 8/15 и 8/15
   *   L83 thermoknight цель 4–5: 3×4 4×8 5×3 | 3×3 4×11 5×1 — 11/15 и 12/15
   *   L85 sandparity   цель 4–5: 4×15       | 4×15        — 15/15 и 15/15
   *   L87 sandparity   цель 4–5: 4×14 5×1   | 4×14 5×1    — 15/15 и 15/15
   *   L89 killerdiag   цель 4–5: 4×14 5×1   | 4×15        — 15/15 и 15/15
   *   L91 killerdiag   цель 4–5: 4×14 5×1   | 4×14 5×1    — 15/15 и 15/15
   * Потолок 5 по смыслу effectiveBand (27.08): потолок = «верх, который ПРИНИМАЕМ»,
   * пол держится ступенью ниже и обязан браться массово. Пятёрка достижима у всех
   * трёх (thermoknight 9/60, killerdiag 3/60, sandparity 2/60), четвёрка массова у
   * sandparity и killerdiag (60/60). Потолок 4 сделал бы полосу 3–4 и выбрасывал бы пятёрки.
   *
   * ⚠️ ОТКРЫТО: у thermoknight на ВХОДЕ пояса (L81) пол 4 не берётся почти в половине
   * досок — тройка 14/60 по двум прогонам на L81 и L83 вместе, 7/15 на самом L81.
   * Это не потолок, а слабость генератора пары термометр+антиконь; проба здесь
   * вероятностную величину не сторожит (см. шапку), число записано для починки.
   */
  thermoknight: 5, sandparity: 5, killerdiag: 5,
};

/** 27.08 стояло 80 — комбо-пояс 81..92 не сторожил никто (так же было в sudoku-ladder-monotonic). */
const LAST_LEVEL = 92;
const LEVELS = Array.from({ length: LAST_LEVEL }, (_, i) => i + 1);

describe('лестница судоку требует только достижимого', () => {
  it('есть что проверять — уровни, варианты и цели на месте', () => {
    const variants = new Set(LEVELS.map((l) => String(levelConfig(l).variant)));
    expect(variants.size).toBeGreaterThanOrEqual(12);
    const bands = new Set(LEVELS.map((l) => { const t = targetTier(l); return `${t.min}-${t.max}`; }));
    expect(bands.size).toBeGreaterThanOrEqual(5);   // полос несколько, а не одна на всех
  });

  it('🔴 у каждого варианта лестницы, кроме классики, ЕСТЬ замеренный потолок — пропуск молча запрещён', () => {
    /**
     * Проба ниже делала `if (ceiling === undefined) continue` — для классики это верно,
     * но так же молча проходил ЛЮБОЙ новый вариант, чей потолок не замерили. Ровно так
     * комбо-пояс 81–92 жил без сторожа с 29.08 по 16.09.2026.
     */
    const безПотолка = [...new Set(LEVELS.map((l) => String(levelConfig(l).variant)))]
      .filter((v) => v !== 'none' && MEASURED_CEILING[v] === undefined);
    expect(`вариантов без замеренного потолка: ${безПотолка.join(' ') || 'нет'}`).toBe('вариантов без замеренного потолка: нет');
  });

  it('🔴 объявленный ПОЛ уровня не выше потолка его варианта', () => {
    const bad: string[] = [];
    for (const lv of LEVELS) {
      const variant = String(levelConfig(lv).variant);
      const ceiling = MEASURED_CEILING[variant];
      if (ceiling === undefined) continue;          // классика: потолка не мерили
      const { min } = targetTier(lv);
      if (min > ceiling) bad.push(`L${lv} ${variant}: пол ${min} выше потолка ${ceiling}`);
    }
    expect(bad).toEqual([]);
  });

  it('🔴 верх полосы каждого варианта равен его потолку — редкая трудная доска принимается', () => {
    /**
     * ⚠️ ПЕРЕПИСАН 27.08.2026 вместе с уходом «пилы». Прежде тест требовал
     * СЫРОЙ targetTier(top).max === 6 на верхних уровнях блоков — это кодировало
     * пилу «каждый вариант дорастает до 6..6», которой больше нет: рамка
     * глобальная, а закон полосы — effectiveBand. Смысл теста сохранён и
     * усилен: на верхнем уровне своего блока каждый вариант обязан ПРИНИМАТЬ
     * свою самую трудную достижимую доску, то есть max эффективной полосы
     * равен замеренному потолку варианта, а не занижен рамкой.
     */
    for (const lv of [33, 37, 41, 45, 49, 53, 57, 84, 88, 92]) {   // + верх каждой комбо-пары
      const variant = String(levelConfig(lv).variant);
      const eff = effectiveBand(variant as never, targetTier(lv));
      const ceiling = MEASURED_CEILING[variant];
      if (ceiling === undefined) continue;
      expect(`L${lv} ${variant}: max ${eff.max}`).toBe(`L${lv} ${variant}: max ${Math.min(ceiling, targetTier(lv).max)}`);
      expect(eff.max).toBeGreaterThanOrEqual(Math.min(ceiling, 5));
    }
  });

  it('🔴 полоса остаётся полосой: пол не выше потолка внутри самой цели', () => {
    const bad: string[] = [];
    for (const lv of LEVELS) {
      const { min, max } = targetTier(lv);
      if (min > max) bad.push(`L${lv}: пол ${min} выше собственного потолка ${max}`);
      if (min < 1 || max > 9) bad.push(`L${lv}: полоса ${min}-${max} вне шкалы техник`);
    }
    expect(bad).toEqual([]);
  });

  it('🔴 сложность по лестнице не падает: пол каждого уровня не ниже предыдущего внутри своей фазы', () => {
    // Между фазами вариантов падение законно — новое правило само добавляет
    // трудности. А внутри одной фазы пол обязан только расти.
    const bad: string[] = [];
    for (let lv = 2; lv <= LAST_LEVEL; lv++) {
      if (String(levelConfig(lv).variant) !== String(levelConfig(lv - 1).variant)) continue;
      const prev = targetTier(lv - 1).min;
      const cur = targetTier(lv).min;
      if (cur < prev) bad.push(`L${lv}: пол ${cur} ниже, чем у L${lv - 1} (${prev})`);
    }
    expect(bad).toEqual([]);
  });
});
