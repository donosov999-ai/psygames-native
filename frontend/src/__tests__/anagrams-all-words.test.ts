/**
 * 🔴 РЕЖИМ «НАЙДИ ВСЕ СЛОВА» — ПРОВЕРЯЕМ НАБОРЫ ЧИСЛАМИ.
 *
 * Наборы собраны отдельными скриптами из внешних источников (`wordlist-build/`),
 * а значит могут молча испортиться при пересборке: не тот словарь, не та
 * кодировка, не тот отсев. Пробы держат ровно то, ради чего режим и делался.
 */
import {
  allWordsLocales, allWordsCount, allWordsPack, allWordsLetters,
  собираетсяИзПлиток, сдатьСлово, всёНайдено, подсказкаAllWords, allWordsНачат,
} from '@/src/games/anagrams/core/allWords';

describe('наборы «найди все слова»', () => {
  it('есть все восемь языков, и ни один не пустой', () => {
    /**
     * 🔴 СПИСОК ПРОВЕРЯЕТСЯ ЦЕЛИКОМ, А НЕ «ЕСТЬ ЛИ РУССКИЙ». Наборы подключаются
     * импортом; забыть строку в `НАБОРЫ` ничего не ломает — язык просто молча
     * получает английский набор. Такое видно только сверкой полного списка.
     *
     * ⚠️ Языков в приложении одиннадцать, наборов семь. Это разобрано замером по
     * каждой письменности (`WORDLIST_NONLATIN.md`), а не забыто: китайскому
     * механика не подходит по числу, остальным четырём нужна своя плитка и свой
     * источник. Появится набор — строка здесь обязана вырасти вместе с ним.
     */
    expect(allWordsLocales()).toEqual(['de', 'en', 'es', 'fr', 'it', 'ko', 'pt', 'ru']);
    const мало = allWordsLocales().filter((l) => allWordsCount(l) < 300);
    expect(`наборов меньше 300 раскладок: ${мало.join(', ')}`).toBe('наборов меньше 300 раскладок: ');
    expect(allWordsCount('en')).toBeGreaterThan(1000);
  });

  /**
   * ⚠️ ЯЗЫК БЕЗ НАБОРА ПОЛУЧАЕТ АНГЛИЙСКИЙ, А НЕ ПУСТОЙ ЭКРАН. Строка стоит
   * потому, что запасной путь `?? НАБОРЫ.en` — единственное, что отделяет
   * японца от режима без единой раскладки.
   */
  it('🔴 язык без своего набора получает английский, а не пустоту', () => {
    // ko с 06.09.2026 имеет свой набор — см. chamo.ts, поэтому здесь его больше нет
    for (const loc of ['ja', 'zh', 'ar', 'hi']) {
      expect(`${loc}: ${allWordsCount(loc)}`).toBe(`${loc}: ${allWordsCount('en')}`);
      expect(allWordsPack(loc, 1)).not.toBeNull();
    }
  });

  it('🔴 КАЖДОЕ слово раскладки собирается из букв базы', () => {
    // Ради этого режим и существует: несобираемая цель делает уровень
    // непроходимым, а заметно это только на ней самой.
    const плохо: string[] = [];
    for (const loc of allWordsLocales()) {
      for (let i = 1; i <= allWordsCount(loc); i++) {
        const p = allWordsPack(loc, i)!;
        for (const w of p.words) {
          if (!собираетсяИзПлиток(w, [...p.base])) плохо.push(`${loc} «${p.base}» ⊅ «${w}»`);
        }
      }
    }
    expect(плохо.slice(0, 5)).toEqual([]);
  });

  it('база длиной 7–8, целей 6…22, дублей нет, цель ≠ база', () => {
    const плохо: string[] = [];
    for (const loc of allWordsLocales()) {
      for (let i = 1; i <= allWordsCount(loc); i++) {
        const p = allWordsPack(loc, i)!;
        const n = [...p.base].length;
        if (n < 7 || n > 8) плохо.push(`${loc} «${p.base}»: база ${n} букв`);
        // ⚠️ ВЕРХ 22, А НЕ 14. С 06.09.2026 число слов — это ось сложности: сборщик
        // ведёт его от начала набора к концу (en 8→22, ru 10→18), потому что список
        // слов теперь прокручивается и «не влезает на экран» перестало ограничивать.
        if (p.words.length < 6 || p.words.length > 22) плохо.push(`${loc} «${p.base}»: целей ${p.words.length}`);
        if (new Set(p.words).size !== p.words.length) плохо.push(`${loc} «${p.base}»: дубль в целях`);
        if (p.words.indexOf(p.base) >= 0) плохо.push(`${loc} «${p.base}»: база среди целей`);
      }
    }
    expect(плохо.slice(0, 5)).toEqual([]);
  });

  it('уровень даёт ту же раскладку всегда, а набор идёт по кругу', () => {
    const a = allWordsPack('ru', 3)!;
    expect(allWordsPack('ru', 3)!.base).toBe(a.base);
    expect(allWordsPack('ru', 3 + allWordsCount('ru'))!.base).toBe(a.base);
  });

  it('неизвестный язык не роняет игру — отдаётся английский', () => {
    expect(allWordsPack('ja', 1)).not.toBeNull();
  });

  it('🔴 банк — это буквы базы, перемешанные, а НЕ другой состав', () => {
    for (const loc of allWordsLocales()) {
      for (const уровень of [1, 7, 42]) {
        const p = allWordsPack(loc, уровень)!;
        const банк = allWordsLetters(p, уровень);
        expect(банк.slice().sort().join('')).toBe([...p.base].sort().join(''));
        // И каждое слово собирается уже из БАНКА, а не только из базы.
        for (const w of p.words) expect(`${w}: ${собираетсяИзПлиток(w, банк)}`).toBe(`${w}: true`);
      }
    }
  });

  it('перемешивание детерминированно от уровня', () => {
    const p = allWordsPack('ru', 5)!;
    expect(allWordsLetters(p, 5).join('')).toBe(allWordsLetters(p, 5).join(''));
  });
});

describe('сдача слова', () => {
  const p = allWordsPack('ru', 1)!;

  it('цель засчитывается, повтор виден отдельно, чужое — мимо', () => {
    const цель = p.words[0]!;
    expect(сдатьСлово(p, цель, [])).toBe('цель');
    expect(сдатьСлово(p, цель.toUpperCase(), [])).toBe('цель');
    expect(сдатьСлово(p, цель, [цель])).toBe('повтор');
    expect(сдатьСлово(p, 'ъъъ', [])).toBe('мимо');
  });

  it('уровень закрыт, когда найдены ВСЕ', () => {
    expect(всёНайдено(p, [])).toBe(false);
    expect(всёНайдено(p, p.words.slice(0, -1))).toBe(false);
    expect(всёНайдено(p, p.words)).toBe(true);
  });

  it('🔴 подсказка даёт САМОЕ КОРОТКОЕ ненайденное, а не решает уровень', () => {
    const h = подсказкаAllWords(p, [])!;
    expect(h.слово.length).toBe(Math.min(...p.words.map((w) => w.length)));
    expect(h.открыто).toBe(1);
    expect(подсказкаAllWords(p, p.words)).toBeNull();
  });

  /**
   * 🔴 ПОДСКАЗКА НЕ БУКСУЕТ НА ОДНОМ СЛОВЕ. Найдено игрой 06.09.2026: слово
   * открывается не больше чем на `длина − 1` букву, и следующее нажатие
   * списывало подсказку впустую.
   */
  it('исчерпав слово, подсказка переходит к следующему', () => {
    const короткое = p.words.reduce((a, b) => (b.length < a.length ? b : a));
    const доПредела = { [короткое]: короткое.length - 1 };
    const h = подсказкаAllWords(p, [], доПредела)!;
    expect(h.слово).not.toBe(короткое);
  });

  it('когда открывать нечего вовсе — отдаёт null, а не пустой шаг', () => {
    const всёОткрыто: Record<string, number> = {};
    for (const w of p.words) всёОткрыто[w] = w.length - 1;
    expect(подсказкаAllWords(p, [], всёОткрыто)).toBeNull();
  });

  it('повторная подсказка на том же слове открывает СЛЕДУЮЩУЮ букву', () => {
    const первая = подсказкаAllWords(p, [])!;
    const вторая = подсказкаAllWords(p, [], { [первая.слово]: первая.открыто })!;
    if (первая.слово.length > 2) {
      expect(`${вторая.слово}: ${вторая.открыто}`).toBe(`${первая.слово}: ${первая.открыто + 1}`);
    }
  });

  it('«есть что терять» — с первого найденного слова', () => {
    expect(allWordsНачат([])).toBe(false);
    expect(allWordsНачат(['кот'])).toBe(true);
  });

  /**
   * 🔴 БОНУСНЫЕ СЛОВА: НАСТОЯЩЕЕ СЛОВО НЕ ПРОПАДАЕТ.
   *
   * 📍 Раньше слово, собранное из букв базы и существующее в языке, получало
   * «мимо» и исчезало: человек видел, что слово верное, и не понимал, за что его
   * отвергли. Замер по английскому набору: из банка средней базы собирается ещё
   * несколько настоящих слов сверх целей уровня — все они уходили в никуда.
   *
   * ⚠️ Уровень при этом закрывается ТОЛЬКО целями. Иначе копилка стала бы обходом
   * задачи: набрал десяток лишних слов — и уровень пройден.
   */
  describe('копилка бонусных слов', () => {
    it('🔴 слово языка из букв базы — «бонус», а не «мимо»', () => {
      // Ищем настоящую пару: слово из ДРУГОЙ раскладки, которое собирается из этой базы
      let нашли: { pack: any; слово: string } | null = null;
      const все = new Set<string>();
      for (let L = 1; L <= 300; L += 1) {
        const p = allWordsPack('en', L)!;
        все.add(p.base);
        for (const w of p.words) все.add(w);
      }
      for (let L = 1; L <= 300 && !нашли; L += 1) {
        const p = allWordsPack('en', L)!;
        for (const w of все) {
          if (p.words.indexOf(w) >= 0 || w === p.base) continue;
          if (собираетсяИзПлиток(w, [...p.base])) { нашли = { pack: p, слово: w }; break; }
        }
      }
      expect(нашли).not.toBeNull();
      expect(сдатьСлово(нашли!.pack, нашли!.слово, [], 'en')).toBe('бонус');
      // без локали поведение прежнее — «мимо»
      expect(сдатьСлово(нашли!.pack, нашли!.слово, [])).toBe('мимо');
    });

    it('🔴 набор букв, не являющийся словом, остаётся «мимо»', () => {
      const p = allWordsPack('en', 1)!;
      expect(сдатьСлово(p, 'zzzz', [], 'en')).toBe('мимо');
    });

    it('🔴 бонус не закрывает уровень — это делают только цели', () => {
      const p = allWordsPack('en', 1)!;
      expect(всёНайдено(p, ['какое-то-бонусное'])).toBe(false);
      expect(всёНайдено(p, p.words)).toBe(true);
    });

    it('цель остаётся целью, а повтор — повтором', () => {
      const p = allWordsPack('en', 1)!;
      expect(сдатьСлово(p, p.words[0]!, [], 'en')).toBe('цель');
      expect(сдатьСлово(p, p.words[0]!, [p.words[0]!], 'en')).toBe('повтор');
    });
  });

  /**
   * 🔴 ПЕРЕМЕШИВАНИЕ МЕНЯЕТ ПОРЯДОК, А НЕ СОСТАВ. Если бы состав поехал, слово из
   * целей стало бы несобираемым — а человек не понял бы, почему уровень вдруг
   * перестал решаться.
   */
  describe('перемешивание банка', () => {
    it('🔴 состав плиток не меняется ни при одном повороте', () => {
      const p = allWordsPack('ru', 5)!;
      const эталон = [...p.base].sort().join('');
      for (let n = 0; n <= 6; n += 1) {
        expect(allWordsLetters(p, 5 + n).slice().sort().join('')).toBe(эталон);
      }
    });

    it('🔴 порядок хотя бы раз меняется — иначе кнопка ничего не делает', () => {
      const p = allWordsPack('ru', 5)!;
      const первый = allWordsLetters(p, 5).join('');
      const другие = [1, 2, 3, 4, 5, 6].map((n) => allWordsLetters(p, 5 + n).join(''));
      expect(другие.some((x) => x !== первый)).toBe(true);
    });

    it('уровень остаётся воспроизводимым: тот же номер без поворотов — тот же порядок', () => {
      const p = allWordsPack('ru', 5)!;
      expect(allWordsLetters(p, 5).join('')).toBe(allWordsLetters(p, 5).join(''));
    });
  });
});
