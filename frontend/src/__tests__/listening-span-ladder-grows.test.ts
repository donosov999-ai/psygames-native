import { levelParams, LSPAN_VOLUME_TOP } from '@/app/games/listening-span';

/** Подпись уровня = всё, что человек может почувствовать. Совпали подписи — совпали уровни. */
const подпись = (l: number) => JSON.stringify(levelParams(l));

describe('listening-span: лестница различает соседние уровни', () => {
  it('замер ДО зафиксирован: объём и скорость кончаются на L9', () => {
    expect(levelParams(LSPAN_VOLUME_TOP).span).toBe(8);
    expect(levelParams(LSPAN_VOLUME_TOP).gapMs).toBe(500);
    // и выше по объёму/скорости не растёт — иначе замер ДО был бы про другое
    expect(levelParams(60).span).toBe(levelParams(LSPAN_VOLUME_TOP).span);
    expect(levelParams(60).gapMs).toBe(levelParams(LSPAN_VOLUME_TOP).gapMs);
  });

  it('до L9 прежняя лестница не тронута — объём растёт, пауза сокращается', () => {
    expect(levelParams(1).span).toBe(3);
    expect(levelParams(6).span).toBe(8);
    expect(levelParams(1).gapMs).toBe(700);
    // задержки в прежней полосе нет: игрокам ниже плато сложность не меняли
    for (let L = 1; L <= LSPAN_VOLUME_TOP; L++) {
      expect(`L${L} holdMs=${levelParams(L).holdMs}`).toBe(`L${L} holdMs=0`);
    }
  });

  /**
   * 🔴 ГЛАВНОЕ. Ни одной пары соседей с одинаковой подписью — на всём пробеге.
   */
  it('🔴 ни одного уровня-клона на L1…L60', () => {
    const клоны: string[] = [];
    for (let L = 2; L <= 60; L++) {
      if (подпись(L) === подпись(L - 1)) клоны.push(`L${L}=L${L - 1}`);
    }
    expect(`клонов: ${клоны.length}${клоны.length ? ' — ' + клоны.slice(0, 6).join(', ') : ''}`)
      .toBe('клонов: 0');
  });

  it('🔴 и выше плато растёт именно задержка, монотонно', () => {
    for (let L = LSPAN_VOLUME_TOP + 1; L <= 60; L++) {
      const было = levelParams(L - 1).holdMs;
      const стало = levelParams(L).holdMs;
      expect(`L${L}: ${стало} > ${было}`).toBe(`L${L}: ${было + 700} > ${было}`);
    }
  });

  /**
   * ⚠️ Потолка у задержки нет сознательно: ограничить её сейчас — вернуть плато.
   * Полосу можно будет закончить, только когда начнётся следующая ось (задача 103cd98d).
   */
  it('у задержки нет потолка — на L60 она заметно больше, чем на L20', () => {
    expect(levelParams(60).holdMs).toBeGreaterThan(levelParams(20).holdMs * 3);
  });
});
