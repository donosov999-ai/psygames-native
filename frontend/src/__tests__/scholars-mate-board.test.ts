/**
 * 🔴 ДОСКА ОБЯЗАНА ПОКАЗЫВАТЬ ТУ ЖЕ ПОЗИЦИЮ, ЧТО РАЗБИРАЕТ ДВИЖОК.
 *
 * Расстановка из FEN написана своя — иначе на каждую клетку пришлось бы звать
 * chess.js, а их 64 на кадр. Своя расстановка = второй разбор того же формата,
 * а два разбора одного формата рано или поздно расходятся: на рокировке, на
 * пустых рядах, на чёрных фигурах строчными буквами.
 *
 * Расхождение тут особенно подлое: игра работает, ход засчитывается по движку,
 * а НА ДОСКЕ стоит другое. Человек видит одно, отвечает про другое.
 *
 * Поэтому обе расстановки сверяются на всех видах заданий.
 */
import { _расставитьДляПроб } from '@/src/games/scholars-mate/ScholarsMateGame';
import { puzzlesOf } from '@/src/games/scholars-mate/core/deck';
import { shownFen } from '@/src/games/scholars-mate/core/check';

describe('доска «Детского мата»', () => {
  it('есть что проверять: разбор возвращает 64 клетки', () => {
    const { мой, их } = _расставитьДляПроб('rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1');
    expect(мой.length).toBe(64);
    expect(их.length).toBe(64);
    expect(мой.filter(Boolean).length).toBe(32);
  });

  it('🔴 своя расстановка совпадает с chess.js на всех видах заданий', () => {
    const расхождения: string[] = [];
    for (const kind of ['mate', 'defend', 'threat', 'fromGames', 'sacrifice'] as const) {
      for (const p of puzzlesOf(kind).slice(0, 60)) {
        const fen = shownFen(p);
        const { мой, их } = _расставитьДляПроб(fen);
        for (let i = 0; i < 64; i++) {
          if (мой[i] !== их[i]) { расхождения.push(`${kind} клетка ${i}: ${мой[i]} ≠ ${их[i]} — ${fen}`); break; }
        }
      }
    }
    expect(расхождения.slice(0, 3)).toEqual([]);
  });

  it('🔴 пустые ряды и цифры сжатия разбираются верно', () => {
    // 8 подряд пустых, цифра на краю, одинокая фигура — три места, где
    // самодельный разбор ломается чаще всего.
    for (const fen of [
      '8/8/8/8/8/8/8/K6k w - - 0 1',
      'k7/8/8/8/8/8/8/7K b - - 0 1',
      '4k3/8/8/3Q4/8/8/8/4K3 w - - 0 1',
    ]) {
      const { мой, их } = _расставитьДляПроб(fen);
      expect(мой).toEqual(их);
    }
  });
});
