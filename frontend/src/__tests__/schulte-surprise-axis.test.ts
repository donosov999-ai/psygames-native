/**
 * 🔴 ОСЬ «НЕПРЕДСКАЗУЕМОСТЬ» ПРОДОЛЖАЕТ ЛЕСТНИЦУ ШУЛЬТЕ, А НЕ ПЕРЕПИСЫВАЕТ ЕЁ.
 *
 * ЗАМЕР ДО. Разметка по десяти осям: у Шульте заняты ЧЕТЫРЕ — объём, строгость
 * порядка, сходство, двойная задача. Лестница кончалась на 15-м, дальше 385
 * уровней подряд с одной настройкой. Я сам тогда написал «растить нечем,
 * ступени выписаны руками» — отказ без замера, снятый правилом «потолков нет».
 *
 * ЗАМЕР ПОСЛЕ: лестница 15 → 18, настроек 15 → 18, уровни 1..15 нетронуты.
 *
 * 🔴 ПОЧЕМУ ПОЗДНО ОБЪЯВЛЯЕТСЯ НЕ НАПРАВЛЕНИЕ, КАК БЫЛО В ПЛАНЕ. С 12-го уровня
 * содержимое «смешанное», а для него обратный ход и «от центра» не применяются
 * по построению — варьировать нечего. Взято другое правило той же оси: с чего
 * начинается чередование, с цифры (1-А-2-Б) или с буквы (А-1-Б-2).
 *
 * ⚠️ И ПОЧЕМУ ОСЬ НЕ РАСТЁТ СЕТКОЙ. `maxGridFor('mixed', …)`: латиница → 7,
 * кириллица → 8, ГРЕЧЕСКИЙ → ровно 6. Уровни общие для всех письменностей,
 * 7×7 подвесил бы греческую партию. Это проверяется строкой ниже, а не
 * запоминается.
 */
import { levelParams, maxGridFor } from '@/app/games/schulte';
import { SCRIPTS, SCRIPT_IDS } from '@/src/constants/scripts';

declare const __dirname: string;
declare function require(m: string): any;

function вершина(предел = 400): number {
  let последний = 1;
  let прежняя = JSON.stringify(levelParams(1));
  for (let L = 2; L <= предел; L += 1) {
    const текущая = JSON.stringify(levelParams(L));
    if (текущая !== прежняя) { последний = L; прежняя = текущая; }
  }
  return последний;
}

const ПОСЛЕДНИЙ_БЕЗ_СЮРПРИЗА = 15;

describe('🔴 Шульте: ось «непредсказуемость»', () => {
  it('🔴 уровни 1..15 не тронуты — ни сюрприза, ни подвижных клеток', () => {
    const тронуты: string[] = [];
    for (let L = 1; L <= ПОСЛЕДНИЙ_БЕЗ_СЮРПРИЗА; L += 1) {
      const p = levelParams(L);
      if (p.surpriseStart || p.moving) тронуты.push(`L${L}: сюрприз=${p.surpriseStart} движение=${p.moving}`);
    }
    expect(тронуты).toEqual([]);
  });

  it('🔴 лестница выросла за 15-й', () => {
    expect(вершина()).toBeGreaterThan(ПОСЛЕДНИЙ_БЕЗ_СЮРПРИЗА);
    const настроек = new Set(
      Array.from({ length: 400 }, (_, i) => JSON.stringify(levelParams(i + 1))),
    ).size;
    expect(настроек).toBeGreaterThan(ПОСЛЕДНИЙ_БЕЗ_СЮРПРИЗА);
  });

  it('🔴 есть уровни, которые бедный алфавит НЕ тянет — значит обрезка нужна', () => {
    /**
     * 🔴 НАЙДЕНО ЭТИМ ГЕЙТОМ, А НЕ ЖАЛОБОЙ, и это давний висяк, а не мой.
     * Уровни 6, 7, 10, 11 — это 5×5 буквами, 25 клеток. Греческий алфавит даёт
     * 24: не хватает РОВНО ОДНОЙ буквы. `alphabet.slice(0, 25)` молча возвращал
     * 24 знака, последовательность выходила короче поля, и условие завершения
     * `currentIndex === totalCells - 1` не наступало никогда. Таймера у Шульте
     * нет — экран висел, пока человек не уйдёт сам.
     *
     * Ручная настройка ограничивалась `maxSizeFor` всегда; путь ПО УРОВНЮ ставил
     * размер напрямую и обрезки не имел.
     */
    const беднейший = Math.min(...SCRIPT_IDS.map((id) => SCRIPTS[id].chars.length));
    const тесные: string[] = [];
    for (let L = 1; L <= 400; L += 1) {
      const p = levelParams(L);
      if (p.gridSize > maxGridFor(p.contentMode, беднейший)) тесные.push(`L${L}: ${p.gridSize}×${p.gridSize} ${p.contentMode}`);
    }
    // Это НЕ «дефект»: лестница объявляет размер для нормального алфавита, а
    // экран обрезает под текущий. Строка нужна, чтобы обрезка не осталась без
    // повода: исчезнут тесные уровни — исчезнет и смысл обрезки, и мы об этом
    // узнаем здесь, а не через год.
    expect(тесные.length).toBeGreaterThan(0);
  });

  it('🔴 экран ОБРЕЗАЕТ размер уровня под алфавит', () => {
    const экран: string = require('fs').readFileSync(
      require('path').join(__dirname, '../../app/games/schulte.tsx'), 'utf8',
    );
    expect(экран).toMatch(/const влезает = Math\.min\(p\.gridSize, maxSizeFor\(p\.contentMode\)\);/);
    expect(экран).toMatch(/setGridSize\(влезает\)/);
    expect(экран).toMatch(/generateGrid\(влезает,/);
  });

  it('🔴 сюрприз не выключается обратно — лестница не откатывается', () => {
    const откаты: string[] = [];
    let включался = false;
    for (let L = 1; L <= 400; L += 1) {
      if (levelParams(L).surpriseStart) включался = true;
      else if (включался) откаты.push(`L${L}: сюрприз пропал после включения`);
    }
    expect(включался).toBe(true);
    expect(откаты).toEqual([]);
  });
});

describe('проводка: сюрприз доехал до экрана', () => {
  /** ⚠️ Проверка исходника, называю своим именем: жребий и таймер живут в React-состоянии. */
  const текст: string = require('fs').readFileSync(
    require('path').join(__dirname, '../../app/games/schulte.tsx'), 'utf8',
  );

  it('🔴 правило тянется жребием и объявляется по таймеру', () => {
    expect(текст).toMatch(/const жребий = p\.surpriseStart \? тянутьЖребий\(\) : false;/);
    expect(текст).toMatch(/setRuleRevealed\(!p\.surpriseStart\)/);
    expect(текст).toMatch(/setTimeout\(\(\) => setRuleRevealed\(true\), ЗАДЕРЖКА_ОБЪЯВЛЕНИЯ_МС\)/);
  });

  it('🔴 до объявления цель скрыта, а нажатия не считаются', () => {
    // Обе половины обязательны. Скрыть цель, но считать нажатия — это ловушка:
    // человек теряет очки за то, чего не мог знать. Сюрприз стоит ВРЕМЕНИ.
    expect(текст).toMatch(/\{ruleRevealed \? currentTarget : '\?'\}/);
    expect(текст).toMatch(/if \(!ruleRevealed\) return;/);
  });

  it('🔴 чередование умеет начинаться с буквы', () => {
    expect(текст).toMatch(/const сБуквы = lfArg \?\? lettersFirst;/);
    expect(текст).toMatch(/if \(сБуквы\) \{/);
  });
});
