/**
 * История зарядок не должна стираться от неудачного чтения.
 *
 * ЗАЧЕМ. Репорт Вали 12.08: «Куда деваются огонечки, было много — все исчезли».
 * Отметки в календаре серии берутся из истории зарядок, а она лежит одним ключом.
 * Чтение при ЛЮБОЙ ошибке молча возвращало пустой список, и следующая запись сохраняла
 * его же плюс одну запись — история за месяцы стиралась без единого сообщения.
 *
 * ⚠️ ПРОВЕРЯЕМ РЕШЕНИЕ, А НЕ ХРАНИЛИЩЕ. Первая попытка подменяла AsyncStorage и смотрела
 * на вызовы записи — и была ЗЕЛЁНОЙ ПО ЛОЖНОЙ ПРИЧИНЕ: warmup.ts берёт хранилище
 * динамическим импортом внутри функции, подмена до того экземпляра не достаёт, и записи
 * не происходило ни в одном случае. Тест «проверял», что её нет, когда её не было нигде.
 * Поэтому правило вынесено в mergeHistory и проверяется прямо.
 */
import { mergeHistory } from '../services/warmup';

const entry = (date: string): any => ({
  date, weekday: 1, weekday_name: 'пн', duration_min: 5,
  track: 'training', total_score: 100, completed: true,
  steps_done: 3, steps_total: 3,
});

describe('запись истории зарядок', () => {
  it('к прочитанному добавляется новая запись', () => {
    const cur = [entry('2026-08-01'), entry('2026-08-02')];
    const next = mergeHistory(cur, entry('2026-08-03'));
    expect(next?.length).toBe(3);
  });

  it('🔴 чтение не удалось (null) → НЕ ПИСАТЬ', () => {
    expect(mergeHistory(null, entry('2026-08-03'))).toBeNull();
  });

  it('пустая история — честное «пусто», запись проходит', () => {
    expect(mergeHistory([], entry('2026-08-03'))?.length).toBe(1);
  });

  it('исходный массив не портится', () => {
    const cur = [entry('2026-08-01')];
    mergeHistory(cur, entry('2026-08-02'));
    expect(cur.length).toBe(1);
  });
});
