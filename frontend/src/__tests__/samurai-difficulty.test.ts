/**
 * СУДОКУ-САМУРАЙ: СТУПЕНИ СЛОЖНОСТИ НАСТОЯЩИЕ, И ИХ НЕ РЕШАЕТ СКОРОСТЬ ТЕЛЕФОНА.
 *
 * ЧТО ЛОМАЛОСЬ (замер 19.08.2026 на прежнем коде, три доски на уровень):
 *   · Уровни 1, 3, 5, 8 и 12 решались ОДНИМИ голыми одиночками — все двенадцать
 *     «ступеней» были одной и той же задачей, менялась только длина рутины. Сложность
 *     мерили долей выколотых клеток, а это не та ось.
 *   · Доля клеток тоже врала: экран обещал «закрыто 62%», доска отдавала 30%. Причина —
 *     выкалывание обрывалось по часам (`gameNow() + 3000`). То есть уровень назначал не
 *     номер уровня, а быстродействие устройства: на медленном телефоне подсказок было
 *     БОЛЬШЕ, чем на быстром. Это не сложность, это лотерея.
 *   · Тесты самурая (`samurai.test.ts`) при этом были зелёные — они проверяли
 *     `services/samurai`, которого экран не исполнял ни строчки: раскладка и генерация
 *     жили в экране своей копией.
 *
 * ЧТО ПРОВЕРЯЕМ ЗДЕСЬ. Не «сгенерировалось без ошибки», а по существу:
 *   1. ступень уровня = МИНИМАЛЬНЫЙ набор приёмов, которым доска ещё берётся, и он
 *      растёт по уровням;
 *   2. ни одна доска выше второго уровня не берётся голыми одиночками (тот самый регресс);
 *   3. решение единственно — НЕЗАВИСИМЫМ перебором, а не тем же решателем, что копал;
 *   4. генерация не смотрит на часы: гейт гоняет её под ВРАЖДЕБНЫМИ часами, которые
 *      прыгают на десять минут за вызов, и требует того же результата;
 *   5. число на экране («закрыто {p}% клеток») сходится с тем, что реально выкопано;
 *   6. клетка в рабочем режиме — настоящая цель для пальца (48pt), а не 16pt.
 *
 * Всё гоняется НАСТОЯЩИМИ функциями экрана. Гейт, который повторяет правило своей
 * копией, зелен вслепую.
 */

// ⚠️ ВРАЖДЕБНЫЕ ЧАСЫ. Прежний генератор останавливал выкалывание по gameNow(); под этим
// моком он выкопал бы НОЛЬ клеток и весь файл покраснел бы. Нынешний часов не касается.
let mockClock = 0;
jest.mock('@/src/services/gamePause', () => ({
  gameNow: () => { mockClock += 600000; return mockClock; },   // +10 минут за каждый вызов
  isGamePaused: () => false,
}));

import {
  MAX_LEVEL, levelBand, levelParams, generateSamuraiLevel, gradeSamurai, minTierOf,
  countSolutions, countSolutionsFast, buildSolutionCanvas, digByLogic, cellSizeFor,
  CELLS, UNITS, SIZE, GRIDS,
} from '@/app/games/sudoku-samurai';
import { GRID_ORIGINS } from '@/src/services/samurai';
import { TECHNIQUE_TIER } from '@/src/services/sudoku-grade';

/**
 * Доски генерируем ОДИН раз на весь гейт: партия уровня 8 собирается 2–6 с, и гонять
 * генератор в каждом it значило бы получить гейт на пять минут, который перестанут ждать.
 */
const boards = new Map<number, ReturnType<typeof generateSamuraiLevel>>();

declare const __dirname: string;
declare function require(m: string): any;

const TIER_NAME: Record<number, string> = {
  1: 'голые одиночки',
  2: 'скрытые одиночки',
  3: 'связанные кандидаты',
  4: 'голые пары/тройки',
  9: 'логики не хватает',
};

/**
 * ЦЕНА ГЕЙТА. Доска уровня 8 и выше собирается 2–6 с: там нужны голые пары, а это самая
 * дорогая ступень решателя. Полный набор уровней держал прогон на 197 с и в одиночку решал
 * время всей сборки (остальные 80 наборов — 10 с). Гейт, который идёт три минуты, перестают
 * запускать перед коммитом, и он превращается в украшение.
 *
 * Поэтому по умолчанию берём три уровня — по одному на каждую из трёх нижних ступеней.
 * Этого достаточно, чтобы поймать ВСЕ поломки, ради которых гейт написан: лестница уровней
 * проверяется по таблице целиком (все 12), а живые доски — там, где ступень задана точно.
 * Верхнюю полосу (ступень 4) добираем набором из пяти уровней:
 *
 *     SAMURAI_FULL=1 npx jest src/__tests__/samurai-difficulty.test.ts
 *
 * ⚠️ 197 с — ЭТО ПРО ВСЕ ДВЕНАДЦАТЬ УРОВНЕЙ, А НЕ ПРО ЭТОТ НАБОР. Цифру мерили один раз и
 * с тех пор носили как довод «дорого»; замер 19.08.2026 на этом файле: быстрый набор 9.3 с,
 * полный 15.6 с. Шесть секунд — не та цена, ради которой верхняя ступень остаётся
 * непроверенной на каждой сборке. Поэтому в CI выставлен SAMURAI_FULL=1, и держится это
 * не на памяти, а проверкой ниже.
 *
 * Мутационная проверка гонялась на БЫСТРОМ наборе: все четыре поломки он ловит (см. отчёт).
 */
declare const process: { env: Record<string, string | undefined> };
const FULL = process.env.SAMURAI_FULL === '1';

/** Уровни из задания на замер. Полный набор — [1, 3, 5, 8, 12]. */
const PROBE = FULL ? [1, 3, 5, 8, 12] : [1, 3, 5];

/**
 * 🔴 СТОРОЖ САМОГО ФЛАГА. Урезанный набор не падает — он просто проверяет меньше, и
 * поэтому снятый в CI `SAMURAI_FULL` был бы невидим: все тесты зелены, а верхняя ступень
 * не строится ни разу. Ровно так гейт и умирает — молча и с зелёным отчётом.
 *
 * Локально флага нет намеренно: перед коммитом важна скорость. Требуем полный набор
 * только там, где он и должен быть обязателен, — на сборке.
 */
it('🔴 в CI берём полный набор уровней, иначе ступень «голые пары» не проверяется никогда', () => {
  if (process.env.CI !== 'true') return;
  expect(`SAMURAI_FULL=${process.env.SAMURAI_FULL ?? '(не задан)'}`).toBe('SAMURAI_FULL=1');
});

beforeAll(() => {
  for (const L of PROBE) boards.set(L, generateSamuraiLevel(L));
}, 600000);
const boardOf = (L: number) => boards.get(L)!;

describe('поле и зоны', () => {
  it('369 клеток и 131 зона — блоки на стыках общие, а не задвоенные', () => {
    expect(CELLS.length).toBe(5 * 81 - 4 * 9);
    // 5 сеток × (9 строк + 9 столбцов) = 90 линий; блоков 45 − 4 общих = 41
    expect(UNITS.length).toBe(90 + 41);
    for (const cells of UNITS) expect(cells.length).toBe(9);
  });

  it('раскладка у экрана и у services/samurai ОДНА — иначе тесты сервиса зелены вслепую', () => {
    expect(GRIDS).toBe(GRID_ORIGINS);
    expect(SIZE).toBe(21);
  });
});

describe('ступени сложности', () => {
  /**
   * 🔴 ГЛАВНОЕ. Полоса уровня должна быть РАЗНОЙ на разных уровнях, иначе «12 уровней» —
   * это один уровень, повторённый двенадцать раз. Проверяем саму таблицу отдельно от
   * генерации: если её схлопнут в константу, тест про доски ещё может случайно пройти.
   */
  it('таблица уровней задаёт лестницу, а не одну ступень', () => {
    const tiers = new Set(Array.from({ length: MAX_LEVEL }, (_, i) => levelBand(i + 1).max));
    expect([...tiers].sort()).toEqual([1, 2, 3, 4]);
    // на уровнях из задания ступень строго растёт, пока лестница не кончится
    // таблицу проверяем ЦЕЛИКОМ и всегда — она дешёвая, а именно её схлопывание
    // и означало бы возврат фиктивной сложности
    expect([1, 3, 5, 8, 12].map((L) => levelBand(L).max)).toEqual([1, 2, 3, 4, 4]);
    for (let L = 2; L <= MAX_LEVEL; L++) {
      expect(`L${L}: ${levelBand(L).max >= levelBand(L - 1).max}`).toBe(`L${L}: true`);
    }
    // пол не выше потолка — иначе генератор гонялся бы за недостижимым
    for (let L = 1; L <= MAX_LEVEL; L++) expect(levelBand(L).min).toBeLessThanOrEqual(levelBand(L).max);
  });

  /**
   * Живой замер: для каждого уровня из задания генерируем доски и считаем, какой
   * МИНИМАЛЬНЫЙ набор приёмов её берёт. Именно минимальный: доска, которая берётся
   * голыми одиночками, не становится сложнее оттого, что её можно решить и парами.
   */
  it('минимальный достаточный приём совпадает с полосой уровня', () => {
    const bad: string[] = [];
    const report: string[] = [];
    for (const L of PROBE) {
      const band = levelBand(L);
      const g = boardOf(L);
      const need = minTierOf(g.puzzle, TECHNIQUE_TIER.naked_subset);
      report.push(`L${L}: полоса [${band.min}..${band.max}] → нужен ${need} (${TIER_NAME[need]}), дырок ${g.blanks} из ${CELLS.length}`);
      if (need < band.min || need > band.max) {
        bad.push(`L${L}: полоса [${band.min}..${band.max}], а доска берётся ступенью ${need} (${TIER_NAME[need]})`);
      }
    }
    console.log(report.join('\n'));
    expect(bad).toEqual([]);
  }, 120000);

  /**
   * Нижние три ступени генератор берёт ТОЧНО — там пол равен потолку. Отдельная
   * проверка нужна, чтобы полосу нельзя было тихо расширить до [1..4] и сделать
   * гейт выше бессмысленным.
   */
  it('уровни 1, 3 и 5 дают ровно свою ступень', () => {
    expect(`L1: ${minTierOf(boardOf(1).puzzle, 4)}`).toBe('L1: 1');
    expect(`L3: ${minTierOf(boardOf(3).puzzle, 4)}`).toBe('L3: 2');
    expect(`L5: ${minTierOf(boardOf(5).puzzle, 4)}`).toBe('L5: 3');
  });

  /**
   * Тот самый регресс отдельной проверкой: выше второго уровня доска НЕ ДОЛЖНА
   * браться одними голыми одиночками. Это и была фиктивная сложность.
   */
  it('выше второго уровня голых одиночек не хватает', () => {
    const bad: string[] = [];
    for (const L of PROBE.filter((n) => n >= 3)) {
      if (gradeSamurai(boardOf(L).puzzle, TECHNIQUE_TIER.naked_single).solved) {
        bad.push(`L${L}: доска решается одними голыми одиночками — ступень фиктивная`);
      }
    }
    expect(bad).toEqual([]);
  });
});

describe('решение единственно', () => {
  /**
   * Быстрый перебор — свой, и доверять ему можно только сверив со штатным. Приём
   * позаимствован у фрактальной судоку (там штатная проверка стоила 1061 мс на сетку);
   * здесь та же история — штатный countSolutions гоняет isValid на каждого кандидата.
   *
   * 🔴 СВЕРКА ИДЁТ И НА МНОГОРЕШЁННЫХ ДОСКАХ, и это главное. Сверка только на досках с
   * единственным решением ничего не проверяет: её прошёл бы и счётчик, который ВСЕГДА
   * отвечает «одно» — а врут быстрые счётчики ровно на многорешённых. Поэтому доски со
   * сломанной единственностью строятся здесь нарочно, и их количество проверяется
   * отдельным утверждением: ноль таких досок = гейт зелен вслепую.
   */
  it('быстрый перебор согласен со штатным — и на однорешённых, и на многорешённых досках', () => {
    const disagree: string[] = [];
    let одно = 0, много = 0;
    const check = (p: number[][], метка: string) => {
      const slow = countSolutions(p.map((r) => [...r]), 2, { steps: 400000 });
      const fast = countSolutionsFast(p, 2);
      if (slow !== fast) disagree.push(`${метка}: штатный ${slow}, быстрый ${fast}`);
      if (fast >= 2) много++; else if (fast === 1) одно++;
    };

    const sol = buildSolutionCanvas();
    // ── доски с ЕДИНСТВЕННЫМ решением, разной плотности
    for (const cap of [60, 100, 140]) check(digByLogic(sol, 1, cap).puzzle, `единственное, ${cap} дырок`);

    // ── ломаем единственность: снимаем подсказки, пока решений не станет два
    const broken = digByLogic(sol, 1, 140).puzzle.map((r) => [...r]);
    let сломано = false;
    for (const [r, c] of CELLS) {
      if (broken[r][c] === 0) continue;
      broken[r][c] = 0;
      if (countSolutionsFast(broken, 2) >= 2) { сломано = true; break; }
    }
    expect(`единственность удалось сломать: ${сломано}`).toBe('единственность удалось сломать: true');

    // ── и сверяем на НЕЙ и на трёх ещё более дырявых: снятие подсказок решений не убавляет
    check(broken, 'сломанная, 0 доп. снятий');
    let доп = 0;
    for (const [r, c] of CELLS) {
      if (доп >= 3) break;
      if (broken[r][c] === 0) continue;
      broken[r][c] = 0; доп++;
      check(broken, `сломанная, ${доп} доп. снятий`);
    }

    expect(disagree).toEqual([]);
    // ⚠️ Без этих двух строк сверку прошёл бы счётчик-константа
    expect(`однорешённых в выборке ${одно > 0}, многорешённых ${много > 0}`)
      .toBe('однорешённых в выборке true, многорешённых true');
  }, 300000);

  /**
   * ⚠️ ЧЕСТНАЯ ГРАНИЦА ЭТОЙ ПРОВЕРКИ. На верхней ступени (голые пары, ~75% дырок) независимый
   * перебор физически не успевает: замер 19.08.2026 — 397 с и бюджет узлов исчерпан без
   * вердикта. Это не поломка доски, а предел метода: перебору, чтобы ДОКАЗАТЬ единственность,
   * нужно обойти всё дерево, а логике достаточно пройти вынужденную цепочку.
   *
   * Поэтому здесь два разных требования:
   *   · второго решения не найдено НИ НА ОДНОМ уровне — это ловит порчу генератора;
   *   · на ступенях 1–3 перебор обязан именно ДОКАЗАТЬ единственность (вернуть 1), иначе
   *     проверка выродилась бы в «мы посмотрели и ничего не увидели».
   * На ступени 4 единственность держится на построении: доска собрана так, что каждый шаг
   * логики вынужден, а значит второму решению взяться неоткуда.
   */
  it('доска каждого уровня имеет ровно одно решение', () => {
    const bad: string[] = [];
    const отчёт: string[] = [];
    const БЮДЖЕТ = 120000;   // узлов; больше — только дольше ждать того же «не уложился»
    for (const L of PROBE) {
      const g = boardOf(L);
      const n = countSolutionsFast(g.puzzle, 2, БЮДЖЕТ);
      отчёт.push(`L${L}: ${n === 1 ? 'единственность ДОКАЗАНА перебором' : n === -1 ? 'перебор не уложился в бюджет — второго решения не найдено' : `решений ${n}`}`);
      if (n >= 2) bad.push(`L${L}: решений ${n} — честный ход игрока считался бы ошибкой`);
      if (n === 1 || n === -1) { /* порядок */ } else if (n === 0) bad.push(`L${L}: решений нет вовсе`);
      if (levelBand(L).max <= 3 && n !== 1) bad.push(`L${L}: ступень ${levelBand(L).max}, а перебор не доказал единственность (${n})`);
      for (const [r, c] of CELLS) if (g.puzzle[r][c] !== 0 && g.puzzle[r][c] !== g.solution[r][c]) {
        bad.push(`L${L}: подсказка (${r},${c}) не из решения`);
        break;
      }
    }
    console.log(отчёт.join('\n'));
    expect(bad).toEqual([]);
  }, 300000);
});

describe('сложность не зависит от железа', () => {
  /**
   * Весь файл уже идёт под часами, которые прыгают на 10 минут за вызов (мок наверху).
   * Здесь проверяем это в лоб: доска выкапывается до заказанного, а не обрывается.
   * На прежнем коде дедлайн `gameNow() + 3000` сработал бы на ПЕРВОМ же обращении.
   */
  it('под прыгающими часами доска всё равно выкапывается до заказанного', () => {
    const before = mockClock;
    const g = generateSamuraiLevel(1);
    expect(mockClock).toBe(before);   // генерация вообще не спрашивала времени
    expect(g.blanks).toBe(Math.round(CELLS.length * levelParams(1).digRatio));
    expect(boardOf(1).blanks).toBe(g.blanks);   // и на общем наборе то же число
  }, 120000);

  /** Тот же вопрос со стороны исходника: в пути генерации не должно быть часов. */
  it('в коде генерации нет обращений к часам', () => {
    const fs = require('fs'), path = require('path');
    const src: string = fs.readFileSync(path.join(__dirname, '../../app/games/sudoku-samurai.tsx'), 'utf8');
    const gen = src.slice(src.indexOf('export function digByLogic'), src.indexOf('export default function'));
    expect(gen).not.toMatch(/gameNow|Date\.now|performance\.now/);
  });
});

describe('экран не врёт про доску', () => {
  it('обещанная доля закрытых клеток сходится с выкопанной', () => {
    const bad: string[] = [];
    for (const L of PROBE) {
      const promised = levelParams(L).digRatio;
      const actual = boardOf(L).blanks / CELLS.length;
      // ±5 п.п.: на ступенях 2+ глубину задаёт логика, точное число плавает от раскладки
      if (Math.abs(actual - promised) > 0.05) {
        bad.push(`L${L}: обещано ${(promised * 100).toFixed(0)}%, выкопано ${(actual * 100).toFixed(0)}%`);
      }
    }
    expect(bad).toEqual([]);
  });
});

describe('в клетку можно попасть пальцем', () => {
  /**
   * Аудит 19.08.2026: клетка 16pt при норме 48, цифра в ней 9pt. Двадцать одна клетка
   * в ряд крупнее в телефон не влезает (21 × 48 = 1008pt), поэтому режим «вижу весь
   * крест» и не может быть рабочим — он карта. Рабочий режим обязан держать норму.
   */
  it('в рабочем режиме клетка не мельче 48pt на любом телефоне', () => {
    const bad: string[] = [];
    for (const w of [320, 360, 375, 390, 414, 430, 768, 1024]) {
      const zoom = cellSizeFor(w, 'zoom');
      if (zoom < 48) bad.push(`ширина ${w}: клетка ${zoom}pt < 48`);
    }
    expect(bad).toEqual([]);
  });

  it('карта остаётся картой — всё поле видно целиком', () => {
    for (const w of [320, 390, 430]) {
      expect(`${w}: ${cellSizeFor(w, 'fit') * SIZE <= w}`).toBe(`${w}: true`);
    }
  });
});
