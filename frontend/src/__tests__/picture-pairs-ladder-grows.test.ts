/**
 * 🔴 ЛЕСТНИЦА «ПАРНЫХ КАРТИНОК» ОБЯЗАНА РАЗЛИЧАТЬ СОСЕДНИЕ УРОВНИ — ДО САМОГО ВЕРХА.
 *
 * ПРАВИЛО РАЗДЕЛА (Денис, 06.09.2026, дословно): «никаких потолков нет нигде,
 * всегда можно растить сложность, вопрос подхода». Полный текст с таблицей осей —
 * `~/dev/psygames/span-chat/RULE_NO_CEILINGS.md`.
 *
 * ЗАМЕР ДО (16.09.2026, задача 2fb42171). Экран пришёл в раздел восьмым и без единой
 * пробы. Прогон `levelCfg()` на L1…L60: групп 4 + (L − 13) упираются в двенадцать
 * картинок набора (SPRITE_COUNT) на L21, показ упёрся в пол 250 мс ещё на L14 —
 * дальше не менялось НИЧЕГО. Соседних одинаковых уровней — 39 из 59.
 *
 * ЗАМЕР ПОСЛЕ. Ось 9 — карты меняются местами после ошибки, четверть обмена на
 * уровень. Почему не задержка после показа и почему четверть — числами в
 * комментарии к `levelCfg` (модель партии: показ даёт 3,9 % ходов, партия — всё).
 *
 * ⚠️ ЧЕГО ЭТА ПРОБА НЕ ДОКАЗЫВАЕТ. Она читает ОБЪЯВЛЕНИЕ. Что обмены ИСПОЛНЯЮТСЯ на
 * экране — видно, какие клетки, и только они, — стережёт `picture-pairs-swaps`.
 */
import { levelCfg, PAIRS_VOLUME_TOP, обменовПослеОшибки } from '@/app/games/picture-pairs';
import { SPRITE_COUNT } from '@/src/constants/pairThemes';

/** Подпись уровня = всё, что человек может почувствовать. Совпали подписи — совпали уровни. */
const подпись = (l: number) => JSON.stringify(levelCfg(l));

describe('picture-pairs: лестница различает соседние уровни', () => {
  it('замер ДО зафиксирован: объём кончается на L21 — там, где кончаются картинки набора', () => {
    expect(`верх объёма L${PAIRS_VOLUME_TOP}, картинок ${SPRITE_COUNT}`).toBe('верх объёма L21, картинок 12');
    const top = levelCfg(PAIRS_VOLUME_TOP);
    expect(`${top.pairs} групп по ${top.groupSize}, показ ${top.previewMs} мс`).toBe('12 групп по 4, показ 250 мс');
    // выше по прежним осям не растёт — иначе замер ДО был бы про другое
    const L60 = levelCfg(60);
    expect(`${L60.pairs} групп по ${L60.groupSize}, показ ${L60.previewMs} мс`).toBe('12 групп по 4, показ 250 мс');
  });

  it('ниже верха лестница НЕ тронута — обменов в прежней полосе нет', () => {
    for (let L = 1; L <= PAIRS_VOLUME_TOP; L++) {
      expect(`L${L} обменов на ошибку: ${levelCfg(L).swapsPerMiss}`).toBe(`L${L} обменов на ошибку: 0`);
    }
  });

  /** 🔴 ГЛАВНОЕ. Ни одной пары соседей с одинаковой подписью на всём пробеге. */
  it('🔴 ни одного уровня-клона на L1…L60', () => {
    const клоны: string[] = [];
    for (let L = 2; L <= 60; L++) {
      if (подпись(L) === подпись(L - 1)) клоны.push(`L${L}=L${L - 1}`);
    }
    expect(`клонов: ${клоны.length}${клоны.length ? ' — ' + клоны.slice(0, 6).join(', ') : ''}`)
      .toBe('клонов: 0');
  });

  it('🔴 выше верха растут именно обмены — ровно на четверть за уровень', () => {
    for (let L = PAIRS_VOLUME_TOP + 1; L <= 60; L++) {
      const шаг = levelCfg(L).swapsPerMiss - levelCfg(L - 1).swapsPerMiss;
      expect(`L${L}: +${шаг}`).toBe(`L${L}: +0.25`);
    }
    expect([22, 25, 41, 60].map((L) => `L${L}=${levelCfg(L).swapsPerMiss}`).join(' '))
      .toBe('L22=0.25 L25=1 L41=5 L60=9.75');
  });

  it('число обменов после ошибки: целая часть — всегда, дробная — броском', () => {
    expect(обменовПослеОшибки(0, () => 0)).toBe(0);
    expect(обменовПослеОшибки(0.25, () => 0.1)).toBe(1);
    expect(обменовПослеОшибки(0.25, () => 0.5)).toBe(0);
    expect(обменовПослеОшибки(4, () => 0)).toBe(4);
    expect(обменовПослеОшибки(4, () => 0.999)).toBe(4);
    expect(обменовПослеОшибки(9.75, () => 0.7)).toBe(10);
    expect(обменовПослеОшибки(9.75, () => 0.8)).toBe(9);
    // в среднем выходит ровно объявленное: 20 000 бросков детерминированного генератора
    let x = 20260916;
    const rnd = () => ((x = (x * 1103515245 + 12345) % 2147483648) / 2147483648);
    for (const ставка of [0.25, 1.5, 9.75]) {
      let сумма = 0;
      for (let i = 0; i < 20000; i++) сумма += обменовПослеОшибки(ставка, rnd);
      expect(`ставка ${ставка}: среднее близко — ${Math.abs(сумма / 20000 - ставка) < 0.02}`).toBe(`ставка ${ставка}: среднее близко — true`);
    }
  });
});
