/**
 * ДОЛЯ ДОСОК, ГДЕ МЕРА НЕ СЧИТАЕТСЯ — НАЗВАНА ЧИСЛОМ, А НЕ ЗАМОЛЧАНА (ТЗ §4.4).
 *
 * 🔴 ЗАЧЕМ. Оценщик техник молчит там, где доска выше его лестницы: `gradePuzzle`
 * возвращает `solved: false`, экран показывает `boardTier === null` и подписывает
 * уровень поясом вместо приёма. Это не поломка — это ЧЕСТНАЯ граница измерителя.
 * Опасна не она, а молчание о ней: пока доля не названа числом, «мера есть»
 * звучит одинаково и при 0%, и при 85% нечитаемых досок.
 *
 * ЗАМЕР 09.09.2026, банковский путь (levelConfig.variant === 'none' и N = 9,
 * четыре профиля на уровень — зерно у банка от профиля):
 *   · уровни 5–8:   молчит 0 из 16   — мера работает всегда;
 *   · уровни 58–80: молчит 92 из 92  — молчит ВЕЗДЕ, на каждом уровне 4 из 4;
 *   · итого:        92 из 108, то есть 85,2%.
 * Причина известна и записана в шапке services/sudoku-bank: банк отдаёт доски с
 * рейтингом SE выше 3.6, а наша лестница техник кончается на голой тройке.
 *
 * ЗАМЕР ВАРИАНТНОГО ПУТИ (logicalBuilder, L12/30/46/54/85): молчит 0 из 5 — там
 * молчания нет по построению, генератор отдаёт только те доски, которые сам
 * оценил. Поэтому гейт меряет банковский путь: всё молчание живёт там.
 *
 * ⚠️ ХРАПОВИК, А НЕ РАВЕНСТВО. Требовать «ровно 92» значит краснеть на КАЖДОМ
 * расширении лестницы техник — то есть наказывать за улучшение. Требовать «мало»
 * нельзя: сегодня это 100% банковских уровней. Поэтому доля может только
 * УМЕНЬШАТЬСЯ: вырастет — красная, упадёт — красная с просьбой опустить число,
 * чтобы достижение закрепилось и назад дороги не было.
 */
import { bankBoardForLevel } from '@/src/services/sudoku-bank';
import { gradePuzzle } from '@/src/services/sudoku-grade';
import { dimsForSize, levelConfig } from '@/src/services/sudoku-core';

/** Профили берутся именованные: зерно банка зависит от профиля, один профиль — одна доска. */
const PROFILES = ['p1', 'p2', 'p3', 'p4'];

/** Известное молчание на 09.09.2026 — 92 доски из 92. Менять ТОЛЬКО в меньшую сторону. */
const KNOWN_SILENT_HIGH = 92;

const d = dimsForSize(9);

function банковскиеУровни(from: number, to: number): number[] {
  const out: number[] = [];
  for (let L = from; L <= to; L++) {
    const cfg = levelConfig(L) as unknown as { N: number; variant: string };
    if (cfg.variant === 'none' && cfg.N === 9) out.push(L);
  }
  return out;
}

function молчание(levels: number[]): { всего: number; молчит: number } {
  let всего = 0; let молчит = 0;
  for (const L of levels) {
    for (const pid of PROFILES) {
      const b = bankBoardForLevel(L, pid, 0);
      const g = gradePuzzle(b.puzzle, { N: d.N, BR: d.BR, BC: d.BC, variant: 'none' });
      всего++;
      if (!g.solved) молчит++;
    }
  }
  return { всего, молчит };
}

const НИЗ = банковскиеУровни(1, 57);
const ВЕРХ = банковскиеУровни(58, 92);

const низ = молчание(НИЗ);
const верх = молчание(ВЕРХ);
const доля = ((низ.молчит + верх.молчит) / (низ.всего + верх.всего) * 100).toFixed(1);

describe(`мера молчит на ${низ.молчит + верх.молчит} досках из ${низ.всего + верх.всего} (${доля}%)`, () => {
  it('есть что мерить — иначе проба зелена вслепую', () => {
    expect(`низ ${НИЗ.length} уровней · верх ${ВЕРХ.length} уровней`)
      .toBe(`низ ${Math.max(НИЗ.length, 4)} уровней · верх ${Math.max(ВЕРХ.length, 20)} уровней`);
  });

  it('🔴 на нижних банковских уровнях мера считается ВСЕГДА', () => {
    expect(`молчит ${низ.молчит} из ${низ.всего}`).toBe(`молчит 0 из ${низ.всего}`);
  });

  /**
   * ⚠️ ЧЕСТНО: СЕГОДНЯ ЭТА ПРОБА ПОКРАСНЕТЬ НЕ МОЖЕТ. Молчание наверху уже на
   * потолке — 92 из 92, расти некуда, поэтому мутацией её не свалить. Она станет
   * живой в тот день, когда лестница техник дорастёт до банковских досок и число
   * упадёт. Держать её всё равно надо: тогда она и начнёт сторожить откат.
   * Живая сейчас — проба ниже, про закрепление достижения (мутация её валит).
   */
  it(`🔴 молчание наверху не растёт (сейчас ${верх.молчит} из ${верх.всего})`, () => {
    expect(`молчит ${верх.молчит}, известно ${KNOWN_SILENT_HIGH}`)
      .toBe(`молчит ${Math.min(верх.молчит, KNOWN_SILENT_HIGH)}, известно ${KNOWN_SILENT_HIGH}`);
  });

  it('🔴 достижение закрепляется: упало молчание — опусти число в KNOWN_SILENT_HIGH', () => {
    // Обратная сторона храповика. Без неё лестницу техник можно поднять, забыть
    // про константу, и она молча разрешит откат обратно к 92.
    expect(`известно ${KNOWN_SILENT_HIGH}, фактически ${верх.молчит}`)
      .toBe(`известно ${верх.молчит}, фактически ${верх.молчит}`);
  });
});
