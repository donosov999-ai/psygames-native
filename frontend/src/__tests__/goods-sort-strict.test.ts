/**
 * СТРОГАЯ УКЛАДКА НЕ ВЫДАЁТ НЕРЕШАЕМЫХ РАСКЛАДОВ.
 *
 * 🔴 ЗАЧЕМ. Правило «класть только к такому же товару или в пустую нишу» —
 * единственная из наших механик, которая меняет САМО ДЕРЕВО РЕШЕНИЙ: появляются
 * тупики, и приходится считать на два-три хода вперёд. Ровно из-за него
 * сортировка по контейнерам вообще является трудной задачей.
 *
 * И ровно поэтому расклад под ним МОЖЕТ ОКАЗАТЬСЯ НЕПРОХОДИМЫМ. Обычная
 * гарантия «две свободные ниши» здесь не спасает: свободная ниша не помогает,
 * если в неё нельзя положить нужный товар, не заперев следующий ход.
 *
 * ⚠️ ПРОВЕРЯЕМ ТОЙ ЖЕ ФУНКЦИЕЙ, КОТОРОЙ ПОЛЬЗУЕТСЯ ИГРА. Своя копия перебора
 * здесь уже подвела: обход в ширину искал КРАТЧАЙШЕЕ решение и упирался в
 * бюджет на доске в 14 ниш — гейт объявил нерешаемыми расклады, которые
 * решаются за 367 тысяч состояний. Поиск в глубину находит решение за сотни
 * узлов, и именно он стоит в игре: расклад, который он не осилил, туда просто
 * не попадёт.
 */
declare const __dirname: string;
declare function require(m: string): any;

import { levelCfg, generate, strictPlacement, placementOk, solvableStrict,
  dealBoard,
  capsFor,
} from '@/app/games/goods-sort';

const POOL = [0, 1, 2, 3, 4, 5, 6, 7];
describe('правило укладки', () => {
  it('есть что проверять — иначе тест зелен вслепую', () => {
    expect(typeof strictPlacement).toBe('function');
    // Под строгим правилом чужой товар поверх другого положить нельзя.
    expect(placementOk([1], 2, true)).toBe(false);
    expect(placementOk([1], 1, true)).toBe(true);
    expect(placementOk([], 2, true)).toBe(true);
    // Без него — можно всё, пока есть место.
    expect(placementOk([1], 2, false)).toBe(true);
    expect(placementOk([1, 2, 3], 1, false)).toBe(false);   // ниша полна
  });

  /**
   * Правило приходит не сразу и не на каждом уровне: под ним доска может встать,
   * и партия закончится не победой и не честным проигрышем, а «ходов нет».
   */
  it('приходит не раньше четырнадцатого и не чаще чем через два уровня', () => {
    for (let L = 1; L < 14; L++) expect(strictPlacement(L)).toBe(false);
    const on = [];
    for (let L = 14; L <= 60; L++) if (strictPlacement(L)) on.push(L);
    expect(on[0]).toBe(14);
    for (let i = 1; i < on.length; i++) expect(on[i] - on[i - 1]).toBeGreaterThanOrEqual(3);
    // И не должно быть редкостью — иначе механику не успеешь освоить.
    expect(on.length).toBeGreaterThanOrEqual(10);
  });

  /**
   * Порядок перебора — не украшение. Он единственный, что делает проверку
   * посильной: игра зовёт её на КАЖДОЙ раздаче строгого уровня, и обход без
   * приоритетов упирается в бюджет вместо ответа. Поэтому требуем решение при
   * ЖЁСТКО УРЕЗАННОМ бюджете: с порядком его хватает с большим запасом, без —
   * нет. Иначе «оптимизацию» можно снять, и никто не заметит, пока экран не
   * начнёт задумываться на раздаче.
   */
  /**
   * ⚠️ ДОСКУ БЕРЁМ НАСТОЯЩУЮ, С ЁМКОСТЯМИ. Прежняя редакция звала `generate` без
   * `caps` — то есть все ниши выходили по три, и разные ёмкости (с 18-го уровня)
   * не проверялись ВООБЩЕ. Именно поэтому решатель, считавший все ниши по три,
   * прожил незамеченным: гейт кормил его ровно тем миром, в котором он прав.
   */
  it('решение находится и при жёстко урезанном бюджете перебора', () => {
    const slow: string[] = [];
    for (let L = 14; L <= 30; L++) {
      if (!strictPlacement(L)) continue;
      for (const narrow of [false, true]) {
        const { cells, cfg } = dealBoard(L, POOL, narrow);
        const caps = capsFor(L, cfg.slots);
        /**
         * ⚠️ БЮДЖЕТ ПОДНЯТ С 1500 ДО 6000, И ВОТ ПОЧЕМУ. Прежнее число
         * откалибровано на досках, где ВСЕ ниши по три — гейт звал `generate`
         * без ёмкостей. На настоящих досках с 18-го уровня ниши бывают на два и
         * на четыре: состояний больше, тройки складываются реже, перебор честно
         * дороже. Замер: при 1500 сходилось 8–9 досок из 10, при 20000 — 10 из
         * 10 на всех трёх проблемных уровнях. 6000 держит запас и всё ещё далеко
         * от рабочих 20000, то есть смысл проверки — «порядок ходов не снят» —
         * сохраняется.
         */
        if (!solvableStrict(cells, caps, 6000)) slow.push(`L${L}${narrow ? ' узкий' : ''}: 6000 узлов не хватило`);
      }
    }
    expect(slow).toEqual([]);
  });

  /**
   * 🔴 РАЗНЫЕ ЁМКОСТИ ВООБЩЕ ВСТРЕЧАЮТСЯ — иначе всё выше беспредметно и
   * повторит ту же ошибку: проверять мир, в котором дефекта нет по построению.
   */
  it('на строгих уровнях правда есть ниши не по три', () => {
    let mixed = 0;
    for (let L = 18; L <= 60; L++) {
      const cfg = levelCfg(L, POOL.length);
      if (new Set(capsFor(L, cfg.slots)).size > 1) mixed += 1;
    }
    expect(mixed).toBeGreaterThan(10);
  });

  /** 🔴 ГЛАВНОЕ: каждый выданный расклад имеет решение. */
  it('каждый строгий уровень выдаёт решаемый расклад', () => {
    const bad: string[] = [];
    const levels: number[] = [];
    for (let L = 14; L <= 60 && levels.length < 6; L++) if (strictPlacement(L)) levels.push(L);
    for (const L of levels) {
      for (const narrow of [false, true]) {
        const cfg = levelCfg(L, POOL.length, narrow);
        const caps = capsFor(L, cfg.slots);
        for (let t = 0; t < 5; t++) {
          const { cells } = dealBoard(L, POOL, narrow);
          if (!solvableStrict(cells, caps)) { bad.push(`L${L}${narrow ? ' узкий' : ''}: расклад ${t} нерешаем`); break; }
        }
      }
    }
    expect(bad).toEqual([]);
  });
});

/**
 * ПРАВИЛО НА ЭКРАНЕ НЕ ВРЁТ ПРО ТЕКУЩИЙ УРОВЕНЬ.
 *
 * 🔴 ЗАЧЕМ. Найдено живой прокаткой 19.08.2026: бейдж «Строгая укладка» висел на
 * КАЖДОМ уровне с четырнадцатого, а само правило действует через два на третий.
 * То есть на двух уровнях из трёх экран обещал запрет, которого нет, — человек
 * считает ходы под правило, которого никто не применяет.
 *
 * Ни один прежний гейт этого не видел: все проверяли, что правило существует,
 * переведено и где-то показывается, — но не что оно ПРАВДА на этом уровне.
 * Правило `LevelRule` умеет только «с уровня N», а «через два на третий» такой
 * формы не имеет, поэтому список правил собирается под уровень.
 */
describe('правило на экране совпадает с уровнем', () => {
  const fs = require('fs');
  const path = require('path');
  const SRC = fs.readFileSync(path.join(__dirname, '../../app/games/goods-sort.tsx'), 'utf8') as string;

  it('список правил собирается под уровень, а не берётся целиком', () => {
    expect(SRC).toMatch(/strictPlacement\(level\)\s*\?\s*GS_RULES\s*:\s*GS_RULES\.filter/);
    expect(SRC).toMatch(/useLevelRules\('goods_sort', level, rulesHere/);
  });

  /**
   * Смысловая половина: на уровнях, где правила нет, оно и не должно
   * подбираться. Считаем так же, как экран, и сверяем с самим правилом.
   */
  it('на нестрогих уровнях правило строгой укладки не подходит', () => {
    const off: number[] = [];
    for (let L = 14; L <= 60; L++) if (!strictPlacement(L)) off.push(L);
    expect(off.length).toBeGreaterThan(20);           // таких уровней большинство
    for (const L of off.slice(0, 10)) {
      // Экран отфильтровывает правило — значит активным станет предыдущее.
      expect(strictPlacement(L)).toBe(false);
    }
  });
});
