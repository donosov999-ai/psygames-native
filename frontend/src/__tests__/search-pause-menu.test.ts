/**
 * 🔴 ШЕСТЬ ИГР РАЗДЕЛА «ПОИСК» ОТДАЮТ МЕНЮ ПАУЗЫ — И НИ ОДНОГО МЁРТВОГО ПУНКТА.
 *
 * ЗАЧЕМ. Каркас с 2.52.2 умеет `pauseActions`: стрелка «назад» ДЕРЖИТ партию
 * (`holdGame`) и показывает меню, вместо того чтобы выкидывать одним касанием.
 * Игра, не давшая список, ведёт себя по-старому — то есть без этой правки
 * секундомер Шульте продолжал бы идти после случайного касания стрелки.
 *
 * ЗАМЕР ДО (09.09.2026, по коду, все 94 игровых экрана): `pauseActions` передаёт
 * ОДИН экран — `sudoku.tsx`, он же образец. У моих шести было ноль.
 *
 * 🔴 ПОЧЕМУ ЗДЕСЬ НЕ ТРЕБУЕТСЯ РОВНО ЧЕТЫРЕ ПУНКТА, КАК У ОБРАЗЦА.
 * У судоку есть мид-партийная справка (`setRulesOpen`), поэтому её меню —
 * «Продолжить · Заново · Правила · На главную». У моих шести справки в партии
 * либо нет вовсе (`GameAbout` живёт на экране НАСТРОЙКИ и из меню не
 * открывается), либо она условная: `LevelRuleModal` рисует что-то только при
 * `levelRules.active` (`LevelRules.tsx:168`). Пункт, который в половине случаев
 * ничего не открывает, хуже отсутствующего — человек решит, что подвисло.
 * Поэтому гейт требует не «четыре», а «каждый пункт что-то делает».
 *
 * ⚠️ ПРОВЕРКА ПО ИСХОДНИКУ, И ЭТО НАЗВАНО ЯВНО. Поведение самого меню держит
 * `game-shell-pause-menu` — там оно отрисовывается и нажимается. Здесь
 * проверяется ПРОВОДКА: что список дошёл до живого `<GameShell>` и что в нём
 * нет пунктов-пустышек. То же деление, что у образца в `game-shell-pause-menu`.
 */
/*
 * Читаем через общий помощник раздела, а не своим `readFileSync`: в tsconfig
 * проекта нет типов узла, и прямой `import … from 'fs'` роняет `tsc` двумя
 * ошибками «Cannot find name 'fs'». Проверено на себе тем же заходом.
 * Помощник заодно умеет тонкие маршруты — экран, делегирующий соседу.
 */
import { исходникЭкрана } from './helpers/screenSource';

const ИГРЫ = ['visual-search', 'find-differences', 'mahjong', 'schulte', 'quick-count', 'object-tracker'];

const исходник = (игра: string) =>
  исходникЭкрана(игра)
    // Пояснения вырезаются ДО поиска: иначе слово из комментария сойдёт за код.
    // На этом я уже спотыкался — проверка находила `pauseActions` в тексте про него.
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');

/** Открывающие теги `<GameShell …>`; хвост стрелки `=>` за конец тега не считается. */
const тегиShell = (src: string): string[] =>
  src.split(/<GameShell\b/).slice(1).map((кусок) => кусок.match(/^([\s\S]*?)(?<!=)>/)?.[1] ?? '');

/** Все блоки `pauseActions={[ … ]}` файла. */
const блоки = (src: string): string[] =>
  [...src.matchAll(/pauseActions=\{\[([\s\S]*?)\]\}/g)].map((m) => m[1]);

/** Пункты блока: id → его текст до конца записи. */
const пункты = (блок: string): { id: string; тело: string }[] =>
  [...блок.matchAll(/\{[^{}]*?id:\s*'([a-z]+)'[^{}]*\}/g)].map((m) => ({ id: m[1], тело: m[0] }));

describe('🔴 раздел «Поиск»: меню паузы есть у всех шести и без пустых пунктов', () => {
  it('есть что проверять: все шесть экранов читаются и держат каркас', () => {
    // Опечатка в имени маршрута дала бы пустой перебор и вечно зелёный гейт.
    for (const g of ИГРЫ) {
      const src = исходник(g);
      expect(`${g}: ${src.length > 500 && тегиShell(src).length > 0}`).toBe(`${g}: true`);
    }
  });

  it('🔴 каждая из шести передаёт pauseActions', () => {
    const без = ИГРЫ.filter((g) => блоки(исходник(g)).length === 0);
    expect(без).toEqual([]);
  });

  it('🔴 меню стоит на КАЖДОМ игровом GameShell, а не на одном из двух', () => {
    // Шульте рисует партию и блочную серию РАЗНЫМИ вызовами каркаса. Меню на
    // одном из них означает, что во втором стрелка по-прежнему выкидывает без
    // вопроса, — а человек этой разницы не знает.
    const плохо = ИГРЫ
      .map((g) => ({ g, теги: тегиShell(исходник(g)) }))
      .map(({ g, теги }) => ({ g, всего: теги.length, сМеню: теги.filter((t) => /pauseActions=\{\[/.test(t)).length }))
      .filter((r) => r.всего !== r.сМеню)
      .map((r) => `${r.g}: каркасов ${r.всего}, с меню ${r.сМеню}`);
    expect(плохо).toEqual([]);
  });

  it('🔴 первый пункт — «Продолжить», последний — уход', () => {
    const плохо: string[] = [];
    for (const g of ИГРЫ) {
      for (const б of блоки(исходник(g))) {
        const ids = пункты(б).map((п) => п.id);
        if (ids[0] !== 'resume') плохо.push(`${g}: первый пункт «${ids[0]}», а не resume`);
        if (ids[ids.length - 1] !== 'home') плохо.push(`${g}: последний пункт «${ids[ids.length - 1]}», а не home`);
      }
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 НИ ОДНОГО ПУСТОГО ПУНКТА: у всех, кроме «Продолжить», есть действие', () => {
    // «Продолжить» действия не требует — меню закрывает сам каркас.
    // «Уход» идёт через leave, тоже каркасом. Всё остальное обязано что-то делать,
    // иначе кнопка молчит в ответ на нажатие.
    const немые: string[] = [];
    for (const g of ИГРЫ) {
      for (const б of блоки(исходник(g))) {
        for (const п of пункты(б)) {
          if (п.id === 'resume') continue;
          const есть = /onPress:/.test(п.тело) || /leave:\s*true/.test(п.тело);
          if (!есть) немые.push(`${g}/${п.id}: ни onPress, ни leave`);
        }
      }
    }
    expect(немые).toEqual([]);
  });

  it('🔴 уход идёт через leave, а не своим router.back()', () => {
    // Свой уход обошёл бы onSaveBeforeExit — маджонг потерял бы «продолжить».
    const плохо: string[] = [];
    for (const g of ИГРЫ) {
      for (const б of блоки(исходник(g))) {
        const п = пункты(б).find((x) => x.id === 'home');
        if (п && !/leave:\s*true/.test(п.тело)) плохо.push(`${g}: home без leave`);
      }
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 подписи — только словами из словаря', () => {
    const свои: string[] = [];
    for (const g of ИГРЫ) {
      for (const б of блоки(исходник(g))) {
        for (const п of пункты(б)) {
          if (!/label:\s*t\(/.test(п.тело)) свои.push(`${g}/${п.id}: подпись не из t()`);
        }
      }
    }
    expect(свои).toEqual([]);
  });

  it('🔴 «Заново» у Шульте помнит режим, а не сбрасывает на ручные настройки', () => {
    // startGame(true) идёт по лестнице, startGame(false) — по ручному config.
    // Жёсткое `startGame(false)` молча выкинуло бы игрока с уровня 12 в свободную
    // партию, и «Заново» перестало бы значить «то же самое ещё раз».
    //
    // ⚠️ ПРОВЕРЯЕМ СМЫСЛ, А НЕ МЕСТО, И ЭТО ИСПРАВЛЕНИЕ ТОГО ЖЕ ДНЯ. Сначала здесь
    // стоял поиск дословного `startGame(useLevelRef.current)` ВНУТРИ блока меню.
    // Через час чтение `ref` пришлось вынести в отдельную функцию (компилятор
    // React считает ref в пропсах обращением во время отрисовки), поведение не
    // изменилось — а проба покраснела на верном коде. Держим цепочку: пункт зовёт
    // функцию, функция передаёт запомненный режим.
    const src = исходник('schulte');
    const партия = блоки(src)[0];
    const вызов = /onPress:\s*\(\)\s*=>\s*([A-Za-zА-Яа-яЁё_$][\w$А-Яа-яЁё]*)\s*\(/.exec(партия);
    expect(`«Заново» зовёт функцию: ${!!вызов}`).toBe('«Заново» зовёт функцию: true');
    const имя = вызов![1];
    // Либо режим передаётся прямо в пункте, либо через названную функцию файла.
    const тело = имя === 'startGame'
      ? партия
      : new RegExp(`const\\s+${имя}\\s*=[^;]*;`).exec(src)?.[0] ?? '';
    expect(`${имя} помнит режим: ${/startGame\(useLevelRef\.current\)/.test(тело)}`).toBe(`${имя} помнит режим: true`);
    // И отдельно: жёстко зашитого режима в меню быть не должно.
    expect(`жёсткий режим в меню: ${/startGame\((?:true|false)\)/.test(партия)}`).toBe('жёсткий режим в меню: false');
  });

  it('🔴 «Заново» в серии Шульте закрывает прежний прогон перед новым', () => {
    // Иначе открытая серия осталась бы висеть и попала в статистику дважды.
    const серия = блоки(исходник('schulte'))[1];
    expect(`закрывает прежнюю: ${/leaveSeries\(false\);\s*beginSeries\(\)/.test(серия)}`).toBe('закрывает прежнюю: true');
  });

  it('🔴 у слежения последний пункт назван тем, что делает', () => {
    // `leave` уводит через `onBack`, а у слежения onBack = leaveToConfig, то есть
    // экран НАСТРОЙКИ. Подпись «На главную» на такой кнопке врала бы.
    const src = исходник('object-tracker');
    const п = пункты(блоки(src)[0]).find((x) => x.id === 'home')!;
    expect(`подпись слежения: ${/t\('configureGame'\)/.test(п.тело)}`).toBe('подпись слежения: true');
    expect(`onBack ведёт в настройку: ${/onBack=\{leaveToConfig\}/.test(src)}`).toBe('onBack ведёт в настройку: true');
  });
});
