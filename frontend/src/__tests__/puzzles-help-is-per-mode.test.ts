/**
 * СПРАВКА ГОЛОВОЛОМКИ ДОЛЖНА БЫТЬ ПРО ЭТУ ГОЛОВОЛОМКУ.
 *
 * 🔴 ПОВОД. Сорок две головоломки Саймона Тэтхэма живут на ОДНОМ маршруте
 * `/games/puzzles`, режим выбирается `?mode=<имя>`. Карта справки строилась по
 * маршрутам, а `pathname` строку запроса не несёт — поэтому всем сорока двум
 * показывался один и тот же текст, `puzzlesUnrulyIntroDesc`. Человек открывал
 * «Галактики», жал «Правила» и читал про чёрные и белые клетки «Чёт-нечета».
 *
 * 📍 Живой замер 16.09.2026 (задача 2b774e8b): четыре РАЗНЫЕ головоломки брошены
 * за 90 секунд подряд с отзывами «Как играть? Где справка?», «Где цифры как
 * играть?». Кнопка «Правила» при этом видна на всех четырёх кадрах — то есть
 * искали не кнопку, а ответ за ней.
 *
 * ⚠️ ПРОБА СМОТРИТ НА КАРТУ, А НЕ НА ГЕНЕРАТОР. Грепать `gen-helpmap.mjs` по
 * слову «mode» значило бы ловить приём, а не дефект: карта могла остаться
 * несобранной, и всё равно было бы зелено.
 */
import { HELP_MAP } from '@/src/constants/helpMap';
import { РЕЖИМЫ, КЛЮЧ_ИМЕНИ, ПО_УМОЛЧАНИЮ } from '@/src/games/tatham-bridge/names';

/** Головоломки координатора — у них текст «как ходить» обязан быть написан. */
const МОИ = ['Unruly', 'Slant', 'Black Box', 'Guess'];

describe('справка головоломок — по режиму, а не одна на всех', () => {
  it('🔴 у каждого из 42 режимов своя запись в карте', () => {
    const нет = РЕЖИМЫ.filter((р) => !HELP_MAP[`/games/puzzles?mode=${р}`]);
    expect(нет).toEqual([]);
    expect(`режимов в карте: ${РЕЖИМЫ.length}`).toBe(`режимов в карте: ${РЕЖИМЫ.length}`);
  });

  it('🔴 тексты не повторяются: сорок две головоломки — сорок два разных ключа', () => {
    const ключи = РЕЖИМЫ.map((р) => HELP_MAP[`/games/puzzles?mode=${р}`]?.introKey);
    expect(ключи.filter((k) => !k)).toEqual([]);
    expect(new Set(ключи).size).toBe(РЕЖИМЫ.length);
  });

  it('🔴 имя в справке — имя ЭТОЙ головоломки', () => {
    const врут = РЕЖИМЫ.filter((р) => HELP_MAP[`/games/puzzles?mode=${р}`]?.nameKey !== КЛЮЧ_ИМЕНИ[р]);
    expect(врут).toEqual([]);
  });

  it('голый маршрут ведёт себя как режим по умолчанию', () => {
    const голый = HELP_MAP['/games/puzzles'];
    const умолчание = HELP_MAP[`/games/puzzles?mode=${ПО_УМОЛЧАНИЮ}`];
    expect(голый).toEqual(умолчание);
  });

  /**
   * Своим четырём текст «как ходить» написан, у остальных пока стоит короткое
   * описание — оно хотя бы про ЭТУ игру. Порог поднимает владелец режима, когда
   * напишет свой: тогда сюда добавляется его режим.
   */
  it('🔴 у головоломок координатора есть СВОЙ текст «как ходить», а не описание цели', () => {
    const безСвоего = МОИ.filter((р) => {
      const е = HELP_MAP[`/games/puzzles?mode=${р}`];
      return е?.introKey !== `${КЛЮЧ_ИМЕНИ[р]}IntroDesc`;
    });
    expect(безСвоего).toEqual([]);
  });
});
