/**
 * 🔴 ОСЬ 9 — НЕПРЕДСКАЗУЕМОСТЬ: направление объявляется ПОСЛЕ показа.
 *
 * ЗАЧЕМ. Объём (9 цифр) и скорость (350/550 мс) кончились на L14, задержка уже
 * введена. Третья ось — момент объявления: ряд приходится держать, не зная, как
 * его отдавать — прямо, задом наперёд или по возрастанию. Это НЕ новый режим:
 * три направления есть с L11 (ось 6), меняется только когда о них говорят.
 *
 * ⚠️ ЧЕГО ЭТА ПРОБА НЕ ДОКАЗЫВАЕТ. Что направление действительно скрыто на экране
 * до ввода — это исполнение, его меряет игровой прогон
 * `span-chat/probe/playthrough.mjs`. Здесь проверяется ОБЪЯВЛЕНИЕ: с какого уровня
 * лестница просит розыгрыш. Разделение важное: сегодня уже трижды оказалось, что
 * зелёная проба объявления ничего не говорит об исполнении.
 */
import { levelParams, DS_VOLUME_TOP, DIRECTIONS, expectedDigits } from '@/app/games/digit-span';

describe('digit-span: направление объявляется после показа', () => {
  it('до порога направление известно заранее — прежняя лестница не тронута', () => {
    for (let L = 1; L <= DS_VOLUME_TOP; L++) {
      expect(`L${L} розыгрыш=${levelParams(L).surpriseDir}`).toBe(`L${L} розыгрыш=false`);
    }
  });

  it('🔴 выше порога розыгрыш включён и больше не выключается', () => {
    for (let L = DS_VOLUME_TOP + 1; L <= 60; L++) {
      expect(`L${L} розыгрыш=${levelParams(L).surpriseDir}`).toBe(`L${L} розыгрыш=true`);
    }
  });

  it('разыгрывается из ВСЕХ трёх направлений, и каждое даёт свой ответ', () => {
    expect(DIRECTIONS).toEqual(['forward', 'backward', 'ascending']);
    const ряд = [5, 2, 8, 1];
    const ответы = DIRECTIONS.map((d) => expectedDigits(ряд, d).join(''));
    expect(`ответов ${new Set(ответы).size} из 3: ${ответы.join(' · ')}`)
      .toBe('ответов 3 из 3: 5281 · 1825 · 1258');
  });

  /**
   * ⚠️ Без этого ось была бы бутафорией: если направление разыграно, но ответ
   * считается по одному правилу, человек не почувствует разницы, а ошибётся.
   */
  it('🔴 ответ считается по РАЗЫГРАННОМУ направлению, не по показанному порядку', () => {
    const ряд = [5, 2, 8, 1];
    expect(expectedDigits(ряд, 'ascending')).toEqual([1, 2, 5, 8]);
    expect(expectedDigits(ряд, 'backward')).toEqual([1, 8, 2, 5]);
  });
});
