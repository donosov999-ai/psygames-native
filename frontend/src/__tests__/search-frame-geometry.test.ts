/**
 * 🔴 ШЕСТЬ ИГР РАЗДЕЛА «ПОИСК» ПОКАЗЫВАЮТ СЧЁТЧИКИ ОДИНАКОВО.
 *
 * ЗАЧЕМ. Денис играет «Зарядку»: игры идут вперемешку, и интерфейс между ними
 * ПРЫГАЕТ. Его слова 07.09.2026: «если мы будем делать Зарядку, смешивая разные
 * штуки, показывая то один то другой, интерфейс скачущий будет раздражать».
 *
 * ЗАМЕР ПО КОДУ (07.09.2026, все 94 игровых экрана): `hud` передают 50, `stats` —
 * 44, и ДВАДЦАТЬ ВОСЕМЬ передают ОБА СРАЗУ. Это не «побеждает один»: `GameShell`
 * рисует обе ветки (`:785` и `:825`), а `statsFlex` (`:1113`) — колонка.
 *
 * 🔴 ЗАМЕР ЖИВЬЁМ ЭТУ ФОРМУЛИРОВКУ ПОПРАВИЛ, И ПОПРАВИЛ МЕНЯ. Сначала здесь
 * стояло «получаются ДВЕ полосы вместо одной» — вывод из чтения кода. Браузерный
 * замер того же дня (окна 390×844 и 360×800, собранный бандл) показал, что второй
 * ряд появляется, только если в `stats` есть ВИДИМОЕ содержимое:
 *   плашка 61 — один ряд `hud` (corsi, n-back, ханой, мои пятеро);
 *   плашка 78 — судоку: `hud` плюс мелочь в `stats` (+17);
 *   плашка 149 — корректура: `hud` плюс коробка задания (+88), и верх поля
 *                уезжает со 119 на 207;
 *   плашка 13 — слежение: счётчиков нет вовсе.
 * Разброс по разделу выходит 13…149, то есть 136 точек.
 *
 * ⚠️ Где `stats` был ПУСТЫМ (отличия, быстрый счёт), второго ряда не было —
 * вредило другое: `GameShell:771` по НАЛИЧИЮ `stats` выбирает, тянуть плашку во
 * всю ширину или сжимать по содержимому (`statsPlateBare`). Пустой `<View>`
 * истинен, поэтому у быстрого счёта плашка меняла ШИРИНУ между вспышкой и
 * ответом — прямо посреди пробы. Разные дефекты, и лечатся они одинаково, но
 * называть их одним словом «две полосы» было неточно.
 *
 * 🔴 ПОЧЕМУ РЕЕСТР, А НЕ ЗАПРЕТ. Запретить `stats` целиком нельзя: у маджонга и
 * Шульте там живут настоящие счётчики, и снять их одним движением значит
 * оставить игру без показаний. Поэтому долг перечислен ПОИМЁННО и с причиной, а
 * гейт следит за двумя вещами сразу: список не растёт и не протухает. Тот же
 * приём, что у соседнего `hud-labels` с его `BUSY`.
 *
 * ⚠️ ЗАПИСЬ В РЕЕСТРЕ — ЭТО ОБЯЗАТЕЛЬСТВО, А НЕ ИНДУЛЬГЕНЦИЯ. Перевёл экран на
 * `hud` — удали строку тем же коммитом, иначе гейт покраснеет на «протухшей»
 * записи и скажет об этом прямо.
 */
import { исходникЭкрана } from './helpers/screenSource';

/** Шесть игр раздела. Корректура сюда НЕ входит: 07.09 отдана разделу «Слова». */
const МОИ = ['visual-search', 'find-differences', 'mahjong', 'schulte', 'quick-count', 'object-tracker'];

/**
 * Экраны, у которых `stats` ещё есть, — с причиной и сроком.
 * 🔴 Список обязан только СОКРАЩАТЬСЯ.
 */
const ЕЩЁ_НА_STATS: Record<string, string> = {
  // 07.09.2026: зрительный поиск снят — LevelRuleBadge переехал в headerRight.
  schulte:
    'остался ОДИН кружок активной группы и только в режиме разделённого внимания: '
    + 'ModItem умеет пять канонических тонов, а тут цвет — идентификатор группы. '
    + 'Ждёт ModItem.color от координатора; счётчики уже в hud',
};

/**
 * Экраны, у которых счётчиков нет НИ в `hud`, НИ в `stats`, — с причиной.
 *
 * 🔴 ЭТО ДРУГОЙ ДОЛГ, А НЕ РАЗНОВИДНОСТЬ ПЕРВОГО. В `ЕЩЁ_НА_STATS` счётчики
 * есть, просто нарисованы своей вёрсткой. Здесь их у каркаса нет вовсе: модуль
 * рисует показания внутри поля. «Перевести» для этих двух случаев означает
 * разное, и один список на оба врал бы про объём работы.
 */
const ЕЩЁ_БЕЗ_HUD: Record<string, string> = {
  // 🔴 ПУСТ С 09.09.2026 — и это конец долга, а не потеря реестра.
  // Слежение было последним: модуль рисовал уровень и прогресс внутри поля,
  // плашка каркаса стояла пустой (высота 8 против 56 у соседей), верх поля 71
  // против 119. Теперь модуль отдаёт числа наверх (`onHud`), а счётчики рисует
  // каркас. Проверку НЕ снимаю: пустой реестр — единственное состояние, при
  // котором она что-то стоит, и первая же новая игра без счётчиков её разбудит.
};

const естьПроп = (src: string, имя: string) => new RegExp(`\\b${имя}=\\{`).test(src);

describe('🔴 раздел «Поиск»: одна полоса счётчиков, а не две', () => {
  it('есть что проверять: все шесть экранов читаются', () => {
    // Иначе опечатка в имени маршрута дала бы пустой перебор и вечно зелёный гейт.
    for (const g of МОИ) expect(`${g}: ${исходникЭкрана(g).length > 500}`).toBe(`${g}: true`);
  });

  it('🔴 никто, кроме перечисленных в реестре, не передаёт stats', () => {
    const лишние = МОИ
      .filter((g) => !(g in ЕЩЁ_НА_STATS))
      .filter((g) => естьПроп(исходникЭкрана(g), 'stats'));
    expect(лишние).toEqual([]);
  });

  it('🔴 реестр не протух: у каждой записи stats ДЕЙСТВИТЕЛЬНО ещё есть', () => {
    // Протухшая запись хуже отсутствующей: она разрешает то, чего уже нет, и
    // молча пропустит возврат дефекта на этот экран.
    const мёртвые = Object.keys(ЕЩЁ_НА_STATS)
      .filter((g) => !естьПроп(исходникЭкрана(g), 'stats'))
      .map((g) => `${g}: stats уже снят — удали строку из ЕЩЁ_НА_STATS`);
    expect(мёртвые).toEqual([]);
  });

  it('🔴 у каждой записи реестра есть ПРИЧИНА, а не пустая строка', () => {
    const немые = Object.entries(ЕЩЁ_НА_STATS)
      .filter(([, почему]) => почему.trim().length < 20)
      .map(([g]) => g);
    expect(немые).toEqual([]);
  });

  it('🔴 счётчики идут через hud у ВСЕХ, кроме перечисленных в ЕЩЁ_БЕЗ_HUD', () => {
    // Снять stats и не дать hud — это не «одна полоса», а НИ ОДНОЙ: игрок
    // остался бы без показаний, и гейт «нет stats» был бы этим доволен.
    // Ровно это и поймалось на слежении при первом прогоне 07.09.2026.
    //
    // 🔴 ЗАПИСЬ В ЕЩЁ_НА_STATS БОЛЬШЕ НЕ ОСВОБОЖДАЕТ ОТ hud (07.09.2026).
    // Освобождала — и это была дыра: Шульте лежала в реестре, а значит могла
    // держать все три счётчика своей вёрсткой сколько угодно, и ни одна проба
    // этого не замечала. Долг в реестре — про ОСТАТОК в `stats`, а не про право
    // не иметь `hud`; кто в реестре, тот обязан и то и другое.
    const без = МОИ
      .filter((g) => !(g in ЕЩЁ_БЕЗ_HUD))
      .filter((g) => !естьПроп(исходникЭкрана(g), 'hud'))
      .map((g) => `${g}: счётчиков нет в hud`);
    expect(без).toEqual([]);
  });

  it('🔴 реестр «без hud» не протух', () => {
    const мёртвые = Object.keys(ЕЩЁ_БЕЗ_HUD)
      .filter((g) => естьПроп(исходникЭкрана(g), 'hud'))
      .map((g) => `${g}: hud уже есть — удали строку из ЕЩЁ_БЕЗ_HUD`);
    expect(мёртвые).toEqual([]);
  });

  it('🔴 ни один экран не числится в ОБОИХ реестрах сразу', () => {
    // Иначе долг прячется дважды и не закрывается ни разу.
    const оба = Object.keys(ЕЩЁ_НА_STATS).filter((g) => g in ЕЩЁ_БЕЗ_HUD);
    expect(оба).toEqual([]);
  });

  it('🔴 мёртвых стилей statsRow не осталось у переведённых', () => {
    const мусор = МОИ
      .filter((g) => !(g in ЕЩЁ_НА_STATS))
      .filter((g) => /statsRow/.test(исходникЭкрана(g)))
      .map((g) => `${g}: styles.statsRow осиротел`);
    expect(мусор).toEqual([]);
  });
});
