/**
 * 🔴 ДВЕ НОВЫЕ ОСИ ВЫБОРА-РЕАКЦИИ: ПОХОЖЕСТЬ ЗНАКА И НЕЙТРАЛЬ.
 *
 * ПОВОД. Трудность росла числом альтернатив (2 → 3 → 4) и упиралась в экран:
 * больше кнопок в полосу ответа не влезает. Это выглядело как потолок, а было
 * незаконченным поиском оси.
 * 📌 Слово Дениса 10.09.2026: «можно усложнить, рисуя не стрелки тогда, а
 * иногда вообще нейтраль или что-то похожее на стрелку — скобку».
 *
 * ЧТО СТЕРЕЖЁТСЯ ЗДЕСЬ И ПОЧЕМУ ИМЕННО ЭТО.
 * 1. Доля нейтралей ЗАМОРОЖЕНА. Растить её с уровнем — тот самый дефект, что в
 *    разделе чинился семь раз: игрок становится осторожнее, RT растёт от
 *    осторожности, и ручка уровня начинает двигать саму измеряемую величину.
 * 2. Направления раздаются РАВНОМЕРНО. Перекос превратил бы пробу выбора в
 *    пробу ожидания: одну кнопку можно было бы держать наготове.
 * 3. Начертание идёт по лестнице и доходит до скобки. Ось, включённая только на
 *    верхней трети, — это не ось, а украшение верха (у CPT так и вышло с
 *    похожими буквами: механизм есть, на L1–L10 отключён).
 */
import { levelParams, levelCondition, nextStim, NEUTRAL_RATE, type Direction } from '@/app/games/choice-rt';
import { choiceRtLoad } from '@/src/games/attention/load';

const УРОВНИ = Array.from({ length: 15 }, (_, i) => i + 1);
const N = 20000;

describe('выбор-реакция: нейтраль и начертание знака', () => {
  it('есть что проверять — иначе набор зелен вслепую', () => {
    expect(`поле начертания: ${'glyph' in levelParams(1)}`).toBe('поле начертания: true');
    expect(typeof nextStim).toBe('function');
  });

  /**
   * 🔴 Заморозка проверяется НЕ чтением константы, а прогоном раздачи на каждом
   * уровне: доля обязана быть одной и той же снизу доверху.
   */
  it('🔴 доля нейтралей одинакова на всех уровнях и равна объявленной', () => {
    const мимо: string[] = [];
    for (const L of [1, 8, 15]) {
      const dirs = levelParams(L).dirs;
      let н = 0;
      for (let i = 0; i < N; i++) if (nextStim(dirs) === 'neutral') н++;
      const доля = н / N;
      if (Math.abs(доля - NEUTRAL_RATE) > 0.012) мимо.push(`L${L}: ${доля.toFixed(3)} против ${NEUTRAL_RATE}`);
    }
    expect(мимо).toEqual([]);
    // и сама объявленная доля — в канонном коридоре пустых проб 10…20 %
    expect(`${NEUTRAL_RATE >= 0.10 && NEUTRAL_RATE <= 0.20}`).toBe('true');
  });

  it('🔴 направления раздаются равномерно — иначе это проба ожидания, а не выбора', () => {
    const перекосы: string[] = [];
    for (const L of [1, 8, 15]) {
      const dirs = levelParams(L).dirs;
      const счёт: Record<string, number> = {};
      for (let i = 0; i < N; i++) {
        const s = nextStim(dirs);
        if (s !== 'neutral') счёт[s] = (счёт[s] ?? 0) + 1;
      }
      const всего = Object.values(счёт).reduce((a, b) => a + b, 0);
      const ждём = 1 / dirs.length;
      for (const d of dirs) {
        const доля = (счёт[d] ?? 0) / всего;
        if (Math.abs(доля - ждём) > 0.02) перекосы.push(`L${L} ${d}: ${доля.toFixed(3)} против ${ждём.toFixed(3)}`);
      }
    }
    expect(перекосы).toEqual([]);
  });

  it('нейтраль не совпадает ни с одним направлением', () => {
    const направления: Direction[] = ['left', 'right', 'up', 'down'];
    expect(направления).not.toContain('neutral' as unknown as Direction);
  });

  it('🔴 начертание идёт по лестнице, не откатывается и доходит до скобки', () => {
    const порядок = ['arrow', 'chevron', 'bracket'];
    const ряд = УРОВНИ.map((L) => levelParams(L).glyph);
    const откаты = ряд.filter((g, i) => i > 0 && порядок.indexOf(g) < порядок.indexOf(ряд[i - 1]));
    expect(откаты).toEqual([]);
    expect(`L1 ${ряд[0]} · L15 ${ряд[14]} · всех начертаний ${new Set(ряд).size}`)
      .toBe('L1 arrow · L15 bracket · всех начертаний 3');
  });

  /**
   * 🔴 Мера уровня обязана ВИДЕТЬ начертание, а не только окно и число кнопок.
   * L3 и L4 отличаются ровно начертанием (стрелка → шеврон) и окном: направлений
   * там поровну (оба ≤5 → две). Значит отношение нагрузок обязано равняться
   * отношению окон, умноженному на шаг начертания.
   *
   * ⚠️ Шаг 1.2 стоит здесь ЧИСЛОМ, а не берётся из проверяемого модуля. Импорт
   * сделал бы пробу слепой: подвинули бы обе стороны разом, и она бы не заметила
   * (так уже случилось на пороге окна этой же игры).
   */
  it('🔴 мера уровня учитывает начертание, а не только окно и число кнопок', () => {
    const p3 = levelParams(3), p4 = levelParams(4);
    expect(`направлений поровну: ${p3.dirs.length === p4.dirs.length}`).toBe('направлений поровну: true');
    expect(`начертание меняется: ${p3.glyph} → ${p4.glyph}`).toBe('начертание меняется: arrow → chevron');
    const ждём = (p3.windowMs / p4.windowMs) * 1.2;
    const факт = choiceRtLoad(4) / choiceRtLoad(3);
    expect(`отношение ${факт.toFixed(3)} ≈ ${ждём.toFixed(3)}`).toBe(`отношение ${ждём.toFixed(3)} ≈ ${ждём.toFixed(3)}`);
  });

  it('условие партии несёт начертание — иначе два прохода несравнимы', () => {
    expect(Object.keys(levelCondition(1))).toContain('glyph');
    expect(levelCondition(15).glyph).toBe(levelParams(15).glyph);
  });
});
