/**
 * 🔴 В ЗАРЯДКЕ СЛОЖНОСТЬ ИДЁТ С ЛИЧНОГО УРОВНЯ, А НЕ С УМОЛЧАНИЯ.
 *
 * 📍 РЕШЕНИЕ ДЕНИСА 09.09.2026: «зарядка и оценка идут с ЛИЧНОГО уровня» —
 * играет один человек, и меряем прогресс человека. Коммит `8f0bfc47` снял
 * подмену уровня картой тира в семи экранах. Замер 09.09 по языковому разделу
 * нашёл ту же беду в другой форме.
 *
 * ЧТО БЫЛО в `semantic-sort`: `useLevel = !isPreset`, и в зарядке уровень не
 * участвовал ВОВСЕ. Число категорий-дистракторов бралось из умолчания `cats = 3`
 * — одинаково человеку с первым уровнем (полагается 2) и с двенадцатым
 * (полагается 4). Это не косметика: категории-дистракторы и есть вторая ось
 * сложности игры.
 *
 * ⚠️ ЧТО ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ И ПОЧЕМУ. Число КРУГОВ в зарядке по-прежнему за
 * зарядкой: она набирает шаги под бюджет и вправе задать длину шага. Требовать
 * «кругов тоже с уровня» значило бы сломать бюджет — на двенадцатом уровне шаг
 * стал бы длиннее обещанного.
 *
 * ⚠️ И ПОЧЕМУ ТОЛЬКО ОДНА ИГРА. Замер по четырём играм раздела: у `cloze`
 * уровень задаёт `rounds` и `timeLimitMs`, у `lexical-decision` — `trials` и
 * `windowMs`. В зарядке и то и другое задаёт САМА зарядка (длина шага) либо
 * снимает нарочно (лимит времени = 0, самотёк). Уровню там нечего применять;
 * «провести уровень» в них было бы лозунгом, а не правкой. У `vocab-srs`
 * расписание карточек идёт от SRS, не от уровня.
 */
declare const __dirname: string;
declare function require(id: string): any;

const читать = (rel: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, rel), 'utf8') as string;
/** Комментарии срезаются: проверка обязана смотреть на КОД, а не на пояснения. */
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

/** Повторяет формулу экрана — чтобы гонять её на выдуманных уровнях. */
const катНаУровне = (level: number): number => (level <= 3 ? 2 : level <= 8 ? 3 : 4);

describe('сложность зарядки берётся с личного уровня', () => {
  it('🔴 у разных уровней разная сложность — иначе ось не работает', () => {
    expect([1, 3, 4, 8, 9, 15].map(катНаУровне)).toEqual([2, 2, 3, 3, 4, 4]);
    // Умолчание пресета — 3: первому и двенадцатому уровню оно одинаково неверно.
    expect(катНаУровне(1)).not.toBe(3);
    expect(катНаУровне(12)).not.toBe(3);
  });

  /**
   * 🔴 ГЛАВНАЯ ПРОБА. Ветки `useLevel` мало: до 09.09.2026 она была, и именно
   * она отсекала уровень в зарядке. Требуется ВТОРАЯ ветка — «пресет без явного
   * `cats` берёт сложность с уровня».
   */
  it('🔴 в пресете без явного cats сложность берётся с уровня', () => {
    const src = код(читать('../../app/games/semantic-sort.tsx'));
    expect(src).toMatch(/const catsЗадано = num\('cats', 0\) > 0;/);
    expect(src).toMatch(/\}\s*else if \(!catsЗадано\)\s*\{\s*cpr = p\.catsPerRound;/);
  });

  it('🔴 уровень считается ДО ветвления, а не внутри уровневой ветки', () => {
    const src = код(читать('../../app/games/semantic-sort.tsx'));
    // `levelParams` и `levelRef` обязаны стоять до `if (useLevel)`, иначе в
    // пресете уровень снова окажется недоступен.
    const i = src.indexOf('const p = levelParams(lvl.level);');
    const j = src.indexOf('if (useLevel) {');
    expect(`p до ветвления: ${i >= 0 && j > i}`).toBe('p до ветвления: true');
  });

  it('число кругов в зарядке остаётся за зарядкой', () => {
    const src = код(читать('../../app/games/semantic-sort.tsx'));
    // Круги переопределяются только в уровневом режиме; в пресете их задаёт шаг.
    expect(src).toMatch(/if \(useLevel\) \{\s*rc = p\.roundsCount;/);
  });

  /**
   * ⚠️ ОТРИЦАТЕЛЬНАЯ ПРОВЕРКА ПО ТРЁМ ОСТАЛЬНЫМ ИГРАМ РАЗДЕЛА. Если у них
   * появится своя ось сложности, не зависящая от длины шага, — эту пробу надо
   * будет расширить, а не удалить. Пока фиксируем ЗАМЕР: у них уровень задаёт
   * только длину и лимит времени.
   */
  it('у cloze и lexical-decision уровень задаёт длину и время, а не отдельную ось', () => {
    const cl = код(читать('../../app/games/cloze.tsx'));
    expect(cl).toMatch(/rounds = Math\.min\(16, 5 \+ level\)/);
    expect(cl).toMatch(/timeLimitMs = Math\.max\(4500/);
    const ld = код(читать('../../app/games/lexical-decision.tsx'));
    expect(ld).toMatch(/trials = level <= 5/);
    expect(ld).toMatch(/windowMs = Math\.max\(1100/);
  });

  /**
   * 🔴 ЗАПРЕТ ВОЗВРАТА КАРТЫ ТИРА — то же, что сторожит `assessment-metrics`
   * для семи экранов, но по языковому разделу.
   */
  it('🔴 ни один экран раздела не подменяет уровень картой тира', () => {
    const плохо: string[] = [];
    for (const g of ['semantic-sort', 'cloze', 'lexical-decision', 'vocab-srs']) {
      const src = код(читать(`../../app/games/${g}.tsx`));
      if (/PRESET_LEVEL_BY_DIFF|\{\s*easy:\s*\d+\s*,\s*medium:\s*\d+\s*,\s*hard:\s*\d+\s*\}/.test(src)) плохо.push(g);
    }
    expect(`с картой тира: ${плохо.join(', ') || '—'}`).toBe('с картой тира: —');
  });
});
