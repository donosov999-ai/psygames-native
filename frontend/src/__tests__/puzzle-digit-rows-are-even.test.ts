/**
 * 🔴 РЯД КЛАВИШ ЦИФР ДЕЛИТСЯ ПОРОВНУ, А НЕ «СКОЛЬКО ВЛЕЗЛО — ОСТАЛЬНОЕ ВНИЗ».
 *
 * 📍 ПОВОД. Отзывы Дениса 18.09.2026, iPhone 403×873, v2.54.22: `fc2085a2` («Заполнение
 * областей») — «Почему цифры не в два ряда»; `eb132a28` (Solo) — «ряд цифр кривой снизу».
 * Замер той же сборки: на 403×873 десять клавиш ложились 6+4, на 360×640 — 5+5. Нижний ряд
 * то вдвое короче верхнего, то вровень, и решало это окно, а не замысел.
 *
 * ЧТО СТЕРЕЖЁТ: при любой ширине и любом числе клавиш ряды отличаются не больше чем на одну
 * клавишу. Проба считает РАЗБИЕНИЕ, которое даст перенос при выданной ширине ряда
 * (`разбиение`), а не читает стиль экрана.
 *
 * ⚠️ Ширина в расчёт приходит ИЗМЕРЕННАЯ (`onLayout` узла под доской). Считать её из ширины
 * окна нельзя: замер 18.09 на 360×640 дал 5 клавиш в ряду там, где «окно − поля сцены»
 * обещало 6 — между окном и рядом лежат поля каркаса.
 */
import { ширинаРовныхРядов, разбиение, клавишВРяд, ШИРИНА_КЛАВИШИ, ЗАЗОР_КЛАВИШ } from '@/src/games/tatham-bridge/keyRows';
import { РЕЖИМЫ_РАЗДЕЛА } from '@/src/games/tatham-bridge/sections/sudoku';
import { ЦИФРОВЫЕ, клавишДоски } from '@/src/games/tatham-bridge/names';

/** Ширина, в которую влезает ровно N клавиш: N·50 + (N−1)·6. */
const подНклавиш = (n: number) => n * ШИРИНА_КЛАВИШИ + (n - 1) * ЗАЗОР_КЛАВИШ;
/** Как лягут клавиши при данной доступной ширине с нашей правкой. */
const какЛягут = (клавиш: number, доступно: number) =>
  разбиение(клавиш, ширинаРовныхРядов(клавиш, доступно) ?? доступно);

describe('ряды клавиш цифр делятся поровну', () => {
  it('🔴 десять клавиш там, где влезает шесть, — это 5+5, а не 6+4', () => {
    const доступно = подНклавиш(6);
    expect(клавишВРяд(доступно)).toBe(6);
    expect(какЛягут(10, доступно)).toEqual([5, 5]);
  });

  it('🔴 семь клавиш при шести влезающих — 4+3 (ровнее не бывает)', () => {
    expect(какЛягут(7, подНклавиш(6))).toEqual([4, 3]);
  });

  it('что влезает в строку — тем и остаётся: ширину не навязываем', () => {
    expect(ширинаРовныхРядов(5, подНклавиш(6))).toBeUndefined();
    expect(какЛягут(5, подНклавиш(6))).toEqual([5]);
  });

  /**
   * ⚠️ ПРЕДЕЛ, НАЙДЕННЫЙ ЭТОЙ ЖЕ ПРОБОЙ: ровный делёж доступен, пока рядов ДВА. Ширина у ряда
   * одна, перенос заполняет каждый ряд до отказа — поэтому 13 клавиш при шести влезающих дают
   * 5+5+3, а ровнее (5+4+4) одной шириной не разложить. У наших шести режимов клавиш не больше
   * десяти (сторона 9 плюс «Стереть»), и на всех измеренных ширинах это ровно два ряда — проба ниже.
   */
  it('🔴 пока рядов два — они отличаются не больше чем на одну клавишу', () => {
    const кривые: string[] = [];
    for (let д = 240; д <= 420; д += 7) {
      for (let к = 2; к <= 13; к += 1) {
        const ряды = какЛягут(к, д);
        if (ряды.length !== 2) continue;
        if (Math.max(...ряды) - Math.min(...ряды) > 1) кривые.push(`${к} клавиш на ${д}px → ${ряды.join('+')}`);
      }
    }
    expect(кривые).toEqual([]);
  });

  it('три ряда одной шириной ровными не делаются — и это записано, а не забыто', () => {
    expect(какЛягут(13, подНклавиш(6))).toEqual([5, 5, 3]);
  });

  it('🔴 шесть цифровых режимов раздела: на каждой ступени ряды ровные на 360, 390 и 403', () => {
    const кривые: string[] = [];
    for (const [имя, настройка] of Object.entries(РЕЖИМЫ_РАЗДЕЛА)) {
      if (!ЦИФРОВЫЕ.has(имя)) continue;
      for (const шаг of настройка.лестница ?? []) {
        const клавиш = клавишДоски(имя, шаг.параметры) + 1;          // + «Стереть»
        for (const д of [274, 316, 383]) {                            // измеренные ширины ряда: 360, 390, 403
          const ряды = какЛягут(клавиш, д);
          if (ряды.length > 2) кривые.push(`${имя} ${шаг.параметры} на ${д}px → ${ряды.length} ряда`);
          else if (Math.max(...ряды) - Math.min(...ряды) > 1) кривые.push(`${имя} ${шаг.параметры} на ${д}px → ${ряды.join('+')}`);
        }
      }
    }
    expect(кривые).toEqual([]);
  });

  it('есть что мерить: цифровых режимов раздела шесть', () => {
    expect(Object.keys(РЕЖИМЫ_РАЗДЕЛА).filter((и) => ЦИФРОВЫЕ.has(и)).sort())
      .toEqual(['Filling', 'Keen', 'Solo', 'Towers', 'Undead', 'Unequal']);
  });
});
