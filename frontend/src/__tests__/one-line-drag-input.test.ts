/**
 * «ОДНА ЛИНИЯ» — ЛИНИЯ РИСУЕТСЯ ПАЛЬЦЕМ, А НЕ СОБИРАЕТСЯ ТЫКАНЬЕМ В КРУЖКИ.
 *
 * 🔴 ЧТО НАШЛОСЬ 22.08.2026, когда Денис дал живую игру-образец. Ход выбирался
 * ближайшей вершиной в 38 пикселях от пальца — без всякой связи с тем, есть ли
 * туда ребро и вёл ли человек ВДОЛЬ него. Игра про «начерти одним росчерком»
 * превращалась в «ткни по очереди в семь кнопок», и это было ровно то, на что
 * Денис показал словами «а там просто линии».
 *
 * ⚠️ И ЭТО БЫЛ НЕ ТОЛЬКО ВКУС. Палец, проехавший мимо чужой точки, звал ход,
 * которого нет; партия засчитывала ОШИБКУ, ошибка роняла точность, точность
 * решала, засчитан ли уровень. То есть игра наказывала за движение пальцем — за
 * то самое, чего от человека и хочет.
 *
 * Проверяется поведение чистой функции, а не наличие строчек в экране: экран
 * можно переписать, а правило «веду по линии — идёт ход, веду мимо — не идёт»
 * обязано остаться.
 */
import { edgeTargetVertex } from '@/src/games/one-line/core/geometry';
import type { GraphVertex } from '@/src/games/one-line/core/types';

const v = (id: string, x: number, y: number): GraphVertex => ({ id, x, y });

/** Доля доски: вершина радиусом 24 px на доске 620 px — как в экране. */
const R = 24 / 620;
const opts = { radius: R };

const from = v('c', 0.5, 0.5);
const right = v('r', 0.9, 0.5);      // ребро строго вправо
const down = v('d', 0.5, 0.9);       // ребро строго вниз
const near = v('n', 0.62, 0.5);      // короткое ребро вправо, ближе первого

describe('ход рождается ведением вдоль ребра', () => {
  it('палец дошёл до конца ребра — ход идёт', () => {
    expect(edgeTargetVertex(from, [right], 0.89, 0.5, opts)?.id).toBe('r');
  });

  it('палец только тронулся с места — хода ещё нет', () => {
    expect(edgeTargetVertex(from, [right], 0.6, 0.5, opts)).toBeNull();
  });

  /**
   * Допуск вбок один и тот же в пикселях на любой длине ребра. Угловой допуск
   * вёл бы себя наоборот: на коротком ребре не попасть, на длинном — задеть соседнее.
   */
  it('лёгкий увод вбок прощается', () => {
    expect(edgeTargetVertex(from, [right], 0.89, 0.5 + R, opts)?.id).toBe('r');
  });

  it('увод вбок дальше порога — хода нет', () => {
    expect(edgeTargetVertex(from, [right], 0.89, 0.5 + R * 2, opts)).toBeNull();
  });

  it('тот же допуск вбок работает и на КОРОТКОМ ребре', () => {
    expect(edgeTargetVertex(from, [near], 0.61, 0.5 + R, opts)?.id).toBe('n');
    expect(edgeTargetVertex(from, [near], 0.61, 0.5 + R * 2, opts)).toBeNull();
  });

  /**
   * 🔴 НАЗАД — НЕ ВПЕРЁД. Движение в противоположную сторону отклоняется от прямой
   * ребра ровно так же мало, как движение вдоль неё: без явной проверки направления
   * оно читалось бы как ход.
   */
  it('движение в противоположную сторону ходом не считается', () => {
    expect(edgeTargetVertex(from, [right], 0.1, 0.5, opts)).toBeNull();
  });

  it('палец у ближней вершины — дальняя того же направления ещё не взята', () => {
    expect(edgeTargetVertex(from, [right, near], 0.61, 0.5, opts)?.id).toBe('n');
  });

  /**
   * 🔴 ОТВЕТ НЕ ЗАВИСИТ ОТ ПОРЯДКА ПЕРЕБОРА. Когда палец ушёл дальше ОБЕИХ вершин
   * одного направления, подходят обе — и выиграть обязана ближняя, в каком бы
   * порядке они ни лежали в списке. Первая редакция этой проверки подавала их так,
   * что дальняя не проходила по «дошёл до конца» вовсе, и снятие правила «ближняя
   * побеждает» оставалось незамеченным: ответ совпадал случайно.
   */
  it('на развилке побеждает БЛИЖНЯЯ, как бы соседи ни лежали в списке', () => {
    expect(edgeTargetVertex(from, [near, right], 0.89, 0.5, opts)?.id).toBe('n');
    expect(edgeTargetVertex(from, [right, near], 0.89, 0.5, opts)?.id).toBe('n');
  });

  it('перпендикулярное ребро не задевается', () => {
    expect(edgeTargetVertex(from, [down], 0.89, 0.5, opts)).toBeNull();
  });

  /**
   * 🔴 ГЛАВНОЕ. Вершина без непройденного ребра в список соседей не попадает вовсе —
   * значит палец не может позвать ход, которого нет, и партия не может засчитать
   * за это ошибку.
   */
  it('вершина без ребра под палец не попадает', () => {
    expect(edgeTargetVertex(from, [], 0.89, 0.5, opts)).toBeNull();
  });

  it('палец стоит в самой вершине — хода нет', () => {
    expect(edgeTargetVertex(from, [right], from.x, from.y, opts)).toBeNull();
  });
});
