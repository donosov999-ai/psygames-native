/**
 * 🎓 РАЗБОР «МНЕМОНИКИ» УЧИТ ТОМУ ЖЕ, ЧТО ПОКАЗЫВАЕТ ЭКРАН.
 *
 * 🔴 ГЛАВНОЕ: опора в разборе обязана совпадать со словарём 00–99. Разойдись они — человек
 * выучил бы приём, который игра не подтверждает: на экране запоминания под числом стоит
 * ДРУГОЕ слово. Проба сверяет каждую карточку со словарём.
 */
import { pegFor } from '@/src/games/mnemonics/pegs';
import { собратьРазборМнемоники } from '@/src/games/mnemonics/teach';

describe('разбор «Мнемоники»', () => {
  it('🔴 в режиме чисел опора совпадает со словарём 00–99', () => {
    const числа = ['82', '70', '13', '45', '99'];
    const { карточки } = собратьРазборМнемоники(числа, 'numbers', 'ru');
    const опоры = карточки.filter((к) => к.вид === 'опора');
    expect(опоры.length).toBeGreaterThan(0);
    for (const к of опоры) {
      expect(к.поля!.word).toBe(pegFor(Number(к.поля!.n), 'ru'));
      expect(String(к.поля!.why)).toMatch(/=\d/);
    }
  });

  it('🔴 цепочка связывает СОСЕДНИЕ опоры, а не случайные слова', () => {
    const числа = ['82', '70', '13'];
    const { карточки } = собратьРазборМнемоники(числа, 'numbers', 'ru');
    const связки = карточки.filter((к) => к.вид === 'связка');
    expect(связки).toHaveLength(2);
    expect(связки[0]!.поля!.a).toBe(pegFor(82, 'ru'));
    expect(связки[0]!.поля!.b).toBe(pegFor(70, 'ru'));
    expect(связки[1]!.поля!.a).toBe(pegFor(70, 'ru'));
    expect(связки[1]!.поля!.b).toBe(pegFor(13, 'ru'));
  });

  it('🔴 язык без таблицы опор получает ДРУГОЙ приём, а не чужие слова', () => {
    const { карточки } = собратьРазборМнемоники(['82', '70'], 'numbers', 'de');
    expect(карточки[0]!.ключ).toBe('teachMnemoIntroNumbersNoPegs');
    expect(карточки.filter((к) => к.вид === 'опора' && к.поля?.word !== undefined)).toEqual([]);
  });

  it('режим слов строит цепочку из самих слов', () => {
    const слова = ['дом', 'собака', 'окно'];
    const { карточки } = собратьРазборМнемоники(слова, 'words', 'ru');
    expect(карточки[0]!.ключ).toBe('teachMnemoIntroWords');
    const связки = карточки.filter((к) => к.вид === 'связка');
    expect(связки[0]!.поля!.a).toBe('дом');
    expect(связки[0]!.поля!.b).toBe('собака');
  });

  it('🔴 длинный ряд не даёт длинный ролик: показываем не больше четырёх', () => {
    const много = Array.from({ length: 15 }, (_, i) => String(10 + i));
    const { карточки } = собратьРазборМнемоники(много, 'numbers', 'ru');
    expect(карточки.filter((к) => к.вид === 'опора')).toHaveLength(4);
    expect(карточки.length).toBeLessThanOrEqual(12);
  });

  it('🔴 вступление обещает разобрать ровно столько, сколько разбор покажет', () => {
    // 30.09.2026 живьём: «Разберём 5 чисел этого ряда» — и четыре опоры. Длину ряда называет карточка порядка.
    for (const длина of [2, 5, 15]) {
      const ряд = Array.from({ length: длина }, (_, i) => String(10 + i));
      const { карточки } = собратьРазборМнемоники(ряд, 'numbers', 'ru');
      const показано = карточки.filter((к) => к.вид === 'опора').length;
      expect(карточки[0]!.поля!.n).toBe(показано);
      expect(карточки.find((к) => к.вид === 'порядок')!.поля!.n).toBe(длина);
    }
  });

  it('у каждой карточки есть ключ, последняя — итог', () => {
    const { карточки } = собратьРазборМнемоники(['11', '22'], 'numbers', 'ru');
    expect(карточки.filter((к) => !к.ключ)).toEqual([]);
    expect(карточки[карточки.length - 1]!.вид).toBe('готово');
  });
});
