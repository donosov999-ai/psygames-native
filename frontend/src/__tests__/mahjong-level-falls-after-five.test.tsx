import React from 'react';
import { usePersistentLevel } from '@/src/hooks/usePersistentLevel';

// Идиома репозитория: под jest `__dirname` есть, а tsc про него не знает без объявления.
declare const __dirname: string;

jest.mock('@/src/contexts/ProfileContext', () => ({ useProfile: () => ({ profile: { id: 'проба' } }) }));
jest.mock('@/src/services/api', () => ({ getMaxLevelFromSessions: async () => 0 }));
jest.mock('@/src/services/levelCache', () => ({
  cachedLevelValue: () => undefined,
  rememberLevelValue: () => {},
  warmLevelCache: async () => {},
}));

const TestRenderer = require('react-test-renderer');  // eslint-disable-line @typescript-eslint/no-require-imports

/** Смонтировать хук и вернуть его ручки. */
async function поднять(gameId: string, порог?: number) {
  let ручки: any;
  /*
   * ⚠️ ИМЯ ЛАТИНИЦЕЙ, И ЭТО НЕ КАПРИЗ. Правило `react-hooks/rules-of-hooks` узнаёт
   * компонент по ЗАГЛАВНОЙ ЛАТИНСКОЙ букве; «Проба» с кириллической «П» оно
   * компонентом не считает и даёт две ошибки на ровном месте. Остальные имена в
   * файле русские — линту важна только эта буква.
   */
  function Host() {
    /*
     * Один вызов, без ветвления: хук нельзя звать условно. `порог` приходит
     * `undefined`, когда проверяем ОБЩЕЕ правило, — и тогда срабатывает довод по
     * умолчанию самого хука. То есть вторая проба и правда меряет умолчание, а не
     * подсунутую тройку.
     */
    ручки = usePersistentLevel(gameId, 1, порог);
    return null;
  }
  await TestRenderer.act(async () => { TestRenderer.create(React.createElement(Host)); });
  await TestRenderer.act(async () => { ручки.setLevel(10); });
  return () => ручки;
}

describe('лестница маджонга опускается с пятого провала', () => {
  it('🔴 четыре провала подряд уровень НЕ трогают, пятый опускает', async () => {
    const дай = await поднять('mahjong_проба', 5);
    const шаги: string[] = [];
    for (let i = 1; i <= 5; i += 1) {
      let упал = false;
      await TestRenderer.act(async () => { упал = дай().fail(); });
      шаги.push(`${i}: ${упал ? 'опустился' : 'держится'} (${дай().level})`);
    }
    expect(шаги.join(' · ')).toBe(
      '1: держится (10) · 2: держится (10) · 3: держится (10) · 4: держится (10) · 5: опустился (9)',
    );
  });

  it('🔴 у остальных игр порог прежний — третий провал опускает', async () => {
    const дай = await поднять('другая_проба');
    const шаги: string[] = [];
    for (let i = 1; i <= 3; i += 1) {
      let упал = false;
      await TestRenderer.act(async () => { упал = дай().fail(); });
      шаги.push(`${i}: ${упал ? 'опустился' : 'держится'}`);
    }
    expect(шаги.join(' · ')).toBe('1: держится · 2: держится · 3: опустился');
  });

  it('🔴 одна собранная доска стирает серию: после успеха счёт идёт заново', async () => {
    const дай = await поднять('mahjong_серия', 5);
    for (let i = 0; i < 4; i += 1) await TestRenderer.act(async () => { дай().fail(); });
    await TestRenderer.act(async () => { дай().reach(11); });   // успех обнуляет серию
    let упал = false;
    await TestRenderer.act(async () => { упал = дай().fail(); });
    expect(`после успеха первый провал опустил: ${упал}`).toBe('после успеха первый провал опустил: false');
  });
});

/**
 * ⚠️ ВТОРАЯ ПОЛОВИНА, БЕЗ КОТОРОЙ ПЕРВАЯ НИЧЕГО НЕ ЗНАЧИТ.
 *
 * Пробы выше меряют ХУК: дай ему порог — он его соблюдёт. Но хук можно научить
 * чему угодно, а игра будет звать его по-старому, и человек ничего не заметит.
 * В этом самом проекте так уже было: `lvl.fail()` существовал, был верен и просто
 * НЕ ЗВАЛСЯ из маджонга — лестница оставалась односторонней при исправном хуке.
 *
 * Поэтому здесь проверяется ПРОВОДКА: игра просит пятый порог и действительно
 * зовёт провал в той ветке, где доска встала насмерть.
 */
describe('порог доехал до самой игры', () => {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const fs = require('fs');
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const path = require('path');
  const исходник = fs.readFileSync(path.join(__dirname, '../../app/games/mahjong.tsx'), 'utf8') as string;

  it('🔴 маджонг просит у хука порог 5, а не общий', () => {
    const m = /usePersistentLevel\(\s*'mahjong'\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/.exec(исходник);
    expect(`порог у маджонга: ${m ? m[2] : 'не задан вовсе'}`).toBe('порог у маджонга: 5');
  });

  /**
   * ⚠️ КОММЕНТАРИИ ВЫРЕЗАЮТСЯ ДО ПРОВЕРКИ, И ЭТО НЕ ПРИДИРКА. Первая редакция этой
   * пробы искала `lvl.fail()` в теле как есть — и осталась ЗЕЛЁНОЙ, когда я на
   * мутации удалил сам вызов: рядом стоит комментарий со словами «до этого
   * `lvl.fail()` здесь не звался», и регулярка находила его. Проба ловила слово,
   * а не работу. Поймано мутацией, а не чтением.
   */
  const безКомментариев = (t: string) => t.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');

  it('🔴 провал зовётся там же, где пишется проигрыш — в терминальном тупике', () => {
    const тело = /const restartLevel = \(\) => \{([\s\S]*?)\n  \};/.exec(исходник);
    const код = тело ? безКомментариев(тело[1]) : '';
    expect(`запись проигрыша: ${/passed: false/.test(код)} · вызов провала: ${/lvl\.fail\(\)/.test(код)}`)
      .toBe('запись проигрыша: true · вызов провала: true');
  });
});
