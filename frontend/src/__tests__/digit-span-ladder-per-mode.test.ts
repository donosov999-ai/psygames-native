/**
 * 🔴 У КАЖДОГО СПОСОБА ПОДАЧИ СВОЯ ЛЕСТНИЦА.
 *
 * ЗАМЕР ДО (07.09.2026). Уровень был ОДИН на три режима: `usePersistentLevel('digit_span')`
 * на строке 212, а `lvl.reach()` вызывался без единой проверки режима. При этом рекорд
 * автор развёл: очки пишутся только при `delivery === 'screen'`. Значит он знал, что
 * режимы несравнимы, — заслон просто не доехал до второго потребителя. Следствие:
 * зачёт по зрительному охвату («весь ряд разом» читают глазами) двигал ту лестницу,
 * по которой потом играют слуховую петлю.
 *
 * ЧТО СТЕРЕЖЁТ ЭТА ПРОБА. Ключ лестницы у трёх режимов разный, и считается он от
 * ЭФФЕКТИВНОГО режима: без озвучки голосовая партия идёт экраном и обязана двигать
 * экранную лестницу — ровно как она уже двигает экранный рекорд.
 *
 * ⚠️ МИГРАЦИИ НЕТ И НЕ НУЖНО: экранный режим оставлен на прежнем ключе `digit_span`,
 * поэтому накопленный игроками уровень переезжает сам. Проба это тоже стережёт —
 * если кто-то переименует экранный ключ, у всех игроков обнулится уровень.
 */
import { effectiveDelivery, ladderIdFor, DELIVERIES, type Delivery } from '@/app/games/digit-span';

/**
 * 🔴 БЕРЁМ ПРАВИЛО ИЗ ЭКРАНА, А НЕ СВОЮ КОПИЮ.
 *
 * Сначала я написал здесь копию расчёта — и мутация экрана (вернуть общий ключ на
 * все режимы) НЕ покрасила пробу: копия осталась прежней. Гейт мерил сам себя.
 * Это третий за день случай одного класса: сверяешь объявление вместо исполнения.
 * Теперь ключ приходит из `ladderIdFor`, и мутация экрана красит пробу.
 */
const ключЛестницы = ladderIdFor;

describe('digit-span: лестница у каждого режима своя', () => {
  it('🔴 три режима — три разных ключа, ни одного совпадения', () => {
    const ключи = DELIVERIES.map((d) => ключЛестницы(d, null));
    expect(`ключей ${new Set(ключи).size} из ${ключи.length}: ${ключи.join(', ')}`)
      .toBe('ключей 3 из 3: digit_span, digit_span_voice, digit_span_all');
  });

  it('⚠️ экранный ключ НЕ переименован — иначе у всех игроков обнулится уровень', () => {
    expect(ключЛестницы('screen' as Delivery, null)).toBe('digit_span');
  });

  it('без озвучки голосовая партия идёт экраном — и двигает экранную лестницу', () => {
    expect(ключЛестницы('voice' as Delivery, 'sound-off')).toBe('digit_span');
    expect(ключЛестницы('voice' as Delivery, null)).toBe('digit_span_voice');
    // а «разом» экранный: озвучка ему не нужна, лестница своя при любой доступности
    expect(ключЛестницы('all' as Delivery, 'sound-off')).toBe('digit_span_all');
  });
});
