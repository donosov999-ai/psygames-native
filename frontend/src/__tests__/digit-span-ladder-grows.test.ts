import { levelParams, DS_VOLUME_TOP, DELIVERIES } from '@/app/games/digit-span';

/** Подпись уровня = всё, что человек может почувствовать. */
const подпись = (l: number) => JSON.stringify(levelParams(l));

describe('digit-span: лестница различает соседние уровни', () => {
  it('замер ДО зафиксирован: объём и скорость кончаются на L14', () => {
    const top = levelParams(DS_VOLUME_TOP);
    expect(`${top.startLen} цифр, показ ${top.showMs}, пауза ${top.gapMs}`)
      .toBe('9 цифр, показ 350, пауза 550');
    // выше по объёму и скорости не растёт — иначе замер ДО был бы про другое
    expect(levelParams(60).startLen).toBe(top.startLen);
    expect(levelParams(60).showMs).toBe(top.showMs);
    expect(levelParams(60).gapMs).toBe(top.gapMs);
  });

  it('прежняя лестница не тронута: длина, ускорение и обратный ввод на местах', () => {
    expect(levelParams(1).startLen).toBe(4);
    expect(levelParams(6).startLen).toBe(9);
    expect(levelParams(10).reverse).toBe(false);
    expect(levelParams(11).reverse).toBe(true);
    // и ниже плато задержки нет: игрокам в прежней полосе сложность не меняли
    for (let L = 1; L <= DS_VOLUME_TOP; L++) {
      expect(`L${L} holdMs=${levelParams(L).holdMs}`).toBe(`L${L} holdMs=0`);
    }
  });

  /**
   * 🔴 ГЛАВНОЕ. Ни одной пары соседей с одинаковой подписью на всём пробеге.
   */
  it('🔴 ни одного уровня-клона на L1…L60', () => {
    const клоны: string[] = [];
    for (let L = 2; L <= 60; L++) {
      if (подпись(L) === подпись(L - 1)) клоны.push(`L${L}=L${L - 1}`);
    }
    expect(`клонов: ${клоны.length}${клоны.length ? ' — ' + клоны.slice(0, 6).join(', ') : ''}`)
      .toBe('клонов: 0');
  });

  it('🔴 выше плато растёт именно задержка, монотонно', () => {
    for (let L = DS_VOLUME_TOP + 1; L <= 60; L++) {
      const было = levelParams(L - 1).holdMs;
      expect(`L${L}: ${levelParams(L).holdMs}`).toBe(`L${L}: ${было + 700}`);
    }
  });

  /**
   * ⚠️ ЗАДЕРЖКА ОБЩАЯ ДЛЯ ВСЕХ ТРЁХ СПОСОБОВ ПОДАЧИ. Открытие ввода сведено в одно
   * место (`openInput`) именно поэтому: три отдельных `setPhase('input')`
   * разъехались бы — в одном режиме задержка была бы, в другом нет. Тем же когда-то
   * кончилось правило разбора ответа, о чём написано у `expectedDigits`.
   */
  it('способов подачи по-прежнему три, и лестница у них одна', () => {
    expect(DELIVERIES.length).toBe(3);
    expect(levelParams(20).holdMs).toBeGreaterThan(0);
  });
});

