declare const __dirname: string;
declare function require(id: string): any;

const fs = require('fs');
const path = require('path');
const КОРЕНЬ = path.join(__dirname, '../..');
const читать = (о: string) => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8') as string;

/** Ключи базового словаря: `  ключ: {` на двух пробелах отступа. */
function ключиСловаря(): Set<string> {
  const src = читать('src/contexts/LanguageContext.tsx');
  return new Set([...src.matchAll(/^ {2}([a-zA-Z_][\w]*):\s*\{/gm)].map((m) => m[1]));
}

/** Все ключи, которые развилки просят у словаря. */
function ключиРазвилок(): { маршрут: string; поле: string; ключ: string }[] {
  const src = читать('src/constants/hubContents.ts');
  const out: { маршрут: string; поле: string; ключ: string }[] = [];
  // одна карточка — одна фигурная скобка с `route:` внутри
  for (const m of src.matchAll(/\{[^{}]*route:\s*'([^']+)'[^{}]*\}/g)) {
    const карточка = m[0];
    const маршрут = m[1];
    for (const поле of ['nameKey', 'descKey', 'typeKey']) {
      const k = new RegExp(`${поле}:\\s*'([^']+)'`).exec(карточка);
      if (k) out.push({ маршрут, поле, ключ: k[1] });
    }
  }
  return out;
}

describe('ключи развилок существуют в словаре', () => {
  const словарь = ключиСловаря();
  const просят = ключиРазвилок();

  it('есть что проверять — иначе проба зелена вслепую', () => {
    expect(`ключей словаря ${словарь.size > 1000} · ключей развилок ${просят.length > 80}`)
      .toBe('ключей словаря true · ключей развилок true');
  });

  it('🔴 ни один ключ развилки не потерян: иначе человек увидит сам ключ', () => {
    const битые = просят
      .filter((x) => !словарь.has(x.ключ))
      .map((x) => `${x.маршрут} ${x.поле}='${x.ключ}'`);
    expect(битые).toEqual([]);
  });
});
