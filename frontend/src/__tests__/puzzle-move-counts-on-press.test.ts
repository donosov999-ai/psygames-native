/**
 * 🔴 ХОД СЧИТАЕТСЯ ЗА ВЕСЬ ЖЕСТ, А НЕ ПО ОТПУСКАНИЮ.
 *
 * НАЙДЕНО ГЛАЗАМИ, НЕ ГЕЙТОМ, 16.09.2026. На живом стенде «Трубы»: четыре настоящих
 * клика по доске, картинка каждый раз перерисовывается, собственный счёт движка растёт
 * («Соединено: 8/25») — а в шапке всё те же «Ходов: 0». То же у всех, кто играется
 * тычком, а таких в разделе большинство.
 *
 * ПРИЧИНА. У большинства движков Тэтхэма `interpret_move` отдаёт ход на LEFT_BUTTON,
 * то есть на НАЖАТИИ; отпускание после этого честно отвечает «эффекта нет». Экран
 * смотрел ТОЛЬКО на отпускание и результат нажатия выбрасывал.
 *
 * ⚠️ ЦЕНА, кроме подписи в шапке: счёт партии считается как `1000 − ходов × 5`.
 * Значит каждый, кто играет тычком, всегда получал ровно 1000 очков, а лестница
 * видела партию, в которой не было сделано ни одного хода.
 *
 * 🔴 ПОЧЕМУ ПРОБА НА ПРАВИЛО, А НЕ НА ЭКРАН. Под jest мост молчит: `psy_generate`
 * возвращает 0 (причина не найдена, записана в шапке гейта моста), сыграть партию в
 * пробе нечем. Поэтому правило вынесено из экрана в `play.ts` рядом с `нажать()`,
 * которое это и так знало, — и проверяется здесь последовательностями жестов.
 * Живьём проверено кликами на стенде, отдельно.
 */
import { ходЗаЖест, type Жест } from '@/src/games/tatham-bridge/play';

/** Прогнать жест целиком и вернуть, сколько ходов засчитано. */
function ходов(жесты: [Жест, boolean][]): number {
  let накоплено = false, ходов = 0;
  for (const [жест, подействовало] of жесты) {
    const r = ходЗаЖест(жест, подействовало, накоплено);
    накоплено = r.накоплено;
    if (r.ход) ходов += 1;
  }
  return ходов;
}

describe('ход головоломки считается за весь жест', () => {
  it('🔴 эффект на НАЖАТИИ засчитан, даже если отпускание пустое — тот самый дефект', () => {
    expect(ходов([['нажал', true], ['отпустил', false]])).toBe(1);
  });

  it('эффект на отпускании тоже засчитан — движки разные', () => {
    expect(ходов([['нажал', false], ['отпустил', true]])).toBe(1);
  });

  it('🔴 промах по пустому месту ходом НЕ считается (замер аудита 12.09.2026)', () => {
    expect(ходов([['нажал', false], ['отпустил', false]])).toBe(0);
  });

  it('🔴 протяжка — ОДИН ход, а не сорок кадров', () => {
    expect(ходов([['нажал', true], ['ведёт', true], ['ведёт', true], ['ведёт', true], ['отпустил', true]])).toBe(1);
  });

  it('эффект посреди протяжки засчитан, даже если ни нажатие, ни отпускание пустые', () => {
    expect(ходов([['нажал', false], ['ведёт', true], ['отпустил', false]])).toBe(1);
  });

  it('два жеста подряд — два хода, накопленное не протекает во второй', () => {
    expect(ходов([
      ['нажал', true], ['отпустил', false],
      ['нажал', true], ['отпустил', false],
    ])).toBe(2);
  });

  it('🔴 пустой жест ПОСЛЕ удачного не засчитывается — накопленное обнуляется', () => {
    expect(ходов([
      ['нажал', true], ['отпустил', false],
      ['нажал', false], ['отпустил', false],
    ])).toBe(1);
  });
});
