/**
 * СПИСОК РАСФОРМИРОВАННЫХ РАЗВИЛОК НЕ ПРОТУХАЕТ.
 *
 * 12.09.2026 пять развилок расформированы решением Дениса, а их экраны остались
 * на диске: в каждой задаче стоит «удалять только по отдельному слову», и слова
 * он не давал. Чтобы гейты по-прежнему узнавали эти файлы как развилки, они
 * перечислены руками в `_helpers/hubScreens.ts`.
 *
 * 🔴 Ручной список без сторожа — это будущая ложь. Здесь сторож: строка обязана
 * описывать РЕАЛЬНОЕ положение дел, иначе прогон краснеет.
 *   · файла нет   → развилку снесли, строку надо убрать;
 *   · карточка `hub: true` вернулась в каталог → развилка жива, строку убрать.
 * То есть список умеет только сокращаться, и в день сноса уборка не забудется.
 */
import { РАСФОРМИРОВАННЫЕ } from './_helpers/hubScreens';
import { GAMES } from '../constants/games';

// Node-API через require с локальными объявлениями: @types/node в проекте нет.
declare const __dirname: string;
declare function require(m: string): any;
const fs = require('fs');
const path = require('path');

describe('расформированные развилки', () => {
  const ЭКРАНЫ = path.join(__dirname, '../../app/games');

  it('есть что проверять — иначе проба зелена вслепую', () => {
    expect(РАСФОРМИРОВАННЫЕ.size).toBeGreaterThan(0);
  });

  it('🔴 каждая запись описывает живое положение: файл на месте, карточки в каталоге нет', () => {
    const вКаталоге = new Set(
      GAMES.filter((g) => (g as { hub?: boolean }).hub && g.route)
        .map((g) => `${g.route.replace(/^\/games\//, '')}.tsx`),
    );
    const протухшие: string[] = [];
    for (const файл of РАСФОРМИРОВАННЫЕ) {
      if (!fs.existsSync(path.join(ЭКРАНЫ, файл))) {
        протухшие.push(`${файл}: экрана уже нет — убрать строку из hubScreens.ts`);
      }
      if (вКаталоге.has(файл)) {
        протухшие.push(`${файл}: развилка снова в каталоге — убрать строку из hubScreens.ts`);
      }
    }
    expect(протухшие).toEqual([]);
  });
});
