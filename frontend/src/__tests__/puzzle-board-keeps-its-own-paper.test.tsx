import React from 'react';
import renderer, { act } from 'react-test-renderer';
import PuzzleCanvas from '@/src/components/PuzzleCanvas';
import type { Партия } from '@/src/games/tatham-bridge/play';

/** Палитра «Мостов»: 0 — его серый лист, 1 — чернила, чистый чёрный. */
const МОСТЫ = ['212,212,212', '0,0,0', '255,255,255'];

function доска(палитра: string[], фон: string) {
  const партия = {
    ширина: 192, высота: 192, палитра,
    примитивы: [
      { вид: 'прямоугольник', x: 0, y: 0, ш: 192, в: 192, цвет: 0 },
      { вид: 'круг', x: 24, y: 24, r: 14, заливка: 1, контур: 1 },
    ],
    статус: 0,
  } as unknown as Партия;
  let д: renderer.ReactTestRenderer;
  act(() => {
    д = renderer.create(
      <PuzzleCanvas партия={партия} ширина={192} onЖест={() => {}} фон={фон} />,
    );
  });
  const заливки = д!.root
    .findAll((у) => typeof (у.props as any)?.fill === 'string', { deep: true })
    .map((у) => String((у.props as any).fill));
  act(() => { д!.unmount(); });
  return заливки;
}

const врозь = (a: string, b: string) => {
  const ч = (s: string) => (s.startsWith('#')
    ? [1, 3, 5].map((i) => parseInt(s.slice(i, i + 2), 16))
    : s.split(',').map(Number));
  const [p, q] = [ч(a), ч(b)];
  return Math.round(Math.sqrt(p.reduce((s, v, i) => s + (v - q[i]) ** 2, 0)));
};

describe('доска головоломки держит свой лист', () => {
  it('🔴 в тёмной теме фон доски — цвет движка, а не чёрная страница', () => {
    const з = доска(МОСТЫ, '#000000');
    expect(з.length).toBeGreaterThan(0);          // есть что мерить
    expect(з).toContain('212,212,212');           // его лист на месте
    expect(з).not.toContain('#000000');           // страница на доску не попала
  });

  it('🔴 чернила «Мостов» различимы на этом листе', () => {
    const з = доска(МОСТЫ, '#000000');
    const лист = з.find((c) => c === '212,212,212');
    const чернила = з.find((c) => c === '0,0,0');
    expect(лист).toBeDefined();
    expect(чернила).toBeDefined();
    expect(врозь(лист!, чернила!)).toBeGreaterThan(60);
  });

  /**
   * КОНТРОЛЬ С ИЗВЕСТНЫМ ОТВЕТОМ (`PROJECT_REF_RULES §15`). Без него проба
   * зеленела бы и на холсте, который вообще не рисует подложку: «не содержит
   * #000000» истинно и для пустого списка. Здесь холст получает палитру, у
   * которой НЕТ нулевого цвета, — и тогда запасным становится наш фон.
   */
  it('контроль: палитра без нулевого цвета — подложка берётся из темы', () => {
    const з = доска([], '#101014');
    expect(з).toContain('#101014');
  });
});
