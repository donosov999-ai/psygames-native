/**
 * ПРОСЬБУ «ОТКРОЙ МЕНЮ ПАУЗЫ» ПОЛУЧАЕТ ТОЛЬКО ВЕРХНИЙ КАРКАС.
 *
 * Полноэкранный забег закрывает шапку своим слоем и просит меню паузы через
 * службу (`requestPauseMenu`), а каркас в ответ берёт СВОЮ задержку. Под экраном,
 * открытым через push, остаётся смонтированный предыдущий экран со своим
 * каркасом. Если просьба уходит всем подписанным, задержку возьмёт и скрытый
 * каркас. «Продолжить» в видимом меню снимет одну, вторая повиснет — игра стоит
 * при закрытом меню.
 *
 * Проба поведением, по службе без экранов: две подписки, просьба, кто ответил.
 */
import { holdGame, isGameHeld, onPauseMenuRequest, requestPauseMenu } from '@/src/services/gamePause';

/** Подписка, которая ведёт себя как каркас: на просьбу берёт одну задержку. */
function каркас(имя: string, журнал: string[]) {
  let снять: (() => void) | null = null;
  const отписка = onPauseMenuRequest(() => {
    журнал.push(имя);
    if (!снять) снять = holdGame();
  });
  return {
    продолжить: () => { снять?.(); снять = null; },
    размонтировать: () => { снять?.(); снять = null; отписка(); },
  };
}

describe('просьба меню паузы', () => {
  it('без каркаса просить некого — false, задержки нет', () => {
    expect(requestPauseMenu()).toBe(false);
    expect(isGameHeld()).toBe(false);
  });

  it('🔴 два каркаса в стопке — отвечает только верхний, и «Продолжить» отпускает игру', () => {
    const журнал: string[] = [];
    const скрытый = каркас('скрытый', журнал);
    const видимый = каркас('видимый', журнал);
    try {
      expect(requestPauseMenu()).toBe(true);
      expect(журнал).toEqual(['видимый']);
      expect(isGameHeld()).toBe(true);

      видимый.продолжить();
      // Разошли просьбу всем — здесь осталась бы задержка скрытого каркаса.
      expect(`игра после «Продолжить» стоит: ${isGameHeld()}`).toBe('игра после «Продолжить» стоит: false');
    } finally {
      // Упавшая проверка не должна оставлять подписки и задержки следующей пробе.
      видимый.размонтировать();
      скрытый.размонтировать();
    }
  });

  it('верхний ушёл (назад) — просьбу снова получает оставшийся', () => {
    const журнал: string[] = [];
    const нижний = каркас('нижний', журнал);
    const верхний = каркас('верхний', журнал);
    верхний.размонтировать();

    expect(requestPauseMenu()).toBe(true);
    expect(журнал).toEqual(['нижний']);

    нижний.размонтировать();
    expect(isGameHeld()).toBe(false);
    expect(requestPauseMenu()).toBe(false);
  });
});
