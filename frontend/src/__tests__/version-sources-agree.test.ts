declare const __dirname: string;
declare function require(id: string): any;

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '../..');          // frontend/
const РЕПО = path.resolve(КОРЕНЬ, '..');                   // корень репозитория

const источники: Array<[string, () => string | undefined]> = [
  ['frontend/app.json', () => JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'app.json'), 'utf8')).expo?.version],
  ['frontend/package.json', () => JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'package.json'), 'utf8')).version],
  ['src-tauri/tauri.conf.json', () => JSON.parse(fs.readFileSync(path.join(РЕПО, 'src-tauri/tauri.conf.json'), 'utf8')).version],
];

describe('версия приложения в трёх файлах', () => {
  it('все три источника называют одну и ту же версию', () => {
    const снято = источники.map(([имя, читать]) => [имя, читать()] as const);
    const значения = [...new Set(снято.map(([, v]) => v))];
    // Сообщение перечисляет источники поимённо: «не совпали» без имён бесполезно.
    expect({ различных: значения.length, снято: Object.fromEntries(снято) })
      .toEqual({ различных: 1, снято: Object.fromEntries(снято) });
  });

  it('версия похожа на версию, а не на пустоту', () => {
    for (const [имя, читать] of источники) {
      expect(`${имя}: ${читать()}`).toMatch(/: \d+\.\d+\.\d+$/);
    }
  });

  it('🔴 самая свежая запись «Что нового» — про ЭТУ версию', () => {
    const src = fs.readFileSync(path.join(КОРЕНЬ, 'src/constants/whatsNew.ts'), 'utf8');
    const первая = /version:\s*'([\d.]+)'/.exec(src);
    const текущая = источники[0][1]();
    /**
     * ⚠️ Зачем это здесь. Собрать сборку без записи в «Что нового» легко, и тогда
     * человек после обновления видит пустую модалку — то есть обновление, про
     * которое нечего сказать. Проверяем ровно первую запись: список ведётся
     * сверху вниз, и новая версия обязана оказаться на первом месте.
     */
    expect(`whatsNew первая запись: ${первая?.[1]}`).toBe(`whatsNew первая запись: ${текущая}`);
  });
});
