/**
 * ВЕРСИЯ ЖИВЁТ В ТРЁХ ФАЙЛАХ, И ОНИ ОБЯЗАНЫ СОВПАДАТЬ.
 *
 * 🔴 СЛУЧАЙ, РАДИ КОТОРОГО НАПИСАНО. 27.08.2026 я поднял версию до 1.240.1 в
 * `frontend/app.json` и `frontend/package.json`, собрал приложение — и получил
 * бандл `PsyGames_1.240.0_aarch64.dmg`. Третий источник, `src-tauri/tauri.conf.json`,
 * остался на 1.240.0, и именно он попадает в Info.plist, то есть В ТО, ЧТО ВИДИТ
 * ЧЕЛОВЕК в «О программе».
 *
 * ⚠️ Синхронизировать их было НЕКОМУ: поиск по сборке и скриптам не дал ни одной
 * строки, которая бы правила `tauri.conf.json` по версии из `app.json`. Три
 * источника, ноль связи — расходились они молча, и заметить это можно было только
 * прочитав имя собранного файла.
 *
 * Почему это дороже, чем кажется. Проверка обновлений (`appUpdates.ts`) сравнивает
 * версию ИЗ ПРИЛОЖЕНИЯ с `psy-games.pro/play/version.json`, который пишется из
 * тега. Если версия в приложении отстаёт от тега, человеку будут вечно предлагать
 * обновление, которое он уже поставил; если опережает — не предложат никогда.
 *
 * ⚠️ `Cargo.toml` намеренно НЕ проверяется: там 1.0.0 и это версия рустового ящика,
 * а не приложения. Tauri берёт версию из `tauri.conf.json`.
 */
declare const __dirname: string;
declare function require(id: string): any;

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '../..');          // frontend/
const РЕПО = path.resolve(КОРЕНЬ, '..');                   // корень репозитория

const источники: Array<[string, () => string | undefined]> = [
  ['frontend/app.json', () => JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'app.json'), 'utf8')).expo?.version],
  ['frontend/package.json', () => JSON.parse(fs.readFileSync(path.join(КОРЕНЬ, 'package.json'), 'utf8')).version],
  ['src-tauri/tauri.conf.json', () => JSON.parse(fs.readFileSync(path.join(РЕПО, 'src-tauri/tauri.conf.json'), 'utf8')).version],
];

describe('версия приложения в трёх файлах', () => {
  it('все три источника называют одну и ту же версию', () => {
    const снято = источники.map(([имя, читать]) => [имя, читать()] as const);
    const значения = [...new Set(снято.map(([, v]) => v))];
    // Сообщение перечисляет источники поимённо: «не совпали» без имён бесполезно.
    expect({ различных: значения.length, снято: Object.fromEntries(снято) })
      .toEqual({ различных: 1, снято: Object.fromEntries(снято) });
  });

  /**
   * 🔴 ЛИНИЯ ОДНА НА ВСЕ СБОРКИ — И ИСТОЧНИК У НЕЁ ОДИН.
   *
   * 📍 Решение Дениса 24.09.2026: «льём везде на Flutter, никаких двух веток».
   *
   * ⚠️ ЭТА ПРОВЕРКА ЗАМЕНИЛА СВОЮ ЖЕ ПРЕДЫДУЩУЮ РЕДАКЦИЮ, И ЭТО ВАЖНО ПОНЯТЬ.
   * Часом раньше здесь стояло «версия веба не заходит в линию 2.55.x, занятую
   * гибридом» — правило, закреплявшее РАЗДЕЛЕНИЕ линий. Денис его отменил: линия
   * одна. Оставить старую проверку значило бы сторожить отменённое решение.
   *
   * Теперь разделения нет по построению: `flutter-testflight.yml` берёт номер из
   * `frontend/app.json`, а не из поля запуска. Сторожим то, что осталось, — чтобы
   * ручной ход в запуске не вернул вторую линию через чёрный ход.
   */
  it('🔴 гибрид берёт версию из app.json, а не из поля запуска', () => {
    const поток = fs.readFileSync(
      path.join(РЕПО, '.github/workflows/flutter-testflight.yml'), 'utf8') as string;
    expect(`берёт из app.json: ${поток.includes("require('./frontend/app.json').expo.version")}`)
      .toBe('берёт из app.json: true');
    // Поле запуска осталось запасным ходом, но обязательным быть не может:
    // обязательное поле — это приглашение снова развести линии руками.
    expect(`версия обязательна в запуске: ${/version:\s*\n\s*description:[^\n]*\n\s*required: true/.test(поток)}`)
      .toBe('версия обязательна в запуске: false');
  });

  it('версия похожа на версию, а не на пустоту', () => {
    for (const [имя, читать] of источники) {
      expect(`${имя}: ${читать()}`).toMatch(/: \d+\.\d+\.\d+$/);
    }
  });

  /**
   * 🔴 ЗАПИСЬ «ЧТО НОВОГО» ЧИТАЕТСЯ ИМПОРТОМ, А НЕ РЕГУЛЯРКОЙ.
   *
   * Прежняя редакция брала версию из файла регуляркой по тексту — и 02.09.2026
   * пропустила сломанный файл: при вставке записи 2.26.0 потерялась открывающая
   * скобка объекта, `WHATS_NEW` перестал быть валидным TypeScript. Регулярка
   * нашла нужную строку и позеленела; сборка v2.26.0 упала на `tsc` уже в CI,
   * тег пришлось хоронить и выпускать патч.
   *
   * Импорт делает подмену невозможной: не парсится — тест падает здесь, до тега.
   */
  it('🔴 самая свежая запись «Что нового» — про ЭТУ версию, и файл цел', () => {
    const { WHATS_NEW } = require('../constants/whatsNew');
    const текущая = источники[0][1]();
    expect(Array.isArray(WHATS_NEW)).toBe(true);
    expect(WHATS_NEW.length).toBeGreaterThan(3);
    /**
     * ⚠️ Зачем это здесь. Собрать сборку без записи в «Что нового» легко, и тогда
     * человек после обновления видит пустую модалку — то есть обновление, о
     * котором нечего сказать. Проверяем ровно первую запись: список идёт сверху
     * вниз, и новая версия обязана оказаться на первом месте.
     */
    expect(`whatsNew первая запись: ${WHATS_NEW[0].version}`).toBe(`whatsNew первая запись: ${текущая}`);
    // И запись не пустая: обе локали заполнены — иначе модалка пуста на половине языков.
    expect(WHATS_NEW[0].ru.length).toBeGreaterThan(0);
    expect(WHATS_NEW[0].en.length).toBeGreaterThan(0);
    expect(WHATS_NEW[0].ru.every((s: string) => s.trim().length > 10)).toBe(true);
    expect(WHATS_NEW[0].en.every((s: string) => s.trim().length > 10)).toBe(true);
  });
});
