/**
 * 🔴 ЦЕНА ОШИБКИ В «ДЕТСКОМ МАТЕ» РАСТЁТ С УРОВНЕМ.
 *
 * Правило Дениса 06.09.2026 «потолков нет нигде». Порог прохождения стоял
 * константой 0,75 на всех сорока ступенях — ось «цена ошибки» была не отвергнута,
 * а не заведена.
 *
 * 📍 ЗАМЕР ПО ЖИВЫМ ПОДХОДАМ (`cognitive_sessions`, 23 записи на 06.09.2026):
 * медиана доли верных 0,88; порог 0,75 проходят 70% подходов, 0,875 — 65%.
 * ⚠️ Все 23 подхода лежат на уровнях 1–16, то есть НИЖЕ рубежа: на живых данных
 * правка не меняет ни одного подхода. Калибрована она устройством колоды, а не
 * выборкой, и это записано прямо — как появятся подходы выше восемнадцатого,
 * перемерить.
 */
import { допускПромахов, порогУровня } from '@/src/games/scholars-mate/core/run';
import { levelParams, LEVELS } from '@/src/games/scholars-mate/core/deck';

describe('порог прохождения по уровням', () => {
  it('🔴 допуск промахов падает 2 → 1, и рубеж там, где появляются угадываемые вопросы', () => {
    const ряд = Array.from({ length: LEVELS }, (_, i) => допускПромахов(i + 1));
    expect(`допуск по уровням: ${[...new Set(ряд)].join(',')}`).toBe('допуск по уровням: 2,1');
    const рубеж = ряд.findIndex((v, i) => i > 0 && v !== ряд[i - 1]!) + 1;
    expect(`рубеж допуска: ${рубеж}`).toBe('рубеж допуска: 19');
    // На том же уровне в колоду входит `threat` — вопрос «да/нет», угадываемый 1/2.
    const доРубежа = levelParams(рубеж - 1).kinds.includes('threat');
    const наРубеже = levelParams(рубеж).kinds.includes('threat');
    expect(`угадываемые вопросы: до рубежа ${доРубежа}, на рубеже ${наРубеже}`)
      .toBe('угадываемые вопросы: до рубежа false, на рубеже true');
  });

  it('🔴 порог считается ИЗ ДЛИНЫ подхода, а не задан долей', () => {
    // 8 позиций, допуск 2 → 0,75; 10 позиций, допуск 1 → 0,9; 8 и допуск 1 → 0,875.
    expect(`ур.1 (${levelParams(1).count} поз): ${порогУровня(1, levelParams(1).count).toFixed(3)}`)
      .toBe('ур.1 (8 поз): 0.750');
    expect(`ур.19 (${levelParams(19).count} поз): ${порогУровня(19, levelParams(19).count).toFixed(3)}`)
      .toBe('ур.19 (10 поз): 0.900');
    expect(`ур.40 (${levelParams(40).count} поз): ${порогУровня(40, levelParams(40).count).toFixed(3)}`)
      .toBe('ур.40 (8 поз): 0.875');
  });

  it('🔴 порог НИКОГДА не требует безошибочности — иначе это лотерея под секундомером', () => {
    const жёсткие: string[] = [];
    for (let L = 1; L <= LEVELS; L++) {
      const n = levelParams(L).count;
      if (порогУровня(L, n) > (n - 1) / n + 1e-9) жёсткие.push(`ур.${L}`);
      if (допускПромахов(L) < 1) жёсткие.push(`ур.${L}: допуск 0`);
    }
    expect(`уровней без права на промах: ${жёсткие.length} → ${жёсткие.join(',')}`)
      .toBe('уровней без права на промах: 0 → ');
  });

  it('🔴 порог растёт монотонно — лестница не проседает', () => {
    const ряд = Array.from({ length: LEVELS }, (_, i) => допускПромахов(i + 1));
    expect(`допуск не растёт нигде: ${ряд.every((v, i) => i === 0 || v <= ряд[i - 1]!)}`)
      .toBe('допуск не растёт нигде: true');
  });

  it('вырожденный подход не делит на ноль', () => {
    expect(порогУровня(1, 0)).toBe(1);
  });
});
