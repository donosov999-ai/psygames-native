/**
 * 🔴 ТЕМАТИЧЕСКАЯ ЗАРЯДКА ДЛИТСЯ СТОЛЬКО, СКОЛЬКО ОБЕЩАЕТ.
 *
 * 📍 ПОЧЕМУ ЭТОТ НАБОР ПОЯВИЛСЯ ОТДЕЛЬНО ОТ `warmup-duration-honest`. Тот держит
 * ±25 % у УТРЕННЕЙ зарядки и появился 08.09.2026 по отчёту тестировщиков
 * `c810938d` («просишь пять минут — получаешь 2:45»). Но правка тогда дошла
 * только до `warmup.ts`, а три тематические карточки — шахматы, слова, языки —
 * остались на старой единице, и гейта на них не было ВООБЩЕ.
 *
 * Замер 09.09.2026 до починки, доля фактического времени к обещанному:
 *   шахматы  5/10/15 →  0,50 / 0,41 / 0,42
 *   слова    5/10/15 →  1,11 / 1,44 / 1,33
 *   языки    5/10/15 →  0,75 / 0,81 / 0,72
 * Врут в РАЗНЫЕ стороны: `chess_blind` объявлен 150 с при замере 39, `anagrams`
 * — 90 при 200. Общим коэффициентом такое не лечится, поэтому `темаШаги` теперь
 * считает бюджет через `estimateStepSec`, а не через объявленное поле `секунд`.
 *
 * ⚠️ ДОПУСК ТОТ ЖЕ ±25 %, что у утренней, и это нарочно: два разных допуска в
 * одном приложении означали бы, что «честно» зависит от того, какую кнопку
 * нажали. Верхняя граница нужна не меньше нижней — зарядка, которая вместо
 * обещанных десяти минут идёт четырнадцать, ломает планы человека так же.
 */
import {
  ДЛИТЕЛЬНОСТИ, темаШаги, замерШагов, chessWarmupSteps, wordWarmupSteps, type WarmupMinutes,
} from '@/src/services/chessWarmup';
import { языковыеТемы } from '@/src/services/languageFlow';
import { estimateStepSec } from '@/src/services/gameDuration';

const УРОВНИ = { vocab_srs: 4, cloze: 7, semantic_sort: 2, lexical_decision: 9 };

const КАРТОЧКИ: readonly [string, (m: WarmupMinutes) => ReturnType<typeof темаШаги>][] = [
  ['шахматы', (m) => chessWarmupSteps({ minutes: m, mateLevel: 3, blindLevel: 3 })],
  ['слова', (m) => wordWarmupSteps({ minutes: m, anagramsLevel: 3, proofreadingLevel: 3 })],
  ['языки', (m) => темаШаги(языковыеТемы(УРОВНИ), m)],
];

describe('тематическая зарядка укладывается в обещание', () => {
  it('🔴 каждая карточка на каждой длительности — в пределах ±25 %', () => {
    const плохо: string[] = [];
    for (const [имя, сбор] of КАРТОЧКИ) {
      for (const м of ДЛИТЕЛЬНОСТИ) {
        const доля = замерШагов(сбор(м)) / (м * 60);
        if (доля < 0.75 || доля > 1.25) плохо.push(`${имя} ${м}м: ${доля.toFixed(2)}`);
      }
    }
    expect(`вне допуска: ${плохо.join(', ') || '—'}`).toBe('вне допуска: —');
  });

  /**
   * 🔴 КОНТРПРОБА, БЕЗ КОТОРОЙ ГЕЙТ ВЫШЕ НИЧЕГО НЕ ЗНАЧИТ. Если считать план
   * ОБЪЯВЛЕННЫМИ числами — как было до 09.09.2026, — хотя бы одна карточка
   * обязана выйти за допуск. Иначе замер и объявление совпадают, и переход на
   * `estimateStepSec` был бы пустой правкой.
   */
  it('🔴 по объявленным числам хотя бы одна карточка выходит за допуск', () => {
    const вне: string[] = [];
    for (const [имя, сбор] of КАРТОЧКИ) {
      for (const м of ДЛИТЕЛЬНОСТИ) {
        const объявлено = сбор(м).reduce((s, x) => s + x.est_duration_sec, 0);
        const доля = объявлено / (м * 60);
        if (доля < 0.75 || доля > 1.25) вне.push(`${имя} ${м}м`);
      }
    }
    expect(`вышедших за допуск по объявленному: ${вне.length > 0}`).toBe('вышедших за допуск по объявленному: true');
  });

  it('🔴 дольше время — строго больше подходов, у каждой карточки', () => {
    for (const [имя, сбор] of КАРТОЧКИ) {
      const n = ДЛИТЕЛЬНОСТИ.map((м) => сбор(м).length);
      for (let i = 1; i < n.length; i += 1) {
        expect(`${имя}: ${ДЛИТЕЛЬНОСТИ[i - 1]}м ${n[i - 1]} < ${ДЛИТЕЛЬНОСТИ[i]}м ${n[i]}`)
          .toBe(`${имя}: ${ДЛИТЕЛЬНОСТИ[i - 1]}м ${n[i - 1]} < ${ДЛИТЕЛЬНОСТИ[i]}м ${n[i]! > n[i - 1]! ? n[i] : 'НЕ БОЛЬШЕ'}`);
      }
    }
  });

  it('длительностей четыре, и двадцать среди них — литералом', () => {
    expect([...ДЛИТЕЛЬНОСТИ]).toEqual([5, 10, 15, 20]);
  });

  it('пустая тема не роняет и не даёт шагов', () => {
    expect(темаШаги([], 10)).toEqual([]);
    expect(замерШагов([])).toBe(0);
  });

  /**
   * ⚠️ ЗАПАСНОЕ ЗНАЧЕНИЕ ЖИВОЕ, И ЭТО ПРОВЕРЯЕТСЯ. `cloze` и `lexical_decision`
   * на 09.09.2026 в снимке медиан отсутствуют — партий мало. Для них
   * `estimateStepSec` обязан вернуть объявленное число, а не ноль и не выдумку;
   * иначе языковая зарядка молча считала бы их бесплатными.
   */
  it('🔴 игра без замера оценивается объявленным числом, а не нулём', () => {
    const шаг = { game_id: 'cloze', game_route: '/games/cloze', est_duration_sec: 100 };
    expect(estimateStepSec(шаг)).toBe(100);
    const свой = { game_id: 'vocab_srs', game_route: '/games/vocab-srs', est_duration_sec: 60 };
    expect(estimateStepSec(свой)).not.toBe(60);   // у неё замер есть — берётся он
  });
});
