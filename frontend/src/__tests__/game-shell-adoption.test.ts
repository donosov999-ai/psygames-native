/**
 * ПАРТИЯ ИДЁТ В ОБЩЕМ КАРКАСЕ, А НЕ В СВОЁМ.
 *
 * 🔴 ЧТО ДАЁТ КАРКАС И ЧЕГО ЛИШЁН ЭКРАН БЕЗ НЕГО. `GameShell` держит две вещи,
 * которые нельзя завести «по желанию каждого экрана»:
 *   · партия встаёт на паузу, пока открыто окно отзыва — иначе человек пишет о
 *     проблеме, а время партии идёт;
 *   · «назад» (в шапке И аппаратная) спрашивает, когда терять есть что, — иначе
 *     начатая партия стирается молча.
 *
 * 20.08.2026 шесть новых игр перевели на каркас. `math-slider` пропустили, и
 * нашлось это не гейтом, а сверкой руками месяц спустя: гейт `game-frame-edges`
 * проверял ПОЛЯ и отступы каркаса — у тех, кто его уже взял, — и про экран,
 * который каркас не взял вовсе, не знал ничего.
 *
 * ⚠️ ПОЧЕМУ СПИСОК ИСКЛЮЧЕНИЙ БЕРЁТСЯ ИЗ КАТАЛОГА, А НЕ ПИШЕТСЯ ЗДЕСЬ. Каркас не
 * нужен страницам-развилкам: они не игра, а выбор из нескольких. Развилки уже
 * помечены в каталоге (`hub: true`) — это тот же признак, по которому они не
 * считаются в «69 упражнений». Свой список рядом с каталогом разошёлся бы с ним
 * молча, и однажды новая развилка стала бы требовать каркас, а новая игра —
 * нет. Один источник, а не два.
 */
declare const __dirname: string;
declare function require(m: string): any;
const { readFileSync, readdirSync } = require('fs');
const { join } = require('path');

const APP_GAMES = join(__dirname, '../../app/games');
const CATALOGUE = join(__dirname, '../constants/games.ts');

/** Комментарии срезаем: слово `GameShell` встречается в пояснениях соседей. */
const code = (src: string): string =>
  src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

/** route → развилка ли. Читаем каталог, а не пишем список руками. */
function hubsByRoute(): Map<string, boolean> {
  const src = readFileSync(CATALOGUE, 'utf8') as string;
  const map = new Map<string, boolean>();
  for (const m of src.matchAll(/route:\s*'([^']+)'([\s\S]{0,400}?)(?=\n\s{2}\}|\n\s{4}id:)/g)) {
    map.set(m[1], /hub:\s*true/.test(m[2]));
  }
  // Развилка может стоять и ПЕРЕД route в записи — добираем вторым проходом.
  for (const m of src.matchAll(/\{[\s\S]{0,800}?\}/g)) {
    const r = m[0].match(/route:\s*'([^']+)'/);
    if (r) map.set(r[1], /hub:\s*true/.test(m[0]));
  }
  return map;
}

const screens = (): string[] =>
  readdirSync(APP_GAMES).filter((f: string) => f.endsWith('.tsx')).map((f: string) => f.replace(/\.tsx$/, ''));

describe('партия идёт в общем каркасе', () => {
  it('есть что проверять — иначе гейт зелен вслепую', () => {
    expect(screens().length).toBeGreaterThanOrEqual(60);
    expect([...hubsByRoute().values()].filter(Boolean).length).toBeGreaterThanOrEqual(3);
  });

  it('🔴 каждый экран игры взял общий каркас, кроме страниц-развилок', () => {
    const hubs = hubsByRoute();
    const без: string[] = [];
    for (const name of screens()) {
      const src = code(readFileSync(join(APP_GAMES, `${name}.tsx`), 'utf8') as string);
      if (/<GameShell[\s>]/.test(src)) continue;
      const hub = hubs.get(`/games/${name}`);
      if (hub === true) continue;                       // развилка — каркас не нужен
      без.push(hub === undefined
        ? `${name}: нет каркаса И нет записи в каталоге — либо игра без каркаса, либо экран-сирота`
        : `${name}: игра без общего каркаса — нет паузы на время отзыва и вопроса при выходе`);
    }
    expect(без).toEqual([]);
  });

  /**
   * ⚠️ ПРО ВТОРОЙ ВЫХОД ЗДЕСЬ ПРОВЕРКИ НЕТ — И ЭТО НАРОЧНО. Она была, и на первом
   * же прогоне «нашла дыру» в `memory-palace`: экран на каркасе отдаёт модулю
   * `onExit`. Дырой это не было. Разбор в `module-games-guard.test.ts` уже
   * сделан и точнее моего: модуль рисует «Выход» ровно в двух ветках — на экране
   * ПРАВИЛ (партия не начата, терять нечего) и на своём экране ИТОГА, который
   * выключен пропом `showOwnResults={false}`. До живой партии кнопка не доезжает.
   *
   * Моя проверка смотрела только на наличие пропа и объявила бы дырой любой
   * такой случай. Проверка, которая краснеет на правильном коде, дороже, чем её
   * отсутствие: её отключают целиком. Поэтому вопрос второго выхода остаётся за
   * тем гейтом, где он разобран, а этот держит ровно одно — что каркас ВЗЯТ.
   */
});
