/**
 * 🔴 СТРОГАЯ УКЛАДКА СУДИТ ПО ВЗЯТОМУ ТОВАРУ, А НЕ ПО ВЕРХНЕМУ.
 *
 * 📍 ПОВОД (задача 230f2887, найдено 23.09.2026 при переносе экрана на Flutter).
 * В вебе `canPlaceInto` брала тип ВЕРХНЕГО товара ниши-источника
 * (`src[src.length - 1]`), а `moveItem` уносила тот, по которому ткнули
 * (`splice` по `fromIdx`). Пока берут верхний — одно и то же; стоит взять из
 * середины ряда, и проверка считает один вид, а уезжает другой. Со строгой
 * укладки (с L30) ход проходил, и в нише оказывались два разных вида.
 *
 * ⚠️ ЧТО ЭТА ПРОБА ПОКРЫВАЕТ И ЧЕГО НЕ ПОКРЫВАЕТ — ЧЕСТНО.
 * Она пиНИТ ПРАВИЛО: `canPlace` обязана решать по ПЕРЕДАННОМУ виду, и для двух
 * разных видов из одной ниши ответы обязаны расходиться. Это и есть то, что
 * экран нарушал, передавая не тот вид.
 * Она НЕ доходит до самого экрана: `app/games/goods-sort.tsx` не рендерит ни
 * одна проба раздела — замер в шапке `goods-sort-honest`: экран стоит 3298 мс
 * против 14 мс у ядра. Заводить харнесс на 3,3 с ради кода, который с переезда
 * на Flutter до людей не доходит (`/games/goods-sort` перехвачен нативно,
 * `hybrid_app.dart:137`), несоразмерно. Поведение перенесённого экрана сторожит
 * `flutter/test/goods_sort_screen_test.dart`.
 */
import { canPlace, makeBoard } from '@/src/games/goods-sort/core/board';

/** Ниша 0: снизу вверх [вид 7, вид 3]. Верхний — 3, под ним — 7. */
const доска = () => makeBoard([[7, 3], [3], []], [3, 3, 3]);

describe('строгая укладка судит по взятому товару', () => {
  it('премиса: в нише-источнике ДВА разных вида, и верхний не тот, что внизу', () => {
    const b = доска();
    expect(b.cells[0]).toEqual([7, 3]);
    expect(b.cells[0]![b.cells[0]!.length - 1]).toBe(3);
  });

  it('🔴 ГЛАВНОЕ: в нишу с видом 3 можно положить вид 3 и НЕЛЬЗЯ вид 7', () => {
    const b = доска();
    // Ниша 1 занята видом 3 — со строгой укладкой туда идёт только свой вид.
    expect(canPlace(b, 1, 3, true)).toBe(true);
    expect(canPlace(b, 1, 7, true)).toBe(false);
    // Именно на этой разнице экран и спотыкался: он спрашивал про вид 3
    // (верхний), а уносил вид 7 (взятый из середины).
  });

  it('без строгой укладки вид не важен — только место', () => {
    const b = доска();
    expect(canPlace(b, 1, 7, false)).toBe(true);
    expect(canPlace(b, 1, 3, false)).toBe(true);
  });

  it('в пустую нишу можно любой вид, и при строгой тоже', () => {
    const b = доска();
    expect(canPlace(b, 2, 7, true)).toBe(true);
    expect(canPlace(b, 2, 3, true)).toBe(true);
  });

  it('🔴 полная ниша отказывает ЛЮБОМУ виду — место проверяется раньше вида', () => {
    const b = makeBoard([[7, 7, 7], [3], []], [3, 3, 3]);
    expect(canPlace(b, 0, 7, true)).toBe(false);
    expect(canPlace(b, 0, 7, false)).toBe(false);
  });
});
