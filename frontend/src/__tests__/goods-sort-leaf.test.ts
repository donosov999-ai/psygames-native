/**
 * ЛИСТ СОРТИРОВКИ ОСТАЁТСЯ ЛИСТОМ. Проверка загрузкой, а не чтением импортов.
 *
 * 🔴 ЧТО СТОЯЛО ЗА ЭТИМ ГЕЙТОМ.
 *
 * До 06.09.2026 вся арифметика уровня — правила, раздача, цели, раскладка —
 * лежала в `app/games/goods-sort.tsx` вместе с вёрсткой, картинками и звуком.
 * ТРИДЦАТЬ ЧЕТЫРЕ пробы звали оттуда `levelCfg(L)`, и каждая ради этого
 * поднимала весь экран.
 *
 * ЗАМЕР 06.09.2026 (`require` внутри пробы, время в мс, модули — по `require.cache`):
 *   экран  3298 мс · +845 модулей react-native/expo
 *   лист     14 мс · +0
 * Двести тридцать пять раз. Тридцать четыре гейта — около двух минут прогона,
 * уходивших в загрузку вёрстки ради чистых чисел.
 *
 * ⚠️ ПОЧЕМУ СТОРОЖ НУЖЕН ИМЕННО ТАКОЙ. Граница «лист без React» держится
 * НАМЕРЕНИЕМ, а рушится одной строкой: `import { LevelRule } from '…/LevelRules'`
 * вместо `import type` — и React вернулся, а все пробы остались зелёными, только
 * прогон снова стал долгим. Разбор импортов глазами эту разницу не ловит:
 * `import type` и `import` пишутся почти одинаково, и через ТРЕТИЙ модуль
 * зависимость приезжает вообще без упоминания React в этом файле.
 *
 * Поэтому здесь не разбор текста, а ЗАГРУЗКА: лист требуется первым в чистом
 * окружении, и считается, сколько react-модулей после этого прибавилось в кэше.
 * Ноль — лист. Не ноль — уже не лист, и гейт называет виновника по имени.
 */

/**
 * Модули, ради ухода от которых лист и заведён — ДВА рода, и второй важнее.
 *
 * 🔴 ЗАМЕР МУТАЦИЙ 06.09.2026 объяснил, почему одного рода мало. Подмена
 * `import type { LevelRule }` на обычный `import` возвращает React в лист — но
 * счётчик из `node_modules` этого НЕ ВИДИТ: `react-native` уже лежит в кэше,
 * его туда положила подкладка `jest-expo` до первой строки пробы. Прибавка
 * ноль, а зависимость есть.
 *
 * Видно её по ВТОРОМУ роду: вместе с `LevelRules` в кэш приезжает наш
 * собственный компонент из `src/components/`. Свои экранные папки — надёжный
 * признак, потому что их подкладка не грузит никогда.
 */
const ТЯЖЁЛЫЕ = /node_modules[\\/](react-native|react-dom|expo-[\w-]+|@expo|@react-navigation|react-native-[\w-]+)[\\/]/;

/** Свои экранные папки: компонент, хук, контекст или сам экран в кэше = лист протёк. */
const СВОИ_ЭКРАННЫЕ = /[\\/](app[\\/]games|src[\\/](components|hooks|contexts))[\\/]/;

/*
 * ⚠️ `require.cache` не описан в типах проекта (узловых типов в tsconfig нет),
 * поэтому берётся приведением — точечно и с причиной, как соседние пробы делают
 * с `readFileSync`. Молча копить предупреждение в общем долге хуже.
 */
function тяжёлыеВКэше(): string[] {
  const кэш = (require as unknown as { cache: Record<string, unknown> }).cache;
  return Object.keys(кэш).filter((k) => ТЯЖЁЛЫЕ.test(k) || СВОИ_ЭКРАННЫЕ.test(k));
}

describe('лист сортировки не тянет экран', () => {
  /**
   * 🔴 СНИМОК ДО — ОБЯЗАТЕЛЕН. Подкладка `jest-expo` сама поднимает часть
   * react-native ДО первой строки пробы (замер: 51 модуль). Считай мы модули
   * по абсолютному числу, гейт краснел бы от чужой настройки и зеленел бы,
   * если бы подкладка однажды стала тяжелее. Считаем ПРИБАВКУ.
   */
  const доСписком = new Set(тяжёлыеВКэше());
  const до = доСписком.size;
  const t0 = Date.now();
  const лист = require('@/src/games/goods-sort/core/level');
  const мс = Date.now() - t0;
  const после = тяжёлыеВКэше();

  it('загрузка листа не добавляет ни экранных модулей, ни react-native', () => {
    // Виновников называем поимённо: «стало на 40 больше» не подсказывает, ЧТО
    // именно приехало и через какой импорт его выдернули.
    const пришли = после
      .filter((k) => !доСписком.has(k))
      .map((k) => k.replace(/^.*node_modules[\\/]/, ''))
      .slice(0, 8);
    expect(пришли).toEqual([]);
    expect(после.length - до).toBe(0);
  });

  /**
   * Лист не просто «лёгкий» — он рабочий. Без этого пункта пустой файл прошёл бы
   * оба замера с блеском: ноль модулей, ноль миллисекунд.
   */
  it('и при этом он живой: правила, раздача и цели отвечают', () => {
    expect(лист.GS_RULES.length).toBeGreaterThanOrEqual(10);
    expect(лист.levelCfg(12, 8, false).types).toBeGreaterThan(0);
    expect(['all', 'pick', 'free', 'moves']).toContain(лист.goalPlan(7).kind);
    expect(лист.gridFor(30, true).cols).toBe(3);
    // Раздача — самое дорогое, что уехало: она обязана работать без экрана.
    const d = лист.dealBoard(12, [0, 1, 2, 3, 4, 5, 6, 7], false);
    expect(d.cells.length).toBeGreaterThan(0);
  });

  /**
   * 🔴 ЦЕНА ЭКРАНА МЕРЯЕТСЯ ЗДЕСЬ ЖЕ, И ОДНИМ ПУНКТОМ, А НЕ ДВУМЯ.
   *
   * Экран грузится РОВНО РАЗ на файл пробы: `require` кладёт модуль в кэш, и
   * второй вызов уже бесплатен. Пока замер отношения и замер «экран правда
   * тяжёлый» стояли двумя пунктами, второй видел прибавку ноль и краснел — не
   * от дефекта, а от порядка выполнения. Один пункт, один `require`.
   *
   * ⚠️ ОТНОШЕНИЕ, А НЕ АБСОЛЮТНОЕ ЧИСЛО МИЛЛИСЕКУНД. Первая редакция требовала
   * «лист быстрее 200 мс» — по замеру 14 мс это выглядело запасом в четырнадцать
   * раз. Прогон холодным кэшем (`jest --no-cache`) дал 128 и 160 мс: почти весь
   * запас съедала пересборка Babel, и первый же чистый прогон в сборочной машине
   * покрасил бы гейт на исправном коде. Пересборка дорожает для обоих, а разница
   * лист/экран — свойство зависимостей, а не машины.
   */
  it('🔴 экран действительно тянет вёрстку, и лист дешевле него на порядок', () => {
    const доЭкрана = тяжёлыеВКэше().length;
    const t1 = Date.now();
    require('@/app/games/goods-sort');
    const экранМс = Date.now() - t1;
    const прибавка = тяжёлыеВКэше().length - доЭкрана;

    // Замер не вхолостую: без этого пункта «прибавка листа = 0» ничего не значила
    // бы — она была бы нулём и в проекте, где тяжёлого не осталось вовсе.
    expect(прибавка).toBeGreaterThan(100);

    // Оба числа в сообщении: иначе при падении не видно, что именно поехало.
    const отношение = экранМс / Math.max(1, мс);
    expect(`лист ${мс} мс · экран ${экранМс} мс · отношение ${отношение.toFixed(1)}`)
      .toMatch(/отношение (1\d|[2-9]\d|\d{3,})/);
  });
});
