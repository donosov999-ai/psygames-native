/**
 * 🔴 СКРЫТЫЙ СЛОЙ — ЧЕСТНАЯ НЕПОЛНАЯ ИНФОРМАЦИЯ, А НЕ УГАДАЙКА.
 *
 * 📍 ПОЧЕМУ ГЕЙТ ИМЕННО ТАКОЙ. Отзывы на чужие игры с этой механикой звучат
 * одинаково: «по сути играешь в угадайку, повезёт — не повезёт». Разбор
 * `REF_WATER_SORT.md` §6 разложил, ЧТО именно превращает механику в угадайку, и
 * вышло шесть условий. Здесь проверяется каждое, потому что нарушение любого
 * одного возвращает тот самый отзыв — а по коду это не видно.
 */
import { levelParams, generateLevel } from '@/src/games/water-sort/core/generate';
import {
  СКРЫТО_С, скрытоНаУровне, скрытыеСлои, слойВиден, скрытоОсталось,
  звёздыПоХодам, ключСлоя,
} from '@/src/games/water-sort/core/hidden';

jest.setTimeout(300000);

const зерно = (s: number) => {
  let a = s >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

describe('скрытый слой в переливалке', () => {
  it('есть что проверять: механика включается и не на каждом уровне', () => {
    const скрытых = Array.from({ length: 60 }, (_, i) => i + 1).filter(скрытоНаУровне);
    expect(скрытых.length).toBeGreaterThan(5);
    expect(скрытых.length).toBeLessThan(30);   // прореженный ритм, а не фон
    expect(скрытоНаУровне(СКРЫТО_С - 1)).toBe(false);
    expect(скрытоНаУровне(СКРЫТО_С)).toBe(true);
  });

  /**
   * ⚠️ МЕХАНИКА ПРИХОДИТ ТУДА, ГДЕ ЛЕСТНИЦА КОНЧИЛАСЬ, а не поверх растущей.
   * Замер: обе оси переливалки в потолке с четырнадцатого уровня.
   */
  it('🔴 скрытый слой начинается ПОСЛЕ того, как лестница упёрлась в потолок', () => {
    const верх = levelParams(СКРЫТО_С);
    const до = levelParams(СКРЫТО_С - 2);
    expect(`цветов ${верх.colors} = ${до.colors}, высота ${верх.cap} = ${до.cap}`)
      .toBe(`цветов ${верх.colors} = ${верх.colors}, высота ${верх.cap} = ${верх.cap}`);
  });

  /**
   * ⚠️ ПРОВЕРЯЕТСЯ ОБЕ ПОЛОВИНЫ, И ЭТО НЕ ПРИДИРКА. `слойВиден` жёстко отвечает
   * «видно» для верхнего слоя — то есть отрисовка спасёт от ошибки генератора, и
   * человек ничего не заметит. Но ошибка останется: набор скрытого будет врать,
   * а на нём считается «цена неопределённости». Мутация это и вскрыла — проба,
   * спрашивавшая только `слойВиден`, пережила спрятанный верхний слой.
   */
  it('🔴 УСЛОВИЕ 1: верхний слой виден всегда — и не помечен скрытым', () => {
    const беды: string[] = [];
    for (let L = СКРЫТО_С; L <= 60; L += 1) {
      if (!скрытоНаУровне(L)) continue;
      const { field } = generateLevel(L, зерно(L));
      const скрытые = скрытыеСлои(field, зерно(L * 7));
      for (let i = 0; i < field.tubes.length; i += 1) {
        const t = field.tubes[i] as readonly number[];
        if (t.length === 0) continue;
        if (!слойВиден(field, скрытые, i, t.length - 1)) беды.push(`L${L} сосуд ${i}: верхний не виден`);
        if (скрытые.has(ключСлоя(i, t.length - 1))) беды.push(`L${L} сосуд ${i}: верхний помечен скрытым`);
      }
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  it('🔴 УСЛОВИЕ 2: не больше одного скрытого слоя на сосуд', () => {
    const беды: string[] = [];
    for (let L = СКРЫТО_С; L <= 60; L += 1) {
      if (!скрытоНаУровне(L)) continue;
      const { field } = generateLevel(L, зерно(L));
      const скрытые = скрытыеСлои(field, зерно(L * 7));
      const наСосуд = new Map<number, number>();
      for (const k of скрытые) {
        const сосуд = Math.floor(k / 100);
        наСосуд.set(сосуд, (наСосуд.get(сосуд) ?? 0) + 1);
      }
      for (const [сосуд, n] of наСосуд) if (n > 1) беды.push(`L${L} сосуд ${сосуд}: ${n}`);
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  it('🔴 УСЛОВИЕ 3: свободных сосудов остаётся столько же — механика их не съедает', () => {
    for (let L = СКРЫТО_С; L <= 40; L += 1) {
      if (!скрытоНаУровне(L)) continue;
      expect(`L${L}: пустых ${levelParams(L).empty}`).toBe(`L${L}: пустых 2`);
    }
  });

  /**
   * 🔴 УСЛОВИЕ 4 — ТО, ИЗ-ЗА ЧЕГО ЛЮДИ И ПИШУТ ПРО УГАДАЙКУ. Под скрытым слоем
   * минимума не существует: разведка стоит ходов, которых в минимуме нет.
   */
  it('🔴 УСЛОВИЕ 4: на скрытых уровнях звёзды по ходам не выдаются', () => {
    const беды: string[] = [];
    for (let L = 1; L <= 60; L += 1) {
      if (скрытоНаУровне(L) === звёздыПоХодам(L)) беды.push(`L${L}`);
    }
    expect(беды).toEqual([]);
    expect(звёздыПоХодам(1)).toBe(true);
    expect(звёздыПоХодам(СКРЫТО_С)).toBe(false);
  });

  it('⚠️ прячется не всё подряд: однотонные и короткие сосуды не трогаются', () => {
    const беды: string[] = [];
    for (let L = СКРЫТО_С; L <= 40; L += 1) {
      if (!скрытоНаУровне(L)) continue;
      const { field } = generateLevel(L, зерно(L));
      const скрытые = скрытыеСлои(field, зерно(L * 7));
      for (const k of скрытые) {
        const сосуд = Math.floor(k / 100);
        const t = field.tubes[сосуд] as readonly number[];
        if (t.length < 2) беды.push(`L${L}: спрятано в сосуде из ${t.length}`);
        if (t.every((c) => c === t[0])) беды.push(`L${L}: спрятано в однотонном`);
      }
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  /**
   * 🔴 САМОПРОВЕРКА ОТ СЛЕПОГО ЗЕЛЁНОГО. Всё выше зеленеет и на «не спрятано
   * ничего». Требуем, чтобы механика правда работала: скрытое есть, и его
   * заметная доля, а не один слой на всю доску.
   */
  it('🔴 механика не вырождена: спрятано хотя бы по трети сосудов', () => {
    const слабые: string[] = [];
    for (let L = СКРЫТО_С; L <= 40; L += 1) {
      if (!скрытоНаУровне(L)) continue;
      const { field } = generateLevel(L, зерно(L));
      const скрытые = скрытыеСлои(field, зерно(L * 7));
      const занятых = field.tubes.filter((t) => t.length >= 2).length;
      if (скрытые.size * 3 < занятых) слабые.push(`L${L}: ${скрытые.size} из ${занятых}`);
      if (скрытоОсталось(field, скрытые) !== скрытые.size) {
        слабые.push(`L${L}: счёт скрытого расходится`);
      }
    }
    expect(слабые.slice(0, 5)).toEqual([]);
  });

  it('⚠️ раздача повторяется: тот же уровень — то же спрятанное', () => {
    for (const L of [16, 19, 25]) {
      const a = скрытыеСлои(generateLevel(L, зерно(L)).field, зерно(L * 7));
      const b = скрытыеСлои(generateLevel(L, зерно(L)).field, зерно(L * 7));
      expect([...a].sort().join(',')).toBe([...b].sort().join(','));
    }
  });

  it('ключ слоя не путает сосуды и глубины', () => {
    expect(ключСлоя(0, 3)).not.toBe(ключСлоя(3, 0));
    expect(Math.floor(ключСлоя(7, 4) / 100)).toBe(7);
    expect(ключСлоя(7, 4) % 100).toBe(4);
  });
});
