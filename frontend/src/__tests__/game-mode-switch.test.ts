/**
 * Экран РИСУЕТ общую панель. Тег ловим регуляркой с границей, а не подстрокой:
 * `includes('<GameModeSwitch')` радостно узнаёт себя в `<GameModeSwitchOff`, и на
 * мутационной проверке гейт из-за этого промолчал на подмене компонента.
 */
const usesSwitch = (f: string) => /<GameModeSwitch[\s/>]/.test(code(f));

/** Разметка самого элемента панели — от тега до закрывающего `/>`. */
function switchElement(f: string): string {
  const s = code(f);
  const at = s.indexOf('<GameModeSwitch');
  if (at < 0) return '';
  const end = s.indexOf('/>', at);
  return end < 0 ? s.slice(at) : s.slice(at, end + 2);
}

/**
 * Имя состояния, которое панель ПИШЕТ. Берётся из самой разметки (`onChange`), а не
 * зашито списком: гейт на дословное имя в этом проекте уже четырежды краснел на
 * правильной правке — переименовал обработчик, и проверка упала.
 */
function switchState(f: string): { setter: string; state: string } {
  const el = switchElement(f);
  const setter = (el.match(/\bset[A-Z]\w*/) || [])[0] || '';
  if (!setter) return { setter: '', state: '' };
  const st = code(f).match(new RegExp(`const \\[(\\w+), ${setter}\\] = useState`));
  return { setter, state: st ? st[1] : '' };
}

/**
 * Сколько мест на экране ПОКАЗЫВАЮТСЯ ПО ЭТОМУ СОСТОЯНИЮ. Ноль — панель декорация:
 * кнопки переключаются, экран не меняется. Считаются два вида записи:
 *   {mode === 'levels' && …}  и  {mode === 'classic' ? … : …}   — прямое сравнение;
 *   const byLevel = playMode === 'levels' || isPreset;  {byLevel && …}  — через флаг.
 */
function renderGates(f: string, state: string): number {
  if (!state) return 0;
  const s = code(f);
  const direct = s.match(new RegExp(`\\{[^{}]*\\b${state}\\s*===\\s*['"][^'"]*['"][^{}]{0,24}(?:&&|\\?)`, 'g')) || [];
  const aliases = [...s.matchAll(new RegExp(`const (\\w+) = [^;\\n]*\\b${state}\\b`, 'g'))]
    .map((m: any) => m[1]).filter((a: string) => a !== state);
  let viaFlag = 0;
  for (const a of aliases) {
    viaFlag += (s.match(new RegExp(`\\{\\s*!?\\s*${a}\\s*&&`, 'g')) || []).length;
  }
  return direct.length + viaFlag;
}

