/**
 * 🔴 СЛУХОВАЯ ИГРА БЕРЁТ ТОЛЬКО ТЕ СЛОВА, КОТОРЫЕ УМЕЕТ ПРОИЗНЕСТИ.
 *
 * 📍 ЗАМЕР 09.09.2026, И ПОЛОМКА БЫЛА МОЯ. Коммит `30d63aa2` вырастил общий
 * словарь 196 → 283 слова ради языковой зарядки. Записи стимулов снимались под
 * прежние 196, поэтому доля озвученных в мешке «Слухового охвата» упала:
 *   en 188/196 = 96 %  →  189/283 = 67 %
 *   es 187/196 = 95 %  →  187/283 = 66 %
 *   de 189/196 = 96 %  →  189/283 = 67 %
 * Каждое третье слово стало уходить на СИСТЕМНЫЙ голос устройства, которого для
 * нужного языка на части телефонов нет вовсе. В игре, где межсловный интервал —
 * сам измеряемый параметр, это порча пробы.
 *
 * ⚠️ ЭТО КЛАСС, А НЕ СЛУЧАЙ. Общий словарь читают пять экранов, и озвучивает
 * его ровно один — этот. Значит рост словаря будет и дальше разбавлять
 * озвученную долю, и заметить это можно только пробой.
 */
import { TRANSLATION_VOCAB } from '@/src/constants/translationVocab';
import { voiceUrl } from '@/src/services/voiceSamples';

declare const __dirname: string;
declare function require(id: string): any;
const читать = (rel: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, rel), 'utf8') as string;
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

/** Языки, у которых корпус записей ЕСТЬ (см. voiceSamples). */
const С_ЗАПИСЯМИ = ['ru', 'en', 'de', 'es', 'pt', 'zh', 'hi'] as const;
/** Языки словаря без единой записи — там игра обязана остаться живой. */
const БЕЗ_ЗАПИСЕЙ = ['fr', 'it', 'ja', 'ko', 'ar'] as const;

/** Повторяет отбор экрана — чтобы гонять его на всех языках сразу. */
const МИН = 8 * 2 * 3;
function мешок(lang: string): { всего: number; озвучено: number; выбрано: number } {
  const все = Array.from(new Set(
    TRANSLATION_VOCAB.map((e) => e[lang]).filter((w): w is string => typeof w === 'string' && !!w),
  ));
  const оз = все.filter((w) => voiceUrl(w, lang) !== null);
  return { всего: все.length, озвучено: оз.length, выбрано: (оз.length >= МИН ? оз : все).length };
}

describe('«Слуховой охват» произносит то, что показывает', () => {
  it('есть что проверять — словарь и записи на месте', () => {
    expect(TRANSLATION_VOCAB.length).toBeGreaterThan(200);
    expect(мешок('en').озвучено).toBeGreaterThan(100);
  });

  it('🔴 у языков с записями мешок озвучен ЦЕЛИКОМ', () => {
    const плохо: string[] = [];
    for (const l of С_ЗАПИСЯМИ) {
      const м = мешок(l);
      const немых = м.выбрано - м.озвучено;
      if (немых > 0) плохо.push(`${l}: немых ${немых} из ${м.выбрано}`);
    }
    expect(`с немыми словами: ${плохо.join(', ') || '—'}`).toBe('с немыми словами: —');
  });

  /**
   * ⚠️ ОТРИЦАТЕЛЬНАЯ СТОРОНА ПРАВИЛА. Жёсткий фильтр убил бы игру на пяти
   * языках, где записей нет ни одной: мешок стал бы пустым. Проверяется, что
   * запасной путь жив и даёт достаточно слов на партию.
   */
  it('🔴 у языков без записей игра остаётся живой — мешок не пустеет', () => {
    const плохо: string[] = [];
    for (const l of БЕЗ_ЗАПИСЕЙ) {
      const м = мешок(l);
      if (м.озвучено > 0) плохо.push(`${l}: записи внезапно появились — порог пересчитать`);
      if (м.выбрано < 16) плохо.push(`${l}: в мешке ${м.выбрано} при партии в 16 слов`);
    }
    expect(`сломано: ${плохо.join(', ') || '—'}`).toBe('сломано: —');
  });

  it('🔴 экран отбирает по записям, а не берёт словарь целиком', () => {
    const src = код(читать('../../app/games/listening-span.tsx'));
    expect(src).toMatch(/voiceUrl\(w, targetLang\) !== null/);
    // Возврат к безусловному мешку — именно та поломка, что была до 09.09.2026.
    expect(src).toMatch(/озвученные\.length >= МИН_ОЗВУЧЕННЫХ \? озвученные : все/);
  });

  /**
   * 📌 СТОРОЖ НА БУДУЩИЙ РОСТ СЛОВАРЯ. Пока доля озвученных выше порога, отбор
   * работает молча. Упадёт ниже — игра тихо вернётся на системный голос, и об
   * этом надо узнать здесь, а не от человека без испанского голоса в телефоне.
   */
  it('🔴 озвученных хватает с запасом на трёх языках потока', () => {
    const мало: string[] = [];
    for (const l of ['en', 'es', 'de']) {
      const м = мешок(l);
      if (м.озвучено < МИН) мало.push(`${l}: озвучено ${м.озвучено} при пороге ${МИН}`);
    }
    expect(`ниже порога: ${мало.join(', ') || '—'}`).toBe('ниже порога: —');
  });
});
