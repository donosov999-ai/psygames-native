/**
 * 🔴 ЧЕТЫРЕ ЭКРАНА РАЗДЕЛА ВЫГЛЯДЯТ ОДИНАКОВО — ЭТО ПЕРВАЯ ПРОСЬБА ДЕНИСА ПО НЕМУ.
 *
 * 📍 07.09.2026, дословно: «первое их надо будет привести к единому дизайну в
 * хабе, чтобы при зарядке экраны и управление не скакало, а было единым».
 * В зарядке эти экраны идут подряд, и любая разница в посадке полосы ответа
 * читается как дёрганье.
 *
 * ЗАМЕР 09.09.2026 на 390×844, ДО правки (низ полосы ответа):
 *   vocab-srs 834 · cloze 834 · semantic-sort 834 · lexical-decision 844
 * Последний уходил на 10 px ниже соседей — впритык к краю. Причина: его кнопки
 * лежали голым фрагментом `<>`, без общей обёртки, и отступы задавала каждая
 * сама. ПОСЛЕ: 834 у всех четырёх.
 *
 * ⚠️ ВЕРХ ПОЛОСЫ ОСТАЁТСЯ РАЗНЫМ (714 / 714 / 756 / 736), И ЭТО НЕ ДЕФЕКТ.
 * Полоса прижата к НИЗУ и растёт вверх по содержимому: три категории — одна
 * строка, четыре варианта — две. Требовать одинакового верха значило бы либо
 * растягивать короткую полосу пустотой, либо резать длинную.
 *
 * ⚠️ ЗДЕСЬ ПРОВЕРЯЕТСЯ ИСХОДНИК, А НЕ ПИКСЕЛИ. Геометрию меряет отдельная джоба
 * на собранном бандле (`pan-audit`); эта проба ловит ПРИЧИНУ — возврат к
 * фрагменту или к самодельной вёрстке счётчиков, — и ловит её за секунду.
 */
declare const __dirname: string;
declare function require(id: string): any;

const читать = (g: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, '../../app/games', `${g}.tsx`), 'utf8') as string;
/** Комментарии срезаются: проверка обязана смотреть на КОД, а не на пояснения. */
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

/** Четыре экрана, входящие в языковой поток: они идут подряд в зарядке. */
const В_ПОТОКЕ = ['vocab-srs', 'cloze', 'semantic-sort', 'lexical-decision'] as const;

/**
 * Остальные экраны раздела. У них тоже есть низ, и он тоже обязан быть объявлен
 * — иначе каркас угадывает по наличию пропа, а это и был запрещённый приём.
 *
 * ⚠️ `phonemic-fluency` СЮДА НЕ ВХОДИТ, и это замер, а не пропуск: у неё нет
 * `toolbar` вовсе (весь ввод в поле). Объявлять низ там, где его нет, значило бы
 * соврать каркасу.
 */
const ВНЕ_ПОТОКА = ['anagrams', 'story-recall', 'phoneme-pairs', 'chinese-tones',
  'pseudoword-echo', 'dictation'] as const;

const ЭКРАНЫ = [...В_ПОТОКЕ, ...ВНЕ_ПОТОКА] as const;

describe('единый вид экранов языкового раздела', () => {
  it('🔴 каждый экран с низом ОБЪЯВЛЯЕТ, что там — ответ или действия', () => {
    const без = ЭКРАНЫ.filter((g) => !/bottom="(answer|actions)"/.test(код(читать(g))));
    expect(`без объявления низа: ${без.join(', ') || '—'}`).toBe('без объявления низа: —');
  });

  /**
   * 🔴 ЧТО ИМЕННО ВНИЗУ — ПО РЕЕСТРУ ПРОЕКТА, А НЕ ПО СВЕЖЕМУ ВПЕЧАТЛЕНИЮ.
   *
   * ⚠️ ЗДЕСЬ Я ОШИБСЯ И ПОЙМАЛ ЭТО ЧУЖИМ ГЕЙТОМ. Прочитав `toolbar` анаграмм
   * («Сбросить», «Сдать») и пересказа («OK», «пропустить»), я объявил обоим
   * `bottom="actions"`. Проба `slot-meaning` покраснела и объяснила почему:
   * `actions` означает не «внизу игровые кнопки», а «каркас рисует внизу
   * `headerActions`», и тогда `toolbar` быть не должно.
   *
   * А главное — в `slot-meaning` УЖЕ ЛЕЖИТ разбор обеих игр, и обе там записаны
   * как ОТВЕТ: у анаграмм «Отменить» и «Сброс» правят ЧЕРНОВИК набранного
   * слова, а «Проверить» — сдача; у пересказа «OK» и «Готово» — сдача этапа.
   * Реестр старше и подробнее моего впечатления, поэтому решает он.
   */
  it('🔴 действия и ответ не перепутаны', () => {
    const действия: string[] = [];
    const плохо: string[] = [];
    for (const g of ЭКРАНЫ) {
      const s = код(читать(g));
      const ждём = действия.includes(g) ? 'actions' : 'answer';
      if (!new RegExp(`bottom="${ждём}"`).test(s)) плохо.push(`${g}: ждали ${ждём}`);
    }
    expect(`перепутано: ${плохо.join(', ') || '—'}`).toBe('перепутано: —');
  });

  /**
   * ⚠️ ПРОБА СБЫЛАСЬ, А НЕ УСТАРЕЛА. Прежняя редакция требовала у «Беглости речи»
   * ПУСТОГО низа и в своём же комментарии писала: «появится `toolbar` — проба
   * потребует объявить низ и здесь». Он появился — коммит bd048eb9 от 11.09.2026:
   * поле ввода слова переехало из поля в полосу ответа, потому что без `bottom`
   * каркас полосу не рисует, а гейт геометрии раздела опознаёт «мы в партии»
   * именно по ней, и экран не измерялся вовсе — единственный из одиннадцати.
   *
   * Смысл проверки сохранён ЦЕЛИКОМ и лишь развёрнут в обе стороны: `bottom`
   * без `toolbar` — это полоса «для единообразия», пустая и лживая; `toolbar`
   * без `bottom` — это содержимое, которому каркас не выделил места. Врозь они
   * не бывают ни у кого из одиннадцати.
   */
  it('у «Беглости речи» низ и его содержимое объявлены ВМЕСТЕ', () => {
    const s = код(читать('phonemic-fluency'));
    const естьТулбар = /toolbar=\{/.test(s);
    const естьНиз = /bottom="/.test(s);
    expect(`toolbar: ${естьТулбар} · bottom: ${естьНиз}`).toBe('toolbar: true · bottom: true');
    // и низ объявлен именно ОТВЕТОМ — там стоит поле ввода слова, а не служебный ряд
    expect(/bottom="answer"/.test(s)).toBe(true);
  });

  /**
   * 🔴 СЧЁТЧИКИ ОТДАЮТСЯ ДАННЫМИ, А НЕ ВЁРСТКОЙ. Пока игра передаёт `stats` с
   * готовой разметкой, вид шапки принадлежит ей, и четыре экрана расходятся при
   * первой же правке одного. С `hud` решает каркас — один на всех.
   */
  /**
   * 🔴 СЧЁТЧИКИ — ДАННЫМИ, НО `stats` НЕ ЗАПРЕЩЁН, И ЭТО ВАЖНО.
   *
   * ⚠️ ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ ПРОБЫ (VER 1) требовала, чтобы `stats` не было
   * вовсе. Замер 09.09.2026 показал, что правило неверно: **15 экранов проекта**
   * держат в `stats` значок правила уровня (`LevelRuleBadge`) рядом с `hud` —
   * это канон, а не остаток. У `pseudoword-echo` там ровно он, у
   * `phonemic-fluency` — буква-стимул. Запрет сломал бы работающее.
   *
   * Проверяется то, что и требовалось: счётчики отданы ДАННЫМИ. А в `stats` не
   * должно остаться СВОЕЙ РАЗМЕТКИ СЧЁТЧИКОВ — её признак `hudRow`/`hudText`.
   */
  it('🔴 счётчики переданы данными, а своей разметки счётчиков в stats нет', () => {
    const плохо: string[] = [];
    for (const g of ЭКРАНЫ) {
      const s = код(читать(g));
      if (g !== 'story-recall' && !/hud=\{/.test(s)) плохо.push(`${g}: нет hud`);
      const m = s.match(/stats=\{[\s\S]{0,400}?\n\s{8}\}/);
      if (m && /styles\.hudRow|styles\.hudText/.test(m[0])) плохо.push(`${g}: счётчики вёрсткой в stats`);
      if (m && /<View style=\{styles\.statsRow\}>\s*<\/View>/.test(m[0])) плохо.push(`${g}: пустой stats`);
    }
    expect(`плохо: ${плохо.join(' · ') || '—'}`).toBe('плохо: —');
  });

  /**
   * 🔴 ПОЛОСА ОТВЕТА — В КОНТЕЙНЕРЕ, А НЕ ФРАГМЕНТОМ. Именно фрагмент увёл
   * «Слово или нет?» на 10 px ниже соседей: без обёртки отступы задавала каждая
   * кнопка сама.
   */
  /**
   * 🔴 ПОЛОСА — В КОНТЕЙНЕРЕ, А НЕ ФРАГМЕНТОМ. Именно фрагмент увёл «Слово или
   * нет?» на 10 px ниже соседей: без обёртки отступы задавала каждая кнопка.
   *
   * ⚠️ ПЕРВАЯ РЕДАКЦИЯ ЭТОЙ ПРОБЫ БЫЛА СЛЕПА, и поймала это мутация, а не
   * чтение. Она смотрела только на ПЕРВЫЕ 60 знаков после `toolbar={`, а у
   * «Пересказа» там стоит тернарник `isDistractor ? (` — фрагмент шёл дальше и
   * не попадал в окно. Мутация «вернуть фрагмент» осталась зелёной. Теперь
   * ищется весь блок `toolbar` целиком, по балансу скобок.
   */
  it('🔴 у каждого экрана полоса лежит в общем контейнере, а не фрагментом', () => {
    const плохо: string[] = [];
    for (const g of ЭКРАНЫ) {
      const s = код(читать(g));
      const i = s.indexOf('toolbar={');
      if (i < 0) continue;                    // экран без полосы — не наш случай
      let гл = 0; let j = i + 'toolbar='.length;
      for (; j < s.length; j += 1) {
        if (s[j] === '{') гл += 1;
        else if (s[j] === '}') { гл -= 1; if (гл === 0) break; }
      }
      if (/<>/.test(s.slice(i, j))) плохо.push(`${g}: фрагмент вместо контейнера`);
    }
    expect(`фрагментом: ${плохо.join(', ') || '—'}`).toBe('фрагментом: —');
  });

  it('контейнер полосы описан одинаково у всех, кто его завёл', () => {
    const образцы = new Set<string>();
    for (const g of ЭКРАНЫ) {
      const m = код(читать(g)).match(/toolbarOptions:\s*\{[^}]*\}/);
      if (m) образцы.add(m[0].replace(/\s+/g, ' '));
    }
    expect(`разных описаний: ${образцы.size}`).toBe('разных описаний: 1');
  });
});
