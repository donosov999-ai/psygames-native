/**
 * ИГРА, ПОМЕЧЕННАЯ «В ХАБЕ», ОБЯЗАНА БЫТЬ В ХАБЕ ВИДНА.
 *
 * 🔴 ЗАЧЕМ. Вопрос Дениса 04.09.2026: «проверь, что так же висит, но не
 * показывается в хабах». Повод — «Торможение»: у `go_no_go` и `stop_signal` в
 * каталоге стояло `mergedInto: 'attention_conflict'`, то есть «мы в хабе», а
 * экран хаба про них не знал вовсе. Карточка при этом спрятана из каталога
 * (`hideFromMenu`), и попасть в упражнение было НЕОТКУДА — оно жило только тем,
 * что на него ссылался пресет зарядки.
 *
 * Пометка `mergedInto` — это обещание человеку: «ищи внутри такого-то хаба».
 * Гейт проверяет, что обещание выполнимо: из экрана хаба ДО игры можно дойти по
 * ссылкам (в том числе через промежуточный экран — например, групповую карточку).
 *
 * ⚠️ Комментарии срезаем: упоминание маршрута в объяснении не считается ссылкой.
 */
import { HUB_CONTENTS } from '@/src/constants/hubContents';

declare const __dirname: string;
declare function require(m: string): any;
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '../..');
const КАТАЛОГ = path.join(КОРЕНЬ, 'src/constants/games.ts');

const безКомментариев = (t: string) =>
  t.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');

interface Карточка { id: string; route?: string; merged?: string }

function каталог(): Карточка[] {
  const src = безКомментариев(fs.readFileSync(КАТАЛОГ, 'utf8'));
  const из: Карточка[] = [];
  for (const m of src.matchAll(/\n {2}\{\n([\s\S]*?)\n {2}\},/g)) {
    const b = m[1]!;
    const id = /id:\s*'([a-z0-9_-]+)'/.exec(b)?.[1];
    if (!id) continue;
    из.push({
      id,
      route: /route:\s*'(\/games\/[a-z0-9-]+)'/.exec(b)?.[1],
      merged: /mergedInto:\s*'([a-z0-9_]+)'/.exec(b)?.[1],
    });
  }
  if (!из.length) throw new Error('каталог не разобрался — гейт проверял бы пустоту');
  return из;
}

/**
 * СОСЕДИ ПО НАБОРУ — второй способ дойти, появившийся 05.09.2026.
 *
 * Парадигмы, слитые под одну карточку (`src/constants/gameSuites.ts`), больше не
 * перечислены в хабе: до них доходят плашками переключателя ВНУТРИ первой из них.
 * Список соседей лежит в реестре, а не в файле экрана, поэтому обход по строковым
 * литералам их не видит и считал бы сиротами.
 *
 * ⚠️ ПЕРЕХОД ЗАСЧИТЫВАЕТСЯ, ТОЛЬКО ЕСЛИ ЭКРАН ДЕЙСТВИТЕЛЬНО РИСУЕТ ПЕРЕКЛЮЧАТЕЛЬ.
 * Иначе гейт разрешал бы дойти по ссылке, которой на экране нет: убери
 * `<GameSuiteSwitch />` из `stroop.tsx` — и Simon с ANT становятся недостижимы,
 * а проба обязана это заметить.
 */
function соседиПоНабору(маршрут: string): string[] {
  const реестр = безКомментариев(fs.readFileSync(path.join(КОРЕНЬ, 'src/constants/gameSuites.ts'), 'utf8'));
  for (const блок of реестр.split('modes: [').slice(1)) {
    const маршруты = [...блок.slice(0, блок.indexOf('],')).matchAll(/route:\s*'(\/games\/[a-z0-9-]+)'/g)].map((m) => m[1]!);
    if (маршруты.includes(маршрут)) return маршруты;
  }
  return [];
}

/** Дойти от экрана `старт` до `цель` по ссылкам между экранами игр. */
function достижимо(старт: string, цель: string): boolean {
  const виден = new Set<string>();
  const очередь = [старт];
  while (очередь.length) {
    const r = очередь.shift()!;
    if (r === цель) return true;
    if (виден.has(r)) continue;
    виден.add(r);
    const f = path.join(КОРЕНЬ, 'app' + r + '.tsx');
    if (!fs.existsSync(f)) continue;
    const s = безКомментариев(fs.readFileSync(f, 'utf8'));
    for (const m of s.matchAll(/'(\/games\/[a-z0-9-]+)'/g)) if (!виден.has(m[1]!)) очередь.push(m[1]!);
    /**
     * 🔴 СОСТАВ РАЗВИЛКИ ЖИВЁТ В РЕЕСТРЕ, А НЕ В РАЗМЕТКЕ ЭКРАНА.
     *
     * 05.09.2026 списки карточек переехали из шестнадцати экранов в
     * `src/constants/hubContents.ts` — иначе число на значке и список внутри
     * расходились (24 пары профиль×развилка). Обход по ссылкам в JSX после
     * этого перестал видеть ЛЮБУЮ игру за развилкой: гейт краснел на всех
     * шестнадцати сразу. Свойство то же, место другое.
     */
    for (const карточка of HUB_CONTENTS[r] ?? []) {
      // Карточка режима (`/games/x?mode=…`, как у судоку и лаборатории) ведёт и к самому экрану `/games/x`:
      // хвост запроса — режим внутри того же экрана, а не другой маршрут (09.09.2026, spatial-lab).
      for (const шаг of [карточка.route, карточка.route.split('?')[0]]) if (!виден.has(шаг)) очередь.push(шаг);
    }
    if (s.includes('<GameSuiteSwitch')) {
      for (const сосед of соседиПоНабору(r)) if (!виден.has(сосед)) очередь.push(сосед);
    }
  }
  return false;
}

/**
 * 🟢 ДОЛГ ЗАКРЫТ 12.09.2026 — СПИСОК ПУСТ, И ЭТО НЕ ФОРМАЛЬНОСТЬ.
 *
 * Здесь стояли `go_no_go` и `stop_signal` с пометкой «дубликаты на 1012 строк,
 * из хаба не дойти». Первая половина записи была НЕВЕРНА, и это вскрылось
 * замером, когда Денис попросил скриншоты перед сносом:
 *   · у `/games/inhibition` задержка стоп-сигнала назначается НОМЕРОМ УРОВНЯ
 *     (`ssd = min(480, 150 + (level-1)*24)`, inhibition.tsx);
 *   · у `/games/stop-signal` она ходит по лестнице 1-вверх/1-вниз и считается
 *     SSRT методом интеграции — ядро `src/games/stop-signal/core/**`, 54 КБ.
 * То есть отдельный экран был не дубликатом, а ПОЧИНКОЙ: коммит 2724c83c от
 * 23.08.2026 воспроизвёл прежний дефект численно (разброс долей торможения
 * 85 процентных пунктов) и уравнял его лестницей. Починка полгода не доезжала
 * до игрока, потому что у экрана не было ни одного входа.
 *
 * Вторая половина записи снята по делу: 12.09.2026 заведён набор
 * `suite_inhibition`, и все три экрана получили `<GameSuiteSwitch />` — теперь
 * из «Конфликта внимания» до каждого доходишь переключателем.
 *
 * ⚠️ ЧТО ЕЩЁ НЕ РЕШЕНО: какая из двух реализаций стоп-сигнала останется —
 * задача TeamOps 4c4de3c2. Сейчас обе на виду рядом НАМЕРЕННО, это витрина на
 * время решения, а не конечная форма. Пустой список ниже говорит «до каждой
 * игры можно дойти», а не «вопрос закрыт».
 */
const ДОЛГ: Record<string, string> = {};

describe('игры, помеченные слитыми в хаб', () => {
  const карточки = каталог();
  const поId = Object.fromEntries(карточки.map((к) => [к.id, к]));
  const слитые = карточки.filter((к) => к.merged);

  it('есть что проверять — иначе гейт зелен вслепую', () => {
    expect(слитые.length).toBeGreaterThan(5);
  });

  it('🔴 у каждой слитой игры хаб существует и имеет свой экран', () => {
    const плохие = слитые
      .filter((к) => {
        const хаб = поId[к.merged!];
        return !хаб?.route || !fs.existsSync(path.join(КОРЕНЬ, 'app' + хаб.route + '.tsx'));
      })
      .map((к) => `${к.id} → «${к.merged}»`);
    expect(плохие).toEqual([]);
  });

  it('🔴 из хаба до слитой игры МОЖНО дойти по ссылкам', () => {
    const сироты = слитые
      .filter((к) => !ДОЛГ[к.id])
      .filter((к) => {
        const хаб = поId[к.merged!];
        return !к.route || !хаб?.route || !достижимо(хаб.route, к.route);
      })
      .map((к) => `${к.id} (${к.route}) — помечена в «${к.merged}», но из хаба не дойти`);
    expect(сироты).toEqual([]);
  });

  it('долг не протух: записанные сироты всё ещё сироты', () => {
    const починенные = Object.keys(ДОЛГ).filter((id) => {
      const к = поId[id];
      const хаб = к?.merged ? поId[к.merged] : undefined;
      return к?.route && хаб?.route && достижимо(хаб.route, к.route);
    });
    expect(`починены, но остались в долге: ${починенные.join(', ')}`).toBe('починены, но остались в долге: ');
  });

  it('самопроверка: выдуманная слитая игра ловится', () => {
    const хаб = поId['attention_conflict'];
    expect(хаб?.route).toBeTruthy();
    expect(достижимо(хаб!.route!, '/games/такой-игры-нет')).toBe(false);
  });
});
