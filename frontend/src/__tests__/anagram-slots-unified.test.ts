/**
 * УПРАВЛЕНИЕ ВСЕХ РЕЖИМОВ АНАГРАММ ЖИВЁТ В СЛОТАХ КАРКАСА, А НЕ ПОД ПОЛЕМ.
 *
 * 📍 РЕШЕНИЕ ДЕНИСА 07.09.2026: прибить нижние полосы всех режимов к каркасу,
 * как у классики. Повод — «Зарядка», которая мешает разные игры подряд.
 *
 * 🔴 ЗАМЕР ДО, живьём на 375×812: у классики полоса прибита в 10 точках от низа,
 * у трёх остальных висела в 72 — там, где кончилось содержимое, потому что кнопки
 * рисовались ВНУТРИ компонента режима. Ряд «Найди все слова» из четырёх кнопок
 * занимал 519 точек при экране 375, «Сброс» и «Проверить» обрезались краем, а
 * плавающая кнопка чата накрывала «Сброс» на 16×11.
 *
 * ЗАМЕР ПОСЛЕ, там же: низ прибит к краю (отступ 0) у «Найди все слова» и
 * кроссворда — «Сброс» и «Проверить»; у «Слово-квадрата» низа НЕТ вовсе (он
 * сдаёт слово сам на пятой букве); служебное во всех трёх — в шапке.
 *
 * ⚠️ РАСКЛАДКА СМЫСЛОВАЯ, ЕЁ ЗАДАЁТ КАРКАС (`GameShell.tsx:215-278`), и она же
 * стережётся `slot-meaning.test.ts`. Здесь проверяется другое: что режимы
 * ОТДАЮТ управление наверх и не рисуют свой ряд.
 */
declare const __dirname: string;
declare function require(id: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');
const ROOT = join(__dirname, '../..');
const читать = (p: string) => readFileSync(join(ROOT, p), 'utf8');

/** Комментарии — не код: рассказ о механизме не должен засчитываться за механизм. */
function безКомментариев(s: string): string {
  let out = '', i = 0;
  while (i < s.length) {
    const c = s[i], n = s[i + 1];
    if (c === '/' && n === '*') { const e = s.indexOf('*/', i + 2); out += ' '; i = e < 0 ? s.length : e + 2; continue; }
    if (c === '/' && n === '/') { const e = s.indexOf('\n', i); out += ' '; i = e < 0 ? s.length : e; continue; }
    out += c; i++;
  }
  return out;
}

const РЕЖИМЫ = [
  'src/games/anagrams/WordSquareGame.tsx',
  'src/games/anagrams/AllWordsGame.tsx',
  'src/games/anagrams/CrosswordGame.tsx',
] as const;

it('каждый режим отдаёт управление наверх', () => {
  const плохо: string[] = [];
  for (const п of РЕЖИМЫ) {
    const код = безКомментариев(читать(п));
    if (!/onУправление\?\.\(\{/.test(код)) плохо.push(`${п}: не публикует управление`);
  }
  expect(плохо).toEqual([]);
});

it('ни один режим не рисует свой ряд кнопок под полем', () => {
  const плохо: string[] = [];
  for (const п of РЕЖИМЫ) {
    const код = безКомментариев(читать(п));
    if (/стилиРежима\.действия/.test(код)) плохо.push(`${п}: ряд кнопок остался в вёрстке режима`);
  }
  expect(плохо).toEqual([]);
});

/**
 * 🔴 САМОЕ ВАЖНОЕ: ССЫЛКИ НАРУЖУ НЕИЗМЕННЫ ЗА ВСЮ ЖИЗНЬ КОМПОНЕНТА.
 *
 * Первая версия обернула их в `useCallback` с зависимостями — и экран лёг с
 * «Maximum update depth exceeded» на первом же кадре: `сдать` зависит от
 * `onComplete`, а тот приходит из экрана инлайновой стрелкой, то есть новый на
 * каждой отрисовке. Мешок публиковался заново, экран писал его в состояние,
 * состояние вызывало отрисовку — круг.
 *
 * Приём — «свежий реф»: обёртка с ПУСТЫМ списком зависимостей читает текущее
 * значение из рефа, который обновляется эффектом после отрисовки.
 */
it('обёртки действий не зависят ни от чего — иначе петля отрисовок', () => {
  const плохо: string[] = [];
  for (const п of РЕЖИМЫ) {
    const код = безКомментариев(читать(п));
    if (!/свежееRef/.test(код)) плохо.push(`${п}: нет свежего рефа`);
    // Обёртка обязана быть с пустыми зависимостями: иначе она пересоздаётся.
    for (const имя of ['подсказкаДействие', 'сдатьНабранное']) {
      const m = new RegExp(`const ${имя} = React\\.useCallback\\([\\s\\S]*?\\}, \\[([^\\]]*)\\]\\)`).exec(код);
      if (m && m[1].trim() !== '') плохо.push(`${п}: ${имя} зависит от [${m[1].trim()}]`);
    }
  }
  expect(плохо).toEqual([]);
});

it('🔴 каждая обёртка режима отдаёт каркасу ОБА слота', () => {
  /*
   * 📍 Мутация 07.09.2026: `toolbar={низРежима}` → `toolbar={undefined}` во всех
   * трёх режимах — и прежняя редакция этой пробы осталась зелёной. Порог был
   * «слотов не меньше, чем обёрток минус три», то есть не меньше одного: его
   * в одиночку закрывала классика со своей встроенной полосой.
   *
   * ⚠️ Порог, который выполняется независимо от проверяемого, — не проверка.
   * Поэтому спрашиваем поимённо: у обёртки, внутри которой стоит компонент
   * режима, ОБА слота должны быть переданы. Игрок иначе теряет «Сбросить» и
   * «Проверить» целиком, а гейт молчит.
   */
  const код = безКомментариев(читать('app/games/anagrams.tsx'));
  const куски = код.split('<GameShell').slice(1);
  expect(куски.length).toBeGreaterThanOrEqual(4);

  const плохо: string[] = [];
  let обёртокРежимов = 0;
  for (const кусок of куски) {
    const тело = кусок.split('</GameShell>')[0];
    // Имя компонента = имя файла режима: WordSquareGame.tsx → <WordSquareGame
    const режим = РЕЖИМЫ.find((р) => тело.includes(`<${р.split('/').pop()!.replace('.tsx', '')}`));
    if (!режим) continue;                       // классика рисует поле сама
    обёртокРежимов++;
    if (!/toolbar=\{низРежима\}/.test(тело)) плохо.push(`${режим}: нижняя полоса каркасу не передана`);
    if (!/headerActions=\{шапкаДействий\}/.test(тело)) плохо.push(`${режим}: шапка каркасу не передана`);
    if (!/onУправление=\{/.test(тело)) плохо.push(`${режим}: мешок действий не поднимается`);
  }
  expect(плохо).toEqual([]);
  expect(обёртокРежимов).toBe(РЕЖИМЫ.length);

  // Обе памятки собираются из поднятого мешка, а не из внутренностей режима.
  expect(код).toMatch(/const низРежима[\s\S]{0,400}управление/);
  expect(код).toMatch(/const шапкаДействий[\s\S]{0,400}управление/);
  expect(код).toMatch(/GameAuxAction/);
});
