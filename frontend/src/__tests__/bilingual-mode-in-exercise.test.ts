/**
 * 🔴 ДВА ЯЗЫКА В ОДНОЙ ПАРТИИ — ВНУТРИ УПРАЖНЕНИЯ, А НЕ ТОЛЬКО МЕЖДУ ШАГАМИ.
 *
 * 📍 ПРАВКА ДЕНИСА 09.09.2026: «зарядка это финальный режим билингво; я просил,
 * чтобы В УПРАЖНЕНИЯХ появился режим билингво, где переводы надо находить».
 * ЗАМЕР ТОГО ЖЕ ДНЯ: чередование жило только между шагами зарядки, а внутри
 * партии язык был один — у всех пяти словарных экранов ровно один `targetLang`
 * на весь заход, ни одного места с двумя иностранными в одной сессии.
 */
import { рядЯзыков, разложитьПоРяду, параЯзыков, БИЛИНГВО } from '@/src/services/bilingualMode';
import { ПОСЛЕДОВАТЕЛЬНОСТЬ, долиПовторов } from '@/src/services/languageFlow';

declare const __dirname: string;
declare function require(id: string): any;
const читать = (rel: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, rel), 'utf8') as string;
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

describe('режим билингво внутри упражнения', () => {
  it('🔴 в ряду есть ОБА языка и они чередуются', () => {
    const р = рядЯзыков(12, 'ru');
    expect(new Set(р).size).toBe(2);
    let смен = 0;
    for (let i = 1; i < р.length; i += 1) if (р[i] !== р[i - 1]) смен += 1;
    expect(`смен на 12 элементах: ${смен > 0}`).toBe('смен на 12 элементах: true');
  });

  /**
   * 🔴 ПОВТОРЫ ОБЯЗАТЕЛЬНЫ, И ЭТО НЕ ВКУСОВЩИНА. Без повторов разность
   * «переключения минус повторы» возвращает РОВНО НОЛЬ, и цена переключения не
   * считается вовсе. Чистое `en, es, en, es` выглядит «более билингвально», а
   * мерить в нём нечего.
   */
  it('🔴 в ряду есть повторы, а не чистое чередование', () => {
    const р = рядЯзыков(12, 'ru');
    let повторов = 0;
    for (let i = 1; i < р.length; i += 1) if (р[i] === р[i - 1]) повторов += 1;
    expect(`повторов: ${повторов > 0}`).toBe('повторов: true');
  });

  /**
   * 🔴 РЯД БЕРЁТСЯ ИЗ ПОТОКА, А НЕ ПИШЕТСЯ ЗАНОВО. Вторая копия узора разошлась
   * бы с первой при первой правке, и два масштаба одного правила стали бы
   * мерить разное.
   */
  it('🔴 узор тот же, что у зарядки', () => {
    const р = рядЯзыков(ПОСЛЕДОВАТЕЛЬНОСТЬ.length, 'ru');
    const [первый] = параЯзыков('ru');
    const узор = р.map((l) => (l === первый ? 'A' : 'B')).join('');
    const эталон = ПОСЛЕДОВАТЕЛЬНОСТЬ.map((l) => (l === 'en' ? 'A' : 'B')).join('');
    expect(узор).toBe(эталон);
    expect(Math.round(долиПовторов().доля * 100)).toBe(33);
  });

  it('🔴 родной язык целью не бывает ни на одном интерфейсе', () => {
    const плохо: string[] = [];
    for (const ui of ['ru', 'en', 'es', 'de', 'fr']) {
      if (рядЯзыков(8, ui).includes(ui)) плохо.push(ui);
    }
    expect(`родной попал в цель: ${плохо.join(', ') || '—'}`).toBe('родной попал в цель: —');
  });

  it('🔴 элементы двух языков раскладываются вперемешку', () => {
    const { элементы, сколькоСмен } = разложитьПоРяду(
      { en: ['a1', 'a2', 'a3', 'a4', 'a5', 'a6'], es: ['b1', 'b2', 'b3', 'b4', 'b5', 'b6'] }, 12, 'ru',
    );
    expect(элементы.length).toBe(12);
    expect(new Set(элементы.map((x) => x.язык)).size).toBe(2);
    expect(сколькоСмен).toBeGreaterThan(0);
  });

  /**
   * 🔴 МАТЕРИАЛ ОДНОГО ЯЗЫКА КОНЧИЛСЯ — ПАРТИЯ НЕ ОБРЫВАЕТСЯ, НО И НЕ ВРЁТ.
   * Добор идёт из второго языка, а `сколькоСмен` честно падает: по одному лишь
   * включённому флагу «партия была двуязычной» утверждать нельзя.
   */
  it('🔴 при нехватке одного языка партия достраивается, а число смен честное', () => {
    const { элементы, сколькоСмен } = разложитьПоРяду({ en: ['a1', 'a2'], es: ['b1'] }, 10, 'ru');
    expect(элементы.length).toBe(3);              // всего материала три — больше взять неоткуда
    const один = разложитьПоРяду({ en: ['a1', 'a2', 'a3'], es: [] }, 3, 'ru');
    expect(`смен на одном языке: ${один.сколькоСмен}`).toBe('смен на одном языке: 0');
  });

  it('пустой материал не роняет разбор', () => {
    expect(разложитьПоРяду({}, 5, 'ru').элементы).toEqual([]);
    expect(рядЯзыков(0, 'ru')).toEqual([]);
    expect(рядЯзыков(-3, 'ru')).toEqual([]);
  });

  describe('«Словарь SRS» — первый носитель режима', () => {
    const src = () => код(читать('../../app/games/vocab-srs.tsx'));

    it('🔴 режим есть и виден человеком, а не только параметром', () => {
      expect(src()).toMatch(/setБилингво/);
      expect(src()).toMatch(/t\('bilingualMode'\)/);
    });

    /**
     * 🔴 ОЦЕНКА УХОДИТ В КОЛОДУ СВОЕГО ЯЗЫКА. Расписание повторов SRS живёт на
     * ПАРЕ языков; отправить ответ по испанской карточке в английскую колоду —
     * значит испортить график обеих.
     */
    it('🔴 оценка карточки уходит в колоду ЕЁ языка', () => {
      expect(src()).toMatch(/gradeCard\(language, card\.lang \?\? tgt/);
      expect(src()).not.toMatch(/gradeCard\(language, tgt/);
    });

    /**
     * 🔴 ДИСТРАКТОРЫ — ИЗ ЯЗЫКА КАРТОЧКИ. Испанское слово среди английских
     * видно, не зная ни одного из них: смешанные варианты подсказывают ответ.
     */
    it('🔴 варианты ответа берутся из языка этой карточки', () => {
      expect(src()).toMatch(/поЯзыкам \?\? пулЯзыков\)\[card\.lang/);
    });

    it('🔴 в статистику пишется пара языков и число настоящих смен', () => {
      expect(src()).toMatch(/target_lang: билингво \? параЯзыков\(language\)\.join\('\+'\) : tgt/);
      expect(src()).toMatch(/lang_switches: сменЯзыка/);
    });

    it('параметр режима называется одинаково везде', () => {
      expect(БИЛИНГВО).toBe('bilingual');
      expect(src()).toMatch(/str\(БИЛИНГВО, ''\) === '1'/);
    });
  });
});
