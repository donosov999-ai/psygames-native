/**
 * 🔴 ЛЕСТНИЦА КАЖДОЙ ПРОБЫ КОНФЛИКТА ВНИМАНИЯ ДЕЙСТВИТЕЛЬНО РАСТЁТ.
 *
 * Отчёт тестировщицы 04.09.2026 по развилке «Конфликт внимания»: «надо
 * прокачать их, каждому продумать уровни сложности, а потом замиксуем в уровни
 * как таблицы Шульте или в зарядке».
 *
 * 📍 Замер показал, что лестницы у всех четырёх УЖЕ есть и все монотонны. Но
 * это ровно тот случай, где «есть» проверялось глазами по формуле, а формулу
 * правят: в «Детском мате» 05.09.2026 лестница выглядела растущей и при этом
 * ОТКАТЫВАЛАСЬ назад на стыках участков — 20 → 12 с возвратом к 16. Поэтому
 * здесь свойство закреплено прогоном, а не прочтением.
 *
 * ⚠️ Мерится ГЛАВНАЯ ОСЬ каждой пробы — окно ответа: именно оно делает конфликт
 * трудным. Число проб и доли конфликтных проверяются отдельно своими гейтами.
 */
import { levelParams as stroopLevel } from '@/app/games/stroop';
import { levelParams as flankerLevel } from '@/app/games/flanker';
import { levelParams as simonLevel } from '@/app/games/simon';
import { levelParams as emoLevel } from '@/app/games/stroop-emotional';
import { levelParams as choiceLevel } from '@/app/games/choice-rt';

/**
 * ⚠️ ПОЛ ОКНА У КАЖДОЙ ПРОБЫ СВОЙ, И ЭТО НЕ ПРИДИРКА К ФОРМЕ.
 *
 * До 07.09.2026 пол был один на всех — 900 мс, с обоснованием «ниже меряется не
 * торможение, а моторный предел». Обоснование верное, но оно ПРО ТОРМОЖЕНИЕ, и
 * потому переносится только на конфликтные пробы. Когда в список добавился
 * `choice-rt`, где торможения нет вовсе, общий пол оказался бы числом без
 * причины — а число без причины следующая правка сдвинет, не заметив.
 */
const ЛЕСТНИЦЫ = [
  { имя: 'Струп', окно: (L: number) => stroopLevel(L).windowMs, пол: 900 },
  { имя: 'Фланкер', окно: (L: number) => flankerLevel(L).windowMs, пол: 900 },
  { имя: 'Саймон', окно: (L: number) => simonLevel(L).windowMs, пол: 900 },
  { имя: 'Струп: эмоции', окно: (L: number) => emoLevel(L).answerWindowMs, пол: 900 },
  /**
   * 🔴 ДОБАВЛЕН 07.09.2026, И ДОБАВЛЕН ПОТОМУ, ЧТО ЕГО ТУТ НЕ БЫЛО.
   *
   * Пока `choice-rt` не входил в список, его окно спокойно уходило до 750 мс
   * (L14 = 830, L15 = 750) — ниже общего пола 900, и никто этого не видел.
   *
   * Свой пол 1000 мс обоснован законом Хика: RT = a + b·log₂(n), наклон b в
   * большинстве исследований 150–200 мс/бит при a ≈ 250 мс, значит при четырёх
   * альтернативах предсказанное среднее 550–650 мс, а у нас ещё и сенсорный
   * экран. Дедлайн в 750 мс срезает правый хвост, причём при четырёх
   * альтернативах сильнее, чем при двух, — то есть уплощает НАКЛОН, ради
   * которого парадигма существует.
   */
  { имя: 'Выбор реакции', окно: (L: number) => choiceLevel(L).windowMs, пол: 1000 },
];

const УРОВНЕЙ = 15;

describe('«Конфликт внимания»: лестницы четырёх проб', () => {
  it('есть что проверять: у всех четырёх лестница читается', () => {
    for (const л of ЛЕСТНИЦЫ) {
      expect(`${л.имя}: ${Number.isFinite(л.окно(1))}`).toBe(`${л.имя}: true`);
    }
  });

  it('🔴 окно ответа сужается МОНОТОННО — ни одного отката назад', () => {
    const откаты: string[] = [];
    for (const л of ЛЕСТНИЦЫ) {
      let прошлое = Infinity;
      for (let L = 1; L <= УРОВНЕЙ; L++) {
        const в = л.окно(L);
        if (в > прошлое) откаты.push(`${л.имя} L${L}: ${прошлое} → ${в}`);
        прошлое = в;
      }
    }
    expect(откаты).toEqual([]);
  });

  it('🔴 лестница действительно проходит путь, а не топчется', () => {
    for (const л of ЛЕСТНИЦЫ) {
      const первый = л.окно(1);
      const последний = л.окно(УРОВНЕЙ);
      // Не меньше чем вдвое: иначе «растёт» ничего не значит на практике.
      expect(`${л.имя}: ${первый} → ${последний}`).toBe(`${л.имя}: ${первый} → ${последний}`);
      expect(последний).toBeLessThanOrEqual(первый / 2);
    }
  });

  it('🔴 и не проваливается ниже человеческой реакции — у каждой пробы по СВОЕМУ полу', () => {
    const пробои: string[] = [];
    for (const л of ЛЕСТНИЦЫ) {
      for (let L = 1; L <= 40; L++) {
        if (л.окно(L) < л.пол) пробои.push(`${л.имя} L${L}: ${л.окно(L)} < ${л.пол}`);
      }
    }
    expect(пробои).toEqual([]);
  });

  /**
   * 🔴 СОБСТВЕННЫЙ ОГРАНИЧИТЕЛЬ ИГРЫ НЕ ОБЪЯВЛЯЕТСЯ, А МЕРИТСЯ.
   *
   * Первая версия этой пробы сверяла верхний уровень с полем `пол` и покраснела
   * на Струпе — и оказалась права: у Струпа в коде стоит `Math.max(1200, ...)`,
   * а в списке выше для него было записано 900. Число в гейте расходилось с
   * числом в игре, и держало на самом деле НИЧЕГО: подвинь кто-нибудь 1200 на
   * 700, проба бы не заметила, ведь 700 всё ещё больше 900.
   *
   * 🔴 И ВТОРОЕ, ПОЙМАННОЕ МУТАЦИЕЙ 07.09.2026. Сначала я подставил сюда
 * `пол: CHOICE_RT_WINDOW_FLOOR_MS` — импортом из самой игры, чтобы «число жило в
 * одном месте». Мутация (опустить пол игры обратно на 750) прошла ЗЕЛЕНО: от
 * импорта двигались ОБА конца сравнения сразу — и объявленная граница, и
 * фактический кламп. Гейт сверял лестницу с движущейся мишенью, то есть не
 * проверял ничего.
 * 📌 Порог, взятый у проверяемого, — не порог. Психометрическая граница пишется
 * здесь ЛИТЕРАЛОМ, руками, с обоснованием; из игры берётся только поведение.
 *
 * Поэтому величин здесь ДВЕ, и у них разные роли:
   *   · `пол` — психометрическая граница, ниже которой проба теряет смысл.
   *     Объявляется человеком с обоснованием (см. список выше);
   *   · кламп игры — то, что фактически стоит в её формуле. Он не переписывается
   *     сюда, а СНИМАЕТСЯ с лестницы: минимум окна на сорока уровнях. Тогда
   *     разойтись с кодом ему неоткуда.
   *
   * Проверяется, что кламп не ниже психометрической границы И что лестница до
   * него доходит: ограничитель, до которого не дошли, можно двигать свободно —
   * ни одна проба не покраснеет. Это тот же случай, что «ступень из фильтра»:
   * величина, которая никогда не срабатывает, только выглядит величиной.
   */
  it('🔴 кламп игры снят с лестницы, не ниже психометрической границы и лестница до него доходит', () => {
    const беды: string[] = [];
    for (const л of ЛЕСТНИЦЫ) {
      const поУровням = Array.from({ length: 40 }, (_, i) => л.окно(i + 1));
      const кламп = Math.min(...поУровням);
      const верх = л.окно(УРОВНЕЙ);
      if (кламп < л.пол) беды.push(`${л.имя}: кламп ${кламп} ниже границы ${л.пол}`);
      if (верх > кламп * 1.2) беды.push(`${л.имя}: L${УРОВНЕЙ} даёт ${верх}, а кламп ${кламп} — лестница до него не доходит`);
    }
    expect(беды).toEqual([]);
  });
});
