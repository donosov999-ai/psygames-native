declare const __dirname: string;
const fs = require('fs');
const path = require('path');

/**
 * 🔴 С ЛЮБОГО ЭКРАНА ВИДЕН ВЫХОД — И ОН НЕ В КОНЦЕ ПРОКРУТКИ.
 *
 * Отчёт Дениса 03.09.2026 со скриншотом онбординга: «и как отсюда выйти на шаг
 * назад? Это архитектурная ошибка во всех упражнениях, из-за неё я и говорю про
 * сквозные одинаковые тулбары». Он прав, и это ТРЕТИЙ случай за один день:
 *   · «Поворот фигур» — кнопка «дальше» под развёрнутым разбором, уезжала за край;
 *   · онбординг — единственное «Пропустить» под всем списком игр;
 *   · и оба раза дефект выглядел как «приложение зависло», хотя оно работало.
 *
 * ⚠️ ЭТОТ ГЕЙТ ПРОВЕРЯЕТ ТОЛЬКО «ВЫХОД СУЩЕСТВУЕТ», И ЭТО ВСЁ, ЧТО ОН МОЖЕТ.
 * Сначала здесь стояла вторая проба — «выход не внутри прокрутки», по чтению
 * исходника. Я вернул дефект мутацией, и она осталась ЗЕЛЁНОЙ: в одном файле живут
 * два экрана, и она находила выход соседнего. Проба удалена, а не «подкручена»:
 * где именно нарисован узел, исходником не выяснить. Это проверяет
 * `onboarding-exit-visible.test.ts` — по настоящему дереву, и обе мутации там
 * краснеют.
 *
 * Игровые экраны сюда не входят: у них выход даёт каркас `GameShell` (стрелка в
 * шапке), и это ровно тот «сквозной тулбар», которого Денис просит везде.
 */
const КОРЕНЬ = path.resolve(__dirname, '../..');

/** Экраны верхнего уровня: файлы `app/*.tsx`, кроме служебных и игр. */
function экраны(): string[] {
  return fs.readdirSync(path.join(КОРЕНЬ, 'app'))
    .filter((f: string) => f.endsWith('.tsx') && !f.startsWith('_') && !f.startsWith('+'))
    .map((f: string) => path.join('app', f));
}

/**
 * Есть ли в файле элемент выхода.
 *
 * ⚠️ Первый вид детектора искал только стрелку и «пропустить» — и объявил
 * запертыми три экрана, где выход есть кнопкой «на главную» (`router.replace('/')`).
 * Отказ, не подтверждённый чтением файла, — это ложная тревога, а гейт, кричащий
 * на исправном коде, отучают слушать. Поэтому «уйти домой» тоже считается выходом.
 */
function естьВыход(код: string): boolean {
  return /arrow-back|router\.back|goBackOrHome|goHome|router\.replace\('\/'|t\('skip'\)|name="close"|'close-'/i.test(код);
}

describe('выход виден с любого экрана', () => {
  it('🔴 у каждого экрана верхнего уровня выход вообще существует', () => {
    // Главная — исключение по смыслу: из неё выходить некуда, она и есть дом.
    const дом = ['app/index.tsx'];
    const безВыхода = экраны()
      .filter((rel) => !дом.includes(rel))
      .filter((rel) => !естьВыход(fs.readFileSync(path.join(КОРЕНЬ, rel), 'utf8') as string));
    expect(безВыхода).toEqual([]);
  });
});
