const мост = () => readFileSync(join(__dirname, '../games/tatham-bridge/play.ts'), 'utf8');

describe('ход засчитывается по ответу движка', () => {
  it('🔴 мост отдаёт признак «подействовало», а не только снимок', () => {
    const м = мост();
    expect(м).toMatch(/export interface Итог/);
    expect(м).toContain('подействовало: ответ === ПОДЕЙСТВОВАЛО');
    // Значение взято из его же enum, а не выдумано числом на месте.
    expect(м).toMatch(/const ПОДЕЙСТВОВАЛО = 1;/);
  });

  /**
   * 🔴 УТВЕРЖДЕНИЕ ПЕРЕПИСАНО 16.09.2026, И ВОТ ПОЧЕМУ. Прежнее требовало от экрана
   * ДОСЛОВНУЮ запись правила: `if (жест === 'отпустил' && итог.подействовало)`.
   * psygames-spatial-claude-mac нашёл на живом экране «Труб», что это правило врёт —
   * у большинства движков Тэтхэма `interpret_move` отдаёт ход на НАЖАТИИ, и четыре
   * настоящих клика давали «Ходов: 0», — и вынес правило в одну общую функцию
   * `ходЗаЖест` (`play.ts:180`). Правило стало верным, а гейт покраснел: он сторожил
   * не смысл, а буквы. Проба по строке живёт ровно до первой честной переделки.
   *
   * Что здесь остаётся сторожить: экран НЕ заводит вторую копию правила, а зовёт
   * общую функцию и растит счётчик только по её ответу. Само поведение правила
   * (промах не считается, протяжка — один ход) проверяет `puzzle-move-counts-on-press`.
   */
  it('🔴 экран не переписывает правило хода, а зовёт общее', () => {
    const с = код();
    expect(с).toContain('ходЗаЖест(жест, итог.подействовало, эффектЗаЖест.current)');
    expect(с).toContain('if (ход) setХодов((n) => n + 1);');
    // Стрелка — свой случай: у многих режимов она двигает КУРСОР, а не фигуру.
    expect(с).toContain('if (итог.подействовало) setХодов((n) => n + 1);');
    // Ни одной ветки, растящей счётчик безусловно.
    expect(с).not.toMatch(/^\s*if \(жест === 'отпустил'\) setХодов/m);
    expect(с).not.toMatch(/^\s*setХодов\(\(n\) => n \+ 1\);/m);
  });
});

