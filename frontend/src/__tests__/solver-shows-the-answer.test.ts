/**
 * «ПОКАЗАТЬ РЕШЕНИЕ» ПОКАЗЫВАЕТ РЕШЕНИЕ, А НЕ КАРТОЧКУ ИТОГА ПОВЕРХ НЕГО.
 *
 * 🔴 ПОВОД — два независимых источника одного дня, 12.09.2026:
 * · аудит сорока головоломок (`psygames-codex-mac`, пункт P1-01,
 *   /Users/denisonosov/dev/psygames-game-lab/audit/puzzles-40-2026-09-12/FINDINGS.md):
 *   воспроизведено в интерфейсе у 31 игры из 37, где решатель вообще есть;
 * · отчёты тестировщиков `8a1b20d6` и `67561a7f` — «нажимаю показать решение, а меня
 *   выкидывает вот сюда».
 *
 * ПРИЧИНА. Решатель возвращает решённую позицию, у неё статус 1 — то есть победа.
 * Общий путь конца партии ставил фазу `cleared`, и карточка итога ложилась поверх
 * ответа. Дефект не в движках: они отдают ровно то, что просили.
 *
 * ⚠️ ГЕЙТ ПО ИСХОДНИКУ, И Я ЭТО НЕ ПРЯЧУ. Состояние живёт в хуках экрана; чтобы
 * прогнать это поведением, нужен рендер экрана с настоящим мостом WASM — отдельная
 * работа. ДОЛГ: заменить поведенческой пробой, когда мост поднимут в jest.
 */
declare const __dirname: string;
const { readFileSync } = require('fs');   // eslint-disable-line @typescript-eslint/no-require-imports
const { join } = require('path');         // eslint-disable-line @typescript-eslint/no-require-imports

const код = () => readFileSync(join(__dirname, '../../app/games/puzzles.tsx'), 'utf8');

describe('показ решения не накрывается карточкой итога', () => {
  it('есть что проверять — решатель и фаза итога на месте', () => {
    const с = код();
    expect(с).toContain('setСдался(true)');
    expect(с).toContain("setФаза('cleared')");
  });

  it('🔴 разбор объявлен третьим состоянием, а не победой', () => {
    expect(код()).toMatch(/const разбор = сдался && победа;/);
  });

  it('🔴 фаза итога НЕ ставится, когда показан ответ', () => {
    const с = код();
    // Голого `setФаза('cleared');` быть не должно — только под защитой разбора.
    expect(с).toContain("if (!разбор) setФаза('cleared');");
    expect(с).not.toMatch(/^\s*setФаза\('cleared'\);\s*$/m);
  });

  it('🔴 просмотр ответа не опускает лестницу', () => {
    // `lvl.fail()` в ветке «иначе» срабатывал и на разборе: минус ступень за то,
    // что человек посмотрел ответ, — строже, чем за проигрыш.
    expect(код()).toContain('else if (!разбор) lvl.fail();');
  });
});

/**
 * ━━━ «ЗАНОВО» ПОВТОРЯЕТ ТУ ЖЕ РАЗДАЧУ (P2-06) ━━━
 *
 * Аудит сорока головоломок, 12.09.2026: и меню паузы, и карточка тупика звали
 * `новая()`, а она бросает новое зерно — человек, упёршийся в доску, терял её.
 * Живое воспроизведение в «Мостах» до первого хода (`restart-ui.json`).
 */
describe('«Заново» и «Новая партия» — разные вещи', () => {
  it('🔴 есть отдельный «заново», и он берёт СОХРАНЁННОЕ зерно', () => {
    const с = код();
    expect(с).toMatch(/const заново = useCallback\(/);
    // Ключ: раздача теми же параметрами и тем же зерном, а не новым броском.
    const н = с.indexOf('const заново = useCallback(');
    const тело = с.slice(н, с.indexOf('}, [движок, ступень, зерно, раздать]);', н));
    expect(тело).toContain('раздать(движок, ступень, зерно)');
    expect(тело).not.toContain('Math.random');
  });

  it('🔴 меню паузы зовёт «заново», а не новую раздачу', () => {
    expect(код()).toContain("{ id: 'restart', label: t('restart'), icon: 'refresh', onPress: () => заново() }");
  });

  it('«Новая партия» по-прежнему меняет зерно — иначе после победы будет та же доска', () => {
    const с = код();
    const н = с.indexOf('const новая = useCallback(');
    const тело = с.slice(н, с.indexOf('}, [движок, ступень, раздать]);', н));
    expect(тело).toContain('Math.random');
  });
});

/**
 * ━━━ ХОД СЧИТАЕТ ДВИЖОК, А НЕ ПАЛЕЦ (P1-05) ━━━
 *
 * Замер аудита 12.09.2026, «Мосты»: касание пустого края поля в точке 2,2 — рисунок
 * строго тот же, счётчик 0 → 1 (`noop-moves-ui.json`). Счёт идёт в баллы формулой
 * `1000 − ходов × 5`, то есть промах по пустому месту стоил очков.
 *
 * Движок отвечает `PKR_SOME_EFFECT` (1) только когда позиция ИЗМЕНИЛАСЬ; мост это
 * значение пробрасывал, а экран выбрасывал. Определять ход по различию рисунка
 * нельзя: движение курсора и подсветка тоже меняют картинку.
 */
const мост = () => readFileSync(join(__dirname, '../games/tatham-bridge/play.ts'), 'utf8');

describe('ход засчитывается по ответу движка', () => {
  it('🔴 мост отдаёт признак «подействовало», а не только снимок', () => {
    const м = мост();
    expect(м).toMatch(/export interface Итог/);
    expect(м).toContain('подействовало: ответ === ПОДЕЙСТВОВАЛО');
    // Значение взято из его же enum, а не выдумано числом на месте.
    expect(м).toMatch(/const ПОДЕЙСТВОВАЛО = 1;/);
  });

  it('🔴 экран растит счётчик ТОЛЬКО на настоящем ходе', () => {
    const с = код();
    expect(с).toContain("if (жест === 'отпустил' && итог.подействовало) setХодов((n) => n + 1);");
    expect(с).toContain('if (итог.подействовало) setХодов((n) => n + 1);');
    // Безусловного роста счётчика на отпускании и на стрелке больше нет.
    expect(с).not.toMatch(/^\s*if \(жест === 'отпустил'\) setХодов/m);
  });
});

/**
 * ━━━ «СТЕРЕТЬ» В «УГАДАЙ КОД» СТИРАЕТ, А НЕ ОТМЕНЯЕТ ХОД (P1-03) ━━━
 *
 * Живой сценарий аудита 12.09.2026: «Начать → 1 → 2 → Стереть» — рисунок до и после
 * одинаков, два выбранных цвета остаются (`guess-erase-ui.json`). Отмена возвращала 0
 * и не меняла ничего: неподтверждённый ряд в историю движка не записан.
 *
 * 🔴 И ОТДЕЛЬНО — УРОК ПРО МОЙ ЖЕ ПРЕЖНИЙ ЗАМЕР. В экране было записано: «перебор
 * 32…127 плюс 8/9/13/27/127 не нашёл НИ ОДНОГО кода, который убирает поставленный
 * цвет». Перебор честный, вывод неверный: забой стирает только если под курсором
 * ЕСТЬ фишка (`guess.c:950`), а цифра сама двигает курсор на следующую пустую
 * (`guess.c:947`). Пробовали стирать там, где пусто.
 * Если КАЖДЫЙ код даёт «ничего» — подозревай состояние, а не набор кодов.
 */
describe('стирание введённого ряда', () => {
  it('🔴 есть двухшаговое стирание, и отмена хода тут ни при чём', () => {
    const м = мост();
    expect(м).toMatch(/export async function стеретьВвод\(\): Promise<Итог>/);
    const н = м.indexOf('export async function стеретьВвод');
    const тело = м.slice(н, м.indexOf('\n}', н));
    // Сначала забой под курсором…
    expect(тело).toContain('const ЗАБОЙ = 8;');
    // …и шаг влево ТОЛЬКО если первый забой ничего не сделал.
    expect(тело).toContain('if (прямо.подействовало) return прямо;');
    expect(тело).toContain("await стрелка('влево')");
    // Отмена хода в стирании не участвует.
    expect(тело).not.toContain('отменить');
  });

  it('🔴 кнопка «Стереть» зовёт стирание, а не отмену', () => {
    const с = код();
    expect(с).toContain('if (ВВОД.has(имяРежима)) { void стеретьВвод()');
    expect(с).not.toContain('if (ВВОД.has(имяРежима)) { void отменить()');
  });
});

