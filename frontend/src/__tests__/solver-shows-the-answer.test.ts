declare const __dirname: string;
const { readFileSync } = require('fs');   // eslint-disable-line @typescript-eslint/no-require-imports
const { join } = require('path');         // eslint-disable-line @typescript-eslint/no-require-imports

const код = () => readFileSync(join(__dirname, '../../app/games/puzzles.tsx'), 'utf8');

describe('показ решения не накрывается карточкой итога', () => {
  it('есть что проверять — решатель и фаза итога на месте', () => {
    const с = код();
    expect(с).toContain('setСдался(true)');
    expect(с).toContain("setФаза('cleared')");
  });

  it('🔴 разбор объявлен третьим состоянием, а не победой', () => {
    expect(код()).toMatch(/const разбор = сдался && победа;/);
  });

  it('🔴 фаза итога НЕ ставится, когда показан ответ', () => {
    const с = код();
    // Голого `setФаза('cleared');` быть не должно — только под защитой разбора.
    expect(с).toContain("if (!разбор) setФаза('cleared');");
    expect(с).not.toMatch(/^\s*setФаза\('cleared'\);\s*$/m);
  });

  it('🔴 просмотр ответа не опускает лестницу', () => {
    // `lvl.fail()` в ветке «иначе» срабатывал и на разборе: минус ступень за то,
    // что человек посмотрел ответ, — строже, чем за проигрыш.
    expect(код()).toContain('else if (!разбор) lvl.fail();');
  });
});

/**
 * ━━━ «ЗАНОВО» ПОВТОРЯЕТ ТУ ЖЕ РАЗДАЧУ (P2-06) ━━━
 *
 * Аудит сорока головоломок, 12.09.2026: и меню паузы, и карточка тупика звали
 * `новая()`, а она бросает новое зерно — человек, упёршийся в доску, терял её.
 * Живое воспроизведение в «Мостах» до первого хода (`restart-ui.json`).
 */
describe('«Заново» и «Новая партия» — разные вещи', () => {
  it('🔴 есть отдельный «заново», и он берёт СОХРАНЁННОЕ зерно', () => {
    const с = код();
    expect(с).toMatch(/const заново = useCallback\(/);
    // Ключ: раздача теми же параметрами и тем же зерном, а не новым броском.
    const н = с.indexOf('const заново = useCallback(');
    const тело = с.slice(н, с.indexOf('}, [движок, ступень, зерно, раздать]);', н));
    expect(тело).toContain('раздать(движок, ступень, зерно)');
    expect(тело).not.toContain('Math.random');
  });

  it('🔴 меню паузы зовёт «заново», а не новую раздачу', () => {
    expect(код()).toContain("{ id: 'restart', label: t('restart'), icon: 'refresh', onPress: () => заново() }");
  });

  it('«Новая партия» по-прежнему меняет зерно — иначе после победы будет та же доска', () => {
    const с = код();
    const н = с.indexOf('const новая = useCallback(');
    const тело = с.slice(н, с.indexOf('}, [движок, ступень, раздать]);', н));
    expect(тело).toContain('Math.random');
  });
});
