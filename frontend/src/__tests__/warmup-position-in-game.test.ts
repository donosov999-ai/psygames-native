declare const __dirname: string;
declare function require(id: string): any;
const читать = (rel: string): string =>
  require('fs').readFileSync(require('path').join(__dirname, rel), 'utf8') as string;
const код = (s: string): string =>
  s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

/** Повторяет правило каркаса — чтобы гонять его на выдуманных состояниях. */
function позиция(active: boolean, idx: number, всего: number): string | null {
  const n = active ? всего : 0;
  return n > 1 ? `${Math.min(idx + 1, n)}/${n}` : null;
}

describe('место в серии видно внутри партии', () => {
  it('🔴 идёт серия — показываем номер шага и всего', () => {
    expect(позиция(true, 0, 12)).toBe('1/12');
    expect(позиция(true, 6, 12)).toBe('7/12');
  });

  it('🔴 серия не идёт — не показываем ничего', () => {
    expect(позиция(false, 3, 12)).toBeNull();
  });

  /**
   * ⚠️ «1/1» — НЕ СЕРИЯ. Одиночная игра, запущенная как плейлист из одного
   * шага, показала бы подпись, которая ничего не сообщает, зато занимает место
   * в шапке рядом со справкой и «пропустить».
   */
  it('🔴 один шаг — это не серия, подписи нет', () => {
    expect(позиция(true, 0, 1)).toBeNull();
    expect(позиция(true, 0, 0)).toBeNull();
  });

  /**
   * ⚠️ ЗАЖИМ СВЕРХУ. `currentIdx` на последнем шаге успевает стать равным длине
   * до размонтажа экрана — без зажима человек увидел бы «13/12».
   */
  it('🔴 номер не перескакивает через общее число', () => {
    expect(позиция(true, 12, 12)).toBe('12/12');
    expect(позиция(true, 99, 12)).toBe('12/12');
  });

  it('🔴 каркас считает по тому же правилу, а не по своему', () => {
    const src = код(читать('../components/GameShell.tsx'));
    expect(src).toMatch(/wuВсего > 1 \? `\$\{Math\.min\(wu!\.currentIdx \+ 1, wuВсего\)\}\/\$\{wuВсего\}` : null/);
    // Подпись для скринридера обязана быть словами, а не голым «3/12».
    expect(src).toMatch(/wuПодпись = wuПозиция \? `\$\{t\('unitGames'\)\}/);
  });

  it('🔴 индикатор нарисован в шапке рядом с «пропустить»', () => {
    const src = код(читать('../components/GameShell.tsx'));
    const i = src.indexOf('testID="warmup-position"');
    const j = src.indexOf('testID="warmup-skip-step"');
    expect(`нарисован: ${i > 0} · рядом со skip: ${i > 0 && j > i}`)
      .toBe('нарисован: true · рядом со skip: true');
  });

  /**
   * ⚠️ МОСТ НЕ ТРОГАЛИ. Счётчик там был и остаётся — это разные места, и
   * убирать один ради другого было бы заменой, а не починкой.
   */
  it('на мосту счётчик серии остался на месте', () => {
    const src = код(читать('../../app/warmup-bridge.tsx'));
    expect(src).toMatch(/warmup\.currentIdx\}\/\{meta\?\.steps\.length/);
  });
});
