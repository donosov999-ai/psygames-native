/**
 * 🔴 ЗАДАНИЕ ЧИТАЕТСЯ ДО ПЕРВОЙ ВСПЫШКИ, А НЕ ПОВЕРХ НЕЁ.
 *
 * ПОВОД — отчёт Вали 08.09.2026 (app_feedback 7be44621, профиль «Микро-релакс»):
 * «Задание не крупно и не видно сразу, пока читаешь его клетки закрываются».
 *
 * ЗАМЕР 11.09.2026, из-за которого отчёт признан моим дефектом, а не пожеланием:
 * подпись фазы и время показа росли НАВСТРЕЧУ друг другу.
 *   L8  показ 940 мс · подпись 17 симв
 *   L15 показ 500 мс (пол лестницы) · подпись 17 симв
 *   L16 показ 500 мс · подпись 40 симв  ← ложные вспышки включаются здесь же
 * То есть самая длинная подпись появляется ровно там, где показ упёрся в пол.
 *
 * ЧТО ЗДЕСЬ СТОРОЖИТСЯ, тремя разными утверждениями:
 *  1. пауза даётся на НОВОМ уровне и не даётся на повторном раунде;
 *  2. `flashMs` — ось сложности — НЕ ТРОНУТ (отчёт про читаемость, не про сложность);
 *  3. пауза не короче того, что нужно на чтение самой длинной подписи.
 */
import { паузаНаЧтение, levelParams, MM_VOLUME_TOP, ЧИТАТЬ_ЗАДАНИЕ_МС } from '@/app/games/memory-matrix';

/** Самая длинная подпись фазы: «🔴 Запомни КРАСНЫЕ · Перечёркнутые — мимо». */
const ДЛИННАЯ_ПОДПИСЬ = '🔴 Запомни КРАСНЫЕ · Перечёркнутые — мимо';
/** Беглое чтение короткой знакомой строки взрослым, символов в секунду. */
const ЧТЕНИЕ_СИМВ_В_СЕК = 18;
/**
 * 🔴 ЛИТЕРАЛ, А НЕ ИМПОРТ ВЕЛИЧИНЫ. Взять `ЧИТАТЬ_ЗАДАНИЕ_МС` как ожидание было бы
 * порогом из проверяемого: правка экрана двигала бы оба конца, и проба ослепла бы.
 * Поэтому число здесь своё, а ниже стоит сверка с экраном — она и покраснеет,
 * если кто-то поменяет паузу, не тронув пробу.
 */
const ПАУЗА_В_ЭКРАНЕ = 1800;

describe('матрица: задание успевают прочитать', () => {
  it('🔴 пауза в экране равна той, что сторожит проба', () => {
    expect(ЧИТАТЬ_ЗАДАНИЕ_МС).toBe(ПАУЗА_В_ЭКРАНЕ);
  });

  it('🔴 на новом уровне пауза есть, на повторном раунде её нет', () => {
    expect(паузаНаЧтение(16, -1, ПАУЗА_В_ЭКРАНЕ)).toBe(ПАУЗА_В_ЭКРАНЕ);   // первый раунд уровня
    expect(паузаНаЧтение(16, 16, ПАУЗА_В_ЭКРАНЕ)).toBe(0);                 // второй раунд того же
    expect(паузаНаЧтение(17, 16, ПАУЗА_В_ЭКРАНЕ)).toBe(ПАУЗА_В_ЭКРАНЕ);    // уровень сменился
  });

  it('🔴 ось сложности не тронута: показ на дне лестницы по-прежнему 500 мс', () => {
    // Если кто-то «починит» читаемость, замедлив показ, — покраснеет здесь.
    expect(levelParams(MM_VOLUME_TOP).flashMs).toBe(500);
    expect(levelParams(MM_VOLUME_TOP + 1).flashMs).toBe(500);
    expect(levelParams(30).flashMs).toBe(500);
    expect(levelParams(1).flashMs).toBe(1430);
  });

  it('🔴 паузы хватает на самую длинную подпись', () => {
    const нужно = (ДЛИННАЯ_ПОДПИСЬ.length / ЧТЕНИЕ_СИМВ_В_СЕК) * 1000;
    // ⚠️ 18 симв/с — модельная величина, не замер Вали. Поэтому утверждение мягкое:
    // пауза обязана покрывать чтение хотя бы на три четверти, а не «точно столько».
    expect(ПАУЗА_В_ЭКРАНЕ).toBeGreaterThan(нужно * 0.75);
  });

  it('🔴 ложные вспышки и дно показа встречаются на L16 — премиса дефекта', () => {
    /*
     * ⚠️ УРОВЕНЬ ЛИТЕРАЛОМ, А НЕ `MM_VOLUME_TOP + 1`. Первая редакция этой пробы брала
     * его из проверяемого — и мутация «MM_VOLUME_TOP 15 → 20» прошла ЗЕЛЁНОЙ: ожидание
     * уехало вместе с константой. Порог, взятый из подопытного, двигает оба конца.
     * Ради этого совпадения правка и делалась: разойдутся — читать разбор заново.
     */
    expect(MM_VOLUME_TOP).toBe(15);
    expect(levelParams(16).decoys).toBeGreaterThan(0);
    expect(levelParams(16).flashMs).toBe(500);
    expect(levelParams(15).decoys).toBe(0);
  });
});
