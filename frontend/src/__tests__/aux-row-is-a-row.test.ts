declare const __dirname: string;
declare function require(id: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');
const ROOT = join(__dirname, '../..');
const читать = (p: string) => readFileSync(join(ROOT, p), 'utf8') as string;

/** Тело стиля по имени: `имя: { … }` до закрывающей скобки того же уровня. */
function стиль(код: string, имя: string): string | null {
  const m = new RegExp(`\\n  ${имя}:\\s*\\{`).exec(код);
  if (!m) return null;
  const от = код.indexOf('{', m.index);
  let гл = 0;
  for (let i = от; i < код.length; i++) {
    if (код[i] === '{') гл++;
    else if (код[i] === '}' && --гл === 0) return код.slice(от, i + 1);
  }
  return null;
}

it('🔴 полоса служебных кнопок — ряд, иначе её высота схлопывается в ноль', () => {
  const каркас = читать('src/components/GameShell.tsx');
  const тело = стиль(каркас, 'headerActions');
  expect(тело).not.toBeNull();
  expect(тело).toMatch(/flexDirection:\s*'row'/);
});

it('🔴 связка держится: ребёнок тянется по главной оси — родитель обязан быть рядом', () => {
  const кнопка = читать('src/components/GameAuxAction.tsx');
  const полоса = стиль(кнопка, 'bar');
  expect(полоса).not.toBeNull();

  const тянется = /flexGrow:\s*1/.test(полоса!) && /flexBasis:\s*0/.test(полоса!);
  if (!тянется) return;   // сняли растяжение — связка не нужна, проверять нечего

  /*
   * Растяжение по главной оси есть. Значит КАЖДЫЙ, кто кладёт `GameAuxBar` в
   * свой контейнер, обязан объявить этот контейнер рядом — иначе повторится
   * схлопывание в ноль. Проверяем оба места каркаса, где полоса живёт: шапку и
   * нижний слот для игр с `bottom="actions"`.
   */
  const каркас = читать('src/components/GameShell.tsx');
  const плохо: string[] = [];
  for (const имя of ['headerActions', 'toolbar']) {
    const т = стиль(каркас, имя);
    if (!т) { плохо.push(`${имя}: стиль не найден`); continue; }
    if (!/flexDirection:\s*'row'/.test(т)) плохо.push(`${имя}: не ряд, а полоса тянется по главной оси`);
  }
  expect(плохо).toEqual([]);
});
