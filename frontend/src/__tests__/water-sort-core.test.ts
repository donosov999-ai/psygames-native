/**
 * Чтение исходника без `import fs`: типов Node в проекте нет, а `require` без
 * объявления ловит линт. Тот же приём, что в pet-anchors.test.ts.
 */
declare const __dirname: string;
declare function require(m: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');
const читать = (rel: string): string => readFileSync(join(__dirname, rel), 'utf8');

describe('нормы экрана «Пробирок»', () => {
  const исходник: string = читать('../../app/games/water-sort.tsx');

  it('есть что проверять — файл экрана прочитан', () => {
    expect(исходник.length).toBeGreaterThan(3000);
    expect(исходник).toContain('кнопка:');
  });

  it('🔴 кнопки партии не ниже 48 — это порог целей нажатия НА ПОЛЕ, а не 44', () => {
    const m = /кнопка:\s*\{\s*minHeight:\s*(\d+)/.exec(исходник);
    expect(`minHeight кнопки: ${m?.[1] ?? 'не найден'}`).toBe('minHeight кнопки: 48');
  });

  it('🔴 ряд кнопок переносится — на 360 px три штуки в строку не помещаются', () => {
    const m = /кнопки:\s*\{([^}]*)\}/.exec(исходник);
    expect(`перенос строки в ряду кнопок: ${/flexWrap:\s*'wrap'/.test(m?.[1] ?? '')}`)
      .toBe('перенос строки в ряду кнопок: true');
  });
});
