/* bart-spread-does-not-move-the-measure · VER 1 · 16.09.2026 */
import { burstCapForBalloon, levelCondition } from '@/app/games/bart';

/**
 * 🔴 ЗАЧЕМ ЭТА ПРОБА. У BART мера прохода — `adj_avg_pumps`, среднее число
 * нажатий на не лопнувших шарах. При равномерной точке взрыва выгоднее всего
 * качать до ПОЛОВИНЫ предела, поэтому мера жёстко привязана к пределу: рост
 * `maxBurst` 16 → 128 поднимает её примерно в восемь раз.
 *
 * Третья ось (разброс предела между шарами) добавлена 16.09.2026, чтобы снять
 * два мёртвых перехода — без неё L13, L14 и L15 совпадали по всем параметрам.
 * И выбрана она ровно из-за одного свойства: разброс СИММЕТРИЧЕН вокруг
 * предела, значит среднее не двигается, а растёт только неопределённость.
 *
 * Если это свойство сломать — например сделать разброс односторонним, —
 * третья ось начнёт двигать саму измеряемую величину, то есть станет тем самым
 * дефектом, от которого раздел избавлялся восемь раз. Проба стережёт именно
 * это, и стережёт ПРОГОНОМ генератора, а не чтением формулы.
 */

/** Воспроизводимый бросок: проба не должна падать по монетке. */
function генератор(seed: number): () => number {
  let x = seed >>> 0;
  return () => {
    x = (x * 1664525 + 1013904223) >>> 0;
    return x / 4294967296;
  };
}

function среднийПредел(maxBurst: number, spread: number, n: number, seed: number): number {
  const rnd = генератор(seed);
  let сумма = 0;
  for (let i = 0; i < n; i++) сумма += burstCapForBalloon(maxBurst, spread, rnd);
  return сумма / n;
}

describe('BART: разброс предела растит неопределённость, но не среднее', () => {
  it('🔴 среднее по многим шарам остаётся у предела при любом разбросе', () => {
    const предел = 100;
    const отклонения = [0, 0.2, 0.35, 0.5].map((s) => {
      const ср = среднийПредел(предел, s, 20000, 12345);
      return { разброс: s, отклонениеПроц: Math.abs(ср - предел) / предел * 100 };
    });
    /* 1,5 % — запас на конечную выборку, не «примерно похоже». При
       одностороннем разбросе отклонение было бы порядка самого разброса,
       то есть в десятки раз больше. */
    for (const о of отклонения) expect(о.отклонениеПроц).toBeLessThan(1.5);
  });

  it('🔴 и это не зелёное вслепую: разброс ДЕЙСТВИТЕЛЬНО разбрасывает', () => {
    const предел = 100;
    const разные = (s: number) => {
      const rnd = генератор(777);
      return new Set(Array.from({ length: 200 }, () => burstCapForBalloon(предел, s, rnd))).size;
    };
    expect(разные(0)).toBe(1);              // без разброса все шары одинаковы
    expect(разные(0.5)).toBeGreaterThan(30); // с разбросом — десятки разных пределов
  });

  it('на первом уровне разброса нет, на последнем он наибольший', () => {
    expect(levelCondition(1).burstSpread).toBe(0);
    expect(levelCondition(15).burstSpread).toBe(0.5);
    const по = Array.from({ length: 15 }, (_, i) => levelCondition(i + 1).burstSpread);
    for (let i = 1; i < по.length; i++) expect(по[i]).toBeGreaterThanOrEqual(по[i - 1]);
  });

  it('предел отдельного шара не опускается до бессмысленного', () => {
    /* При большом разбросе и маленьком пределе шар мог бы лопаться с первого
       нажатия — это не сложность, а поломка. Пол 4 стоит в генераторе. */
    const rnd = генератор(999);
    const мин = Math.min(...Array.from({ length: 5000 }, () => burstCapForBalloon(16, 0.5, rnd)));
    expect(мин).toBeGreaterThanOrEqual(4);
  });
});
