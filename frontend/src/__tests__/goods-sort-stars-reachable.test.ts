/**
 * 🔴 ТРИ ЗВЕЗДЫ МОЖНО ПОЛУЧИТЬ. Раньше — нельзя было.
 *
 * Замер 02.09.2026 (пункт 6.5 карты дорог, поиск A* с допустимой эвристикой):
 *  · эталон ходов был прикидкой `types × 3` — завышал реальный минимум на треть
 *    устойчиво (доля по девяти уровням: 0,68–0,80, среднее 0,732);
 *  · порог трёх звёзд стоял «ходов ≤ 0,6 × эталон» = 1,8 × types, а реальный
 *    минимум — 2,1–2,3 × types;
 *  · итог: **высшая оценка недостижима на 95 % досок** (21 из 22). Сколь угодно
 *    хорошая игра давала две звезды, и увидеть это можно было только перебором.
 *
 * ⚠️ ЭТОТ ГЕЙТ МЕРЯЕТ ПОИСКОМ, А НЕ ФОРМУЛОЙ. Проверка «порог больше эталона»
 * ничего не стоит: оба числа из одного места и согласуются по определению.
 * Вопрос был в том, согласуются ли они с ИГРОЙ, — а это отвечает только решатель.
 */
import { dealBoard, capsForBoard, levelCfg, moveReference, REF_PER_TYPE, starsForMoves } from '../../app/games/goods-sort';
import { minMoves } from '../services/goodsSortMinMoves';

describe('звёзды достижимы', () => {
  const POOL = Array.from({ length: 34 }, (_, i) => i);

  it('эталон откалиброван по замеру, а не по рассуждению', () => {
    // 2,2 — среднее 0,732 от прежних трёх ходов на вид. Возврат к трём краснит гейт ниже.
    expect(REF_PER_TYPE).toBeGreaterThan(1.9);
    expect(REF_PER_TYPE).toBeLessThan(2.6);
  });

  it('🔴 порог трёх звёзд не ниже реального минимума доски', () => {
    const недостижимо: string[] = [];
    let проверено = 0;
    for (let L = 1; L <= 10; L++) {
      for (let i = 0; i < 3; i++) {
        const d = dealBoard(L, POOL, false);
        const r = minMoves(d.cells, capsForBoard(L, d.cells), 20000);
        if (r.moves === null) continue;            // трудная доска — не наш случай
        проверено++;
        const cfg = levelCfg(L, POOL.length, false);
        /**
         * ⚠️ Спрашиваем У САМОЙ ИГРЫ: «сыграв за минимум ходов, сколько получишь?».
         * Первая редакция считала порог своей копией формулы — и мутация «верни
         * прежний эталон 3 × types» её не роняла: два числа из одного рассуждения
         * согласуются между собой, что бы в них ни подставили.
         */
        const звёзды = starsForMoves(r.moves, moveReference(cfg));
        if (звёзды < 3) недостижимо.push(`L${L}: за минимум ${r.moves} ходов дают ${звёзды} звезды`);
      }
    }
    expect(проверено).toBeGreaterThan(8);          // есть на чём считать
    expect(недостижимо).toEqual([]);
  }, 600000);

  it('шкала не выродилась: две и одна звезда тоже возможны', () => {
    const cfg = levelCfg(5, POOL.length, false);
    const ref = moveReference(cfg);
    // Шкала проверяется вердиктами игры, а не пересчётом её же формулы.
    expect(starsForMoves(ref, ref)).toBe(3);                       // ровно минимум — три
    expect(starsForMoves(Math.ceil(ref * 1.4), ref)).toBe(2);      // с запасом — две
    expect(starsForMoves(Math.ceil(ref * 2.5), ref)).toBe(1);      // долго — одна
  });
});
