/**
 * 🔴 ПОЛЕ ФИЛВОРДОВ РАСТЁТ ПО УРОВНЯМ И ВЛЕЗАЕТ В ЭКРАН.
 *
 * 📍 ЗАМЕР, ИЗ-ЗА КОТОРОГО ГЕЙТ НАПИСАН (06.09.2026). В `fillwordsLevel` стояло
 * `Math.min(8, …)` на ОБЕ стороны: потолок 8×8 брался на 13-м уровне, и уровни
 * 13…500 выдавали ОДНО И ТО ЖЕ поле. Разных форм за первые 60 уровней было
 * ЧЕТЫРЕ. При этом все 93 пробы филвордов были зелёными — они проверяли, что
 * поле разбирается, а не что оно меняется.
 *
 * ⚠️ ПОЭТОМУ ЗДЕСЬ ДВЕ РАЗНЫЕ ПРОВЕРКИ, И ОБЕ НУЖНЫ. Одна — что лестница правда
 * идёт вверх (прогоном всех уровней, а не сравнением первого с последним:
 * ломается такое на стыках участков). Вторая — что выросшее поле ВЛЕЗАЕТ:
 * расти можно ровно до тех пор, пока клетка не упёрлась в нижний зажим 22
 * точки, после которого сетка вылезает за край экрана.
 */
import { fillwordsLevel, generateFillwords, assertFullCoverage, ширинаПодПоле } from '@/src/games/fillwords/core/generator';
import { FILLWORDS_LOCALES } from '@/src/games/fillwords/core/words';

/** Формула клетки — та же, что в `app/games/proofreading.tsx:505-515`. */
function клетка(rows: number, cols: number, width: number, height: number): number {
  const availableHeight = Math.max(200, height - 210);
  const containerW = Math.min(width - 24, 760);
  return Math.max(22, Math.min(Math.floor(containerW / cols), Math.floor(availableHeight / rows), 72));
}

describe('лестница филвордов', () => {
  it('🔴 поле растёт и ни разу не откатывается за 200 уровней', () => {
    const откаты: string[] = [];
    let предКлеток = 0; let предСтрок = 0; let предСтолбцов = 0;
    for (let L = 1; L <= 200; L += 1) {
      const c = fillwordsLevel(L);
      if (c.rows * c.cols < предКлеток) откаты.push(`L${L}: клеток ${предКлеток}→${c.rows * c.cols}`);
      if (c.rows < предСтрок) откаты.push(`L${L}: строк ${предСтрок}→${c.rows}`);
      if (c.cols < предСтолбцов) откаты.push(`L${L}: столбцов ${предСтолбцов}→${c.cols}`);
      предКлеток = c.rows * c.cols; предСтрок = c.rows; предСтолбцов = c.cols;
    }
    expect(откаты).toEqual([]);
  });

  /**
   * 🔴 ГЛАВНАЯ ПРОВЕРКА — ИМЕННО ОНА КРАСНЕЛА БЫ НА СТАРОМ КОДЕ. Четыре формы за
   * шестьдесят уровней означают, что с тринадцатого человек играет одно и то же.
   */
  it('🔴 разных форм поля за 60 уровней не меньше десяти', () => {
    const формы = new Set<string>();
    for (let L = 1; L <= 60; L += 1) {
      const c = fillwordsLevel(L);
      формы.add(`${c.rows}x${c.cols}`);
    }
    expect(`форм ${формы.size}`).toBe(`форм ${Math.max(формы.size, 10)}`);
  });

  it('🔴 поле не квадратное — иначе вытянутых сеток жанра не будет вовсе', () => {
    const прямоугольных = Array.from({ length: 60 }, (_, i) => fillwordsLevel(i + 1))
      .filter((c) => c.rows !== c.cols).length;
    expect(`прямоугольных ${прямоугольных > 20}`).toBe('прямоугольных true');
  });

  /**
   * 🔴 ВЫРОСШЕЕ ПОЛЕ ВЛЕЗАЕТ В САМЫЙ УЗКИЙ ТЕЛЕФОН. Считается той же формулой,
   * что в экране: клетка зажата снизу 22 точками, и как только ширина сетки
   * перевалит за контейнер, поле поедет за край.
   */
  it('🔴 сетка влезает по ширине на 360 и по высоте на 640 точек', () => {
    const беды: string[] = [];
    for (let L = 1; L <= 200; L += 1) {
      const c = fillwordsLevel(L);
      for (const [w, h] of [[360, 640], [390, 844], [320, 568]]) {
        const cs = клетка(c.rows, c.cols, w as number, h as number);
        const ширина = cs * c.cols;
        const высота = cs * c.rows;
        const контейнер = Math.min((w as number) - 24, 760);
        const доступно = Math.max(200, (h as number) - 210);
        if (ширина > контейнер) беды.push(`L${L} ${w}x${h}: сетка ${ширина} > ${контейнер}`);
        if (высота > доступно) беды.push(`L${L} ${w}x${h}: высота ${высота} > ${доступно}`);
      }
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  /**
   * ⚠️ И ПОЛЕ НА ВЕРХУ ЛЕСТНИЦЫ ПРАВДА СОБИРАЕТСЯ. Прямоугольники генератор умел
   * и раньше, но «умел» и «проверено» — разные утверждения, а цена ошибки здесь
   * максимальная: неразбираемое поле человек читает как зависшую игру.
   */
  it('🔴 верх лестницы генерируется и разбирается целиком', () => {
    const плохо: string[] = [];
    for (const L of [1, 13, 24, 40, 120]) {
      const c = fillwordsLevel(L);
      const b = generateFillwords({ rows: c.rows, cols: c.cols, locale: 'ru', seed: L, maxWordLen: c.maxWordLen });
      if (!b) { плохо.push(`L${L}: поле не собралось`); continue; }
      const клеток = b.words.reduce((n, w) => n + w.path.length, 0);
      if (клеток !== c.rows * c.cols) плохо.push(`L${L}: покрыто ${клеток} из ${c.rows * c.cols}`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 ЛЕСТНИЦА ОБЯЗАНА ЖИТЬ ДАЛЬШЕ ДВАДЦАТЬ ВТОРОГО УРОВНЯ.
   *
   * 📍 Замер 06.09.2026: на 5000 уровнях лестница давала 22 РАЗНЫХ настройки, и
   * с 22-го уровня всё замирало — 4979 уровней (99,6%) были одинаковы: 12×9,
   * слово ≤8, время 194. Проверки выше этого не видели: они смотрят первые 200
   * уровней и разнообразие форм за первые 60, а замирание начиналось ровно там,
   * куда они не заглядывали.
   */
  it('🔴 настройки уровня не замирают на 22-м — лестница живёт дальше', () => {
    const виды = new Set<string>();
    for (let L = 1; L <= 5000; L += 1) {
      const c = fillwordsLevel(L);
      виды.add(`${c.rows}x${c.cols}|${c.minWordLen}|${c.maxWordLen}|${c.timeLimitSec}`);
    }
    const посл = fillwordsLevel(5000);
    let замерло = 5000;
    for (let L = 5000; L >= 1; L -= 1) {
      const c = fillwordsLevel(L);
      if (c.rows !== посл.rows || c.cols !== посл.cols || c.minWordLen !== посл.minWordLen
        || c.maxWordLen !== посл.maxWordLen || c.timeLimitSec !== посл.timeLimitSec) break;
      замерло = L;
    }
    expect(`настроек ${виды.size >= 28} · замирает после ${замерло >= 80}`)
      .toBe('настроек true · замирает после true');
  });

  /**
   * 🔴 ПОЛ ДЛИНЫ СЛОВА РАСТЁТ И НИ РАЗУ НЕ ОТКАТЫВАЕТСЯ — И НЕ ПЕРЕГОНЯЕТ ПОТОЛОК.
   * Это третья ось лестницы; она выбрана замером, а не на глаз: на поле 12×9
   * форма даёт ×1,3 к пространству поиска, а пол длины ×3,3, потому что растёт
   * длина пути, а не их число (путей длины 3 из середины поля 56, длины 8 —
   * 444 876). Разбор в шапке `fillwordsLevel`.
   */
  it('🔴 пол длины слова растёт по уровням и не перегоняет потолок', () => {
    const беды: string[] = [];
    let предПол = 0;
    for (let L = 1; L <= 300; L += 1) {
      const c = fillwordsLevel(L);
      if (c.minWordLen < предПол) беды.push(`L${L}: пол откатился ${предПол}→${c.minWordLen}`);
      if (c.minWordLen > c.maxWordLen) беды.push(`L${L}: пол ${c.minWordLen} выше потолка ${c.maxWordLen}`);
      предПол = c.minWordLen;
    }
    if (fillwordsLevel(300).minWordLen <= fillwordsLevel(1).minWordLen) {
      беды.push('пол вообще не вырос за 300 уровней — оси нет');
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  /**
   * 🔴 КРАЙ ЛЕСТНИЦЫ СОБИРАЕТСЯ НА КАЖДОМ ЯЗЫКЕ, А НЕ ТОЛЬКО НА БОГАТОМ.
   *
   * 📍 Замер 06.09.2026: с полом 7 на большом поле немецкий и португальский не
   * собирались ВОВСЕ — 40 попыток из 70 падали с «не набирает N клеток словами»,
   * то есть верхние уровни были для этих языков сломаны. Длинных слов в них
   * меньше, а слова в одном поле не повторяются. Лечится отступлением пола вниз
   * (см. `generateFillwords`), и проверять надо именно ЯЗЫКИ, а не средний случай.
   */
  it('🔴 верхние уровни собираются на ВСЕХ языках со словарём', () => {
    const беды: string[] = [];
    for (const loc of [...FILLWORDS_LOCALES]) {
      for (const L of [40, 60, 80, 94, 300]) {
        const cfg = fillwordsLevel(L);
        for (let seed = 1; seed <= 4; seed += 1) {
          try {
            const p = generateFillwords({
              rows: cfg.rows, cols: cfg.cols, locale: loc, seed,
              maxWordLen: cfg.maxWordLen, minWordLen: cfg.minWordLen,
            });
            assertFullCoverage(p);
          } catch (e) {
            беды.push(`${loc} L${L} seed${seed}: ${String((e as Error).message).slice(0, 50)}`);
          }
        }
      }
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  /**
   * 🔴 ОТСТУПЛЕНИЕ ПОЛА — СТРАХОВКА, И ПРОВЕРЯТЬ ЕЁ НАДО ТАМ, ГДЕ ОНА СРАБАТЫВАЕТ.
   *
   * 📍 Проба выше («верхние уровни на всех языках») зелёная и без отступления:
   * мутация это показала. Причина не в том, что страховка лишняя, а в том, что
   * нынешняя лестница до неё не доходит — потолок опустился с 20 строк до 16,
   * поле стало 144 клетки вместо 180, и словаря снова хватает.
   *
   * Поэтому здесь поле запрашивается НАПРЯМУЮ, мимо лестницы, и берётся такое,
   * которого словарь заведомо не тянет: без отступления `18×9` с полом 7 не
   * собирается у немецкого ни разу из шести, `20×9` — ни у немецкого, ни у
   * португальского. С отступлением обязаны собираться оба.
   */
  it('🔴 поле, которого словарь не тянет, отдаётся полегче, а не падает', () => {
    const беды: string[] = [];
    for (const [loc, rows] of [['de', 18], ['de', 20], ['pt', 20]] as const) {
      for (let seed = 1; seed <= 6; seed += 1) {
        try {
          const p = generateFillwords({ rows, cols: 9, locale: loc, seed, minWordLen: 7, maxWordLen: 8 });
          assertFullCoverage(p);
          // отступило — значит какое-то слово короче запрошенных семи; это и есть смысл
          const мин = Math.min(...p.words.map((w) => w.word.length));
          if (мин > 8) беды.push(`${loc} ${rows}x9 seed${seed}: слово длиннее потолка`);
        } catch (e) {
          беды.push(`${loc} ${rows}x9 seed${seed}: упало — ${String((e as Error).message).slice(0, 45)}`);
        }
      }
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  it('🔴 время считается от площади, а не от квадрата стороны', () => {
    for (const L of [16, 24, 40]) {
      const c = fillwordsLevel(L);
      // Секунд на клетку в человеческом диапазоне: не меньше 1,5 и не больше 3,5.
      const наКлетку = c.timeLimitSec / (c.rows * c.cols);
      expect(`L${L}: ${наКлетку >= 1.5 && наКлетку <= 3.5}`).toBe(`L${L}: true`);
    }
  });

  /**
   * 🔴 СО СПИСКОМ СЛОВ ПОЛЕ ОБЯЗАНО БЫТЬ НИЖЕ — ИНАЧЕ ОНО ВЫЛЕЗЕТ МОЛЧА.
   *
   * 📍 Замер: на экране 320×568 под сетку остаётся 358 точек. Список из двадцати
   * слов по три в строке — семь строк, около 126 точек; полю достаётся 232, а
   * шестнадцать строк по 22 точки требуют 352. Клетка при этом упирается в свой
   * минимум и дальше не ужимается, поэтому переполнение не видно ни по одной
   * прежней проверке — сетка просто уезжает за край.
   */
  /**
   * 🔴 СО СПИСКОМ СБОКУ ПОЛЕ ВЛЕЗАЕТ ПО ШИРИНЕ, А НЕ ПО ВЫСОТЕ.
   *
   * 📍 Сначала список стоял НАД полем и забирал высоту: на 320×568 он съедал
   * около 126 точек из 358, полю оставалось 232 — десять строк. Я ограничил
   * форму десятью строками, и это было лечение симптома. Замер показал лучшее:
   * сбоку список забирает ШИРИНУ, которой у поля запас. 90 точек оставляют 206 —
   * девять столбцов, а строк снова шестнадцать. Клеток 144 против 90.
   *
   * Поэтому потолок формы один на оба режима, а проверять надо ШИРИНУ.
   */
  it('🔴 со списком сбоку поле влезает по ширине на самом узком экране', () => {
    const W = 320; const H = 568;
    // ⚠️ Берём ту же функцию, что зовёт экран, а не копию формулы: копия сверяет
    // модель сама с собой и пропускает случай «экран расчёт не применил».
    const подПоле = ширинаПодПоле(W, true);
    const доступноH = Math.max(200, H - 210);
    const беды: string[] = [];
    for (let L = 1; L <= 300; L += 1) {
      const c = fillwordsLevel(L);
      const клетка = Math.max(22, Math.min(Math.floor(подПоле / c.cols), Math.floor(доступноH / c.rows), 72));
      if (клетка * c.cols > подПоле) беды.push(`L${L}: ${c.rows}×${c.cols} требует ${клетка * c.cols} при ${подПоле}`);
      if (клетка * c.rows > доступноH) беды.push(`L${L}: по высоте ${клетка * c.rows} при ${доступноH}`);
    }
    expect(беды.slice(0, 3)).toEqual([]);
  });

  /**
   * 🔴 ПРОВЕРЯЕМ САМО ВЫЧИТАНИЕ, А НЕ ЕГО СЛЕДСТВИЕ.
   *
   * Проба выше смотрит, влезает ли поле, — и она проходит ДАЖЕ ЕСЛИ ширина списка
   * не вычтена: девять столбцов по 22 точки укладываются и в 296, и в 206.
   * Мутация «расчёт вернул полную ширину» проскочила мимо неё дважды. Свойство,
   * ради которого функция написана, надо утверждать прямо.
   */
  it('🔴 со списком сбоку полю достаётся МЕНЬШЕ ширины, чем без него', () => {
    for (const W of [320, 360, 414, 768]) {
      const сСписком = ширинаПодПоле(W, true);
      const без = ширинаПодПоле(W, false);
      expect(`${W}: ${сСписком < без}`).toBe(`${W}: true`);
      // и вычитается именно ширина колонки, а не что попало
      expect(без - сСписком).toBe(Math.min(120, Math.round(W * 0.3)));
    }
  });

  it('потолок формы один на оба режима — список высоту больше не занимает', () => {
    expect(fillwordsLevel(300).rows).toBe(16);
  });
});
