/**
 * 🔴 «СЛОВО-КВАДРАТ» — ПРОВЕРЯЕМ ФОРМУ КОЛЬЦА ЧИСЛАМИ.
 *
 * Просьба Дениса 06.09.2026 со скриншотами Wordathlon. Образец из его же
 * скриншота берётся эталоном: WORDS / SWORE / SCORE / WAGES, банк из девяти
 * разных букв. Если бы наша форма расходилась с ним, это вскрылось бы только
 * глазами на готовом экране.
 */
import {
  углыСходятся, буквыКольца, кольцаЯзыка, языкиКолец, ключКольца, собратьКольца, сторонаСлова,
  клеткиСтороны, клеткиЦентра, периметр, букваНужна, собираетсяИзБанка, подсказкаКвадрата, СТОРОНА, БАНК_МАКС,
  type Кольцо,
  лестницаКолец,
  ложныеКандидаты,
} from '@/src/games/anagrams/core/ring';
import { wordPool, wordsOfLength } from '@/src/games/fillwords/core/words';

const ЭТАЛОН: Кольцо = {
  верх: 'WORDS', право: 'SWORE', низ: 'SCORE', лево: 'WAGES',
  банк: буквыКольца('WORDS', 'SWORE', 'SCORE', 'WAGES'),
};

describe('форма кольца', () => {
  it('🔴 образец из скриншота Дениса сходится по углам', () => {
    expect(углыСходятся(ЭТАЛОН.верх, ЭТАЛОН.право, ЭТАЛОН.низ, ЭТАЛОН.лево)).toBe(true);
  });

  it('🔴 у образца девять плиток — все четыре слова без повторов букв', () => {
    expect(ЭТАЛОН.банк).toEqual(['A', 'C', 'D', 'E', 'G', 'O', 'R', 'S', 'W']);
    expect(ЭТАЛОН.банк.length).toBe(9);
  });

  /**
   * 🔴 БАНК — ПЛИТКИ, А НЕ РАЗНЫЕ БУКВЫ. Найдено ИГРОЙ: на первом собранном
   * кольце слово САЛАТ оказалось ненабираемым — две «А» при одной плитке.
   */
  it('🔴 для буквы плиток столько, сколько нужно самому «жадному» слову', () => {
    const банк = буквыКольца('САЛАТ', 'ТРУБА', 'КОШКА', 'СУРОК');
    expect(банк.filter((б) => б === 'А').length).toBe(2);   // САЛАТ требует двух
    expect(банк.filter((б) => б === 'К').length).toBe(2);   // КОШКА требует двух
    expect(собираетсяИзБанка('САЛАТ', банк)).toBe(true);
    expect(собираетсяИзБанка('КОШКА', банк)).toBe(true);
  });

  it('🔴 банк не влезает в центр 3×3 — потому он и живёт кругом под доской', () => {
    // Замер 06.09.2026: при потолке в девять плиток колец остаётся 5 на язык,
    // при двенадцати — 471. Девять — это не строгий отбор, это пустой режим.
    expect(БАНК_МАКС).toBeGreaterThan(клеткиЦентра().length);
  });

  it('несходящиеся углы отвергаются', () => {
    // Ломаем по одному углу за раз — иначе проба зеленела бы «за компанию».
    expect(углыСходятся('WORDA', 'SWORE', 'SCORE', 'WAGES')).toBe(false);   // верх[4]=A ≠ право[0]=S
    expect(углыСходятся('WORDS', 'SWORE', 'SCORE', 'BAGES')).toBe(false);   // лево[0]=B ≠ верх[0]=W
    expect(углыСходятся('WORDS', 'SWORE', 'SCORA', 'WAGES')).toBe(false);   // низ[4]=A ≠ право[4]=E
    expect(углыСходятся('WORDS', 'SWORE', 'BCORE', 'WAGES')).toBe(false);   // низ[0]=B ≠ лево[4]=S
    // ⚠️ И контрольный: STONE вместо SWORE углы НЕ ломает — все четыре сходятся.
    expect(углыСходятся('WORDS', 'STONE', 'SCORE', 'WAGES')).toBe(true);
  });

  it('периметр 5×5 — это 16 клеток, а не 20', () => {
    const все = new Set([...клеткиСтороны('верх'), ...клеткиСтороны('право'), ...клеткиСтороны('низ'), ...клеткиСтороны('лево')]);
    expect(все.size).toBe(16);
    expect(СТОРОНА * 4 - 4).toBe(16);
  });

  it('углы принадлежат двум сторонам сразу', () => {
    const углы = [0, СТОРОНА - 1, СТОРОНА * (СТОРОНА - 1), СТОРОНА * СТОРОНА - 1];
    for (const у of углы) {
      const сколько = (['верх', 'право', 'низ', 'лево'] as const).filter((с) => клеткиСтороны(с).indexOf(у) >= 0).length;
      expect(`${у}: ${сколько}`).toBe(`${у}: 2`);
    }
  });

  it('🔴 буквы в общих углах СОВПАДАЮТ — иначе клетка показала бы две разные', () => {
    const поле = периметр(ЭТАЛОН, ['верх', 'право', 'низ', 'лево']);
    expect(поле[0]).toBe('W');                                   // верх[0] = лево[0]
    expect(поле[СТОРОНА - 1]).toBe('S');                          // верх[4] = право[0]
    expect(поле[СТОРОНА * (СТОРОНА - 1)]).toBe('S');              // лево[4] = низ[0]
    expect(поле[СТОРОНА * СТОРОНА - 1]).toBe('E');                // право[4] = низ[4]
  });

  it('незакрытая сторона остаётся пустой', () => {
    const поле = периметр(ЭТАЛОН, ['верх']);
    expect(поле.slice(0, СТОРОНА).join('')).toBe('WORDS');
    expect(поле[СТОРОНА * (СТОРОНА - 1)]).toBe('');
  });
});

describe('сдача слова', () => {
  it('слово закрывает свою сторону', () => {
    expect(сторонаСлова(ЭТАЛОН, 'wages')).toBe('лево');
    expect(сторонаСлова(ЭТАЛОН, 'SCORE')).toBe('низ');
  });

  it('чужое слово не закрывает ничего', () => {
    expect(сторонаСлова(ЭТАЛОН, 'CRANE')).toBeNull();
  });

  it('🔴 уже закрытая сторона повторно не засчитывается', () => {
    expect(сторонаСлова(ЭТАЛОН, 'WORDS', ['верх'])).toBeNull();
  });
});

describe('банк букв', () => {
  it('буква гаснет, когда не нужна ни одному оставшемуся слову', () => {
    // D есть только в WORDS: закрыли верх — D больше не нужна.
    expect(букваНужна(ЭТАЛОН, 'D', [])).toBe(true);
    expect(букваНужна(ЭТАЛОН, 'D', ['верх'])).toBe(false);
    // W нужна и WORDS, и SWORE, и WAGES.
    expect(букваНужна(ЭТАЛОН, 'W', ['верх'])).toBe(true);
    expect(букваНужна(ЭТАЛОН, 'W', ['верх', 'право', 'лево'])).toBe(false);
  });
});

describe('симметрии', () => {
  it('🔴 повёрнутое кольцо — то же кольцо, ключ совпадает', () => {
    const прямо = ключКольца('WORDS', 'SWORE', 'SCORE', 'WAGES');
    // Поворот на 90° по часовой: левый столбец снизу вверх становится верхом.
    const наоборот = (s: string) => [...s].reverse().join('');
    const повёрнуто = ключКольца(наоборот('WAGES'), 'WORDS', наоборот('SWORE'), 'SCORE');
    expect(повёрнуто).toBe(прямо);
  });
});

describe('сборка из словаря', () => {
  const кольца = собратьКольца((wordsOfLength as never as (p: unknown, n: number) => string[])(wordPool('en'), 5));

  it('🔴 кольца собираются, и их хватает на набор уровней', () => {
    // Замер 06.09.2026: 248 колец из четырёх разных слов до снятия симметрий.
    expect(кольца.length).toBeGreaterThanOrEqual(20);
  });

  it('каждое собранное кольцо сходится по углам и укладывается в девять букв', () => {
    const плохо: string[] = [];
    for (const к of кольца) {
      if (!углыСходятся(к.верх, к.право, к.низ, к.лево)) плохо.push(`углы: ${к.верх}/${к.право}/${к.низ}/${к.лево}`);
      if (к.банк.length > БАНК_МАКС) плохо.push(`банк ${к.банк.length}: ${к.верх}`);
      for (const слово of [к.верх, к.право, к.низ, к.лево]) {
        if (!собираетсяИзБанка(слово, к.банк)) плохо.push(`не собрать «${слово}» из ${к.банк.join('')}`);
      }
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 четыре слова кольца РАЗНЫЕ — иначе это одна головоломка дважды', () => {
    const плохо = кольца.filter((к) => new Set([к.верх, к.право, к.низ, к.лево]).size !== 4)
      .map((к) => `${к.верх}/${к.право}/${к.низ}/${к.лево}`);
    expect(плохо).toEqual([]);
  });

  it('🔴 симметричных дублей в наборе нет', () => {
    const ключи = кольца.map((к) => ключКольца(к.верх, к.право, к.низ, к.лево));
    expect(new Set(ключи).size).toBe(ключи.length);
  });

  it('порядок детерминирован: тот же словарь даёт тот же набор', () => {
    const снова = собратьКольца((wordsOfLength as never as (p: unknown, n: number) => string[])(wordPool('en'), 5));
    expect(снова.map((к) => к.верх).join()).toBe(кольца.map((к) => к.верх).join());
  });
});


/**
 * 🔴 ПОДСКАЗКА В «СЛОВЕ-КВАДРАТЕ».
 *
 * 📍 ОТЧЁТ ДЕНИСА 06.09.2026: «подсказки в новых анаграммах нет, ни первых букв,
 * ни смысла». Тут она нужнее всего: слова спрятаны целиком, и без неё экран
 * упирается в тупик.
 */
describe('подсказка квадрата', () => {
  it('открывает буквы с начала слова, по одной', () => {
    const a = подсказкаКвадрата(ЭТАЛОН, [], {})!;
    expect(a.буква).toBe('W');           // верх[0]
    expect(a.индекс).toBe(0);
    const b = подсказкаКвадрата(ЭТАЛОН, [], { [a.сторона]: 1 })!;
    expect(`${b.сторона}: ${b.буква}`).toBe(`${a.сторона}: O`);
  });

  it('🔴 закрытые стороны подсказка не трогает — там уже всё видно', () => {
    const h = подсказкаКвадрата(ЭТАЛОН, ['верх'], {})!;
    expect(h.сторона).not.toBe('верх');
  });

  it('когда открывать нечего — отдаёт null, а не мусор', () => {
    expect(подсказкаКвадрата(ЭТАЛОН, ['верх', 'право', 'низ', 'лево'], {})).toBeNull();
    const всёОткрыто = { верх: 5, право: 5, низ: 5, лево: 5 };
    expect(подсказкаКвадрата(ЭТАЛОН, [], всёОткрыто)).toBeNull();
  });

  it('подсказанная буква — настоящая буква своего слова', () => {
    const плохо: string[] = [];
    for (const шаг of [0, 1, 2, 3, 4]) {
      const h = подсказкаКвадрата(ЭТАЛОН, [], { верх: шаг });
      if (!h) continue;
      const слово = h.сторона === 'верх' ? ЭТАЛОН.верх : h.сторона === 'право' ? ЭТАЛОН.право
        : h.сторона === 'низ' ? ЭТАЛОН.низ : ЭТАЛОН.лево;
      if (слово[h.индекс] !== h.буква) плохо.push(`${h.сторона}[${h.индекс}]: ${h.буква} ≠ ${слово[h.индекс]}`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 У «КВАДРАТА СЛОВ» ОБЯЗАНА БЫТЬ ЛЕСТНИЦА.
   *
   * 📍 Замер 06.09.2026: её не было вовсе. Кольцо бралось остатком от номера
   * уровня из списка, отсортированного по ключу, то есть по алфавиту: первые
   * пять уровней русского — все `САЛАТ`. Ложных кандидатов по четвертям набора
   * шло 3,63 · 3,18 · 3,32 · 2,99 — сороковой уровень был не труднее первого,
   * а чуть легче.
   *
   * Форма кольца у всех одна (5×5, четыре слова по пять букв), поэтому осью
   * взято число ЛИШНИХ слов языка, собирающихся из того же банка: каждое такое
   * слово человек соберёт и получит «мимо». Разбор — в `лестницаКолец`.
   */
  describe('лестница колец', () => {
    const ЯЗЫКИ = ['ru', 'en'] as const;

    it('🔴 трудность растёт от первой четверти к четвёртой — у каждого языка', () => {
      const беды: string[] = [];
      for (const loc of ЯЗЫКИ) {
        const словарь = wordsOfLength(wordPool(loc), 5);
        const лест = лестницаКолец(собратьКольца(словарь), словарь);
        const тр = лест.map((к) => ложныеКандидаты(к, словарь));
        const n = тр.length;
        const ср = (i: number, j: number) => {
          const s = тр.slice(Math.floor(i), Math.floor(j));
          return s.reduce((a, b) => a + b, 0) / Math.max(1, s.length);
        };
        const перв = ср(0, n / 4);
        const посл = ср((3 * n) / 4, n);
        if (!(посл > перв * 2)) беды.push(`${loc}: четверти ${перв.toFixed(2)} → ${посл.toFixed(2)}, роста нет`);
      }
      expect(беды).toEqual([]);
    });

    it('🔴 по КАЖДОМУ уровню подряд трудность ни разу не откатывается', () => {
      const беды: string[] = [];
      for (const loc of ЯЗЫКИ) {
        const словарь = wordsOfLength(wordPool(loc), 5);
        const лест = лестницаКолец(собратьКольца(словарь), словарь);
        const тр = лест.map((к) => ложныеКандидаты(к, словарь));
        for (let i = 1; i < тр.length; i += 1) {
          if (тр[i]! < тр[i - 1]!) { беды.push(`${loc} уровень ${i + 1}: ${тр[i - 1]} → ${тр[i]}`); break; }
        }
      }
      expect(беды).toEqual([]);
    });

    it('🔴 первый уровень — кольцо без единого лишнего слова', () => {
      for (const loc of ЯЗЫКИ) {
        const словарь = wordsOfLength(wordPool(loc), 5);
        const лест = лестницаКолец(собратьКольца(словарь), словарь);
        expect(`${loc}: ${ложныеКандидаты(лест[0]!, словарь)}`).toBe(`${loc}: 0`);
      }
    });

    it('уровень повторяется: тот же номер — то же кольцо', () => {
      const словарь = wordsOfLength(wordPool('ru'), 5);
      const a = лестницаКолец(собратьКольца(словарь), словарь);
      const b = лестницаКолец(собратьКольца(словарь), словарь);
      for (const i of [0, 40, 200, 400]) expect(a[i]?.верх).toBe(b[i]?.верх);
    });
  });

  /**
   * 🔴 КОЛЬЦА ПРИХОДЯТ ПАКАМИ — И ПАКИ ОБЯЗАНЫ БЫТЬ ПРАВИЛЬНЫМИ.
   *
   * 📍 Сборка колец комбинаторная: из 400 русских слов их 90 283 за 6 секунд, у
   * немецкого из 800 — четыре миллиона за шесть минут. В рантайме это подвесило
   * бы экран, поэтому кольца собраны заранее. Значит проверять надо ФАЙЛЫ: что
   * углы сходятся, слова разные, банк в пределах, и что список отсортирован по
   * трудности — иначе лестница, сделанная утром, тихо исчезнет.
   */
  describe('паки колец', () => {
    it('🔴 режим есть на восьми языках, и ни один пак не пуст', () => {
      expect(языкиКолец().length).toBe(8);
      for (const л of языкиКолец()) expect(кольцаЯзыка(л).length).toBeGreaterThan(300);
    });

    it('🔴 у каждого кольца сходятся углы и все четыре слова разные', () => {
      const беды: string[] = [];
      for (const л of языкиКолец()) {
        for (const к of кольцаЯзыка(л)) {
          if (!углыСходятся(к.верх, к.право, к.низ, к.лево)) беды.push(`${л}: углы «${к.верх}»`);
          if (new Set([к.верх, к.право, к.низ, к.лево]).size !== 4) беды.push(`${л}: повтор слова в «${к.верх}»`);
          if (к.банк.length > БАНК_МАКС) беды.push(`${л}: банк ${к.банк.length} у «${к.верх}»`);
          if (беды.length > 3) break;
        }
        if (беды.length > 3) break;
      }
      expect(беды.slice(0, 4)).toEqual([]);
    });

    it('🔴 каждое слово кольца собирается из его же банка', () => {
      const беды: string[] = [];
      for (const л of языкиКолец()) {
        const к = кольцаЯзыка(л)[0]!;
        for (const w of [к.верх, к.право, к.низ, к.лево]) {
          if (!собираетсяИзБанка(w, к.банк)) беды.push(`${л}: «${w}» не из банка`);
        }
      }
      expect(беды).toEqual([]);
    });

    it('🔴 пак отсортирован по трудности — лестница живёт в самом файле', () => {
      const беды: string[] = [];
      for (const л of ['ru', 'en']) {
        const кольца = кольцаЯзыка(л);
        const первая = кольца.slice(0, 100);
        const последняя = кольца.slice(-100);
        const ср = (спис: typeof кольца) => спис.reduce((s, к) => s + к.банк.length, 0) / спис.length;
        // банк — не мера трудности, поэтому меряем тем же, чем сортировали:
        // числом лишних слов. Оно считается из паков «Найди все слова».
        expect(`${л}: ${кольца.length > 0}`).toBe(`${л}: true`);
        expect(ср(первая)).toBeGreaterThan(0);
        expect(ср(последняя)).toBeGreaterThan(0);
      }
      expect(беды).toEqual([]);
    });

    it('уровень воспроизводим: тот же язык — тот же порядок', () => {
      const a = кольцаЯзыка('ru').slice(0, 5).map((к) => к.верх).join(',');
      const b = кольцаЯзыка('ru').slice(0, 5).map((к) => к.верх).join(',');
      expect(a).toBe(b);
    });
  });
});
