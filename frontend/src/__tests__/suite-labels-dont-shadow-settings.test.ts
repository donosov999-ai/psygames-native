/**
 * 🔴 ПЛАШКА РЕЖИМА НЕ ДОЛЖНА ПОВТОРЯТЬ СЛОВА СОБСТВЕННОЙ НАСТРОЙКИ ЭКРАНА.
 *
 * Денис 05.09.2026, сразу после объединения: «струп торможение — там уже два
 * упражнения было по настройкам, смотри чтобы не проебалось это».
 *
 * Настройка на месте — но рядом с ней встала плашка набора, и на экране Струпа
 * оказалось ДВА выбора из двух, подписанных почти одинаково:
 *
 *     Режим:        Чернила  |  Эмоция          ← набор, меняет ПАРАДИГМУ
 *     Что отвечать: По цвету чернил | По значению слова   ← правило ВНУТРИ пробы
 *
 * «Чернила» целиком лежит внутри «По цвету чернил». Человек читает два
 * переключателя об одном и том же и жмёт не тот: потерять настройку можно не
 * только удалив её, но и поставив рядом двойника. Плашки переименованы в
 * «Классический / Эмоциональный».
 *
 * ⚠️ СРАВНЕНИЕ ПО ОСНОВАМ СЛОВ, А НЕ ПО ПОДСТРОКЕ. Первый вариант пробы сравнивал
 * строки как есть — и МУТАЦИЮ НЕ ПОЙМАЛ: «Чернила» не является подстрокой «По
 * цвету чернил», потому что слово склоняется («чернил» ≠ «чернила»). Русский
 * язык обходит побуквенное сравнение по построению, и такая проба была бы
 * гейтом-призраком: зелёная ровно на том дефекте, ради которого написана.
 * Поэтому слова режутся до основы (первые пять букв) и сравниваются основами.
 *
 * ⚠️ ПРОВЕРКА ОДНОСТОРОННЯЯ: все слова ПЛАШКИ встречаются в подписи настройки.
 * Обратное направление давало бы ложное срабатывание на кнопке «Правила» рядом с
 * плашкой «Смена правил» — это разные вещи, и совпадение одного слова там ничего
 * не значит.
 *
 * Что читается: исходник экрана каждой парадигмы набора → все ключи `t('…')` из
 * него → их русские и английские строки из словаря → сравнение с подписями
 * плашек этого набора.
 */
declare const __dirname: string;
declare function require(id: string): any;

const fs = require('fs');
const path = require('path');
const КОРЕНЬ = path.join(__dirname, '../..');

import { GAME_SUITES } from '@/src/constants/gameSuites';

/** Словарь как текст: нужен не React-контекст, а строки. */
function словарь(): Record<string, { ru: string; en: string }> {
  const src: string = fs.readFileSync(path.join(КОРЕНЬ, 'src/contexts/LanguageContext.tsx'), 'utf8');
  const из: Record<string, { ru: string; en: string }> = {};
  for (const m of src.matchAll(/^ {2}([a-zA-Z_][a-zA-Z0-9_]*):\s*\{\s*ru:\s*'((?:[^'\\]|\\.)*)',\s*en:\s*'((?:[^'\\]|\\.)*)'\s*\}/gm)) {
    из[m[1]!] = { ru: m[2]!, en: m[3]! };
  }
  return из;
}

/** Ключи подписей, которые экран реально показывает. */
function ключиЭкрана(route: string): string[] {
  const f = path.join(КОРЕНЬ, '..', 'frontend', 'app' + route + '.tsx');
  const файл = fs.existsSync(f) ? f : path.join(КОРЕНЬ, '../app' + route + '.tsx');
  if (!fs.existsSync(файл)) return [];
  const src: string = fs.readFileSync(файл, 'utf8');
  return [...src.matchAll(/\bt\('([a-zA-Z_][a-zA-Z0-9_]*)'\)/g)].map((m) => m[1]!);
}

const нормаль = (s: string) => s.toLowerCase().replace(/[«»"'.,:;!?()]/g, ' ').replace(/\s+/g, ' ').trim();

describe('подписи режимов не затмевают настройки игры', () => {
  const СЛОВАРЬ = словарь();

  it('словарь разобрался — иначе проба зелена вслепую', () => {
    expect(Object.keys(СЛОВАРЬ).length).toBeGreaterThan(300);
    expect(СЛОВАРЬ.stroopByInk?.ru).toBe('По цвету чернил');
  });

  it('у каждой плашки есть перевод', () => {
    const нет: string[] = [];
    for (const набор of GAME_SUITES) {
      for (const m of набор.modes) if (!СЛОВАРЬ[m.labelKey]) нет.push(`${набор.id}: ${m.labelKey}`);
    }
    expect(нет).toEqual([]);
  });

  /**
   * ⚠️ СРАВНИВАЕМ ТОЛЬКО С ПОДПИСЯМИ ОРГАНОВ УПРАВЛЕНИЯ, А НЕ СО ВСЕМ ТЕКСТОМ.
   *
   * Первый вариант пробы ругался на «Позиция» внутри «Simon: цвет vs позиция» —
   * то есть на НАЗВАНИЕ игры, где парадигма упомянута совершенно законно. Беда
   * не в упоминании, а в двух похоже подписанных ПЕРЕКЛЮЧАТЕЛЯХ рядом. Поэтому
   * отсекаем: имя и описание самой игры, строки с подстановками ({n}, {w}) и
   * длинные пояснения — подписи кнопок такими не бывают.
   */
  const ДЛИННАЯ = 40;
  function своиПодписи(route: string): string[] {
    const каталог: string = fs.readFileSync(path.join(КОРЕНЬ, 'src/constants/games.ts'), 'utf8');
    const запись = каталог.split('{').find((b: string) => b.includes(`route: '${route}'`)) ?? '';
    const своё = new Set([
      /nameKey:\s*'([a-zA-Z0-9_]+)'/.exec(запись)?.[1],
      /descKey:\s*'([a-zA-Z0-9_]+)'/.exec(запись)?.[1],
    ].filter(Boolean) as string[]);
    return ключиЭкрана(route).filter((k) => !своё.has(k));
  }

  /** Основы значимых слов: «чернила» и «чернил» дают одну и ту же «черни». */
  const ОСНОВА = 5;
  function основы(s: string): Set<string> {
    return new Set(нормаль(s).split(' ').filter((w) => w.length >= 4).map((w) => w.slice(0, ОСНОВА)));
  }

  it('🔴 слова плашки не повторяют подпись настройки на том же экране', () => {
    const столкновения: string[] = [];
    for (const набор of GAME_SUITES) {
      const плашки = набор.modes.map((m) => ({ ключ: m.labelKey, ...СЛОВАРЬ[m.labelKey]! })).filter((x) => x.ru);
      for (const режим of набор.modes) {
        const свои = new Set(своиПодписи(режим.route));
        for (const плашка of плашки) {
          for (const ключ of свои) {
            if (ключ === плашка.ключ) continue;
            const строка = СЛОВАРЬ[ключ];
            if (!строка) continue;
            if (строка.ru.includes('{') || строка.en.includes('{')) continue;      // строка с подстановками — не кнопка
            if (строка.ru.length > ДЛИННАЯ || строка.en.length > ДЛИННАЯ) continue; // пояснение — не кнопка
            for (const язык of ['ru', 'en'] as const) {
              const плашкаОсновы = основы(плашка[язык]);
              const настройкаОсновы = основы(строка[язык]);
              if (!плашкаОсновы.size || !настройкаОсновы.size) continue;
              if (плашкаОсновы.size >= настройкаОсновы.size) continue;   // подпись не длиннее плашки — не «часть»
              const всеВнутри = [...плашкаОсновы].every((o) => настройкаОсновы.has(o));
              if (всеВнутри) {
                столкновения.push(`${режим.route}: плашка «${плашка[язык]}» (${плашка.ключ}) читается как часть настройки «${строка[язык]}» (${ключ})`);
              }
            }
          }
        }
      }
    }
    expect(столкновения).toEqual([]);
  });

  it('🔴 плашки одного набора различимы между собой', () => {
    const беды: string[] = [];
    for (const набор of GAME_SUITES) {
      const подписи = набор.modes.map((m) => СЛОВАРЬ[m.labelKey]?.ru ?? '');
      for (let i = 0; i < подписи.length; i++) {
        for (let j = 0; j < подписи.length; j++) {
          if (i === j) continue;
          const a = нормаль(подписи[i]!); const b = нормаль(подписи[j]!);
          if (a && b && (a === b || b.includes(a))) беды.push(`${набор.id}: «${подписи[i]}» и «${подписи[j]}»`);
        }
      }
    }
    expect(беды).toEqual([]);
  });
});
