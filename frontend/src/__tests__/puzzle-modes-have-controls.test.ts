/**
 * У КАЖДОГО РЕЖИМА ГОЛОВОЛОМОК ЕСТЬ ЧЕМ ИГРАТЬ.
 *
 * 🔴 ПОВОД — Денис 10.09.2026: «игры что перенёс не работают, сломана игровая
 * механика… почти все». Прогон моста по всем сорока (тычок в центр клетки, тычок в
 * ребро, тычок в узел, протяжка, правая кнопка, цифра, стрелка — и сравнение
 * рисунка до и после) дал точную картину:
 *
 *   не играется НИЧЕМ                     0 из 40
 *   отвечают только на стрелки            Map, Pegs, Signpost, Solo, Untangle
 *   отвечают на узел и стрелки            Unequal
 *   правая кнопка даёт свой результат     15 игр
 *   цифра вписывается                     Keen, Towers, Solo, Unequal, Filling, Undead
 *
 * А на экране крест стрелок показывался только `Cube` и `Inertia`, второго действия
 * не существовало вовсе (признак был зашит `false`), клавиш цифр не было ни одной.
 * То есть у шести игр на экране НЕ БЫЛО НИ ОДНОГО рабочего органа: доска
 * рисуется, а тронуть её нечем. Это и есть «сломана механика».
 *
 * ⚠️ Проба сверяет СПИСКИ с замером, а не гоняет wasm: `psy_generate` в jest
 * возвращает 0 (причина не найдена, записана в заголовке моста), поэтому живой
 * прогон делается скриптом, а здесь закрепляется его результат.
 */
import { СТРЕЛОЧНЫЕ, ЦИФРОВЫЕ, ВТОРОЕ_ДЕЙСТВИЕ, клавишДоски } from '@/src/games/tatham-bridge/names';

/** Кому без стрелок нечем играть — замер 10.09.2026. */
const БЕЗ_СТРЕЛОК_НИКАК = ['Map', 'Pegs', 'Signpost', 'Solo', 'Untangle', 'Unequal'];
/** Кому нужно вписывать число. */
const ВПИСЫВАЮТ_ЧИСЛО = ['Keen', 'Towers', 'Solo', 'Unequal'];

describe('у каждого режима головоломок есть чем играть', () => {
  it('есть что проверять — списки не пусты', () => {
    expect(СТРЕЛОЧНЫЕ.size).toBeGreaterThan(2);
    expect(ЦИФРОВЫЕ.size).toBeGreaterThan(0);
    expect(ВТОРОЕ_ДЕЙСТВИЕ.size).toBeGreaterThan(10);
  });

  it('🔴 у кого без стрелок нет ни одного рабочего органа — крест показан', () => {
    const без = БЕЗ_СТРЕЛОК_НИКАК.filter((и) => !СТРЕЛОЧНЫЕ.has(и));
    expect(без).toEqual([]);
  });

  it('🔴 кто вписывает число — у того есть клавиши цифр', () => {
    const без = ВПИСЫВАЮТ_ЧИСЛО.filter((и) => !ЦИФРОВЫЕ.has(и));
    expect(без).toEqual([]);
  });

  it('🔴 Solo и Unequal нужны ОБА органа: стрелки водят курсор, цифры вписывают', () => {
    for (const и of ['Solo', 'Unequal']) {
      expect(`${и}: стрелки ${СТРЕЛОЧНЫЕ.has(и)}, цифры ${ЦИФРОВЫЕ.has(и)}`)
        .toBe(`${и}: стрелки true, цифры true`);
    }
  });

  it('🔴 Магниты среди тех, кому нужно второе действие — им ставят пустую клетку', () => {
    // Ровно тот случай, с которого начался разбор: 103 хода и доска не сходится.
    expect(ВТОРОЕ_ДЕЙСТВИЕ.has('Magnets')).toBe(true);
  });

  it('🔴 клавиш столько, сколько сторона доски, а не девять всегда', () => {
    // Параметры, а не подписи: у Keen и Towers это «4de», у Undead «4x4de».
    expect(клавишДоски('Keen', '4de')).toBe(4);
    expect(клавишДоски('Towers', '5de')).toBe(5);
    /**
     * 🔴 У «НЕЖИТИ» ЦИФРА — ВИД ЧУДОВИЩА, А НЕ СТОРОНА ДОСКИ. Их три: призрак,
     * вампир, зомби. Здесь стояло 4 — «сторона поля», и это было МОЕЙ ошибкой,
     * пойманной прогоном 11.09.2026: доска принимает только 1, 2, 3, а мы раздавали
     * 4, 5 и 7 клавиш — от одной до четырёх мёртвых на каждой из восьми ступеней.
     */
    expect(клавишДоски('Undead', '4x4dt')).toBe(3);
    expect(клавишДоски('Undead', '7x7dt')).toBe(3);
    // 🔴 У судоку число — БЛОКИ: «2x2» это поле 4×4 и цифры 1–4, а не 1–2.
    expect(клавишДоски('Solo', '2x2')).toBe(4);
    expect(клавишДоски('Solo', '3x3')).toBe(9);
    // У «Заполнения» цифра — размер области, поле тут ни при чём.
    expect(клавишДоски('Filling', '13x9')).toBe(9);
    // Не разобрали — девять, как у судоку.
    expect(клавишДоски('Pegs', 'Cross 5x7')).toBe(9);
  });
});

/**
 * ИГРАМ, ГДЕ ТЫЧОК НЕ РАБОТАЕТ, ЕСТЬ ЧЕМ ИГРАТЬ И ПРО ЭТО СКАЗАНО.
 *
 * Замер 11.09.2026 (одиночный тычок по сетке, критерий — изменение рисунка):
 *   «Раскраска карты» 0 из 663 · «Колышки» 0 из 297 · «Указатели» 0 из 360
 *   «Распутать» 0 из 384 · «Угадай код» 0 из 396
 * При этом вводный текст раздела обещал «короткое нажатие по полю делает ход».
 */
describe('тычок работает не у всех', () => {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const имена = require('@/src/games/tatham-bridge/names');

  it('🔴 четверым сказано, что тянут пальцем, а не касаются', () => {
    expect([...имена.ТОЛЬКО_ПРОТЯЖКА].sort()).toEqual(['Map', 'Pegs', 'Signpost', 'Untangle']);
  });

  it('🔴 «Угадай код» вместо подсказки получил ОРГАНЫ: цифры цветов и «Готово»', () => {
    // Тянуть пальцем ему больше не нужно — поэтому в списке подсказки его нет.
    expect(имена.ТОЛЬКО_ПРОТЯЖКА.has('Guess')).toBe(false);
    expect(имена.ЦИФРОВЫЕ.has('Guess')).toBe(true);
    expect(имена.ВВОД.has('Guess')).toBe(true);
    // ⚠️ Цифра там — ЦВЕТ, и число цветов стоит в `c<N>`, а не первым числом.
    expect(имена.клавишДоски('Guess', 'c6p4g10Bm')).toBe(6);
    expect(имена.клавишДоски('Guess', 'c8p5g12Bm')).toBe(8);
  });

  it('🔴 у всех четверых стрелки или второе действие тоже на месте', () => {
    const плохо: string[] = [];
    for (const имя of имена.ТОЛЬКО_ПРОТЯЖКА) {
      if (!имена.СТРЕЛОЧНЫЕ.has(имя) && !имена.ВТОРОЕ_ДЕЙСТВИЕ.has(имя)) плохо.push(имя);
    }
    expect(плохо).toEqual([]);
  });
});
