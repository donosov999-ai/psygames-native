/**
 * 🔴 СЕМЬЯ СОРТИРОВОК ДЕЛИТ ФОРМУ, А НЕ КОД. И это вывод замера, а не вкус.
 *
 * Пункт «общее ядро семьи» разбирался всерьёз: свести «Сортировку товаров»,
 * «Торты» и «Переливалку» на один `board.ts`. Замер отверг:
 *
 *   · у ядер сортировки и тортов ШЕСТЬ общих имён функций (`makeBoard`,
 *     `canPlace`, `moveTop`, `isCleared`, `isEmpty`, `roomIn`) и НОЛЬ
 *     совпадающих тел. Каждое отличается, потому что отличается сама ячейка:
 *     у товаров ниша со своей ёмкостью и правилом укладки, у тортов тарелка
 *     ровно на шесть плюс очередь входящих;
 *   · у решателей общих строк 22 из 68 и 160 — это каркас A* по корзинам.
 *     Вынести его в общий поиск значит сэкономить около пятнадцати строк на
 *     каждого и добавить пять колбэков и параметр типа.
 *
 * Общее ядро было бы объединением условий, а не общим кодом: `canPlace` пришлось
 * бы учить строгой укладке, поштучным ёмкостям, джокерам и фиксированному кругу
 * разом. Это дороже, чем два коротких честных ядра.
 *
 * 🔴 ЧТО ПЕРЕНОСИТСЯ, РАЗ КОД НЕ ПЕРЕНОСИТСЯ: ФОРМА МОДУЛЯ. Она уже повторена
 * в обоих намеренно, и вот эта проба следит, чтобы не разъехалась. Форма стоила
 * дорого: каждый её пункт — вывод из чужой поломки.
 */
import * as товары from '@/src/games/goods-sort/core/board';
import * as торты from '@/src/games/cake-sort/core/plate';
import * as решательТовары from '@/src/games/goods-sort/core/solver';
import * as решательТорты from '@/src/games/cake-sort/core/solver';

const ЯДРА: Record<string, Record<string, unknown>> = { 'goods-sort': товары, 'cake-sort': торты };

describe('форма ядер семьи сортировок', () => {
  it('есть что проверять — ядер несколько', () => {
    expect(Object.keys(ЯДРА).length).toBeGreaterThanOrEqual(2);
  });

  /**
   * 🔴 ОДНА ПРАВДА О РАЗМЕЩЕНИИ. `canPlace` — единственное место, где живёт
   * ответ «можно ли положить». Сортировка товаров платила за две копии этой
   * формулы: экран разрешал ход, которого раздача не предполагала.
   */
  it('🔴 у каждого ядра есть одна правда о размещении и о ходе', () => {
    const нет: string[] = [];
    for (const [имя, м] of Object.entries(ЯДРА)) {
      for (const ф of ['makeBoard', 'canPlace', 'moveTop', 'isCleared', 'roomIn']) {
        if (typeof м[ф] !== 'function') нет.push(`${имя}: нет ${ф}`);
      }
    }
    expect(нет).toEqual([]);
  });

  /**
   * 🔴 СБОРКА ДОСКИ ПАДАЕТ ГРОМКО, А НЕ ПОРТИТ ТИХО. Боевой краш 30.08.2026:
   * «доска собрана неверно: ниш 9, ёмкостей 7» — и это ХОРОШИЙ исход, потому что
   * его видно. Молчаливая доска с рассинхроном ёмкостей играется до первого
   * необъяснимого отказа.
   */
  it('🔴 makeBoard бракует несогласованную доску, а не собирает её молча', () => {
    expect(() => товары.makeBoard([[1], [2]], [3])).toThrow();
    expect(() => торты.makeBoard([[1, 1, 1, 1, 1, 1, 1]])).toThrow();
  });

  /**
   * 🔴 «БЮДЖЕТ КОНЧИЛСЯ» ≠ «НЕРЕШАЕМО». Урок стоил сортировке товаров до восьми
   * пересборок по ~90 мс и полсекунды подвисания на старте уровня. Оба решателя
   * обязаны отличать «не знаю» от «нет» — иначе хорошая доска бракуется.
   */
  it('🔴 оба решателя отличают исчерпание бюджета от доказанной нерешаемости', () => {
    /**
     * ⚠️ Проверяется ОТВЕТ решателя, а не имя функции: у товаров предикат
     * «доказанно нерешаемо» живёт в экране, у тортов — в ядре, и требовать
     * одинакового расположения значило бы навязывать форму ради формы. Общее
     * здесь одно и важное: результат несёт `exhausted` отдельным флагом.
     */
    // Доска побольше: на маленькой один узел успевает найти решение, и разницы не видно.
    const т = решательТовары.solveStrict(товары.makeBoard([[1, 2, 3], [3, 2, 1], [2, 3, 1], []], [3, 3, 3, 3]), 1);
    expect(typeof т.exhausted).toBe('boolean');
    expect(typeof т.solvable).toBe('boolean');
    const к = решательТорты.solve(торты.makeBoard([[1, 1], [1, 1], [1, 1], []]), 1);
    expect(typeof к.exhausted).toBe('boolean');
    expect(typeof к.solvable).toBe('boolean');
    /**
     * 🔴 И ГЛАВНОЕ ИСПОЛНЕНИЕМ: при бюджете в один узел решение НЕ найдено, но
     * нерешаемость и НЕ доказана. Смешать эти два ответа — значит браковать
     * хорошие доски; сортировка товаров платила за это до восьми пересборок.
     */
    expect(к.solvable).toBe(false);
    expect(к.exhausted).toBe(true);
    expect(решательТорты.provenUnsolvable(торты.makeBoard([[1, 1], [1, 1], [1, 1], []]), 1)).toBe(false);
    expect(т.solvable).toBe(false);
    expect(т.exhausted).toBe(true);
  });

  /**
   * ⚠️ И ФОРМА НЕ ЗНАЧИТ ОДИНАКОВОСТЬ. Проверяем ЯВНО, что тела разошлись:
   * если однажды они совпадут, значит игры сошлись, и тогда объединение ядер
   * перестанет быть невыгодным — эту пробу надо будет переписать, а не обойти.
   */
  it('ядра остаются разными: круг у тортов не равен тройке у товаров', () => {
    expect(торты.CIRCLE).toBe(6);
    expect(товары.TRIPLE).toBe(3);
    expect(торты.CIRCLE).not.toBe(товары.TRIPLE);
  });
});
