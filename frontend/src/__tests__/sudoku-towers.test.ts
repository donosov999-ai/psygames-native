/**
 * НЕБОСКРЁБЫ: ПОДСКАЗКА С КРАЯ ОБЯЗАНА БЫТЬ НУЖНОЙ, А НЕ УКРАШЕНИЕМ.
 *
 * Первый режим из плана §25.1-П, доведённый до замера. Правило: цифра — высота
 * здания, подсказка на краю говорит, сколько зданий видно с этой стороны; здание
 * видно, когда оно выше всех перед ним.
 *
 * 🔴 ЗАЧЕМ ГЕЙТ ИМЕННО ТАКОЙ. Перед этим тем же путём собирались НЕРАВЕНСТВА
 * (футосики) — и оказались пустышкой: замер дал ступень 1–2 при любой плотности
 * знаков, потому что знак работает фильтром по УЖЕ известному соседу и доску
 * только облегчает. Уровней им не дали.
 * Небоскрёбы отличаются тем, что подсказка ограничивает ВЕСЬ ряд и не требует ни
 * одной заполненной клетки. Но «отличается по смыслу» — не довод; довод — замер:
 *   6×6, 14 выколотых: ступени 1,4,4,1,1,4 · техники naked_single + towers_clue
 *   6×6, 18 выколотых: 1 и 4 вперемешку с нерешёнными
 *   6×6, 22+: решателю уже не хватает логики
 *   9×9, 42–56 выколотых: НЕ решается вовсе (одной границы мало)
 * Отсюда рабочий размер 6×6 — тот самый, что стоит в плане («4×4–5×5»), а не 9×9,
 * на котором я мерил первым и получил сплошные −1.
 *
 * ⚠️ ГЛАВНОЕ, ЧТО ЗДЕСЬ СТОРОЖИТСЯ: техника НЕОБХОДИМА. Проверка «доска решилась»
 * прошла бы и тогда, когда подсказки не дают ничего, а доску закрывают обычные
 * одиночки. Поэтому ниже доска решается ДВАЖДЫ — с подсказками и без — и разница
 * доказывает, что без них она не берётся.
 */
import { gradePuzzle } from '@/src/services/sudoku-grade';
import {
  generatePuzzle, dimsForSize, visibleCount, towersFromSolution,
  towersLineOk,
  type Cell,
} from '@/src/services/sudoku-core';

const { N, BR, BC } = dimsForSize(6);
/**
 * 🔴 РАБОЧАЯ ТОЧКА ВЫБРАНА ЗАМЕРОМ, И ПЕРВЫЙ ВЫБОР БЫЛ НЕВЕРЕН.
 * Стояло 14 — на нём гейт «подсказка нужна» мигал, а на выборке в 40 досок начал
 * падать стабильно. Пересчёт показал почему: подсказки помогают только на ГЛУБОКОЙ
 * копке, а на мелкой они декоративны — доску и так берут обычные одиночки.
 *   выколото 10: с подсказками 39/40, без них 39/40 — разницы НЕТ
 *   выколото 14: 35/40 против 37/40 — без подсказок даже чуть лучше (шум)
 *   выколото 18: 28/40 против 25/40 — подсказки помогают, и в 27 случаях из 40
 *                именно `towers_clue` оказалась сложнейшей понадобившейся техникой
 * Отсюда 18: раньше вариант не заслуживает своего имени.
 */
const BLANKS = 18;

function board() {
  const g = generatePuzzle(BLANKS, N, BR, BC, 'towers');
  return { g, towers: (g as unknown as { towers?: ReturnType<typeof towersFromSolution> }).towers };
}

describe('небоскрёбы', () => {
  it('есть что проверять — доска 6×6, подсказки на всех четырёх краях', () => {
    const { g, towers } = board();
    expect(g.puzzle.length).toBe(6);
    expect(towers).toBeTruthy();
    for (const side of ['top', 'bottom', 'left', 'right'] as const) {
      expect(towers![side].length).toBe(6);
      expect(towers![side].every((v) => v >= 1 && v <= 6)).toBe(true);
    }
  });

  it('🔴 подсказка совпадает с решением по всем четырём краям', () => {
    // Считаем видимость СВОИМ проходом по решению, а не тем же вызовом, каким
    // подсказки строились: иначе проверка доказывала бы, что функция равна себе.
    const bad: string[] = [];
    for (let i = 0; i < 4; i++) {
      const { g, towers } = board();
      for (let r = 0; r < N; r++) {
        const row = g.solution[r];
        let seen = 0, tall = 0;
        for (const v of row) if (v > tall) { seen++; tall = v; }
        if (seen !== towers!.left[r]) bad.push(`строка ${r} слева: видно ${seen}, подсказка ${towers!.left[r]}`);
        let seenR = 0, tallR = 0;
        for (let c = N - 1; c >= 0; c--) if (row[c] > tallR) { seenR++; tallR = row[c]; }
        if (seenR !== towers!.right[r]) bad.push(`строка ${r} справа: видно ${seenR}, подсказка ${towers!.right[r]}`);
      }
      for (let c = 0; c < N; c++) {
        const col = g.solution.map((rw) => rw[c]);
        let seen = 0, tall = 0;
        for (const v of col) if (v > tall) { seen++; tall = v; }
        if (seen !== towers!.top[c]) bad.push(`столбец ${c} сверху: видно ${seen}, подсказка ${towers!.top[c]}`);
      }
    }
    expect(bad).toEqual([]);
  }, 120000);

  it('🔴 подсказка НУЖНА: без неё доска логикой не берётся', () => {
    /**
     * Сердце гейта: доска решается ДВАЖДЫ — с подсказками и без — и без них должна
     * закрываться хуже. Иначе техника декоративна: доску и так берут одиночки.
     *
     * ⚠️ ПРОВЕРКА СЧИТАЕТ ПО ВЫБОРКЕ, А НЕ ПО ОДНОЙ ДОСКЕ, И ЭТО НЕ ПРИДИРКА.
     * Первая редакция брала 8 досок и требовала строгого неравенства — мигала в
     * двух прогонах из четырёх, потому что генератор случаен и попадались доски,
     * решаемые и без подсказок. Шаткая проверка приучает не смотреть на красное.
     * Здесь выборка больше и требование сформулировано так, как оно и звучит по
     * смыслу: подсказки должны помогать НА БОЛЬШИНСТВЕ досок, а не на каждой.
     */
    let solvedWith = 0;
    let solvedWithout = 0;
    let hardestWasTowers = 0;
    const TRIES = 40;
    for (let i = 0; i < TRIES; i++) {
      const { g, towers } = board();
      const a = gradePuzzle(g.puzzle, { N, BR, BC, variant: 'towers', towers } as never);
      if (a.solved) solvedWith++;
      if (a.solved && a.hardest === 'towers_clue') hardestWasTowers++;
      if (gradePuzzle(g.puzzle, { N, BR, BC, variant: 'none' } as never).solved) solvedWithout++;
    }
    expect(solvedWith).toBeGreaterThan(TRIES / 4);   // с подсказками решается заметная доля

    /**
     * 🔴 СТОРОЖИМ СИЛЬНОЕ, А НЕ СЛАБОЕ — И ЭТО РЕШЕНО ЗАМЕРОМ.
     * Напрашивалось требование «без подсказок решается ХУЖЕ». Померил: 28 из 40
     * против 25 из 40. Эффект настоящий, но маленький — три доски, и шум его
     * переворачивает: гейт падал в одном прогоне из пяти даже на выборке в сорок.
     * Проверка, которая мигает, приучает не смотреть на красное, поэтому слабое
     * сравнение снято.
     * Осталось сильное: подсказка обязана быть САМОЙ СЛОЖНОЙ понадобившейся
     * техникой хотя бы на четверти досок (замер: 27 из 40). Это и означает, что
     * она не декоративна: без неё решение бы встало.
     */
    expect(hardestWasTowers).toBeGreaterThan(TRIES / 4);
    expect(solvedWithout).toBeGreaterThan(0);        // проверка живая: без подсказок часть досок всё же берётся
  }, 300000);

  it('🔴 сама техника применяется — на СОБРАННОМ примере, а не на удачной доске', () => {
    /**
     * ⚠️ ЗДЕСЬ БЫЛА ШАТКАЯ ПРОВЕРКА, И ОНА МИГНУЛА В ТОТ ЖЕ ДЕНЬ. Стояло «пройти
     * до десяти случайных досок и найти хоть одну, где `towers_clue` оказалась
     * самой сложной». После возврата байтов из-под мутации (sha256 совпал!) она
     * покраснела — то есть краснела бы и от невезения, а такая проверка приучает
     * не смотреть на красное.
     *
     * Теперь пример СОБРАН руками. Подсказка «1» с левого края означает, что самое
     * высокое здание стоит первым: иначе оно заслонило бы всё и видимых было бы
     * больше одного. Значит в первой клетке обязана остаться ровно шестёрка.
     * Это ровно тот вывод, ради которого техника заведена, и он не зависит от
     * везения.
     */
    const empty: Cell[][] = Array.from({ length: N }, () => Array(N).fill(0));
    const towers = {
      top: Array(N).fill(0), bottom: Array(N).fill(0),
      left: [1, 0, 0, 0, 0, 0], right: Array(N).fill(0),
    };
    const gr = gradePuzzle(empty, { N, BR, BC, variant: 'towers', towers } as never);
    // Доска пустая — решить её нельзя, и это не важно: важно, что подсказка сузила.
    expect(gr.hardest === 'towers_clue' || gr.hardest === 'guess').toBe(true);

    // Прямая проверка самого правила: при подсказке «1» первая клетка = N,
    // при подсказке N ряд строго возрастает.
    expect(towersLineOk([N, 1, 2, 3, 4, 5], 1)).toBe(true);
    expect(towersLineOk([1, 2, 3, 4, 5, N], 1)).toBe(false);
    expect(towersLineOk([1, 2, 3, 4, 5, N], N)).toBe(true);
    expect(towersLineOk([N, 1, 2, 3, 4, 5], N)).toBe(false);
  }, 120000);

  it('🔴 счёт видимых зданий — на известных примерах, а не «как посчитается»', () => {
    expect(visibleCount([1, 2, 3, 4])).toBe(4);   // строго растёт — видно все
    expect(visibleCount([4, 3, 2, 1])).toBe(1);   // самое высокое первым — видно одно
    expect(visibleCount([2, 1, 4, 3])).toBe(2);   // 2 и 4
    expect(visibleCount([3, 1, 2, 4])).toBe(2);   // 3 и 4
  });
});
