/**
 * СЕМЬ ЧИСЛОВЫХ СЕТОК РАЗВИЛКИ «СУДОКУ»: ЛЕСТНИЦА ИДЁТ ВВЕРХ И НЕ МЕНЯЕТ ПРАВИЛО.
 *
 * 🔴 ЗАЧЕМ. Уровень отображается в ступень один в один (`app/games/puzzles.tsx:96`,
 * `ступень = level - 1`), поэтому порядок строк лестницы И ЕСТЬ порядок сложности
 * для человека. Замер 16.09.2026 по авторским пресетам показал две беды:
 *   · 11 ступеней из 38 в трёх играх молча дают ДРУГУЮ игру — Solo 6 из 16
 *     (диагонали, клетки-суммы, кривые блоки), Unequal 3 (смежность вместо
 *     неравенств), Keen 2 (только умножение);
 *   · провалы сложности, где поле выросло, а класс рухнул: Singles 4, Solo 3,
 *     Unequal 2, Undead 2, Towers 1, Keen 1.
 *
 * ⚠️ ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕЛАЕТ. Он не генерирует доски: модуль Тэтхэма под jest
 * стартует, но `psy_generate` возвращает ноль (записано в шапке
 * `scripts/tatham-bridge-gate.mjs`, причина не найдена). Что КАЖДАЯ строка
 * открывается, проверено отдельным прогоном в чистом node и записано числами в
 * шапке `СВОЯ_ЛЕСТНИЦА`. Здесь сторожится ФОРМА лестницы — то, что ломается
 * правкой таблицы, а не движком.
 */
import { СВОЯ_ЛЕСТНИЦА, ИМЯ_ВТОРОГО, ВТОРОЕ_ДЕЙСТВИЕ, КЛЮЧ_ОПИСАНИЯ } from '@/src/games/tatham-bridge/names';

declare const __dirname: string;
declare function require(id: string): any;

/** Семь движков развилки «Судоку и числовые сетки» (переехали 13.09.2026). */
const МОИ = ['Solo', 'Towers', 'Unequal', 'Keen', 'Singles', 'Filling', 'Undead'] as const;

/** Ступеней в лестнице — столько же, сколько у Mines/Loopy/Sokoban. */
const СТУПЕНЕЙ = 5;

/**
 * Признак ЧУЖОГО ПРАВИЛА в хвосте параметров (размер отрезан).
 * Буквы — из исходников Тэтхэма: у Solo `x` диагонали, `j` кривые блоки,
 * `k` клетки-суммы; у Unequal `a` смежность; у Keen `m` только умножение.
 */
const ЧУЖОЕ_ПРАВИЛО: Record<string, RegExp> = {
  Solo: /[xjk]/,
  Unequal: /a/,
  Keen: /m/,
};

const сторона = (п: string): number => {
  const m = /^(\d+)(?:\s*[x×]\s*(\d+))?/i.exec(п);
  return m ? Math.max(Number(m[1]), Number(m[2] ?? m[1])) : 0;
};
/** Ранг класса по букве — внутри ОДНОГО движка она значит одно и то же. */
const РАНГ: Record<string, number> = { b: 2, e: 2, t: 5, n: 3, i: 4, k: 5, h: 6, a: 7, x: 8, u: 9 };
const класс = (имя: string, п: string): number => {
  const хвост = п.replace(/^\d+(\s*[x×]\s*\d+)?/, '');
  const m = /d([a-z])/i.exec(хвост);
  if (!m) return 0;
  // ⚠️ У Solo буква значит своё: de = Extreme, du = Unreasonable, db = Basic.
  const собств: Record<string, number> = { b: 2, i: 4, a: 7, e: 8, u: 9 };
  return имя === 'Solo' ? (собств[m[1]!] ?? 0) : (РАНГ[m[1]!] ?? 0);
};

describe('лестницы семи числовых сеток', () => {
  it('🔴 у каждой из семи есть своя лестница ровно из пяти ступеней', () => {
    const плохо = МОИ.filter((m) => (СВОЯ_ЛЕСТНИЦА[m]?.length ?? 0) !== СТУПЕНЕЙ)
      .map((m) => `${m}:${СВОЯ_ЛЕСТНИЦА[m]?.length ?? 0}`);
    expect(`не по ${СТУПЕНЕЙ}: ${плохо.join(' ') || 'нет'}`).toBe(`не по ${СТУПЕНЕЙ}: нет`);
  });

  it('🔴 лестница НЕ МЕНЯЕТ ПРАВИЛО — того, что было у автора, здесь быть не должно', () => {
    const чужие: string[] = [];
    for (const [имя, re] of Object.entries(ЧУЖОЕ_ПРАВИЛО)) {
      for (const шаг of СВОЯ_ЛЕСТНИЦА[имя] ?? []) {
        const хвост = шаг.параметры.replace(/^\d+(\s*[x×]\s*\d+)?/, '');
        if (re.test(хвост)) чужие.push(`${имя}/${шаг.параметры}`);
      }
    }
    expect(`чужое правило: ${чужие.join(' ') || 'нет'}`).toBe('чужое правило: нет');
  });

  it('🔴 лестница идёт вверх: поле не убывает, класс внутри поля не убывает', () => {
    const провалы: string[] = [];
    for (const имя of МОИ) {
      const ряд = СВОЯ_ЛЕСТНИЦА[имя] ?? [];
      for (let i = 1; i < ряд.length; i++) {
        const a = ряд[i - 1]!; const b = ряд[i]!;
        const са = сторона(a.параметры); const сб = сторона(b.параметры);
        if (сб < са) { провалы.push(`${имя} ${a.параметры}→${b.параметры}: поле ${са}→${сб}`); continue; }
        if (сб === са && класс(имя, b.параметры) < класс(имя, a.параметры)) {
          провалы.push(`${имя} ${a.параметры}→${b.параметры}: класс ${класс(имя, a.параметры)}→${класс(имя, b.параметры)}`);
        }
      }
    }
    expect(`провалов ${провалы.length}: ${провалы.slice(0, 4).join(' · ') || 'нет'}`).toBe('провалов 0: нет');
  });

  it('🔴 верхняя ступень действительно труднее нижней, а не равна ей', () => {
    const плоские = МОИ.filter((имя) => {
      const ряд = СВОЯ_ЛЕСТНИЦА[имя] ?? [];
      const н = ряд[0]!; const в = ряд[ряд.length - 1]!;
      return сторона(в.параметры) === сторона(н.параметры)
        && класс(имя, в.параметры) === класс(имя, н.параметры);
    });
    expect(`плоских лестниц: ${плоские.join(' ') || 'нет'}`).toBe('плоских лестниц: нет');
  });

  /**
   * 🔴 ОПИСАНИЕ ОТВЕЧАЕТ «КУДА НАЖИМАТЬ», А НЕ ОПИСЫВАЕТ ЦЕЛЬ.
   *
   * ПОВОД — отчёты NZT-48 от 14.09.2026 на 2.54.11: четыре штуки за полторы минуты,
   * все с экрана /games/puzzles — «Как играть? Где справка?», «Где цифры или там
   * должно быть?». Замер 16.09: все семь описаний рассказывали ЦЕЛЬ и ни одно —
   * порядок хода.
   */
  it('🔴 описание каждой из семи говорит, куда нажимать', () => {
    const fs = require('fs'); const path = require('path');
    const словарь = fs.readFileSync(path.join(__dirname, '../contexts/LanguageContext.tsx'), 'utf8') as string;
    const ru = (ключ: string): string => {
      const m = словарь.match(new RegExp(`^  ${ключ}: \\{ ru: '((?:[^'\\\\]|\\\\.)*)'`, 'm'));
      return m ? m[1]! : '';
    };
    const немые = МОИ.filter((имя) => !/ажми/.test(ru(КЛЮЧ_ОПИСАНИЯ[имя] ?? '')));
    expect(`без указания действия: ${немые.join(' ') || 'нет'}`).toBe('без указания действия: нет');
  });

  /**
   * ⚠️ РЕГРЕССИЯ, КОТОРУЮ Я САМ И СОЗДАЛ. Описание «Судоку Тэтхэма» обещало
   * «авторскую лестницу из шестнадцати ступеней». После правки 16.09 лестница наша и
   * в ней ПЯТЬ ступеней — текст стал враньём во всех одиннадцати языках. Проба
   * сторожит, чтобы обещание числа ступеней не вернулось в описание.
   */
  it('🔴 описание не обещает чужую лестницу из шестнадцати ступеней', () => {
    const fs = require('fs'); const path = require('path');
    const файлы = ['../contexts/LanguageContext.tsx',
      ...['de','es','pt','fr','it','zh','ja','ko','hi','ar'].map((l) => `../contexts/translations/${l}.ts`)];
    const виноватые = файлы.filter((ф) => {
      const т = fs.readFileSync(path.join(__dirname, ф), 'utf8') as string;
      const m = т.match(/puzzlesSoloDesc["']?:\s*["'{][^\n]*/);
      return m ? /16|шестнадц|sixteen|sech|dieci|seize|dezasseis|dieciséis|十六/i.test(m[0]) : false;
    });
    expect(`обещают 16 ступеней: ${виноватые.length}`).toBe('обещают 16 ступеней: 0');
  });

  it('🔴 у каждого моего режима со вторым действием есть своё имя для него', () => {
    const без = МОИ.filter((имя) => ВТОРОЕ_ДЕЙСТВИЕ.has(имя) && !ИМЯ_ВТОРОГО[имя]);
    expect(`без имени: ${без.join(' ') || 'нет'}`).toBe('без имени: нет');
    // И наоборот: имя без самого действия — тоже ошибка.
    const лишние = Object.keys(ИМЯ_ВТОРОГО).filter((имя) => !ВТОРОЕ_ДЕЙСТВИЕ.has(имя));
    expect(`имя без действия: ${лишние.join(' ') || 'нет'}`).toBe('имя без действия: нет');
  });

  it('🔴 имена второго действия переведены во всех локалях', () => {
    const fs = require('fs'); const path = require('path');
    const ключи = [...new Set(Object.values(ИМЯ_ВТОРОГО))];
    const дыры: string[] = [];
    for (const л of ['de','es','pt','fr','it','zh','ja','ko','hi','ar']) {
      const т = fs.readFileSync(path.join(__dirname, `../contexts/translations/${л}.ts`), 'utf8') as string;
      for (const к of ключи) if (!т.includes(`"${к}"`)) дыры.push(`${л}/${к}`);
    }
    expect(`не переведено: ${дыры.join(' ') || 'нет'}`).toBe('не переведено: нет');
  });

  it('есть что мерить — иначе проба зелена вслепую', () => {
    expect(`режимов ${МОИ.length}, строк всего ${МОИ.reduce((s, m) => s + (СВОЯ_ЛЕСТНИЦА[m]?.length ?? 0), 0)}`)
      .toBe('режимов 7, строк всего 35');
  });
});
