/**
 * СНИМОК ВСЕХ ТАБЛИЦ РЕЖИМОВ — ЧТОБЫ РАСКЛАДКА ПО ВЛАДЕЛЬЦАМ НИЧЕГО НЕ ПОТЕРЯЛА.
 *
 * 🔴 ПОВОД, Денис 16.09.2026: «своя лестница заводится в puzzles.tsx — так разнеси
 * её на хабы, чтобы была доступна каждому своя; какого чёрта они один файл мусолят?»
 * И он прав: в `names.ts` четырнадцать таблиц, ключ у всех — имя режима, а режимы
 * принадлежат ШЕСТИ разным чатам. Значит любая правка любого из шести шла через один
 * файл — и через меня.
 *
 * Раскладка такого размера опасна ровно одним: молча потерять строку. Поэтому
 * СНАЧАЛА снимается отпечаток всех таблиц КАК ЕСТЬ, и он же становится приёмкой:
 * после раскладки собранные таблицы обязаны совпасть с ним до строчки.
 *
 * Файл отпечатка `tatham-tables.generated.json` заводится этой же пробой при первом
 * прогоне (так же устроен `pet-silhouette.generated.json`). Обновлять его руками
 * можно ТОЛЬКО вместе с осознанной правкой состава — и тогда объяснять в коммите,
 * что именно изменилось и почему.
 */
import {
  ПО_УМОЛЧАНИЮ, КЛЮЧ_ИМЕНИ, КЛЮЧ_ОПИСАНИЯ, СТРЕЛОЧНЫЕ, ВТОРОЕ_ДЕЙСТВИЕ, ЦИФРОВЫЕ,
  ИМЯ_ВТОРОГО, ВВОД, ПЛАН_ШАГАМИ, ВЫБОР, ВЫБОР_ВТОРОЙ, ВОСЕМЬ_НАПРАВЛЕНИЙ,
  ТОЛЬКО_ПРОТЯЖКА, СВОЯ_ЛЕСТНИЦА, РЕЖИМЫ,
} from '@/src/games/tatham-bridge/names';

declare const __dirname: string;
const { readFileSync, writeFileSync, existsSync } = require('fs');   // eslint-disable-line @typescript-eslint/no-require-imports
const { join } = require('path');                                    // eslint-disable-line @typescript-eslint/no-require-imports

const ФАЙЛ = join(__dirname, 'tatham-tables.generated.json');
const список = (м: Set<string>) => [...м].sort();

const снимок = () => ({
  поУмолчанию: ПО_УМОЛЧАНИЮ,
  режимы: [...РЕЖИМЫ].sort(),
  ключИмени: КЛЮЧ_ИМЕНИ,
  ключОписания: КЛЮЧ_ОПИСАНИЯ,
  имяВторого: ИМЯ_ВТОРОГО,
  стрелочные: список(СТРЕЛОЧНЫЕ),
  второеДействие: список(ВТОРОЕ_ДЕЙСТВИЕ),
  цифровые: список(ЦИФРОВЫЕ),
  ввод: список(ВВОД),
  планШагами: список(ПЛАН_ШАГАМИ),
  выбор: список(ВЫБОР),
  выборВторой: список(ВЫБОР_ВТОРОЙ),
  восемьНаправлений: список(ВОСЕМЬ_НАПРАВЛЕНИЙ),
  толькоПротяжка: список(ТОЛЬКО_ПРОТЯЖКА),
  свояЛестница: СВОЯ_ЛЕСТНИЦА,
});

describe('таблицы режимов Тэтхэма', () => {
  it('есть что мерить — сорок два режима на месте', () => {
    expect(РЕЖИМЫ.length).toBe(42);
  });

  it('🔴 состав таблиц совпадает с отпечатком', () => {
    const сейчас = снимок();
    if (!existsSync(ФАЙЛ)) {
      writeFileSync(ФАЙЛ, `${JSON.stringify(сейчас, null, 2)}\n`, 'utf8');
      console.log(`[tatham-tables] отпечаток заведён: ${ФАЙЛ}`);
      return;
    }
    expect(сейчас).toEqual(JSON.parse(readFileSync(ФАЙЛ, 'utf8')));
  });
});
