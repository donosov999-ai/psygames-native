/**
 * ЗАВЕДЁННЫЙ ПРОФИЛЬ ОБЯЗАН БЫТЬ ВИДЕН.
 *
 * 🔴 ЧТО БЫЛО. Профиль «Новинки» завели полностью: название, описание на двух
 * языках, состав, который сам считается по датам, запись в каталоге. И он не
 * показывался НИКОМУ: свитчер прятал его фильтром `tier !== 'owner'`, а `owner`
 * ему поставили, желая сказать «не продаётся». Слово значило другое.
 *
 * 🔴 21.10.2026, решение Дениса (d5e5814a): монетизации нет. Ярусов, цен и списка
 * скрытых больше нет — в выборе все профили, на всех платформах. Здесь проверяется,
 * что так и осталось: ни у одного профиля нет полей продажи, и у каждого есть подписи.
 */
import { PROFILES, PROFILE_BY_ID } from '@/src/constants/profiles';
import { translateFor } from '@/src/contexts/LanguageContext';

/** Поля, которыми профиль продавался. Вернулось любое — вернулась монетизация. */
const SALE_FIELDS = ['tier', 'price', 'price_year', 'price_year_old', 'sales_hook', 'sales_hook_en', 'sales_hook_source', 'sales_hook_source_en'];

describe('видимость профилей в выборе', () => {
  it('есть что проверять — иначе тест зелен вслепую', () => {
    expect(PROFILES.length).toBeGreaterThan(8);
  });

  it('🔴 ни у одного профиля нет яруса, цены и продающих строк', () => {
    const sold = PROFILES.flatMap((p) => SALE_FIELDS.filter((f) => f in p).map((f) => `${p.id}: ${f}`));
    expect(sold).toEqual([]);
  });

  /** Та самая витрина, ради которой всё и чинилось. */
  it('🔴 «Новинки» и полный доступ — среди профилей выбора', () => {
    expect(`whatsnew: ${!!PROFILE_BY_ID['whatsnew' as never]}`).toBe('whatsnew: true');
    expect(`odv999: ${!!PROFILE_BY_ID['odv999' as never]}`).toBe('odv999: true');
  });

  /**
   * 🔴 У ВИДИМОГО ПРОФИЛЯ ОБЯЗАНЫ БЫТЬ ПОДПИСИ. Свитчер зовёт их как
   * `t('profileName_' + id)`, и отсутствующий ключ человек видит на карточке
   * сырым: «profileName_whatsnew». Ровно это и случилось, когда витрину
   * показали, — ключи никто не заводил, потому что раньше её никто не
   * запрашивал. Проверка нужна именно здесь: гейт словаря ловит битые вызовы
   * по коду, а этот вызов собирается из строки на лету и в код не попадает.
   */
  it('🔴 у каждого профиля есть название и описание в словаре (ru и en)', () => {
    const missing: string[] = [];
    for (const p of PROFILES) {
      for (const lang of ['ru', 'en']) {
        for (const key of [`profileName_${p.id}`, `profileDesc_${p.id}`]) {
          // Спрашиваем ровно то, что увидит человек: перевод, а не наличие ключа
          // в каком-то объекте. Вернулся сам ключ — значит на карточке будет он.
          const shown = translateFor(lang as never, key);
          if (!shown || shown === key) missing.push(`${p.id}/${lang}: ${key} не переведён — человек увидит имя ключа`);
        }
      }
    }
    expect(missing).toEqual([]);
  });
});
