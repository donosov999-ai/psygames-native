/**
 * 🔴 НИ ОДНА ЦИФРА НЕ ЛЮБИМАЯ.
 *
 * 📍 ОТЧЁТ ВАЛИ 05.09.2026, дословно: «почему в блоках, которые не являются
 * квадратными, то есть начиная с 54-го уровня, самая часто встречающаяся цифра
 * — семёрка? Семёрку всегда проще всего закрыть, после идёт единица. Шестёрка —
 * вечный изгой».
 *
 * Утверждение проверяемое, и проверить его надо было ДО ответа. Замер по
 * 100 доскам (25 на уровень, 54–57 — вариант `jigsaw`, неквадратные блоки):
 *
 *   L54: 8=12,6% 1=11,9% 9=11,5% 2=11,3% 6=11,1% 4=10,9% 5=10,5% 3=10,3% 7=10,1%
 *   L55: 8=12,3% 5=11,9% 9=11,7% 2=11,3% 6=10,9% 7=10,9% 1=10,7% 3=10,1% 4=10,1%
 *   L56: 1=12,8% 6=12,8% 4=11,4% 5=11,0% 2=10,8% 9=10,8% 7=10,2% 8=10,2% 3=10,0%
 *   L57: 9=12,6% 7=11,9% 6=11,7% 3=11,3% 5=11,3% 2=10,9% 8=10,7% 1=10,1% 4=9,3%
 *
 * Перекоса нет: при ожидаемых 11,1 % размах 9,3–12,8 %, а «самая частая» цифра
 * на каждом уровне СВОЯ (8, 8, 1, 9) — это шум выборки, а не любимчик
 * генератора. Семёрка на L54 оказалась наоборот самой РЕДКОЙ. Шестёрка изгоем
 * тоже не выходит: 11,1 % · 10,9 % · 12,8 % · 11,7 %.
 *
 * Проба стоит, чтобы НАСТОЯЩИЙ перекос не проскочил молча.
 *
 * 🔴 ДОСКИ СОБИРАЮТСЯ ПО ЗЕРНУ, А НЕ ПО БРОСКУ (17.09.2026).
 *
 * 📍 Сборка метки v2.54.17 (прогон 35176164688) упала здесь: «L54: цифра 7 —
 * 6,9 % из 320». Перекоса при этом нет. Замер по генератору из main: 240 досок
 * на L54 и L56 — все цифры в пределах 1,1σ, семёрка на L54 10,9 %; ещё 240 досок
 * с бюджетом 400 и 1200 мс вместо 6000 (так генератор работает на медленной
 * машине) — в пределах 1,3σ, запасной путь у 8 досок из 240. Упала проба от
 * броска: бутстреп по тем же доскам даёт ложное падение в 0,45 % прогонов, а
 * прогонов у неё десятки в день.
 *
 * Поэтому каждая доска собирается на своём зерне (`makeRng`; `Math.random`
 * подменяется на время одной доски). При том же генераторе вердикт всегда один,
 * и сменить его может только правка кода. Зерно своё у КАЖДОЙ доски, а не одно на
 * цикл: иначе доска, пропущенная по бюджету, сдвинула бы поток всем следующим.
 *
 * ГРАНИЦЫ. У доски ~20 подсказок, на уровень 16 досок — около 320 (раньше здесь
 * было записано 500: столько давали 25 досок первого замера). Разброс доли цифры
 * по 16 доскам — 1,1 п.п., а не 1,8, как у независимых бросков: судоку разносит
 * цифры по доске. Значит 7 % — это 3,7σ ниже ожидаемых 11,1 %, а 15,5 % — 3,9σ
 * выше: шум за границу не выходит, а любимая или обойдённая цифра выходит.
 * Что граница кусается, проверено мутацией выкапывания в `digByLogic` (17.09.2026):
 * семёрку не выкапывать никогда — красная, семёрок 35,9 % и 35,5 %; пропускать
 * семёрку с вероятностью 0,35 — красная, 15,8 % и 15,7 %; выкапывать семёрки
 * первыми — красная, 0 % на обоих уровнях.
 */
import { levelConfig } from '@/src/services/sudoku-core';
import { generateLogical } from '@/src/services/sudoku-grade';
import { makeRng } from '@/src/services/seed';

jest.setTimeout(900_000);

/** Неквадратные блоки — те самые уровни, про которые был отчёт. */
const УРОВНИ = [54, 56];
const ДОСОК = 16;
const НИЖЕ = 0.07, ВЫШЕ = 0.155;

/**
 * ⚠️ БЮДЖЕТ С ЗАПАСОМ, А НЕ 6000 МС: ЗЕРНО ДЕРЖИТ ДОСКУ, ТОЛЬКО ПОКА ЕЁ НЕ ОБРЕЗАЛИ ЧАСЫ.
 * Генератор прерывает заходы по `Date.now()`, и обрезанная доска выходит другой,
 * хотя `budgetSpent` на логическом пути остаётся false. Замер: 4 доски из 240
 * упирались в 6000 мс даже на Mac, а CI медленнее почти вдвое. С запасом в минуту
 * доска зависит только от зерна.
 */
const БЮДЖЕТ_МС = 60_000;

/** Собрать доску на своём зерне: генератор берёт случайность только из `Math.random`. */
function поЗерну<T>(зерно: string, собрать: () => T): T {
  const подмена = jest.spyOn(Math, 'random').mockImplementation(makeRng(зерно));
  try { return собрать(); } finally { подмена.mockRestore(); }
}

describe('судоку: цифры раздаются поровну', () => {
  it('🔴 ни одна цифра не встречается в подсказках заметно чаще прочих', () => {
    const плохо: string[] = [];
    for (const level of УРОВНИ) {
      const cfg = levelConfig(level);
      expect(cfg.variant).toBe('jigsaw');          // ⚠️ иначе проба мерит не тот вариант
      const счёт = new Array(cfg.N + 1).fill(0);
      let всего = 0, досок = 0, пропущено = 0;
      for (let s = 0; s < ДОСОК; s++) {
        const r = поЗерну(`sudoku-digit-fairness:${level}:${s}`,
          () => generateLogical(level, cfg.blanks, cfg.N, cfg.BR, cfg.BC, cfg.variant, { budgetMs: БЮДЖЕТ_МС }));
        /**
         * 🔴 ДОСКА, СОБРАННАЯ НА ИСЧЕРПАННОМ БЮДЖЕТЕ, В ЗАМЕР НЕ ИДЁТ.
         *
         * 📍 Проба зеленела в одиночку и падала в полном прогоне: под нагрузкой
         * генератор упирался во время и отдавал доску другого устройства — а
         * доля цифр в ней меряет уже не генератор, а загрузку машины. Тот же
         * класс, что «исчерпание бюджета — не вердикт».
         */
        if (r.budgetSpent) { пропущено++; continue; }
        досок++;
        for (const row of r.gen.puzzle as unknown as number[][]) {
          for (const v of row) if (v > 0) { счёт[v]++; всего++; }
        }
      }
      // Выборка обязана быть настоящей: иначе это не «перекоса нет», а «нечего мерить».
      expect(`L${level}: досок ${досок}, пропущено ${пропущено}`).toBe(`L${level}: досок ${досок}, пропущено ${пропущено}`);
      expect(досок).toBeGreaterThanOrEqual(6);
      expect(всего).toBeGreaterThan(150);
      for (let v = 1; v <= cfg.N; v++) {
        const доля = счёт[v]! / всего;
        if (доля < НИЖЕ || доля > ВЫШЕ) {
          плохо.push(`L${level}: цифра ${v} — ${Math.round(доля * 1000) / 10}% из ${всего}`);
        }
      }
    }
    expect(плохо).toEqual([]);
  });
});
