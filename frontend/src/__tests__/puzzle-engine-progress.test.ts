/**
 * ХОД ПАРТИИ ИЗ ДВИЖКА ДОХОДИТ ДО ЧЕЛОВЕКА — И НАШИМИ СЛОВАМИ.
 *
 * 📍 Денис 10.09.2026 про головоломки: «в конце ничего не происходит, ни конца, ни
 * след. уровень, замер экран». Обратной связи по ходу партии не было: в шапке стояли
 * «уровень» и «ходы», а движок всё это время считал своё и писал в строку состояния,
 * которую мы выбрасывали.
 *
 * Здесь проверяется разбор: строки взяты ЖИВЫМИ из замера 10.09.2026 по всем сорока
 * (`psy_status_text` после хода), а не придуманы.
 */
import { ходПартии } from '@/src/games/tatham-bridge/status';

/** Замер 10.09.2026: что реально пишут движки. Слева — движок, справа — его строка. */
const ЖИВЫЕ: [string, string, string | null, string | null][] = [
  // движок        строка движка                     ключ подписи            значение
  ['Black Box',   'Balls marked: 0 / 5',            'puzzleHudMarked',      '0/5'],
  ['Mines',       '[0:00] Marked: 3 / 10',          'puzzleHudMarked',      '3/10'],
  ['Mosaic',      'Clues left: 44',                 'puzzleHudCluesLeft',   '44'],
  ['Net',         'Active: 6/25',                   'puzzleHudActive',      '6/25'],
  ['Netslide',    'Moves: 8 Active: 3/9',           'puzzleHudActive',      '3/9'],
  ['Inertia',     'Gems: 16',                       'puzzleHudGems',        '16'],
  ['Flood',       '19 / 22 moves',                  'puzzleHudMovesUsed',   '19/22'],
  // ⚠️ «Счёт» берёт ОБЩИЙ ключ `score`: он в словаре уже был, и гейт дублей прав —
  // одинаковый текст под двумя ключами расходится при первой же правке.
  ['Same Game',   'Score: 1',                       'score',                '1'],
  ['Palisade',    'Region size: 5',                 'puzzleHudRegion',      '5'],
  // 🔴 Одинокие ходы ПРОПУСКАЕМ сознательно: свой счётчик ходов в шапке уже есть,
  // и второй такой же рядом — не обратная связь, а шум.
  ['Cube',        'Moves: 23',                      null,                   null],
  ['Fifteen',     'Moves: 11',                      null,                   null],
  // ⚠️ Свободный текст движка не переводим и не показываем по-английски.
  ['Black Box',   '20 too many balls marked.',      null,                   null],
  ['Inertia',     'DEAD!   Deaths: 1',              null,                   null],
  ['Mines',       '[0:00] DEAD!  Deaths: 1',        null,                   null],
  ['молчит',      '',                               null,                   null],
];

describe('ход партии из движка', () => {
  it('🔴 живые строки всех четырнадцати разбираются так, как намерено', () => {
    const плохо: string[] = [];
    for (const [движок, строка, ключ, значение] of ЖИВЫЕ) {
      const r = ходПартии(строка);
      const вышло = r ? `${r.ключ}=${r.значение}` : 'null';
      const ждём = ключ ? `${ключ}=${значение}` : 'null';
      if (вышло !== ждём) плохо.push(`${движок} «${строка}» → ${вышло}, а ждали ${ждём}`);
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 у «Пятнашек со сдвигом» берётся ВТОРАЯ величина, а не первая', () => {
    // «Moves: 8 Active: 3/9» — ходы у нас свои, а вот сколько узлов уже на месте,
    // не знает никто, кроме движка. Ошибка здесь показала бы ходы дважды.
    expect(ходПартии('Moves: 8 Active: 3/9')).toEqual({ ключ: 'puzzleHudActive', значение: '3/9' });
  });

  /**
   * 🔴 ПРОВЕРЯЕТСЯ НАЛИЧИЕ ПЕРЕВОДА В ЯЗЫКЕ, А НЕ «ХОТЬ ЧТО-ТО ПОКАЗАЛОСЬ».
   *
   * ⚠️ Первая редакция звала `translateFor(язык, ключ)` и требовала, чтобы ответ не
   * совпал с ключом. Проба была ЗЕЛЁНОЙ и после того, как я вручную вырезал немецкий
   * перевод: цепочка фолбэков (`LanguageContext`: инлайн → overlay → EN → RU → key)
   * подставляет английское слово, и до «ключа наружу» дело не доходит НИКОГДА, пока
   * в инлайне есть `en`. Такая проба стережёт не перевод, а существование ключа.
   *
   * Поэтому смотрим прямо в словари языков: подпись обязана быть в каждом из десяти.
   */
  it('🔴 подпись переведена в каждом из двенадцати языков, а не подставлена английским', () => {
    const ключи = [...new Set(ЖИВЫЕ.map(([, , к]) => к).filter(Boolean) as string[])];
    expect(ключи.length).toBeGreaterThanOrEqual(7);

    const плохо: string[] = [];
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const { translateFor } = require('@/src/contexts/LanguageContext');
    for (const к of ключи) {
      for (const язык of ['ru', 'en']) {          // база живёт инлайном
        const текст = translateFor(язык, к);
        if (!текст || текст === к) плохо.push(`${к} @ ${язык} (инлайн)`);
      }
    }
    for (const язык of ['de', 'es', 'fr', 'it', 'pt', 'ar', 'hi', 'ja', 'ko', 'zh']) {
      // eslint-disable-next-line @typescript-eslint/no-require-imports
      const словарь = require(`@/src/contexts/translations/${язык}`).default as Record<string, string>;
      for (const к of ключи) {
        if (!словарь[к]) плохо.push(`${к} @ ${язык} (нет в словаре языка — покажется по-английски)`);
      }
    }
    expect(плохо).toEqual([]);
  });
});
