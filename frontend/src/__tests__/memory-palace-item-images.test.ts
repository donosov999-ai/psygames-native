/**
 * 🔴 У КАЖДОГО ПРЕДМЕТА БИБЛИОТЕКИ ЕСТЬ КАРТИНКА.
 *
 * ОТКУДА. Приём «дворец памяти» держится на ярком образе: лампу можно
 * представить большой, движущейся и звучащей на фонтане — ровно об этом просит
 * экран «Оживите ассоциации», — а «оранжевый ромб» представить нечем. До
 * 07.09.2026 предметы были цветными фигурами, и это была вторая половина
 * жалобы «нихуя не понятно по смыслу игры».
 *
 * 📍 Замер: 56 предметов нарисованы одним листом 7×8 (kie, 18 кредитов), фон
 * снят скиллом bg-cutout методом colorkey — 56 из 56 без потерь, проверено
 * контактным листом. Вес всех ассетов 472 КБ.
 *
 * ЧТО СТОРОЖИТ ЭТА ПРОБА. Карта картинок собирается скриптом
 * scripts/build-palace-items.mjs, а библиотека предметов живёт в
 * core/content.ts, и они могут разъехаться молча: добавили предмет — картинки
 * нет, игрок видит запасную фигуру и снова «не понимает смысла». Проба ловит
 * расхождение сразу.
 */
import { PALACE_ITEM_LIBRARY } from '@/src/games/memory-palace/core/content';
import { generateMemoryPalaceRound } from '@/src/games/memory-palace/core';
import { palaceItemImage, PALACE_ITEM_IMAGES } from '@/src/games/memory-palace/palaceItems.generated';

describe('Дворец памяти · картинки предметов', () => {
  it('есть что проверять: библиотека и карта непусты', () => {
    expect(PALACE_ITEM_LIBRARY.length).toBeGreaterThan(0);
    expect(Object.keys(PALACE_ITEM_IMAGES).length).toBeGreaterThanOrEqual(PALACE_ITEM_LIBRARY.length);
  });

  it('🔴 у каждого предмета библиотеки есть своя картинка', () => {
    const без = PALACE_ITEM_LIBRARY.filter((item) => palaceItemImage(item.id) === null).map((i) => i.id);
    expect({ без_картинки: без, всего: PALACE_ITEM_LIBRARY.length })
      .toEqual({ без_картинки: [], всего: PALACE_ITEM_LIBRARY.length });
  });

  /**
   * 🔴 ПОКРЫТИЕ ПОЛНОЕ В ОБЕ СТОРОНЫ: ни предмета без картинки, ни картинки без
   * предмета.
   *
   * ⚠️ Прежняя редакция требовала, чтобы картинок было БОЛЬШЕ библиотеки —
   * «есть куда расширять». 07.09.2026 библиотека доросла с 16 предметов до 56,
   * запас кончился, и проба покраснела на верном коде. Это была проверка
   * временного состояния, а не правила. Правило же в другом: наборы обязаны
   * совпадать, иначе либо предмет выйдет к игроку запасной фигурой, либо
   * картинка будет лежать в сборке мёртвым весом.
   */
  it('🔴 наборы совпадают: картинок ровно столько же, сколько предметов', () => {
    const идПредметов = new Set(PALACE_ITEM_LIBRARY.map((i) => i.id));
    const лишние = Object.keys(PALACE_ITEM_IMAGES).filter((k) => !идПредметов.has(k));
    expect({ лишних_картинок: лишние, предметов: идПредметов.size, картинок: Object.keys(PALACE_ITEM_IMAGES).length })
      .toEqual({ лишних_картинок: [], предметов: идПредметов.size, картинок: идПредметов.size });
  });

  /**
   * 🔴 РАДИ ЧЕГО НАБОР РАСШИРЯЛИ: ПАРТИИ ПЕРЕСТАЛИ ПОВТОРЯТЬСЯ ПО СОСТАВУ.
   *
   * 📍 Замер ДО (16 предметов в библиотеке): на пятнадцатом уровне партия берёт
   * 12 целевых и 4 лишних — то есть ВЕСЬ набор целиком. Две партии одного
   * уровня совпадали по составу на 100%, менялся только порядок.
   * ПОСЛЕ (56 предметов): из них выбирается 16, и пересечение падает.
   */
  it('🔴 на верхнем уровне две партии не совпадают по составу', () => {
    const состав = (seed: string) => {
      const r = generateMemoryPalaceRound(seed, 15);
      return new Set([...r.targetItems, ...r.distractorItems].map((i) => i.id));
    };
    const a = состав('партия-а');
    const b = состав('партия-б');
    const общих = [...a].filter((id) => b.has(id)).length;
    expect({ взято: a.size, общих_из: a.size, совпало_полностью: общих === a.size })
      .toEqual({ взято: a.size, общих_из: a.size, совпало_полностью: false });
    // Пересечение должно быть заметно меньше половины: 16 из 56 — это редкая встреча.
    expect(общих).toBeLessThan(a.size * 0.7);
  });
});
