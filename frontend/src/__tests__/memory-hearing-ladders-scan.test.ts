/**
 * 🔴 ДОЛГ ЛЕСТНИЦ: с какого уровня партия перестаёт меняться. ЗАМЕР 11.09.2026.
 *
 * Цель — чтобы здесь у всех стояло `УРОВНИ`, то есть плато не наступает в
 * сорока уровнях. Пока стоит меньше — это записанный долг, а не норма.
 * Каждая строка закрывается своим коммитом с новой осью и своей мутацией;
 * число в этой таблице поднимается ТЕМ ЖЕ коммитом.
 *
 * ⚠️ Проба требует «не хуже записанного», а не «ровно столько»: ось, поднявшая
 * потолок, обязана пройти, а потерянная ось — покраснеть. Просто оставить
 * красную пробу в общем дереве нельзя: она встанет в выпуске у девяти чатов.
 */
const ДОЛГ_ПЛАТО: Record<string, number> = {
  'word-pairs': 16,        // две оси: число пар и время на пару, обе упёрлись
  'pseudoword-echo': 15,   // длина, доля трудных, темп, шум — все с ограничителем на 15
  'phoneme-pairs': 15,     // число проб, темп, шум, допуск ошибок
  'chinese-tones': 15,     // число проб, темп, шум, допуск ошибок
  'mnemonics': 15,         // число слов, пауза удержания, примеры-помехи
  'dictation': 15,         // число фраз, темп, шум, задержка ввода
};

/**
 * Окно, внутри которого лестница ОБЯЗАНА расти. Пока это долг игры; поднимется
 * долг — вместе с ним расширится и проверка каждой оси, без правки самих осей.
 */
function ОКНО(игра: string): number { return ДОЛГ_ПЛАТО[игра]!; }

/** Плато не хуже записанного в долге. Выросло — поднимите число в таблице. */
function проверитьПлато(игра: string, плато: number): void {
  const записано = ДОЛГ_ПЛАТО[игра]!;
  expect({ игра, плато_не_хуже_долга: плато >= записано, плато, записано })
    .toEqual({ игра, плато_не_хуже_долга: true, плато, записано });
}
