/**
 * 🔴 КЛЮЧ ПОЛОЖЕНИЯ НЕСЁТ И СВОЙСТВА СОСУДА, А НЕ ОДНО СОДЕРЖИМОЕ.
 *
 * Память обхода у решателя — множество ключей: увидел ключ второй раз, дальше не
 * идёт. Ключ поэтому обязан различать РАЗНЫЕ положения. Сосуды в переливалке
 * давно перестали быть одинаковыми: у каждого может быть своя вместимость
 * (`caps`, короткие сосуды с L20), камни на дне (`stones`) и срок открытия
 * (`opensAt`). Две порции красного в сосуде на ЧЕТЫРЕ и те же две в сосуде на
 * ДВА — разные положения: в одном есть куда долить, в другом сосуд уже закрыт.
 *
 * 📍 КАК НАШЛОСЬ, 07.09.2026. При вводе строгого налива решатель объявил
 * `unsolvable` пять досок из пяти на L26 и L33. Проверка: те же доски
 * собираются, если проиграть на них обычное решение по одной порции (149 и 147
 * ходов) — значит решение существовало, и обход выбрасывал его сам.
 * После починки: L26 стало 5 решённых из 5, L33 — 4 из 5.
 *
 * ⚠️ И ПЕРЕБОР ПОДЕШЕВЕЛ, А НЕ ПОДОРОЖАЛ, хотя ключ стал точнее. Замер на L20:
 * 137 703 узла → 5 726. Причина понятна: раньше обход выбрасывал верный путь и
 * был вынужден перебирать тупики до конца.
 *
 * ⚠️ Дефект НЕ про строгий налив — он про обычный тоже: `caps`/`stones`/`opensAt`
 * идут с L20. Просто там перебор мельче и промах реже. Цена промаха —
 * «уровень непроходим» на доске, которая проходится.
 */
import { fieldKey, pour, isSolved, canPour, type Field } from '@/src/games/water-sort/core/tubes';
import { generateLevel, solve } from '@/src/games/water-sort/core/generate';

describe('ключ положения различает сосуды', () => {
  it('🔴 одно содержимое в сосудах РАЗНОЙ вместимости — разные ключи', () => {
    /*
     * Содержимое ОДНО И ТО ЖЕ, различаются только вместимости: слева пара единиц
     * стоит в сосуде на 4 (можно долить), справа — в сосуде на 2 (он уже полон).
     * Положения разные, и ключи обязаны это видеть.
     *
     * ⚠️ Первая редакция пробы переставила заодно и содержимое — вышло ТО ЖЕ
     * положение с другим порядком сосудов, и проба честно упала. Менять надо
     * ровно одно свойство, иначе мерится не то, что названо.
     */
    const в4: Field = { tubes: [[1, 1], [2]], cap: 4, caps: [4, 2] };
    const в2: Field = { tubes: [[1, 1], [2]], cap: 4, caps: [2, 4] };
    expect(fieldKey(в4)).not.toBe(fieldKey(в2));
  });

  it('🔴 одно содержимое, но камни на дне — разные ключи', () => {
    const чистый: Field = { tubes: [[1, 1], []], cap: 4, stones: [0, 0] };
    const сКамнями: Field = { tubes: [[1, 1], []], cap: 4, stones: [1, 0] };
    expect(fieldKey(чистый)).not.toBe(fieldKey(сКамнями));
  });

  it('🔴 одно содержимое, но разный срок открытия — разные ключи', () => {
    const открыт: Field = { tubes: [[1], []], cap: 4, opensAt: [0, 0] };
    const отложен: Field = { tubes: [[1], []], cap: 4, opensAt: [0, 3] };
    expect(fieldKey(открыт)).not.toBe(fieldKey(отложен));
  });

  /**
   * ⚠️ И ОБРАТНАЯ ПОЛОВИНА: сосуды по-прежнему НЕ ПРИКОЛОЧЕНЫ. Одинаковые по
   * содержимому и свойствам, но переставленные местами — то же положение.
   * Потеряй мы это, обход стал бы разбирать одну доску по многу раз, бюджет
   * выгорел бы, и генератор объявил бы непроходимыми решаемые расклады.
   */
  it('перестановка одинаковых сосудов положения НЕ меняет', () => {
    const слева: Field = { tubes: [[1, 1], [2], []], cap: 4, caps: [4, 4, 4] };
    const справа: Field = { tubes: [[2], [], [1, 1]], cap: 4, caps: [4, 4, 4] };
    expect(fieldKey(слева)).toBe(fieldKey(справа));
  });
});

describe('решатель не выбрасывает настоящее решение', () => {
  /**
   * 🔴 ГЛАВНАЯ ПРОБА: доска, которую решатель назвал бы нерешаемой, ДОЛЖНА
   * решаться. Проверяем не мнением, а построением — проигрываем найденное
   * обычное решение по ОДНОЙ порции за ход и смотрим, собралось ли поле.
   *
   * Так и был найден дефект: строгий налив умеет повторить любой обычный ход
   * (лить по одной, пока цвет сверху тот же), значит всё, что решается обычным
   * наливом, обязано решаться и строгим. Решатель утверждал обратное.
   */
  it('🔴 всё, что решается обычным наливом, решается и по одной порции', () => {
    let проверено = 0;
    for (const L of [20, 26, 33]) {
      const { field } = generateLevel(L);
      const обычное = solve(field, 300_000);
      if (обычное.outcome !== 'solved') continue;
      проверено += 1;

      let f: Field = { ...field, strict: true };
      for (const m of обычное.moves) {
        // Повторяем тот же перелив, пока он законен и цвет сверху совпадает.
        for (let шаг = 0; шаг < 8; шаг += 1) {
          if (!canPour(f, m.from, m.to)) break;
          const n = pour(f, m.from, m.to);
          if (!n) break;
          f = { ...n, strict: true };
          const из = f.tubes[m.from] as number[];
          const в = f.tubes[m.to] as number[];
          if (!из.length || из[из.length - 1] !== в[в.length - 1]) break;
        }
      }
      expect(isSolved(f)).toBe(true);
    }
    // Иначе проба хвалит пустоту: ни одной решаемой доски не досталось.
    expect(проверено).toBeGreaterThan(0);
  }, 120_000);

  it('🔴 и сам решатель на этих уровнях находит решение, а не отказ', () => {
    const счёт: Record<string, number> = {};
    for (const L of [20, 26]) {
      for (let k = 0; k < 3; k += 1) {
        const { field } = generateLevel(L);
        const r = solve({ ...field, strict: true }, 1_000_000);
        счёт[r.outcome] = (счёт[r.outcome] ?? 0) + 1;
      }
    }
    expect(счёт.unsolvable ?? 0).toBe(0);
    expect(счёт.solved ?? 0).toBeGreaterThan(4);
  }, 180_000);
});

describe('строгий налив: за ход уходит одна порция', () => {
  /**
   * 🔴 ОСЬ «СТРОГОСТЬ ПОРЯДКА», КОТОРОЙ У ПЕРЕЛИВАЛКИ НЕ БЫЛО.
   *
   * Обычный перелив забирает весь верхний ряд одного цвета сразу — так эта игра
   * выглядит у всех. Строгий налив ограничивает ход одной порцией: три синих
   * уходят тремя ходами, и план приходится держать дальше вперёд.
   *
   * ⚠️ Признак лежит НА ПОЛЕ, поэтому решатель играет по тому же правилу. Будь
   * он доводом одной функции — у игры появились бы два правила хода, одно у
   * экрана, другое у решателя, и доказанная решаемость считалась бы для другой
   * игры.
   */
  it('🔴 обычный ход забирает весь ряд, строгий — ровно одну порцию', () => {
    const поле: Field = { tubes: [[7, 7, 7], []], cap: 4, caps: [4, 4] };
    /*
     * ⚠️ Источник НЕ однороден целиком? Однороден — и потому `canPour` такой
     * перелив запрещает («однородную в пустую» бессмысленно). Берём поле, где
     * сверху ряд из трёх, а под ним чужой цвет.
     */
    const годное: Field = { tubes: [[1, 7, 7, 7], []], cap: 4, caps: [4, 4] };
    void поле;

    const обычно = pour(годное, 0, 1);
    expect(обычно).not.toBeNull();
    expect((обычно!.tubes[1] as number[]).length).toBe(3);   // весь ряд

    const строго = pour({ ...годное, strict: true }, 0, 1);
    expect(строго).not.toBeNull();
    expect((строго!.tubes[1] as number[]).length).toBe(1);   // ровно одна
    expect((строго!.tubes[0] as number[]).length).toBe(3);   // и источник потерял одну
  });

  /** И ход остаётся законным: за три хода уходит то же, что обычный сделал за один. */
  it('три строгих хода дают то же, что один обычный', () => {
    const начало: Field = { tubes: [[1, 7, 7, 7], []], cap: 4, caps: [4, 4] };
    let f: Field = { ...начало, strict: true };
    for (let k = 0; k < 3; k += 1) {
      const n = pour(f, 0, 1);
      expect(n).not.toBeNull();
      f = { ...n as Field, strict: true };
    }
    const обычно = pour(начало, 0, 1) as Field;
    expect(f.tubes[0]).toEqual(обычно.tubes[0]);
    expect(f.tubes[1]).toEqual(обычно.tubes[1]);
  });
});
