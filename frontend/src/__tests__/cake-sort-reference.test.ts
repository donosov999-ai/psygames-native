/**
 * 🔴 КАЛИБРОВКА ЭТАЛОНА ЗАМЕРЕНА ДЛЯ ШЕСТЁРОК, А НЕ УНАСЛЕДОВАНА ОТ ТРОЕК.
 *
 * ТЗ раздела требует дословно: «калибровка `REF_PER_TYPE = 2.2` снята под
 * тройки; для шестёрок она неверна — перезамерь A*, а не переноси число».
 *
 * ЗАМЕР ДО (что было бы при унаследованном 2,2): порог трёх звёзд — «ходов
 * ≤ 1,15 × эталон», то есть 2,53 × виды. Настоящий минимум, найденный A* на 40
 * столах, — 5,37…5,92 × виды (среднее 5,63). Высшая оценка недостижима на
 * КАЖДОМ столе.
 *
 * ЗАМЕР ПОСЛЕ: при 5,6 порог трёх звёзд 6,44 × виды, минимум укладывается в него
 * с запасом, и три звезды достижимы.
 *
 * ⚠️ Проверка ИСПОЛНЯЕТ настоящий A* на настоящих столах, а не пересказывает
 * числа из комментария. Столы берутся маленькие: с шести видов A* перестаёт
 * доходить до дна, и это записано как граница замера, а не спрятано.
 */
import { CIRCLE } from '@/src/games/cake-sort/core/plate';
import { стол } from '@/src/games/cake-sort/tools/reference-boards';
import { minMoves, lowerBound } from '@/src/games/cake-sort/core/solver';
import { REF_PER_TYPE, moveReference, starsForMoves, referenceFor, starsFor } from '@/src/games/cake-sort/core/stars';
import { deal, levelCfg } from '@/src/games/cake-sort/core/level';
import { prebuiltMin, prebuiltPath, PREBUILT_COUNT } from '@/src/games/cake-sort/core/prebuilt';

jest.setTimeout(300000);

/** Число, которое было бы, унаследуй мы калибровку сортировки товаров. */
const УНАСЛЕДОВАННОЕ = 2.2;

/**
 * 🔴 КАЛИБРОВКА БЕРЁТСЯ ИЗ ДАННЫХ, А НЕ СЧИТАЕТСЯ КАЖДЫЙ ПРОГОН (задача af4c7ff1).
 *
 * 📍 Здесь стоял замер: двадцать четыре стола, на каждом точный поиск A* с
 * бюджетом 200 000 узлов. В CI это 231–346 с НА КАЖДЫЙ ПРОГОН ради числа,
 * которое меняется раз в полгода. Теперь замер лежит в
 * `core/reference-calibration.json` (пишет `tools/record-reference.gen.ts`), а
 * проба сверяет с ним константу.
 *
 * ⚠️ ЧТОБЫ ДАННЫЕ НЕ ПРЕВРАТИЛИСЬ В ОБЕЩАНИЕ НА СЛОВО, часть столов
 * ПЕРЕМЕРЯЕТСЯ ЖИВЬЁМ каждый прогон и сверяется с записанным: изменится
 * решатель или правила — расхождение назовёт стол и оба числа.
 */
// eslint-disable-next-line @typescript-eslint/no-require-imports
const КАЛИБРОВКА = require('@/src/games/cake-sort/core/reference-calibration.json') as {
  budget: number;
  boards: { types: number; plates: number; seed: number; min: number | null }[];
};

interface Замер { types: number; min: number }

const замеры: Замер[] = КАЛИБРОВКА.boards
  .filter((b) => b.min !== null)
  .map((b) => ({ types: b.types, min: b.min as number }));

describe('эталон ходов для круга из шести', () => {
  /**
   * ⚠️ ПОРОГ ОПУЩЕН 20 → 12 ПОСЛЕ СМЕНЫ ПРАВИЛ 16.09.2026. Ход берёт любой кусок,
   * ветвление шире, и A* доходит до дна реже: замер дал 16 досок из 24 против
   * прежних 24. Порог поставлен НИЖЕ намеренного (12), чтобы проба краснела на
   * настоящей потере досок, а не на дрожании в одну-две.
   */
  it('есть что проверять — A* дошёл до дна на достаточном числе столов', () => {
    expect(замеры.length).toBeGreaterThanOrEqual(12);
    expect(КАЛИБРОВКА.budget).toBe(200000);
  });

  /**
   * 🔴 ЖИВАЯ СВЕРКА ВЫБОРКИ: данные обязаны сходиться с решателем СЕГОДНЯ.
   *
   * Без этой пробы записанная калибровка стала бы обещанием на слово: правила
   * поменяются, минимумы уедут, а константа останется сверяться со старыми
   * числами и всё так же зеленеть.
   */
  it('🔴 записанная калибровка сходится с живым расчётом на выборке столов', () => {
    const живьём = КАЛИБРОВКА.boards.filter((b) => b.min !== null).slice(0, 3);
    const врут: string[] = [];
    for (const b of живьём) {
      const m = minMoves(стол(b.types, b.plates, b.seed), КАЛИБРОВКА.budget);
      if (m.moves !== b.min) {
        врут.push(`стол ${b.types}×${b.plates} зерно ${b.seed}: в файле ${b.min}, живой расчёт ${m.moves}`);
      }
    }
    expect(врут).toEqual([]);
    expect(живьём.length).toBe(3);
  });

  /**
   * 🔴 ГЛАВНОЕ: при унаследованном 2,2 три звезды недостижимы. Этот пункт и
   * краснел бы на состоянии ДО — он проверяет ровно тот дефект, ради которого
   * ТЗ запрещает переносить число.
   */
  it('🔴 унаследованное 2,2 сделало бы высшую оценку недостижимой', () => {
    const достижимо = замеры.filter(({ types, min }) => {
      const эталон = Math.round(types * УНАСЛЕДОВАННОЕ);
      return starsForMoves(min, эталон) === 3;
    });
    /*
     * ⚠️ ПРОВЕРКА ПЕРЕВЁРНУТА 16.09.2026, И ВОТ ПОЧЕМУ. При старых правилах 2,2
     * давало НЕДОСТИЖИМЫЕ три звезды, и проба требовала ноль. При свободном
     * выборе минимум упал до 3,4 × виды, и теперь опасность обратная: старое
     * число 5,6 стало СЛИШКОМ ЩЕДРЫМ. Порог трёх звёзд при нём — 1,15 × 5,6 =
     * 6,44 × виды против минимума 3,4 × виды, то есть можно играть почти вдвое
     * хуже лучшего и получать высшую оценку.
     *
     * Требовать ноль по-прежнему нельзя: 2,2 сегодня достижимо на двух досках из
     * шестнадцати — правила стали мягче. Поэтому проверяется то, что и есть
     * дефект: НАСКОЛЬКО щедрым был бы унаследованный эталон.
     */
    expect(достижимо.length).toBeLessThan(замеры.length / 2);

    const прежнее = 5.6;
    const запасХода = замеры
      .map(({ types, min }) => (1.15 * прежнее * types) / min)
      .reduce((a, b) => a + b, 0) / замеры.length;
    expect(запасХода).toBeGreaterThan(1.5);     // замер 16.09.2026: 1,89
  });

  it('🔴 при замеренной калибровке три звезды достижимы на КАЖДОМ столе', () => {
    const недостижимо = замеры
      .filter(({ types, min }) => starsForMoves(min, moveReference(types)) !== 3)
      .map(({ types, min }) => `виды ${types}: минимум ${min} при эталоне ${moveReference(types)}`);
    expect(недостижимо).toEqual([]);
  });

  it('минимум на малых столах лежит в коридоре, который дал замер', () => {
    const отношения = замеры.map(({ types, min }) => min / types);
    const среднее = отношения.reduce((a, b) => a + b, 0) / отношения.length;
    /*
     * ⚠️ КОРИДОР ПЕРЕСНЯТ: 5,0…6,3 → 3,0…4,2. Свободный выбор куска уронил
     * минимум с 5,4…5,9 до 3,4 × виды (замер 16.09.2026 на 16 досках). Старые
     * границы краснели бы на ИСПРАВНОЙ игре.
     */
    expect(среднее).toBeGreaterThan(3.0);
    expect(среднее).toBeLessThan(4.2);
  });

  /**
   * Калибровка обязана лежать в измеренном коридоре. Слишком мало — три звезды
   * недостижимы; слишком много — их дают за небрежную игру, и оценка перестаёт
   * что-либо значить.
   *
   * 🔴 С 16.09.2026 КОРИДОР СНИМАЕТСЯ С БОЛЬШИХ СТОЛОВ, А НЕ С МАЛЫХ. На вшитых
   * уровнях калибровка не работает вовсе: L1…L4 идут от точного минимума,
   * остальные — от длины записанной партии. Эталоном она осталась только ЗА
   * последним вшитым уровнем, а столы там — та же семья, что верх лестницы:
   * видов столько, сколько даёт палитра, и есть очередь. Прежний коридор «среднее
   * малых столов ± 0,7» стерёг число, которым больше ничего не считается.
   *
   * Потребность стола — длина лучшей известной партии ÷ 1,15 ÷ кругов: столько
   * ходов на круг нужно калибровке, чтобы эта партия без всякой записи получила
   * три звезды. Проверяется ИСПОЛНЕНИЕМ `starsFor` по записанным данным.
   */
  it('🔴 калибровка лежит в коридоре потребности столов той же семьи, что за вшитыми', () => {
    const видовНаВерху = levelCfg(PREBUILT_COUNT).types;
    const семья: { L: number; путь: number; кругов: number; нужно: number }[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      const c = levelCfg(L);
      if (c.types !== видовНаВерху || c.queue === 0) continue;
      const кругов = c.types + c.queue;
      const путь = prebuiltPath(L)!;
      семья.push({ L, путь, кругов, нужно: путь / (1.15 * кругов) });
    }
    // Премиса: семья — это большая часть лестницы, а не пара столов.
    expect(семья.length).toBeGreaterThan(80);
    // Слишком мало: хоть один стол семьи не получил бы трёх звёзд за лучшую партию.
    const мимо = семья
      .filter((с) => starsFor(с.путь, с.кругов, null) !== 3)
      .map((с) => `L${с.L}: партия ${с.путь}, нужно ${с.нужно.toFixed(3)} на круг при ${REF_PER_TYPE}`);
    expect(мимо).toEqual([]);
    // Слишком много: щедрее самого требовательного стола не больше чем на шаг округления.
    const самыйТребовательный = Math.max(...семья.map((с) => с.нужно));
    expect(REF_PER_TYPE - самыйТребовательный).toBeLessThan(0.1);
  });

  /**
   * 📌 Структура, из-за которой перенос был обречён: эталон пропорционален
   * `CIRCLE − 1`, а не постоянен. Для троек 2,2 ≈ 2 × 1,1; для шестёрок
   * 5,6 ≈ 5 × 1,12. Проверяем, что замеренный минимум этой форме отвечает, — иначе
   * следующий круг (восьмёрка, четвёрка) снова унаследуют не то.
   */
  it('эталон пропорционален «круг минус один», а не взят постоянным', () => {
    /*
     * ⚠️ ДОЛЯ ПЕРЕСНЯТА: 1,0…1,3 → 0,6…0,9, и это не подгонка, а следствие правил.
     * Пока ход брал ВЕРХНИЙ кусок, вид приходилось РАСКАПЫВАТЬ — отсюда чуть
     * больше одного переноса на каждый из `CIRCLE − 1`. Со свободным выбором
     * раскапывать не нужно: берётся сразу нужный, и переносов требуется меньше,
     * чем звеньев.
     *
     * ⚠️ И С ТОГО ЖЕ ДНЯ МЕРЯЕТСЯ ПО ТОЧНЫМ МИНИМУМАМ, А НЕ ПО `REF_PER_TYPE`.
     * Калибровка стала запасным эталоном больших столов с очередью (см. пробу
     * выше), и её число к структуре минимума отношения больше не имеет: там ходы
     * уходят ещё и на то, чтобы расчистить место под приходящие круги.
     * Утверждение этой пробы — про минимум, значит и мерить его надо минимумом.
     * Замер 16.09.2026: 3,4 / 5 ≈ 0,68.
     */
    const среднийМинимум = замеры.map(({ types, min }) => min / types).reduce((a, b) => a + b, 0) / замеры.length;
    const наПеренос = среднийМинимум / (CIRCLE - 1);
    expect(наПеренос).toBeGreaterThan(0.6);
    expect(наПеренос).toBeLessThan(0.9);
  });

  /**
   * 🔴 ИГРА ПО МИНИМУМУ ОБЯЗАНА ДАВАТЬ ТРИ ЗВЕЗДЫ. Это и есть смысл всей
   * калибровки: сыграл идеально — получил высшую оценку. В сортировке товаров
   * этого не было на 95 % досок, и увидеть это можно было только перебором.
   */
  it('🔴 идеальная игра даёт три звезды на каждом замеренном столе', () => {
    const мимо = замеры
      .filter(({ types, min }) => starsFor(min, types, min) !== 3)
      .map(({ types, min }) => `виды ${types}: минимум ${min} не даёт трёх звёзд`);
    expect(мимо).toEqual([]);
  });

  /**
   * 🔴 ТОЧНЫЙ МИНИМУМ ВСЕГДА ПОБЕЖДАЕТ ОЦЕНКУ. Если фон успел посчитать, звёзды
   * идут по нему; не успел — по калибровке. Проверяется исполнением, а не
   * разбором строчки в экране.
   */
  it('🔴 эталон берёт точный минимум, когда он есть, и калибровку, когда нет', () => {
    const оценка = moveReference(5);
    expect(referenceFor(5, null)).toBe(оценка);
    expect(referenceFor(5, 21)).toBe(21);
    // Нулевой и отрицательный «минимум» — не ответ, а сбой: берём калибровку.
    expect(referenceFor(5, 0)).toBe(оценка);
    /*
     * 🔴 ТРЕТИЙ ИСТОЧНИК С 16.09.2026 — ДЛИНА ЗАПИСАННОЙ ПАРТИИ. Порядок строгий:
     * точный минимум честнее записи, запись честнее калибровки.
     */
    expect(referenceFor(5, 21, 30)).toBe(21);
    expect(referenceFor(5, null, 30)).toBe(30);
    expect(referenceFor(5, null, 0)).toBe(оценка);
    /*
     * И это меняет оценку. ⚠️ Числа выводятся из калибровки, а не пишутся
     * литералом: прежние «28 ходов» держались на 5,6 хода на круг и краснели бы
     * на любой честной перекалибровке. Ходов — ровно на пороге трёх звёзд по
     * оценке; минимум — такой, что по нему эти ходы уже выше порога.
     */
    const ходов = Math.floor(оценка * 1.15);
    const минимум = Math.floor(ходов / 1.15) - 2;
    expect(starsFor(ходов, 5, null)).toBe(3);
    expect(starsFor(ходов, 5, минимум)).not.toBe(3);
  });

  /**
   * 🔴 ЭТАЛОН СЧИТАЕТСЯ ПО КРУГАМ, А НЕ ПО ВИДАМ — И БЕЗ ЭТОГО ТРИ ЗВЕЗДЫ
   * ДОКАЗУЕМО НЕДОСТИЖИМЫ НА ВЕРХНЕЙ ПОЛОВИНЕ ЛЕСТНИЦЫ.
   *
   * Пока каждый вид давал ровно один круг, «по видам» и «по кругам» были одним
   * числом. С очередью входящих кругов больше видов: на L60 их восемнадцать
   * против одиннадцати, на L120 — двадцать шесть против одиннадцати, потому что
   * видов не может стать больше палитры, а кругов может.
   *
   * ⚠️ ПРОВЕРЯЕТСЯ ДОКАЗУЕМЫМ ЧИСЛОМ, А НЕ МНЕНИЕМ. `lowerBound` — допустимая
   * нижняя граница числа ходов: сыграть быстрее неё нельзя в принципе. Если
   * порог трёх звёзд оказался НИЖЕ неё, высшая оценка недостижима как ни играй.
   *
   * ЗАМЕР 07.09.2026 по L1…L120, худшее отношение «граница ÷ порог 3★»:
   *   по кругам — **0,66** (запас есть везде)
   *   по видам  — **1,43** (порог ниже границы: три звезды невозможны)
   */
  it('🔴 порог трёх звёзд нигде не ниже доказуемого минимума уровня', () => {
    const мимо: string[] = [];
    let худшее = 0;
    for (let L = 1; L <= 120; L += 3) {
      const c = levelCfg(L);
      const граница = lowerBound(deal(L).board);
      /*
       * ⚠️ С 16.09.2026 порог — тот, что получит игрок: точный минимум, иначе
       * длина записанной партии, иначе калибровка. Прежняя редакция брала одну
       * калибровку на всех 120 уровнях — а на них она больше не работает.
       */
      const порог = referenceFor(c.types + c.queue, prebuiltMin(L), prebuiltPath(L)) * 1.15;
      худшее = Math.max(худшее, граница / порог);
      if (граница > порог) мимо.push(`L${L}: граница ${граница} выше порога ${Math.round(порог)}`);
    }
    expect(мимо).toEqual([]);
    // И запас не «на волосок»: худший уровень укладывается с третью запаса.
    expect(худшее).toBeLessThan(0.8);
  }, 300_000);

  /**
   * 🔴 И ОБРАТНАЯ СТОРОНА ТОГО ЖЕ ЗАМЕРА: счёт ПО ВИДАМ обязан ломаться.
   *
   * Без этого пункта предыдущий зеленел бы и при подмене «кругов» на «виды» на
   * нижних уровнях, где очереди нет и два счёта совпадают. Здесь берётся
   * уровень, где очередь заведомо есть, и утверждается, что старая формула
   * делает три звезды НЕВОЗМОЖНЫМИ, — то есть что разница не косметическая.
   */
  it('🔴 счёт эталона по видам сделал бы высшую оценку невозможной', () => {
    /*
     * ⚠️ Уровень ищется ЗАМЕРОМ, а не берётся наугад. Первая редакция этой пробы
     * называла L60 — и покраснела: там граница 67 против порога 71, разрыв ещё
     * не открылся. Виды упираются в палитру на L17, круги растут дальше, и
     * расходятся эти два счёта постепенно. Проба обязана найти место расхождения
     * сама, иначе она стережёт номер уровня, а не утверждение.
     */
    let первый = 0;
    for (let L = 1; L <= 120 && !первый; L += 1) {
      const c = levelCfg(L);
      if (lowerBound(deal(L).board) > referenceFor(c.types, null) * 1.15) первый = L;
    }
    expect(первый).toBeGreaterThan(0);
    // И это не «где-то за горизонтом»: разрыв открывается в пределах лестницы.
    expect(первый).toBeLessThanOrEqual(90);
    // А счёт по кругам на том же уровне высшую оценку оставляет достижимой.
    const c = levelCfg(первый);
    expect(c.queue).toBeGreaterThan(0);
    expect(lowerBound(deal(первый).board)).toBeLessThan(referenceFor(c.types + c.queue, null) * 1.15);
  }, 300_000);

  it('звёзды считаются от эталона и различают игру', () => {
    const э = moveReference(5);
    expect(starsForMoves(Math.round(э * 1.0), э)).toBe(3);
    expect(starsForMoves(Math.round(э * 1.4), э)).toBe(2);
    expect(starsForMoves(Math.round(э * 2.0), э)).toBe(1);
  });
});
