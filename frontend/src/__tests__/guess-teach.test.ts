/**
 * 🔴 РАЗБОР «УГАДАЙ КОД» ОБЯЗАН ДОВОДИТЬ ДО КОДА, СЧИТАТЬ МЕТКИ КАК ДВИЖОК И СТАВИТЬ ПОПЫТКИ ТАК, КАК ИХ
 * СТАВИТ ЧЕЛОВЕК.
 *
 * Раскатка обучения (Денис 17.09.2026: «обучение зашло — раскатывай везде по всем играм»). Раздачи —
 * настоящие, сняты с моста (`scripts/capture-guess-boards.mjs`): секрет из строки ответа после
 * `psy_solve` и ответы САМОГО движка на попытки, поставленные протяжкой из палитры. Формула меток
 * сверяется с ними, а не сама с собой.
 */
import { LANGUAGES, translateFor } from '@/src/contexts/LanguageContext';
import { разобрать as разобратьРисунок, type Партия } from '@/src/games/tatham-bridge/play';
import {
  ответ, всеКоды, согласные, худшийОстаток, план, перваяПопытка, параметрыИзСтроки, доскаСРисунка,
  сыгранныеПопытки, текстШага, КЛЮЧИ_РАЗБОРА_УГАДЫВАНИЯ, type Код,
} from '@/src/games/tatham-bridge/guess-teach';
import { учительGuess } from '@/src/games/tatham-bridge/teach/guess';
import { УЧИТЕЛЯ } from '@/src/games/tatham-bridge/teach';
import снимок from './guess-teach-boards.generated.json';

interface Раздача {
  параметры: string; зерно: number; секрет: Код;
  ответы: { попытка: Код; чёрных: number; белых: number }[];
  рисунокПопыток: string[]; рисунокРешения?: string[];
}
const раздачи = снимок.раздачи as unknown as Раздача[];
const партия = (рисунок: string[]): Партия => ({ примитивы: разобратьРисунок(рисунок.join('\n')), ширина: 263, высота: 420 } as unknown as Партия);

describe('разбор «Угадай код» по шагам', () => {
  it('снимок живой: обе ступени движка, по три раздачи, у первой — рисунок решения', () => {
    expect(new Set(раздачи.map((р) => р.параметры))).toEqual(new Set(['c6p4g10Bm', 'c8p5g12Bm']));
    expect(раздачи).toHaveLength(6);
    expect(раздачи.filter((р) => р.рисунокРешения)).toHaveLength(2);
  });

  it('🔴 метки считаются как у движка: все ответы, снятые с моста, совпадают', () => {
    const расхождения = раздачи.flatMap((р) => р.ответы
      .filter((о) => { const м = ответ(р.секрет, о.попытка); return м.чёрных !== о.чёрных || м.белых !== о.белых; })
      .map((о) => `${р.параметры}#${р.зерно}: ${о.попытка} → движок ${о.чёрных}/${о.белых}, формула ${JSON.stringify(ответ(р.секрет, о.попытка))}`));
    expect(раздачи.flatMap((р) => р.ответы)).toHaveLength(24);
    expect(расхождения).toEqual([]);
  });

  it.each(раздачи.map((р) => [`${р.параметры}#${р.зерно}`, р] as const))(
    '🔴 %s: план с пустой доски и с четырёх сыгранных попыток приходит к коду в пределах попыток',
    (_, р) => {
      const п = параметрыИзСтроки(р.параметры)!;
      for (const сыграно of [[], р.ответы.map((о) => о.попытка)]) {
        const шаги = план(р.секрет, сыграно, п);
        expect(шаги.length).toBeGreaterThan(0);
        expect(шаги[шаги.length - 1]!.попытка).toEqual(р.секрет);
        expect(шаги[шаги.length - 1]!.номер).toBeLessThan(п.попыток);
        // Каждая попытка после первой согласна со всеми ответами до неё, и «в худшем» посчитано честно.
        const история = сыграно.map((попытка) => ({ попытка, ответ: ответ(р.секрет, попытка) }));
        шаги.forEach((шаг, i) => {
          expect(шаг.номер).toBe(сыграно.length + i);
          const кандидаты = согласные(всеКоды(п), история);
          expect(шаг.осталось).toBe(кандидаты.length);
          if (история.length) expect(кандидаты.some((к) => к.join() === шаг.попытка.join())).toBe(true);
          else expect(шаг.попытка).toEqual(перваяПопытка(п.фишек));
          expect(шаг.вХудшем).toBe(худшийОстаток(шаг.попытка, кандидаты));
          история.push({ попытка: шаг.попытка, ответ: ответ(р.секрет, шаг.попытка) });
        });
      }
    },
  );

  it('«Стандарт» 6×4: каждый шестой из 1 296 кодов угадан не дольше чем за 6 попыток из 10', () => {
    const п = параметрыИзСтроки('c6p4g10Bm')!;
    const коды = всеКоды(п);
    expect(коды).toHaveLength(1296);
    let худший = 0;
    for (let i = 0; i < коды.length; i += 6) худший = Math.max(худший, план(коды[i]!, [], п).length);
    expect(худший).toBeLessThanOrEqual(6);
  });

  it('🔴 доска снимается с рисунка: палитра, сыгранные ряды и их метки, строка ответа решения', () => {
    for (const р of раздачи) {
      const п = параметрыИзСтроки(р.параметры)!;
      const доска = доскаСРисунка(разобратьРисунок(р.рисунокПопыток.join('\n')), п)!;
      expect(доска.палитра).toHaveLength(п.цветов);
      expect(сыгранныеПопытки(доска)).toEqual(р.ответы.map((о) => о.попытка));
      р.ответы.forEach((о, i) => expect([доска.метки[i]!.чёрных, доска.метки[i]!.белых]).toEqual([о.чёрных, о.белых]));
      expect(доска.код).toBeNull();
      if (р.рисунокРешения) expect(доскаСРисунка(разобратьРисунок(р.рисунокРешения.join('\n')), п)!.код).toEqual(р.секрет);
    }
  });

  it.each(раздачи.filter((р) => р.рисунокРешения).map((р) => [р.параметры, р] as const))(
    '🔴 %s: карточки учителя, прокликанные как человеком, ставят попытки плана в следующие ряды и угадывают код',
    (_, р) => {
      const п = параметрыИзСтроки(р.параметры)!;
      const доска = доскаСРисунка(разобратьРисунок(р.рисунокПопыток.join('\n')), п)!;
      const карточки = учительGuess.урок({ партия: партия(р.рисунокПопыток), решение: партия(р.рисунокРешения!), параметры: р.параметры })!;
      const ожидание = план(р.секрет, р.ответы.map((о) => о.попытка), п);
      expect(карточки).toHaveLength(ожидание.length);
      const ближайший = <T extends { x: number; y: number }>(т: { x: number; y: number }, из: T[]) =>
        из.reduce((a, b) => (Math.hypot(a.x - т.x, a.y - т.y) <= Math.hypot(b.x - т.x, b.y - т.y) ? a : b));
      карточки.forEach((карточка, k) => {
        expect(карточка.ходов).toBe(1);
        const протяжки = карточка.нажатия.filter((н) => н.до);
        const касание = карточка.нажатия.filter((н) => !н.до);
        expect([протяжки.length, касание.length]).toEqual([п.фишек, 1]);
        const лунки = доска.ряды.flat();
        const поставлено = Array<number>(п.фишек).fill(0);
        let ряд = -1;
        for (const н of протяжки) {
          const цвет = доска.палитра.indexOf(ближайший(н, доска.палитра)) + 1;
          const л = ближайший(н.до!, лунки);
          ряд = доска.ряды.findIndex((р2) => р2.includes(л));
          поставлено[доска.ряды[ряд]!.indexOf(л)] = цвет;
        }
        expect(ряд).toBe(ожидание[k]!.номер);
        expect(ближайший(касание[0]!, доска.метки)).toBe(доска.метки[ряд]);
        expect(поставлено).toEqual(ожидание[k]!.попытка);
      });
      expect(ожидание[ожидание.length - 1]!.попытка).toEqual(р.секрет);
    },
  );

  it('учитель зарегистрирован для экрана головоломок; без решения движка молчит', () => {
    expect(УЧИТЕЛЯ.Guess).toBe(учительGuess);
    const р = раздачи[0]!;
    expect(учительGuess.урок({ партия: партия(р.рисунокПопыток), решение: null, параметры: р.параметры })).toBeNull();
  });

  it('🔴 объяснение есть на всех двенадцати языках, со своими подстановками, и ни одна не остаётся сырой', () => {
    const языки = (LANGUAGES as { code: string }[]).map((l) => l.code);
    expect(языки).toHaveLength(12);
    const подстановки: Record<string, string[]> = {
      teachGuessFirst: ['{code}'], teachGuessNext: ['{n}', '{b}', '{w}', '{k}', '{code}', '{m}'], teachGuessOnly: ['{n}', '{b}', '{w}', '{code}'],
    };
    const пропуски: string[] = [];
    for (const я of языки) for (const к of КЛЮЧИ_РАЗБОРА_УГАДЫВАНИЯ) {
      const текст = translateFor(я, к);
      if (текст === к) пропуски.push(`${я}:${к} — нет ключа`);
      if (я !== 'en' && текст === translateFor('en', к)) пропуски.push(`${я}:${к} — английский фолбэк`);
      for (const п of подстановки[к] ?? []) if (!текст.includes(п)) пропуски.push(`${я}:${к} — нет ${п}`);
    }
    expect(пропуски).toEqual([]);
    const р = раздачи[0]!;
    const шаги = план(р.секрет, [], параметрыИзСтроки(р.параметры)!);
    for (const я of языки) for (const шаг of шаги) expect(текстШага(шаг, (к) => translateFor(я, к))).not.toMatch(/\{(code|n|b|w|k|m)\}/);
    expect(текстШага(шаги[0]!, (к) => translateFor('ru', к))).toContain('Первая попытка — 1 1 2 2');
    const второй = шаги[1]!;
    expect(текстШага(второй, (к) => translateFor('ru', к))).toContain(
      `Ответ на попытку 1: ● ${второй.прошлая!.ответ.чёрных}`,
    );
  });
});
