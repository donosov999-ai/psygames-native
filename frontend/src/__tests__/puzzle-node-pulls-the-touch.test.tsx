/**
 * УЗЕЛ МЕЛЬЧЕ ПАЛЬЦА — КАСАНИЕ ПРИТЯГИВАЕТСЯ К НЕМУ, А НЕ УХОДИТ В ПУСТОЕ МЕСТО.
 *
 * 📍 Дословно из отчётов 18.09.2026 («Распутать», 2.54.22): «узлы толком не хватает»,
 * «ни хуя она не хватает толком». На кадре — ступень 3/5 и НОЛЬ ходов за партию.
 *
 * ЗАМЕР 23.09.2026 (готовая веб-сборка, стенд :8099, iPhone 13, настоящий touch, ступень
 * «Expert» = 20 узлов): поле 256 единиц рисуется в 240 px, значит единица = 0,94 px; движок
 * берёт узел в радиусе `DRAG_THRESHOLD` = 12 единиц (`untangle.c:48`) — 11,3 px. Цель
 * диаметром 22,6 px при норме касания 44. Промах на 15 px — узел не взят НИ РАЗУ из шести.
 *
 * 🔴 ЧТО ИМЕННО СТОРОЖИТ ЭТА ПРОБА. Не «есть проп» и не «есть функция», а КООРДИНАТУ,
 * КОТОРАЯ УХОДИТ В ДВИЖОК: касание мимо узла обязано прийти в его центр, а касание в пустом
 * поле — остаться там, где палец. Второе не менее важно первого: притяни всё подряд — и
 * человек начнёт двигать узлы, которых не трогал.
 */
import React from 'react';
import renderer, { act } from 'react-test-renderer';
import PuzzleCanvas from '@/src/components/PuzzleCanvas';
import { ПРИТЯЖЕНИЕ_К_УЗЛУ } from '@/src/games/tatham-bridge/names';
import type { Партия } from '@/src/games/tatham-bridge/play';

/**
 * Узлы «Распутать»: у каждого фоновый круг радиусом DRAG_THRESHOLD и сам кружок.
 *
 * ⚠️ Третий узел стоит ВПЛОТНУЮ ко второму (25 единиц) нарочно: пока в радиус притяжения
 * попадал ровно один узел, проба «берётся ближайший» была зелёной и с испорченным поиском —
 * мутация «не запоминать лучшее расстояние» её не роняла. На 25 узлах соседи стоят именно так.
 */
const УЗЛЫ = [
  { x: 60, y: 60 },
  { x: 200, y: 180 },
  { x: 222, y: 192 },
];

function доска(): Партия {
  return {
    ширина: 256,
    высота: 256,
    палитра: ['255,255,255', '0,0,0', '255,0,0'],
    примитивы: [
      { вид: 'прямоугольник', x: 0, y: 0, ш: 256, в: 256, цвет: 0 },
      ...УЗЛЫ.flatMap((у) => [
        { вид: 'круг', x: у.x, y: у.y, r: 12, заливка: 0, контур: 0 },
        { вид: 'круг', x: у.x, y: у.y, r: 6, заливка: 1, контур: 1 },
      ]),
    ],
    статус: 0,
  } as unknown as Партия;
}

/**
 * Прогнать жест по холсту и вернуть точку, которую холст отдал движку на «нажал».
 * Масштаб 1: доска 256 рисуется в 256 точек, поэтому экранные координаты равны его.
 */
function нажатие(x: number, y: number, притяжение: number): [number, number] | null {
  let ушло: [number, number] | null = null;
  let д: renderer.ReactTestRenderer;
  act(() => {
    д = renderer.create(
      <PuzzleCanvas
        партия={доска()}
        ширина={256}
        высота={256}
        фон="#fff"
        примагничивание={притяжение}
        onЖест={(гx, гy, ж) => {
          if (ж === 'нажал' && !ушло) ушло = [гx, гy];
        }}
      />,
    );
  });
  const холст = д!.root.findAll((у) => typeof (у.props as any)?.onResponderGrant === 'function')[0];
  const событие = (сx: number, сy: number) => ({ nativeEvent: { locationX: сx, locationY: сy } });
  act(() => {
    холст.props.onResponderGrant(событие(x, y));
    // Палец поехал — холст объявляет протяжку и шлёт «нажал» в точке НАЧАЛА жеста.
    холст.props.onResponderMove(событие(x + 40, y + 40));
    холст.props.onResponderRelease(событие(x + 40, y + 40));
  });
  act(() => { д!.unmount(); });
  return ушло;
}

describe('касание «Распутать» притягивается к узлу', () => {
  it('🔴 промах мимо узла приходит в движок КАК ПОПАДАНИЕ в его центр', () => {
    const радиус = ПРИТЯЖЕНИЕ_К_УЗЛУ.Untangle;
    expect(радиус).toBeGreaterThan(12);   // больше DRAG_THRESHOLD движка, иначе чинить нечего

    // Промахи, на которых в замере 23.09 узел не брался ни разу: 15…26 единиц поля.
    for (const d of [0, 8, 15, 20, 26]) {
      const точка = нажатие(УЗЛЫ[0].x + d, УЗЛЫ[0].y, радиус);
      expect(точка).toEqual([УЗЛЫ[0].x, УЗЛЫ[0].y]);
    }
  });

  it('🔴 касание в пустом поле остаётся там, где палец', () => {
    const радиус = ПРИТЯЖЕНИЕ_К_УЗЛУ.Untangle;
    // Ровно посередине между первым и вторым узлом: до ближайшего 85 единиц — это не промах,
    // это пустое место, и касание обязано остаться в нём.
    const точка = нажатие(130, 120, радиус);
    expect(точка).toEqual([130, 120]);
  });

  it('🔴 из двух соседних притягивается БЛИЖАЙШИЙ, а не любой подходящий', () => {
    const радиус = ПРИТЯЖЕНИЕ_К_УЗЛУ.Untangle;
    // До второго узла 10,8 единицы, до третьего 14,4 — оба в радиусе притяжения.
    expect(нажатие(210, 184, радиус)).toEqual([УЗЛЫ[1].x, УЗЛЫ[1].y]);
    // И наоборот: касание ближе к третьему обязано взять третий.
    expect(нажатие(230, 198, радиус)).toEqual([УЗЛЫ[2].x, УЗЛЫ[2].y]);
  });

  it('🔴 без притяжения (все прочие головоломки) координата не меняется', () => {
    // У остальных 41 режима цель — клетка, а не точка: сдвигать касание там нельзя.
    const точка = нажатие(УЗЛЫ[0].x + 15, УЗЛЫ[0].y, 0);
    expect(точка).toEqual([УЗЛЫ[0].x + 15, УЗЛЫ[0].y]);
  });
});
