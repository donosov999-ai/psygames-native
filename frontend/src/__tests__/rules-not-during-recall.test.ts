/**
 * 🔴 КАРТОЧКА ПРАВИЛ НЕ ВСПЛЫВАЕТ В МИГ ВСПОМИНАНИЯ.
 *
 * 📍 ОТЧЁТ ВАЛИ 06.09.2026, дословно: «вначале вылезла сетка с теми квадратами,
 * которые нужно запомнить, и пока я их запоминала, сетка исчезла, а вместо
 * пустых квадратов появилась расшифровка… естественно, я забыла всю сетку».
 *
 * Карточка правил в фазе удержания СТИРАЕТ то, что человек держит в рабочей
 * памяти, — ровно то, что упражнение и меряет. Это не косметика: подход
 * становится замером не памяти, а способности читать под нагрузкой.
 *
 * Замер 06.09.2026: так было в ДЕВЯТИ играх сразу. Гейт нужен потому, что
 * ошибка не видна в коде игры — строка `useLevelRules(..., phase === 'recall')`
 * выглядит совершенно естественно, и именно её пишут по образцу соседней игры.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ИГРЫ = join(__dirname, '../../app/games');

/**
 * Фазы, в которых человек ЧТО-ТО ДЕРЖИТ: показ ряда, удержание, ввод ответа.
 * Открывать поверх них карточку правил нельзя ничем.
 */
const ОПАСНЫЕ = ['recall', 'input', 'memorize', 'memorise', 'showing', 'eq', 'holding', 'study'];

/** Комментарии срезаем: правило проекта — комментарий не зеленит и не роняет проверку. */
const безКомментариев = (t: string) => t.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');

describe('правила уровня не мешают вспоминать', () => {
  const файлы = readdirSync(ИГРЫ).filter((f) => f.endsWith('.tsx'));
  const вызовы: { файл: string; условие: string }[] = [];
  for (const f of файлы) {
    const текст = безКомментариев(readFileSync(join(ИГРЫ, f), 'utf8'));
    for (const m of текст.matchAll(/useLevelRules\(([\s\S]*?)\);/g)) {
      вызовы.push({ файл: f, условие: m[1]!.replace(/\s+/g, ' ') });
    }
  }

  it('есть что проверять — иначе гейт зелен вслепую', () => {
    expect(вызовы.length).toBeGreaterThanOrEqual(15);
  });

  it('🔴 ни одна игра не открывает правила в фазе удержания или ввода', () => {
    const плохо: string[] = [];
    for (const в of вызовы) {
      for (const ф of ОПАСНЫЕ) {
        // Ищем сравнение фазы именно с опасным именем: `phase === 'recall'`.
        if (new RegExp(`===\\s*['"]${ф}['"]`).test(в.условие)) {
          плохо.push(`${в.файл}: правила в фазе «${ф}»`);
        }
      }
    }
    expect(плохо).toEqual([]);
  });
});
