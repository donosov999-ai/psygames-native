/**
 * 🔴 «ЗАЩИТИСЬ» СУДИТСЯ ЖИВЬЁМ, А НЕ ПО ГОТОВОМУ СПИСКУ.
 *
 * 📍 ЗАМЕР 06.09.2026 ПО ВСЕМУ ПУЛУ. В поле `s` у задач вида `defend` лежит список
 * «спасающих» ходов. Он НЕВЕРЕН: из 3977 ходов **237 (6,0%) не спасают** — после
 * них соперник ставит мат в один. Затронуто **197 позиций из 378 (52,1%)**.
 * Позиций, где не спасает НИ ОДИН ход из списка, — ноль, то есть пул решаем, а
 * слишком широк именно список ответов.
 *
 * Сегодня это никому не вредит: `check()` для `defend` в список не смотрит, а
 * считает живьём — `спасся = !естьМатВОдин(после)`, и `bestDefence()` отдельно
 * пропускает ходы, после которых есть мат в один.
 *
 * 🔴 ЗАЧЕМ ТОГДА ГЕЙТ. Потому что «оптимизация» напрашивается сама и выглядит как
 * упрощение: строкой ниже, для матовых видов, верность уже решается через
 * `(p.solutions as string[]).includes(uci)` (`check.ts:133`). Повтори тот же приём
 * для `defend` — и половина позиций начнёт выдавать «✓» за ход, проигрывающий в
 * один ход, а тестировщик получит «верно» за проигрыш.
 *
 * Проба держит обе стороны различия: список НЕ достаточен (в нём есть негодные)
 * и НЕ необходим (спасающий ход вне списка обязан засчитываться).
 */
import { Chess } from 'chess.js';
import { check } from '@/src/games/scholars-mate/core/check';
import type { ScholarsPuzzle } from '@/src/games/scholars-mate/core/types';

declare function require(m: string): any;
declare const __dirname: string;
const path = require('path');

const банк = require(path.join(__dirname, '../games/scholars-mate/data/puzzles.json'));

/** Задача в том виде, в каком её собирает колода (`deck.ts`). */
const задача = (x: any): ScholarsPuzzle => ({
  kind: 'defend', fen: x.f, solutions: x.s ?? [], san: x.n ?? [], rating: x.r ?? 0,
} as ScholarsPuzzle);

/**
 * ⚠️ ОДНА ДОСКА НА ВСЮ ПРОВЕРКУ, ход-откат. Первая редакция создавала `new Chess`
 * на КАЖДЫЙ ход-кандидат: полный обход пула шёл 412 секунд, и такой гейт не
 * окупается — его выключат. С `move`/`undo` те же числа считаются за секунды.
 */
const матВОдин = (fen: string): boolean => {
  const g = new Chess(fen);
  for (const m of g.moves({ verbose: true }) as any[]) {
    try { g.move(m); } catch { continue; }
    const мат = g.isCheckmate();
    g.undo();
    if (мат) return true;
  }
  return false;
};

/** Сыграть ход и вернуть позицию после него, либо null. */
function после(fen: string, uci: string): string | null {
  const g = new Chess(fen);
  try { g.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), ...(uci.length > 4 ? { promotion: uci[4] } : {}) }); }
  catch { return null; }
  return g.fen();
}

describe('«Защитись»: приговор считается, а не берётся из списка', () => {
  it('🔴 в готовом списке есть ходы, которые НЕ спасают — на них он и опасен', () => {
    let ходов = 0; let негодных = 0; let позицийСНегодным = 0;
    for (const x of банк.defend as any[]) {
      let есть = false;
      for (const uci of (x.s ?? []) as string[]) {
        ходов++;
        const п = после(x.f, uci);
        if (!п || матВОдин(п)) { негодных++; есть = true; }
      }
      if (есть) позицийСНегодным++;
    }
    // Числа зафиксированы: если пул пересоберут и они изменятся, это надо заметить.
    expect(`негодных ходов ${негодных} из ${ходов}, позиций ${позицийСНегодным} из ${(банк.defend as any[]).length}`)
      .toBe('негодных ходов 237 из 3977, позиций 197 из 378');
  });

  it('🔴 негодный ход из списка НЕ засчитывается', () => {
    const примеры: string[] = [];
    let проверено = 0;
    for (const x of банк.defend as any[]) {
      for (const uci of (x.s ?? []) as string[]) {
        const п = после(x.f, uci);
        if (!п || !матВОдин(п)) continue;
        проверено++;
        if (check(задача(x), uci).correct) примеры.push(`${uci} в ${String(x.f).split(' ')[0].slice(0, 24)}`);
        if (проверено >= 60) break;
      }
      if (проверено >= 60) break;
    }
    expect(`проверено негодных ходов: ${проверено >= 40}`).toBe('проверено негодных ходов: true');
    expect(`засчитано негодных: ${примеры.length} → ${примеры.slice(0, 2).join(' | ')}`)
      .toBe('засчитано негодных: 0 → ');
  });

  /**
   * 🔴 ПРИГОВОР НЕ ЗАВИСИТ ОТ СПИСКА ВОВСЕ — прямая проверка.
   *
   * 📍 Здесь сначала стояло «спасающий ход ВНЕ списка засчитывается». Замер это
   * утверждение снял: таких ходов НЕТ ни одного на 40 просмотренных позициях —
   * список ПОЛОН (содержит все спасающие), но НЕВЕРЕН (содержит и лишние).
   * Проба на несуществующий случай зеленела бы вслепую и шла четыре минуты.
   *
   * Точная инверсия дешевле и строже: стираем список у задачи и убеждаемся, что
   * приговор не изменился ни на спасающем ходе, ни на проигрывающем. Если
   * `check` начнёт смотреть в `solutions`, оба утверждения рухнут сразу.
   */
  it('🔴 с ПУСТЫМ списком приговор тот же — значит список не участвует', () => {
    let сСписком = 0; let без = 0; let расхождений = 0;
    const примеры: string[] = [];
    for (const x of (банк.defend as any[]).slice(0, 20)) {
      const g = new Chess(x.f);
      for (const m of (g.moves({ verbose: true }) as any[]).slice(0, 5)) {
        const uci = `${m.from}${m.to}${m.promotion ?? ''}`;
        const a = check(задача(x), uci).correct;
        const b = check({ ...задача(x), solutions: [] } as ScholarsPuzzle, uci).correct;
        if (a) сСписком++;
        if (b) без++;
        if (a !== b) { расхождений++; if (примеры.length < 2) примеры.push(uci); }
      }
    }
    expect(`ходов засчитано со списком ${сСписком}, без списка ${без}`)
      .toBe(`ходов засчитано со списком ${сСписком}, без списка ${сСписком}`);
    expect(`расхождений: ${расхождений} → ${примеры.join(' | ')}`).toBe('расхождений: 0 → ');
    // Проба не зелена вслепую: хоть что-то засчитано, иначе сравнивались бы два нуля.
    expect(`засчитанных ходов больше нуля: ${сСписком > 0}`).toBe('засчитанных ходов больше нуля: true');
  });
});
