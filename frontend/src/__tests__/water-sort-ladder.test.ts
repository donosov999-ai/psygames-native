/**
 * 🔴 ЛЕСТНИЦА ПЕРЕЛИВАЛКИ РАСТЁТ, А ГДЕ НЕ РАСТЁТ — ТАМ ЭТО СКАЗАНО ВСЛУХ.
 *
 * 📍 ЗАМЕР ДО ПРАВКИ (06.09.2026, длина решения, 12 раздач на уровень):
 * L10 = 56,3 хода, **L11 = 48,1** — одиннадцатый уровень был на 15% ЛЕГЧЕ
 * десятого. Причина видна в самих числах: на L10 стояло 12 цветов при высоте 4,
 * на L11 высота росла до 5, но цвета сбрасывались до восьми.
 *
 * ⚠️ ПРЕЖНЯЯ ПРОБА ЭТОГО НЕ ВИДЕЛА: она сравнивала среднее первых трёх уровней
 * со средним последних трёх, а ломалось ровно между ними — на СТЫКЕ участков.
 * Поэтому здесь уровни прогоняются подряд.
 *
 * ⚠️ ВТОРАЯ ПОЛОВИНА ПРОБЫ — ПРО ПЛОСКИЙ ХВОСТ, и она нужна не меньше первой.
 * С L14 обе рабочие оси в потолке: 12 цветов это вся палитра, высота 5 — предел
 * различимости столбика. Уровни там отличаются только раскладом, и разброс
 * 73–81 — это шум раздачи, а не ступени. Проба фиксирует ФАКТ плоскости: пока
 * она зелёная, никто не примет шум за лестницу, а появится третья ось — строка
 * покраснеет и её придётся переписать осознанно.
 */
import { levelParams, generateLevel } from '@/src/games/water-sort/core/generate';
import {
  capOf, stonesIn, isOpen, isDone, canPour, makeField, type Field,
} from '@/src/games/water-sort/core/tubes';

jest.setTimeout(300000);

/** Детерминированный ГПСЧ: иначе «стало легче» меряется на других раскладах. */
const зерно = (s: number) => {
  let a = s >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
};

function ходов(L: number, n = 10): number {
  let сумма = 0;
  for (let i = 0; i < n; i += 1) сумма += generateLevel(L, зерно(L * 1000 + i)).solutionMoves;
  return сумма / n;
}

/** Уровень, с которого лестница упирается в потолок обеих осей. */
const ПОТОЛОК_С = 14;

describe('лестница переливалки', () => {
  it('есть что проверять: параметры уровня меняются по ходу лестницы', () => {
    const формы = new Set(Array.from({ length: 20 }, (_, i) => {
      const p = levelParams(i + 1);
      return `${p.colors}x${p.cap}x${p.empty}`;
    }));
    expect(формы.size).toBeGreaterThanOrEqual(12);
  });

  /**
   * 🔴 ГЛАВНАЯ ПРОВЕРКА — ИМЕННО ОНА КРАСНЕЛА БЫ НА СТАРОМ КОДЕ.
   * Порог в 2 хода — допуск на шум раздачи, а не на ступень: провал на стыке был
   * восемь ходов.
   */
  it('🔴 до потолка ни один уровень не легче предыдущего', () => {
    const откаты: string[] = [];
    let пред = 0;
    for (let L = 1; L <= ПОТОЛОК_С; L += 1) {
      const ср = ходов(L);
      if (ср < пред - 2) откаты.push(`L${L}: ${пред.toFixed(1)} → ${ср.toFixed(1)}`);
      пред = ср;
    }
    expect(откаты).toEqual([]);
  });

  it('🔴 порций на доске не убывает — это то, из чего берётся трудность', () => {
    const откаты: string[] = [];
    let пред = 0;
    for (let L = 1; L <= 60; L += 1) {
      const p = levelParams(L);
      const порций = p.colors * p.cap;
      if (порций < пред) откаты.push(`L${L}: ${пред} → ${порций}`);
      пред = порций;
    }
    expect(откаты).toEqual([]);
  });

  it('🔴 лестница доходит до края: последний уровень вдвое длиннее первого', () => {
    const первый = ходов(1);
    const верх = ходов(ПОТОЛОК_С);
    expect(`${верх > первый * 2}`).toBe('true');
  });

  /**
   * ⚠️ ПЛОСКИЙ ХВОСТ ЗАФИКСИРОВАН, А НЕ ЗАМАСКИРОВАН. Если однажды разброс
   * L20…L60 выйдет за шум, эта строка покраснеет — и хвост придётся описать
   * заново, а не сделать вид, что лестница там была всегда.
   */
  /**
   * 🔴 ХВОСТ БОЛЬШЕ НЕ ПЛОСКИЙ — И ЭТО ПРОВЕРЯЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ.
   *
   * До 06.09.2026 здесь стояло обратное: проба ЗАПИСЫВАЛА плоский хвост как
   * состояние дел («разброс меньше 15 ходов»). Числа расклада с 14-го уровня и
   * до сорокового не менялись вовсе: двенадцать цветов — потолок палитры, пятая
   * порция — потолок высоты. Трудность держал один скрытый слой с 16-го.
   *
   * Теперь выше потолка идут три КАЧЕСТВЕННЫЕ оси, и проба сторожит ровно то,
   * на чём я уже обжёгся в этот же день в «Соедини точки»: план уровня обязан
   * ИСПОЛНЯТЬСЯ НА ПОЛЕ. Замер до починки: план просил сосуд с камнями, на поле
   * их было НОЛЬ на всех уровнях — приёмы садились только на пустые сосуды,
   * укорочение съедало оба, и поздние оси молча отменялись.
   */
  it('🔴 приёмы верхней полосы приходят по очереди и назад не откатываются', () => {
    const оси = (L: number) => {
      const p = levelParams(L);
      return [p.shortBy, p.stones, p.deferred];
    };
    const откаты: string[] = [];
    for (let L = 2; L <= 40; L += 1) {
      const было = оси(L - 1); const стало = оси(L);
      for (let k = 0; k < 3; k += 1) {
        if ((стало[k] as number) < (было[k] as number)) откаты.push(`L${L}, ось ${k}: ${было[k]}→${стало[k]}`);
      }
    }
    expect(откаты).toEqual([]);
    // И верх лестницы действительно несёт все три, иначе «оси» — только слово.
    expect(оси(40).every((n) => n > 0)).toBe(true);
    expect(оси(14).every((n) => n === 0)).toBe(true);
  });

  it('🔴 план уровня ИСПОЛНЯЕТСЯ на поле, а не остаётся в таблице', () => {
    const беды: string[] = [];
    for (const L of [18, 22, 26, 32, 34, 40]) {
      const p = levelParams(L);
      const f = generateLevel(L, зерно(L * 31 + 5)).field;
      const короткий = f.tubes.map((_, i) => f.cap - capOf(f, i)).reduce((a, b) => Math.max(a, b), 0);
      const камней = f.tubes.map((_, i) => stonesIn(f, i)).reduce((a, b) => Math.max(a, b), 0);
      const запечатано = f.tubes.filter((_, i) => !isOpen(f, i)).length;
      if (короткий !== p.shortBy) беды.push(`L${L}: укорочение ${короткий}, а план ${p.shortBy}`);
      if (камней !== p.stones) беды.push(`L${L}: камней ${камней}, а план ${p.stones}`);
      if (запечатано !== p.deferred) беды.push(`L${L}: запечатано ${запечатано}, а план ${p.deferred}`);
    }
    expect(беды).toEqual([]);
  });

  /**
   * 🔴 ТРИ ОСИ НЕ СВОДЯТСЯ ДРУГ К ДРУГУ. Если бы камни были просто «сосудом
   * поменьше», лестница не выросла бы — это был бы один приём под тремя
   * именами. Проверяется смысловая разница: сосуд с камнями НЕ становится домом
   * цвета даже налитый доверху, а короткий — становится.
   */
  it('🔴 сосуд с камнями домом цвета не становится, а короткий становится', () => {
    const короткий = makeField([[], [0, 0, 0]], 5);
    const сКамнями = makeField([[], [0, 0, 0]], 5);
    const кор: Field = { ...короткий, caps: [5, 3] };
    // Буфер налит ДО СВОЕЙ пригодной высоты (5 − 2 камня = 3): если бы он был
    // домом цвета, он бы уже закрылся. Заполнить его выше нельзя — `roomIn` не
    // даст, — и сравнение с полной высотой прикрывало бы дефект молча.
    const кам: Field = { ...сКамнями, caps: [5, 5], stones: [0, 2] };
    expect(`короткий налит доверху закрыт: ${isDone(кор, 1)}`).toBe('короткий налит доверху закрыт: true');
    expect(`с камнями налит доверху закрыт: ${isDone(кам, 1)}`).toBe('с камнями налит доверху закрыт: false');
    // И пустым — закрыт: отчитаться за буфер значит его опустошить.
    const пустойБуфер: Field = { ...makeField([[], []], 5), stones: [0, 2] };
    expect(isDone(пустойБуфер, 1)).toBe(true);
  });

  /** 🔴 Запечатанный сосуд не берёт и не отдаёт, пока не открылся. */
  it('🔴 печать держит сосуд вне игры до нужного числа собранных цветов', () => {
    // ⚠️ ИСТОЧНИК РАЗНОЦВЕТНЫЙ НАРОЧНО: однородный столбик в пустой сосуд игра
    // не переливает по давнему правилу («то же содержимое в другой посуде»), и
    // проба на однородном мерила бы этот запрет, а не печать.
    const f: Field = { ...makeField([[0, 1], [1, 0], []], 2), opensAt: [0, 0, 1] };
    // Ни один цвет не собран — третий сосуд закрыт и ходов в него нет.
    expect(isOpen(f, 2)).toBe(false);
    expect(canPour(f, 0, 2)).toBe(false);
    // Соберём первый цвет — печать снимается сама, от положения, а не флагом.
    const собран: Field = { ...f, tubes: [[0, 0], [1, 0], []] };
    expect(isOpen(собран, 2)).toBe(true);
    expect(canPour(собран, 1, 2)).toBe(true);
  });
});
