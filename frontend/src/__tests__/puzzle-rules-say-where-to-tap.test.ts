/**
 * 🔴 СТРОКА ПРАВИЛА ОТВЕЧАЕТ «КУДА НАЖИМАТЬ», А НЕ ТОЛЬКО «ЧТО СОБРАТЬ».
 *
 * 📍 ЗАМЕР 16.09.2026 по девяти головоломкам развилки «Сортировка»: все ДЕВЯТЬ
 * описаний называли ЦЕЛЬ и ни одно не говорило, чем ходить. Живая жалоба ровно
 * этого рода — задача 2b774e8b: четыре РАЗНЫЕ головоломки брошены за 90 секунд
 * со словами «Как играть? Где справка?».
 *
 * ⚠️ СТРОКА ЭТА — ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ТАКОЕ МОЖНО СКАЗАТЬ. Она стоит под
 * доской (`app/games/puzzles.tsx`, `numberOfLines={3}`) и видна всю партию, в
 * отличие от справки, которую открывают один раз.
 *
 * ⚠️ ГЛАГОЛ ДОЛЖЕН СОВПАДАТЬ С ЗАМЕРОМ, А НЕ С ЗДРАВЫМ СМЫСЛОМ. Способ хода у
 * каждой игры мерян прибором `scripts/puzzle-input-probe.mjs` (зерно 777, 25
 * точек, 44 пары; ход отличается от движения курсора отменой):
 *     Мосты      тычок 6/25 · протяжка 8/44        → «тяни от острова к острову»
 *     Снос групп тычок 25/25, второй тап снимает    → «тапни группу, потом ещё раз»
 *     Заливка    тычок 25/25                        → «тапни клетку»
 *     Петля      тычок 24/25                        → «тапни между точками»
 *     Жемчужная  тычок 21/25                        → «тапни между клетками»
 *     Рельсы     тычок 22/25                        → «тапни клетку»
 *     Инерция    ходит стрелками, в т.ч. диагонали  → «ходи стрелками»
 *     Колышки    тычок 0/297 (замер 11.09)          → «тяни колышек»
 *     Указатели  тычок 0/360 (замер 11.09)          → «тяни от клетки»
 * Двойная проверка здесь же: у кого в `ТОЛЬКО_ПРОТЯЖКА` стоит протяжка, у того в
 * тексте обязан быть глагол протяжки, а не «тапни». Разъедется одно с другим —
 * текст начнёт врать, и это будет хуже прежнего молчания.
 */
import { КЛЮЧ_ОПИСАНИЯ, ТОЛЬКО_ПРОТЯЖКА } from '@/src/games/tatham-bridge/names';

declare const __dirname: string;
// eslint-disable-next-line @typescript-eslint/no-require-imports
const fs = require('fs');
// eslint-disable-next-line @typescript-eslint/no-require-imports
const path = require('path');

/** Девять движков развилки «Сортировка» — состав на 13.09.2026. */
const МОИ = ['Pegs', 'Flood', 'Same Game', 'Signpost', 'Inertia', 'Loopy', 'Pearl', 'Bridges', 'Train Tracks'];

/** Русский текст ключа прямо из словаря — читаем файлом, контекст React тут не нужен. */
function текстКлюча(ключ: string): string {
  const файл = fs.readFileSync(path.join(__dirname, '..', 'contexts', 'LanguageContext.tsx'), 'utf8');
  const m = new RegExp(`\\n  ${ключ}: \\{ ru: '([^']*)'`).exec(файл);
  return m ? (m[1] as string) : '';
}

/** Глаголы «куда нажимать». Список короткий нарочно: он же держит единый язык. */
const ТЫЧОК = /Тапни|Нажми/;
const ПРОТЯЖКА = /Тяни|Протяни/;
const СТРЕЛКИ = /стрелк/i;

describe('правило под доской говорит, чем ходить', () => {
  it('премиса: у всех девяти текст вообще есть', () => {
    const пустые = МОИ.filter((имя) => !текстКлюча(КЛЮЧ_ОПИСАНИЯ[имя] ?? '').length);
    expect(пустые).toEqual([]);
  });

  it('🔴 у всех девяти сказано, ЧЕМ ходить, а не только что собрать', () => {
    const молчат = МОИ.filter((имя) => {
      const т = текстКлюча(КЛЮЧ_ОПИСАНИЯ[имя] ?? '');
      return !(ТЫЧОК.test(т) || ПРОТЯЖКА.test(т) || СТРЕЛКИ.test(т));
    });
    expect(молчат).toEqual([]);
  });

  it('🔴 кому сказано «тяни» — тот и правда только протяжкой', () => {
    /*
     * Обратная сторона: текст не имеет права звать тапать там, где тап не
     * работает. «Колышки» 0 тычков из 297, «Указатели» 0 из 360 — замер 11.09.
     */
    const врут = МОИ.filter((имя) => {
      const т = текстКлюча(КЛЮЧ_ОПИСАНИЯ[имя] ?? '');
      return ТОЛЬКО_ПРОТЯЖКА.has(имя) && ТЫЧОК.test(т);
    });
    expect(врут).toEqual([]);
  });

  it('🔴 и наоборот: «тапни» стоит только у тех, у кого тычок работает', () => {
    const врут = МОИ.filter((имя) => {
      const т = текстКлюча(КЛЮЧ_ОПИСАНИЯ[имя] ?? '');
      return ТЫЧОК.test(т) && ТОЛЬКО_ПРОТЯЖКА.has(имя);
    });
    expect(врут).toEqual([]);
  });

  it('строка влезает в три отведённые ей строки', () => {
    /*
     * ⚠️ ПОРОГ ПОСЛЕ ЗАМЕРА, А НЕ ДО. Под доской `numberOfLines={3}` при 13 px на
     * ширине 390 — это около 140 знаков. Самое длинное из девяти — 111, запас
     * есть; ставим 150, чтобы проба ловила настоящее переполнение, а не правку в
     * пару слов.
     */
    const длинные = МОИ
      .map((имя) => ({ имя, n: текстКлюча(КЛЮЧ_ОПИСАНИЯ[имя] ?? '').length }))
      .filter((x) => x.n > 150);
    expect(длинные).toEqual([]);
  });
});
