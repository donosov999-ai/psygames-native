import { исходникЭкрана } from './helpers/screenSource';
import { HUB_CONTENTS } from '@/src/constants/hubContents';

/** Состав раздела берём из хабов, а не из ручного списка — он устаревает молча. */
const ИГРЫ_РАЗДЕЛА: string[] = ['/games/mnemonics-hub', '/games/hearing-hub']
  .flatMap((хаб) => HUB_CONTENTS[хаб] ?? [])
  .map((карточка) => карточка.route.replace('/games/', ''));

/** Пункты, без которых меню не меню. `rules` необязателен: он есть не у всех игр. */
const ОБЯЗАТЕЛЬНЫЕ = ['resume', 'restart', 'home'] as const;

describe('Память и слух · меню паузы у каждой игры', () => {
  it('есть что проверять: восемь игр раздела', () => {
    expect(ИГРЫ_РАЗДЕЛА).toHaveLength(8);
  });

  it('🔴 каждая игра раздела передаёт caркасу pauseActions', () => {
    const без = ИГРЫ_РАЗДЕЛА.filter((игра) => !/pauseActions=\{(?!undefined)/.test(исходникЭкрана(игра)));
    expect({ без_меню_паузы: без }).toEqual({ без_меню_паузы: [] });
  });

  it('🔴 в меню есть продолжить, заново и выход — а не один пункт для галочки', () => {
    const неполные: string[] = [];
    for (const игра of ИГРЫ_РАЗДЕЛА) {
      const код = исходникЭкрана(игра);
      const нет = ОБЯЗАТЕЛЬНЫЕ.filter((id) => !new RegExp(`id: '${id}'`).test(код));
      if (нет.length) неполные.push(`${игра}: нет ${нет.join(', ')}`);
    }
    expect({ неполные }).toEqual({ неполные: [] });
  });

  /**
   * 🔴 Выход домой — через `leave: true`, а не своим `router.back()`.
   * Каркас на этом флаге сперва сохраняет партию в «продолжить», потом уходит;
   * своя навигация сохранение теряет, и человек возвращается на пустое место.
   */
  it('🔴 выход домой идёт путём каркаса, с сохранением партии', () => {
    const свои: string[] = [];
    for (const игра of ИГРЫ_РАЗДЕЛА) {
      const код = исходникЭкрана(игра);
      const домой = код.match(/\{[^}]*id: 'home'[^}]*\}/g) ?? [];
      for (const пункт of домой) {
        if (!/leave: true/.test(пункт)) свои.push(`${игра}: ${пункт.slice(0, 80)}`);
      }
    }
    expect({ выход_мимо_каркаса: свои }).toEqual({ выход_мимо_каркаса: [] });
  });
});
