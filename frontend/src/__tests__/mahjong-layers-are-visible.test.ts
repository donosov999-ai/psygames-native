/**
 * 🔴 ЭТАЖИ ОБЯЗАНЫ БЫТЬ ВИДНЫ ГЛАЗАМИ, А НЕ ТОЛЬКО ЧЕСТНЫ.
 *
 * Отчёт Дениса 05.09.2026 по кадрам с симулятора: «оно просто скачет случайным
 * образом… смысл маджонга, что мы реально разбираем его сверху, всё что видно —
 * то и используется». Правило свободы при этом было исправно: соседняя проба
 * `mahjong-layer-offset-honest` показывала ноль расхождений картинки с правилом.
 *
 * Вот в чём подвох. Та проба ловит ЛОЖЬ картинки — «выглядит накрытой, но
 * свободна» и наоборот. Она полностью зелена и на доске, где этажей не видно
 * ВООБЩЕ: ноль лжи у плоской картинки тоже ноль. Именно туда игра и приехала
 * после починки 03.09, когда сдвиг слоёв ужали до 3 px ради честности: доска
 * стала честной и плоской одновременно, а притушённые плитки читались как
 * случайные.
 *
 * Поэтому здесь проверяется вторая половина: соседние этажи РАЗЛИЧИМЫ. Три
 * признака высоты, и ни один не двигает плитку по сетке:
 *   размер — верхний слой меньше (`tileScaleFor`),
 *   тон    — нижние темнее (`layerTintFor`),
 *   тень   — растёт со слоем (в экране).
 *
 * ⚠️ Обе пробы нужны вместе. Одна ловит враньё, другая — немоту.
 */
import { tileScaleFor, layerTintFor, layerOffsetFor } from '@/src/games/mahjong/board';

/** Яркость цвета #rrggbb, 0…255. */
function яркость(hex: string): number {
  const n = parseInt(hex.slice(1), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  return 0.299 * r + 0.587 * g + 0.114 * b;
}

describe('маджонг: этажи различимы', () => {
  const ЭТАЖЕЙ = [1, 2, 3, 4, 5];      // сколько слоёв бывает на уровнях

  it('есть что проверять: функции высоты существуют и зависят от слоя', () => {
    expect(tileScaleFor(0, 4)).toBe(1);
    expect(tileScaleFor(4, 4)).toBeLessThan(1);
    expect(layerTintFor(0, 4)).not.toBe(layerTintFor(4, 4));
  });

  it('🔴 соседние этажи отличаются тоном заметно, а не на единицу яркости', () => {
    const слабые: string[] = [];
    for (const слоёв of ЭТАЖЕЙ) {
      const max = слоёв - 1;
      if (max <= 0) continue;
      for (let l = 0; l < max; l++) {
        const d = Math.abs(яркость(layerTintFor(l, max)) - яркость(layerTintFor(l + 1, max)));
        // 6 единиц яркости — нижняя граница различимости соседних плиток на
        // светлом фоне доски; ниже человек их не разделяет.
        if (d < 6) слабые.push(`${слоёв} слоёв, этажи ${l}/${l + 1}: разница яркости ${d.toFixed(1)}`);
      }
    }
    expect(слабые).toEqual([]);
  });

  it('🔴 верх светлее низа — стопка читается сверху вниз, а не наоборот', () => {
    const перевёрнутые: string[] = [];
    for (const слоёв of ЭТАЖЕЙ) {
      const max = слоёв - 1;
      if (max <= 0) continue;
      if (яркость(layerTintFor(max, max)) <= яркость(layerTintFor(0, max))) {
        перевёрнутые.push(`${слоёв} слоёв: верхний этаж не светлее нижнего`);
      }
    }
    expect(перевёрнутые).toEqual([]);
  });

  it('🔴 верхняя плитка меньше нижней — нижняя выглядывает рамкой', () => {
    const плоские: string[] = [];
    for (const слоёв of ЭТАЖЕЙ) {
      const max = слоёв - 1;
      if (max <= 0) continue;
      if (tileScaleFor(max, max) >= tileScaleFor(0, max)) плоские.push(`${слоёв} слоёв: размер не меняется`);
    }
    expect(плоские).toEqual([]);
  });

  it('🔴 признаков высоты минимум ДВА на любом числе слоёв — один можно не заметить', () => {
    const бедные: string[] = [];
    for (const слоёв of ЭТАЖЕЙ) {
      const max = слоёв - 1;
      if (max <= 0) continue;
      const признаки = [
        tileScaleFor(max, max) < tileScaleFor(0, max),                                   // размер
        яркость(layerTintFor(max, max)) - яркость(layerTintFor(0, max)) >= 6,            // тон
        layerOffsetFor(max) >= 1,                                                        // сдвиг
      ].filter(Boolean).length;
      if (признаки < 2) бедные.push(`${слоёв} слоёв: признаков высоты всего ${признаки}`);
    }
    expect(бедные).toEqual([]);
  });
});
