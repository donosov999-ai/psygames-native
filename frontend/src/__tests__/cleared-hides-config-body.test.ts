declare const __dirname: string;
declare function require(m: string): any;
const { readFileSync, readdirSync } = require('fs');
const { join } = require('path');

const ИГРЫ = join(__dirname, '../../app/games');

/** Экраны игр, где вообще есть плашка «уровень пройден». */
function сПлашкой(): { имя: string; текст: string }[] {
  return readdirSync(ИГРЫ)
    .filter((f: string) => f.endsWith('.tsx'))
    .map((f: string) => ({ имя: f.replace(/\.tsx$/, ''), текст: readFileSync(join(ИГРЫ, f), 'utf8') as string }))
    .filter((g: { текст: string }) => /phase === 'cleared' &&/.test(g.текст));
}

describe('между уровнями не видно экрана настройки', () => {
  const игры = сПлашкой();

  it('есть что проверять: плашка «уровень пройден» стоит в десятках игр', () => {
    expect(игры.length).toBeGreaterThan(20);
  });

  it('🔴 LevelCleared НЕ наложение — значит тело обязано прятаться', () => {
    // Если однажды плашку сделают полноэкранным наложением, эта проба должна
    // покраснеть первой: тогда всё правило ниже теряет смысл и его надо снять,
    // а не тихо носить дальше.
    const стили: string = readFileSync(join(__dirname, '../components/LevelCleared.tsx'), 'utf8');
    expect(стили).toMatch(/full:\s*\{\s*flex:\s*1/);
    expect(стили).not.toMatch(/full:\s*\{[^}]*position:\s*'absolute'/);
  });

  it('🔴 у каждой игры с плашкой тело экрана настройки скрыто по фазе', () => {
    const голые: string[] = [];
    for (const g of игры) {
      // Тело экрана настройки — прокрутка со `styles.body`. Нет её вовсе —
      // раскладка другая, и правило к игре не применимо.
      if (!/<ScrollView contentContainerStyle=\{styles\.body\}>/.test(g.текст)) continue;
      if (!/phase === 'config' &&/.test(g.текст)) голые.push(g.имя);
    }
    expect(голые).toEqual([]);
  });

  it('🔴 условие стоит ПЕРЕД телом, а не где-то в файле', () => {
    const кривые: string[] = [];
    for (const g of игры) {
      const тело = g.текст.indexOf('<ScrollView contentContainerStyle={styles.body}>');
      if (тело < 0) continue;
      const условие = g.текст.lastIndexOf("phase === 'config' &&", тело);
      // 400 символов — комментарий с пояснением между условием и телом помещается,
      // а случайное совпадение из другой части файла нет.
      if (условие < 0 || тело - условие > 400) кривые.push(g.имя);
    }
    expect(кривые).toEqual([]);
  });
});
