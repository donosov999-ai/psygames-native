/**
 * СТРЕЛКИ СТОЯТ ТАМ, КУДА ВЕДУТ.
 *
 * 🔴 РЕШЕНИЕ ДЕНИСА 16.09.2026 по кадру раскладки клавиш: «это оптимальная схема,
 * скажи всем, у кого есть стрелки, чтобы поправили у себя на такую» — перевёрнутая
 * «Т»: ↑ отдельной строкой над рядом ← ↓ →.
 *
 * ЧТО БЫЛО. В `puzzles.tsx` стиль назывался `крестовина`, а был `flexDirection: 'row'`:
 * все четыре стрелки одной строкой в порядке ← ↑ ↓ →. «Вверх» и «вниз» стояли РЯДОМ
 * ПО ГОРИЗОНТАЛИ и различались только значком. Палец целится в место, а не читает
 * иконку, — оттого весь раздел и читался как «перенесли компьютерную версию».
 * У «Инерции» было хуже: четыре прямых одной строкой плюс четыре диагональных другой,
 * восемь кнопок, и ни одна не стоит там, куда ведёт.
 *
 * ПОЧЕМУ ПРОБА НА КОМПОНЕНТ, А НЕ НА ЭКРАН. Крестовина вынесена в общий `ArrowPad`
 * ровно затем, чтобы схема была ОДНА на приложение: за день уже разъехались справка
 * (четыре независимых механизма) и подписи второго действия (две карты, один ключ,
 * красный tsc). Проба сторожит сам компонент — значит и всех, кто его возьмёт.
 */
import React from 'react';
import renderer, { act } from 'react-test-renderer';
import ArrowPad, { type Направление } from '@/src/components/ArrowPad';

/** Подписи кнопок по рядам, сверху вниз. */
function ряды(восемь?: boolean, наНажатие: (к: Направление) => void = () => {}) {
  let д: renderer.ReactTestRenderer;
  act(() => { д = renderer.create(<ArrowPad восемь={восемь} onPress={наНажатие} />); });
  const вых: string[][] = [];
  for (let i = 0; i < 4; i++) {
    const ряд = д!.root.findAll(
      (у) => (у.props as any)?.testID === `arrow-pad-row-${i}`, { deep: true },
    )[0];
    if (!ряд) break;
    // ⚠️ Подпись висит и на самой кнопке, и на узлах внутри неё: без отбора по
    // `onPress` каждая кнопка считалась бы трижды (замер: 12 вместо 4).
    вых.push(ряд.findAll((у) => typeof (у.props as any)?.accessibilityLabel === 'string'
      && typeof (у.props as any)?.onPress === 'function', { deep: true })
      .map((у) => String((у.props as any).accessibilityLabel)));
  }
  const жать = (метка: string) => {
    const к = д!.root.findAll((у) => (у.props as any)?.accessibilityLabel === метка
      && typeof (у.props as any)?.onPress === 'function', { deep: true })[0];
    act(() => { (к.props as any).onPress(); });
  };
  return { вых, жать, снять: () => act(() => { д!.unmount(); }) };
}

describe('крестовина стрелок — перевёрнутая «Т»', () => {
  it('есть что мерить — рядов два, кнопок четыре', () => {
    const { вых, снять } = ряды();
    expect(вых.length).toBe(2);
    expect(вых.flat().length).toBe(4);
    снять();
  });

  it('🔴 «вверх» стоит ОТДЕЛЬНОЙ строкой над рядом ← ↓ →', () => {
    const { вых, снять } = ряды();
    expect(вых[0]).toEqual(['вверх']);
    expect(вых[1]).toEqual(['влево', 'вниз', 'вправо']);
    снять();
  });

  /**
   * КОНТРОЛЬ С ИЗВЕСТНЫМ ОТВЕТОМ: ровно та схема, что была до 16.09.2026 —
   * «вверх» и «вниз» в одной строке. Без этой проверки утверждение выше зеленело
   * бы и на раскладке, где строк две, но верх с низом всё равно бок о бок.
   */
  it('🔴 ни один ряд не держит «вверх» и «вниз» одновременно', () => {
    const { вых, снять } = ряды();
    for (const ряд of вых) {
      expect(`${ряд.includes('вверх') && ряд.includes('вниз')}`).toBe('false');
    }
    снять();
  });

  it('нажатие отдаёт СВОЁ направление словом', () => {
    const было: Направление[] = [];
    const { жать, снять } = ряды(false, (к) => было.push(к));
    жать('вниз'); жать('влево');
    expect(было).toEqual(['вниз', 'влево']);
    снять();
  });
});

describe('восемь направлений — блок 3×3, середина пуста', () => {
  it('🔴 каждая кнопка на своём месте, рядов три', () => {
    const { вых, снять } = ряды(true);
    expect(вых.length).toBe(3);
    expect(вых[0]).toEqual(['вверх-влево', 'вверх', 'вверх-вправо']);
    expect(вых[1]).toEqual(['влево', 'вправо']);          // середина — дырка, кнопки в ней нет
    expect(вых[2]).toEqual(['вниз-влево', 'вниз', 'вниз-вправо']);
    expect(вых.flat().length).toBe(8);
    снять();
  });

  it('угловое нажатие отдаёт диагональ, а не прямое направление', () => {
    const было: Направление[] = [];
    const { жать, снять } = ряды(true, (к) => было.push(к));
    жать('вверх-вправо'); жать('вверх');
    expect(было).toEqual(['вверх-вправо', 'вверх']);
    снять();
  });
});
