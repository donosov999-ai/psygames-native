/**
 * 🎓 РАЗБОР «ПАР СЛОВ» ГОВОРИТ ТО, ЧТО ИГРА ЗАСЧИТЫВАЕТ.
 *
 * 🔴 Связка, показанная в разборе, обязана быть ТОЙ ЖЕ парой, которую игра примет при
 * соединении. Проба берёт слова прямо из карточек и соединяет ими партию: если карточка
 * назовёт чужое слово, соединение даст ошибку и проба покраснеет.
 */
import { собратьРазборПар, type ПараРазбора } from '@/src/games/word-pairs/teach';
import { levelParams } from '@/app/games/word-pairs';

const пары: ПараРазбора[] = [
  { id: 0, слово1: 'окно', слово2: 'кошка' },
  { id: 1, слово1: 'мост', слово2: 'сахар' },
  { id: 2, слово1: 'перо', слово2: 'лампа' },
  { id: 3, слово1: 'ветер', слово2: 'ключ' },
  { id: 4, слово1: 'камень', слово2: 'река' },
];

/** Соединение, как в игре: левое слово пары и её же правое. */
function соединить(парыИгры: ПараРазбора[], ходы: { a: string; b: string }[]): number {
  let ошибок = 0;
  for (const ход of ходы) {
    const пара = парыИгры.find((p) => p.слово1 === ход.a);
    if (!пара || пара.слово2 !== ход.b) ошибок += 1;
  }
  return ошибок;
}

describe('разбор «Пар слов»', () => {
  it('🔴 связки из карточек соединяются в игре без единой ошибки', () => {
    const { карточки } = собратьРазборПар(пары);
    const ходы = карточки
      .filter((к) => к.вид === 'связка')
      .map((к) => ({ a: String(к.поля!.a), b: String(к.поля!.b) }));
    expect(ходы.length).toBeGreaterThan(0);
    expect(соединить(пары, ходы)).toBe(0);
  });

  it('🔴 разбор берёт НАСТОЯЩИЕ пары партии, а не выдуманные слова', () => {
    const { карточки } = собратьРазборПар(пары);
    const слова = new Set(пары.flatMap((p) => [p.слово1, p.слово2]));
    for (const к of карточки) {
      if (к.поля?.a !== undefined) expect(слова.has(String(к.поля.a))).toBe(true);
      if (к.поля?.b !== undefined) expect(слова.has(String(к.поля.b))).toBe(true);
    }
  });

  it('🔴 длинный уровень не даёт длинный ролик: показываем не больше четырёх пар', () => {
    const много: ПараРазбора[] = Array.from({ length: levelParams(15).pairCount }, (_, i) => ({
      id: i, слово1: `л${i}`, слово2: `п${i}`,
    }));
    const { карточки } = собратьРазборПар(много);
    expect(карточки.filter((к) => к.вид === 'связка')).toHaveLength(4);
    expect(карточки.length).toBeLessThanOrEqual(8);
  });

  it('проверка идёт ЗАДОМ НАПЕРЁД и сперва прячет второе слово', () => {
    const { карточки } = собратьРазборПар(пары);
    const проверка = карточки.find((к) => к.вид === 'проверка')!;
    expect(проверка.открыто).toBe(false);
    expect(проверка.поля!.b).toBe(пары[0]!.слово2);
  });

  it('у каждой карточки есть ключ словаря, последняя — итог', () => {
    const { карточки } = собратьРазборПар(пары);
    expect(карточки.filter((к) => !к.ключ)).toEqual([]);
    expect(карточки[карточки.length - 1]!.вид).toBe('готово');
  });
});
