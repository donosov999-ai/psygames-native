/**
 * 🔴 ОСЬ «ОТВЛЕЧЕНИЕ»: ПРИМАНКА ВЫГЛЯДИТ КАК ЦЕЛЬ И ТРОГАТЬ ЕЁ НЕЛЬЗЯ.
 *
 * ЗАМЕР ДО. У зрительного поиска были заняты ДВЕ оси из десяти: объём (18→72
 * объекта, целей 1→4) и сходство (конъюнкция с 8-го). То, что игрок видит на
 * СТАРТЕ уровня, замирало на 15-м — дальше росла только скорость добора внутри
 * партии, то есть L60 и L20 начинались одинаково.
 *
 * ЗАМЕР ПОСЛЕ: старт уровня 15 → 31, настроек 15 → 21, уровни 1..15 нетронуты.
 *
 * ⚠️ ПОЧЕМУ ОБЫЧНЫЙ ОТВЛЕКАЮЩИЙ — НЕ ЭТА ОСЬ. Промах по нему и так штрафуется, а
 * их количество — это ось 1, объём. Ось 5 про ПОДАВЛЕНИЕ: предмет той же формы и
 * того же цвета, что цель, отличается ровно меткой. Его нельзя взять на
 * автомате, которым идёт весь поиск.
 *
 * 🔴 ГЕЙТ ПРОВЕРЯЕТ СБОРКУ ПОЛЯ ИСПОЛНЕНИЕМ. Приманка, случайно назначенная
 * ЦЕЛЬЮ, сделала бы уровень непроходимым, а увидеть это чтением исходника
 * нельзя — только прогнав раздачу много раз.
 */
import { levelParams, makeBoard } from '@/app/games/visual-search';

declare const __dirname: string;
declare function require(m: string): any;

const БЕЗ_ПРИМАНОК_ДО = 15;
const сигнатура = (L: number) => JSON.stringify(levelParams(L, 1));

function вершина(предел = 400): number {
  let последний = 1;
  let прежняя = сигнатура(1);
  for (let L = 2; L <= предел; L += 1) {
    const текущая = сигнатура(L);
    if (текущая !== прежняя) { последний = L; прежняя = текущая; }
  }
  return последний;
}

describe('🔴 зрительный поиск: ось «отвлечение»', () => {
  it('🔴 уровни 1..15 не тронуты — приманок там нет', () => {
    const сприманками: string[] = [];
    for (let L = 1; L <= БЕЗ_ПРИМАНОК_ДО; L += 1) {
      const d = levelParams(L, 1).decoys;
      if (d !== 0) сприманками.push(`L${L}: приманок ${d}`);
    }
    expect(сприманками).toEqual([]);
  });

  it('🔴 старт уровня перестал замирать на 15-м', () => {
    expect(вершина()).toBeGreaterThan(БЕЗ_ПРИМАНОК_ДО);
    const настроек = new Set(Array.from({ length: 400 }, (_, i) => сигнатура(i + 1))).size;
    expect(настроек).toBeGreaterThan(БЕЗ_ПРИМАНОК_ДО);
  });

  it('🔴 приманок не становится меньше с ростом уровня', () => {
    const откаты: string[] = [];
    for (let L = 2; L <= 400; L += 1) {
      const было = levelParams(L - 1, 1).decoys;
      const стало = levelParams(L, 1).decoys;
      if (стало < было) откаты.push(`L${L}: ${было} → ${стало}`);
    }
    expect(откаты).toEqual([]);
  });

  it('🔴 НИ ОДНА приманка не оказывается целью — иначе уровень непроходим', () => {
    // Прогон, а не чтение: назначение приманок случайное, и столкновение с
    // целью проявилось бы раз в сотню раздач. Двести раздач на каждом из
    // уровней, где приманки есть.
    const беды: string[] = [];
    for (const L of [16, 19, 25, 31, 40]) {
      const p = levelParams(L, 1);
      for (let n = 0; n < 200; n += 1) {
        const доска = makeBoard(p.count, 'T', '#ff0000', p.targetCount, p.conjunction, 300, 300, undefined, p.decoys);
        const целиПриманки = доска.filter((it) => it.isTarget && it.decoy).length;
        if (целиПриманки > 0) { беды.push(`L${L}, раздача ${n}: ${целиПриманки} целей помечены приманкой`); break; }
        const целей = доска.filter((it) => it.isTarget).length;
        if (целей !== p.targetCount) { беды.push(`L${L}, раздача ${n}: целей ${целей} вместо ${p.targetCount}`); break; }
      }
    }
    expect(беды).toEqual([]);
  });

  it('🔴 приманок на поле ровно столько, сколько просит уровень', () => {
    const расхождения: string[] = [];
    for (const L of [16, 19, 25, 31]) {
      const p = levelParams(L, 1);
      const доска = makeBoard(p.count, 'T', '#ff0000', p.targetCount, p.conjunction, 300, 300, undefined, p.decoys);
      const было = доска.filter((it) => it.decoy).length;
      if (было !== p.decoys) расхождения.push(`L${L}: приманок ${было} вместо ${p.decoys}`);
    }
    expect(расхождения).toEqual([]);
  });

  it('🔴 приманка неотличима от цели по форме и цвету — иначе это обычный отвлекающий', () => {
    // Ровно в этом и трудность. Отличайся она формой — искалась бы тем же
    // автоматом, что и всё поле, и никакого подавления не требовала.
    const p = levelParams(25, 1);
    const доска = makeBoard(p.count, 'T', '#ff0000', p.targetCount, p.conjunction, 300, 300, undefined, p.decoys);
    const цель = доска.find((it) => it.isTarget) as (typeof доска)[number];
    const приманки = доска.filter((it) => it.decoy);
    expect(приманки.length).toBeGreaterThan(0);
    for (const d of приманки) {
      expect(`${d.shape}/${d.color}`).toBe(`${цель.shape}/${цель.color}`);
    }
  });
});

describe('проводка: приманку видно и СЛЫШНО', () => {
  /**
   * ⚠️ Проверка исходника, называю своим именем. Вторая строка тут важнее первой:
   * приманка отличается от цели ОДНОЙ точкой, и без подписи для озвучки уровень
   * стал бы непроходимым для незрячего игрока — различий ноль.
   */
  const текст: string = require('fs').readFileSync(
    require('path').join(__dirname, '../../app/games/visual-search.tsx'), 'utf8',
  );

  it('🔴 метка рисуется и не перехватывает нажатие', () => {
    expect(текст).toMatch(/\{it\.decoy && \(/);
    expect(текст).toMatch(/pointerEvents="none"/);
  });

  it('🔴 приманка названа в озвучке', () => {
    expect(текст).toMatch(/\(it\.decoy \? `, \$\{t\('skip'\)\}` : ''\)/);
  });
});
