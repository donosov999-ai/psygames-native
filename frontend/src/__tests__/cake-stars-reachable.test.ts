/**
 * 🔴 ТРИ ЗВЕЗДЫ ДОСТИЖИМЫ НА КАЖДОМ ВШИТОМ УРОВНЕ — ПОСТРОЕНИЕМ, А НЕ ОЦЕНКОЙ.
 *
 * ПОВОД. Свободный выбор куска (16.09.2026) сломал калибровку «ходов на круг»:
 * малым столам без очереди хватает 3,75 (A* до дна), уровням с очередью нужно
 * до 4,46 (длина партии лучом ÷ 1,15 ÷ кругов). Одно число честным быть не может.
 * Точный минимум при этом достаётся только на L1…L4 (L5 и L6 не дошли до дна за
 * 400 000 узлов).
 *
 * РЕШЕНИЕ — ДАННЫЕ, А НЕ ФОРМУЛА. У каждого вшитого уровня записана длина
 * предъявленной партии (`path`, поиск `beamPath` шириной 150). Где точного
 * минимума нет, эталон звёзд — она. Порог «ходов ≤ 1,15 × эталон» от длины
 * существующей партии достижим по построению.
 *
 * ЧТО ЗДЕСЬ СТОРОЖИТСЯ — ВСЁ, ЧЕМ ЗАПИСЬ МОЖЕТ СОВРАТЬ:
 *   · записи нет (вшитый уровень без длины — звёзды уедут на калибровку);
 *   · запись КОРОЧЕ невозможного — ниже доказуемой нижней границы или точного
 *     минимума (тогда три звезды недостижимы, а данные выдают обратное);
 *   · запись не от этого луча — перепрогон на выборке обязан дать ровно её;
 *   · экран не берёт запись — проверяется в `cake-wedge-is-a-cake` по шапке;
 *   · калибровка ЗА вшитыми уровнями ниже того, что нужно самым большим столам.
 */
import { prebuilt, prebuiltMin, prebuiltPath, PREBUILT_COUNT } from '@/src/games/cake-sort/core/prebuilt';
import { referenceFor, starsFor, moveReference } from '@/src/games/cake-sort/core/stars';
import { beamPath, lowerBound } from '@/src/games/cake-sort/core/solver';
import { makeBoard } from '@/src/games/cake-sort/core/plate';

jest.setTimeout(600_000);

const ШИРИНА = 150;

/** Доска вшитого уровня тем же путём, каким её получает экран. */
function доска(L: number) {
  const у = prebuilt(L)!;
  return makeBoard(у.plates.map((p) => [...p]), у.queue.map((p) => [...p]));
}

describe('три звезды достижимы на каждом вшитом уровне', () => {
  it('премиса: вшитых уровней 120, и у каждого записана длина партии', () => {
    expect(PREBUILT_COUNT).toBe(120);
    const без: number[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) if (!(prebuiltPath(L)! > 0)) без.push(L);
    expect(без).toEqual([]);
  });

  it('🔴 записанная партия не короче доказуемого: нижней границы и точного минимума', () => {
    const врут: string[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      const путь = prebuiltPath(L)!;
      const граница = lowerBound(доска(L));
      const минимум = prebuiltMin(L);
      if (путь < граница) врут.push(`L${L}: партия ${путь} короче нижней границы ${граница}`);
      if (минимум !== null && путь < минимум) врут.push(`L${L}: партия ${путь} короче точного минимума ${минимум}`);
    }
    expect(врут).toEqual([]);
  });

  it('🔴 игра длиной в лучшую известную партию даёт три звезды — на всех 120', () => {
    const мимо: string[] = [];
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      const у = prebuilt(L)!;
      const кругов = у.types + у.queue.length;
      const минимум = prebuiltMin(L);
      const путь = prebuiltPath(L);
      /* Лучшее, что известно про эту доску: минимум, если он есть, иначе партия. */
      const лучшее = минимум ?? путь!;
      if (starsFor(лучшее, кругов, минимум, путь) !== 3) {
        мимо.push(`L${L}: ${лучшее} ходов при эталоне ${referenceFor(кругов, минимум, путь)}`);
      }
    }
    expect(мимо).toEqual([]);
  });

  it('🔴 эталон берётся из записи, а не из калибровки, где минимума нет', () => {
    let проверено = 0;
    for (let L = 1; L <= PREBUILT_COUNT; L += 1) {
      if (prebuiltMin(L) !== null) continue;
      const у = prebuilt(L)!;
      expect(referenceFor(у.types + у.queue.length, null, prebuiltPath(L))).toBe(prebuiltPath(L));
      проверено += 1;
    }
    expect(проверено).toBeGreaterThan(100);
  });

  /**
   * 🔴 ДАННЫЕ НЕ ВЫДУМАНЫ: луч той же ширины на той же доске даёт ровно записанное.
   * Луч детерминирован (устойчивая сортировка, порядок ходов `moves`), поэтому
   * требуется РАВЕНСТВО, а не «не длиннее». Уровни выборки — быстрые (до пары
   * секунд) и из разных частей лестницы: без очереди, с одной и с тремя стопками.
   */
  it('🔴 луч воспроизводит записанную длину на выборке уровней', () => {
    const разошлись: string[] = [];
    for (const L of [5, 12, 21]) {
      const заново = beamPath(доска(L), ШИРИНА);
      if (заново !== prebuiltPath(L)) разошлись.push(`L${L}: записано ${prebuiltPath(L)}, луч даёт ${заново}`);
    }
    expect(разошлись).toEqual([]);
  });

  /**
   * ⚠️ ЗА ВШИТЫМИ УРОВНЯМИ ЗВЁЗДЫ ИДУТ ОТ КАЛИБРОВКИ — и она обязана быть не ниже
   * того, что нужно самым большим вшитым столам. Столы за L120 не меньше их: видов
   * не больше палитры, а очередь только растёт.
   */
  it('🔴 калибровка за границей не ниже потребности верхних вшитых столов', () => {
    const мало: string[] = [];
    for (let L = PREBUILT_COUNT - 9; L <= PREBUILT_COUNT; L += 1) {
      const у = prebuilt(L)!;
      const кругов = у.types + у.queue.length;
      if (starsFor(prebuiltPath(L)!, кругов, null) !== 3) {
        мало.push(`L${L}: партия ${prebuiltPath(L)} при калибровке ${moveReference(кругов)} не даёт трёх звёзд`);
      }
    }
    expect(мало).toEqual([]);
  });
});
