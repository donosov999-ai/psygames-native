/**
 * 🔴 ЦВЕТА ОТКЛИКА — ИЗ ОДНОГО ИСТОЧНИКА, И НАЗАД В КОПИИ НЕ РАЗБЕГАЮТСЯ.
 *
 * ЗАМЕР ДО (11.09.2026): `#22c55e` и `#f43f5e` встречались в девяти экранах
 * раздела 25 раз — в рамке коробки, в её фоне, в подсветке кнопки. Общего
 * источника не было ни одного.
 *
 * ⚠️ ЗАЧЕМ ПРОБА, А НЕ ПРОСТО ПРАВКА. В этом же разделе ровно так разъехались
 * семь копий стиля полосы ответа: они отличались ОДНИМ полем, из-за него низ
 * кнопки гулял на 37 px, и все семь были зелёными — каждая по-своему. Пока число
 * можно вписать руками, однажды его впишут.
 *
 * ⚠️ Проба смотрит ИСХОДНИК, и это тот редкий случай, когда так и надо: она
 * проверяет не поведение, а отсутствие копий. Поведение здесь и не меняется —
 * цвет тот же самый, в этом весь смысл правки.
 */
import { ОТКЛИК } from '@/src/games/attention/layout';

// Тот же приём, что в hud-labels.test.ts: узловые типы в наборе не подключены.
declare const __dirname: string;
// eslint-disable-next-line @typescript-eslint/no-require-imports
const { readFileSync, readdirSync } = require('fs');
// eslint-disable-next-line @typescript-eslint/no-require-imports
const { join } = require('path');

const ИГРЫ = ['stroop', 'flanker', 'cpt', 'targets', 'wcst', 'stroop-emotional',
              'simon', 'choice-rt', 'ant', 'switching-task'];
const КОРЕНЬ = join(__dirname, '../../app/games');
const читать = (g: string) => readFileSync(join(КОРЕНЬ, `${g}.tsx`), 'utf8');
/** Комментарии снимаем: разбор в шапке НАЗЫВАЕТ эти цвета, и это не копия. */
const безКомментариев = (s: string) =>
  s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

describe('цвета отклика раздела — один источник', () => {
  it('есть что проверять — иначе набор зелен вслепую', () => {
    expect(ИГРЫ.length).toBe(10);
    expect(ОТКЛИК.верно).toMatch(/^#[0-9a-f]{6}$/);
    expect(readdirSync(КОРЕНЬ).length).toBeGreaterThan(50);
  });

  it('🔴 ни один экран раздела не пишет цвет отклика числом', () => {
    const копии: string[] = [];
    for (const g of ИГРЫ) {
      const код = безКомментариев(читать(g));
      const найдено = код.match(/#22c55e|#f43f5e/gi) ?? [];
      if (найдено.length) копии.push(`${g}: ${найдено.length} (${[...new Set(найдено)].join(', ')})`);
    }
    expect(копии).toEqual([]);
  });

  /**
   * Обратная сторона: источник обязан БРАТЬСЯ. Если экран перестанет его
   * импортировать, проба выше останется зелёной — копий-то нет.
   */
  it('🔴 экраны, показывающие отклик, берут цвета из общего источника', () => {
    const мимо: string[] = [];
    for (const g of ИГРЫ) {
      const код = безКомментариев(читать(g));
      const естьОтклик = /feedback|fbColor/.test(код);
      if (естьОтклик && !код.includes('ОТКЛИК')) мимо.push(g);
    }
    expect(`экраны с откликом, но без общего источника: ${мимо.join(', ') || '—'}`)
      .toBe('экраны с откликом, но без общего источника: —');
  });

  it('прозрачные варианты — те же цвета, а не отдельная пара', () => {
    expect(ОТКЛИК.верноФон.startsWith(ОТКЛИК.верно)).toBe(true);
    expect(ОТКЛИК.неверноФон.startsWith(ОТКЛИК.неверно)).toBe(true);
  });
});
