/**
 * 🔴 ДИКТАНТ НЕ ШТРАФУЕТ ЗА ТО, ЧТО НЕ ЗВУЧИТ.
 *
 * ОТКУДА. Решение Дениса 11.09.2026: «в диктанте надо сделать, чтобы заглавные
 * не считались ошибкой, и пунктуация тоже».
 *
 * ПОЧЕМУ ЭТО НЕ ПОБЛАЖКА. Диктант меряет СЛУХ: человек слышит фразу и
 * записывает. Заглавная буква и запятая на слух не звучат — требовать их значит
 * мерить орфографию под видом слуха. Хуже: движок печати блокирует курсор на
 * ошибке (метод Шестова, `blockOnError`), и человек запирался на символе,
 * которого не мог услышать, — партия вставала.
 *
 * ⚠️ ДВИЖОК ОБЩИЙ, И В ЭТОМ ВСЯ ОСТОРОЖНОСТЬ. `src/services/typing.ts` несёт
 * ТРИ игры: диктант (мой) плюс печатный ответ словаря `vocab-srs` и беглость
 * `phonemic-fluency` — обе раздела «Языки», чужие. Там печать ПО ОБРАЗЦУ, слово
 * видно, и точный символ осмыслен. Поэтому послабление — отдельный флаг, а не
 * смена общего правила, и проба сторожит ОБА края: что послабление работает и
 * что БЕЗ него ничего не изменилось.
 */
import { createState, pressChar, isPunct, MARK } from '@/src/services/typing';

/** Набрать строку посимвольно. Возвращает состояние и число ошибок. */
function набрать(образец: string, ввод: string, lenient: boolean) {
  const st = createState([образец], lenient);
  for (const ch of ввод) pressChar(st, ch, true, lenient);
  return st;
}

describe('Диктант · регистр и знаки не ошибка', () => {
  it('есть что проверять: движок различает буквы и знаки', () => {
    expect(isPunct(',')).toBe(true);
    expect(isPunct('—')).toBe(true);
    expect(isPunct('а')).toBe(false);
    expect(isPunct(' ')).toBe(false);   // пробел набирают, он слышен паузой
  });

  /** 🔴 Регистр: «привет» засчитывается за «Привет». */
  it('🔴 с послаблением заглавная не ошибка', () => {
    const st = набрать('Привет', 'привет', true);
    expect({ ошибок: st.errors, дошёл_до_конца: st.finishedAt !== null })
      .toEqual({ ошибок: 0, дошёл_до_конца: true });
  });

  /** 🔴 Знаки проставляются сами: человек печатает только буквы и пробелы. */
  it('🔴 с послаблением запятую и точку набирать не надо', () => {
    const st = набрать('Да, конечно.', 'да конечно', true);
    expect({ ошибок: st.errors, дошёл_до_конца: st.finishedAt !== null })
      .toEqual({ ошибок: 0, дошёл_до_конца: true });
  });

  /** Фраза может начинаться со знака — курсор обязан встать сразу на букву. */
  it('🔴 знак в начале фразы перешагивается при создании', () => {
    const st = createState(['— Привет'], true);
    expect(st.pattern[st.pos]).toBe('П');
    expect(st.marks[0]).toBe(MARK.CORRECT);
  });

  /**
   * 🔴 ВТОРОЙ КРАЙ: без флага правило прежнее. Если эта проба покраснеет —
   * значит послабление утекло в словарь и беглость, а там печать по образцу.
   */
  it('🔴 БЕЗ послабления регистр и знаки остаются ошибкой — чужие игры не задеты', () => {
    const регистр = набрать('Привет', 'привет', false);
    const знаки = набрать('Да, конечно.', 'да конечно', false);
    expect({ регистр: регистр.errors > 0, знаки: знаки.errors > 0 })
      .toEqual({ регистр: true, знаки: true });
  });

  /** Настоящая ошибка обязана остаться ошибкой и при послаблении. */
  it('🔴 послабление не прощает неверную букву', () => {
    const st = набрать('Привет', 'прывет', true);
    expect(st.errors).toBeGreaterThan(0);
  });
});
