/**
 * 🔴 У КАЖДОГО ЯЗЫКА ИНТЕРФЕЙСА ДОЛЖЕН БЫТЬ СЛОВАРЬ — ИНАЧЕ РАЗДЕЛ НЕ ОТКРЫВАЕТСЯ.
 *
 * 📍 ЗАМЕР 09.09.2026, живая сборка, все двенадцать интерфейсов. На `fr`, `it`,
 * `ja`, `ko`, `ar` языковая зарядка НЕ ИГРАЛАСЬ вовсе: экран сразу показывал
 * «Всё на сегодня сделано». Причина не в SRS, а в корпусе — якорь партии это
 * ЯЗЫК ИНТЕРФЕЙСА (`vocab-srs.tsx`, `base_lang: language`), а в
 * `TRANSLATION_VOCAB` было семь языков из двенадцати. Нет своего языка —
 * пул пуст — пустое состояние вместо партии.
 *
 * ⚠️ ПОЧЕМУ ЭТОГО НЕ ЛОВИЛ НИКТО. `hasVocab()` в проекте есть и используется в
 * четырёх экранах — но только чтобы отфильтровать ВЫБОР ЦЕЛЕВОГО языка. Случай
 * «своего языка нет в словаре» не сторожил никто: приложение вело себя как
 * исправное, просто раздел был пуст. Дефект видно только с того интерфейса.
 *
 * ⚠️ И ВТОРОЕ, ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ. `vocabLangsOf` требует колонку во ВСЕХ
 * записях: заполнил половину — язык не появился, и снова молча. Поэтому ниже
 * проверяется не «есть ли язык в списке», а каждая запись поимённо.
 */
import { TRANSLATION_VOCAB, VOCAB_LANGS, vocabLangsOf, hasVocab } from '@/src/constants/translationVocab';
import { LANGUAGES } from '@/src/contexts/LanguageContext';

const КОДЫ = (LANGUAGES as { code: string }[]).map((l) => l.code);

describe('словарь покрывает каждый язык интерфейса', () => {
  it('🔴 ни один язык интерфейса не остался без словаря', () => {
    const без = КОДЫ.filter((c) => !hasVocab(c));
    expect(`без словаря: ${без.join(',') || '—'}`).toBe('без словаря: —');
  });

  it('🔴 колонка заполнена во ВСЕХ записях, а не в половине', () => {
    const дыры: string[] = [];
    TRANSLATION_VOCAB.forEach((e, i) => {
      КОДЫ.forEach((c) => {
        if (typeof e[c] !== 'string' || !e[c].length) дыры.push(`${i}:${e.en}:${c}`);
      });
    });
    expect(`пустых клеток ${дыры.length}`).toBe('пустых клеток 0');
  });

  /**
   * Внутри одного языка переводы не повторяются: логика матчинга сверяет ОТВЕТ
   * по переводу, и два разных слова с одним переводом засчитали бы верный ответ
   * ошибкой. 09.09 проверка поймала два настоящих омонима — `fr neuf`
   * (девять/новый) и `ko 눈` (глаз/снег); оба разведены в самом словаре.
   */
  it('🔴 внутри языка переводы не дублируются', () => {
    const плохо: string[] = [];
    КОДЫ.forEach((c) => {
      const счёт = new Map<string, number>();
      TRANSLATION_VOCAB.forEach((e) => счёт.set(e[c], (счёт.get(e[c]) ?? 0) + 1));
      [...счёт].filter(([, n]) => n > 1).forEach(([w]) => плохо.push(`${c}:${w}`));
    });
    expect(`дублей ${плохо.length}${плохо.length ? ' → ' + плохо.join(', ') : ''}`).toBe('дублей 0');
  });

  /**
   * Числа литералами, чтобы рост словаря был ОСОЗНАННЫМ. 09.09.2026 проба
   * сработала как задумано: добавил 7 записей ради запаса филвордов —
   * покраснела и заставила обновить число здесь и перегенерировать пиньинь.
   * ⚠️ Меняешь это число — прогони `node scripts/build-zh-pinyin.mjs` и всех,
   * кто читает словарь: `grep -rl translationVocab src/__tests__`.
   */
  it('число языков и записей — литералами, а не через сам словарь', () => {
    expect(`языков ${VOCAB_LANGS.length} · записей ${TRANSLATION_VOCAB.length}`)
      .toBe('языков 12 · записей 283');
  });

  /** Контрпроба: выбей колонку у ОДНОЙ записи — язык обязан пропасть из списка. */
  it('🔴 контрпроба: дыра в одной записи убирает язык целиком', () => {
    const копия = TRANSLATION_VOCAB.map((e) => ({ ...e }));
    expect(vocabLangsOf(копия)).toContain('ja');
    delete (копия[100] as Record<string, string>).ja;
    expect(vocabLangsOf(копия)).not.toContain('ja');
    expect(vocabLangsOf(копия)).toContain('fr');
  });
});
