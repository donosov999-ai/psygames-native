/* structure-sees-suites · VER 1 · 16.09.2026 */
import { GAME_SUITES, suiteEntryRoute } from '@/src/constants/gameSuites';

/**
 * 🔴 ЧТО СТЕРЕЖЁТ. Собранный STRUCTURE.md — объявленный источник состава для
 * одиннадцати чатов-разделов (ссылки в CHATS_RULES.md §5б и во всех ТЗ). До
 * 16.09.2026 он занижал состав: карточка развилки с `suiteId` открывает не один
 * экран, а набор режимов, а сборщик считал только маршрут карточки. Одиннадцать
 * экранов стояли в таблице каталога с прочерком в колонке «развилки», а документ
 * прямо говорит, что прочерк значит «вход только из профиля, главной или
 * зарядки». То есть про девять экранов «Конфликта внимания» и два «Объёма
 * памяти» он утверждал, что из развилок они недостижимы.
 * Замер починки: прочерков в документе 26 → 15, снялись ровно одиннадцать
 * предсказанных. Мутация: подложен документ от 13.09 — две проверки из трёх
 * покраснели.
 *
 * ⚠️ ПРОВЕРЯЕТСЯ ДОКУМЕНТ, А НЕ ИСХОДНИК СБОРЩИКА. Грепать `build-structure.mjs`
 * по слову «набор» бессмысленно: так ловится приём, а не дефект — приём можно
 * переписать, оставив слово. Здесь читается то, что реально отдано людям.
 *
 * ⚠️ КРАСНЫЙ ЦВЕТ ЗНАЧИТ ОДНО ИЗ ДВУХ, и оба — повод к действию:
 *   1) сборщик снова потерял режимы наборов;
 *   2) STRUCTURE.md устарел — появился новый набор, а документ не пересобран.
 * Лечится одинаково: `cd frontend && npm run structure`, затем коммит.
 *
 * ⚠️ ЧТЕНИЕ ФАЙЛА — ПО ШАБЛОНУ РАЗДЕЛА (`hud-labels.test.ts:38`), а не как
 * придумается: типов node в этом tsconfig нет. `import { readFileSync } from 'fs'`
 * роняет tsc (TS2591), голый `require` даёт предупреждение линта, а `__dirname`
 * без объявления — TS2304. Работает только связка «объявить и позвать» ниже;
 * она проходит все три прогона разом.
 */
declare const __dirname: string;
declare function require(m: string): any;
const { readFileSync } = require('fs');
const { join } = require('path');

function документ(): string {
  return readFileSync(join(__dirname, '../../..', 'STRUCTURE.md'), 'utf8') as string;
}

/** Режимы, спрятанные под карточку: сам вход карточки в таблице и так виден. */
function спрятанныеМаршруты(): string[] {
  return GAME_SUITES.flatMap((s) => s.modes.map((m) => m.route).filter((r) => r !== suiteEntryRoute(s)));
}

describe('STRUCTURE.md видит наборы, а не только карточки', () => {
  it('🔴 ни один экран набора не помечен «развилки: —»', () => {
    const текст = документ();
    const спрятанные = спрятанныеМаршруты();
    expect(спрятанные.length).toBeGreaterThanOrEqual(11); // столько их на 16.09.2026

    const строки = текст.split('\n');
    const сПрочерком = спрятанные.filter((route) => {
      /* Строка таблицы каталога: | имя | `id` | `маршрут` | развилки | */
      const строка = строки.find((l) => l.includes('`' + route + '` |'));
      return строка ? /\|\s*—\s*\|\s*$/.test(строка) : false;
    });
    expect(сПрочерком).toEqual([]);
  });

  it('🔴 каждый экран набора вообще присутствует в документе', () => {
    const текст = документ();
    const пропавшие = GAME_SUITES.flatMap((s) => s.modes.map((m) => m.route)).filter(
      (route) => !текст.includes('`' + route + '`'),
    );
    expect(пропавшие).toEqual([]);
  });

  it('заголовок развилки с набором называет ОБА числа — карточки и экраны', () => {
    /* У «Конфликта внимания» девять карточек и восемнадцать экранов; заголовок
       с одним числом снова выдаёт карточки за экраны. Наборов из >1 режима
       на 16.09.2026 пять, и живут они в двух развилках. */
    const текст = документ();
    const многорежимных = GAME_SUITES.filter((s) => s.modes.length > 1).length;
    expect(многорежимных).toBeGreaterThanOrEqual(5);

    const заголовки = текст.split('\n').filter((l) => /^### .+ · `\/games\/.+` — /.test(l));
    const сОбоимиЧислами = заголовки.filter((l) => l.includes('карточек · ') && l.includes('экранов'));
    expect(сОбоимиЧислами.length).toBeGreaterThanOrEqual(2); // «Конфликт внимания» и «Объём памяти»
  });
});
