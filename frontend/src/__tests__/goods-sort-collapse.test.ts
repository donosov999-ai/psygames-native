/**
 * 🔴 ПОЛКА ЗАКРЫВАЕТСЯ, СТОЛБЕЦ ОСЕДАЕТ, СВЕРХУ ПРИХОДИТ ИЗ КОНЕЧНОЙ ОЧЕРЕДИ.
 *
 * Решение Дениса 06.09.2026 по итогам ресёрча. Механика есть у `Goods Master` и
 * `Item Sort`; там же единственный прямой отзыв о ней — отрицательный: игроки
 * жалуются, что «трудно строить план», разработчики сами признают её
 * «подавляющей». Поэтому берётся она в нашем виде: очередь КОНЕЧНА и разложена
 * заранее, как у «Тортов», — замкнутость мультимножества держит доказуемость.
 *
 * ⚠️ ДВА ПОВЕДЕНИЯ В ОДНОЙ ФУНКЦИИ. Без `col` — прежнее: тройка ушла, ниша
 * осталась пустой (так живут сорок пять уровней и все прежние пробы). С `col` —
 * полка закрывается. Проверяются ОБА, иначе «новое работает» ничего не говорит
 * о том, не сломалось ли старое.
 */
import { makeBoard, collapseTriples, moveTop, isCleared, TRIPLE, type Shelf } from '@/src/games/goods-sort/core/board';
import { solveStrict } from '@/src/games/goods-sort/core/solver';
import { dealCollapse, collapseLevel, COLLAPSE_FROM, strictPlacement } from '@/src/games/goods-sort/core/level';

/** Доска на два столбца по две ниши. Ниша 0 ждёт третью единицу из ниши 2. */
function стол(queue: Shelf[] = []) {
  return makeBoard(
    [[1, 1], [2], [1], [2, 2]],
    [3, 3, 3, 3],
    { col: [0, 1, 0, 1], ids: [10, 11, 12, 13], queue },
  );
}

describe('схлопывание полки', () => {
  it('🔴 без столбцов поведение прежнее: ниша пустеет, но остаётся', () => {
    const b = makeBoard([[1, 1, 1], [2]], [3, 3]);
    const после = collapseTriples(b);
    expect(после.cells.length).toBe(2);          // ниша на месте
    expect(после.cells[0]).toEqual([]);          // и пуста
  });

  it('🔴 со столбцами полка ЗАКРЫВАЕТСЯ и уходит с доски', () => {
    const b = makeBoard([[1, 1, 1], [2]], [3, 3], { col: [0, 0], ids: [5, 6] });
    const после = collapseTriples(b);
    expect(после.cells.length).toBe(1);
    expect(после.ids).toEqual([6]);               // осталась вторая, со своим номером
  });

  it('🔴 столбец оседает, а сверху приходит из очереди — одним событием', () => {
    const после = moveTop(стол([{ cell: [7, 7], cap: 3 }]), 2, 0, false);
    expect(после).not.toBeNull();
    // Первый столбец: сверху пришедшая полка, под ней уцелевшая ниша 12.
    expect(после!.cells[0]).toEqual([7, 7]);
    expect(после!.ids?.[1]).toBe(12);
    // Очередь израсходована ровно на одну полку.
    expect(после!.queue?.length ?? 0).toBe(0);
    // Второй столбец не тронут.
    expect(после!.cells.slice(2)).toEqual([[2], [2, 2]]);
  });

  it('🔴 УСТОЙЧИВЫЙ НОМЕР ПЕРЕЕЗЖАЕТ ВМЕСТЕ С СОДЕРЖИМЫМ', () => {
    const после = moveTop(стол(), 2, 0, false)!;
    // Ниша 10 закрылась; 12 осталась и сохранила номер, хотя место в массиве сменила.
    expect(после.ids).not.toContain(10);
    expect(после.ids).toContain(12);
    const место = после.ids!.indexOf(12);
    expect(после.cells[место]).toEqual([]);      // её содержимое переехало с ней
  });

  it('🔴 ниша на ЧЕТЫРЕ не закрывается: иначе четвёртый товар исчез бы с доски', () => {
    // Тройка единиц сложилась, но рядом лежит двойка — ниша обязана остаться.
    const b = makeBoard([[2, 1, 1, 1]], [4], { col: [0], ids: [1] });
    const после = collapseTriples(b);
    expect(после.cells.length).toBe(1);
    expect(после.cells[0]).toEqual([2]);
    // ⚠️ Мультимножество замкнуто: сколько товаров было минус тройка.
    expect(после.cells.flat().length).toBe(4 - TRIPLE);
  });

  it('🔴 победа НЕ засчитывается, пока очередь не кончилась', () => {
    const пусто = makeBoard([[]], [3], { col: [0], ids: [1], queue: [{ cell: [9], cap: 3 }] });
    expect(isCleared(пусто)).toBe(false);
    const без = makeBoard([[]], [3], { col: [0], ids: [1] });
    expect(isCleared(без)).toBe(true);
  });

  it('🔴 решатель ВИДИТ очередь: доска без неё решаема, с ней — нет', () => {
    // Двойка в очереди прийти может только на закрывшуюся полку, а закрываться нечему.
    const решаемая = makeBoard([[1, 1, 1]], [3], { col: [0], ids: [1] });
    expect(solveStrict(решаемая, 5000).solvable).toBe(true);
    const сОчередью = makeBoard([[1, 1, 1]], [3], { col: [0], ids: [1], queue: [{ cell: [8, 9], cap: 3 }] });
    const r = solveStrict(сОчередью, 5000);
    // Пришедшая полка с двумя РАЗНЫМИ товарами на одинокой доске не разбирается.
    expect(r.solvable).toBe(false);
    expect(r.exhausted).toBe(false);              // это доказанное «нет», а не «не знаю»
  });

  it('🔴 ход переносит поля доски целиком — столбцы, номера и очередь', () => {
    /*
     * ⚠️ Ход выбран так, чтобы тройка НЕ сложилась: единица кладётся на двойку.
     * Первая редакция брала ход 1→3, а он как раз достраивал `[2,2]` до тройки,
     * полка закрывалась и очередь честно расходовалась — проба падала на верном
     * коде, потому что мерила не то, что заявляла.
     */
    const после = moveTop(стол([{ cell: [7], cap: 3 }]), 2, 1, false);
    expect(после).not.toBeNull();
    // Тройки нет: очередь на месте, поля не потеряны.
    expect(после!.col).toBeDefined();
    expect(после!.ids).toBeDefined();
    expect(после!.queue?.length).toBe(1);
  });

  /**
   * ⚠️ ЧЕГО ЭТОТ ГЕЙТ НЕ ЛОВИТ — НАЗЫВАЮ, А НЕ ПОДГОНЯЮ ПРОБУ.
   *
   * Мутация «убрать длину очереди из ключа состояния решателя» ВЫЖИВАЕТ: все
   * восемь пунктов остаются зелёными. Придумать маленькую доску, на которой
   * склейка состояний с разной очередью меняет ответ, я не сумел — случай
   * требует, чтобы одна и та же раскладка ниш встретилась в переборе ДВАЖДЫ с
   * разным остатком очереди.
   *
   * 📍 Но что величина нужна — ЗАМЕРЕНО, а не выведено рассуждением. Прогон 56
   * уровней с очередью и без неё в ключе: ответ решателя отличается на 55
   * уровнях из 56, причём в ОБЕ стороны — на L6 без ключа выходит «нерешаемо»
   * там, где решение есть, на L10 наоборот «решаемо» там, где его нет. То есть
   * без этой строки решатель врёт, а обещание «уровень проверен» становится
   * ложью.
   *
   * Кто возьмётся закрыть: нужен ход, после которого раскладка ниш совпадает с
   * уже виденной, а очередь короче. Замер выше говорит, что такие состояния на
   * боевых раздачах встречаются постоянно — значит случай достижим, у меня не
   * вышло его ужать до пробы.
   */
});

/**
 * 🔴 РАЗДАЧА СО СХЛОПЫВАНИЕМ: ВЕСЬ РАСКЛАД ДОКАЗАН, А НЕ ТОЛЬКО ДОСКА.
 *
 * 📍 ЗАМЕР ДО (06.09.2026). Первая попытка резала хвост вслепую: последние 30 %
 * ниш уходили в очередь без всякой проверки. Из 56 уровней доказано 38, двенадцать
 * упёрлись в бюджет и ШЕСТЬ оказались ДОКАЗАННО НЕРЕШАЕМЫМИ. Причина: очередь
 * подаётся только на место закрывшейся полки, а закрывается лишь полная тройка в
 * нише на три; уехали такие ниши в очередь — она не сдвинется никогда.
 *
 * 📍 ЗАМЕР ПОСЛЕ (07.09.2026): 23 уровня со схлопыванием, доказано 23, попыток в
 * среднем 1,0, запасным путём не ушёл ни один.
 */
describe('раздача со схлопыванием', () => {
  const ПУЛ = Array.from({ length: 34 }, (_, i) => i);

  it('🔴 до порога схлопывания нет, с порога есть — кроме строгих', () => {
    for (let L = 1; L < COLLAPSE_FROM; L += 1) expect(collapseLevel(L)).toBe(false);
    const идут: number[] = []; const строгие: number[] = [];
    for (let L = COLLAPSE_FROM; L <= 90; L += 1) {
      if (collapseLevel(L)) идут.push(L);
      if (strictPlacement(L)) строгие.push(L);
    }
    expect(идут.length).toBeGreaterThan(15);
    // Строгие уровни выше порога есть, и НИ ОДИН из них не схлопывается.
    expect(строгие.filter((L) => L >= COLLAPSE_FROM).length).toBeGreaterThan(3);
    expect(строгие.filter((L) => collapseLevel(L)).length).toBe(0);
  });

  it('🔴 КАЖДЫЙ уровень со схлопыванием доказан решаемым — вместе с очередью', () => {
    const плохо: string[] = [];
    let сОчередью = 0;
    for (let L = COLLAPSE_FROM; L <= 90; L += 1) {
      if (!collapseLevel(L)) continue;
      const d = dealCollapse(L, ПУЛ, true);
      if (d.queue.length > 0) сОчередью += 1;
      if (!d.proven) плохо.push(`L${L}: ниш ${d.cells.length}, очередь ${d.queue.length}, попыток ${d.tries}`);
    }
    expect(плохо).toEqual([]);
    // ⚠️ И очередь ДЕЙСТВИТЕЛЬНО есть: без этого пункт зеленел бы на раздачах
    // без очереди, то есть на игре без механики.
    expect(сОчередью).toBeGreaterThan(15);
  });

  it('🔴 мультимножество замкнуто: в очереди и на доске вместе — весь расклад', () => {
    for (const L of [COLLAPSE_FROM, COLLAPSE_FROM + 5, COLLAPSE_FROM + 11]) {
      if (!collapseLevel(L)) continue;
      const d = dealCollapse(L, ПУЛ, true);
      const наДоске = d.cells.reduce((n, c) => n + c.length, 0);
      const вОчереди = d.queue.reduce((n, s) => n + s.cell.length, 0);
      // Товаров ровно столько, сколько троек, умноженное на три — ни одного лишнего.
      expect((наДоске + вОчереди) % 3).toBe(0);
      expect(d.caps.length).toBe(d.cells.length);
      expect(d.ids.length).toBe(d.cells.length);
      expect(d.col.length).toBe(d.cells.length);
    }
  });

  /**
   * ⚠️ ЧЕГО ЭТОТ БЛОК НЕ ЛОВИТ, И ПОЧЕМУ Я НЕ СТАЛ ПОДГОНЯТЬ ПРОБУ.
   *
   * Мутация «убрать повтор попыток» (вернуть первую раздачу, не спрашивая
   * `proven`) ВЫЖИВАЕТ: все проверки остаются зелёными. Это не дыра в пробе, а
   * замер — попыток в среднем 1,0 на 23 уровнях, то есть первая раздача уже
   * годится всегда, и повтор ни разу не срабатывает.
   *
   * 🔴 УБИРАТЬ ПОВТОР НЕЛЬЗЯ. Ровно так же вела себя проверка раздачи у «Тортов»:
   * 720 раздач дали 0 срабатываний заслона, а стоило тронуть генератор — он
   * понадобился в первый же день. Отбор полок в очередь ещё будут менять
   * (сейчас он берёт ниши на четыре и пустые), и тогда первая попытка перестанет
   * годиться всегда.
   *
   * Что ловится и без повтора: сама ПРОВЕРКА `proven` — если раздача отдаст
   * недоказанный расклад, пункт «каждый уровень доказан» краснеет. Мутация
   * снимает только повтор, но не проверку.
   */
});
