/**
 * 🔴 ЦИФРЫ СУДОКУ ПОМЕЩАЮТСЯ В ПОЛЕ: КЛЕТКА СЧИТАЕТСЯ ОТ МЕСТА, КОТОРОЕ РЕАЛЬНО ДАЛ КАРКАС.
 *
 * 📍 Отчёт 57a0e9cd (17.09.2026, 2.54.20, Android 384×784): «ПОЧЕМУ ТУЛБАР ВНИЗУ ВСЕ ЦИФРЫ ЗАКРЫЛ» — видны 1–5 со
 * срезанным низом, 6–9 нет. С 2.54.20 каркас ставит служебный ряд ПОД полем, а доска считалась от высоты окна с
 * резервом 330, замеренным без этого ряда.
 *
 * ЗАМЕР экспорта, WebKit, 9×9 уровень 62, профиль «Микро-релакс» (числа ниже — отсюда):
 *   · до правки: 384×784 — поле 478, доска 346, низ клавиатуры на 44 px ниже поля; 360×640 — то же +44;
 *   · после (значки в один ряд, клетка от поля): 384×784 — доска 346, цифры внутри поля с запасом 65;
 *     360×640 — доска 256 (было 202), запас 11.
 * Место под содержимое поля (`useGameFieldHeight`) = окно поля − 13: 384×784 → 521, 360×640 → 430.
 */
import { клеткаПортрета } from '@/app/games/sudoku';

/** Высота колонки под доской и над ней: строка-объяснение 51, зазор 14, рамка 4, клавиатура строками по 56 без последнего зазора. */
const колонка = (клетка: number, N: number, строк: number) => 51 + 14 + (клетка * N + 4) + (строк * 56 - 6);

describe('судоку: доска и цифры помещаются в поле каркаса', () => {
  it('🔴 384×784 (экран отчёта): доска по ширине 346, цифры внутри поля', () => {
    const клетка = клеткаПортрета({ width: 384, height: 784, N: 9, clueCols: 0, строкКлавиатуры: 2, высотаПоля: 521 });
    expect(клетка * 9 + 4).toBe(346);
    expect(колонка(клетка, 9, 2)).toBeLessThanOrEqual(521);
  });

  it('🔴 360×640: доска от высоты поля, 256, а не 202 от резерва окна', () => {
    const клетка = клеткаПортрета({ width: 360, height: 640, N: 9, clueCols: 0, строкКлавиатуры: 2, высотаПоля: 430 });
    expect(клетка * 9 + 4).toBe(256);
    expect(колонка(клетка, 9, 2)).toBeLessThanOrEqual(430);
  });

  it('🔴 при любом поле, пока клетка не упёрлась в пол 14, колонка не выше поля — цифры не уходят под ряд', () => {
    const плохие: string[] = [];
    for (const [N, строк] of [[6, 2], [9, 2], [12, 3], [16, 4]] as const) {
      for (let поле = 300; поле <= 900; поле += 7) {
        for (const width of [320, 360, 384, 412, 430]) {
          const клетка = клеткаПортрета({ width, height: 2000, N, clueCols: 0, строкКлавиатуры: строк, высотаПоля: поле });
          if (клетка > 14 && колонка(клетка, N, строк) > поле) плохие.push(`${N}×${N} ширина ${width} поле ${поле}: колонка ${колонка(клетка, N, строк)}`);
        }
      }
    }
    expect(плохие.slice(0, 5)).toEqual([]);
  });

  it('поле ещё не измерено (0) — прежний расчёт от окна, чтобы первый кадр не мигал крошечной доской', () => {
    const клетка = клеткаПортрета({ width: 384, height: 784, N: 9, clueCols: 0, строкКлавиатуры: 2, высотаПоля: 0 });
    expect(клетка).toBe(Math.floor(Math.min((384 - 36) / 9, (784 - 330 - 56 - 51) / 9, 92)));
  });
});
