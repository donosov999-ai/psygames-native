/**
 * УРОВЕНЬ НЕ ЗАСЧИТЫВАЕТСЯ, ПОКА ОЧЕРЕДЬ НЕ ПУСТА.
 *
 * 🔴 ЗАЧЕМ. Отчёт тестировщиков `be449226`: «Перешёл на след уровень, не закончив».
 * Скриншота к нему нет, поэтому первым делом воспроизведение, а не починка.
 *
 * 📍 ЧТО НАШЛОСЬ. Экран объявлял победу по `goalMet`, а та смотрит ТОЛЬКО на доску.
 * С 56-го уровня полки закрываются и уходят, а сверху приходят отложенные из
 * очереди — там пустая доска означает не конец, а «текущие полки разобраны».
 * Ядро это знало и говорило прямо: в `isCleared` очередь и задние ряды учтены с
 * самого начала, и рядом записано «пустая доска при непустой очереди — не победа,
 * а промежуточное состояние». Знание было, а экран пользовался другой функцией.
 *
 * 📍 ЗАМЕР 08.09.2026: очередь есть на трёх уровнях из шестидесяти — L56 («убрать
 * всё»), L58 («убрать названные»), L59 («убрать всё»).
 */
import {
  levelWon, goalMet, goalPlan, queueSize, COLLAPSE_FROM,
} from '@/src/games/goods-sort/core/level';
import { isCleared } from '@/src/games/goods-sort/core/board';

declare function require(m: string): any;
declare const __dirname: string;

const ПУСТАЯ_ДОСКА = [[], [], [], []];
const ЦЕЛЬ_ВСЁ = { kind: 'all' as const };

describe('🔴 пустая доска при непустой очереди — не победа', () => {
  it('🔴 ровно жалоба be449226: доска разобрана, очередь ещё нет', () => {
    // Полки закрылись, доска чиста — но две полки лежат в очереди и ещё придут.
    const очередь = [{ cell: [1, 1, 1] }, { cell: [2, 2, 2] }];
    expect(goalMet(ПУСТАЯ_ДОСКА, ЦЕЛЬ_ВСЁ)).toBe(true);           // так думал экран
    expect(levelWon({ cells: ПУСТАЯ_ДОСКА, queue: очередь }, ЦЕЛЬ_ВСЁ)).toBe(false);
  });

  it('очередь опустела — уровень взят', () => {
    expect(levelWon({ cells: ПУСТАЯ_ДОСКА, queue: [], back: [[], []] }, ЦЕЛЬ_ВСЁ)).toBe(true);
    expect(levelWon({ cells: ПУСТАЯ_ДОСКА }, ЦЕЛЬ_ВСЁ)).toBe(true);   // уровня без очереди это не касается
  });

  it('задние ряды считаются так же: товар за полкой — ещё не убранный товар', () => {
    expect(levelWon({ cells: ПУСТАЯ_ДОСКА, queue: [], back: [[3, 3]] }, ЦЕЛЬ_ВСЁ)).toBe(false);
  });

  it('🔴 цель «убрать названные» тоже ждёт очередь', () => {
    // Названный товар может лежать в отложенной полке: убрать его с доски —
    // ещё не значит убрать с уровня.
    const цель = { kind: 'pick' as const, types: [7] };
    const доска = [[1, 2], [], [3]];
    expect(goalMet(доска, цель)).toBe(true);
    expect(levelWon({ cells: доска, queue: [{ cell: [7, 7, 7] }] }, цель)).toBe(false);
    expect(levelWon({ cells: доска, queue: [] }, цель)).toBe(true);
  });

  it('🔴 недоразобранная доска не становится победой от пустой очереди', () => {
    expect(levelWon({ cells: [[1], []], queue: [] }, ЦЕЛЬ_ВСЁ)).toBe(false);
  });
});

describe('экран и ядро считают победу ОДИНАКОВО', () => {
  /**
   * Расхождение этих двух функций и было дефектом: решатель доказывал решаемость
   * по `isCleared`, а экран заканчивал уровень по `goalMet`.
   */
  it('на цели «убрать всё» levelWon совпадает с isCleared ядра', () => {
    const случаи = [
      { cells: [[], []], queue: [], back: [] },
      { cells: [[], []], queue: [{ cell: [1, 1, 1] }], back: [] },
      { cells: [[1], []], queue: [], back: [] },
      { cells: [[], []], queue: [], back: [[2]] },
    ];
    for (const c of случаи) {
      const ядро = isCleared({ cells: c.cells, queue: c.queue, back: c.back } as any);
      const экран = levelWon(c, ЦЕЛЬ_ВСЁ);
      expect(`${JSON.stringify(c)} → ядро ${ядро}, экран ${экран}`)
        .toBe(`${JSON.stringify(c)} → ядро ${ядро}, экран ${ядро}`);
    }
  });
});

describe('замер: где очередь вообще бывает', () => {
  it('очередь появляется только со схлопывания полок и не раньше', () => {
    expect(COLLAPSE_FROM).toBe(56);
    for (let L = 1; L < 56; L++) expect(`L${L}: ${queueSize(L)}`).toBe(`L${L}: 0`);
    const сОчередью = [];
    for (let L = 1; L <= 60; L++) if (queueSize(L) > 0) сОчередью.push(`L${L}:${goalPlan(L).kind}`);
    expect(сОчередью.join(' ')).toBe('L56:all L58:pick L59:all');
  });
});

describe('🔴 ЭКРАН ЗОВЁТ ИМЕННО ЭТУ ФУНКЦИЮ', () => {
  /**
   * ⚠️ Единственное место набора, где смотрится исходник, — и это не лень.
   * Дефект был не в ядре: ядро считало верно с самого начала. Дефект был в том,
   * что ЭКРАН звал другую функцию. Проверка ядра такое пропускает по построению:
   * контрпроба «вернуть экрану goalMet» не покраснела ни на одной из семи проб
   * выше, пока этой проверки не было.
   *
   * Рендером не поставить: чтобы дойти до победы на 56-м уровне, нужна партия
   * на несколько десятков ходов с генерацией доски.
   */
  const { readFileSync } = require('fs');
  const { join } = require('path');
  const ЗДЕСЬ = __dirname;
  const код = (readFileSync(join(ЗДЕСЬ, '../../app/games/goods-sort.tsx'), 'utf8') as string)
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n').filter((l: string) => !l.trim().startsWith('//')).join('\n');

  it('победа объявляется через levelWon, а не через goalMet', () => {
    expect(`зовёт levelWon: ${/levelWon\(\{ cells:/.test(код)}`).toBe('зовёт levelWon: true');
    // и goalMet больше не решает исход хода
    expect(`goalMet решает исход: ${/if \(goalMet\([^)]*\)\) *\{?\s*setTimeout\(advanceLevel/.test(код)}`)
      .toBe('goalMet решает исход: false');
  });

  it('и очередь берётся из СВЕЖЕГО результата хода, а не из состояния экрана', () => {
    // `setОчередь` в том же обработчике ещё не применился: по нему уровень
    // засчитался бы на ход раньше — тот же дефект с другого конца.
    expect(`очередь из результата хода: ${/queue: послеХода\.queue/.test(код)}`)
      .toBe('очередь из результата хода: true');
  });
});
