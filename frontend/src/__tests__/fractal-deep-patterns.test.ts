/**
 * УЗОР ПОДСКАЗОК В «БЕЗДНЕ» НЕ ПОВТОРЯЕТСЯ, А ДОСКА ОСТАЁТСЯ ЧЕСТНОЙ.
 *
 * 🔴 ЗАЧЕМ. Замер 16.09.2026: первые 400 узлов партии `abyss` давали ровно 40 РАЗНЫХ
 * узоров — каждый повторялся десять раз, на полной партии в 2848 узлов это около
 * семидесяти повторов. Причина в устройстве: банк отдаёт до 40 досок на полосу, а
 * выбор брал строку и отдавал как есть. Цифры менялись (обмен ради кормящей), но
 * перестановка цифр не двигает подсказки — человек видел один рисунок раз за разом.
 *
 * Лечится автоморфизмом (перестановка строк/полос/столбцов/стопок и транспонирование):
 * узор меняется, а валидность, единственность и рейтинг сохраняются по построению.
 * Этот гейт сторожит ОБЕ половины: и что узоры разные, и что доска не испортилась.
 */
import { materializePick, materializeNode, childPath, DEEP_N, type DeepCfg } from '@/src/services/fractal-deep';
import { countSolutions, type Cell } from '@/src/services/sudoku-core';
import { BANK_BR, BANK_BC } from '@/src/services/sudoku-bank';

jest.setTimeout(300000);

const CFG: DeepCfg = { depth: 3, feedCount: 'all', rating: 1.7, unlockShare: 0.24 };
const узор = (p: { puzzle: Cell[][] }) => p.puzzle.map((r) => r.map((v) => (v ? '#' : '.')).join('')).join('');

/** Первые N узлов партии обходом вширь: корень, его дети, дети детей. */
function узлы(seed: string, сколько: number) {
  const out = [materializePick(seed, '', CFG)];
  const корень = out[0]!;
  outer: for (const [r, c] of корень.feedCells) {
    const путь = childPath('', r, c);
    const дитя = materializePick(seed, путь, CFG);
    out.push(дитя);
    for (const [rr, cc] of дитя.feedCells) {
      out.push(materializePick(seed, childPath(путь, rr, cc), CFG));
      if (out.length >= сколько) break outer;
    }
  }
  return out;
}

/** Известная доля на 16.09.2026 — 100% разных. Менять ТОЛЬКО в большую сторону. */
const ИЗВЕСТНО_РАЗНЫХ = 100;

describe('узор подсказок в Бездне', () => {
  it(`🔴 узоры не повторяются (было 40 из 400, стало ${ИЗВЕСТНО_РАЗНЫХ}%)`, () => {
    const ряд = узлы('гейт-узора', 400);
    const доля = Math.round((new Set(ряд.map(узор)).size / ряд.length) * 100);
    expect(`разных ${доля}% при известных ${ИЗВЕСТНО_РАЗНЫХ}%`)
      .toBe(`разных ${Math.max(доля, ИЗВЕСТНО_РАЗНЫХ)}% при известных ${ИЗВЕСТНО_РАЗНЫХ}%`);
    // Обратная сторона храповика: выросло — опусти планку, чтобы достижение закрепилось.
    expect(`известно ${ИЗВЕСТНО_РАЗНЫХ}, фактически ${доля}`).toBe(`известно ${доля}, фактически ${доля}`);
  });

  it('🔴 узел при повторном входе приходит ТЕМ ЖЕ — иначе рука встанет на чужие клетки', () => {
    const расхождения: string[] = [];
    for (const путь of ['', '0,1', '4,4', '0,1/2,3']) {
      const a = materializePick('детерминизм', путь, CFG);
      const b = materializePick('детерминизм', путь, CFG);
      if (узор(a) !== узор(b)) расхождения.push(путь || 'корень');
    }
    expect(`разошлись: ${расхождения.join(' ') || 'нет'}`).toBe('разошлись: нет');
  });

  it('🔴 разные зёрна дают разные доски — тасовка не залипла на одной перестановке', () => {
    const виды = new Set(['з1', 'з2', 'з3', 'з4'].map((s) => узор(materializePick(s, '', CFG))));
    expect(`разных видов ${виды.size} из 4`).toBe('разных видов 4 из 4');
  });

  /**
   * 🔴 ГЛАВНОЕ: ПЕРЕТАСОВКА НЕ ПОРТИТ ДОСКУ. Автоморфизм обязан сохранять
   * единственность решения — проверяем перебором на самой выданной доске, а не
   * рассуждением про свойства перестановок.
   */
  it('🔴 у выданной доски ровно одно решение', () => {
    const плохие: string[] = [];
    for (const путь of ['', '0,1', '4,4']) {
      const узел = materializeNode('единственность', путь, CFG, 0);
      const проба = узел.puzzle.map((row) => [...row]);
      const n = countSolutions(проба, DEEP_N, BANK_BR, BANK_BC, 'none', undefined, 2, { steps: 80000 });
      if (n !== 1) плохие.push(`${путь || 'корень'}:${n}`);
    }
    expect(`не единственных: ${плохие.join(' ') || 'нет'}`).toBe('не единственных: нет');
  });

  it('есть что мерить — иначе проба зелена вслепую', () => {
    expect(`узлов в выборке ${узлы('контроль', 400).length}`).toBe('узлов в выборке 400');
  });
});
