import { КЛЮЧ_ИМЕНИ, КЛЮЧ_ОПИСАНИЯ, ИМЯ_ВТОРОГО } from '@/src/games/tatham-bridge/names';
import { РЕЖИМЫ_РАЗДЕЛА as СЧЁТ } from '@/src/games/tatham-bridge/sections/counting';
import { РЕЖИМЫ_РАЗДЕЛА as ПОИСК } from '@/src/games/tatham-bridge/sections/search';
import { HELP_MAP } from '@/src/constants/helpMap';
import { LANGUAGES, translateFor } from '@/src/contexts/LanguageContext';

const МОИ = [...Object.keys(СЧЁТ), ...Object.keys(ПОИСК)];
const ключСправки = (режим: string): string => HELP_MAP[`/games/puzzles?mode=${режим}`]?.introKey ?? '';

describe('🔴 справка головоломок «Счёта» и «Поиска»', () => {
  it('есть что проверять: двенадцать режимов двух разделов', () => {
    expect(МОИ.length).toBe(12);
  });

  it('🔴 карта ведёт каждый режим на его СВОЙ текст, а не на строку задания', () => {
    const без = МОИ.filter((р) => ключСправки(р) !== `${КЛЮЧ_ИМЕНИ[р]}IntroDesc`)
      .map((р) => `${р} → ${ключСправки(р) || '—'}`);
    expect(без).toEqual([]);
  });

  it('🔴 текст есть на всех двенадцати языках и переведён, а не упал на английский', () => {
    const дыры: string[] = [];
    for (const р of МОИ) {
      const ключ = ключСправки(р), en = translateFor('en', ключ);
      for (const { code } of LANGUAGES) {
        const текст = translateFor(code, ключ);
        if (текст === ключ) дыры.push(`${code}: нет ${ключ}`);
        else if (code !== 'en' && текст === en) дыры.push(`${code}: ${ключ} — английский текст`);
      }
    }
    expect(дыры.slice(0, 5)).toEqual([]);
  });

  it('🔴 справка называет кнопку второго действия этого режима — теми же словами, что на кнопке', () => {
    // Без второго действия три режима не засчитываются никогда (белые «Японского кроссворда» и «Мозаики»,
    // пустые домино «Магнитов») — человек должен знать, какую кнопку жать, на своём языке.
    const немые: string[] = [];
    for (const р of МОИ) {
      const кнопка = ИМЯ_ВТОРОГО[р];
      if (!кнопка) { немые.push(`${р}: у режима нет второго действия`); continue; }
      for (const { code } of LANGUAGES) {
        const подпись = translateFor(code, кнопка);
        if (!translateFor(code, ключСправки(р)).includes(подпись)) немые.push(`${code} ${р}: нет «${подпись}»`);
      }
    }
    expect(немые.slice(0, 5)).toEqual([]);
  });

  it('🔴 «Частокол» называет размер области на каждом поле авторской лестницы', () => {
    // palisade.c presets: 5x5n5, 8x6n6, 10x8n8, 15x12n10. На доске размер не виден — только в справке.
    const поля = ['5×5', '8×6', '10×8', '15×12'];
    const пропуски = LANGUAGES.flatMap(({ code }) => поля
      .filter((п) => !translateFor(code, ключСправки('Palisade')).includes(п)).map((п) => `${code}: ${п}`));
    expect(пропуски).toEqual([]);
  });

  it('строка задания над доской влезает в три строки (стиль rule: кегль 13, ширина 320, высота 54)', () => {
    // Живой замер 17.09.2026 на сборке, 360 точек, 12 режимов × 12 языков: кириллица шире латиницы —
    // ru 130 и 136 знаков резались многоточием на четвёртой строке, ru 129 («Прямоугольники») влезал; латиница
    // до 149 влезала (en «Раскраска карты»). Прежние ru «Домино» 149 и «Раскраска карты» 154 тоже резались —
    // сокращены. Предел — заместитель живого замера (перенос зависит от длины слов), не сам замер.
    const предел = (code: string) => (code === 'ru' ? 129 : 150);
    const длинные = МОИ.flatMap((р) => LANGUAGES
      .map(({ code }) => [code, translateFor(code, КЛЮЧ_ОПИСАНИЯ[р])] as const)
      .filter(([code, текст]) => текст.length > предел(code))
      .map(([code, текст]) => `${code} ${р}: ${текст.length}`));
    expect(длинные).toEqual([]);
  });
});
