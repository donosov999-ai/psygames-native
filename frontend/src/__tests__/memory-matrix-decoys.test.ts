/**
 * 🔴 ОСЬ 5 — ЛОЖНЫЕ ВСПЫШКИ. Клетки, которые загораются и которые НЕ надо запоминать.
 *
 * ЗАЧЕМ. Объём упёрся в физику поля: при двух сериях на 6×6 зажим — 17 клеток, и
 * с L21 их число не растёт (39 уровней-клонов по полю). Сетку не трогаем: 7×7 лишь
 * переносит плато на L32 и уводит дальше от нормы (уже на L11 просят 20 объектов
 * при норме 5±2). Ложные вспышки растят нагрузку не объёмом, а необходимостью
 * отделять нужное от ненужного: держать столько же, а входящего потока больше.
 *
 * ⚠️ ЧЕГО ЭТА ПРОБА НЕ ДОКАЗЫВАЕТ. Что ложные действительно ПОКАЗЫВАЮТСЯ и что тап
 * по ним считается ошибкой — это исполнение, его меряет игровой прогон
 * `span-chat/probe/playthrough.mjs`. Здесь проверяется объявление и — главное —
 * что ложные физически помещаются в свободные клетки.
 */
import { levelParams, MM_VOLUME_TOP, DECOY_ROOM, cellsNeeded } from '@/app/games/memory-matrix';

/**
 * 🔴 БЕРЁМ РАСЧЁТ ИЗ ЭКРАНА, А НЕ СВОЮ КОПИЮ. Сначала здесь стояла копия — и мутация
 * экрана (убрать резерв места под ложные) НЕ покрасила пробу: копия осталась прежней.
 * Четвёртый за день случай «гейт мерит объявление вместо исполнения», и мой.
 */
const занято = (level: number, mode: 'static' | 'sequential') => {
  const g = levelParams(level).gridSize ** 2;
  return g - cellsNeeded(level, 1, mode).free;
};

describe('memory-matrix: ложные вспышки', () => {
  it('ниже плато ложных нет — прежняя полоса не тронута', () => {
    for (let L = 1; L <= MM_VOLUME_TOP; L++) {
      expect(`L${L} ложных=${levelParams(L).decoys}`).toBe(`L${L} ложных=0`);
    }
  });

  it('🔴 выше плато число ложных растёт — до отведённого им места', () => {
    for (let L = MM_VOLUME_TOP + 1; L <= MM_VOLUME_TOP + DECOY_ROOM; L++) {
      expect(`L${L}: ${levelParams(L).decoys}`).toBe(`L${L}: ${levelParams(L - 1).decoys + 1}`);
    }
  });

  /**
   * 🔴 И ГЛАВНОЕ: ложные НЕ УБЫВАЮТ. Первая версия оси именно это и делала —
   * с L20 их становилось 4, потом 2, потому что нужные клетки вытесняли их с поля.
   * Откат сложности хуже плато: игрок проходит уровень, и следующий оказывается легче.
   */
  it('🔴 число ложных ни на одном уровне не падает', () => {
    const упало: string[] = [];
    for (let L = 2; L <= 60; L++) {
      if (levelParams(L).decoys < levelParams(L - 1).decoys) упало.push(`L${L}`);
    }
    expect(`уровней с откатом: ${упало.length}`).toBe('уровней с откатом: 0');
  });

  /**
   * 🔴 ГЛАВНОЕ И САМОЕ ЛОМКОЕ. Ложные берутся из СВОБОДНЫХ клеток: клетка не может
   * быть одновременно нужной и ложной, иначе ответ становится неоднозначным и проба
   * перестаёт измерять. Значит просить их больше, чем осталось, бессмысленно —
   * `newRound` обрежет. Проба показывает, с какого уровня заказ перестаёт влезать.
   */
  it('🔴 сколько ложных реально влезает — и это число НЕ ноль там, где ось работает', () => {
    const first = MM_VOLUME_TOP + 1;
    const свободно = (L: number) => levelParams(L).gridSize ** 2 - занято(L, 'static');
    expect(`на L${first} просим ${levelParams(first).decoys}, влезает ${Math.min(levelParams(first).decoys, свободно(first))}`)
      .toBe(`на L${first} просим 1, влезает 1`);
    /**
     * ⚠️ ЗАМЕР, КОТОРЫЙ МЕНЯ ОСТАНОВИЛ. Без резерва свободных клеток было: L16 → 10,
     * L19 → 6, L20 → 4, L21 и выше → 2. Ложные вытеснялись нужными, и их число
     * ПАДАЛО. Теперь место отведено заранее, и заказ всегда помещается целиком.
     */
    for (let L = first; L <= 60; L++) {
      expect(`L${L}: просим ${levelParams(L).decoys}, свободно ${свободно(L)}`)
        .toBe(`L${L}: просим ${levelParams(L).decoys}, свободно ${Math.max(свободно(L), levelParams(L).decoys)}`);
    }
  });
});
