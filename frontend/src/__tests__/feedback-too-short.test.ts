/**
 * ОБРЫВОК ДИКТОВКИ НЕ УХОДИТ КАК ОТЧЁТ.
 *
 * 🔴 ЗАМЕР 04.09.2026 ПО БОЕВОЙ БАЗЕ. Из 14 открытых отчётов СЕМЬ были обрывками:
 * «I», «The», «I have», «I don’t». У всех семи пустой `audio_path` — то есть это
 * не сорванная расшифровка голосовой заметки, а текст: диктовка клавиатуры
 * успела записать первое слово, палец попал в «Отправить». Половина ленты
 * отчётов оказалась шумом, и настоящие сообщения тонули в нём.
 *
 * ⚠️ ПОРОГ ПРОВЕРЯЕТСЯ НА НАСТОЯЩИХ СТРОКАХ, А НЕ НА ВЫДУМАННЫХ. Ниже — ровно
 * те тексты, что лежат в базе: слева семь обрывков, справа настоящие отчёты
 * Дениса. Порог обязан разделить их без единой ошибки в обе стороны; выдуманный
 * пример «мелко» такой проверкой не является.
 */
import { похожеНаОбрывок, МИН_СЛОВ, МИН_СИМВОЛОВ } from '@/src/services/feedbackTooShort';

declare function require(m: string): any;
declare const __dirname: string;

/** Ровно те строки, что лежали в базе 04.09.2026 со статусом new. */
const ОБРЫВКИ = ['I', 'The', 'I have', 'I don’t', 'I', 'I', 'I'];
const НАСТОЯЩИЕ = [
  'В хаб конфликт внимания',
  'Это тоже в хаб надо Торможение',
  'Питомец мелкий надо увеличить в шапке его',
  'Подсветка не видно нихуя, какую фигуру выделять',
  'Надо чтобы когда выбрал автоматом фиксировал, без лишнего нажатия кнопки',
];

describe('обрывок диктовки', () => {
  it('🔴 все семь обрывков из базы опознаны', () => {
    const пропущены = ОБРЫВКИ.filter((s) => !похожеНаОбрывок(s, false));
    expect(пропущены).toEqual([]);
  });

  it('🔴 ни один настоящий отчёт не задет', () => {
    const задеты = НАСТОЯЩИЕ.filter((s) => похожеНаОбрывок(s, false));
    expect(задеты).toEqual([]);
  });

  it('🔴 с голосовой записью текст не судим: смысл в записи', () => {
    // «[голосом, без текста]» — штатная пометка, и она короче порога
    expect(похожеНаОбрывок('I', true)).toBe(false);
    expect(похожеНаОбрывок('', true)).toBe(false);
  });

  it('🔴 пустое поле ловит другое условие, не это', () => {
    expect(похожеНаОбрывок('', false)).toBe(false);
    expect(похожеНаОбрывок('   ', false)).toBe(false);
  });

  it('🔴 порог стоит в зазоре между обрывками и отчётами', () => {
    const слов = (s: string) => s.trim().split(/\s+/).filter(Boolean).length;
    const худшийОбрывок = Math.max(...ОБРЫВКИ.map(слов));
    const лучшийОтчёт = Math.min(...НАСТОЯЩИЕ.map(слов));
    expect(`обрывки до ${худшийОбрывок} слов, отчёты от ${лучшийОтчёт}`)
      .toBe(`обрывки до 2 слов, отчёты от 4`);
    expect(МИН_СЛОВ).toBeGreaterThan(худшийОбрывок);
    expect(МИН_СЛОВ).toBeLessThanOrEqual(лучшийОтчёт);
    expect(МИН_СИМВОЛОВ).toBeGreaterThan(Math.max(...ОБРЫВКИ.map((s) => s.length)));
  });

  it('🔴 виджет СПРАШИВАЕТ, а не запрещает: развилка, а не отключённая кнопка', () => {
    const fs = require('fs');
    const path = require('path');
    const виджет: string = fs.readFileSync(
      path.join(__dirname, '../components/FeedbackWidget.tsx'), 'utf8');
    expect(виджет).toContain('askShort');
    // у развилки обязан быть выход «отправить как есть» — иначе это запрет
    expect(виджет).toContain('submit(false, true)');
    expect(виджет).toContain('voiceSendAnyway');
  });
});
