/**
 * Пролёт значения пропа: `<имя>={ … }` со сбалансированными скобками.
 * Берём именно пролёт, а не «строку рядом»: комментарий-обоснование, который мы
 * пишем ПЕРЕД пропом, в него не попадает и гейт на собственных объяснениях
 * не срабатывает.
 */
function propSpan(src: string, name: string): string | null {
  const at = src.search(new RegExp(`\\n\\s*${name}=\\{`));
  if (at < 0) return null;
  const open = src.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(open, i + 1);
  }
  return null;
}

/** Есть ли у игры нижняя полоса. `toolbar={undefined}` — это её отсутствие. */
function hasBottomStrip(f: string): boolean {
  const span = propSpan(game(f), 'toolbar');
  return span !== null && span.replace(/\s/g, '') !== '{undefined}';
}

