/**
 * КЛАВИШ СТОЛЬКО, СКОЛЬКО НУЖНО ЭТОЙ ДОСКЕ — ИНАЧЕ СТУПЕНЬ НЕПРОХОДИМА.
 *
 * 🔴 ПОВОД. Доска открывается по НАШЕЙ лестнице (`лестницаДвижка`), а цифровой ряд
 * на main a34a2dd7 считался по АВТОРСКОЙ (`движок?.ступени?.[ступень]`). Кадр 16.09.2026:
 * «Судоку Тэтхэма», шаг 1/5, доска 9×9 с 28 подсказками — и клавиши «1 2 3 4».
 *
 * 📍 РАЗМАХ, посчитан настоящей `клавишДоски` по пресетам автора, снятым из моста
 * (`psy_preset_params`) 16.09.2026: неверное число клавиш на 5 ступенях из 30 —
 *   Solo 1: доска 9×9, клавиш давалось 4 · Solo 2: 9×9, давалось 6 ·
 *   Keen 3: 6×6, давалось 5 · Unequal 4: 6×6, давалось 5 · Unequal 5: 7×7, давалось 5.
 * Каждая из пяти НЕПРОХОДИМА: недостающую цифру ввести нечем — ни клавишей, ни тапом.
 *
 * ⚠️ ДВЕ ПРОБЫ РАЗНОГО РОДА, и обе нужны.
 *   · Проводка — читает исходник экрана: ряд обязан брать параметры из `ступени`,
 *     той же лестницы, что и доска. Это ровно то место, где жил дефект.
 *   · Поведение — исполняет `клавишДоски` на КАЖДОЙ нашей ступени и сверяет с тем,
 *     сколько цифр нужно доске, выведенным из параметров НЕЗАВИСИМО. Ловит поломку
 *     самой функции или ступень, у которой размер не читается.
 */
import { СВОЯ_ЛЕСТНИЦА, ЦИФРОВЫЕ, клавишДоски } from '@/src/games/tatham-bridge/names';

declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');

const ЭКРАН = fs.readFileSync(path.join(__dirname, '../../app/games/puzzles.tsx'), 'utf8') as string;
const МОИ = ['Solo', 'Towers', 'Unequal', 'Keen', 'Singles', 'Filling', 'Undead'] as const;

/** Сколько РАЗНЫХ цифр вписывается на доску — выведено из параметров, без `клавишДоски`. */
function нужноЦифр(имя: string, п: string): number {
  if (имя === 'Undead') return 3;            // призрак, вампир, зомби — undead.c
  if (имя === 'Filling') return 9;           // число — размер области, до девяти
  const блоки = /^(\d+)\s*x\s*(\d+)/i.exec(п);
  if (имя === 'Solo') return блоки ? Number(блоки[1]) * Number(блоки[2]) : 0;  // 3x3 = поле 9×9
  const сторона = /^(\d+)/.exec(п);
  return сторона ? Number(сторона[1]) : 0;   // Towers/Unequal/Keen: цифры 1..сторона
}

describe('цифровой ряд совпадает с доской', () => {
  it('есть что мерить: у каждой из семи своя лестница', () => {
    const пустые = МОИ.filter((m) => !(СВОЯ_ЛЕСТНИЦА[m]?.length));
    expect(`без лестницы: ${пустые.join(' ') || 'нет'}`).toBe('без лестницы: нет');
  });

  it('🔴 ПРОВОДКА: ряд берёт параметры из той же лестницы, что и доска', () => {
    /**
     * ⚠️ Берём СТРОКУ вызова целиком, а не `клавишДоски\([^)]*\)`: внутри вызова стоит
     * `лестницаДвижка(...)`, и регулярка по первой скобке обрезала бы его на середине.
     * ⚠️ Форма `лестницаДвижка(имяРежима, …)[ступень]`, а не локальное `ступени[ступень]`,
     * выбрана замером: чтение локального `ступени` в разметке добавляло 6 ошибок
     * `react-hooks/preserve-manual-memoization` (1 → 7 по файлу), чистая функция модуля — ноль.
     */
    const строки = ЭКРАН.split('\n').filter((с) => с.includes('клавишДоски(') && !/^\s*(\*|\/\/|\{\/\*)/.test(с));
    expect(`строк с вызовом клавишДоски: ${строки.length}`).toBe('строк с вызовом клавишДоски: 1');
    const вызов = строки[0] ?? '';
    expect(`читает авторскую ступень напрямую: ${/движок\??\.ступени\??\.\[ступень\]/.test(вызов)}`)
      .toBe('читает авторскую ступень напрямую: false');
    expect(`идёт через лестницаДвижка: ${/лестницаДвижка\(имяРежима,/.test(вызов)}`)
      .toBe('идёт через лестницаДвижка: true');
    // и доска открывается через ту же функцию — иначе совпадение источников случайно
    expect(`доска через лестницаДвижка: ${/const ступени = движок\s*\?\s*лестницаДвижка\(/.test(ЭКРАН)}`)
      .toBe('доска через лестницаДвижка: true');
  });

  it('🔴 ПОВЕДЕНИЕ: на каждой нашей ступени клавиш ровно столько, сколько цифр нужно доске', () => {
    const врут: string[] = [];
    let проверено = 0;
    for (const m of МОИ) {
      if (!ЦИФРОВЫЕ.has(m)) continue;
      (СВОЯ_ЛЕСТНИЦА[m] ?? []).forEach((ш, i) => {
        проверено++;
        const надо = нужноЦифр(m, ш.параметры), дают = клавишДоски(m, ш.параметры);
        if (!надо || надо !== дают) врут.push(`${m} ст.${i + 1} ${ш.параметры}: надо ${надо}, дают ${дают}`);
      });
    }
    expect(`проверено ступеней: ${проверено > 20}`).toBe('проверено ступеней: true');
    expect(`расходятся: ${врут.join(' · ') || 'нет'}`).toBe('расходятся: нет');
  });

  it('у «Лишних чисел» цифрового ряда нет и не должно быть — доска приходит заполненной', () => {
    expect(`Singles в ЦИФРОВЫЕ: ${ЦИФРОВЫЕ.has('Singles')}`).toBe('Singles в ЦИФРОВЫЕ: false');
  });
});
