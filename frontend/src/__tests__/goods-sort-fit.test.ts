/**
 * ТОВАРЫ НЕ ВЫЛЕЗАЮТ ИЗ ЯЧЕЙКИ НИ НА ОДНОМ ЭКРАНЕ.
 *
 * ЗАЧЕМ. Репорт тестировщицы 18.08.2026 со скриншотом: «Половина банок обрезана».
 * Причина считалась ровно: уровень 8 → сетка 4×3, экран 386px → полка 362px →
 * ячейка 79px. В ячейку честно влезал товар 23px, но стоял пол `Math.max(40, …)`,
 * и бралось 40px. Три товара = 3×40 + два зазора = 128px в ячейке 79px, ряд
 * центрирован → по 24px под обрез с каждой стороны.
 *
 * ⚠️ ПОЛ РАЗМЕРА СТАВИЛСЯ РАДИ ПОПАДАНИЯ ПАЛЬЦЕМ — намерение верное, но он не
 * спрашивал, влезут ли три. По обрезанному товару попасть всё равно нельзя,
 * так что такой минимум не помогал, а мешал.
 *
 * 🔴 ЗДЕСЬ БОЛЬШЕ НЕТ СВОЕЙ АРИФМЕТИКИ — ЗОВЁТСЯ ФОРМУЛА САМОЙ ИГРЫ.
 *
 * Прежняя редакция ПОВТОРЯЛА расчёт у себя, и к 02.09.2026 копия отстала молча:
 * в тесте оставались `width - 24`, потолок товара 112 и рама 7, тогда как игра
 * давно считала по `width - 20`, потолку 148 и раме 9. Тест при этом был
 * зелёный — он добросовестно проверял формулу, которой в игре нет.
 *
 * Теперь раскладка вынесена в `gsLayout` (см. `app/games/goods-sort.tsx`), и
 * проверяется ровно то, что рисуется. Разойтись стало нечему.
 */
import { gridFor, gsLayout } from '../../app/games/goods-sort';

declare const __dirname: string;
declare function require(m: string): any;

const CAP = 3;
const CELL_GAP = 2;

/** Ширины: iPhone SE, типовой Android, её экран, iPhone Pro Max, планшет. */
const WIDTHS = [320, 360, 386, 414, 430, 768, 1024];
/** Сетки берутся из gridFor игры — список руками отставал (см. ниже). */
/**
 * 🔴 СЕТКИ БЕРУТСЯ ИЗ `gridFor`, А НЕ ПЕРЕПИСЫВАЮТСЯ РУКАМИ.
 *
 * 📍 Список был написан руками и не содержал 3×6 — а именно её игра выдаёт с
 * 12-го уровня на любом телефоне (`gridFor(12, true)`). Гейт «шкаф не вылезает
 * за поле» шесть недель мерил пять сеток из шести и молчал, пока Валя не
 * прислала 05.09.2026 скриншот с обрезанным нижним рядом и словами «кошмар
 * просто кошмар».
 *
 * Список, переписанный руками, отстаёт от кода молча: добавили ряд в `gridFor`
 * — гейт об этом не узнал. Поэтому сетки теперь ПРОИЗВОДЯТСЯ из той же
 * функции, что и в игре, по всем уровням до сотого.
 */
const GRIDS = (() => {
  const набор = new Map<string, { cols: number; rows: number }>();
  for (let L = 1; L <= 100; L++) {
    for (const narrow of [false, true]) {
      const g = gridFor(L, narrow);
      набор.set(`${g.cols}x${g.rows}`, g);
    }
  }
  return [...набор.values()];
})();

/**
 * Тонкая обёртка над формулой игры. `rowWidth` берётся ИЗ НЕЁ ЖЕ: 02.09.2026
 * товары поставили внахлёст, и своя формула ширины ряда в тесте сразу же дала
 * ложное «не влезает» на 25 сочетаниях — она считала по-старому, встык.
 */
function layout(width: number, cols: number, rows: number, height = 800, hintH?: number) {
  const availH = Math.max(180, height - 360);
  const l = gsLayout(width, availH, cols, rows, CAP, hintH);
  return { ...l, availH, rowWidth: l.rowW };
}

describe('сортировка товаров: раскладка', () => {
  it('три товара помещаются в ячейку на любой ширине и любой сетке', () => {
    const bad: string[] = [];
    for (const w of WIDTHS) {
      for (const g of GRIDS) {
        const l = layout(w, g.cols, g.rows);
        if (l.rowWidth > l.cellW) {
          bad.push(`${w}px, ${g.cols}×${g.rows}: ряд ${l.rowWidth} > ячейки ${l.cellW}`);
        }
      }
    }
    expect(bad).toEqual([]);
  });

  /** Её случай, поимённо — чтобы регрессия была узнаваемой. */
  /**
   * Её случай, поимённо. После разрежения сетки (19.08) на телефоне колонок
   * три, а не четыре: товар вырос с 23px до 36px. 23px — это размер, при
   * котором нарисованная в 384px жестянка видна цветным пятном, и никакая
   * перерисовка этого не лечит.
   */
  it('экран 386px: товар крупнее 30px и ряд влезает', () => {
    const l = layout(386, 3, 4);
    expect(l.itemSize).toBeGreaterThanOrEqual(30);
    expect(l.rowWidth).toBeLessThanOrEqual(l.cellW);
  });

  it('на телефоне колонок не больше трёх', () => {
    const src = require('fs').readFileSync(
      require('path').join(__dirname, '../../app/games/goods-sort.tsx'), 'utf8') as string;
    expect(src).toMatch(/function gridFor\(L: number, narrow = false\)/);
    expect(src).toMatch(/narrowRef\.current = width < 560/);
  });

  /** Размер считается от ниши, а не от зашитого пола. Проверяем поведением. */
  it('товар растёт вместе с нишей, а не упирается в фиксированный пол', () => {
    const узкий = layout(320, 3, 4);
    const широкий = layout(1024, 3, 4);
    expect(широкий.itemSize).toBeGreaterThan(узкий.itemSize);
    expect(узкий.rowWidth).toBeLessThanOrEqual(узкий.cellW);
  });

  /**
   * 🔴 ШКАФ ЗАНИМАЕТ ПОЛЕ, А НЕ ТРЕТЬ ЕГО.
   *
   * Замер живьём 02.09.2026 (psy-games.pro/play, окно 604×817): поле отдавало
   * шкафу 629 px, шкаф занимал 414 — 215 px пустоты сверху и снизу. Причиной
   * был потолок высоты ниши (1,25 × товара): избыток высоты оставался ВОКРУГ
   * короба комками. Денису это видно первым: «ужать пустоты».
   *
   * Порог 75 % — не идеал вёрстки, а граница «пусто/плотно»: при 1,25 выходило
   * 66 %, при нынешних 1,9 — около 94 %. Мутация «верни 1,25» краснит гейт.
   */
  /**
   * 🔴 ШКАФ ЗАНИМАЕТ ПОЛЕ, А НЕ ТРЕТЬ ЕГО.
   *
   * Замер живьём 02.09.2026 (psy-games.pro/play, окно 604×817): поле отдавало
   * шкафу 629 px, шкаф занимал 414 — 215 px пустоты сверху и снизу. Причиной
   * был потолок высоты ниши (1,25 × товара): избыток высоты оставался ВОКРУГ
   * короба комками. Денису это видно первым: «ужать пустоты».
   *
   * ⚠️ ЭКРАНЫ БЕРЁМ РЕАЛЬНЫЕ, А НЕ ДЕКАРТОВО ПРОИЗВЕДЕНИЕ. Первая редакция
   * перебирала все ширины со всеми высотами и краснела на паре 390×1100 —
   * узкий телефон высотой с планшет. Такого устройства нет, а сетка 4 колонки
   * на ширине 390 не выдаётся вовсе (`narrowRef.current = width < 560`).
   * Гейт, срабатывающий на невозможном сочетании, заставляет чинить призрак.
   */
  const ЭКРАНЫ = [
    { w: 360, h: 800, имя: 'Android' },
    { w: 390, h: 844, имя: 'iPhone' },
    { w: 430, h: 932, имя: 'iPhone Pro Max' },
    { w: 604, h: 817, имя: 'замер 02.09' },
    { w: 768, h: 1024, имя: 'iPad' },
    { w: 1280, h: 800, имя: 'десктоп' },
  ];
  /** Сетки, которые экран реально получает: узкий (<560) — не более трёх колонок. */
  const сеткиДля = (w: number) => GRIDS.filter((g) => (w < 560 ? g.cols <= 3 : true));

  it('сетки взяты из игры', () => { console.log('СЕТКИ:', GRIDS.map(g=>g.cols+'x'+g.rows).join(' ')); expect(GRIDS.length).toBeGreaterThan(4); });

  it('🔴 шкаф заполняет доступную высоту, а не оставляет её воздухом', () => {
    const плохо: string[] = [];
    for (const э of ЭКРАНЫ) {
      for (const g of сеткиДля(э.w)) {
        const l = layout(э.w, g.cols, g.rows, э.h);
        const доля = l.shelfH / l.availH;
        if (доля < 0.75) плохо.push(`${э.имя} ${э.w}×${э.h}, ${g.cols}×${g.rows}: шкаф ${l.shelfH} из ${l.availH} (${Math.round(доля * 100)} %)`);
      }
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 СТРОКА ЦЕЛИ БЫВАЕТ ВЫСОКОЙ, И ШКАФ ОБЯЗАН ЭТО ПЕРЕЖИТЬ.
   *
   * 📍 Отчёт Вали 05.09.2026 со скриншотом обрезанного нижнего ряда: «кошмар
   * просто кошмар». Причина — постоянные 44 px на строку цели при измеренном
   * поле: у цели «собрать тройки» рядом стоят значки товаров 16×26, строка
   * умеет переноситься, а в русском текст длиннее английского. Меряем крайние
   * случаи: одна строка (28), одна со значками (56), две со значками (92).
   */
  it('🔴 шкаф не режется, когда строка цели в две строки со значками', () => {
    const плохо: string[] = [];
    for (const э of ЭКРАНЫ) {
      for (const g of сеткиДля(э.w)) {
        for (const h of [28, 44, 56, 92]) {
          const l = layout(э.w, g.cols, g.rows, э.h, h);
          if (l.shelfH > l.availH - h + 44) {
            плохо.push(`${э.имя}, ${g.cols}×${g.rows}, цель ${h}px: шкаф ${l.shelfH} при поле ${l.availH}`);
          }
        }
      }
    }
    expect(плохо).toEqual([]);
  });

  it('шкаф не вылезает за поле ни на одном экране', () => {
    const плохо: string[] = [];
    for (const э of ЭКРАНЫ) {
      for (const g of сеткиДля(э.w)) {
        const l = layout(э.w, g.cols, g.rows, э.h);
        if (l.shelfH > l.availH) плохо.push(`${э.имя}, ${g.cols}×${g.rows}: шкаф ${l.shelfH} > поля ${l.availH}`);
      }
    }
    expect(плохо).toEqual([]);
  });
});
