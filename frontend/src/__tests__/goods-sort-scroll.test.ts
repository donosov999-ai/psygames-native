/**
 * ВИТРИНА НА ДВА-ТРИ ЭКРАНА (§4.4 ТЗ) — И ТРИ ВОЗРАЖЕНИЯ РАЗБОРА §4а.
 *
 * 🔴 ТЗ РАЗРЕШАЕТ ЭТУ ОСЬ, НО ТРЕБУЕТ ЗАКРЫТЬ ВОЗРАЖЕНИЯ, А НЕ ОБОЙТИ ИХ.
 * Дословно их было три, и каждое здесь либо проверяется, либо опровергнуто
 * замером — с числом, а не словами.
 *
 * ВОЗРАЖЕНИЕ 1: «при 10 рядах товар ужимается до 18 точек — нужна мини-карта».
 *   ЗАМЕР 06.09.2026 ДО правки, телефон 390×844, поле 484:
 *     рядов  6 → товар 31 px      рядов  8 → товар 21 px
 *     рядов  7 → товар 25 px      рядов 10 → товар 18 px
 *   Возражение верно до знака: пол был зашит как `Math.max(18, …)`, и товар
 *   доходил до него ровно на десяти рядах, а читаемых 30 терял уже на седьмом.
 *   ЗАКРЫТО ДВУМЯ ВЕЩАМИ: пол поднят до `ITEM_FLOOR = 30` (ужиматься больше
 *   нечему — вместо этого растёт шкаф), и добавлена мини-карта. Оба сторожатся
 *   ниже ИСПОЛНЕНИЕМ.
 *
 * ВОЗРАЖЕНИЕ 2: «возвращается дефект „перетаскивание лагает“ — замерь FPS до и
 *   после». ЗАМЕРЕНО в живом Chrome на настоящем перетаскивании (не на
 *   синтетических событиях: они до PanResponder не доходят, доска не менялась):
 *     уровень 34, 14 ниш, скрытая информация и примёрзшие ряды, 28 спрайтов;
 *     desktop 1280 → 1061 кадр, 120 к/с, медиана 8,3 мс, худший 10,4 мс;
 *     телефон 390×844 с процессором вчетверо медленнее → 3864 кадра, 120 к/с,
 *     медиана 8,3 мс, худший 16,2 мс, кадров дороже 16,7 мс — НОЛЬ.
 *   Дефекта нет ни до, ни после. Проверять это пробой нельзя — кадры меряются
 *   только в живом браузере, — поэтому число записано здесь, а не выдумано.
 *
 * ВОЗРАЖЕНИЕ 3: «на 30–40 нишах перестаёт доказываться решаемость — генерируй
 *   офлайн». ЗАМЕР: при боевом потолке в 11 видов сорок ниш доказаны 6 из 6 за
 *   3 мс на доску; в тесном случае (запас 2, видов почти по числу ниш) доля
 *   недоказанных не растёт с размером — 2 из 5 на двенадцати нишах и 0 из 5 на
 *   сорока. Опровергнуто числом: решаемость упирается в отношение видов к
 *   запасу, а не в размер доски. Офлайн-генерация не нужна, и проверка ниже
 *   держит это утверждение живым.
 */
import {
  SCROLL_FROM, ITEM_FLOOR, gridFor, gsLayout, levelCfg, targetSlots,
  strictPlacement, miniMap, capsFor, dealBoard, obstaclePlan,
} from '@/src/games/goods-sort/core/level';
import { makeBoard } from '@/src/games/goods-sort/core/board';
import { solveStrict } from '@/src/games/goods-sort/core/solver';

jest.setTimeout(300000);

/** Экраны, на которых игру реально смотрят. Поле = высота минус шапка и панель. */
const ЭКРАНЫ = [
  { имя: 'iPhone 390', w: 390, поле: 484 },
  { имя: 'Android 360', w: 360, поле: 440 },
  { имя: 'планшет 768', w: 768, поле: 620 },
  { имя: 'десктоп 1280', w: 1280, поле: 440 },
];
const ПУЛ = Array.from({ length: 34 }, (_, i) => i);

describe('витрина на два-три экрана', () => {
  it('🔴 до порога витрины ничего не едет — прокрутка не приходит раньше своего уровня', () => {
    const рано: string[] = [];
    for (let L = 1; L < SCROLL_FROM; L += 1) {
      for (const э of ЭКРАНЫ) {
        const узкий = э.w < 560;
        const g = gridFor(L, узкий);
        // Ниже порога пол не задан — ровно так игра и зовёт раскладку.
        if (gsLayout(э.w, э.поле, g.cols, g.rows, 4, undefined, 0).scrolls) рано.push(`L${L} на ${э.имя}`);
      }
    }
    expect(рано).toEqual([]);
  });

  it('🔴 с порога витрины шкаф едет — и это не одиночный случай', () => {
    const едет: number[] = [];
    for (let L = SCROLL_FROM; L <= 60; L += 1) {
      const g = gridFor(L, true);
      if (gsLayout(390, 484, g.cols, g.rows, 4, undefined, ITEM_FLOOR).scrolls) едет.push(L);
    }
    // Строгие уровни намеренно не едут — у них доска остаётся короткой.
    const строгих = [];
    for (let L = SCROLL_FROM; L <= 60; L += 1) if (strictPlacement(L)) строгих.push(L);
    expect(едет.length).toBe(60 - SCROLL_FROM + 1 - строгих.length);
    expect(едет.length).toBeGreaterThan(8);
  });

  /**
   * 🔴 ВОЗРАЖЕНИЕ 1, ГЛАВНАЯ ЕГО ПОЛОВИНА: товар НЕ УЖИМАЕТСЯ. Проверяется на
   * всех уровнях и всех экранах разом — потому что дефект был именно в том, что
   * на одном экране всё выглядело прилично, а на другом нет.
   */
  it('🔴 товар нигде и никогда не мельче читаемого пола', () => {
    const мелко: string[] = [];
    for (let L = 1; L <= 60; L += 1) {
      for (const э of ЭКРАНЫ) {
        const g = gridFor(L, э.w < 560);
        const l = gsLayout(э.w, э.поле, g.cols, g.rows, 4, undefined, L >= SCROLL_FROM ? ITEM_FLOOR : 0);
        // ⚠️ Ширина ячейки — жёсткий потолок: в узкую нишу товар физически не
        // влезет, и пол её не отменяет. Поэтому спрашиваем про ВЫСОТУ ряда,
        // где пол и работает: ниша обязана быть не ниже читаемого товара.
        // И спрашиваем только на витрине: ниже порога пол не задан намеренно.
        if (L >= SCROLL_FROM && l.nicheH < Math.round(ITEM_FLOOR / 0.6)) мелко.push(`L${L} ${э.имя}: ниша ${l.nicheH}`);
      }
    }
    expect(мелко).toEqual([]);
  });

  it('🔴 витрина действительно на два-три экрана, а не на полтора', () => {
    const g = gridFor(59, true);      // 60-й строгий, у него доска намеренно короткая
    const l = gsLayout(390, 484, g.cols, g.rows, 4, undefined, ITEM_FLOOR);
    const экранов = l.boardH / (484 - 44);
    expect(экранов).toBeGreaterThan(1.4);
    expect(экранов).toBeLessThan(3.2);
    // И это РОСТ: на плато шкаф был в один экран.
    const было = gsLayout(390, 484, 3, 6, 4, undefined, 0);
    expect(было.scrolls).toBe(false);
    expect(l.boardH).toBeGreaterThan(было.boardH * 1.4);
  });

  /**
   * 🔴 ВОЗРАЖЕНИЕ 1, ВТОРАЯ ПОЛОВИНА: КАРТА. Проверяется не тем, что она есть,
   * а тем, что она НИЧЕГО НЕ ТЕРЯЕТ: сумма ниш по рядам карты равна числу ниш
   * на доске. Карта, забывшая ряд, хуже её отсутствия — она врёт про структуру.
   */
  it('🔴 карта покрывает КАЖДУЮ нишу доски, на всех уровнях витрины', () => {
    const плохо: string[] = [];
    for (let L = SCROLL_FROM; L <= 60; L += 1) {
      const cfg = levelCfg(L, ПУЛ.length, true);
      const { cells } = dealBoard(L, ПУЛ, true);
      const caps = capsFor(L, cells.length);
      const карта = miniMap(cells, caps, cfg.mask, gridFor(L, true).cols, [], null);
      const всего = карта.reduce((s, r) => s + r.niches, 0);
      if (всего !== cells.length) плохо.push(`L${L}: в карте ${всего} ниш, на доске ${cells.length}`);
      // И пустые в карте — это настоящие пустые ниши, а не «сколько-нибудь».
      const пустых = карта.reduce((s, r) => s + r.empty, 0);
      const наДоске = cells.filter((c) => c.length === 0).length;
      if (пустых !== наДоске) плохо.push(`L${L}: пустых в карте ${пустых}, на доске ${наДоске}`);
    }
    expect(плохо).toEqual([]);
  });

  it('🔴 карта различает ряды, а не показывает одинаковые полоски', () => {
    const cfg = levelCfg(SCROLL_FROM + 6, ПУЛ.length, true);
    const { cells } = dealBoard(SCROLL_FROM + 6, ПУЛ, true);
    const карта = miniMap(cells, capsFor(SCROLL_FROM + 6, cells.length), cfg.mask,
      gridFor(SCROLL_FROM + 6, true).cols, [], { row: 2, type: 1 });
    expect(карта.length).toBeGreaterThanOrEqual(8);
    // Примёрзший ряд отмечен ровно один — тот, что задан.
    expect(карта.filter((r) => r.frozen).map((r) => r.row)).toEqual([2]);
    // Ряды не одинаковы: иначе карта не несёт никаких сведений.
    expect(new Set(карта.map((r) => `${r.niches}/${r.empty}`)).size).toBeGreaterThan(1);
  });

  /**
   * 🔴 ВОЗРАЖЕНИЕ 3, ЖИВЬЁМ: решаемость доказывается на КАЖДОМ уровне витрины.
   * Не «мы посчитали однажды», а прогон здесь и сейчас — иначе утверждение
   * протухнет вместе с первой правкой генератора.
   */
  it('🔴 каждый уровень витрины доказуемо решается — и быстро', () => {
    const плохо: string[] = [];
    let самыйДолгий = 0;
    let больших = 0;
    for (let L = SCROLL_FROM; L <= 60; L += 1) {
      /*
       * ⚠️ Строгие уровни исключены НЕ ради зелёного цвета: у них доска
       * намеренно короткая (12 ниш), они не едут и к витрине отношения не
       * имеют. А недоказуемость на них — давняя и записанная: замер 02.09.2026
       * дал 13 досок из 60, упирающихся в бюджет, и `targetSlots` уменьшает им
       * доску именно поэтому. Меряем то, про что возражение: БОЛЬШИЕ доски.
       */
      if (strictPlacement(L)) continue;
      const { cells } = dealBoard(L, ПУЛ, true);
      const caps = capsFor(L, cells.length);
      if (cells.length >= 18) больших += 1;
      const t = Date.now();
      const r = solveStrict(makeBoard(cells, caps), 20000);
      самыйДолгий = Math.max(самыйДолгий, Date.now() - t);
      if (!r.solvable) плохо.push(`L${L}: решаемость не доказана при ${cells.length} нишах`);
    }
    expect(плохо).toEqual([]);
    // Проверено именно на больших досках, а не на десятке мелких.
    expect(больших).toBeGreaterThan(8);
    // ⚠️ И это дёшево: разбор §4а опасался, что на большой доске доказательство
    // станет неподъёмным и уровни придётся генерировать офлайн.
    expect(самыйДолгий).toBeLessThan(1500);
  });

  it('число ниш на витрине следует своей цели, а не рисунку формы', () => {
    const мимо: string[] = [];
    for (let L = SCROLL_FROM; L <= 60; L += 1) {
      for (const узкий of [true, false]) {
        const ниш = levelCfg(L, ПУЛ.length, узкий).mask.filter(Boolean).length;
        if (Math.abs(ниш - targetSlots(L)) > 2) мимо.push(`L${L}${узкий ? ' (телефон)' : ''}: ниш ${ниш}, цель ${targetSlots(L)}`);
      }
    }
    expect(мимо).toEqual([]);
  });

  it('вбок витрина не растёт — колонок не больше, чем было', () => {
    for (let L = SCROLL_FROM; L <= 60; L += 1) {
      expect(gridFor(L, true).cols).toBe(3);
      expect(gridFor(L, false).cols).toBeLessThanOrEqual(4);
    }
  });

  /** Препятствия на витрине остаются: доска выросла, а правила не отменились. */
  it('препятствия доезжают до витрины', () => {
    let сПрепятствием = 0;
    for (let L = SCROLL_FROM; L <= 60; L += 1) {
      const o = obstaclePlan(L);
      if (o.blocked + o.locked + o.covered > 0 || o.frozenRow) сПрепятствием += 1;
    }
    expect(сПрепятствием).toBeGreaterThan(5);
  });
});
