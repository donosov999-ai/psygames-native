/**
 * КОРЕЙСКИЕ ПЛИТКИ: РАЗОБРАЛ — СОБРАЛ ОБРАТНО, БЕЗ ПОТЕРЬ.
 *
 * 🔴 ЗАЧЕМ. В корейском плитка банка — чамо (ㅅ, ㅏ, ㄹ), а читать человек должен
 * слово в блоках (사랑). Если сборка обратно неоднозначна, игра покажет не то
 * слово, которое человек набрал, — и это невозможно объяснить.
 *
 * Проба гоняет обе стороны на настоящем наборе, а не на образцах: каждая база и
 * каждая цель из `allWordsKo.json` обязаны собраться в блоки и разобраться назад
 * в те же самые плитки.
 */
import { вЧамо, изЧамо, показатьКорейское, слогХангыля } from '@/src/games/anagrams/core/chamo';

const KO = require('@/src/constants/allWordsKo.json') as { base: string; words: string[] }[];

describe('корейские плитки — чамо', () => {
  it('есть что проверять', () => {
    expect(KO.length).toBeGreaterThan(500);
  });

  it('🔴 каждая плитка набора — совместимостное чамо, а не блок и не буква', () => {
    const чужие = new Set<string>();
    for (const p of KO) {
      for (const ch of [...p.base, ...p.words.join('')]) {
        const c = ch.codePointAt(0)!;
        if (c < 0x3131 || c > 0x3163) чужие.add(ch);
      }
    }
    expect([...чужие].slice(0, 5)).toEqual([]);
  });

  it('🔴 каждая база и каждая цель собираются в слоговые блоки', () => {
    const беды: string[] = [];
    for (const p of KO) {
      if (изЧамо(p.base) === null) беды.push(`база «${p.base}» не собирается`);
      for (const w of p.words) if (изЧамо(w) === null) беды.push(`цель «${w}» не собирается`);
      if (беды.length > 4) break;
    }
    expect(беды.slice(0, 5)).toEqual([]);
  });

  it('🔴 круговой ход без потерь: чамо → блоки → те же чамо', () => {
    const беды: string[] = [];
    for (const p of KO) {
      for (const w of [p.base, ...p.words]) {
        const блоки = изЧамо(w);
        if (блоки === null || вЧамо(блоки) !== w) {
          беды.push(`«${w}» → «${блоки}» → «${блоки ? вЧамо(блоки) : null}»`);
          break;
        }
      }
      if (беды.length) break;
    }
    expect(беды).toEqual([]);
  });

  it('🔴 правило хвоста: согласная уходит в следующий слог, если за ней гласная', () => {
    // 사랑 = ㅅㅏㄹㅏㅇ — ㄹ здесь начало второго слога, а не хвост первого
    expect(изЧамо('ㅅㅏㄹㅏㅇ')).toBe('사랑');
    // 살앙 = ㅅㅏㄹ + ㅇㅏㅇ — на одну плитку больше, и это другое слово
    expect(изЧамо('ㅅㅏㄹㅇㅏㅇ')).toBe('살앙');
    expect(вЧамо('사랑')).toBe('ㅅㅏㄹㅏㅇ');
    expect(вЧамо('살앙')).toBe('ㅅㅏㄹㅇㅏㅇ');
  });

  it('не-хангыль отвергается, а показ никогда не роняет экран', () => {
    expect(вЧамо('hello')).toBeNull();
    expect(изЧамо('ㄱ')).toBeNull();          // согласная без гласной — не слог
    expect(показатьКорейское('ㄱ')).toBe('ㄱ');  // но показать всё равно можно
    expect(слогХангыля('사')).toBe(true);
    expect(слогХангыля('ㅅ')).toBe(false);
  });
});
