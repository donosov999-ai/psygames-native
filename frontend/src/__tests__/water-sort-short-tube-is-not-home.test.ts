/**
 * 🔴 УКОРОЧЕННЫЙ СОСУД ДОМОМ НЕ БЫВАЕТ — ИНАЧЕ УРОВЕНЬ ЗАПИРАЕТСЯ САМ.
 *
 * 📍 НАЙДЕНО ЗАМЕРОМ 07.09.2026, а не придумано. Приём «укорочение» ставит на
 * поле сосуды полезной высоты 4 (на L30 — 3), тогда как каждый цвет даёт
 * `cap` = 5 порций. Прежнее правило называло домом сосуд, полный ДО СВОЕЙ
 * высоты. Значит:
 *   1. игрок наливает 4 порции цвета в короткий сосуд — это выглядит прогрессом;
 *   2. `isDone` = true, и `sealDone` САМ запечатывает сосуд и увозит его;
 *   3. пятая порция остаётся на поле, а дома для неё больше нет — дом требует
 *      всех пяти.
 * Уровень становится непроходимым, причём игрок не делал ничего запрещённого и
 * выбора ему не давали: печать срабатывает сама, после хода.
 *
 * ⚠️ ЗНАЧОК «УРОВЕНЬ ПРОВЕРЕН» ЭТОГО НЕ ЛОВИЛ. Решатель считает по модели, где
 * печати нет, и честно находил решение — просто не то, которое остаётся игроку
 * после того, как печать сработала. Ровно та разница, ради которой значок и
 * заведён, только с другой стороны.
 *
 * ⚠️ И ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ДЕФЕКТА: из полного однородного сосуда нельзя
 * было вылить (запрет «однородную в пустую»). Для дома это верно — ход ничего не
 * меняет. Для укороченного НЕ верно: домом он стать не может, значит однородный
 * столбик в нём тупик, и выход наружу — единственный ход. Обе половины проверены
 * ниже, потому что без второй первая только меняет вид ловушки.
 */
import { generateLevel } from '@/src/games/water-sort/core/generate';
import { isDone, sealDone, legalMoves, doneCount, pour, fieldKey, полезная, isBuffer } from '@/src/games/water-sort/core/tubes';

jest.setTimeout(600000);

/** Уровни, на которых укорочение работает: проверяем на них, а не «вообще». */
const С_УКОРОЧЕНИЕМ = [18, 19, 24, 30, 36, 42];

/** Первый укороченный сосуд поля, либо −1. */
function короткий(f: ReturnType<typeof generateLevel>['field']): number {
  return f.tubes.findIndex((_, i) => !isBuffer(f, i) && полезная(f, i) > 0 && полезная(f, i) < f.cap);
}

describe('укороченный сосуд — место для манёвра, а не дом', () => {
  it('есть что проверять: укороченные сосуды на поле действительно есть', () => {
    const нашлись = С_УКОРОЧЕНИЕМ.filter((L) => короткий(generateLevel(L).field) >= 0);
    expect(нашлись.length).toBeGreaterThan(3);
  });

  /**
   * 🔴 ГЛАВНОЕ: НАЛИТЫЙ ОДНИМ ЦВЕТОМ КОРОТКИЙ СОСУД НЕ ЗАПЕЧАТЫВАЕТСЯ.
   *
   * Собираем ровно то положение, в котором игра запиралась: короткий сосуд полон
   * одним цветом. Ни `isDone`, ни `sealDone` не имеют права счесть его домом.
   */
  it('🔴 короткий сосуд, полный одним цветом, не считается домом и не уезжает', () => {
    const плохо: string[] = [];
    for (const L of С_УКОРОЧЕНИЕМ) {
      const f = generateLevel(L).field;
      const i = короткий(f);
      if (i < 0) continue;
      const h = полезная(f, i);
      const порченое = { ...f, tubes: f.tubes.map((t, k) => (k === i ? Array(h).fill(0) : [...t])) };
      if (isDone(порченое, i)) плохо.push(`L${L}: сосуд ${i} высотой ${h} объявлен домом`);
      if (sealDone(порченое).sealed > 0) плохо.push(`L${L}: сосуд ${i} высотой ${h} запечатан и уехал`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 ОБРАТНАЯ СТОРОНА: ПОЛНОЙ ВЫСОТЫ СОСУД ДОМОМ БЫТЬ ОБЯЗАН. Без этого пункта
   * «короткий не дом» чинилось бы тем, что домом не считается никто, и партия
   * перестала бы сходиться вовсе.
   */
  it('🔴 сосуд полной высоты, полный одним цветом, домом остаётся', () => {
    const плохо: string[] = [];
    for (const L of С_УКОРОЧЕНИЕМ) {
      const f = generateLevel(L).field;
      const i = f.tubes.findIndex((_, k) => !isBuffer(f, k) && полезная(f, k) === f.cap);
      if (i < 0) continue;
      const собран = { ...f, tubes: f.tubes.map((t, k) => (k === i ? Array(f.cap).fill(0) : [...t])) };
      if (!isDone(собран, i)) плохо.push(`L${L}: сосуд ${i} полной высоты домом не признан`);
      if (sealDone(собран).sealed === 0) плохо.push(`L${L}: собранный сосуд ${i} не уехал`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 И ИЗ КОРОТКОГО ЕСТЬ ВЫХОД. Запрет «однородную в пустую» для него снят:
   * иначе игрок, наливший туда один цвет доверху, оказывается заперт без единого
   * хода — ловушка та же, только называется иначе.
   */
  it('🔴 из короткого сосуда, полного одним цветом, можно вылить в пустой', () => {
    const плохо: string[] = [];
    for (const L of С_УКОРОЧЕНИЕМ) {
      const f = generateLevel(L).field;
      const i = короткий(f);
      if (i < 0) continue;
      const пустой = f.tubes.findIndex((t, k) => k !== i && t.length === 0 && !isBuffer(f, k));
      if (пустой < 0) continue;
      const h = полезная(f, i);
      const порченое = { ...f, tubes: f.tubes.map((t, k) => (k === i ? Array(h).fill(0) : k === пустой ? [] : [...t])) };
      const наружу = legalMoves(порченое).filter((m) => m.from === i);
      if (!наружу.length) плохо.push(`L${L}: из сосуда ${i} нет ни одного хода`);
    }
    expect(плохо).toEqual([]);
  });

  /**
   * 🔴 И ТА ЖЕ ПРАВКА СВОДИТ МОДЕЛЬ РЕШАТЕЛЯ С ЭКРАНОМ.
   *
   * 📍 Замер ДО правки: 130 023 законных хода из раздач L1…L45 давали **127
   * падений** счёта собранных (L24, L26, L28, L30, L36) — то есть решатель умел
   * РАЗОБРАТЬ уже собранный сосуд, чего игрок не может: у него сосуд запечатан и
   * уехал. Решатель был сильнее игрока, и его «решаемо» могло опираться на ход,
   * которого у человека нет. После правки — 0 падений на 138 612 ходах.
   */
  it('🔴 счёт собранных не падает ни на одном законном ходу', () => {
    let падений = 0; let проверено = 0;
    for (let L = 1; L <= 45; L += 1) {
      const поле = generateLevel(L).field;
      const видели = new Set<string>();
      let очередь = [поле];
      for (let шаг = 0; шаг < 5 && очередь.length; шаг += 1) {
        const дальше: typeof очередь = [];
        for (const f of очередь.slice(0, 200)) {
          const было = doneCount(f);
          for (const m of legalMoves(f)) {
            const n = pour(f, m.from, m.to);
            if (!n) continue;
            проверено += 1;
            if (doneCount(n) < было) падений += 1;
            const k = fieldKey(n);
            if (!видели.has(k)) { видели.add(k); дальше.push(n); }
          }
        }
        очередь = дальше;
      }
    }
    // Иначе проба зелена вслепую: ходов не было вовсе.
    expect(проверено).toBeGreaterThan(50000);
    expect(падений).toBe(0);
  });
});
