/**
 * 🔴 ТРЕТЬИ ОСИ ФЛАНКЕРА И МИШЕНЕЙ.
 *
 * ПОВОД. Срез лестниц 10.09.2026: у обеих по ДВЕ оси, хотя множитель нагрузки
 * большой (×21,0 и ×11,1). Большой множитель здесь не заслуга, а признак: обе
 * оси выжаты досуха — окно фланкера упирается в пол 1000 мс на L15, зазор доходит
 * до 4 px, а число квадратов у мишеней ограничено палитрой (все цвета «не мишени»
 * обязаны быть разными) и даёт всего ЧЕТЫРЕ разных значения на 15 ступеней.
 *
 * ⚠️ ОБЕ НОВЫЕ ОСИ ВЫБИРАЛИСЬ ПО ОДНОМУ ПРИЗНАКУ — ЧТОБЫ НЕ ТРОГАТЬ МЕРУ.
 * Фланкер: показатель `flanker_effect_ms` — разность с ЖЁСТКОЙ нормой 70±30, и
 * почти всё, что напрашивается, попадает прямо в неё (больше фланкеров — эффект
 * растёт; перцептивная нагрузка — по теории Лави сжимается). Взят ОБЪЁМ: он не
 * меняет эффект на пробу, зато чинит его оценку — при 20 пробах и pCong 0,40
 * половина разности считалась по ВОСЬМИ числам.
 * Мишени: показатель `commission_errors`; ось сходства цветов запрещена — вся
 * задача это сравнение цветов, а запаса различимости для дальтоников нет. Взят
 * РАЗБРОС по вертикали: цвета не трогает, долю мишеней не трогает.
 */
import { levelParams as flParams, levelCondition as flCond } from '@/app/games/flanker';
import { levelParams as tgParams, levelCondition as tgCond } from '@/app/games/targets';
import { flankerLoad, targetsLoad, flankerCongruentTrials } from '@/src/games/attention/load';

const УРОВНИ = Array.from({ length: 15 }, (_, i) => i + 1);

describe('фланкер: объём как третья ось', () => {
  it('есть что проверять — иначе набор зелен вслепую', () => {
    expect(`поле объёма: ${'trials' in flParams(1)}`).toBe('поле объёма: true');
  });

  it('🔴 объём растёт — раньше он был зашит одним числом на всю лестницу', () => {
    const ряд = УРОВНИ.map((L) => flParams(L).trials);
    expect(ряд.filter((v, i) => i > 0 && v < ряд[i - 1])).toEqual([]);
    expect(`L1 ${ряд[0]} · L15 ${ряд[14]} · разных значений ${new Set(ряд).size}`)
      .toBe('L1 20 · L15 32 · разных значений 3');
  });

  /**
   * 🔴 РАДИ ЧЕГО ОСЬ И ВЗЯТА. Половина разности считается по согласованным
   * пробам; их было восемь. Проба стережёт, чтобы верх лестницы давал заметно
   * больше — иначе норма 70±30 проверяется по горстке.
   */
  it('🔴 согласованных проб на верхнем уровне заметно больше, чем на нижнем', () => {
    const низ = flankerCongruentTrials(1), верх = flankerCongruentTrials(15);
    expect(`низ ${низ} · верх ${верх} · рост ${(верх / низ).toFixed(2)}×`)
      .toBe(`низ 8 · верх 13 · рост ${(верх / низ).toFixed(2)}×`);
    expect(верх).toBeGreaterThanOrEqual(12);
  });

  /**
   * 🔴 Доли конгруэнтных и неконгруэнтных ЗАМОРОЖЕНЫ: они прямо модулируют
   * измеряемый эффект. Объём растёт, доли стоят — проверяем оба конца.
   */
  it('🔴 доли конгруэнтных и неконгруэнтных не двинулись ни на одном уровне', () => {
    const cong = new Set(УРОВНИ.map((L) => flParams(L).pCong));
    const incong = new Set(УРОВНИ.map((L) => flParams(L).pIncong));
    expect(`разных pCong ${cong.size}, разных pIncong ${incong.size}`)
      .toBe('разных pCong 1, разных pIncong 1');
  });

  it('🔴 мера уровня видит объём (шаг числом, не импортом)', () => {
    const p5 = flParams(5), p6 = flParams(6);
    expect(`объём ${p5.trials} → ${p6.trials}`).toBe('объём 20 → 26');
    const ждём = (p5.gapPx / p6.gapPx) * (p5.windowMs / p6.windowMs) * (26 / 20);
    expect(`${(flankerLoad(6) / flankerLoad(5)).toFixed(3)}`).toBe(`${ждём.toFixed(3)}`);
  });

  it('условие партии несёт объём', () => {
    expect(Object.keys(flCond(1))).toContain('trials');
  });
});

describe('мишени: разброс фигур как третья ось', () => {
  it('есть что проверять', () => {
    expect(`поле разброса: ${'jitterPx' in tgParams(1)}`).toBe('поле разброса: true');
  });

  it('🔴 разброс растёт, первые ступени ровные, и он различает БОЛЬШЕ уровней, чем число квадратов', () => {
    const разброс = УРОВНИ.map((L) => tgParams(L).jitterPx);
    const квадраты = УРОВНИ.map((L) => tgParams(L).numSquares);
    expect(разброс.filter((v, i) => i > 0 && v < разброс[i - 1])).toEqual([]);
    expect(`L1 ${разброс[0]} · L15 ${разброс[14]}`).toBe('L1 0 · L15 26');
    // ради этого ось и заводилась: у числа квадратов всего четыре значения
    expect(`значений: разброс ${new Set(разброс).size} против квадратов ${new Set(квадраты).size}`)
      .toBe(`значений: разброс ${new Set(разброс).size} против квадратов 4`);
    expect(new Set(разброс).size).toBeGreaterThan(new Set(квадраты).size);
  });

  /**
   * 🔴 Доля мишеней — константа парадигмы, а не ручка. Новая ось не должна была
   * её задеть даже случайно.
   */
  it('🔴 число квадратов по-прежнему не выходит за палитру', () => {
    const плохо = УРОВНИ.filter((L) => tgParams(L).numSquares > 6);
    expect(`уровни, где «не мишень» построить нельзя: ${плохо.join(', ') || '—'}`)
      .toBe('уровни, где «не мишень» построить нельзя: —');
  });

  it('🔴 мера уровня видит разброс', () => {
    const p4 = tgParams(4), p5 = tgParams(5);
    expect(`разброс ${p4.jitterPx} → ${p5.jitterPx}`).toBe('разброс 0 → 8');
    const ждём = p4.numSquares === p5.numSquares
      ? (p4.delay / p5.delay) * (1 + p5.jitterPx / 26)
      : (p5.numSquares / p4.numSquares) * (p4.delay / p5.delay) * (1 + p5.jitterPx / 26);
    expect(`${(targetsLoad(5) / targetsLoad(4)).toFixed(3)}`).toBe(`${ждём.toFixed(3)}`);
  });

  it('условие партии несёт разброс — у мишеней условия не было вовсе', () => {
    expect(Object.keys(tgCond(1))).toEqual(expect.arrayContaining(['delay', 'numSquares', 'jitterPx']));
  });
});
