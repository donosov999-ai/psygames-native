import { паузаНаЧтение, levelParams } from '@/app/games/memory-matrix';

/** Быстрое чтение короткой фразы, знаков в секунду. Тем же числом сделан замер выше. */
const ЗН_В_СЕК = 22;
const надоМс = (s: string) => Math.round((s.length / ЗН_В_СЕК) * 1000);

const КОРОТКАЯ = 'Запомните клетки!';                                  // 17 знаков
const СРЕДНЯЯ = '🟣 Запомни ФИОЛЕТОВЫЕ';                               // 20
const ДЛИННАЯ = '🟣 Запомни ФИОЛЕТОВЫЕ · Перечёркнутые — мимо';        // 43

describe('memory-matrix: задание успевает прочитаться', () => {
  it('🔴 новой подписи дают не меньше, чем нужно на её длину', () => {
    for (const с of [КОРОТКАЯ, СРЕДНЯЯ, ДЛИННАЯ]) {
      const дано = паузаНаЧтение(с, '');
      expect(`${с.length} зн.: дано ${дано} мс, надо ${надоМс(с)}`)
        .toBe(`${с.length} зн.: дано ${дано} мс, надо ${надоМс(с)}`);
      expect(дано).toBeGreaterThanOrEqual(надоМс(с));
    }
  });

  /**
   * 🔴 ГЛАВНОЕ: пауза обязана перекрывать окно вспышки на тех уровнях, где
   * раньше не перекрывала. Иначе починка только называется починкой.
   */
  it('🔴 на уровнях, где подпись не помещалась в показ, времени теперь хватает', () => {
    const плохие: string[] = [];
    for (let L = 1; L <= 30; L++) {
      const p = levelParams(L);
      const подпись = p.decoys > 0
        ? ДЛИННАЯ
        : p.seriesCount === 2 ? СРЕДНЯЯ : КОРОТКАЯ;
      const дано = паузаНаЧтение(подпись, '');   // строка новая — уровень только начался
      if (дано < надоМс(подпись)) плохие.push(`L${L}: дано ${дано} < надо ${надоМс(подпись)} (окно показа ${p.flashMs})`);
    }
    expect(`уровней без времени на чтение: ${плохие.length}${плохие.length ? ' — ' + плохие.slice(0, 4).join('; ') : ''}`)
      .toBe('уровней без времени на чтение: 0');
  });

  it('🔴 прочитанную подпись второй раз не показывают — игра не встаёт', () => {
    expect(паузаНаЧтение(ДЛИННАЯ, ДЛИННАЯ)).toBe(0);
    expect(паузаНаЧтение(КОРОТКАЯ, КОРОТКАЯ)).toBe(0);
    // а смена задания паузу возвращает: приход второй серии и приход ложных
    expect(паузаНаЧтение(СРЕДНЯЯ, КОРОТКАЯ)).toBeGreaterThan(0);
    expect(паузаНаЧтение(ДЛИННАЯ, СРЕДНЯЯ)).toBeGreaterThan(0);
  });

  it('пауза не бесконечна — длинная строка не останавливает игру дольше 2,2 с', () => {
    expect(паузаНаЧтение('x'.repeat(400), '')).toBe(2200);
  });

  /**
   * ⚠️ ЛЕСТНИЦА НЕ ТРОНУТА. Отчёт про читаемость, а не про сложность: пауза стоит
   * ДО показа. Если кто-то «починит» жалобу, замедлив показ, — эта проба покраснеет.
   */
  it('🔴 показ и объём остались прежними: чинили чтение, а не сложность', () => {
    expect(`L15 ${JSON.stringify(levelParams(15))}`)
      .toBe('L15 {"gridSize":6,"baseFlashes":13,"flashMs":500,"seriesCount":2,"holdMs":0,"decoys":0}');
    expect(`L20 ${JSON.stringify(levelParams(20))}`)
      .toBe('L20 {"gridSize":6,"baseFlashes":16,"flashMs":500,"seriesCount":2,"holdMs":3500,"decoys":5}');
  });
});
