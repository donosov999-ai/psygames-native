/** Пробирка снизу вверх: последний элемент — верхний слой. */
export type Tube = readonly number[];

export interface Field {
  readonly tubes: readonly Tube[];
  /**
   * Вместимость по умолчанию и САМАЯ БОЛЬШАЯ на поле. Отдельные сосуды могут
   * быть меньше — см. `caps`. Раскладка рисует столб по этому числу, поэтому
   * короткий сосуд выходит визуально коротким, а не с толстыми порциями.
   */
  readonly cap: number;
  /**
   * 🔴 СВОЯ ВМЕСТИМОСТЬ У СОСУДА. Пусто — все по `cap`. Короткий сосуд остаётся
   * ПОЛНОПРАВНЫМ домом цвета: он «закрыт», когда налит одним цветом доверху
   * СВОЕЙ высоты. Отсюда и трудность: цвет, которого шесть порций, в сосуд на
   * четыре не убрать целиком, и его приходится делить или вести в другой.
   */
  readonly caps?: readonly number[];
  /**
   * 🔴 КАМНИ НА ДНЕ — НЕ ПРОСТО МЕНЬШЕ МЕСТА.
   *
   * Соблазн был сделать камни синонимом короткого сосуда: и то и другое
   * отнимает место. Тогда это был бы один приём под двумя именами. Разница
   * здесь смысловая: сосуд с камнями НИКОГДА НЕ СЧИТАЕТСЯ ДОМОМ ЦВЕТА. Налить
   * в него можно, и это его смысл — временное хранилище, — но partия сходится
   * только когда он снова пуст. То есть камни дают не «на две порции меньше», а
   * буфер, за который придётся отчитаться.
   */
  readonly stones?: readonly number[];
  /**
   * 🔴 ОТЛОЖЕННЫЙ СОСУД: открывается, когда закрыто столько-то других. Ноль —
   * открыт сразу. Пустой сосуд, выданный в начале, снимает половину задачи;
   * выданный ПОСЛЕ первого собранного цвета, он делит партию на две части —
   * дожать без него, дальше с ним.
   */
  readonly opensAt?: readonly number[];
  /**
   * 🔴 СКОЛЬКО СОСУДОВ УЖЕ УЕХАЛО С ПОЛЯ. Собранный цвет не остаётся стоять
   * погашенным — он запечатывается и уезжает, ряд смыкается (решение Дениса
   * 06.09.2026).
   *
   * ⚠️ БЕЗ ЭТОГО СЧЁТЧИКА ОТЛОЖЕННЫЙ СОСУД ЗАКРЫВАЕТСЯ ОБРАТНО. `isOpen`
   * спрашивает `doneCount`, а тот считает закрытые сосуды НА ПОЛЕ. Уехал
   * собранный — счёт упал, и уже открытый отложенный снова заперся бы посреди
   * партии. Уехавшие обязаны продолжать считаться.
   */
  readonly sealed?: number;
}

/** Вместимость КОНКРЕТНОГО сосуда. */
export const capOf = (f: Field, i: number): number => f.caps?.[i] ?? f.cap;
/** Сколько камней лежит на дне сосуда. */
export const stonesIn = (f: Field, i: number): number => f.stones?.[i] ?? 0;
/** Сколько порций реально помещается: высота минус камни. */
export const полезная = (f: Field, i: number): number => capOf(f, i) - stonesIn(f, i);
/** Сосуд с камнями домом цвета не станет — только временным хранилищем. */
export const isBuffer = (f: Field, i: number): boolean => stonesIn(f, i) > 0;

/**
 * Сколько ЦВЕТОВ собрано — от этого числа открываются отложенные сосуды.
 *
 * 🔴 ПУСТЫЕ НЕ В СЧЁТ, И ЭТО НЕ ПРИДИРКА. Сначала здесь стояло `isDone`, а он
 * называет закрытым и пустой сосуд. Пустых на поле два, значит счёт начинался с
 * двойки — и печать «откроется после первого закрытого» снималась ДО ПЕРВОГО
 * ХОДА. Замер 06.09.2026: запечатанных сосудов на поле 0 при плане 1–3, на всех
 * уровнях. Приём существовал только в таблице.
 */
export function doneCount(f: Field): number {
  // Уехавшие продолжают считаться: см. `Field.sealed`.
  let n = f.sealed ?? 0;
  for (let i = 0; i < f.tubes.length; i += 1) {
    const t = f.tubes[i]!;
    if (t.length > 0 && isDone(f, i)) n += 1;
  }
  return n;
}

/**
 * Открыт ли сосуд прямо сейчас. Считается ОТ ПОЛОЖЕНИЯ, а не хранится флагом:
 * иначе отмена хода вернула бы содержимое, но не замок, и поле рассказывало бы
 * о себе неправду. Тот же приём, что у скрытого слоя (`hidden.ts`).
 */
export function isOpen(f: Field, i: number): boolean {
  const надо = f.opensAt?.[i] ?? 0;
  return надо <= 0 || doneCount(f) >= надо;
}

export interface Move { readonly from: number; readonly to: number }

export function makeField(tubes: readonly (readonly number[])[], cap: number): Field {
  if (cap <= 0) throw new Error('вместимость пробирки должна быть больше нуля');
  for (const t of tubes) {
    if (t.length > cap) throw new Error(`в пробирке ${t.length} порций при вместимости ${cap}`);
  }
  return { tubes: tubes.map((t) => [...t]), cap };
}

export const isEmptyTube = (t: Tube): boolean => t.length === 0;
export const topColor = (t: Tube): number | null => (t.length ? t[t.length - 1]! : null);
export const roomIn = (f: Field, i: number): number => полезная(f, i) - f.tubes[i]!.length;

/** Высота верхнего одноцветного столбика. */
export function topRun(t: Tube): number {
  if (!t.length) return 0;
  const c = t[t.length - 1]!;
  let n = 1;
  for (let i = t.length - 2; i >= 0 && t[i] === c; i--) n++;
  return n;
}

/**
 * Сосуд «закрыт»: пустой либо налит одним цветом доверху СВОЕЙ высоты.
 *
 * ⚠️ СОСУД С КАМНЯМИ ЗАКРЫТ ТОЛЬКО ПУСТЫМ. Он временное хранилище, а не дом:
 * оставленный в нём цвет — незаконченное дело, и партия не сходится.
 */
export function isDone(f: Field, i: number): boolean {
  const t = f.tubes[i]!;
  if (t.length === 0) return true;
  if (isBuffer(f, i)) return false;
  /**
   * ⚠️ СРАВНИВАЕМ С ПРИГОДНОЙ ВЫСОТОЙ, А НЕ С ПОЛНОЙ. Камни занимают дно, и
   * налить поверх них можно только `capOf − камни`. Первая редакция сравнивала
   * с `capOf`, и это было НЕЗАМЕТНО ровно потому, что строкой выше буфер
   * отсекается: полный сосуд с камнями до сравнения не доходил. Мутация это и
   * показала — сняв заслон «буфер не дом», проба осталась зелёной, потому что
   * второе условие всё равно не выполнялось. Один дефект прикрывал другой.
   */
  return t.length === полезная(f, i) && topRun(t) === t.length;
}


/**
 * 🔴 СОБРАННЫЙ ЦВЕТ ЗАПЕЧАТЫВАЕТСЯ И УЕЗЖАЕТ, РЯД СМЫКАЕТСЯ.
 *
 * Решение Дениса 06.09.2026: «запечатанный сосуд уезжает, ряд сдвигается».
 * Раньше он оставался на поле погашенным — место занимал, в ход не шёл.
 *
 * ⚠️ УЕЗЖАЕТ ТОЛЬКО ПОЛНЫЙ ДОМ ЦВЕТА. Пустой сосуд `isDone` тоже считает
 * законченным — и убери его, игрок лишится места для манёвра, то есть самой
 * игры. Сосуд с камнями домом не бывает по построению (`isBuffer`).
 *
 * ⚠️ ВСЕ РЯДЫ ПОЛЯ ЕДУТ ВМЕСТЕ. `caps`, `stones` и `opensAt` — параллельные
 * массивы, адресуемые тем же номером, что и `tubes`. Сдвинь один и забудь
 * другой — и у сосуда окажется чужая высота или чужой замок. Это тот же класс,
 * на котором я в тот же день потерял три поля доски в «Сортировке товаров».
 */
export function sealDone(f: Field): { field: Field; sealed: number } {
  const убрать: boolean[] = f.tubes.map((t, i) => t.length > 0 && isDone(f, i));
  const сколько = убрать.filter(Boolean).length;
  if (!сколько) return { field: f, sealed: 0 };
  const оставить = <T,>(ряд: readonly T[] | undefined): T[] | undefined =>
    (ряд ? ряд.filter((_, i) => !убрать[i]) : undefined);
  const поле: Field = {
    ...f,
    tubes: f.tubes.filter((_, i) => !убрать[i]).map((t) => [...t]),
    caps: оставить(f.caps),
    stones: оставить(f.stones),
    opensAt: оставить(f.opensAt),
    sealed: (f.sealed ?? 0) + сколько,
  };
  return { field: поле, sealed: сколько };
}

export function isSolved(f: Field): boolean {
  return f.tubes.every((_, i) => isDone(f, i));
}

/**
 * Разрешён ли перелив.
 *
 * ⚠️ ПЕРЕЛИВ ИЗ ОДНОЦВЕТНОЙ ПРОБИРКИ В ПУСТУЮ ЗАПРЕЩЁН. Формально он законен и
 * ничего не ломает, но не меняет положения: то же содержимое в другой посуде.
 * Без запрета решатель ходит по кругу «туда-обратно» и упирается в бюджет на
 * досках, которые решаются за десять ходов, а человек получает подсказку,
 * ведущую в никуда.
 */
export function canPour(f: Field, from: number, to: number): boolean {
  if (from === to) return false;
  // Отложенный сосуд не берёт и не отдаёт, пока не открылся.
  if (!isOpen(f, from) || !isOpen(f, to)) return false;
  const a = f.tubes[from]!;
  const b = f.tubes[to]!;
  if (!a.length) return false;
  if (roomIn(f, to) === 0) return false;
  const цвет = topColor(a)!;
  if (b.length === 0) {
    // ⚠️ ЗАПРЕТ «ОДНОРОДНУЮ В ПУСТУЮ» НЕ РАСПРОСТРАНЯЕТСЯ НА БУФЕР И ОБРАТНО.
    // Из сосуда с камнями содержимое ОБЯЗАНО уйти, иначе партия не сходится, —
    // и это единственный его ход, когда все цвета уже разобраны. А переливать
    // однородный столбик В буфер бессмысленно ровно так же, как в пустой сосуд.
    if (isBuffer(f, to)) return topRun(a) !== a.length;
    if (isBuffer(f, from)) return true;
    return topRun(a) !== a.length;
  }
  return topColor(b) === цвет;
}

/** Сколько порций реально перельётся. */
export function pourAmount(f: Field, from: number, to: number): number {
  if (!canPour(f, from, to)) return 0;
  return Math.min(topRun(f.tubes[from]!), roomIn(f, to));
}

/** Новое поле после перелива; null — ход незаконен. */
export function pour(f: Field, from: number, to: number): Field | null {
  const n = pourAmount(f, from, to);
  if (!n) return null;
  const цвет = topColor(f.tubes[from]!)!;
  const tubes = f.tubes.map((t, i) => {
    if (i === from) return t.slice(0, t.length - n);
    if (i === to) return [...t, ...Array(n).fill(цвет)];
    return t;
  });
  /*
   * 🔴 ЗАПЕЧАТКА СЮДА НЕ ВХОДИТ — И ЭТО ЗАМЕР, А НЕ НЕДОСМОТР.
   *
   * В «Тортах» и «Сортировке товаров» схлопывание положено ВНУТРЬ хода: там оно
   * освобождает место и подаёт новое, то есть меняет множество доступных ходов,
   * и решатель обязан его видеть. Здесь наоборот: собранный сосуд ИНЕРТЕН.
   * Вылить из него некуда — весь цвет уже в нём, а других порций этого цвета на
   * поле нет по построению; налить в него нельзя — он полон. Значит его отъезд
   * не меняет НИ ОДНОГО достижимого положения, и решателю его моделировать
   * незачем.
   *
   * 📍 Цена ошибки замерена. Сначала я поставил `sealDone` сюда «как у соседей»,
   * и генератор уровней сломался: проба «план уровня исполняется на поле» шла
   * 11,5 с и проходила, стала идти 100 с и падать — на L34 и L40 раздача теряла
   * ВСЕ три приёма (укорочение, камни, печать) и уходила в запасной путь.
   * Причина: сдвиг номеров сосудов внутри хода ломает генератору сверку плана.
   *
   * Поэтому отъезд живёт в игровом слое (экран зовёт `sealDone` после хода), а
   * ядро хода остаётся тем же, что видит решатель и на чём собирается уровень.
   */
  return { ...f, tubes };
}

export function legalMoves(f: Field): Move[] {
  const ходы: Move[] = [];
  for (let a = 0; a < f.tubes.length; a++) {
    for (let b = 0; b < f.tubes.length; b++) if (canPour(f, a, b)) ходы.push({ from: a, to: b });
  }
  return ходы;
}

/**
 * Ключ положения для памяти обхода.
 *
 * ⚠️ ПРОБИРКИ СОРТИРУЮТСЯ. Поле «красная слева, синяя справа» и «синяя слева,
 * красная справа» — одно и то же положение: пробирки не приколочены, важно лишь
 * их содержимое. Без сортировки обход разбирает одну доску по многу раз, бюджет
 * выгорает, и генератор объявляет непроходимыми решаемые расклады.
 */
export function fieldKey(f: Field): string {
  return f.tubes.map((t) => t.join(',')).sort().join('|');
}
