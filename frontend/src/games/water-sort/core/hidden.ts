import type { Field } from './tubes';

/** С какого уровня появляется скрытый слой. */
export const СКРЫТО_С = 16;

/**
 * Уровень со скрытым слоем. Прореженным ритмом, а не подряд: механика, идущая
 * каждый уровень, перестаёт быть событием и становится фоном.
 */
export function скрытоНаУровне(level: number): boolean {
  const L = Math.max(1, Math.floor(level) || 1);
  return L >= СКРЫТО_С && (L - СКРЫТО_С) % 3 === 0;
}

/** Ключ клетки: `сосуд * 100 + глубина`. Глубина 0 — дно. */
export const ключСлоя = (сосуд: number, глубина: number): number => сосуд * 100 + глубина;

/**
 * Какие слои спрятаны при раздаче.
 *
 * ⚠️ ПРЯЧЕМ ТОЛЬКО ТО, ПОД ЧЕМ ЕСТЬ ЧТО-ТО ЕЩЁ. Слой закрывается не «наугад», а
 * ровно один в сосуде и никогда не верхний: сосуд из двух слоёв даёт скрытым
 * нижний, сосуд из одного — не даёт ничего. Пустые и уже собранные сосуды не
 * трогаем: там прятать нечего, а закрытый однотонный столбик читался бы как
 * поломка.
 */
export function скрытыеСлои(field: Field, rnd: () => number): Set<number> {
  const из = new Set<number>();
  for (let i = 0; i < field.tubes.length; i += 1) {
    const t = field.tubes[i] as readonly number[];
    if (t.length < 2) continue;
    // Однотонный столбик не прячем: скрывать в нём нечего, а выглядит как сбой.
    if (t.every((c) => c === t[0])) continue;
    // Глубина от 0 (дно) до length-2 — верхний слой остаётся виден всегда.
    const глубина = Math.floor(rnd() * (t.length - 1));
    из.add(ключСлоя(i, глубина));
  }
  return из;
}

/**
 * Слой открыт для взгляда: он не спрятан ЛИБО уже стал верхним.
 *
 * 🔴 ОТКРЫТИЕ ПРОИСХОДИТ ОТ ХОДА, А НЕ ОТ ПОКУПКИ. Слой становится видимым
 * ровно тогда, когда над ним ничего не осталось, — то есть разведка оплачивается
 * ходами, а не рекламой и не звёздами. Это и отличает честную неполную
 * информацию от угадайки: игрок сам решает, чем платить за знание.
 */
export function слойВиден(
  field: Field, скрытые: ReadonlySet<number>, сосуд: number, глубина: number,
): boolean {
  const t = field.tubes[сосуд] as readonly number[] | undefined;
  if (!t) return true;
  if (глубина >= t.length - 1) return true;          // верхний виден всегда
  return !скрытые.has(ключСлоя(сосуд, глубина));
}

/** Сколько слоёв ещё не открыто — цифра для замера «цены неопределённости». */
export function скрытоОсталось(field: Field, скрытые: ReadonlySet<number>): number {
  let n = 0;
  for (let i = 0; i < field.tubes.length; i += 1) {
    const t = field.tubes[i] as readonly number[];
    for (let d = 0; d < t.length; d += 1) if (!слойВиден(field, скрытые, i, d)) n += 1;
  }
  return n;
}

/**
 * ⚠️ ПОД СКРЫТЫМ СЛОЕМ «ХОДОВ СВЕРХ МИНИМУМА» НЕ СУЩЕСТВУЕТ, и это не мнение.
 * Минимум считается от ПОЛНОЙ информации; человек, честно разведавший доску,
 * потратит на разведку ходы, которых в минимуме нет, — и получит одну звезду за
 * то, чего не мог знать. Условие 4 из шести.
 */
export function звёздыПоХодам(level: number): boolean {
  return !скрытоНаУровне(level);
}
