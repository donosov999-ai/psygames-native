/**
 * РЕШАТЕЛЬ И ГЕНЕРАТОР РАСКЛАДОВ.
 *
 * Стратегия взята у `tjwood100/ball-sort-puzzle-solver`: раздать случайно и
 * ПРОВЕРИТЬ решателем, а не пытаться строить заведомо решаемое обратными ходами.
 * Обратные ходы дают расклады, у которых решение — это ровно тот путь, которым их
 * собирали, и трудность у них плоская. Случайная раздача с проверкой даёт разброс,
 * а цена проверки мала: доски здесь маленькие.
 *
 * 🔴 ИСЧЕРПАНИЕ БЮДЖЕТА — ЭТО ТРЕТИЙ ИСХОД, А НЕ «НЕ РЕШАЕТСЯ».
 *
 * Урок, оплаченный на судоку 04.09.2026: счётчик, упёршийся в бюджет, отвечает
 * «нет решения» тем же значением, что и настоящее «нет решения», и вызывающий код
 * не может их различить. Здесь это выглядело бы так: генератор молча выбрасывает
 * решаемые расклады, потому что они СЛОЖНЫЕ, и лестница уровней оказывается
 * заполнена одними лёгкими досками — при полностью исправном решателе.
 *
 * Поэтому `solve` возвращает `outcome`, а не булево, и генератор при исчерпании
 * бюджета НЕ считает доску негодной, а даёт решателю больше места.
 */
import { Field, Move, fieldKey, isSolved, legalMoves, makeField, pour, topRun } from './tubes';

export type SolveOutcome = 'solved' | 'unsolvable' | 'budget';

export interface SolveResult {
  outcome: SolveOutcome;
  /** Путь до решения — только при outcome === 'solved'. */
  moves: Move[];
  /** Сколько положений разобрано: по нему видно, упёрлись мы в бюджет или в стену. */
  visited: number;
}

/**
 * Поиск в глубину с памятью положений.
 *
 * ⚠️ ХОДЫ УПОРЯДОЧЕНЫ, И ЭТО НЕ УКРАШЕНИЕ. Сначала те, что ЗАКРЫВАЮТ пробирку
 * (доливают до полной одноцветной) или освобождают её целиком: без порядка обход
 * блуждает по перестановкам и упирается в бюджет там, где решение в семь ходов.
 */
function порядокХодов(f: Field, ходы: Move[]): Move[] {
  const вес = (m: Move): number => {
    const из = f.tubes[m.from]!;
    const в = f.tubes[m.to]!;
    const n = Math.min(topRun(из), f.cap - в.length);
    let w = 0;
    if (в.length + n === f.cap) w -= 4;              // пробирка закрывается
    if (topRun(из) === из.length) w -= 3;            // источник пустеет целиком
    if (в.length === 0) w += 2;                      // занимать пустую — на потом
    return w;
  };
  return [...ходы].sort((a, b) => вес(a) - вес(b));
}

export function solve(start: Field, budget = 60000): SolveResult {
  const виден = new Set<string>();
  let разобрано = 0;
  const путь: Move[] = [];
  let исчерпан = false;

  const идти = (f: Field): boolean => {
    if (isSolved(f)) return true;
    if (разобрано >= budget) { исчерпан = true; return false; }
    const ключ = fieldKey(f);
    if (виден.has(ключ)) return false;
    виден.add(ключ);
    разобрано++;
    for (const m of порядокХодов(f, legalMoves(f))) {
      const следующее = pour(f, m.from, m.to);
      if (!следующее) continue;
      путь.push(m);
      if (идти(следующее)) return true;
      путь.pop();
      if (исчерпан) return false;
    }
    return false;
  };

  const решено = идти(start);
  if (решено) return { outcome: 'solved', moves: [...путь], visited: разобрано };
  return { outcome: исчерпан ? 'budget' : 'unsolvable', moves: [], visited: разобрано };
}

export interface LevelParams {
  /** Сколько цветов. Каждый занимает ровно `cap` порций. */
  colors: number;
  /** Вместимость пробирки. */
  cap: number;
  /** Сколько пустых пробирок сверх цветных. */
  empty: number;
  /** Ниже этого числа ходов расклад считается пустым — раздали почти собранным. */
  minMoves: number;
}

/**
 * Лестница из пятнадцати уровней.
 *
 * 🔴 ПУСТЫХ ПРОБИРОК ВСЕГДА ДВЕ, И ЭТО ИЗМЕРЕНО, А НЕ ВЫБРАНО НА ВКУС.
 *
 * Первая редакция лестницы растила трудность второй осью — убирала одну свободную
 * пробирку на 14–15 уровнях. Замер 05.09.2026, по 40 случайных раздач на набор
 * параметров:
 *
 *   цветов 11 · высота 5 · пустых 1  → решаемо  0/40
 *   цветов 10 · высота 5 · пустых 1  → решаемо  0/40
 *   цветов  9 · высота 4 · пустых 1  → решаемо  0/40
 *   цветов 11 · высота 5 · пустых 2  → решаемо 40/40
 *   цветов 10 · высота 5 · пустых 2  → решаемо 40/40
 *   цветов  9 · высота 4 · пустых 2  → решаемо 40/40
 *
 * Сто двадцать раздач с одной свободной пробиркой — ни одной решаемой. Это не
 * «сложнее», это «невозможно»: генератор перебирал бы попытки впустую и уходил в
 * запасной путь, а человек получал бы вырожденную доску на самых верхних уровнях.
 * Ось «меньше свободных пробирок» годится только для генерации ОБРАТНЫМИ ходами
 * от собранного положения — там решаемость гарантирована построением, но и
 * трудность плоская. Пока эта ось не используется.
 *
 * Остаются две работающие оси: число цветов (растит перебор) и высота пробирки
 * (растит длину столбиков, которые надо переливать целиком).
 */
/**
 * 🔴 НА СТЫКЕ ВЫСОТ ЧИСЛО ЦВЕТОВ НЕ ПАДАЕТ. Замер 06.09.2026 по длине решения
 * (12 раздач на уровень): L10 давал 56,3 хода, а L11 — 48,1, то есть
 * одиннадцатый уровень был на 15% ЛЕГЧЕ десятого. Причина видна прямо в старых
 * числах: на L10 стояло 12 цветов при высоте 4, а на L11 высота росла до 5, но
 * цвета сбрасывались до восьми — 48 порций против 40.
 *
 * ⚠️ ЛОМАЛОСЬ ИМЕННО НА ГРАНИЦЕ УЧАСТКОВ, и прежняя проба этого не видела: она
 * сравнивала среднее первых трёх уровней со средним последних трёх, а между
 * ними лежало всё интересное. Теперь стык прогоняется подряд.
 *
 * ⚠️ ХВОСТ ЛЕСТНИЦЫ ПЛОСКИЙ, И ЭТО ЧЕСТНО СКАЗАНО, А НЕ СКРЫТО. Обе рабочие оси
 * упёрлись в потолок: 12 цветов — вся палитра, высота 5 — предел различимости
 * столбика. С L14 уровни отличаются только раскладом (73–79 ходов). Растить
 * дальше нечем, пока не заведена третья ось — разная вместимость у РАЗНЫХ
 * сосудов (замер: 10 свободных порций в двух сосудах решаемы 39 раз из 40, те
 * же 10 в одном — 0 из 40).
 */
export function levelParams(level: number): LevelParams {
  const L = Math.max(1, level);
  if (L <= 10) return { colors: 2 + L, cap: 4, empty: 2, minMoves: 4 + L * 2 };
  // Высота 5 приходит СРАЗУ с десятью цветами: 50 порций против 48 на L10.
  if (L <= 13) return { colors: 9 + (L - 10), cap: 5, empty: 2, minMoves: 30 + (L - 10) * 4 };
  return { colors: 12, cap: 5, empty: 2, minMoves: 42 };   // L14+
}

function перемешать<T>(a: T[], rnd: () => number): T[] {
  const r = [...a];
  for (let i = r.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [r[i], r[j]] = [r[j]!, r[i]!];
  }
  return r;
}

export interface GeneratedLevel {
  field: Field;
  /** Длина найденного решения — грубая мера трудности расклада. */
  solutionMoves: number;
  /** Сколько раскладов пришлось отбросить: видно, что генератор не выродился. */
  attempts: number;
}

/**
 * Раздать расклад под параметры уровня.
 *
 * ⚠️ ГЕНЕРАТОР ОБЯЗАН ВЕРНУТЬ ДОСКУ. Молчаливый `null` в игре означает пустой
 * экран, и по нему не видно, кончились ли попытки или сломался решатель. Поэтому
 * при исчерпании попыток последняя ПРОВЕРЕННО решаемая доска возвращается даже
 * если она проще, чем просили, а `attempts` показывает, сколько стоило.
 */
export function generateLevel(level: number, rnd: () => number = Math.random): GeneratedLevel {
  const p = levelParams(level);
  const порции: number[] = [];
  for (let c = 0; c < p.colors; c++) for (let k = 0; k < p.cap; k++) порции.push(c);

  let запасной: GeneratedLevel | null = null;
  const ПОПЫТОК = 60;
  let бюджет = 60000;

  for (let attempt = 1; attempt <= ПОПЫТОК; attempt++) {
    const колода = перемешать(порции, rnd);
    const tubes: number[][] = [];
    for (let i = 0; i < p.colors; i++) tubes.push(колода.slice(i * p.cap, (i + 1) * p.cap));
    for (let i = 0; i < p.empty; i++) tubes.push([]);
    const field = makeField(tubes, p.cap);

    // уже собранное или почти собранное — не задача
    const собрано = field.tubes.filter((t, i) => t.length && topRun(t) === t.length && t.length === field.cap).length;
    if (собрано >= p.colors - 1) continue;

    const r = solve(field, бюджет);
    if (r.outcome === 'budget') {
      /**
       * 🔴 БЮДЖЕТ КОНЧИЛСЯ — ЭТО ПРО РЕШАТЕЛЯ, А НЕ ПРО ДОСКУ. Выбросить её
       * значило бы систематически выбрасывать САМЫЕ СЛОЖНЫЕ расклады и получить
       * лестницу из лёгких досок при исправном решателе.
       */
      бюджет *= 2;
      continue;
    }
    if (r.outcome !== 'solved') continue;

    const итог: GeneratedLevel = { field, solutionMoves: r.moves.length, attempts: attempt };
    if (r.moves.length >= p.minMoves) return итог;
    if (!запасной || r.moves.length > запасной.solutionMoves) запасной = итог;
  }
  if (запасной) return { ...запасной, attempts: ПОПЫТОК };

  /**
   * 🔴 ЗАПАСНОЙ ПУТЬ НЕ СМЕЕТ ОТДАТЬ СОБРАННУЮ ДОСКУ. Первая редакция отдавала
   * именно её — «заведомо решаемую», — и проба поймала это на 15-м уровне: доска
   * приходила уже собранной, то есть уровень открывался пройденным. Решаемость
   * без задачи не стоит ничего.
   *
   * Вместо этого добавляем свободную пробирку, пока раздача не станет решаемой.
   * Такая доска легче заказанной — и это записано в `attempts`, — но она ЗАДАЧА.
   * Обрыв гарантирован: при числе свободных пробирок, равном числу цветов,
   * расклад решается разбором в лоб.
   */
  for (let extra = 1; extra <= p.colors; extra++) {
    for (let attempt = 1; attempt <= 20; attempt++) {
      const колода = перемешать(порции, rnd);
      const tubes: number[][] = [];
      for (let i = 0; i < p.colors; i++) tubes.push(колода.slice(i * p.cap, (i + 1) * p.cap));
      for (let i = 0; i < p.empty + extra; i++) tubes.push([]);
      const field = makeField(tubes, p.cap);
      if (isSolved(field)) continue;
      const r = solve(field, 200000);
      if (r.outcome === 'solved' && r.moves.length >= 4) {
        return { field, solutionMoves: r.moves.length, attempts: ПОПЫТОК + extra };
      }
    }
  }
  throw new Error(`генератор не смог раздать решаемый расклад для уровня ${level}`);
}
