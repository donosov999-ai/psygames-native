/** Отступ слота ответа в GameShell: FAB_GUTTER 66 слева и справа. */
export const GUTTER_BOTH = 132;

/** Зазор между кнопками ответа и между рядами. */
export const BTN_GAP = 8;

/** Норма попадания пальцем (Material); её же держит `tap-target-audit`. */
export const MIN_TAP = 48;

/**
 * ВЫСОТА ПОЛОСЫ ОТВЕТА — ОДНА НА ВЕСЬ РАЗДЕЛ И РАВНАЯ СОСЕДСКОЙ.
 *
 * 120 = два ряда по 48 + зазор 8 + отступы 2×8. Ровно `ANSWER_BAR_H` раздела
 * «Внимание»; гейт `search-frame-geometry` сверяет равенство, чтобы разделы не
 * разъехались молча при чьей-нибудь правке.
 */
export const SEARCH_BAR_H = 120;

/** Самый узкий телефон, который считаем настоящим (см. тот же приём у соседей). */
const MIN_SCREEN_W = 320;

/** Ноль, NaN и отрицательное — не размер экрана (первый кадр веб-сборки отдаёт 0). */
const экран = (v: number): number => (Number.isFinite(v) && v >= MIN_SCREEN_W ? v : MIN_SCREEN_W);

/**
 * 🔴 СКОЛЬКО ВАРИАНТОВ ОТВЕТА ВЛЕЗАЕТ — ЭТО НЕ ВКУС, А АРИФМЕТИКА.
 *
 * Замер 09.09.2026. Каркас держит по краям слота ответа `FAB_GUTTER = 66` с
 * ОБЕИХ сторон, значит на экране 320 под кнопки остаётся 188 точек. При норме
 * пальца 48 и зазоре 8 в ряд помещается ТРИ кнопки. Отсюда:
 *
 *   вариантов  5–6 → 3 столбца, ДВА ряда, кнопка 57 px на 320    ✅
 *   вариантов  7–8 → 3 столбца, ТРИ ряда  (полоса 180)           ✗ полоса дышит
 *   вариантов 9–11 → 3 столбца, ЧЕТЫРЕ ряда (полоса 236)         ✗ треть экрана
 *
 * У быстрого счёта вариантов было 7…11 — они считались как `minN−2 … maxN+2`,
 * то есть зависели от уровня. Поэтому полоса меняла высоту И ОТ УРОВНЯ, И ОТ
 * ЭКРАНА: замер дал 133 на 390 против 193 на 360 при семи вариантах, а на
 * L20–L24 их одиннадцать.
 *
 * ⚠️ ЦЕНА РЕШЕНИЯ НАЗВАНА ЧЕСТНО: угадывание наугад дорожает с 1/11 до 1/6.
 * На прохождение это не влияет — порог `accuracy >= 80 %` абсолютный, и
 * угадывающий не проходит ни при одиннадцати вариантах, ни при шести. Если
 * Денис захочет иначе — меняется ОДНО число здесь, а не вёрстка шести экранов.
 */
export const ANSWER_MAX = 6;

export interface AnswerGrid {
  cols: number;
  rows: number;
  /** Сторона кнопки: квадрат, чтобы цифра стояла в центре. */
  size: number;
}

/**
 * Раскладка кнопок ответа. Столбцы считаются от САМОГО УЗКОГО экрана, а не от
 * текущего: иначе на 390 получится два ряда, на 360 — три, и полоса поедет при
 * переходе между телефонами. Именно это и было замерено (133 против 193).
 */
export function answerGrid(count: number, screenW: number): AnswerGrid {
  const n = Math.max(1, Math.min(count, ANSWER_MAX));
  const узкое = MIN_SCREEN_W - GUTTER_BOTH;
  const cols = Math.max(1, Math.floor((узкое + BTN_GAP) / (MIN_TAP + BTN_GAP)));
  const rows = Math.ceil(n / cols);
  // На широком экране кнопка может быть крупнее, но не настолько, чтобы ряды
  // перестали помещаться в SEARCH_BAR_H: высоту полосы задаём мы, а не кнопка.
  const свободно = экран(screenW) - GUTTER_BOTH;
  const поШирине = Math.floor((свободно - (cols - 1) * BTN_GAP) / cols);
  const поВысоте = Math.floor((SEARCH_BAR_H - 16 - (rows - 1) * BTN_GAP) / rows);
  return { cols, rows, size: Math.max(MIN_TAP, Math.min(поШирине, поВысоте)) };
}

/** Слагаемые высоты слота `toolbar` в каркасе — читаются из `GameShell`, не выдуманы. */
const TOOLBAR_PAD_TOP = 10;    // styles.toolbar.paddingTop
const TOOLBAR_PAD_MIN = 10;    // paddingBottom: Math.max(insets.bottom, 10)
const HAIRLINE = 1;            // borderTopWidth: StyleSheet.hairlineWidth

/**
 * СКОЛЬКО МЕСТА ЗАРЕЗЕРВИРОВАТЬ ВНИЗУ ПОЛЯ у игры БЕЗ полосы ответа.
 *
 * 🔴 РЕЗЕРВ РАВЕН ПОЛНОЙ ВЫСОТЕ СЛОТА, А НЕ ВЫСОТЕ КНОПОК. Каркас добавляет к
 * содержимому полосы `paddingTop 10`, `paddingBottom max(insets.bottom, 10)` и
 * волосяную линию сверху (`GameShell`, `styles.toolbar`). Считать по одному
 * `SEARCH_BAR_H` значило бы недобрать 21 точку, и центры полей всё равно бы не
 * сошлись — просто меньше.
 *
 * ⚠️ Вычитать `insets.bottom` НЕ надо, и это проверено по коду каркаса:
 * корневой `SafeAreaView` объявлен `edges={['top','left','right']}` — нижний
 * вырез контейнеру НЕ применяется. Значит поле игры без полосы доходит до
 * самого низа экрана, ровно как поле игры с полосой доходит до её верха.
 *
 * На вебе и Android (`insets.bottom = 0`) это 120 + 10 + 10 + 1 = 141.
 * На iPhone с вырезом 34 — 120 + 10 + 34 + 1 = 165.
 */
export function reserveBottom(insetBottom: number): number {
  const низ = Number.isFinite(insetBottom) && insetBottom > 0 ? insetBottom : 0;
  return SEARCH_BAR_H + TOOLBAR_PAD_TOP + Math.max(низ, TOOLBAR_PAD_MIN) + HAIRLINE;
}
