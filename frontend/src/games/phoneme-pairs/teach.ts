/**
 * 🎓 РАЗБОР ПО ШАГАМ «ФОНЕМНЫХ ПАР»: УЗНАТЬ, ГДЕ ПАРА РАСХОДИТСЯ, И СЛУШАТЬ ТОЛЬКО ЭТО МЕСТО.
 *
 * 📍 Денис 17.09.2026: для слуховых игр — «на что слушать и чем отличаются варианты». У минимальной
 * пары ответ один: слова совпадают во всём, кроме одного звука, и слушать надо именно его.
 *
 * ЧЕМУ УЧИТ, ПО ШАГАМ (два примера из пула уровня):
 * 1. приём: пара расходится в одном месте;
 * 2. пара: оба слова звучат, место расхождения показано;
 * 3. проба: звучит одно из двух — «слушайте только место различия»;
 * 4. ответ: какое прозвучало и где было различие;
 * 5. итог.
 *
 * 🔴 МЕСТО РАСХОЖДЕНИЯ — ПО ДАННЫМ, НО НЕ ВЕЗДЕ ПО НАПИСАНИЮ. Замер 30.09.2026 по всем 75 парам:
 * · русский, испанский, португальский — разница в написании совпадает со звуком (дом/том → д|т,
 *   банка/банька → н|нь, pero/perro → r|rr);
 * · китайский — иероглифы разные целиком, поэтому место ищется по пиньиню (山 shān / 三 sān →
 *   sh|s, 饭 fàn / 放 fàng → n|ng);
 * · английский и немецкий — написание ОБМАНЫВАЕТ: у snack/snake оно расходится в «ck|ke», а слова
 *   различаются гласной, которая сидит в общем начале «sna». Все пары этих двух языков различаются
 *   только гласным (так их описывает и автор игры), поэтому разбор говорит «гласный в середине»
 *   и букв не подсвечивает.
 *
 * ⚠️ ТЕКУЩЕЕ ЗАДАНИЕ В РАЗБОР НЕ ПОПАДАЕТ: разбор открывается посреди партии.
 */
import { ZH_PINYIN } from '@/src/constants/zhPinyin.generated';

export type Пара = [string, string];
export type ВидРазличия = 'буквы' | 'гласный' | 'пиньинь';

/** Отрезок [начало, конец) в символах слова. */
export type Отрезок = [number, number];

export interface КарточкаФонем {
  вид: 'приём' | 'пара' | 'проба' | 'ответ' | 'готово';
  /** Ключ словаря: язык живёт в словаре, не в коде. */
  ключ: string;
  поля?: Record<string, string | number>;
  /** Пара-пример или `null`. */
  пара: Пара | null;
  /** Какое слово пары звучит на пробе и названо в ответе (индекс) или `null`. */
  звучит: 0 | 1 | null;
  /** Что произнести при показе карточки — слова по порядку. */
  звук: string[];
  /** Где слова расходятся (по написанию или по пиньиню) или `null` для гласного. */
  отличие: { a: Отрезок; b: Отрезок } | null;
}

export interface РазборФонем {
  карточки: КарточкаФонем[];
  примеры: Пара[];
}

/** Англичанам и немцам написание не помогает: все их пары различаются только гласным. */
export function видРазличия(язык: string): ВидРазличия {
  if (язык === 'en' || язык === 'de') return 'гласный';
  if (язык === 'zh') return 'пиньинь';
  return 'буквы';
}

/** Пул пар уровня — та же формула, что у партии (экран зовёт эту же функцию). */
export function пулУровня(все: readonly Пара[], лёгкие: boolean): Пара[] {
  return лёгкие ? все.slice(0, Math.max(2, Math.ceil(все.length / 2))) : [...все];
}

/**
 * Где две строки расходятся: общее начало и общий конец отбрасываются. Если у одной стороны
 * отличие пустое (pero/perro, банка/банька), обе стороны расширяются на символ влево — иначе
 * человеку показали бы «ничего против r».
 */
export function гдеРасходятся(a: string, b: string): { a: Отрезок; b: Отрезок } {
  const А = Array.from(a);
  const Б = Array.from(b);
  let начало = 0;
  while (начало < А.length && начало < Б.length && А[начало] === Б[начало]) начало++;
  let хвост = 0;
  while (
    хвост < А.length - начало && хвост < Б.length - начало
    && А[А.length - 1 - хвост] === Б[Б.length - 1 - хвост]
  ) хвост++;
  let конецА = А.length - хвост;
  let конецБ = Б.length - хвост;
  if ((конецА === начало || конецБ === начало) && начало > 0) {
    начало -= 1;
  }
  if (конецА === начало) конецА += 1;
  if (конецБ === начало) конецБ += 1;
  return { a: [начало, конецА], b: [начало, конецБ] };
}

const кусок = (слово: string, [с, по]: Отрезок) => Array.from(слово).slice(с, по).join('');
const пиньинь = (знак: string) => ZH_PINYIN[знак]?.pinyin ?? знак;

export function собратьРазборФонем(
  пул: readonly Пара[],
  язык: string,
  /** Пара текущего задания — в разбор не берётся. */
  исключить: Пара | null,
  rnd: () => number = Math.random,
): РазборФонем {
  const вид = видРазличия(язык);
  const тотЖе = (п: Пара) =>
    !!исключить && ((п[0] === исключить[0] && п[1] === исключить[1]) || (п[0] === исключить[1] && п[1] === исключить[0]));
  const годные = пул.filter((п) => !тотЖе(п));
  for (let i = годные.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [годные[i], годные[j]] = [годные[j]!, годные[i]!];
  }
  const примеры = годные.slice(0, 2);

  const карточки: КарточкаФонем[] = [
    { вид: 'приём', ключ: 'teachPhIntro', пара: null, звучит: null, звук: [], отличие: null },
  ];
  for (const пара of примеры) {
    const [a, b] = пара;
    const показ = (с: string) => (вид === 'пиньинь' ? `${с} ${пиньинь(с)}` : с);
    const место = вид === 'гласный' ? null : вид === 'пиньинь'
      ? гдеРасходятся(пиньинь(a), пиньинь(b))
      : гдеРасходятся(a, b);
    const da = место ? кусок(вид === 'пиньинь' ? пиньинь(a) : a, место.a) : '';
    const db = место ? кусок(вид === 'пиньинь' ? пиньинь(b) : b, место.b) : '';
    const звучит: 0 | 1 = rnd() < 0.5 ? 0 : 1;
    const слово = пара[звучит];
    карточки.push({
      вид: 'пара',
      ключ: место ? 'teachPhSpot' : 'teachPhVowel',
      поля: место ? { a: показ(a), b: показ(b), da, db } : { a: показ(a), b: показ(b) },
      пара,
      звучит: null,
      звук: [a, b],
      отличие: место,
    });
    карточки.push({ вид: 'проба', ключ: 'teachPhProbe', пара, звучит, звук: [слово], отличие: место });
    карточки.push({
      вид: 'ответ',
      ключ: место ? 'teachPhAnswerSpot' : 'teachPhAnswerVowel',
      поля: место ? { w: показ(слово), dx: звучит === 0 ? da : db } : { w: показ(слово) },
      пара,
      звучит,
      звук: [слово],
      отличие: место,
    });
  }
  карточки.push({ вид: 'готово', ключ: 'teachPhDone', пара: null, звучит: null, звук: [], отличие: null });
  return { карточки, примеры };
}
