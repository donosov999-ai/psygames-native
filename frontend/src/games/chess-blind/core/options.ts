/**
 * ВАРИАНТЫ ОТВЕТА ДЛЯ ОПРОСА «что стоит на клетке».
 *
 * 🔴 ПОЧЕМУ В ЯДРЕ, А НЕ В ФАЙЛЕ МАРШРУТА. Это чистая логика трудности, и её
 * надо проверять НАПРЯМУЮ, по уровням. Пока она жила в экране, наружу торчал
 * только компонент: проба могла посчитать кнопки лишь на том уровне, который
 * экран сам себе прочитал из хранилища по ключу профиля, — а на первом уровне
 * лестница ещё не разошлась, и мутация «игнорировать лестницу, всегда шесть»
 * проходила пробу насквозь. Тот же довод уже записан рядом, в `puzzle.ts`, про
 * сборку фигур для доски: проверять надо то место, где ошибка случается.
 */
import { puzzleLevelParams } from './puzzle';

/** Фигура так, как её держит доска экрана: важны только тип и сторона. */
export interface ФигураНаДоске { readonly type: PieceType; readonly white: boolean }
export type PieceType = 'K' | 'Q' | 'R' | 'B' | 'N' | 'P';
/** Вариант ответа: та же пара «тип + сторона». */
export interface Combo { readonly type: PieceType; readonly white: boolean }

const comboKey = (c: { type: PieceType; white: boolean }) => `${c.type}${c.white ? 'w' : 'b'}`;

/** Перемешать, не трогая исходный массив. */
function shuffle<T>(arr: readonly T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
}

/**
 * ВАРИАНТЫ ОТВЕТА. 🔴 ДВЕ ОСИ ТРУДНОСТИ, КОТОРЫХ ЗДЕСЬ НЕ БЫЛО.
 *
 * 📍 Было: ровно шесть вариантов на всех пятнадцати уровнях, набранных СЛУЧАЙНО
 * с доски. То есть ни число вариантов, ни их похожесть от уровня не зависели —
 * оси «отвлечение» просто не существовало, хотя лестница растила всё остальное.
 *
 * Стало (правило Дениса 06.09.2026 «потолков нет нигде»):
 *   · `optionCount` — 6 → 8 → 10, случайность падает с 1/6 до 1/10;
 *   · `sameColorShare` — доля отвлекающих ТОГО ЖЕ ЦВЕТА, 0 → 0,5 → 1.
 *
 * Цвет — самый сильный признак на доске: отличить чёрного коня от белой ладьи
 * легко, от чёрной ладьи — нет. Наверху вопрос становится «какая фигура», а не
 * «какая сторона».
 *
 * ⚠️ ОДНОЦВЕТНЫХ ВАРИАНТОВ ВСЕГО ШЕСТЬ (шесть типов фигур), поэтому при десяти
 * вариантах полностью одноцветный набор невозможен. Доля — это НАМЕРЕНИЕ, а не
 * обещание: сначала берём столько одноцветных, сколько есть, потом добираем
 * остальными. Требовать точную долю значило бы уронить число вариантов.
 */
export function buildOptions(final: readonly ФигураНаДоске[], answer: Combo, level: number): Combo[] {
  const { optionCount, sameColorShare } = puzzleLevelParams(level);
  const все: Combo[] = (['K', 'Q', 'R', 'B', 'N', 'P'] as PieceType[])
    .flatMap((t) => [{ type: t, white: true }, { type: t, white: false }])
    .filter((c) => !(c.type === answer.type && c.white === answer.white));

  const наДоске = new Set<string>();
  final.forEach((p) => наДоске.add(comboKey(p)));
  const сДоски = (c: Combo) => наДоске.has(comboKey(c));

  // Одного цвета с ответом — самые трудные; из них сначала те, что есть на доске.
  const свои = shuffle(все.filter((c) => c.white === answer.white));
  const чужие = shuffle(все.filter((c) => c.white !== answer.white));
  const поПользе = (a: Combo[]) => [...a.filter(сДоски), ...a.filter((c) => !сДоски(c))];

  const надо = optionCount - 1;
  /**
   * ⚠️ ДОЛЯ — ЭТО МИНИМУМ, А НЕ ПРЕДПИСАНИЕ «ОСТАЛЬНЫЕ ЧУЖИЕ». Первая редакция
   * при доле 0 ставила все варианты ЧУЖОГО цвета — и ответ оказывался
   * единственным своего цвета, то есть цвет выдавал его сразу. Это не «нулевая
   * трудность подбора», а подсказка, и она хуже прежнего случайного набора.
   * Проба поймала: своих на первом уровне выходило 0%.
   *
   * Поэтому: сначала берём столько ОДНОЦВЕТНЫХ, сколько велит доля, а остаток
   * добираем из общей перемешанной кучи — как было до лестницы.
   */
  const хотимСвоих = Math.min(свои.length, Math.round(надо * sameColorShare));
  const обязательные = поПользе(свои).slice(0, хотимСвоих);
  const остальные = shuffle([...поПользе(свои).slice(хотимСвоих), ...поПользе(чужие)]);
  const выбор = [...обязательные, ...остальные];

  const opts: Combo[] = [answer];
  for (const c of выбор) {
    if (opts.length > надо) break;
    if (!opts.some((o) => o.type === c.type && o.white === c.white)) opts.push(c);
  }
  return shuffle(opts);
}

