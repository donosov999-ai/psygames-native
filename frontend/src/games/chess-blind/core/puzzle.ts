/**
 * Вид фигуры в записи ЭКРАНА — прописной ('N'). У ядра он строчный ('n'), как в
 * FEN. Две записи сложились независимо: ядро повторяет запись FEN, экран —
 * ключи глифов и ключи словаря `chessPcW*`/`chessPcB*`, собранные на прописных.
 */
export type PuzzlePieceType = 'K' | 'Q' | 'R' | 'B' | 'N' | 'P';

/** Фигура в том виде, в каком её держит и двигает экран. `sq` — клетка СЕТКИ ЭКРАНА. */
export interface PuzzlePiece {
  id: number;
  type: PuzzlePieceType;
  white: boolean;
  /** 0..63, строка 0 — ВОСЬМАЯ горизонталь: сетка рисуется сверху вниз. */
  sq: number;
}

/**
 * ПОЗИЦИЯ ЯДРА → ФИГУРЫ ДЛЯ ДОСКИ ЭКРАНА. ЗДЕСЬ ПРИМЕНЯЕТСЯ ПЕРЕВОРОТ.
 *
 * 🔴 ПОЧЕМУ ЭТА ФУНКЦИЯ В ЯДРЕ, А НЕ В ЭКРАНЕ (решение 27.08.2026). Сам
 * переворот считает `screenIndex` из `board.ts`, и он пробой закрыт. Но
 * ПРИМЕНЯЕТСЯ он здесь, и подмена `screenIndex(index)` на голый `index` оставила
 * бы пробу `screenIndex` зелёной, а доску — перевёрнутой. Пока сборка жила в
 * файле маршрута, дотянуться до неё проба не могла вовсе: наружу тот отдаёт
 * только компонент. Проверять надо ТО МЕСТО, ГДЕ ОШИБКА СЛУЧАЕТСЯ.
 *
 * ⚠️ ПЕРЕВЁРНУТУЮ ДОСКУ НЕ ВИДНО ГЛАЗОМ. Фигур на ней ровно столько же, цвета
 * клеток совпадают (сумма координат меняет чётность дважды), позиция выглядит
 * законной. Поэтому проба сверяет ИМЯ поля, а не число фигур: у первой фигуры
 * позиции `8/8/8/4kppp/...` король обязан оказаться на e5, то есть в третьей
 * строке сетки снизу, а не в третьей сверху.
 */
export function toScreenPieces(position: ChessPosition): PuzzlePiece[] {
  const out: PuzzlePiece[] = [];
  position.squares.forEach((cell, index) => {
    if (!cell) return;
    out.push({
      id: out.length + 1,
      type: cell.type.toUpperCase() as PuzzlePieceType,
      white: cell.color === 'w',
      sq: screenIndex(index),
    });
  });
  return out;
}
