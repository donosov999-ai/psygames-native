/**
 * СЧЁТ МЕЖДУ ПОКАЗОМ И ОПРОСОМ — ось «интерференция».
 *
 * 🔴 ЗАЧЕМ. Правило Дениса 06.09.2026 «потолков нет нигде»: у «Доски в уме» из
 * десяти осей роста было занято четыре. Эта — пятая, и она отличается от прочих
 * тем, что меняет УСТРОЙСТВО подхода, а не параметр: между показом позиции и
 * вопросом о ней вклинивается посторонняя задача, и удержать доску проговором
 * «конь це-три, ладья а-один» больше нельзя.
 *
 * Приём классический — operation span (Turner & Engle): чередование счёта и
 * запоминания. В приложении он уже стоит в упражнении «Объём операций»
 * (`app/games/ospan.tsx`), и форма примера взята оттуда: выражение плюс
 * ПОКАЗАННЫЙ ответ, человек говорит «верно/неверно». Это дешевле ввода числа —
 * два нажатия вместо клавиатуры, и не отнимает у подхода много времени.
 *
 * ⚠️ КОД СВОЙ, А НЕ ОБЩИЙ, И ЭТО НЕ ОТ ХОРОШЕЙ ЖИЗНИ. `makeEquation` в `ospan`
 * НЕ экспортирована, а сам файл — чужого раздела, и править его мне нельзя.
 * Правильный конец у этой истории — вынести генератор в общее ядро и звать из
 * обоих мест; просьба координатору отправлена. Пока дублирую ФОРМУ (выражение +
 * показанный ответ + доля неверных 1/2), а не копирую строки.
 *
 * ⚠️ ЧТО ЭТО НЕ МЕРЯЕТ. Ответ на пример НЕ входит в счёт партии: это помеха, а
 * не задание. Мерить им человека значило бы подменить предмет упражнения —
 * память на позицию — устным счётом.
 */

/**
 * С какого уровня включается помеха.
 *
 * 🔴 РУБЕЖ ТОТ ЖЕ, ЧТО У ОСТАЛЬНЫХ ОСЕЙ (11), а не новый. На нём опрос уже
 * меняется с «что стоит» на «где стоит», и там же растут варианты и вопросы.
 * Свой рубеж у каждой оси означал бы, что трудность прыгает в четырёх разных
 * местах и человек не понимает, что именно изменилось.
 */
export const УРОВЕНЬ_ПОМЕХИ = 11;

export function нужнаПомеха(level: number): boolean {
  return level >= УРОВЕНЬ_ПОМЕХИ;
}

/**
 * Сколько примеров показать. Растёт вместе с уровнем, но медленно: помеха
 * удлиняет подход, а подход и так длинный — показ, ходы, опрос.
 *
 * ⚠️ ТРИ — ПОТОЛОК, И ОН НЕ ОТ ЛЕНИ. На двадцатом уровне подход это показ 5 с,
 * СЕМНАДЦАТЬ ходов вслепую и пять вопросов; четвёртый пример растил бы не
 * трудность удержания, а длину партии. Трудность выше двадцатого несут фигуры
 * (18 → 22) и ходы (17 → 24).
 */
export function примеровНаПодход(level: number): number {
  if (!нужнаПомеха(level)) return 0;
  if (level >= 20) return 3;
  return level >= 14 ? 2 : 1;
}

export interface Пример {
  /** Левая часть, уже собранная: «7 + 5». Всегда LTR — математика не зеркалится. */
  readonly слева: string;
  /** Показанный ответ — он может быть и неверным. */
  readonly показан: number;
  /** Верен ли показанный ответ. */
  readonly верно: boolean;
}

/** Псевдослучайное 0..1; свой источник — чтобы пример можно было воспроизвести в пробе. */
export type Случай = () => number;

/**
 * Пример на счёт. `трудный` добавляет умножение и числа покрупнее — так же, как
 * это сделано в «Объёме операций».
 *
 * ⚠️ НЕВЕРНЫЙ ОТВЕТ ОТЛИЧАЕТСЯ НЕ МЕНЬШЕ ЧЕМ НА ЕДИНИЦУ И НЕ БОЛЬШЕ ЧЕМ НА ТРИ.
 * Отличие в десятки видно, не считая, — тогда помеха перестаёт быть счётом и
 * становится ещё одной задачей на зрение, которых в этой игре и так хватает.
 */
export function сделатьПример(трудный: boolean, rnd: Случай = Math.random): Пример {
  const a = 1 + Math.floor(rnd() * (трудный ? 12 : 9));
  const b = 1 + Math.floor(rnd() * (трудный ? 12 : 9));
  const знаки = трудный ? ['+', '-', '×'] : ['+', '-'];
  const знак = знаки[Math.floor(rnd() * знаки.length)]!;
  const ответ = знак === '+' ? a + b : знак === '-' ? a - b : a * b;
  const верно = rnd() < 0.5;
  const сдвиг = (rnd() < 0.5 ? -1 : 1) * (1 + Math.floor(rnd() * 3));
  const показан = верно ? ответ : ответ + сдвиг;
  // Сдвиг мог случайно дать тот же ответ — тогда это верный пример, и врать нельзя.
  return { слева: `${a} ${знак} ${b}`, показан, верно: показан === ответ };
}
