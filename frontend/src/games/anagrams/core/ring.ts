/**
 * 🔴 «ЕСТЬ ЧТО ТЕРЯТЬ» — ПРЕДИКАТ, А НЕ ФЛАГ В КОМПОНЕНТЕ.
 *
 * Вопрос при выходе обязан задаваться ровно тогда, когда уход что-то стирает.
 * Пока предикат живёт булевым состоянием внутри экрана, проверить его нечем:
 * гейт `module-games-guard` гоняет его НАСТОЯЩИМ путём, а не читает разметку.
 *
 * Терять есть что с первой взятой плитки: набранное слово уходит вместе с
 * экраном. Закрытые стороны тем более.
 */
export function квадратНачат(линия: readonly number[], закрыты: readonly Сторона[]): boolean {
  return линия.length > 0 || закрыты.length > 0;
}

/**
 * 🔴 ПОДСКАЗКА В «СЛОВЕ-КВАДРАТЕ»: ОЧЕРЕДНАЯ БУКВА НЕЗАКРЫТОЙ СТОРОНЫ.
 *
 * 📍 ОТЧЁТ ДЕНИСА 06.09.2026: «подсказки в новых анаграммах нет, ни первых
 * букв, ни смысла». Тут она нужнее, чем где-либо: слова спрятаны целиком, и
 * если ни одно не приходит в голову, делать на экране решительно нечего.
 *
 * Открывается по одной букве и с начала слова: угол общий с соседом, поэтому
 * первая же буква двигает СРАЗУ ДВЕ стороны — подсказка окупает себя, не решая
 * головоломку.
 */
export function подсказкаКвадрата(
  к: Кольцо,
  закрыты: readonly Сторона[],
  открыто: Readonly<Record<string, number>>,
): { сторона: Сторона; буква: string; индекс: number } | null {
  const пары: [Сторона, string][] = [['верх', к.верх], ['право', к.право], ['низ', к.низ], ['лево', к.лево]];
  for (const [имя, слово] of пары) {
    if (закрыты.indexOf(имя) >= 0) continue;
    const уже = открыто[имя] ?? 0;
    if (уже >= слово.length) continue;
    return { сторона: имя, буква: слово[уже]!, индекс: уже };
  }
  return null;
}
