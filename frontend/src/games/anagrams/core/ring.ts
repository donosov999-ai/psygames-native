interface ЗаписьКольца { t: string; r: string; b: string; l: string; x: number }

const ПАКИ: Record<string, ЗаписьКольца[]> = {
  ru: RINGS_RU as ЗаписьКольца[], en: RINGS_EN as ЗаписьКольца[],
  de: RINGS_DE as ЗаписьКольца[], es: RINGS_ES as ЗаписьКольца[],
  fr: RINGS_FR as ЗаписьКольца[], it: RINGS_IT as ЗаписьКольца[],
  pt: RINGS_PT as ЗаписьКольца[], ko: RINGS_KO as ЗаписьКольца[],
};

const РАЗОБРАННЫЕ = new Map<string, Кольцо[]>();

/** Кольца языка в порядке возрастания трудности. Неизвестный язык — английский. */
export function кольцаЯзыка(locale: string): Кольцо[] {
  const готовые = РАЗОБРАННЫЕ.get(locale);
  if (готовые) return готовые;
  const пак = ПАКИ[locale] ?? ПАКИ.en ?? [];
  // Банк считается здесь же: в паке его нет намеренно — он однозначно выводится
  // из четырёх слов, и хранить его значило бы удвоить вес файла ради того, что
  // считается за один проход.
  const из = пак.map((з) => ({
    верх: з.t, право: з.r, низ: з.b, лево: з.l,
    банк: буквыКольца(з.t, з.r, з.b, з.l),
  }));
  РАЗОБРАННЫЕ.set(locale, из);
  return из;
}

/** Языки, на которых режим есть. */
export function языкиКолец(): string[] {
  return Object.keys(ПАКИ).sort();
}

/** Слова кольца в порядке сторон. */
export function словаКольца(к: Кольцо): string[] {
  return [к.верх, к.право, к.низ, к.лево];
}

export type Сторона = 'верх' | 'право' | 'низ' | 'лево';

/**
 * Какую сторону закрывает слово. `null` — ни одну.
 *
 * ⚠️ Сторона возвращается ОДНА, даже если слово подходит к двум: иначе игра
 * закрыла бы обе разом, и человек не понял бы, за что засчитали второе.
 * Уже закрытые стороны в поиске не участвуют.
 */
export function сторонаСлова(к: Кольцо, слово: string, закрыты: readonly Сторона[] = []): Сторона | null {
  const w = слово.toUpperCase();
  const пары: [Сторона, string][] = [['верх', к.верх], ['право', к.право], ['низ', к.низ], ['лево', к.лево]];
  for (const [имя, значение] of пары) {
    if (закрыты.indexOf(имя) >= 0) continue;
    if (значение === w) return имя;
  }
  return null;
}

/**
 * Клетки периметра 5×5 по индексу (строка × 5 + столбец) и буква в каждой.
 * Углы принадлежат двум сторонам сразу, поэтому карта — от клетки к буквам, а
 * не от слова к клеткам: рисовать надо клетку, а не слово.
 */
export function клеткиСтороны(сторона: Сторона): number[] {
  const N = СТОРОНА;
  switch (сторона) {
    case 'верх': return Array.from({ length: N }, (_, i) => i);
    case 'низ': return Array.from({ length: N }, (_, i) => (N - 1) * N + i);
    case 'лево': return Array.from({ length: N }, (_, i) => i * N);
    case 'право': return Array.from({ length: N }, (_, i) => i * N + (N - 1));
  }
}

/** Буквы периметра по клеткам; в незакрытых сторонах — пустая строка. */
export function периметр(к: Кольцо, закрыты: readonly Сторона[]): string[] {
  const поле = new Array(СТОРОНА * СТОРОНА).fill('');
  for (const сторона of закрыты) {
    const слово = сторона === 'верх' ? к.верх : сторона === 'право' ? к.право : сторона === 'низ' ? к.низ : к.лево;
    клеткиСтороны(сторона).forEach((клетка, i) => { поле[клетка] = слово[i]!; });
  }
  return поле;
}

/** Клетки центра 3×3 — там лежит банк букв. */
export function клеткиЦентра(): number[] {
  const out: number[] = [];
  for (let r = 1; r < СТОРОНА - 1; r++) for (let c = 1; c < СТОРОНА - 1; c++) out.push(r * СТОРОНА + c);
  return out;
}

/**
 * Нужна ли буква ещё хоть одному неразобранному слову. Разобранные слова букву
 * не держат — в образце буква гаснет ровно тогда, когда становится не нужна.
 */
export function букваНужна(к: Кольцо, буква: string, закрыты: readonly Сторона[]): boolean {
  const пары: [Сторона, string][] = [['верх', к.верх], ['право', к.право], ['низ', к.низ], ['лево', к.лево]];
  return пары.some(([имя, слово]) => закрыты.indexOf(имя) < 0 && слово.indexOf(буква) >= 0);
}

