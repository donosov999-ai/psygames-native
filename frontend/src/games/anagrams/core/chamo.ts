/**
 * 🔴 КОРЕЙСКИЙ: ПЛИТКА — ЧАМО, А ПОКАЗЫВАТЬ НАДО СЛОГОВЫЕ БЛОКИ.
 *
 * 📍 Разбор `WORDLIST_NONLATIN.md`: из пяти нелатинских языков корейский
 * переносится в «Найди все слова» чище всех, но только если плиткой взять
 * ЧАМО, а не слоговой блок. Блоками медиана подслов выходит 4, и шести подслов
 * набирается лишь у 29% баз; чамо дают медиану 21 при базе в семь плиток.
 *
 * Отсюда двойственность, которой нет у латиницы: игрок нажимает плитки по
 * одной (ㅅ, ㅏ, ㄹ, ㅏ, ㅇ), а прочитать он должен слово в привычном виде
 * (사랑). Этот файл — мост между двумя формами.
 *
 * ⚠️ ПЛИТКИ — СОВМЕСТИМОСТНЫЕ ЧАМО (U+3131…U+3163), НЕ «БАЗОВЫЕ». Соблазнительно
 * разложить дальше (ㄲ = ㄱ+ㄱ, ㅐ = ㅏ+ㅣ) и получить банк из 24 плиток размером с
 * латиницу. Замер: так обратно собирается 22 946 слов из 49 321 = 46,5%, то есть
 * больше половины ломается (내가 → 나ㅣ가, 왜 → 오ㅐ). На совместимостных — 100,0%.
 *
 * ⚠️ ОДНОЗНАЧНОСТЬ ДАЁТ ЯЗЫК, А НЕ УДАЧА. «Пустая» согласная ㅇ в начале слога и
 * разведённые позиции делают разбивку единственной: 사랑 = ㅅㅏㄹㅏㅇ, а 살앙 =
 * ㅅㅏㄹㅇㅏㅇ — на одну плитку больше. Проверено на всех 49 313 словах корпуса:
 * разобрано в чамо и собрано обратно точно 49 313 / 49 313 = 100,0%.
 */

/** Начальные согласные слога, в порядке кодировки. */
const НАЧАЛЬНЫЕ = [...'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'];
/** Гласные слога. */
const ГЛАСНЫЕ = [...'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'];
/** Конечные согласные; пустая строка — слог без хвоста. */
const КОНЕЧНЫЕ = ['', ...'ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ'];

const БАЗА_СЛОГА = 0xAC00;
const ЧИСЛО_СЛОГОВ = 11172;

/** Слоговой ли это блок хангыля. */
export function слогХангыля(ch: string): boolean {
  const k = ch.codePointAt(0)! - БАЗА_СЛОГА;
  return k >= 0 && k < ЧИСЛО_СЛОГОВ;
}

/** Слово в блоках → строка чамо. `null`, если это не хангыль. */
export function вЧамо(слово: string): string | null {
  const из: string[] = [];
  for (const ch of слово) {
    const k = ch.codePointAt(0)! - БАЗА_СЛОГА;
    if (k < 0 || k >= ЧИСЛО_СЛОГОВ) return null;
    из.push(НАЧАЛЬНЫЕ[Math.floor(k / 588)]!);
    из.push(ГЛАСНЫЕ[Math.floor((k % 588) / 28)]!);
    const хвост = КОНЕЧНЫЕ[k % 28]!;
    if (хвост) из.push(хвост);
  }
  return из.join('');
}

/**
 * Строка чамо → слово в блоках. `null`, если поток не складывается в слоги.
 *
 * 🔴 ЕДИНСТВЕННОЕ ПРАВИЛО, НА КОТОРОМ ВСЁ ДЕРЖИТСЯ: конечная согласная забирается
 * в текущий слог ТОЛЬКО ЕСЛИ следом за ней не идёт гласная. Иначе она — начало
 * следующего слога. Так работает и обычная корейская клавиатура: 사 + ㄹ + ㅏ
 * даёт 사라, а не 살ㅏ.
 */
export function изЧамо(чамо: string): string | null {
  const п = [...чамо];
  const из: string[] = [];
  let i = 0;
  while (i < п.length) {
    const нач = НАЧАЛЬНЫЕ.indexOf(п[i]!);
    if (нач < 0) return null;
    i += 1;
    const глас = i < п.length ? ГЛАСНЫЕ.indexOf(п[i]!) : -1;
    if (глас < 0) return null;
    i += 1;
    let кон = 0;
    if (i < п.length) {
      const место = КОНЕЧНЫЕ.indexOf(п[i]!);
      const следомГласная = i + 1 < п.length && ГЛАСНЫЕ.indexOf(п[i + 1]!) >= 0;
      if (место > 0 && !следомГласная) { кон = место; i += 1; }
    }
    из.push(String.fromCodePoint(БАЗА_СЛОГА + (нач * 21 + глас) * 28 + кон));
  }
  return из.join('');
}

/**
 * Как показать цель игроку: слоговыми блоками, если поток складывается, иначе
 * как есть. Показ никогда не должен ронять экран — поэтому здесь `??`, а не
 * бросок: неудачная сборка означает лишь, что человек увидит чамо.
 */
export function показатьКорейское(чамо: string): string {
  return изЧамо(чамо) ?? чамо;
}
