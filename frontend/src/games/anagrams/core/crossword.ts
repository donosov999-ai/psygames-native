/**
 * РЕЖИМ «КРОССВОРД»: слова из ОДНОГО набора букв вписываются в связную сетку.
 *
 * Просьба Дениса 06.09.2026 по «Магии Слов»: «тоже крутой режим кроссворда надо
 * добавить». Отличие от режима «Найди все слова» не косметическое: там найденное
 * слово вычёркивается из списка и больше ни на что не влияет, здесь каждая
 * найденная буква СТОИТ НА ПОЛЕ и подсказывает соседнее слово. Работа меняется —
 * из перебора букв в чтение частично открытого слова.
 *
 * 🔴 ПОЧЕМУ СЕТКА СЧИТАЕТСЯ НА ЛЕТУ, А НЕ ЛЕЖИТ В ФАЙЛЕ. Уложенные сетки для
 * семи языков — это примерно 2,5 МБ в пакете приложения. Укладчик же считает
 * одну раскладку за миллисекунды, а зерно берётся от уровня, поэтому уровень N
 * ВСЕГДА даёт одну и ту же сетку. Плюс новый язык получает режим сразу, без
 * пересборки данных.
 *
 * ⚠️ ПРАВИЛА УКЛАДКИ — КЛАССИЧЕСКИЙ КРИПТОВОРД, И ЧЕТВЁРТОЕ ГЛАВНОЕ:
 *   1. слово идёт слева направо или сверху вниз, без изломов;
 *   2. чужая буква на пути принимается ТОЛЬКО совпав — это пересечение;
 *   3. клетка перед первой буквой и после последней пуста, иначе на поле
 *      читается склейка «КОТ» + «ОСА» = «КОТОСА»;
 *   4. пустая клетка слова не касается боком чужой буквы — иначе два слова
 *      идут параллельно вплотную и в поперечнике читается мусор;
 *   5. каждое слово, кроме первого, пересекается с уже уложенным — связность
 *      сетки отсюда следует по построению, её не надо проверять потом.
 *
 * Правило 4 — то, из-за чего «уложилось всё» не бывает бесплатным: без него в
 * сетку влезает что угодно, но читается она как каша. Замер при снятом правиле
 * (питон-прототип, `wordlist-build/probe_crossword.py`): проверка ловила 119
 * раскладок из 120.
 *
 * 📍 ЗАМЕР, ЗАДАВШИЙ ЛЕСТНИЦУ (06.09.2026, 300 раскладок ru и en, 24 перезапуска).
 * Сторона сетки решается ЧИСЛОМ СЛОВ, а не языком:
 *   6 слов → сторона медиана 8, в 11×11 влезает 100% ru и 99% en;
 *   8 слов → 9, влезает 95% / 84%;
 *   10 слов → 9–11, влезает 74% / 66%;
 *   14 слов (весь пак) → 11, влезает 63% / 66%.
 * Поэтому число слов растёт с уровнем: это и лестница трудности, и то, что
 * держит клетку читаемой на телефоне.
 */

export const ГОРИЗ = 0;
export const ВЕРТ = 1;

export interface РазмещённоеСлово {
  слово: string;
  r: number;
  c: number;
  /** `ГОРИЗ` или `ВЕРТ`. */
  d: number;
}

export interface Кроссворд {
  /** Слова на своих местах; координаты уже сдвинуты в начало координат. */
  слова: РазмещённоеСлово[];
  rows: number;
  cols: number;
  /** Буква в каждой занятой клетке. Ключ — `r * cols + c`. */
  буквы: Map<number, string>;
  /** Слова, которым места не нашлось. Пусто у всех уровней, что доходят до игры. */
  вне: string[];
}

/** Детерминированный генератор: уровень N обязан давать одну и ту же сетку. */
function зерно(s: number): () => number {
  let a = s >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Ключ клетки. Координаты во время укладки бывают отрицательными — сдвигаем. */
const СДВИГ = 64;
const ШИРИНА = 256;
const ключ = (r: number, c: number): number => (r + СДВИГ) * ШИРИНА + (c + СДВИГ);

class Поле {
  буквы = new Map<number, string>();
  гор = new Set<number>();
  вер = new Set<number>();
  слова: РазмещённоеСлово[] = [];

  /** Число пересечений, если слово встанет сюда, либо `null` — если нельзя. */
  можно(слово: string, r: number, c: number, d: number): number | null {
    const dr = d === ГОРИЗ ? 0 : 1;
    const dc = d === ГОРИЗ ? 1 : 0;
    const свои = d === ГОРИЗ ? this.гор : this.вер;
    // Правило 3: торцы.
    if (this.буквы.has(ключ(r - dr, c - dc))) return null;
    if (this.буквы.has(ключ(r + dr * слово.length, c + dc * слово.length))) return null;
    let пересечений = 0;
    for (let i = 0; i < слово.length; i += 1) {
      const rr = r + dr * i;
      const cc = c + dc * i;
      const k = ключ(rr, cc);
      if (свои.has(k)) return null;   // вдоль своего направления слова не наслаиваются
      const есть = this.буквы.get(k);
      if (есть !== undefined) {
        if (есть !== слово[i]) return null;   // правило 2
        пересечений += 1;
      } else if (d === ГОРИЗ) {
        // Правило 4: пустая клетка не касается боком чужой буквы.
        if (this.буквы.has(ключ(rr - 1, cc)) || this.буквы.has(ключ(rr + 1, cc))) return null;
      } else if (this.буквы.has(ключ(rr, cc - 1)) || this.буквы.has(ключ(rr, cc + 1))) {
        return null;
      }
    }
    return пересечений;
  }

  ставить(слово: string, r: number, c: number, d: number): void {
    const dr = d === ГОРИЗ ? 0 : 1;
    const dc = d === ГОРИЗ ? 1 : 0;
    const свои = d === ГОРИЗ ? this.гор : this.вер;
    for (let i = 0; i < слово.length; i += 1) {
      const k = ключ(r + dr * i, c + dc * i);
      this.буквы.set(k, слово[i] as string);
      свои.add(k);
    }
    this.слова.push({ слово, r, c, d });
  }

  /** Границы занятого прямоугольника: `[rmin, cmin, rows, cols]`. */
  рамка(): [number, number, number, number] {
    if (this.буквы.size === 0) return [0, 0, 0, 0];
    let rmin = Infinity; let rmax = -Infinity; let cmin = Infinity; let cmax = -Infinity;
    for (const k of this.буквы.keys()) {
      const r = Math.floor(k / ШИРИНА) - СДВИГ;
      const c = (k % ШИРИНА) - СДВИГ;
      if (r < rmin) rmin = r; if (r > rmax) rmax = r;
      if (c < cmin) cmin = c; if (c > cmax) cmax = c;
    }
    return [rmin, cmin, rmax - rmin + 1, cmax - cmin + 1];
  }
}

/**
 * Один жадный проход в заданном порядке слов.
 *
 * ⚠️ ДВА ПРОХОДА, А НЕ ОДИН. Слово, не вставшее третьим, часто встаёт последним:
 * к тому времени на поле больше букв, и появляются новые точки пересечения. Без
 * второго прохода укладка занижается на ровном месте.
 */
function уложить(слова: string[], порядок: number[], предел: number): { поле: Поле; вне: string[] } {
  const поле = new Поле();
  поле.ставить(слова[порядок[0] as number] as string, 0, 0, ГОРИЗ);
  let осталось = порядок.slice(1).map((i) => слова[i] as string);

  for (let проход = 0; проход < 2; проход += 1) {
    const неВстали: string[] = [];
    for (const слово of осталось) {
      let лучшее: { оценка: number; r: number; c: number; d: number } | null = null;
      // Кандидаты — только клетки с нужной буквой: пересечение обязательно,
      // значит перебирать пустое поле незачем.
      for (const [k, ch] of this_entries(поле)) {
        const rr = Math.floor(k / ШИРИНА) - СДВИГ;
        const cc = (k % ШИРИНА) - СДВИГ;
        for (let i = 0; i < слово.length; i += 1) {
          if (слово[i] !== ch) continue;
          for (const d of [ГОРИЗ, ВЕРТ]) {
            const r = d === ВЕРТ ? rr - i : rr;
            const c = d === ГОРИЗ ? cc - i : cc;
            const n = поле.можно(слово, r, c, d);
            if (!n) continue;   // null или ноль пересечений — не годится
            const [rmin, cmin, rows, cols] = поле.рамка();
            const r2 = r + (d === ВЕРТ ? слово.length - 1 : 0);
            const c2 = c + (d === ГОРИЗ ? слово.length - 1 : 0);
            const h = Math.max(rmin + rows - 1, r2) - Math.min(rmin, r) + 1;
            const w = Math.max(cmin + cols - 1, c2) - Math.min(cmin, c) + 1;
            if (предел && (h > предел || w > предел)) continue;
            // Компактность важнее числа пересечений: на телефоне решает сторона.
            const оценка = h * w * 1000 - n * 10 + Math.abs(h - w);
            if (лучшее === null || оценка < лучшее.оценка) лучшее = { оценка, r, c, d };
          }
        }
      }
      if (лучшее === null) неВстали.push(слово);
      else поле.ставить(слово, лучшее.r, лучшее.c, лучшее.d);
    }
    if (неВстали.length === 0) return { поле, вне: [] };
    if (неВстали.length === осталось.length) return { поле, вне: неВстали };
    осталось = неВстали;
  }
  return { поле, вне: осталось };
}

/** Снимок клеток на момент начала перебора — поле меняется внутри цикла. */
function this_entries(поле: Поле): [number, string][] {
  return [...поле.буквы.entries()];
}

/**
 * Лучшая укладка из нескольких порядков слов.
 *
 * Первый порядок — от длинных к коротким: длинное слово задаёт хребет сетки, и с
 * него укладка идёт лучше, чем со случайного.
 *
 * 🔴 ПЕРЕЗАПУСКОВ 24, А НЕ 12 — И ЭТО ЗАМЕР, А НЕ ЗАПАС НА ВСЯКИЙ СЛУЧАЙ.
 *
 * 📍 06.09.2026 на шестом уровне русского уровень оказался НЕДОСОБИРАЕМ: из слов
 * базы «молодой» (ДОЛОЙ, ДОМОЙ, ДОМ, ЛОМ, МОЙ, МОЛ) слово ДОЛОЙ не вставало в
 * сетку, и закрыть уровень было нельзя. Случай редкий, но ранний: до шестого
 * уровня доходят все.
 *
 * Укладчик жадный, и дюжины случайных порядков ему иногда не хватает — при том
 * что уложить МОЖНО: с 40 перезапусками эта раскладка встаёт в 5×7, и 38 сидов
 * из 40 берут её даже дюжиной. То есть дело было в числе попыток, а не в правилах.
 *
 * Цена померена на всех 12 185 раскладках семи языков:
 *   12 перезапусков — не уложилась 1, по 2,66 мс на уровень, худший 49 мс;
 *   24 — не уложилось НИ ОДНОЙ, по 5,03 мс, худший 78 мс;
 *   40 — тоже ноль, но по 15,75 мс и худший 233 мс, то есть заметная задержка.
 * Двадцать четыре — первое число, на котором ноль, и оно ещё дёшево.
 */
export function собратьКроссворд(
  слова: readonly string[], seedЧисло: number, перезапусков = 24, предел = 0,
): Кроссворд {
  const сп = [...слова];
  const rnd = зерно(seedЧисло);
  const длинные = sortIndicesByLength(сп);
  let лучшее: { поле: Поле; вне: string[]; ключ: number } | null = null;
  for (let k = 0; k < перезапусков; k += 1) {
    const порядок = k === 0 ? длинные : перемешать(сп.length, rnd);
    const { поле, вне } = уложить(сп, порядок, предел);
    const [, , rows, cols] = поле.рамка();
    const оценка = вне.length * 1e6 + rows * cols * 100 + Math.max(rows, cols);
    if (лучшее === null || оценка < лучшее.ключ) лучшее = { поле, вне, ключ: оценка };
    const [, , h, w] = лучшее.поле.рамка();
    if (лучшее.вне.length === 0 && Math.max(h, w) <= 9) break;   // уже компактно
  }
  const { поле, вне } = лучшее as { поле: Поле; вне: string[] };
  const [rmin, cmin, rows, cols] = поле.рамка();
  const буквы = new Map<number, string>();
  for (const [k, ch] of поле.буквы) {
    const r = Math.floor(k / ШИРИНА) - СДВИГ - rmin;
    const c = (k % ШИРИНА) - СДВИГ - cmin;
    буквы.set(r * cols + c, ch);
  }
  return {
    слова: поле.слова.map((w) => ({ ...w, r: w.r - rmin, c: w.c - cmin })),
    rows, cols, буквы, вне,
  };
}

function sortIndicesByLength(слова: string[]): number[] {
  return слова.map((_, i) => i).sort((a, b) => (слова[b] as string).length - (слова[a] as string).length);
}

function перемешать(n: number, rnd: () => number): number[] {
  const из = Array.from({ length: n }, (_, i) => i);
  for (let i = n - 1; i > 0; i -= 1) {
    const j = Math.floor(rnd() * (i + 1));
    [из[i], из[j]] = [из[j] as number, из[i] as number];
  }
  return из;
}

/**
 * СКОЛЬКО СЛОВ БЕРЁМ НА УРОВНЕ. Это одновременно лестница трудности и то, что
 * держит клетку читаемой: см. замер в шапке — сторона сетки решается числом
 * слов, а не языком.
 */
export const СЛОВ_МИН = 6;
export const СЛОВ_МАКС = 10;
export function словНаУровне(level: number): number {
  const L = Math.max(1, Math.floor(level));
  return Math.min(СЛОВ_МАКС, СЛОВ_МИН + Math.floor((L - 1) / 6));
}

/**
 * СКОЛЬКО ПОДСКАЗОК ДАЁТСЯ НА УРОВНЕ — вторая ось лестницы.
 *
 * 📍 Правило Дениса 06.09.2026: «никаких потолков нет нигде, всегда можно растить
 * сложность, вопрос подхода». Замер прогоном всех уровней: у кроссворда было
 * ПЯТЬ различимых настроек (слов 6, 7, 8, 9, 10), последняя новая на 25-м, и
 * дальше уровни не отличались ничем.
 *
 * ⚠️ Число слов расти не может, и это замер вёрстки, а не вкус: сторона сетки
 * решается числом слов, и при 6→10 в телефонную коробку 12×12 влезает 88,3%
 * раскладок; одиннадцатое слово выводит сетку за экран.
 *
 * ⚠️ Ось времени кроссворду не подходит по устройству: таймера у режима нет
 * вовсе, а вводить его значит менять жанр — здесь думают, а не спешат.
 *
 * Остаётся цена ошибки. Подсказка открывает букву и уже считается в исход
 * (`подсказок` уходит в onComplete), но лимита у неё не было — то есть уровень
 * всегда можно было пройти, открыв всё. Убывание 5 → 0 делает поздние уровни
 * действительно закрытыми для перебора. Шаг редкий: каждая отнятая подсказка
 * меняет партию сильнее, чем лишнее слово в сетке.
 */
export const ПОДСКАЗОК_МАКС = 5;
export function подсказокНаУровне(level: number): number {
  const L = Math.max(1, Math.floor(level));
  const послеСлов = Math.max(0, L - 25);
  return Math.max(0, ПОДСКАЗОК_МАКС - Math.floor(послеСлов / 8));
}

/** Слова уровня: самые длинные из раскладки — они задают хребет сетки. */
export function словаУровня(pack: { words: readonly string[] }, level: number): string[] {
  const n = словНаУровне(level);
  return [...new Set(pack.words.map((w) => w.toUpperCase()))]
    .sort((a, b) => (b.length - a.length) || (a < b ? -1 : 1))
    .slice(0, n);
}

/** Слово найдено? Сравнение регистронезависимое — банк букв рисуется прописными. */
export function естьВКроссворде(к: Кроссворд, слово: string): boolean {
  const s = слово.toUpperCase();
  return к.слова.some((w) => w.слово === s);
}

/** Все слова открыты. */
export function кроссвордСобран(к: Кроссворд, найдены: readonly string[]): boolean {
  const н = new Set(найдены.map((s) => s.toUpperCase()));
  return к.слова.every((w) => н.has(w.слово));
}

/**
 * ПОДСКАЗКА — ОТКРЫВАЕТ ОДНУ БУКВУ САМОГО КОРОТКОГО НЕНАЙДЕННОГО СЛОВА.
 * Не первую букву слова целиком: в кроссворде открытая буква работает на два
 * слова сразу, и одной хватает, чтобы сдвинуться с мёртвой точки.
 */
export function подсказкаКроссворда(
  к: Кроссворд, найдены: readonly string[], открыто: Record<string, number> = {},
): { слово: string; открыто: number } | null {
  const н = new Set(найдены.map((s) => s.toUpperCase()));
  const осталось = к.слова
    .map((w) => w.слово)
    .filter((s) => !н.has(s) && (открыто[s] ?? 0) < s.length - 1);
  if (осталось.length === 0) return null;
  const слово = осталось.reduce((a, b) => (b.length < a.length ? b : a));
  return { слово, открыто: (открыто[слово] ?? 0) + 1 };
}

/** Партия начата: хоть одно слово найдено. Нужна `module-games-guard`. */
export function кроссвордНачат(найдены: readonly string[]): boolean {
  return найдены.length > 0;
}
