/**
 * СЛОВА ЗАДАННОЙ ДЛИНЫ — ДЛЯ КЛАССИЧЕСКИХ АНАГРАММ НА ЯЗЫКАХ БЕЗ СВОЕГО БАНКА.
 *
 * 🔴 ЗАЧЕМ. Классика кормится из `anagramWords.json`, где ключи только `ru` и
 * `en`, и экран разруливал это строкой `const cl = isRu ? 'ru' : 'en'` — то есть
 * ЛЮБОЙ не-русский язык получал АНГЛИЙСКИЙ банк. Открыть немецкий, не тронув
 * источник, значило бы показать немцу английские слова под немецкой подписью;
 * именно поэтому список языков классики был заперт на двух.
 *
 * 🟢 ПОЧЕМУ БЕРЁМ ОТСЮДА, А НЕ СОБИРАЕМ НОВЫЙ ФАЙЛ. Наборы «Найди все слова» УЖЕ
 * лежат в бандле и уже прошли гейт на бранную лексику — новых байт не нужно
 * вовсе. Замер 06.09.2026, уникальных слов 4–8 букв: de 5353 · es 3824 ·
 * fr 3868 · it 4707 · pt 5261. Для сравнения, курированные банки: ru 549, en 489.
 *
 * ⚠️ У СЛОВ ОТСЮДА НЕТ ПОДСКАЗКИ И ТЕМЫ, и это осознанно. Подсказка в классике
 * необязательна — у неё свой тумблер, и при выключенном она пуста и так. Тема
 * фильтрует только размеченные слова, поэтому язык без разметки тем просто не
 * предлагает эту ось. Обещать подсказку и отдавать пустую строку было бы хуже,
 * чем честно её не иметь.
 *
 * ⚠️ ДЕВЯТИБУКВЕННЫХ СЛОВ ЗДЕСЬ НЕТ НИ У ОДНОГО ЯЗЫКА: базы наборов не длиннее
 * восьми, значит и подслова тоже. Вызов с len=9 вернёт пусто — это не поломка,
 * а граница данных, и экран обязан её учитывать.
 */
const КЭШ_ПО_ДЛИНЕ = new Map<string, string[]>();

export function словаПоДлине(locale: string, len: number): string[] {
  const ключ = `${locale}:${len}`;
  const готовое = КЭШ_ПО_ДЛИНЕ.get(ключ);
  if (готовое) return готовое;
  const набор = НАБОРЫ[locale];
  if (!набор) { КЭШ_ПО_ДЛИНЕ.set(ключ, []); return []; }
  const собрано = new Set<string>();
  for (const пак of набор) {
    if ([...пак.base].length === len) собрано.add(пак.base);
    for (const w of пак.words) if ([...w].length === len) собрано.add(w);
  }
  const итог = [...собрано];
  КЭШ_ПО_ДЛИНЕ.set(ключ, итог);
  return итог;
}

/**
 * БАНК КЛАССИКИ ДЛЯ ЯЗЫКА БЕЗ КУРИРОВАННОГО СЛОВАРЯ — СО СПУСКОМ ПО ДЛИНЕ.
 *
 * 🔴 ПОЧЕМУ СПУСК ОБЯЗАТЕЛЕН. `LEVEL_LENGTHS` классики просит длину 9 на уровнях
 * 11–15, а базы наборов не длиннее восьми — девятибуквенных подслов нет ни у
 * одного языка (замер 06.09.2026: ровно 0 у всех десяти). Без спуска банк
 * приходил бы пустым ровно там, куда доходит игрок.
 *
 * 🔴 ПОЧЕМУ ЗДЕСЬ, А НЕ НА ЭКРАНЕ. Сначала спуск был написан в `anagrams.tsx`, а
 * проба повторяла его своей копией — и мутация «подменить язык английским»
 * ПРОШЛА МИМО обеих: копия проверяла себя, экран никто не спрашивал. Один
 * экземпляр на оба потребителя убирает эту щель.
 *
 * Порог 4 слова — тот же, что у отката по теме: меньше нечего тасовать.
 */
export function банкКлассики(locale: string, len: number): string[] {
  for (let n = len; n >= 4; n--) {
    const слова = словаПоДлине(locale, n);
    if (слова.length >= 4) return слова;
  }
  return [];
}

/**
 * 🔴 ПОРЯДОК УРОВНЕЙ ЗАДАЁТСЯ ЗДЕСЬ, А НЕ ПОРЯДКОМ СТРОК В ФАЙЛЕ.
 *
 * 📍 ЗАМЕР 06.09.2026, из-за которого это заведено. `allWordsPack` брал раскладку
 * по индексу, то есть уровень N был просто N-й строкой JSON. У пяти наборов,
 * собранных в тот день, строки лежат по алфавиту — и слов на раскладку по
 * четвертям выходило 12,8 · 12,6 · 12,7 · 12,6. Лестницы не было ВООБЩЕ: сороковой
 * уровень ровно такой же, как первый. У ru и en она появилась случайно, как
 * побочный эффект чужой правки (базы стали отбираться по частоте), — то есть
 * держалась на том, чем сортировал сборщик.
 *
 * ⚠️ ЧИСЛО СЛОВ — И ЕСТЬ ТРУДНОСТЬ. Раскладка на шесть целей закрывается за
 * минуту, на восемнадцать — это уже сеанс. Поэтому сортируем по нему.
 *
 * 🔴 ВТОРОЙ КЛЮЧ — ПОРЯДОК СТРОК В ФАЙЛЕ, А НЕ АЛФАВИТ. Второй ключ нужен, иначе
 * «уровень N» перестал бы повторяться, — но сортировка по базе возвращала ровно
 * тот дефект, ради которого сборщики переводили на частотный ранг, просто этажом
 * ниже: не по всему набору, а внутри каждой ступени.
 *
 * 📍 Замер 06.09.2026, при уже зелёном гейте лестницы: первым уровнем английского
 * вставало `ability`, за ним `activate`, `against`, `already`, `alright` — азбука.
 * В первой ступени 130 раскладок, и места их баз по частоте шли от 1-го до
 * 1998-го, то есть узнаваемость внутри ступени была случайной. У русского то же:
 * уровень 1 «автомат», 599-й по частоте из 1061.
 *
 * Строки в JSON лежат по частотному рангу — так их пишет сборщик. Значит
 * исходный индекс и есть «насколько слово узнаваемо», и он же даёт устойчивость
 * порядка. Сравнение идёт по нему, а не по алфавиту.
 */
const ЛЕСТНИЦЫ = new Map<string, AllWordsPack[]>();
function лестница(locale: string): AllWordsPack[] {
  const готовая = ЛЕСТНИЦЫ.get(locale);
  if (готовая) return готовая;
  const набор = НАБОРЫ[locale] ?? НАБОРЫ.en ?? [];
  const место = new Map(набор.map((p, i) => [p.base, i]));   // порядок строк = частота
  const из = [...набор].sort((a, b) =>
    (a.words.length - b.words.length) || (место.get(a.base)! - место.get(b.base)!));
  ЛЕСТНИЦЫ.set(locale, из);
  return из;
}

/**
 * Раскладка уровня. Детерминированно от уровня: уровень N всегда даёт одну и ту
 * же раскладку, а набор проходится по кругу — от коротких раскладок к длинным.
 */
export function allWordsPack(locale: string, level: number): AllWordsPack | null {
  const набор = лестница(locale);
  if (набор.length === 0) return null;
  const i = (Math.max(1, Math.floor(level)) - 1) % набор.length;
  return набор[i] ?? null;
}

/**
 * Буквы банка — это ПЛИТКИ базы, перемешанные детерминированно от уровня.
 *
 * ⚠️ ЗЕРНО — ЭТО НЕ ТОЛЬКО НОМЕР УРОВНЯ. Кнопка «перемешать» на экране передаёт
 * сюда `уровень + число нажатий`: порядок меняется, состав нет, и при повторном
 * заходе на уровень с нуля раскладка та же самая. Так у Zen Word и «Моря слов»:
 * когда взгляд залип на одном порядке, помогает именно перестановка.
 *
 * ⚠️ Порядок перемешивается, а состав нет: банк обязан быть ровно буквами базы,
 * иначе слово из целей окажется несобираемым. Тот же урок, что в «Слове-квадрате»,
 * где САЛАТ не набирался при одной плитке «А».
 */
export function allWordsLetters(pack: AllWordsPack, seed: number): string[] {
  const буквы = [...pack.base];
  let s = (Math.floor(seed) || 1) >>> 0;
  const дальше = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 0x100000000; };
  for (let i = буквы.length - 1; i > 0; i--) {
    const j = Math.floor(дальше() * (i + 1));
    [буквы[i], буквы[j]] = [буквы[j]!, буквы[i]!];
  }
  return буквы;
}

/** Собирается ли слово из плиток банка, беря каждую не больше раза. */
export function собираетсяИзПлиток(слово: string, плитки: readonly string[]): boolean {
  const остаток = [...плитки];
  for (const ch of слово) {
    const i = остаток.indexOf(ch);
    if (i < 0) return false;
    остаток.splice(i, 1);
  }
  return true;
}

export type ИсходСлова = 'цель' | 'повтор' | 'бонус' | 'мимо';

/**
 * 🔴 СЛОВАРЬ ЯЗЫКА — ВСЕ СЛОВА ВСЕХ ЕГО РАСКЛАДОК, СОБРАННЫЕ ОДИН РАЗ.
 *
 * Нужен ради бонусных слов: человек собрал из букв базы настоящее слово, которое
 * просто не попало в цели этого уровня. Отдельный словарь заводить не за чем —
 * набор языка сам и есть проверенный список: каждое слово в нём прошло отбор по
 * частоте, морфологии и стоп-листу.
 */
const СЛОВАРИ = new Map<string, Set<string>>();
function словарьЯзыка(locale: string): Set<string> {
  const готовый = СЛОВАРИ.get(locale);
  if (готовый) return готовый;
  const из = new Set<string>();
  for (const p of НАБОРЫ[locale] ?? НАБОРЫ.en ?? []) {
    из.add(p.base);
    for (const w of p.words) из.add(w);
  }
  СЛОВАРИ.set(locale, из);
  return из;
}

/**
 * Что случилось со сданным словом. Найденные передаются, а не хранятся тут.
 *
 * 🔴 «БОНУС» — ЭТО НЕ ПОБЛАЖКА, А ЧЕСТНОСТЬ. Раньше настоящее слово, собранное из
 * букв базы, получало «мимо» и пропадало: человек видел, что слово верное, и не
 * понимал, за что его отвергли. Отчёт Дениса про соседний режим был ровно об
 * этом — «ввожу любое слово, что можно составить, оно не фиксируется».
 *
 * Уровень по-прежнему закрывается ТОЛЬКО целями: бонус идёт в копилку и не
 * приближает конец. Иначе он превратился бы в обход задачи.
 *
 * ⚠️ Локаль нужна, потому что словарь у каждого языка свой. Без неё пришлось бы
 * искать слово во всех восьми — и корейское чамо-слово нашлось бы в русском
 * наборе ровно никогда, зато проверка стала бы вдесятеро дороже.
 */
export function сдатьСлово(
  pack: AllWordsPack, слово: string, найдены: readonly string[], locale?: string,
): ИсходСлова {
  const w = слово.toLowerCase();
  if (найдены.indexOf(w) >= 0) return 'повтор';
  if (pack.words.indexOf(w) >= 0) return 'цель';
  if (locale && w !== pack.base && собираетсяИзПлиток(w, [...pack.base])
      && словарьЯзыка(locale).has(w)) return 'бонус';
  return 'мимо';
}

export function всёНайдено(pack: AllWordsPack, найдены: readonly string[]): boolean {
  return pack.words.every((w) => найдены.indexOf(w) >= 0);
}

/**
 * Подсказка: самое КОРОТКОЕ ненайденное слово, и открывается у него первая буква.
 * Короткое, потому что подсказка обязана сдвинуть с мёртвой точки, а не решить
 * уровень; урок филвордов того же дня — подсказка, не окупающая свою цену,
 * читается как «не работает».
 */
export function подсказкаAllWords(
  pack: AllWordsPack,
  найдены: readonly string[],
  открыто: Readonly<Record<string, number>> = {},
): { слово: string; открыто: number } | null {
  /**
   * 🔴 БЕРЁМ САМОЕ КОРОТКОЕ ИЗ ТЕХ, ГДЕ ЕЩЁ ЕСТЬ ЧТО ОТКРЫВАТЬ.
   *
   * 📍 Найдено игрой 06.09.2026: подсказка всегда бралась за самое короткое
   * слово, а у него открывать можно не больше `длина − 1` буквы (иначе она
   * решает слово целиком). Третье нажатие на трёхбуквенном слове списывало
   * подсказку и не делало НИЧЕГО — ровно то, на что Денис жаловался в
   * филвордах: «подсказка ни фига не работает».
   */
  const осталось = pack.words
    .filter((w) => найдены.indexOf(w) < 0 && (открыто[w] ?? 0) < w.length - 1);
  if (осталось.length === 0) return null;
  const слово = осталось.reduce((a, b) => (b.length < a.length ? b : a));
  return { слово, открыто: (открыто[слово] ?? 0) + 1 };
}

/** «Есть что терять»: хоть одно слово найдено. */
export function allWordsНачат(найдены: readonly string[]): boolean {
  return найдены.length > 0;
}
