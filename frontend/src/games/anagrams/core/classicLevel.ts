/** Длина слова по уровню. Девять — потолок: девятибуквенных слов у банков 56 и 49. */
export const LEVEL_LENGTHS = [4, 4, 5, 5, 6, 6, 7, 7, 8, 8, 9, 9, 9, 9, 9] as const;
export type WordLen = 4 | 5 | 6 | 7 | 8 | 9;

/** Пол времени на слово. При девяти буквах это 1,7 с на букву — быстро, но достижимо. */
export const ПОЛ_СЕК = 15;
/** Уровень, на котором длина слова упёрлась и включается ось времени. */
const ДЛИНА_УПЁРЛАСЬ = 15;

export interface ClassicLevelCfg {
  length: WordLen;
  trials: number;
  wordSec: number;
}

/**
 * 📍 ПРАВИЛО ДЕНИСА 06.09.2026: «никаких потолков нет нигде, всегда можно растить
 * сложность, вопрос подхода». Замер прогоном всех уровней: было 12 различимых
 * настроек, последняя новая на 15-м — дальше длина упёрта в девять, а время в
 * тридцать секунд, и уровни 16+ ничем не отличались.
 *
 * Длина расти не может: девятибуквенных слов у курированных банков 56 (ru) и
 * 49 (en), а у языков без банка их нет вовсе — наборы «Найди все слова» не
 * длиннее восьми букв. Зато тридцать секунд были ВЫБРАННЫМ числом, а не границей.
 *
 * ⚠️ Ось «цена ошибки» классике не подходит, и это замер, а не лень: подсказка
 * здесь не тратится по кнопке, а показывается сама и управляется ТУМБЛЕРОМ
 * игрока. Сделать её ступенью значило бы отнимать у человека то, что он включил.
 */
export function classicLevel(level: number): ClassicLevelCfg {
  const L = Math.max(1, Math.floor(level) || 1);
  const length = LEVEL_LENGTHS[Math.min(L, LEVEL_LENGTHS.length) - 1] as WordLen;
  const trials = 10;
  const базоваяСек = L <= 6 ? 0 : Math.max(30, 98 - (L - 6) * 8);
  const послеДлины = Math.max(0, L - ДЛИНА_УПЁРЛАСЬ);
  const wordSec = базоваяСек === 0 ? 0
    : Math.max(ПОЛ_СЕК, базоваяСек - Math.floor(послеДлины / 2));
  return { length, trials, wordSec };
}
