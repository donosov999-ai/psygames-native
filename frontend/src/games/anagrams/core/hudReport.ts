export interface ОтчётРежима {
  /** Сколько целей закрыто. */
  найдено: number;
  /** Сколько целей всего. */
  всего: number;
  /** Взятые подсказки — цена уровня. */
  подсказок: number;
  /** Промахи там, где режим их считает (слово-квадрат). */
  промахов?: number;
  /** Бонусные слова копилки — только у «Найди все слова». */
  бонусов?: number;
}

/**
 * 🔴 УПРАВЛЕНИЕ РЕЖИМА — ПЛОСКИЙ МЕШОК СТАБИЛЬНЫХ ССЫЛОК, А НЕ МАССИВ ДЕЙСТВИЙ.
 *
 * 📍 РЕШЕНИЕ ДЕНИСА 07.09.2026: прибить нижние полосы всех режимов к каркасу,
 * как у классики. Каркасу нужен готовый узел в проп `toolbar`, а кнопки жили
 * ВНУТРИ компонентов режимов и зависели от их состояния (длина набранной линии,
 * «уровень закрыт», остаток подсказок).
 *
 * ⚠️ ПОЧЕМУ НЕ МАССИВ `ДействиеРежима[]`, КАК Я СНАЧАЛА ЗАВЁЛ. Массив объектов
 * пересобирается на КАЖДОЙ отрисовке, экран кладёт его в состояние, состояние
 * вызывает следующую отрисовку — партия крутится в петле на каждом касании поля.
 * Плоский мешок из стабильных `useCallback` и примитивных флагов такого не даёт:
 * зависимости эффекта сравниваются по значению и по неизменной ссылке.
 *
 * Приём взят готовым из `src/games/dots-connect/DotsConnectGame.tsx` (`onAux`,
 * строки 560-578) — там та же петля разобрана в комментарии и решена так же.
 *
 * ⚠️ РАСКЛАДКА ПО СЛОТАМ — СМЫСЛОВАЯ, ЕЁ ЗАДАЁТ КАРКАС (`GameShell.tsx:215-278`):
 *   низ (`toolbar`)         = ОТВЕТ игрока: «Сброс» правит черновик, «Проверить» сдаёт;
 *   шапка (`headerActions`) = служебное: «Подсказка», «Перемешать».
 * Правило выведено замером по 43 играм и стережётся `slot-meaning.test.ts` и
 * живым `scripts/slot-audit.mjs`. Класть подсказку вниз нельзя даже когда там пусто.
 */
export interface УправлениеРежима {
  /** Сброс набранного черновика. `null` — у режима такой кнопки нет. */
  сброс: (() => void) | null;
  /** Есть ли что сбрасывать прямо сейчас. */
  сбросДоступен: boolean;
  /** Сдача ответа. `null` — режим сдаёт сам (у «Слово-квадрата» на пятой букве). */
  сдать: (() => void) | null;
  /** Набрано ли достаточно, чтобы сдавать. */
  сдатьДоступно: boolean;
  /** Подсказка — служебное, едет в шапку. */
  подсказка: (() => void) | null;
  подсказкаДоступна: boolean;
  /** Остаток подсказок, если у режима есть лимит; иначе не показываем счётчик. */
  подсказокОсталось?: number;
  /** Перемешать плитки — служебное, едет в шапку. Есть только у «Найди все слова». */
  перемешать: (() => void) | null;
}
