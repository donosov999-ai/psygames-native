import { StyleSheet } from 'react-native';

/*
  ⚠️ ТИП ДЕЙСТВИЯ ОТСЮДА УБРАН. Сначала я завёл `ДействиеРежима` и массив
  действий — но массив пересобирается на каждой отрисовке и зацикливает экран,
  который держит его в состоянии. Рабочая форма — плоский мешок стабильных
  ссылок `УправлениеРежима` в `core/hudReport.ts`, рядом с отчётом счётчиков:
  оба про одно и то же — режим отдаёт ДАННЫЕ, вид решает каркас.
*/

export const ВЫСОТА_КНОПКИ = 48;

export const стилиРежима = StyleSheet.create({
  /**
   * Ряд действий. `flexWrap` без `maxWidth` НЕ переносит — ряду не от чего
   * отсчитывать край, он просто едет за экран. Замер 07.09.2026: четыре кнопки
   * занимали 519 точек при экране 375, две из них были обрезаны.
   */
  действия: {
    flexDirection: 'row',
    flexWrap: 'wrap',
    justifyContent: 'center',
    gap: 10,
    maxWidth: '100%',
    // Ряд занимает всю выданную каркасом полосу — иначе кнопкам не от чего
    // отсчитывать свою долю и они снова разъедутся по строкам.
    alignSelf: 'stretch',
  },
  /**
   * 🔴 КНОПКИ ДЕЛЯТ ВЫДАННУЮ ШИРИНУ, А НЕ ТРЕБУЮТ СВОЮ.
   *
   * 📍 Замер живьём 07.09.2026, 375×812, режим «Все слова»: каркас отдаёт под
   * нижнюю полосу 243 точки (по 66 с каждого края — там висят справка и чат),
   * а двум кнопкам при `minWidth: 110` и отступах по 24 нужно 264. Разница в
   * 21 точку ставила их в ДВА РЯДА: «Сбросить» на 68 от низа, «Проверить» на 10.
   *
   * ⚠️ Жёсткая ширина здесь вредна вдвойне: длина подписи меняется с языком
   * («Проверить» ↔ «Comprobar» ↔ «Überprüfen»), и на любом переводе подлиннее
   * ряд ломался бы снова. Поэтому ширину назначает не кнопка, а полоса.
   */
  кнопка: {
    minHeight: ВЫСОТА_КНОПКИ,
    flexGrow: 1,
    flexShrink: 1,
    flexBasis: 0,
    minWidth: 0,
    maxWidth: 200,
    paddingHorizontal: 12,
    paddingVertical: 10,
    borderRadius: 16,
    borderWidth: 1.5,
    alignItems: 'center',
    justifyContent: 'center',
  },
  кнопкаТекст: { fontSize: 15, fontWeight: '700' },
});
