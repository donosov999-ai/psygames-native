import { levelOutcome } from '@/src/services/levelOutcome';
/**
 * Состояние подхода: что уже наработано и какая из этого выходит цифра.
 *
 * 🔴 ПОЧЕМУ ЭТИ ДВЕ ФУНКЦИИ ЖИВУТ В ЯДРЕ, А НЕ В КОМПОНЕНТЕ. Обе — предмет
 * проверок, которые нельзя провести чтением разметки: «есть что терять» гейт
 * `module-games-guard` ГОНЯЕТ, а медиана — главная цифра упражнения, и её
 * поведение на чётной длине и на пустом списке должно быть закреплено пробой,
 * а не намерением.
 */
import type { ScholarsAttempt } from './types';

/**
 * Есть ли что терять при выходе.
 *
 * Черта — ПЕРВАЯ ЗАПИСАННАЯ ПОПЫТКА, а не начало подхода: набор позиций
 * повторим по зерну, и уход с нулём попыток не теряет ничего, кроме пары
 * секунд. Как только попытка записана, она уже в медиане и в доле верных —
 * молча стирать её нельзя.
 *
 * ⚠️ Прозеванная по времени позиция — ТОЖЕ попытка: она идёт в ошибки и
 * портит подход ровно так же, как неверный ход. Отдельного «ну я же не
 * ходил» здесь нет.
 */
export function scholarsArmed(attempts: readonly ScholarsAttempt[]): boolean {
  return attempts.length > 0;
}

/**
 * Медиана времени — 🔴 ГЛАВНАЯ ЦИФРА УПРАЖНЕНИЯ.
 *
 * Не среднее: одна зевнутая позиция с полным лимитом (20 секунд против
 * полутора) утащила бы среднее так, что рост скорости стал бы не виден.
 * Медиана к такому выбросу равнодушна — она и уходит в сессию.
 */
export function медианаМс(в: readonly number[]): number {
  if (!в.length) return 0;
  const s = [...в].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m]! : Math.round((s[m - 1]! + s[m]!) / 2);
}

/** Толщина рамки доски. Считается ВНУТРЬ ширины: у react-native-web `box-sizing: border-box`. */
export const РАМКА_ДОСКИ = 2;

/**
 * 🔴 РАЗМЕР КЛЕТКИ — ЦЕЛОЕ ЧИСЛО, И ВОСЕМЬ ШТУК ОБЯЗАНЫ ВЛЕЗТЬ В РЯД.
 *
 * 📍 ЧТО СЛОМАЛОСЬ 05.09.2026, замер в браузере на 375 px. Клетка считалась как
 * `size / 8`: при size = 343 это 42,875. Восемь таких = 343, а внутрь рамки
 * помещается 339 — восьмая клетка каждого ряда переносилась на следующую
 * строку, и доска ехала лесенкой: сверху семь колонок, снизу обрезанные фигуры.
 * Позиция при этом РАЗБИРАЛАСЬ верно — движок не при чём, врал только глаз.
 *
 * Дробная клетка ломает и без переноса: браузер округляет каждую по-своему, и
 * поля разъезжаются на пиксель — на доске это видно сразу.
 *
 * Поэтому клетка ЦЕЛАЯ, а ширина доски выводится из неё, а не наоборот.
 */
export function размерКлетки(size: number): number {
  return Math.max(1, Math.floor((size - РАМКА_ДОСКИ * 2) / 8));
}

/** Ширина доски под целую клетку: восемь клеток плюс рамка с двух сторон. */
export function ширинаДоски(size: number): number {
  return размерКлетки(size) * 8 + РАМКА_ДОСКИ * 2;
}

/**
 * 🔴 ЗВЁЗДЫ — ПО АБСОЛЮТНОМУ ВРЕМЕНИ УЗНАВАНИЯ, А НЕ ПО ДОЛЕ ОТ ОКНА.
 *
 * 📍 ЗАМЕР НА ЖИВЫХ ПОДХОДАХ 05.09.2026 (15 сыгранных, база `cognitive_sessions`):
 * прежнее правило «медиана ≤ 33% отведённого времени» дало ТРИ ЗВЕЗДЫ в 14
 * случаях из 15. Лестница из сорока ступеней, а награда одна и та же на всех —
 * это не оценка, а поздравление.
 *
 * Причина арифметическая: доля считалась от ОКНА ОТВЕТА (20…4 с), а медиана
 * меряет время до первого касания — 1,3…2,9 с в живых подходах. На нижних
 * уровнях 33% от двадцати секунд это 6,6 с, туда попадает кто угодно.
 *
 * Порог теперь в миллисекундах и РАСТЁТ с уровнем: наверху позиции труднее
 * (рейтинг 1299…2000 против 584…967), и требовать там ту же скорость нечестно.
 * На пятнадцати живых подходах новое правило даёт 4 подхода на три звезды,
 * 6 на две и 5 на одну — то есть лестница снова что-то значит.
 */
export function starsFor(medianMs: number, level: number): 1 | 2 | 3 {
  if (!medianMs) return 1;
  const L = Math.max(1, level);
  const наТри = 1400 + (L - 1) * 20;      // L1 1,40 с → L40 2,18 с
  const наДве = 2400 + (L - 1) * 25;      // L1 2,40 с → L40 3,38 с
  if (medianMs <= наТри) return 3;
  if (medianMs <= наДве) return 2;
  return 1;
}

/**
 * 🔴 ЧТО ПРОИСХОДИТ В КОНЦЕ ПОДХОДА — ОДНИМ РЕШЕНИЕМ, А НЕ ЦЕПОЧКОЙ `if` В ЭКРАНЕ.
 *
 * 📍 Пока это жило в разметке, из четырёх условий сложился тупик: подход в
 * режиме уходил в карточку итога без ступени и без «дальше». Отчёт Дениса
 * 05.09.2026: «партию прошёл, завершилось всё и всё висит, где следующий
 * уровень». Проба на такую логику возможна, только если логика — функция.
 */
export type ФазаПослеПодхода = 'config' | 'cleared' | 'result';
export type ДвижениеСтупени = 'вверх' | 'вниз' | 'стоит';

/**
 * 🔴 КУДА ДВИГАТЬ СТУПЕНЬ В ПОТОКЕ — ПО МЕДИАНЕ, А НЕ ПО ДОЛЕ ВЕРНЫХ.
 *
 * 📍 РЕШЕНИЕ ДЕНИСА 06.09.2026. До него поток ступень не двигал вовсе: в нём нет
 * границы подхода, брать было нечего, и на экране итога честно не появлялось
 * «дальше». Но жалоба `67eade4e` («партию прошёл, всё висит, где следующий
 * уровень») пришла именно после подхода, и ответ «в потоке ступеней не бывает»
 * человека не устраивает.
 *
 * ⚠️ ПОРОГ НЕ ВЫДУМАН — ЭТО УЖЕ ОТКАЛИБРОВАННАЯ ШКАЛА `starsFor`. Она подобрана
 * по пятнадцати живым подходам и даёт на них 4 подхода на три звезды, 6 на две и
 * 5 на одну. Заводить рядом второй порог значило бы, что «быстро» в звёздах и
 * «быстро» в лестнице — разные величины, и человек увидит три звезды при
 * понижении уровня.
 *
 * 🔴 И ПОЧЕМУ ИМЕННО В ПОТОКЕ ЭТО ЧЕСТНЕЕ, ЧЕМ В ОБЫЧНОМ ПОДХОДЕ. Медиана по
 * восьми позициям гуляет ±25% (замер Монте-Карло, 4000 подходов), по сорока —
 * ±12%. Поток при секунде-двух на позицию даёт СОТНИ позиций за десять минут,
 * то есть его медиана точнее любой другой в игре. Двигать ступень по ней —
 * самый надёжный замер, какой у нас есть, а не самый слабый.
 */
export function ступеньПоМедиане(медианаМс: number, уровень: number): ДвижениеСтупени {
  // Ни одного верного ответа — медианы нет; это не повод понижать молча.
  if (!медианаМс) return 'стоит';
  const звёзды = starsFor(медианаМс, уровень);
  return звёзды === 3 ? 'вверх' : звёзды === 1 ? 'вниз' : 'стоит';
}

export function итогПодхода(о: {
  /** Было ли хоть одно касание: подход без касаний не считается вовсе. */
  касались: boolean;
  /** Взят ли порог доли верных. */
  взял: boolean;
  /** Поток — единственный режим без ступеней: десять минут подряд без границ подхода. */
  поток: boolean;
  /** Экран открыт с заданным уровнем извне (хаб, ссылка) — лестницу не трогаем. */
  предустановка: boolean;
  /** Разрешено ли этой игре цеплять следующий уровень. */
  цепочка: boolean;
}): { фаза: ФазаПослеПодхода; ступень: ДвижениеСтупени } {
  // Подход без единого касания не считается вовсе: назад в настройку, ничего не пишем.
  if (!о.касались) return { фаза: 'config', ступень: 'стоит' };
  /**
   * ⚠️ ОБЩЕЕ ПРАВИЛО ИГРЫ, А НЕ ВТОРАЯ ЕГО КОПИЯ. `levelOutcome` — то самое
   * место, где решается судьба уровня после партии; у него же стоит гейт
   * `warmup-level-drift`. Поток для этого правила такой же «не личная партия»,
   * как шаг зарядки: в нём десять минут подряд без границ подхода, брать там
   * нечего.
   */
  const о2 = levelOutcome({ isPreset: о.предустановка || о.поток, cleared: о.взял });
  const ступень: ДвижениеСтупени = о2.raiseLevel ? (о.цепочка ? 'вверх' : 'стоит')
    : о2.lowerLevel ? 'вниз' : 'стоит';
  return { фаза: о2.phase, ступень };
}
