/**
 * Состояние подхода: что уже наработано и какая из этого выходит цифра.
 *
 * 🔴 ПОЧЕМУ ЭТИ ДВЕ ФУНКЦИИ ЖИВУТ В ЯДРЕ, А НЕ В КОМПОНЕНТЕ. Обе — предмет
 * проверок, которые нельзя провести чтением разметки: «есть что терять» гейт
 * `module-games-guard` ГОНЯЕТ, а медиана — главная цифра упражнения, и её
 * поведение на чётной длине и на пустом списке должно быть закреплено пробой,
 * а не намерением.
 */
import type { ScholarsAttempt } from './types';

/**
 * Есть ли что терять при выходе.
 *
 * Черта — ПЕРВАЯ ЗАПИСАННАЯ ПОПЫТКА, а не начало подхода: набор позиций
 * повторим по зерну, и уход с нулём попыток не теряет ничего, кроме пары
 * секунд. Как только попытка записана, она уже в медиане и в доле верных —
 * молча стирать её нельзя.
 *
 * ⚠️ Прозеванная по времени позиция — ТОЖЕ попытка: она идёт в ошибки и
 * портит подход ровно так же, как неверный ход. Отдельного «ну я же не
 * ходил» здесь нет.
 */
export function scholarsArmed(attempts: readonly ScholarsAttempt[]): boolean {
  return attempts.length > 0;
}

/**
 * Медиана времени — 🔴 ГЛАВНАЯ ЦИФРА УПРАЖНЕНИЯ.
 *
 * Не среднее: одна зевнутая позиция с полным лимитом (20 секунд против
 * полутора) утащила бы среднее так, что рост скорости стал бы не виден.
 * Медиана к такому выбросу равнодушна — она и уходит в сессию.
 */
export function медианаМс(в: readonly number[]): number {
  if (!в.length) return 0;
  const s = [...в].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m]! : Math.round((s[m - 1]! + s[m]!) / 2);
}
