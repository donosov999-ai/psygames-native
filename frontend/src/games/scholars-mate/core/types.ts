/* psygames-scholars-mate-types · VER 1 · 05.09.2026 */
/**
 * «Детский мат» — заученные этюды НА СКОРОСТЬ.
 *
 * ЗАЧЕМ ОТДЕЛЬНОЕ УПРАЖНЕНИЕ, ЕСЛИ ЕСТЬ «ШАХМАТЫ ВСЛЕПУЮ». Там тренируется
 * удержание позиции в голове — медленно и по одной фигуре. Здесь наоборот:
 * позиция на виду, узор один и тот же, и меряется ВРЕМЯ УЗНАВАНИЯ. Просьба
 * Дениса 05.09.2026: «чтобы чисто на скорость делать заученные этюды».
 *
 * Это разные навыки и разные пробы. Узнавание узора — то, чем сильный игрок
 * отличается от слабого больше, чем глубиной расчёта (Chase & Simon, 1973:
 * мастер запоминает позицию не по фигурам, а по знакомым кускам).
 *
 * ЧЕТЫРЕ ВИДА ЗАДАНИЯ, все на одной механике «доска + один ход»:
 *   mate      — поставь детский мат в один ход;
 *   fromGames — то же, но позиция из настоящей партии Lichess, с рейтингом;
 *   sacrifice — мат с ЖЕРТВОЙ, в два-три хода (просьба Дениса тем же днём);
 *   defend    — соперник грозит матом, защитись;
 *   threat    — грозит ли мат следующим ходом, да/нет.
 *
 * 🔴 ЛОВУШКА ФОРМАТА LICHESS, из-за которой задача выглядит нерешаемой.
 * В их записи ПЕРВЫЙ ход последовательности принадлежит СОПЕРНИКУ. Позиция,
 * которую видит человек, получается только ПОСЛЕ него. Показать `fen` как есть
 * — значит показать чужую позицию и спросить ход, которого в ней нет.
 * Поэтому у таких заданий есть поле `pre`, и движок обязан его сыграть.
 */

/** Вид задания. */
/**
 * 🔴 УЗОР МАТА — ВТОРАЯ ОСЬ ЛЕСТНИЦЫ, И ОНА ПОЯВИЛАСЬ ПО ЗАМЕЧАНИЮ ДЕНИСА.
 *
 * 05.09.2026, пройдя три уровня, дословно: «по сути одна комбинация, слон и
 * ферзь, дают то за чёрных то за белых из разных позиций — я бы не сказал, что
 * это разные». Он прав: лестница меняла секунды, сторону и обстановку, а УЗОР
 * был один на все сорок уровней.
 *
 * Теперь каждые несколько ступеней приходит новый мотив, и он НАЗЫВАЕТСЯ на
 * экране — иначе человек не знает, чему научился. Замер по всей базе Lichess
 * (мат в 1 до 14-го хода, узор определён движком):
 *   scholar 10 029 · queenKnight 13 429 · queenAlone 6 146 ·
 *   knightOpening 5 806 · smothered 5 278 · bishopF7 5 136 · fool 883
 */
export type ScholarsMotif =
  | 'scholar'        // детский мат: ферзь на f7/f2 при поддержке слона
  | 'queenKnight'    // тот же удар, но поле держит конь
  | 'queenAlone'     // ферзь на f7/f2 без поддержки
  | 'bishopF7'       // матует слон, а не ферзь
  | 'fool'           // мат дурака: ферзь на h4/h5 в первые ходы
  | 'knightOpening'  // мат конём в дебюте (сюда попадает и мат Легаля)
  | 'smothered'      // удушающий мат конём
  /**
   * 🔴 ИМЕНОВАННЫЕ УЗОРЫ ДЛЯ РУЧНОГО ВЫБОРА — просьба Дениса 05.09.2026:
   * «сделай выпадающим списком выбор режима… чтобы можно было выбрать и
   * отрабатывать отдельный».
   *
   * ⚠️ В лестнице их нет, и это не забывчивость. Там узор обязан быть узнаваем
   * в ДЕБЮТНОЙ позиции, а дебютных у арабского мата 18 на 7 474 — лестницы из
   * них не выйдет. При ручном выборе человек уже знает, что тренирует, поэтому
   * ограничение снято и берётся весь пул.
   */
  | 'backRankMate' | 'pillsburysMate' | 'operaMate' | 'epauletteMate'
  | 'cornerMate' | 'hookMate' | 'swallowstailMate' | 'arabianMate'
  | 'anastasiaMate' | 'morphysMate' | 'bodenMate' | 'doubleBishopMate'
  | 'dovetailMate' | 'killBoxMate' | 'vukovicMate' | 'balestraMate'
  | 'triangleMate' | 'blindSwineMate';

export type ScholarsKind = 'mate' | 'fromGames' | 'sacrifice' | 'defend' | 'threat';

export interface ScholarsPuzzle {
  readonly kind: ScholarsKind;
  /** Позиция ДО пре-хода. Показывать человеку только после `pre`. */
  readonly fen: string;
  /** Ход соперника, который надо сыграть перед вопросом (только Lichess). */
  readonly pre?: string;
  /** Верные ходы в записи uci. У `threat` пусто. */
  readonly solutions: readonly string[];
  /** Те же ходы в записи SAN — показать «лучший» после ответа. */
  readonly san?: readonly string[];
  /**
   * Продолжение для мата в 2–3 хода: наш ход, ответ соперника, наш ход…
   * Индексы чётные — наши, нечётные — соперника.
   */
  readonly line?: readonly string[];
  /** Мат в N ходов. */
  readonly mateIn: number;
  /** Рейтинг Lichess; у своих позиций 0 — они вне лестницы рейтинга. */
  readonly rating: number;
  /** Узор мата — только у позиций из партий; у своих он всегда `scholar`. */
  readonly motif?: ScholarsMotif;
  /** Ответ да/нет для `threat`. */
  readonly threat?: boolean;
  /** Ссылка на партию — источник, называем по правилу CC0. */
  readonly url?: string;
}

export interface ScholarsLevel {
  readonly level: number;
  /** Какие виды заданий встречаются на этом уровне. */
  readonly kinds: readonly ScholarsKind[];
  /** Сколько позиций в подходе. */
  readonly count: number;
  /**
   * Сколько секунд даётся на позицию.
   *
   * 🔴 ЭТО И ЕСТЬ ОСЬ ТРУДНОСТИ, а не доля решённых. Узор один и тот же;
   * растёт не сложность узора, а требуемая скорость узнавания. Так же устроена
   * лестница у «Шульте»: та же таблица, меньше времени.
   */
  readonly seconds: number;
  /**
   * 🔴 ПОЛОСА рейтинга задач Lichess: [нижняя, верхняя]. 0,0 — только свои позиции.
   *
   * 📍 ЗАЧЕМ ПОЛОСА, А НЕ ПОТОЛОК. В VER 1 стоял односторонний фильтр
   * `rating <= maxRating`, и лестница не двигалась: медиана поданного рейтинга
   * L11 = 555, L20 = 847, L40 = 1096, а на пяти переходах она ПАДАЛА. Причина
   * арифметическая: 14 829 записей пула из 16 427 ниже 1200, поэтому «потолок
   * 1800» и «потолок 1200» дают почти одну и ту же выборку. Уровень 35 честно
   * выдавал задачи рейтинга 399.
   */
  readonly minRating: number;
  readonly maxRating: number;
  /**
   * Какие узоры разрешены на этой ступени. Список РАСТЁТ с уровнем: новый
   * мотив добавляется к прежним, а не заменяет их, — иначе выученное
   * перестаёт встречаться и забывается.
   */
  readonly motifs: readonly ScholarsMotif[];
}

export interface ScholarsAttempt {
  readonly puzzle: ScholarsPuzzle;
  /** Что сыграл человек: uci, либо 'yes'/'no' для `threat`. */
  readonly answer: string;
  readonly correct: boolean;
  /** Сколько миллисекунд заняла позиция целиком — от показа до ответа. */
  readonly ms: number;
  /**
   * 🔴 ВРЕМЯ ДО ПЕРВОГО КАСАНИЯ — И ЭТО ГЛАВНАЯ ВЕЛИЧИНА УПРАЖНЕНИЯ.
   *
   * 📍 ПОЧЕМУ НЕ `ms`. Ход делается ДВУМЯ тапами: фигура, потом клетка. По
   * закону Фиттса два тапа по доске такого размера стоят ≈1,21 с плюс саккады —
   * то есть у полного времени есть пол в районе 1,7–2,2 с, ниже которого оно не
   * опустится, сколько ни узнавай. А само узнавание знакомого куска позиции
   * (Chase & Simon, Gobet & Simon) занимает порядка 50 мс — около 2,5% от
   * измеряемого. Заявленная цель «1,2 с» была ниже стоимости одной моторики.
   *
   * Время до ПЕРВОГО касания моторику почти не содержит: палец идёт к фигуре,
   * которую глаз уже нашёл. Оно и уходит в медиану.
   *
   * ⚠️ У вопроса «грозит ли» тап один, и `msFirst === ms`. Это не подгонка:
   * там и нет второго движения.
   */
  readonly msFirst: number;
  /** Истекло время на позицию. */
  readonly timeout: boolean;
}

export interface ScholarsResult {
  readonly attempts: readonly ScholarsAttempt[];
  readonly solved: number;
  readonly total: number;
  /** Медиана времени ДО ПЕРВОГО КАСАНИЯ по верным ответам, мс — главная цифра. */
  readonly medianMs: number;
  /** Медиана полного времени позиции, мс — для сессии и сравнения с лимитом. */
  readonly medianFullMs: number;
  /** Самый быстрый верный ответ, мс. */
  readonly bestMs: number;
  /** Длиннейшая серия верных подряд. */
  readonly streak: number;
  readonly accuracy: number;
  /**
   * 🔴 ЧЕЛОВЕК ВООБЩЕ ИГРАЛ? Ни одного касания доски за весь подход — значит
   * экран просто остался открытым, а секундомер добил позиции таймаутами.
   *
   * 📍 НАЙДЕНО В ЖИВЫХ ДАННЫХ 05.09.2026: три подхода подряд с 0 решённых и
   * 10–11 «ошибками», все с нулевой медианой. Механика при этом цела —
   * прогон тех же колод через компонент даёт 10 из 10. Беда в другом: такой
   * подход засчитывался как проигранный и ПОНИЖАЛ УРОВЕНЬ за игру, которой
   * не было.
   */
  readonly touched: boolean;
}
