/** Что игрок реально может сделать прямо сейчас. */
export type MahjongExit = 'shuffle' | 'undo' | 'restart';

export interface StuckInput {
  /** Ходов на доске сейчас — `availablePairs`. */
  openPairs: number;
  /** Перетасовок осталось; -1 = без лимита (первые уровни). */
  shufflesLeft: number;
  /**
   * Перетасовка ПРОВЕРЕНА раздатчиком: она даст разбираемую доску.
   * ⚠️ Не «бюджет не пуст», а именно проверено — см. вечный отказ в шапке.
   */
  shuffleDeals: boolean;
  /** Есть что отменять И бюджет отмен не исчерпан. */
  canUndo: boolean;
}

/**
 * Выходы из положения. Пусто = доска жива, выходить неоткуда и не надо.
 * На вставшей доске список НИКОГДА не пуст: последним стоит `restart`.
 */
export function mahjongExits(s: StuckInput): MahjongExit[] {
  if (s.openPairs > 0) return [];
  const выходы: MahjongExit[] = [];
  if (s.shufflesLeft !== 0 && s.shuffleDeals) выходы.push('shuffle');
  if (s.canUndo) выходы.push('undo');
  // Ни перетасовки, ни отмены — остаётся правда: уровень придётся начать заново.
  if (выходы.length === 0) выходы.push('restart');
  return выходы;
}

/**
 * Ключ строки под доской. `null` = доска жива, идёт обычная подсказка.
 *
 * ⚠️ Ключи, а не тексты: инлайн ru/en знает два языка из двенадцати, и это уже
 * ловил гейт `ci-i18n-hardcode-guard`.
 */
export function mahjongStuckKey(s: StuckInput): string | null {
  const выходы = mahjongExits(s);
  if (выходы.length === 0) return null;
  const есть = (e: MahjongExit) => выходы.includes(e);
  if (есть('shuffle') && есть('undo')) return 'mahjongNoPairs';
  if (есть('shuffle')) return 'mahjongStuckShuffle';
  if (есть('undo')) return 'mahjongStuckUndo';
  return 'mahjongStuckRestart';
}

