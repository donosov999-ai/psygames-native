import { buildPositions, silhouetteForLevel } from './silhouettes';
import { layoutForLevel } from './layouts';
import { mahjongLevel } from '@/src/services/mahjongLevels';

/**
 * Габариты поля уровня в полуклетках — ПОСТОЯННАЯ, а не мерка по живым плиткам.
 *
 * 🔴 ЗАЧЕМ. Дважды один и тот же дефект: 26.08.2026 прыгал подъём слоёв, 02.09.2026 —
 * ширина и высота. Оба раза причина одна: величина, из которой считается размер
 * плитки и координаты ВСЕХ плиток, бралась максимумом по ОСТАВШИМСЯ плиткам. Сняли
 * пару с края — край уменьшился, размер полуклетки вырос, и доска поехала целиком.
 * Денис 02.09: «маджонг кривит ряды, скачут при выделении двух одинаковых; вроде
 * чинил — опять скачет».
 *
 * Раскладка уровня детерминирована его номером, а раздача только расставляет
 * символы по её местам. Значит край можно посчитать заранее и держать весь уровень —
 * что и делает эта функция. Тест рядом проверяет главное: предсказание НЕ МЕНЬШЕ
 * фактического края любой раздачи этого уровня; иначе защёлка в экране всё равно
 * подтянулась бы вверх, и прыжок вернулся бы.
 */
export function mahjongExtent(level: number): { x: number; y: number } {
  const p = mahjongLevel(level);
  const места = layoutForLevel(level)?.places
    ?? buildPositions(p.layers, p.pairs * 2, p.cols, silhouetteForLevel(level));
  let x = 2, y = 2;
  for (const q of места) { if (q.x + 2 > x) x = q.x + 2; if (q.y + 2 > y) y = q.y + 2; }
  return { x, y };
}
