/**
 * ЯДРО ДОСКИ МАДЖОНГА: что такое плитка, когда она свободна и сколько пар можно
 * снять ПРЯМО СЕЙЧАС.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. `isFree` жил в экране `app/games/mahjong.tsx`, и всё, чему
 * он нужен (счётчик доступных пар, набор силуэтов, проверки), тянуло бы за собой
 * целый экран с React, роутером и контекстами. Экран по-прежнему реэкспортирует
 * `Tile`/`isFree` — старые импорты и проверки не тронуты.
 */

/** Плитка на доске. x,y — в ПОЛУКЛЕТКАХ: сама плитка занимает 2×2 полуклетки. */
export interface Tile { id: number; x: number; y: number; layer: number; symbol: number; }

/** «Перекрывает ли» позиция верхнего слоя позицию нижнего (тайл 2×2 в полуклетках). */
export function overlaps(a: { x: number; y: number }, b: { x: number; y: number }): boolean {
  return Math.abs(a.x - b.x) < 2 && Math.abs(a.y - b.y) < 2;
}

/**
 * НАКРЫТА ЛИ ПЛИТКА СВЕРХУ — половина (а) правила свободы, отдельным именем.
 *
 * 🔴 Режим «скрытая информация» (задача ec15d176, §20 плана слияния): на скрытых
 * уровнях лицо плитки видно только когда СВЕРХУ никто не лежит. Зажатость с боков
 * лицо не прячет — соседние лица в жизни видны. Логика нарочно та же, что пункт
 * (а) в `isFree`: разойдутся — «?» будет стоять на нажимаемой плитке.
 */
export function coveredFromAbove(tiles: Tile[], alive: boolean[], i: number): boolean {
  const t = tiles[i];
  for (let j = 0; j < tiles.length; j++) {
    if (!alive[j] || j === i) continue;
    if (tiles[j].layer > t.layer && overlaps(tiles[j], t)) return true;
  }
  return false;
}

/** Свободен ли тайл i среди ОСТАВШИХСЯ: (а) сверху нет перекрывающего, (б) слева ИЛИ справа открыто. */
export function isFree(tiles: Tile[], alive: boolean[], i: number): boolean {
  const t = tiles[i];
  // (а) ничего на слое выше, перекрывающего позицию
  for (let j = 0; j < tiles.length; j++) {
    if (!alive[j] || j === i) continue;
    if (tiles[j].layer > t.layer && overlaps(tiles[j], t)) return false;
  }
  // (б) сосед на ТОМ ЖЕ слое вплотную слева / справа (та же y-полоса, x±2)
  let blockedL = false, blockedR = false;
  for (let j = 0; j < tiles.length; j++) {
    if (!alive[j] || j === i) continue;
    if (tiles[j].layer !== t.layer) continue;
    if (Math.abs(tiles[j].y - t.y) < 2) {
      if (Math.abs(tiles[j].x - (t.x - 2)) < 1) blockedL = true;
      if (Math.abs(tiles[j].x - (t.x + 2)) < 1) blockedR = true;
    }
  }
  return !(blockedL && blockedR);
}

/**
 * КТО ИМЕННО ДЕРЖИТ ПЛИТКУ.
 *
 * 🔴 ЗАЧЕМ. Игра умела сказать «эта плитка занята» и «доска встала», но не умела
 * показать ВИНОВНЫХ. Человек тычет в пару одинаковых рисунков, ничего не
 * происходит, и он не понимает, что мешает: правило свободной плитки читается в
 * справке, но на доске из шестидесяти плиток глазами его не применить.
 * «Заблокирована» без «кем» — это отказ без объяснения, тот же класс, что молчащая
 * судоку и молчащий самурай.
 *
 * Возвращаем ровно тех, кто отвечает за отказ, и ничего сверх:
 *   • накрывающие сверху — их придётся снять в любом случае;
 *   • боковые соседи — ТОЛЬКО если заперты ОБА бока. Один сосед плитку не держит:
 *     свободна она уже тогда, когда открыт хоть один край. Подсветить одного —
 *     значит соврать про правило.
 */
export function blockersOf(tiles: Tile[], alive: boolean[], i: number): number[] {
  const t = tiles[i];
  if (!t || !alive[i]) return [];
  const above: number[] = [];
  for (let j = 0; j < tiles.length; j++) {
    if (!alive[j] || j === i) continue;
    const o = tiles[j] as Tile;
    if (o.layer > t.layer && overlaps(o, t)) above.push(j);
  }
  const left: number[] = [];
  const right: number[] = [];
  for (let j = 0; j < tiles.length; j++) {
    if (!alive[j] || j === i) continue;
    const o = tiles[j] as Tile;
    if (o.layer !== t.layer) continue;
    if (Math.abs(o.y - t.y) >= 2) continue;
    if (Math.abs(o.x - (t.x - 2)) < 1) left.push(j);
    if (Math.abs(o.x - (t.x + 2)) < 1) right.push(j);
  }
  // Бока виноваты только вместе: открытый край снимает запрет целиком.
  const sides = left.length > 0 && right.length > 0 ? left.concat(right) : [];
  return above.concat(sides);
}

/**
 * Свобода СРАЗУ ДЛЯ ВСЕХ плиток одним проходом.
 *
 * Зачем не звать `isFree` в цикле: он сам обходит доску, и цикл поверх него даёт
 * O(n²) на каждый пересчёт — при 144 плитках это 20 тысяч сравнений на КАЖДУЮ
 * перерисовку шапки. Здесь тот же ответ считается за один обход: покрытие сверху и
 * соседей слева/справа собираем в один проход по парам, дальше только чтение.
 *
 * ⚠️ Ответ обязан СОВПАДАТЬ с `isFree` плитка-в-плитку — иначе счётчик в шапке
 * начнёт расходиться с тем, что доска реально даёт нажать. Совпадение сторожит
 * проверка `mahjong-pairs.test.ts`, и ломается она нарочно (см. её шапку).
 */
export function freeFlags(tiles: Tile[], alive: boolean[]): boolean[] {
  const n = tiles.length;
  const covered = new Array<boolean>(n).fill(false);
  const blockedL = new Array<boolean>(n).fill(false);
  const blockedR = new Array<boolean>(n).fill(false);
  for (let i = 0; i < n; i++) {
    if (!alive[i]) continue;
    const a = tiles[i];
    for (let j = i + 1; j < n; j++) {
      if (!alive[j]) continue;
      const b = tiles[j];
      if (a.layer !== b.layer) {
        // Кто выше — тот накрывает, и только при перекрытии клеток.
        if (overlaps(a, b)) { if (b.layer > a.layer) covered[i] = true; else covered[j] = true; }
        continue;
      }
      if (Math.abs(a.y - b.y) >= 2) continue;
      if (Math.abs(b.x - (a.x - 2)) < 1) { blockedL[i] = true; blockedR[j] = true; }
      else if (Math.abs(b.x - (a.x + 2)) < 1) { blockedR[i] = true; blockedL[j] = true; }
    }
  }
  const out = new Array<boolean>(n).fill(false);
  for (let i = 0; i < n; i++) out[i] = alive[i] && !covered[i] && !(blockedL[i] && blockedR[i]);
  return out;
}

/**
 * СКОЛЬКО ПАР МОЖНО СНЯТЬ ПРЯМО СЕЙЧАС.
 *
 * 🔴 ЗАЧЕМ ЭТО ВООБЩЕ. Верхний по полезности отзыв к Vita Mahjong (100 млн
 * установок) — жалоба на то, что из игры убрали окошко «сколько пар ещё можно
 * собрать»: без него человек жмёт перетасовку ВСЛЕПУЮ, не зная, встала доска или он
 * просто не видит пару. У нас перетасовка — расходуемый ресурс (одна-три на
 * уровень), то есть цена слепого нажатия ещё выше, чем в образце.
 *
 * ЗАМЕР 22.08.2026, ЗАЧЕМ ЭТО НЕ УКРАШЕНИЕ. Прогнал случайный разбор (игрок берёт
 * любую доступную пару) по 100 партий на уровень, силуэты вперемешку: доска встаёт
 * НАСМЕРТЬ в 31 % партий на 6 уровне, 38 % на 12-м и 44 % на 20-м. То есть примерно
 * каждая третья партия доходит до состояния, о котором раньше игра не сообщала
 * НИЧЕМ: плитки на месте, тапы не работают, объяснения нет. Минимум ходов, увиденный
 * по ходу партии, — один: между «всё хорошо» и «конец» бывает ровно один шаг.
 *
 * ⚠️ СЧИТАЮТСЯ СОЧЕТАНИЯ, А НЕ «сколько снимется подряд». Если свободны ТРИ
 * одинаковые плитки — это 3 разных хода (C(3,2)), а не один: какие две снимешь,
 * такая третья останется, и от выбора зависит, откроется низ или запрётся. Число
 * на экране отвечает ровно на вопрос «сколько у меня сейчас ходов», а не «сколько
 * пар доживёт до конца» — последнее без полного перебора не считается вовсе.
 */
export function availablePairs(tiles: Tile[], alive: boolean[]): number {
  const free = freeFlags(tiles, alive);
  const bySymbol = new Map<number, number>();
  for (let i = 0; i < tiles.length; i++) {
    if (!free[i]) continue;
    const s = tiles[i].symbol;
    bySymbol.set(s, (bySymbol.get(s) ?? 0) + 1);
  }
  let pairs = 0;
  for (const k of bySymbol.values()) pairs += (k * (k - 1)) / 2;
  return pairs;
}

/**
 * ГДЕ РИСОВАТЬ ПЛИТКУ: пиксельный сдвиг относительно левого верхнего угла поля.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ ДВУМЯ СТРОКАМИ В РАЗМЕТКЕ. Раньше верхний слой
 * был сдвинут ещё и В ДАННЫХ (к координате прибавлялась клетка на слой), и формула
 * `y * half - layer * offset` не могла уйти в минус. Силуэты кладут слои РОВНО друг
 * на друга, и плитка верхнего слоя в самой верхней строке (крепость и ромб на 1
 * уровне, бабочка на 6-м, замер 22.08.2026) уезжала за край контейнера и обрезалась.
 *
 * Поэтому подъём считается ОТ САМОГО ВЕРХНЕГО слоя вниз: картинка та же (чем выше
 * слой, тем выше плитка), но отрицательных координат не бывает по построению.
 * Проверка `mahjong-silhouettes.test.ts` зовёт именно эту функцию на настоящих
 * раскладках всех форм.
 */
/**
 * НА СКОЛЬКО ПИКСЕЛЕЙ ПОДНИМАТЬ КАЖДЫЙ СЛОЙ.
 *
 * 🔴 ЖИВЁТ РЯДОМ С `tilePlacement`, А НЕ В ЭКРАНЕ. Доступность считается по СЕТКЕ
 * (`overlaps`), а рисуется плитка со сдвигом, который о сетке ничего не знает и
 * НАКАПЛИВАЕТСЯ по слоям. Стоит сдвигу набежать больше полуклетки — картинка
 * начинает врать: плитка выглядит накрытой, будучи свободной, и наоборот. Отчёт
 * Дениса 03.09.2026: «слои криво доступны и скачут».
 *
 * Замер по всем 40 уровням (`mahjong-layer-offset-honest`): прежняя `half * 0.35`
 * давала 4283 плитки «выглядит накрытой, но свободна» и 369 «накрыта, но не видно».
 * Эта формула даёт 0 и 0.
 *
 * ⚠️ ПОЧЕМУ ОДНА ФУНКЦИЯ НА ЭКРАН И ПРОБУ. Своя копия правила у проверяющего — это
 * проверка собственной выдумки: экран меняют, гейт остаётся зелёным. В этом проекте
 * так уже расходилась вендор-копия ядра.
 */
export function layerOffsetFor(maxLayer: number): number {
  return Math.max(1, Math.floor(6 / Math.max(1, maxLayer)));
}

/**
 * НАСКОЛЬКО ПЛИТКА ВЕРХНЕГО СЛОЯ МЕНЬШЕ НИЖНЕЙ.
 *
 * 🔴 ЗАЧЕМ ВООБЩЕ. Отчёт Дениса 05.09.2026 по кадрам с симулятора: «оно просто
 * скачет случайным образом… смысл маджонга, что мы реально разбираем его
 * сверху». Правило свободы при этом исправно — сломана ЧИТАЕМОСТЬ.
 *
 * Разбор. 03.09 по жалобе «слои криво доступны и скачут» сдвиг слоёв был
 * уменьшен до `floor(6/maxLayer)` — 3 px на двух слоях. Геометрия перестала
 * врать, но вместе с ней исчезли и этажи: верхняя плитка ложится ПОЧТИ ТОЧНО на
 * нижнюю и закрывает её целиком. Доска выглядит одним плоским слоем, на котором
 * часть плиток притушена без видимой причины.
 *
 * ⚠️ ВЕРНУТЬ СДВИГ НЕЛЬЗЯ — на нём краснеет `mahjong-layer-offset-honest`: сдвиг
 * уводит верхнюю плитку на соседнюю нижнюю, которую она НЕ накрывает, и картинка
 * начинает обещать недоступность там, где её нет. Прежняя формула давала 4283
 * таких пары.
 *
 * Поэтому глубина держится на РАЗМЕРЕ: каждый слой выше рисуется чуть меньше и
 * по центру своей клетки, и нижняя плитка выглядывает из-под накрывающей ровной
 * рамкой. Перекрытие при этом только УМЕНЬШАЕТСЯ — соврать в сторону «выглядит
 * накрытой» такой приём не может по построению.
 */
export function tileScaleFor(layer: number, maxLayer: number): number {
  if (maxLayer <= 0) return 1;
  /**
   * 📍 ШАГ ПОДОБРАН ЗАМЕРОМ, А НЕ НА ГЛАЗ. Прогон `mahjong-layer-offset-honest`
   * по всем 40 уровням при разных значениях:
   *     0,20 / maxLayer → 2 пробы красные
   *     0,16 / maxLayer → 2
   *     0,12 / maxLayer → 1
   *     0,10 / maxLayer → 0  ← взято
   * Краснела ровно одна половина правила: «накрыта, но не видно». Ужать сильнее
   * значит оторвать верхнюю плитку от той, которую она по правилу накрывает, —
   * на глубоких уровнях полуклетка всего 12 px, и запас съедается быстро.
   * Потолок 0,07 на слой оставлен для двухслойных уровней: там 0,10/1 дало бы
   * десять процентов, а семи достаточно, чтобы рамка читалась.
   */
  const шаг = Math.min(0.07, 0.1 / maxLayer);
  return Math.max(0.7, 1 - layer * шаг);
}

/**
 * ТОН ПЛИТКИ ПО ЭТАЖУ — третий признак высоты после размера и тени.
 *
 * 🔴 ПОЧЕМУ РАЗМЕРА НЕ ХВАТИЛО. Замер 05.09.2026: на двухслойном уровне
 * полуклетка 14 px, плитка 26 px, уменьшение 7% даёт рамку в ОДИН пиксель.
 * Такую «глубину» не видно. Сдвиг ограничен пробой честности, размер — пробой
 * «накрыта, но не видно»; остаётся то, что вообще не трогает геометрию, — тон.
 *
 * Нижние этажи темнее и холоднее, верхний белый. Стопка читается как стопка,
 * а перекрытие при этом ни на пиксель не меняется.
 *
 * ⚠️ ЖИВЁТ В ЯДРЕ, А НЕ В ЭКРАНЕ: по этим же значениям проба проверяет, что
 * соседние этажи РАЗЛИЧИМЫ. Копия в экране означала бы проверку выдумки.
 */
/**
 * ГЛУБИНА ЭТАЖА — СИЛА ЗАТЕМНЕНИЯ, а не оттенок.
 *
 * 🔴 ПОЧЕМУ ПЕРЕПИСАНО. До 05.09.2026 этаж красился бледными тонами
 * (`layerTintFor`: белый → #bccadd). Они и правда различались на 6+ единиц
 * яркости — и проба это исправно подтверждала. Но 05.09 под плитку легла
 * КОСТЯНАЯ ПЛАШКА, и бледная плёнка 34% на тёплой кости перестала читаться
 * вовсе: я собрал ту же композицию теми же числами и увидел пять одинаковых
 * плиток. Проба при этом осталась зелёной, потому что мерила ФУНКЦИЮ, а не
 * то, что видно на доске. Классический призрак.
 *
 * Здесь возвращается прозрачность ТЁМНОЙ плёнки: верхний этаж чистая кость,
 * каждый следующий вниз глубже в тени. На кости это работает так же, как в
 * жизни: нижние плитки в стопке действительно темнее.
 *
 * Шаг 0,115 и потолок 0,36 — не на глаз: при средней кости (232,215,185) и
 * плёнке (38,42,52) это даёт падение яркости с 217 до 160, то есть разницу,
 * которую видно через всю доску. Числа сторожит проба по СОСТАВЛЕННОМУ цвету.
 */
export function layerShadeFor(layer: number, maxLayer: number): number {
  if (maxLayer <= 0) return 0;
  const сверху = maxLayer - layer;          // 0 — самый верхний этаж
  /**
   * ⚠️ ДИАПАЗОН РАСТЯГИВАЕТСЯ ПО ЧИСЛУ ЭТАЖЕЙ, а не режется потолком.
   * Сначала здесь стоял постоянный шаг 0,115 с потолком 0,36 — и на пяти этажах
   * два нижних упирались в потолок, давая разницу яркости 2,6 при пороге 6. То
   * есть на самых высоких уровнях, где стопка и нужна, она снова становилась
   * плоской. Проба это поймала на пятислойной доске.
   */
  return (сверху / maxLayer) * 0.36;
}

/**
 * @deprecated БОЛЬШЕ НИГДЕ НЕ ЗОВЁТСЯ (проверено 05.09.2026 поиском по src и app).
 * Бледные тона рассчитаны на белую доску; под костяной плашкой они не читаются —
 * см. `layerShadeFor` и историю в её шапке. Оставлено как след того, ЧТО именно
 * не сработало: без этого следа тот же путь пройдут заново. Удалять — отдельным
 * решением Дениса, не походя.
 */
export function layerTintFor(layer: number, maxLayer: number): string {
  if (maxLayer <= 0) return '#f8fafc';
  const сверху = maxLayer - layer;                       // 0 = самый верх
  const тона = ['#ffffff', '#eef2f7', '#dde5ef', '#ccd7e6', '#bccadd'];
  return тона[Math.min(сверху, тона.length - 1)];
}

export function tilePlacement(
  t: { x: number; y: number; layer: number }, maxLayer: number, half: number, layerOffset: number,
): { left: number; top: number } {
  return {
    left: t.x * half + t.layer * layerOffset,
    top: t.y * half + (maxLayer - t.layer) * layerOffset,
  };
}
