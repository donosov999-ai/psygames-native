/**
 * d′ — ЧУВСТВИТЕЛЬНОСТЬ ПО ТЕОРИИ ОБНАРУЖЕНИЯ СИГНАЛА, ОТДЕЛЬНО ОТ ЭКРАНА.
 *
 * 🔴 ЗАЧЕМ ВЫНЕСЕНО. Расчёт жил внутри `finishGame` в `app/games/n-back.tsx`:
 * замыкание обработчика, аппроксимация обратной нормали объявлена там же
 * локальной функцией. Число уходило в сессию полем `d_prime`, человеку не
 * показывалось, и проверить его было нечем — чтобы дойти до одной формулы,
 * пришлось бы поднять весь экран с таймерами, речью и хранилищем. Здесь тот же
 * счёт живёт чистой функцией: те же входы — те же числа, и их можно предъявить.
 *
 * ⚠️ ЧИСЛА ПЕРЕНЕСЕНЫ БАЙТ В БАЙТ. Коэффициенты аппроксимации, порядок
 * действий, поправка и округление до сотых — как были. Перенос, который «заодно
 * чуть улучшил формулу», обесценил бы историю: сохранённые `d_prime` прошлых
 * партий перестали бы сравниваться с новыми.
 *
 * ПОЧЕМУ НЕ ГОЛАЯ ТОЧНОСТЬ. В n-back доля верных ответов смешивает два разных
 * умения: заметить повтор и удержаться от нажатия на новом. Осторожный игрок,
 * который почти всегда молчит, набирает высокий процент на одних правильных
 * отказах — повторов он при этом не видит. d′ разводит эти два случая:
 * `d′ = z(доля попаданий) − z(доля ложных тревог)`, ноль = ответы наугад.
 *
 * ⚠️ ДВА КАНАЛА СЧИТАЮТСЯ ПОРОЗНЬ. В двойном режиме (клетка + буква) пробы
 * независимы: повтор клетки и повтор буквы выпадают сами по себе. Общий d′ по
 * смешанным пробам не имеет смысла — поэтому функция принимает счётчики ОДНОГО
 * канала, а вызывающий зовёт её дважды.
 */

/** Четыре исхода проб одного канала. Сумма = число проб, на которые был исход. */
export interface NBackCounts {
  /** Повтор был, человек нажал. */
  hits: number;
  /** Повтор был, человек промолчал. */
  misses: number;
  /** Повтора не было, человек нажал. */
  falseAlarms: number;
  /** Повтора не было, человек промолчал. */
  correctRejections: number;
}

export interface NBackSignal {
  /** Сколько проб дошло до исхода. Ноль = партии не было. */
  answered: number;
  /** Доля попаданий с лог-линейной поправкой. */
  hitRate: number;
  /** Доля ложных тревог с лог-линейной поправкой. */
  falseAlarmRate: number;
  /** z(hitRate) − z(falseAlarmRate), округлено до сотых. */
  dPrime: number;
}

/**
 * d′ ответов наугад. Не «плохо», а «по этим ответам нельзя сказать, различал ли
 * человек повтор»: обе доли равны, разность z-оценок обнуляется.
 */
export const NBACK_DPRIME_CHANCE = 0;

/**
 * Обратная функция нормального распределения — рациональная аппроксимация
 * (Beasley–Springer–Moro, вариант Acklam). Точности до шестого знака хватает с
 * запасом: d′ показывается с двумя.
 *
 * ⚠️ Область определения — открытый интервал (0, 1). Крайние доли сюда не
 * доезжают: лог-линейная поправка ниже отодвигает их от нуля и единицы ещё до
 * вызова, и именно поэтому она обязательна, а не «на всякий случай».
 */
export function zScore(p: number): number {
  const a = [-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02, 1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00];
  const b = [-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02, 6.680131188771972e+01, -1.328068155288572e+01];
  const c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00, -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00];
  const d = [7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e+00, 3.754408661907416e+00];
  const pLow = 0.02425, pHigh = 1 - pLow;
  let q, r;
  if (p < pLow) { q = Math.sqrt(-2 * Math.log(p)); return (((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5]) / ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1); }
  if (p <= pHigh) { q = p - 0.5; r = q*q; return (((((a[0]*r+a[1])*r+a[2])*r+a[3])*r+a[4])*r+a[5])*q / (((((b[0]*r+b[1])*r+b[2])*r+b[3])*r+b[4])*r+1); }
  q = Math.sqrt(-2 * Math.log(1 - p));
  return -(((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5]) / ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1);
}

/**
 * Лог-линейная поправка Снодграсса–Корвина (1988): к числителю 0.5, к
 * знаменателю 1.
 *
 * 🔴 БЕЗ НЕЁ ЧИСТАЯ ПАРТИЯ ДАЁТ БЕСКОНЕЧНОСТЬ. Ни одного промаха — доля
 * попаданий ровно 1, z(1) = +∞; ни одной ложной тревоги — доля 0, z(0) = −∞.
 * На экране человека это «Infinity» или «NaN» вместо числа, в базе — сломанная
 * история. Поправка сдвигает крайние доли внутрь интервала, оставляя порядок
 * между игроками прежним.
 *
 * ⚠️ Проб не было вовсе (обрыв партии, канал не участвовал) — берём 0.5, то
 * есть «ничего не знаем». Делить не на что, и выдумывать нечего.
 */
function correctedRate(yes: number, no: number): number {
  const trials = yes + no;
  return trials > 0 ? (yes + 0.5) / (trials + 1) : 0.5;
}

/** Доли и d′ по одному каналу. Пустые счётчики дают ровно d′ = 0, без деления на ноль. */
export function signalDetection(counts: NBackCounts): NBackSignal {
  const { hits, misses, falseAlarms, correctRejections } = counts;
  const hitRate = correctedRate(hits, misses);
  const falseAlarmRate = correctedRate(falseAlarms, correctRejections);
  return {
    answered: hits + misses + falseAlarms + correctRejections,
    hitRate,
    falseAlarmRate,
    dPrime: Number((zScore(hitRate) - zScore(falseAlarmRate)).toFixed(2)),
  };
}

/**
 * Доля верных ответов в процентах: попадания плюс правильные отказы.
 *
 * ⚠️ `whenNothingAnswered` — НЕ УКРАШЕНИЕ ПОДПИСИ, а разные смыслы у двух
 * каналов. Визуальный канал есть всегда: пустой — это ноль, партии не было.
 * Слуховой в одиночном режиме не участвует, а итог уровня берётся МИНИМУМОМ
 * из двух каналов; вернув там ноль, мы завалили бы уровень человеку, который
 * ничего неверного не сделал. Поэтому значение выбирает вызывающий.
 */
export function accuracyPercent(counts: NBackCounts, whenNothingAnswered: number): number {
  const { hits, misses, falseAlarms, correctRejections } = counts;
  const answered = hits + misses + falseAlarms + correctRejections;
  return answered > 0 ? Math.round(((hits + correctRejections) / answered) * 100) : whenNothingAnswered;
}
