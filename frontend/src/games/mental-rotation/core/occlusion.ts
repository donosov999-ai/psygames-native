import { allOrientations } from './geometry';
import type { Cube, Shape } from './types';

const КЛЮЧ = (c: Cube) => c.join(',');

/**
 * Кубики, которых на рисунке не видно ВООБЩЕ: перед кубиком по лучу взгляда (1,1,1)
 * стоит другой кубик той же фигуры.
 */
export function hiddenCubes(shape: Shape): Shape {
  const есть = new Set(shape.map(КЛЮЧ));
  const предел = Math.max(...shape.map((c) => Math.max(c[0], c[1], c[2]))) + 1;
  return shape.filter((c) => {
    // Идём по лучу взгляда: между кубиком и тем, что его закрывает, бывает пустота,
    // поэтому проверяется весь луч, а не только ближайший сосед.
    for (let k = 1; c[0] + k <= предел && c[1] + k <= предел && c[2] + k <= предел; k++) {
      if (есть.has(КЛЮЧ([c[0] + k, c[1] + k, c[2] + k]))) return true;
    }
    return false;
  });
}

/**
 * Отпечаток РИСУНКА фигуры: какие грани реально попадают на экран.
 *
 * Грань рисуется, когда она смотрит на зрителя (`+x`, `+y`, `+z` — остальные отсечены)
 * и у неё нет соседа. Кубики, закрытые целиком, в отпечаток не входят. Две фигуры с
 * ОДИНАКОВЫМ отпечатком выглядят одинаково — сколько бы кубиков ни отличалось внутри.
 *
 * ⚠️ Отпечаток берётся от фигуры КАК ОНА ЛЕЖИТ: варианты ответа рисуются без поворота
 * (`shapeSurface(..., 'x', 0)`), поэтому сравнивать их отпечатки честно.
 */
export function visibleSignature(shape: Shape): string {
  const есть = new Set(shape.map(КЛЮЧ));
  const скрыт = new Set(hiddenCubes(shape).map(КЛЮЧ));
  const минX = Math.min(...shape.map((c) => c[0]));
  const минY = Math.min(...shape.map((c) => c[1]));
  const минZ = Math.min(...shape.map((c) => c[2]));
  const грани: string[] = [];
  for (const c of shape) {
    if (скрыт.has(КЛЮЧ(c))) continue;
    const [x, y, z] = [c[0] - минX, c[1] - минY, c[2] - минZ];
    if (!есть.has(КЛЮЧ([c[0] + 1, c[1], c[2]]))) грани.push(`${x},${y},${z}:x`);
    if (!есть.has(КЛЮЧ([c[0], c[1] + 1, c[2]]))) грани.push(`${x},${y},${z}:y`);
    if (!есть.has(КЛЮЧ([c[0], c[1], c[2] + 1]))) грани.push(`${x},${y},${z}:z`);
  }
  return грани.sort().join('|');
}

/** Две фигуры рисуются одинаково — различить их глазами нельзя. */
export function looksTheSame(a: Shape, b: Shape): boolean {
  return visibleSignature(a) === visibleSignature(b);
}

/**
 * Ракурсы фигуры, в которых видны ВСЕ её кубики. Пусто — таких нет вовсе.
 *
 * ЗАМЕР 23.09.2026 по каталогу фигур, которые реально выпадают (`shapesOfSize`, 4–9
 * кубиков): такой ракурс есть у 25 фигур из 26 — 100 % на размерах 4–8 и 11 из 12 на
 * девяти. В среднем чистых ракурсов 10–18 из 24. То есть выбор ракурса решает задачу
 * почти всегда, и отбраковывать фигуры не нужно.
 */
export function orientationsWithoutHidden(shape: Shape): Shape[] {
  return allOrientations(shape).filter((o) => hiddenCubes(o).length === 0);
}

/**
 * Ракурс, в котором видно как можно больше: случайный из чистых, а если чистых нет —
 * тот, где скрыто МЕНЬШЕ ВСЕГО, а не первый попавшийся.
 *
 * ⚠️ Годится там, где ответ ВЫЧИСЛЯЕТСЯ из самой фигуры («Проекция», «Точка зрения»):
 * повернули фигуру — повернулись и все её виды, задание остаётся согласованным. Там,
 * где ракурс варианта связан с эталоном (подделка «переставлен один кубик» у
 * «Поворота»), крутить нельзя — см. `rotation.ts`.
 */
export function clearestOrientation(shape: Shape, выбор: (варианты: Shape[]) => Shape): Shape {
  const все = allOrientations(shape);
  const чистые = все.filter((o) => hiddenCubes(o).length === 0);
  if (чистые.length) return выбор(чистые);
  let лучший = все[0];
  let лучшее = Infinity;
  for (const o of все) {
    const n = hiddenCubes(o).length;
    if (n < лучшее) { лучшее = n; лучший = o; }
  }
  return лучший;
}
