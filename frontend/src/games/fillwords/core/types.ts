/**
 * ТИПЫ ФИЛВОРДОВ. Одна мысль на весь модуль: РАСКЛАДКА — ЭТО РАЗБИЕНИЕ ПОЛЯ.
 *
 * В обычном «поиске слов» (word search) слова прячут в случайный буквенный шум:
 * нашёл все слова — часть букв так и осталась мусором. В филвордах мусора нет
 * вовсе: каждая клетка принадлежит ровно одному слову, и уровень закрыт, когда
 * поле РАЗОБРАНО ЦЕЛИКОМ. Отсюда устройство типов ниже:
 *
 *   · `letters` — то, что видит человек (по одной букве на клетку);
 *   · `words[i].path` — то, из чего поле собрано: клетки слова в порядке чтения.
 *
 * ⚠️ ИНВАРИАНТ, РАДИ КОТОРОГО ВСЁ И ЗАТЕВАЛОСЬ: пути слов ПОПАРНО НЕ
 * ПЕРЕСЕКАЮТСЯ и в объединении дают ВСЕ клетки поля. Если его нарушить, игра
 * становится нечестной сразу и молча: человек находит все слова из списка, а
 * поле не пустеет — и закрыть уровень нельзя вообще ничем. Поэтому генератор
 * строит раскладку ОТ РЕШЕНИЯ (режет гамильтонов путь на отрезки), а не
 * пытается доказать покрытие постфактум. Сторожит `fillwords-core.test.ts`.
 */

/** Индекс клетки: `row * cols + col`. Плоский массив вместо матрицы — так поле
 *  переживает JSON (сохранение партии) и не плодит вложенных копий. */
export type CellIndex = number;

/** Слово, УЛОЖЕННОЕ в поле: сами буквы и клетки, по которым оно читается. */
export interface PlantedWord {
  /** Слово заглавными — ровно так, как оно написано в клетках. */
  word: string;
  /** Клетки слова по порядку букв. Соседние в пути — соседи на поле (8 сторон). */
  path: CellIndex[];
}

/** Готовое поле филвордов. Всё, что нужно, чтобы партию восстановить один в один. */
export interface FillwordsPuzzle {
  rows: number;
  cols: number;
  /** Язык слов — он же язык, на котором режим вообще предлагается. */
  locale: string;
  /** Зерно ГПСЧ: одно и то же зерно → одно и то же поле (нужно гейтам и повтору уровня). */
  seed: number;
  /** Буквы поля, по одной на клетку. Длина = rows * cols. */
  letters: string[];
  /** Уложенные слова. Их пути в сумме покрывают поле целиком и не пересекаются. */
  words: PlantedWord[];
}

/**
 * ПОЧЕМУ ЖЕСТ ОТКЛОНЁН. Причина возвращается кодом, а не булевым «нет», и это
 * не украшение: по коду видно, КАКАЯ проверка сработала. Гейт требует именно
 * `not-adjacent` на прыжке через клетку — убери проверку соседства, и ответ
 * станет `no-match`, то есть тест покраснеет. Булево «не принято» такой подмены
 * не заметило бы: жест отклонён и там, и там.
 */
export type FillwordsRejectReason =
  /** Меньше двух клеток — это тап, а не протягивание. */
  | 'too-short'
  /** Палец вернулся на уже пройденную клетку — линия сама себя пересекла. */
  | 'repeat'
  /** Соседние в линии клетки не соседи на поле — прыжок. */
  | 'not-adjacent'
  /** Клетка уже разобрана найденным словом. */
  | 'taken'
  /** Линия ведёт не по слову: такой раскладки в поле нет. */
  | 'no-match';

/** Разбор жеста: либо попадание в конкретное слово, либо причина отказа. */
export type FillwordsTrace =
  | { ok: true; wordIndex: number }
  | { ok: false; reason: FillwordsRejectReason };

/** Состояние партии. Чистые данные: любые действия возвращают НОВЫЙ объект. */
export interface FillwordsSession {
  puzzle: FillwordsPuzzle;
  /**
   * Кто занял клетку: индекс слова в `puzzle.words` или -1, если буква ещё на
   * поле. Именно по этому массиву считается «поле разобрано» — по БУКВАМ, а не
   * по числу найденных слов. Разница видна, когда раскладка сломана: слова
   * кончились, а буквы остались, и уровень честно НЕ закрывается.
   */
  owner: number[];
  /** Индексы найденных слов в порядке нахождения — по нему берётся цвет подсветки. */
  found: number[];
  /** Сколько раз брали подсказку (цена уровня, идёт в звёзды). */
  hints: number;
  /** Сколько раз линия вела в никуда — «ложные тревоги» корректуры. */
  mistakes: number;
}

/** Подсказка: какое слово подсвечиваем и с каких клеток оно начинается. */
export interface FillwordsHint {
  wordIndex: number;
  cells: CellIndex[];
}
