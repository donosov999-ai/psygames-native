export type ВидЛовушки = 'гласная' | 'согласная' | 'перестановка' | 'удвоение';

export interface Ловушка {
  вариант: string;
  вид: ВидЛовушки;
  /** Где в ВАРИАНТЕ стоит отличие: [начало, конец). */
  где: [number, number];
  /** Что в услышанном слове на этом месте и что в варианте. */
  было: string;
  стало: string;
}

export interface КарточкаЭха {
  вид: 'приём' | 'слушаем' | 'отсев' | 'ответ' | 'готово';
  ключ: string;
  поля?: Record<string, string | number>;
  /** Какой вариант разбирается на карточке отсева или назван в ответе. */
  вариант: string | null;
  /** Отсеянные к этой карточке варианты (включая текущий). */
  отсеяно: string[];
  /** Что произнести при показе карточки. */
  звук: string[];
  /** Где подчеркнуть отличие в текущем варианте. */
  где: [number, number] | null;
}

const КЛЮЧ: Record<ВидЛовушки, string> = {
  гласная: 'teachEchoVowel',
  согласная: 'teachEchoConsonant',
  перестановка: 'teachEchoSwap',
  удвоение: 'teachEchoDouble',
};

/** Чем вариант отличается от слова. `null` — если ни один из четырёх видов генератора не подходит. */
export function разобратьЛовушку(слово: string, вариант: string, гласные: string): Ловушка | null {
  const С = Array.from(слово);
  const В = Array.from(вариант);
  if (С.length === В.length) {
    const разные = С.map((_, i) => i).filter((i) => С[i] !== В[i]);
    if (разные.length === 1) {
      const i = разные[0]!;
      const гласнаяБыла = гласные.includes(С[i]!.toLowerCase());
      const гласнаяСтала = гласные.includes(В[i]!.toLowerCase());
      if (гласнаяБыла !== гласнаяСтала) return null;   // генератор меняет только внутри класса
      return { вариант, вид: гласнаяБыла ? 'гласная' : 'согласная', где: [i, i + 1], было: С[i]!, стало: В[i]! };
    }
    if (разные.length === 2 && разные[1] === разные[0]! + 1) {
      const i = разные[0]!;
      if (В[i] === С[i + 1] && В[i + 1] === С[i]) {
        return { вариант, вид: 'перестановка', где: [i, i + 2], было: С[i]! + С[i + 1]!, стало: В[i]! + В[i + 1]! };
      }
    }
    return null;
  }
  if (В.length === С.length + 1) {
    for (let j = 1; j < В.length; j++) {
      if (В[j] === В[j - 1] && [...В.slice(0, j), ...В.slice(j + 1)].join('') === слово) {
        return { вариант, вид: 'удвоение', где: [j - 1, j + 1], было: В[j - 1]!, стало: В[j - 1]! + В[j]! };
      }
    }
  }
  return null;
}

export function собратьРазборЭха(
  раунд: { word: string; options: string[] },
  гласные: string,
): { карточки: КарточкаЭха[]; ловушки: Ловушка[] } {
  const слово = раунд.word;
  const ловушки = раунд.options
    .filter((в) => в !== слово)
    .map((в) => разобратьЛовушку(слово, в, гласные))
    .filter((л): л is Ловушка => л !== null);

  const карточки: КарточкаЭха[] = [
    { вид: 'приём', ключ: 'teachEchoIntro', вариант: null, отсеяно: [], звук: [], где: null },
    { вид: 'слушаем', ключ: 'teachEchoListen', вариант: null, отсеяно: [], звук: [слово], где: null },
  ];
  const отсеяно: string[] = [];
  for (const л of ловушки) {
    отсеяно.push(л.вариант);
    карточки.push({
      вид: 'отсев',
      ключ: КЛЮЧ[л.вид],
      поля: { v: л.вариант, a: л.было, b: л.стало },
      вариант: л.вариант,
      отсеяно: [...отсеяно],
      звук: [],
      где: л.где,
    });
  }
  карточки.push({ вид: 'ответ', ключ: 'teachEchoPick', поля: { w: слово }, вариант: слово, отсеяно: [...отсеяно], звук: [слово], где: null });
  карточки.push({ вид: 'готово', ключ: 'teachEchoDone', вариант: null, отсеяно: [...отсеяно], звук: [], где: null });
  return { карточки, ловушки };
}
