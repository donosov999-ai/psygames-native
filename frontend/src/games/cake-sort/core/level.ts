/**
 * УРОВНИ ТОРТОВ: чем задаётся стол и как раздаётся, чтобы он ТОЧНО разбирался.
 *
 * 🔴 НИ ОДНО ЧИСЛО НЕ УНАСЛЕДОВАНО ОТ СОРТИРОВКИ ТОВАРОВ. Там круг замыкается
 * тремя, здесь шестью, и это меняет арифметику целиком: тарелка обязана стать
 * ОДНОРОДНОЙ И ПОЛНОЙ, люфта внутри неё нет. Весь запас манёвра переезжает на
 * число тарелок — потому их и больше, чем ниш (замер геометрии: на 360 точках
 * читаемы 5 столбцов, то есть до 20 тарелок против 14 ниш).
 */
import { Board, CIRCLE, Plate, makeBoard, completeIn } from './plate';
import { provenUnsolvable, solve } from './solver';

/** Наибольшее число тарелок, влезающих читаемо (5 столбцов × 4 ряда — см. layout). */
export const PLATES_MAX = 20;

/** Пол запаса: столько тарелок сверх числа видов должно оставаться на манёвр. */
export const SPARES_MIN = 2;

export interface CakeLevel {
  /** Видов начинки на столе. Каждый вид — ровно один круг из шести секторов. */
  types: number;
  /** Тарелок на столе. */
  plates: number;
  /**
   * Сколько кругов приходит из очереди СВЕРХ тех, что лежат на столе.
   *
   * 🔴 ИМЕННО «СВЕРХ», А НЕ «ВМЕСТО», И ЭТО ПОЧИНЕННЫЙ ДЕФЕКТ. Первая редакция
   * понимала очередь как часть тех же тарелок — отложенный хвост раскладки. На
   * деле раскладка плотная: сектора ложатся в ПЕРВЫЕ тарелки подряд, а очередь
   * бралась из ПОСЛЕДНИХ, то есть всегда из пустых. Замер 07.09.2026: на всех
   * уровнях L7…L60 `cfg.queue` обещал от 1 до 7, а на доске очередь была РОВНО
   * НОЛЬ — счётчик очереди в шапке показывал 0 всю жизнь игры.
   *
   * Теперь очередь — ДОПОЛНИТЕЛЬНЫЙ материал: ещё столько кругов тех же видов,
   * которые приезжают на освободившееся место. Стол при этом остаётся ровно тем,
   * что доказан решателем, а очередь добавляет к нему продолжение.
   */
  queue: number;
}

/**
 * 🔴 ЛЕСТНИЦА ЗАДАНА ОТ ЁМКОСТИ, А НЕ «НА ГЛАЗ».
 *
 * Видов растёт по одному через уровень, тарелок — так, чтобы запас манёвра
 * никогда не падал ниже `SPARES_MIN`. Проверять это надо ПРОГОНОМ по всем
 * уровням: соседние игры уже жили с лестницей, которая упиралась в потолок на
 * тринадцатом уровне и дальше выдавала одно и то же, а все пробы были зелёными.
 */
export function levelCfg(L: number): CakeLevel {
  const n = Math.max(1, Math.floor(L) || 1);
  const types = Math.min(11, 2 + Math.floor((n + 1) / 2));
  const plates = Math.min(PLATES_MAX, types + Math.max(SPARES_MIN, 2 + Math.floor(n / 6)));
  const queue = n < QUEUE_FROM ? 0 : 1 + Math.floor((n - QUEUE_FROM) / 8);
  return { types, plates, queue: Math.max(0, queue) };
}

/**
 * 🔴 ОЧЕРЕДЬ ВХОДЯЩИХ — С L7, И ЭТО ОТДЕЛЬНАЯ СУЩНОСТЬ, А НЕ УКРАШЕНИЕ.
 *
 * У нас такого нет нигде: во всех играх семьи мультимножество лежит на столе
 * целиком. Здесь часть тарелок ОТЛОЖЕНА и приходит на освободившееся место.
 *
 * ⚠️ Очередь КОНЕЧНА и известна заранее — иначе рушится единственная наша
 * отстройка. Разбор §8 дословно: «замкнутость мультимножества держит всю
 * гарантию решаемости». Бесконечный поток нельзя доказать вообще никак, и
 * именно на этом конкурент собрал 454 жалобы на непроходимые уровни.
 */
export const QUEUE_FROM = 7;

/** Детерминированный генератор: уровень обязан повторяться при повторном заходе. */
function rng(seed: number): () => number {
  let s = (seed * 2654435761) >>> 0;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >> 17;
    s ^= s << 5; s >>>= 0;
    return s / 4294967296;
  };
}

function shuffle<T>(arr: T[], rand: () => number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j] as T, a[i] as T];
  }
  return a;
}

/**
 * 🔴 СЕКТОРОВ ВСЕГДА КРАТНО ШЕСТИ, И ЭТО ИНВАРИАНТ, А НЕ СЛЕДСТВИЕ.
 *
 * Материал СТОЛА: каждый вид даёт ровно один круг. Очередь добавляет к нему ещё
 * целые круги (`extraSectors`), поэтому кратность держится и на сумме. Нарушь
 * её — и на столе останется хвост, который нельзя замкнуть никогда: уровень
 * станет непроходимым, причём молча, потому что ходы у игрока ещё будут.
 */
function sectors(types: number): number[] {
  const out: number[] = [];
  for (let t = 0; t < types; t += 1) for (let k = 0; k < CIRCLE; k += 1) out.push(t);
  return out;
}

/** Разложить сектора по тарелкам: заполняем подряд, остаток тарелок — пустые. */
function layOut(all: number[], plates: number): Plate[] {
  const out: number[][] = Array.from({ length: plates }, () => []);
  let i = 0;
  for (const s of all) {
    while ((out[i] as number[]).length >= CIRCLE) i += 1;
    (out[i] as number[]).push(s);
  }
  return out;
}

/**
 * 🔴 МАТЕРИАЛ ОЧЕРЕДИ: ЕЩЁ `extra` КРУГОВ ТЕХ ЖЕ ВИДОВ.
 *
 * ⚠️ ВИДЫ ПОВТОРЯЮТСЯ НАМЕРЕННО, и это ровно то, что снимает потолок лестницы.
 * Видов не может стать больше одиннадцати — столько цветов в палитре, — но
 * КРУГОВ одного вида может быть сколько угодно: круг замыкается шестью, и
 * двенадцать секторов одного вида это просто два круга. Пока очередь считалась
 * долей от числа тарелок, лестница замирала на L63 навсегда; теперь растёт
 * материал, а не пестрота.
 *
 * ⚠️ Кратность шести сохраняется по построению: каждый круг — ровно шесть
 * секторов ОДНОГО вида. Замкнутость мультимножества — то, на чём держится вся
 * доказуемость, и ломать её ради разнообразия нельзя.
 */
function extraSectors(types: number, extra: number): number[] {
  const out: number[] = [];
  for (let k = 0; k < extra; k += 1) {
    const t = k % Math.max(1, types);
    for (let j = 0; j < CIRCLE; j += 1) out.push(t);
  }
  return out;
}

export interface Deal {
  board: Board;
  cfg: CakeLevel;
  /** Сколько раз пришлось пересобирать. Для замера стоимости раздачи. */
  tries: number;
  /**
   * 🔴 РЕШАЕМОСТЬ ДОКАЗАНА, А НЕ «НЕ ОПРОВЕРГНУТА».
   *
   * Игроку показывается значок «уровень проверен» — и это обещание, за которое
   * надо отвечать. `provenUnsolvable` отвечает лишь «не доказано, что нельзя»,
   * а это НЕ то же самое: при исчерпании бюджета он молчит. Поэтому здесь
   * отдельный флаг, и он ставится только когда решатель НАШЁЛ решение.
   *
   * Ровно на этой разнице стоит вся наша отстройка: у разобранного конкурента
   * 454 отзыва про непроходимые уровни.
   */
  proven: boolean;
}

/**
 * 🔴 ЗА ЧТО РАЗДАЧА БРАКУЕТСЯ. Отдельной функцией, а не строчками внутри `deal`,
 * НАМЕРЕННО — и вот почему.
 *
 * Замер 06.09.2026: 720 раздач (L1…L60 × 12 попыток) дали **0 готовых кругов и
 * 0 доказанно нерешаемых столов**. То есть при нынешнем генераторе оба заслона
 * НЕ СРАБАТЫВАЮТ НИ РАЗУ, и мутация «убрать проверку» проходила мимо гейта —
 * ровно та ловушка, на которой сортировка товаров уже стояла с недостижимой
 * страховкой `clampGoalToLevel`.
 *
 * Строчка, которую нельзя проверить исполнением, ничего не стережёт. Вынесенную
 * функцию гейт зовёт НАПРЯМУЮ, подавая ей заведомо плохие столы, — и заслон
 * остаётся живым, даже пока генератор до него не доводит. Убирать заслон нельзя:
 * генератор ещё будут менять, и тогда он понадобится в первый же день.
 *
 * ⚠️ Бракуются два случая, и только они: круг уже замкнут (даровая победа) и
 * стол ДОКАЗАННО нерешаем. Исчерпание бюджета — не брак: «не знаю» ≠ «нет», и
 * на этой разнице сортировка товаров теряла полсекунды на старте уровня,
 * пересобирая хорошие столы.
 */
export function dealRejected(board: Board): false | 'готовый круг' | 'нерешаемо' {
  if (board.plates.some((p) => completeIn(p) !== null)) return 'готовый круг';
  if (board.queue.some((p) => completeIn(p) !== null)) return 'готовый круг';
  if (provenUnsolvable(board)) return 'нерешаемо';
  return false;
}

/**
 * Стол и очередь одной раздачей.
 *
 * ⚠️ СТОЛ ЗАНИМАЕТ ВСЕ ТАРЕЛКИ УРОВНЯ, а очередь стоит отдельно. Прежде очередь
 * отрезалась от ХВОСТА раскладки — и оказывалась пустой всегда, потому что
 * раскладка плотная: занятыми выходят первые `types` тарелок, а хвост пуст по
 * построению. Отрезать от пустого места можно только пустоту.
 */
function собрать(L: number, tries: number, cfg: CakeLevel): Board {
  const rand = rng(L * 1000 + tries);
  /**
   * 🔴 СТОЛ И ОЧЕРЕДЬ МЕШАЮТСЯ ОДНОЙ КОЛОДОЙ, А НЕ ДВУМЯ.
   *
   * 📍 Замер отверг раздельный вариант. Материал очереди сам по себе — целые
   * круги, и на L7…L12 (одна лишняя круглая порция) стопка выходила ОДНОРОДНОЙ
   * по построению: шесть секторов одного вида. Заслон `dealRejected` честно
   * браковал её как готовый круг — все двенадцать попыток подряд, — и раздача
   * уходила в запасную ветку, отдавая ровно то, что забраковала.
   *
   * Общая колода лечит причину: каждая стопка, и на столе и в очереди, набрана
   * из перемешанного целого, поэтому однородной может оказаться только случайно.
   */
  const все = [...sectors(cfg.types), ...extraSectors(cfg.types, cfg.queue)];
  const плотно = layOut(shuffle(все, rand), cfg.types + cfg.queue);
  /*
   * ⚠️ Очередь берётся ИЗ НАЧАЛА плотной раскладки, а не из хвоста стола. Хвост
   * раскладки пуст по построению — именно на этом прежняя очередь и умирала.
   */
  const пустых = Math.max(0, cfg.plates - cfg.types);
  const plates: Plate[] = [...плотно.slice(0, cfg.types), ...Array.from({ length: пустых }, () => [] as number[])];
  return makeBoard(plates, плотно.slice(cfg.types));
}

/** Раздача уровня с ДОКАЗАННОЙ решаемостью. */
export function deal(L: number, attempts = 12): Deal {
  const cfg = levelCfg(L);
  for (let tries = 0; tries < attempts; tries += 1) {
    const board = собрать(L, tries, cfg);
    if (dealRejected(board)) continue;
    return { board, cfg, tries, proven: provenSolvable(board) };
  }
  // Не нашли за отведённые попытки — отдаём последнюю честно, как есть.
  const запасной = собрать(L, attempts, cfg);
  return { board: запасной, cfg, tries: attempts, proven: provenSolvable(запасной) };
}

/**
 * 🔴 РЕШЕНИЕ НАЙДЕНО — НЕ ТО ЖЕ, ЧТО «НЕ ДОКАЗАНО, ЧТО НЕЛЬЗЯ».
 *
 * Значок «уровень проверен» ставится по этому ответу, и разница между двумя
 * формулировками — это и есть цена обещания:
 *   `provenSolvable`      — решатель НАШЁЛ решение. При исчерпании бюджета: нет.
 *   `!provenUnsolvable`   — не доказано обратное. При исчерпании бюджета: ДА.
 * Вторая при нехватке бюджета молча says «проверено» о столе, про который ничего
 * не известно. Отдельной функцией — чтобы гейт мог подать ей заведомо малый
 * бюджет и увидеть разницу: на живых уровнях обе отвечают одинаково, и мутация
 * «подменить одну другой» без такого входа проходит незамеченной.
 */
export function provenSolvable(b: Board, budget = 20000): boolean {
  return solve(b, budget).solvable;
}

/** Разбирается ли стол вообще. Обёртка с говорящим именем для экрана и гейтов. */
export function solvable(b: Board, budget = 20000): boolean {
  return solve(b, budget).solvable;
}
