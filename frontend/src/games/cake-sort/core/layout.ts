/**
 * ГЕОМЕТРИЯ СТОЛА — считается ДО отрисовки, потому что она решает, сколько
 * тарелок вообще можно показать.
 *
 * 🔴 ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧИСЛА В РАЗМЕТКЕ. Требование ТЗ дословно:
 * «тарелок на экране больше, чем ниш: посчитай размер сектора при 360 точках
 * ширины ДО того, как рисовать». В сортировке товаров это уже стоило дефекта —
 * товар ужимался до 18 точек, и заметили это замером, а не глазами.
 *
 * ⚠️ У СЕКТОРА ДВА РАЗМЕРА, И ВАЖЕН МЕНЬШИЙ. Клин занимает шестую часть круга:
 * по внешнему краю его дуга ≈ 1,047·r, у центра — ноль. Читаемость решает не
 * внешняя дуга, а ширина на СРЕДНЕМ радиусе: `π·(r/2)/3 ≈ 0,524·r`. Мерить по
 * внешнему краю — значит завысить себе оценку вдвое и нарисовать нечитаемое.
 */

import { CIRCLE } from './plate';

/** Отступ между тарелками и от края стола, в точках. */
export const PLATE_GAP = 8;

/**
 * 🔴 ПОЛ ЧИТАЕМОСТИ СЕКТОРА — 15 ТОЧЕК ПО СРЕДНЕМУ РАДИУСУ.
 *
 * Взят не с потолка и не из сортировки: там пол 18 точек стоит под СПРАЙТ —
 * рисунок с деталями, тенью и этикеткой. Сектор торта — сплошной клин с
 * контуром, и различать надо цвет и форму клина, а не детали внутри.
 *
 * ЗАМЕР при ширине стола 360 точек (`tableLayout`, прогон 2…8 столбцов). Числа
 * пересняты 09.09.2026, когда `sectorWidth` стала мерить ТОРТ, а не тарелку:
 *
 *   2 столбца — тарелка 168, сектор 38,5 · 3 — 109 и 24,7 · 4 — 80 и 17,4
 *   5 — 62 и **13,3** · 6 — 51 и 10,5 · 7 — 42 и 8,4 · 8 — 36 и 6,9
 *
 * То есть на 360 точках читаемы **четыре столбца**, пятый уже под полом. Прежняя
 * редакция этой таблицы обещала пять — она мерила круг тарелки, а не круг торта,
 * и завышала каждую строку в 1,23 раза.
 *
 * ⚠️ Первая редакция этого комментария несла числа 33 / 25 / 19 / 14 — я написал
 * их до прогона, и все четыре оказались завышены примерно в полтора раза.
 * Замер исправил; строка оставлена как напоминание, что «примерно посчитал в
 * уме» и «померил» здесь расходятся на 60 %.
 */
export const SECTOR_MIN = 15;

export interface TableLayout {
  /** Столбцов тарелок. */
  cols: number;
  /** Диаметр тарелки, точки. */
  plate: number;
  /** Радиус тарелки, точки. */
  radius: number;
  /** Ширина сектора по среднему радиусу — то, чем меряется читаемость. */
  sector: number;
  /**
   * Дуга сектора по внешнему краю. Показательна, но НЕ она решает.
   * ⚠️ Считается по кругу ТОРТА, как и `sector`: две меры одного клина обязаны
   * быть про один круг, иначе их отношение (ровно 2) перестаёт что-либо значить.
   */
  sectorOuter: number;
}

/**
 * Ширина сектора по среднему радиусу для тарелки диаметром `plate`.
 *
 * ⚠️ Число секторов берётся из ядра (`CIRCLE`), а не пишется здесь шестёркой.
 * Своя копия правила игры в файле разметки — это две правды об одном: поменяют
 * круг в ядре, а геометрия останется считать по-старому, и заметить это будет
 * нечем, кроме глаз.
 */
/**
 * 🔴 ДОЛЯ ТОРТА ОТ РАДИУСА ТАРЕЛКИ — И ОНА ЖЕ УЧАСТВУЕТ В ЗАМЕРЕ ЧИТАЕМОСТИ.
 *
 * 📍 Денис 09.09.2026, дословно: «тортики должны быть больше, у тебя тарелка всё
 * занимает место, в тортиках главное это тортики».
 *
 * 📍 ЗАМЕР, ПОКАЗАВШИЙ, ЧТО ОН ПРАВ ЧИСЛОМ, А НЕ ВПЕЧАТЛЕНИЕМ. Клинья рисовались
 * радиусом `0,72·(r−3)`, а `sectorWidth` мерила ТАРЕЛКУ целиком. То есть замер
 * читаемости шёл по кругу, которого на экране нет: при 360 точках и пяти
 * столбцах он давал 16,3 точки при поле 15, а настоящий клин выходил 10,6 —
 * 71 % от собственного пола игры. Пол не нарушался «немного»: его просто мерили
 * не по тому кругу.
 *
 * 📍 ОТКУДА 0,90. Лист сравнения (0,72 / 0,82 / 0,90 / 0,97 на тарелке
 * `sweet/p0`): у 0,72 торт сидит в глубине оборки и занимает 52 % площади
 * тарелки; у 0,90 торт накрывает внутреннюю оборку, наружные фестоны остаются
 * рамкой — тарелка ещё читается тарелкой, а главным стал торт; у 0,97 тарелка
 * вырождается в ободок. Отдельная проверка по самим спрайтам: дно тарелки у
 * темы «сладкая» кончается на 0,695 радиуса, у «шахмат» и «био» — на 0,89…0,94,
 * то есть 0,90 у тонкобортных тем остаётся внутри дна, а у пышных ложится на
 * оборку намеренно.
 */
export const CAKE_FILL = 0.90;

/**
 * Отступ от края тарелки до торта, точки. Тот же, что стоит в отрисовке клина.
 */
export const CAKE_INSET = 3;

/** Радиус САМОГО ТОРТА на тарелке диаметром `plate`. */
export function cakeRadius(plate: number): number {
  return Math.max(0, CAKE_FILL * (plate / 2 - CAKE_INSET));
}

/**
 * Ширина сектора по среднему радиусу.
 *
 * ⚠️ МЕРИМ ТОРТ, А НЕ ТАРЕЛКУ. Игрок различает КЛИН, и меряться обязано ровно
 * то, что нарисовано: круг торта меньше круга тарелки, и разница не в процентах,
 * а в целом столбце — при 360 точках честный замер снимает пятый столбец.
 *
 * ⚠️ Число секторов берётся из ядра (`CIRCLE`), а не пишется здесь шестёркой.
 * Своя копия правила игры в файле разметки — это две правды об одном: поменяют
 * круг в ядре, а геометрия останется считать по-старому, и заметить это будет
 * нечем, кроме глаз.
 */
export function sectorWidth(plate: number): number {
  const r = cakeRadius(plate);
  return (Math.PI * (r / 2)) / (CIRCLE / 2);
}

/**
 * Раскладка стола при данной ширине и числе столбцов.
 *
 * ⚠️ Ничего не «подгоняет»: если тарелки не влезают читаемо, это видно по
 * `sector < SECTOR_MIN`, и решение принимает вызывающий, а не эта функция.
 */
export function tableLayout(width: number, cols: number): TableLayout {
  const plate = (width - PLATE_GAP * (cols + 1)) / cols;
  const radius = plate / 2;
  return {
    cols,
    plate,
    radius,
    sector: sectorWidth(plate),
    sectorOuter: (2 * Math.PI * cakeRadius(plate)) / CIRCLE,
  };
}

/**
 * Сколько столбцов ещё читаемы при данной ширине. Возвращает наибольшее число
 * столбцов, при котором сектор не ушёл под пол.
 *
 * 🔴 ЭТО И ЕСТЬ ОТВЕТ НА «ТАРЕЛОК БОЛЬШЕ, ЧЕМ НИШ»: не пожелание, а число,
 * посчитанное от ширины экрана.
 */
export function maxCols(width: number, limit = 8): number {
  let best = 1;
  for (let c = 1; c <= limit; c += 1) {
    if (tableLayout(width, c).sector >= SECTOR_MIN) best = c;
  }
  return best;
}

/**
 * 🔴 ТАРЕЛКА ПОД ТОЧКОЙ — ЧИСТАЯ ФУНКЦИЯ, А НЕ АРИФМЕТИКА В ОБРАБОТЧИКЕ ЖЕСТА.
 *
 * Перетаскивание считает попадание десятки раз в секунду, и ошибка здесь не
 * падает, а промахивается: товар едет не в ту тарелку, и на глаз промах в одну
 * ячейку от промаха в ноль не отличить. В сортировке товаров эту арифметику
 * пришлось выносить ровно по этой причине — ловится только замером.
 *
 * ⚠️ ПОПАДАНИЕ СЧИТАЕТСЯ ПО КРУГУ, А НЕ ПО КЛЕТКЕ. Тарелка круглая, и угол её
 * клетки — пустое место: палец там означает «мимо», а не «в тарелку». Разница
 * велика: у круга, вписанного в квадрат, вне круга остаётся 21 % площади.
 */
export function plateAtPoint(
  x: number, y: number, cols: number, plate: number, count: number,
): number | null {
  const шаг = plate + PLATE_GAP;
  const c = Math.floor((x - PLATE_GAP / 2) / шаг);
  const r = Math.floor((y - PLATE_GAP / 2) / шаг);
  if (c < 0 || c >= cols || r < 0) return null;
  const i = r * cols + c;
  if (i < 0 || i >= count) return null;
  // Центр этой тарелки и проверка, что палец внутри круга, а не в углу клетки.
  const cx = PLATE_GAP / 2 + c * шаг + plate / 2;
  const cy = PLATE_GAP / 2 + r * шаг + plate / 2;
  const dx = x - cx; const dy = y - cy;
  return dx * dx + dy * dy <= (plate / 2) * (plate / 2) ? i : null;
}

/**
 * 🔴 СТОЛ ПОДБИРАЕТСЯ ПОД ШИРИНУ **И ВЫСОТУ**, А НЕ ПОД ОДНУ ШИРИНУ.
 *
 * 📍 Зачем понадобилось. Пока клинья рисовались долей 0,72, а читаемость мерилась
 * по тарелке, `maxCols` завышал число столбцов, и стол случайно влезал по высоте.
 * Стоило замеру стать честным (`sectorWidth` меряет торт), как столбцов стало
 * меньше, тарелки крупнее — и двадцать тарелок на телефоне 360×640 перестали
 * помещаться в поле: пять рядов по 88 точек против ~440 доступных.
 *
 * Просить у ширины то, что решает высота, — та же ошибка, что жила в сортировке
 * товаров: там раскладка тоже сперва считала только ширину, и нижний ряд полок
 * уезжал под обрез (отчёт Вали 05.09.2026 «кошмар просто кошмар»).
 *
 * ПРАВИЛО ВЫБОРА, по порядку:
 *   1. столбцов столько, чтобы стол ВЛЕЗ по высоте — переполнение хуже мелкого
 *      торта, потому что нижние тарелки просто не увидеть;
 *   2. среди влезающих берём НАИМЕНЬШЕЕ число столбцов — самые крупные торты;
 *   3. пол читаемости (`SECTOR_MIN`) отсекает сверху: больше столбцов, чем
 *      читаемо, не берём, пока стол и так влезает.
 *
 * ⚠️ Когда высота требует больше столбцов, чем позволяет пол читаемости, побеждает
 * высота. Это не «пол отменили»: это честный ответ, что столько тарелок на такой
 * экран читаемо не ставится, и `sector` в ответе покажет насколько.
 */
export function tableFit(
  width: number, height: number, plates: number, limit = 8, min = 3,
): TableLayout & { rows: number } {
  const годится: number[] = [];
  const влезает: number[] = [];
  /*
   * ⚠️ НЕ МЕНЬШЕ ТРЁХ СТОЛБЦОВ, ПОКА ТАРЕЛОК ХВАТАЕТ. Высокий узкий стол в два
   * столбца даёт самые крупные торты и самый неудобный обзор: партия читается
   * рядом, а не колонкой, и на двух столбцах взгляд перестаёт схватывать стол
   * целиком. Прежняя редакция держала тот же пол выражением `max(3, …)`.
   */
  const низ = Math.max(1, Math.min(min, plates));
  for (let c = низ; c <= Math.min(limit, Math.max(1, plates)); c += 1) {
    const l = tableLayout(width, c);
    if (l.plate <= 0) continue;
    const rows = Math.ceil(plates / c);
    const нужно = rows * (l.plate + PLATE_GAP) + PLATE_GAP;
    if (нужно <= height) влезает.push(c);
    if (нужно <= height && l.sector >= SECTOR_MIN) годится.push(c);
  }
  const c = годится.length ? (годится[0] as number)
    : влезает.length ? (влезает[0] as number)
    : Math.min(limit, Math.max(низ, plates));
  return { ...tableLayout(width, c), rows: Math.ceil(plates / c) };
}
