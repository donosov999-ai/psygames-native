/**
 * ГЕОМЕТРИЯ СТОЛА — считается ДО отрисовки, потому что она решает, сколько
 * тарелок вообще можно показать.
 *
 * 🔴 ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧИСЛА В РАЗМЕТКЕ. Требование ТЗ дословно:
 * «тарелок на экране больше, чем ниш: посчитай размер сектора при 360 точках
 * ширины ДО того, как рисовать». В сортировке товаров это уже стоило дефекта —
 * товар ужимался до 18 точек, и заметили это замером, а не глазами.
 *
 * ⚠️ У СЕКТОРА ДВА РАЗМЕРА, И ВАЖЕН МЕНЬШИЙ. Клин занимает шестую часть круга:
 * по внешнему краю его дуга ≈ 1,047·r, у центра — ноль. Читаемость решает не
 * внешняя дуга, а ширина на СРЕДНЕМ радиусе: `π·(r/2)/3 ≈ 0,524·r`. Мерить по
 * внешнему краю — значит завысить себе оценку вдвое и нарисовать нечитаемое.
 */

import { CIRCLE } from './plate';

/** Отступ между тарелками и от края стола, в точках. */
export const PLATE_GAP = 8;

/**
 * 🔴 ПОЛ ЧИТАЕМОСТИ СЕКТОРА — 15 ТОЧЕК ПО СРЕДНЕМУ РАДИУСУ.
 *
 * Взят не с потолка и не из сортировки: там пол 18 точек стоит под СПРАЙТ —
 * рисунок с деталями, тенью и этикеткой. Сектор торта — сплошной клин с
 * контуром, и различать надо цвет и форму клина, а не детали внутри.
 *
 * ЗАМЕР при ширине стола 360 точек (`tableLayout`, прогон 2…8 столбцов):
 *
 *   2 столбца — тарелка 168, сектор 44,0 · 3 — 109 и 28,6 · 4 — 80 и 20,9
 *   5 — 62 и 16,3 · 6 — 51 и **13,3** · 7 — 42 и 11,1 · 8 — 36 и 9,4
 *
 * То есть на 360 точках читаемы **пять столбцов**, шестой уже под полом. На 414
 * точках проходят шесть. Это и есть ответ на «тарелок больше, чем ниш»: 5 × 4 =
 * 20 тарелок против 14 ниш в сортировке — и число посчитано от ширины экрана, а
 * не назначено.
 *
 * ⚠️ Первая редакция этого комментария несла числа 33 / 25 / 19 / 14 — я написал
 * их до прогона, и все четыре оказались завышены примерно в полтора раза.
 * Замер исправил; строка оставлена как напоминание, что «примерно посчитал в
 * уме» и «померил» здесь расходятся на 60 %.
 */
export const SECTOR_MIN = 15;

export interface TableLayout {
  /** Столбцов тарелок. */
  cols: number;
  /** Диаметр тарелки, точки. */
  plate: number;
  /** Радиус тарелки, точки. */
  radius: number;
  /** Ширина сектора по среднему радиусу — то, чем меряется читаемость. */
  sector: number;
  /** Дуга сектора по внешнему краю. Показательна, но НЕ она решает. */
  sectorOuter: number;
}

/**
 * Ширина сектора по среднему радиусу для тарелки диаметром `plate`.
 *
 * ⚠️ Число секторов берётся из ядра (`CIRCLE`), а не пишется здесь шестёркой.
 * Своя копия правила игры в файле разметки — это две правды об одном: поменяют
 * круг в ядре, а геометрия останется считать по-старому, и заметить это будет
 * нечем, кроме глаз.
 */
export function sectorWidth(plate: number): number {
  const r = plate / 2;
  return (Math.PI * (r / 2)) / (CIRCLE / 2);
}

/**
 * Раскладка стола при данной ширине и числе столбцов.
 *
 * ⚠️ Ничего не «подгоняет»: если тарелки не влезают читаемо, это видно по
 * `sector < SECTOR_MIN`, и решение принимает вызывающий, а не эта функция.
 */
export function tableLayout(width: number, cols: number): TableLayout {
  const plate = (width - PLATE_GAP * (cols + 1)) / cols;
  const radius = plate / 2;
  return {
    cols,
    plate,
    radius,
    sector: sectorWidth(plate),
    sectorOuter: (2 * Math.PI * radius) / CIRCLE,
  };
}

/**
 * Сколько столбцов ещё читаемы при данной ширине. Возвращает наибольшее число
 * столбцов, при котором сектор не ушёл под пол.
 *
 * 🔴 ЭТО И ЕСТЬ ОТВЕТ НА «ТАРЕЛОК БОЛЬШЕ, ЧЕМ НИШ»: не пожелание, а число,
 * посчитанное от ширины экрана.
 */
export function maxCols(width: number, limit = 8): number {
  let best = 1;
  for (let c = 1; c <= limit; c += 1) {
    if (tableLayout(width, c).sector >= SECTOR_MIN) best = c;
  }
  return best;
}
