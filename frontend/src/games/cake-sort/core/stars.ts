/**
 * ЭТАЛОН ХОДОВ И ЗВЁЗДЫ — единственное место, где они считаются.
 *
 * 🔴 КАЛИБРОВКА ЗАМЕРЕНА ДЛЯ ШЕСТЁРОК, А НЕ УНАСЛЕДОВАНА ОТ ТРОЕК.
 *
 * ТЗ раздела требует это прямо: «калибровка `REF_PER_TYPE = 2.2` снята под
 * тройки; для шестёрок она неверна — перезамерь A*, а не переноси число».
 *
 * ЗАМЕР (A* с допустимой эвристикой, `minMoves` без отсечений, бюджет 200 000
 * узлов; 40 столов, виды 3…6, запас тарелок 2 и 3):
 *
 *   виды 3, тарелок 5 — 5,67 · виды 3, тарелок 6 — 5,67
 *   виды 4, тарелок 6 — 5,67 · виды 4, тарелок 7 — 5,54
 *   виды 5, тарелок 7 — 5,57 · виды 5, тарелок 8 — 5,37
 *   виды 6, тарелок 8 — 5,92 (две доски из шести не уложились в бюджет)
 *   разброс по отдельным столам 5,0…6,3 · среднее **5,63**
 *
 * 🔴 ЧТО БЫЛО БЫ, УНАСЛЕДУЙ МЫ 2,2. Порог трёх звёзд — «ходов ≤ 1,15 × эталон».
 * При 2,2 это 2,53 × виды, а настоящий минимум 5,6 × виды: высшая оценка была бы
 * недостижима на КАЖДОМ столе, сколь угодно хорошо ни играй. Ровно этот дефект
 * сортировка товаров уже пережила (там три звезды были недостижимы на 95 %
 * досок), и увидеть его можно только перебором. Сторожит `cake-sort-reference`.
 *
 * 📌 И СТРУКТУРА, КОТОРАЯ ОБЪЯСНЯЕТ, ПОЧЕМУ ПЕРЕНОС БЫЛ ОБРЕЧЁН. Чтобы свести
 * вид в один круг, нужно минимум `CIRCLE − 1` переносов. Замеры дают 2,2 при
 * тройках (2 × 1,10) и 5,63 при шестёрках (5 × 1,13) — то есть эталон
 * пропорционален `CIRCLE − 1`, а не постоянен. Число, снятое под один круг,
 * к другому кругу отношения не имеет.
 *
 * ⚠️ ГРАНИЦЫ ЗАМЕРА, ЧЕСТНО. A* доходит до дна только на малых столах: с
 * шести видов две доски из шести уже не уложились в 200 000 узлов, а на боевых
 * уровнях с L6 не укладывается ни одна (60 000 узлов, 1,0–1,7 с). Значит 5,63 —
 * это замер по видам 3…6, а не по всей лестнице. Дальше он ЭКСТРАПОЛИРУЕТСЯ, и
 * это записано здесь прямо, чтобы следующий не принял его за измеренное.
 */
/** Ходов на один вид начинки. Замер, а не прикидка — см. шапку файла. */
export const REF_PER_TYPE = 5.6;

/**
 * Эталон ходов уровня. Одно место на игру и на гейт: два своих эталона однажды
 * разъедутся, и оценка на экране заспорит с оценкой в данных.
 */
export function moveReference(types: number): number {
  return Math.round(types * REF_PER_TYPE);
}

/**
 * Звёзды по ходам. Пороги считаются от ЭТАЛОНА, а не от доли «сколько не жалко»:
 * до +15 % сверх эталона — три звезды · до +60 % — две · дальше — одна.
 *
 * ⚠️ Вынесено наружу ради гейта. Проверка, повторяющая формулу у себя, ничего не
 * стоит: два числа из одного рассуждения согласуются по определению.
 */
export function starsForMoves(moves: number, reference: number): 1 | 2 | 3 {
  if (reference <= 0) return 1;
  if (moves <= reference * 1.15) return 3;
  if (moves <= reference * 1.6) return 2;
  return 1;
}
