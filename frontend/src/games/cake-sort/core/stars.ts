/**
 * ЭТАЛОН ХОДОВ И ЗВЁЗДЫ — единственное место, где они считаются.
 *
 * 🔴 КАЛИБРОВКА ЗАМЕРЕНА ДЛЯ ШЕСТЁРОК, А НЕ УНАСЛЕДОВАНА ОТ ТРОЕК.
 *
 * ТЗ раздела требует это прямо: «калибровка `REF_PER_TYPE = 2.2` снята под
 * тройки; для шестёрок она неверна — перезамерь A*, а не переноси число».
 *
 * ЗАМЕР (A* с допустимой эвристикой, `minMoves` без отсечений, бюджет 200 000
 * узлов; 40 столов, виды 3…6, запас тарелок 2 и 3):
 *
 *   виды 3, тарелок 5 — 5,67 · виды 3, тарелок 6 — 5,67
 *   виды 4, тарелок 6 — 5,67 · виды 4, тарелок 7 — 5,54
 *   виды 5, тарелок 7 — 5,57 · виды 5, тарелок 8 — 5,37
 *   виды 6, тарелок 8 — 5,92 (две доски из шести не уложились в бюджет)
 *   разброс по отдельным столам 5,0…6,3 · среднее **5,63**
 *
 * 🔴 ЧТО БЫЛО БЫ, УНАСЛЕДУЙ МЫ 2,2. Порог трёх звёзд — «ходов ≤ 1,15 × эталон».
 * При 2,2 это 2,53 × виды, а настоящий минимум 5,6 × виды: высшая оценка была бы
 * недостижима на КАЖДОМ столе, сколь угодно хорошо ни играй. Ровно этот дефект
 * сортировка товаров уже пережила (там три звезды были недостижимы на 95 %
 * досок), и увидеть его можно только перебором. Сторожит `cake-sort-reference`.
 *
 * 📌 И СТРУКТУРА, КОТОРАЯ ОБЪЯСНЯЕТ, ПОЧЕМУ ПЕРЕНОС БЫЛ ОБРЕЧЁН. Чтобы свести
 * вид в один круг, нужно минимум `CIRCLE − 1` переносов. Замеры дают 2,2 при
 * тройках (2 × 1,10) и 5,63 при шестёрках (5 × 1,13) — то есть эталон
 * пропорционален `CIRCLE − 1`, а не постоянен. Число, снятое под один круг,
 * к другому кругу отношения не имеет.
 *
 * ⚠️ ГРАНИЦЫ ЗАМЕРА, ЧЕСТНО. A* доходит до дна только на малых столах: с
 * шести видов две доски из шести уже не уложились в 200 000 узлов, а на боевых
 * уровнях с L6 не укладывается ни одна (60 000 узлов, 1,0–1,7 с). Значит 5,63 —
 * это замер по видам 3…6, а не по всей лестнице. Дальше он ЭКСТРАПОЛИРУЕТСЯ, и
 * это записано здесь прямо, чтобы следующий не принял его за измеренное.
 */
/**
 * Ходов на один КРУГ. Замер, а не прикидка — см. шапку файла.
 *
 * 🔴 5,6 → 3,75 ПОСЛЕ СМЕНЫ ПРАВИЛ 16.09.2026. Ход стал брать ЛЮБОЙ кусок, а не
 * верхний в стопке (решение Дениса), и ходов нужно заметно меньше. Прежнее число
 * завышало эталон на треть: три звезды («ходов ≤ 1,15 × эталон») доставались бы
 * даром на каждом столе — зеркальный дефект того, о котором предупреждает шапка
 * этого файла про унаследованные 2,2.
 *
 * ЗАМЕР тем же способом, что и прежний (`scripts/measure/cake-ref-free-choice.measure.ts`,
 * A* до дна, минимум делится на число кругов):
 *   L1 кругов 3 · минимум 11 · на круг 3,67
 *   L2 кругов 3 · минимум 12 · на круг 4,00
 *   L3 кругов 4 · минимум 15 · на круг 3,75
 *   L4 кругов 4 · минимум 15 · на круг 3,75
 *   коридор 3,67…4,00 · медиана 3,75 · досок 4
 *
 * ⚠️ ГРАНИЦЫ ЗАМЕРА, ЧЕСТНО — те же, что были у 5,6, и даже уже. При свободном
 * выборе ветвление шире (260 ходов на L20 против прежних десятков), и с L5 A* не
 * доходит до дна вовсе: 60 000 узлов исчерпаны за 4–10 секунд, 120 000 — за
 * 8–13. Значит 3,75 снят по кругам 3…4, а дальше ЭКСТРАПОЛИРУЕТСЯ.
 */
export const REF_PER_TYPE = 3.75;

/**
 * Эталон ходов уровня. Одно место на игру и на гейт: два своих эталона однажды
 * разъедутся, и оценка на экране заспорит с оценкой в данных.
 *
 * 🔴 СЧИТАЕТСЯ ПО ЧИСЛУ КРУГОВ, А НЕ ПО ЧИСЛУ ВИДОВ, И ЭТО ДВА РАЗНЫХ ЧИСЛА.
 *
 * Пока каждый вид давал ровно один круг, они совпадали, и разницы не было
 * видно. С очередью входящих кругов становится больше видов: на L60 видов
 * одиннадцать, а кругов восемнадцать. Считай эталон по видам — он занизится в
 * полтора раза, и три звезды («ходов ≤ 1,15 × эталон») станут недостижимы на
 * КАЖДОМ столе, сколь угодно хорошо ни играй.
 *
 * ⚠️ Это ровно тот дефект, о котором предупреждает шапка этого же файла на
 * примере унаследованной калибровки 2,2. Разница в том, что там занижался
 * множитель, а здесь — то, на что он множится.
 */
export function moveReference(circles: number): number {
  return Math.round(circles * REF_PER_TYPE);
}

/**
 * Звёзды по ходам. Пороги считаются от ЭТАЛОНА, а не от доли «сколько не жалко»:
 * до +15 % сверх эталона — три звезды · до +60 % — две · дальше — одна.
 *
 * ⚠️ Вынесено наружу ради гейта. Проверка, повторяющая формулу у себя, ничего не
 * стоит: два числа из одного рассуждения согласуются по определению.
 */
export function starsForMoves(moves: number, reference: number): 1 | 2 | 3 {
  if (reference <= 0) return 1;
  if (moves <= reference * 1.15) return 3;
  if (moves <= reference * 1.6) return 2;
  return 1;
}

/**
 * 🔴 ЭТАЛОН ПАРТИИ: точный минимум, если фоновый расчёт успел, иначе калибровка.
 *
 * Одна функция на игру и на гейт. Раньше этот выбор жил строчкой в экране —
 * тогда проверить его можно было только разбором исходника, а разбор исходника
 * не проверка: он видит форму записи, а не поведение.
 *
 * ⚠️ Точный минимум ВСЕГДА лучше оценки: на просторном столе он заметно меньше
 * калибровки, и звёзды по оценке выдавались бы за небрежную игру.
 */
export function referenceFor(circles: number, exactMin: number | null): number {
  return exactMin !== null && exactMin > 0 ? exactMin : moveReference(circles);
}

/**
 * Звёзды партии. Отдельно от `starsForMoves`, потому что здесь принимается ещё
 * и решение «по чему меряем» — а оно и есть та часть, которая ломается молча.
 */
export function starsFor(moves: number, circles: number, exactMin: number | null): 1 | 2 | 3 {
  return starsForMoves(moves, referenceFor(circles, exactMin));
}
