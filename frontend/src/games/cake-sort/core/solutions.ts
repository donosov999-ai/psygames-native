/**
 * ЗАПИСАННЫЕ РЕШЕНИЯ ВШИТЫХ УРОВНЕЙ — чтобы не искать путь на устройстве.
 *
 * 🔴 ЗАЧЕМ (задача af4c7ff1, замер 23.09.2026). Поиск пути дорожает с
 * ветвлением, и на бюджете 20000 один вызов стоит: L1 — 119 мс, L5 — 4,2 с,
 * L10 — 25,0 с, L20 — больше минуты. На экране бюджет урезан до 400 (82–756 мс),
 * но и это работа в кадре отрисовки на каждое нажатие подсказки. Путь найден
 * ОДИН РАЗ офлайн (`tools/record-solutions.gen.ts`) и лежит готовым.
 *
 * 🔴 ПЛОСКИЕ ТРОЙКИ И ОТДЕЛЬНЫЙ ФАЙЛ. Объекты `{from,type,to}` рядом с доской
 * раздули `levels.json` со 149 до 732 КБ — а он едет и в приложение, и в ассеты
 * переноса на Flutter. Тройки чисел: 10 148 ходов в 96 КБ.
 *
 * ⚠️ ФАЙЛ ЧИТАЕТСЯ ЛЕНИВО, при первом обращении. Подсказку жмут не все и не
 * всегда; разбирать сто килобайт на старте игры незачем.
 */

export interface Ход { from: number; type: number; to: number }

let кэш: Map<number, Ход[]> | null = null;

function загрузить(): Map<number, Ход[]> {
  if (кэш) return кэш;
  кэш = new Map();
  try {
     
    const файл = require('./solutions.json') as { moves: Record<string, number[]> };
    for (const [уровень, плоско] of Object.entries(файл.moves ?? {})) {
      const ходы: Ход[] = [];
      for (let i = 0; i + 2 < плоско.length; i += 3) {
        ходы.push({ from: плоско[i] as number, type: плоско[i + 1] as number, to: плоско[i + 2] as number });
      }
      кэш.set(Number(уровень), ходы);
    }
  } catch {
    /* Файла нет — игра работает как раньше, просто ищет путь сама. */
  }
  return кэш;
}

/**
 * Записанное решение уровня или `null`, если его нет.
 *
 * ⚠️ Возвращается КОПИЯ: экран режет путь по мере ходов игрока, и общий массив
 * он бы укоротил для всех.
 */
export function prebuiltSolution(L: number): Ход[] | null {
  const ходы = загрузить().get(Math.max(1, Math.floor(L) || 1));
  return ходы && ходы.length ? ходы.map((m) => ({ ...m })) : null;
}

/** Сколько уровней с записанным решением — для гейтов и отчётов. */
export function solutionsCount(): number {
  return загрузить().size;
}
