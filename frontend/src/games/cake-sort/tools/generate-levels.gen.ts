/**
 * 🔴 ОФЛАЙН-ГЕНЕРАЦИЯ УРОВНЕЙ С ДОКАЗАННЫМ МИНИМУМОМ ХОДОВ.
 *
 * ЗАЧЕМ. Две задачи, у которых один ответ:
 *
 * 1. Звёзды. `minMoves` — точный поиск A*, и он честно перестаёт доходить до дна
 *    с шестого уровня: замер дал 60 000 узлов и 1,0–1,7 с на стол. Держать на
 *    этом старт уровня нельзя, поэтому выше L6 звёзды шли от КАЛИБРОВКИ 5,6 —
 *    оценки по числу видов. Оценка не обязана иметь отношения к тому, за сколько
 *    доска решается на самом деле.
 * 2. Размер доски. Разбор §4а: на 30–40 нишах перебор не доказывает ничего,
 *    значит уровни надо генерировать офлайн и вшивать.
 *
 * Здесь и то и другое: столы считаются ЗАРАНЕЕ, вместе с доказательством
 * решаемости и точным минимумом, и ложатся файлом. На устройстве не считается
 * ничего — оно читает готовое.
 *
 * ⚠️ ЭТО ИНСТРУМЕНТ, А НЕ ПРОБА. `testMatch` берёт только `src/__tests__`,
 * поэтому в обычный прогон файл не попадает. Запуск явный:
 *
 *   npx jest --testMatch '**\/tools/*.gen.ts' --testTimeout 900000
 *
 * ⚠️ И ОН ЗОВЁТ ТО ЖЕ ЯДРО, ЧТО ИГРА. Своя копия правил в генераторе — два
 * источника одной правды: подвинут круг в ядре, а файл останется от старых
 * правил, и заметить это будет нечем.
 */
import { deal } from '../core/level';
import { solve, minMoves } from '../core/solver';
import { allSectors, CIRCLE } from '../core/plate';

declare const __dirname: string;
declare function require(id: string): any;
const fs = require('fs');
const path = require('path');

const СКОЛЬКО = Number(process.env.CAKE_LEVELS ?? 60);
/**
 * Бюджет точного минимума. На устройстве держим 30 000 — там важна отзывчивость.
 *
 * 🔴 ЗДЕСЬ БЫЛО 400 000 «раз время не жмёт», и это оказалось неверно дважды.
 *
 * ⚠️ Жмёт не время, а ПАМЯТЬ. A* держит каждое виденное состояние в карте и
 * целые доски в корзинах. После того как очередь входящих стала настоящей,
 * доски выросли (156 секторов на L120 против 66), и прогон на 120 уровней
 * упёрся в предел кучи узла: замер 07.09.2026 — `FATAL ERROR: Ineffective
 * mark-compacts near heap limit`, 4 075 МБ на 322-й секунде, файл не записан.
 *
 * ⚠️ И главное: за эти 400 000 не покупается НИ ОДНОГО лишнего уровня. Замер
 * того же дня — где точный минимум ещё достижим:
 *
 *   бюджет  40 000: L1 (394 узла) · L3 (4 202) · L5 (9 286) · L6 — нет
 *   бюджет 120 000: те же + L6 (100 590 узлов, 1,7 с, куча 179 МБ) · L7 — нет
 *                   (L7 съедает 120 000 узлов и 391 МБ, не дойдя до дна)
 *
 * То есть граница проходит по L6 и держится там: между L6 и L7 поиск дорожает
 * на порядок, и удвоение бюджета её не сдвигает. 120 000 берёт всё, что берётся,
 * и не падает. Переопределяется `CAKE_MIN_BUDGET`, если понадобится померить
 * границу заново.
 */
const БЮДЖЕТ_МИНИМУМА = Number(process.env.CAKE_MIN_BUDGET ?? 120000);
const БЮДЖЕТ_РЕШАЕМОСТИ = 20000;

jest.setTimeout(1800000);

it(`генерирует ${СКОЛЬКО} уровней тортов с доказанной решаемостью`, () => {
  const уровни: unknown[] = [];
  let сМинимумом = 0;
  const пропущено: string[] = [];

  /**
   * 🔴 ПЕРЕСТАЁМ ПЛАТИТЬ ЗА ТОЧНЫЙ МИНИМУМ, КОГДА ОН УЖЕ НЕДОСТИЖИМ.
   *
   * Стол растёт по всем трём осям монотонно: видов не убывает, тарелок не
   * убывает, очередь не убывает. Значит и пространство состояний только растёт,
   * и уровень, на котором A* не дошёл до дна, не станет проще на следующем.
   *
   * ⚠️ Порог в три подряд, а не в один: соседние уровни отличаются раскладом, и
   * одна неудача может быть невезением конкретной раздачи, а не границей.
   *
   * 📍 Замер 07.09.2026 оправдывает саму отсечку: на всех 120 уровнях точный
   * минимум находится ровно на шести первых, а каждая безнадёжная попытка стоит
   * полного бюджета. Без отсечки прогон занимал больше двадцати минут и однажды
   * упёрся в предел кучи; с ней — секунды.
   */
  let подрядБезМинимума = 0;
  const СДАЁМСЯ_ПОСЛЕ = 3;

  for (let L = 1; L <= СКОЛЬКО; L += 1) {
    const { board, cfg, tries } = deal(L);
    const r = solve(board, БЮДЖЕТ_РЕШАЕМОСТИ);
    /**
     * 🔴 В ФАЙЛ НЕ КЛАДЁМ ТО, ЧТО НЕ ДОКАЗАНО. Непроходимый уровень, вшитый в
     * сборку, хуже посчитанного на месте: его уже не пересоберёшь на устройстве.
     */
    if (!r.solvable) { пропущено.push(`L${L}: решаемость не доказана (исчерпание=${r.exhausted})`); continue; }
    const секторов = allSectors(board).length;
    if (секторов % CIRCLE !== 0) { пропущено.push(`L${L}: секторов ${секторов} не кратно кругу`); continue; }
    const m = подрядБезМинимума >= СДАЁМСЯ_ПОСЛЕ
      ? { moves: null }
      : minMoves(board, БЮДЖЕТ_МИНИМУМА);
    if (m.moves !== null) { сМинимумом += 1; подрядБезМинимума = 0; } else подрядБезМинимума += 1;
    уровни.push({
      level: L, types: cfg.types,
      plates: board.plates.map((p) => [...p]),
      queue: board.queue.map((p) => [...p]),
      /** Точный минимум ходов; null — не уложились даже в офлайн-бюджет. */
      min: m.moves, tries,
    });
  }

  const файл = path.join(__dirname, '..', 'core', 'levels.json');
  fs.writeFileSync(файл, `${JSON.stringify({ circle: CIRCLE, levels: уровни }, null, 1)}\n`, 'utf8');
  console.log(`ГОТОВО: уровней ${уровни.length} из ${СКОЛЬКО} · с точным минимумом ${сМинимумом}`);
  if (пропущено.length) console.log(`ПРОПУЩЕНО: ${пропущено.join(' | ')}`);

  expect(уровни.length).toBe(СКОЛЬКО);
  expect(пропущено).toEqual([]);
});
