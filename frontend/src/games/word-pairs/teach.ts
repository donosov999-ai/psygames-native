/**
 * 🎓 РАЗБОР ПО ШАГАМ «ПАРЫ СЛОВ»: ПРИЁМ СВЯЗКИ, А НЕ ПРАВИЛА ЭКРАНА.
 *
 * 📍 Денис 17.09.2026: «обучение зашло — раскатывай везде». Для игр на запоминание разбор
 * обязан проговаривать САМ ПРИЁМ на настоящем материале уровня.
 *
 * 🔴 ЧЕМУ УЧИМ. Пара слов держится не повторением, а ОДНОЙ картинкой, где оба слова
 * действуют вместе: не «окно — кошка» двадцать раз про себя, а кошка, которая сидит в окне.
 * Поэтому карточки называют оба слова и просят связать их сценой, а не «запомнить».
 * Второй приём — проверка задом наперёд: если по второму слову всплывает первое, связка
 * держится; если нет — картинка была вялой.
 *
 * ⚠️ РАЗБОР ГОВОРИТ РОВНО ТО, ЧТО ИГРА ЗАСЧИТАЕТ: пары берутся из самой партии, и проба
 * `word-pairs-teach` соединяет их карточками, требуя ноль ошибок.
 */

export interface ПараРазбора { id: number; слово1: string; слово2: string }

export interface КарточкаПар {
  вид: 'приём' | 'связка' | 'проверка' | 'соединение' | 'готово';
  /** Ключ словаря: язык живёт в словаре, не в коде. */
  ключ: string;
  поля?: Record<string, string | number>;
  /** Какую пару подсветить (индекс) или `null`. */
  пара: number | null;
  /** Показывать ли второе слово пары: на проверке оно сперва скрыто. */
  открыто: boolean;
}

export interface РазборПар {
  карточки: КарточкаПар[];
  /** Пары, которые разбор показал: ими и играем в пробе. */
  пары: ПараРазбора[];
}

/**
 * ⚠️ РАЗБОР БЕРЁТ НЕ БОЛЬШЕ ЧЕТЫРЁХ ПАР. На первых уровнях их и так четыре, но лестница
 * доходит до пятнадцати: полный разбор пятнадцати пар — это сорок карточек и три минуты
 * ролика, который никто не досмотрит. Приём показывается на четырёх, дальше человек
 * применяет его сам — за этим разбор и нужен.
 */
const ПОКАЗЫВАЕМ_ПАР = 4;

export function собратьРазборПар(пары: readonly ПараРазбора[]): РазборПар {
  const взято = пары.slice(0, Math.min(ПОКАЗЫВАЕМ_ПАР, пары.length));
  const карточки: КарточкаПар[] = [{
    вид: 'приём',
    ключ: 'teachPairsIntro',
    поля: { n: пары.length },
    пара: null,
    открыто: false,
  }];

  взято.forEach((пара, i) => {
    карточки.push({
      вид: 'связка',
      ключ: i === 0 ? 'teachPairsLinkFirst' : 'teachPairsLink',
      поля: { a: пара.слово1, b: пара.слово2 },
      пара: i,
      открыто: true,
    });
  });

  /** Проверка задом наперёд — на первой паре: по второму слову вспоминаем первое. */
  карточки.push({
    вид: 'проверка',
    ключ: 'teachPairsCheck',
    поля: { a: взято[0]!.слово1, b: взято[0]!.слово2 },
    пара: 0,
    открыто: false,
  });

  карточки.push({
    вид: 'соединение',
    ключ: 'teachPairsMatch',
    поля: { n: пары.length },
    пара: null,
    открыто: true,
  });

  карточки.push({ вид: 'готово', ключ: 'teachPairsDone', пара: null, открыто: true });
  return { карточки, пары: [...пары] };
}
