/**
 * 🎓 РАЗБОР ПО ШАГАМ «ПРОЧТИ ЭМОЦИЮ»: ПРИЗНАКИ ГЛАЗ → СРАВНЕНИЕ → ВЫБОР.
 *
 * 📍 Денис 17.09.2026: «обучение … учил логике игры: почему тут ставим». У этой игры логика —
 * не ход, а чтение: сначала признаки глаз (брови, веки, взгляд), потом сравнение с тем, как
 * выглядели бы соседние слова, и только потом выбор. Правило-вступление (`teachRmetEyes`) общее
 * с Flutter-половиной: «сравнивайте варианты между собой, а не с первым впечатлением».
 *
 * 🔴 СРАВНЕНИЕ ТОЛЬКО ПО ДАННЫМ САМОЙ ИГРЫ. Как выглядел бы «раздражённый», разбор говорит
 * признаками, которые игра сама приписала «раздражённому» в его пункте (`hint`), и показывает
 * его фото. Для слов без своего пункта признаков в данных нет — такое слово разбор не описывает.
 * Поэтому примеры берутся из пунктов, где сравнивать есть с чем. Замер 30.09.2026: для русских
 * слов таких пунктов 11 из 18, для английских — 6 из 18 (формы слов в двух языках расходятся:
 * «испуганный» — это и frightened, и fearful).
 *
 * ⚠️ РАЗБОР НЕ ГОВОРИТ «ЗДЕСЬ ЭТОГО НЕТ». Признаки соседних слов иногда пересекаются: у
 * «умоляющего» и «уверенного» оба описания говорят о прищуре. Утверждать отсутствие признака
 * значило бы учить неправде; поэтому карточка сравнения называет признаки соседа и просит
 * сравнить, а выбор называет признаки, которые решают.
 *
 * ⚠️ ПРИМЕР НЕ СОВПАДАЕТ С ТЕКУЩИМ ЗАДАНИЕМ: разбор открывается посреди партии, и пример с тем
 * же пунктом просто показал бы ответ.
 */

export interface ПунктЭмоции {
  hint_ru: string;
  hint_en: string;
  correct_ru: string;
  correct_en: string;
  options_ru: string[];
  options_en: string[];
}

export interface КарточкаЭмоции {
  вид: 'приём' | 'признаки' | 'сравнение' | 'выбор' | 'готово';
  /** Ключ словаря: язык живёт в словаре, не в коде. */
  ключ: string;
  поля?: Record<string, string | number>;
  /** Пункт-пример (индекс в переданном списке) или `null`. */
  пункт: number | null;
  /** С чьим пунктом сравниваем на этой карточке (индекс) или `null`. */
  сосед: number | null;
  /** Выбранный ответ — только на карточке выбора. */
  выбрано: string | null;
}

export interface РазборЭмоций {
  карточки: КарточкаЭмоции[];
  /** Пункты-примеры по порядку показа. */
  примеры: number[];
}

/** Два примера: приём виден на втором, дальше человек применяет его сам. */
const ПРИМЕРОВ = 2;
/** Больше двух сравнений на пример — это уже перебор всех слов, а не приём. */
const СРАВНЕНИЙ = 2;

const поле = (п: ПунктЭмоции, ru: boolean) => ({
  подсказка: ru ? п.hint_ru : п.hint_en,
  верное: ru ? п.correct_ru : п.correct_en,
  варианты: ru ? п.options_ru : п.options_en,
});

/** С какими вариантами пункта есть что сравнить: слово — верный ответ другого пункта. */
export function соседиПункта(пункты: readonly ПунктЭмоции[], индекс: number, язык: string): number[] {
  const ru = язык === 'ru';
  const { верное, варианты } = поле(пункты[индекс]!, ru);
  const поСлову = new Map(пункты.map((п, i) => [поле(п, ru).верное, i] as const));
  return варианты
    .filter((в) => в !== верное && поСлову.has(в))
    .map((в) => поСлову.get(в)!);
}

export function собратьРазборЭмоций(
  пункты: readonly ПунктЭмоции[],
  язык: string,
  исключить: number | null,
  rnd: () => number = Math.random,
): РазборЭмоций {
  const ru = язык === 'ru';
  const годные = пункты
    .map((_, i) => i)
    .filter((i) => i !== исключить && соседиПункта(пункты, i, язык).length > 0);
  // Перемешиваем годные и берём первые: пример каждый раз свой, как и партия.
  for (let i = годные.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [годные[i], годные[j]] = [годные[j]!, годные[i]!];
  }
  const примеры = годные.slice(0, ПРИМЕРОВ);

  const карточки: КарточкаЭмоции[] = [
    { вид: 'приём', ключ: 'teachRmetEyes', пункт: null, сосед: null, выбрано: null },
  ];
  for (const i of примеры) {
    const { подсказка, верное } = поле(пункты[i]!, ru);
    карточки.push({ вид: 'признаки', ключ: 'teachRmetCues', поля: { hint: подсказка }, пункт: i, сосед: null, выбрано: null });
    for (const с of соседиПункта(пункты, i, язык).slice(0, СРАВНЕНИЙ)) {
      const сосед = поле(пункты[с]!, ru);
      карточки.push({
        вид: 'сравнение',
        ключ: 'teachRmetCompare',
        поля: { word: сосед.верное, cues: сосед.подсказка },
        пункт: i,
        сосед: с,
        выбрано: null,
      });
    }
    карточки.push({
      вид: 'выбор',
      ключ: 'teachRmetPick',
      поля: { word: верное, hint: подсказка },
      пункт: i,
      сосед: null,
      выбрано: верное,
    });
  }
  карточки.push({ вид: 'готово', ключ: 'teachRmetDone', пункт: null, сосед: null, выбрано: null });
  return { карточки, примеры };
}
