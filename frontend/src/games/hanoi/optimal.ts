/**
 * МИНИМУМ ХОДОВ В ХАНОЙСКОЙ БАШНЕ — ПО ЧИСЛУ СТЕРЖНЕЙ, А НЕ ВСЕГДА ПО ТРЁМ.
 *
 * 🔴 ЧТО БЫЛО. В экране стояло `optimal = (n) => 2**n - 1` — формула для ТРЁХ
 * стержней. А уровни дают три стержня только до L4: с L5 их четыре, с L10 — пять.
 * Замер расхождения (истинный минимум против показанного):
 *   L5  (5 дисков / 4 стержня):  13  против   31  — в 2,4 раза
 *   L9  (9 / 4):                 41  против  511  — в 12,5 раза
 *   L13 (12 / 5):                47  против 4095  — в 87 раз
 *
 * Три следствия сразу, и каждое портит своё:
 *  · в шапке висела цель, завышенная в 87 раз — «Ходов 0 / 4095»;
 *  · `stars = moves <= optimal` давало с L5 ТРИ ЗВЕЗДЫ за любое решение —
 *    оценка переставала что-либо оценивать;
 *  · счёт раздувался примерно до 200 000 против задуманной тысячи.
 *
 * ━━━ ФРЕЙМ — СТЮАРТ ━━━
 * Для p > 3 стержней минимум даёт рекуррента Фрейма — Стюарта: перенести верхние
 * k дисков на запасной стержень (он остаётся доступным, отсюда `2·FS(k, p)`),
 * затем нижние n−k классической задачей на p−1 стержнях, затем вернуть k.
 *     FS(n, p) = min по k∈[1, n−1] { 2·FS(k, p) + FS(n−k, p−1) }
 *     FS(0, p) = 0 · FS(n, 3) = 2ⁿ − 1
 *
 * ⚠️ ЭТО МИНИМУМ ПО ГИПОТЕЗЕ, А НЕ ДОКАЗАННЫЙ ФАКТ ДЛЯ ЛЮБЫХ n И p. Оптимальность
 * Фрейма — Стюарта доказана для четырёх стержней (Bousch, 2014); для пяти и более
 * она остаётся гипотезой, хотя проверена перебором далеко за наши двенадцать
 * дисков. Для игры этого достаточно с запасом, но писать «истинный минимум» без
 * оговорки было бы неточно.
 *
 * ⚠️ ЧИСЛА НЕ ХАРДКОДИМ. Таблица считается один раз и кэшируется: захардкоженные
 * значения разойдутся с уровнями в первый же раз, когда тронут `levelParams`.
 */

/** Кэш: ключ `n:p`. Считается лениво, живёт всё время работы приложения. */
const кэш = new Map<string, number>();

export function frameStewart(n: number, p: number): number {
  if (n <= 0) return 0;
  if (n === 1) return 1;
  /**
   * ⚠️ Меньше трёх стержней задача не решается вовсе: диск некуда переложить.
   * Возвращать здесь 0 или ∞ значит тихо соврать, поэтому падаем — такого вызова
   * в игре быть не может, и если он появился, это ошибка уровней, а не счёта.
   */
  if (p < 3) throw new Error(`Ханой: ${p} стержня(ей) — задача неразрешима`);
  if (p === 3) return Math.pow(2, n) - 1;

  const ключ = `${n}:${p}`;
  const готовое = кэш.get(ключ);
  if (готовое !== undefined) return готовое;

  let лучшее = Infinity;
  for (let k = 1; k < n; k++) {
    const вариант = 2 * frameStewart(k, p) + frameStewart(n - k, p - 1);
    if (вариант < лучшее) лучшее = вариант;
  }
  кэш.set(ключ, лучшее);
  return лучшее;
}

/**
 * Счёт за собранную башню — ОДНА формула на все места.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНОЙ ФУНКЦИЕЙ. Формула была написана дважды и по-разному:
 * при сохранении считалось `moves + 1 - optimal`, на экране результата
 * `moves - optimal`. Расхождение ровно 50 очков — то есть человек видел одно
 * число, а в его историю уходило другое. Спорить с такой историей нечем.
 */
export function hanoiScore(ходов: number, минимум: number, секунд: number): number {
  return Math.max(0, Math.round(1000 - (ходов - минимум) * 50 - секунд));
}

/**
 * Звёзды за решение. Три — только за оптимум, дальше по запасу.
 * ⚠️ Порог «1.5×» сохранён от прежней редакции намеренно: он не был сломан,
 * ломалась подставляемая в него величина.
 */
export function hanoiStars(ходов: number, минимум: number): 1 | 2 | 3 {
  if (ходов <= минимум) return 3;
  if (ходов <= Math.ceil(минимум * 1.5)) return 2;
  return 1;
}
