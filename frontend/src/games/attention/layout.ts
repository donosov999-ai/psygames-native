/**
 * ЕДИНАЯ ГЕОМЕТРИЯ ДЕСЯТИ ПРОБ РАЗДЕЛА — ЧИСЛА В ОДНОМ МЕСТЕ.
 *
 * 🔴 ЗАЧЕМ. В «Зарядке» пробы идут вперемешку: то один Струп, то другой, то
 * фланкер, то Саймон. Если у каждой свои размеры, интерфейс прыгает между
 * пробами, и это раздражает сильнее, чем сама задача. Замер 07.09.2026 по
 * десяти играм (телефон 390×844, каждая в партии):
 *
 *   высота полосы ответа   85…281 px   разброс 196
 *   центр окна стимула     403…504     разброс 101
 *   высота окна стимула    120…358     разброс 238
 *   размеров кнопок        ШЕСТЬ: 58×74, 64×64, 88×88, 102×48, 121×68, 258×72
 *   рядов кнопок           1, 2 и 4
 *
 * Самый наглядный случай — два Струпа подряд: обычный даёт полосу 281 px и
 * ЧЕТЫРЕ ряда кнопок, эмоциональный — 127 px и два. Между двумя пробами одной
 * методики экран дёргается на 154 px.
 *
 * ⚠️ ПОЧЕМУ ЧИНИТСЯ ЗДЕСЬ, А НЕ В КАРКАСЕ. Высоту полосы ответа задаёт
 * СОДЕРЖИМОЕ экрана, а не `GameShell`: каркас лишь оборачивает то, что игра
 * положила в слот `toolbar`. Значит разнобой развели сами игры, каждая своим
 * набором чисел, и свести его надо тоже у себя. Каркас не трогаем.
 *
 * ⚠️ И ОТДЕЛЬНО — ПОЧЕМУ РАЗМЕРЫ СЧИТАЮТСЯ, А НЕ ЗАШИТЫ. `GameShell` держит в
 * слоте ответа симметричный отступ `FAB_GUTTER = 66` с обеих сторон под
 * плавающую кнопку отзыва, и там же записано: «игры, считающие размеры от неё,
 * обязаны считать от ширины экрана, а не от зашитых чисел». На этом уже
 * споткнулся WCST: зашитая ширина 80 не влезала в оставшиеся 258, и четыре
 * эталона ложились 3 + 1 (починено, коммит 169b62f9).
 */

/** Отступ слота ответа в GameShell: FAB_GUTTER 66 слева и справа. */
export const GUTTER_BOTH = 132;

/** Зазор между кнопками ответа и между рядами. */
export const BTN_GAP = 12;

/** Норма попадания пальцем на поле (Material); её же держит tap-target-audit. */
export const MIN_TAP = 48;

/**
 * ВЫСОТА ПОЛОСЫ ОТВЕТА — ОДНА НА ВСЕ ДЕСЯТЬ.
 *
 * 120 выбрано не «на глаз»: это самый тесный вариант, в который влезают все три
 * типа ответа без нарушения нормы пальца.
 *   две стороны:      круг 88 + отступы 2×16 = 120  ← определяющий тип
 *   четыре варианта:  два ряда по 48 + зазор 12 = 108, влезает
 *   одна кнопка:      56 + отступы, влезает с запасом
 * Меньше 120 не даёт круг 88, больше — незачем: полоса начнёт съедать поле.
 */
export const ANSWER_BAR_H = 120;

/**
 * 🔴 ПОЛОСА ОТВЕТА — ОДИН СТИЛЬ НА ВСЕ ДЕСЯТЬ, А НЕ СЕМЬ КОПИЙ.
 *
 * ЧТО БЫЛО ДО 09.09.2026. Обёртка `AnswerBar` есть, но ею пользуются ТРИ пробы
 * из десяти; остальные семь держат собственную копию под своим именем —
 * `answersGrid`, `toolbarLtr`, `refRow`, `choiceGrid`, `choiceRow`. Копии
 * разошлись в одном поле: у flanker, simon и switching-task стоял
 * `alignItems: 'center'`, у stroop, wcst, stroop-emotional и ant не стояло
 * ничего. Из-за этого низ кнопки уезжал вслед за ВЫСОТОЙ самой кнопки:
 *
 *   замер 09.09, кадр 375×812 — низ кнопки 753…790 при каноне 802;
 *   тот же замер 390×844      — низ кнопки 788…822 при каноне 834.
 *
 * Полоса при этом стояла безупречно: её низ 812 (и 844) у ВСЕХ десяти, разброс
 * ноль. Разъезжалось содержимое внутри неё.
 *
 * ⚠️ И гейт этого не видел, потому что мерил ВЫСОТУ полосы — 141 у всех, разброс
 * 0, зелено по праву. Пальцу безразлична высота полосы; жалоба, с которой всё
 * началось, звучала «кнопка прыгает».
 *
 * 📌 ЯКОРЬ СНИЗУ, А НЕ ПО ЦЕНТРУ — в этом вся правка. `alignItems: 'flex-end'`
 * ставит низ кнопки на низ полосы независимо от её высоты; `alignContent`
 * прижимает к низу и многорядные раскладки (два ряда плашек у Струпа).
 * Замысел был таким с самого начала — он записан выше, у `ANSWER_BAR_H`:
 * «круг 88 + отступы 2×16 = 120». Центрирование его не выполняло.
 *
 * Свои зазоры игры дописывают ПОСЛЕ раскрытия: `{ ...ANSWER_BAR_ROW, gap: 24 }`.
 * Стережёт `frontend/scripts/attention-geometry-audit.mjs` — он мерит низ кнопки
 * и сверяет его с каноном слота каркаса (`GameShell`: paddingBottom 10).
 */
export const ANSWER_BAR_ROW = {
  height: ANSWER_BAR_H,
  flexDirection: 'row',
  flexWrap: 'wrap',
  justifyContent: 'center',
  alignItems: 'flex-end',
  alignContent: 'flex-end',
  gap: BTN_GAP,
  width: '100%',
} as const;

/**
 * ОКНО СТИМУЛА — ОДНА КОРОБКА НА ВСЕ ДЕСЯТЬ.
 *
 * 360×300. Ширина — по экрану 390 минус поля каркаса; высота 300 берётся из
 * самого крупного нынешнего стимула (CPT 358 и «переключение» 320 ужимаются,
 * фланкер 120 и эмоциональный Струп 130 перестают болтаться в пустоте).
 * Коробка НЕ дышит: стимул вписывается внутрь, а её собственный размер не
 * зависит от того, что показывают. Именно дыхание коробки и двигало центр на
 * 101 px между пробами.
 */
export const STIM_W = 360;
export const STIM_H = 300;
export const STIM_RADIUS = 20;

/**
 * 🔴 КОРОБКА СТИМУЛА — ОДИН СТИЛЬ НА ВЕСЬ РАЗДЕЛ, А НЕ СЕМЬ КОПИЙ.
 *
 * ПОВОД. Владелец 10.09.2026 посмотрел три экрана рядом: «пляшет между тремя
 * экранами окно вывода». Замер гейтом подтвердил числом:
 *   центр коробки 387 · 389 · 397 · 399 · 411 · 411 · 438 — разброс 51 px,
 *   а у Струпа, WCST и мишеней коробки НЕТ ВОВСЕ.
 * Разбор оформления нашёл причину разнобоя: каждый экран держал свою копию
 * стиля. Радиусы 14 · 16 · 16 · 16 · 24 · 24 · 28, рамка то 0, то 2, то 1→3.
 *
 * ⚠️ И самое показательное: `STIM_RADIUS = 20` объявлен ЗДЕСЬ с 07.09, и его не
 * брал НИ ОДИН экран — grep давал ноль попаданий вне этого файла. Объявить общее
 * число мало: пока каждый пишет своё, общее число остаётся комментарием.
 *
 * ⚠️ РАМКА ПОСТОЯННОЙ ТОЛЩИНЫ, меняется только ЦВЕТ. У flanker, simon и cpt она
 * росла 1 → 3 на отклике, и внутренняя область прыгала на 4 px ПОД ЕЩЁ ВИДИМЫМ
 * стимулом — то есть стимул съезжал в момент ответа.
 *
 * Размеры сюда НЕ входят: их даёт `stimBox(w, h)` от экрана. Цвета тоже: они
 * зависят от темы и от отклика, и живут в самом экране.
 */
export const STIM_BOX = {
  borderRadius: STIM_RADIUS,
  borderWidth: 2,
  justifyContent: 'center',
  alignItems: 'center',
} as const;

/**
 * КОРОБКА СТИМУЛА — ОДНА НА ВСЕ ДЕСЯТЬ, И ОНА НЕ ДЫШИТ.
 *
 * 🔴 ЗАЧЕМ ФУНКЦИЯ, А НЕ ДВЕ КОНСТАНТЫ. Замер 07.09 показал не только разные
 * размеры (120…358 по высоте), но и разные СПОСОБЫ их считать: CPT берёт
 * `min(ширина−32, высота·0.5, 460)`, «переключение» — `min(ширина−36, 320)`,
 * фланкер и эмоциональный Струп зашивают числа. Пока правило у каждого своё,
 * коробка будет дышать при любой правке. Здесь правило одно.
 *
 * Высота ограничена долей экрана, а не числом: на низком экране коробка 300 px
 * съела бы поле вместе с подсказкой. `side` — меньшая сторона, от неё игры
 * масштабируют сам стимул (буква, стрелки, карточка), как делали от своей.
 */
/**
 * Самый узкий телефон, который мы считаем настоящим. Ноль и отрицательное от
 * системы приводятся к нему — тогда первый кадр выглядит как маленький телефон,
 * а не как сломанная вёрстка.
 *
 * 🔴 07.09.2026. В веб-сборке (Android у нас WebView — значит и телефон)
 * `useWindowDimensions()` на первом кадре отдаёт 0. Раньше это гасили
 * ограничители `Math.max(14, ...)`, стоявшие инлайном у каждого экрана;
 * сведение геометрии их убрало, и ноль пошёл прямо в формулы:
 * `stimBox(0,0)` давал ширину −30, `answerButton('single',0)` — 0.
 * Стережёт `src/__tests__/attention-layout-zero-frame.test.ts`.
 *
 * ⚠️ Это ВТОРОЙ рубеж, а не замена первому: экран обязан брать размер
 * защищённым `useScreenSize()` (`src/hooks/useScreenWidth.ts`). Здесь — на
 * случай, если в формулу прилетит мусор откуда-то ещё.
 */
const MIN_SCREEN_W = 320;
const MIN_SCREEN_H = 480;

/** Ноль, NaN и отрицательное — не размеры экрана. */
const экран = (v: number, пол: number): number =>
  Number.isFinite(v) && v >= пол ? v : пол;

export function stimBox(screenW: number, screenH: number): { w: number; h: number; side: number } {
  const ш = экран(screenW, MIN_SCREEN_W);
  const в = экран(screenH, MIN_SCREEN_H);
  const w = Math.min(STIM_W, ш - 30);
  const h = Math.min(STIM_H, Math.round(в * 0.38));
  return { w, h, side: Math.min(w, h) };
}

export type AnswerKind = 'side' | 'choice' | 'single';

/**
 * РАЗМЕР КНОПКИ ОТВЕТА ПО ТИПУ ОТВЕТА.
 *
 *   'side'   — две стороны (лево/право): круг. Так уже у фланкера и Саймона;
 *              выбор-реакция и ANT подтягиваются к ним с нынешних 64.
 *   'choice' — четыре варианта, два ряда по две. Струп (сейчас 4 ряда),
 *              эмоциональный Струп (2 ряда) и WCST (1 ряд) сводятся сюда.
 *   'single' — одна кнопка на всю ширину (мишени; CPT — решение Дениса 07.09).
 *
 * Ширина считается от экрана: доступно `screenW - GUTTER_BOTH`.
 */
export function answerButton(kind: AnswerKind, screenW: number): { w: number; h: number; radius: number } {
  const avail = экран(screenW, MIN_SCREEN_W) - GUTTER_BOTH;
  if (kind === 'side') {
    // круг не растягиваем: 88 — привычный размер у фланкера и Саймона, и он
    // определяет высоту полосы. На очень узком экране ужимаем до нормы пальца.
    const d = Math.max(MIN_TAP, Math.min(88, Math.floor((avail - BTN_GAP) / 2)));
    return { w: d, h: d, radius: Math.round(d / 2) };
  }
  if (kind === 'choice') {
    const w = Math.max(MIN_TAP, Math.min(170, Math.floor((avail - BTN_GAP) / 2)));
    return { w, h: MIN_TAP, radius: 14 };
  }
  return { w: Math.max(MIN_TAP, avail), h: 56, radius: 16 };
}

/** Сколько рядов занимает ответ данного типа — для проверки, что полоса не переполнена. */
export const answerRows = (kind: AnswerKind): number => (kind === 'choice' ? 2 : 1);

/** Высота, которую ответ реально займёт. Должна помещаться в ANSWER_BAR_H. */
export function answerContentH(kind: AnswerKind, screenW: number): number {
  const b = answerButton(kind, screenW);
  const rows = answerRows(kind);
  return rows * b.h + (rows - 1) * BTN_GAP;
}
