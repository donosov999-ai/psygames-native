/* Наклон Хика для «Выбора-реакции»: RT против log2(числа альтернатив). */

/**
 * 🔴 ЗАЧЕМ ЭТОТ ФАЙЛ. «Выбор-реакция» была ЕДИНСТВЕННЫМ экраном развилки
 * «Конфликт внимания» без клинического показателя: в SESSION_MEASURE у неё
 * стояло `mean_rt` с пометкой «🔴 КЛИНИЧЕСКОГО ПОКАЗАТЕЛЯ НЕТ».
 *
 * Канонная мера этой парадигмы — НАКЛОН ХИКА: насколько растёт время ответа,
 * когда вариантов становится больше. Закон Хика: RT ≈ a + b·log2(n), и
 * клиническое значение имеет именно b — скорость перебора вариантов.
 *
 * ЧЕМ БЫЛО ЗАБЛОКИРОВАНО: наклон требует РАЗНОГО числа альтернатив, а число
 * менялось только МЕЖДУ уровнями — и вместе с ним менялось окно ответа. Две
 * точки, снятые при разных окнах, несравнимы: изменились сразу две величины.
 *
 * ЧТО СДЕЛАНО: число альтернатив меняется БЛОКАМИ ВНУТРИ партии при одном и том
 * же окне. Так набирается несколько точек за один заход, и всё, кроме числа
 * вариантов, остаётся постоянным.
 *
 * ⚠️ И ЕЩЁ ОДНО УСЛОВИЕ, БЕЗ КОТОРОГО НАКЛОН НЕДЕЙСТВИТЕЛЕН: моторика.
 * Если при двух вариантах кнопки стоят ближе, чем при четырёх, в замер влезает
 * закон Фиттса (время ∝ log2(2D/W)), и наклон выйдет смесью двух законов.
 * У экрана крестовина рисует ВСЕ четыре позиции всегда, неактивные — пустыми
 * (`есть(d) ? padBtn(d) : пусто(...)` в choice-rt.tsx), поэтому расстояние до
 * любой живой кнопки не зависит от их числа. Это свойство обязательно к
 * сохранению: сломаешь его — сломается мера.
 */

/** Точка замера: сколько вариантов было живо и сколько мс занял ответ. */
export type ТочкаХика = { n: number; rt: number };

export type НаклонХика = {
  /** Наклон b в RT ≈ a + b·log2(n), мс на бит. null = посчитать нельзя. */
  slopeMsPerBit: number | null;
  /** Свободный член a — базовое время без выбора, мс. */
  interceptMs: number | null;
  /** Сколько РАЗНЫХ n участвовало. Меньше двух — прямую не провести. */
  distinctN: number;
  /** Сколько проб легло в замер. */
  trials: number;
  /** Среднее RT по каждому n — чтобы наклон можно было перепроверить глазами. */
  byN: { n: number; meanRt: number; trials: number }[];
};

/**
 * Наклон по методу наименьших квадратов на оси log2(n).
 *
 * ⚠️ ВОЗВРАЩАЕТ null, А НЕ НОЛЬ, когда точек мало. Ноль означал бы «перебор
 * бесплатен» — сильное клиническое утверждение; отсутствие данных должно
 * выглядеть как отсутствие, иначе пустая партия читается как идеальная.
 * Тот же принцип, что у `ssrt_ms` в стоп-сигнале и `vigilanceAccuracySlope`.
 */
export function наклонХика(точки: ТочкаХика[]): НаклонХика {
  const годные = точки.filter((т) => Number.isFinite(т.rt) && т.rt > 0 && т.n >= 2);
  const поN = new Map<number, number[]>();
  for (const т of годные) {
    const было = поN.get(т.n);
    if (было) было.push(т.rt); else поN.set(т.n, [т.rt]);
  }
  const byN = [...поN.entries()]
    .map(([n, rts]) => ({ n, meanRt: Math.round(rts.reduce((a, b) => a + b, 0) / rts.length), trials: rts.length }))
    .sort((a, b) => a.n - b.n);

  if (byN.length < 2) {
    return { slopeMsPerBit: null, interceptMs: null, distinctN: byN.length, trials: годные.length, byN };
  }
  /* Регрессия по СРЕДНИМ, а не по всем пробам: иначе n с большим числом проб
     перетянет прямую на себя просто количеством. */
  const xs = byN.map((т) => Math.log2(т.n));
  const ys = byN.map((т) => т.meanRt);
  const сx = xs.reduce((a, b) => a + b, 0) / xs.length;
  const сy = ys.reduce((a, b) => a + b, 0) / ys.length;
  let верх = 0, низ = 0;
  for (let i = 0; i < xs.length; i++) { верх += (xs[i]! - сx) * (ys[i]! - сy); низ += (xs[i]! - сx) ** 2; }
  if (низ === 0) return { slopeMsPerBit: null, interceptMs: null, distinctN: byN.length, trials: годные.length, byN };
  const b = верх / низ;
  return {
    slopeMsPerBit: Math.round(b),
    interceptMs: Math.round(сy - b * сx),
    distinctN: byN.length,
    trials: годные.length,
    byN,
  };
}


/**
 * Блоки уровня: какие наборы направлений сменяют друг друга ВНУТРИ партии.
 *
 * ⚠️ Порядок фиксированный и идёт от меньшего к большему: так человек входит в
 * задание на самом простом наборе. Перемешивать блоки нельзя — при случайном
 * порядке наклон поедет от обучения по ходу партии, а не от числа вариантов.
 */
export const БЛОКИ_ХИКА: Record<'малый' | 'средний' | 'полный', number[]> = {
  малый: [2, 3],
  средний: [2, 3, 4],
  полный: [2, 3, 4],
};
