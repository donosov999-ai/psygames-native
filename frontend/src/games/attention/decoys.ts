/**
 * ПОМЕХИ ВОКРУГ СТИМУЛА — ОДИН НАБОР НА ВЕСЬ РАЗДЕЛ.
 *
 * 🔴 ЗАЧЕМ ОБЩИЙ МОДУЛЬ, А НЕ ПО КОПИИ В КАЖДОЙ ИГРЕ. Вся ценность этой оси
 * держится на ОДНОМ условии: помеха не должна быть буквой или цифрой. Стоит
 * одной игре завести свой список и добавить туда `B` или `7` — и помеха начнёт
 * «афишировать» одну из задач: у переключения задач это цифра или буква, по
 * которым и судят, у Струпа — буква, из которых складывается слово. Проба
 * перестанет быть перцептивной и станет смысловой, а мера прохода поедет.
 * Условие, живущее в одном месте, стережётся одной пробой; разошедшиеся копии
 * не стережёт ничто — в этом разделе уже было семь копий одного стиля полосы
 * ответа, и они разъехались в одном поле.
 *
 * ⚠️ ПОЧЕМУ ЭТА ОСЬ ВООБЩЕ ГОДИТСЯ. У обеих игр мера прохода — РАЗНОСТЬ
 * (switch_cost_ms, interference_ms). Ось, действующая на две половины разности
 * по-разному, попадает прямо в неё и портит. Помехи — свойство САМОГО СТИМУЛА,
 * а не перехода и не конгруэнтности: удлиняют обе половины одинаково и из
 * разности сокращаются. Ровно поэтому отвергнуты очевидные оси вроде интервала
 * подготовки (разбор в шапке switching-task.tsx).
 *
 * 📌 Валюта не выдумана: «плотность помех» уже ось у мишеней (`numSquares`) и у
 * фланкера (`gapPx`) в этом же разделе.
 */

/** Знаки-помехи: ни один не буква и не цифра ни в одной из письменностей игры. */
export const DECOY_GLYPHS = ['#', '§', '%', '&', '@', '¤', '¶', '='];

/**
 * Предел по бокам. Коробка стимула раздела 360 px, ядро ~120 px, знак ~40 px:
 * больше четырёх не влезает, а ужимать ядро нельзя — мерили бы остроту зрения.
 */
export const DECOYS_MAX = 4;

/**
 * Помехи для ОДНОЙ пробы.
 *
 * ⚠️ Зовётся при рождении пробы, а не в отрисовке: иначе знаки менялись бы на
 * каждом кадре, мельтешение читалось бы как движение и добавляло к пробе совсем
 * другую нагрузку.
 */
export function makeDecoys(n: number, rnd: () => number = Math.random): string[] {
  const сколько = Math.max(0, Math.min(DECOYS_MAX, Math.floor(n)));
  return Array.from({ length: сколько },
    () => DECOY_GLYPHS[Math.floor(rnd() * DECOY_GLYPHS.length)]);
}
