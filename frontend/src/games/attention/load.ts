/**
 * СТРУП — «теснота окна × переключение правила».
 *
 * Доля конфликтных ЗАМОРОЖЕНА каноном 50/50 (`INCONGRUENT_RATIO`) и ручкой сложности
 * быть не может: величину измеряемого эффекта задаёт сама доля. Поэтому трудность
 * растёт двумя другими путями — окном ответа и долей проб, идущих по ДРУГОМУ правилу
 * (называть слово вместо цвета). Вторая ось канонная (Stroop task switching) и не
 * трогает пропорцию конфликта.
 * Валюта: во сколько раз тесней первого уровня по обоим путям сразу.
 */
export function stroopLoad(level: number): number {
  const p = stroopParams(level);
  const base = stroopParams(1).windowMs;
  // Вторая ось — доля проб с ДРУГИМ правилом (переключение). До L4 её нет, поэтому
  // множитель начинается с 1 и растёт: (1 + доля), а не сама доля — иначе нижние
  // уровни обнулили бы нагрузку целиком.
  // 🔴 10.09.2026 четвёртый множитель — помехи вокруг слова. Ось сходства
  // цветов отвергнута замером: запаса различимости для дальтоников нет
  // (ΔE 8,2 под протанопией ДО всякого сближения). Разбор — в stroop.tsx.
  return ((base / p.windowMs) * (1 + p.switchRate)) * (1 + p.decoys / 4);
}

/**
 * ФЛАНКЕР — «цена помехи»: насколько тесно фланги стоят к цели и как мало времени
 * на подавление.
 *
 * 🔴 РАНЬШЕ ЗДЕСЬ БЫЛА ДОЛЯ КОНФЛИКТНЫХ, И ЭТО БЫЛ ДЕФЕКТ, А НЕ ФОРМУЛА.
 * Уровень рос долей (0,30 → 0,65), а proportion-congruent effect говорит: чем
 * больше доля конфликтных, тем МЕНЬШЕ измеряемый эффект. Ручка, которой рос
 * уровень, уменьшала величину, ради которой проба существует. Доли заморожены
 * (flanker.tsx), сложность переехала на канонную ось Эриксена — разнос
 * «цель ↔ фланги», где интерференция падает с ростом расстояния, то есть
 * трудность растёт при СБЛИЖЕНИИ. Разбор и числа — PROJECT_REF §0 ДЕФЕКТ 1 и §3.
 *
 * Валюта: во сколько раз теснее, чем на первом уровне, — по разносу и по окну.
 */
export function flankerLoad(level: number): number {
  const p = flankerParams(level);
  const base = flankerParams(1);
  // 🔴 10.09.2026 третий множитель — объём. Разбор, почему именно он и почему
  // не более сильная ось, — в шапке levelParams в flanker.tsx.
  return ((base.gapPx / p.gapPx) * (base.windowMs / p.windowMs)) * (p.trials / base.trials);
}

/**
 * Сколько СОГЛАСОВАННЫХ проб даёт уровень. Из них считается `mean_rt_congruent` —
 * половина разности `flanker_effect_ms`. Мало проб → среднее по горстке, и
 * показатель превращается в шум. Тот же довод записан у Струпа (stroop.tsx:120-126).
 */
export function flankerCongruentTrials(level: number): number {
  const p = flankerParams(level);
  return Math.round(p.trials * p.pCong);
}

/**
 * CPT — «темп × нагрузка на контекст × составность правила».
 *
 * Множители, и ни один не про секунды: скорость подачи (ISI), переход X → AX
 * (появляется удержание контекста в рабочей памяти), доля букв-двойников
 * (перцептивная нагрузка) и — с 10.09.2026 — само ПРАВИЛО.
 *
 * 🔴 Две оси добавлены по слову Дениса, и обе доли целей не трогают:
 *   мишень не X — приходится держать правило ЭТОЙ партии поверх привычки;
 *   мишень определённого ЦВЕТА — правило становится составным (буква И цвет).
 *
 * ⚠️ Честно про числа. У перехода X → AX множитель 1,5 стоял и раньше — он тоже
 * порядковый, не выведенный. Новые два (1,15 и 1,4) такие же: порядок
 * достоверен (непривычная мишень труднее привычной, составное правило труднее
 * простого), величина шага — заглушка.
 * 📌 Чем её заменить: партия пишет `target` и `colorRule` в условие рядом с
 * `commission_errors` и `rt_variability`. Накопится — берём отношение
 * показателей при ОДИНАКОВЫХ ISI и доле двойников, и оно встаёт сюда.
 */
export function cptLoad(level: number): number {
  const p = cptParams(level);
  const base = cptParams(1).isiMs;
  const contextLoad = p.mode === 'AX' ? 1.5 : 1;
  const unfamiliarTarget = p.target === 'X' ? 1 : 1.15;
  const conjunctionRule = p.colorRule ? 1.4 : 1;
  return (base / p.isiMs) * contextLoad * (1 + p.confusableRatio)
       * unfamiliarTarget * conjunctionRule;
}

/**
 * МИШЕНИ — «плотность помех».
 *
 * Ровно та величина, которую Денис назвал для этой пробы: сколько отвлекающих
 * квадратов приходится на решение и за какой срок его надо принять.
 */
export function targetsLoad(level: number): number {
  const p = targetsParams(level);
  const base = targetsParams(1).delay;
  // 🔴 10.09.2026 третий множитель — разброс фигур. Ось сходства цветов
  // отвергнута замером: вся задача это сравнение цветов, а запаса
  // различимости для дальтоников нет. Разбор — в targets.tsx.
  return (p.numSquares * (base / p.delay)) * (1 + p.jitterPx / 26);
}

/**
 * WCST — «частота смены правила».
 *
 * Величина прохода — сколько ходов уходит на перехват нового правила; спрос на неё
 * со стороны уровня — как часто правило меняется, то есть сколько раз за партию
 * человеку придётся этот перехват совершить.
 *
 * ⚠️ ОТСТУПЛЕНИЕ ОТ КАНОНА, ЧИСЛОМ. Канон WCST — смена после 10 подряд верных
 * (Heaton et al. 1993). У нас 9 на L1 и 3 на L12 (wcst.tsx:114), то есть ниже
 * канона на ВСЕХ уровнях, а на верхнем — втрое. При серии в 3 «перехватил правило»
 * и «трижды угадал» перестают различаться.
 */
/**
 * 🔴 10.09.2026 добавлена ТРЕТЬЯ ОСЬ — доля разводящих карт.
 *
 * Формула считала только частоту смен, а частота смен и объём давали одинаковые
 * параметры на пяти переходах из одиннадцати: L2=L1, L4=L3, L6=L5, L8=L7,
 * L10=L9. Мера уровня показывала ровное место там, где человек проходил ступень.
 *
 * Доля входит отношением к первому уровню, как и остальные оси файла. Что она
 * растит спрос именно на `rule_catch_mean`, а не сжимает его, проверено
 * симуляцией двух моделей игрока (разбор и числа — в шапке `levelCondition`
 * в `app/games/wcst.tsx`).
 */
export function wcstLoad(level: number): number {
  const p = wcstParams(level);
  const base = wcstParams(1);
  return (p.trials / p.ruleChangeStreak) * (p.discriminatingShare / base.discriminatingShare);
}

/** Мера уровня для любой из пяти. Складывать между пробами НЕЛЬЗЯ — валюты разные. */
/**
 * ЭМОЦИОНАЛЬНЫЙ СТРУП — «теснота окна × теснота паузы».
 *
 * Мера прохода — разность RT относительно нейтральных слов. Доли валентностей
 * заморожены равными и ручкой быть не могут (тот же довод, что у обычного
 * Струпа). Остаются две оси, и обе НЕ входят в формулу разности: сколько времени
 * дано на ответ и сколько на восстановление между пробами.
 * Валюта: во сколько раз тесней первого уровня по обоим путям сразу.
 */
export function emotionalStroopLoad(level: number): number {
  const p = emoParams(level);
  const base = emoParams(1);
  return (base.answerWindowMs / p.answerWindowMs) * (base.isiBaseMs / p.isiBaseMs);
}

/**
 * САЙМОН — «теснота окна × нехватка подготовки».
 *
 * Мера прохода — разность RT между несовпадающими и совпадающими пробами; доля
 * заморожена. Трудность растёт окном ответа и сокращением паузы ДО стимула:
 * меньше паузы — меньше времени собраться, но сам конфликт положения и значения
 * от этого не слабеет.
 * ⚠️ Дрожание паузы (`preJitterMs`) здесь СОКРАЩАЕТСЯ 600 → 200, то есть момент
 * становится предсказуемее. В валюту не берём: это ось в лёгкую сторону, и
 * складывать её с двумя тесными значило бы прятать облегчение внутри роста.
 */
export function simonLoad(level: number): number {
  const p = simonParams(level);
  const base = simonParams(1);
  return (base.windowMs / p.windowMs) * (base.preMinMs / p.preMinMs);
}

/**
 * ВЫБОР РЕАКЦИИ — «битов выбора на единицу времени».
 *
 * Единственная проба раздела, у которой валюта берётся прямо из закона: Хик
 * говорит RT = a + b·log₂(n), то есть трудность выбора меряется БИТАМИ, а не
 * числом кнопок. Две альтернативы — один бит, четыре — два.
 * Валюта: во сколько раз больше битов надо разрешить и во сколько раз меньше на
 * это дано времени.
 * 🔴 У пробы нет клинического показателя, и наклон Хика по ней посчитать нельзя
 * (число альтернатив постоянно внутри партии) — открытый вопрос, PROJECT_REF §10.
 */
/**
 * 🔴 10.09.2026 добавлена третья ось — НАЧЕРТАНИЕ ЗНАКА.
 *
 * Было две: число альтернатив (закон Хика) и окно ответа. Обе упирались —
 * альтернатив больше четырёх в полосу ответа не влезает.
 *
 * ⚠️ ЧЕСТНО ПРО ЧИСЛА. У числа альтернатив есть канон — биты Хика, log₂(n), и
 * они здесь и стоят. У начертания канонного числа НЕТ: что скобку читать
 * труднее стрелки — очевидно, а НАСКОЛЬКО труднее — не измерено.
 * Поэтому множители ниже ПОРЯДКОВЫЕ: порядок (стрелка < шеврон < скобка)
 * достоверен, шаг между ними — заглушка.
 *
 * 📌 Как заглушка будет заменена замером: с 10.09 каждая партия пишет в
 * `details` своё условие (`levelCondition`, поле `glyph`) рядом с `mean_rt`.
 * Накопится — берём медианный RT по каждому начертанию при ОДИНАКОВЫХ окне и
 * числе альтернатив, и отношение этих медиан встаёт сюда вместо 1,2 и 1,4.
 */
const GLYPH_LOAD: Record<string, number> = { arrow: 1, chevron: 1.2, bracket: 1.4 };

export function choiceRtLoad(level: number): number {
  const p = choiceParams(level);
  const base = choiceParams(1);
  return (Math.log2(p.dirs.length) / Math.log2(base.dirs.length))
       * (base.windowMs / p.windowMs)
       * (GLYPH_LOAD[p.glyph] / GLYPH_LOAD[base.glyph]);
}

/**
 * ANT — «теснота окна × непредсказуемость момента».
 *
 * ⚠️ ЗДЕСЬ ОТНОШЕНИЕ ПЕРЕВЁРНУТО ОТНОСИТЕЛЬНО ОСТАЛЬНЫХ, и это не описка.
 * У всех прочих проб величина СОКРАЩАЕТСЯ с уровнем (окно, пауза), поэтому в
 * числителе стоит база. У ANT разбросы РАСТУТ: пред-пауза 400 → 1520, CTOA
 * 100 → 660 — чем они больше, тем труднее предугадать момент появления цели.
 * Поэтому здесь числитель и знаменатель меняются местами.
 * Доли заморожены на каноне Fan 2002, ручкой быть не могут.
 */
export function antLoad(level: number): number {
  const p = antParams(level);
  const base = antParams(1);
  return (base.windowMs / p.windowMs)
       * ((p.preJitterMs + p.ctoaVarMs) / (base.preJitterMs + base.ctoaVarMs));
}

/**
 * ПЕРЕКЛЮЧЕНИЕ ЗАДАЧ — «теснота окна × объём удержания».
 *
 * Мера прохода — стоимость переключения (разность RT смена−повтор). Доля смен
 * заморожена на каноне 0,5 и ручкой быть не может. Остаются окно ответа и объём:
 * чем длиннее партия, тем дольше держать в голове два правила сразу.
 * 🚫 Интервал подготовки (cue-stimulus interval) сюда НЕ входит намеренно — он
 * прямо модулирует саму стоимость переключения; разбор в шапке switching-task.
 */
export function switchingLoad(level: number): number {
  const p = switchParams(level);
  const base = switchParams(1);
  // 🔴 10.09.2026 третий множитель — плотность помех вокруг стимула. Разбор,
  // почему именно она (а не интервал подготовки, не предсказуемость и не третья
  // задача), — в шапке DECOY_GLYPHS в switching-task.tsx.
  // ⚠️ Шаг порядковый, как у начертания у choice-rt: что четыре помехи мешают
  // сильнее двух — очевидно, НАСКОЛЬКО — не измерено. Заменяется отношением
  // медиан RT по записанному условию, когда партии накопятся.
  // Замер 10.09.2026 прогоном: L1 → L15 даёт ×8,1 (было ×4,0 на двух осях).
  return (base.windowMs / p.windowMs) * (p.trials / base.trials) * (1 + p.decoys / 4);
}

/**
 * Go/No-Go — «темп и объём».
 *
 * Величина прохода — ошибки торможения (нажатия на no-go). Ось у неё НЕ доля
 * no-go: доля заморожена, и её рост добавлял бы ошибок, не делая задачу труднее.
 * Труднее становится от того, что решение «не жать» приходится принимать быстрее
 * и чаще: окно ответа сжимается 1100 → 550 мс, пауза между пробами 600 → 280 мс,
 * а самих проб становится 24 → 40.
 *
 * ⚠️ Складывать это число с нагрузкой других проб нельзя: у каждой своя валюта.
 */
export function goNoGoLoad(level: number): number {
  const p = goNoGoParams(level);
  const б = goNoGoParams(1);
  return p.trials * (б.windowMs / p.windowMs) * (б.itiMinMs / p.itiMinMs);
}

/**
 * Стоп-сигнал — «темп и объём».
 *
 * Величина прохода — SSRT. Осью сложности он быть не может сам себе: SSRT
 * считается из доли стоп-проб, и рост доли сдвинул бы саму измеряемую величину.
 * Не может ею быть и задержка стоп-сигнала (SSD) — её ведёт сходящаяся лестница,
 * переживающая партию, а не номер уровня. Остаются темп и объём: окно ответа
 * 1400 → 700 мс, фиксация 700 → 350, разброс 700 → 280, пауза 600 → 320,
 * проб 12 → 20.
 *
 * ⚠️ Складывать с нагрузкой других проб нельзя: у каждой своя валюта.
 */
export function stopSignalLoad(level: number): number {
  const p = stopSignalParams(level);
  const б = stopSignalParams(1);
  return p.trials * (б.goWindowMs / p.goWindowMs) * (б.interTrialMs / p.interTrialMs);
}

/**
 * Торможение — «темп, задержка и объём».
 *
 * Доля стоп-проб осью НЕ является и заморожена (разбор в inhibition.tsx):
 * мера прохода — ошибки торможения, и рост доли добавлял бы их сам собой.
 * Растут три другие величины: окно ответа 1300 → 852 мс, задержка стоп-сигнала
 * 150 → 480 мс (позже сигнал — труднее отменить), проб 20 → 32.
 *
 * ⚠️ Складывать с нагрузкой других проб нельзя: у каждой своя валюта.
 */
export function inhibitionLoad(level: number): number {
  const p = inhibitionCondition(level);
  const б = inhibitionCondition(1);
  return p.trials * (б.goWindow / p.goWindow) * (p.ssd / б.ssd);
}

/**
 * Познер — «темп и непредсказуемость паузы».
 *
 * Величина прохода РАЗНОСТНАЯ (выигрыш от подсказки), поэтому доля валидных
 * подсказок заморожена и осью не служит. Растут две другие величины: окно
 * ответа 2200 → 900 мс и разброс паузы между подсказкой и мишенью — с 100 мс
 * (150…250) до 620 мс (80…700). Чем шире разброс, тем меньше можно подгадать
 * момент появления мишени.
 *
 * ⚠️ Складывать с нагрузкой других проб нельзя: у каждой своя валюта.
 */
export function posnerLoad(level: number): number {
  const p = posnerParams(level);
  const б = posnerParams(1);
  const разброс = (x: { soaMinMs: number; soaMaxMs: number }) => x.soaMaxMs - x.soaMinMs;
  return p.trials * (б.windowMs / p.windowMs) * (разброс(p) / разброс(б));
}

/**
 * Корректура — «объём поля и темп сканирования».
 *
 * Величина прохода — доля пропущенных целей, поэтому осью служит не число
 * целей, а сколько поля надо просмотреть и за какое время: сетка растёт
 * 8×8 → 16×12, а времени на клетку остаётся 1,00 → 0,45 с. Порог прохода тоже
 * поднимается: 80 % → 90 % → 100 % найденных.
 *
 * ⚠️ Складывать с нагрузкой других проб нельзя: у каждой своя валюта.
 */
export function proofreadingLoad(level: number): number {
  const p = proofParams(level);
  const б = proofParams(1);
  const клеток = (x: { rows: number; cols: number }) => x.rows * x.cols;
  const наКлетку = (x: { rows: number; cols: number; timeLimitSec: number }) => x.timeLimitSec / клеток(x);
  return (клеток(p) / клеток(б)) * (наКлетку(б) / наКлетку(p)) * (p.minFoundPct / б.minFoundPct);
}

export function attentionLoad(mode: AttentionMode, level: number): number {
  switch (mode) {
    case 'stroop':  return stroopLoad(level);
    case 'flanker': return flankerLoad(level);
    case 'cpt':     return cptLoad(level);
    case 'targets': return targetsLoad(level);
    case 'wcst':    return wcstLoad(level);
    case 'stroop-emotional': return emotionalStroopLoad(level);
    case 'simon':            return simonLoad(level);
    case 'choice-rt':        return choiceRtLoad(level);
    case 'ant':              return antLoad(level);
    case 'switching-task':   return switchingLoad(level);
    case 'go-no-go':         return goNoGoLoad(level);
    case 'stop-signal':      return stopSignalLoad(level);
    case 'inhibition':       return inhibitionLoad(level);
    case 'posner':           return posnerLoad(level);
    case 'proofreading':     return proofreadingLoad(level);
  }
}

