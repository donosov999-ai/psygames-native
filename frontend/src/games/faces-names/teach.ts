import type { FacesNamesPuzzle } from './core';

export interface КарточкаЛиц {
  вид: 'приём' | 'черта' | 'помеха' | 'узнавание' | 'имя' | 'готово';
  /** Ключ словаря: язык живёт в словаре, не в коде. */
  ключ: string;
  поля?: Record<string, string | number>;
  /** Кого показать на сцене (id) или `null` — сцена пуста. */
  человек: string | null;
}

export interface РазборЛиц {
  карточки: КарточкаЛиц[];
  /** Кого разбор показал по порядку: этих же людей игра и спросит. */
  люди: string[];
}

/**
 * ⚠️ РАЗБОР ПОКАЗЫВАЕТ НЕ БОЛЬШЕ ТРЁХ ЛИЦ. На первых уровнях их два-три, но лестница
 * доходит до двенадцати: полный разбор двенадцати лиц — это полторы минуты ролика, который
 * закроют на середине. Приём показывается на трёх, дальше человек применяет его сам.
 */
const ПОКАЗЫВАЕМ_ЛИЦ = 3;

export function собратьРазборЛиц(
  puzzle: FacesNamesPuzzle,
  описание: (personId: string) => string,
): РазборЛиц {
  const люди = puzzle.studiedPersonIds.slice(0, Math.min(ПОКАЗЫВАЕМ_ЛИЦ, puzzle.studiedPersonIds.length));
  const имя = (id: string) => puzzle.people.find((p) => p.id === id)?.name ?? id;
  const фактId = (id: string) => puzzle.people.find((p) => p.id === id)?.factId ?? '';

  const карточки: КарточкаЛиц[] = [{
    вид: 'приём',
    ключ: 'teachFacesIntro',
    поля: { n: puzzle.studiedPersonIds.length },
    человек: null,
  }];

  люди.forEach((id, i) => {
    карточки.push({
      вид: 'черта',
      ключ: i === 0 ? 'teachFacesFeatureFirst' : 'teachFacesFeature',
      поля: { name: имя(id), feature: описание(id), fact: фактId(id) },
      человек: id,
    });
  });

  карточки.push({
    вид: 'помеха',
    ключ: 'teachFacesInterference',
    поля: { n: puzzle.interferencePrompts.length },
    человек: null,
  });

  карточки.push({
    вид: 'узнавание',
    ключ: 'teachFacesRecognition',
    поля: { name: имя(люди[0]!), feature: описание(люди[0]!) },
    человек: люди[0]!,
  });

  карточки.push({
    вид: 'имя',
    ключ: puzzle.factRecallEnabled ? 'teachFacesNameAndFact' : 'teachFacesName',
    поля: { name: имя(люди[0]!), fact: фактId(люди[0]!) },
    человек: люди[0]!,
  });

  карточки.push({ вид: 'готово', ключ: 'teachFacesDone', человек: null });
  return { карточки, люди };
}
