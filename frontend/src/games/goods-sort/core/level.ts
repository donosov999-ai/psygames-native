/**
 * 🔴 МИНИ-КАРТА ЕДУЩЕЙ ВИТРИНЫ. Данные, а не рисование: экран лишь красит точки.
 *
 * 📍 ЗАЧЕМ ОНА, ДОСЛОВНО ИЗ ВОЗРАЖЕНИЯ §4а: «структура должна быть видна даром,
 * а содержание вспоминаться». На доске в один экран структура видна сама —
 * поэтому карта появляется ТОЛЬКО когда шкаф едет. Постоянная карта была бы
 * лишним элементом на восьмидесяти процентах уровней.
 *
 * ⚠️ Карта показывает не товары, а СОСТОЯНИЕ РЯДА: сколько ниш занято, сколько
 * пусто, есть ли препятствие. Показывать в ней сами товары бессмысленно — на
 * полоске в несколько пикселей их всё равно не различить, а вот «внизу три
 * пустые ниши» читается и решает, куда ехать.
 */
export interface MiniRow {
  /** Номер ряда, с нуля. */
  row: number;
  /** Ниш в ряду (без вырезов формы). */
  niches: number;
  /** Из них пустых — главное, что человек ищет на большой доске. */
  empty: number;
  /** Из них с препятствием: закрытая или запертая по ходам. */
  blocked: number;
  /**
   * Ряд примёрз целиком.
   *
   * ⚠️ Отдельным полем, а не через `blocked`: примерзание в этой игре — свойство
   * РЯДА (`frozen: { row, type }`), а не ниши, и `Obstacle` про него ничего не
   * знает. Первая редакция спросила у ниши `kind === 'frozen'` — типов такого
   * нет, и `tsc` это поймал сразу. Своя сущность требует своего поля.
   */
  frozen: boolean;
  /** Ряд заполнен доверху — там ходов почти нет. */
  full: number;
}

/**
 * Свод по рядам для мини-карты.
 *
 * ⚠️ Ниши считаются ПО МАСКЕ, а не по числу столбцов: у формы бывают вырезы, и
 * ряд из трёх клеток может нести одну нишу. Считать по `cols` значит рисовать
 * карту доски, которой нет.
 */
export function miniMap(
  cells: readonly (readonly number[])[],
  caps: readonly number[],
  mask: readonly boolean[],
  cols: number,
  obstacles: readonly (Obstacle | null)[] = [],
  frozenRow: { row: number; type: number } | null = null,
): MiniRow[] {
  const rows = Math.ceil(mask.length / cols);
  const out: MiniRow[] = [];
  let idx = 0;
  const начало: number[] = [];
  for (let p = 0; p < mask.length; p += 1) { начало.push(idx); if (mask[p]) idx += 1; }
  for (let r = 0; r < rows; r += 1) {
    let niches = 0, empty = 0, blocked = 0, full = 0;
    for (let c = 0; c < cols; c += 1) {
      const p = r * cols + c;
      if (p >= mask.length || !mask[p]) continue;
      const i = начало[p] as number;
      niches += 1;
      const ячейка = cells[i] ?? [];
      if (ячейка.length === 0) empty += 1;
      if (ячейка.length >= (caps[i] ?? 3)) full += 1;
      const o = obstacles[i];
      if (o && (o.kind === 'blocked' || o.kind === 'locked')) blocked += 1;
    }
    out.push({ row: r, niches, empty, blocked, full, frozen: frozenRow?.row === r });
  }
  return out;
}

export const NARROW_WIDTH = 560;

/** Узкий ли экран: на нём сетка ограничена тремя колонками. */
export function isNarrow(width: number): boolean {
  return width < NARROW_WIDTH;
}

export function gridFor(L: number, narrow = false): { cols: number; rows: number } {
  // ⚠️ На телефоне ряды идут ВМЕСТО колонок: вниз экран тянется, вбок нет.
  // Так шкаф заполняет поле при правильной пропорции ниши, а не растянутыми
  // коробками. У эталона стартовая доска тоже высокая — 3 колонки на 5 рядов.
  if (L <= 7) return narrow ? { cols: 3, rows: 4 } : { cols: 3, rows: 3 };
  if (L <= 11) return narrow ? { cols: 3, rows: 5 } : { cols: 4, rows: 3 };
  if (L < SCROLL_FROM) return narrow ? { cols: 3, rows: 6 } : { cols: 4, rows: 4 };
  /**
   * 🔴 ВИТРИНА НА ДВА-ТРИ ЭКРАНА (§4.4 ТЗ). Ряды растут, КОЛОНКИ НЕТ.
   *
   * Вбок экран не ездит — это правило игры, а не вкус: вертикально телефон
   * тянется, горизонтально нет. Поэтому витрина растёт единственным доступным
   * способом, а товар при этом НЕ ужимается: за размер отвечает `ITEM_FLOOR`,
   * и шкаф просто перестаёт влезать в поле, о чём `gsLayout` говорит вслух.
   *
   * Шаг по два ряда каждые пять уровней, потолок 10 (телефон) и 8 (широкий):
   * при 10 рядах и поле в 484 px шкаф выходит около двух с половиной экранов —
   * это и есть «два-три экрана» из ТЗ, посчитанные, а не названные на глаз.
   */
  /**
   * ⚠️ СТРОГИЙ УРОВЕНЬ НЕ ЕДЕТ — у него доска ОСТАЁТСЯ короткой.
   *
   * Это не исключение ради удобства, а тот же канон, что и в `targetSlots`:
   * «класть только к такому же» тяжелее любой прибавки ниш, поэтому трудный
   * уровень делается меньше, а не больше (Royal Match: «меньше сущностей, но
   * глубже»). Заодно снимается вопрос, который иначе пришлось бы решать: как
   * совместить цель в 12 ниш с формой на 3×10, где меньше 24 не бывает.
   */
  if (strictPlacement(L)) return narrow ? { cols: 3, rows: 6 } : { cols: 4, rows: 4 };
  const ступень = Math.min(2, Math.floor((L - SCROLL_FROM) / 5));
  return narrow
    ? { cols: 3, rows: Math.min(10, 6 + 2 * (1 + ступень)) }
    : { cols: 4, rows: Math.min(8, 4 + 2 * (1 + ступень)) };
}

