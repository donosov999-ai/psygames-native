export const WARM_FAMILY: number[] = [4, 6, 9, 10, 14, 16, 17, 18, 33, 34, 36, 37, 39, 40];

export function monochromeLevel(L: number): boolean {
  if (L < MONO_FROM || (L - MONO_FROM) % 4 !== 0) return false;
  return !strictPlacement(L) && !hiddenInfo(L) && !movingNiches(L);
}

/**
 * Пул видов для уровня. На одноцветном подменяется тёплой семьёй, на остальных
 * остаётся набором игрока.
 *
 * ⚠️ РАЗДАЧУ РЕЖИМ НЕ МЕНЯЕТ — только пул. Тот же принцип, что у скрытой
 * информации: «доска обязана оставаться той же, меняется только видимость».
 * Тогда цену режима можно померить разностью на сопоставимых досках.
 */
export function poolForLevel(L: number, base: number[]): number[] {
  return monochromeLevel(L) ? WARM_FAMILY : base;
}

export function movingNiches(L: number): boolean {
  if (L < MOVING_FROM || (L - MOVING_FROM) % 3 !== 0) return false;
  if (obstaclePlan(L).frozenRow) return false;
  /**
   * ⚠️ И НЕ НА ЦЕЛИ «ОСВОБОДИТЬ НИШИ». Она помечает КОНКРЕТНЫЕ ниши номерами
   * (`Goal.niches`), а сдвиг возит содержимое между номерами — цель поехала бы
   * вместе с доской, и «опустошить помеченные» перестало бы что-либо значить.
   * Тот же приём, которым `hiddenInfo` отводит цель «уложиться в ходы».
   */
  return goalPlan(L).kind !== 'free';
}

/**
 * Перестановка ниш на шаге `step`: `perm[i]` — куда переезжает содержимое ниши
 * `i`. Внутри каждой группы одинаковой ёмкости — поворот, поэтому неподвижных
 * точек в группе нет вовсе, а группа из одной ниши остаётся на месте (менять её
 * не с кем).
 *
 * Шаг поворота зависит от `step`, иначе второй сдвиг вернул бы доску в прежний
 * вид при группе из двух — и механика гасила бы сама себя через ход.
 */
export function nicheShift(caps: readonly number[], step: number): number[] {
  const perm = caps.map((_, i) => i);
  const группы = new Map<number, number[]>();
  caps.forEach((c, i) => {
    const g = группы.get(c);
    if (g) g.push(i); else группы.set(c, [i]);
  });
  for (const места of группы.values()) {
    const n = места.length;
    if (n < 2) continue;
    const сдвиг = 1 + (step % (n - 1));
    for (let k = 0; k < n; k += 1) {
      perm[места[k] as number] = места[(k + сдвиг) % n] as number;
    }
  }
  return perm;
}

/**
 * С какого уровня приходит скрытая информация. Шестнадцатый — между строгой
 * укладкой (14) и смешанной ёмкостью (18): верх лесенки и так вводит по новой
 * механике раз в два уровня, режим встаёт в свой свободный такт.
 */
/**
 * 🔴 ЯВНАЯ СВЯЗЬ «ПОРОГ МЕХАНИКИ → ПРАВИЛО». Данные, а не совпадение чисел.
 *
 * 📍 Заведено 06.09.2026 после того, как я выпустил витрину БЕЗ правила и все
 * пробы остались зелёными. Первая редакция проверки сверяла порог с правилом
 * ПО УРОВНЮ — и тут же соврала: `SINGLE_CAP_FROM = 26`, а на 26-м стоит правило
 * «примёрзший ряд», механика совсем другая. Совпало число, а не смысл.
 *
 * `null` означает ДОЛГ, а не норму: механика видимая, правила нет, причина
 * названа в гейте `goods-sort-rule-for-every-threshold`.
 */
export const THRESHOLD_RULES: Record<string, string | null> = {
  MIXED_CAP_FROM: null,     // ниши разной вместимости с L18 — долг
  SINGLE_CAP_FROM: null,    // ниша ровно на один товар с L26 — долг, уровень занят «примёрзшим рядом»
  HIDDEN_FROM: 'hidden',
  JOKER_FROM: 'joker',
  MONO_FROM: 'mono',
  MOVING_FROM: 'moving',
  SCROLL_FROM: 'showcase',
};

export const HIDDEN_FROM = 34;

/**
 * Идёт ли на уровне режим скрытой информации. Включение — по уровню, как у
 * всех усложнений этой игры (образец — strictPlacement): никаких переключателей
 * в настройке, механика приходит сама на верхних уровнях.
 *
 * 🔴 РИТМ «ЧЕРЕЗ ДВА НА ТРЕТИЙ» СО СДВИГОМ +2 ОТ СТРОГОЙ УКЛАДКИ — это не
 * вкус, а арифметика: (L−14)%3=0 и (L−16)%3=0 несовместимы, режимы НИКОГДА не
 * совпадают. Стек двух режимов был бы кашей (та же причина, по которой
 * препятствий нет до L6), а тупики строгой укладки вслепую — не сложность,
 * а лотерея: тупик там надо ВИДЕТЬ за два-три хода, скрытость это отменяет.
 *
 * 🔴 ЦЕЛЬ «УЛОЖИСЬ В ХОДЫ» ИСКЛЮЧЕНА (§20.4): лимит ходов — это минимум,
 * объявленный целью, а минимума при неполной информации не существует.
 * Первый реальный отвод — L25: кандидат ритма, но цель moves. Проверка
 * исполняется, а не украшает (мутация «убери отвод» краснит гейт на L25).
 *
 * Правило уровня заведено 02.09.2026 (LevelRule key 'hidden'), тексты — в словаре
 * на двенадцати языках (`lr_goods_sort_hidden_*`). До этого механика шла молча:
 * с шестнадцатого уровня часть товара пряталась под «?», а объяснения не было ни
 * одного — игрок узнавал о ней, натыкаясь.
 */
export function hiddenInfo(L: number): boolean {
  if (L < HIDDEN_FROM || (L - HIDDEN_FROM) % 3 !== 0) return false;
  return goalPlan(L).kind !== 'moves';
}

/**
 * 🔴 РАСКЛАДКА ШКАФА — ОДНА ФОРМУЛА НА ИГРУ И НА ГЕЙТ.
 *
 * До 02.09.2026 арифметика жила в теле компонента, а гейт `goods-sort-fit`
 * ПОВТОРЯЛ её у себя. Формулы разъехались молча: у гейта осталось `width - 24`,
 * потолок товара 112 и рама 7, у игры уже были `width - 20`, потолок 148 и
 * рама 9. Тест при этом зеленел — он честно проверял формулу, которой в игре
 * нет. Ровно так же незаметно разъезжается любая величина, продублированная
 * «для проверки».
 *
 * Теперь считает одна функция, а гейт зовёт ЕЁ. Разойтись стало нечему.
 *
 * ЧТО ЧЕМ ОГРАНИЧЕНО:
 * · товар — шириной (`capWide` штук в ряд) И высотой (rows рядов на экран);
 * · ниша — высотой товара снизу и доступной высотой сверху;
 * · шкаф — суммой рядов; лишняя высота уходит ВНУТРЬ ниш, а не остаётся
 *   воздухом вокруг (замер 02.09: было 414 из 629 доступных).
 */
export interface GsLayout {
  boardW: number; cellW: number; itemSize: number; itemH: number;
  /** Размер товара для ниши такой вместимости (см. `itemBox` в `gsLayout`). */
  itemBox: (cap: number) => { w: number; h: number };
  nicheH: number; shelfH: number;
  /** Доля перекрытия соседних товаров в нише: 0 — встык, 0,3 — как на полке. */
  overlap: number;
  /**
   * Сколько занимает полный ряд товаров ВНУТРИ ниши, с учётом нахлёста.
   * Считается здесь, а не у вызывающего: гейт вписывания однажды уже проверял
   * собственную копию формулы вместо игры (см. `goods-sort-fit`).
   */
  rowW: number;
  /**
   * Высота шкафа и то, перерастает ли он поле. `scrolls` — не украшение: экран
   * по нему решает, оборачивать ли доску в прокрутку, а гейт — проверять, что
   * товар при этом не ужался ниже пола.
   */
  boardH: number;
  scrolls: boolean;
}

export function gsLayout(
  width: number, availH: number, cols: number, rows: number, capWide = 3, hintH?: number,
  /**
   * 🔴 ПОЛ ЧИТАЕМОСТИ ТОВАРА — ПАРАМЕТР, А НЕ ЗАШИТАЯ КОНСТАНТА. По умолчанию
   * нуль, то есть прежнее поведение.
   *
   * 📍 ЗАМЕР 06.09.2026, объясняющий, почему параметр. Первая редакция включила
   * пол ВСЕГДА — и уровни 12…45 на Android 360 поехали: шкаф 420 при поле 396.
   * Двадцать четыре пикселя переполнения ради товара 27 → 30. Полоса прокрутки
   * на всю игру за три пикселя — плохой размен.
   * ⚠️ Хуже был случай 320 px: там товар упирается в ШИРИНУ ячейки и остаётся 26
   * при любом поле, то есть доска ехала бы, ничего не выигрывая.
   *
   * Поэтому пол включается только там, где доска и так задумана едущей —
   * с `SCROLL_FROM`. Прежние сорок пять уровней остаются какими были, а
   * «27 px на Android 360» — отдельная давняя беда, и чинить её надо отдельно,
   * а не прицепом к витрине.
   */
  floorItem = 0,
): GsLayout {
  const CELL_GAP = 2;         // зазор между товарами внутри ниши (styles.cellRow)
  const ITEM_ASPECT = 0.6;    // ширина/высота, снято с самих спрайтов
  /**
   * 🔴 ВЫСОТА СТРОКИ ЦЕЛИ — ИЗМЕРЕННАЯ, А НЕ ЗАШИТАЯ.
   *
   * 📍 ОТЧЁТ ВАЛИ 05.09.2026 со скриншотом: «кошмар просто кошмар» — нижний ряд
   * полок под обрез. Высоту поля игра честно МЕРЯЕТ (`fieldH`, onLayout), но
   * мерит она весь столбец ВМЕСТЕ со строкой цели, а вычитала из него
   * постоянные 44 px. Строка цели постоянной не бывает: у цели «собрать тройки»
   * рядом стоят значки товаров 16×26, `goalLine` умеет переноситься
   * (`flexWrap`), а в русском текст длиннее английского — две строки вместо
   * одной, и всё, что не поместилось, уезжает под нижний край.
   *
   * Это тот же класс, что и прежний `height - 360`: константа на месте замера.
   * Тогда померили поле и оставили константу на подсказку — беда переехала на
   * шаг ниже и подождала, пока цель станет длиннее.
   *
   * 44 остаётся оценкой ПЕРВОГО кадра, пока onLayout ещё не сработал.
   */
  const SHELF_GAP = 9, HINT_H = Math.max(0, Math.round(hintH ?? 44)), SHELF_PAD = 9;

  const boardW = Math.min(width - 20, 1200);
  const cellW = Math.floor((boardW - SHELF_PAD * 2 - SHELF_GAP * (cols - 1)) / cols);

  /**
   * 🔴 ВЫСОТА ОДНОЙ НИШИ ВЫВОДИТСЯ ИЗ ПОЛЯ, А НЕ ИЗ ТОВАРА.
   *
   * Прежний расчёт шёл наоборот: сначала товар по «availH / rows − 14», потом
   * ниша не меньше «товар + 8». Обе величины по отдельности выглядели разумно,
   * а вместе давали шкаф ВЫШЕ ПОЛЯ: замер гейта на десктопе 1280×800 — короб
   * 465 при поле 440, то есть нижний ряд под обрез. Ровно на этот обрез и был
   * репорт «половина банок обрезана» (18.08.2026); тогда починили ширину, а
   * высота осталась с той же болезнью и просто ждала своего экрана.
   *
   * Теперь порядок обратный и замкнутый: сколько высоты у ниши — столько и
   * товару, а не наоборот. Шкаф не может перерасти поле по построению.
   */
  const свободно = availH - HINT_H - SHELF_GAP * (rows - 1) - SHELF_PAD * 2 - 9;
  /**
   * 🔴 РЯД НЕ УЖИМАЕТСЯ НИЖЕ ЧИТАЕМОГО — ТАМ, ГДЕ ПОЛ ЗАДАН. Раньше высота ряда
   * делилась поровну всегда, и при десяти рядах товар доходил до 18 px.
   * Не влезло — шкаф становится выше поля и едет, а не мельчает.
   */
  const perRow = Math.floor(свободно / rows);   // пол применяется ниже, после расчёта ячейки
  /**
   * 🔴 ТОВАРЫ СТОЯТ ВНАХЛЁСТ, КАК НА НАСТОЯЩЕЙ ПОЛКЕ.
   *
   * Замер 02.09.2026 на iPhone Pro Max (430 px): ниша 124 px, три товара встык
   * по 40 px. Товар был ограничен НЕ высотой и не спрайтом (непрозрачная часть
   * занимает 96–98 % картинки — проверено), а простой арифметикой «три в ряд».
   * Отсюда репорт Вали «ужасно товары мелкие»: на телефоне иначе и не выходило.
   *
   * У эталона жанра предметы на полке перекрываются — потому и крупные. Товар в
   * магазине и стоит внахлёст: заднее видно из-за переднего, а не рядом с ним.
   *
   * Арифметика: ряд занимает `item × (1 + (n − 1) × (1 − OVERLAP))`, значит при
   * трёх штуках и нахлёсте 0,3 делитель 2,4 вместо 3 — товар крупнее на четверть
   * ЛИНЕЙНО и в полтора раза по площади, при той же нише.
   *
   * ⚠️ ПОЧЕМУ 0,3, А НЕ БОЛЬШЕ. Перекрытое надо УЗНАВАТЬ: у молочных бутылок
   * разница в этикетке (§7.3), и накрыв половину, мы вернули бы дефект «шесть
   * одинаковых силуэтов». Треть скрывает бок и оставляет и верх, и этикетку.
   * ⚠️ И перекрытый товар остаётся НАЖИМАЕМЫМ: видимая доля 0,7 × item всё равно
   * шире, чем товар был до нахлёста (0,7 × 50 = 35 против 40 — почти столько же),
   * а передний виден целиком. Это сторожит `tap-target-audit`.
   */
  const OVERLAP = 0.3;
  const рядДелитель = 1 + (capWide - 1) * (1 - OVERLAP);
  const fitsInCell = Math.floor((cellW - CELL_GAP * (capWide - 1)) / рядДелитель);
  const fitsInRow = Math.floor((perRow - 8) * ITEM_ASPECT);
  /**
   * 🔴 ПОЛ ДЕРЖИТ ВЫСОТУ РЯДА, А ШИРИНА ЯЧЕЙКИ ОСТАЁТСЯ ЖЁСТКИМ ПОТОЛКОМ.
   *
   * 📍 Первая редакция ставила пол снаружи всего минимума — и товар на 320 px
   * при четырёх колонках стал 30 px при ячейке, где помещается 21: ряд из трёх
   * вылез за нишу (76 против 63). Ширину нарушать нельзя ничем: она физическая,
   * товар просто не влезет. А вот высоту ряда ужимать НЕ НАДО — вместо этого
   * растёт шкаф. Поэтому пол стоит внутри, на `fitsInRow`, а не снаружи.
   */
  /**
   * 🔴 ПОЛ ДЕЙСТВУЕТ ВНУТРИ МИНИМУМА, А ШИРИНА ЯЧЕЙКИ ОСТАЁТСЯ ЖЁСТКИМ ПОТОЛКОМ.
   *
   * `Math.max(floorItem, fitsInRow)` не даёт ВЫСОТЕ ряда ужать товар ниже пола;
   * внешний `Math.min(…, fitsInCell)` не даёт полу нарушить ширину. Порядок
   * важен: поставь пол снаружи — и товар на 320 px при четырёх колонках стал бы
   * 30 при ячейке на 21, то есть ряд из трёх вылез бы за нишу (замер: 76 против 63).
   *
   * 📍 ДВЕ ВЫЖИВШИЕ МУТАЦИИ ПРИВЕЛИ СЮДА, И ОБЕ НАЗЫВАЛИ ЛИШНЕЕ, А НЕ ДЫРУ.
   * Сначала был отдельный пол на ВЫСОТУ РЯДА (`perRow`) — мутация «снять его»
   * прошла незамеченной: работу делал этот же `Math.max`. Хуже: на 320 px тот
   * пол раздувал нишу с 54 до 58 px и ВКЛЮЧАЛ ПРОКРУТКУ (3×5, поле 380: шкаф
   * 333 → 353), не увеличив товар ни на пиксель, — доска ехала впустую.
   * Потом появилась страховка `Math.min(floorItem, fitsInCell)` — и тоже выжила:
   * замер на 4608 раскладках показал побайтовое совпадение с формой без неё,
   * потому что `fitsInCell` уже стоит потолком в этой же строке.
   * Обе убраны. Выжившая мутация — повод убрать код, а не дописать проверку.
   */
  const itemSize = Math.max(18, Math.min(148, fitsInCell, Math.max(floorItem, fitsInRow)));
  const itemH = Math.round(itemSize / ITEM_ASPECT);

  // Избыток высоты уходит ВНУТРЬ ниши (товар стоит на доске, над ним видна
  // задняя стенка), но не выше `perRow` — иначе короб снова перерастёт поле.
  /**
   * Избыток высоты уходит ВНУТРЬ ниши (товар стоит на доске, над ним видна
   * задняя стенка), но не выше `perRow` — иначе короб перерастёт поле зря.
   * ⚠️ Нижняя граница — сам товар плюс воздух: если поле мало, ниша всё равно
   * не станет ниже своего содержимого, и шкаф честно объявит себя едущим.
   */
  const nicheH = Math.max(itemH + 8, Math.min(Math.round(itemH * 2.2), perRow));
  // Высота всего короба: ряды + зазоры между ними + рама сверху/снизу + торец.
  const shelfH = nicheH * rows + SHELF_GAP * (rows - 1) + SHELF_PAD * 2 + 9;

  const шагРяда = itemSize * (1 - OVERLAP) + CELL_GAP;
  const rowW = Math.round(itemSize + (capWide - 1) * шагРяда);

  /**
   * 🔴 РАЗМЕР ТОВАРА — ПО СВОЕЙ НИШЕ, А НЕ ПО САМОЙ ЖАДНОЙ НА ДОСКЕ.
   *
   * Замер 03.09.2026 (телефон 390, уровень 20): с 18-го уровня появляется одна
   * ниша на четыре товара, и `capWideHere = Math.max(...caps)` ужимал товар во
   * ВСЁМ шкафу — 44 → 33 по стороне, почти вдвое по площади. Семнадцать ниш
   * платили за одну. Это и есть вторая половина жалобы Вали «ужасно товары
   * мелкие»: первую (арифметику «три встык») закрыл нахлёст, а эту — нет.
   *
   * Высота ниши общая: ряды обязаны совпадать по всей доске, иначе полки
   * разъедутся. А ширина у каждой ниши своя, и товар в ней считается от её
   * собственной вместимости.
   */
  const itemBox = (cap: number): { w: number; h: number } => {
    const c = Math.max(1, Math.round(cap));
    const дел = 1 + (c - 1) * (1 - OVERLAP);
    const поШирине = Math.floor((cellW - CELL_GAP * (c - 1)) / дел);
    const w = Math.max(18, Math.min(148, поШирине, Math.max(floorItem, fitsInRow)));
    return { w, h: Math.round(w / ITEM_ASPECT) };
  };

  /**
   * ⚠️ Признак прокрутки считается ПО ШКАФУ, а не по числу рядов: одно и то же
   * число рядов на планшете влезает, а на телефоне нет. Сравниваем то, что
   * нарисуется, с тем, что есть — иначе получится ещё одна константа на месте
   * замера, а их этот файл уже пережил три.
   */
  const boardH = shelfH;
  const scrolls = boardH > availH - HINT_H;

  return { boardW, cellW, itemSize, itemH, nicheH, shelfH, overlap: OVERLAP, rowW, itemBox, boardH, scrolls };
}

export function gsRulesForLevel(L: number): LevelRule[] {
  return GS_RULES.filter((r) => {
    if (r.key === 'strict') return strictPlacement(L);
    if (r.key === 'hidden') return hiddenInfo(L);
    return true;
  });
}

/**
 * Ключи скрытых мест раздачи: всё, что лежит НЕ спереди («ниша:позиция»).
 * Тот же список, из которого «накрытый товар» (L8) выбирает себе выборку —
 * источник один, чтобы «что вообще можно спрятать» не разъехалось между двумя
 * механиками скрытости.
 */
export function hideDeepSpots(cells: number[][]): string[] {
  const out: string[] = [];
  cells.forEach((c, i) => c.forEach((_, j) => { if (j < c.length - 1) out.push(`${i}:${j}`); }));
  return out;
}

/**
 * Перенос ключей скрытости через изъятие товара (fromCell, fromIdx).
 *
 * 🔴 КЛЮЧИ ПОЗИЦИОННЫЕ, А ПОЗИЦИИ СДВИГАЮТСЯ. splice убирает товар из середины
 * ряда, всё правее съезжает на единицу — а ключи до сих пор оставались на
 * месте: в [скрытый, скрытый, видимый] изъятие среднего дарило его ключ
 * ВИДИМОМУ товару, вставшему на ту позицию, и тот темнел на глазах. При двух
 * накрытых на доску это жило незаметно, при «скрыто всё в глубине» стреляло бы
 * через ход.
 *
 * Ключ самого изъятого умирает: товар ложится в цель ПОСЛЕДНИМ, то есть
 * спереди, а спереди скрытых не бывает — «выкопать ?» и есть его вскрытие.
 */
export function shiftCoveredAfterTake(covered: Iterable<string>, fromCell: number, fromIdx: number): string[] {
  const out: string[] = [];
  for (const k of Array.from(covered)) {
    const [i, j] = k.split(':').map(Number);
    if (i !== fromCell) { out.push(k); continue; }
    if (j === fromIdx) continue;
    out.push(j > fromIdx ? `${i}:${j - 1}` : k);
  }
  return out;
}

/**
 * ВСКРЫТИЕ: перед кем никого не осталось — тот виден. Правило одно на обе
 * механики скрытости, и на «?», и на силуэты накрытого: справка накрытого с
 * восьмого уровня так и обещает («сними тот, что перед ним, и узнаешь, что
 * это»), а код до этой правки держал силуэт до полного опустошения ниши — то
 * есть правило на экране расходилось с игрой.
 *
 * Пустую нишу отдельно чистить не надо: у неё len−1 = −1, любой ключ ≥ 0
 * оказывается «спереди или дальше» и снимается этим же условием.
 *
 * ⚠️ ПОСЛЕ КАСКАДА КЛЮЧИ НЕ ПЕРЕСЧИТЫВАЮТСЯ, И ЭТО НЕ ДЫРА: тройка забирает из
 * ниши три товара, при ёмкостях 2–4 там остаётся максимум один — а единственный
 * всегда спереди, и его ключ снимает эта же проверка.
 */
export function revealUncovered(covered: Iterable<string>, cells: number[][]): string[] {
  const out: string[] = [];
  for (const k of Array.from(covered)) {
    const [i, j] = k.split(':').map(Number);
    if (j < (cells[i]?.length ?? 0) - 1) out.push(k);
  }
  return out;
}

/**
 * ЭТАЛОН ХОДОВ УРОВНЯ — единственное место, где он считается. По нему меряются
 * и звёзды (starsFor), и moves_over_min в записи сессии: два своих эталона
 * однажды разъехались бы, и оценка на экране спорила бы с оценкой в данных.
 * Где лимита нет — types × 3: каждой тройке нужно до трёх перекладываний
 * (тот же расчёт, из которого лимит потом и строится).
 */
export function moveReference(cfg: { moveLimit: number; types: number }): number {
  return cfg.moveLimit > 0 ? cfg.moveLimit : Math.round(cfg.types * REF_PER_TYPE);
}

/**
 * 🔴 СКОЛЬКО ХОДОВ НА ВИД ТОВАРА — ЗАМЕР, А НЕ ПРИКИДКА (пункт 6.5, 02.09.2026).
 *
 * Было `types × 3` из рассуждения «каждой тройке до трёх перекладываний». Замер
 * поиском A* с допустимой эвристикой (`services/goodsSortMinMoves`) на девяти
 * уровнях, по шесть досок каждый:
 *
 *   L1: минимум 8,3 при оценке 12 (доля 0,69) · L4: 13,6 при 18 (0,76)
 *   L8: 15,0 при 21 (0,71) · L11: 12,2 при 18 (0,68) · среднее по девяти — 0,732
 *
 * То есть прикидка завышала эталон на треть, и завышала устойчиво.
 *
 * 🔴 ЧЕМ ЭТО ОБЕРНУЛОСЬ. Порог трёх звёзд стоял «ходов ≤ 0,6 × эталон», то есть
 * 1,8 × types. Реальный минимум — 2,1–2,3 × types. **Высшая оценка была недостижима
 * на 95 % досок** (замер: 21 из 22). Игрок не мог получить три звезды, сколь угодно
 * хорошо играя, — и никакой формулой этого не видно, только перебором.
 *
 * ⚠️ Точный минимум на лету НЕ считается: тот же замер показал 6–10 секунд и
 * 40 000 узлов уже с пятнадцатого уровня. Поэтому эталон — калиброванная оценка,
 * а точное число берётся, когда фоновый расчёт успел (см. `starsFor`).
 */
export const REF_PER_TYPE = 2.2;

/**
 * 🔴 ЦЕНА ЦЕПОЧКИ — ЧИСТАЯ ФУНКЦИЯ, А НЕ СТРОЧКА В ОБРАБОТЧИКЕ.
 *
 * Вторая тройка в одном ходу стоит ×2, третья ×3 и дальше: цепочка дороже той
 * же работы вразбивку, и её есть смысл выстраивать. Раньше это жило только
 * внутри каскада, и гейт проверял его СОВПАДЕНИЕМ СТРОКИ `gained += 50 * n`.
 * Такая проверка ловит форму записи: переставь слагаемые — покраснеет на верном
 * коде, поменяй 50 на 5 — останется зелёной. Вынесено, чтобы вызывать.
 */
export const CLEAR_SCORE = 50;

export function scoreForClears(n: number): number {
  if (n <= 0) return 0;
  return CLEAR_SCORE * (n * (n + 1)) / 2;
}

/**
 * Подсветка «здесь пара» — ОБУЧАЮЩАЯ, а не постоянная. На первых уровнях это
 * ровно то, что надо объяснить; дальше она снимает половину зрительного поиска —
 * как раз ту работу, ради которой сюда приходят.
 */
export const PAIR_HINT_UNTIL = 5;

export function pairHintVisible(L: number): boolean {
  return L <= PAIR_HINT_UNTIL;
}

/**
 * 🔴 ЗВЁЗДЫ ПО ХОДАМ — ОДНА ФОРМУЛА НА ИГРУ И НА ГЕЙТ.
 *
 * Пороги считаются от ЭТАЛОНА (точного минимума этой доски, если фоновый расчёт
 * успел, иначе калиброванной оценки), а не от доли «сколько не жалко»:
 *   до +15 % сверх минимума — три звезды · до +60 % — две · дальше — одна.
 *
 * ⚠️ Вынесено наружу именно ради гейта. Проверка, которая ПОВТОРЯЕТ формулу у себя,
 * ничего не стоит: два числа из одного рассуждения согласуются по определению.
 * `goods-sort-stars-reachable` зовёт эту функцию и сверяет её вердикт с минимумом,
 * найденным поиском, — то есть с игрой, а не с самой собой.
 */
export function starsForMoves(moves: number, reference: number): 1 | 2 | 3 {
  if (moves <= Math.ceil(reference * 1.15)) return 3;
  if (moves <= Math.ceil(reference * 1.6)) return 2;
  return 1;
}

/**
 * ЗАМЕРЫ ПАРТИИ СКРЫТОЙ ИНФОРМАЦИИ — §20.4: что меряем ВМЕСТО ходов сверх
 * минимума.
 *   · firstMoveMs — сколько думал до первого хода, зная, что информации не хватает;
 *   · planRevisions — пересмотры плана: отмены и возвраты (товар едет назад);
 *   · movesBeforeFirstReveal — ходов к моменту первого вскрытия, включая
 *     вскрывший: исследует сначала или лезет напролом.
 * null = событие не наступило либо партия поднята из снимка без замеров.
 */
export interface HiddenRunStats {
  firstMoveMs: number | null;
  planRevisions: number;
  movesBeforeFirstReveal: number | null;
}

/** Чистый лист замеров — им начинается каждый уровень. */
export const EMPTY_HIDDEN_STATS: HiddenRunStats = { firstMoveMs: null, planRevisions: 0, movesBeforeFirstReveal: null };

/**
 * details СЕССИИ — единственное место, где решается, какие числа уходят в запись.
 *
 * 🔴 §20.4 — ПРАВИЛО ИЗМЕРЕНИЯ, БЕЗ КОТОРОГО РЕЖИМ ВРЁТ. Обычный уровень пишет
 * moves_over_min — расстояние до эталона (бывает отрицательным: эталон это «до
 * трёх ходов на тройку», а не точный минимум). На уровне скрытой информации
 * минимума НЕ СУЩЕСТВУЕТ: оптимальная стратегия зависит от того, что
 * вскроется. Поэтому поля moves_over_min там НЕТ ВООБЩЕ — не ноль и не null,
 * а отсутствует: ноль читался бы как «сыграл без лишних ходов», null — как
 * «замер сломался». Вместо него — три замера §20.4. Сырой счётчик moves
 * остаётся в обоих: он факт, а не сравнение с несуществующим эталоном.
 *
 * Разность §20.5 (цена неопределённости) собирается потом из ПАР сессий —
 * обычной и скрытой на сопоставимых досках; раздачу режим не меняет.
 */
export function sessionDetails(
  level: number,
  moves: number,
  hidden: boolean,
  reference: number,
  stats: HiddenRunStats = EMPTY_HIDDEN_STATS,
): Record<string, number | boolean | null> {
  if (!hidden) return { level, moves, moves_over_min: moves - reference };
  return {
    level,
    moves,
    hidden_info: true,
    time_to_first_move_ms: stats.firstMoveMs,
    plan_revisions: stats.planRevisions,
    moves_before_first_reveal: stats.movesBeforeFirstReveal,
  };
}

