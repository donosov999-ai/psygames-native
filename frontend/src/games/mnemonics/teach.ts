/**
 * 🎓 РАЗБОР ПО ШАГАМ «МНЕМОНИКА»: ДВА РАЗНЫХ ПРИЁМА НА ДВА РЕЖИМА.
 *
 * 📍 Денис 17.09.2026: «обучение зашло — раскатывай везде». Здесь особенно уместно: отчёт
 * NZT-48 (13.09.2026) был ровно про это — «игра требует запомнить, но не даёт приёма».
 * Словарь опор 00–99 уже появился (`pegs.ts`); разбор показывает, КАК им пользоваться.
 *
 * 🔴 ПРИЁМ ЗАВИСИТ ОТ РЕЖИМА, И ПОДМЕНЯТЬ ИХ НЕЛЬЗЯ:
 * · СЛОВА — цепочка: каждое следующее слово ДЕЙСТВУЕТ с предыдущим в одной сцене. Порядок
 *   держится сценой, а не счётом: «дом → собака» это собака на крыше дома, а не «первое,
 *   второе».
 * · ЧИСЛА — буквенно-цифровой код: число превращается в СЛОВО по согласным (82 → вино), и
 *   дальше цепочка строится из этих слов. Пытаться удержать цифры как цифры — то самое, на
 *   что жаловался отчёт.
 *
 * ⚠️ ОПОРА БЕРЁТСЯ ИЗ СЛОВАРЯ, А НЕ ПРИДУМЫВАЕТСЯ НА ХОДУ: `pegFor`/`pegHint` — те же, что
 * показывает экран запоминания. Разойдись разбор со словарём — человек выучил бы приём,
 * который игра не подтверждает.
 */
import { pegFor, pegHint, hasPegTable } from './pegs';

export type РежимРазбора = 'words' | 'numbers';

export interface КарточкаМнемо {
  вид: 'приём' | 'опора' | 'связка' | 'порядок' | 'готово';
  /** Ключ словаря: язык живёт в словаре, не в коде. */
  ключ: string;
  поля?: Record<string, string | number>;
  /** Какой элемент ряда подсветить (индекс) или `null`. */
  элемент: number | null;
}

export interface РазборМнемо {
  карточки: КарточкаМнемо[];
  /** Что разбор показал по порядку — ровно эти элементы игра и спросит. */
  элементы: string[];
}

/**
 * ⚠️ ПОКАЗЫВАЕМ НЕ БОЛЬШЕ ЧЕТЫРЁХ ЭЛЕМЕНТОВ. Лестница доходит до пятнадцати, и полный
 * разбор превратился бы в трёхминутный ролик. Приём показывается на четырёх, дальше
 * человек применяет его сам — за этим разбор и нужен.
 */
const ПОКАЗЫВАЕМ = 4;

export function собратьРазборМнемоники(
  элементы: readonly string[],
  режим: РежимРазбора,
  язык: string,
): РазборМнемо {
  const взято = элементы.slice(0, Math.min(ПОКАЗЫВАЕМ, элементы.length));
  const опорыЕсть = режим === 'numbers' && hasPegTable(язык);

  const карточки: КарточкаМнемо[] = [{
    вид: 'приём',
    ключ: режим === 'numbers'
      ? (опорыЕсть ? 'teachMnemoIntroNumbers' : 'teachMnemoIntroNumbersNoPegs')
      : 'teachMnemoIntroWords',
    поля: { n: элементы.length },
    элемент: null,
  }];

  взято.forEach((элемент, i) => {
    if (опорыЕсть) {
      const число = Number(элемент);
      const слово = pegFor(число, язык) ?? элемент;
      const разбор = (pegHint(число, язык) ?? '').split(': ')[1] ?? '';
      карточки.push({
        вид: 'опора',
        ключ: i === 0 ? 'teachMnemoPegFirst' : 'teachMnemoPeg',
        поля: { n: элемент, word: слово, why: разбор },
        элемент: i,
      });
      if (i > 0) {
        const прошлое = pegFor(Number(взято[i - 1]), язык) ?? взято[i - 1]!;
        карточки.push({
          вид: 'связка',
          ключ: 'teachMnemoChain',
          поля: { a: прошлое, b: слово },
          элемент: i,
        });
      }
      return;
    }
    карточки.push({
      вид: i === 0 ? 'опора' : 'связка',
      ключ: i === 0 ? 'teachMnemoWordFirst' : 'teachMnemoChainWords',
      поля: { a: i === 0 ? элемент : взято[i - 1]!, b: элемент },
      элемент: i,
    });
  });

  карточки.push({
    вид: 'порядок',
    ключ: 'teachMnemoOrder',
    поля: { n: элементы.length },
    элемент: null,
  });
  карточки.push({ вид: 'готово', ключ: 'teachMnemoDone', элемент: null });
  return { карточки, элементы: [...элементы] };
}
