/**
 * ЛЕСТНИЦА ЗАДЕРЖКИ И ОСИ УРОВНЯ — ДВЕ РАЗНЫЕ РУЧКИ, И ИХ НЕЛЬЗЯ ПУТАТЬ.
 *
 * 🔴 ГЛАВНОЕ ПРАВИЛО ФАЙЛА: ЗАДЕРЖКА ПРИНАДЛЕЖИТ ЛЕСТНИЦЕ, А НЕ УРОВНЮ.
 * До 23.08.2026 `levelParams` возвращал `ssd = min(430, 150 + (level−1)*20)` —
 * то есть трудность торможения назначалась НОМЕРОМ УРОВНЯ, одинаково для всех.
 * Быстрый игрок при этом тормозил успешно в одной пробе из десяти, медленный —
 * в девяти. Мерить торможение так нельзя в принципе: у двух людей мерка была
 * разная. Поэтому `levelParams` про задержку больше НЕ ЗНАЕТ НИЧЕГО, а задержку
 * двигает `nextSsd` по результату каждой стоп-пробы.
 *
 * ⚠️ ЧЕМ ТОГДА КРУТИТСЯ УРОВЕНЬ. Темпом подачи (пауза до GO, пауза между
 * пробами) и окном ответа — ровно тем, что разрешает §0 реестра дефектов
 * (`PSYGAMES_DEFECTS.md`): «сложность крутим темпом, окном ответа и объёмом».
 * И тем, что там прямо запрещено, — долей стоп-проб — не крутится: она
 * КОНСТАНТА (`STOP_PROB`).
 *
 * 🔴 ДОЛЯ СТОП-ПРОБ 25%, А НЕ 40%. Прежние 40% — тот же класс дефекта §1: при
 * такой доле преобладающей реакции нет, «жать» не становится привычкой, и
 * тормозить оказывается нечего. Канон — 25%.
 */
import type { StopSignalTrial } from './ssrt';

/**
 * С чего начинается лестница у нового игрока.
 *
 * ⚠️ Руководство (Verbruggen et al., 2019) советует 300 мс; берём 250 мс, потому
 * что окно ответа здесь короче лабораторного (700…1400 мс против 1500+), и от
 * 300 мс лестница у быстрого игрока первые пробы шла бы только вниз. Точка
 * старта на итог не влияет — лестница сходится туда же, — а вот число проб до
 * схождения от неё зависит.
 */
export const SSD_START_MS = 250;
/**
 * Шаг 50 мс — канон. Мельче (16 мс) лестница не успевает сойтись за партию,
 * крупнее — теряет разрешение и скачет вокруг точки схождения.
 */
export const SSD_STEP_MS = 50;
export const SSD_MIN_MS = 50;
export const SSD_MAX_MS = 700;
/** Доля стоп-проб. Константа, уровнем НЕ крутится — см. шапку. */
export const STOP_PROB = 0.25;

export function clampSsd(ms: number): number {
  return Math.min(SSD_MAX_MS, Math.max(SSD_MIN_MS, Math.round(ms)));
}

/**
 * ОДИН ВВЕРХ / ОДИН ВНИЗ.
 *
 * Удержался — задержка растёт, стоп-сигнал в следующий раз придёт ПОЗЖЕ, и
 * тормозить будет труднее. Сорвался — падает. Такая лестница по построению
 * сходится к доле удавшихся торможений ≈ 0.5 у ЛЮБОГО игрока: быстрый осядет на
 * маленькой задержке, медленный на большой, а половина останется половиной. Из
 * этой точки и только из неё имеет смысл SSRT.
 *
 * ⚠️ ШАГ ВНИЗ ДЕЛАЕТСЯ НА ЛЮБОМ ОТВЕТЕ В СТОП-ПРОБЕ, включая нажатие ДО показа
 * сигнала: методика требует именно этого, иначе преждевременные нажатия тихо
 * подтягивали бы лестницу вверх.
 */
export function nextSsd(currentMs: number, inhibited: boolean): number {
  const step = inhibited ? SSD_STEP_MS : -SSD_STEP_MS;
  return clampSsd(currentMs + step);
}

export interface StopSignalLevel {
  /** Число проб партии. */
  trials: number;
  /** Доля стоп-проб. Всегда `STOP_PROB` — поле оставлено, чтобы экран не знал про константу. */
  stopProb: number;
  /** Окно ответа на GO. Ось сложности №1. */
  goWindowMs: number;
  /** Минимальная пауза перед GO. Ось сложности №2 (темп). */
  fixMinMs: number;
  /** Разброс паузы перед GO поверх минимума — чтобы момент GO нельзя было выучить. */
  fixJitterMs: number;
  /** Пауза после обратной связи до следующей пробы. Ось сложности №3 (темп). */
  interTrialMs: number;
}

/**
 * Параметры уровня 1..15 (дальше значения упираются в потолки).
 *
 * 🔴 НИ ОДНОГО ПОЛЯ ПРО ЗАДЕРЖКУ. Если оно тут появится — вернулся дефект §2.1.
 * Проба `stop-signal-ssrt.test.ts` держит это поведением, а не осмотром текста:
 * при задержке от уровня доля удавшихся торможений перестаёт сходиться к 50%
 * у трёх модельных игроков с разной скоростью, и гейт краснеет.
 *
 * ⚠️ ЛЕСТНИЦА УРОВНЕЙ ОБЯЗАНА ОСТАТЬСЯ ЛЕСТНИЦЕЙ. Все три оси идут вниз строго
 * монотонно с первого уровня по пятнадцатый: окно 1400 → 700 мс, пауза до GO
 * 700 → 350 мс, пауза между пробами 600 → 320 мс. Пятнадцатый ощутимо плотнее
 * первого, и это проверяется числами, а не обещанием.
 */
export function levelParams(level: number): StopSignalLevel {
  const step = Math.max(0, Math.min(14, Math.round(level) - 1));   // 0..14
  return {
    trials: level <= 5 ? 12 : level <= 10 ? 16 : 20,
    stopProb: STOP_PROB,
    goWindowMs: 1400 - step * 50,      // 1400 → 700
    fixMinMs: 700 - step * 25,         // 700 → 350
    fixJitterMs: 700 - step * 30,      // 700 → 280
    interTrialMs: 600 - step * 20,     // 600 → 320
  };
}

/**
 * Сколько проб храним для замера.
 *
 * 🔴 ЗАЧЕМ ХРАНИТЬ ВООБЩЕ. В партии 12…20 проб, из них стоп-проб при доле 25%
 * выходит три-пять. Лестница за пять шагов не проходит и половины пути от
 * старта до точки схождения, а SSRT по пяти стоп-пробам — это не оценка, а
 * шум с видом числа. Поэтому и ступень лестницы, и сами пробы ПЕРЕЖИВАЮТ
 * партию: лестница сходится за несколько заходов, а SSRT считается по
 * накопленному окну. Ровно так же устроен настоящий стоп-сигнал — там задержка
 * тоже не сбрасывается между блоками.
 *
 * ⚠️ ОКНО, А НЕ ВСЯ ИСТОРИЯ. Замер должен описывать сегодняшнего человека, а не
 * его же полгода назад; плюс хранилище не должно расти без предела.
 */
export const POOL_MAX_TRIALS = 160;

/** Добавить пробы партии к накопленному окну, отрезав всё, что вышло за потолок. */
export function appendTrials(
  pool: readonly StopSignalTrial[],
  run: readonly StopSignalTrial[],
): StopSignalTrial[] {
  const merged = [...pool, ...run];
  return merged.length > POOL_MAX_TRIALS ? merged.slice(merged.length - POOL_MAX_TRIALS) : merged;
}

/** Сколько стоп-проб в окне. Экран показывает это число, пока их не хватает на замер. */
export function countStopTrials(pool: readonly StopSignalTrial[]): number {
  return pool.reduce((n, t) => (t.isStop ? n + 1 : n), 0);
}
