/**
 * SSRT — ВРЕМЯ ТОРМОЖЕНИЯ. ЕДИНСТВЕННОЕ ЧИСЛО, РАДИ КОТОРОГО ЭТА ИГРА ЕСТЬ.
 *
 * 🔴 ЧТО СТОЯЛО ЗДЕСЬ ДО 23.08.2026 И ПОЧЕМУ ЭТО ХУЖЕ ОБЫЧНОГО БАГА.
 * Экран отдавал «счёт» = попадания×50 + удержания×100 − ошибки×60 − среднее
 * время реакции×0.1, а задержку стоп-сигнала (SSD) назначал УРОВЕНЬ:
 * `ssd = min(430, 150 + (level−1)*20)`. Лестницы не было вовсе. Из этого
 * следует ровно одно: у быстрого игрока стоп-сигнал приходил заведомо поздно и
 * торможение срывалось почти всегда, у медленного — заведомо рано и удавалось
 * почти всегда. Игра называлась «торможение», а мерила базовую скорость
 * реакции. И выдавала при этом правдоподобное число, поэтому никто не замечал.
 *
 * 🟢 ЧТО ТЕПЕРЬ. Задержка ходит по лестнице (`ladder.ts`) и сходится к точке,
 * где торможение удаётся примерно в половине стоп-проб — У ЛЮБОГО игрока,
 * быстрого и медленного. Из этой точки и только из неё считается SSRT.
 *
 * ─── ПОЧЕМУ МЕТОД ИНТЕГРАЦИИ, А НЕ МЕТОД СРЕДНЕГО ───────────────────────────
 *
 * Метод среднего: SSRT = среднее время реакции GO − средняя задержка. Одна
 * строка, и в ней вся беда: распределение времён реакции скошено вправо
 * (редкие очень медленные ответы тянут среднее), а модель гонки говорит про
 * ПОРЯДКОВУЮ статистику, а не про среднее. Скос сдвигает оценку вверх тем
 * сильнее, чем длиннее правый хвост, — то есть сильнее всего у уставшего
 * игрока, у которого как раз и хочется померить торможение честно.
 *
 * Метод интеграции берёт n-ю по скорости реакцию GO, где n = число GO-ответов ×
 * доля сорванных торможений, и вычитает из неё среднюю задержку. Это ровно то,
 * что предписывает модель гонки: сорванными оказываются САМЫЕ БЫСТРЫЕ ответы,
 * и граница между сорванными и удержанными лежит на n-й порядковой статистике.
 * Скос правого хвоста на неё не влияет. Согласованное руководство по стоп-
 * сигналу (Verbruggen et al., 2019, eLife 8:e46323) называет метод интеграции
 * наименее смещённым из известных — на нём и стоим.
 *
 * ⚠️ ЭТАЛОН, С КОТОРЫМ СВЕРЯЛИСЬ. Пакет `@jspsych-contrib/plugin-stop-signal`
 * (MIT) открывали глазами: ни лестницы, ни SSRT там НЕТ — это показ двух
 * картинок с кнопками, форк `plugin-animation-button-response` (видно по его же
 * `package.json`: описание и `homepage` остались от донора). Копировать оттуда
 * было нечего, ни строки не взято, файл лицензии поэтому не приносим. Считаем
 * по описанию методики из руководства выше.
 *
 * ─── УСЛОВИЯ ПРИМЕНИМОСТИ. ВЫДУМАННОЕ ЧИСЛО ХУЖЕ ОТСУТСТВИЯ ЧИСЛА ────────────
 *
 * У метода интеграции есть границы, за которыми оценка смещена, и молча выдать
 * её там — значит соврать красивым числом. Поэтому проверяются четыре вещи, и
 * при любом непопадании `ssrtMs` равен `null`, а `doubt` называет ПРИЧИНУ
 * человеческим текстом:
 *   · стоп-проб должно быть достаточно (`MIN_STOP_TRIALS`), иначе доля
 *     сорванных торможений — это 2/5 или 3/5, и n-я порядковая статистика
 *     скачет на сотни миллисекунд от одной пробы;
 *   · доля сорванных торможений обязана лежать в 0.25…0.75 — это прямая
 *     рекомендация руководства: за её пределами лестница не сошлась и оценка
 *     смещена;
 *   · время реакции на СОРВАННЫХ стоп-пробах не должно превышать время реакции
 *     на обычных GO-пробах. Превысило — нарушена сама модель гонки, на которой
 *     держится вся арифметика, и считать по ней нельзя;
 *   · пропусков GO должно быть мало: каждый пропуск идёт в расчёт как самый
 *     медленный ответ, и при их обилии оценка ползёт вниз.
 */

/** Одна проба партии — ровно то, что нужно расчёту, и ничего сверх. */
export interface StopSignalTrial {
  /** Стоп-проба (был или должен был быть сигнал «стоп») либо обычная GO-проба. */
  isStop: boolean;
  /**
   * Задержка стоп-сигнала НА ЭТОЙ пробе. У GO-проб её нет.
   * ⚠️ Пишется даже тогда, когда человек нажал раньше, чем сигнал показался:
   * ступень лестницы всё равно была назначена, и в среднюю задержку она входит.
   */
  ssdMs: number | null;
  /** Время реакции от появления GO. `null` — не нажал вовсе. */
  rtMs: number | null;
  /**
   * Окно ответа этой пробы. Им ЗАМЕЩАЕТСЯ пропуск GO: по методике пропуск
   * получает максимальное время реакции, а максимум здесь — это и есть окно.
   */
  goWindowMs: number;
}

/** Почему числу нельзя верить. `null` — верить можно. */
export type SsrtDoubt =
  | 'noStopTrials'
  | 'tooFewStopTrials'
  | 'noGoResponses'
  | 'tooManyOmissions'
  | 'pRespondOffTarget'
  | 'raceModelViolated';

export interface SsrtEstimate {
  /** Метод назван в самом числе — чтобы сохранённую партию нельзя было спутать. */
  method: 'integration';
  /** Само время торможения в мс. `null` = условия применимости не выполнены. */
  ssrtMs: number | null;
  /** Можно ли показывать число человеку и класть в историю. */
  trustworthy: boolean;
  doubt: SsrtDoubt | null;
  /** p(respond | signal) — доля стоп-проб, где торможение СОРВАЛОСЬ. */
  pRespond: number;
  /** Доля стоп-проб, где торможение УДАЛОСЬ. Это та самая половина, к которой сходится лестница. */
  pInhibit: number;
  meanSsdMs: number;
  /** Среднее по нажатым GO-пробам (пропуски сюда не идут — это подпись для человека). */
  meanGoRtMs: number;
  /** Среднее по сорванным стоп-пробам. Нужно для проверки модели гонки. */
  meanFailedStopRtMs: number;
  /** n-я по скорости реакция GO — то, из чего вычитается задержка. */
  nthGoRtMs: number | null;
  goTrials: number;
  goOmissions: number;
  stopTrials: number;
  failedStops: number;
}

/** Границы, за которыми руководство прямо запрещает оценивать SSRT. */
export const P_RESPOND_MIN = 0.25;
export const P_RESPOND_MAX = 0.75;
/**
 * Меньше двенадцати стоп-проб — это не замер. Доля сорванных торможений при
 * пяти пробах принимает всего шесть значений, и n-я порядковая статистика
 * прыгает через сотню миллисекунд от одной-единственной пробы.
 */
export const MIN_STOP_TRIALS = 12;
/** Доля пропущенных GO, выше которой оценка смещается вниз ощутимо. */
export const MAX_OMISSION_RATE = 0.1;

const mean = (xs: readonly number[]): number =>
  (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);

/**
 * Оценка SSRT методом интеграции по набору проб.
 *
 * ⚠️ Функция чистая и не знает ни про экран, ни про уровень: те же пробы — то
 * же число. Ровно поэтому её можно предъявить модельному игроку с ЗАДАННЫМ
 * временем торможения и проверить, что оно восстанавливается.
 */
export function estimateSsrt(trials: readonly StopSignalTrial[]): SsrtEstimate {
  const go = trials.filter((t) => !t.isStop);
  const stop = trials.filter((t) => t.isStop);

  // Пропуск GO участвует в расчёте как САМЫЙ МЕДЛЕННЫЙ ответ — так предписывает
  // методика. Выбросить его значило бы укоротить распределение справа и занизить
  // n-ю порядковую статистику, то есть занизить SSRT молча.
  const goRts = go.map((t) => (t.rtMs === null ? t.goWindowMs : t.rtMs)).sort((a, b) => a - b);
  const goOmissions = go.filter((t) => t.rtMs === null).length;
  const pressedGoRts = go.filter((t) => t.rtMs !== null).map((t) => t.rtMs as number);

  const failed = stop.filter((t) => t.rtMs !== null);
  const pRespond = stop.length > 0 ? failed.length / stop.length : 0;
  const meanSsdMs = mean(stop.map((t) => (t.ssdMs === null ? 0 : t.ssdMs)));

  // n = сколько самых быстрых GO-ответов «проиграли бы» торможению.
  // Округляем к ближайшему и держим в пределах массива: n = 0 означало бы
  // «граница левее самого быстрого ответа», а такого порядкового номера нет.
  const nRaw = Math.round(goRts.length * pRespond);
  const n = goRts.length > 0 ? Math.min(goRts.length, Math.max(1, nRaw)) : 0;
  const nthGoRtMs = n > 0 ? goRts[n - 1] : null;

  const meanGoRtMs = mean(pressedGoRts);
  const meanFailedStopRtMs = mean(failed.map((t) => t.rtMs as number));
  const omissionRate = go.length > 0 ? goOmissions / go.length : 0;

  // Порядок проверок — от «нечего считать» к «считать можно, но смещённо».
  let doubt: SsrtDoubt | null = null;
  if (stop.length === 0) doubt = 'noStopTrials';
  else if (stop.length < MIN_STOP_TRIALS) doubt = 'tooFewStopTrials';
  else if (goRts.length === 0) doubt = 'noGoResponses';
  else if (omissionRate > MAX_OMISSION_RATE) doubt = 'tooManyOmissions';
  else if (pRespond < P_RESPOND_MIN || pRespond > P_RESPOND_MAX) doubt = 'pRespondOffTarget';
  else if (failed.length > 0 && pressedGoRts.length > 0 && meanFailedStopRtMs > meanGoRtMs) {
    doubt = 'raceModelViolated';
  }

  const ssrtMs = nthGoRtMs === null ? null : Math.round(nthGoRtMs - meanSsdMs);

  return {
    method: 'integration',
    ssrtMs: doubt === null ? ssrtMs : null,
    trustworthy: doubt === null,
    doubt,
    pRespond,
    pInhibit: stop.length > 0 ? 1 - pRespond : 0,
    meanSsdMs: Math.round(meanSsdMs),
    meanGoRtMs: Math.round(meanGoRtMs),
    meanFailedStopRtMs: Math.round(meanFailedStopRtMs),
    nthGoRtMs,
    goTrials: go.length,
    goOmissions,
    stopTrials: stop.length,
    failedStops: failed.length,
  };
}
