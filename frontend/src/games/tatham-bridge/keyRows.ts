/**
 * 🔴 РЯДЫ КЛАВИШ ДЕЛЯТСЯ ПОРОВНУ, А НЕ «СКОЛЬКО ВЛЕЗЛО — ОСТАЛЬНОЕ ВНИЗ».
 *
 * Отзывы Дениса 18.09.2026, iPhone 403×873, v2.54.22: `fc2085a2` («Заполнение областей»)
 * «Почему цифры не в два ряда» и `eb132a28` (Solo) «ряд цифр кривой снизу». Перенос по месту
 * давал 6+4 на 403×873 и 5+5 на 360×640: нижний ряд то вдвое короче верхнего, то вровень, и
 * зависело это от окна, а не от замысла.
 *
 * Считаем, сколько клавиш ВЛЕЗАЕТ в измеренную ширину, делим на нужное число рядов и сужаем
 * ряд до ровного дележа: 10 клавиш при шести влезающих — 5+5; 7 клавиш — 4+3.
 *
 * ⚠️ Ширина сюда приходит ИЗМЕРЕННАЯ (`onLayout` узла под доской), а не посчитанная из окна:
 * замер 18.09.2026 на 360×640 показал 5 клавиш в ряду там, где «окно − поля сцены» обещало 6.
 * Между окном и рядом лежат поля каркаса, и считать их по памяти — промахнуться ещё раз.
 */
export const ШИРИНА_КЛАВИШИ = 50;
export const ЗАЗОР_КЛАВИШ = 6;

/** Сколько клавиш влезает в ряд по измеренной ширине. */
export function клавишВРяд(доступно: number, шКлавиши = ШИРИНА_КЛАВИШИ, зазор = ЗАЗОР_КЛАВИШ): number {
  if (доступно <= 0) return 1;
  return Math.max(1, Math.floor((доступно + зазор) / (шКлавиши + зазор)));
}

/**
 * Ширина ряда, при которой перенос делит клавиши поровну.
 * `undefined` — всё влезает одной строкой: тогда ширину не навязываем.
 */
export function ширинаРовныхРядов(
  клавиш: number, доступно: number, шКлавиши = ШИРИНА_КЛАВИШИ, зазор = ЗАЗОР_КЛАВИШ,
): number | undefined {
  if (доступно <= 0 || клавиш <= 1) return undefined;
  const влезает = клавишВРяд(доступно, шКлавиши, зазор);
  if (клавиш <= влезает) return undefined;
  const рядов = Math.ceil(клавиш / влезает);
  const вРяду = Math.ceil(клавиш / рядов);
  return вРяду * шКлавиши + (вРяду - 1) * зазор;
}

/** Как лягут клавиши при данной ширине ряда — для проб и замеров: [6, 4] это «6 сверху, 4 снизу». */
export function разбиение(
  клавиш: number, ширинаРяда: number, шКлавиши = ШИРИНА_КЛАВИШИ, зазор = ЗАЗОР_КЛАВИШ,
): number[] {
  const вРяду = клавишВРяд(ширинаРяда, шКлавиши, зазор);
  const ряды: number[] = [];
  for (let о = клавиш; о > 0; о -= вРяду) ряды.push(Math.min(вРяду, о));
  return ряды;
}
