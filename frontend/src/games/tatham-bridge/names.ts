/**
 * 🔴 СКОЛЬКО КЛАВИШ ПОКАЗЫВАТЬ — ИЗ РАЗМЕРА ДОСКИ, А НЕ ДЕВЯТЬ ВСЕГДА.
 *
 * Первая моя редакция рисовала 1–9 всем подряд. На листе всех сорока это сразу
 * видно: у «Пятнашек» 4×4 под доской девять клавиш, у «Домино» третьего порядка —
 * тоже девять. Клавиша, которой в этой игре не бывает, хуже отсутствия: человек
 * жмёт и ничего не происходит.
 *
 * Параметры пресета у Тэтхэма начинаются с размера («4x4 Easy», «5x5», «9x7»),
 * отсюда и число. Не разобрали — девять, как у судоку.
 *
 * ⚠️ И СПИСОК СУЖЕН. В нём было семь имён по прогону «нажали 1 — доска изменилась»,
 * но у «Пятнашек» и «Труб со сдвигом» цифра меняет доску не потому, что это ввод
 * числа: у них другой смысл клавиш. Оставлены те, где вписать число — само правило.
 */
export function клавишДоски(имя: string, параметры: string): number {
  const п = параметры.trim();
  /**
   * ⚠️ У СУДОКУ ЧИСЛО В ПАРАМЕТРАХ — ЭТО БЛОКИ, А НЕ СТОРОНА ДОСКИ. `2x2` значит
   * блоки два на два, то есть поле 4×4 и цифры 1–4. Первая редакция читала это как
   * сторону и рисовала ДВЕ клавиши на доску, где нужно четыре — видно на листе всех
   * сорока: под «Судоку Тэтхэма» стояли «1 2».
   */
  if (имя === 'Solo') {
    const m = /^(\d+)\s*x\s*(\d+)/i.exec(п);
    if (m) { const n = Number(m[1]) * Number(m[2]); return n >= 2 && n <= 16 ? n : 9; }
    return 9;
  }
  /**
   * ⚠️ У «Заполнения областей» цифра — РАЗМЕР ОБЛАСТИ, а не сторона поля: параметры
   * `9x7` описывают доску, а вписывают числа до девяти. Поэтому исключение.
   */
  if (имя === 'Filling') return 9;
  /**
   * 🔴 У «НЕЖИТИ» ЦИФРА — ЭТО ВИД ЧУДОВИЩА, А НЕ СТОРОНА ПОЛЯ. Их ровно три:
   * призрак, вампир, зомби (`undead.c`). Мы читали сторону доски и раздавали 4, 5
   * и 7 клавиш — замер 11.09.2026: доска принимает только 1, 2, 3, остальные
   * МЁРТВЫЕ на всех восьми ступенях, от одной до четырёх штук на каждой.
   */
  if (имя === 'Undead') return 3;
  /**
   * 🔴 У «УГАДАЙ КОД» ЦИФРА — ЭТО ЦВЕТ, И ИХ ЧИСЛО СТОИТ В `c<N>`, а не первым числом
   * параметров: `c6p4g10Bm` — шесть цветов, четыре колышка, десять попыток.
   *
   * ⚠️ Первый мой замер сказал «принимает 1–4» и был ИЗМЕРЕНИЕМ НЕ ТОГО: цифры
   * нажимались подряд, ряд из четырёх колышков заполнялся, и дальше доска молчала —
   * не потому, что цифры не те, а потому что класть некуда. На СВЕЖЕЙ доске
   * принимаются все шесть (и все восемь на `c8p5g12Bm`).
   */
  if (имя === 'Guess') {
    const m = /c(\d+)/i.exec(п);
    const n = m ? Number(m[1]) : 6;
    return n >= 2 && n <= 12 ? n : 6;
  }
  /**
   * Остальные пишут сторону поля первым числом: у Keen и Towers это `4de`, у Undead
   * `4x4de`, у Unequal `4de` (имя пресета при этом «Unequal: 4x4 Easy» — читать надо
   * ПАРАМЕТРЫ, а не подпись).
   */
  const m = /^(\d+)(?:\s*x\s*(\d+))?/i.exec(п);
  if (!m) return 9;
  const n = Math.max(Number(m[1]), Number(m[2] ?? m[1]));
  return n >= 2 && n <= 12 ? n : 9;
}


