/** Ступень лестницы: подпись человеку и параметры движка. */
export interface ШагЛестницы { имя: string; параметры: string }

export interface НастройкаРежима {
  /** Ключ словаря с названием игры. Описание выводится как `<ключ>Desc`. */
  имя: string;
  /**
   * Второе действие (правая кнопка движка). `true` — есть, но своего имени нет
   * и кнопка подписывается общим словом; строка — ключ словаря со СВОИМ именем
   * («Флажок», «Крестик», «Карандаш»).
   */
  второе?: true | string;
  /** Крестовина стрелок: у части движков ход делается только курсором. */
  стрелки?: true;
  /** Ряд цифр под доской. */
  цифры?: true;
  /**
   * Что нарисовано на клавишах ряда вместо чисел — по порядку для цифр 1..N: знак на
   * клавише и ключ словаря с именем для чтеца экрана. Нужно там, где цифра движка
   * значит НЕ число: у «Нежити» 1 — призрак, 2 — вампир, 3 — зомби (`undead.c:1931–1945`).
   * Код клавиши движку остаётся цифрой — меняется только то, что видит человек.
   */
  знакиЦифр?: readonly { знак: string; имя: string }[];
  /** Своя строка ввода (пока только «Угадай код»). */
  ввод?: true;
  /** Ход планируется шагами, а не одним тычком. */
  планШагами?: true;
  /** Сначала выбрать клетку, потом подтвердить командой. */
  выбор?: true;
  /** У выбора есть и вторая команда. */
  выборВторой?: true;
  /**
   * Имя второй команды курсора, когда переключателя правой кнопки у режима НЕТ.
   * `второе: 'ключ'` не годится: оно заодно включает переключатель для пальца,
   * а у таких режимов правая кнопка пальцем не делает ничего — вышла бы
   * кнопка-пустышка. Пример: «Прямоугольники», правый тычок 0/25, а ВЫБРАТЬ-2
   * ведёт стирающую протяжку (`rect.c:2438`).
   */
  имяВторогоВыбора?: string;
  /** Курсор ходит по восьми направлениям, а не по четырём. */
  восемьНаправлений?: true;
  /** Тычок не работает вовсе — только протяжка. */
  толькоПротяжка?: true;
  /** Своя лестница вместо авторской. Нет — берётся авторская. */
  лестница?: ШагЛестницы[];
}

/** Паспорт раздела: чьи это режимы и куда ведёт его развилка. */
export interface ПаспортРаздела { имя: string; хаб: string; чат: string }
