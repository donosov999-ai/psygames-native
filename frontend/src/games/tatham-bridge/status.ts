/**
 * ХОД ПАРТИИ СЧИТАЕТ САМ ДВИЖОК — МЫ ЭТО ВЫБРАСЫВАЛИ.
 *
 * 📍 Денис 10.09.2026 про головоломки: «в конце ничего не происходит, ни конца, ни
 * след. уровень, замер экран». Часть этого — отсутствие обратной связи по ходу
 * партии: в шапке стояли только «уровень» и «ходы».
 *
 * Между тем движки Тэтхэма ведут строку состояния (`status_bar`), и в ней ровно то,
 * чего не хватало: сколько шариков отмечено из скольких, сколько подсказок осталось,
 * сколько узлов уже соединено. Замер 10.09.2026: строку дают ЧЕТЫРНАДЦАТЬ движков
 * из сорока, и у двенадцати из них она меняется по ходу игры.
 *
 * ⚠️ ПОЧЕМУ ЕЁ НЕЛЬЗЯ ПОКАЗЫВАТЬ КАК ЕСТЬ. Текст английский и идёт из движка:
 * «Balls marked: 0 / 5» посреди русского экрана — не перевод, а дыра. Поэтому здесь
 * из строки достаются ЧИСЛА, а подпись берётся наша, из словаря.
 *
 * ⚠️ И ПОЧЕМУ РАЗБОР ТЕРПИМ К НЕЗНАКОМОМУ. Кроме счётчиков движок пишет туда
 * предупреждения и приговоры — «20 too many balls marked.», «DEAD!   Deaths: 1».
 * Их не разобрать в число, и переводить свободный текст мы не беремся: незнакомая
 * строка даёт `null`, то есть слот в шапке просто не появляется. Показать
 * по-английски было бы хуже, чем не показать.
 */

/** Что показать в шапке: ключ подписи из словаря и уже собранное значение. */
export type ХодПартии = { ключ: string; значение: string } | null;

/**
 * Замер 10.09.2026 по всем сорока — какие формы вообще встречаются:
 *   «Balls marked: 0 / 5»          Black Box
 *   «[0:00] Marked: 0 / 10»        Mines (впереди часы автора, мы их не показываем)
 *   «Clues left: 44»               Mosaic
 *   «Active: 6/25»                 Net
 *   «Moves: 0 Active: 3/9»         Netslide (две величины, берём вторую — первую
 *                                   наша шапка считает сама)
 *   «Gems: 16»                     Inertia
 *   «0 / 22 moves»                 Flood (бюджет ходов, а не счётчик)
 *   «Score: 0»                     Same Game
 *   «Region size: 5»               Palisade
 *   «Moves: N»                     Cube, Fifteen, Flip, Sixteen, Twiddle
 *
 * ⚠️ Одинокое «Moves: N» СОЗНАТЕЛЬНО пропускается: ходы у нас уже есть в шапке своим
 * счётчиком, и второй такой же рядом — не обратная связь, а шум.
 */
const ФОРМЫ: { узор: RegExp; ключ: string; пара?: true }[] = [
  { узор: /(?:Balls )?[Mm]arked:\s*(\d+)\s*\/\s*(\d+)/, ключ: 'puzzleHudMarked', пара: true },
  { узор: /Active:\s*(\d+)\s*\/\s*(\d+)/,               ключ: 'puzzleHudActive', пара: true },
  { узор: /^(\d+)\s*\/\s*(\d+)\s+moves$/,               ключ: 'puzzleHudMovesUsed', пара: true },
  { узор: /Clues left:\s*(\d+)/,                        ключ: 'puzzleHudCluesLeft' },
  { узор: /Gems:\s*(\d+)/,                              ключ: 'puzzleHudGems' },
  { узор: /Score:\s*(\d+)/,                              ключ: 'score' },              // общий ключ словаря: «Счёт» там уже есть
  { узор: /Region size:\s*(\d+)/,                       ключ: 'puzzleHudRegion' },
];

/** Разобрать строку состояния движка в подпись + значение. Незнакомое → `null`. */
export function ходПартии(строка: string): ХодПартии {
  const s = (строка || '').trim();
  if (!s) return null;
  for (const ф of ФОРМЫ) {
    const m = ф.узор.exec(s);
    if (!m) continue;
    return { ключ: ф.ключ, значение: ф.пара ? `${m[1]}/${m[2]}` : String(m[1]) };
  }
  return null;
}
