import type { Примитив } from './play';

/**
 * Режимы, где «лишняя линия» имеет смысл, а подсветка движка её не показывает. Номера — цвета, которыми движок рисует
 * линию игрока (enum исходника), сверенные с рисунком моста (снимок пробы `puzzle-where-error`). Сравнение — по МЕСТУ
 * прямоугольника, а не по цвету: мост у перегруженного острова красный, а в решении на том же месте — чёрный.
 * Добавлять режим — только с замером: верная линия даёт 0 лишних, неверная — не 0.
 */
export const ЦВЕТ_ЛИНИИ: Record<string, number[]> = {
  Galaxies: [6],     // COL_EDGE, galaxies.c:126
  Bridges: [1, 8],   // COL_FOREGROUND и COL_WARNING — цвет моста, bridges.c:2843 (draw_general_line)
};

export interface Рамка { x: number; y: number; ш: number; в: number }

/** Поле вокруг линии: линию шириной 2–3 единицы иначе не обвести рамкой, которую видно пальцу и глазу. */
const ПОЛЕ = 7;

type Прямоугольник = Extract<Примитив, { вид: 'прямоугольник' }>;

const ключ = (п: Прямоугольник) => `${п.x} ${п.y} ${п.ш} ${п.в}`;

function линии(примитивы: Примитив[], цвета: number[]): Прямоугольник[] {
  return примитивы.filter((п): п is Прямоугольник => п.вид === 'прямоугольник' && цвета.includes(п.цвет) && п.ш > 0 && п.в > 0);
}

/** Касаются ли два прямоугольника (стык в одну единицу тоже касание: шов рисуется встык). */
function касаются(а: Рамка, б: Рамка): boolean {
  return а.x <= б.x + б.ш && б.x <= а.x + а.ш && а.y <= б.y + б.в && б.y <= а.y + а.в;
}

/**
 * Лишние линии: рамки вокруг кусков, которые есть на доске игрока и которых нет в решении.
 * `null` — режим не из `ЦВЕТ_ЛИНИИ`: сверять нечего, и экран кнопку не показывает.
 */
export function лишниеЛинии(режим: string, доска: Примитив[], решение: Примитив[]): Рамка[] | null {
  const цвета = ЦВЕТ_ЛИНИИ[режим];
  if (цвета === undefined) return null;
  const вРешении = new Set(линии(решение, цвета).map(ключ));
  const лишние: Рамка[] = [];
  const видели = new Set<string>();
  for (const п of линии(доска, цвета)) {
    const к = ключ(п);
    if (вРешении.has(к) || видели.has(к)) continue;
    видели.add(к);
    лишние.push({ x: п.x, y: п.y, ш: п.ш, в: п.в });
  }
  // Склейка касающихся кусков: одна граница — одна рамка, длинный неверный разрез — одна длинная рамка.
  // Повторяем, пока есть что склеить: новая рамка может дотянуться до группы, проверенной раньше.
  const группы: Рамка[] = лишние.map((к) => ({ ...к }));
  let склеили = true;
  while (склеили) {
    склеили = false;
    for (let i = 0; i < группы.length && !склеили; i++) {
      for (let j = i + 1; j < группы.length; j++) {
        if (!касаются(группы[i], группы[j])) continue;
        const а = группы[i], б = группы.splice(j, 1)[0];
        const x = Math.min(а.x, б.x), y = Math.min(а.y, б.y);
        группы[i] = { x, y, ш: Math.max(а.x + а.ш, б.x + б.ш) - x, в: Math.max(а.y + а.в, б.y + б.в) - y };
        склеили = true;
        break;
      }
    }
  }
  return группы.map((г) => ({ x: г.x - ПОЛЕ, y: г.y - ПОЛЕ, ш: г.ш + 2 * ПОЛЕ, в: г.в + 2 * ПОЛЕ }));
}
