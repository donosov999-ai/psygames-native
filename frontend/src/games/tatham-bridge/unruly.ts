/**
 * ПРАВИЛА «ЧЁТ-НЕЧЕТ» (Unruly) — на нашей стороне, потому что они в две строки.
 *
 * Дорого у Тэтхэма стоит не правило, а ГЕНЕРАТОР с гарантией единственного решения и
 * лестницей сложности; его мы и берём кодом. Проверку хода писать своими руками дешевле,
 * чем тащить через мост: она нужна на КАЖДОЕ нажатие, а ходить в wasm за этим — лишняя цена.
 *
 * Правила: в строке и столбце поровну нулей и единиц; трёх одинаковых подряд не бывает.
 */
export type Клетка = 0 | 1 | null;

/** Доска из ASCII движка: строки вида «. . 0 0 . .» → сетка. */
export function изТекста(строки: string[]): Клетка[][] {
  return строки.map((s) =>
    s.trim().split(/\s+/).map((c) => (c === '0' ? 0 : c === '1' ? 1 : null)) as Клетка[],
  );
}

/** Номера строк и столбцов, где правило нарушено. Пусто — нарушений нет. */
export function нарушения(поле: Клетка[][]): { строки: number[]; столбцы: number[] } {
  const h = поле.length;
  const w = h ? поле[0].length : 0;
  const строки: number[] = [];
  const столбцы: number[] = [];

  const плохаяЛиния = (значения: Клетка[]): boolean => {
    // три одинаковых подряд
    for (let i = 0; i + 2 < значения.length; i++) {
      const a = значения[i];
      if (a !== null && a === значения[i + 1] && a === значения[i + 2]) return true;
    }
    // перевес: заполненных одного знака больше половины
    const нулей = значения.filter((v) => v === 0).length;
    const единиц = значения.filter((v) => v === 1).length;
    return нулей > значения.length / 2 || единиц > значения.length / 2;
  };

  for (let y = 0; y < h; y++) if (плохаяЛиния(поле[y])) строки.push(y);
  for (let x = 0; x < w; x++) if (плохаяЛиния(поле.map((r) => r[x]))) столбцы.push(x);
  return { строки, столбцы };
}

/** Решено ли: пустых клеток нет и ни одно правило не нарушено. */
export function решено(поле: Клетка[][]): boolean {
  if (поле.some((r) => r.some((c) => c === null))) return false;
  const { строки, столбцы } = нарушения(поле);
  return строки.length === 0 && столбцы.length === 0;
}
