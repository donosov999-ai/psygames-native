/**
 * 🔴 РАЗБОР ПО ШАГАМ «УГАДАЙ КОД» (Guess): КАК ВЫВОДИТЬ КОД ИЗ МЕТОК И КАКУЮ ПОПЫТКУ ДЕЛАТЬ СЛЕДУЮЩЕЙ.
 *
 * 📍 Денис 17.09.2026, проверив пилот на «Чёт-нечет»: «да, обучение зашло — раскатывай везде по
 * всем играм». В этой игре нечего «ставить по правилу» — правило одно: метки. Поэтому разбор учит
 * двум вещам:
 *   · читать ответ: ● — цвет стоит на своём месте, ○ — цвет есть в коде, но в другом месте;
 *   · выбирать попытку, которая отсекает больше всего: среди кодов, согласных со ВСЕМИ ответами,
 *     берётся тот, после которого в худшем случае останется меньше всего вариантов (минимакс
 *     Кнута, 1977). Первая попытка — две пары цветов, «1 1 2 2»: так у Кнута, и ответ на неё
 *     сразу говорит о двух цветах.
 *
 * Метки считает движок (`guess.c`, `mark_pegs`); здесь та же формула, и проба сверяет её с ответами
 * самого движка на снятых с моста раздачах, а не с этим же файлом.
 *
 * ⚠️ ПЕРЕБОР ОГРАНИЧЕН — ЗАМЕР, А НЕ ОСТОРОЖНОСТЬ. Полный минимакс на «Супере» (8 цветов × 5, кодов
 * 32 768) считался 17.09.2026 в среднем 1,7 с на план и до 2,4 с (Node на маке; телефон медленнее в
 * разы) — это ожидание перед разбором. Поэтому выбор попытки ищется среди не больше
 * `ПРЕДЕЛ_КАНДИДАТОВ` согласных кодов и оценивается на выборке не больше `ПРЕДЕЛ_ОЦЕНКИ` — обе
 * равномерно по списку. На «Стандарте» после первой попытки согласных не больше 256, и выборки
 * совпадают со всем списком: там это честный минимакс Кнута.
 * Число, которое называет текст («останется не больше {m}»), считается ТОЧНО, по всем согласным.
 */

export type Код = number[];

export interface Ответ { чёрных: number; белых: number }

export interface ПараметрыКода { цветов: number; фишек: number; попыток: number }

const ПРЕДЕЛ_КАНДИДАТОВ = 150;
const ПРЕДЕЛ_ОЦЕНКИ = 600;

/** Равномерная выборка из списка — не больше `предел` элементов, первый всегда в ней. */
function выборка<T>(список: readonly T[], предел: number): readonly T[] {
  if (список.length <= предел) return список;
  const шаг = список.length / предел;
  return Array.from({ length: предел }, (_, i) => список[Math.floor(i * шаг)]!);
}

/** «c6p4g10Bm» → 6 цветов, 4 фишки, 10 попыток. */
export function параметрыИзСтроки(параметры: string): ПараметрыКода | null {
  const c = /c(\d+)/.exec(параметры), p = /p(\d+)/.exec(параметры), g = /g(\d+)/.exec(параметры);
  if (!c || !p || !g) return null;
  return { цветов: Number(c[1]), фишек: Number(p[1]), попыток: Number(g[1]) };
}

/** Ответ на попытку: чёрных — совпало место и цвет; белых — цвет есть, но в другом месте. */
export function ответ(секрет: Код, попытка: Код): Ответ {
  let чёрных = 0;
  const вСекрете = new Map<number, number>(), вПопытке = new Map<number, number>();
  for (let i = 0; i < секрет.length; i++) {
    if (секрет[i] === попытка[i]) { чёрных++; continue; }
    вСекрете.set(секрет[i]!, (вСекрете.get(секрет[i]!) ?? 0) + 1);
    вПопытке.set(попытка[i]!, (вПопытке.get(попытка[i]!) ?? 0) + 1);
  }
  let белых = 0;
  for (const [цвет, n] of вПопытке) белых += Math.min(n, вСекрете.get(цвет) ?? 0);
  return { чёрных, белых };
}

/** Все коды по порядку: 1111, 1112, … */
export function всеКоды({ цветов, фишек }: Pick<ПараметрыКода, 'цветов' | 'фишек'>): Код[] {
  const out: Код[] = [];
  const код = Array<number>(фишек).fill(1);
  for (;;) {
    out.push([...код]);
    let i = фишек - 1;
    while (i >= 0 && код[i] === цветов) { код[i] = 1; i--; }
    if (i < 0) return out;
    код[i]!++;
  }
}

const равны = (a: Ответ, b: Ответ) => a.чёрных === b.чёрных && a.белых === b.белых;

/** Коды, согласные со всеми сыгранными попытками. */
export function согласные(коды: readonly Код[], сыграно: readonly { попытка: Код; ответ: Ответ }[]): Код[] {
  return коды.filter((к) => сыграно.every((с) => равны(ответ(к, с.попытка), с.ответ)));
}

/** Сколько вариантов останется в худшем случае после попытки. */
export function худшийОстаток(попытка: Код, кандидаты: readonly Код[]): number {
  const корзины = new Map<number, number>();
  let худший = 0;
  for (const к of кандидаты) {
    const о = ответ(к, попытка);
    const ключ = о.чёрных * 16 + о.белых;
    const n = (корзины.get(ключ) ?? 0) + 1;
    корзины.set(ключ, n);
    if (n > худший) худший = n;
  }
  return худший;
}

export interface ШагУгадывания {
  /** Номер попытки с нуля — он же ряд на доске. */
  номер: number;
  попытка: Код;
  /** Сколько кодов согласно со всеми ответами ДО этой попытки. */
  осталось: number;
  /** Сколько останется в худшем случае ПОСЛЕ неё. */
  вХудшем: number;
  /** Предыдущая попытка и ответ на неё — о них говорит карточка. */
  прошлая?: { номер: number; попытка: Код; ответ: Ответ };
}

/** Первая попытка без сведений — пары цветов: «1 1 2 2», «1 1 2 2 3». */
export function перваяПопытка(фишек: number): Код {
  return Array.from({ length: фишек }, (_, i) => Math.floor(i / 2) + 1);
}

/**
 * План разбора от позиции человека до угаданного кода. `сыграно` — попытки, которые уже на доске;
 * ответы на них те же, что показал движок. `секрет` нужен, чтобы знать ответы на СЛЕДУЮЩИЕ попытки.
 */
export function план(секрет: Код, сыграно: readonly Код[], п: ПараметрыКода): ШагУгадывания[] {
  const история = сыграно.map((попытка) => ({ попытка, ответ: ответ(секрет, попытка) }));
  if (история.some((с) => с.ответ.чёрных === п.фишек)) return [];
  // Согласные коды отсеиваются по одному новому ответу, а не заново по всей истории.
  let кандидаты = согласные(всеКоды(п), история);
  const шаги: ШагУгадывания[] = [];
  for (let номер = история.length; номер < п.попыток; номер++) {
    if (!кандидаты.length) break;
    let попытка: Код;
    if (!история.length) {
      попытка = перваяПопытка(п.фишек);
    } else if (кандидаты.length === 1) {
      попытка = кандидаты[0]!;
    } else {
      const оценка = выборка(кандидаты, ПРЕДЕЛ_ОЦЕНКИ);
      let лучший = Infinity;
      попытка = кандидаты[0]!;
      for (const кандидат of выборка(кандидаты, ПРЕДЕЛ_КАНДИДАТОВ)) {
        const остаток = худшийОстаток(кандидат, оценка);
        if (остаток < лучший) { лучший = остаток; попытка = кандидат; }
      }
    }
    const прошлое = история[история.length - 1];
    шаги.push({
      номер, попытка, осталось: кандидаты.length, вХудшем: худшийОстаток(попытка, кандидаты),
      ...(прошлое ? { прошлая: { номер: номер - 1, попытка: прошлое.попытка, ответ: прошлое.ответ } } : {}),
    });
    const о = ответ(секрет, попытка);
    история.push({ попытка, ответ: о });
    if (о.чёрных === п.фишек) break;
    кандидаты = согласные(кандидаты, [{ попытка, ответ: о }]);
  }
  return шаги;
}

/* ── доска с рисунка движка ─────────────────────────────────────────────── */

interface ПримитивКруг { вид: string; x?: number; y?: number; r?: number; заливка?: number }

export interface ДоскаУгадывания {
  /** Центры цветов палитры сверху вниз: цвет k — индекс k − 1. */
  палитра: { x: number; y: number; r: number }[];
  /** Лунки попыток: ряд сверху вниз, в ряду слева направо; цвет 0 — пусто. */
  ряды: { x: number; y: number; r: number; цвет: number }[][];
  /** Метки ряда: центр блока меток, сколько чёрных и белых, и горит ли «можно отправить». */
  метки: { x: number; y: number; ш: number; в: number; чёрных: number; белых: number; готов: boolean }[];
  /** Строка ответа после решения: цвета кода или null, если её нет на рисунке. */
  код: Код | null;
}

/**
 * Заливки рисунка — порядок `enum` в `guess.c`. Замер на мосту 17.09.2026 («c6p4g10Bm»): пустая лунка
 * и пустая метка — 5; цвет k — 5 + k; чёрная метка — 16, белая — 17; ряд, который можно отправить,
 * рисует метки заливкой 3.
 */
const ПУСТО = 5, ЧЁРНАЯ = 16, БЕЛАЯ = 17, ГОТОВ = 3;

/**
 * Доска с рисунка: большие круги — палитра (крайний левый столбец) и лунки, маленькие — метки.
 * `null` — рисунок не похож на доску этих параметров.
 */
export function доскаСРисунка(примитивы: readonly ПримитивКруг[], п: ПараметрыКода): ДоскаУгадывания | null {
  const круги = примитивы.filter((к): к is Required<Pick<ПримитивКруг, 'x' | 'y' | 'r' | 'заливка'>> & ПримитивКруг =>
    к.вид === 'круг' && к.x !== undefined && к.y !== undefined && к.r !== undefined && к.заливка !== undefined);
  if (!круги.length) return null;
  const большой = Math.max(...круги.map((к) => к.r));
  // Последний круг в точке — тот, что виден: движок перерисовывает поверх.
  const поТочке = new Map<string, (typeof круги)[number]>();
  for (const к of круги) поТочке.set(`${к.x},${к.y},${к.r >= большой * 0.7 ? 'б' : 'м'}`, к);
  const видимые = [...поТочке.values()];
  const крупные = видимые.filter((к) => к.r >= большой * 0.7);
  const мелкие = видимые.filter((к) => к.r < большой * 0.7);
  const левый = Math.min(...крупные.map((к) => к.x));
  const палитра = крупные.filter((к) => к.x === левый).sort((a, b) => a.y - b.y).map(({ x, y, r }) => ({ x, y, r }));
  if (палитра.length !== п.цветов) return null;
  const поY = new Map<number, (typeof круги)[number][]>();
  for (const к of крупные) if (к.x !== левый) поY.set(к.y, [...(поY.get(к.y) ?? []), к]);
  const строки = [...поY.entries()].sort((a, b) => a[0] - b[0]).map(([, р]) => р.sort((a, b) => a.x - b.x));
  if (строки.length < п.попыток || строки.slice(0, п.попыток).some((р) => р.length !== п.фишек)) return null;
  const цвет = (заливка: number) => (заливка === ПУСТО ? 0 : заливка - ПУСТО);
  const ряды = строки.slice(0, п.попыток).map((р) => р.map((к) => ({ x: к.x, y: к.y, r: к.r, цвет: цвет(к.заливка) })));
  const шаг = п.попыток > 1 ? ряды[1]![0]!.y - ряды[0]![0]!.y : большой * 2;
  const метки = ряды.map((р) => {
    const свои = мелкие.filter((к) => Math.abs(к.y - р[0]!.y) < шаг / 2);
    if (!свои.length) return { x: р[р.length - 1]!.x + большой * 2, y: р[0]!.y, ш: 0, в: 0, чёрных: 0, белых: 0, готов: false };
    const x0 = Math.min(...свои.map((к) => к.x - к.r)), x1 = Math.max(...свои.map((к) => к.x + к.r));
    const y0 = Math.min(...свои.map((к) => к.y - к.r)), y1 = Math.max(...свои.map((к) => к.y + к.r));
    return {
      x: (x0 + x1) / 2, y: (y0 + y1) / 2, ш: x1 - x0, в: y1 - y0,
      чёрных: свои.filter((к) => к.заливка === ЧЁРНАЯ).length,
      белых: свои.filter((к) => к.заливка === БЕЛАЯ).length,
      готов: свои.some((к) => к.заливка === ГОТОВ),
    };
  });
  const последняя = строки[п.попыток];
  const код = последняя && последняя.length === п.фишек && последняя.every((к) => к.заливка > ПУСТО && к.заливка < ЧЁРНАЯ)
    ? последняя.map((к) => цвет(к.заливка)) : null;
  return { палитра, ряды, метки, код };
}

/**
 * Попытки, уже отправленные на доске: ряды сверху, целиком заполненные и не «готовые к отправке».
 * Заполненный, но не отправленный ряд движок рисует метками заливки 3 — это ещё не попытка.
 */
export function сыгранныеПопытки(доска: ДоскаУгадывания): Код[] {
  const out: Код[] = [];
  for (let i = 0; i < доска.ряды.length; i++) {
    const ряд = доска.ряды[i]!;
    if (ряд.some((л) => л.цвет === 0) || доска.метки[i]?.готов) break;
    out.push(ряд.map((л) => л.цвет));
  }
  return out;
}

