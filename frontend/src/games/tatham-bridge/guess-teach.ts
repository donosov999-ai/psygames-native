export const КЛЮЧИ_РАЗБОРА_УГАДЫВАНИЯ = ['teachGuessFirst', 'teachGuessNext', 'teachGuessOnly'] as const;

const запись = (код: Код) => код.join(' ');

/** Объяснение шага человеческими словами. */
export function текстШага(шаг: ШагУгадывания, t: (ключ: string) => string): string {
  const подставить = (текст: string) => текст
    .split('{code}').join(запись(шаг.попытка))
    .split('{n}').join(String((шаг.прошлая?.номер ?? 0) + 1))
    .split('{b}').join(String(шаг.прошлая?.ответ.чёрных ?? 0))
    .split('{w}').join(String(шаг.прошлая?.ответ.белых ?? 0))
    .split('{k}').join(String(шаг.осталось))
    .split('{m}').join(String(шаг.вХудшем));
  if (!шаг.прошлая) return подставить(t('teachGuessFirst'));
  return подставить(t(шаг.осталось === 1 ? 'teachGuessOnly' : 'teachGuessNext'));
}
