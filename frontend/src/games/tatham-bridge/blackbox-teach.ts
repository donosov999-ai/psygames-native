export const КЛЮЧИ_РАЗБОРА_ЯЩИКА = [
  'teachBoxFirst', 'teachBoxNext', 'teachBoxNextMany', 'teachBoxPlace',
  'teachBoxHit', 'teachBoxReflect', 'teachBoxThrough', 'teachBoxTurn',
] as const;

/** Что сказал прошлый луч — словами правила. */
function ответСловами(выстрел: Выстрел, t: (ключ: string) => string): string {
  if (выстрел.итог === 'H') return t('teachBoxHit');
  if (выстрел.итог === 'R') return t('teachBoxReflect');
  // «Насквозь» — только если луч ни разу не повернул: выйти напротив можно и после поворотов.
  return t(выстрел.поворотов ? 'teachBoxTurn' : 'teachBoxThrough');
}

/** Объяснение шага человеческими словами. */
export function текстШага(шаг: ШагЯщика, t: (ключ: string) => string): string {
  const подставить = (текст: string) => текст
    .split('{answer}').join(шаг.прошлый ? ответСловами(шаг.прошлый, t) : '')
    .split('{k}').join(String(шаг.согласных))
    .split('{r}').join(String(шаг.разных ?? 1))
    .split('{b}').join(String(шаг.шары?.length ?? 0));
  if (шаг.вид === 'шары') return подставить(t('teachBoxPlace'));
  if (!шаг.прошлый) return подставить(t('teachBoxFirst'));
  return подставить(t(шаг.много ? 'teachBoxNextMany' : 'teachBoxNext'));
}
