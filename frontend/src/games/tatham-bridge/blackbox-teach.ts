/** Направления: 0 вверх, 1 вправо, 2 вниз, 3 влево — как в `blackbox.c`. */
const DX = [0, 1, 0, -1], DY = [-1, 0, 1, 0];

export interface ПараметрыЯщика { w: number; h: number; мин: number; макс: number }

/** «w8h8m3M6» → поле 8×8, шаров от 3 до 6. */
export function параметрыИзСтроки(параметры: string): ПараметрыЯщика | null {
  const m = /w(\d+)h(\d+)m(\d+)M(\d+)/.exec(параметры);
  return m ? { w: Number(m[1]), h: Number(m[2]), мин: Number(m[3]), макс: Number(m[4]) } : null;
}

/** Вход луча: клетка рамки (gx, gy — с рамкой, поле 1…w) и направление внутрь. */
export interface Вход { gx: number; gy: number; d: number }

/** Все входы по периметру: сверху, справа, снизу, слева. */
export function входы(w: number, h: number): Вход[] {
  const out: Вход[] = [];
  for (let x = 1; x <= w; x++) out.push({ gx: x, gy: 0, d: 2 });
  for (let y = 1; y <= h; y++) out.push({ gx: w + 1, gy: y, d: 3 });
  for (let x = w; x >= 1; x--) out.push({ gx: x, gy: h + 1, d: 0 });
  for (let y = h; y >= 1; y--) out.push({ gx: 0, gy: y, d: 1 });
  return out;
}

/** Ответ луча: поглощён, отражён или вышел во вход с этим номером. */
export type Итог = 'H' | 'R' | number;

type Состояние = { итог: Итог; поворотов?: number } | { упёрся: number };

/**
 * Луч по клеткам: −1 — неизвестно, 0 — пусто, 1 — шар. Если ответ зависит от неизвестной клетки,
 * возвращается она (`упёрся`) — поиск берёт её следующей.
 */
function лучПоКлеткам(w: number, h: number, клетки: Int8Array, i: number, все: readonly Вход[]): Состояние {
  const вход = все[i]!;
  let x = вход.gx, y = вход.gy, d = вход.d;
  const взгляд = (x: number, y: number, d: number, куда: -1 | 0 | 1): number => {
    let nx = x + DX[d]!, ny = y + DY[d]!;
    if (куда) { const s = (d + (куда > 0 ? 1 : 3)) % 4; nx += DX[s]!; ny += DY[s]!; }
    if (nx < 1 || ny < 1 || nx > w || ny > h) return 0;
    const id = (ny - 1) * w + (nx - 1);
    return клетки[id] === -1 ? -1 - id : клетки[id]!;
  };
  const f = взгляд(x, y, d, 0); if (f < 0) return { упёрся: -1 - f }; if (f) return { итог: 'H' };
  const l = взгляд(x, y, d, -1); if (l < 0) return { упёрся: -1 - l };
  const r = взгляд(x, y, d, 1); if (r < 0) return { упёрся: -1 - r };
  if (l || r) return { итог: 'R' };
  x += DX[d]!; y += DY[d]!;
  let поворотов = 0;
  for (let шаг = 0; шаг < 4 * (w + 2) * (h + 2); шаг++) {
    if (x < 1 || y < 1 || x > w || y > h) {
      const выход = все.findIndex((в) => в.gx === x && в.gy === y);
      return { итог: выход === i ? 'R' : выход, поворотов };
    }
    const f2 = взгляд(x, y, d, 0); if (f2 < 0) return { упёрся: -1 - f2 }; if (f2) return { итог: 'H', поворотов };
    const l2 = взгляд(x, y, d, -1); if (l2 < 0) return { упёрся: -1 - l2 };
    if (l2) { d = (d + 1) % 4; поворотов++; continue; }
    const r2 = взгляд(x, y, d, 1); if (r2 < 0) return { упёрся: -1 - r2 };
    if (r2) { d = (d + 3) % 4; поворотов++; continue; }
    x += DX[d]!; y += DY[d]!;
  }
  return { итог: 'R', поворотов };
}

/** Ответ луча при известной раскладке шаров (индексы клеток y·w + x) и сколько раз он повернул. */
export function ходЛуча(п: Pick<ПараметрыЯщика, 'w' | 'h'>, шары: ReadonlySet<number>, i: number, все: readonly Вход[]): { итог: Итог; поворотов: number } {
  const клетки = new Int8Array(п.w * п.h);
  for (const ш of шары) клетки[ш] = 1;
  const с = лучПоКлеткам(п.w, п.h, клетки, i, все) as { итог: Итог; поворотов?: number };
  return { итог: с.итог, поворотов: с.поворотов ?? 0 };
}

export const луч = (п: Pick<ПараметрыЯщика, 'w' | 'h'>, шары: ReadonlySet<number>, i: number, все: readonly Вход[]): Итог => ходЛуча(п, шары, i, все).итог;

/** Выстрел: вход и ответ; `поворотов` — у настоящего луча, для слов карточки. */
export interface Выстрел { i: number; итог: Итог; поворотов?: number }

/** Раскладки, согласные со всеми выстрелами, — не больше `предел`. `полон` — перебор исчерпан. */
export function согласные(п: ПараметрыЯщика, выстрелы: readonly Выстрел[], все: readonly Вход[], предел: number): { раскладки: number[][]; полон: boolean } {
  const { w, h, мин, макс } = п;
  const клетки = new Int8Array(w * h).fill(-1);
  const раскладки: number[][] = [];
  const состояние = выстрелы.map((в) => лучПоКлеткам(w, h, клетки, в.i, все));
  if (состояние.some((с, k) => 'итог' in с && с.итог !== выстрелы[k]!.итог)) return { раскладки, полон: true };
  const dfs = (шаров: number, неизвестных: number): void => {
    if (раскладки.length >= предел) return;
    const упёршийся = состояние.find((с): с is { упёрся: number } => 'упёрся' in с);
    if (!упёршийся) {
      // Все выстрелы решены: оставшиеся клетки ни на один не влияют — перебираем их сочетаниями.
      const свободные: number[] = [], стоит: number[] = [];
      for (let i = 0; i < w * h; i++) { if (клетки[i] === -1) свободные.push(i); else if (клетки[i] === 1) стоит.push(i); }
      for (let k = Math.max(0, мин - шаров); k <= Math.min(макс - шаров, свободные.length); k++) {
        const выбор = Array.from({ length: k }, (_, i) => i);
        for (;;) {
          раскладки.push([...стоит, ...выбор.map((i) => свободные[i]!)].sort((a, b) => a - b));
          if (раскладки.length >= предел) return;
          let i = k - 1;
          while (i >= 0 && выбор[i] === свободные.length - k + i) i--;
          if (i < 0) break;
          выбор[i]!++;
          for (let j = i + 1; j < k; j++) выбор[j] = выбор[j - 1]! + 1;
        }
      }
      return;
    }
    const клетка = упёршийся.упёрся;
    for (const v of [0, 1] as const) {
      if (v && шаров >= макс) continue;
      if (!v && шаров + неизвестных - 1 < мин) continue;
      клетки[клетка] = v;
      const изменено: [number, Состояние][] = [];
      let годится = true;
      for (let k = 0; k < состояние.length; k++) {
        const с = состояние[k]!;
        if (!('упёрся' in с) || с.упёрся !== клетка) continue;
        изменено.push([k, с]);
        const новое = лучПоКлеткам(w, h, клетки, выстрелы[k]!.i, все);
        состояние[k] = новое;
        if ('итог' in новое && новое.итог !== выстрелы[k]!.итог) { годится = false; break; }
      }
      if (годится) dfs(шаров + v, неизвестных - 1);
      for (const [k, было] of изменено) состояние[k] = было;
      клетки[клетка] = -1;
      if (раскладки.length >= предел) return;
    }
  };
  dfs(0, w * h);
  return { раскладки, полон: раскладки.length < предел };
}

/** Сколько раскладок ищется, чтобы выбрать следующий выстрел. */
const ПРЕДЕЛ_РАСКЛАДОК = 40;

export interface ШагЯщика {
  вид: 'выстрел' | 'шары';
  /** Для выстрела — какой вход; для «шары» — не задан. */
  вход?: number;
  /** Сколько раскладок согласно с выстрелами до этого шага; `много` — поиск упёрся в предел: их не меньше. */
  согласных: number; много: boolean;
  /** Выстрел: сколько разных ответов дают здесь найденные раскладки. */
  разных?: number;
  /** Прошлый выстрел и его ответ — о нём говорит карточка. */
  прошлый?: Выстрел;
  /** «шары»: какие клетки отметить. */
  шары?: number[];
}

/**
 * План разбора от позиции человека. `шары` — настоящая раскладка (из решения движка): ответы на
 * следующие выстрелы берутся из неё, и её же разбор отмечает в конце — она всегда среди согласных.
 */
export function план(п: ПараметрыЯщика, шары: ReadonlySet<number>, сделано: readonly Выстрел[]): ШагЯщика[] {
  const все = входы(п.w, п.h);
  const выстрелы: Выстрел[] = сделано.map((в) => ({ ...в, поворотов: ходЛуча(п, шары, в.i, все).поворотов }));
  const шаги: ШагЯщика[] = [];
  for (let шаг = 0; шаг <= все.length; шаг++) {
    const { раскладки, полон } = согласные(п, выстрелы, все, ПРЕДЕЛ_РАСКЛАДОК);
    let лучший = -1, разных = 1;
    for (let i = 0; i < все.length; i++) {
      if (выстрелы.some((в) => в.i === i)) continue;
      const ответы = new Set(раскладки.map((р) => String(луч(п, new Set(р), i, все))));
      if (ответы.size > разных) { разных = ответы.size; лучший = i; }
    }
    const прошлый = выстрелы[выстрелы.length - 1];
    const общее = { согласных: раскладки.length, много: !полон, ...(прошлый ? { прошлый } : {}) };
    if (полон && лучший < 0) { шаги.push({ вид: 'шары', ...общее, шары: [...шары].sort((a, b) => a - b) }); break; }
    if (лучший < 0) {
      // Предел поиска: раскладок больше, чем найдено, а найденные ещё не расходятся — первый свободный вход.
      лучший = все.findIndex((_, i) => !выстрелы.some((в) => в.i === i));
      разных = 1;
      if (лучший < 0) { шаги.push({ вид: 'шары', ...общее, шары: [...шары].sort((a, b) => a - b) }); break; }
    }
    шаги.push({ вид: 'выстрел', вход: лучший, разных, ...общее });
    выстрелы.push({ i: лучший, ...ходЛуча(п, шары, лучший, все) });
  }
  return шаги;
}

/* ── доска с рисунка движка ─────────────────────────────────────────────── */

interface ПримитивЯщика { вид: string; x?: number; y?: number; r?: number; заливка?: number; текст?: string }

export interface ДоскаЯщика {
  /** Плитка в координатах движка: ширина = плитка × (w + 3). */
  плитка: number;
  /** Сделанные выстрелы: вход и ответ. */
  выстрелы: Выстрел[];
  /** Клетки, отмеченные человеком как шар. */
  отмечено: number[];
  /** Шары решения (после `psy_solve`), если рисунок их показывает. */
  шары: number[];
}

/**
 * Заливки и подписи рисунка (замер на мосту 17.09.2026, «w5h5m3M3»): отметка человека — круг r 14
 * заливки 8; шар, открытый решением, — заливки 9; подпись входа — текст «H», «R» или номер пары,
 * одинаковый на обоих концах.
 */
const ОТМЕТКА = 8, ШАР = 9;

/** Центр клетки с рамкой (gx 0…w+1) в координатах движка. */
export const центр = (g: number, плитка: number) => плитка * g + плитка;

export function доскаСРисунка(примитивы: readonly ПримитивЯщика[], ширина: number, п: ПараметрыЯщика): ДоскаЯщика | null {
  const плитка = ширина / (п.w + 3);
  if (!Number.isFinite(плитка) || плитка <= 0) return null;
  const все = входы(п.w, п.h);
  const клеткаПо = (x: number, y: number) => ({ gx: Math.round((x - плитка) / плитка), gy: Math.round((y - плитка) / плитка) });
  const подписи = new Map<number, string>();
  const поКлетке = new Map<number, number>();
  for (const пр of примитивы) {
    if (пр.вид === 'текст' && пр.x !== undefined && пр.y !== undefined && пр.текст) {
      const { gx, gy } = клеткаПо(пр.x, пр.y);
      const i = все.findIndex((в) => в.gx === gx && в.gy === gy);
      if (i >= 0) подписи.set(i, пр.текст.trim());
    } else if (пр.вид === 'круг' && пр.x !== undefined && пр.y !== undefined && пр.заливка !== undefined && (пр.r ?? 0) >= плитка * 0.4) {
      const { gx, gy } = клеткаПо(пр.x, пр.y);
      if (gx >= 1 && gy >= 1 && gx <= п.w && gy <= п.h) поКлетке.set((gy - 1) * п.w + (gx - 1), пр.заливка);
    }
  }
  const выстрелы: Выстрел[] = [];
  for (const [i, подпись] of подписи) {
    if (подпись === 'H' || подпись === 'R') { выстрелы.push({ i, итог: подпись }); continue; }
    if (!/^\d+$/.test(подпись)) continue;
    const пара = [...подписи].find(([j, т]) => j !== i && т === подпись);
    if (пара) выстрелы.push({ i, итог: пара[0] });
  }
  return {
    плитка,
    выстрелы: выстрелы.sort((a, b) => a.i - b.i),
    отмечено: [...поКлетке].filter(([, з]) => з === ОТМЕТКА).map(([к]) => к).sort((a, b) => a - b),
    шары: [...поКлетке].filter(([, з]) => з === ШАР).map(([к]) => к).sort((a, b) => a - b),
  };
}

