import type { Клетка } from './unruly';

export type ПриёмРазбора = 'пара' | 'зазор' | 'счёт' | 'перебор';

export interface Точка { x: number; y: number }

export interface ШагРазбора {
  приём: ПриёмРазбора;
  /** Линия, в которой сделан вывод: к ней относится объяснение. */
  линия: { вид: 'строка' | 'столбец'; номер: number };
  /** Что ставим: клетка и цвет (0 — белая, 1 — чёрная, как в тексте движка). */
  ставим: (Точка & { v: 0 | 1 })[];
  /** На что смотреть, чтобы понять вывод: клетки-основания. */
  опора: Точка[];
  /** Только у «перебора»: сколько способов дописать линию осталось. */
  вариантов?: number;
}

/**
 * ⚠️ ПЕРЕБОР ЛИНИИ ОГРАНИЧЕН 16 ПУСТЫМИ КЛЕТКАМИ: 2^16 = 65 536 раскладок — предел одного
 * шага на телефоне. Самая длинная линия нашей лестницы — 14 клеток, так что на деле предел
 * не срабатывает; он страхует от будущей ступени покрупнее.
 */
const ПРЕДЕЛ_ПЕРЕБОРА = 16;

const другой = (v: 0 | 1): 0 | 1 => (v === 0 ? 1 : 0);

interface Линия { вид: 'строка' | 'столбец'; номер: number; клетки: Точка[] }

function линииДоски(поле: Клетка[][]): Линия[] {
  const h = поле.length;
  const w = h ? поле[0]!.length : 0;
  const out: Линия[] = [];
  for (let y = 0; y < h; y++) out.push({ вид: 'строка', номер: y, клетки: Array.from({ length: w }, (_, x) => ({ x, y })) });
  for (let x = 0; x < w; x++) out.push({ вид: 'столбец', номер: x, клетки: Array.from({ length: h }, (_, y) => ({ x, y })) });
  return out;
}

const значение = (поле: Клетка[][], т: Точка): Клетка => поле[т.y]![т.x]!;

/** Следующий логический ход от текущей позиции. `null` — приёмы кончились (доска решена или стоит). */
export function следующийШаг(поле: Клетка[][]): ШагРазбора | null {
  const линии = линииДоски(поле);

  // 1–2. Угроза трёх подряд: пара и зазор.
  for (const л of линии) {
    const к = л.клетки;
    const зн = к.map((т) => значение(поле, т));
    for (let i = 0; i + 1 < зн.length; i++) {
      const a = зн[i];
      if (a === null || a !== зн[i + 1]) continue;
      const ставим: ШагРазбора['ставим'] = [];
      if (i - 1 >= 0 && зн[i - 1] === null) ставим.push({ ...к[i - 1]!, v: другой(a) });
      if (i + 2 < зн.length && зн[i + 2] === null) ставим.push({ ...к[i + 2]!, v: другой(a) });
      if (ставим.length) return { приём: 'пара', линия: { вид: л.вид, номер: л.номер }, ставим, опора: [к[i]!, к[i + 1]!] };
    }
    for (let i = 0; i + 2 < зн.length; i++) {
      const a = зн[i];
      if (a === null || a !== зн[i + 2] || зн[i + 1] !== null) continue;
      return { приём: 'зазор', линия: { вид: л.вид, номер: л.номер }, ставим: [{ ...к[i + 1]!, v: другой(a) }], опора: [к[i]!, к[i + 2]!] };
    }
  }

  // 3. Счёт: одного цвета уже половина линии.
  for (const л of линии) {
    const к = л.клетки;
    const зн = к.map((т) => значение(поле, т));
    const половина = зн.length / 2;
    if (!зн.includes(null)) continue;
    for (const v of [0, 1] as const) {
      if (зн.filter((z) => z === v).length !== половина) continue;
      return {
        приём: 'счёт', линия: { вид: л.вид, номер: л.номер },
        ставим: к.filter((_, i) => зн[i] === null).map((т) => ({ ...т, v: другой(v) })),
        опора: к.filter((_, i) => зн[i] === v),
      };
    }
  }

  // 4. Перебор линии: во всех допустимых раскладках клетка одного цвета.
  for (const л of линии) {
    const к = л.клетки;
    const зн = к.map((т) => значение(поле, т));
    const пустые = зн.flatMap((z, i) => (z === null ? [i] : []));
    if (!пустые.length || пустые.length > ПРЕДЕЛ_ПЕРЕБОРА) continue;
    const половина = зн.length / 2;
    let общее: (0 | 1 | -1)[] | null = null;
    let вариантов = 0;
    for (let m = 0; m < 1 << пустые.length; m++) {
      const z = [...зн] as (0 | 1)[];
      пустые.forEach((i, b) => { z[i] = ((m >> b) & 1) as 0 | 1; });
      if (z.filter((q) => q === 0).length !== половина) continue;
      let тройка = false;
      for (let i = 0; i + 2 < z.length; i++) if (z[i] === z[i + 1] && z[i] === z[i + 2]) { тройка = true; break; }
      if (тройка) continue;
      вариантов++;
      общее = общее ? общее.map((q, i) => (q === z[i] ? q : -1)) : [...z];
    }
    if (!общее) continue;
    const итог = общее;
    const ставим = пустые.filter((i) => итог[i] !== -1).map((i) => ({ ...к[i]!, v: итог[i] as 0 | 1 }));
    if (ставим.length) {
      return {
        приём: 'перебор', линия: { вид: л.вид, номер: л.номер }, ставим,
        опора: к.filter((_, i) => зн[i] !== null), вариантов,
      };
    }
  }
  return null;
}

/** Применить шаг к копии доски. */
export function применить(поле: Клетка[][], шаг: ШагРазбора): Клетка[][] {
  const новое = поле.map((r) => [...r]);
  for (const с of шаг.ставим) новое[с.y]![с.x] = с.v;
  return новое;
}

/** Весь разбор от позиции до конца: шаги и доска, к которой он пришёл. */
export function разобрать(поле: Клетка[][]): { шаги: ШагРазбора[]; поле: Клетка[][]; решено: boolean } {
  let текущее = поле.map((r) => [...r]);
  const шаги: ШагРазбора[] = [];
  // Каждый шаг ставит хотя бы одну клетку, поэтому шагов не больше, чем пустых клеток.
  const предел = текущее.flat().filter((c) => c === null).length;
  for (let n = 0; n < предел; n++) {
    const шаг = следующийШаг(текущее);
    if (!шаг) break;
    шаги.push(шаг);
    текущее = применить(текущее, шаг);
  }
  return { шаги, поле: текущее, решено: текущее.every((r) => r.every((c) => c !== null)) };
}

/** Клетки, которые человек поставил не так, как в решении. */
export function расхождения(поле: Клетка[][], решение: Клетка[][]): (Точка & { v: 0 | 1 })[] {
  const out: (Точка & { v: 0 | 1 })[] = [];
  поле.forEach((r, y) => r.forEach((c, x) => {
    if (c !== null && решение[y]?.[x] !== c) out.push({ x, y, v: c });
  }));
  return out;
}

/* ── доска и геометрия с рисунка движка ─────────────────────────────────── */

/**
 * Цвета клетки в палитре движка — порядок `enum` в `unruly.c`: COL_BACKGROUND, COL_GRID,
 * COL_EMPTY, COL_0, COL_0_HIGHLIGHT, COL_0_LOWLIGHT, COL_1, … Замер на мосту 17.09.2026:
 * клетка 8×8 рисуется прямоугольником 31×31 цвета 2 (пусто), 3 (белая) или 6 (чёрная).
 */
const ЦВЕТ_ПУСТО = 2;
const ЦВЕТ_БЕЛАЯ = 3;
const ЦВЕТ_ЧЁРНАЯ = 6;

/** Размер доски из параметров ступени: «8x8dt» → 8×8. */
export function размерИзПараметров(параметры: string): { w: number; h: number } | null {
  const m = /^(\d+)x(\d+)/.exec(параметры);
  return m ? { w: Number(m[1]), h: Number(m[2]) } : null;
}

/**
 * Плитка в координатах движка. У автора поле = плитка × (w + 1), клетка x начинается с
 * x·плитка + плитка/2 (`game_compute_size`, `COORD` в `unruly.c`).
 */
export function плиткаДоски(ширинаПоля: number, w: number): number {
  return ширинаПоля / (w + 1);
}

/** Прямоугольник клетки в координатах движка — для подсветки поверх холста. */
export function прямоугольникКлетки(т: Точка, плитка: number): { x: number; y: number; ш: number; в: number } {
  return { x: т.x * плитка + плитка / 2, y: т.y * плитка + плитка / 2, ш: плитка, в: плитка };
}

/** Центр клетки в координатах движка — туда жмём, чтобы поставить цвет. */
export function центрКлетки(т: Точка, плитка: number): { x: number; y: number } {
  return { x: (т.x + 1) * плитка, y: (т.y + 1) * плитка };
}

interface ПримитивПрямоугольник { вид: string; x?: number; y?: number; ш?: number; в?: number; цвет?: number }

/**
 * Доска с рисунка: для каждой клетки берём ПОСЛЕДНИЙ прямоугольник цвета клетки, накрывающий
 * её центр (движок перерисовывает клетку поверх старой). `null` — рисунок не похож на доску
 * этого размера: хотя бы одна клетка без плитки.
 */
export function доскаСРисунка(
  примитивы: readonly ПримитивПрямоугольник[], ширинаПоля: number, w: number, h: number,
): Клетка[][] | null {
  const плитка = плиткаДоски(ширинаПоля, w);
  const поле: (Клетка | undefined)[][] = Array.from({ length: h }, () => Array<Клетка | undefined>(w).fill(undefined));
  for (const п of примитивы) {
    if (п.вид !== 'прямоугольник' || п.x === undefined || п.y === undefined || п.ш === undefined || п.в === undefined) continue;
    const знач: Клетка | undefined = п.цвет === ЦВЕТ_ПУСТО ? null : п.цвет === ЦВЕТ_БЕЛАЯ ? 0 : п.цвет === ЦВЕТ_ЧЁРНАЯ ? 1 : undefined;
    if (знач === undefined) continue;
    const x0 = Math.floor((п.x - плитка / 2) / плитка);
    const y0 = Math.floor((п.y - плитка / 2) / плитка);
    for (let y = Math.max(0, y0); y < h; y++) {
      const cy = (y + 1) * плитка;
      if (cy < п.y) continue;
      if (cy >= п.y + п.в) break;
      for (let x = Math.max(0, x0); x < w; x++) {
        const cx = (x + 1) * плитка;
        if (cx < п.x) continue;
        if (cx >= п.x + п.ш) break;
        поле[y]![x] = знач;
      }
    }
  }
  if (поле.some((r) => r.some((c) => c === undefined))) return null;
  return поле as Клетка[][];
}

