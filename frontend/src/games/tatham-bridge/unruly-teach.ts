/** Объяснение шага человеческими словами. */
export function текстШага(шаг: ШагРазбора, t: (ключ: string) => string): string {
  const линия = t(шаг.линия.вид === 'строка' ? 'teachRow' : 'teachCol').replace('{n}', String(шаг.линия.номер + 1));
  const ключ = шаг.приём === 'пара' ? 'teachUnrulyPair'
    : шаг.приём === 'зазор' ? 'teachUnrulyGap'
    : шаг.приём === 'счёт' ? 'teachUnrulyCount'
    : (шаг.вариантов ?? 0) <= 1 ? 'teachUnrulyLineOne' : 'teachUnrulyLineMany';
  return t(ключ).replace('{line}', линия).replace('{k}', String(шаг.вариантов ?? 1));
}
