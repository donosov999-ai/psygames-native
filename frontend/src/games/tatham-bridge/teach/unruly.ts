/**
 * УЧИТЕЛЬ «ЧЁТ-НЕЧЕТ» — первый носитель формата `УчительРежима` (пилот, проверен Денисом
 * 17.09.2026: «обучение зашло»). Приёмы и их замер — `../unruly-teach.ts`; здесь только перевод
 * шагов в карточки: текст, рамки на доске и нажатия, которыми шаг делается.
 */
import type { Клетка } from '../unruly';
import {
  разобрать, доскаСРисунка, размерИзПараметров, расхождения, плиткаДоски, прямоугольникКлетки,
  центрКлетки, текстШага, type Точка,
} from '../unruly-teach';
import type { КарточкаУрока, РамкаУрока, УчительРежима } from './types';

export const учительUnruly: УчительРежима = {
  нуженРешатель: true,
  урок({ партия, решение, параметры }) {
    const размер = размерИзПараметров(параметры);
    if (!размер || !решение) return null;
    const { w, h } = размер;
    const поле = доскаСРисунка(партия.примитивы, партия.ширина, w, h);
    const решённое = доскаСРисунка(решение.примитивы, решение.ширина, w, h);
    if (!поле || !решённое) return null;
    const плитка = плиткаДоски(партия.ширина, w);
    const рамка = (т: Точка, вид: РамкаУрока['вид']): РамкаУрока => ({ ...прямоугольникКлетки(т, плитка), вид });
    /**
     * Цвет задаётся кнопкой (`unruly.c`, interpret_move): по пустой клетке левая даёт чёрную (1),
     * правая — белую (0); по занятой правая стирает чёрную, левая — белую.
     */
    const нажатие = (т: Точка, правой: boolean) => ({ ...центрКлетки(т, плитка), правой });

    const карточки: КарточкаУрока[] = [];
    const ошибки = расхождения(поле, решённое);
    if (ошибки.length) {
      карточки.push({
        приём: 'ошибки',
        текст: (t) => t('teachErrors'),
        рамки: ошибки.map((о) => рамка(о, 'ошибка')),
        нажатия: ошибки.map((о) => нажатие(о, о.v === 1)),
      });
    }
    const безОшибок: Клетка[][] = поле.map((r, y) => r.map((c, x) => (ошибки.some((о) => о.x === x && о.y === y) ? null : c)));
    for (const шаг of разобрать(безОшибок).шаги) {
      // Счёт и перебор опираются на ВСЮ линию — рамка вокруг линии, а не по клетке.
      const опора: РамкаУрока[] = шаг.приём === 'счёт' || шаг.приём === 'перебор'
        ? [{
            ...прямоугольникКлетки(шаг.линия.вид === 'строка' ? { x: 0, y: шаг.линия.номер } : { x: шаг.линия.номер, y: 0 }, плитка),
            ...(шаг.линия.вид === 'строка' ? { ш: плитка * w } : { в: плитка * h }),
            вид: 'опора',
          }]
        : шаг.опора.map((т) => рамка(т, 'опора'));
      карточки.push({
        приём: шаг.приём,
        текст: (t) => текстШага(шаг, t),
        рамки: [...опора, ...шаг.ставим.map((т) => рамка(т, 'ставим'))],
        нажатия: шаг.ставим.map((с) => нажатие(с, с.v === 0)),
      });
    }
    return карточки;
  },
};
