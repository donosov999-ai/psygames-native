import type { Партия } from '../play';

/** Нажатие по доске в координатах движка: так разбор делает ход. */
export interface НажатиеУрока { x: number; y: number; правой: boolean }

/** Рамка поверх доски в координатах движка. */
export interface РамкаУрока {
  x: number; y: number; ш: number; в: number;
  /** опора — на что смотреть; ставим — куда ход; ошибка — что стереть. */
  вид: 'опора' | 'ставим' | 'ошибка';
}

export interface КарточкаУрока {
  /** Объяснение шага словами правила — через словарь, на языке человека. */
  текст: (t: (ключ: string) => string) => string;
  рамки: РамкаУрока[];
  /** Чем сделать ход этой карточки. Пусто — карточка только поясняет. */
  нажатия: НажатиеУрока[];
  /** Имя приёма: повтор уже показанного приёма плеер показывает коротко. */
  приём: string;
}

export interface ВходУрока {
  /** Текущая позиция человека. */
  партия: Партия;
  /** Та же партия, решённая движком (`psy_solve`), или null, если движок решить не может. */
  решение: Партия | null;
  /** Параметры ступени, например «8x8dt». */
  параметры: string;
}

export interface УчительРежима {
  /**
   * Карточки урока от текущей позиции (без итоговой — её добавляет экран). null — доску снять
   * не удалось, разбора не будет. Функция чистая: движок она не трогает.
   */
  урок(вход: ВходУрока): КарточкаУрока[] | null;
  /** Нужен ли решатель движка. true — экран даст `решение`; режим без решателя разбор не получит. */
  нуженРешатель: boolean;
}
