/**
 * УЧИТЕЛЬ «УГАДАЙ КОД» (Guess). Выбор попыток и ответы — `../guess-teach.ts`; здесь карточки:
 * текст, рамки (лунки ряда и метки прошлого ответа) и ввод попытки.
 *
 * Ввод — как у человека (`guess.c`, interpret_move): цвет тянется из палитры в лунку, попытка
 * отправляется касанием меток своего ряда. Ход движка — только отправка, поэтому у карточки
 * `ходов: 1`: «Назад» снимает одну попытку целиком.
 */
import { доскаСРисунка, параметрыИзСтроки, план, сыгранныеПопытки, текстШага } from '../guess-teach';
import type { КарточкаУрока, РамкаУрока, УчительРежима } from './types';

export const учительGuess: УчительРежима = {
  нуженРешатель: true,
  урок({ партия, решение, параметры }) {
    const п = параметрыИзСтроки(параметры);
    if (!п || !решение) return null;
    const доска = доскаСРисунка(партия.примитивы, п);
    const решённая = доскаСРисунка(решение.примитивы, п);
    if (!доска || !решённая?.код) return null;
    const лунка = (л: { x: number; y: number; r: number }, вид: РамкаУрока['вид']): РамкаУрока =>
      ({ x: л.x - л.r - 3, y: л.y - л.r - 3, ш: 2 * л.r + 6, в: 2 * л.r + 6, вид });
    const карточки: КарточкаУрока[] = [];
    for (const шаг of план(решённая.код, сыгранныеПопытки(доска), п)) {
      const ряд = доска.ряды[шаг.номер];
      const метки = доска.метки[шаг.номер];
      if (!ряд || !метки) break;
      const прошлые = доска.метки[шаг.прошлая?.номер ?? -1];
      const опора: РамкаУрока[] = шаг.прошлая && прошлые
        ? [{ x: прошлые.x - прошлые.ш / 2 - 3, y: прошлые.y - прошлые.в / 2 - 3, ш: прошлые.ш + 6, в: прошлые.в + 6, вид: 'опора' }]
        : [];
      карточки.push({
        приём: !шаг.прошлая ? 'первая' : шаг.осталось === 1 ? 'один-код' : 'минимакс',
        текст: (t) => текстШага(шаг, t),
        рамки: [...опора, ...ряд.map((л) => лунка(л, 'ставим'))],
        нажатия: [
          ...шаг.попытка.map((цвет, i) => {
            const из = доска.палитра[цвет - 1]!;
            return { x: из.x, y: из.y, правой: false, до: { x: ряд[i]!.x, y: ряд[i]!.y } };
          }),
          { x: метки.x, y: метки.y, правой: false },
        ],
        ходов: 1,
      });
    }
    return карточки.length ? карточки : null;
  },
};
