/**
 * УЧИТЕЛЬ «КОСЫХ ЧЕРТ» (Slant). Приёмы и их замер — `../slant-teach.ts`; здесь только перевод
 * шагов в карточки: текст, рамки на доске и нажатия, которыми шаг делается.
 */
import {
  разобрать, доскаСРисунка, размерИзПараметров, расхождения, плиткаДоски, прямоугольникКлетки,
  рамкаУзла, центрКлетки, текстШага, type Косая, type Точка,
} from '../slant-teach';
import type { КарточкаУрока, РамкаУрока, УчительРежима } from './types';

export const учительSlant: УчительРежима = {
  нуженРешатель: true,
  урок({ партия, решение, параметры }) {
    const размер = размерИзПараметров(параметры);
    if (!размер || !решение) return null;
    const { w, h } = размер;
    const доска = доскаСРисунка(партия.примитивы, партия.ширина, w, h);
    const решённая = доскаСРисунка(решение.примитивы, решение.ширина, w, h);
    if (!доска || !решённая || решённая.клетки.some((r) => r.some((c) => c === 0))) return null;
    const плитка = плиткаДоски(партия.ширина, w);
    /**
     * ⚠️ РАМКА КЛЕТКИ С ОТСТУПОМ ВНУТРЬ. Числа стоят на УГЛАХ клеток: кружок радиусом 10 при плитке 32
     * (`slant.c`, draw_clue). Рамка во всю клетку проходила по центру кружка: живьём 17.09.2026 на
     * шаге «узлу нужны все» зелёные рамки закрыли саму «2». Холст рисует рамку со сдвигом 2 внутрь,
     * линией 4 и скруглением 5 (`PuzzleCanvas`, подсветка) — у внешнего края контура скругление 7.
     * При отступе 6 ближайшая к узлу точка контура на (6 + 7)·√2 − 7 ≈ 11,4 — дальше края кружка.
     * Больше отступ не нужен: при 0,25 плитки рамка сжималась в колечко 16 px и клетку не выделяла.
     */
    const отступ = 6;
    const клетка = (т: Точка, вид: РамкаУрока['вид']): РамкаУрока => {
      const р = прямоугольникКлетки(т, плитка);
      return { x: р.x + отступ, y: р.y + отступ, ш: р.ш - 2 * отступ, в: р.в - 2 * отступ, вид };
    };
    /**
     * Кнопка по клетке (`slant.c`, interpret_move): левая по пустой ставит «\», правая — «/».
     * Левая по «/» и правая по «\» стирают черту.
     */
    const поставить = (т: Точка & { v: Косая }) => ({ ...центрКлетки(т, плитка), правой: т.v === 1 });
    const стереть = (т: Точка & { v: Косая }) => ({ ...центрКлетки(т, плитка), правой: т.v === -1 });

    const карточки: КарточкаУрока[] = [];
    const ошибки = расхождения(доска.клетки, решённая.клетки);
    if (ошибки.length) {
      карточки.push({
        приём: 'ошибки',
        текст: (t) => t('teachErrors'),
        рамки: ошибки.map((о) => клетка(о, 'ошибка')),
        нажатия: ошибки.map(стереть),
      });
    }
    const безОшибок = {
      клетки: доска.клетки.map((r, y) => r.map((c, x) => (ошибки.some((о) => о.x === x && о.y === y) ? 0 : c))),
      подсказки: доска.подсказки,
    };
    for (const шаг of разобрать(безОшибок).шаги) {
      const опора: РамкаУрока[] = [
        ...(шаг.узел ? [{ ...рамкаУзла(шаг.узел, плитка), вид: 'опора' as const }] : []),
        ...(шаг.цепочка ?? []).filter((т) => !шаг.ставим.some((с) => с.x === т.x && с.y === т.y)).map((т) => клетка(т, 'опора')),
      ];
      карточки.push({
        приём: шаг.приём,
        текст: (t) => текстШага(шаг, t),
        рамки: [...опора, ...шаг.ставим.map((с) => клетка(с, 'ставим'))],
        нажатия: шаг.ставим.map(поставить),
      });
    }
    return карточки;
  },
};
