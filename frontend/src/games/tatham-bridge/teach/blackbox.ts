/**
 * УЧИТЕЛЬ «ЧЁРНОГО ЯЩИКА» (Black Box). Лучи, поиск раскладок и выбор выстрела — `../blackbox-teach.ts`;
 * здесь карточки: текст, рамки и нажатия.
 *
 * Ввод — как у человека (`blackbox.c`, interpret_move): левая по клетке рамки — выстрел, по клетке
 * поля — отметка шара (повторно — снять), по углу (0, 0) — проверка. Каждое нажатие — ход движка,
 * поэтому «Назад» отменяет по нажатию, как у остальных режимов.
 */
import { доскаСРисунка, параметрыИзСтроки, план, входы, центр, текстШага } from '../blackbox-teach';
import type { КарточкаУрока, РамкаУрока, УчительРежима } from './types';

export const учительBlackBox: УчительРежима = {
  нуженРешатель: true,
  урок({ партия, решение, параметры }) {
    const п = параметрыИзСтроки(параметры);
    if (!п || !решение) return null;
    const доска = доскаСРисунка(партия.примитивы, партия.ширина, п);
    const решённая = доскаСРисунка(решение.примитивы, решение.ширина, п);
    if (!доска || !решённая || решённая.шары.length < п.мин || решённая.шары.length > п.макс) return null;
    const { плитка } = доска;
    const все = входы(п.w, п.h);
    const клеткаРамки = (gx: number, gy: number, вид: РамкаУрока['вид']): РамкаУрока =>
      ({ x: плитка * gx + плитка / 2, y: плитка * gy + плитка / 2, ш: плитка, в: плитка, вид });
    const клеткаПоля = (к: number, вид: РамкаУрока['вид']) => клеткаРамки((к % п.w) + 1, Math.floor(к / п.w) + 1, вид);
    const нажатьКлетку = (к: number) => ({ x: центр((к % п.w) + 1, плитка), y: центр(Math.floor(к / п.w) + 1, плитка), правой: false });

    const карточки: КарточкаУрока[] = [];
    for (const шаг of план(п, new Set(решённая.шары), доска.выстрелы)) {
      const опора: РамкаУрока[] = [];
      if (шаг.прошлый) {
        const вход = все[шаг.прошлый.i]!;
        опора.push(клеткаРамки(вход.gx, вход.gy, 'опора'));
        if (typeof шаг.прошлый.итог === 'number') {
          const выход = все[шаг.прошлый.итог]!;
          опора.push(клеткаРамки(выход.gx, выход.gy, 'опора'));
        }
      }
      if (шаг.вид === 'выстрел') {
        const вход = все[шаг.вход!]!;
        карточки.push({
          приём: шаг.прошлый ? 'выстрел' : 'первый-выстрел',
          текст: (t) => текстШага(шаг, t),
          рамки: [...опора, клеткаРамки(вход.gx, вход.gy, 'ставим')],
          нажатия: [{ x: центр(вход.gx, плитка), y: центр(вход.gy, плитка), правой: false }],
        });
        continue;
      }
      // Отметить раскладку: снять лишние отметки человека, поставить недостающие, проверить.
      const цель = new Set(шаг.шары ?? []);
      const лишние = доска.отмечено.filter((к) => !цель.has(к));
      const недостаёт = [...цель].filter((к) => !доска.отмечено.includes(к));
      карточки.push({
        приём: 'шары',
        текст: (t) => текстШага(шаг, t),
        рамки: [...опора, ...лишние.map((к) => клеткаПоля(к, 'ошибка')), ...[...цель].map((к) => клеткаПоля(к, 'ставим'))],
        нажатия: [...лишние.map(нажатьКлетку), ...недостаёт.map(нажатьКлетку), { x: центр(0, плитка), y: центр(0, плитка), правой: false }],
      });
    }
    return карточки.length ? карточки : null;
  },
};
