interface ПримитивЦвета { вид: string; цвет?: number; заливка?: number; контур?: number }

/** Есть ли на рисунке цвет ошибки этого режима — в заливке, контуре, линии или тексте. */
export function естьОшибкаНаРисунке(режим: string, примитивы: readonly ПримитивЦвета[]): boolean {
  const номера = ЦВЕТ_ОШИБКИ[режим];
  if (!номера?.length) return false;
  return примитивы.some((п) => [п.цвет, п.заливка, п.контур].some((c) => c !== undefined && номера.includes(c)));
}
