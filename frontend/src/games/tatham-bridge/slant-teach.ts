/** Черта в клетке: −1 — «\», +1 — «/»; так же, как `soln` в `slant.c`. */
export type Косая = -1 | 1;
/** 0 — клетка пустая. */
export type КлеткаКосой = Косая | 0;

export interface Точка { x: number; y: number }

export interface ДоскаКосых {
  /** h строк по w клеток. */
  клетки: КлеткаКосой[][];
  /** (h + 1) строк по (w + 1) узлов; null — в узле числа нет. */
  подсказки: (number | null)[][];
}

export type ПриёмКосых = 'узел-полон' | 'узел-добор' | 'петля' | 'проверка';

export interface ШагКосых {
  приём: ПриёмКосых;
  ставим: (Точка & { v: Косая })[];
  /** Узел-основание: у «узла» — тот, по которому вывод; у «проверки» — тот, что не набрал число. */
  узел?: Точка & { число: number };
  /** Сколько черт узлу ещё нужно (у «узел-добор»). */
  нужно?: number;
  /** Клетки цепочки: её замкнула бы черта («петля») или по ней замкнулась петля в «проверке». */
  цепочка?: Точка[];
  /** «Проверка»: какую черту пробовали и чем кончилось. */
  проба?: { v: Косая; итог: 'узел' | 'петля' };
}

const размер = (д: ДоскаКосых) => ({ w: д.клетки[0]?.length ?? 0, h: д.клетки.length });

/** Клетки вокруг узла и черта, которой клетка касается узла. */
function соседиУзла(px: number, py: number, w: number, h: number): { x: number; y: number; к: Косая }[] {
  const out: { x: number; y: number; к: Косая }[] = [];
  for (const [x, y, к] of [[px - 1, py - 1, -1], [px, py - 1, 1], [px - 1, py, 1], [px, py, -1]] as const) {
    if (x >= 0 && y >= 0 && x < w && y < h) out.push({ x, y, к });
  }
  return out;
}

/** Узлы, которые соединяет черта клетки. */
function концы(x: number, y: number, v: Косая): [Точка, Точка] {
  return v === -1 ? [{ x, y }, { x: x + 1, y: y + 1 }] : [{ x: x + 1, y }, { x, y: y + 1 }];
}

/**
 * Цепочка клеток с чертами, соединяющая два узла, — поиск в ширину по уже поставленным чертам.
 * `без` — клетка, которую не считать (та, что сама замкнула бы петлю).
 */
function цепочкаМежду(клетки: КлеткаКосой[][], a: Точка, b: Точка, без?: Точка): Точка[] | null {
  const h = клетки.length, w = клетки[0]?.length ?? 0;
  const ключ = (т: Точка) => т.y * (w + 1) + т.x;
  const рёбра = new Map<number, { к: Точка; клетка: Точка }[]>();
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const v = клетки[y]![x]!;
    if (!v || (без && без.x === x && без.y === y)) continue;
    const [p, q] = концы(x, y, v);
    for (const [от, к] of [[p, q], [q, p]] as const) {
      const список = рёбра.get(ключ(от)) ?? [];
      список.push({ к, клетка: { x, y } });
      рёбра.set(ключ(от), список);
    }
  }
  const откуда = new Map<number, { от: number; клетка: Точка } | null>([[ключ(a), null]]);
  const очередь = [a];
  while (очередь.length) {
    const т = очередь.shift()!;
    if (ключ(т) === ключ(b)) {
      const путь: Точка[] = [];
      for (let к = ключ(b), шаг = откуда.get(к); шаг; шаг = откуда.get(к)) { путь.push(шаг.клетка); к = шаг.от; }
      return путь.reverse();
    }
    for (const ребро of рёбра.get(ключ(т)) ?? []) {
      if (откуда.has(ключ(ребро.к))) continue;
      откуда.set(ключ(ребро.к), { от: ключ(т), клетка: ребро.клетка });
      очередь.push(ребро.к);
    }
  }
  return null;
}

type Противоречие = { вид: 'узел'; узел: Точка & { число: number } } | { вид: 'петля'; цепочка: Точка[] };

/** Нарушено ли правило: узлу не набрать число или черты уже замкнулись в петлю. */
function противоречие(д: ДоскаКосых): Противоречие | null {
  const { w, h } = размер(д);
  for (let py = 0; py <= h; py++) for (let px = 0; px <= w; px++) {
    const число = д.подсказки[py]?.[px];
    if (число === null || число === undefined) continue;
    let касаются = 0, пустых = 0;
    for (const с of соседиУзла(px, py, w, h)) {
      const v = д.клетки[с.y]![с.x]!;
      if (!v) пустых++; else if (v === с.к) касаются++;
    }
    if (касаются > число || касаются + пустых < число) return { вид: 'узел', узел: { x: px, y: py, число } };
  }
  const корень = Array.from({ length: (w + 1) * (h + 1) }, (_, i) => i);
  const найти = (i: number): number => { while (корень[i] !== i) { корень[i] = корень[корень[i]!]!; i = корень[i]!; } return i; };
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const v = д.клетки[y]![x]!;
    if (!v) continue;
    const [p, q] = концы(x, y, v);
    const a = найти(p.y * (w + 1) + p.x), b = найти(q.y * (w + 1) + q.x);
    if (a === b) return { вид: 'петля', цепочка: [...(цепочкаМежду(д.клетки, p, q, { x, y }) ?? []), { x, y }] };
    корень[a] = b;
  }
  return null;
}

/** Узлы и петля — приёмы, которые видны на доске сразу, без пробы. */
function прямойШаг(д: ДоскаКосых): ШагКосых | null {
  const { w, h } = размер(д);
  for (let py = 0; py <= h; py++) for (let px = 0; px <= w; px++) {
    const число = д.подсказки[py]?.[px];
    if (число === null || число === undefined) continue;
    let касаются = 0;
    const пустые: { x: number; y: number; к: Косая }[] = [];
    for (const с of соседиУзла(px, py, w, h)) {
      const v = д.клетки[с.y]![с.x]!;
      if (!v) пустые.push(с); else if (v === с.к) касаются++;
    }
    if (!пустые.length) continue;
    const узел = { x: px, y: py, число };
    if (касаются === число) {
      return { приём: 'узел-полон', узел, ставим: пустые.map((с) => ({ x: с.x, y: с.y, v: (-с.к) as Косая })) };
    }
    if (касаются + пустые.length === число) {
      return { приём: 'узел-добор', узел, нужно: пустые.length, ставим: пустые.map((с) => ({ x: с.x, y: с.y, v: с.к })) };
    }
  }
  // Связность узлов по поставленным чертам — одним проходом; цепочку ищем, только когда вывод найден.
  const корень = Array.from({ length: (w + 1) * (h + 1) }, (_, i) => i);
  const найти = (i: number): number => { while (корень[i] !== i) { корень[i] = корень[корень[i]!]!; i = корень[i]!; } return i; };
  const номер = (т: Точка) => т.y * (w + 1) + т.x;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const v = д.клетки[y]![x]!;
    if (!v) continue;
    const [p, q] = концы(x, y, v);
    корень[найти(номер(p))] = найти(номер(q));
  }
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (д.клетки[y]![x]) continue;
    for (const запрет of [-1, 1] as const) {
      const [p, q] = концы(x, y, запрет);
      if (найти(номер(p)) !== найти(номер(q))) continue;
      return { приём: 'петля', ставим: [{ x, y, v: (-запрет) as Косая }], цепочка: цепочкаМежду(д.клетки, p, q) ?? [] };
    }
  }
  return null;
}

/** Применить шаг к копии доски. */
export function применить(д: ДоскаКосых, шаг: Pick<ШагКосых, 'ставим'>): ДоскаКосых {
  const клетки = д.клетки.map((r) => [...r]);
  for (const с of шаг.ставим) клетки[с.y]![с.x] = с.v;
  return { клетки, подсказки: д.подсказки };
}

/** Прямыми приёмами до упора: противоречие — чем оно кончилось, иначе null. */
function довестиДоПротиворечия(д: ДоскаКосых): Противоречие | null {
  let т = д;
  const предел = т.клетки.flat().filter((c) => !c).length + 1;
  for (let i = 0; i < предел; i++) {
    const пр = противоречие(т);
    if (пр) return пр;
    const шаг = прямойШаг(т);
    if (!шаг) return null;
    т = применить(т, шаг);
  }
  return противоречие(т);
}

/** Следующий логический ход от текущей позиции. `null` — доска решена или приёмы кончились. */
export function следующийШаг(д: ДоскаКосых): ШагКосых | null {
  const прямой = прямойШаг(д);
  if (прямой) return прямой;
  const { w, h } = размер(д);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (д.клетки[y]![x]) continue;
    for (const v of [-1, 1] as const) {
      const пр = довестиДоПротиворечия(применить(д, { ставим: [{ x, y, v }] }));
      if (!пр) continue;
      return {
        приём: 'проверка', ставим: [{ x, y, v: (-v) as Косая }], проба: { v, итог: пр.вид },
        ...(пр.вид === 'узел' ? { узел: пр.узел } : { цепочка: пр.цепочка }),
      };
    }
  }
  return null;
}

/** Весь разбор от позиции до конца: шаги и доска, к которой он пришёл. */
export function разобрать(д: ДоскаКосых): { шаги: ШагКосых[]; доска: ДоскаКосых; решено: boolean } {
  let т: ДоскаКосых = { клетки: д.клетки.map((r) => [...r]), подсказки: д.подсказки };
  const шаги: ШагКосых[] = [];
  // Каждый шаг ставит хотя бы одну черту, поэтому шагов не больше, чем пустых клеток.
  const предел = т.клетки.flat().filter((c) => !c).length;
  for (let n = 0; n < предел; n++) {
    const шаг = следующийШаг(т);
    if (!шаг) break;
    шаги.push(шаг);
    т = применить(т, шаг);
  }
  return { шаги, доска: т, решено: т.клетки.every((r) => r.every((c) => c !== 0)) };
}

/** Черты, которые человек поставил не так, как в решении. */
export function расхождения(клетки: КлеткаКосой[][], решение: КлеткаКосой[][]): (Точка & { v: Косая })[] {
  const out: (Точка & { v: Косая })[] = [];
  клетки.forEach((r, y) => r.forEach((c, x) => {
    if (c !== 0 && решение[y]?.[x] !== c) out.push({ x, y, v: c });
  }));
  return out;
}

/* ── доска и геометрия с рисунка движка ─────────────────────────────────── */

/** Размер доски из параметров ступени: «5x5de» → 5×5. */
export function размерИзПараметров(параметры: string): { w: number; h: number } | null {
  const m = /^(\d+)x(\d+)/.exec(параметры);
  return m ? { w: Number(m[1]), h: Number(m[2]) } : null;
}

/**
 * Плитка в координатах движка. У автора поле = 2·BORDER + w·плитка + 1, BORDER = плитка
 * (`slant.c`: `game_compute_size`, `COORD(x) = x·TILESIZE + BORDER`). Замер на мосту 17.09.2026:
 * 5×5 — ширина 225, плитка 32.
 */
export function плиткаДоски(ширинаПоля: number, w: number): number {
  return (ширинаПоля - 1) / (w + 2);
}

/** Прямоугольник клетки в координатах движка — для рамки поверх холста. */
export function прямоугольникКлетки(т: Точка, плитка: number): { x: number; y: number; ш: number; в: number } {
  return { x: (т.x + 1) * плитка, y: (т.y + 1) * плитка, ш: плитка, в: плитка };
}

/** Рамка вокруг узла сетки — квадрат по кружку с числом. */
export function рамкаУзла(т: Точка, плитка: number): { x: number; y: number; ш: number; в: number } {
  const сторона = плитка * 0.8;
  return { x: (т.x + 1) * плитка - сторона / 2, y: (т.y + 1) * плитка - сторона / 2, ш: сторона, в: сторона };
}

/** Центр клетки в координатах движка — туда жмём, чтобы поставить черту. */
export function центрКлетки(т: Точка, плитка: number): { x: number; y: number } {
  return { x: (т.x + 1.5) * плитка, y: (т.y + 1.5) * плитка };
}

interface ПримитивРисунка {
  вид: string;
  x?: number; y?: number; ш?: number; в?: number;
  x1?: number; y1?: number; x2?: number; y2?: number;
  текст?: string;
}

/**
 * Доска с рисунка движка.
 *   · число — текст из одной цифры 0–4 в узле сетки (`draw_text` поверх кружка);
 *   · черта — линия, середина которой лежит в клетке; наклон по знаку dx·dy: плюс — «\», минус —
 *     «/». Толстая черта рисуется тремя линиями со сдвигом на пиксель — середина у всех в той же
 *     клетке, наклон тот же.
 * `null` — рисунок не похож на доску этого размера: хотя бы у одной клетки нет своей плитки фона.
 */
export function доскаСРисунка(
  примитивы: readonly ПримитивРисунка[], ширинаПоля: number, w: number, h: number,
): ДоскаКосых | null {
  const плитка = плиткаДоски(ширинаПоля, w);
  const клетки: КлеткаКосой[][] = Array.from({ length: h }, () => Array<КлеткаКосой>(w).fill(0));
  const подсказки: (number | null)[][] = Array.from({ length: h + 1 }, () => Array<number | null>(w + 1).fill(null));
  const есть: boolean[][] = Array.from({ length: h }, () => Array<boolean>(w).fill(false));
  for (const п of примитивы) {
    if (п.вид === 'прямоугольник' && п.x !== undefined && п.y !== undefined && п.ш !== undefined && п.в !== undefined) {
      // Плитка фона клетки — квадрат около плитки. Общий фон поля и линии сетки не в счёт.
      if (п.ш < плитка * 0.9 || п.в < плитка * 0.9 || п.ш > плитка * 1.5 || п.в > плитка * 1.5) continue;
      const cx = Math.floor((п.x + п.ш / 2) / плитка) - 1, cy = Math.floor((п.y + п.в / 2) / плитка) - 1;
      if (cx >= 0 && cy >= 0 && cx < w && cy < h) есть[cy]![cx] = true;
    } else if (п.вид === 'текст' && п.x !== undefined && п.y !== undefined && п.текст !== undefined) {
      if (!/^[0-4]$/.test(п.текст)) continue;
      const px = Math.round(п.x / плитка) - 1, py = Math.round(п.y / плитка) - 1;
      if (px >= 0 && py >= 0 && px <= w && py <= h) подсказки[py]![px] = Number(п.текст);
    } else if (п.вид === 'линия' && п.x1 !== undefined && п.y1 !== undefined && п.x2 !== undefined && п.y2 !== undefined) {
      const dx = п.x2 - п.x1, dy = п.y2 - п.y1;
      if (!dx || !dy) continue;
      const cx = Math.floor((п.x1 + п.x2) / 2 / плитка) - 1, cy = Math.floor((п.y1 + п.y2) / 2 / плитка) - 1;
      if (cx >= 0 && cy >= 0 && cx < w && cy < h) клетки[cy]![cx] = dx * dy > 0 ? -1 : 1;
    }
  }
  if (есть.some((r) => r.some((e) => !e))) return null;
  return { клетки, подсказки };
}

