/** Ключи словаря разбора «Косых черт» — отдельным списком, чтобы проба сверила их на всех языках. */
export const КЛЮЧИ_РАЗБОРА_КОСЫХ = [
  'teachSlantFull', 'teachSlantNeed', 'teachSlantLoop', 'teachSlantTryClue', 'teachSlantTryLoop',
] as const;

const знак = (v: Косая) => (v === -1 ? '\\' : '/');

/** Объяснение шага человеческими словами. */
export function текстШага(шаг: ШагКосых, t: (ключ: string) => string): string {
  const v = шаг.ставим[0]?.v ?? 1;
  const число = String(шаг.узел?.число ?? '');
  if (шаг.приём === 'узел-полон') return t('teachSlantFull').split('{n}').join(число);
  if (шаг.приём === 'узел-добор') return t('teachSlantNeed').split('{n}').join(число).split('{k}').join(String(шаг.нужно ?? 0));
  const ключ = шаг.приём === 'петля' ? 'teachSlantLoop' : шаг.проба?.итог === 'узел' ? 'teachSlantTryClue' : 'teachSlantTryLoop';
  const проба = шаг.приём === 'петля' ? (-v as Косая) : (шаг.проба?.v ?? (-v as Косая));
  return t(ключ).split('{a}').join(знак(проба)).split('{b}').join(знак(v)).split('{n}').join(число);
}
