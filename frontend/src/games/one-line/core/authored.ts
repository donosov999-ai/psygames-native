import type { EdgeKind, GraphEdge, GraphVertex } from './types';

export interface AuthoredLevel {
  /** Имя фигуры — для проверок и разбора, человеку не показывается. */
  shape: string;
  vertices: GraphVertex[];
  edges: GraphEdge[];
  /** Готовый путь по вершинам: им проверяется решаемость и живёт подсказка. */
  solution: string[];
}

const v = (index: number, x: number, y: number): GraphVertex => ({ id: `v${index}`, x, y });
const e = (index: number, a: number, b: number, kind: EdgeKind): GraphEdge => (
  kind === 'single' ? { id: `e${index}`, a: `v${a}`, b: `v${b}` } : { id: `e${index}`, a: `v${a}`, b: `v${b}`, kind }
);

