/** Сколько уровней нарисовано руками. Дальше подхватывает генератор. */
export const AUTHORED_LEVEL_COUNT = AUTHORED_LEVELS.length;

/** Рисованный уровень под этот номер, или `null` — значит дальше генератор. */
export function authoredLevel(level: number): AuthoredLevel | null {
  return AUTHORED_LEVELS[Math.floor(level) - 1] ?? null;
}
