/**
 * ТОНЫ ПИНЬИНЯ: СНЯТЬ ЗНАК, ПОСТАВИТЬ ЗНАК, УЗНАТЬ ТОН.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ЯДРОМ. Упражнение спрашивает «какой тон вы услышали», а на
 * старших уровнях — «какой слог целиком». Варианты ответа = ТОТ ЖЕ слог в четырёх
 * тонах, и их надо построить: в банке лежит только правильное написание.
 * Постановка знака — не «прилепить над первой гласной», а правило с тремя
 * исключениями; ошибка в нём тихо научит человека неправильному написанию.
 *
 * ПРАВИЛО (стандартное):
 *   · есть `a` или `e` — знак на неё (они не встречаются вместе);
 *   · есть `ou` — знак на `o`;
 *   · иначе — на ПОСЛЕДНЮЮ гласную (отсюда liú, guī, huán).
 *
 * Проверяется не примерами, а прогоном по всему банку: снять знак и поставить
 * обратно обязано вернуть исходное написание для каждого из 431 слога.
 */

/** Гласные с диакритикой → (базовая буква, тон). */
const ЗНАКИ: Record<string, [string, number]> = {};
const РЯДЫ: [string, string][] = [
  ['a', 'āáǎà'], ['e', 'ēéěè'], ['i', 'īíǐì'],
  ['o', 'ōóǒò'], ['u', 'ūúǔù'], ['ü', 'ǖǘǚǜ'],
];
for (const [база, ряд] of РЯДЫ) {
  [...ряд].forEach((б, i) => { ЗНАКИ[б] = [база, i + 1]; });
}
/** Обратная таблица: (базовая буква, тон) → буква со знаком. */
const СО_ЗНАКОМ: Record<string, string[]> = Object.fromEntries(РЯДЫ.map(([б, р]) => [б, [...р]]));

/** Тон написанного слога: 1–4 по диакритике, 5 = нейтральный (знака нет). */
export function toneOf(pinyin: string): number {
  for (const с of pinyin) {
    const з = ЗНАКИ[с];
    if (з) return з[1];
  }
  return 5;
}

/** Слог без тонового знака: `zhǎo` → `zhao`. */
export function stripTone(pinyin: string): string {
  return [...pinyin].map((с) => ЗНАКИ[с]?.[0] ?? с).join('');
}

/**
 * Поставить тон на слог без знака. Тон 5 (нейтральный) оставляет слог как есть.
 * Возвращает исходную строку, если гласных нет вовсе — на мусоре не падаем.
 */
export function applyTone(base: string, tone: number): string {
  if (tone === 5 || tone < 1 || tone > 4) return base;
  const буквы = [...base];
  const гласные = буквы.map((с, i) => ({ с, i })).filter((x) => 'aeiouü'.includes(x.с));
  if (!гласные.length) return base;
  let цель = гласные[гласные.length - 1]!;                 // по умолчанию — последняя гласная
  const a = гласные.find((x) => x.с === 'a');
  const e = гласные.find((x) => x.с === 'e');
  if (a) цель = a;
  else if (e) цель = e;
  else {
    // `ou` — знак на `o`; в остальных парах правило «последняя гласная» уже верно.
    const o = гласные.find((x) => x.с === 'o');
    if (o && буквы[o.i + 1] === 'u') цель = o;
  }
  буквы[цель.i] = СО_ЗНАКОМ[цель.с]![tone - 1]!;
  return буквы.join('');
}

/**
 * Четыре написания одного слога — варианты ответа старших уровней. Порядок
 * всегда 1→4: тон и есть смысл вопроса, перемешивать надо на экране, а не здесь.
 */
export function allTones(pinyin: string): string[] {
  const база = stripTone(pinyin);
  return [1, 2, 3, 4].map((т) => applyTone(база, т));
}
