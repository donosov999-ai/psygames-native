import type { ZhSyllable } from '@/src/constants/zhToneBank.generated';
import { stripTone } from '@/src/games/chinese-tones/core/pinyin';

export type Тон = 1 | 2 | 3 | 4;
export type БанкТонов = Record<Тон, ZhSyllable[]>;

export interface СлогРазбора extends ZhSyllable {
  тон: Тон;
}

export interface КарточкаТона {
  вид: 'приём' | 'тон' | 'пара' | 'готово';
  /** Ключ словаря: язык живёт в словаре, не в коде. */
  ключ: string;
  поля?: Record<string, string | number>;
  /** Какую линию подсветить на поле или `null`. */
  тон: Тон | null;
  /** Что произнести при показе карточки — иероглифы по порядку. */
  звук: string[];
  /** Какие слова показать на поле. */
  слоги: СлогРазбора[];
}

export interface РазборТонов {
  карточки: КарточкаТона[];
  /** Слог, показанный во всех четырёх тонах (без знака тона). */
  основа: string;
}

const ТОНЫ: Тон[] = [1, 2, 3, 4];

/** Слоги банка по основе: основа → тон → слова этого тона. */
function поОснове(банк: БанкТонов): Map<string, Map<Тон, ZhSyllable[]>> {
  const out = new Map<string, Map<Тон, ZhSyllable[]>>();
  for (const тон of ТОНЫ) {
    for (const слог of банк[тон]) {
      const основа = stripTone(слог.pinyin);
      if (!out.has(основа)) out.set(основа, new Map());
      const поТону = out.get(основа)!;
      if (!поТону.has(тон)) поТону.set(тон, []);
      поТону.get(тон)!.push(слог);
    }
  }
  return out;
}

/** Основы, у которых в банке есть все четыре тона. Экспорт — для пробы. */
export function основыВоВсехТонах(банк: БанкТонов): string[] {
  return [...поОснове(банк)].filter(([, т]) => т.size === 4).map(([о]) => о);
}

/** Основы, у которых есть и второй, и третий тон. Экспорт — для пробы. */
export function основыСПарой23(банк: БанкТонов): string[] {
  return [...поОснове(банк)].filter(([, т]) => т.has(2) && т.has(3)).map(([о]) => о);
}

function случайный<T>(список: T[], rnd: () => number): T {
  return список[Math.floor(rnd() * список.length)]!;
}

export function собратьРазборТонов(
  банк: БанкТонов,
  /** Пиньинь текущего задания — его слог в разбор не берётся. */
  исключить: string | null,
  rnd: () => number = Math.random,
): РазборТонов {
  const карта = поОснове(банк);
  const безТекущего = (основа: string) =>
    ![...карта.get(основа)!.values()].some((слова) => слова.some((с) => с.pinyin === исключить));

  const полные = основыВоВсехТонах(банк).filter(безТекущего);
  const основа = случайный(полные, rnd);
  const набор: СлогРазбора[] = ТОНЫ.map((тон) => ({ ...карта.get(основа)!.get(тон)![0]!, тон }));

  const пары = основыСПарой23(банк).filter((о) => о !== основа && безТекущего(о));
  const параОснова = случайный(пары, rnd);
  const второй: СлогРазбора = { ...карта.get(параОснова)!.get(2)![0]!, тон: 2 };
  const третий: СлогРазбора = { ...карта.get(параОснова)!.get(3)![0]!, тон: 3 };

  const карточки: КарточкаТона[] = [
    { вид: 'приём', ключ: 'teachZhIntro', тон: null, звук: [], слоги: набор },
    ...набор.map((с): КарточкаТона => ({
      вид: 'тон',
      ключ: `teachZhTone${с.тон}`,
      поля: { zh: с.zh, py: с.pinyin },
      тон: с.тон,
      звук: [с.zh],
      слоги: набор,
    })),
    {
      вид: 'пара',
      ключ: 'teachZhPair23',
      поля: { a: второй.zh, pa: второй.pinyin, b: третий.zh, pb: третий.pinyin },
      тон: null,
      звук: [второй.zh, третий.zh],
      слоги: [второй, третий],
    },
    { вид: 'готово', ключ: 'teachZhDone', тон: null, звук: [], слоги: набор },
  ];
  return { карточки, основа };
}
