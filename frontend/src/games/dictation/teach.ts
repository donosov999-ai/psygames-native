import type { DictationPhrase } from '@/src/games/dictation/core/phrases';

export interface КарточкаДиктанта {
  вид: 'приём' | 'слушаем' | 'кусок' | 'застрял' | 'готово';
  ключ: string;
  поля?: Record<string, string | number>;
  /** Сколько кусков уже набрано к этой карточке (для поля). */
  набрано: number;
  /** Какой кусок сейчас (индекс) или `null`. */
  кусок: number | null;
  /** Что произнести при показе карточки. */
  звук: string[];
}

export interface РазборДиктанта {
  фраза: string;
  куски: string[];
  карточки: КарточкаДиктанта[];
}

const СЛОВ_В_КУСКЕ = 3;
const ПУНКТУАЦИЯ = /[，。！？、；：,.!?]/;

/** Режет фразу на куски. Склейка кусков (`склеить`) обязана дать исходный текст. */
export function разрезать(текст: string, язык: string): string[] {
  if (язык === 'zh') {
    const куски: string[] = [];
    let тек = '';
    for (const знак of Array.from(текст)) {
      тек += знак;
      if (ПУНКТУАЦИЯ.test(знак)) { куски.push(тек); тек = ''; }
    }
    if (тек) куски.push(тек);
    return куски;
  }
  const слова = текст.split(' ').filter((с) => с.length > 0);
  const куски: string[] = [];
  for (let i = 0; i < слова.length; i += СЛОВ_В_КУСКЕ) куски.push(слова.slice(i, i + СЛОВ_В_КУСКЕ).join(' '));
  return куски;
}

export const склеить = (куски: string[], язык: string) => куски.join(язык === 'zh' ? '' : ' ');

export function собратьРазборДиктанта(
  пул: readonly DictationPhrase[],
  язык: string,
  /** Текст текущей фразы — в разбор не берётся. */
  исключить: string | null,
  rnd: () => number = Math.random,
): РазборДиктанта | null {
  const годные = пул.filter((ф) => ф.text !== исключить);
  if (годные.length === 0) return null;
  const фраза = годные[Math.floor(rnd() * годные.length)]!.text;
  const куски = разрезать(фраза, язык);
  const карточки: КарточкаДиктанта[] = [
    { вид: 'приём', ключ: 'teachDictIntro', набрано: 0, кусок: null, звук: [] },
    { вид: 'слушаем', ключ: 'teachDictListen', набрано: 0, кусок: null, звук: [фраза] },
    ...куски.map((к, i): КарточкаДиктанта => ({
      вид: 'кусок',
      ключ: 'teachDictChunk',
      поля: { i: i + 1, c: к },
      набрано: i,
      кусок: i,
      звук: [к],
    })),
    { вид: 'застрял', ключ: 'teachDictStuck', набрано: куски.length, кусок: null, звук: [] },
    { вид: 'готово', ключ: 'teachDictDone', набрано: куски.length, кусок: null, звук: [] },
  ];
  return { фраза, куски, карточки };
}
