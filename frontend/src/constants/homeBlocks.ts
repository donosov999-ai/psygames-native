/**
 * БЛОКИ ГЛАВНОЙ — РЕЕСТР С УСТОЙЧИВЫМИ ИМЕНАМИ.
 *
 * Просьба Дениса 13.09.2026: «состав главной надо ещё редактировать, какие блоки
 * там показывать». Чтобы этим можно было управлять файлом, у блоков должны быть
 * ИМЕНА — иначе редактор пришлось бы привязывать к номерам строк в разметке, и
 * первая же правка экрана сделала бы файл настроек враньём.
 *
 * 🔴 ФАЙЛ УМЕЕТ ТОЛЬКО УБРАТЬ БЛОК, НО НЕ ПОКАЗАТЬ ЕГО НАСИЛЬНО.
 * У каждого блока есть свои условия: «Рекомендуем сегодня» не рисуется, пока
 * рекомендаций нет; «Сегодня» — пока сегодня ничего не сыграно. Если бы файл мог
 * включать блок поверх этих условий, человек увидел бы заголовок над пустотой —
 * ровно тот дефект, который в этом проекте уже ловили («заголовок над пустотой
 * читается как поломка», комментарий у блока рекомендаций).
 *
 * Поэтому правило одно: блок показывается, если ЕГО СОБСТВЕННЫЕ УСЛОВИЯ выполнены
 * И он не выключен файлом.
 */

/** Порядок — сверху вниз, как на экране. Он же порядок в редакторе. */
export const БЛОКИ_ГЛАВНОЙ = [
  { id: 'цель_дня', подпись: 'Цель дня' },
  { id: 'сегодня', подпись: 'Сегодня — что сыграно за сутки' },
  { id: 'рекомендации', подпись: 'Рекомендуем сегодня' },
  { id: 'практики', подпись: 'Практики дня: зарядка, пауза, вызов' },
  { id: 'любимые_разделы', подпись: 'Любимые разделы и лента игр' },
] as const;

export type ИдБлокаГлавной = (typeof БЛОКИ_ГЛАВНОЙ)[number]['id'];

const ВСЕ_ИД: readonly string[] = БЛОКИ_ГЛАВНОЙ.map((б) => б.id);

export function естьТакойБлок(id: string): boolean {
  return ВСЕ_ИД.includes(id);
}

/**
 * Показывать ли блок. `список` — из файла настроек профиля; `null`/`undefined`
 * означает «файл про главную ничего не говорил», то есть показываем всё.
 */
export function показыватьБлок(id: ИдБлокаГлавной, список: readonly string[] | null | undefined): boolean {
  if (!список) return true;
  return список.includes(id);
}
