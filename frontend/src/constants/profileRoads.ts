/** Все девять городов подряд — они же часть общего набора для чередования. */
export const ROAD_LIST: number[] = Object.values(PROFILE_ROADS);

/** Через сколько уровней своя картина возвращается как веха. */
export const MILESTONE_EVERY = 5;

/**
 * Своя ли это веха для профиля. Первый уровень — всегда своя: человек только что
 * выбрал профиль, и первое, что он видит за труд, должно быть про НЕГО.
 */
export function isOwnCityLevel(level: number): boolean {
  return level <= 1 || level % MILESTONE_EVERY === 0;
}

/** Город профиля; `undefined` — у профиля своего города нет, идёт общий набор. */
export function profileRoad(id?: string): number | undefined {
  return id ? PROFILE_ROADS[id] : undefined;
}
