/**
 * ДОСКА ГОЛОВОЛОМКИ ТЭТХЭМА, НАРИСОВАННАЯ НАШИМ SVG.
 *
 * Движок отдаёт список примитивов — прямоугольники, линии, круги, многоугольники,
 * текст. Здесь они превращаются в SVG и масштабируются под ширину экрана. Нажатие
 * пересчитывается обратно в ЕГО координаты и уходит в движок: правила знает он.
 *
 * ⚠️ Цвета берём из ЕГО палитры, но фон подменяем нашим: у него он чисто белый, а у
 * нас тема бывает тёмной. Индекс 0 в его палитре — всегда фон (`frontend_default_colour`).
 */
import React, { useCallback, useEffect, useRef } from 'react';
import { View, StyleSheet } from 'react-native';
import Svg, { Rect, Line, Circle, Polygon, Text as SvgText, G, Defs, ClipPath } from 'react-native-svg';
import type { Партия, Примитив, Жест } from '@/src/games/tatham-bridge/play';

interface Props {
  партия: Партия;
  /** Доступная ширина в точках — доска впишется в неё целиком. */
  ширина: number;
  /**
   * 🔴 ДОСКА ВПИСЫВАЕТСЯ В КВАДРАТ, А НЕ ТОЛЬКО В ШИРИНУ.
   *
   * 📍 Денис 11.09.2026 по контактному листу всех сорока: «дизайн плавает, центры
   * квадратов особенно: то там по высоте, то там, то шире, то уже — надо к единому
   * стандарту прийти». Так и было: масштаб считался ТОЛЬКО по ширине, и высота
   * получалась какая выйдет.
   *
   * Замер 11.09.2026 по первым ступеням: ровно квадратных досок 31 из 40, остальные
   * девять вытянуты до 1,43 («Обзор» 320×224). Пока мерили по ширине, эти девять
   * занимали по высоте меньше остальных, и доска на экране прыгала от игры к игре.
   *
   * Теперь носитель даёт КВАДРАТ, доска вписывается по обеим сторонам и стоит в его
   * середине: место под доску у всех сорока одно и то же, а разной остаётся только
   * сама доска.
   */
  высота?: number;
  /**
   * 🔴 ЖЕСТ ЦЕЛИКОМ, А НЕ ОДИН ТАП. Пять головоломок из сорока (Untangle, Pegs,
   * Rectangles, Loopy, Slant) без протяжки не играются вовсе: узел надо тащить,
   * прямоугольник растягивать, линию вести. Родные оболочки автора шлют ровно эти
   * три события, поэтому и мы шлём их, а не «нажатие» одним махом.
   */
  onЖест: (x: number, y: number, жест: Жест, правой: boolean) => void;
  фон: string;
}

export default function PuzzleCanvas({ партия, ширина, высота, onЖест, фон }: Props) {
  const { ширина: W, высота: H, палитра, примитивы } = партия;
  /**
   * 🔴 ПОТОЛОК УВЕЛИЧЕНИЯ — ЕДИНСТВЕННОЕ, ЧТО МЕШАЛО «МОЗАИКЕ» ЗАПОЛНИТЬ ЭКРАН.
   *
   * Замер 10.09.2026 по всем сорока на первой ступени лестницы, телефон 360 точек
   * (под доску остаётся 328): доля ширины, которую занимает доска, —
   *   «Мозаика» 62 %, следующая за ней «Цепная реакция» 93 %, остальные 94–100 %.
   * Одна игра из тридцати восьми выпадала на треть экрана, и не из-за своей доски,
   * а из-за потолка: её поле 128 точек против 190–450 у всех прочих, поэтому в
   * потолок 1.6 упиралась только она.
   *
   * 2.4 подобрано замером, а не на глаз: при нём «Мозаика» даёт 94 % — ровно как
   * соседи, — и ни одна другая игра потолка больше не касается (следующая по
   * мелкости доска 190 точек вписывается уже при 1.73).
   *
   * ⚠️ На широком экране рост ограничен не здесь. Вызывающий экран сам зажимает
   * `ширина = Math.min(width - 32, 420)`, и без этого потолок пришлось бы считать
   * заново: 3×3 на всю ширину монитора — это клетки в ладонь.
   */
  const МАКС_УВЕЛИЧЕНИЕ = 2.4;
  const поле = высота ?? ширина;
  const масштаб = W > 0 && H > 0 ? Math.min(ширина / W, поле / H, МАКС_УВЕЛИЧЕНИЕ) : 1;

  const цвет = useCallback((i: number): string => {
    if (i < 0) return 'transparent';
    if (i === 0) return фон;                       // фон — наш, не его белый
    return палитра[i] ?? '#888';
  }, [палитра, фон]);

  /** Экранная точка → координата его поля. */
  const точка = useCallback((e: any): [number, number] => {
    const { locationX, locationY } = e.nativeEvent;
    return [locationX / масштаб, locationY / масштаб];
  }, [масштаб]);

  /**
   * ⚠️ Во ВРЕМЯ протяжки `locationX` считается от того элемента, где жест начался, —
   * это ровно наш холст, поэтому пересчёт один и тот же на всех трёх событиях.
   */
  /**
   * 🔴 ДОЛГОЕ НАЖАТИЕ — ЭТО ПРАВАЯ КНОПКА. БЕЗ НЕЁ 15 ИГР ИЗ 40 НЕ РЕШАЮТСЯ.
   *
   * 📍 Отчёт Дениса 10.09.2026, «Магниты»: доска заполнена целиком, 103 хода,
   * подсказки красные, «в конце ничего не происходит». Так и должно было быть:
   * в «Магнитах» часть половинок домино обязана остаться ПУСТОЙ, а пустую ставят
   * правой кнопкой. У нас `правой` было зашито `false` — второго действия не
   * существовало, и головоломка была нерешаема в принципе.
   *
   * ЗАМЕР по мосту 10.09.2026: правая кнопка даёт СВОЙ результат у пятнадцати —
   * Black Box, Dominosa, Keen, Light Up, Loopy, Magnets, Mosaic, Palisade,
   * Signpost, Singles, Slant, Tents, Towers, Twiddle, Unruly.
   *
   * КАК УСТРОЕНО. Нажатие не отправляется сразу: ждём `ДОЛГОЕ_МС`.
   *   · палец сдвинулся раньше — это протяжка, шлём левую с исходной точки;
   *   · время вышло без движения — шлём ПРАВУЮ нажатие+отпускание;
   *   · отпустил раньше — обычный левый тычок.
   * Иначе кнопку пришлось бы выбирать до того, как ясно, что за жест.
   */
  const ДОЛГОЕ_МС = 420;
  const ПОРОГ_СДВИГА = 8;                       // точек поля, дальше — это уже протяжка
  const жестРеф = useRef<{
    x: number; y: number; начат: boolean; правой: boolean; таймер: any;
    посX: number; посY: number;
  } | null>(null);

  const снятьТаймер = useCallback(() => {
    const ж = жестРеф.current;
    if (ж?.таймер) { clearTimeout(ж.таймер); ж.таймер = null; }
  }, []);

  const начать = useCallback((e: any) => {
    const [x, y] = точка(e);
    снятьТаймер();
    const ж = { x, y, начат: false, правой: false, таймер: null as any, посX: x, посY: y };
    жестРеф.current = ж;
    ж.таймер = setTimeout(() => {
      if (!жестРеф.current || жестРеф.current !== ж || ж.начат) return;
      ж.начат = true; ж.правой = true;
      onЖест(ж.x, ж.y, 'нажал', true);
    }, ДОЛГОЕ_МС);
  }, [точка, onЖест, снятьТаймер]);

  const вести = useCallback((e: any) => {
    const ж = жестРеф.current; if (!ж) return;
    const [x, y] = точка(e);
    if (!ж.начат) {
      if (Math.abs(x - ж.x) < ПОРОГ_СДВИГА && Math.abs(y - ж.y) < ПОРОГ_СДВИГА) return;
      снятьТаймер();
      ж.начат = true;                            // сдвинулся раньше срока — обычная протяжка
      onЖест(ж.x, ж.y, 'нажал', false);
    } else if (ж.правой) {
      /**
       * 🔴 МЕДЛЕННАЯ ПРОТЯЖКА ТЕРЯЛА ХОД. Палец подержали на месте дольше 420 мс —
       * мы уже объявили жест правой кнопкой; а он после этого ПОЕХАЛ, и вся протяжка
       * уходила правой. Замер 11.09.2026: «Колышки» 0 ходов из 48 и «Прямоугольники»
       * 0 из 48 такой протяжкой против 1 и 34 обычной. То есть неторопливый человек
       * просто не мог сыграть.
       *
       * Чиним по факту движения: отпускаем правую ТАМ ЖЕ, где нажали (движок видит
       * щелчок в одну точку — своё законное второе действие), и заново начинаем
       * жест ЛЕВОЙ от исходной точки. Отменить уже отправленное нажатие нельзя, а
       * так человек получает ровно то, что делал пальцем.
       */
      onЖест(ж.x, ж.y, 'отпустил', true);
      ж.правой = false;
      onЖест(ж.x, ж.y, 'нажал', false);
    }
    ж.посX = x; ж.посY = y;
    onЖест(x, y, 'ведёт', ж.правой);
  }, [точка, onЖест, снятьТаймер]);

  const отпустить = useCallback((e: any) => {
    const ж = жестРеф.current; if (!ж) return;
    const [x, y] = точка(e);
    снятьТаймер();
    if (!ж.начат) onЖест(ж.x, ж.y, 'нажал', false);   // короткий тычок
    onЖест(x, y, 'отпустил', ж.правой);
    жестРеф.current = null;
  }, [точка, onЖест, снятьТаймер]);

  /**
   * 🔴 ОБРЫВ ЖЕСТА — НЕ ОТПУСКАНИЕ. Раньше `onResponderTerminate` звал тот же
   * `отпустить`, и прерванное касание превращалось в ХОД: обработчик дописывал
   * «нажал» за короткий тычок и тут же «отпустил». Трасса из аудита Кодекса
   * 12.09.2026 (40 головоломок, `gesture-contract.json`): «cancel до таймера:
   * down-left → up-left» — то есть щелчок там, где человек жест ОТМЕНИЛ.
   * Обрыв случается не в экзотике: его шлёт система, когда жест перехватывает
   * прокрутка или уходит страница.
   *
   * Что делаем — по тому, что движок УЖЕ получил, а не по общему правилу:
   * · жест не начинался (`!начат`) — движку не ушло ничего, и мы не шлём ничего.
   *   Это ровно тот случай, где рождался лишний щелчок.
   * · жест начался — «нажал» уже ушло, и бросить нельзя: движок останется с
   *   зажатой кнопкой, а следующее касание придёт не по порядку. Отпускаем в
   *   ПОСЛЕДНЕЙ точке протяжки, а не в начальной: движок эту точку уже видел,
   *   и отпускание в начале означало бы щелчок там, откуда палец давно ушёл.
   *
   * ⚠️ Отменить уже отправленное нажатие нельзя — у авторских движков нет такой
   * команды. Поэтому починка убирает ЛИШНЕЕ действие, а не выдумывает отмену.
   */
  const оборвать = useCallback(() => {
    const ж = жестРеф.current; if (!ж) return;
    снятьТаймер();
    if (ж.начат) onЖест(ж.посX, ж.посY, 'отпустил', ж.правой);
    жестРеф.current = null;
  }, [onЖест, снятьТаймер]);

  useEffect(() => снятьТаймер, [снятьТаймер]);

  return (
    <View
      /**
       * 🔴 ВЫДЕЛЕНИЕ ТЕКСТА КРАЛО ЖЕСТ — ОТСЮДА «СЛОМАНА ИГРОВАЯ МЕХАНИКА».
       *
       * 📍 Снимок Дениса 10.09.2026, «Чёт-нечет»: поперёк экрана голубая полоса и
       * синяя точка над подсказкой. Это не артефакт отрисовки — это ВЫДЕЛЕНИЕ
       * ТЕКСТА и его ползунок. Приложение на iOS и Android — Tauri, то есть
       * WebView; долгое нажатие там начинает выделять текст и ЗАБИРАЕТ жест себе.
       * До холста он не доходит, и головоломка перестаёт отвечать на протяжку.
       *
       * ⚠️ Задеты все, где надо вести пальцем: Untangle, Pegs, Loopy, Pearl,
       * Tracks, Slant, Galaxies… Замер по мосту: сам движок при этом ЦЕЛ — из
       * сорока открываются все сорок, на программный тычок отвечают тридцать два.
       * Ломалось именно наше касание, а не его правила.
       *
       * `userSelect: 'none'` снимает выделение, `touchAction: 'none'` — прокрутку
       * и масштаб щипком под пальцем на доске. Свойства веб-специфичные, поэтому
       * идут через `as any`: react-native-web их пробрасывает, нативная сборка
       * молча пропускает.
       */
      style={[styles.box, { width: W * масштаб, height: H * масштаб },
        { userSelect: 'none', WebkitUserSelect: 'none', WebkitTouchCallout: 'none', touchAction: 'none' } as any]}
      onStartShouldSetResponder={() => true}
      onMoveShouldSetResponder={() => true}
      onResponderGrant={начать}
      onResponderMove={вести}
      onResponderRelease={отпустить}
      onResponderTerminate={оборвать}
    >
      <Svg width={W * масштаб} height={H * масштаб} viewBox={`0 0 ${W} ${H}`}>
        <Rect x={0} y={0} width={W} height={H} fill={фон} />
        {собрать(примитивы, цвет)}
      </Svg>
    </View>
  );
}

/**
 * 🔴 ОБРЕЗКА СОБИРАЕТСЯ В ГРУППЫ, А НЕ ПРОПУСКАЕТСЯ.
 *
 * Раньше `K`/`U` выбрасывались с пометкой «на нашем рисовании не сказываются». Замер
 * 11.09.2026: ими пользуются ДВАДЦАТЬ ЧЕТЫРЕ движка из сорока (у «Раскраски карты»
 * 300 обрезок на 1252 примитива). Автор перерисовывает клетку несколько раз, и каждый
 * раз обрезка оставляет от рисунка узкую полоску; без неё поздний кусок ложится
 * целиком и закрашивает то, что нарисовано раньше.
 *
 * 📍 Видно было так: в «Мостах» кружки островов стояли ПУСТЫЕ. Число мостов движок
 * рисует (`T 24 24 16 257 1 2`), но следующий белый круг того же острова ложился
 * поверх цифры. А число в «Мостах» — это вся головоломка.
 *
 * Пары `K`…`U` у автора не вложены, но стек здесь всё равно: он стоит копейку, а
 * непарная `U` без него уронила бы сборку.
 */
function собрать(примитивы: Примитив[], цвет: (i: number) => string) {
  type Узел = React.ReactElement | null;
  const корень: Узел[] = [];
  const стек: { обрезка: { x: number; y: number; ш: number; в: number }; дети: Узел[] }[] = [];
  const куда = () => (стек.length ? стек[стек.length - 1].дети : корень);
  примитивы.forEach((п, k) => {
    if (п.вид === 'обрезка') { стек.push({ обрезка: п, дети: [] }); return; }
    if (п.вид === 'снять') {
      const слой = стек.pop();
      if (!слой) return;                       // непарная `U` — молча пропускаем
      const id = `обр${k}`;
      куда().push(
        <G key={`g${k}`} clipPath={`url(#${id})`}>
          <Defs>
            <ClipPath id={id}>
              <Rect x={слой.обрезка.x} y={слой.обрезка.y} width={слой.обрезка.ш} height={слой.обрезка.в} />
            </ClipPath>
          </Defs>
          {слой.дети}
        </G>,
      );
      return;
    }
    куда().push(рисовать(п, k, цвет));
  });
  // Обрезка, не закрытая до конца рисунка: содержимое всё равно показываем.
  while (стек.length) { const слой = стек.pop()!; корень.push(...слой.дети); }
  return корень;
}

function рисовать(п: Примитив, k: number, цвет: (i: number) => string) {
  switch (п.вид) {
    case 'прямоугольник':
      return <Rect key={k} x={п.x} y={п.y} width={п.ш} height={п.в} fill={цвет(п.цвет)} />;
    case 'линия':
      return <Line key={k} x1={п.x1} y1={п.y1} x2={п.x2} y2={п.y2}
        stroke={цвет(п.цвет)} strokeWidth={п.толщина ?? 1} strokeLinecap="round" />;
    case 'круг':
      return <Circle key={k} cx={п.x} cy={п.y} r={п.r}
        fill={цвет(п.заливка)} stroke={цвет(п.контур)} strokeWidth={1} />;
    case 'многоугольник':
      return <Polygon key={k} points={пары(п.точки)}
        fill={цвет(п.заливка)} stroke={цвет(п.контур)} strokeWidth={1} />;
    case 'текст': {
      // его выравнивание: 0 — влево, 1 — по центру, 2 — вправо (ALIGN_HLEFT/HCENTRE/HRIGHT)
      const якорь = (п.выравнивание & 1) ? 'middle' : (п.выравнивание & 2) ? 'end' : 'start';
      /**
       * 🔴 ВЕРТИКАЛЬНОЕ ВЫРАВНИВАНИЕ ТОЖЕ ЛЕЖИТ В ЭТОМ ЧИСЛЕ, И ОНО ЧИТАЛОСЬ НЕ ВСЁ.
       * `ALIGN_VCENTRE` — это бит `0x100`, и почти весь текст коллекции приходит с
       * ним: замер 11.09.2026 — выравнивание 257 (0x101) у «Мостов», «Лишних чисел»,
       * судоку и прочих. Мы читали только младшие два бита, поэтому цифра ставилась
       * базовой линией на середину клетки — то есть заметно ВЫШЕ центра.
       * Сдвиг 0,35 от кегля — обычная доля от базовой линии до середины строчных.
       */
      const посередине = (п.выравнивание & 0x100) !== 0;
      return <SvgText key={k} x={п.x} y={п.y + (посередине ? п.размер * 0.35 : 0)}
        fontSize={п.размер} fill={цвет(п.цвет)}
        textAnchor={якорь} fontWeight="600">{п.текст}</SvgText>;
    }
    default:
      return null;
  }
}

const пары = (т: number[]): string => {
  const out: string[] = [];
  for (let i = 0; i + 1 < т.length; i += 2) out.push(`${т[i]},${т[i + 1]}`);
  return out.join(' ');
};

const styles = StyleSheet.create({
  box: { alignSelf: 'center' },
});
