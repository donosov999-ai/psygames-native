import { Animated } from 'react-native';

/**
 * Доводчик значения для «сочных» элементов.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ. Правило «в щадящем режиме то же самое, но мгновенно»
 * нужно четырём компонентам juice сразу. Если писать его в каждом, пятый
 * компонент, дописанный по образцу соседнего, тихо вернёт пружину обратно —
 * ровно так уже возвращались настенные часы в играх.
 *
 * ПОЧЕМУ НЕ ПРОСТО «НЕ ДВИГАТЬ». Пружина — это отскок и перелёт через цель,
 * то есть самое укачивающее, что тут есть. А сам факт «кнопка вдавилась»,
 * «карта повернулась лицом» — это ответ интерфейса на действие, без него
 * непонятно, засчиталось нажатие или нет. Поэтому в щадящем режиме конечное
 * состояние выставляется сразу: смысл остаётся, движения нет.
 */
export function settle(
  value: Animated.Value,
  to: number,
  reduced: boolean,
  cfg: { friction?: number; tension?: number } = {},
) {
  if (reduced) {
    // stopAnimation важен: настройку могли включить посреди летящей пружины,
    // и без остановки она продолжит тянуть значение поверх выставленного.
    value.stopAnimation();
    value.setValue(to);
    return;
  }
  Animated.spring(value, { toValue: to, useNativeDriver: true, ...cfg }).start();
}
