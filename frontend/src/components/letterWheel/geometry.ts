/**
 * 🔴 КРУГ БУКВ — ГЕОМЕТРИЯ ОТДЕЛЬНО ОТ РАЗМЕТКИ.
 *
 * 📍 ПРОСЬБА ДЕНИСА 06.09.2026, дословно: «надо круг с буквами для введения у
 * них перенять, им удобнее вводить». Речь про «Море слов» и Zen Word: буквы
 * стоят по окружности, палец ведёт линию, слово собирается по пути.
 *
 * Почему геометрия здесь, а не в компоненте: попадание пальца в букву — это
 * ЧИСЛО, и проверять его надо числом. В разметке его не проверить ничем, а
 * ошибиться в нём легко: у нас уже был случай, когда доска считалась
 * `size / 8` и восьмая клетка уезжала на новую строку.
 */

export interface ТочкаБуквы { x: number; y: number; }

/**
 * Точки букв на окружности. Первая — СВЕРХУ, дальше по часовой стрелке:
 * так читает глаз, и так же устроены образцы жанра.
 *
 * `size` — сторона квадрата, в который вписан круг; центр в его середине.
 * `radius` — расстояние от центра до центра буквы (не до края круга).
 */
export function точкиКруга(n: number, size: number, radius?: number): ТочкаБуквы[] {
  const k = Math.max(1, Math.floor(n));
  const c = size / 2;
  const r = radius ?? size * 0.34;
  if (k === 1) return [{ x: c, y: c }];
  const out: ТочкаБуквы[] = [];
  for (let i = 0; i < k; i++) {
    const угол = -Math.PI / 2 + (2 * Math.PI * i) / k;
    out.push({ x: c + r * Math.cos(угол), y: c + r * Math.sin(угол) });
  }
  return out;
}

/**
 * Какая буква под пальцем. `-1` — ни одна.
 *
 * ⚠️ Радиус попадания БОЛЬШЕ нарисованной буквы: палец толще курсора, и по
 * норме цель нажатия не меньше 44 точек. Но не больше половины расстояния
 * между соседями — иначе одно касание попадало бы сразу в две буквы, и
 * ведение линии стало бы случайным.
 */
export function радиусПопадания(n: number, size: number, radius?: number): number {
  const точки = точкиКруга(n, size, radius);
  if (точки.length < 2) return size / 2;
  const d = Math.hypot(точки[1]!.x - точки[0]!.x, точки[1]!.y - точки[0]!.y);
  return Math.min(Math.max(22, size * 0.11), d / 2);
}

export function буквоПод(точки: readonly ТочкаБуквы[], x: number, y: number, радиус: number): number {
  let лучшая = -1;
  let ближе = Infinity;
  for (let i = 0; i < точки.length; i++) {
    const d = Math.hypot(точки[i]!.x - x, точки[i]!.y - y);
    if (d <= радиус && d < ближе) { ближе = d; лучшая = i; }
  }
  return лучшая;
}

/**
 * 🔴 ШАГ ВЕДЕНИЯ — ОДНО ПРАВИЛО НА ВСЕ СПОСОБЫ ВВОДА (палец и тап).
 *
 * Три исхода, и каждый нужен:
 *   · та же буква или пусто → линия не меняется, возвращается ОНА ЖЕ;
 *   · предпоследняя буква → стираем хвост (так исправляют, не отпуская палец);
 *   · новая буква → линия удлиняется.
 *
 * ⚠️ Повторно взять УЖЕ ВЗЯТУЮ букву нельзя: каждая плитка круга — одна штука,
 * как в образце. Слово с двумя одинаковыми буквами берёт две разные плитки.
 * Тот же приём, что в филвордах: [[правило шага живёт в ядре]].
 */
export function шагЛинии(линия: readonly number[], буква: number): number[] {
  if (буква < 0) return линия as number[];
  const n = линия.length;
  if (n > 0 && линия[n - 1] === буква) return линия as number[];
  if (n > 1 && линия[n - 2] === буква) return линия.slice(0, n - 1);
  if (линия.indexOf(буква) >= 0) return линия as number[];
  return [...линия, буква];
}

/** Слово, набранное линией. */
export function словоИзЛинии(буквы: readonly string[], линия: readonly number[]): string {
  return линия.map((i) => буквы[i] ?? '').join('');
}
