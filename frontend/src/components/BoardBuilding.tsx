import React from 'react';
import { View, Text, StyleSheet, ActivityIndicator } from 'react-native';
import { useTheme } from '@/src/contexts/ThemeContext';
import { useLanguage } from '@/src/contexts/LanguageContext';

/** Сколько сборка должна реально идти, чтобы назвать её долгой. */
export const SLOW_MS = 2000;

/** Что показываем про идущую сборку. Всё здесь — измеренное, ничего выдуманного. */
export interface BuildStatus {
  /** Номер идущего шага, с единицы. */
  step: number;
  /** Сколько шагов может понадобиться всего (ПОТОЛОК, а не обещание: сборка вправе
   *  кончиться раньше, поэтому долей работы это число не является). */
  steps: number;
  /** С начала сборки уже прошло больше SLOW_MS — по часам, а не по уровню. */
  slow: boolean;
}

/**
 * Отдать экрану кадр перед тем, как занять поток.
 *
 * `requestAnimationFrame` срабатывает ПЕРЕД отрисовкой кадра, поэтому одного его
 * мало: вернув управление в rAF, мы снова заняли бы поток до того, как кадр
 * доехал до экрана. `setTimeout` внутри rAF уходит в следующую задачу — то есть
 * уже ПОСЛЕ того, как этот кадр нарисован.
 */
export function nextFrame(): Promise<void> {
  return new Promise<void>((resolve) => {
    const queue = () => { setTimeout(resolve, 0); };
    if (typeof requestAnimationFrame === 'function') requestAnimationFrame(queue);
    else queue();
  });
}

/**
 * Прогон генерации ПО ШАГАМ, с кадром перед каждым.
 *
 * Шаг остаётся синхронным (переписывать решатель в корутину — совсем другая работа),
 * но между шагами поток отпускается, и экран успевает и нарисоваться, и обновить
 * строку. Отсюда же берётся честный счётчик: `step` — ровно тот номер, который
 * сейчас крутится в цикле генератора.
 *
 * ⚠️ `show` зовётся ПЕРЕД `frame`, а `frame` — ПЕРЕД `step`. Любая другая
 * расстановка возвращает исходный баг: строка появляется, когда работа уже сделана.
 *
 * `now` передаётся снаружи, потому что в играх часы игровые (`gameNow`), а не
 * настенные, и потому что гейт обязан уметь двигать их руками.
 */
export async function runSteps<T>(o: {
  /** Потолок числа шагов. */
  steps: number;
  /** Один шаг работы. Возвращает ЛУЧШЕЕ, что есть после него. */
  step: (n: number) => T;
  /** Хватит, дальше не пробуем. */
  enough: (best: T) => boolean;
  /** Показать состояние человеку. */
  show: (s: BuildStatus) => void;
  /** Отдать кадр. */
  frame: () => Promise<void>;
  /** Часы. */
  now: () => number;
  /** Порог «долго». */
  slowAfterMs?: number;
}): Promise<T> {
  const steps = Math.max(1, o.steps);
  const slowAfter = o.slowAfterMs ?? SLOW_MS;
  const started = o.now();
  let best!: T;
  for (let n = 1; n <= steps; n++) {
    o.show({ step: n, steps, slow: o.now() - started >= slowAfter });
    await o.frame();
    best = o.step(n);
    if (o.enough(best)) break;
  }
  return best;
}

/**
 * Строка ожидания. Спиннер + человеческий текст, БЕЗ шкалы процентов.
 *
 * Второй строкой добавляется «уровень сложный, доска подбирается» — но только
 * когда сборка правда затянулась, иначе это была бы заранее заготовленная
 * жалоба, а не сообщение о происходящем.
 */
export default function BoardBuilding({ status, tint }: { status: BuildStatus; tint?: string }) {
  const { colors } = useTheme();
  const { t } = useLanguage();
  const color = tint ?? colors.primary;
  return (
    <View style={styles.wrap} testID="board-building" accessibilityLiveRegion="polite">
      <ActivityIndicator size="large" color={color} />
      <Text style={[styles.line, { color: colors.text }]}>{t('boardBuilding')}</Text>
      {status.slow && (
        <Text style={[styles.hint, { color: colors.textSecondary }]}>{t('boardBuildingSlow')}</Text>
      )}
      {status.steps > 1 && (
        <Text style={[styles.hint, { color: colors.textSecondary }]}>
          {t('boardBuildingStep').replace('{n}', String(status.step)).replace('{max}', String(status.steps))}
        </Text>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  wrap: { flex: 1, alignItems: 'center', justifyContent: 'center', gap: 12, padding: 24 },
  line: { fontSize: 16, fontWeight: '700', textAlign: 'center' },
  hint: { fontSize: 13, textAlign: 'center', lineHeight: 19 },
});
