/**
 * 🔴 НАДО ЛИ СООБЩИТЬ НАВЕРХ О ПОБЕДЕ. Вынесено из компонента, чтобы это можно было
 * проверить пробой: дефект жил ровно здесь и на экране был невидим.
 *
 * ЧТО БЫЛО (отчёт 63e3ef0d, «Решил задачу на следующий уровень не переходит»):
 * победа сообщалась ТОЛЬКО когда экран открыт шагом зарядки (`preset`). В обычной
 * партии ветка молча возвращалась, а окно «уровень собран» с кнопкой «дальше» рисует
 * МАРШРУТ и рисует его как раз по этому сообщению. Уровень при этом засчитывался —
 * строка «Пройдено N/50» росла, — а перехода не было. Снаружи: «решил, а дальше некуда».
 *
 * ⚠️ ОДНОКРАТНОСТЬ ПО УРОВНЮ, А НЕ ОДНИМ ФЛАГОМ НА ВСЮ ЖИЗНЬ ЭКРАНА. В зарядке
 * уровень один, логического флага хватало. В обычной партии человек за одно
 * монтирование проходит уровень за уровнем, и `true` заглушил бы все победы, кроме
 * первой. Поэтому возвращается ИМЯ победы «режим:уровень».
 *
 * @returns имя победы, если о ней надо сообщить; иначе null
 */
export function победаКОтправке({готово,уровень,режим,занято,ужеОтправлено}:{
  готово:boolean;уровень:number|null;режим:string;занято:boolean;ужеОтправлено:string;
}):string|null {
  if(!готово||занято)return null;
  if(уровень===null)return null;           // свободная игра — не уровень, сообщать нечего
  const отметка=`${режим}:${уровень}`;
  return отметка===ужеОтправлено?null:отметка;
}
