import React from 'react';
import { View, StyleSheet } from 'react-native';

/**
 * Сторона квадрата под доску. Считается от ширины экрана, но не больше 420: дальше
 * доска перестаёт читаться как единое поле, взгляд бегает по краям.
 */
export function сторонаДоски(ширинаЭкрана: number): number {
  return Math.min(ширинаЭкрана - 32, 420);
}

export default function PlayBoard({ ширинаЭкрана, children, testID }: {
  ширинаЭкрана: number;
  children: React.ReactNode;
  testID?: string;
}) {
  const сторона = сторонаДоски(ширинаЭкрана);
  return (
    <View testID={testID ?? 'play-board'} style={[styles.квадрат, { width: сторона, height: сторона }]}>
      {children}
    </View>
  );
}

const styles = StyleSheet.create({
  квадрат: { alignItems: 'center', justifyContent: 'center' },
});
