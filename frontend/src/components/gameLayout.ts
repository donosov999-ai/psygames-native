/**
 * ГЕОМЕТРИЯ ЭКРАНА ИГРЫ — ОДИН ИСТОЧНИК НА ВСЕ РАЗДЕЛЫ.
 *
 * 🔴 ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Денис 11.09.2026: «чтобы они без тебя могли потом
 * выравнивать, чтобы ядро позволяло это, чтобы были каркасы, которые настраиваются
 * центрально и тюнингуются под нужды на месте».
 *
 * До него каждый раздел выводил числа сам: `src/games/attention/layout.ts` и
 * `src/games/search/layout.ts` завели свои `GUTTER_BOTH`, `MIN_TAP`, `ANSWER_BAR_H`
 * — и в комментарии «Поиска» прямо записано: «числа взяты у соседей, а не придуманы…
 * свои 118 или 124 развели бы разделы между собой, и скачок вернулся бы, только
 * реже». То есть два чата ВРУЧНУЮ держали константы в согласии. Это и расходится
 * первым: правку внесут в один модуль, второй останется старым, и никто не заметит,
 * потому что каждый по-своему зелёный.
 *
 * ⚠️ ЧТО ЗДЕСЬ ЛЕЖИТ, А ЧТО НЕТ.
 * Здесь — только то, что задаёт КАРКАС и что обязано совпадать у всех: высоты полос
 * над полем и под ним, из них — верх и центр поля. Вид, цвета и внутренняя вёрстка
 * экрана остаются у раздела: сводить их значило бы запретить играм отличаться.
 *
 * ⚠️ ЧИСЛА ЗАМЕРЕНЫ, А НЕ НАЗНАЧЕНЫ. Замер 11.09.2026 на собранном вебе, окно
 * 390×844, прибор `search-chat/geom.mjs` (чат «Поиск»).
 */

/** Высота шапки: кнопка паузы, заголовок, правый слот. Замер: 58 на всех экранах. */
export const ШАПКА = 58;

/**
 * 🔴 ПОЛОСА ПОКАЗАТЕЛЕЙ ЗАНИМАЕТ МЕСТО ВСЕГДА, ДАЖЕ ПУСТАЯ.
 *
 * Замер 11.09.2026: 61 у большинства и 13 у «Тортов» с «Пиццей», где счётчиков мало
 * и полоса схлопывалась. Отсюда верх поля 71 вместо 119 и центр поля 458 вместо 482
 * — то есть содержимое двух экранов стояло на 24 точки выше соседних.
 *
 * Резерв — тот же приём, которым «Поиск» держит низ (`reserveBottom`): место под
 * необязательный элемент занимается всегда, чтобы поле не прыгало между
 * упражнениями «Зарядки». Цена — 48 точек пустоты на двух экранах из восьмидесяти.
 */
export const ПОЛОСА_ПОКАЗАТЕЛЕЙ = 61;

/**
 * Ряд служебных действий («Отменить», «Подсказка», «Заново»). Замер: 54–56.
 *
 * ⚠️ ОН НЕ ВСЕГДА НАД ПОЛЕМ, И В ЭТОМ БЫЛА ПОЛОВИНА РАЗБРОСА. Правило каркаса
 * (`GameShell`, «низ принадлежит ОТВЕТУ; там, где ответа кнопками нет, низ отдаётся
 * служебному») требует от игр с ответом ТАПОМ ПО ПОЛЮ объявлять `bottom="actions"`.
 * Семь экранов его не объявили, ряд стоял над полем и опускал его: верх 173 вместо
 * 119, центр 509/516 вместо 482.
 */
export const РЯД_ДЕЙСТВИЙ = 56;

/**
 * Высота полосы ответа внизу. 120 — согласованное число «Внимания» и «Поиска»
 * (`ANSWER_BAR_H`, `SEARCH_BAR_H`), сведённое ими вручную 07–09.09.2026.
 * Теперь оно живёт здесь, а разделы берут его отсюда.
 */
export const ПОЛОСА_ОТВЕТА = 120;

/** Норма попадания пальцем (Material); её же держит `tap-target-audit`. */
export const ПАЛЕЦ = 48;

/** Отступы слота ответа: FAB_GUTTER 66 слева и справа. */
export const ПОЛЯ_ОТВЕТА = 132;

/**
 * Верх поля — там, где кончается всё, что каркас рисует НАД ним.
 * Замер после починок 11.09.2026: 119 у всех измеренных экранов (58 + 61).
 */
export const ВЕРХ_ПОЛЯ = ШАПКА + ПОЛОСА_ПОКАЗАТЕЛЕЙ;

/**
 * Центр поля на экране заданной высоты — то, к чему экран равняет содержимое.
 *
 * 🔴 НОРМА ВЕРТИКАЛИ (решение координатора 11.09.2026 по замеру чата «Поиск»):
 * содержимое стоит по центру СВОЕГО поля, отклонение меньше `ДОПУСК`.
 *
 * Почему правилом, а не числом: чат «Поиск» намерил медиану 438 и честно написал,
 * что это «то, что есть, а не то, что решено». Медиана меняется вместе с составом
 * экранов и не переносится на другие размеры окна. Центр поля считается из высот и
 * верен на любом экране.
 *
 * @param высотаОкна высота окна в точках (390×844 → 844)
 * @param снизу      сколько занято под полем: полоса ответа, тулбар, свой резерв
 */
export function центрПоля(высотаОкна: number, снизу = 0): number {
  return ВЕРХ_ПОЛЯ + (высотаОкна - ВЕРХ_ПОЛЯ - снизу) / 2;
}

/**
 * Допуск нормы. 40 — порог, которым чат «Поиск» считал свои классы; на нём же стоит
 * гейт. ⚠️ Ужимать его можно только вместе с замером: сначала показать, что экраны
 * держатся, потом опускать число — иначе гейт краснеет на живых экранах.
 */
export const ДОПУСК = 40;

/**
 * Сколько места экран хочет зарезервировать под полем, не рисуя там ничего.
 *
 * 🔴 ЭТО И ЕСТЬ «ТЮНИНГ НА МЕСТЕ». Раздел «Поиск» завёл такой резерв у себя, чтобы
 * пять его игр без полосы ответа стояли там же, где шестая с полосой, — и в
 * «Зарядке» поле не прыгало между перемешанными пробами. Разброс центра внутри
 * раздела стал 0 вместо 118.
 *
 * Теперь считать его надо ОТСЮДА, а не от собственной полосы: раздел объявляет, что
 * у него внизу, а число берёт из ядра.
 */
export const резервПодПолосуОтвета = (естьПолоса: boolean) => (естьПолоса ? 0 : ПОЛОСА_ОТВЕТА);
