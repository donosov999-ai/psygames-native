/**
 * GameAuxAction — СЛУЖЕБНОЕ действие игры. Одна кнопка на всё приложение.
 *
 * 🔴 ЗАЧЕМ КОМПОНЕНТ, А НЕ ПРОСТО «ПЕРЕНЕСТИ КНОПКИ». Правило «служебное — в
 * шапку» без общего элемента живёт ровно до следующего экрана: новый автор
 * рисует свою кнопку своим стилем и кладёт куда удобнее. Проверить такое
 * можно только по словам в разметке, а гейты по словам в этом проекте уже
 * шесть раз краснели на ПРАВИЛЬНОЙ правке (переименовал обработчик — упал).
 *
 * Поэтому служебное действие — это ТИП, а не подпись. Раз тип один:
 *   · его видно в разметке структурно (гейт `slot-meaning` ищет компонент,
 *     а не слова «отмена»/«перемешать» — переименование его не сломает);
 *   · его видно в живом DOM по `data-testid="game-aux"` — значит браузерный
 *     аудит может проверить не «написано ли», а «нарисовано ли и ГДЕ»;
 *   · попадание пальцем задано здесь один раз (48×48 — норма Material для
 *     того, по чему стучат в игре), и его нельзя случайно потерять в одной
 *     игре из сорока трёх.
 *
 * ЧТО СЧИТАЕТСЯ СЛУЖЕБНЫМ (граница проведена в GameShell, здесь — коротко):
 * действие, которое трогает ИГРУ помимо ответа — тратит ресурс (подсказка,
 * перетасовка), откатывает ЗАСЧИТАННЫЙ ход, заново подаёт задание, обрывает
 * сеанс. Правка собственного черновика ответа («Сброс», «стереть букву»)
 * служебной НЕ является: она не трогает ничего, кроме ещё не сданного ответа.
 */
import React from 'react';
import { View, Text, StyleSheet, TouchableOpacity } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useTheme } from '@/src/contexts/ThemeContext';
import { useLanguage } from '@/src/contexts/LanguageContext';
import { useLadderLock } from '@/src/contexts/PlayerLevelContext';

export interface GameAuxActionProps {
  /** Иконка Ionicons. Без неё кнопка остаётся текстовой — так у «СТОП». */
  icon?: React.ComponentProps<typeof Ionicons>['name'];
  /** Подпись — УЖЕ переведённая (`t('btn_undo')`), не ключ. */
  label: string;
  /**
   * Остаток ресурса прямо на кнопке.
   *
   * ЗАЧЕМ. Ресурс, о котором узнаёшь только когда он кончился, читается как
   * поломка, а не как правило (замечание по маджонгу). Цена видна ДО нажатия.
   */
  count?: number;
  /** Цвет иконки — игры красят своё действие в свой акцент. */
  tint?: string;
  /**
   * Действие обрывает сеанс («СТОП»). Красная рамка и подпись: это не отмена
   * хода, это конец упражнения, и спутать их нельзя.
   */
  danger?: boolean;
  disabled?: boolean;
  /**
   * Ключ лестницы замков (`hint`, `undo`, …). Если приём ещё не открыт по
   * уровню игрока, кнопка рисуется ЗАПЕРТОЙ, а не прячется.
   *
   * 🔴 ПОЧЕМУ НЕ ПРЯТАТЬ. Пропавшая кнопка читается как «в этой игре такого
   * нет» — и приём, открывшийся через два уровня, игрок просто не заметит.
   * Видимый замок работает наоборот: он сам объясняет, что впереди есть куда
   * идти, и делает это бесплатно. Ради этого лестница и заводилась.
   *
   * ⚠️ Без ключа поведение прежнее — ни одна из сорока трёх игр не меняется,
   * пока её автор не назовёт приём.
   */
  ladder?: string;
  onPress: () => void;
}

/** Красный «СТОП» — один и тот же во всех упражнениях с сеансом. */
const DANGER = '#f43f5e';

export function GameAuxAction({ icon, label, count, tint, danger, disabled, ladder, onPress }: GameAuxActionProps) {
  const { colors } = useTheme();
  const { t } = useLanguage();
  const { заперт, порог } = useLadderLock(ladder);
  const [сказали, setСказали] = React.useState(false);

  const fg = заперт ? colors.textSecondary : (danger ? DANGER : colors.text);
  return (
    <TouchableOpacity
      testID="game-aux"
      accessibilityRole="button"
      // Счётчик уходит в подпись для скринридера: «Перемешать · 3» вслух
      // читается как одно слово с числом, а не как два соседних элемента.
      accessibilityLabel={
        заперт ? `${label} — ${t('ladderLockedAt').replace('{n}', String(порог))}`
        : count === undefined ? label : `${label} — ${count}`
      }
      accessibilityState={{ disabled: !!disabled || заперт }}
      // Запертую кнопку НЕ отключаем: нажатие обязано ответить «откроется на
      // уровне N». Отключённая кнопка на нажатие молчит, и замок превращается
      // в поломку — ровно та жалоба, что уже приходила про кончившийся ресурс.
      disabled={disabled && !заперт}
      onPress={заперт ? () => setСказали((v) => !v) : onPress}
      activeOpacity={0.8}
      style={[
        styles.btn,
        {
          backgroundColor: colors.surface,
          borderColor: заперт ? colors.border : (danger ? DANGER : colors.border),
          opacity: заперт ? 0.55 : (disabled ? 0.4 : 1),
        },
      ]}
    >
      {заперт
        ? <Ionicons name="lock-closed" size={18} color={colors.textSecondary} />
        : (icon ? <Ionicons name={icon} size={18} color={tint ?? fg} /> : null)}
      <Text style={[styles.label, { color: fg }]} numberOfLines={1}>
        {заперт || count === undefined ? label : `${label} · ${count}`}
      </Text>
      {/* Ответ на нажатие по замку: чем именно он откроется. */}
      {сказали && порог !== null ? (
        <View style={[styles.tip, { backgroundColor: colors.text }]}>
          <Text style={[styles.tipText, { color: colors.background }]} numberOfLines={2}>
            {t('ladderLockedAt').replace('{n}', String(порог))}
          </Text>
        </View>
      ) : null}
    </TouchableOpacity>
  );
}

/**
 * Ряд служебных действий — то, что кладут в `GameShell.headerActions`.
 *
 * Перенос по строкам (`flexWrap`) обязателен: при системном крупном шрифте и в
 * длинных языках (de/fr) три пилюли в 390 pt не встают, а ужатая до многоточия
 * подпись служебного действия — худшее, что тут может быть.
 */
export function GameAuxBar({ children }: { children: React.ReactNode }) {
  return <View style={styles.bar}>{children}</View>;
}

const styles = StyleSheet.create({
  /**
   * Пузырь ответа на нажатие по замку. Абсолютный и БЕЗ влияния на поток: ряд
   * служебных кнопок и так вылезал за край на узких экранах, и всплывающая
   * подпись не имеет права добавлять туда ширину.
   */
  tip: {
    position: 'absolute',
    top: '100%',
    left: 0,
    marginTop: 6,
    maxWidth: 190,
    paddingHorizontal: 9,
    paddingVertical: 6,
    borderRadius: 8,
    zIndex: 20,
  },
  tipText: { fontSize: 12, fontWeight: '600' },
  /**
   * Зазор 6, а не 8: при переносе на вторую строку каждая лишняя пара точек
   * между кнопками отнимается у поля дважды — по горизонтали и по вертикали.
   * Сами кнопки не трогаем: 48×48 держит гейт нажатий (репорт Вали 01.09.2026
   * «цифры 7-8-9 не работают» — они уезжали под нижний край экрана).
   */
  /**
   * 🔴 `flexWrap` БЕЗ ОГРАНИЧЕНИЯ ШИРИНЫ НЕ ПЕРЕНОСИТ НИЧЕГО.
   *
   * Перенос здесь стоял с самого начала — и не работал ни разу. Замер 02.09.2026
   * на экране 360 px: ряд «Отменить · Подсказка · Перемешать» занял 456 px, то
   * есть вылез за край на 76, и вместе с ним поехала вся страница вбок. Отсюда и
   * отчёт Дениса «поехали кнопки верх тулбара».
   *
   * Причина — правило флексбокса, а не ошибка в числах. Оба места, куда каркас
   * кладёт этот ряд, сами строчные (`flexDirection: 'row'`). Ребёнок строки НЕ
   * растягивается по ширине родителя: его ширина берётся по содержимому. А раз
   * ширина всегда равна содержимому — переносить нечего, и `flexWrap` молчит,
   * сколько бы кнопок в ряд ни встало.
   *
   * `maxWidth: '100%'` даёт ряду границу — ту самую, относительно которой перенос
   * и считается. `flexShrink` с `minWidth: 0` разрешают строке ужаться (без нуля
   * потомок с текстом не даёт себя сжать).
   */
  /**
   * 🔴 У РЯДА ДОЛЖНА БЫТЬ ШИРИНА, А НЕ ТОЛЬКО ПОТОЛОК.
   *
   * Замер 03.09.2026 на симуляторе iPhone 17 Pro Max (440 точек — самый широкий
   * телефон): три кнопки «Отменить · Подсказка · Перемешать» не влезли, и третья
   * ушла за правый край. Если режет ТАМ, режет везде.
   *
   * `flexWrap` без границы ширины не переносит НИЧЕГО: ребёнок строки меряется по
   * содержимому, а раз ширина всегда равна содержимому — переносить нечего. Здесь
   * стоял `maxWidth: '100%'` — «не шире родителя», но ширину он не задаёт, и ряд
   * оставался шириной со своё содержимое. Пара «`width: '100%'` + `maxWidth: '100%'`»
   * и есть то, что обычно имеют в виду, когда пишут одно `maxWidth`.
   *
   * ⚠️ `flexShrink: 1` убран нарочно: он давал ряду ужиматься ВМЕСТО переноса, а
   * кнопки внутри не сжимаются (у детей flex по умолчанию `flexShrink: 0`) — то
   * есть ряд становился уже своего содержимого, и лишнее просто вылезало.
   */
  bar: {
    flexDirection: 'row', alignItems: 'center', justifyContent: 'center',
    gap: 6, rowGap: 6, flexWrap: 'wrap',
    /**
     * ⚠️ `flexGrow: 1` + `flexBasis: 0`, а НЕ `width: '100%'`.
     *
     * Замер на симуляторе 03.09.2026 (iPhone 17 Pro Max, 440 точек): с процентной
     * шириной ряд всё равно выходил за края — и не только справа. Левый край кнопки
     * «Отменить» стоял на 19 точках при отступе контейнера 68, то есть содержимое
     * шире коробки и, центрируясь (`justifyContent: 'center'`), вылезало СИММЕТРИЧНО
     * с обеих сторон. Процент считается от родителя, и на нём легко промахнуться
     * мимо его внутренних отступов.
     *
     * Пара «расти на всё свободное + базис ноль» задаёт ширину по ОСТАВШЕМУСЯ месту
     * главной оси — ровно то, что нужно переносу: есть от чего переносить.
     * `minWidth: 0` обязателен, иначе потомок с текстом не даёт коробке ужаться.
     */
    flexGrow: 1, flexBasis: 0, minWidth: 0, maxWidth: '100%',
  },
  // 48×48 — норма Material для того, по чему стучат в игре (тот же порог, что
  // у `scripts/tap-target-audit.mjs` во втором проходе). Радиус 999 = пилюля:
  // служебное не должно выглядеть как кнопка ответа, а те у нас прямоугольные.
  btn: {
    minWidth: 48,
    minHeight: 48,
    borderRadius: 999,
    borderWidth: 1.5,
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'center',
    gap: 6,
    paddingHorizontal: 14,
    /**
     * 🔴 КНОПКА ОБЯЗАНА СЖИМАТЬСЯ. Третий заход по одному дефекту.
     *
     * Замер на симуляторе 03.09.2026 (iPhone 17 Pro Max, 440 точек): «Перемешать»
     * срезан правым краем экрана, а «Отменить» начинается на 20 точках при отступе
     * контейнера 68 — ряд шире коробки и вылезает с ОБЕИХ сторон.
     *
     * Две попытки чинить это шириной РЯДА (`width: '100%'`, затем `flexGrow: 1 +
     * flexBasis: 0`) не помогли: обе проверены пересборкой под симулятор, кадр не
     * изменился. Значит переносу мешает не ряд.
     *
     * Здесь причина, до которой я дошёл не сразу: у детей flex по умолчанию
     * `flexShrink: 0`. Три кнопки с фиксированным содержимым НЕ УМЕЛИ стать уже, и
     * ряду было нечего ужимать — он просто вылезал. Теперь кнопка сжимается, а
     * подпись внутри укорачивается многоточием (`numberOfLines={1}` уже стоял).
     *
     * ⚠️ `minWidth: 48` держит палец: сжиматься можно, но не до непопадаемости.
     */
    flexShrink: 1,
  },
  /** Подпись ужимается вместе с кнопкой: без `minWidth: 0` текст не даёт себя сжать. */
  label: { fontSize: 14, fontWeight: '700', flexShrink: 1, minWidth: 0 },
});

export default GameAuxAction;
