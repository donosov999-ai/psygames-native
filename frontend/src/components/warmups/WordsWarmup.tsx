/**
 * СОСТАВ СЛОВЕСНОЙ ЗАРЯДКИ. Просьба Дениса 06.09.2026, дословно: «надо зарядку
 * по словам собрать на 5-10 минут (надо по идее выбор сделать в зарядках по
 * времени, чтобы понять, какую серию запускают)».
 *
 * ⚠️ ПОЧЕМУ СОСТАВ ЖИВЁТ ЗДЕСЬ, А НЕ В ЭКРАНЕ РАЗВИЛКИ. Гейт `hub-badge` требует,
 * чтобы экран развилки не хранил НИКАКИХ маршрутов: ровно из-за такой копии
 * значок на главной разъехался с содержимым (замер 05.09.2026 — 6 развилок из
 * 16). Состав зарядки — тоже маршруты, и держать его в экране значит вернуть
 * второй источник правды. Экран получает готовую карточку.
 *
 * ⚠️ ПОЧЕМУ ТРИ УПРАЖНЕНИЯ, А НЕ ВСЕ ИЗ РАЗВИЛКИ. Зарядка — это разные ЗАХОДЫ к
 * слову, а не обход каталога: собрать слово из букв (анаграммы), найти слово
 * глазами в поле букв (филворды), достать слово из памяти по признаку
 * (беглость). Четвёртое упражнение того же вида дало бы длину без нового навыка.
 */
import React from 'react';
import { WarmupCard } from '@/src/components/WarmupCard';
import { usePersistentLevel } from '@/src/hooks/usePersistentLevel';
import {
  ШАГ_АНАГРАММЫ_СЕК, ШАГ_ФИЛВОРДЫ_СЕК, ШАГ_БЕГЛОСТЬ_СЕК,
} from '@/src/services/chessWarmup';

export const АКЦЕНТ_СЛОВА = '#8b5cf6';

export function WordsWarmup() {
  /** Уровни — из СОБСТВЕННЫХ лестниц упражнений: человек продолжает с места. */
  const анаграммы = usePersistentLevel('anagrams');
  const корректура = usePersistentLevel('proofreading');
  return (
    <WarmupCard
      темы={[
        { game_id: 'anagrams', game_route: '/games/anagrams', секунд: ШАГ_АНАГРАММЫ_СЕК, уровень: анаграммы.level },
        { game_id: 'proofreading', game_route: '/games/proofreading', секунд: ШАГ_ФИЛВОРДЫ_СЕК, уровень: корректура.level, настройки: { mode: 'fillwords' } },
        // «Беглость речи» без лестницы: там круг задаётся длительностью, а не уровнем.
        { game_id: 'phonemic_fluency', game_route: '/games/phonemic-fluency', секунд: ШАГ_БЕГЛОСТЬ_СЕК, уровень: 1 },
      ]}
      titleKey="wordsWarmupTitle"
      descKey="wordsWarmupDesc"
      ярлык="слова"
      accent={АКЦЕНТ_СЛОВА}
      loading={!анаграммы.loaded || !корректура.loaded}
    />
  );
}
