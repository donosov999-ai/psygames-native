/**
 * ГЕЙТ СБОРКИ: каждый уровень судоку решаем и решается ЕДИНСТВЕННЫМ образом.
 *
 * Требование Дениса 07.08: решатель должен не просто выдавать сложность, а гарантировать
 * при каждой сборке, что (1) решение есть и (2) оно одно. На второе Валя жаловалась не раз:
 *   «Игра в текущем моменте имеет несколько вариантов победы»
 *   «Вот сейчас в итоге произошла ошибка, а могло быть оба варианта»
 * Такой пазл нечестен вдвойне: человек ставит цифру второго решения и получает «ошибку»,
 * потому что ввод сверяется с зашитым решением.
 *
 * Как это проверяется дёшево. Если пазл добирается ЛОГИКОЙ (лестница техник), то каждый
 * шаг вынужден — второму решению взяться неоткуда, единственность выходит по построению.
 * Дорогой перебор countSolutions нужен только там, где конкретной попытке логики не
 * хватило. Sandwich теперь распространяет суммы по маскам и обязан оставаться на
 * логическом пути; отдельная проверка ниже не даст ему тихо вернуться к fallback.
 *
 * Проверяются ВСЕ уровни от 1 до LAST_LEVEL (57 — последний в игре) — по пазлу на уровень.
 *
 * Живёт в src/__gates__, а НЕ в src/__tests__: прогон стоит ~210 с (генерация 52 досок,
 * плюс перебор там, где логики не хватило). В общем наборе это сделало бы локальный
 * `npm test` невыносимым — он идёт 5 с. Запускается отдельно: `npm run test:levels`,
 * и этим же шагом в CI на каждой сборке.
 */
import { levelConfig, countSolutions, Variant } from '@/src/services/sudoku-core';
import { generateLogical, gradePuzzle, TECHNIQUE_TIER } from '@/src/services/sudoku-grade';

/**
 * 🔴 БЫЛО 52 С ПОЯСНЕНИЕМ «дальше правило не меняется». Это неправда: с 54-го
 * идёт ThermoCage — термометр И клетки-суммы на одной доске, отдельное правило со
 * своим решателем. Четыре последних уровня игры не проверяла ни одна сборка, и
 * именно там нашлись доски, которые логикой не берутся вовсе. Проверяем до конца.
 */
const LAST_LEVEL = 80;
const LEVELS = Array.from({ length: LAST_LEVEL }, (_, i) => i + 1);

describe('гейт: все уровни судоку решаемы и решение единственно', () => {
  jest.setTimeout(600_000);

  it.each(LEVELS)('уровень %i', (level) => {
    const cfg = levelConfig(level);
    const r = generateLogical(level, cfg.blanks, cfg.N, cfg.BR, cfg.BC, cfg.variant, { budgetMs: 2200 });
    const { puzzle, solution } = r.gen;

    // L38–41 обязаны идти новым логическим путём. Без этого sandwich незаметно
    // откатится к прежнему «число дырок + перебор», хотя общий гейт останется зелёным.
    if (cfg.variant === 'sandwich') {
      expect(r.fellBack).toBe(false);
      expect(r.grade.tier).toBeGreaterThanOrEqual(TECHNIQUE_TIER.sandwich_sum);
    }

    // 1. Доска вообще получилась: не пустая и не полностью заполненная.
    let blanks = 0;
    for (let i = 0; i < cfg.N; i++) for (let j = 0; j < cfg.N; j++) if (puzzle[i][j] === 0) blanks++;
    expect(blanks).toBeGreaterThanOrEqual(cfg.size === 6 ? 8 : 24);
    expect(blanks).toBeLessThan(cfg.N * cfg.N);

    // 2. Открытые клетки совпадают с решением — иначе честный ход считался бы ошибкой.
    for (let i = 0; i < cfg.N; i++) for (let j = 0; j < cfg.N; j++) {
      if (puzzle[i][j] !== 0) expect(puzzle[i][j]).toBe(solution[i][j]);
    }

    // 3. Решение единственно. Логический путь даёт это по построению (каждый шаг вынужден);
    //    где логики не хватило — досчитываем перебором.
    const solvedByLogic = r.grade.solved && r.grade.tier < TECHNIQUE_TIER.guess;

    // 3a. Если решатель дошёл логикой — он обязан прийти РОВНО к эталонному решению.
    //     Это ловит неверный пруннинг: с ним решатель «решит» чужую сетку и объявит
    //     единственность там, где её нет. Без этой сверки гарантия была бы на слово.
    if (solvedByLogic && r.grade.grid) {
      for (let i = 0; i < cfg.N; i++) expect(r.grade.grid[i]).toEqual(solution[i]);
    }

    if (!solvedByLogic) {
      const eff: Variant = (cfg.variant === 'jigsaw' && !r.gen.regions)
        || (cfg.variant === 'thermo' && !r.gen.thermo)
        || (cfg.variant === 'arrow' && !r.gen.arrow) ? 'none' : cfg.variant;
      const n = countSolutions(
        puzzle.map((row) => [...row]), cfg.N, cfg.BR, cfg.BC, eff, r.gen.regions,
        2, { steps: 60_000 }, r.gen.thermo, r.gen.arrow,
      );
      expect(n).toBe(1);
    }
  });
});

describe('гейт: сложность растёт по уровням, а не стоит', () => {
  jest.setTimeout(600_000);

  // Берём фазы, которые решатель понимает уверенно, включая новый sandwich-путь.
  const PROBES = [8, 12, 19, 28, 33, 37, 41];

  /**
   * 🔴 ПОВТОРОВ ПЯТЬ, А НЕ ОДИН — И ЭТО НЕ ПЕРЕСТРАХОВКА.
   *
   * Ступень измеряется на СГЕНЕРИРОВАННОЙ доске, то есть это случайная величина.
   * Замер 27.08.2026, по пять досок на уровень:
   *   L8  none      [1,1,1,1,1]
   *   L12 diagonal  [2,2,3,3,3]
   *   L19 hyper     [2,3,3,3,3]
   *   L28 antiking  [2,3,3,3,4]   ← разброс в ДВЕ ступени на одном уровне
   *   L33 evenodd   [4,4,4,4,5]
   *   L37 kropki    [4,4,4,4,4]
   *   L41 sandwich  [4,4,4,4,4]
   * Одиночный замер врёт в обе стороны. Именно так родился репорт «на L37 провал»:
   * тот прогон вытянул 3 там, где медиана 4. И так же одиночный замер пропустил бы
   * настоящую просадку, вытянув удачную доску.
   */
  const ПОВТОРОВ = 5;

  /** Медиана — устойчива к одному выбросу, в отличие от среднего и от минимума. */
  const медиана = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

  it('🔴 лестница не проваливается НИ НА ОДНОМ шаге, а не только на краях', () => {
    const замеры = PROBES.map((lv) => {
      const cfg = levelConfig(lv);
      const выборка: number[] = [];
      for (let i = 0; i < ПОВТОРОВ; i++) {
        const r = generateLogical(lv, cfg.blanks, cfg.N, cfg.BR, cfg.BC, cfg.variant, { budgetMs: 2200 });
        выборка.push(r.grade.tier);
      }
      return { lv, variant: cfg.variant, выборка, tier: медиана(выборка) };
    });
    // eslint-disable-next-line no-console
    console.log('\nсложность по уровням (медиана из ' + ПОВТОРОВ + '):\n'
      + замеры.map((z) => `  L${z.lv} ${z.variant}: [${z.выборка.join(',')}] → ${z.tier}`).join('\n'));

    /**
     * 🔴 ПРЕЖДЕ СРАВНИВАЛИСЬ ТОЛЬКО КРАЙНИЕ ЗАМЕРЫ:
     *     expect(tiers[tiers.length - 1].tier).toBeGreaterThan(tiers[0].tier)
     * Провал в СЕРЕДИНЕ проходил по построению — хоть яма на двенадцать уровней,
     * лишь бы последний оказался выше первого. Гейт зеленел на сломанной лестнице,
     * то есть отвечал не на тот вопрос, ради которого написан.
     * Теперь каждый шаг сверяется с максимумом всех предыдущих.
     */
    /**
     * ⚠️ ДОПУСК В ОДНУ СТУПЕНЬ — ИЗ ЗАМЕРА, А НЕ ИЗ ОСТОРОЖНОСТИ.
     * Даже медиана из пяти гуляет: два прогона подряд 27.08.2026 дали для L12
     * медианы 3 и 2. Требовать строгого «не ниже» значит завести гейт, который
     * краснеет от собственного шума, — а это ровно то, что обесценивает проверку:
     * на красное перестают смотреть.
     * Просадка на ДВЕ ступени шумом уже не объясняется: именно такой была
     * жалоба, из-за которой всё началось (5 → 3 на L37).
     */
    const ДОПУСК = 1;
    const провалы: string[] = [];
    let достигнутый = -Infinity;
    for (const z of замеры) {
      if (z.tier < достигнутый - ДОПУСК) {
        провалы.push(`L${z.lv} (${z.variant}): ${z.tier} — ниже достигнутого ${достигнутый} больше чем на ${ДОПУСК}`);
      }
      достигнутый = Math.max(достигнутый, z.tier);
    }
    expect(провалы).toEqual([]);
  });

  /**
   * 🔴 ПЛОСКАЯ ЛЕСТНИЦА — ЭТО ТОЖЕ ПОЛОМКА, ПРОСТО МЕДЛЕННАЯ.
   *
   * Замер 27.08.2026, три прогона по пять досок на пробу:
   *   медианы 1,3,3,3,4,4,4 → плоских шагов 4
   *   медианы 1,2,3,3,4,4,4 → плоских шагов 3
   *   медианы 1,2,3,3,4,4,4 → плоских шагов 2
   * То есть РОВНО ДВЕ-ТРИ ступени роста на тридцати трёх уровнях: с L12 по L28
   * сложность почти стоит, с L33 по L41 стоит снова.
   * ⚠️ Долг взят по ХУДШЕМУ из наблюдённых прогонов, а не по типичному: гейт не
   * должен краснеть от того, что в этот раз повезло меньше.
   *
   * ⚠️ И это ещё оптимистично. Ступень считается по БАЗОВОЙ доске: маркерные
   * варианты (evenodd, kropki, sandwich) движок как ограничение не применяет, а
   * игроку их метки ВИДНЫ и работают подсказкой. Значит пережитая сложность на
   * L30–41 ниже, чем показывают эти четвёрки, и насколько — отсюда не измерить.
   *
   * Держим ДОЛГ числом: плато не должно становиться длиннее. Починили — опустите
   * число; выросло — гейт краснеет и объясняет, где именно встало.
   */
  const ДОЛГ_ПЛОСКИХ_ШАГОВ = 4;

  it('🔴 плато не растёт: долг записан числом, а не забыт', () => {
    const замеры = PROBES.map((lv) => {
      const cfg = levelConfig(lv);
      const выборка: number[] = [];
      for (let i = 0; i < ПОВТОРОВ; i++) {
        const r = generateLogical(lv, cfg.blanks, cfg.N, cfg.BR, cfg.BC, cfg.variant, { budgetMs: 2200 });
        выборка.push(r.grade.tier);
      }
      return { lv, variant: cfg.variant, tier: медиана(выборка) };
    });
    const плоских = замеры.slice(1).filter((z, i) => z.tier === замеры[i].tier);
    const где = плоских.map((z) => `L${z.lv} ${z.variant}=${z.tier}`).join(' · ');
    // eslint-disable-next-line no-console
    console.log(`\nплоских шагов: ${плоских.length} из ${замеры.length - 1} — ${где}`);
    expect(`плоских шагов ${плоских.length} (долг ${ДОЛГ_ПЛОСКИХ_ШАГОВ}): ${где}`)
      .toBe(`плоских шагов ${Math.min(плоских.length, ДОЛГ_ПЛОСКИХ_ШАГОВ)} (долг ${ДОЛГ_ПЛОСКИХ_ШАГОВ}): ${где}`);
  });
});
