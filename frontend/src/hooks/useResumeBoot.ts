import { useEffect, useRef } from 'react';
import { useProfile } from '@/src/contexts/ProfileContext';
import { loadResume } from '@/src/services/resume';

/**
 * ПОДЪЁМ НЕЗАКОНЧЕННОЙ ПАРТИИ ПРИ ВХОДЕ В ИГРУ — один на все игры.
 *
 * 🔴 ЧТО БЫЛО СЛОМАНО. Этот кусок был скопирован в девять игр слово в слово, и
 * во всех девяти одинаково неверно: подъём срабатывал на ПЕРВОМ рендере, когда
 * настоящий профиль ещё не прочитан.
 *
 * `ProfileContext` отдаёт профиль синхронно и по умолчанию — `free`, а настоящий
 * приезжает из хранилища асинхронно. Партии лежат по ключу с профилем внутри.
 * Значит на первом рендере подъём читал ключ `…_free`, взводил свой сторож
 * `bootRef`, и когда приходил настоящий профиль, повторный заход упирался в этот
 * сторож и уходил ни с чем.
 *
 * Последствий два, и второе хуже первого:
 *   · у всех, кто играет НЕ на `free`, незаконченная партия не поднималась никогда;
 *   · а если партия на `free` в хранилище была, она поднималась ЧУЖОМУ профилю.
 *
 * ⚠️ ПОЧЕМУ ЖДЁМ `ready`, А НЕ «ПРОФИЛЬ НЕ ПУСТ». Профиль не бывает пустым — он с
 * первой миллисекунды равен `free`. Отличить «человек играет на free» от «мы ещё
 * не знаем, кто это» по самому профилю НЕЛЬЗЯ; единственный честный признак —
 * флаг готовности контекста. Он встаёт в том же обновлении, что и настоящий
 * профиль, поэтому к моменту подъёма профиль уже верный.
 *
 * ⚠️ ПОЧЕМУ ХУКОМ, А НЕ ПРАВКОЙ В ДЕВЯТИ ФАЙЛАХ. Ошибка размножилась копипастом
 * и прожила так до десятой игры. Починка в девяти местах оставляет десятому
 * экрану ровно ту же возможность. Гейт `resume-boot.test.ts` требует, чтобы
 * `loadResume` звали только отсюда.
 *
 * @param skip  путь зарядки (`autostart`): там человек явно запустил свежий шаг,
 *              и поднятая партия подменила бы заданный плейлистом уровень.
 */
export function useResumeBoot<T>(
  gameId: string,
  resumeVersion: number,
  onLoaded: (saved: T | null) => void,
  skip: boolean,
): void {
  const { profile, ready } = useProfile();
  const bootRef = useRef(false);

  /**
   * Обработчик держим в ссылке, а не в зависимостях: игры передают сюда стрелку,
   * созданную заново на каждом рендере. В зависимостях она перезапускала бы
   * эффект бесконечно, а в списке-без-неё линтер справедливо ругался бы на
   * устаревшее замыкание. Ссылка снимает оба вопроса.
   */
  const cbRef = useRef(onLoaded);
  cbRef.current = onLoaded;

  useEffect(() => {
    if (skip || bootRef.current) return;
    if (!ready) return;               // ← та самая починка: без неё профиль ещё `free`
    const pid = profile?.id;
    if (!pid) return;
    bootRef.current = true;
    let cancelled = false;
    loadResume<T>(gameId, pid, resumeVersion)
      .then((saved) => { if (!cancelled) cbRef.current(saved); })
      .catch(() => { /* нет партии — обычный вход через настройку */ });
    return () => { cancelled = true; };
  }, [ready, profile?.id, skip, gameId, resumeVersion]);
}
