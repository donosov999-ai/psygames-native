/**
 * ШИРИНА ЭКРАНА, КОТОРОЙ МОЖНО ВЕРИТЬ НА ПЕРВОМ КАДРЕ.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ХУК РАДИ ОДНОЙ СТРОЧКИ. В веб-сборке (а Android у нас
 * WebView, то есть это и телефон) `useWindowDimensions()` на ПЕРВОМ кадре
 * отдаёт 0, а обновляется только по событию `resize` — которого при обычной
 * загрузке экрана не бывает. Ноль уезжает в вёрстку и запекается там навсегда:
 * до поворота экрана, то есть у большинства — насовсем.
 *
 * За один день 19.08.2026 эта ловушка сработала ДВАЖДЫ:
 *   · тропинка уровней схлопывалась в полоску 24 px на 62 экранах из 64
 *     (`maxWidth: winW` с нулём внутри) — подпись вставала по букве в столбик;
 *   · дорожка в заставке между уровнями сжалась со 280 px до 105
 *     (`Math.min(width - 80, 280)` при нуле даёт −80).
 *
 * Второй раз — в НОВОМ файле, написанном через час после починки первого. Значит
 * дело не во внимательности: голый `useWindowDimensions()` просто нельзя пускать
 * в размеры. Поэтому защита живёт здесь одна на всех.
 *
 * ЗАПАСНОЕ ЗНАЧЕНИЕ — ширина обычного телефона. Оно нужно ровно на один кадр:
 * как только система сообщит настоящую, хук вернёт её.
 */
import { useWindowDimensions } from 'react-native';

/** Ширина обычного телефона — на тот единственный кадр, когда настоящая ещё не известна. */
export const FALLBACK_SCREEN_W = 390;

export function useScreenWidth(): number {
  const { width } = useWindowDimensions();
  return width > 0 ? width : FALLBACK_SCREEN_W;
}

/** Высота обычного телефона — парная к `FALLBACK_SCREEN_W`. */
export const FALLBACK_SCREEN_H = 844;

/**
 * РАЗМЕР ЭКРАНА ЦЕЛИКОМ — та же защита, что и у ширины.
 *
 * 🔴 ЗАЧЕМ ЗДЕСЬ, А НЕ ОТДЕЛЬНЫМ ФАЙЛОМ. Ловушка одна и та же, и в шапке выше
 * прямо сказано: защита живёт в одном месте. Второй файл с тем же нулём на
 * первом кадре — это третий раз наступить на те же грабли, только красивее.
 *
 * Высота нужна там, где считают положение от НИЗА экрана: ноль в высоте не
 * сжимает вёрстку, а уводит элемент в противоположный угол. Так 21.08.2026
 * перетащенная кнопка отзыва после перезагрузки оказывалась в левом верхнем
 * углу вместо своего места — доля экрана умножалась на нулевую высоту.
 */
export function useScreenSize(): { w: number; h: number } {
  const { width, height } = useWindowDimensions();
  return {
    w: width > 0 ? width : FALLBACK_SCREEN_W,
    h: height > 0 ? height : FALLBACK_SCREEN_H,
  };
}
