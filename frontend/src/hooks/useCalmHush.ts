import { useEffect } from 'react';
import { setCalmHush } from '@/src/services/feedback';

/**
 * @param calm — идёт ли спокойный шаг (`useGamePreset().isCalm`).
 *
 * Пример: `useCalmHush(isCalm);` — одной строкой рядом с остальными хуками игры.
 */
export function useCalmHush(calm: boolean): void {
  useEffect(() => {
    if (!calm) return;
    setCalmHush(true);
    return () => setCalmHush(false);
  }, [calm]);
}
