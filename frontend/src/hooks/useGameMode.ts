/**
 * useGameMode — в каком режиме сейчас запущена игра.
 *
 * ЗАЧЕМ. До этого каждая игра сама решала, что делать после раунда, а зарядка
 * догадывалась о завершении по сохранённой сессии. Два независимых решения о
 * будущем одного экрана — это гонка, и она стреляла:
 *
 *   маджонг: доиграл уровень → через 1400 мс сам грузит СЛЕДУЮЩИЙ уровень;
 *   зарядка: увидела сессию → через 3500 мс (вечером) уходит к СЛЕДУЮЩЕЙ игре.
 *
 * Человек видит, как начался второй уровень, и через секунду экран выдёргивают.
 * Репорт Вали дословно: «Маджонг выдаёт уровень 2 и ВЫЛЕТАЕТ в вечерней зарядке»,
 * и то же про сортировку товаров. Оба на v1.193.0.
 *
 * ⚠️ ЛЕЧИТЬ ЭТО ПООДИНОЧКЕ БЕССМЫСЛЕННО. Игр шесть десятков, и каждая новая заводит
 * баг заново — ровно как было с судоку, где «цифру на подложке» чинили в трёх версиях
 * подряд, перечисляя варианты правил. Поэтому режим объявляется ОДИН раз и правило
 * «что происходит после раунда» следует из него, а не из привычек конкретного экрана.
 *
 * РЕЖИМЫ И ЧТО ОНИ ЗНАЧАТ ПОСЛЕ РАУНДА:
 *   levels — обычная игра: уровень засчитан, следующий стартует сам;
 *   free   — свободная партия или пресет: показать итог, уровень не трогать;
 *   warmup — шаг зарядки: НИЧЕГО не запускать. Раунд закончен, дальше распоряжается
 *            зарядка — она уведёт на следующую игру сама.
 */
import { useLocalSearchParams } from 'expo-router';

export type GameMode = 'levels' | 'free' | 'warmup';

/**
 * Признаки берём из параметров маршрута, а не из контекста зарядки: экран игры
 * монтируется РАНЬШЕ, чем контекст успевает сообщить о себе, и на первом кадре
 * контекст ещё пуст. Параметр приходит вместе с навигацией и верен сразу.
 *
 *   wu=1   — шаг плейлиста зарядки (ставит stepToParams);
 *   auto=1 — самозапуск без зарядки: ежедневный вызов, «продолжить партию».
 */
export function useGameMode(): GameMode {
  const params = useLocalSearchParams<Record<string, string>>();
  if (params?.wu === '1') return 'warmup';
  if (params?.preset === '1' || params?.free === '1') return 'free';
  return 'levels';
}

/** Нужно ли запускать следующий уровень после пройденного. */
export function shouldChainNextLevel(mode: GameMode): boolean {
  return mode === 'levels';
}
